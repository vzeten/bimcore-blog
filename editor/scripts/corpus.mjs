// Команда `npm run editor:corpus`: запуск корпусного прогона и его отчёт человеку.
// Сами правила — в `corpusRules.mjs`, и они же проверяются машиной; здесь только вид и запуск.
// Разделено потому, что вместе они перерастали предел размера файла (SPEC 4.9).

import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

import {БЛОКЕР, ПРЕДУПРЕЖДЕНИЕ} from '../src/core/prepare.mjs';
import {
  НЕТ_ШАПКИ, ПЕРЕПИСАН, РАЗОШЁЛСЯ, ТОЛЬКО_ПЕРЕВОДЫ, беды, подготовка, прогон,
} from './corpusRules.mjs';

const EDITOR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REPO = path.resolve(EDITOR, '..');

/**
 * Перечень путей под своей строкой итога: сами различия печатаются только там, где они есть.
 * Перечень обрезан, а его длина названа числом: отчёт обязан показать различия и итог, а не
 * простыню по каждому файлу. Полное число всегда стоит в строке итога выше.
 */
const ПОКАЗАТЬ = 5;

function перечислить(записи) {
  for (const запись of записи.slice(0, ПОКАЗАТЬ)) {
    console.log(`    ${запись.путь}`);
    for (const строка of запись.строки) console.log(строка);
  }

  if (записи.length > ПОКАЗАТЬ) console.log(`    …и ещё ${записи.length - ПОКАЗАТЬ}`);
}

/** Сводка «код находки — сколько раз», в устойчивом порядке. */
function поКодам(находки) {
  const счёт = new Map();
  for (const найдено of находки) счёт.set(найдено.код, (счёт.get(найдено.код) ?? 0) + 1);

  return [...счёт.entries()]
    .sort(([кодA], [кодB]) => кодA.localeCompare(кодB, 'ru'))
    .map(([код, сколько]) => `${код} ×${сколько}`)
    .join(', ');
}

/**
 * Печать отчёта и красный вердикт. Возвращает число бед, по которому команда завершает работу.
 * Наружу не отдаётся: файл при подключении сразу запускает прогон по всему репозиторию, поэтому
 * экспорт выглядел бы дверью для теста, которой быть не может. Правила, которые проверяет машина,
 * живут в `corpusRules.mjs`.
 */
function печать(итогПрогона, итогПодготовки) {
  const {пути, покорням, поИсходам} = итогПрогона;
  const находки = итогПодготовки.находки;
  const блокеры = находки.filter((найдено) => найдено.уровень === БЛОКЕР);
  const предупреждения = находки.filter((найдено) => найдено.уровень === ПРЕДУПРЕЖДЕНИЕ);
  const прочие = находки.filter((найдено) => ![БЛОКЕР, ПРЕДУПРЕЖДЕНИЕ].includes(найдено.уровень));

  console.log('Корпусный прогон');
  console.log(`  файлов контента: ${пути.length}`);
  for (const корень of покорням) {
    console.log(`    ${корень.папка}: ${корень.пути.length}${корень.наСайте ? '' : ' (вне сайта)'}`);
  }

  console.log('');
  console.log('Открыл и сохранил без правок');
  for (const [исход, надпись] of [
    [ПЕРЕПИСАН, 'файл был бы переписан'],
    [РАЗОШЁЛСЯ, 'собранный текст разошёлся с файлом'],
    [ТОЛЬКО_ПЕРЕВОДЫ, 'разница только в переводах строк (в файле они разные, сборка сведёт их к одному виду)'],
    [НЕТ_ШАПКИ, 'шапки в файле нет (сборка припишет её при первой правке человека)'],
  ]) {
    console.log(`  ${надпись}: ${поИсходам.get(исход).length}`);
    перечислить(поИсходам.get(исход));
  }

  console.log('');
  console.log('Правила подготовки (по статьям, без проверки качества и полной сборки)');
  console.log(`  статей: ${итогПодготовки.всего}, проверено: ${итогПодготовки.проверено}, вне сайта (не проверяются): ${итогПодготовки.внеСайта}`);
  console.log(`  блокеров: ${блокеры.length}${блокеры.length > 0 ? ` — ${поКодам(блокеры)}` : ''}`);
  console.log(`  предупреждений: ${предупреждения.length}${предупреждения.length > 0 ? ` — ${поКодам(предупреждения)}` : ''}`);
  if (прочие.length > 0) console.log(`  прочих уровней: ${прочие.length} — ${поКодам(прочие)}`);

  const найденные = беды(итогПрогона, итогПодготовки);

  if (найденные.length > 0) {
    console.log('');
    for (const беда of найденные) console.log(`Прогон красный: ${беда}.`);
  }

  return найденные.length;
}

const settings = JSON.parse(fs.readFileSync(path.join(EDITOR, 'settings.json'), 'utf8'));
const итог = прогон(REPO, settings);
if (печать(итог, подготовка(итог.пути, итог.тексты, settings)) > 0) process.exitCode = 1;
