// Правила одноразовой команды «забрать хранилище»: что считать годным источником и годным корнем
// материалов и каким кодом отказать. Слов для человека здесь нет — только коды (SPEC 6.10);
// печатает их команда, потому что она одна знает, чей это источник.
//
// Сам перенос не повторяется ни строкой: зовётся тот же `перенестиСырьём`, что и при запуске
// сервера. Отличий ровно два, и оба намеренные. Первое: источник называет человек, а не место кода.
// Второе: признак испытательного корня НЕ отменяет заказанный перенос — иначе команда для любого
// корня, кроме владельческого, тихо возвращала бы нули, и старая копия выглядела бы пустой.

import fs from 'node:fs';
import path from 'node:path';

import {БЕДА_ЧТЕНИЯ, перенестиСырьём} from '../src/adapters/draftMigrate.mjs';
import {хранилищеРедактора} from '../src/adapters/draftStore.mjs';
import {абсолютный, выборКорня} from '../src/core/materialRoot.mjs';
import {одинПуть} from '../src/core/draftHome.mjs';

/** Коды отказов. Тексты — в самой команде. */
export const НЕ_ДВА_ДОВОДА = 'неДваДовода';
export const ИСТОЧНИК_НЕ_АБСОЛЮТНЫЙ = 'источникНеАбсолютный';
export const НЕТ_ИСТОЧНИКА = 'нетИсточника';
export const НЕ_ХРАНИЛИЩЕ = 'неХранилище';
export const КОРЕНЬ_НЕГОДЕН = 'кореньНегоден';
export const ТОТ_ЖЕ_ИСТОЧНИК = 'тотЖеИсточник';
export const НЕЧИТАЕМО = 'нечитаемо';
export const НЕ_СОСТОЯЛСЯ = 'неСостоялся';

/** Ровно два довода, оба непустые: угадывать пропущенный путь команда не имеет права. */
export function доводы(аргументы) {
  const свои = аргументы.map((довод) => String(довод ?? '').trim()).filter((довод) => довод !== '');
  if (свои.length !== 2 || аргументы.length !== 2) return {отказ: НЕ_ДВА_ДОВОДА, значение: аргументы.join(' ')};

  return {источник: свои[0], корень: свои[1]};
}

/** Папка на месте. Нечитаемый путь — не «нет папки», а беда со своим кодом. */
function вид(путь, диск) {
  try {
    return {папка: диск.statSync(путь).isDirectory()};
  } catch (error) {
    if (error?.code === 'ENOENT' || error?.code === 'ENOTDIR') return {папка: false};
    return {беда: error?.code ?? String(error?.message ?? '')};
  }
}

/**
 * Годен ли источник: абсолютный путь, существующая папка, и в ней лежит хотя бы одна папка
 * хранения. Последнее — не придирка: без неё пустой чужой каталог прошёл бы как «переносить
 * нечего», а человек прочитал бы это как «работы там нет».
 */
function проверитьИсточник(названный, settings, диск) {
  // Абсолютность проверяется по тому, что НАПИСАЛ человек: приведи путь заранее — и относительный
  // молча стал бы путём от папки запуска, то есть снова от места кода.
  if (!абсолютный(названный)) return {отказ: ИСТОЧНИК_НЕ_АБСОЛЮТНЫЙ, значение: названный};

  const источник = path.resolve(названный);
  const свой = вид(источник, диск);
  if (свой.беда) return {отказ: НЕЧИТАЕМО, значение: источник, причина: свой.беда};
  if (!свой.папка) return {отказ: НЕТ_ИСТОЧНИКА, значение: источник};

  const хранит = ['папкаЧерновиков', 'папкаСнимков'].map((ключ) => {
    const внутри = вид(path.join(источник, settings['хранение'][ключ]), диск);
    return внутри.беда ? {беда: внутри.беда, путь: path.join(источник, settings['хранение'][ключ])} : внутри;
  });
  const беда = хранит.find((свой) => свой.беда);
  if (беда) return {отказ: НЕЧИТАЕМО, значение: беда.путь, причина: беда.беда};
  if (!хранит.some((свой) => свой.папка)) return {отказ: НЕ_ХРАНИЛИЩЕ, значение: источник};

  return {путь: источник};
}

/**
 * Годен ли корень назначения. Проверка — та же, что у запуска (`выборКорня`), но её ответ про
 * испытательность здесь НЕ применяется: корень назвал человек, и «чужой» корень — обычное дело
 * для этой команды. Пустой довод сюда не доходит (`доводы`), а относительный отсекается правилом.
 */
function проверитьКорень(корень, settings, диск) {
  if (!абсолютный(корень)) return {отказ: КОРЕНЬ_НЕГОДЕН, значение: корень, причина: 'неАбсолютный'};

  const итог = выборКорня(settings, (путь) => вид(путь, диск).папка === true, корень);
  if (итог['отказ']) return {отказ: КОРЕНЬ_НЕГОДЕН, значение: итог['значение'], причина: итог['отказ']};

  return {корень: path.resolve(итог['корень'])};
}

/**
 * Забрать хранилище из явно названной папки в общее хранилище названного корня материалов.
 * Возвращает отчёт переноса или отказ с кодом. Источник только читается.
 */
export function забратьХранилище({источник, корень, settings, диск = fs}) {
  const свой = проверитьИсточник(источник, settings, диск);
  if (свой['отказ']) return свой;

  const дом = проверитьКорень(корень, settings, диск);
  if (дом['отказ']) return дом;

  // Источник, указанный на само общее хранилище, переносить нечего — но это отказ, а не отчёт с
  // нулями: молчаливый ноль человек прочитает как «в старой копии пусто» и удалит её.
  if (одинПуть(свой['путь'], хранилищеРедактора(дом['корень']))) {
    return {отказ: ТОТ_ЖЕ_ИСТОЧНИК, значение: свой['путь']};
  }

  let отчёт;
  try {
    отчёт = перенестиСырьём({repo: дом['корень'], кодDir: свой['путь'], settings, испытательный: false, диск});
  } catch (error) {
    if (error?.name !== БЕДА_ЧТЕНИЯ) throw error;
    return {отказ: НЕЧИТАЕМО, значение: error['путь'], причина: error['причина']};
  }

  // Ноль без переноса не бывает отчётом: если правило почему-то отменило работу, это отказ.
  if (!отчёт['перенос']) return {отказ: НЕ_СОСТОЯЛСЯ, значение: свой['путь']};

  return {...отчёт, источник: свой['путь']};
}
