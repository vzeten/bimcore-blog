// Команда `npm run editor:worktree-remove -- <путь>`: убрать временную рабочую копию безопасно.
//
// **Зачем отдельная команда.** Обычный `git worktree remove` не обещает ничего про связи внутри
// удаляемой папки: соединение каталогов на настоящие зависимости он проходит насквозь, и вместе с
// копией уходит то, на что связь смотрела. Один такой случай уже стоил проекту всех корневых
// зависимостей. Поэтому уборка рабочих копий делается этой командой, а не голой командой git.
//
// Только вид и запуск: весь порядок — в `src/adapters/safeRemove.mjs`, и он же работает внутри
// сборки плана. Второго набора правил у команды нет.
//
// Коды завершения точные: 0 — копия убрана (или её уже не было), 1 — отказ. Отказ означает, что
// каталог остался на месте нетронутым: разбирается человек, а не программа.

import {execFileSync} from 'node:child_process';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

import {убратьКопию} from '../src/adapters/safeRemove.mjs';

const EDITOR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const РЕПОЗИТОРИЙ = path.resolve(EDITOR, '..');

/**
 * Где вообще разрешено удалять. Два места и ни одним больше: папка рабочих копий помощников и сам
 * репозиторий, внутри которого живут временные копии сборки плана.
 */
const РАЗРЕШЁННЫЕ = [
  path.join(EDITOR, '.coordination', 'worktrees'),
  РЕПОЗИТОРИЙ,
];

/** Тонкая обёртка над git. `simple-git` здесь не нужен: команде хватает одного вызова. */
const git = {
  raw: async (аргументы) => execFileSync('git', ['-C', РЕПОЗИТОРИЙ, ...аргументы], {encoding: 'utf8'}),
};

const отказы = {
  путьНеПонят: 'путь не понят',
  путьНеРазрешён: 'этот путь не входит в места, где разрешено удалять рабочие копии',
  путьЗанят: 'внутри этого пути идёт работа прямо сейчас',
  копияСсылка: 'сам путь является связью — удалять по нему нельзя',
  этоГлавнаяКопия: 'это главная рабочая копия репозитория',
  копияНеУчтена: 'git не знает такой рабочей копии',
  учётНеПрочитан: 'не удалось спросить git про рабочие копии',
  обходНеПолон: 'дерево не удалось осмотреть целиком',
  ссылкаНеСнята: 'связь внутри копии не снялась',
  ссылкаОсталась: 'внутри копии осталась связь',
  цельНеЧитается: 'не удалось узнать, куда смотрит связь',
  цельПропала: 'то, на что смотрела связь, исчезло',
  копияНеУбрана: 'папку не удалось удалить',
};

const путь = process.argv[2];

if (путь === undefined || путь.trim() === '') {
  console.error('Нужен один довод: полный путь к рабочей копии.');
  console.error('Порядок: npm run editor:worktree-remove -- <путь>');
  process.exit(1);
}

const цель = path.resolve(путь);

// Оба пути печатаются ДО любого действия: человек видит, что именно будет убрано и откуда.
console.log(`Репозиторий: ${РЕПОЗИТОРИЙ}`);
console.log(`Убирается:   ${цель}`);

const итог = await убратьКопию({git, путь: цель, корни: РАЗРЕШЁННЫЕ});

for (const снятая of итог.снятые ?? []) {
  console.log(`Связь снята: ${снятая.связь} -> ${снятая.цель} (цель не тронута)`);
}

if (итог.ошибка) {
  console.error(`Отказ: ${отказы[итог.ошибка] ?? итог.ошибка}${итог.подробность ? ` — ${итог.подробность}` : ''}`);
  console.error('Каталог остался на месте. Разберитесь с причиной и повторите.');
  process.exit(1);
}

console.log(итог.нечего ? 'Убирать было нечего, учёт git прибран.' : 'Копия убрана, учёт git прибран.');
