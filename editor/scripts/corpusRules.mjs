// Правила корпусного прогона: что он смотрит и отчего краснеет. Отчёт — в `corpus.mjs`, он же
// точка входа команды `npm run editor:corpus`. Разделено потому, что правила проверяются машиной,
// а печать — это вид; вместе они перерастали предел размера файла (SPEC 4.9).
//
// Обходит все файлы контента из настройки «контент», для каждого повторяет путь «программа
// открыла и сохранила без правок» тем же кодом, каким сохраняет сервер, и сравнивает результат
// с байтами файла на диске. Затем прогоняет по статьям сайта местные правила подготовки.
//
// Правил проверки статьи здесь нет и быть не должно: своё правило рядом с проверяемым — это второй
// источник правды, и прогон однажды подтвердил бы сам себя. Всё зовётся из `src`. Свои у прогона
// только меры о нём самом: полнота обхода (пустой корень сайта, ноль проверенных статей) и признак
// «шапки в файле нет» — он нарочно считается по первым знакам файла, а не по успеху разбора.
// Спроси прогон о шапке тот же разбор, который проверяется, — файл с нераспознанной шапкой сошёл бы
// за файл без шапки, и порча такого файла оказалась бы в жёлтом исходе.
//
// Требования к команде (`TASKS.md`, шаг 5): одинаковый вход — одинаковый выход, в сеть не ходит
// вовсе (git не спрашивается), пропуск файлов «по кэшу» запрещён, печатает различия и итог,
// а не простыню по каждому файлу.
//
// Правила прогона проверяются машиной (`tests/corpus.test.mjs`), поэтому файл отдаёт их наружу
// и сам ничего не запускает.

import fs from 'node:fs';
import path from 'node:path';

import {buildHead, nothingChanged, sameText, splitArticle} from '../src/core/articleFile.mjs';
import {safeFrontmatter} from '../src/core/safeFrontmatter.mjs';
import {groupArticles} from '../src/core/articles.mjs';
import {проверитьМестные} from '../src/core/prepare.mjs';
import {walk} from '../src/adapters/library.mjs';
import {собрать} from '../src/adapters/saveRoute.mjs';

/**
 * Исходы одного файла. Красные — только те два, где виновата программа: она переписала бы файл
 * человека либо собрала бы из него другой текст. Остальные расхождения объяснимы самим файлом,
 * и выдавать их за поломку значит приучать к красному прогону, на который перестают смотреть.
 */
export const СОВПАЛ = 'совпал';
export const ПЕРЕПИСАН = 'переписан';
export const РАЗОШЁЛСЯ = 'разошёлся';
export const ТОЛЬКО_ПЕРЕВОДЫ = 'толькоПереводы';
export const НЕТ_ШАПКИ = 'нетШапки';

/**
 * Все файлы статей по корням контента, в порядке, не зависящем от обхода файловой системы: иначе
 * два запуска на одной машине печатали бы разные отчёты, и сравнить «до» с «после» было бы нечем.
 *
 * Разбивка по корням — не украшение отчёта, а мера полноты. `walk` на несуществующей папке
 * отвечает пустым списком без ошибки, поэтому переименованный корень, переехавшая локаль или
 * запуск не в том дереве дали бы «изменилось бы файлов: 0» — прогон промолчал бы ровно там, где
 * должен закричать. Пустой корень сайта считается провалом прогона; корень вне сайта (песочница)
 * пустым быть вправе — пробную статью человек удаляет когда захочет.
 */
export function файлыКонтента(repo, settings) {
  const покорням = settings['контент'].map((корень) => ({
    папка: корень['папка'],
    наСайте: корень['наСайте'] === true,
    пути: walk(path.join(repo, корень['папка']))
      .map((файл) => path.relative(repo, файл).split(path.sep).join('/'))
      .sort(),
  }));

  return {
    покорням,
    пути: [...new Set(покорням.flatMap((корень) => корень.пути))].sort(),
    пустыеКорниСайта: покорням.filter((корень) => корень.наСайте && корень.пути.length === 0),
  };
}

/**
 * «Открыл и сохранил без правок» ровно тем путём, каким это делает сервер: шапка проходит защитную
 * проверку, и файл записывается только тогда, когда после неё в статье что-то изменилось.
 *
 * Проверок две, и они разные. Первая: сервер вообще не должен записать файл. Вторая: даже не
 * записанный, собранный текст обязан совпасть с файлом байт в байт — разошёлся, значит первая же
 * настоящая правка перепишет заодно и чужие строки (SPEC 3.5, 5.1). Проверяй прогон только первую,
 * и поломка сборки текста пряталась бы за заслоном «ничего не изменилось».
 *
 * Два расхождения из второй проверки объяснимы самим файлом, но объяснение обязано быть двойным:
 * и причина в файле есть, и расхождение ровно та, которую эта причина даёт. Проверь прогон только
 * причину — порча содержимого в таком файле прошла бы мимо; проверь только вид расхождения —
 * прогон обвинил бы в поломке программы чужие исправные файлы. Обе половины проверяются:
 * · **разные переводы строк в самом файле**: сборка сводит их к одному виду, поэтому расхождение
 *   прощается только тогда, когда оно исчезает при одних переводах строк (`sameText`, правило
 *   ядра) И в файле действительно есть оба вида;
 * · **шапки в файле нет вовсе**: сборка припишет пустую, и это решённое поведение программы (шапка
 *   появляется правкой человека в его собственном файле, `CURRENT_TASK.md`, круг 1б).
 *
 * Ожидаемый вид считается от текста файла, а не от того, что разбор счёл телом: возьми прогон
 * `current.body`, и обе стороны сравнения собрались бы из одних кусков — проверка сверяла бы сама
 * себя и пропускала бы удвоение невидимой метки. Признак «шапки нет» — тоже свой: файл, начатый
 * с `---`, шапку имеет, даже если разбор её не принял, и порча такого файла обязана быть красной.
 */
export function исходФайла(rel, raw, settings) {
  const current = splitArticle(raw);
  const safe = safeFrontmatter(rel, current.frontmatterRaw, settings['контент']);
  const тело = raw.slice(current.метка.length);
  const безШапки = !тело.startsWith('---');

  return классифицировать({
    raw,
    текст: собрать(current, safe.frontmatterRaw, current.body),
    пишет: !nothingChanged(current, {body: current.body, frontmatterRaw: safe.frontmatterRaw}),
    // Единственное законное отличие файла без шапки — пустая шапка перед прежним текстом,
    // собранная тем же правилом ядра. Отличие сверх неё объяснить нечем.
    ожидаемое: безШапки
      ? buildHead({frontmatterRaw: '', eol: current.eol, метка: current.метка}) + тело
      : raw,
    смешаныПереводы: смешаныПереводы(raw),
  });
}

/** Есть ли в файле переводы строк обоих видов сразу. Считается, а не предполагается. */
export function смешаныПереводы(raw) {
  return (raw.match(/\r\n/g) || []).length > 0 && (raw.match(/(?<!\r)\n/g) || []).length > 0;
}

/**
 * Чем кончился один файл. Отделено от чтения и сборки, чтобы правило можно было проверить
 * машиной на любой паре «файл — собранный текст», а не только на том, что лежит на диске сегодня.
 *
 * `ожидаемое` — вид файла, с которым собранному тексту позволено совпасть помимо самого файла.
 * Совпал с ним — расхождение объяснено до байта; не совпал — красное, каким бы объяснимым
 * ни выглядело.
 */
export function классифицировать({raw, текст, пишет, ожидаемое, смешаныПереводы: смешаны}) {
  if (пишет) return {исход: ПЕРЕПИСАН, строки: различия(raw, текст)};
  if (текст === raw) return {исход: СОВПАЛ, строки: []};

  const безШапки = ожидаемое !== raw;
  if (текст === ожидаемое) return {исход: НЕТ_ШАПКИ, строки: []};
  if (смешаны && sameText(текст, ожидаемое)) {
    return {исход: безШапки ? НЕТ_ШАПКИ : ТОЛЬКО_ПЕРЕВОДЫ, строки: []};
  }

  return {исход: РАЗОШЁЛСЯ, строки: различия(raw, текст)};
}

/**
 * Первые различающиеся строки: человеку нужно место, а не весь файл.
 * Строки режутся по `\n`, а хвостовой `\r` остаётся в тексте и виден в кавычках: различие только
 * в переводах строк — тоже различие, и молчаливый показ «строки одинаковые» вводил бы в заблуждение.
 */
function различия(было, стало, сколько = 3) {
  const a = было.split('\n');
  const b = стало.split('\n');
  const строки = [];

  for (let i = 0; i < Math.max(a.length, b.length) && строки.length < сколько; i += 1) {
    if (a[i] === b[i]) continue;
    строки.push(`      строка ${i + 1}: ${JSON.stringify(a[i] ?? null)} → ${JSON.stringify(b[i] ?? null)}`);
  }

  return строки;
}

/** Прогон «открыл и сохранил» по всем файлам контента: тексты читаются один раз на весь прогон. */
export function прогон(repo, settings) {
  const {пути, покорням, пустыеКорниСайта} = файлыКонтента(repo, settings);
  const тексты = new Map();
  const поИсходам = new Map([[ПЕРЕПИСАН, []], [РАЗОШЁЛСЯ, []], [ТОЛЬКО_ПЕРЕВОДЫ, []], [НЕТ_ШАПКИ, []]]);

  for (const rel of пути) {
    const raw = fs.readFileSync(path.join(repo, rel), 'utf8');
    тексты.set(rel, raw);

    const {исход, строки} = исходФайла(rel, raw, settings);
    if (исход !== СОВПАЛ) поИсходам.get(исход).push({путь: rel, строки});
  }

  return {пути, покорням, пустыеКорниСайта, тексты, поИсходам};
}

/**
 * Правила подготовки по статьям, а не по файлам: они спрашивают статью целиком — все её языковые
 * версии и категорию из общего свода. Статья вне сайта (песочница) пропускается: подготовка для
 * неё недоступна вовсе, и мерить прогоном то, чего программа не делает, значит выдумывать находки.
 */
export function подготовка(пути, тексты, settings) {
  // Из файла берётся один путь. Ни видимость, ни название сюда не кладутся: правила подготовки
  // считают видимость сами из содержимого версии, а название нужно реестру для показа, и здесь оба
  // поля были бы мёртвыми. Поле, которое никто не читает, в этой программе уже жило целый круг
  // незамеченным (`saveRoute.mjs`).
  const файлы = пути.map((rel) => ({path: rel}));

  const статьи = groupArticles(файлы, settings);
  const находки = [];
  let проверено = 0;
  let внеСайта = 0;

  for (const статья of статьи) {
    if (!статья.наСайте) {
      внеСайта += 1;
      continue;
    }

    const снимок = Object.values(статья.versions)
      .map((версия) => ({путь: версия.path, содержимое: тексты.get(версия.path) ?? ''}))
      .sort((a, b) => a.путь.localeCompare(b.путь));

    находки.push(...проверитьМестные(снимок, статья.category, settings));
    проверено += 1;
  }

  return {всего: статьи.length, проверено, внеСайта, находки};
}

/**
 * Отчего прогон красный. Отдельно от печати, потому что это и есть его правило: единственное,
 * ради чего команда существует, обязано проверяться машиной, а не разовым запуском руками.
 *
 * Каждая беда — сломанное обещание программы, а не вкус.
 * · Пустой корень сайта и ноль проверенных статей: прогон ничего не смотрел, а «ноль изменившихся»
 *   выглядит успехом. Полнота нужна обеим половинам прогона, файлам и статьям.
 * · Переписанный файл: сохранение без правок тронуло чужой текст (SPEC 5.1).
 * · Разошедшийся текст: файл сегодня не пишется, но первая же правка утащит с собой чужие строки.
 *
 * Находки подготовки прогон не валят: живые статьи сайта писались до программы, часть из них
 * подготовку сегодня не проходит, и владелец решил их не трогать. Красней прогон и на них,
 * он был бы красным всегда и перестал бы что-либо доказывать.
 */
export function беды(итогПрогона, итогПодготовки) {
  const {пути, пустыеКорниСайта, поИсходам} = итогПрогона;

  return [
    ...пустыеКорниСайта.map((корень) => `корень сайта пуст или недоступен: ${корень.папка}`),
    ...(поИсходам.get(ПЕРЕПИСАН).length > 0 ? ['сохранение без правок изменило бы файлы человека'] : []),
    ...(поИсходам.get(РАЗОШЁЛСЯ).length > 0 ? ['собранный текст расходится с файлом'] : []),
    ...(пути.length > 0 && итогПодготовки.проверено === 0
      ? ['правила подготовки не проверили ни одной статьи, хотя файлы контента найдены'] : []),
    // «Проверять нечего» — беда того, кто собирал снимок, а снимок здесь собирает сам прогон
    // (`prepare.mjs`). В общем счёте блокеров она затерялась бы среди находок живых статей.
    ...(итогПодготовки.находки.some((найдено) => найдено.код === 'нечегоПроверять')
      ? ['снимок статьи пришёл к правилам пустым — это поломка самого прогона'] : []),
  ];
}

