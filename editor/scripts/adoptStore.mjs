// Команда `npm run editor:adopt -- <источник> <корень материалов>`: одноразово забрать черновики и
// историю из ЯВНО названной папки старого хранилища в общее хранилище названного корня материалов.
// Сами правила — в `adoptRules.mjs`, перенос — общий с запуском сервера; здесь только вид и запуск.
//
// Это разовый ход, а не режим: настройки не заводятся, обычный запуск после него по-прежнему читает
// только общее хранилище у материалов. Источник команда лишь читает.

import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

import {
  ИСТОЧНИК_НЕ_АБСОЛЮТНЫЙ, КОРЕНЬ_НЕГОДЕН, НЕЧИТАЕМО, НЕ_ДВА_ДОВОДА, НЕ_СОСТОЯЛСЯ, НЕ_ХРАНИЛИЩЕ,
  НЕТ_ИСТОЧНИКА, ТОТ_ЖЕ_ИСТОЧНИК, доводы, забратьХранилище,
} from './adoptRules.mjs';
import {хранилищеРедактора} from '../src/adapters/draftStore.mjs';

const EDITOR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** Точные коды завершения: успех, отказ и «перенос прошёл, но есть спор». */
export const УСПЕХ = 0;
export const ОТКАЗ = 1;
export const СПОР = 2;

const ОБРАЗЕЦ = 'npm run editor:adopt -- <путь старого хранилища> <корень материалов>';

/** Слова отказов живут здесь: только команда знает, что источник назвал человек. */
const ОТКАЗЫ = {
  [НЕ_ДВА_ДОВОДА]: `нужны ровно два непустых довода. Образец: ${ОБРАЗЕЦ}`,
  [ИСТОЧНИК_НЕ_АБСОЛЮТНЫЙ]: 'путь источника должен быть полным, от буквы диска',
  [НЕТ_ИСТОЧНИКА]: 'указанной папки источника нет на диске',
  [НЕ_ХРАНИЛИЩЕ]: 'в указанной папке нет ни черновиков, ни истории — это не хранилище редактора',
  [ТОТ_ЖЕ_ИСТОЧНИК]: 'источник и есть общее хранилище этого корня — переносить неоткуда',
  [НЕ_СОСТОЯЛСЯ]: 'перенос не состоялся, и нулевой отчёт был бы неправдой',
  [НЕЧИТАЕМО]: 'указанный источник не читается; это не пустая папка, а беда доступа',
};

/** Причины негодного корня приходят кодами из правила выбора корня. */
const КОРНИ = {
  неАбсолютный: 'корень материалов должен быть указан полным путём, от буквы диска',
  нетПапки: 'указанного корня материалов нет на диске',
  неМатериалы: 'в указанном корне нет ни одной папки контента сайта',
};

function отказать(итог) {
  const слова = итог['отказ'] === КОРЕНЬ_НЕГОДЕН
    ? (КОРНИ[итог['причина']] ?? итог['причина'])
    : ОТКАЗЫ[итог['отказ']];
  console.error(`Отказ: ${слова}`);
  if (итог['значение']) console.error(`  ${итог['значение']}`);
  if (итог['отказ'] === НЕЧИТАЕМО && итог['причина']) console.error(`  причина: ${итог['причина']}`);
  process.exit(ОТКАЗ);
}

/** Итог числами и поимённо: спорные и пропущенные без имён человек потом не найдёт. */
function напечатать(отчёт) {
  console.log(`перенесено черновиков: ${отчёт['черновиков']}`);
  console.log(`перенесено снимков: ${отчёт['снимков']}`);
  console.log(`совпало и не переносилось: ${отчёт['совпало']}`);
  console.log(`споров: ${отчёт['споров']}`);
  for (const спор of отчёт['спорные']) console.log(`  ${спор['статья'] ?? '(статья неизвестна)'} → ${спор['вариант']}`);
  console.log(`осталось в источнике (посторонние имена): ${отчёт['пропущено'].length}`);
  for (const имя of отчёт['пропущено']) console.log(`  ${имя}`);
}

const settings = JSON.parse(fs.readFileSync(path.join(EDITOR, 'settings.json'), 'utf8'));
const разбор = доводы(process.argv.slice(2));

// Оба пути называются ДО любой записи: человек обязан увидеть, откуда и куда пойдёт работа.
console.log('Забрать хранилище');
console.log(`  источник:   ${разбор['источник'] ?? '(не указан)'}`);
console.log(`  назначение: ${разбор['корень'] ? хранилищеРедактора(path.resolve(разбор['корень'])) : '(не указано)'}`);

if (разбор['отказ']) отказать(разбор);

const итог = забратьХранилище({источник: разбор['источник'], корень: разбор['корень'], settings});
if (итог['отказ']) отказать(итог);

напечатать(итог);
// Спор — не успех: работа человека раздвоилась, и до разбора запись этой статьи заперта.
process.exit(итог['споров'] > 0 ? СПОР : УСПЕХ);
