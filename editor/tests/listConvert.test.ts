// Имя каждого теста повторяет формулировку правила.
// Кнопки списка: абзацы -> пункты компактного списка, повторное нажатие -> абзацы, другой вид -> маркеры.
// Единицы берутся из того же дерева разбора markdown, что и в окне; правка проходит тот же фильтр
// разметки, что и в окне (`поверхностьРедактирования`), поэтому молчаливое вето здесь было бы видно.
import {describe, expect, it} from 'vitest';
import {ChangeSet, EditorState} from '@codemirror/state';
import {commonmarkLanguage, markdown} from '@codemirror/lang-markdown';
import {видСписка, преобразованиеСписка, type Окружение} from '../src/core/listConvert';
import {границыСоветов} from '../src/core/tipBlock';
import {КОСАЯ_ПЕРЕНОСА, блокВнеРазбора, внутриОграды} from '../src/ui/livePreview/softBreak';
import {поверхностьРедактирования} from '../src/ui/editor/structureGuard';

function окружение(text: string): Окружение {
  const строки = text.split('\n');
  return {
    дерево: commonmarkLanguage.parser.parse(text),
    границы: границыСоветов(строки, внутриОграды(строки)),
    обычная: (строка) => !блокВнеРазбора(строка),
    косая: (строка) => КОСАЯ_ПЕРЕНОСА.test(строка),
    разбор: (t) => commonmarkLanguage.parser.parse(t),
  };
}

/** Правка кнопкой, проведённая через состояние редактора с фильтром разметки, как в окне. */
export function применить(text: string, from: number, to: number, вид: 'точки' | 'числа'): {текст: string; выбор: string} | null {
  const правка = преобразованиеСписка(text, {from, to}, вид, окружение(text));
  if (правка === null) return null;
  const state = EditorState.create({doc: text, extensions: [markdown({addKeymap: false}), поверхностьРедактирования({})]});
  const первая = state.changes(правка.changes);
  const все = первая.compose(ChangeSet.of(правка.затем, первая.newLength));
  const итог = state.update({changes: все, selection: {anchor: все.mapPos(правка.выделение.from, 1), head: все.mapPos(правка.выделение.to, -1)}}).state;
  const {from: a, to: b} = итог.selection.main;
  return {текст: итог.doc.toString(), выбор: итог.doc.sliceString(a, b)};
}

/** Выделить фрагмент текста по его словам: от начала первого до конца второго. */
function выбрав(text: string, от: string, до = от): [number, number] {
  return [text.indexOf(от), text.indexOf(до) + до.length];
}

const вид = (text: string, from: number, to = from) => видСписка(text, {from, to}, окружение(text));

describe('абзацы становятся пунктами компактного списка', () => {
  it('каждый задетый абзац — пункт, пустые строки между ними уходят, текст вокруг не трогается', () => {
    const текст = 'До.\n\nПервый.\n\nВторой.\n\nТретий.\n\nПосле.';
    expect(применить(текст, ...выбрав(текст, 'Первый', 'Второй'), 'точки'))
      .toEqual({текст: 'До.\n\n- Первый.\n- Второй.\n\nТретий.\n\nПосле.', выбор: 'Первый.\n- Второй.'});
    expect(применить(текст, ...выбрав(текст, 'Первый', 'Третий'), 'числа')?.текст)
      .toBe('До.\n\n1. Первый.\n2. Второй.\n3. Третий.\n\nПосле.');
  });

  it('частичное выделение действует на весь задетый абзац, курсор без выделения — на свой абзац', () => {
    const текст = 'Первый абзац\nвторая строка.\n\nВторой.';
    expect(применить(текст, 3, 3, 'точки')?.текст).toBe('- Первый абзац\n  вторая строка.\n\nВторой.');
  });

  it('перенос внутри абзаца остаётся внутри пункта: жёсткий — с косой, мягкий — строкой с отступом', () => {
    expect(применить('раз\\\nдва\nтри', 0, 0, 'точки')?.текст).toBe('- раз\\\n  два\n  три');
    expect(применить('раз\\\nдва', 0, 0, 'числа')?.текст).toBe('1. раз\\\n   два');
  });

  it('косая переноса перед пустой строкой не мешает: правка не задевает скрытый диапазон и проходит фильтр', () => {
    expect(применить('Раз\\\n\n', 0, 3, 'точки')?.текст).toBe('- Раз\\\n\n');
    expect(применить('Раз\\\n\nДва\\\n\n', 0, 9, 'точки')?.текст).toBe('- Раз\n- Два\\\n\n');
  });

  it('«2.» посреди абзаца — текст, а не пункт: абзац целиком становится одним пунктом и число остаётся', () => {
    const текст = 'Смета на этапы работ\n2. монтаж каркаса\nпо проекту';
    expect(применить(текст, ...выбрав(текст, 'по проекту'), 'точки')?.текст)
      .toBe('- Смета на этапы работ\n  2. монтаж каркаса\n  по проекту');
    expect(вид(текст, текст.indexOf('монтаж'))).toBeNull();
    // Единица же прерывает абзац: `1. пункт` под текстом — настоящий пункт.
    expect(применить('Текст\n1. пункт', 8, 8, 'числа')?.текст).toBe('Текст\n\nпункт');
  });

  it('inline-разметка, слова и порядок не меняются', () => {
    const текст = '**Жирный** и [ссылка](x).\n\nВторой `код`.';
    expect(применить(текст, 0, текст.length, 'точки')?.текст).toBe('- **Жирный** и [ссылка](x).\n- Второй `код`.');
  });

  it('нумерация начинается с единицы и идёт по порядку, отступ продолжения не больше трёх пробелов', () => {
    const текст = Array.from({length: 11}, (_, i) => `Абзац ${i + 1}\nещё`).join('\n\n');
    const итог = применить(текст, 0, текст.length, 'числа')!.текст;
    expect(итог.split('\n').filter((s) => /^\d+\. /.test(s)).length).toBe(11);
    expect(итог).toContain('10. Абзац 10\n   ещё\n11. Абзац 11\n   ещё');
  });
});

describe('повторное нажатие действующего вида возвращает абзацы', () => {
  it('пункты становятся отдельными абзацами, продолжения теряют отступ, косая переноса остаётся', () => {
    expect(применить('- раз\\\n  два\n- три', 0, 17, 'точки')).toEqual({текст: 'раз\\\nдва\n\nтри', выбор: 'раз\\\nдва\n\nтри'});
    expect(применить('- раз\\\n  два\n- три', 0, 0, 'точки')?.текст).toBe('раз\\\nдва\n\n- три');
    expect(применить('1. a\n2. b\n', 0, 9, 'числа')?.текст).toBe('a\n\nb\n');
  });

  it('снятые пункты в середине компактного списка отделяются пустой строкой от оставшихся', () => {
    const текст = '- a\n- b\n- c\n- d';
    expect(применить(текст, 5, 9, 'точки')).toEqual({текст: '- a\n\nb\n\nc\n\n- d', выбор: 'b\n\nc'});
  });

  it('снятие блочного пункта выводит его абзацы, картинку и вложенный список наружу, слова целы', () => {
    expect(применить('- Раз\n\n  ![](./a.png)\n\n  Ещё абзац\n- Два', 2, 2, 'точки')?.текст).toBe('Раз\n\n![](./a.png)\n\nЕщё абзац\n\n- Два');
    expect(применить('- a\n  - вложенный\n- b', 0, 19, 'точки')?.текст).toBe('a\n- вложенный\n\nb');
  });

  it('действующий вид: все задетые единицы — пункты одного вида', () => {
    expect(вид('- a\n- b', 0)).toBe('точки');
    expect(вид('1. a\n2. b', 0, 8)).toBe('числа');
    expect(вид('- a\n\nАбзац.', 0, 7)).toBeNull();
    expect(вид('- a\n1. b', 0, 7)).toBeNull();
    expect(вид('Абзац.', 0)).toBeNull();
  });
});

describe('смена вида меняет маркеры и отступ продолжений, слова и вложения прежние', () => {
  it('точки -> числа и обратно: слова, переносы и порядок прежние, отступ продолжения по новому маркеру', () => {
    expect(применить('- раз\\\n  два\n- три', 0, 17, 'числа')?.текст).toBe('1. раз\\\n   два\n2. три');
    expect(применить('1. раз\\\n   два\n2. три', 0, 20, 'точки')?.текст).toBe('- раз\\\n  два\n- три');
  });

  it('вложенный список и блочный пункт идут за маркером: продолжения сдвигаются на ширину маркера, пустые строки внутри пункта остаются', () => {
    expect(применить('- Родитель\n  - Раз\n  - Два\n- Сосед', 2, 2, 'числа')?.текст).toBe('1. Родитель\n   - Раз\n   - Два\n- Сосед');
    expect(применить('- Раз\n\n  ![](./a.png)\n- Два', 0, 24, 'числа')?.текст).toBe('1. Раз\n\n   ![](./a.png)\n2. Два');
  });

  it('выделение целиком внутри вложенного списка правит его пункты, родитель не трогается', () => {
    const текст = '- Родитель\n  - Раз\n  - Два';
    expect(применить(текст, ...выбрав(текст, 'Раз', 'Два'), 'числа')?.текст).toBe('- Родитель\n  1. Раз\n  2. Два');
  });

  it('смесь абзацев и пунктов другого вида — всё становится пунктами нажатого вида', () => {
    expect(применить('Абзац.\n\n1. пункт', 0, 12, 'точки')?.текст).toBe('- Абзац.\n- пункт');
  });

  it('последний пункт компактного списка меняет вид один: список другого вида соседом не считается', () => {
    expect(применить('1. a\n2. b\n3. c', 10, 10, 'точки')?.текст).toBe('1. a\n2. b\n- c');
    expect(применить('- a\n- b\n- c', 4, 4, 'числа')?.текст).toBe('- a\n1. b\n- c');
  });

  it('простой пункт рядом с блочным правится без общего отказа; зазор к блочному соседу остаётся', () => {
    expect(применить('- Раз\n- Два\n\n  Второй абзац', 2, 5, 'числа')?.текст).toBe('1. Раз\n- Два\n\n  Второй абзац');
  });
});

describe('затронутый список уплотняется и объединяется с соседями того же вида', () => {
  it('новые пункты рядом с маркированным списком входят в него: зазор уходит, слова соседа прежние', () => {
    const снизу = 'Раз\n\nДва\n\nТри\n\n- один\n- два';
    expect(применить(снизу, ...выбрав(снизу, 'Раз', 'Три'), 'точки')?.текст).toBe('- Раз\n- Два\n- Три\n- один\n- два');
    const сверху = '- один\n- два\n\nРаз\n\nДва';
    expect(применить(сверху, ...выбрав(сверху, 'Раз', 'Два'), 'точки')?.текст).toBe('- один\n- два\n- Раз\n- Два');
    const сОбеих = '- один\n\nРаз\n\nДва\n\n* два';
    expect(применить(сОбеих, ...выбрав(сОбеих, 'Раз', 'Два'), 'точки')?.текст).toBe('- один\n- Раз\n- Два\n- два');
  });

  it('нумерованный сосед сверху продолжает счёт, снизу — перенумеровывается подряд; разделитель номера один', () => {
    const сверху = '1. один\n2. два\n\nТри\n\nЧетыре';
    expect(применить(сверху, ...выбрав(сверху, 'Три', 'Четыре'), 'числа')?.текст).toBe('1. один\n2. два\n3. Три\n4. Четыре');
    const снизу = 'Раз\n\n1) один\n2) два';
    expect(применить(снизу, 0, 3, 'числа')?.текст).toBe('1. Раз\n2. один\n3. два');
  });

  it('многострочные абзацы рядом со списком: переносы внутри пунктов, слова соседа прежние', () => {
    const текст = 'Раз\\\nещё раз\n\nДва\nи два\n\n- один\n  продолжение\n- два';
    expect(применить(текст, ...выбрав(текст, 'Раз', 'и два'), 'точки')?.текст).toBe('- Раз\\\n  ещё раз\n- Два\n  и два\n- один\n  продолжение\n- два');
  });

  it('частичное выделение старого разреженного списка уплотняет его целиком; сосед другого вида остаётся за зазором', () => {
    const текст = '- Раз\n\n- Два\n\n- Три\n\n- Другой';
    expect(применить(текст, 2, текст.indexOf('\n\n- Другой'), 'числа')?.текст).toBe('1. Раз\n2. Два\n3. Три\n\n- Другой');
    expect(применить(текст, 0, текст.length, 'числа')?.текст).toBe('1. Раз\n2. Два\n3. Три\n4. Другой');
    expect(применить('- a\n\n- b', 5, 8, 'числа')?.текст).toBe('- a\n\n1. b');
    expect(применить('- a\n\n- b', 5, 8, 'точки')?.текст).toBe('- a\n\nb');
  });

  it('список другого вида и список за текстом или границей примечания не сливаются', () => {
    expect(применить('- один\n- два\n\nАбзац', 15, 15, 'числа')?.текст).toBe('- один\n- два\n\n1. Абзац');
    expect(применить('- один\n\nКонтроль:\n\nРаз', 21, 21, 'точки')?.текст).toBe('- один\n\nКонтроль:\n\n- Раз');
    expect(применить(':::note\n- один\n:::\n\nРаз', 21, 21, 'точки')?.текст).toBe(':::note\n- один\n:::\n\n- Раз');
  });

  it('соседний список, включённый в выделение, продолжается компактно; снятие рядом с чужим списком его не трогает', () => {
    expect(применить('- один\n- два\n\nАбзац', 0, 20, 'точки')?.текст).toBe('- один\n- два\n- Абзац');
    const список = '* Раз\n* Два\n\n- один';
    expect(применить(список, ...выбрав(список, 'Раз', 'Два'), 'точки')?.текст).toBe('Раз\n\nДва\n\n- один');
  });
});

describe('форма, которую окно и сайт читают по-разному, не трогается и не создаётся', () => {
  it('«2. b» сразу под пунктом «- a»: сайт начинает список, дерево продолжает пункт — рядом с этим отказ', () => {
    const текст = '- a\n2. b\n\nАбзац';
    expect(применить(текст, ...выбрав(текст, 'Абзац'), 'числа')).toBeNull();
    expect(применить(текст, ...выбрав(текст, 'Абзац'), 'точки')).toBeNull();
    expect(применить(текст, 0, 3, 'числа')).toBeNull();
  });

  it('смена вида пункта не ставит строку с чужим номером под пункт другого списка', () => {
    const текст = '1. Первый\n2. Второй\n3. Третий';
    expect(применить(текст, ...выбрав(текст, 'Второй'), 'точки')).toBeNull();
    expect(применить(текст, ...выбрав(текст, 'Первый'), 'точки')).toBeNull();
    expect(применить(текст, ...выбрав(текст, 'Третий'), 'точки')?.текст).toBe('1. Первый\n2. Второй\n- Третий');
    expect(применить(текст, ...выбрав(текст, 'Второй'), 'числа')?.текст).toBe('1. Первый\n\nВторой\n\n3. Третий');
  });

  it('номер с отступом внутри пункта и номер посреди обычного абзаца оба разбора читают одинаково — правка идёт', () => {
    const пункт = '- Смета\n  2. монтаж\n  по проекту';
    expect(применить(пункт, 0, пункт.length, 'точки')?.текст).toBe('Смета\n2. монтаж\nпо проекту');
    expect(применить(пункт, 0, пункт.length, 'числа')?.текст).toBe('1. Смета\n   2. монтаж\n   по проекту');
    const абзац = 'Смета на этапы работ\n2. монтаж каркаса\nпо проекту';
    expect(применить(абзац, ...выбрав(абзац, 'по проекту'), 'точки')?.текст).toBe('- Смета на этапы работ\n  2. монтаж каркаса\n  по проекту');
  });
});

describe('что нельзя превратить без потерь, не трогается целиком', () => {
  it('заголовок, цитата, таблица, код, картинка, JSX и граница примечания — отказ', () => {
    for (const текст of [
      'Абзац.\n\n## Заголовок',
      '> цитата',
      '| a | b |\n|---|---|',
      '```\n- код\n```',
      '![картинка](a.png)',
      '<YouTube id="x" />',
      ':::tip\nТекст\n:::',
      'Абзац.\n\n    отступной код',
    ]) {
      expect(преобразованиеСписка(текст, {from: 0, to: текст.length}, 'точки', окружение(текст))).toBeNull();
    }
  });

  it('отказ только если задето: абзац перед заголовком превращается, сам заголовок не задет', () => {
    expect(применить('Абзац.\n\n## Заголовок', 0, 3, 'точки')?.текст).toBe('- Абзац.\n\n## Заголовок');
  });

  it('текст внутри примечания превращается, если границы не задеты; абзац вплотную под заголовком — тоже', () => {
    expect(применить(':::tip\nТекст.\n:::', 8, 8, 'точки')?.текст).toBe(':::tip\n- Текст.\n:::');
    expect(применить(':::tip\n- a\n:::\nПосле', 8, 8, 'точки')?.текст).toBe(':::tip\na\n:::\nПосле');
    expect(применить('## Заголовок\nАбзац.', 14, 14, 'точки')?.текст).toBe('## Заголовок\n- Абзац.');
  });

  it('внутри :::note и :::tip списки создаются, меняют вид, уплотняются и снимаются так же', () => {
    for (const тип of ['note[Примечание]', 'tip']) {
      const текст = `:::${тип}\nРаз\n\nДва\n:::\n\nПосле`;
      const список = применить(текст, ...выбрав(текст, 'Раз', 'Два'), 'точки')!.текст;
      expect(список).toBe(`:::${тип}\n- Раз\n- Два\n:::\n\nПосле`);
      const числа = применить(список, ...выбрав(список, 'Раз', 'Два'), 'числа')!.текст;
      expect(числа).toBe(`:::${тип}\n1. Раз\n2. Два\n:::\n\nПосле`);
      expect(применить(числа, ...выбрав(числа, 'Раз', 'Два'), 'числа')?.текст).toBe(текст);
      const разреженный = `:::${тип}\n- Раз\n\n- Два\n:::`;
      expect(применить(разреженный, ...выбрав(разреженный, 'Раз', 'Два'), 'числа')?.текст).toBe(`:::${тип}\n1. Раз\n2. Два\n:::`);
      // Частичное выделение меняет вид только у задетого пункта: невыделенный остаётся точкой.
      expect(применить(разреженный, ...выбрав(разреженный, 'Раз'), 'числа')?.текст).toBe(`:::${тип}\n1. Раз\n\n- Два\n:::`);
    }
  });
});
