// Имя каждого теста повторяет формулировку правила.
// Кнопки списка: абзацы -> пункты компактного списка, повторное нажатие -> абзацы, другой вид -> только маркеры.
// Единицы берутся из того же дерева разбора markdown, что и в окне.
import {describe, expect, it} from 'vitest';
import {commonmarkLanguage} from '@codemirror/lang-markdown';
import {видСписка, преобразованиеСписка, type Окружение} from '../src/core/listConvert';
import {границыСоветов} from '../src/core/tipBlock';
import {блокВнеРазбора, внутриОграды} from '../src/ui/livePreview/softBreak';

function окружение(text: string): Окружение {
  const строки = text.split('\n');
  return {дерево: commonmarkLanguage.parser.parse(text), границы: границыСоветов(строки, внутриОграды(строки)), обычная: (строка) => !блокВнеРазбора(строка)};
}

function применить(text: string, from: number, to: number, вид: 'точки' | 'числа'): {текст: string; выбор: string} | null {
  const edit = преобразованиеСписка(text, {from, to}, вид, окружение(text));
  if (edit === null) return null;
  const текст = text.slice(0, edit.from) + edit.insert + text.slice(edit.to);
  const выбор = edit.select ? edit.insert.slice(edit.select.from, edit.select.to) : '';
  return {текст, выбор};
}

/** Выделить фрагмент текста по его словам: от начала первого до конца второго. */
function выбрав(text: string, от: string, до = от): [number, number] {
  return [text.indexOf(от), text.indexOf(до) + до.length];
}

const вид = (text: string, from: number, to = from) => видСписка(text, {from, to}, окружение(text));

describe('абзацы становятся пунктами компактного списка', () => {
  it('каждый задетый абзац — пункт, пустые строки между ними уходят, соседи не трогаются', () => {
    const текст = 'До.\n\nПервый.\n\nВторой.\n\nТретий.\n\nПосле.';
    expect(применить(текст, ...выбрав(текст, 'Первый', 'Второй'), 'точки'))
      .toEqual({текст: 'До.\n\n- Первый.\n- Второй.\n\nТретий.\n\nПосле.', выбор: '- Первый.\n- Второй.'});
    expect(применить(текст, ...выбрав(текст, 'Первый', 'Третий'), 'числа')?.текст)
      .toBe('До.\n\n1. Первый.\n2. Второй.\n3. Третий.\n\nПосле.');
  });

  it('частичное выделение действует на весь задетый абзац, курсор без выделения — на свой абзац', () => {
    const текст = 'Первый абзац\nвторая строка.\n\nВторой.';
    expect(применить(текст, 3, 3, 'точки')?.текст).toBe('- Первый абзац\n  вторая строка.\n\nВторой.');
  });

  it('перенос внутри абзаца остаётся внутри пункта: жёсткий — с косой, мягкий — строкой с отступом', () => {
    expect(применить('раз\\\nдва\nтри', 0, 0, 'точки')?.текст).toBe('- раз\\\n  два\n  три');
    expect(применить('раз\\\nдва', 0, 0, 'числа')?.текст).toBe('1. раз\\\n   два');
  });

  it('«2.» посреди абзаца — текст, а не пункт: абзац целиком становится одним пунктом и число остаётся', () => {
    const текст = 'Смета на этапы работ\n2. монтаж каркаса\nпо проекту';
    expect(применить(текст, ...выбрав(текст, 'по проекту'), 'точки')?.текст)
      .toBe('- Смета на этапы работ\n  2. монтаж каркаса\n  по проекту');
    expect(вид(текст, текст.indexOf('монтаж'))).toBeNull();
    // Единица же прерывает абзац: `1. пункт` под текстом — настоящий пункт.
    expect(применить('Текст\n1. пункт', 8, 8, 'числа')?.текст).toBe('Текст\n\nпункт');
  });

  it('inline-разметка, слова и порядок не меняются', () => {
    const текст = '**Жирный** и [ссылка](x).\n\nВторой `код`.';
    expect(применить(текст, 0, текст.length, 'точки')?.текст).toBe('- **Жирный** и [ссылка](x).\n- Второй `код`.');
  });

  it('нумерация начинается с единицы и идёт по порядку, отступ продолжения не больше трёх пробелов', () => {
    const текст = Array.from({length: 11}, (_, i) => `Абзац ${i + 1}\nещё`).join('\n\n');
    const итог = применить(текст, 0, текст.length, 'числа')!.текст;
    expect(итог.split('\n').filter((s) => /^\d+\. /.test(s)).length).toBe(11);
    expect(итог).toContain('10. Абзац 10\n   ещё\n11. Абзац 11\n   ещё');
  });
});

describe('повторное нажатие действующего вида возвращает абзацы', () => {
  it('пункты становятся отдельными абзацами, продолжения теряют отступ, косая переноса остаётся', () => {
    expect(применить('- раз\\\n  два\n- три', 0, 17, 'точки')).toEqual({текст: 'раз\\\nдва\n\nтри', выбор: 'раз\\\nдва\n\nтри'});
    expect(применить('- раз\\\n  два\n- три', 0, 0, 'точки')?.текст).toBe('раз\\\nдва\n\n- три');
    expect(применить('1. a\n2. b\n', 0, 9, 'числа')?.текст).toBe('a\n\nb\n');
  });

  it('снятые пункты в середине компактного списка отделяются пустой строкой от оставшихся', () => {
    const текст = '- a\n- b\n- c\n- d';
    expect(применить(текст, 5, 9, 'точки')).toEqual({текст: '- a\n\nb\n\nc\n\n- d', выбор: 'b\n\nc'});
  });

  it('действующий вид: все задетые единицы — пункты одного вида', () => {
    expect(вид('- a\n- b', 0)).toBe('точки');
    expect(вид('1. a\n2. b', 0, 8)).toBe('числа');
    expect(вид('- a\n\nАбзац.', 0, 7)).toBeNull();
    expect(вид('- a\n1. b', 0, 7)).toBeNull();
    expect(вид('Абзац.', 0)).toBeNull();
  });
});

describe('смена вида меняет только маркеры', () => {
  it('точки -> числа и обратно: слова, переносы и порядок прежние, отступ продолжения по новому маркеру', () => {
    expect(применить('- раз\\\n  два\n- три', 0, 17, 'числа')?.текст).toBe('1. раз\\\n   два\n2. три');
    expect(применить('1. раз\\\n   два\n2. три', 0, 20, 'точки')?.текст).toBe('- раз\\\n  два\n- три');
  });

  it('смесь абзацев и пунктов другого вида — всё становится пунктами нажатого вида', () => {
    expect(применить('Абзац.\n\n1. пункт', 0, 12, 'точки')?.текст).toBe('- Абзац.\n- пункт');
  });

  it('пункт посреди компактного списка меняет вид один: соседи остаются как были', () => {
    expect(применить('1. a\n2. b\n3. c', 5, 5, 'точки')?.текст).toBe('1. a\n- b\n3. c');
  });
});

describe('невыделенные соседи не меняются: иначе отказ целиком', () => {
  it('абзац рядом со списком того же вида и знака через пустую строку слился бы с ним — отказ', () => {
    const снизу = '- один\n- два\n\nАбзац';
    expect(применить(снизу, ...выбрав(снизу, 'Абзац'), 'точки')).toBeNull();
    const сверху = 'Абзац\n\n- один\n- два';
    expect(применить(сверху, 0, 5, 'точки')).toBeNull();
    const числа = '1. один\n2. два\n\nАбзац';
    expect(применить(числа, ...выбрав(числа, 'Абзац'), 'числа')).toBeNull();
  });

  it('другой вид или другой знак не сливаются — преобразование идёт', () => {
    const текст = '- один\n- два\n\nАбзац';
    expect(применить(текст, ...выбрав(текст, 'Абзац'), 'числа')?.текст).toBe('- один\n- два\n\n1. Абзац');
    const звёзды = '* один\n\nАбзац';
    expect(применить(звёзды, ...выбрав(звёзды, 'Абзац'), 'точки')?.текст).toBe('* один\n\n- Абзац');
  });

  it('соседний список, включённый в выделение, продолжается компактно', () => {
    const текст = '- один\n- два\n\nАбзац';
    expect(применить(текст, 0, текст.length, 'точки')?.текст).toBe('- один\n- два\n- Абзац');
  });

  it('пункт разреженного списка через пустую строку от невыделенного соседа — отказ и на смену вида, и на снятие', () => {
    const текст = '- a\n\n- b';
    expect(применить(текст, 5, 8, 'числа')).toBeNull();
    expect(применить(текст, 5, 8, 'точки')).toBeNull();
    expect(применить(текст, 0, текст.length, 'числа')?.текст).toBe('1. a\n2. b');
  });
});

describe('что нельзя превратить без потерь, не трогается целиком', () => {
  it('вложенный список, заголовок, цитата, таблица, код, картинка, JSX и граница примечания — отказ', () => {
    for (const текст of [
      '- a\n  - вложенный\n- b',
      'Абзац.\n\n## Заголовок',
      '> цитата',
      '| a | b |\n|---|---|',
      '```\n- код\n```',
      '![картинка](a.png)',
      '<YouTube id="x" />',
      ':::tip\nТекст\n:::',
      'Абзац.\n\n    отступной код',
    ]) {
      expect(преобразованиеСписка(текст, {from: 0, to: текст.length}, 'точки', окружение(текст))).toBeNull();
    }
  });

  it('отказ только если задето: абзац перед заголовком превращается, сам заголовок не задет', () => {
    expect(применить('Абзац.\n\n## Заголовок', 0, 3, 'точки')?.текст).toBe('- Абзац.\n\n## Заголовок');
  });

  it('текст внутри примечания превращается, если границы не задеты; абзац вплотную под заголовком — тоже', () => {
    expect(применить(':::tip\nТекст.\n:::', 8, 8, 'точки')?.текст).toBe(':::tip\n- Текст.\n:::');
    expect(применить(':::tip\n- a\n:::\nПосле', 8, 8, 'точки')?.текст).toBe(':::tip\na\n:::\nПосле');
    expect(применить('## Заголовок\nАбзац.', 14, 14, 'точки')?.текст).toBe('## Заголовок\n- Абзац.');
  });
});
