// Имя каждого теста повторяет формулировку правила.
// Итог выпуска — то, что человек читает вместо списка файлов: чистая функция, проверяется фактами.
import {describe, expect, it} from 'vitest';

import {итогВыпуска} from '../src/core/releaseSummary.mjs';
import {ВЕРСИЯ, КАРТИНКА, СОСТОЯНИЕ} from '../src/core/release.mjs';

const RU = 'i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba/index.mdx';
const EN = 'docs/lessons/proba/index.mdx';
const КАРТИНКА_RU = 'i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba/img-01.png';

const файлы = [
  {путь: RU, назначение: ВЕРСИЯ, локаль: 'ru'},
  {путь: `${RU.replace('index.mdx', '')}_state.json`, назначение: СОСТОЯНИЕ, локаль: 'ru'},
  {путь: КАРТИНКА_RU, назначение: КАРТИНКА, локаль: 'ru'},
  {путь: EN, назначение: ВЕРСИЯ, локаль: 'en'},
];

const итог = (правки = {}) => итогВыпуска({
  файлы,
  изменённые: [RU],
  заглушки: ['en'],
  всеЛокали: ['ru', 'en', 'es'],
  ...правки,
});

const состояние = (ответ, локаль) => ответ.версии.find((версия) => версия.локаль === локаль).состояние;

describe('итог выпуска человеческим языком', () => {
  it('изменившаяся языковая версия названа изменившейся', () => {
    expect(состояние(итог(), 'ru')).toBe('изменилась');
  });

  it('существующая заглушка названа заглушкой, а не изменением', () => {
    expect(состояние(итог(), 'en')).toBe('заглушка');
  });

  it('язык, версии которого нет вовсе, назван отдельно, а не пропущен молчанием', () => {
    expect(состояние(итог(), 'es')).toBe('нетВерсии');
  });

  it('неизменившаяся не заглушка названа оставшейся как была', () => {
    expect(состояние(итог({заглушки: []}), 'en')).toBe('неМенялась');
  });

  it('заглушка, которую тронули, названа изменившейся: заглушкой она уже не останется', () => {
    expect(состояние(итог({изменённые: [RU, EN]}), 'en')).toBe('изменилась');
  });

  it('версия, у которой изменился только файл готовности, названа изменившейся', () => {
    const готовность = `${RU.replace('index.mdx', '')}_state.json`;

    expect(состояние(итог({изменённые: [готовность]}), 'ru')).toBe('изменилась');
  });

  it('скрытая на сайте версия помечена скрытой, а видимая — нет', () => {
    const ответ = итог({скрытые: ['es', 'en']});

    expect(ответ.версии.find((версия) => версия.локаль === 'en').скрыта).toBe(true);
    expect(ответ.версии.find((версия) => версия.локаль === 'ru').скрыта).toBe(false);
  });

  it('у языка без версии скрытость не выдумывается', () => {
    expect(итог({скрытые: ['es']}).версии.find((версия) => версия.локаль === 'es').скрыта).toBe(false);
  });

  it('неизменённые картинки не называются вовсе', () => {
    expect(итог().картинки).toEqual([]);
  });

  it('изменившаяся картинка названа, и только она', () => {
    expect(итог({изменённые: [КАРТИНКА_RU]}).картинки).toEqual([КАРТИНКА_RU]);
  });

  it('изменившаяся картинка сама по себе версию изменившейся не делает', () => {
    expect(состояние(итог({изменённые: [КАРТИНКА_RU]}), 'ru')).toBe('неМенялась');
  });

  it('ни один файл не расходится с сайтом — публиковать нечего', () => {
    expect(итог({изменённые: []}).естьЧтоПубликовать).toBe(false);
  });

  it('хоть один файл расходится с сайтом — публиковать есть что', () => {
    expect(итог().естьЧтоПубликовать).toBe(true);
  });
});
