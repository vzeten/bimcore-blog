// Имя каждого теста повторяет формулировку правила.
// Набор букв в большой статье не пересчитывает неизменные слои заново: цвет успевает за человеком,
// а переиспользование прошлого расчёта не меняет ни одного цвета.
import {describe, expect, it} from 'vitest';
import {ChangeSet, Text} from '@codemirror/state';
import {colorize, type Colorized, type Layer, type LayerKind, type Правка} from '../src/core/colorize';
import {служебноеУдаление} from '../src/ui/layerColors';
import {слоиБольшойСтатьи} from './bigArticleHarness';

/**
 * Предел на одну букву. Взят с большим запасом: исправленный расчёт укладывается в единицы
 * миллисекунд, а полное сравнение всей статьи со всеми слоями занимает больше секунды — между
 * ними два порядка. Такой зазор переживает и медленную машину, и уборку мусора в середине замера,
 * но возврат дорогого пересчёта на каждую букву поймает.
 */
const БЮДЖЕТ_БУКВЫ = 50;

/** Букв в замере: хватает, чтобы середина ряда была устойчивой, и не растягивает прогон тестов. */
const БУКВ = 24;

/** Цепочка окна: неизменные слои, текст на их конец и накопленные поверх него правки. */
function цепочка(before: Layer[], исходный: Text, правки: ChangeSet, doc: Text): Layer[] {
  const границы: Правка[] = [];
  правки.iterChangedRanges((fromA, toA, fromB, toB) => границы.push({fromA, toA, fromB, toB}));
  return [...before, {text: исходный.toString(), kind: 'current'}, {text: doc.toString(), kind: 'current', правки: границы}];
}

/** Расчёт без переиспользования: чужая цепочка сбивает память, следом идёт полный счёт. */
function начисто(слои: Layer[]): Colorized {
  colorize([{text: 'посторонний текст', kind: 'site'}], служебноеУдаление);
  return colorize(слои, служебноеУдаление);
}

/** Набор букв подряд в середине статьи — по одной правке на букву, как транзакции окна. */
function набрать(before: Layer[], файл: string, букв: number): {времена: number[]; слои: Layer[]; итог: Colorized} {
  const исходный = Text.of(файл.split('\n'));
  let doc = исходный;
  let правки = ChangeSet.empty(doc.length);
  const место = файл.indexOf(' ', Math.floor(файл.length / 2)) + 1;

  let слои = цепочка(before, исходный, правки, doc);
  let итог = colorize(слои, служебноеУдаление);
  const времена: number[] = [];

  for (let i = 0; i < букв; i += 1) {
    const шаг = ChangeSet.of({from: место + i, insert: 'о'}, doc.length);
    doc = шаг.apply(doc);
    правки = правки.compose(шаг);
    слои = цепочка(before, исходный, правки, doc);
    const начало = performance.now();
    итог = colorize(слои, служебноеУдаление);
    времена.push(performance.now() - начало);
  }

  return {времена, слои, итог};
}

/** Середина ряда замеров: одна случайная задержка машины не решает исход проверки. */
function середина(времена: number[]): number {
  const ряд = [...времена].sort((a, b) => a - b);
  return ряд[Math.floor(ряд.length / 2)];
}

describe('набор в большой статье не пересчитывает неизменные слои заново', () => {
  it('материал проверки — статья 23-25 тысяч знаков и четыре состояния', () => {
    const {слои, файл} = слоиБольшойСтатьи();
    expect(слои).toHaveLength(4);
    expect(файл.length).toBeGreaterThanOrEqual(23000);
    expect(файл.length).toBeLessThanOrEqual(25000);
    // Слои различаются: одинаковые состояния сделали бы замер нечестно лёгким.
    expect(new Set(слои.map((с) => с.text)).size).toBe(4);
  });

  it('одна набранная буква укладывается в бюджет живого набора', () => {
    const {слои, файл} = слоиБольшойСтатьи();
    const {времена} = набрать(слои, файл, БУКВ);

    expect(середина(времена)).toBeLessThan(БЮДЖЕТ_БУКВЫ);
    // Ни одна буква не должна выпадать в секундную паузу.
    expect(Math.max(...времена)).toBeLessThan(БЮДЖЕТ_БУКВЫ * 4);
  });

  it('окраска набранного та же, что при полном расчёте той же цепочки', () => {
    const {слои, файл} = слоиБольшойСтатьи();
    const набор = набрать(слои, файл, БУКВ);

    expect(набор.итог).toEqual(начисто(набор.слои));
  });
});

describe('память окраски сравнивает слои по значению, а не по ссылке', () => {
  /** Цепочка, объекты которой между вызовами НЕ пересоздаются: их правят прямо на месте. */
  const цепь = (прошлый: string, kind: LayerKind, окно: string, правки?: Правка[]): Layer[] =>
    [{text: прошлый, kind}, {text: окно, kind: 'current', правки}];

  /** Слой изменили на месте — прошлый ответ обязан устареть и совпасть с полным расчётом. */
  function проверить(слои: Layer[], изменить: (слои: Layer[]) => void): void {
    const было = colorize(слои, служебноеУдаление);
    изменить(слои);
    const стало = colorize(слои, служебноеУдаление);

    expect(стало).not.toEqual(было);
    expect(стало).toEqual(начисто(слои));
  }

  it('текст слоя, изменённый прямо в его объекте, пересчитывает окраску', () => {
    проверить(цепь('раз два три', 'site', 'раз два три'), (слои) => {
      слои[0].text = 'раз ДВА три';
    });
  });

  it('происхождение слоя, изменённое прямо в его объекте, пересчитывает окраску', () => {
    проверить(цепь('раз два три', 'site', 'раз два три'), (слои) => {
      слои[0].kind = 'prevAi';
    });
  });

  it('границы правки, дописанные прямо в тот же массив, пересчитывают окраску', () => {
    проверить(цепь('раз два три', 'site', 'раз ДВА три', []), (слои) => {
      слои[1].правки!.push({fromA: 4, toA: 7, fromB: 4, toB: 7});
    });
  });
});

describe('автосохранение по ходу набора не возвращает дорогой пересчёт', () => {
  /**
   * Сохранение меняет цепочку: набранное уходит в файл, и от него же считаются дальнейшие правки.
   * Пересчитать при этом придётся только хвост цепочки — прошлые состояния статьи не изменились.
   */
  it('первая окраска после записи файла укладывается в бюджет и совпадает с полным расчётом', () => {
    const {слои: before, файл} = слоиБольшойСтатьи();
    const набор = набрать(before, файл, 8);
    const записано = набор.слои[набор.слои.length - 1].text;

    // Цепочка после записи: тело файла — это то, что человек только что набрал.
    const свежие: Layer[] = [...before.slice(0, -1), {text: записано, kind: 'prevHuman'}];
    const исходный = Text.of(записано.split('\n'));
    const слои = цепочка(свежие, исходный, ChangeSet.empty(исходный.length), исходный);

    const начало = performance.now();
    const итог = colorize(слои, служебноеУдаление);
    const заняло = performance.now() - начало;

    expect(итог).toEqual(начисто(слои));
    expect(заняло).toBeLessThan(БЮДЖЕТ_БУКВЫ * 4);
  });
});

describe('переиспользование прошлого расчёта не меняет окраску правок', () => {
  const действия: {имя: string; правка: (текст: string) => {from: number; to?: number; insert?: string}}[] = [
    {имя: 'вставка', правка: (текст) => ({from: текст.indexOf('## Раздел 7'), insert: 'Новый абзац руками.\n\n'})},
    {имя: 'удаление', правка: (текст) => ({from: текст.indexOf('## Раздел 9'), to: текст.indexOf('## Раздел 9') + 11})},
    {имя: 'форматирование', правка: (текст) => ({from: текст.indexOf('поэтому'), to: текст.indexOf('поэтому') + 7, insert: '**поэтому**'})},
  ];

  for (const {имя, правка} of действия) {
    it(`${имя} красится так же, как при полном расчёте, и отмена с повтором возвращают тот же цвет`, () => {
      const {слои: before, файл} = слоиБольшойСтатьи();
      const исходный = Text.of(файл.split('\n'));
      let doc = исходный;
      let правки = ChangeSet.empty(doc.length);

      const шаг = ChangeSet.of(правка(файл), doc.length);
      const обратно = шаг.invert(doc);
      const было = colorize(цепочка(before, исходный, правки, doc), служебноеУдаление);

      doc = шаг.apply(doc);
      правки = правки.compose(шаг);
      const после = цепочка(before, исходный, правки, doc);
      expect(colorize(после, служебноеУдаление)).toEqual(начисто(после));

      // Отмена идёт той же дорогой, что и правка: правки складываются и гасят друг друга.
      doc = обратно.apply(doc);
      правки = правки.compose(обратно);
      const отмена = цепочка(before, исходный, правки, doc);
      expect(colorize(отмена, служебноеУдаление)).toEqual(было);

      doc = шаг.apply(doc);
      правки = правки.compose(шаг);
      const повтор = цепочка(before, исходный, правки, doc);
      expect(colorize(повтор, служебноеУдаление)).toEqual(начисто(повтор));
    });
  }
});
