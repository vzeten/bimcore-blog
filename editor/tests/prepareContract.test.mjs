// Имя каждого теста повторяет формулировку правила.
// Договор подготовки: настройка, снимок и обещания блокам, которые придут позже.
import {describe, expect, it} from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

import {БЛОКЕР, ПРЕДУПРЕЖДЕНИЕ, ЭТАПЫ, подготовкаПрошла, проверитьМестные} from '../src/core/prepare.mjs';

const EDITOR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const НАСТРОЙКИ = JSON.parse(fs.readFileSync(path.join(EDITOR, 'settings.json'), 'utf8'));

const RU = 'i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba/index.mdx';
const EN = 'docs/lessons/proba/index.mdx';

/** Статья из шапок: тело правилам этого блока не нужно, но снимок несёт файл целиком. */
const снимок = (шапки) => Object.entries(шапки)
  .map(([путь, шапка]) => ({путь, содержимое: `---\n${шапка}\n---\n\nТекст статьи.\n`}));

const ЦЕЛАЯ = {
  [RU]: 'title: "Проба"\nslug: /lessons/proba\ndescription: "Понятное описание"\nkeywords: [розетки]',
  [EN]: 'title: "Translation placeholder: Проба"\nslug: /lessons/proba\ndescription: "Placeholder page. The English translation of this article is not ready yet."\nunlisted: true',
};

const проверить = (шапки, категория = 'урок') => проверитьМестные(снимок(шапки), категория, НАСТРОЙКИ);
const коды = (находки) => находки.map((находка) => находка.код);

/** Кусок кода правил: структурные проверки допустимы как предохранители от регресса (SPEC 5.2.1). */
const кусокКода = (имя, файл = 'prepareRules.mjs') => new RegExp(`const ${имя} = \\{([\\s\\S]*?)\\};`)
  .exec(fs.readFileSync(path.join(EDITOR, 'src/core', файл), 'utf8'))[1];

describe('подготовка статьи: сломанная настройка кричит, а не молчит', () => {
  const сНастройкой = (обязательные) => проверитьМестные(
    снимок(ЦЕЛАЯ), 'урок', {...НАСТРОЙКИ, обязательныеПоля: обязательные},
  );

  it('категория, которой нет среди категорий статей, останавливает подготовку до самих проверок', () => {
    // Владелец правит настройки, не запуская тестов: переименует «урок» — и требование
    // ключевых слов испарилось бы молча, а статья уехала бы на сайт без них.
    expect(коды(сНастройкой({уроки: ['keywords']}))).toEqual(['настройкаНеЗнаетКатегорию']);
  });

  it('описание в списке полей категории отвергается: оно условие выпуска, а поля категории только просят', () => {
    expect(коды(сНастройкой({урок: ['description']}))).toEqual(['описаниеНеПолеКатегории']);
  });

  it('поле, которому негде стоять в шапке ЭТОГО рода, останавливает выпуск и говорится один раз', () => {
    // `tags` есть у блога и нет у документации. Спроси подготовка метки у урока — человек получил
    // бы «заполните метки» и не нашёл такого поля в свойствах вовсе. И это беда одной настройки,
    // а не трёх файлов: трижды повторять её у трёхъязычной статьи незачем.
    const находки = сНастройкой({урок: ['tags']}).filter((найдено) => найдено.код === 'полюНегдеСтоять');

    expect(находки).toHaveLength(1);
    expect(находки[0]).toMatchObject({уровень: БЛОКЕР, поле: 'tags', путь: null});
  });

  it('настройки обязательных полей может не быть вовсе: это «ничего не требуем», а не поломка', () => {
    const без = {...НАСТРОЙКИ};
    delete без['обязательныеПоля'];

    expect(() => проверитьМестные(снимок(ЦЕЛАЯ), 'урок', без)).not.toThrow();
    expect(коды(проверитьМестные(снимок(ЦЕЛАЯ), 'урок', без))).not.toContain('полеКатегорииПусто');
  });

  it('живая настройка редактора проверку проходит', () => {
    expect(коды(проверить(ЦЕЛАЯ))).not.toContain('настройкаНеЗнаетКатегорию');
  });
});

describe('подготовка статьи: договор снимка', () => {
  it('служебные файлы статьи версией не считаются: спрашивать с них поля статьи нелепо', () => {
    // Блок В читает файлы состояния тем же заходом, чтобы снять с них отпечатки. Прими их правила
    // за языковые версии — человек получил бы «заполните описание» у файла, которого не открывал,
    // а настоящая русская версия оказалась бы вытеснена из проверок.
    const сСостоянием = [
      ...снимок(ЦЕЛАЯ),
      {путь: 'i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba/_state.json', содержимое: '{"готовность":"Черновик"}'},
    ];
    const находки = проверитьМестные(сСостоянием, 'урок', НАСТРОЙКИ);

    expect(находки.every((найдено) => !String(найдено.путь ?? '').endsWith('.json'))).toBe(true);
    expect(подготовкаПрошла(находки)).toBe(true);
  });

  it('пустой снимок останавливает выпуск: проверять нечего — это сбой, а не чистая статья', () => {
    expect(коды(проверитьМестные([], 'урок', НАСТРОЙКИ))).toEqual(['нечегоПроверять']);
  });

  it('статья, написанная как .md, для подготовки существует: Docusaurus собирает и такие', () => {
    // «Что считать файлом статьи» знает одно место на всю программу. Разойдись подготовка с
    // обходом папок — статья была бы видна в реестре, а подготовка сказала бы «проверять нечего».
    const мд = [{путь: 'docs/lessons/proba/index.md', содержимое: '---\ntitle: "A"\ndescription: "Есть"\nkeywords: [a]\n---\n'}];

    expect(коды(проверитьМестные(мд, 'урок', НАСТРОЙКИ))).not.toContain('нечегоПроверять');
  });

  it('запись снимка без содержимого не роняет проверки стеком', () => {
    const битая = [{путь: RU}, {путь: EN}];

    expect(() => проверитьМестные(битая, 'урок', НАСТРОЙКИ)).not.toThrow();
  });
});

describe('подготовка статьи: договор с блоками, которые придут позже', () => {
  it('вердикт «прошла» решает одно место: нет находок уровня блокер', () => {
    expect(подготовкаПрошла([])).toBe(true);
    expect(подготовкаПрошла([{уровень: ПРЕДУПРЕЖДЕНИЕ}])).toBe(true);
    expect(подготовкаПрошла([{уровень: ПРЕДУПРЕЖДЕНИЕ}, {уровень: БЛОКЕР}])).toBe(false);
  });

  it('дорогие этапы стоят в порядке последними, и они помечены как внешние', () => {
    const внешние = ЭТАПЫ.filter((этап) => этап.внешний).map((этап) => этап.код);

    expect(внешние).toEqual(['contentCheck', 'сборка']);
    expect(ЭТАПЫ.slice(-2).every((этап) => этап.внешний)).toBe(true);
  });

  it('у каждого местного этапа есть своё правило: забытое даёт находку, а не падение', () => {
    // Предохранитель: добавь кто-нибудь этап в перечень и забудь про правило — подготовка упала бы
    // голым TypeError вместо того, чтобы сказать человеку хоть что-то.
    const правила = кусокКода('ПРАВИЛА', 'prepare.mjs');

    for (const этап of ЭТАПЫ.filter((этап) => !этап.внешний)) {
      expect(правила.includes(этап.код), этап.код).toBe(true);
    }
  });

  it('каждая находка местных проверок называет свой этап, и этап есть в порядке', () => {
    const битая = {...ЦЕЛАЯ, [RU]: 'title: "Проба"\nslug: proba\ndescription: '};
    const коды = new Set(ЭТАПЫ.map((этап) => этап.код));

    for (const находка of проверить(битая)) {
      expect(коды.has(находка.этап), находка.код).toBe(true);
    }
  });

  it('у каждой причины запрета правки поля назван уровень или назван отказ считать её бедой', () => {
    // Предохранитель от регресса: новая причина, заведённая в настройках и забытая в правилах,
    // должна давать красный тест, а не молчаливый пропуск.
    const карта = кусокКода('УРОВЕНЬ_ЗАПРЕТА');

    for (const причина of Object.keys(НАСТРОЙКИ['полеЗаперто'])) {
      expect(карта.includes(`${причина}:`), причина).toBe(true);
    }
  });

  it('у каждой правки защитной проверки шапки назван уровень явно, а не «всё прочее»', () => {
    // Иначе новое защитное правило станет блокером молча: без слова человеку и без теста.
    const карта = кусокКода('УРОВЕНЬ_ПРАВКИ');
    const защита = fs.readFileSync(path.join(EDITOR, 'src/core/safeFrontmatter.mjs'), 'utf8');
    const коды = [...защита.matchAll(/код: '([^']+)'/g)].map((найдено) => найдено[1]);

    expect(коды.length).toBeGreaterThan(0);
    for (const код of коды) expect(карта.includes(`${код}:`), код).toBe(true);
  });
});
