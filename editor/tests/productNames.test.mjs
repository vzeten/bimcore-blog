// Названия товаров из карточек, уже стоящих в статьях: чем список магазина дополняется и чем нет.
import {describe, expect, it} from 'vitest';

import {названияИзСтатей, сНазваниямиСтатей} from '../src/core/productNames.mjs';

/** Карточка написана так же, как её пишут статьи сайта: столбиком, с картинкой выражением. */
const карточка = ({код = '100', имя, описание = 'Комнатные растения и кашпо.'} = {}) => `---
title: A
---

import productPreview from './product.png';

<ProductCard
  name="${имя}"
  eyebrow="Набор семейств Revit"
  description="${описание}"
  image={productPreview}
  imageAlt="${имя} — превью набора"
  buyUrl="https://bimcore.one/products/plants-revit-families"
  ecwidProductId="${код}"
/>

текст
`;

const ТОВАР = {id: '100', названия: {en: 'Plant Revit Families'}, адрес: 'https://bimcore.one/p', картинка: 'https://cdn/p.png'};

describe('названия товаров из статей', () => {
  it('слово статьи достаётся языку этой статьи и коду её товара', () => {
    const названия = названияИзСтатей([{локаль: 'ru', текст: карточка({имя: 'Растения для Revit'})}]);

    expect(названия.get('100')).toEqual({ru: 'Растения для Revit'});
  });

  it('описание карточки в общий список не собирается: оно свойство своей статьи', () => {
    const названия = названияИзСтатей([{локаль: 'ru', текст: карточка({имя: 'Растения для Revit'})}]);

    expect(JSON.stringify([...названия])).not.toContain('кашпо');
  });

  it('пустого языка у статьи вне корней сайта нет: догадки, чей это язык, не будет', () => {
    const названия = названияИзСтатей([{локаль: null, текст: карточка({имя: 'Растения для Revit'})}]);

    expect(названия.size).toBe(0);
  });

  it('две статьи одного языка спорят о названии — язык не даёт слова, поле остаётся человеку', () => {
    const названия = названияИзСтатей([
      {локаль: 'ru', текст: карточка({имя: 'Растения для Revit'})},
      {локаль: 'ru', текст: карточка({имя: 'Растения'})},
    ]);

    expect(названия.has('100')).toBe(false);
  });

  it('спор одного языка не отнимает слово у другого', () => {
    const названия = названияИзСтатей([
      {локаль: 'ru', текст: карточка({имя: 'Растения для Revit'})},
      {локаль: 'ru', текст: карточка({имя: 'Растения'})},
      {локаль: 'en', текст: карточка({имя: 'Plant Revit Families'})},
    ]);

    expect(названия.get('100')).toEqual({en: 'Plant Revit Families'});
  });

  it('повтор одного и того же слова спором не считается', () => {
    const названия = названияИзСтатей([
      {локаль: 'ru', текст: карточка({имя: 'Растения для Revit'})},
      {локаль: 'ru', текст: карточка({имя: 'Растения для Revit', описание: 'Другое описание.'})},
    ]);

    expect(названия.get('100')).toEqual({ru: 'Растения для Revit'});
  });

  it('спор о слове наружу не выходит вовсе: подставлять его каталогу нечем', () => {
    const спорные = названияИзСтатей([
      {локаль: 'ru', текст: карточка({имя: 'Растения для Revit'})},
      {локаль: 'ru', текст: карточка({имя: 'Растения'})},
    ]);
    const [товар] = сНазваниямиСтатей([{...ТОВАР, названия: {en: 'Plant Revit Families', ru: ''}}], спорные);

    expect(товар.названия).toEqual({en: 'Plant Revit Families', ru: ''});
  });

  it('карточка без кода товара или без названия слов не даёт', () => {
    const названия = названияИзСтатей([
      {локаль: 'ru', текст: карточка({имя: '', код: '100'})},
      {локаль: 'ru', текст: карточка({имя: 'Кресла', код: ''})},
    ]);

    expect(названия.size).toBe(0);
  });

  it('каталог дополняется языком, которого в магазине нет', () => {
    const [товар] = сНазваниямиСтатей([ТОВАР], new Map([['100', {ru: 'Растения для Revit'}]]));

    expect(товар.названия).toEqual({en: 'Plant Revit Families', ru: 'Растения для Revit'});
  });

  it('слово магазина статьёй не переписывается, а пустое — дополняется', () => {
    const [товар] = сНазваниямиСтатей(
      [{...ТОВАР, названия: {en: 'Plant Revit Families', ru: ''}}],
      new Map([['100', {en: 'Растения', ru: 'Растения для Revit'}]]),
    );

    expect(товар.названия).toEqual({en: 'Plant Revit Families', ru: 'Растения для Revit'});
  });

  it('товар, о котором в статьях не написано, остаётся прежним', () => {
    const [товар] = сНазваниямиСтатей([ТОВАР], new Map([['999', {ru: 'Кресла для Revit'}]]));

    expect(товар).toEqual(ТОВАР);
  });
});
