// Имя каждого теста повторяет формулировку правила.
// Очередь автосохранения проверяется без React: что записано, что нет, и что вернул уход из статьи.
import {describe, expect, it, vi} from 'vitest';
import {createAutosaveQueue, type DraftPayload} from '../src/ui/autosaveQueue';

const правка = (over: Partial<DraftPayload> = {}): DraftPayload => ({
  path: 'docs/a/index.mdx',
  body: 'набранный текст',
  frontmatterRaw: 'title: A',
  отпечатокБазы: 'ОТП1',
  ...over,
});

/** Запись черновика, подменённая на запоминающую: что ушло и с каким исходом. */
function хранилище(успех = true) {
  const записано: DraftPayload[] = [];

  const запись = vi.fn(async (данные: DraftPayload, effects: {ok: () => void; fail: (r: string) => void}) => {
    записано.push(данные);
    if (успех) effects.ok();
    else effects.fail('сервер недоступен');
  });

  return {записано, запись: запись as never};
}

describe('уход из статьи не теряет ждущую правку', () => {
  it('ждущая правка дописывается немедленно, а не выбрасывается', async () => {
    // Между последней буквой и таймером лежат секунды, и в них умещается уход в другую статью.
    const {записано, запись} = хранилище();
    const очередь = createAutosaveQueue(() => 3, () => undefined, запись);

    очередь.запланировать(правка());
    const получилось = await очередь.дописать();

    expect(получилось).toBe(true);
    expect(записано).toHaveLength(1);
    expect(записано[0].body).toBe('набранный текст');
  });

  it('дописывать нечего — запросов не шлём и уходу не мешаем', async () => {
    const {записано, запись} = хранилище();
    const очередь = createAutosaveQueue(() => 3, () => undefined, запись);

    expect(await очередь.дописать()).toBe(true);
    expect(записано).toHaveLength(0);
  });

  it('не удалось дописать — уходящий получает отказ, а не молчаливую потерю', async () => {
    const {запись} = хранилище(false);
    const состояния: string[] = [];
    const очередь = createAutosaveQueue(() => 3, (state) => состояния.push(state), запись);

    очередь.запланировать(правка());

    expect(await очередь.дописать()).toBe(false);
    expect(состояния.at(-1)).toBe('неУдалосьАвтосохранить');
  });

  it('правка, набранная во время самого дописывания, тоже уезжает в черновик', async () => {
    // Человек печатает, пока идёт принудительная запись перед уходом: очередь обязана
    // отправить и эту правку, а не стереть её вместе с записанной.
    const записано: DraftPayload[] = [];
    let очередь: ReturnType<typeof createAutosaveQueue>;
    let разДопечатал = false;

    const запись = vi.fn(async (данные: DraftPayload, effects: {ok: () => void; fail: (r: string) => void}) => {
      записано.push(данные);
      if (!разДопечатал) {
        разДопечатал = true;
        очередь.запланировать(правка({body: 'допечатал во время записи'}));
      }
      effects.ok();
    });

    очередь = createAutosaveQueue(() => 3, () => undefined, запись as never);
    очередь.запланировать(правка());

    expect(await очередь.дописать()).toBe(true);
    expect(записано.map((з) => з.body)).toEqual(['набранный текст', 'допечатал во время записи']);
  });

  it('ответ «устарел» не считается записью: правка уезжает снова с новой меткой', async () => {
    // Сервер отвечает 200, но на диск ничего не кладёт: там уже что-то новее. Считать это
    // успехом значит отпустить человека из статьи, хотя работа никуда не записалась.
    const записано: DraftPayload[] = [];
    const запись = vi.fn(async (данные: DraftPayload, effects: {ok: (о?: unknown) => void; fail: (r: string) => void}) => {
      записано.push(данные);
      effects.ok(записано.length === 1 ? {устарел: true} : {автосохранено: 'ок'});
    });
    const очередь = createAutosaveQueue(() => 3, () => undefined, запись as never);

    очередь.запланировать(правка());

    expect(await очередь.дописать()).toBe(true);
    expect(записано).toHaveLength(2);
    expect(Date.parse(записано[1].правкаОт ?? '')).toBeGreaterThan(Date.parse(записано[0].правкаОт ?? ''));
  });

  it('запись подряд отклоняется как устаревшая — уход из статьи не разрешается', async () => {
    // Бесконечно перештамповывать нельзя: иначе уход застрянет навсегда. Один повтор — и отказ.
    const записано: DraftPayload[] = [];
    const запись = vi.fn(async (данные: DraftPayload, effects: {ok: (о?: unknown) => void; fail: (r: string) => void}) => {
      записано.push(данные);
      effects.ok({устарел: true});
    });
    const очередь = createAutosaveQueue(() => 3, () => undefined, запись as never);

    очередь.запланировать(правка());

    expect(await очередь.дописать()).toBe(false);
    expect(записано).toHaveLength(2);
  });

  it('два ухода подряд не шлют две записи одной и той же правки', async () => {
    // Быстрые два нажатия (например, по двум версиям подряд) иначе отправили бы два запроса.
    const записано: DraftPayload[] = [];
    const запись = vi.fn(async (данные: DraftPayload, effects: {ok: () => void; fail: (r: string) => void}) => {
      записано.push(данные);
      await new Promise((r) => setTimeout(r, 10));
      effects.ok();
    });
    const очередь = createAutosaveQueue(() => 3, () => undefined, запись as never);

    очередь.запланировать(правка());
    const [первый, второй] = await Promise.all([очередь.дописать(), очередь.дописать()]);

    expect(записано).toHaveLength(1);
    expect([первый, второй]).toEqual([true, true]);
  });

  it('после отказа правка остаётся ждущей: вторая попытка уйти снова её записывает', async () => {
    // Иначе второй уход сказал бы «всё записано» и увёл человека из статьи с пустым черновиком.
    const записано: DraftPayload[] = [];
    let падать = true;
    const запись = vi.fn(async (данные: DraftPayload, effects: {ok: () => void; fail: (r: string) => void}) => {
      записано.push(данные);
      if (падать) effects.fail('сервер недоступен');
      else effects.ok();
    });
    const очередь = createAutosaveQueue(() => 3, () => undefined, запись as never);

    очередь.запланировать(правка());
    expect(await очередь.дописать()).toBe(false);

    падать = false;
    expect(await очередь.дописать()).toBe(true);
    expect(записано).toHaveLength(2);
    expect(записано[1].body).toBe('набранный текст');
  });

  it('дописанная правка не пишется второй раз по таймеру', async () => {
    const {записано, запись} = хранилище();
    const очередь = createAutosaveQueue(() => 0, () => undefined, запись);

    очередь.запланировать(правка());
    await очередь.дописать();
    await new Promise((r) => setTimeout(r, 20));

    expect(записано).toHaveLength(1);
  });

  it('правка, набранная во время дописывания, тоже не теряется', async () => {
    // Человек печатает, пока идёт уход из статьи: эта буква попадает в очередь уже после первого
    // дописывания, и второе дописывание перед сменой статьи обязано её записать.
    const {записано, запись} = хранилище();
    const очередь = createAutosaveQueue(() => 3, () => undefined, запись);

    очередь.запланировать(правка());
    await очередь.дописать();
    очередь.запланировать(правка({body: 'дописал во время ухода'}));
    await очередь.дописать();

    expect(записано.map((з) => з.body)).toEqual(['набранный текст', 'дописал во время ухода']);
  });

  it('отмена по-прежнему выбрасывает ждущую правку: работа уже в файле', async () => {
    // После настоящего сохранения черновик не нужен — это другой случай, и он не меняется.
    const {записано, запись} = хранилище();
    const очередь = createAutosaveQueue(() => 0, () => undefined, запись);

    очередь.запланировать(правка());
    очередь.отменить();
    await new Promise((r) => setTimeout(r, 20));

    expect(записано).toHaveLength(0);
  });
});

describe('очередь после обычной записи по таймеру', () => {
  it('записанная по таймеру правка перестаёт быть ждущей: второй раз её не шлём', async () => {
    // Иначе вход в просмотр версии послал бы тот же черновик второй раз — уже как новое действие.
    const {записано, запись} = хранилище();
    const очередь = createAutosaveQueue(() => 0, () => undefined, запись);

    очередь.запланировать(правка());
    await new Promise((r) => setTimeout(r, 20));
    expect(записано).toHaveLength(1);

    await очередь.дописать();

    expect(записано).toHaveLength(1);
  });
});

describe('порядок правок во времени', () => {
  it('две правки в одну и ту же миллисекунду получают строго разные метки времени', async () => {
    // Часы останавливаем нарочно: правки правда могут случиться в одну миллисекунду, а порядок
    // черновиков держится на метке — при равных метках сервер не отличил бы старую запись от новой.
    const часы = vi.spyOn(Date, 'now').mockReturnValue(Date.parse('2026-08-05T12:00:00.000Z'));
    const {записано, запись} = хранилище();
    const очередь = createAutosaveQueue(() => 3, () => undefined, запись);

    очередь.запланировать(правка({body: 'первая'}));
    await очередь.дописать();
    очередь.запланировать(правка({body: 'вторая'}));
    await очередь.дописать();

    const [первая, вторая] = записано.map((з) => Date.parse(з.правкаОт ?? ''));
    expect(вторая).toBeGreaterThan(первая);
    часы.mockRestore();
  });

  it('ручное сохранение берёт метку из тех же часов, что и очередь', async () => {
    // Иначе автосохранение и сохранение могут получить одинаковую метку, и сервер не поймёт,
    // какая из двух записей запоздала.
    const часы = vi.spyOn(Date, 'now').mockReturnValue(Date.parse('2026-08-05T12:00:00.000Z'));
    const {записано, запись} = хранилище();
    const очередь = createAutosaveQueue(() => 3, () => undefined, запись);

    очередь.запланировать(правка());
    await очередь.дописать();
    const отСохранения = очередь.метка();

    expect(Date.parse(отСохранения)).toBeGreaterThan(Date.parse(записано[0].правкаОт ?? ''));
    часы.mockRestore();
  });
});

describe('интервал автосохранения', () => {
  it('интервал берётся в момент правки, а не при создании очереди', async () => {
    // Настройки приходят с сервера после первой отрисовки: очередь, запомнившая ноль,
    // писала бы черновик на каждую букву.
    const {записано, запись} = хранилище();
    let интервал = 0;
    const очередь = createAutosaveQueue(() => интервал, () => undefined, запись);

    интервал = 60;
    очередь.запланировать(правка());
    await new Promise((r) => setTimeout(r, 30));

    expect(записано).toHaveLength(0);
    очередь.отменить();
  });
});
