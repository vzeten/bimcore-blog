// Имя каждого теста повторяет формулировку правила.
// Обновление страницы возвращает в ту же статью; если открыть её нельзя, окно объясняет причину
// и только тогда переводит запись истории в реестр (ED-039).
import {describe, expect, it, vi} from 'vitest';

import {восстановитьПриЗапуске, статьяИзИстории} from '../src/ui/restoreOnLoad';

const ход = (состояние: unknown, открыть: (path: string) => Promise<boolean>) => {
  const поставитьРеестр = vi.fn();
  const открыватель = vi.fn(открыть);
  return {
    ход: {состояние: состояние as never, открыть: открыватель, поставитьРеестр},
    открыватель,
    поставитьРеестр,
  };
};

describe('что открыто по состоянию записи истории', () => {
  it('статья в состоянии — её путь', () => {
    expect(статьяИзИстории({вид: 'статья', path: 'blog/proba/index.mdx'})).toBe('blog/proba/index.mdx');
  });

  it('реестр, пустое и чужое состояние — открывать нечего', () => {
    for (const состояние of [null, {вид: 'реестр'}, {}, {вид: 'статья'}, {вид: 'статья', path: ''}]) {
      expect(статьяИзИстории(состояние as never)).toBeNull();
    }
  });

  it('путь не строкой статьёй не считается: такое состояние оставил кто-то другой', () => {
    expect(статьяИзИстории({вид: 'статья', path: 42} as never)).toBeNull();
    expect(статьяИзИстории('строка' as never)).toBeNull();
  });
});

describe('восстановление статьи при запуске окна', () => {
  it('статья открылась — запись истории не трогается: следующее обновление вернёт ту же статью', async () => {
    const {ход: х, открыватель, поставитьРеестр} = ход({вид: 'статья', path: 'blog/proba/index.mdx'}, async () => true);

    await expect(восстановитьПриЗапуске(х)).resolves.toBe('blog/proba/index.mdx');
    expect(открыватель).toHaveBeenCalledWith('blog/proba/index.mdx');
    expect(поставитьРеестр).not.toHaveBeenCalled();
  });

  it('статью открыть не вышло — реестр ставится после попытки, а причину человек уже увидел', async () => {
    const порядок: string[] = [];
    const {ход: х, поставитьРеестр} = ход({вид: 'статья', path: 'blog/нет/index.mdx'}, async () => {
      порядок.push('открыть');
      return false;
    });
    х.поставитьРеестр = () => порядок.push('реестр');

    await expect(восстановитьПриЗапуске(х)).resolves.toBeNull();
    expect(порядок).toEqual(['открыть', 'реестр']);
    expect(поставитьРеестр).not.toHaveBeenCalled();
  });

  it('в состоянии не статья — окно сразу остаётся реестром и ничего не открывает', async () => {
    const {ход: х, открыватель, поставитьРеестр} = ход({вид: 'реестр'}, async () => true);

    await expect(восстановитьПриЗапуске(х)).resolves.toBeNull();
    expect(открыватель).not.toHaveBeenCalled();
    expect(поставитьРеестр).toHaveBeenCalledTimes(1);
  });
});
