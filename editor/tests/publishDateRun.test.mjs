// Имя каждого теста повторяет формулировку правила.
//
// Дата записи блога в ходе публикации: ход окна разговаривает с НАСТОЯЩИМИ ручками сервера, а те —
// с настоящим git во временном репозитории и «сервером сайта» рядом. Проверяется то, ради чего
// правило заведено: дата появляется в ФАЙЛЕ до обязательных проверок, а значит её видят и проверки,
// и состав, и коммит.
import {afterEach, beforeEach, describe, expect, it} from 'vitest';
import fs from 'node:fs';
import path from 'node:path';

import {проверить} from '../src/ui/publishRun';
import {запомнитьКоммит, запомнитьПоказ} from '../src/adapters/pushMemory.mjs';
import {ЖДАТЬ_GIT} from './saveHarness.mjs';
import {EN as ДОКИ, СТАТЬЯ, дверь, поставитьДатуВФайл, среда, убратьПесочницы, ход} from './runHarness.mjs';

const БЛОГ_EN = 'blog/proba/index.mdx';
const БЛОГ_RU = 'i18n/ru/docusaurus-plugin-content-blog/proba/index.mdx';
const ЗАПИСЬ = (дата = null) => [
  '---',
  'title: "Проба"',
  // Адрес записи блога пишется без ведущего слэша: с ним обязательные проверки останавливают выпуск.
  'slug: proba',
  'description: "Про пробу."',
  ...(дата === null ? [] : [`date: ${дата}`]),
  'authors: [ivan]',
  '---',
  '',
  'Текст записи.',
  '',
].join('\n');

const дата = (repo, rel) => /^date: (.+)$/m.exec(fs.readFileSync(path.join(repo, rel), 'utf8'))?.[1] ?? null;
const сегодня = () => {
  const сейчас = new Date();
  const два = (число) => String(число).padStart(2, '0');
  return `${сейчас.getFullYear()}-${два(сейчас.getMonth() + 1)}-${два(сейчас.getDate())}`;
};

beforeEach(() => {
  запомнитьКоммит(null);
  запомнитьПоказ(null);
});

afterEach(() => {
  запомнитьКоммит(null);
  запомнитьПоказ(null);
  убратьПесочницы();
});

describe('дата записи блога в ходе публикации', () => {
  it('записи на сайте ещё нет — публикация сама ставит сегодняшний день, и проверки видят файл с датой', async () => {
    // На сайте лежит только статья документации: запись блога человек ещё не выпускал.
    const с = await среда({файлы: {[ДОКИ]: СТАТЬЯ, [БЛОГ_EN]: ЗАПИСЬ()}, вКоммите: [ДОКИ]});
    const записка = [];
    const х = ход(дверь(с, записка), [], поставитьДатуВФайл(с.repo, БЛОГ_EN));

    const вопрос = await проверить(БЛОГ_EN, false, х);

    expect(вопрос.вид).toBe('проверено');
    expect(дата(с.repo, БЛОГ_EN)).toBe(сегодня());
    // Дата спрашивается ДО обязательных проверок: иначе проверенное и собранное разошлось бы с тем,
    // что уедет на сайт.
    const адреса = записка.map((шаг) => шаг.адрес);
    expect(адреса.indexOf('/api/publish/date')).toBeLessThan(адреса.indexOf('/api/prepare'));
  }, ЖДАТЬ_GIT);

  it('запись уже на сайте — остаётся её дата с сайта, даже если в файле человека даты нет', async () => {
    const с = await среда({файлы: {[ДОКИ]: СТАТЬЯ, [БЛОГ_EN]: ЗАПИСЬ('2026-01-05')}, вКоммите: [ДОКИ, БЛОГ_EN]});
    // Дату в файле стёрли руками. Программа обязана вернуть ту, что стоит на сайте, а не сегодняшнюю:
    // смена даты вышедшей записи двигает её в ленте и в карте сайта.
    fs.writeFileSync(path.join(с.repo, БЛОГ_EN), `${ЗАПИСЬ()}\nНовая строка.\n`, 'utf8');
    const х = ход(дверь(с, []), [], поставитьДатуВФайл(с.repo, БЛОГ_EN));

    const вопрос = await проверить(БЛОГ_EN, false, х);

    expect(вопрос.вид).toBe('проверено');
    expect(дата(с.repo, БЛОГ_EN)).toBe('2026-01-05');
  }, ЖДАТЬ_GIT);

  it('опубликован соседний язык — перевод получает его дату: языковые версии стоят в ленте одним днём', async () => {
    const с = await среда({
      файлы: {[ДОКИ]: СТАТЬЯ, [БЛОГ_EN]: ЗАПИСЬ('2026-07-12'), [БЛОГ_RU]: ЗАПИСЬ()},
      вКоммите: [ДОКИ, БЛОГ_EN],
    });
    const х = ход(дверь(с, []), [], поставитьДатуВФайл(с.repo, БЛОГ_RU));

    const вопрос = await проверить(БЛОГ_RU, false, х);

    expect(вопрос.вид).toBe('проверено');
    expect(дата(с.repo, БЛОГ_RU)).toBe('2026-07-12');
    // Дата английской версии не тронута: публикуется только открытая локаль.
    expect(дата(с.repo, БЛОГ_EN)).toBe('2026-07-12');
  }, ЖДАТЬ_GIT);

  it('состав выпуска отказывает, пока дата не поставлена: проверенное и записанное обязаны совпасть', async () => {
    // Запрос мимо окна — с датой, которой в файле нет. Сервер не считает состав по такому файлу:
    // иначе проверки судили бы об одном, а на сайт уехало бы другое.
    const с = await среда({файлы: {[ДОКИ]: СТАТЬЯ, [БЛОГ_EN]: ЗАПИСЬ()}, вКоммите: [ДОКИ]});
    const дверьСервера = дверь(с, []);

    await expect(дверьСервера('/api/release', {path: БЛОГ_EN}))
      .rejects.toMatchObject({ответ: {код: 'датаУстарела'}});
  }, ЖДАТЬ_GIT);

  it('у статьи документации даты не бывает: ход её не ставит и файл не трогает', async () => {
    const с = await среда({файлы: {[ДОКИ]: СТАТЬЯ}, вКоммите: [ДОКИ]});
    fs.writeFileSync(path.join(с.repo, ДОКИ), `${СТАТЬЯ}\nНовая строка.\n`, 'utf8');
    const до = fs.readFileSync(path.join(с.repo, ДОКИ), 'utf8');
    const х = ход(дверь(с, []), [], async () => {
      throw new Error('дату документации ставить нельзя');
    });

    const вопрос = await проверить(ДОКИ, false, х);

    expect(вопрос.вид).toBe('проверено');
    expect(fs.readFileSync(path.join(с.repo, ДОКИ), 'utf8')).toBe(до);
  }, ЖДАТЬ_GIT);
});
