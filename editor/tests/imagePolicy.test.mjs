import {describe, expect, it} from 'vitest';

import {
  выигрышСтоитЗамены, килобайты, рецепты, решениеПоКартинке,
} from '../src/core/imagePolicy.mjs';

const НАСТРОЙКИ = {
  картинки: {
    ширинаПикселей: 1100,
    качествоPng: 92,
    усилиеПалитры: 7,
    размывкаPng: 0.8,
    качествоJpg: 87,
    выигрышПроцентов: 10,
    выигрышКилобайт: 10,
    пределГифМегабайт: 5,
  },
};

const решение = (что) => решениеПоКартинке({...что, настройки: НАСТРОЙКИ}).действие;

describe('решение по картинке', () => {
  it('JPG и PNG всегда идут в обработку: что легче — решают сами представления', () => {
    expect(решение({формат: 'jpg', анимация: false, байтов: 20 * 1024})).toBe('обработать');
    expect(решение({формат: 'png', анимация: false, байтов: 3_000_000})).toBe('обработать');
  });

  it('чужой формат программа не трогает вовсе', () => {
    expect(решение({формат: 'gif', анимация: false, байтов: 20 * 1024})).toBe('оставить');
  });

  it('анимация не обрабатывается ни при каком весе', () => {
    expect(решение({формат: 'gif', анимация: true, байтов: 4 * 1024 * 1024})).toBe('оставить');
    expect(решение({формат: 'png', анимация: true, байтов: 900 * 1024})).toBe('оставить');
  });

  it('анимация ровно в предел принимается, а тяжелее — отвергается своей причиной', () => {
    expect(решение({формат: 'gif', анимация: true, байтов: 5 * 1024 * 1024})).toBe('оставить');

    const отказ = решениеПоКартинке({
      формат: 'gif', анимация: true, байтов: 5 * 1024 * 1024 + 1, настройки: НАСТРОЙКИ,
    });
    expect(отказ.действие).toBe('отказать');
    expect(отказ.причина).toBe('анимацияТяжёлая');
  });
});

describe('рецепты представлений', () => {
  it('у непрозрачной картинки два представления — PNG и JPG', () => {
    const набор = рецепты({прозрачная: false, настройки: НАСТРОЙКИ});
    expect(набор.map((р) => р.формат)).toEqual(['png', 'jpg']);
    expect(набор[0].качество).toBe(92);
    expect(набор[1].качество).toBe(87);
  });

  it('у прозрачной картинки JPG не готовится: он прозрачности не хранит', () => {
    expect(рецепты({прозрачная: true, настройки: НАСТРОЙКИ}).map((р) => р.формат)).toEqual(['png']);
  });
});

describe('стоит ли менять файл человека', () => {
  const стоит = (было, стало) => выигрышСтоитЗамены({былоБайт: было, сталоБайт: стало, настройки: НАСТРОЙКИ});

  it('заметный выигрыш — меняем', () => {
    // Живой случай владельца: картинка 1782 КБ и её JPG-представление 210 КБ.
    expect(стоит(1_782_158, 209_567)).toBe(true);
  });

  it('выигрыш меньше десятой части — оставляем файл человека', () => {
    // Снимок из Telegram: новое представление отличается меньше чем на процент.
    expect(стоит(209_577, 208_900)).toBe(false);
  });

  it('доля большая, но килобайтов мало — оставляем: трогать файл не за что', () => {
    expect(стоит(30 * 1024, 21 * 1024)).toBe(false);
  });

  it('килобайтов много, но доля мала — тоже оставляем', () => {
    expect(стоит(1000 * 1024, 960 * 1024)).toBe(false);
  });

  it('оба условия ровно на границе — меняем', () => {
    expect(стоит(100 * 1024, 90 * 1024)).toBe(true);
  });

  it('новое представление тяжелее — менять нечего', () => {
    // Живой случай владельца: 25 109 Б против 26 219 Б у нового PNG.
    expect(стоит(25_109, 26_219)).toBe(false);
  });
});

describe('вес для человека', () => {
  it('считается по 1024, как в проводнике', () => {
    expect(килобайты(204800)).toBe(200);
    expect(килобайты(1536)).toBe(2);
  });
});
