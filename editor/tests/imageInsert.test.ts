// Имя каждого теста повторяет формулировку правила.
// Куда встаёт новая картинка: место задаёт курсор, но картинка ложится отдельным блоком.
import {describe, expect, it} from 'vitest';
import {местоВставкиКартинки} from '../src/core/imageInsert';

const SRC = './img-02.png';
const УЗЕЛ = `![](${SRC})`;

/** Текст после вставки: правило возвращает правку, применяет её редактор. */
function применить(текст: string, курсор: number, перевод = '\n'): string {
  const место = местоВставкиКартинки(текст, курсор, SRC, перевод);
  return текст.slice(0, место.from) + место.insert + текст.slice(место.from);
}

describe('место новой картинки', () => {
  it('курсор посреди абзаца — картинка встаёт под абзацем, слово не разрывается', () => {
    const текст = 'Первый абзац про Revit.\n\nВторой абзац.';

    expect(применить(текст, 5)).toBe(`Первый абзац про Revit.\n\n${УЗЕЛ}\n\nВторой абзац.`);
  });

  it('курсор в начале статьи — картинка встаёт перед первым абзацем, а не в конце', () => {
    const текст = 'Первый абзац.\n\nВторой абзац.';

    expect(применить(текст, 0)).toBe(`${УЗЕЛ}\n\nПервый абзац.\n\nВторой абзац.`);
  });

  it('курсор в конце статьи — картинка встаёт последней, и под ней есть строка для текста', () => {
    const текст = 'Первый абзац.\n\nПоследний абзац.';

    const место = местоВставкиКартинки(текст, текст.length, SRC, '\n');
    expect(применить(текст, текст.length)).toBe(`Первый абзац.\n\nПоследний абзац.\n\n${УЗЕЛ}\n`);
    // Курсор стоит на строке под картинкой: на самой строке картинки места для текста нет.
    expect(место.курсор).toBe(место.узелДо + 1);
  });

  it('курсор в строке таблицы — картинка встаёт под всей таблицей, строки таблицы целы', () => {
    const текст = 'Текст.\n\n| Что | Как |\n|---|---|\n| раз | два |\n\nДальше.';
    const внутриТаблицы = текст.indexOf('| раз') + 3;

    expect(применить(текст, внутриТаблицы))
      .toBe(`Текст.\n\n| Что | Как |\n|---|---|\n| раз | два |\n\n${УЗЕЛ}\n\nДальше.`);
  });

  it('курсор в заголовке — картинка встаёт сразу под заголовком, а не под всем разделом', () => {
    // Заголовок и абзац идут вплотную, без пустой строки: так написаны живые статьи сайта.
    const текст = '## Раздел\nПервая строка раздела.\nВторая строка.';

    expect(применить(текст, 4)).toBe(`## Раздел\n\n${УЗЕЛ}\n\nПервая строка раздела.\nВторая строка.`);
  });

  it('курсор в пункте списка — картинка встаёт под всем списком, список не разрывается', () => {
    const текст = 'Перед списком.\n\n- первый пункт\n- второй пункт\n- третий пункт\n\nПосле списка.';
    const внутриПункта = текст.indexOf('- второй') + 5;

    expect(применить(текст, внутриПункта))
      .toBe(`Перед списком.\n\n- первый пункт\n- второй пункт\n- третий пункт\n\n${УЗЕЛ}\n\nПосле списка.`);
  });

  it('курсор на строке-продолжении пункта — картинка встаёт под всем списком, а не между пунктами', () => {
    // Длинный пункт перенесён на вторую строку: сама по себе она выглядит обычным текстом,
    // но принадлежит списку, и картинка не должна разрезать его пополам.
    const текст = 'Перед списком.\n\n- первый пункт\n  его продолжение\n- второй пункт\n\nПосле списка.';
    const наПродолжении = текст.indexOf('его продолжение') + 4;

    expect(применить(текст, наПродолжении))
      .toBe(`Перед списком.\n\n- первый пункт\n  его продолжение\n- второй пункт\n\n${УЗЕЛ}\n\nПосле списка.`);
  });

  it('ограда другого вида внутри куска кода его не закрывает', () => {
    // Внутри `~~~~` строка ``` — это код, а не конец куска: иначе картинка легла бы внутрь кода.
    const текст = 'Текст.\n\n~~~~\n```\nкод\n```\n~~~~\n\nДальше.';

    expect(применить(текст, текст.indexOf('код') + 1))
      .toBe(`Текст.\n\n~~~~\n\`\`\`\nкод\n\`\`\`\n~~~~\n\n${УЗЕЛ}\n\nДальше.`);
  });

  it('строка с подписью языка кусок кода не закрывает', () => {
    // Закрывающая ограда идёт без хвоста: `` ```js `` внутри куска — это код, а не его конец.
    const текст = 'Текст.\n\n```\n```js\nконст = 1;\n```\n\nДальше.';

    expect(применить(текст, текст.indexOf('конст') + 2))
      .toBe(`Текст.\n\n\`\`\`\n\`\`\`js\nконст = 1;\n\`\`\`\n\n${УЗЕЛ}\n\nДальше.`);
  });

  it('курсор на пустой строке — картинка встаёт ровно на неё, пустые строки вокруг остаются', () => {
    const текст = 'Абзац.\n\nСледующий абзац.';

    expect(применить(текст, 7)).toBe(`Абзац.\n\n${УЗЕЛ}\n\nСледующий абзац.`);
  });

  it('курсор на строке другой картинки — новая встаёт под ней, а не внутрь её разметки', () => {
    const текст = `Текст.\n\n![Старая](./img-01.jpg)\n\nДальше.`;
    const внутриСтарой = текст.indexOf('![Старая') + 4;

    expect(применить(текст, внутриСтарой))
      .toBe(`Текст.\n\n![Старая](./img-01.jpg)\n\n${УЗЕЛ}\n\nДальше.`);
  });

  it('курсор внутри многострочного блока разметки — картинка встаёт под всем блоком', () => {
    // Так записан `<ProductCard …/>` в живых статьях: несколько строк без пустых между ними.
    const текст = '<ProductCard\n  name="Стулья"\n  buyUrl="https://bimcore.one"\n/>\n\nДальше.';

    expect(применить(текст, текст.indexOf('name') + 2))
      .toBe(`<ProductCard\n  name="Стулья"\n  buyUrl="https://bimcore.one"\n/>\n\n${УЗЕЛ}\n\nДальше.`);
  });

  it('курсор внутри огороженного куска кода — картинка встаёт после ограды, а не внутрь кода', () => {
    const текст = 'Текст.\n\n```js\nconst a = 1;\n\nconst b = 2;\n```\n\nДальше.';

    expect(применить(текст, текст.indexOf('const a') + 3))
      .toBe(`Текст.\n\n\`\`\`js\nconst a = 1;\n\nconst b = 2;\n\`\`\`\n\n${УЗЕЛ}\n\nДальше.`);
  });

  it('пустая статья — картинка становится её первой строкой', () => {
    expect(применить('', 0)).toBe(`${УЗЕЛ}\n`);
  });

  it('файл в windows-виде получает windows-переводы строк, а не смесь', () => {
    const текст = 'Первый абзац.\r\n\r\nВторой абзац.';

    expect(применить(текст, 5, '\r\n')).toBe(`Первый абзац.\r\n\r\n${УЗЕЛ}\r\n\r\nВторой абзац.`);
  });

  it('вставка ничего не заменяет: выделенный человеком текст остаётся на месте', () => {
    const текст = 'Первый абзац.\n\nВторой абзац.';
    const место = местоВставкиКартинки(текст, 5, SRC, '\n');

    // Правка только дописывает: в тексте после вставки исходный текст присутствует целиком.
    expect(место.insert).toContain(УЗЕЛ);
    expect(применить(текст, 5).replace(место.insert, '')).toBe(текст);
  });

  it('границы узла показывают саму картинку: по ним открывается панель alt-текста', () => {
    const текст = 'Абзац.';
    const место = местоВставкиКартинки(текст, 3, SRC, '\n');
    const после = текст.slice(0, место.from) + место.insert + текст.slice(место.from);

    expect(после.slice(место.узелОт, место.узелДо)).toBe(УЗЕЛ);
  });

  it('курсор за пределами текста не роняет правило, а прижимается к его границе', () => {
    expect(применить('Абзац.', 999)).toBe(`Абзац.\n\n${УЗЕЛ}\n`);
  });
});
