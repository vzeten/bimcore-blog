// Имя каждого теста повторяет формулировку правила.
// Каркас публикации: чем станет сайт, когда человек публикует одну открытую языковую версию.
import {describe, expect, it} from 'vitest';

import {ДИСК, СОЗДАНО, каркасПлана, публикацияВозможна} from '../src/core/publishPlan.mjs';
import {ВЕРСИЯ, КАРТИНКА, СОСТОЯНИЕ} from '../src/core/release.mjs';
import {ВНЕ_КАНОНА} from '../src/core/articleKind.mjs';

const RU = 'i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba/index.mdx';
const EN = 'docs/lessons/proba/index.mdx';
const ES = 'i18n/es/docusaurus-plugin-content-docs/current/lessons/proba/index.mdx';

const версия = (путь, локаль, ещё = {}) => ({
  путь, локаль, состояние: null, файлыПапки: [], статейВПапке: 1, ...ещё,
});

const язык = (локаль, путь, опубликован, ещё = {}) => ({
  локаль, путь, опубликован, заглушка: `байты ${локаль}`, ...ещё,
});

/** Обычный случай: оба соседа давно на сайте, публикуется русская версия. */
const каркас = (ещё = {}) => каркасПлана({
  открытаяВерсия: версия(RU, 'ru'),
  наСайте: true,
  языки: [язык('ru', RU, false), язык('en', EN, true), язык('es', ES, true)],
  ...ещё,
});

const пути = (итог, назначение) => итог.записи
  .filter((запись) => назначение === undefined || запись.назначение === назначение)
  .map((запись) => запись.путь);

const запись = (итог, путь) => итог.записи.find((строка) => строка.путь === путь);

describe('каркас публикации: открытый язык', () => {
  it('оба соседа уже на сайте — уезжает только открытая версия', () => {
    const итог = каркас();

    expect(пути(итог, ВЕРСИЯ)).toEqual([RU]);
    expect(итог.отказ).toBe(null);
    expect(публикацияВозможна(итог)).toBe(true);
  });

  it('открыт английский — уезжает английский', () => {
    const итог = каркас({
      открытаяВерсия: версия(EN, 'en'),
      языки: [язык('ru', RU, true), язык('en', EN, false), язык('es', ES, true)],
    });

    expect(пути(итог, ВЕРСИЯ)).toEqual([EN]);
  });

  it('открыт испанский — уезжает испанский', () => {
    const итог = каркас({
      открытаяВерсия: версия(ES, 'es'),
      языки: [язык('ru', RU, true), язык('en', EN, true), язык('es', ES, false)],
    });

    expect(пути(итог, ВЕРСИЯ)).toEqual([ES]);
  });

  it('готовность и картинки уезжают у открытой версии', () => {
    const итог = каркас({
      открытаяВерсия: версия(RU, 'ru', {
        состояние: 'i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba/_state.json',
        файлыПапки: ['i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba/cover.png'],
      }),
    });

    expect(пути(итог, СОСТОЯНИЕ)).toEqual(['i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba/_state.json']);
    expect(пути(итог, КАРТИНКА)).toEqual(['i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba/cover.png']);
  });

  it('у записи с диска текста нет: байты положит материализация, правило их не знает', () => {
    expect(запись(каркас(), RU)).toMatchObject({источник: ДИСК, текст: null, режим: '100644'});
  });

  it('локальные соседи на решение не влияют ничем: подсунутый список версий правило не читает', () => {
    // Единственный способ рассказать правилу о соседе — перечень языков, а он говорит только про
    // сайт. Даже если адаптер по привычке подложит факты соседей, результат обязан не измениться:
    // именно на этом держится обещание «начатый перевод не уезжает и не мешает».
    const соседи = [версия(EN, 'en'), версия(ES, 'es', {файлыПапки: ['i18n/es/.../cover.png']})];

    expect(каркас({версии: соседи})).toEqual(каркас());
  });

  it('беда самой открытой версии по-прежнему запрещает публикацию', () => {
    const итог = каркас({открытаяВерсия: версия(RU, 'ru', {статейВПапке: 2})});

    expect(итог.разрывы.map((разрыв) => разрыв.причина)).toEqual(['папкаНеОдна']);
    expect(публикацияВозможна(итог)).toBe(false);
  });

  it('открытая версия вне канона даёт прежний разрыв', () => {
    expect(каркас({открытаяВерсия: версия(RU, 'ru', {вид: ВНЕ_КАНОНА})}).разрывы
      .map((разрыв) => разрыв.причина)).toEqual(['внеКанона']);
  });

  it('открытой версии нет вовсе — состав не доказан', () => {
    for (const пусто of [undefined, null, {}, {путь: ''}]) {
      expect(каркасПлана({открытаяВерсия: пусто, наСайте: true, языки: []}).разрывы)
        .toEqual([{причина: 'нетВерсий'}]);
    }
  });

  it('порядок записей — по кодам знаков, а не по языку системы', () => {
    const итог = каркас({языки: [язык('ru', RU, false), язык('en', EN, false), язык('es', ES, false)]});

    expect(пути(итог)).toEqual([...пути(итог)].sort());
  });
});

describe('каркас публикации: язык, которого на сайте нет', () => {
  it('файла языка нет на сайте — в каркас идёт созданная заглушка', () => {
    const итог = каркас({языки: [язык('ru', RU, false), язык('en', EN, true), язык('es', ES, false)]});

    expect(пути(итог, ВЕРСИЯ)).toEqual([ES, RU]);
    expect(запись(итог, ES)).toMatchObject({источник: СОЗДАНО, текст: 'байты es', локаль: 'es'});
    expect(публикацияВозможна(итог)).toBe(true);
  });

  it('у созданной заглушки уезжает только её файл: ни готовности, ни картинок', () => {
    const итог = каркас({языки: [язык('ru', RU, false), язык('en', EN, true), язык('es', ES, false)]});

    expect(пути(итог, СОСТОЯНИЕ)).toEqual([]);
    expect(пути(итог, КАРТИНКА)).toEqual([]);
  });

  it('старая статья без одной локали получает её заглушку: это принятая постепенная миграция', () => {
    const итог = каркас({языки: [язык('ru', RU, true), язык('en', EN, true), язык('es', ES, false)]});

    expect(пути(итог, ВЕРСИЯ)).toEqual([ES, RU]);
  });

  it('нет ни одного языка на сайте — заглушки получают все, кроме открытого', () => {
    const итог = каркас({языки: [язык('ru', RU, false), язык('en', EN, false), язык('es', ES, false)]});

    expect(пути(итог, ВЕРСИЯ)).toEqual([EN, ES, RU]);
    expect(запись(итог, RU).источник).toBe(ДИСК);
    expect(запись(итог, EN).источник).toBe(СОЗДАНО);
    expect(запись(итог, ES).источник).toBe(СОЗДАНО);
  });

  it('языки берутся из настроек: четвёртый работает без правки кода', () => {
    const DE = 'i18n/de/docusaurus-plugin-content-docs/current/lessons/proba/index.mdx';
    const итог = каркас({
      языки: [язык('ru', RU, false), язык('en', EN, true), язык('es', ES, true), язык('de', DE, false)],
    });

    expect(пути(итог, ВЕРСИЯ)).toEqual([DE, RU]);
    expect(запись(итог, DE).текст).toBe('байты de');
  });
});

describe('каркас публикации: незнание и порча всегда отказ', () => {
  const отказ = (ещё) => каркас(ещё).отказ;
  const факт = (чего, локали = []) => ({код: 'фактыНеизвестны', локали, чего});

  it('статья вне сайта публикуется одной открытой версией и заглушек не знает', () => {
    const итог = каркас({наСайте: false, языки: []});

    expect(пути(итог, ВЕРСИЯ)).toEqual([RU]);
    expect(итог.отказ).toBe(null);
  });

  it('признака «статья на сайте» нет вовсе — это не песочница, а незнание', () => {
    for (const место of [undefined, null, 'да', 0]) expect(отказ({наСайте: место})).toEqual(факт('место'));
  });

  it('пустой или испорченный перечень языков молча защиту не отменяет', () => {
    for (const языки of [undefined, null, [], 'ru', [{}], [язык('', RU, false)]]) {
      expect(отказ({языки}).код).toBe('фактыНеизвестны');
      expect(отказ({языки}).чего).toBe('языки');
    }
  });

  it('повтор языка в перечне — отказ', () => {
    expect(отказ({языки: [язык('ru', RU, false), язык('ru', EN, true)]})).toEqual(факт('языки', ['ru']));
  });

  it('открытого языка в перечне нет — отказ', () => {
    expect(отказ({языки: [язык('en', EN, true), язык('es', ES, true)]})).toEqual(факт('языки', ['ru']));
  });

  it('перечень описывает другую статью: путь открытого языка не совпал — отказ', () => {
    expect(отказ({языки: [язык('ru', 'docs/lessons/other/index.mdx', false), язык('en', EN, true)]}))
      .toEqual(факт('своя', ['ru']));
  });

  it('про язык не удалось узнать, есть ли он на сайте, — отказ, а не догадка', () => {
    for (const ответ of [undefined, null, 'да', 1]) {
      expect(отказ({языки: [язык('ru', RU, false), язык('en', EN, ответ)]}))
        .toEqual(факт('опубликованная', ['en']));
    }
  });

  it('путь языка уводит за пределы репозитория или записан не так, как лежит, — отказ', () => {
    const плохие = ['', '../чужое.mdx', 'docs/../static/x.mdx', 'docs\\lessons\\proba\\index.mdx', '/docs/x.mdx', 'docs//x.mdx'];

    for (const путь of плохие) {
      expect(отказ({языки: [язык('ru', RU, false), язык('en', путь, false)]})).toEqual(факт('путь', ['en']));
    }
  });

  it('два языка с одним путём — отказ: заглушка легла бы поверх соседа', () => {
    expect(отказ({языки: [язык('ru', RU, false), язык('en', EN, false), язык('es', EN, false)]}))
      .toEqual(факт('столкновение', ['es']));
  });

  it('путь языка совпал с файлом открытой версии — отказ: заглушка стёрла бы работу человека', () => {
    const СОСТОЯНИЕ_RU = 'i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba/_state.json';
    const открытая = версия(RU, 'ru', {состояние: СОСТОЯНИЕ_RU, файлыПапки: [`${RU.replace('/index.mdx', '')}/cover.png`]});

    expect(отказ({открытаяВерсия: открытая, языки: [язык('ru', RU, false), язык('en', СОСТОЯНИЕ_RU, false)]}))
      .toEqual(факт('столкновение', ['en']));
    expect(отказ({
      открытаяВерсия: открытая,
      языки: [язык('ru', RU, false), язык('en', `${RU.replace('/index.mdx', '')}/cover.png`, false)],
    })).toEqual(факт('столкновение', ['en']));
  });

  it('текста заглушки для языка не задано — отказ, а не выдуманный текст', () => {
    for (const заглушка of [undefined, null, '', 5]) {
      expect(отказ({языки: [язык('ru', RU, false), язык('en', EN, false, {заглушка})]}))
        .toEqual({код: 'нетШаблонаЗаглушки', локали: ['en'], чего: null});
    }
  });

  it('негодный путь самой открытой версии — отказ, и записей не отдаётся вовсе', () => {
    const плохие = ['../чужое.mdx', 'C:/outside.mdx', 'docs\\lessons\\proba\\index.mdx', 'docs/./proba/index.mdx'];

    for (const путь of плохие) {
      const итог = каркас({открытаяВерсия: версия(путь, 'ru'), языки: [язык('ru', путь, false)]});

      expect(итог.отказ).toEqual(факт('свойПуть', ['ru']));
      expect(итог.записи).toEqual([]);
    }
  });

  it('негодные готовность и картинка открытой версии — тот же отказ, даже вне сайта', () => {
    const сПлохимСостоянием = версия(RU, 'ru', {состояние: '../чужое/_state.json'});
    const сПлохойКартинкой = версия(RU, 'ru', {файлыПапки: ['C:/чужое/cover.png']});

    for (const открытаяВерсия of [сПлохимСостоянием, сПлохойКартинкой]) {
      // Вне сайта заглушек нет, и прежде такой путь уехал бы в git вовсе без проверки.
      const внеСайта = каркасПлана({открытаяВерсия, наСайте: false, языки: []});

      expect(внеСайта.отказ).toEqual(факт('свойПуть', ['ru']));
      expect(внеСайта.записи).toEqual([]);
      expect(каркас({открытаяВерсия}).отказ).toEqual(факт('свойПуть', ['ru']));
    }
  });

  it('один и тот же путь дважды в составе открытой версии — отказ', () => {
    const итог = каркас({открытаяВерсия: версия(RU, 'ru', {файлыПапки: [RU]})});

    expect(итог.отказ).toEqual(факт('свойПуть', ['ru']));
    expect(итог.записи).toEqual([]);
  });

  it('буква диска в пути языка тоже отвергается', () => {
    expect(отказ({языки: [язык('ru', RU, false), язык('en', 'C:/outside.mdx', false)]}))
      .toEqual(факт('путь', ['en']));
  });

  it('при отказе открытая версия из каркаса не исчезает, но публикация запрещена', () => {
    const итог = каркас({языки: [язык('ru', RU, false), язык('en', EN, false, {заглушка: ''})]});

    expect(пути(итог, ВЕРСИЯ)).toEqual([RU]);
    expect(публикацияВозможна(итог)).toBe(false);
  });
});
