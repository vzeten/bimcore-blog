// Имя каждого теста повторяет формулировку правила.
// Имя нового файла картинки: свободный номер по шаблону из настроек, без перенумерации чужих.
import {describe, expect, it} from 'vitest';
import {имяКартинки, номерКартинки, следующийНомерКартинки} from '../src/core/imageName.mjs';

const ШАБЛОН = 'img-{номер}';
/** Сколько знаков в номере — настройка (`картинки.знаковВНомере`); сегодня их два. */
const ЗНАКОВ = 2;

describe('имя новой картинки', () => {
  it('имя собирается по шаблону из настроек, а не по образцу в коде', () => {
    expect(имяКартинки(ШАБЛОН, 3, 'png', ЗНАКОВ)).toBe('img-03.png');
    expect(имяКартинки('рисунок{номер}', 3, 'png', ЗНАКОВ)).toBeNull();
    expect(имяКартинки('photo-{номер}', 12, 'gif', ЗНАКОВ)).toBe('photo-12.gif');
  });

  it('число знаков в номере берётся из настроек, а не задано в программе', () => {
    expect(имяКартинки(ШАБЛОН, 7, 'png', 3)).toBe('img-007.png');
    expect(имяКартинки(ШАБЛОН, 7, 'png', 1)).toBe('img-7.png');
    // Негодное число знаков — не повод писать имя как получится.
    expect(имяКартинки(ШАБЛОН, 7, 'png', 0)).toBeNull();
    expect(имяКартинки(ШАБЛОН, 7, 'png', undefined)).toBeNull();
  });

  it('подчёркивание в имени не допускается: разрешены латиница, цифры и дефис', () => {
    expect(имяКартинки('img_{номер}', 1, 'png', ЗНАКОВ)).toBeNull();
  });

  it('номер длиннее числа знаков не обрезается', () => {
    expect(имяКартинки(ШАБЛОН, 123, 'jpg', ЗНАКОВ)).toBe('img-123.jpg');
  });

  it('шаблон без места под номер именем не становится', () => {
    // Молча положить файл под именем без номера нельзя: второй такой файл затёр бы первый.
    expect(имяКартинки('img', 1, 'png', ЗНАКОВ)).toBeNull();
    expect(имяКартинки('img-{номер}-{номер}', 1, 'png', ЗНАКОВ)).toBeNull();
    expect(имяКартинки(undefined, 1, 'png', ЗНАКОВ)).toBeNull();
  });

  it('шаблон, дающий небезопасное имя, отвергается: такое имя роняет сборку сайта', () => {
    expect(имяКартинки('картинка-{номер}', 1, 'png', ЗНАКОВ)).toBeNull();
    expect(имяКартинки('img {номер}', 1, 'png', ЗНАКОВ)).toBeNull();
    expect(имяКартинки('../img-{номер}', 1, 'png', ЗНАКОВ)).toBeNull();
    expect(имяКартинки('img/{номер}', 1, 'png', ЗНАКОВ)).toBeNull();
  });
});

describe('номер занятой картинки', () => {
  it('номер считается по шаблону независимо от расширения файла', () => {
    expect(номерКартинки('img-07.jpg', ШАБЛОН)).toBe(7);
    expect(номерКартинки('img-07.PNG', ШАБЛОН)).toBe(7);
    expect(номерКартинки('img-07.gif', ШАБЛОН)).toBe(7);
  });

  it('ведущие нули на номер не влияют: img-1 и img-01 — один и тот же номер', () => {
    expect(номерКартинки('img-1.png', ШАБЛОН)).toBe(1);
    expect(номерКартинки('img-01.png', ШАБЛОН)).toBe(1);
  });

  it('собственное имя картинки номера не занимает', () => {
    // Говорящие имена законны (решение 2026-08-14) и в подсчёте номеров не участвуют.
    expect(номерКартинки('arcat.jpg', ШАБЛОН)).toBeNull();
    expect(номерКартинки('cover.png', ШАБЛОН)).toBeNull();
    expect(номерКартинки('img-.png', ШАБЛОН)).toBeNull();
    expect(номерКартинки('img-01', ШАБЛОН)).toBeNull();
  });
});

describe('следующий свободный номер', () => {
  it('берётся следующий за самым большим занятым, дыры в середине не заполняются', () => {
    // Номер из дыры мог стоять в ссылке уже опубликованной статьи.
    expect(следующийНомерКартинки(['img-01.png', 'img-03.jpg'], ШАБЛОН)).toBe(4);
  });

  it('номер считается занятым при любом расширении: img-01.jpg закрывает и img-01.png', () => {
    expect(следующийНомерКартинки(['img-01.jpg'], ШАБЛОН)).toBe(2);
  });

  it('в папке без картинок программы номер начинается с первого', () => {
    expect(следующийНомерКартинки(['index.mdx', 'arcat.jpg'], ШАБЛОН)).toBe(1);
    expect(следующийНомерКартинки([], ШАБЛОН)).toBe(1);
  });
});
