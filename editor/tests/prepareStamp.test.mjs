// Имя каждого теста повторяет формулировку правила.
//
// Ради чего набор заведён: отпечаток подготовки описывал только файл статьи и её дерево, а сами
// ПРАВИЛА проверок в него не входили. Сервер читает настройки заново на каждый запрос, поэтому
// правка `settings.json` между вопросом человеку и записью меняла вердикт, не меняя отпечатка:
// человек соглашался по одним правилам, а запись шла по другим, и снимок этого не замечал.
import {afterEach, describe, expect, it} from 'vitest';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

import {
  НАСТРОЙКИ_ПРОВЕРОК, подготовкаОткрытой, сверитьПодготовку, срезОднойВерсии,
} from '../src/adapters/prepareStamp.mjs';

const EDITOR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const НАСТРОЙКИ = JSON.parse(fs.readFileSync(path.join(EDITOR, 'settings.json'), 'utf8'));

const RU = 'i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba/index.mdx';
const ГОДНАЯ = '---\ntitle: "Проба"\nslug: /lessons/proba\ndescription: "Про пробу."\n---\n\nТекст.\n';
const БЕЗ_ОПИСАНИЯ = '---\ntitle: "Проба"\nslug: /lessons/proba\n---\n\nТекст.\n';

const песочницы = [];

afterEach(() => {
  while (песочницы.length > 0) fs.rmSync(песочницы.pop(), {recursive: true, force: true});
});

/** Репозиторий с одной статьёй на диске. */
function среда(содержимое = ГОДНАЯ, ещё = {}) {
  const repo = fs.mkdtempSync(path.join(os.tmpdir(), 'editor-stamp-'));
  песочницы.push(repo);

  for (const [rel, текст] of Object.entries({[RU]: содержимое, ...ещё})) {
    fs.mkdirSync(path.join(repo, path.dirname(rel)), {recursive: true});
    fs.writeFileSync(path.join(repo, rel), текст, 'utf8');
  }

  return repo;
}

const отпечаток = (repo, settings = НАСТРОЙКИ) => срезОднойВерсии(repo, RU, settings)?.отпечаток;

/** Другое значение того же вида: список остаётся списком, объект объектом, число числом. */
function иное(значение) {
  if (Array.isArray(значение)) return [...значение, ...значение.slice(0, 1)];
  if (значение !== null && typeof значение === 'object') return {...значение, 'лишний': 'иное'};
  if (typeof значение === 'number') return значение + 1;

  return `${значение}-иное`;
}

describe('отпечаток подготовки описывает и правила проверок', () => {
  it('правка настройки проверок меняет отпечаток: вердикт по ней и выносится', () => {
    const repo = среда();
    const было = отпечаток(repo);

    const стало = отпечаток(repo, {...НАСТРОЙКИ, 'пределОписания': 200});

    expect(стало).not.toBe(было);
  });

  it('каждая настройка, объявленная в снимке, на отпечаток и вправду влияет', () => {
    const repo = среда();
    const было = отпечаток(repo);
    // Спрашивается САМ снимок, а не перечень-пол: в него входит и то, что правила прочитали сверх
    // перечня. Иначе автоматически добавленный ключ мог бы в отпечаток не попасть, и никто бы этого
    // не заметил.
    const ключи = срезОднойВерсии(repo, RU, НАСТРОЙКИ).ключи;
    expect(ключи).toEqual(expect.arrayContaining(НАСТРОЙКИ_ПРОВЕРОК));

    for (const ключ of ключи) {
      // Значение меняется, но вид его сохраняется: правила должны дожить до отпечатка, а не упасть
      // на подставленном мусоре — упавшее правило доказало бы совсем не то.
      const стало = отпечаток(repo, {...НАСТРОЙКИ, [ключ]: иное(НАСТРОЙКИ[ключ])});

      expect(`${ключ}: ${стало}`).not.toBe(`${ключ}: ${было}`);
    }
  });

  it('настройка, к проверкам не относящаяся, отпечаток не трогает', () => {
    const repo = среда();
    const было = отпечаток(repo);

    // Слова окна публикации проверок не касаются: правка фразы не должна останавливать ход.
    const стало = отпечаток(repo, {
      ...НАСТРОЙКИ,
      'публикация': {...НАСТРОЙКИ['публикация'], 'вопрос': 'Другой вопрос?'},
    });

    expect(стало).toBe(было);
  });

  it('перестановка ключей в настройке сменой правил не считается', () => {
    const repo = среда();
    const было = отпечаток(repo);
    const наоборот = Object.fromEntries(Object.entries(НАСТРОЙКИ['локали']).reverse());
    expect(Object.keys(наоборот)).not.toEqual(Object.keys(НАСТРОЙКИ['локали']));

    const стало = отпечаток(repo, {...НАСТРОЙКИ, 'локали': наоборот});

    expect(стало).toBe(было);
  });

  /**
   * Настройки, у которых `контент` спрашивает незаявленный ключ названным способом. Так выглядит
   * правило, решившее по настройке, которой нет в перечне.
   */
  const хитрые = (способ, значение) => {
    const свои = {...НАСТРОЙКИ, 'лишний': значение};
    Object.defineProperty(свои, 'контент', {
      get() {
        способ(this);

        return НАСТРОЙКИ['контент'];
      },
      enumerable: true,
      configurable: true,
    });

    return свои;
  };

  // Спросить настройку можно четырьмя способами, и только первый идёт через чтение. Наблюдай
  // программа один его — правило, решающее по НАЛИЧИЮ ключа, меняло бы вердикт при прежнем
  // отпечатке.
  const способы = {
    'чтением': (свои) => void свои['лишний'],
    'проверкой наличия': (свои) => void ('лишний' in свои),
    'своим ли ключом': (свои) => void Object.hasOwn(свои, 'лишний'),
    'разбором описания': (свои) => void Object.getOwnPropertyDescriptor(свои, 'лишний'),
    'перечислением ключей': (свои) => void Object.keys(свои),
    // Голое перечисление имён спрашивает только сам список и описаний не разбирает: без своей
    // ловушки оно прошло бы мимо наблюдения, хотя ответ его зависит от каждого ключа настроек.
    'перечислением имён': (свои) => void Object.getOwnPropertyNames(свои),
  };

  for (const [имя, способ] of Object.entries(способы)) {
    it(`настройка, спрошенная правилами ${имя}, попадает в снимок сама`, () => {
      // Главное свойство боевого заслона: полнота не держится ни на перечне, ни на памяти человека.
      const repo = среда();

      const первый = подготовкаОткрытой(repo, RU, хитрые(способ, 'первое')).срез;

      expect(НАСТРОЙКИ_ПРОВЕРОК).not.toContain('лишний');
      expect(первый.ключи).toContain('лишний');
      expect(подготовкаОткрытой(repo, RU, хитрые(способ, 'второе')).срез.отпечаток)
        .not.toBe(первый.отпечаток);
    });
  }

  it('отсутствующий ключ, пустой ключ и ключ со значением — три разных снимка', () => {
    // Правило спрашивает НАЛИЧИЕ ключа, и `in` различает все три положения. Слепи отпечаток их в
    // одно — вердикт менялся бы при прежнем снимке, и наблюдение за наличием теряло бы смысл.
    const repo = среда();
    const положение = (правки) => {
      const свои = {...НАСТРОЙКИ, ...правки};
      Object.defineProperty(свои, 'контент', {
        get() {
          void ('лишний' in this);

          return НАСТРОЙКИ['контент'];
        },
        enumerable: true,
        configurable: true,
      });

      return подготовкаОткрытой(repo, RU, свои).срез;
    };

    const нет = положение({});
    const пусто = положение({'лишний': undefined});
    const пустое = положение({'лишний': null});
    const значение = положение({'лишний': 'что-то'});

    expect(нет.ключи).toContain('лишний');
    const отпечатки = [нет, пусто, пустое, значение].map((срез) => срез.отпечаток);
    expect(new Set(отпечатки).size).toBe(4);
  });

  it('за настоящую подготовку не прочитано НИ ОДНОЙ настройки вне перечня', () => {
    // Перечень-пол обязан оставаться честным: сегодня правила читают ровно его. Проверка не зависит
    // от того, как настройку написали в коде, — обёртка видит любое чтение верхнего ключа.
    const прочитанные = new Set();
    const обёртка = new Proxy(НАСТРОЙКИ, {
      get(цель, ключ, приёмник) {
        if (typeof ключ === 'string') прочитанные.add(ключ);

        return Reflect.get(цель, ключ, приёмник);
      },
    });

    // Разные виды записи гоняются нарочно: у каждой свои ветки правил. Одной статьи мало — редкая
    // ветка прочитала бы свою настройку и осталась бы незамеченной.
    const виды = [
      {файлы: {}, путь: RU},
      {файлы: {}, путь: RU, содержимое: БЕЗ_ОПИСАНИЯ},
      {файлы: {'i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba/дочерняя/index.mdx': ГОДНАЯ}, путь: RU},
      {файлы: {'docs/intro.mdx': '---\ntitle: "Главная"\nslug: /\ndescription: "Главная."\n---\n\nТекст.\n'}, путь: 'docs/intro.mdx'},
      {файлы: {'blog/zapis/index.mdx': '---\ntitle: "Запись"\ndescription: "Про запись."\n---\n\nТекст.\n'}, путь: 'blog/zapis/index.mdx'},
      {файлы: {}, путь: RU, содержимое: '---\ntitle: "Проба"\nslug: /lessons/proba\ndescription: "Страница-заглушка. Перевод этой статьи ещё не готов."\nkeywords: []\n---\n\nТекст.\n'},
    ];

    for (const вид of виды) {
      const repo = среда(вид.содержимое ?? ГОДНАЯ, вид.файлы);
      подготовкаОткрытой(repo, вид.путь, обёртка);
    }

    expect([...прочитанные].filter((ключ) => !НАСТРОЙКИ_ПРОВЕРОК.includes(ключ))).toEqual([]);
  });

  it('перечень настроек снимка полон: правила подготовки не читают ничего сверх него', () => {
    // Второй слой, статический: он видит и те ветки правил, до которых живой прогон не дошёл.
    // Перечень файлов НЕ выписан руками — он считается обходом импортов от самого правила подготовки,
    // поэтому новый вспомогательный модуль ядра попадает под проверку сам, без правки теста.
    const ядро = path.join(EDITOR, 'src', 'core');
    const модули = new Set();
    const очередь = ['prepare.mjs'];
    while (очередь.length > 0) {
      const имя = очередь.pop();
      if (модули.has(имя)) continue;
      модули.add(имя);
      const код = fs.readFileSync(path.join(ядро, имя), 'utf8');
      for (const [, сосед] of код.matchAll(/from\s+'\.\/([\wА-Яа-яЁё]+\.mjs)'/g)) очередь.push(сосед);
    }
    expect(модули.size).toBeGreaterThan(5);

    const читаемые = new Set();
    for (const имя of модули) {
      const код = fs.readFileSync(path.join(ядро, имя), 'utf8');
      // Обе записи ключа: и в скобках любой кавычкой, и через точку.
      for (const [, ключ] of код.matchAll(/settings\s*\[\s*['"]([^'"]+)['"]\s*\]/g)) читаемые.add(ключ);
      for (const [, ключ] of код.matchAll(/settings\.([A-Za-zА-Яа-яЁё_][\wА-Яа-яЁё]*)/g)) читаемые.add(ключ);
    }

    expect([...читаемые].sort()).toEqual([...НАСТРОЙКИ_ПРОВЕРОК].sort());
  });
});

describe('зелёная подготовка доказывается сервером, а не окном', () => {
  it('статья с препятствием заслон не проходит даже с верным отпечатком', () => {
    const repo = среда(БЕЗ_ОПИСАНИЯ);

    const ответ = сверитьПодготовку({repo, rel: RU, settings: НАСТРОЙКИ, ждали: отпечаток(repo)});

    expect(ответ.код).toBe('подготовкаНеПрошла');
    expect(ответ.блокеры.map((находка) => находка.код)).toContain('описаниеПусто');
  });

  it('исправная статья с верным отпечатком проходит', () => {
    const repo = среда();

    expect(сверитьПодготовку({repo, rel: RU, settings: НАСТРОЙКИ, ждали: отпечаток(repo)}).код).toBe(null);
  });

  it('пустой и отсутствующий отпечаток — «нет снимка», а не тихий пропуск', () => {
    const repo = среда();

    expect(сверитьПодготовку({repo, rel: RU, settings: НАСТРОЙКИ, ждали: ''}).код).toBe('нетСнимка');
    expect(сверитьПодготовку({repo, rel: RU, settings: НАСТРОЙКИ, ждали: undefined}).код).toBe('нетСнимка');
  });

  it('чужой отпечаток — «статья изменилась», а не отказ по существу', () => {
    const repo = среда();

    expect(сверитьПодготовку({repo, rel: RU, settings: НАСТРОЙКИ, ждали: 'чужое'}).код).toBe('статьяИзменилась');
  });

  it('вердикт заслона тот же, что показан человеку: правило одно на всех', () => {
    const repo = среда(БЕЗ_ОПИСАНИЯ);

    const своё = подготовкаОткрытой(repo, RU, НАСТРОЙКИ);
    const ответ = сверитьПодготовку({repo, rel: RU, settings: НАСТРОЙКИ, ждали: своё.срез.отпечаток});

    expect(своё.прошла).toBe(false);
    expect(ответ.блокеры).toEqual(своё.находки.filter((находка) => находка.уровень === 'блокер'));
  });
});
