// Имя каждого теста повторяет формулировку правила.
// Что окно делает после удачной записи, когда сервер свёл его работу с внешней правкой.
// Правило вынесено из хука отдельной функцией, чтобы проверяться результатом, а не отрисовкой
// (SPEC 5.2.1): рендерера в зависимостях нет и добавлять его запрещено (SPEC 4.10).
import {describe, expect, it} from 'vitest';

import {исходЗаписи} from '../src/ui/useSaving';

describe('база окна двигается только на доказанное', () => {
  it('сервер записал ровно то, что послало окно, — база сдвигается на записанное', () => {
    expect(исходЗаписи({свелось: false, печаталДальше: false})).toBe('сдвинуть');
  });

  it('человек печатал дальше, но сведения не было — база всё равно сдвигается', () => {
    // В файле лежит именно тот снимок, который послало окно; ждущая правка уедет от него.
    expect(исходЗаписи({свелось: false, печаталДальше: true})).toBe('сдвинуть');
  });

  it('сервер свёл стороны, человек больше не набирал — записанное кладётся в окно', () => {
    // Иначе окно показывало бы свой текст, а в файле лежал бы другой, и это звалось «Сохранено».
    expect(исходЗаписи({свелось: true, печаталДальше: false})).toBe('подставить');
  });

  it('сервер свёл стороны, а человек печатал дальше — база окна остаётся прежней', () => {
    // Набранное не знает про внешнюю правку. Уйди оно на сервер с отпечатком НОВОГО файла —
    // расхождения сервер не увидел бы и молча стёр внешнее изменение. Со старой базой он сведёт
    // всё заново: одинаковую часть узнает, внешнюю оставит, дописанное добавит.
    expect(исходЗаписи({свелось: true, печаталДальше: true})).toBe('оставить');
  });
});
