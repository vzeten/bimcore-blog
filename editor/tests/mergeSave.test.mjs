// Имя каждого теста повторяет формулировку правила.
// Сохранение при внешней правке файла: что попадает на диск, что в историю и что в спор.
import {afterEach, describe, expect, it} from 'vitest';
import fs from 'node:fs';
import path from 'node:path';

import {countSnapshots, fingerprint, loadDraft} from '../src/adapters/draftStore.mjs';
import {прочитатьСпор} from '../src/adapters/conflictStore.mjs';
import {фиксироватьВнешнюю} from '../src/adapters/externalVersion.mjs';
import {
  ЖДАТЬ_GIT, EN, RU, НАСТРОЙКИ, подготовить, прочитать, сохранить, статья, убратьПесочницы,
} from './saveHarness.mjs';

afterEach(убратьПесочницы);

/** Настоящая фиксация внешней правки: та же, что стоит в сервере. */
const фиксация = (среда) => async (rel, обязательно) => фиксироватьВнешнюю({
  repo: среда.repo, settings: НАСТРОЙКИ, git: среда.git, ref: 'HEAD', rel, обязательно,
});

/** Написать в файл мимо программы — так делает внешний ИИ в соседнем окне. */
const снаружи = (среда, rel, текст) => fs.writeFileSync(path.join(среда.repo, rel), текст, 'utf8');

describe('внешняя правка сводится с работой человека', () => {
  it('правки разных мест объединяются сами, и человека ни о чём не спрашивают', async () => {
    const среда = await подготовить({[RU]: статья('title: A', '\nпервый\n\nвторой\n')});
    const база = fingerprint(прочитать(среда, RU));
    снаружи(среда, RU, статья('title: A', '\nпервый\n\nВНЕШНИЙ\n'));

    const ответ = await сохранить(среда, {
      rel: RU, шапка: 'title: A', тело: '\nМОЙ\n\nвторой\n', отпечаток: база, фиксировать: фиксация(среда),
    });

    expect(ответ.code).toBe(200);
    expect(прочитать(среда, RU)).toBe(статья('title: A', '\nМОЙ\n\nВНЕШНИЙ\n'));
    expect(прочитатьСпор(среда.repo, НАСТРОЙКИ, RU)).toBeNull();
  }, ЖДАТЬ_GIT);

  it('внешняя версия попадает в историю до того, как файл заменён сведённым текстом', async () => {
    const среда = await подготовить({[RU]: статья('title: A', '\nпервый\n\nвторой\n')});
    const база = fingerprint(прочитать(среда, RU));
    снаружи(среда, RU, статья('title: A', '\nпервый\n\nВНЕШНИЙ\n'));

    await сохранить(среда, {
      rel: RU, шапка: 'title: A', тело: '\nМОЙ\n\nвторой\n', отпечаток: база, фиксировать: фиксация(среда),
    });

    // Две версии: чужая и наша. Потеряй программа первую — вернуться к чужому тексту было бы неоткуда.
    expect(countSnapshots(среда.repo, НАСТРОЙКИ, RU)).toBe(2);
  }, ЖДАТЬ_GIT);

  it('сведённый текст записывается только в открытую версию, соседняя не трогается', async () => {
    const среда = await подготовить({
      [RU]: статья('title: A', '\nпервый\n'),
      [EN]: статья('title: A', '\nпервый\n'),
    });
    const былоEN = прочитать(среда, EN);
    const база = fingerprint(прочитать(среда, RU));
    снаружи(среда, RU, статья('title: A\nimage: ./cover.png', '\nпервый\n'));

    await сохранить(среда, {
      rel: RU, шапка: 'title: A', тело: '\nМОЙ\n', отпечаток: база, фиксировать: фиксация(среда),
    });

    expect(прочитать(среда, RU)).toContain('image: ./cover.png');
    expect(прочитать(среда, RU)).toContain('МОЙ');
    expect(прочитать(среда, EN)).toBe(былоEN);
  }, ЖДАТЬ_GIT);
});

describe('пересечение останавливает запись этой версии', () => {
  it('оба правили одно место — файл не переписан, а стороны легли на диск', async () => {
    const среда = await подготовить({[RU]: статья('title: A', '\nтекст\n')});
    const база = fingerprint(прочитать(среда, RU));
    const чужое = статья('title: A', '\nвнешний текст\n');
    снаружи(среда, RU, чужое);

    const ответ = await сохранить(среда, {
      rel: RU, шапка: 'title: A', тело: '\nмой текст\n', отпечаток: база, фиксировать: фиксация(среда),
    });

    expect(ответ.code).toBe(409);
    expect(ответ.data['спор']['вид']).toBe('спор');
    expect(прочитать(среда, RU)).toBe(чужое);

    const спор = прочитатьСпор(среда.repo, НАСТРОЙКИ, RU);
    expect(спор['база'].body).toBe('\nтекст\n');
    expect(спор['мои'].body).toBe('\nмой текст\n');
    expect(спор['внешние'].body).toBe('\nвнешний текст\n');
  }, ЖДАТЬ_GIT);

  it('работа человека ложится в черновик его версии прежде, чем ручка ответит спором', async () => {
    const среда = await подготовить({[RU]: статья('title: A', '\nтекст\n')});
    const база = fingerprint(прочитать(среда, RU));
    снаружи(среда, RU, статья('title: A', '\nвнешний текст\n'));

    await сохранить(среда, {
      rel: RU, шапка: 'title: A', тело: '\nмой текст\n', отпечаток: база, фиксировать: фиксация(среда),
    });

    expect(loadDraft(среда.repo, НАСТРОЙКИ, RU)['body']).toBe('\nмой текст\n');
  }, ЖДАТЬ_GIT);

  it('спор одной языковой версии не мешает сохранить соседнюю', async () => {
    const среда = await подготовить({
      [RU]: статья('title: A', '\nтекст\n'),
      [EN]: статья('title: A', '\nтекст\n'),
    });
    const база = fingerprint(прочитать(среда, RU));
    снаружи(среда, RU, статья('title: A', '\nвнешний текст\n'));
    await сохранить(среда, {
      rel: RU, шапка: 'title: A', тело: '\nмой текст\n', отпечаток: база, фиксировать: фиксация(среда),
    });

    const ответ = await сохранить(среда, {
      rel: EN, шапка: 'title: A', тело: '\nанглийская правка\n', фиксировать: фиксация(среда),
    });

    expect(ответ.code).toBe(200);
    expect(прочитать(среда, EN)).toContain('английская правка');
  }, ЖДАТЬ_GIT);
});

describe('без доказанной базы программа не сводит стороны сама', () => {
  it('базы нет нигде — обе стороны целы, файл не переписан, сведения не было', async () => {
    const среда = await подготовить({[RU]: статья('title: A', '\nтекст\n')});
    const чужое = статья('title: A', '\nвнешний текст\n');
    снаружи(среда, RU, чужое);

    const ответ = await сохранить(среда, {
      rel: RU, шапка: 'title: A', тело: '\nмой текст\n', отпечаток: 'ОТПЕЧАТКА-ТАКОГО-НЕТ',
      фиксировать: фиксация(среда),
    });

    expect(ответ.code).toBe(409);
    expect(ответ.data['спор']['вид']).toBe('безБазы');
    expect(прочитать(среда, RU)).toBe(чужое);
    expect(loadDraft(среда.repo, НАСТРОЙКИ, RU)['body']).toBe('\nмой текст\n');
  }, ЖДАТЬ_GIT);

  it('версию удалили снаружи — программа её не создаёт заново, но работу человека хранит', async () => {
    const среда = await подготовить({[RU]: статья('title: A', '\nтекст\n')});
    const база = fingerprint(прочитать(среда, RU));
    // Снимок появляется от внешней правки: без него программа эту версию не знает вовсе.
    снаружи(среда, RU, статья('title: A', '\nвнешний текст\n'));
    await фиксация(среда)(RU, false);
    fs.rmSync(path.join(среда.repo, RU));

    const ответ = await сохранить(среда, {
      rel: RU, шапка: 'title: A', тело: '\nмой текст\n', отпечаток: база, фиксировать: фиксация(среда),
    });

    expect(ответ.code).toBe(409);
    expect(ответ.data['спор']['вид']).toBe('нетФайла');
    expect(fs.existsSync(path.join(среда.repo, RU))).toBe(false);
    expect(loadDraft(среда.repo, НАСТРОЙКИ, RU)['body']).toBe('\nмой текст\n');
  }, ЖДАТЬ_GIT);
});
