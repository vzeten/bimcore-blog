// Имя каждого теста повторяет формулировку правила.
// Возврат к версии и откат возврата: окно меняется только после записи пары в черновик.
import {describe, expect, it, vi} from 'vitest';
import {вопросГоден, применитьПару, параРавна, чтоДелать} from '../src/ui/restore';

const версия = {body: 'старый текст', frontmatterRaw: 'title: Старое'};
const окно = {body: 'моя незаписанная правка', frontmatterRaw: 'title: Новое'};

/** Очередь-двойник: помнит, что и в каком порядке уходило на запись, и чем отвечала. */
function очередь(ответы: boolean[]) {
  const записано: string[] = [];
  const записать = vi.fn(async (пара: {body: string}) => {
    записано.push(пара.body);
    return ответы[записано.length - 1] ?? true;
  });

  return {записано, записать};
}

describe('возврат к версии', () => {
  it('окно меняется только после того, как пара записана в черновик', async () => {
    const порядок: string[] = [];

    await применитьПару({новая: версия, вОкне: окно}, {
      записать: async () => {
        порядок.push('запись');
        return true;
      },
      актуально: () => true,
      применить: () => порядок.push('окно'),
      отметить: vi.fn(),
      onОшибка: vi.fn(),
    });

    expect(порядок).toEqual(['запись', 'окно']);
  });

  it('пара уходит в черновик целиком: тело и шапка вместе', async () => {
    const пары: unknown[] = [];

    await применитьПару({новая: версия, вОкне: окно}, {
      записать: async (пара) => {
        пары.push(пара);
        return true;
      },
      актуально: () => true,
      применить: vi.fn(),
      отметить: vi.fn(),
      onОшибка: vi.fn(),
    });

    expect(пары).toEqual([версия]);
  });

  it('запись не удалась — окно не меняется, показана причина', async () => {
    // Иначе в окне лежала бы версия, а на диске прежний черновик: расхождение, ради которого
    // запись и делается до окна.
    const {записать} = очередь([false, true]);
    const применить = vi.fn();
    const onОшибка = vi.fn();

    const вышло = await применитьПару({новая: версия, вОкне: окно}, {
      записать, актуально: () => true, применить, отметить: vi.fn(), onОшибка,
    });

    expect(вышло).toBe(false);
    expect(применить).not.toHaveBeenCalled();
    expect(onОшибка).toHaveBeenCalledWith('возвратНеУдался');
  });

  it('после неудачи пара окна дописывается немедленно, ровно одной попыткой', async () => {
    // Ответ мог пропасть уже после принятой записи: на диске могла остаться версия,
    // которую человек не принимал, и при следующем открытии она всплыла бы как его работа.
    const {записано, записать} = очередь([false, true]);

    await применитьПару({новая: версия, вОкне: окно}, {
      записать, актуально: () => true, применить: vi.fn(), отметить: vi.fn(), onОшибка: vi.fn(),
    });

    expect(записано).toEqual([версия.body, окно.body]);
  });

  it('после неудачи признак несохранённого считается по паре окна, а не по версии', async () => {
    // Лечебная запись идёт через ту же очередь, а она объявляет «Автосохранено» на любую удачную
    // запись. Без пересчёта по окну человек видел бы состояние версии, которую не принимал.
    const {записать} = очередь([false, true]);
    const отметить = vi.fn();

    await применитьПару({новая: версия, вОкне: окно}, {
      записать, актуально: () => true, применить: vi.fn(), отметить, onОшибка: vi.fn(),
    });

    expect(отметить).toHaveBeenCalledWith(окно);
  });

  it('не удалась и лечебная запись — человеку сказано, что диск мог разойтись с окном', async () => {
    const {записать} = очередь([false, false]);
    const onОшибка = vi.fn();

    await применитьПару({новая: версия, вОкне: окно}, {
      записать, актуально: () => true, применить: vi.fn(), отметить: vi.fn(), onОшибка,
    });

    expect(onОшибка).toHaveBeenCalledWith('возвратНеУдалсяДискРазошёлся');
  });

  it('окно уехало, пока шла запись, — состояние чужого окна не подменяется', async () => {
    // Ушли в другую статью или выбрали другую версию: на диск пара легла, это и есть возврат,
    // но применять её к чужому окну нельзя.
    const применить = vi.fn();

    const вышло = await применитьПару({новая: версия, вОкне: окно}, {
      записать: async () => true, актуально: () => false, применить, отметить: vi.fn(), onОшибка: vi.fn(),
    });

    expect(вышло).toBe(true);
    expect(применить).not.toHaveBeenCalled();
  });

  it('откат возврата идёт тем же путём: сначала запись прежней пары, потом окно', async () => {
    // Откат меняет ту же пару, поэтому своей дороги мимо записи у него нет — иначе он сам стал бы
    // дырой, ради закрытия которой появился.
    const {записано, записать} = очередь([true]);
    const применить = vi.fn();

    await применитьПару({новая: окно, вОкне: версия}, {
      записать, актуально: () => true, применить, отметить: vi.fn(), onОшибка: vi.fn(),
    });

    expect(записано).toEqual([окно.body]);
    expect(применить).toHaveBeenCalledWith(окно);
  });
});

describe('возврат и чужое окно', () => {
  // Правило одно: пара относится к тому окну, где её выбрали. Здесь оно проверяется на самом
  // применении; в окне тот же ключ «путь|заход» стережёт вопрос-подтверждение и снимок отката.
  it('окно сменилось между решением и записью — пара в чужое окно не попадает', async () => {
    let ключ = 'docs/a/index.mdx|1';
    const применить = vi.fn();

    await применитьПару({новая: версия, вОкне: окно}, {
      записать: async () => {
        ключ = 'docs/b/index.mdx|2'; // пока шла запись, открыли другую статью
        return true;
      },
      актуально: () => ключ === 'docs/a/index.mdx|1',
      применить,
      отметить: vi.fn(),
      onОшибка: vi.fn(),
    });

    expect(применить).not.toHaveBeenCalled();
  });

  it('неудача возврата видна вызывающему: откат не должен стирать снимок вслепую', async () => {
    // Кнопка «Вернуть как было» — единственный способ вернуть заменённую работу. Стереть снимок
    // при неудачной записи значит отнять его насовсем.
    const {записать} = очередь([false, false]);

    const вышло = await применитьПару({новая: версия, вОкне: окно}, {
      записать, актуально: () => true, применить: vi.fn(), отметить: vi.fn(), onОшибка: vi.fn(),
    });

    expect(вышло).toBe(false);
  });
});

describe('нажатие «Вернуть эту версию»', () => {
  const нажатие = (правки: Partial<Parameters<typeof чтоДелать>[0]>) =>
    чтоДелать({идёт: false, запертоВыбором: false, естьНесохранённые: false, версияНаЭкране: true, ...правки});

  it('возврат при несохранённых правках сначала спрашивает, а не меняет текст', () => {
    expect(нажатие({естьНесохранённые: true})).toBe('спросить');
  });

  it('окно чистое — возврат идёт сразу, без лишнего вопроса', () => {
    expect(нажатие({})).toBe('вернуть');
  });

  it('возврат недоступен, пока не сделан выбор «черновик или файл»', () => {
    // До решения правка запрещена, и подставленную пару затёр бы любой из двух выборов.
    expect(нажатие({запертоВыбором: true, естьНесохранённые: true})).toBe('ничего');
  });

  it('пока идёт запись прошлого возврата, второй возврат не начинается', () => {
    expect(нажатие({идёт: true})).toBe('ничего');
  });

  it('пока грузится другая версия, возврат не берёт ещё видимую прежнюю', () => {
    // В щели между нажатием на отметку и ответом сервера на экране остаётся прежняя версия:
    // возврат в этот миг положил бы в окно не ту, которую человек выбрал.
    expect(нажатие({версияНаЭкране: false, естьНесохранённые: true})).toBe('ничего');
  });
});

describe('годность заданного вопроса', () => {
  const вопрос = {ключОкна: 'docs/a/index.mdx|1', версия: 'v1'};

  it('вопрос относится к тому окну и той версии, где его задали', () => {
    expect(вопросГоден(вопрос, {...вопрос})).toBe(true);
  });

  it('ушли в другую статью — согласие пары уже не применяет', () => {
    expect(вопросГоден(вопрос, {ключОкна: 'docs/b/index.mdx|2', версия: 'v1'})).toBe(false);
  });

  it('выбрали другую версию — старый вопрос не годен', () => {
    expect(вопросГоден(вопрос, {ключОкна: вопрос.ключОкна, версия: 'v2'})).toBe(false);
  });

  it('версия ещё грузится — вопроса на экране нет', () => {
    // В щели между нажатием на версию и ответом на экране нет ни одной: согласие в этот миг
    // применило бы версию, от которой человек уже ушёл.
    expect(вопросГоден(вопрос, {ключОкна: вопрос.ключОкна, версия: null})).toBe(false);
  });
});

describe('совпадение пары с файлом', () => {
  it('пара равна файлу, когда совпадают и тело, и шапка', () => {
    expect(параРавна(версия, {...версия})).toBe(true);
  });

  it('одно тело при разной шапке равной парой не считается', () => {
    // Иначе правка свойств потерялась бы молча: тело то же, а шапка другая.
    expect(параРавна(версия, {...версия, frontmatterRaw: 'title: Другое'})).toBe(false);
  });
});
