// Имя каждого теста повторяет формулировку правила.
// Какого рода картинка лежит в байтах: решает содержимое, а не имя файла.
import {describe, expect, it} from 'vitest';
import {обложкойМожно, похожеНаГиф, типКартинки, типыТелаСтатьи, типыОбложки} from '../src/core/imageType.mjs';

// Начало настоящего PNG: сигнатура, длина первого куска и заголовок изображения `IHDR`.
const PNG = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0, 0, 0, 13, 0x49, 0x48, 0x44, 0x52,
  0x49, 0x44, 0x41, 0x54, 1, 2, 0x49, 0x45, 0x4e, 0x44]);
// Начало настоящего JPEG и метка конца изображения в хвосте.
const JPEG = Buffer.from([0xff, 0xd8, 0xff, 0xe0, 0, 16, 0x4a, 0x46, 0xff, 0xda, 1, 2, 0xff, 0xd9]);
// Настоящий GIF: сигнатура, описание экрана (7 байт), общая палитра, кадр (`0x2C`) и метка
// конца (`0x3B`). В описании экрана объявлена палитра из двух цветов — она обязана быть в файле.
const описаниеЭкрана = Buffer.from([2, 0, 2, 0, 0x80, 0, 0]);
const палитра = Buffer.from([0, 0, 0, 0xff, 0xff, 0xff]);
const кадр = Buffer.from([0x2c, 0, 0, 0, 0, 2, 0, 2, 0, 0, 2, 2, 0x44, 1, 0]);
const собрать = (знак) => Buffer.concat([
  Buffer.from(знак, 'binary'), описаниеЭкрана, палитра, кадр, Buffer.from([0x3b]),
]);
const GIF89 = собрать('GIF89a');
const GIF87 = собрать('GIF87a');

describe('тип картинки по содержимому', () => {
  it('PNG узнаётся по содержимому', () => {
    expect(типКартинки(PNG)).toBe('png');
  });

  it('JPEG узнаётся по содержимому и получает единое расширение jpg', () => {
    // У формата много имён (jpg, jpeg, jpe), а файл на диске должен называться одинаково:
    // обложка ищется по постоянному имени.
    expect(типКартинки(JPEG)).toBe('jpg');
  });

  it('SVG обложкой не считается', () => {
    expect(типКартинки(Buffer.from('<svg xmlns="http://www.w3.org/2000/svg"></svg>', 'utf8'))).toBeNull();
  });

  it('WebP обложкой не считается', () => {
    // RIFF....WEBP — начало похоже на картинку, но это другой формат.
    // Байты длины пишутся числами, а не управляющими знаками в тексте: сырой NUL в исходнике
    // делает файл двоичным для git, и обычный diff по нему перестаёт показываться.
    const webp = Buffer.concat([
      Buffer.from('RIFF', 'binary'), Buffer.alloc(4), Buffer.from('WEBPVP8 ', 'binary'),
    ]);

    expect(типКартинки(webp)).toBeNull();
  });

  it('GIF узнаётся по содержимому — обе живые версии формата', () => {
    expect(типКартинки(GIF89)).toBe('gif');
    expect(типКартинки(GIF87)).toBe('gif');
  });

  it('одна сигнатура GIF картинкой не делает: обрубок заголовка — не картинка', () => {
    expect(типКартинки(Buffer.from('GIF89a', 'binary'))).toBeNull();
  });

  it('GIF без метки конца картинкой не считается', () => {
    expect(типКартинки(GIF89.subarray(0, GIF89.length - 1))).toBeNull();
  });

  it('верное начало и верный конец без строения GIF картинкой не считаются', () => {
    // `GIF89a` + мусор + `0x3B` — не картинка: за палитрой обязан начинаться кадр или расширение.
    const подделка = Buffer.concat([
      Buffer.from('GIF89a', 'binary'),
      Buffer.alloc(20, 0x55),
      Buffer.from([0x3b]),
    ]);

    expect(типКартинки(подделка)).toBeNull();
  });

  it('объявленная, но отсутствующая палитра GIF картинкой не делает', () => {
    // Описание экрана обещает палитру из двух цветов, а в файле её нет: кадр окажется не на месте.
    const безПалитры = Buffer.concat([
      Buffer.from('GIF89a', 'binary'), описаниеЭкрана, кадр, Buffer.from([0x3b]),
    ]);

    expect(типКартинки(безПалитры)).toBeNull();
  });

  it('GIF без общей палитры читается по своему описанию экрана', () => {
    // Палитра не объявлена — первый блок стоит сразу за описанием экрана.
    const своиЦвета = Buffer.concat([
      Buffer.from('GIF89a', 'binary'),
      Buffer.from([2, 0, 2, 0, 0, 0, 0]),
      кадр,
      Buffer.from([0x3b]),
    ]);

    expect(типКартинки(своиЦвета)).toBe('gif');
  });

  it('текстовый файл обложкой не считается', () => {
    expect(типКартинки(Buffer.from('это просто текст', 'utf8'))).toBeNull();
  });

  it('пустые байты обложкой не считаются', () => {
    // Битый base64 превращается в мусор молча: без этой проверки на диск легла бы пустая обложка.
    expect(типКартинки(Buffer.alloc(0))).toBeNull();
  });

  it('обрезанная сигнатура обложкой не считается', () => {
    expect(типКартинки(Buffer.from([0x89, 0x50]))).toBeNull();
  });

  it('PNG без данных изображения обложкой не считается', () => {
    // Верные метки в начале ещё не делают файл картинкой: без куска данных он не откроется.
    expect(типКартинки(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a, 0, 0, 0, 13, 0x49, 0x48, 0x44, 0x52]))).toBeNull();
  });

  it('JPEG без начала данных обложкой не считается', () => {
    expect(типКартинки(Buffer.from([0xff, 0xd8, 0xff, 0xe0, 1, 2, 0xff, 0xd9]))).toBeNull();
  });

  it('JPEG без метки конца обложкой не считается', () => {
    expect(типКартинки(Buffer.from([0xff, 0xd8, 0xff, 0xe0, 0xff, 0xda, 1, 2]))).toBeNull();
  });

  it('картинки нет вовсе — это не картинка, а не падение', () => {
    expect(типКартинки(undefined)).toBeNull();
  });
});

describe('где какой формат принимается', () => {
  it('обложкой могут быть только PNG и JPG, GIF — нет', () => {
    // Обложке анимация не нужна, а имя у неё постоянное: решение владельца о GIF касается тела статьи.
    expect(обложкойМожно('png')).toBe(true);
    expect(обложкойМожно('jpg')).toBe(true);
    expect(обложкойМожно('gif')).toBe(false);
  });

  it('окно выбора обложки предлагает то же, что примет сервер', () => {
    expect(типыОбложки()).toBe('image/png,image/jpeg');
  });

  it('окно выбора картинки статьи предлагает и GIF', () => {
    expect(типыТелаСтатьи()).toBe('image/png,image/jpeg,image/gif');
  });
});

describe('узнавание GIF по одному началу файла', () => {
  // Заслон окна смотрит только начало: файл целиком к этому времени ещё не прочитан.
  it('обе живые версии формата узнаются по началу', () => {
    expect(похожеНаГиф(собрать('GIF89a'))).toBe(true);
    expect(похожеНаГиф(собрать('GIF87a'))).toBe(true);
  });

  it('одних букв GIF8 мало: чужой файл с таким началом анимацией не считается', () => {
    // Иначе тяжёлый файл другой породы получил бы отказ словами про предел анимации.
    expect(похожеНаГиф(Buffer.from('GIF8ZZ', 'binary'))).toBe(false);
  });

  it('картинка другой породы по началу за GIF не принимается', () => {
    expect(похожеНаГиф(PNG)).toBe(false);
    expect(похожеНаГиф(JPEG)).toBe(false);
  });

  it('пустых байтов хватает, чтобы честно ответить «нет», а не упасть', () => {
    expect(похожеНаГиф(Buffer.alloc(0))).toBe(false);
    expect(похожеНаГиф(undefined)).toBe(false);
  });
});
