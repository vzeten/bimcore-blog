// Имя каждого теста повторяет формулировку правила.
// Клавиши списка на настоящем состоянии редактора: раскладка списка идёт первой, как в окне, за ней
// раскладка поверхности и общая, поэтому видно и то, что делает клавиша, когда список её не берёт.
import {describe, expect, it} from 'vitest';
import {syntaxTree} from '@codemirror/language';
import {зазорМеждуПунктами} from '../src/ui/editor/listKeys';
import {нажать, состояние} from './listHarness';

describe('Enter в тексте пункта даёт следующий пункт вплотную и не наследует разреженность', () => {
  it('Enter в конце пункта даёт следующий пункт с тем же маркером', () => {
    expect(нажать('Enter', состояние('- a', 3))).toMatchObject({текст: '- a\n- ', курсор: 6});
  });

  it('Enter в старом разреженном списке: зазоры всего списка уходят, новый пункт вплотную', () => {
    expect(нажать('Enter', состояние('- Раз\n\n- Два', 12))).toMatchObject({текст: '- Раз\n- Два\n- ', курсор: 14});
    expect(нажать('Enter', состояние('- Раз\n- Два\n\n- Три', 18))).toMatchObject({текст: '- Раз\n- Два\n- Три\n- ', курсор: 20});
  });

  it('Enter посреди пункта: текст после курсора уходит в новый пункт', () => {
    expect(нажать('Enter', состояние('- РазДва\n- Три', 5))).toMatchObject({текст: '- Раз\n- Два\n- Три', курсор: 8});
  });

  it('Enter перед маркером даёт пустой пункт выше, курсор остаётся у текста', () => {
    expect(нажать('Enter', состояние('- Раз\n- Два', 6))).toMatchObject({текст: '- Раз\n- \n- Два', курсор: 9});
    expect(нажать('Enter', состояние('1. Раз\n2. Два', 7))).toMatchObject({текст: '1. Раз\n2. \n3. Два', курсор: 11});
  });

  it('выделение внутри одной строки пункта заменяется разбиением, общий перевод строки не вставляется', () => {
    expect(нажать('Enter', состояние('- Раз\n- Два\n- Три', 8, 11))).toMatchObject({текст: '- Раз\n- \n- \n- Три', курсор: 11});
  });

  it('нумерованный: номера всего списка идут подряд, старый зазор перед последним пунктом уходит', () => {
    expect(нажать('Enter', состояние('1. a\n2. b\n\n7. e', 9))).toMatchObject({текст: '1. a\n2. b\n3. \n4. e', курсор: 13});
  });

  it('нумерация начинается с номера первого пункта, а не с единицы', () => {
    expect(нажать('Enter', состояние('8. Раз\n9. Два', 13))).toMatchObject({текст: '8. Раз\n9. Два\n10. ', курсор: 18});
  });

  it('соседний список того же вида через пустую строку входит в список: его маркеры получают знак списка курсора', () => {
    expect(нажать('Enter', состояние('* Сосед\n\n- Раз', 14))).toMatchObject({текст: '- Сосед\n- Раз\n- ', курсор: 16});
  });

  it('список с блочным пунктом не уплотняется: новый пункт вплотную, пустая строка внутри пункта остаётся', () => {
    expect(нажать('Enter', состояние('- Раз\n\n  ![](./a.png)\n- Два', 27))).toMatchObject({текст: '- Раз\n\n  ![](./a.png)\n- Два\n- ', курсор: 30});
  });

  it('вложенный список без пустых строк пункт блочным не делает: Enter во вложенном пункте продолжает вложенный список', () => {
    expect(нажать('Enter', состояние('- Родитель\n  - Раз', 18))).toMatchObject({текст: '- Родитель\n  - Раз\n  - ', курсор: 23});
  });

  it('внутри примечания то же: перед закрывающей `:::` пункт продолжается, разреженный список уплотняется', () => {
    expect(нажать('Enter', состояние(':::note\n- a\n- b\n:::', 15))).toMatchObject({текст: ':::note\n- a\n- b\n- \n:::', курсор: 18});
    expect(нажать('Enter', состояние(':::tip\n- a\n\n- b\n:::', 15))).toMatchObject({текст: ':::tip\n- a\n- b\n- \n:::', курсор: 17});
  });

  it('в коде внутри пункта Enter — обычный перевод строки, маркер в код не вставляется', () => {
    const итог = нажать('Enter', состояние('- Пункт\n\n  ```js\n  const x = 1;\n  ```', 30));
    expect(итог.текст).not.toContain('- const');
    expect(итог.текст.split('\n').length).toBe(6);
    expect(итог.текст.endsWith('  ```')).toBe(true);
  });

  it('ввод не теряется, когда разбор не дошёл до конца длинного текста: новый пункт есть, уплотнения нет', () => {
    const текст = `${'Абзац.\n\n'.repeat(40_000)}- Раз\n\n- Два`;
    const state = состояние(текст, текст.length, текст.length, false);
    if (syntaxTree(state).length >= текст.length) return;
    const итог = нажать('Enter', state);
    expect(итог.текст.startsWith(текст.slice(0, текст.length - 5))).toBe(true);
    expect(/- Два\n(- |\s*)$/.test(итог.текст)).toBe(true);
  });
});

describe('Enter на пустом пункте завершает список без разрежения', () => {
  it('Enter на пустом втором пункте завершает список, не вставляя над ним пустую строку', () => {
    expect(нажать('Enter', состояние('- a\n- ', 6))).toMatchObject({текст: '- a\n\n', курсор: 5});
    expect(нажать('Enter', состояние('1. a\n2. ', 8))).toMatchObject({текст: '1. a\n\n', курсор: 6});
  });

  it('Enter на пустом пункте перед абзацем даёт пустой абзац с разделителями по обе стороны', () => {
    expect(нажать('Enter', состояние('- a\n- b\n- \n\nАбзац.', 10))).toMatchObject({текст: '- a\n- b\n\n\n\nАбзац.', курсор: 9});
  });

  it('Enter на пустом пункте у границы примечания не ставит перед ней пустую строку', () => {
    expect(нажать('Enter', состояние(':::tip\n- a\n- \n:::', 13))).toMatchObject({текст: ':::tip\n- a\n\n\n:::', курсор: 12});
  });

  it('Enter на пустом пункте перед пустым абзацем уводит курсор в него, не заводя второй', () => {
    expect(нажать('Enter', состояние('- a\n- \n', 6))).toMatchObject({текст: '- a\n\n', курсор: 5});
    expect(нажать('Enter', состояние(':::tip\n- a\n- \n\n:::', 13))).toMatchObject({текст: ':::tip\n- a\n\n\n:::', курсор: 12});
  });

  it('Enter на пустом вложенном пункте поднимает его на уровень выше', () => {
    expect(нажать('Enter', состояние('- a\n  - ', 8))).toMatchObject({текст: '- a\n- ', курсор: 6});
  });
});

describe('Enter на строке-продолжении пункта после Shift+Enter даёт новый пункт', () => {
  it('маркированный: новый пункт с тем же маркером', () => {
    expect(нажать('Enter', состояние('- раз\\\n  два', 12))).toMatchObject({текст: '- раз\\\n  два\n- ', курсор: 15});
  });

  it('нумерованный: следующий номер, номера дальше идут подряд', () => {
    expect(нажать('Enter', состояние('1. a\\\n   b\n2. c\n3. d', 10))).toMatchObject({текст: '1. a\\\n   b\n2. \n3. c\n4. d', курсор: 14});
  });

  it('пустое продолжение уходит вместе с косой переноса: перед концом пункта она была бы буквой', () => {
    expect(нажать('Enter', состояние('1. a\\\n   \n2. b', 9))).toMatchObject({текст: '1. a\n2. \n3. b', курсор: 8});
  });

  it('Enter в начале строки-продолжения переносит её текст в новый пункт без лишнего отступа', () => {
    expect(нажать('Enter', состояние('- раз\\\n  два', 9))).toMatchObject({текст: '- раз\n- два', курсор: 8});
  });
});

describe('Shift+Enter в пункте списка переносит текст внутри пункта', () => {
  it('косая и отступ в колонку содержимого: два пробела у точки, три у номера', () => {
    expect(нажать('Shift-Enter', состояние('- раз', 5))).toMatchObject({текст: '- раз\\\n  ', курсор: 9});
    expect(нажать('Shift-Enter', состояние('1. раз', 6))).toMatchObject({текст: '1. раз\\\n   ', курсор: 11});
  });

  it('отступ не больше трёх пробелов: четыре построчный разбор счёл бы кодом', () => {
    expect(нажать('Shift-Enter', состояние('10. раз', 7))).toMatchObject({текст: '10. раз\\\n   ', курсор: 12});
  });

  it('в обычном абзаце перенос без отступа, как и был', () => {
    expect(нажать('Shift-Enter', состояние('раз', 3))).toMatchObject({текст: 'раз\\\n', курсор: 5});
  });
});

describe('Backspace и Delete через зазор между пунктами убирают ровно зазор', () => {
  it('Backspace перед маркером нижнего пункта: пункты встают вплотную, маркер со словами не склеивается', () => {
    expect(нажать('Backspace', состояние('- Раз\n\n- Два', 7))).toMatchObject({текст: '- Раз\n- Два', курсор: 6});
    expect(нажать('Backspace', состояние('- Раз\n\n\n- Два', 8))).toMatchObject({текст: '- Раз\n- Два', курсор: 6});
  });

  it('Delete в конце верхнего пункта делает то же; косая переноса перед зазором уходит', () => {
    expect(нажать('Delete', состояние('- Раз\n\n- Два', 5))).toMatchObject({текст: '- Раз\n- Два', курсор: 5});
    expect(нажать('Delete', состояние('- Раз\\\n\n- Два', 6))).toMatchObject({текст: '- Раз\n- Два', курсор: 5});
  });

  it('зазор после вложенного пункта и между соседними списками одного вида тоже зазор', () => {
    expect(нажать('Backspace', состояние('- a\n  - b\n\n- c', 11))).toMatchObject({текст: '- a\n  - b\n- c', курсор: 10});
    expect(нажать('Backspace', состояние('* a\n\n- b', 5))).toMatchObject({текст: '* a\n- b', курсор: 4});
  });

  it('пустая строка между списком и абзацем, списками разного вида или внутри блочного пункта зазором не считается', () => {
    for (const [текст, pos] of [['- a\n\nАбзац', 5], ['- a\n\n1. b', 5], ['- a\n\n  второй абзац', 5], ['Абзац\n\n- b', 7]] as [string, number][]) {
      expect(зазорМеждуПунктами(состояние(текст, pos), pos, false)).toBeNull();
    }
  });
});
