// Имя каждого теста повторяет формулировку правила.
//
// Про уже записанный, но не уехавший коммит: чем доказывается его состав и что происходит с тем,
// что программа не сумела привести в порядок после записи.
//
// Ради чего набор заведён — две беды, найденные независимой проверкой:
// 1. Досылка судила старый коммит по СЕГОДНЯШНЕМУ диску: удалённая или переименованная после записи
//    картинка становилась «посторонним файлом», и своя же работа запиралась навсегда.
// 2. «Индекс привести не удалось» жило только в ответе окна. После перезапуска сервера отказ
//    забывался, и следующее нажатие «Опубликовать» дослало бы непривёденное на сайт.
import {afterEach, beforeEach, describe, expect, it, vi} from 'vitest';
import fs from 'node:fs';
import path from 'node:path';

import {проверитьИСобрать} from '../src/ui/publishRun';
import {запомнитьКоммит, запомнитьПоказ} from '../src/adapters/pushMemory.mjs';
import {запомнитьСборку} from '../src/adapters/buildMemory.mjs';
import {прочитатьОчередь} from '../src/adapters/commitQueue.mjs';
import {ЖДАТЬ_GIT} from './saveHarness.mjs';
import {EN, RU, НАСТРОЙКИ, СТАТЬЯ, дверь, наСервере, среда, убратьПесочницы, ход} from './runHarness.mjs';

const КАРТИНКА = 'i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba/схема.png';
const ДРУГАЯ = 'i18n/ru/docusaurus-plugin-content-docs/current/lessons/vtoraya/index.mdx';
// Вторая статья ИСПРАВНА по-настоящему: сервер сам доказывает зелёную подготовку, и статья без
// описания до состава больше не доходит. Название проверки на это и рассчитано.
const СТАТЬЯ2 = '---\ntitle: "Вторая"\nslug: /lessons/vtoraya\ndescription: "Про вторую."\n---\n\nВторой текст.\n';

beforeEach(() => {
  запомнитьСборку(null);
  запомнитьКоммит(null);
  запомнитьПоказ(null);
});

afterEach(() => {
  запомнитьСборку(null);
  запомнитьКоммит(null);
  запомнитьПоказ(null);
  убратьПесочницы();
});

const записей = (записка) => записка.filter((шаг) => шаг.адрес === '/api/publish/commit').length;

/** Файл очереди коммитов на диске: в неё программа и пишет доказательство своего происхождения. */
const файлОчереди = (с) => path.join(с.editorDir, НАСТРОЙКИ['хранение']['папкаПубликаций'], 'commits.json');

/** Довести до состояния «записано, но на сайт не уехало» — это оставляет обрыв между ними. */
async function записаноНоНеУехало(с, х, статья = RU) {
  fs.writeFileSync(path.join(с.repo, статья), `${СТАТЬЯ}\nНовая строка.\n`, 'utf8');
  await проверитьИСобрать(статья, false, х);

  return х.запрос('/api/publish/commit', {path: статья, подтверждено: true});
}

describe('состав уже записанного коммита', () => {
  it('картинка, удалённая после записи, не делает свой же коммит посторонним', async () => {
    const с = await среда({файлы: {[RU]: СТАТЬЯ, [EN]: СТАТЬЯ, [КАРТИНКА]: 'старая картинка'}});
    const записка = [];
    const х = ход(дверь(с, записка), []);
    // Картинка правится вместе со статьёй и уезжает в тот же коммит.
    fs.writeFileSync(path.join(с.repo, КАРТИНКА), 'новая картинка', 'utf8');
    const запись = await записаноНоНеУехало(с, х);
    const вКоммите = await с.git.raw(['-c', 'core.quotepath=false', 'show', '--name-only', '--format=', запись.sha]);
    expect(вКоммите).toContain('схема.png');

    // Человек стёр картинку у себя ПОСЛЕ записи. Состав на диске её больше не знает.
    fs.rmSync(path.join(с.repo, КАРТИНКА));
    const былоЗаписей = записей(записка);
    await проверитьИСобрать(RU, false, х);

    // Записанная работа уехала на сайт своим коммитом, второй записи не сделано.
    expect(await наСервере(с.сервер)).toBe(запись.sha);
    expect(записей(записка)).toBe(былоЗаписей);
  }, ЖДАТЬ_GIT);

  it('картинка, переименованная после записи, не делает свой же коммит посторонним', async () => {
    const с = await среда({файлы: {[RU]: СТАТЬЯ, [EN]: СТАТЬЯ, [КАРТИНКА]: 'старая картинка'}});
    const записка = [];
    const х = ход(дверь(с, записка), []);
    fs.writeFileSync(path.join(с.repo, КАРТИНКА), 'новая картинка', 'utf8');
    const запись = await записаноНоНеУехало(с, х);

    const новоеИмя = КАРТИНКА.replace('схема.png', 'схема-2.png');
    fs.renameSync(path.join(с.repo, КАРТИНКА), path.join(с.repo, новоеИмя));
    await проверитьИСобрать(RU, false, х);

    expect(await наСервере(с.сервер)).toBe(запись.sha);
  }, ЖДАТЬ_GIT);

  it('досылка из другой ИСПРАВНОЙ статьи отправляет записанный коммит первой', async () => {
    const с = await среда({файлы: {[RU]: СТАТЬЯ, [EN]: СТАТЬЯ, [ДРУГАЯ]: СТАТЬЯ2}});
    const записка = [];
    const х = ход(дверь(с, записка), []);
    const запись = await записаноНоНеУехало(с, х);
    const былоЗаписей = записей(записка);

    // Человек ушёл в другую статью и нажал «Опубликовать» там. Статья исправна: блокер подготовки
    // у неё остановил бы ход раньше, чем сервер сказал бы про неотправленное, — это известный хвост
    // в `PLAN.md`, а не то, что проверяется здесь.
    await проверитьИСобрать(ДРУГАЯ, false, х);

    expect(await наСервере(с.сервер)).toBe(запись.sha);
    expect(записей(записка)).toBe(былоЗаписей);
  }, ЖДАТЬ_GIT);

  it('переписанная история отправку не проходит: состав коммита разошёлся с записью', async () => {
    const с = await среда();
    const х = ход(дверь(с, []), []);
    const запись = await записаноНоНеУехало(с, х);

    // Портим саму запись: её пути больше не описывают коммит.
    const очередь = JSON.parse(fs.readFileSync(файлОчереди(с), 'utf8'));
    очередь.записи = очередь.записи.map((своя) => ({...своя, пути: ['docs/чужое.mdx']}));
    fs.writeFileSync(файлОчереди(с), JSON.stringify(очередь), 'utf8');

    const беда = await х.запрос('/api/publish/plan', {path: RU}).catch((ошибка) => ошибка);

    expect(беда.ответ.код).toBe('неНашиКоммиты');
    expect(await наСервере(с.сервер)).not.toBe(запись.sha);
  }, ЖДАТЬ_GIT);
});

describe('неприведённое после записи', () => {
  /** Занять замок индекса git: под ним программа не может привести индекс к своему коммиту. */
  const занятьЗамок = (с) => {
    const замок = path.join(с.repo, '.git', 'index.lock');
    fs.writeFileSync(замок, '', 'utf8');

    return замок;
  };

  it('неприведённое ложится в очередь на диск, а не живёт в одном ответе окна', async () => {
    const с = await среда();
    const х = ход(дверь(с, []), []);
    const замок = занятьЗамок(с);

    const запись = await записаноНоНеУехало(с, х);

    expect(запись.невосстановленные.length).toBeGreaterThan(0);
    const очередь = прочитатьОчередь(с.editorDir, НАСТРОЙКИ);
    const своя = очередь.записи.find((строка) => строка.sha === запись.sha);
    expect(своя.невосстановленные).toEqual(запись.невосстановленные);
    fs.rmSync(замок, {force: true});
  }, ЖДАТЬ_GIT);

  it('после перезапуска сервера отказ помнится: показ отвечает «не привели», а не отправляет', async () => {
    const с = await среда();
    const х = ход(дверь(с, []), []);
    const замок = занятьЗамок(с);
    const запись = await записаноНоНеУехало(с, х);
    fs.rmSync(замок, {force: true});
    // Перезапуск сервера: память процесса пуста, на диске осталась только очередь.
    запомнитьСборку(null);
    запомнитьПоказ(null);

    const беда = await х.запрос('/api/publish/plan', {path: RU}).catch((ошибка) => ошибка);

    expect(беда.ответ.код).toBe('невосстановлено');
    expect(await наСервере(с.сервер)).not.toBe(запись.sha);
  }, ЖДАТЬ_GIT);

  it('запрет снимается только доказательством: индекс совпал с нашим коммитом', async () => {
    const с = await среда();
    const х = ход(дверь(с, []), []);
    const замок = занятьЗамок(с);
    const запись = await записаноНоНеУехало(с, х);
    fs.rmSync(замок, {force: true});

    // Человек привёл индекс в порядок сам: теперь он совпадает с нашим коммитом.
    await с.git.raw(['reset', '--quiet']);
    const показ = await х.запрос('/api/publish/plan', {path: RU});

    expect(показ.sha).toBe(запись.sha);
    // Снятый запрет лёг на диск: следующий заход не поднимет его заново.
    const очередь = прочитатьОчередь(с.editorDir, НАСТРОЙКИ);
    expect(очередь.записи.find((своя) => своя.sha === запись.sha).невосстановленные).toEqual([]);
  }, ЖДАТЬ_GIT);

  it('пока индекс не приведён, запрет держится и повторный заход его не забывает', async () => {
    const с = await среда();
    const х = ход(дверь(с, []), []);
    const замок = занятьЗамок(с);
    await записаноНоНеУехало(с, х);
    fs.rmSync(замок, {force: true});

    await х.запрос('/api/publish/plan', {path: RU}).catch(() => undefined);
    const второй = await х.запрос('/api/publish/plan', {path: RU}).catch((ошибка) => ошибка);

    expect(второй.ответ.код).toBe('невосстановлено');
  }, ЖДАТЬ_GIT);

  it('запись очереди без нового поля читается как «восстанавливать нечего», а не как битая', async () => {
    const с = await среда();
    const х = ход(дверь(с, []), []);
    const запись = await записаноНоНеУехало(с, х);

    // Так очередь выглядела до того, как у записи появился перечень неприведённого.
    const очередь = JSON.parse(fs.readFileSync(файлОчереди(с), 'utf8'));
    for (const своя of очередь.записи) delete своя.невосстановленные;
    fs.writeFileSync(файлОчереди(с), JSON.stringify(очередь), 'utf8');

    expect(прочитатьОчередь(с.editorDir, НАСТРОЙКИ).ошибка).toBeUndefined();
    const показ = await х.запрос('/api/publish/plan', {path: RU});
    expect(показ.sha).toBe(запись.sha);
  }, ЖДАТЬ_GIT);

  it('намерение не легло на диск — ветка не сдвигается и записи не остаётся', async () => {
    const с = await среда();
    const х = ход(дверь(с, []), []);
    fs.writeFileSync(path.join(с.repo, RU), `${СТАТЬЯ}Новая строка.\n`, 'utf8');
    await проверитьИСобрать(RU, false, х);
    const былаГолова = (await с.git.raw(['rev-parse', 'HEAD'])).trim();
    // Так это выглядит, когда диск отказал ровно на сбросе очереди.
    const сброс = vi.spyOn(fs, 'fsyncSync').mockImplementation(() => {
      throw Object.assign(new Error('сброс не удался'), {code: 'EIO'});
    });

    let беда;
    try {
      беда = await х.запрос('/api/publish/commit', {path: RU, подтверждено: true}).catch((ошибка) => ошибка);
    } finally {
      сброс.mockRestore();
    }

    expect(беда.ответ.код).toBe('происхождениеНеЗаписано');
    // Ветка на месте, и очередь пуста: недоказанного коммита в ней нет.
    expect((await с.git.raw(['rev-parse', 'HEAD'])).trim()).toBe(былаГолова);
    expect(прочитатьОчередь(с.editorDir, НАСТРОЙКИ).записи).toEqual([]);
  }, ЖДАТЬ_GIT);

  it('подтверждение не легло на диск — на диске остаётся прежнее намерение с запретом', async () => {
    const с = await среда();
    const х = ход(дверь(с, []), []);
    fs.writeFileSync(path.join(с.repo, RU), `${СТАТЬЯ}Новая строка.\n`, 'utf8');
    await проверитьИСобрать(RU, false, х);
    // Первый сброс (намерение) проходит, второй (подтверждение) — нет.
    let осталось = 1;
    const сброс = vi.spyOn(fs, 'fsyncSync').mockImplementation((дескриптор) => {
      if (осталось-- > 0) return undefined;
      throw Object.assign(new Error('сброс не удался'), {code: 'EIO', дескриптор});
    });

    let запись;
    try {
      запись = await х.запрос('/api/publish/commit', {path: RU, подтверждено: true});
    } finally {
      сброс.mockRestore();
    }

    // Запись состоялась, но её итог на диск не лёг: на диске прежнее намерение со строгим запретом.
    const своя = прочитатьОчередь(с.editorDir, НАСТРОЙКИ).записи.find((строка) => строка.sha === запись.sha);
    expect(своя.состояние).toBe('намерение');
    expect(своя.невосстановленные).toEqual(['?']);
    // Человеку про это сказано, и отправка не начинается.
    expect(запись.невосстановленные).toContain('?');
  }, ЖДАТЬ_GIT);
});
