// Имя каждого теста повторяет формулировку правила.
// Черновик сайта (`draft`) как обычное поле шапки: флажок в свойствах ОТКРЫТОЙ языковой версии,
// дословность нетронутого поля и красные буквы ровно по записанному `draft: true`. Своего правила
// записи у поля нет намеренно: пишется оно общим сбором полей, и второго источника правды рядом
// с шапкой не заводится (ED-025).
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {describe, expect, it} from 'vitest';
import {buildFrontmatter, parseFrontmatter, показанныеПоля, порядокПолей} from '../src/ui/headFields';
import {признакиЛокали, цветЛокали, черновикСайта} from '../src/core/localeSigns.mjs';
import type {Settings} from '../src/ui/types';

const EDITOR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const НАСТРОЙКИ = JSON.parse(fs.readFileSync(path.join(EDITOR, 'settings.json'), 'utf8')) as Settings;
const КОРНИ = НАСТРОЙКИ.контент;
const DOCS = 'docs/lessons/foo/index.mdx';
const порядок = порядокПолей(НАСТРОЙКИ, DOCS);

const поля = (шапка: string) => показанныеПоля(parseFrontmatter(шапка, DOCS, КОРНИ), порядок);
const собрать = (шапка: string, изменить: (список: ReturnType<typeof поля>) => ReturnType<typeof поля>) =>
  buildFrontmatter(шапка, изменить(поля(шапка)), DOCS, КОРНИ, порядок);

const переключить = (список: ReturnType<typeof поля>, значение: string) =>
  список.map((поле) => (поле.key === 'draft' ? {...поле, display: значение} : поле));

describe('черновик сайта в свойствах статьи', () => {
  it('поле черновика показывается, даже когда строки draft в шапке нет вовсе', () => {
    // Обычная статья живёт без этой строки, и узнать о черновике человек должен из окна,
    // а не из чужого текстового редактора. До ED-025 поля не было видно ни у одной статьи.
    expect(поля('title: A').find((поле) => поле.key === 'draft'))
      .toEqual({key: 'draft', raw: '', kind: 'флаг', display: ''});
  });

  it('черновик показывается флажком, а не словом true в строке ввода', () => {
    expect(поля('title: A\ndraft: true').find((поле) => поле.key === 'draft')?.kind).toBe('флаг');
    expect(поля('title: A\ndraft: true').find((поле) => поле.key === 'draft')?.display).toBe('true');
  });

  it('draft: false и отсутствие поля равнозначны: режим выключен, флажок снят', () => {
    // Читается тем же правилом логического значения, каким draft читает сам сайт.
    for (const шапка of ['title: A', 'title: A\ndraft: false', 'title: A\ndraft: да']) {
      expect(поля(шапка).find((поле) => поле.key === 'draft')?.display, шапка).toBe('');
    }
  });

  it('включённый флажок дописывает строку черновика на её место в принятом порядке полей', () => {
    expect(собрать('title: A', (список) => переключить(список, 'true'))).toBe('title: A\ndraft: true');
    // Место — то же, каким его показало окно: перед видимостью, а не в конец шапки.
    expect(собрать('title: A\nunlisted: true', (список) => переключить(список, 'true')))
      .toBe('title: A\ndraft: true\nunlisted: true');
  });

  it('снятый флажок убирает строку черновика целиком, а не оставляет пустое значение', () => {
    // Голое `draft:` YAML прочитает как `null`, а обычная статья живёт вообще без строки.
    expect(собрать('title: A\ndraft: true', (список) => переключить(список, ''))).toBe('title: A');
    expect(собрать('title: A\ndraft: true\nunlisted: true', (список) => переключить(список, '')))
      .toBe('title: A\nunlisted: true');
  });

  it('снятый черновик не оставляет одинокий возврат каретки строке, ставшей последней', () => {
    // Файл с windows-переводами строк: у последней строки шапки своего `\r` нет, у соседней есть.
    // Убери строку черновика без уборки — соседняя станет последней с `\r`, а `\r` вместе со
    // следующим переводом строки даёт `\r\r\n`, после которого обложка перестаёт читаться вовсе.
    const шапка = 'title: "Проба"\r\nimage: ./cover.png\r\ndraft: true';
    const снято = собрать(шапка, (список) => переключить(список, ''));

    expect(снято).toBe('title: "Проба"\nimage: ./cover.png');
    expect(поля(снято).find((поле) => поле.key === 'image')?.display).toBe('./cover.png');
  });

  it('включил и снова выключил до сохранения — шапка возвращается прежней, файл менять нечем', () => {
    const шапка = 'title: A\ndescription: "Б"';
    const туда = переключить(поля(шапка), 'true');

    expect(buildFrontmatter(шапка, переключить(туда, ''), DOCS, КОРНИ, порядок)).toBe(шапка);
  });

  it('нетронутый черновик возвращается дословно — и когда строки нет, и когда стоит false', () => {
    // Иначе одно только открытие и сохранение переписывало бы чужой файл (SPEC 5.1): старая
    // опубликованная статья без поля обязана остаться байт в байт такой, какой была.
    for (const шапка of ['title: A', 'title: A\ndraft: false', 'title: A\ndraft: true']) {
      expect(собрать(шапка, (список) => список), шапка).toBe(шапка);
    }
  });

  it('правка соседнего поля строку черновика не трогает', () => {
    const шапка = 'title: A\ndraft: true\nunlisted: true';
    const собрано = собрать(шапка, (список) => список
      .map((поле) => (поле.key === 'title' ? {...поле, display: 'Б'} : поле)));

    expect(собрано).toBe('title: "Б"\ndraft: true\nunlisted: true');
  });

  it('черновик и видимость независимы: снятый черновик видимость не убирает и наоборот', () => {
    // Два разных обещания сайту: `draft` решает, соберётся ли страница, `unlisted` — попадёт ли
    // она в меню. Одно правило вместо двух молча гасило бы живую страницу вместе с черновиком.
    const снять = (список: ReturnType<typeof поля>, ключ: string) => список
      .map((поле) => (поле.key === ключ ? {...поле, display: ''} : поле));

    expect(собрать('title: A\ndraft: true\nunlisted: true', (список) => снять(список, 'draft')))
      .toBe('title: A\nunlisted: true');
    expect(собрать('title: A\ndraft: true\nunlisted: true', (список) => снять(список, 'unlisted')))
      .toBe('title: A\ndraft: true');
  });

  it('шапка после включения флажка читается тем же правилом, каким красноту считает реестр', () => {
    // Иначе окно обещало бы одно, а буквы локали показывали другое.
    const собрано = собрать('title: A', (список) => переключить(список, 'true'));

    expect(черновикСайта(собрано)).toBe(true);
    expect(черновикСайта(собрать(собрано, (список) => переключить(список, '')))).toBe(false);
  });
});

describe('красные буквы локали следуют только записанному draft: true', () => {
  const версия = (правки: Record<string, unknown>) => ({
    опубликован: true, отличается: false, правкаВЧерновике: false, заглушка: false,
    скрыта: false, скрытаВВетке: false, черновикСайта: false, ...правки,
  });

  it('красный цвет даёт draft: true и ничто другое', () => {
    expect(цветЛокали(признакиЛокали(версия({черновикСайта: true})))).toBe('черновик');
    expect(цветЛокали(признакиЛокали(версия({черновикСайта: false})))).toBe('обычная');
    // Ни неуехавшая правка, ни заглушка, ни скрытая страница красноты не дают: у них свои знаки.
    expect(цветЛокали(признакиЛокали(версия({отличается: true, заглушка: true, скрыта: true}))))
      .toBe('обычная');
  });

  it('черновик одной локали не красит соседние: поле живёт в файле своей версии', () => {
    const признаки = {
      ru: признакиЛокали(версия({черновикСайта: true})),
      en: признакиЛокали(версия({})),
      es: признакиЛокали(версия({заглушка: true})),
    };

    expect(цветЛокали(признаки.ru)).toBe('черновик');
    expect(цветЛокали(признаки.en)).toBe('обычная');
    expect(цветЛокали(признаки.es)).toBe('обычная');
  });
});
