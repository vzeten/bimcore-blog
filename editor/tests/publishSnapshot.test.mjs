// Имя каждого теста повторяет формулировку правила.
//
// Ради чего набор заведён: ход публикации спрашивает сервер четыре раза — проверки, состав, полная
// сборка, запись, — и между заходами файл может поменять второе окно или сторонняя программа. Без
// общего снимка человек согласился бы на один перечень, а сборка и коммит согласованно обработали
// бы другой.
import {afterEach, beforeEach, describe, expect, it, vi} from 'vitest';
import fs from 'node:fs';
import path from 'node:path';

import {зафиксироватьИОтправить, проверитьИСобрать} from '../src/ui/publishRun';
import {запомнитьКоммит, запомнитьПоказ} from '../src/adapters/pushMemory.mjs';
import {запомнитьСборку} from '../src/adapters/buildMemory.mjs';
import {срезОднойВерсии} from '../src/adapters/prepareStamp.mjs';
import {ЖДАТЬ_GIT} from './saveHarness.mjs';
import {
  EN, НАСТРОЙКИ, RU, СТАТЬЯ, дверь, наСервере, среда, убратьПесочницы, ход,
} from './runHarness.mjs';

beforeEach(() => {
  запомнитьСборку(null);
  запомнитьКоммит(null);
  запомнитьПоказ(null);
});

afterEach(() => {
  запомнитьСборку(null);
  запомнитьКоммит(null);
  запомнитьПоказ(null);
  убратьПесочницы();
});

// Между четырьмя заходами к серверу файл может поменять кто угодно: второе окно, внешний редактор.
// Без общего снимка человек согласился бы на один перечень, а сборка и коммит согласованно
// обработали бы другой.
describe('снимок один на весь ход публикации', () => {
  it('правка между проверками и составом останавливает ход', async () => {
    const с = await среда();
    const записка = [];
    // Дверь с подменой: между подготовкой и составом файл правится посторонним.
    const дверьСервера = дверь(с, записка);
    const х = ход(async (адрес, тело) => {
      const ответ = await дверьСервера(адрес, тело);
      if (адрес === '/api/prepare') fs.writeFileSync(path.join(с.repo, RU), `${СТАТЬЯ}Чужая правка.\n`, 'utf8');

      return ответ;
    }, []);

    // Отказ сервера ход наверх не переводит в остановку: его ловит окно и показывает словами.
    const беда = await проверитьИСобрать(RU, false, х).catch((ошибка) => ошибка);

    expect(беда.ответ.код).toBe('статьяИзменилась');
    expect(записка.some((шаг) => шаг.адрес === '/api/release/build')).toBe(false);
  }, ЖДАТЬ_GIT);

  it('правка между составом и сборкой останавливает ход до самой сборки', async () => {
    const с = await среда();
    fs.writeFileSync(path.join(с.repo, RU), `${СТАТЬЯ}Новая строка.\n`, 'utf8');
    const записка = [];
    const дверьСервера = дверь(с, записка);
    const х = ход(async (адрес, тело) => {
      const ответ = await дверьСервера(адрес, тело);
      if (адрес === '/api/release') fs.writeFileSync(path.join(с.repo, RU), `${СТАТЬЯ}Другая строка.\n`, 'utf8');

      return ответ;
    }, []);

    const беда = await проверитьИСобрать(RU, false, х).catch((ошибка) => ошибка);

    expect(беда.ответ.код).toBe('статьяИзменилась');
    // Ручка сборки отказала на входе, до запуска самой сборки: она идёт минуты, и гонять её по
    // устаревшему плану незачем.
    expect(записка.filter((шаг) => шаг.адрес === '/api/release/build')).toHaveLength(1);
  }, ЖДАТЬ_GIT);

  it('согласие относится к показанному плану: чужая сборка его не подменяет', async () => {
    const с = await среда();
    fs.writeFileSync(path.join(с.repo, RU), `${СТАТЬЯ}Новая строка.\n`, 'utf8');
    const записка = [];
    const х = ход(дверь(с, записка), []);
    const вопрос = await проверитьИСобрать(RU, false, х);
    expect(вопрос.вид).toBe('спрашиваю');
    const былоНаСервере = await наСервере(с.сервер);

    // Так выглядит второе окно: оно собрало ДРУГОЙ план той же статьи и заменило память сборки.
    //
    // План меняется КАРТИНКОЙ, а не текстом статьи. Правь второе окно сам файл — и запись отказала
    // бы уже на снимке проверок, а заслон отпечатка ПЛАНА остался бы непроверенным: он краснеть
    // перестал бы, и никто бы этого не увидел. Картинка в план входит, во входы проверок — нет.
    fs.writeFileSync(path.join(с.repo, path.dirname(RU), 'cover.png'), 'обложка', 'utf8');
    await проверитьИСобрать(RU, false, ход(дверь(с, []), []));

    // Согласие человека относится к ПЕРВОМУ перечню, и запись его не принимает.
    const беда = await зафиксироватьИОтправить(RU, х, вопрос.отпечаток, вопрос.отпечатокПодготовки).catch((ошибка) => ошибка);

    expect(беда.ответ.код).toBe('статьяИзменилась');
    expect(await наСервере(с.сервер)).toBe(былоНаСервере);
  }, ЖДАТЬ_GIT);

  it('запрос без снимка отвергают все три ручки: и пустой отпечаток, и отсутствующий', async () => {
    const с = await среда();
    // Дверь БЕЗ подстановки снимка: обычно обвязка ведёт себя как окно и снимок кладёт сама, а
    // здесь проверяется запрос МИМО окна — тело ровно такое, каким его прислали.
    const х = ход(дверь(с, [], {безСнимка: true}), []);
    const мимоОкна = [
      ['/api/release', {path: RU, отпечатокПодготовки: ''}],
      ['/api/release', {path: RU}],
      ['/api/release/build', {path: RU, отпечаток: ''}],
      ['/api/release/build', {path: RU}],
      ['/api/publish/commit', {path: RU, подтверждено: true, отпечаток: ''}],
      ['/api/publish/commit', {path: RU, подтверждено: true}],
    ];

    for (const [адрес, тело] of мимоОкна) {
      const беда = await х.запрос(адрес, тело).catch((ошибка) => ошибка);
      expect(беда.ответ?.код).toBe('нетСнимка');
    }
  }, ЖДАТЬ_GIT);

  it('снимков ДВА, и каждый обязателен сам по себе: одним другой не прикрывается', async () => {
    const с = await среда();
    const х = ход(дверь(с, [], {безСнимка: true}), []);
    const проверки = срезОднойВерсии(с.repo, RU, НАСТРОЙКИ).отпечаток;
    // Сборка и запись держат ДВА отпечатка: план, за который человек согласился, и входы проверок,
    // по которым его вообще пустили дальше. Приняв один вместо другого, сервер потерял бы половину
    // снимка и не заметил бы этого.
    const половина = [
      ['/api/release/build', {path: RU, отпечатокПодготовки: проверки}],
      ['/api/publish/commit', {path: RU, подтверждено: true, отпечатокПодготовки: проверки}],
      ['/api/release/build', {path: RU, отпечаток: 'план-какой-нибудь'}],
      ['/api/publish/commit', {path: RU, подтверждено: true, отпечаток: 'план-какой-нибудь'}],
    ];

    for (const [адрес, тело] of половина) {
      const беда = await х.запрос(адрес, тело).catch((ошибка) => ошибка);
      expect(`${адрес} ${JSON.stringify(тело)}: ${беда.ответ?.код}`).toBe(`${адрес} ${JSON.stringify(тело)}: нетСнимка`);
    }
  }, ЖДАТЬ_GIT);

  it('смена правил проверок между заходами останавливает сборку', async () => {
    const с = await среда();
    fs.writeFileSync(path.join(с.repo, RU), `${СТАТЬЯ}Новая строка.\n`, 'utf8');
    const х = ход(дверь(с, []), []);
    // Так выглядит правка `settings.json` между вопросом человеку и сборкой: статья не менялась ни
    // байтом, а правила, по которым её проверяли, стали другими. Сервер читает настройки заново на
    // каждый запрос, и без них в снимке этого не было бы видно вовсе.
    const поПрежнимПравилам = срезОднойВерсии(с.repo, RU, {...НАСТРОЙКИ, 'пределОписания': 200}).отпечаток;

    const беда = await х.запрос('/api/release/build', {path: RU, отпечатокПодготовки: поПрежнимПравилам})
      .catch((ошибка) => ошибка);

    expect(беда.ответ?.код).toBe('статьяИзменилась');
  }, ЖДАТЬ_GIT);


  it('правка МЕЖДУ проверками и составом останавливает ход', async () => {
    const с = await среда();
    fs.writeFileSync(path.join(с.repo, RU), `${СТАТЬЯ}Новая строка.\n`, 'utf8');
    const х = ход(дверь(с, []), []);
    // Отпечаток снят по нынешним байтам, а файл правится ДО захода за составом.
    const срез = срезОднойВерсии(с.repo, RU, НАСТРОЙКИ);
    fs.writeFileSync(path.join(с.repo, RU), `${СТАТЬЯ}Совсем другая.\n`, 'utf8');

    const беда = await х.запрос('/api/release', {path: RU, отпечатокПодготовки: срез.отпечаток})
      .catch((ошибка) => ошибка);

    expect(беда.ответ.код).toBe('статьяИзменилась');
  }, ЖДАТЬ_GIT);

  it('правка ВНУТРИ одного захода состава не проходит: план сверяется с байтами отпечатка', async () => {
    const с = await среда();
    fs.writeFileSync(path.join(с.repo, RU), `${СТАТЬЯ}Новая строка.\n`, 'utf8');
    const х = ход(дверь(с, []), []);
    const полный = path.join(с.repo, RU);
    const срез = срезОднойВерсии(с.repo, RU, НАСТРОЙКИ);

    // Гонка внутри одного захода: ручка успела снять отпечаток по прежним байтам, и ровно между
    // этим чтением и построением плана файл сменился. Воспроизводится точно: первое чтение отдаёт
    // прежние байты и тут же кладёт на диск новые.
    const настоящее = fs.readFileSync;
    let первое = true;
    const чтение = vi.spyOn(fs, 'readFileSync').mockImplementation((цель, вид) => {
      const ответ = настоящее(цель, вид);
      if (первое && String(цель) === полный) {
        первое = false;
        fs.writeFileSync(полный, `${СТАТЬЯ}Подменённая.\n`, 'utf8');
      }

      return ответ;
    });

    let беда;
    try {
      беда = await х.запрос('/api/release', {path: RU, отпечатокПодготовки: срез.отпечаток})
        .catch((ошибка) => ошибка);
    } finally {
      чтение.mockRestore();
    }

    expect(беда.ответ?.код).toBe('статьяИзменилась');
  }, ЖДАТЬ_GIT);

  it('находки подготовки и её отпечаток посчитаны по одним и тем же байтам', async () => {
    const с = await среда();
    const срез = срезОднойВерсии(с.repo, RU, НАСТРОЙКИ);

    // Байты отданы зовущему, а не прочитаны вторым заходом: именно по ним и судят правила.
    expect(срез.байты.toString('utf8')).toBe(fs.readFileSync(path.join(с.repo, RU), 'utf8'));
    // Тот же файл — тот же отпечаток; другой байт — другой.
    expect(срезОднойВерсии(с.repo, RU, НАСТРОЙКИ).отпечаток).toBe(срез.отпечаток);
    fs.writeFileSync(path.join(с.repo, RU), `${СТАТЬЯ}Ещё строка.\n`, 'utf8');
    expect(срезОднойВерсии(с.repo, RU, НАСТРОЙКИ).отпечаток).not.toBe(срез.отпечаток);
  }, ЖДАТЬ_GIT);

  it('ручка записи настройки НЕ перечитывает: оба заслона, план и коммит судят одним объектом', async () => {
    // Настройки сервер читает заново на КАЖДЫЙ запрос — при выборе ручки и при чтении тела. А вот
    // ВНУТРИ самой ручки записи файл не открывается ни разу, и это не мелочь: именно поэтому вердикт,
    // план и коммит судятся одними правилами. Начни ручка перечитывать файл посреди себя — план был
    // бы построен по прежним правилам, а проверен по новым, то есть появилась бы ровно та
    // рассогласованность, ради которой снимок и заведён.
    //
    // Проверка говорит ровно об этом и не больше: обвязка зовёт ручку напрямую, готовым объектом
    // настроек, как это делает сервер, — про его собственные чтения она не свидетельствует.
    const с = await среда();
    fs.writeFileSync(path.join(с.repo, RU), `${СТАТЬЯ}Новая строка.\n`, 'utf8');
    const х = ход(дверь(с, []), []);
    const вопрос = await проверитьИСобрать(RU, false, х);
    expect(вопрос.вид).toBe('спрашиваю');

    const настоящее = fs.readFileSync;
    const прочитанные = [];
    const чтение = vi.spyOn(fs, 'readFileSync').mockImplementation((цель, вид) => {
      прочитанные.push(String(цель));

      return настоящее(цель, вид);
    });

    let итог;
    try {
      итог = await зафиксироватьИОтправить(RU, х, вопрос.отпечаток, вопрос.отпечатокПодготовки);
    } finally {
      чтение.mockRestore();
    }

    expect(итог.вид).toBe('готово');
    expect(прочитанные.filter((путь) => путь.endsWith('settings.json'))).toEqual([]);
  }, ЖДАТЬ_GIT);

  it('правка чужой локали снимок открытой версии не обесценивает', async () => {
    const с = await среда();
    const срез = срезОднойВерсии(с.repo, RU, НАСТРОЙКИ);

    // Английская версия — сосед. Её правка к снимку открытой русской отношения не имеет.
    fs.writeFileSync(path.join(с.repo, EN), `${СТАТЬЯ}Чужая правка.\n`, 'utf8');

    expect(срезОднойВерсии(с.repo, RU, НАСТРОЙКИ).отпечаток).toBe(срез.отпечаток);
  }, ЖДАТЬ_GIT);
});
