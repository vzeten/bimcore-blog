// Имя каждого теста повторяет формулировку правила.
// Состав выпуска: что уедет на сайт вместе со статьёй и что программа доказать не берётся.
import {describe, expect, it} from 'vitest';

import {ВЕРСИЯ, КАРТИНКА, СОСТОЯНИЕ, выпускВозможен, составВыпуска} from '../src/core/release.mjs';

const RU = 'i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba/index.mdx';
const EN = 'docs/lessons/proba/index.mdx';

const версия = (путь, локаль, ещё = {}) => ({
  путь, локаль, состояние: null, файлыПапки: [], статейВПапке: 1, ...ещё,
});

const пути = (состав, назначение) => состав.файлы
  .filter((файл) => назначение === undefined || файл.назначение === назначение)
  .map((файл) => файл.путь);

describe('состав выпуска', () => {
  it('в состав входят все существующие языковые версии статьи', () => {
    const состав = составВыпуска({версии: [версия(RU, 'ru'), версия(EN, 'en')]});

    expect(пути(состав, ВЕРСИЯ)).toEqual([EN, RU]);
    expect(выпускВозможен(состав)).toBe(true);
  });

  it('файл состояния версии входит в состав, когда он есть на диске', () => {
    const сСостоянием = версия(RU, 'ru', {состояние: 'i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba/_state.json'});
    const состав = составВыпуска({версии: [сСостоянием]});

    expect(пути(состав, СОСТОЯНИЕ)).toEqual(['i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba/_state.json']);
  });

  it('файла состояния на диске нет — в составе его тоже нет: обещать несуществующий файл нельзя', () => {
    const состав = составВыпуска({версии: [версия(RU, 'ru')]});

    expect(пути(состав, СОСТОЯНИЕ)).toEqual([]);
  });

  it('картинки из папки статьи входят в состав вместе со своей версией', () => {
    const сКартинками = версия(RU, 'ru', {
      файлыПапки: [
        'i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba/cover.png',
        'i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba/img-1.png',
      ],
    });
    const состав = составВыпуска({версии: [сКартинками]});

    expect(пути(состав, КАРТИНКА)).toHaveLength(2);
    expect(выпускВозможен(состав)).toBe(true);
  });

  it('в папке лежит вторая статья — картинки не приписываются, состав объявляется недоказанным', () => {
    const общаяПапка = версия(RU, 'ru', {
      статейВПапке: 2,
      файлыПапки: ['i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba/cover.png'],
    });
    const состав = составВыпуска({версии: [общаяПапка]});

    // Сама версия в составе осталась: человек видит и доказанное, и то, что доказать не вышло.
    expect(пути(состав, ВЕРСИЯ)).toEqual([RU]);
    expect(пути(состав, КАРТИНКА)).toEqual([]);
    expect(состав.разрывы).toEqual([{причина: 'папкаНеОдна', путь: RU, локаль: 'ru'}]);
    expect(выпускВозможен(состав)).toBe(false);
  });

  it('посторонний файл в состав не попадает: считается только то, что лежит у самой статьи', () => {
    const состав = составВыпуска({версии: [версия(RU, 'ru'), версия(EN, 'en')]});
    const чужие = пути(состав).filter((путь) => !путь.includes('lessons/proba'));

    expect(чужие).toEqual([]);
  });

  it('версий не нашлось вовсе — это разрыв, а не пустой разрешённый выпуск', () => {
    const состав = составВыпуска({версии: []});

    expect(состав.файлы).toEqual([]);
    expect(состав.разрывы).toEqual([{причина: 'нетВерсий'}]);
    expect(выпускВозможен(состав)).toBe(false);
  });
});
