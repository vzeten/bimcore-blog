// Имя каждого теста повторяет формулировку правила.
// Блок видео целиком: как он вставляется, как показан в статье и что видит человек в его свойствах.
import {describe, expect, it} from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {новыйТег, сменаСвойства, type ОписаниеБлока} from '../src/core/jsxBlocks';
import {видБлока} from '../src/ui/livePreview/blocks';
import {датаПонятна, начальные, непонятное, отказСсылки, чтоЗаписать} from '../src/ui/editor/blockFields';

const EDITOR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const НАСТРОЙКИ = JSON.parse(fs.readFileSync(path.join(EDITOR, 'settings.json'), 'utf8'));
const БЛОКИ = НАСТРОЙКИ['блоки'] as Record<string, ОписаниеБлока>;
const ВИДЕО = БЛОКИ['YouTube'];
const ПОДПИСИ = НАСТРОЙКИ['подписи'] as Record<string, string>;

const НОМЕР = 'ifJtfM3LgGg';
const ОБЛОЖКА = `https://i.ytimg.com/vi/${НОМЕР}/hqdefault.jpg`;

describe('новый блок видео берёт начальные значения у самой статьи', () => {
  const шапка: Record<string, string> = {title: 'Розетки для Revit', description: 'Как ставить розетки'};

  it('название и описание предлагаются из шапки: человек чаще всего пишет то же самое', () => {
    expect(новыйТег('YouTube', ВИДЕО, (поле) => (поле.изШапки === undefined ? null : шапка[поле.изШапки] ?? null)))
      .toBe('<YouTube title="Розетки для Revit" description="Как ставить розетки" />');
  });

  it('ссылка, дата и длительность не угадываются: их знает только человек', () => {
    const тег = новыйТег('YouTube', ВИДЕО, (поле) => (поле.изШапки === undefined ? null : шапка[поле.изШапки] ?? null));

    expect(тег).not.toContain('id=');
    expect(тег).not.toContain('uploadDate=');
    expect(тег).not.toContain('duration=');
  });

  it('шапка пуста — пустых свойств в теге не заводится', () => {
    expect(новыйТег('YouTube', ВИДЕО, () => '')).toBe('<YouTube />');
  });

  it('название статьи с кавычкой не ломает блок: такое предложение просто не ставится', () => {
    expect(новыйТег('YouTube', ВИДЕО, (поле) => (поле.имя === 'title' ? 'Урок "про розетки"' : null)))
      .toBe('<YouTube />');
  });
});

describe('как блок видео показан в статье', () => {
  const незнакомое = (значение: string) => `нет такой: ${значение}`;

  it('человек видит обложку и название, а не JSX и не номер видео', () => {
    expect(видБлока(`<YouTube id="${НОМЕР}" title="Урок про розетки" />`, БЛОКИ, незнакомое)).toEqual({
      имя: 'YouTube', подпись: 'Видео', выбор: [], название: 'Урок про розетки', обложка: ОБЛОЖКА,
    });
  });

  it('адрес, дата и число секунд словами не показываются: в тексте статьи они ничего не говорят', () => {
    const вид = видБлока(`<YouTube id="${НОМЕР}" title="Урок" uploadDate="2026-08-01" duration="330" />`, БЛОКИ, незнакомое);

    expect(вид?.выбор).toEqual([]);
  });

  it('номера ещё нет — остаётся понятный блок с названием, без битой картинки', () => {
    expect(видБлока('<YouTube title="Урок про розетки" />', БЛОКИ, незнакомое)).toEqual({
      имя: 'YouTube', подпись: 'Видео', выбор: [], название: 'Урок про розетки',
    });
  });

  it('пустого названия блок не показывает: пустая подпись хуже её отсутствия', () => {
    expect(видБлока('<YouTube title="   " />', БЛОКИ, незнакомое)).toEqual({
      имя: 'YouTube', подпись: 'Видео', выбор: [],
    });
  });

  it('призыв к действию от нового вида не изменился: он по-прежнему показан словом заготовки', () => {
    expect(видБлока('<CTA type="template" />', БЛОКИ, незнакомое)).toEqual({
      имя: 'CTA', подпись: 'Призыв к действию', выбор: ['Шаблон — на страницу шаблона'],
    });
  });
});

describe('существующий блок статьи правкой одного поля не переписывается', () => {
  const старый = `<YouTube id="${НОМЕР}" title="Урок" uploadDate="2026-08-01" duration="PT5M30S" description="Про розетки" data-old="1" />`;

  it('смена названия не трогает ни длительность PT, ни незнакомое свойство', () => {
    expect(сменаСвойства(старый, 'title', 'Другое название'))
      .toBe(`<YouTube id="${НОМЕР}" title="Другое название" uploadDate="2026-08-01" duration="PT5M30S" description="Про розетки" data-old="1" />`);
  });

  it('открытие блока статью не меняет: пока человек ничего не тронул, тег остаётся прежним', () => {
    // Панель только читает тег в свои поля. Перепиши она PT в секунды при открытии — статья
    // изменилась бы сама собой, и человек получил бы правку, которой не делал.
    expect(начальные(старый, ВИДЕО.поля)['duration:мин']).toBe('5');
    expect(сменаСвойства(старый, 'title', 'Урок')).toBe(старый);
  });

  it('длительность переходит в секунды только тогда, когда человек её сам записал', () => {
    expect(сменаСвойства(старый, 'duration', '330'))
      .toBe(`<YouTube id="${НОМЕР}" title="Урок" uploadDate="2026-08-01" duration="330" description="Про розетки" data-old="1" />`);
  });

  it('старый блок программа по-прежнему показывает блоком, а не текстом', () => {
    expect(видБлока(старый, БЛОКИ, () => '')?.название).toBe('Урок');
  });
});

describe('что человек видит в свойствах блока', () => {
  it('вместо номера видео показывается обычная ссылка', () => {
    expect(начальные(`<YouTube id="${НОМЕР}" />`, ВИДЕО.поля).id).toBe(`https://www.youtube.com/watch?v=${НОМЕР}`);
  });

  it('вместо числа секунд показываются минуты и секунды', () => {
    const поля = начальные('<YouTube duration="330" />', ВИДЕО.поля);

    expect(поля['duration:мин']).toBe('5');
    expect(поля['duration:сек']).toBe('30');
  });

  it('пустой блок открывается пустыми полями, а не выдуманными значениями', () => {
    expect(начальные('<YouTube />', ВИДЕО.поля)).toEqual({
      id: '', title: '', description: '', uploadDate: '', 'duration:мин': '', 'duration:сек': '',
    });
  });

  it('непонятная длительность объясняется человеку, а не показывается пустыми минутами молча', () => {
    expect(непонятное('<YouTube duration="пять минут" />', ВИДЕО.поля, ПОДПИСИ).duration)
      .toBe(ПОДПИСИ.блокДлительностьНепонятна);
  });

  it('понятная длительность лишних слов не вызывает', () => {
    expect(непонятное('<YouTube duration="330" />', ВИДЕО.поля, ПОДПИСИ)).toEqual({});
    expect(непонятное('<YouTube duration="PT5M30S" />', ВИДЕО.поля, ПОДПИСИ)).toEqual({});
  });

  it('у каждого отказа ссылки свои слова из настроек, а не голый код причины', () => {
    for (const код of ['пусто', 'неСсылка', 'чужаяСсылка', 'нетНомера']) {
      expect(отказСсылки(ПОДПИСИ, код)).toBeTruthy();
      expect(отказСсылки(ПОДПИСИ, код)).not.toBe(код);
    }
  });

  it('календарь показывается только той дате, которую он умеет показать', () => {
    expect(датаПонятна('2026-08-01')).toBe(true);
    expect(датаПонятна('')).toBe(true);
    expect(датаПонятна('1 августа 2026')).toBe(false);
  });
});

describe('поле, которого человек не трогал, статью не переписывает', () => {
  const поле = (имя: string) => ВИДЕО.поля.find((п) => п.имя === имя)!;
  const нетронуто = () => false;
  const тронуто = () => true;

  it('простой взгляд на свойства не превращает старую запись PT в секунды', () => {
    // Панель показывает `PT1M2S` минутами и секундами. Запиши она их по уходу из поля — статья
    // изменилась бы сама собой, и человек получил бы правку, которой не делал.
    const черновики = начальные(`<YouTube duration="PT1M2S" />`, ВИДЕО.поля);

    expect(чтоЗаписать(поле('duration'), черновики, нетронуто, ПОДПИСИ)).toEqual({вид: 'нечего'});
  });

  it('непонятная длительность от взгляда не стирается в пустоту', () => {
    // Поля у непонятной записи пустые. Запись пустых полей стёрла бы значение человека совсем.
    const черновики = начальные('<YouTube duration="пять минут" />', ВИДЕО.поля);

    expect(чтоЗаписать(поле('duration'), черновики, нетронуто, ПОДПИСИ)).toEqual({вид: 'нечего'});
  });

  it('нетронутыми остаются и ссылка, и название, и дата', () => {
    const черновики = начальные(`<YouTube id="${НОМЕР}" title="Урок" uploadDate="2026-08-01" />`, ВИДЕО.поля);

    for (const имя of ['id', 'title', 'uploadDate']) {
      expect(чтоЗаписать(поле(имя), черновики, нетронуто, ПОДПИСИ), имя).toEqual({вид: 'нечего'});
    }
  });

  it('тронул человек — записывается то, что он набрал, а не то, что было', () => {
    const черновики = {...начальные('<YouTube duration="PT1M2S" />', ВИДЕО.поля), 'duration:мин': '3', 'duration:сек': '45'};

    expect(чтоЗаписать(поле('duration'), черновики, тронуто, ПОДПИСИ)).toEqual({вид: 'записать', значение: '225'});
  });

  it('ссылка тронутого поля становится номером, а чужая ссылка — объяснением', () => {
    const своя = {id: `https://youtu.be/${НОМЕР}?t=42`};
    const чужая = {id: 'https://vimeo.com/76979871'};

    expect(чтоЗаписать(поле('id'), своя, тронуто, ПОДПИСИ)).toEqual({вид: 'записать', значение: НОМЕР});
    expect(чтоЗаписать(поле('id'), чужая, тронуто, ПОДПИСИ)).toEqual({вид: 'беда', беда: ПОДПИСИ.блокСсылкаЧужая});
  });

  it('минуты словами не записываются: человеку говорится, что там нужны числа', () => {
    const черновики = {'duration:мин': 'пять', 'duration:сек': ''};

    expect(чтоЗаписать(поле('duration'), черновики, тронуто, ПОДПИСИ))
      .toEqual({вид: 'беда', беда: ПОДПИСИ.блокДлительностьНеЧисло});
  });
});

describe('настройки блока видео сходятся с договором сайта', () => {
  const компонент = fs.readFileSync(path.resolve(EDITOR, '..', 'src/components/YouTube.jsx'), 'utf8');

  it('программа пишет ровно те свойства, которые читает компонент сайта', () => {
    // Разойдись они — человек заполнил бы поле, которого сайт не смотрит, и не понял бы почему.
    for (const поле of ВИДЕО.поля) {
      expect(компонент.includes(поле.имя), поле.имя).toBe(true);
    }
  });

  it('пункт вставки «Видео» ведёт к этому же блоку, а не пишет сырой JSX', () => {
    const пункт = (НАСТРОЙКИ['вставки'] as Array<Record<string, string>>).find((кнопка) => кнопка['подпись'] === 'Видео');

    expect(пункт).toMatchObject({команда: 'блок', блок: 'YouTube'});
  });
});
