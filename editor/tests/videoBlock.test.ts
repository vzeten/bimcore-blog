// Имя каждого теста повторяет формулировку правила.
// Блок видео целиком: как он вставляется по ссылке, как показан в статье и что человек в нём правит.
import {describe, expect, it} from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {новыйТег, сменаСвойства, type ОписаниеБлока} from '../src/core/jsxBlocks';
import {видБлока} from '../src/ui/livePreview/blocks';
import {датаПонятна, начальные, непонятное, отказСсылки, чтоЗаписать} from '../src/ui/editor/blockFields';

const EDITOR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const НАСТРОЙКИ = JSON.parse(fs.readFileSync(path.join(EDITOR, 'settings.json'), 'utf8'));
const БЛОКИ = НАСТРОЙКИ['блоки'] as Record<string, ОписаниеБлока>;
const ВИДЕО = БЛОКИ['YouTube'];
const ПОДПИСИ = НАСТРОЙКИ['подписи'] as Record<string, string>;

const НОМЕР = 'ifJtfM3LgGg';
const ОБЛОЖКА = `https://i.ytimg.com/vi/${НОМЕР}/hqdefault.jpg`;

describe('вставка видео: человек даёт только ссылку', () => {
  const шапка: Record<string, string> = {title: 'Розетки для Revit', description: 'Как ставить розетки'};
  const тег = () => новыйТег('YouTube', ВИДЕО, ({изШапки}) => (изШапки === undefined ? null : шапка[изШапки] ?? null));

  it('название для доступности берётся у статьи молча, а не спрашивается у человека', () => {
    expect(тег()).toBe('<YouTube title="Розетки для Revit" />');
  });

  it('при вставке спрашивается одно поле — ссылка, остальные свойства вставку не загромождают', () => {
    const приВставке = ВИДЕО.поля.filter((поле) => поле.приВставке === true);

    expect(приВставке.map((поле) => поле.имя)).toEqual(['id']);
    expect(приВставке[0].вид).toBe('ссылкаВидео');
  });

  it('призыв к действию вставкой не урезается: своего поля для вставки у него нет вовсе', () => {
    // Урежь панель и его — человек увидел бы пустые свойства вместо выбора заготовки.
    expect(БЛОКИ['CTA'].поля.some((поле) => поле.приВставке === true)).toBe(false);
    expect(БЛОКИ['CTA'].поля.map((поле) => поле.имя)).toEqual(['type']);
  });

  it('нажав на готовое видео, человек видит все свойства сразу, без вложенного раскрытия', () => {
    expect(ВИДЕО.поля.map((поле) => поле.имя)).toEqual(['id', 'title', 'description', 'uploadDate', 'duration']);
  });

  it('обязательных полей у блока нет вовсе: пустое свойство ничего не блокирует', () => {
    for (const поле of ВИДЕО.поля) {
      expect(поле, поле.имя).not.toHaveProperty('обязательное');
    }
  });

  it('ни ссылка, ни описание, ни дата, ни длительность при вставке не выдумываются', () => {
    for (const свойство of ['id=', 'description=', 'uploadDate=', 'duration=']) {
      expect(тег(), свойство).not.toContain(свойство);
    }
  });

  it('шапка пуста — пустых свойств в теге не заводится', () => {
    expect(новыйТег('YouTube', ВИДЕО, () => '')).toBe('<YouTube />');
  });

  it('название статьи с кавычкой не ломает блок: такое начальное значение просто не ставится', () => {
    expect(новыйТег('YouTube', ВИДЕО, () => 'Урок "про розетки"')).toBe('<YouTube />');
  });

  it('призыв к действию берёт своё значение у раздела, как и раньше', () => {
    expect(новыйТег('CTA', БЛОКИ['CTA'], ({поле}) => (поле === undefined ? null : 'template')))
      .toBe('<CTA type="template" />');
  });
});

describe('как блок видео показан в статье', () => {
  const незнакомое = (значение: string) => `нет такой: ${значение}`;

  it('видео занимает строку целиком и показано обложкой с названием, а не строчкой JSX', () => {
    expect(видБлока(`<YouTube id="${НОМЕР}" title="Урок про розетки" />`, БЛОКИ, незнакомое)).toEqual({
      имя: 'YouTube', подпись: 'Видео', выбор: [], название: 'Урок про розетки',
      обложка: ОБЛОЖКА, воВсюСтроку: true,
    });
  });

  it('свойства, которых человек не вводит, в тексте статьи словами не показываются', () => {
    const вид = видБлока(
      `<YouTube id="${НОМЕР}" title="Урок" uploadDate="2026-08-01" duration="330" description="Про розетки" />`,
      БЛОКИ, незнакомое,
    );

    expect(вид?.выбор).toEqual([]);
    expect(вид?.название).toBe('Урок');
  });

  it('номера ещё нет — остаётся та же полоса с названием, без битой картинки', () => {
    expect(видБлока('<YouTube title="Урок про розетки" />', БЛОКИ, незнакомое)).toEqual({
      имя: 'YouTube', подпись: 'Видео', выбор: [], название: 'Урок про розетки', воВсюСтроку: true,
    });
  });

  it('пустого названия блок не показывает: пустая подпись хуже её отсутствия', () => {
    expect(видБлока('<YouTube title="   " />', БЛОКИ, незнакомое)).toEqual({
      имя: 'YouTube', подпись: 'Видео', выбор: [], воВсюСтроку: true,
    });
  });

  it('призыв к действию полосой не становится: он остаётся строчной плашкой со словом заготовки', () => {
    expect(видБлока('<CTA type="template" />', БЛОКИ, незнакомое)).toEqual({
      имя: 'CTA', подпись: 'Призыв к действию', выбор: ['Шаблон — на страницу шаблона'],
    });
  });
});

describe('старые свойства блока сохраняются дословно', () => {
  const старый = `<YouTube id="${НОМЕР}" title="Урок" uploadDate="2026-08-01" duration="PT5M30S" description="Про розетки" data-old="1" />`;

  it('смена ссылки не трогает ни описание, ни дату, ни длительность PT, ни незнакомое свойство', () => {
    expect(сменаСвойства(старый, 'id', 'O7wQlsdSp30'))
      .toBe('<YouTube id="O7wQlsdSp30" title="Урок" uploadDate="2026-08-01" duration="PT5M30S" description="Про розетки" data-old="1" />');
  });

  it('открытие блока статью не меняет: в панели лежит ссылка, а сам тег остаётся прежним', () => {
    expect(начальные(старый, ВИДЕО.поля).id).toBe(`https://www.youtube.com/watch?v=${НОМЕР}`);
    expect(сменаСвойства(старый, 'id', НОМЕР)).toBe(старый);
  });

  it('дата и длительность остаются ручной правкой: сами собой они не появляются и не исчезают', () => {
    // Их будет заполнять отдельная доработка, и затирать руками введённое она не должна.
    expect(начальные(старый, ВИДЕО.поля).uploadDate).toBe('2026-08-01');
    expect(начальные(старый, ВИДЕО.поля)['duration:мин']).toBe('5');
    expect(сменаСвойства(старый, 'uploadDate', '2026-08-01')).toBe(старый);
  });

  it('непонятная длительность объясняется человеку, а не показывается пустыми минутами молча', () => {
    expect(непонятное('<YouTube duration="пять минут" />', ВИДЕО.поля, ПОДПИСИ).duration)
      .toBe(ПОДПИСИ.блокДлительностьНепонятна);
  });

  it('старый блок программа по-прежнему показывает блоком, а не текстом', () => {
    expect(видБлока(старый, БЛОКИ, () => '')?.название).toBe('Урок');
  });
});

describe('поле, которого человек не трогал, статью не переписывает', () => {
  const ссылка = ВИДЕО.поля.find((поле) => поле.вид === 'ссылкаВидео')!;
  const нетронуто = () => false;
  const тронуто = () => true;

  it('человек открыл свойства и закрыл — записи не происходит вовсе', () => {
    const черновики = начальные(`<YouTube id="${НОМЕР}" />`, ВИДЕО.поля);

    expect(чтоЗаписать(ссылка, черновики, нетронуто, ПОДПИСИ)).toEqual({вид: 'нечего'});
  });

  it('тронул человек — в статью ложится номер видео, а не сама ссылка', () => {
    expect(чтоЗаписать(ссылка, {id: `https://youtu.be/${НОМЕР}?t=42`}, тронуто, ПОДПИСИ))
      .toEqual({вид: 'записать', значение: НОМЕР});
  });

  it('чужая ссылка объясняется словами и в статью не пишется', () => {
    expect(чтоЗаписать(ссылка, {id: 'https://vimeo.com/76979871'}, тронуто, ПОДПИСИ))
      .toEqual({вид: 'беда', беда: ПОДПИСИ.блокСсылкаЧужая});
  });

  it('взгляд на длительность и дату их не переписывает: ни PT в секунды, ни запись в пустоту', () => {
    const поле = (имя: string) => ВИДЕО.поля.find((п) => п.имя === имя)!;
    const черновики = начальные('<YouTube duration="PT1M2S" uploadDate="2026-08-01" />', ВИДЕО.поля);

    expect(чтоЗаписать(поле('duration'), черновики, нетронуто, ПОДПИСИ)).toEqual({вид: 'нечего'});
    expect(чтоЗаписать(поле('uploadDate'), черновики, нетронуто, ПОДПИСИ)).toEqual({вид: 'нечего'});
  });

  it('тронул человек длительность — в статью ложится число секунд, договор компонента сайта', () => {
    const поле = ВИДЕО.поля.find((п) => п.имя === 'duration')!;

    expect(чтоЗаписать(поле, {'duration:мин': '3', 'duration:сек': '45'}, тронуто, ПОДПИСИ))
      .toEqual({вид: 'записать', значение: '225'});
  });

  it('календарь показывается только той дате, которую он умеет показать', () => {
    expect(датаПонятна('2026-08-01')).toBe(true);
    expect(датаПонятна('1 августа 2026')).toBe(false);
  });

  it('у каждого отказа ссылки свои слова из настроек, а не голый код причины', () => {
    for (const код of ['пусто', 'неСсылка', 'чужаяСсылка', 'нетНомера']) {
      expect(отказСсылки(ПОДПИСИ, код)).toBeTruthy();
      expect(отказСсылки(ПОДПИСИ, код)).not.toBe(код);
    }
  });
});

describe('настройки блока видео сходятся с договором сайта', () => {
  const компонент = fs.readFileSync(path.resolve(EDITOR, '..', 'src/components/YouTube.jsx'), 'utf8');

  it('программа пишет ровно те свойства, которые читает компонент сайта', () => {
    // Разойдись они — человек заполнил бы поле, которого сайт не смотрит, и не понял бы почему.
    for (const свойство of [...ВИДЕО.поля.map((поле) => поле.имя), ...Object.keys(ВИДЕО.начальные ?? {})]) {
      expect(компонент.includes(свойство), свойство).toBe(true);
    }
  });

  it('пункт вставки «Видео» ведёт к этому же блоку, а не пишет сырой JSX', () => {
    const пункт = (НАСТРОЙКИ['вставки'] as Array<Record<string, string>>).find((кнопка) => кнопка['подпись'] === 'Видео');

    expect(пункт).toMatchObject({команда: 'блок', блок: 'YouTube'});
  });

  it('подготовка статьи о полях блока ничего не требует: пустая дата и длительность выпуску не мешают', () => {
    const этапы = Object.keys(НАСТРОЙКИ['подготовка']['этапы']);
    const находки = Object.keys(НАСТРОЙКИ['подготовка']['находки']);

    expect(этапы).not.toContain('блокиТела');
    expect(находки.filter((код) => код.startsWith('блок:'))).toEqual([]);
  });
});
