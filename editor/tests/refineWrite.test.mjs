// Имя каждого теста повторяет формулировку правила.
// Запись набора «Доработать»: либо целиком, либо на диске ни байта не меняется; сбой отката — авария.
import {describe, expect, it} from 'vitest';
import fs from 'node:fs';
import path from 'node:path';

import {АварияОтката, дискРедактора, записатьНабор} from '../src/adapters/refineWrite.mjs';
import {НАСТРОЙКИ, RU, jpg, png, репозиторий, снимокДиска} from './refineHarness.mjs';

const ТЕКСТ = '---\ntitle: "A"\n---\n\n![](./a.jpg)\n\n![](./b.png)\n';
const ошибки = НАСТРОЙКИ['ошибкиСервера'];

function среда() {
  const папка = path.posix.dirname(RU);
  const {repo} = репозиторий({[RU]: ТЕКСТ, [`${папка}/a.jpg`]: jpg(2, 2), [`${папка}/b.png`]: png(3, 3)});
  const dir = path.join(repo, path.dirname(RU));
  const снимок = {байтыТекста: Buffer.from(ТЕКСТ, 'utf8'), файлы: new Map([['a.jpg', jpg(2, 2)], ['b.png', png(3, 3)]])};
  return {repo, dir, файлСтатьи: path.join(repo, RU), снимок, ошибки};
}

/** Полный набор: новый файл, перезапись, статья и удаление — по шагу на каждый этап. */
const ИЗМЕНЕНИЯ = {
  текст: ТЕКСТ.replace('a.jpg', 'a.png'),
  файлы: [{имя: 'a.png', байты: png(2, 2)}, {имя: 'b.png', байты: png(3, 3, 5)}, {имя: 'a.jpg', байты: null}],
};

/** Диск, у которого названный шаг ломается на N-м вызове; остальное — настоящие записи. */
function ломаныйДиск(repo, {шаг, вызов = 1, откатТоже = false}) {
  const диск = дискРедактора(repo);
  let счёт = 0;
  return {
    ...диск,
    [шаг]: (...аргументы) => {
      счёт += 1;
      if (счёт === вызов || (откатТоже && счёт > вызов)) throw new Error(`сбой ${шаг} №${счёт}`);
      return диск[шаг](...аргументы);
    },
  };
}

describe('запись набора изменений', () => {
  it('новый файл, перезапись, статья и удаление ложатся вместе, служебных хвостов не остаётся', () => {
    const с = среда();
    записатьНабор({...с, изменения: ИЗМЕНЕНИЯ});

    expect(fs.readFileSync(с.файлСтатьи, 'utf8')).toBe(ИЗМЕНЕНИЯ.текст);
    expect(fs.existsSync(path.join(с.dir, 'a.jpg'))).toBe(false);
    expect(fs.readFileSync(path.join(с.dir, 'a.png'))).toEqual(png(2, 2));
    expect(fs.readFileSync(path.join(с.dir, 'b.png'))).toEqual(png(3, 3, 5));
    expect(fs.readdirSync(path.join(с.repo, 'editor', '.tmp'))).toEqual([]);
  });

  for (const [этап, поломка] of [
    ['новый файл', {шаг: 'новый'}],
    ['перезапись', {шаг: 'поверх', вызов: 1}],
    ['статья', {шаг: 'поверх', вызов: 2}],
    ['удаление', {шаг: 'удалить'}],
  ]) {
    it(`сбой на этапе «${этап}» откатывает сделанное: диск побайтово прежний`, () => {
      const с = среда();
      const до = снимокДиска(с.repo);
      expect(() => записатьНабор({...с, изменения: ИЗМЕНЕНИЯ, диск: ломаныйДиск(с.repo, поломка)})).toThrow(`сбой ${поломка.шаг}`);
      expect(снимокДиска(с.repo)).toBe(до);
    });
  }

  it('имя, занятое файлом, которого не было в снимке, — отказ 409 до единой правки статьи', () => {
    const с = среда();
    fs.writeFileSync(path.join(с.dir, 'a.png'), 'чужой');
    const до = снимокДиска(с.repo);
    expect(() => записатьНабор({...с, изменения: ИЗМЕНЕНИЯ})).toThrow(ошибки['доработкаСнимокУстарел']);
    expect(снимокДиска(с.repo)).toBe(до);
  });

  it('сбой самого отката не выдаётся за восстановление: авария называет невосстановленные файлы', () => {
    const с = среда();
    // Удаление ломается, а возврат перезаписанного файла статьи и b.png (шаг «поверх») — тоже.
    const диск = ломаныйДиск(с.repo, {шаг: 'удалить'});
    const настоящий = дискРедактора(с.repo);
    let записей = 0;
    диск.поверх = (цель, байты) => {
      записей += 1;
      if (записей > 2) throw new Error('диск занят');
      return настоящий.поверх(цель, байты);
    };

    let ошибка = null;
    try {
      записатьНабор({...с, изменения: ИЗМЕНЕНИЯ, диск});
    } catch (е) {
      ошибка = е;
    }
    expect(ошибка).toBeInstanceOf(АварияОтката);
    expect(ошибка.невосстановлено).toEqual([RU, path.posix.join(path.posix.dirname(RU), 'b.png')]);
    expect(ошибка.message).toContain(RU);
    expect(ошибка.message).not.toContain('возвращены');
    // Что откатить удалось — откатано (новый файл убран), что нет — так и лежит новым.
    expect(fs.existsSync(path.join(с.dir, 'a.png'))).toBe(false);
    expect(fs.readFileSync(с.файлСтатьи, 'utf8')).toBe(ИЗМЕНЕНИЯ.текст);
  });
});
