// Настоящие заголовки WebM заданного веса — для проверок формата и предела ролика.
//
// Заголовок EBML с типом документа `webm` и начало сегмента — ровно то, по чему программа узнаёт
// файл. Вес набирается элементом `Void` (`0xEC`), который формат разрешает и который проигрыватель
// пропускает: файл остаётся целым для правил программы, а «ровно предел» и «на байт больше»
// проверяются настоящими байтами, а не числами.

/** Заголовок EBML: сигнатура, длина (11 байт), DocType «webm», DocTypeVersion 2. */
const ЗАГОЛОВОК = Buffer.from([0x1a, 0x45, 0xdf, 0xa3, 0x8b, 0x42, 0x82, 0x84, 0x77, 0x65, 0x62, 0x6d, 0x42, 0x87, 0x81, 0x02]);
/** Сегмент неизвестной длины: так пишут потоковые кодировщики. */
const СЕГМЕНТ = Buffer.from([0x18, 0x53, 0x80, 0x67, 0x01, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff]);

/** Самый маленький WebM, который программа признаёт целым. */
export const WEBM = Buffer.concat([ЗАГОЛОВОК, СЕГМЕНТ]);

/** Тот же заголовок EBML, но тип документа `matroska`: заголовок тот же, а видео не то. */
export const MATROSKA = Buffer.concat([
  Buffer.from([0x1a, 0x45, 0xdf, 0xa3, 0x8f, 0x42, 0x82, 0x88]),
  Buffer.from('matroska', 'binary'),
  Buffer.from([0x42, 0x87, 0x81, 0x02]),
  СЕГМЕНТ,
]);

/** Целый WebM ровно заданного веса: заголовок, сегмент и один элемент `Void` нужной длины. */
export function webmВесом(байт) {
  const служебные = 1 + 8; // метка `Void` и длина восьмибайтовым числом
  const тело = байт - WEBM.length - служебные;
  if (тело < 0) throw new Error(`WebM ровно в ${байт} Б этим способом не собрать`);

  const длина = Buffer.alloc(8);
  длина[0] = 0x01;
  длина.writeUIntBE(тело, 2, 6);
  const готово = Buffer.concat([WEBM, Buffer.from([0xec]), длина, Buffer.alloc(тело, 0)]);
  if (готово.length !== байт) throw new Error(`вышло ${готово.length} Б вместо ${байт} Б`);

  return готово;
}
