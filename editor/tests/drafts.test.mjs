// Имя каждого теста повторяет формулировку правила.
import {describe, expect, it} from 'vitest';
import {draftDecision, draftName, extraSnapshots, newDraft, позже, readDraft, свежееЧерновика, writeDraft} from '../src/core/drafts.mjs';
import {historyFolder} from '../src/core/history.mjs';

const НАСТРОЙКИ = {хранение: {черновикЖивётДней: 14, снимковНаВерсию: 3}};
const ФАЙЛ = {frontmatterRaw: 'title: A', body: 'текст файла'};
const СЕЙЧАС = '2026-08-04T12:00:00.000Z';

const черновик = (over = {}) => newDraft({
  path: 'docs/a/index.mdx',
  frontmatterRaw: 'title: A',
  body: 'текст черновика',
  отпечатокБазы: 'ОТП1',
  когда: '2026-08-04T11:59:00.000Z',
  ...over,
});

describe('черновик автосохранения', () => {
  it('черновик переживает запись и чтение без потерь', () => {
    const back = readDraft(writeDraft(черновик()));

    expect(back.body).toBe('текст черновика');
    expect(back.отпечатокБазы).toBe('ОТП1');
  });

  it('битый файл черновика игнорируется и не роняет программу', () => {
    expect(readDraft('это не json')).toBeNull();
    expect(readDraft('')).toBeNull();
    expect(readDraft(undefined)).toBeNull();
    expect(readDraft('{"нет":"тела"}')).toBeNull();
  });

  it('черновик с недостающим полем считается битым, а не продолжением работы', () => {
    // Без шапки или отпечатка черновик дал бы пустую шапку и сравнение с пустым отпечатком.
    const целый = JSON.parse(writeDraft(черновик()));

    for (const поле of ['path', 'когда', 'отпечатокБазы', 'frontmatterRaw', 'body']) {
      const неполный = {...целый};
      delete неполный[поле];
      expect(readDraft(JSON.stringify(неполный)), поле).toBeNull();
    }
  });

  it('черновики разных статей лежат в разных файлах', () => {
    expect(draftName('docs/a/index.mdx')).not.toBe(draftName('i18n/ru/docs/a/index.mdx'));
    expect(draftName('docs/a/index.mdx')).not.toContain('/');
  });

  it('статьи с похожими путями не делят один файл черновика', () => {
    // Разделитель пути и подчёркивание в имени папки схлопывались в одно имя: две разные статьи
    // писали бы друг другу в черновик, а уборка снимков одной удаляла бы снимки другой.
    expect(draftName('docs/a_b/index.mdx')).not.toBe(draftName('docs/a/b/index.mdx'));
    expect(historyFolder('docs/a_b/index.mdx')).not.toBe(historyFolder('docs/a/b/index.mdx'));
  });
});

describe('что открывать при повторном заходе в статью', () => {
  it('повторное открытие берёт свежий автосохранённый черновик', () => {
    const решение = draftDecision({
      draft: черновик(), файл: ФАЙЛ, отпечатокФайла: 'ОТП1', сейчас: СЕЙЧАС, settings: НАСТРОЙКИ,
    });

    expect(решение).toBe('черновик');
  });

  it('файл изменился снаружи после автосохранения — конфликт, а не молчаливая подмена', () => {
    const решение = draftDecision({
      draft: черновик(), файл: ФАЙЛ, отпечатокФайла: 'ДРУГОЙ', сейчас: СЕЙЧАС, settings: НАСТРОЙКИ,
    });

    expect(решение).toBe('конфликт');
  });

  it('черновика нет — открывается файл', () => {
    expect(draftDecision({
      draft: null, файл: ФАЙЛ, отпечатокФайла: 'ОТП1', сейчас: СЕЙЧАС, settings: НАСТРОЙКИ,
    })).toBe('нет');
  });

  it('черновик слово в слово совпадает с файлом — предлагать нечего', () => {
    const такойЖе = черновик({body: ФАЙЛ.body, frontmatterRaw: ФАЙЛ.frontmatterRaw});

    expect(draftDecision({
      draft: такойЖе, файл: ФАЙЛ, отпечатокФайла: 'ОТП1', сейчас: СЕЙЧАС, settings: НАСТРОЙКИ,
    })).toBe('нет');
  });

  it('черновик отличается от файла только переводами строк — предлагать нечего', () => {
    // На диске файл может быть в windows-виде, а в окне текст живёт в unix-виде (SPEC 3.6).
    // Точное сравнение выдавало бы одинаковые тексты за разные, и человеку предлагали бы
    // «продолжить работу», которой он не делал.
    const другиеПереводы = черновик({
      body: ФАЙЛ.body.replace(/\r\n/g, '\n').split('\n').join('\r\n'),
      frontmatterRaw: ФАЙЛ.frontmatterRaw.replace(/\r\n/g, '\n').split('\n').join('\r\n'),
    });

    expect(draftDecision({
      draft: другиеПереводы, файл: ФАЙЛ, отпечатокФайла: 'ОТП1', сейчас: СЕЙЧАС, settings: НАСТРОЙКИ,
    })).toBe('нет');
  });

  it('протухший черновик игнорируется', () => {
    const старый = черновик({когда: '2026-07-01T10:00:00.000Z'});

    expect(draftDecision({
      draft: старый, файл: ФАЙЛ, отпечатокФайла: 'ОТП1', сейчас: СЕЙЧАС, settings: НАСТРОЙКИ,
    })).toBe('нет');
  });
});

describe('уборка снимков', () => {
  it('снимков остаётся не больше предела, лишние старые уходят', () => {
    const names = ['2026-08-01__я.mdx', '2026-08-02__я.mdx', '2026-08-03__я.mdx', '2026-08-04__я.mdx'];

    expect(extraSnapshots(names, 3)).toEqual(['2026-08-01__я.mdx']);
  });

  it('пока снимков меньше предела, удалять нечего', () => {
    expect(extraSnapshots(['2026-08-01__я.mdx'], 3)).toEqual([]);
  });
});

describe('порядок черновиков на сервере', () => {
  const прежний = {правкаОт: '2026-08-04T12:00:00.000Z'};

  it('поздний запрос со старой правкой свежий черновик не подменяет', () => {
    // Браузер прерывает устаревший запрос, но сервер мог принять его раньше обрыва.
    expect(свежееЧерновика('2026-08-04T11:59:00.000Z', прежний)).toBe(false);
  });

  it('правка новее записанной принимается', () => {
    expect(свежееЧерновика('2026-08-04T12:00:01.000Z', прежний)).toBe(true);
  });

  it('черновика ещё нет — принимается любая правка', () => {
    expect(свежееЧерновика('2026-08-04T12:00:00.000Z', null)).toBe(true);
  });

  it('времени правки нет ни в запросе, ни на диске — черновик принимается по-старому', () => {
    expect(свежееЧерновика(undefined, прежний)).toBe(true);
    expect(свежееЧерновика('2026-08-04T11:00:00.000Z', {})).toBe(true);
  });

  it('порог свежести переживает удаление черновика при сохранении', () => {
    // Сохранение убирает черновик, но помнит время: иначе задержавшийся старый запрос
    // воскресил бы черновик поверх только что сохранённой работы.
    const порог = позже('2026-08-04T12:00:00.000Z', undefined);

    expect(свежееЧерновика('2026-08-04T11:59:00.000Z', {правкаОт: порог})).toBe(false);
  });

  it('запоздавшее сохранение не убирает черновик, написанный после его отправки', () => {
    // Сохранение началось в 12:00, а в 12:05 человек уже набрал новое и оно ушло в черновик:
    // убрать такой черновик значит стереть работу, которой в сохранённом файле нет.
    expect(свежееЧерновика('2026-08-04T12:00:00.000Z', {правкаОт: '2026-08-04T12:05:00.000Z'})).toBe(false);
    expect(свежееЧерновика('2026-08-04T12:05:00.000Z', {правкаОт: '2026-08-04T12:00:00.000Z'})).toBe(true);
  });

  it('позже выбирает более свежее время и переживает пустые значения', () => {
    expect(позже('2026-08-04T12:00:00.000Z', '2026-08-04T11:00:00.000Z')).toBe('2026-08-04T12:00:00.000Z');
    expect(позже('2026-08-04T11:00:00.000Z', '2026-08-04T12:00:00.000Z')).toBe('2026-08-04T12:00:00.000Z');
    expect(позже(undefined, '2026-08-04T12:00:00.000Z')).toBe('2026-08-04T12:00:00.000Z');
    expect(позже(undefined, undefined)).toBeNull();
  });
});

describe('гонка автосохранения с сохранением', () => {
  it('черновик, совпавший с файлом, не даёт конфликта даже со старым отпечатком', () => {
    // Так выглядит черновик, дописанный поздним запросом уже после сохранения:
    // отпечаток базы устарел, но текст совпадает с файлом — продолжать нечего.
    const поздний = черновик({body: ФАЙЛ.body, frontmatterRaw: ФАЙЛ.frontmatterRaw, отпечатокБазы: 'СТАРЫЙ'});

    expect(draftDecision({
      draft: поздний, файл: ФАЙЛ, отпечатокФайла: 'НОВЫЙ', сейчас: СЕЙЧАС, settings: НАСТРОЙКИ,
    })).toBe('нет');
  });
});
