// Имя каждого теста повторяет формулировку правила.
// Правила внешней правки чистые: ни диска, ни git — только вход и результат.
import {describe, expect, it} from 'vitest';
import {авторПравки, времяВерсии, естьВнешняяПравка} from '../src/core/externalEdit.mjs';

const НЕИЗВЕСТНЫЙ = 'Неизвестный';
const ФАЙЛ = '---\ntitle: A\n---\n\nтекст статьи\n';

describe('что считается внешней правкой', () => {
  it('файл разошёлся с известным состоянием — это новая версия', () => {
    expect(естьВнешняяПравка({текстФайла: `${ФАЙЛ}приписка`, известное: ФАЙЛ})).toBe(true);
  });

  it('файл совпадает с известным состоянием — новой версии нет', () => {
    expect(естьВнешняяПравка({текстФайла: ФАЙЛ, известное: ФАЙЛ})).toBe(false);
  });

  it('известного состояния нет — первое увиденное содержимое считается версией', () => {
    expect(естьВнешняяПравка({текстФайла: ФАЙЛ, известное: null})).toBe(true);
  });

  it('изменилась только шапка — это тоже новая версия', () => {
    const сНовойШапкой = '---\ntitle: A\nunlisted: true\n---\n\nтекст статьи\n';

    expect(естьВнешняяПравка({текстФайла: сНовойШапкой, известное: ФАЙЛ})).toBe(true);
  });

  it('изменились только переводы строк — это не новая версия', () => {
    expect(естьВнешняяПравка({текстФайла: ФАЙЛ.replace(/\n/g, '\r\n'), известное: ФАЙЛ})).toBe(false);
  });
});

describe('время внешней версии', () => {
  it('время версии — время изменения файла', () => {
    const когда = времяВерсии({
      времяФайла: '2026-08-04T10:00:00.000Z',
      времяПоследнейВерсии: '2026-08-04T09:00:00.000Z',
      сейчас: '2026-08-04T12:00:00.000Z',
    });

    expect(когда).toBe('2026-08-04T10:00:00.000Z');
  });

  it('время файла не позже последней известной версии — берётся момент обнаружения', () => {
    // Так выглядит файл, восстановленный из копии со старым временем: версия «из прошлого»
    // встала бы в ленте не туда и первой попала бы под уборку лишних снимков.
    const когда = времяВерсии({
      времяФайла: '2026-07-01T10:00:00.000Z',
      времяПоследнейВерсии: '2026-08-04T09:00:00.000Z',
      сейчас: '2026-08-04T12:00:00.000Z',
    });

    expect(когда).toBe('2026-08-04T12:00:00.000Z');
  });

  it('известных версий ещё нет — берётся время изменения файла', () => {
    const когда = времяВерсии({
      времяФайла: '2026-08-04T10:00:00.000Z',
      времяПоследнейВерсии: null,
      сейчас: '2026-08-04T12:00:00.000Z',
    });

    expect(когда).toBe('2026-08-04T10:00:00.000Z');
  });

  it('время файла неразбираемо — берётся момент обнаружения, а не пустое значение', () => {
    const когда = времяВерсии({времяФайла: 'мусор', времяПоследнейВерсии: null, сейчас: '2026-08-04T12:00:00.000Z'});

    expect(когда).toBe('2026-08-04T12:00:00.000Z');
  });
});

describe('кто правил файл', () => {
  const снимок = {когда: '2026-08-04T10:00:00.000Z', автор: 'vzeten'};

  it('автор закоммиченной правки — автор коммита', () => {
    const автор = авторПравки({
      файлГрязный: false,
      авторКоммита: 'Коллега',
      снимок: null,
      времяФайла: '2026-08-04T11:00:00.000Z',
      неизвестный: НЕИЗВЕСТНЫЙ,
    });

    expect(автор).toBe('Коллега');
  });

  it('незакоммиченная правка без следа в истории — автор неизвестен, а не имя из git config', () => {
    const автор = авторПравки({
      файлГрязный: true,
      авторКоммита: 'Коллега',
      снимок: null,
      времяФайла: '2026-08-04T11:00:00.000Z',
      неизвестный: НЕИЗВЕСТНЫЙ,
    });

    expect(автор).toBe(НЕИЗВЕСТНЫЙ);
  });

  it('слово для неизвестного автора берётся из настроек, а не из кода', () => {
    const автор = авторПравки({
      файлГрязный: true,
      авторКоммита: null,
      снимок: null,
      времяФайла: '2026-08-04T11:00:00.000Z',
      неизвестный: 'Кто-то другой',
    });

    expect(автор).toBe('Кто-то другой');
  });

  it('правку сделал сам редактор и записал снимок — показывается автор из снимка', () => {
    const автор = авторПравки({
      файлГрязный: true,
      авторКоммита: null,
      снимок,
      времяФайла: '2026-08-04T10:00:00.000Z',
      неизвестный: НЕИЗВЕСТНЫЙ,
    });

    expect(автор).toBe('vzeten');
  });

  it('файл изменён после нашего снимка — автор снова неизвестен', () => {
    // Снимок остался от прошлого сохранения, а поверх него писал кто-то ещё: подпись из снимка
    // приписала бы владельцу чужую правку.
    const автор = авторПравки({
      файлГрязный: true,
      авторКоммита: null,
      снимок,
      времяФайла: '2026-08-04T10:00:01.000Z',
      неизвестный: НЕИЗВЕСТНЫЙ,
    });

    expect(автор).toBe(НЕИЗВЕСТНЫЙ);
  });

  it('у коммита нет имени автора — берётся слово из настроек', () => {
    const автор = авторПравки({
      файлГрязный: false,
      авторКоммита: '',
      снимок: null,
      времяФайла: '2026-08-04T11:00:00.000Z',
      неизвестный: НЕИЗВЕСТНЫЙ,
    });

    expect(автор).toBe(НЕИЗВЕСТНЫЙ);
  });
});
