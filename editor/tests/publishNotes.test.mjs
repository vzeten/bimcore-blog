// Имя каждого теста повторяет формулировку правила.
//
// Что человек слышит при отказе публикации (решения владельца 2026-09-18 и 2026-09-19): причина —
// словами человека, ссылка называется своим текстом, «На сайт ничего не ушло» — только когда это
// правда. Непроверенное быстрыми проверками человеку не показывается, но едет с исходом и записью.
import {afterEach, describe, expect, it} from 'vitest';
import fs from 'node:fs';
import path from 'node:path';

import {опубликовать} from '../src/ui/publishRun';
import {ничегоНеУшло, местоОстановки, словаНаходки, строкаПричины} from '../src/ui/zones/PublishReason';
import {сМалой} from '../src/ui/zones/PublishButton';
import {ЖДАТЬ_GIT} from './saveHarness.mjs';
import {RU, НАСТРОЙКИ, дверь, наСервере, среда, убратьПесочницы, ход} from './runHarness.mjs';

afterEach(() => убратьПесочницы());

const непроверено = (исход) => (исход.предупреждения ?? []).map((находка) => находка.код);
const пусто = {ключ: 'естьПрепятствия', текст: '', код: null, наОтправке: false, изменены: [], чужие: [], разрывы: [], невосстановленные: [], убрано: [], вывод: ''};

describe('причина отказа словами человека', () => {
  it('ссылка в никуда называется своим текстом, без адреса и номера строки; кнопка — «Показать ссылку»', () => {
    const ссылка = {код: 'ссылкаВНикуда', уровень: 'блокер', этап: 'ссылки', путь: RU, строка: 7, значение: '/lessons/nope/', текст: 'урок про стены'};

    expect(строкаПричины({...пусто, находки: [ссылка]}, НАСТРОЙКИ))
      .toBe('Ссылка «урок про стены» ведёт на страницу, которой нет на сайте. Исправьте или уберите её.');
    expect(местоОстановки({...пусто, находки: [ссылка]})).toEqual({путь: RU, строка: 7, код: 'ссылкаВНикуда'});
    expect(НАСТРОЙКИ['публикация']['показатьСсылку']).toBe('Показать ссылку');
  });

  it('текста у ссылки нет — называется адрес', () => {
    expect(словаНаходки({код: 'ссылкаВНикуда', уровень: 'блокер', этап: 'ссылки', значение: '/lessons/nope/'}, НАСТРОЙКИ))
      .toBe('Ссылка «/lessons/nope/» ведёт на страницу, которой нет на сайте. Исправьте или уберите её.');
  });

  it('находка про поле называет поле его подписью из свойств статьи; поле неизвестно — фраза без имени', () => {
    expect(словаНаходки({код: 'полеКатегорииПусто', уровень: 'предупреждение', этап: 'поляПоиска', поле: 'keywords'}, НАСТРОЙКИ))
      .toBe('Не заполнено поле «Ключевые слова». Заполните его в свойствах статьи.');
    expect(словаНаходки({код: 'поле:ключДважды', уровень: 'блокер', этап: 'шапка', поле: 'description'}, НАСТРОЙКИ))
      .toBe('Поле «Описание для поиска» записано дважды. Уберите лишнее.');
    expect(словаНаходки({код: 'поле:неПрочитано', уровень: 'блокер', этап: 'шапка', поле: 'related'}, НАСТРОЙКИ))
      .toBe('Поле «related» записано так, что его не прочитать. Перепишите его в свойствах статьи.');
    expect(словаНаходки({код: 'полеКатегорииПусто', уровень: 'предупреждение', этап: 'поляПоиска'}, НАСТРОЙКИ))
      .toBe('Не заполнено поле. Заполните его в свойствах статьи.');
  });

  it('технический разбор делает Claude: причина просит показать сообщение ему', () => {
    expect(строкаПричины({...пусто, ключ: 'составНеДоказан', находки: []}, НАСТРОЙКИ))
      .toBe('Не удалось понять, какие файлы относятся к статье. Покажите это сообщение Claude.');
  });

  it('состав не доказан — человеку называется сама причина', () => {
    expect(строкаПричины({...пусто, ключ: 'составНеДоказан', находки: [], разрывы: [{причина: 'папкаНеОдна'}]}, НАСТРОЙКИ))
      .toBe(НАСТРОЙКИ['выпуск']['разрывы']['папкаНеОдна']);
  });
});

describe('непроверенное — не человеку, но с исходом', () => {
  it('досылка прошлой записи — тоже успех, и непроверенное едет и там', async () => {
    const с = await среда();
    fs.appendFileSync(path.join(с.repo, RU), 'Новая строка.\n', 'utf8');
    const основная = дверь(с, []);
    let оборвать = true;
    const сОбрывом = async (адрес, тело) => {
      if (адрес === '/api/publish/push' && оборвать) {
        оборвать = false;
        throw new Error('сеть оборвалась');
      }
      return основная(адрес, тело);
    };
    await опубликовать(RU, false, ход(сОбрывом, []), 'всем').catch(() => null);

    const исход = await опубликовать(RU, false, ход(сОбрывом, []), 'всем');

    expect(исход.вид).toBe('готово');
    expect(непроверено(исход)).toContain('mdxНеПроверен');
  }, ЖДАТЬ_GIT * 2);

  it('ход отдаёт предупреждения проверок вместе с успехом: разборщика MDX нет — это не молчание', async () => {
    const с = await среда();
    fs.appendFileSync(path.join(с.repo, RU), 'Новая строка.\n', 'utf8');

    const исход = await опубликовать(RU, false, ход(дверь(с, []), []), 'всем');

    expect(исход.вид).toBe('готово');
    // В учебном репозитории зависимостей сайта нет, поэтому разметку текста проверить нечем.
    expect(непроверено(исход)).toContain('mdxНеПроверен');
  }, ЖДАТЬ_GIT * 2);
});

describe('начатая публикация доходит до конца, куда бы человек ни ушёл (проба владельца 2026-09-19)', () => {
  it('ушёл из статьи во время проверок — коммит сделан и уехал на сайт', async () => {
    const с = await среда();
    fs.appendFileSync(path.join(с.repo, RU), 'Новая строка.\n', 'utf8');
    const основная = дверь(с, []);
    let живо = true;
    const сУходом = async (адрес, тело) => {
      const ответ = await основная(адрес, тело);
      // Человек ушёл в реестр сразу после обязательных проверок.
      if (адрес === '/api/prepare') живо = false;
      return ответ;
    };

    const исход = await опубликовать(RU, false, {...ход(сУходом, []), жива: () => живо}, 'всем');

    expect(исход.вид).toBe('готово');
    expect(await с.git.raw(['show', `${await наСервере(с.сервер)}:${RU}`])).toContain('Новая строка.');
  }, ЖДАТЬ_GIT * 2);

  it('ушёл раньше, чем окно записало своё (несохранённое), — запись не ложится в чужую статью, ход честно останавливается', async () => {
    const с = await среда();
    let сохранено = false;
    const х = {...ход(дверь(с, []), []), жива: () => false, сохранить: async () => {
      сохранено = true;
      return true;
    }};

    const исход = await опубликовать(RU, true, х, 'всем');

    expect(исход.вид).toBe('прервано');
    expect(сохранено).toBe(false);
  }, ЖДАТЬ_GIT);
});

describe('полоса «Статья «…» не опубликована: …»', () => {
  it('причина после двоеточия — со строчной; имена собственные не трогаются', () => {
    expect(сМалой('Ссылка «урок» ведёт на страницу, которой нет на сайте.')).toBe('ссылка «урок» ведёт на страницу, которой нет на сайте.');
    expect(сМалой('English: есть несохранённая правка')).toBe('English: есть несохранённая правка');
  });
});

describe('«На сайт ничего не ушло» — только правда', () => {
  const остановка = (ещё) => ({...пусто, ключ: null, находки: [], ...ещё});

  it('отказ проверки или записи — ничего не ушло', () => {
    expect(ничегоНеУшло(остановка({ключ: 'естьПрепятствия'}))).toBe(true);
    expect(ничегоНеУшло(остановка({текст: 'Статья изменилась', код: 'статьяИзменилась'}))).toBe(true);
  });

  it('исход отправки неясен, статья записана, но не отправлена или не приведена в порядок — не обещается', () => {
    expect(ничегоНеУшло(остановка({текст: 'Неясно', код: 'исходНеясен'}))).toBe(false);
    expect(ничегоНеУшло(остановка({ключ: 'неОтправилось'}))).toBe(false);
    expect(ничегоНеУшло(остановка({ключ: 'невосстановлено'}))).toBe(false);
    // Сам запрос записи или отправки оборвался без ответа: сервер мог всё принять.
    expect(ничегоНеУшло(остановка({текст: 'Failed to fetch', наОтправке: true}))).toBe(false);
  });
});
