// Имя каждого теста повторяет формулировку правила.
// Чистые правила смены формата: адрес, подсчёт и замена вхождения, проверка использования.
import {describe, expect, it} from 'vitest';

import {адресНовогоФормата, дорогаЗамены, заменитьВхождение, номерВхождения, файлИспользуется} from '../src/core/imageFormat.mjs';
import {перенестиВыбор} from '../src/ui/editor/imagePanelPlace';

const УЗЕЛ = '![Подпись](./img-01.jpg)';

describe('адрес картинки после смены формата', () => {
  it('основа имени сохраняется, расширение меняется', () => {
    expect(адресНовогоФормата('./img-01.jpg', 'png')).toBe('./img-01.png');
  });

  it('точка внутри пути не путается с расширением', () => {
    expect(адресНовогоФормата('./img.v2/pic.jpg', 'png')).toBe('./img.v2/pic.png');
  });

  it('адрес без расширения менять нечем', () => {
    expect(адресНовогоФормата('картинка', 'png')).toBeNull();
  });
});

describe('номер вхождения узла', () => {
  it('единственный узел — первое вхождение', () => {
    const текст = `перед\n${УЗЕЛ}\nпосле`;
    expect(номерВхождения(текст, УЗЕЛ, текст.indexOf(УЗЕЛ))).toBe(1);
  });

  it('одинаковые узлы различаются позицией', () => {
    const текст = `${УЗЕЛ}\n\n${УЗЕЛ}`;
    expect(номерВхождения(текст, УЗЕЛ, 0)).toBe(1);
    expect(номерВхождения(текст, УЗЕЛ, текст.lastIndexOf(УЗЕЛ))).toBe(2);
  });

  it('подсчёт не зависит от вида переводов строк вокруг', () => {
    // Окно считает по LF-тексту, сервер — по файлу с CRLF: номер обязан совпасть.
    const lf = `строка\n${УЗЕЛ}\nи ещё\n${УЗЕЛ}`;
    const crlf = lf.replace(/\n/g, '\r\n');
    expect(номерВхождения(lf, УЗЕЛ, lf.lastIndexOf(УЗЕЛ)))
      .toBe(номерВхождения(crlf, УЗЕЛ, crlf.lastIndexOf(УЗЕЛ)));
  });
});

describe('замена вхождения узла', () => {
  it('меняется ровно названное вхождение, соседи не трогаются', () => {
    const текст = `${УЗЕЛ}\n\n${УЗЕЛ}`;
    const новый = '![Подпись](./img-01.png)';
    expect(заменитьВхождение(текст, УЗЕЛ, 2, новый)).toBe(`${УЗЕЛ}\n\n${новый}`);
  });

  it('вхождений меньше названного номера — текст не меняется вовсе', () => {
    expect(заменитьВхождение(`${УЗЕЛ}`, УЗЕЛ, 2, 'что угодно')).toBeNull();
  });

  it('пустой узел не заменяется никогда', () => {
    expect(заменитьВхождение('текст', '', 1, 'что угодно')).toBeNull();
  });
});

describe('используется ли файл картинки', () => {
  it('ссылка в теле удерживает файл', () => {
    expect(файлИспользуется('осталось ![x](./img-01.jpg) в тексте', 'img-01.jpg')).toBe(true);
  });

  it('обложка в шапке удерживает файл', () => {
    expect(файлИспользуется('---\nimage: ./img-01.jpg\n---\nтело', 'img-01.jpg')).toBe(true);
  });

  it('ни одной ссылки не осталось — файл свободен', () => {
    expect(файлИспользуется('---\nimage: ./cover.png\n---\n![x](./img-01.png)', 'img-01.jpg')).toBe(false);
  });
});

describe('дорога замены картинки', () => {
  const РОДЫ = ['jpg', 'png', 'gif'];

  it('та же порода идёт заменой байтов, другая — сменой формата: все девять переходов', () => {
    // Решение владельца 2026-08-18: JPG, PNG и GIF заменяются во всех направлениях.
    for (const формат of РОДЫ) {
      for (const порода of РОДЫ) {
        const дорога = дорогаЗамены({порода, формат, сохранено: true});
        expect(дорога, `${формат} → ${порода}`).toBe(порода === формат ? 'замена' : 'смена');
      }
    }
  });

  it('порода решает дорогу, а не имя файла: JPEG с именем png идёт заменой байтов у JPG', () => {
    expect(дорогаЗамены({порода: 'jpg', формат: 'jpg', сохранено: true})).toBe('замена');
    expect(дорогаЗамены({порода: 'gif', формат: 'png', сохранено: true})).toBe('смена');
  });

  it('файл не той породы на сервер не отправляется вовсе', () => {
    expect(дорогаЗамены({порода: null, формат: 'png', сохранено: true})).toBe('чужаяПорода');
    expect(дорогаЗамены({порода: undefined, формат: 'png', сохранено: false})).toBe('чужаяПорода');
  });

  it('смена формата требует сохранённого текста, а замена байтов — нет', () => {
    // Смена меняет и файл, и ссылку в статье: серверу нужно с чем сверять то, что видит человек.
    expect(дорогаЗамены({порода: 'gif', формат: 'png', сохранено: false})).toBe('сначалаСохранить');
    expect(дорогаЗамены({порода: 'png', формат: 'png', сохранено: false})).toBe('замена');
  });
});

describe('использование файла и регистр имени', () => {
  it('ссылка в другом регистре удерживает файл от удаления', () => {
    // На Windows `IMG-01.PNG` и `img-01.png` — один файл: сомнение толкуется в пользу сохранения.
    expect(файлИспользуется('![](./IMG-01.PNG)', 'img-01.png')).toBe(true);
    expect(файлИспользуется('image: ./Img-01.Png', 'img-01.png')).toBe(true);
  });

  it('чужое имя файл не удерживает', () => {
    expect(файлИспользуется('![](./img-02.png)', 'img-01.png')).toBe(false);
  });
});

describe('перенос выбранной картинки на новый адрес', () => {
  const было = {src: './img-01.png', alt: 'Подпись', from: 10, to: 40, left: 100, top: 200};
  const весть = {выбор: 3, src: './img-02.jpg', from: 10, to: 41, left: 120, top: 205};

  it('весть своего выбора переносит адрес, границы и место, а alt остаётся', () => {
    expect(перенестиВыбор(было, 3, весть))
      .toEqual({src: './img-02.jpg', alt: 'Подпись', from: 10, to: 41, left: 120, top: 205});
  });

  it('весть чужого выбора ничего не меняет: человек уже нажал другую картинку', () => {
    // Иначе поздний ответ прежней панели подменил бы адрес у чужой картинки и оставил ей чужой alt.
    expect(перенестиВыбор(было, 4, весть)).toBe(было);
  });

  it('картинка уже не выбрана — переносить нечего', () => {
    expect(перенестиВыбор(null, 3, весть)).toBeNull();
  });
});
