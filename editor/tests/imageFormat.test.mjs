// Имя каждого теста повторяет формулировку правила.
// Чистые правила смены формата: адрес, подсчёт и замена вхождения, проверка использования.
import {describe, expect, it} from 'vitest';

import {адресНовогоФормата, заменитьВхождение, номерВхождения, файлИспользуется} from '../src/core/imageFormat.mjs';

const УЗЕЛ = '![Подпись](./img-01.jpg)';

describe('адрес картинки после смены формата', () => {
  it('основа имени сохраняется, расширение меняется', () => {
    expect(адресНовогоФормата('./img-01.jpg', 'png')).toBe('./img-01.png');
  });

  it('точка внутри пути не путается с расширением', () => {
    expect(адресНовогоФормата('./img.v2/pic.jpg', 'png')).toBe('./img.v2/pic.png');
  });

  it('адрес без расширения менять нечем', () => {
    expect(адресНовогоФормата('картинка', 'png')).toBeNull();
  });
});

describe('номер вхождения узла', () => {
  it('единственный узел — первое вхождение', () => {
    const текст = `перед\n${УЗЕЛ}\nпосле`;
    expect(номерВхождения(текст, УЗЕЛ, текст.indexOf(УЗЕЛ))).toBe(1);
  });

  it('одинаковые узлы различаются позицией', () => {
    const текст = `${УЗЕЛ}\n\n${УЗЕЛ}`;
    expect(номерВхождения(текст, УЗЕЛ, 0)).toBe(1);
    expect(номерВхождения(текст, УЗЕЛ, текст.lastIndexOf(УЗЕЛ))).toBe(2);
  });

  it('подсчёт не зависит от вида переводов строк вокруг', () => {
    // Окно считает по LF-тексту, сервер — по файлу с CRLF: номер обязан совпасть.
    const lf = `строка\n${УЗЕЛ}\nи ещё\n${УЗЕЛ}`;
    const crlf = lf.replace(/\n/g, '\r\n');
    expect(номерВхождения(lf, УЗЕЛ, lf.lastIndexOf(УЗЕЛ)))
      .toBe(номерВхождения(crlf, УЗЕЛ, crlf.lastIndexOf(УЗЕЛ)));
  });
});

describe('замена вхождения узла', () => {
  it('меняется ровно названное вхождение, соседи не трогаются', () => {
    const текст = `${УЗЕЛ}\n\n${УЗЕЛ}`;
    const новый = '![Подпись](./img-01.png)';
    expect(заменитьВхождение(текст, УЗЕЛ, 2, новый)).toBe(`${УЗЕЛ}\n\n${новый}`);
  });

  it('вхождений меньше названного номера — текст не меняется вовсе', () => {
    expect(заменитьВхождение(`${УЗЕЛ}`, УЗЕЛ, 2, 'что угодно')).toBeNull();
  });

  it('пустой узел не заменяется никогда', () => {
    expect(заменитьВхождение('текст', '', 1, 'что угодно')).toBeNull();
  });
});

describe('используется ли файл картинки', () => {
  it('ссылка в теле удерживает файл', () => {
    expect(файлИспользуется('осталось ![x](./img-01.jpg) в тексте', 'img-01.jpg')).toBe(true);
  });

  it('обложка в шапке удерживает файл', () => {
    expect(файлИспользуется('---\nimage: ./img-01.jpg\n---\nтело', 'img-01.jpg')).toBe(true);
  });

  it('ни одной ссылки не осталось — файл свободен', () => {
    expect(файлИспользуется('---\nimage: ./cover.png\n---\n![x](./img-01.png)', 'img-01.jpg')).toBe(false);
  });
});
