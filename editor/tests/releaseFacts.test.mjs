// Имя каждого теста повторяет формулировку правила.
// Отпечаток состава: доказательство, что полная сборка видела ровно то содержимое, которое уедет
// в коммит. Здесь проверяется главное его свойство — РАЗНЫЕ составы дают РАЗНЫЕ отпечатки.
import {afterEach, describe, expect, it} from 'vitest';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

import {отпечатокСостава} from '../src/adapters/releaseFacts.mjs';

const EDITOR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const песочницы = [];

/** Временный репозиторий из пар «путь → содержимое»; содержимое бывает и двоичным. */
function среда(файлы) {
  const repo = fs.mkdtempSync(path.join(os.tmpdir(), 'editor-facts-'));
  песочницы.push(repo);

  for (const [rel, содержимое] of Object.entries(файлы)) {
    fs.mkdirSync(path.join(repo, path.dirname(rel)), {recursive: true});
    fs.writeFileSync(path.join(repo, rel), содержимое);
  }

  return repo;
}

/** Состав в том виде, в каком его отдаёт правило состава: важен только путь. */
const состав = (...пути) => пути.map((путь) => ({путь}));

afterEach(() => {
  while (песочницы.length > 0) fs.rmSync(песочницы.pop(), {recursive: true, force: true});
});

describe('отпечаток состава', () => {
  it('один и тот же состав даёт один и тот же отпечаток', () => {
    const repo = среда({'docs/a/index.mdx': 'Текст', 'docs/a/cover.png': 'картинка'});
    const файлы = состав('docs/a/index.mdx', 'docs/a/cover.png');

    expect(отпечатокСостава(repo, файлы)).toBe(отпечатокСостава(repo, файлы));
  });

  it('правка одного байта в содержимом меняет отпечаток', () => {
    const первый = среда({'docs/a/index.mdx': 'Текст'});
    const второй = среда({'docs/a/index.mdx': 'Тексты'});
    const файлы = состав('docs/a/index.mdx');

    expect(отпечатокСостава(первый, файлы)).not.toBe(отпечатокСостава(второй, файлы));
  });

  it('перенос знаков из пути в содержимое меняет отпечаток: склейка не может быть двусмысленной', () => {
    // Без границ кусков оба состава дали бы один поток знаков: «docs/a/имя.mdx» + «X».
    const первый = среда({'docs/a/имя.mdx': 'X'});
    const второй = среда({'docs/a/имя.mdxX': ''});

    expect(отпечатокСостава(первый, состав('docs/a/имя.mdx')))
      .not.toBe(отпечатокСостава(второй, состав('docs/a/имя.mdxX')));
  });

  it('граница пути и содержимого держится и на кириллице, и на латинице: длина считается в байтах', () => {
    // Кириллическая буква занимает два байта, латинская один. Считай программа длину буквами,
    // граница куска врала бы ровно на кириллических путях — а они у нас у каждой русской статьи.
    const кириллица = среда({'docs/статья/имя.mdx': 'X'});
    const латиница = среда({'docs/статья/имя.mdxX': ''});
    const ascii = среда({'docs/a/name.mdx': 'X'});
    const asciiДлиннее = среда({'docs/a/name.mdxX': ''});

    expect(отпечатокСостава(кириллица, состав('docs/статья/имя.mdx')))
      .not.toBe(отпечатокСостава(латиница, состав('docs/статья/имя.mdxX')));
    expect(отпечатокСостава(ascii, состав('docs/a/name.mdx')))
      .not.toBe(отпечатокСостава(asciiДлиннее, состав('docs/a/name.mdxX')));
  });

  it('двоичное содержимое с нулевыми байтами не выдаёт один файл за два: границу задаёт длина', () => {
    // Ровно то, чем опасен разделитель-знак: у картинки нулевой байт внутри содержимого законен.
    // Со знаком-разделителем поток «a NUL <NUL b NUL> NUL» совпал бы с потоком двух пустых файлов
    // «a NUL NUL b NUL NUL», и сборка «подтвердила» бы содержимое, которого не видела.
    const один = среда({'docs/a': Buffer.from([0x00, 0x62, 0x00])});
    const два = среда({'docs/a': Buffer.alloc(0), 'docs/b': Buffer.alloc(0)});

    expect(отпечатокСостава(один, состав('docs/a')))
      .not.toBe(отпечатокСостава(два, состав('docs/a', 'docs/b')));
  });

  it('пропавший файл отличается от файла, чьё содержимое похоже на признак пропажи', () => {
    const пусто = среда({});
    const есть = среда({'docs/a/index.mdx': '-'});

    expect(отпечатокСостава(пусто, состав('docs/a/index.mdx')))
      .not.toBe(отпечатокСостава(есть, состав('docs/a/index.mdx')));
  });

  it('порядок файлов в составе входит в отпечаток', () => {
    const repo = среда({'docs/a/index.mdx': 'первый', 'docs/a/второй.mdx': 'второй'});

    expect(отпечатокСостава(repo, состав('docs/a/index.mdx', 'docs/a/второй.mdx')))
      .not.toBe(отпечатокСостава(repo, состав('docs/a/второй.mdx', 'docs/a/index.mdx')));
  });

  it('исходник отпечатка остаётся текстом: двоичных знаков в нём нет', () => {
    // Предохранитель от возврата прежней беды (SPEC 5.2.1): сырой нулевой байт в литерале делал
    // файл двоичным для git, и отличия по нему переставали читаться вовсе.
    const файл = fs.readFileSync(path.join(EDITOR, 'src/adapters/releaseFacts.mjs'));
    const управляющие = [...файл].filter((байт) => байт < 9 || (байт > 10 && байт < 32 && байт !== 13));

    expect(управляющие).toEqual([]);
  });
});
