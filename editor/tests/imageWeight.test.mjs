// Имя каждого теста повторяет формулировку правила.
// Вес выбранной картинки: единственный отказ — слишком тяжёлый GIF, всё прочее только совет.
import {describe, expect, it} from 'vitest';

import {весКартинки, гифПеревесил, текстОтказаГиф} from '../src/core/imageWeight.mjs';

const МБ = 1024 * 1024;

describe('предел веса анимации', () => {
  it('GIF немного меньше предела принимается', () => {
    expect(гифПеревесил('gif', 5 * МБ - 1024, 5)).toBe(false);
  });

  it('GIF ровно в предел принимается: предел включительный', () => {
    expect(гифПеревесил('gif', 5 * МБ, 5)).toBe(false);
  });

  it('GIF на один байт больше предела отвергается', () => {
    expect(гифПеревесил('gif', 5 * МБ + 1, 5)).toBe(true);
  });

  it('JPG и PNG любого веса пределом анимации не отвергаются', () => {
    expect(гифПеревесил('jpg', 50 * МБ, 5)).toBe(false);
    expect(гифПеревесил('png', 50 * МБ, 5)).toBe(false);
  });
});

describe('совет сжать картинку', () => {
  it('тяжёлый JPG получает совет сжать перед публикацией', () => {
    expect(весКартинки('jpg', 900 * 1024, 500)).toEqual({тяжёлая: true, килобайт: 900});
  });

  it('лёгкий PNG совета не получает', () => {
    expect(весКартинки('png', 100 * 1024, 500)).toEqual({тяжёлая: false, килобайт: 100});
  });

  it('GIF совета сжать не получает никогда: сжимать анимацию человеку нечем', () => {
    // Живой случай владельца: `gigapixelai.gif` около полутора мегабайт — вес заметный,
    // но сказать про него нечего, кроме шума, на который человек ответить не может.
    expect(весКартинки('gif', Math.round(1.5 * МБ), 500)).toEqual({тяжёлая: false, килобайт: 1536});
    expect(весКартинки('gif', 5 * МБ, 500).тяжёлая).toBe(false);
  });
});

describe('текст отказа', () => {
  it('предел подставляется в текст из настройки, а не переписывается в него руками', () => {
    expect(текстОтказаГиф('GIF больше {мегабайт} МБ. Уменьшите заранее', 5))
      .toBe('GIF больше 5 МБ. Уменьшите заранее');
  });

  it('текста нет — отказ остаётся пустой строкой, а не словом undefined', () => {
    expect(текстОтказаГиф(undefined, 5)).toBe('');
  });
});
