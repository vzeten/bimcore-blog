// Правила самого корпусного прогона: чем он краснеет и чему верит на слово.
// Прогон — инструмент ворот всех заданий класса А, и до этих тестов его меры держались только
// на разовых проверках руками: следующая правка команды могла тихо снять красноту.
import {describe, expect, it} from 'vitest';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

import {
  НЕТ_ШАПКИ, ПЕРЕПИСАН, РАЗОШЁЛСЯ, СОВПАЛ, ТОЛЬКО_ПЕРЕВОДЫ,
  беды, исходФайла, классифицировать, подготовка, прогон, смешаныПереводы, файлыКонтента,
} from '../scripts/corpusRules.mjs';

const НАСТРОЙКИ = {
  контент: [
    {локаль: 'en', род: 'docs', папка: 'docs', наСайте: true},
    {локаль: 'ru', род: 'проба', папка: 'sandbox', наСайте: false},
  ],
};

const ПУТЬ = 'docs/lessons/proba/index.mdx';

/** Пара «файл — собранный текст» для чистого правила: расхождение объяснимо только шапкой. */
function пара({raw, текст, ожидаемое = raw}) {
  return {raw, текст, пишет: false, ожидаемое, смешаныПереводы: смешаныПереводы(raw)};
}

describe('исход одного файла', () => {
  it('файл, который сохранение не тронуло бы, — совпал', () => {
    const raw = '---\ntitle: Проба\nslug: /lessons/proba\n---\n\nТекст.\n';

    expect(исходФайла(ПУТЬ, raw, НАСТРОЙКИ).исход).toBe(СОВПАЛ);
  });

  it('защитная правка шапки означает, что файл был бы переписан', () => {
    // Пустая обложка роняет сборку сайта, поэтому сервер убирает её при сохранении (SPEC 2.1).
    const raw = '---\ntitle: Проба\nslug: /lessons/proba\nimage:\n---\n\nТекст.\n';

    expect(исходФайла(ПУТЬ, raw, НАСТРОЙКИ).исход).toBe(ПЕРЕПИСАН);
  });

  it('файл без шапки получает свой исход, а не выдаётся за поломку сборки текста', () => {
    // Сборка припишет такому файлу шапку, и это решённое поведение программы: шапка появляется
    // правкой человека в его собственном файле (круг 1б). Красный прогон тут врал бы про причину.
    expect(исходФайла(ПУТЬ, 'Просто текст.\n', НАСТРОЙКИ).исход).toBe(НЕТ_ШАПКИ);
  });

  it('файл со смешанными переводами строк — разница только в переводах строк', () => {
    const raw = '---\r\ntitle: Проба\r\nslug: /lessons/proba\r\n---\r\n\r\nПервый.\nВторой.\r\n';

    expect(исходФайла(ПУТЬ, raw, НАСТРОЙКИ).исход).toBe(ТОЛЬКО_ПЕРЕВОДЫ);
  });

  it('шапка, которую разбор не принял, — это не файл без шапки, и её порча красная', () => {
    // Пустая шапка без перевода строки между разделителями: `gray-matter` её читает, разбор
    // редактора — нет. Сборка припишет вторую пару разделителей, а старая уедет в тело статьи.
    // Спроси прогон о шапке тот же разбор, который он проверяет, — беда ушла бы в жёлтый исход.
    expect(исходФайла(ПУТЬ, '---\n---\n\nТекст.\n', НАСТРОЙКИ).исход).toBe(РАЗОШЁЛСЯ);
  });

  it('удвоение невидимой метки у файла без шапки — беда программы, а не свойство файла', () => {
    // Ожидаемый вид считается от текста файла, а не от того, что разбор счёл телом: иначе обе
    // стороны сравнения собрались бы из одних кусков и проверка сверяла бы сама себя.
    expect(исходФайла(ПУТЬ, '﻿Текст без шапки.\n', НАСТРОЙКИ).исход).toBe(РАЗОШЁЛСЯ);
  });
});

describe('расхождение прощается только вместе со своей причиной', () => {
  it('смешанные переводы строк не прощают файлу потерянную строку текста', () => {
    // Мера относится к самому расхождению, а не к файлу целиком: скажи прогон «файл смешанный,
    // значит виноват он» — порча содержимого в таком файле прошла бы мимо ворот незамеченной.
    const raw = '---\r\ntitle: Проба\r\n---\r\n\r\nПервая строка.\nВторая строка.\r\n';
    const текст = '---\r\ntitle: Проба\r\n---\r\n\r\nПервая строка.\r\n';

    expect(классифицировать(пара({raw, текст})).исход).toBe(РАЗОШЁЛСЯ);
  });

  it('файл с однородными переводами строк не объясняет расхождение переводами строк', () => {
    // Обратная половина той же меры: сведи сборка весь свод к одному виду переводов строк —
    // расхождение исчезало бы при нормализации, и прогон объявил бы виноватыми исправные файлы.
    const raw = '---\r\ntitle: Проба\r\n---\r\n\r\nТекст.\r\n';
    const текст = raw.replace(/\r\n/g, '\n');

    expect(смешаныПереводы(raw)).toBe(false);
    expect(классифицировать(пара({raw, текст})).исход).toBe(РАЗОШЁЛСЯ);
  });

  it('файл без шапки не прощает расхождение сверх приписанной шапки', () => {
    const raw = 'Просто текст.\n';
    const ожидаемое = `---\n\n---\n${raw}`;

    expect(классифицировать(пара({raw, текст: ожидаемое, ожидаемое})).исход).toBe(НЕТ_ШАПКИ);
    expect(классифицировать(пара({raw, текст: '---\n\n---\nСовсем другой текст.\n', ожидаемое})).исход)
      .toBe(РАЗОШЁЛСЯ);
  });

  it('у разошедшегося текста показано место различия, а не один путь', () => {
    const raw = '---\ntitle: Проба\n---\n\nБыло.\n';
    const текст = '---\ntitle: Проба\n---\n\nСтало.\n';

    expect(классифицировать(пара({raw, текст})).строки.length).toBeGreaterThan(0);
  });
});

describe('отчего прогон красный', () => {
  const пусто = {
    пути: ['docs/a/index.mdx'],
    пустыеКорниСайта: [],
    поИсходам: new Map([[ПЕРЕПИСАН, []], [РАЗОШЁЛСЯ, []], [ТОЛЬКО_ПЕРЕВОДЫ, []], [НЕТ_ШАПКИ, []]]),
  };
  const проверена = {всего: 1, проверено: 1, внеСайта: 0, находки: []};

  it('всё чисто — бед нет', () => {
    expect(беды(пусто, проверена)).toEqual([]);
  });

  it('переписанный файл делает прогон красным', () => {
    const итог = {...пусто, поИсходам: new Map(пусто.поИсходам).set(ПЕРЕПИСАН, [{путь: 'a', строки: []}])};

    expect(беды(итог, проверена)).toHaveLength(1);
  });

  it('разошедшийся с файлом текст делает прогон красным', () => {
    const итог = {...пусто, поИсходам: new Map(пусто.поИсходам).set(РАЗОШЁЛСЯ, [{путь: 'a', строки: []}])};

    expect(беды(итог, проверена)).toHaveLength(1);
  });

  it('пустой корень сайта делает прогон красным', () => {
    expect(беды({...пусто, пустыеКорниСайта: [{папка: 'docs'}]}, проверена)).toHaveLength(1);
  });

  it('ни одной проверенной статьи при найденных файлах — тоже красный', () => {
    // Иначе половина прогона, отвечающая за правила подготовки, молчала бы так же, как молчал бы
    // обход по пустому корню: «блокеров 0» неотличимо от «не смотрел ни одной статьи».
    expect(беды(пусто, {всего: 1, проверено: 0, внеСайта: 1, находки: []})).toHaveLength(1);
  });

  it('пустой снимок статьи — поломка самого прогона, а не строчка в счёте блокеров', () => {
    // Снимок собирает сам прогон, поэтому «проверять нечего» говорит о нём, а не о статье.
    // В общем счёте блокеров эта находка затерялась бы среди находок живых статей.
    const находки = [{уровень: 'блокер', код: 'нечегоПроверять'}];

    expect(беды(пусто, {...проверена, находки})).toHaveLength(1);
  });

  it('объяснимое расхождение и находки подготовки прогон не валят', () => {
    // Иначе прогон был бы красным всегда: живые статьи писались до программы, шесть из них без
    // описания владелец решил не трогать.
    const итог = {
      ...пусто,
      поИсходам: new Map(пусто.поИсходам)
        .set(ТОЛЬКО_ПЕРЕВОДЫ, [{путь: 'a', строки: []}])
        .set(НЕТ_ШАПКИ, [{путь: 'b', строки: []}]),
    };

    expect(беды(итог, {...проверена, находки: [{уровень: 'блокер', код: 'описаниеПусто'}]})).toEqual([]);
  });
});

describe('полнота обхода', () => {
  const ШАПКА = '---\ntitle: Проба\n---\n';

  function дерево(содержимое) {
    const корень = fs.mkdtempSync(path.join(os.tmpdir(), 'corpus-'));
    for (const [файл, текст] of Object.entries(содержимое)) {
      fs.mkdirSync(path.join(корень, path.dirname(файл)), {recursive: true});
      fs.writeFileSync(path.join(корень, файл), текст, 'utf8');
    }
    return корень;
  }

  it('корень сайта, в котором не нашлось ни одного файла, — провал прогона', () => {
    // Иначе переименованная папка, переехавшая локаль или запуск не в том дереве дали бы
    // «изменилось бы файлов: 0», и «ничего не смотрел» стало бы неотличимо от успеха.
    const корень = дерево({'sandbox/proba/index.mdx': ШАПКА});
    const итог = файлыКонтента(корень, НАСТРОЙКИ);

    expect(итог.пустыеКорниСайта.map((корень) => корень.папка)).toEqual(['docs']);
    fs.rmSync(корень, {recursive: true, force: true});
  });

  it('пустой корень вне сайта провалом не считается: пробную статью человек удаляет когда хочет', () => {
    const корень = дерево({'docs/lessons/proba/index.mdx': ШАПКА});
    const итог = файлыКонтента(корень, НАСТРОЙКИ);

    expect(итог.пустыеКорниСайта).toEqual([]);
    expect(итог.пути).toEqual(['docs/lessons/proba/index.mdx']);
    fs.rmSync(корень, {recursive: true, force: true});
  });

  it('порядок файлов не зависит ни от обхода папок, ни от порядка корней в настройках', () => {
    // Корень `blog` стоит в настройках вторым, а по имени идёт первым: без сортировки перечень
    // повторял бы порядок настроек, и два запуска с переставленными корнями дали бы разные отчёты,
    // хотя смотрели на одно и то же.
    const настройки = {
      контент: [
        {локаль: 'en', род: 'docs', папка: 'docs', наСайте: true},
        {локаль: 'en', род: 'blog', папка: 'blog', наСайте: true},
      ],
    };
    const корень = дерево({
      'docs/b/index.mdx': ШАПКА,
      'docs/a/index.mdx': ШАПКА,
      'docs/a/вложенная/index.md': ШАПКА,
      'blog/proba/index.mdx': ШАПКА,
    });

    expect(файлыКонтента(корень, настройки).пути).toEqual([
      'blog/proba/index.mdx', 'docs/a/index.mdx', 'docs/a/вложенная/index.md', 'docs/b/index.mdx',
    ]);
    fs.rmSync(корень, {recursive: true, force: true});
  });

  it('правила подготовки идут по статьям сайта, а статья вне сайта пропускается', () => {
    const корень = дерево({
      'docs/lessons/proba/index.mdx': ШАПКА,
      'sandbox/proba/index.mdx': ШАПКА,
    });
    const итог = прогон(корень, НАСТРОЙКИ);
    const подготовлено = подготовка(итог.пути, итог.тексты, {
      ...НАСТРОЙКИ,
      локали: {en: 'English', ru: 'Русский'},
      основнойЯзык: 'ru',
      обязательныйЯзык: 'en',
      категорииПоПути: {},
      категорииПоРоду: {docs: 'документация', проба: 'проба'},
      категорияСлужебной: 'страница раздела',
      обязательныеПоля: {},
      поляСоздания: {docs: {порядок: ['title'], значения: {}}},
    });

    expect(подготовлено.проверено).toBe(1);
    expect(подготовлено.внеСайта).toBe(1);
    fs.rmSync(корень, {recursive: true, force: true});
  });
});
