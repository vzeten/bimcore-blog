// Имя каждого теста повторяет формулировку правила.
// Канон проекта: что считается статьёй, что категорией и где проходит граница владения файлами.
import {describe, expect, it} from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

import {
  ВНЕ_КАНОНА, КОРНЕВАЯ_СТРАНИЦА, СТАТЬЯ, СТРАНИЦА_КАТЕГОРИИ, границаСостава, видВерсии,
} from '../src/core/articleKind.mjs';
import {groupArticles} from '../src/core/articles.mjs';

const EDITOR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const НАСТРОЙКИ = JSON.parse(fs.readFileSync(path.join(EDITOR, 'settings.json'), 'utf8'));

const файл = (p, extra = {}) => ({
  path: p, title: 'Проба', скрыта: false, готовность: 'Черновик', правил: null, когда: 0, ...extra,
});

describe('вид языковой версии', () => {
  it('каталог с index.mdx без _category_.json — обычная статья', () => {
    expect(видВерсии('docs/lessons/proba/index.mdx', {})).toBe(СТАТЬЯ);
  });

  it('index.mdx рядом с _category_.json — страница категории, а не статья', () => {
    expect(видВерсии('docs/lessons/index.mdx', {категорияРядом: true})).toBe(СТРАНИЦА_КАТЕГОРИИ);
  });

  it('отдельный файл вне своего каталога статьёй не считается', () => {
    expect(видВерсии('docs/lessons/proba-fail.mdx', {})).toBe(ВНЕ_КАНОНА);
  });

  it('index.md статьёй не считается: основной файл статьи всегда index.mdx', () => {
    expect(видВерсии('docs/lessons/proba/index.md', {})).toBe(ВНЕ_КАНОНА);
  });
});

describe('граница собственных файлов', () => {
  it('обычная статья владеет своим каталогом целиком и вглубь', () => {
    expect(границаСостава(СТАТЬЯ)).toBe('каталогРекурсивно');
  });

  it('страница категории владеет только верхним уровнем своего каталога', () => {
    // Вложенные каталоги категории — это её дочерние статьи и подкатегории, чужое добро.
    expect(границаСостава(СТРАНИЦА_КАТЕГОРИИ)).toBe('верхнийУровень');
  });

  it('у записи вне канона собственных файлов нет: её каталог принадлежит не ей', () => {
    expect(границаСостава(ВНЕ_КАНОНА)).toBe('нечего');
  });
});

describe('корневая страница контента', () => {
  it('файл в корне дерева со slug «/» — корневая страница, а не статья: имя файла роли не играет', () => {
    const факты = {вКорнеРода: true, адресКорня: true};

    expect(видВерсии('docs/intro.mdx', факты)).toBe(КОРНЕВАЯ_СТРАНИЦА);
    expect(видВерсии('docs/index.mdx', факты)).toBe(КОРНЕВАЯ_СТРАНИЦА);
  });

  it('корневая страница владеет только собой: корень рода ей не принадлежит', () => {
    expect(границаСостава(КОРНЕВАЯ_СТРАНИЦА)).toBe('толькоФайл');
  });

  it('одиночный файл в корне без slug «/» роли корневой страницы не получает', () => {
    expect(видВерсии('docs/что-то.mdx', {вКорнеРода: true, адресКорня: false})).toBe(ВНЕ_КАНОНА);
  });
});

describe('реестр по этому канону', () => {
  it('вид версии живёт отдельно от требований к шапке: реестр их не меняет', () => {
    // Вид — техническое основание границы владения. Категория, по которой спрашиваются
    // обязательные поля, от него не зависит (решение владельца 2026-08-14).
    const [одна] = groupArticles([файл('docs/intro.mdx', {вКорнеРода: true, адресКорня: true})], НАСТРОЙКИ);

    expect(одна.versions.en.вид).toBe(КОРНЕВАЯ_СТРАНИЦА);
    expect(одна.category).toBe('документация');
  });

  it('страница категории опознаётся по _category_.json, а не по числу соседей', () => {
    const [пустая] = groupArticles([файл('docs/courses/revit-free/index.mdx', {категорияРядом: true})], НАСТРОЙКИ);

    expect(пустая.versions.en.вид).toBe(СТРАНИЦА_КАТЕГОРИИ);
  });
});
