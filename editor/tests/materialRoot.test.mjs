// Имя каждого теста повторяет формулировку правила.
// Корень материалов: обычное окно работает только с папкой владельца, чужой корень — только
// явным испытательным режимом и с именем на виду.
import {describe, expect, it} from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

import {НЕТ_ПАПКИ, НЕ_АБСОЛЮТНЫЙ, НЕ_МАТЕРИАЛЫ, ПАПКА_ВЛАДЕЛЬЦА, выборКорня} from '../src/core/materialRoot.mjs';
import {ВЕТКА_ПРИНЯТОГО, ПАПКА_ПРИНЯТОГО, ПОРТ_ВЛАДЕЛЬЦА, опознание} from '../src/core/runtimeIdentity.mjs';
import {ПЕРЕКЛЮЧАТЕЛЬ, материалыВладельца, строкиЗапуска} from '../src/adapters/materialSource.mjs';

const EDITOR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const настоящие = JSON.parse(fs.readFileSync(path.join(EDITOR, 'settings.json'), 'utf8'));

const КОНТЕНТ = [
  {локаль: 'en', род: 'docs', папка: 'docs', наСайте: true},
  {локаль: 'ru', род: 'blog', папка: 'i18n/ru/docusaurus-plugin-content-blog', наСайте: true},
  {локаль: 'ru', род: 'проба', папка: 'editor/sandbox', наСайте: false},
];

const отказы = {
  [НЕ_АБСОЛЮТНЫЙ]: 'Нужен полный путь от буквы диска',
  [НЕТ_ПАПКИ]: 'Папки материалов нет на диске',
  [НЕ_МАТЕРИАЛЫ]: 'В папке нет контента сайта',
};

const надписи = {
  обычный: 'обычное окно',
  испытательный: 'ИСПЫТАТЕЛЬНЫЙ ЭКЗЕМПЛЯР',
  непринятый: 'КОД НЕ С ПРИНЯТОЙ ВЕТКИ',
  код: 'код',
  материалы: 'материалы',
  адрес: 'адрес',
  наСайте: 'версия на сайте',
  версияНеизвестна: 'версия кода неизвестна',
  веткаНеизвестна: 'про сайт ничего не известно',
};

const настройки = () => ({'контент': КОНТЕНТ, 'материалы': {'отказы': отказы, 'запуск': надписи}});

/** Мир, в котором есть перечисленные папки и больше ничего. */
const мир = (...папки) => (путь) => папки.includes(путь);

const ДОМ = мир(ПАПКА_ВЛАДЕЛЬЦА, `${ПАПКА_ВЛАДЕЛЬЦА}/docs`, 'D:/site', 'D:/site/docs');

describe('обычное окно работает только с постоянной папкой материалов владельца', () => {
  it('обычный корень задан кодом, а не настройками: настройки его не содержат вовсе', () => {
    expect(ПАПКА_ВЛАДЕЛЬЦА).toBe('C:/My_code/bimcore-blog');
    expect(настоящие['материалы']['корень']).toBeUndefined();
  });

  it('без заявки на испытание корень — папка владельца, и выбора у обычного запуска нет', () => {
    expect(выборКорня(настройки(), ДОМ)).toEqual({корень: ПАПКА_ВЛАДЕЛЬЦА, испытательный: false});
    expect(выборКорня(настройки(), ДОМ, null)).toEqual({корень: ПАПКА_ВЛАДЕЛЬЦА, испытательный: false});
    expect(выборКорня(настройки(), ДОМ, '   ')).toEqual({корень: ПАПКА_ВЛАДЕЛЬЦА, испытательный: false});
  });

  it('чужая папка с контентом сама обычным окном не становится: без заявки её не спрашивают', () => {
    // Прежде правило брало корень из настроек, и копия программы со своим `settings.json` молча
    // делалась источником чтения, записи и Git. Теперь чужое дерево ничем не заявишь, кроме
    // переключателя испытания, а тот метит экземпляр.
    const свои = настройки();
    свои['материалы']['корень'] = 'D:/site';

    expect(выборКорня(свои, ДОМ)).toEqual({корень: ПАПКА_ВЛАДЕЛЬЦА, испытательный: false});
  });

  it('папка владельца, названная в другом регистре, остаётся обычным окном', () => {
    const регистр = ПАПКА_ВЛАДЕЛЬЦА.toLowerCase();
    const есть = мир(регистр, `${регистр}/docs`);

    expect(выборКорня(настройки(), есть, регистр)).toEqual({корень: регистр, испытательный: false});
  });
});

describe('чужой корень возможен только явным испытательным режимом и назван при запуске', () => {
  it('заявленный чужой корень принимается, но помечается испытательным', () => {
    expect(выборКорня(настройки(), ДОМ, 'D:/site')).toEqual({корень: 'D:/site', испытательный: true});
  });

  it('переключатель — переменная среды на один запуск, а не строка в настройках', () => {
    expect(ПЕРЕКЛЮЧАТЕЛЬ).toBe('EDITOR_TRIAL_ROOT');

    const server = fs.readFileSync(path.join(EDITOR, 'server.mjs'), 'utf8');
    expect(server).toContain('испытательный: process.env[ПЕРЕКЛЮЧАТЕЛЬ]');
    expect(server).not.toContain("settings['материалы']['корень']");
  });

  it('испытательный запуск называет себя иначе, чем обычный, и оба зовут корень, код и адрес', () => {
    const общее = {код: ПАПКА_ПРИНЯТОГО, коммит: '1234abc', чисто: true, порт: ПОРТ_ВЛАДЕЛЬЦА};
    const позвать = (о) => строкиЗапуска({settings: настройки(), опознание: о, наСайте: 'origin/main'});
    const обычный = позвать(опознание({
      ...общее, корень: ПАПКА_ВЛАДЕЛЬЦА, испытательный: false, ветка: ВЕТКА_ПРИНЯТОГО,
    }));
    const испытание = позвать(опознание({...общее, корень: 'D:/site', испытательный: true, ветка: 'fix/x'}));

    expect(обычный[0]).toBe(надписи.обычный);
    expect(испытание[0]).toBe(надписи.испытательный);

    for (const строки of [обычный, испытание]) {
      const текст = строки.join('\n');
      expect(текст).toContain(ПАПКА_ПРИНЯТОГО);
      expect(текст).toContain('1234abc');
      expect(текст).toContain('http://localhost:4780');
    }

    expect(испытание.join('\n')).toContain('D:/site');
    expect(обычный.join('\n')).toContain(ПАПКА_ВЛАДЕЛЬЦА);
  });

  it('код не с принятой ветки называет себя третьим родом: материалы настоящие, окно испытательное', () => {
    // Самый опасный случай: корень у такой копии тот самый, и по одной папке её от обычного окна
    // не отличить. Пока первая строка говорила «обычное окно», непринятый код так и выглядел.
    const строки = строкиЗапуска({
      settings: настройки(),
      наСайте: null,
      опознание: опознание({
        корень: ПАПКА_ВЛАДЕЛЬЦА, испытательный: false, ветка: 'fix/editor-runtime-ports',
        коммит: '1234abc', код: 'C:/копия/editor', порт: 4791,
      }),
    });

    expect(строки[0]).toBe(надписи.непринятый);
    expect(строки.join('\n')).toContain('http://localhost:4791');
    // Про сайт ничего не известно — так и сказано словами, а не пустым местом.
    expect(строки.join('\n')).toContain(надписи.веткаНеизвестна);
  });

  it('версия кода неизвестна — запуск говорит это словами из настроек', () => {
    const строки = строкиЗапуска({
      settings: настройки(),
      наСайте: 'origin/main',
      опознание: опознание({
        корень: ПАПКА_ВЛАДЕЛЬЦА, испытательный: false, ветка: null, коммит: null,
        код: 'C:/копия/editor', порт: 4791,
      }),
    });

    expect(строки.join('\n')).toContain(надписи.версияНеизвестна);
  });

  it('сервер печатает эти строки при запуске, а не молчит о фактическом корне', () => {
    // Предохранитель от возврата найденного дефекта (SPEC 5.2.1): поведение старта тестом не
    // отыграть — он поднимает порт и Vite, — а вернуть молчаливый запуск легко.
    const server = fs.readFileSync(path.join(EDITOR, 'server.mjs'), 'utf8');

    expect(server).toContain('строкиЗапуска({');
    expect(server).not.toContain("path.resolve(EDITOR_DIR, '..')");
  });
});

describe('неверный корень — отказ, а не соседняя папка молча', () => {
  it('относительная заявка — отказ: она считалась бы от папки запуска, снова от места кода', () => {
    expect(выборКорня(настройки(), ДОМ, '..')).toEqual({отказ: НЕ_АБСОЛЮТНЫЙ, значение: '..'});
    expect(выборКорня(настройки(), ДОМ, 'site/копия')).toEqual({отказ: НЕ_АБСОЛЮТНЫЙ, значение: 'site/копия'});
  });

  it('папки нет на диске — отказ «нет папки», и папки владельца это касается тоже', () => {
    expect(выборКорня(настройки(), ДОМ, 'C:/нет-такой')).toEqual({отказ: НЕТ_ПАПКИ, значение: 'C:/нет-такой'});
    expect(выборКорня(настройки(), мир())).toEqual({отказ: НЕТ_ПАПКИ, значение: ПАПКА_ВЛАДЕЛЬЦА});
  });

  it('папка есть, а папок контента сайта в ней нет — отказ «не материалы»', () => {
    expect(выборКорня(настройки(), мир('C:/пусто'), 'C:/пусто')).toEqual({отказ: НЕ_МАТЕРИАЛЫ, значение: 'C:/пусто'});
    expect(выборКорня(настройки(), мир('C:/проба', 'C:/проба/editor/sandbox'), 'C:/проба'))
      .toEqual({отказ: НЕ_МАТЕРИАЛЫ, значение: 'C:/проба'});
  });

  it('текст отказа берётся из настроек и называет неверное значение', () => {
    const бросок = (заявка, мирок) => {
      try {
        материалыВладельца(настройки(), заявка, мирок);
        return null;
      } catch (error) {
        return error.message;
      }
    };

    expect(бросок('..', мир())).toBe('Нужен полный путь от буквы диска: ..');
    expect(бросок('C:/нет-такой', мир())).toBe('Папки материалов нет на диске: C:/нет-такой');
    expect(бросок('C:/пусто', мир('C:/пусто'))).toBe('В папке нет контента сайта: C:/пусто');
  });
});

describe('закреплённый запуск: настоящие настройки и настоящий диск', () => {
  it('обычное окно берёт папку владельца с диска и не считает себя испытательным', () => {
    expect(материалыВладельца(настоящие)).toEqual({корень: path.resolve(ПАПКА_ВЛАДЕЛЬЦА), испытательный: false});
  });

  it('у каждого кода отказа и у каждой надписи запуска есть свои слова в настройках', () => {
    for (const код of [НЕ_АБСОЛЮТНЫЙ, НЕТ_ПАПКИ, НЕ_МАТЕРИАЛЫ]) {
      expect(настоящие['материалы']['отказы'][код]).toBeTruthy();
    }

    for (const имя of Object.keys(надписи)) {
      expect(настоящие['материалы']['запуск'][имя]).toBeTruthy();
    }
  });
});
