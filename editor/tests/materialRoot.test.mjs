// Имя каждого теста повторяет формулировку правила.
// Корень материалов: где программа берёт статьи владельца и почему она отказывается гадать.
import {describe, expect, it} from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

import {НЕТ_ПАПКИ, НЕ_АБСОЛЮТНЫЙ, НЕ_ЗАДАН, НЕ_МАТЕРИАЛЫ, выборКорня} from '../src/core/materialRoot.mjs';
import {материалыВладельца} from '../src/adapters/materialSource.mjs';

const EDITOR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const настоящие = JSON.parse(fs.readFileSync(path.join(EDITOR, 'settings.json'), 'utf8'));

const КОНТЕНТ = [
  {локаль: 'en', род: 'docs', папка: 'docs', наСайте: true},
  {локаль: 'ru', род: 'blog', папка: 'i18n/ru/docusaurus-plugin-content-blog', наСайте: true},
  {локаль: 'ru', род: 'проба', папка: 'editor/sandbox', наСайте: false},
];

const настройки = (корень, отказы = {}) => ({
  'контент': КОНТЕНТ,
  'материалы': {'корень': корень, 'отказы': отказы},
});

/** Мир, в котором есть перечисленные папки и больше ничего. */
const мир = (...папки) => (путь) => папки.includes(путь);

describe('корень материалов берётся из настроек, а не из места кода', () => {
  it('абсолютный путь с папками контента внутри становится корнем', () => {
    const есть = мир('C:/My_code/bimcore-blog', 'C:/My_code/bimcore-blog/docs');
    expect(выборКорня(настройки('C:/My_code/bimcore-blog'), есть)).toEqual({корень: 'C:/My_code/bimcore-blog'});
  });

  it('хватает одной папки контента сайта: остальных языков в папке может ещё не быть', () => {
    const есть = мир('D:/site', 'D:/site/i18n/ru/docusaurus-plugin-content-blog');
    expect(выборКорня(настройки('D:/site'), есть)).toEqual({корень: 'D:/site'});
  });

  it('косые приводятся к одному виду, лишняя косая на конце убирается', () => {
    const есть = мир('C:/My_code/bimcore-blog', 'C:/My_code/bimcore-blog/docs');
    expect(выборКорня(настройки('C:\\My_code\\bimcore-blog\\'), есть)).toEqual({корень: 'C:/My_code/bimcore-blog'});
    expect(выборКорня(настройки('  C:/My_code/bimcore-blog//  '), есть)).toEqual({корень: 'C:/My_code/bimcore-blog'});
  });

  it('корень не зависит от места кода: тот же ответ, где бы ни лежала программа', () => {
    // Ради этого правило и заведено: раньше корень выводился из папки программы и уезжал
    // вместе с рабочей копией ветки, подменяя статьи владельца её собственным деревом.
    const есть = мир('C:/My_code/bimcore-blog', 'C:/My_code/bimcore-blog/docs');
    const из = (место) => выборКорня({...настройки('C:/My_code/bimcore-blog'), место}, есть);

    expect(из('C:/My_code/bimcore-blog/editor')).toEqual(из('C:/My_code/bimcore-blog/editor/.coordination/worktrees/x/editor'));
  });

  it('папка проб не считается материалами сайта: она не «наСайте»', () => {
    const есть = мир('C:/копия', 'C:/копия/editor/sandbox');
    expect(выборКорня(настройки('C:/копия'), есть)).toEqual({отказ: НЕ_МАТЕРИАЛЫ, значение: 'C:/копия'});
  });
});

describe('неверная настройка корня — отказ, а не соседняя папка молча', () => {
  const есть = мир('C:/My_code/bimcore-blog', 'C:/My_code/bimcore-blog/docs');

  it('корень не задан вовсе, пуст или из одних пробелов — отказ «не задан»', () => {
    expect(выборКорня({'контент': КОНТЕНТ}, есть)).toEqual({отказ: НЕ_ЗАДАН, значение: ''});
    expect(выборКорня(настройки(''), есть)).toEqual({отказ: НЕ_ЗАДАН, значение: ''});
    expect(выборКорня(настройки('   '), есть)).toEqual({отказ: НЕ_ЗАДАН, значение: ''});
  });

  it('относительный путь — отказ: он считался бы от папки запуска, то есть снова от места кода', () => {
    expect(выборКорня(настройки('..'), есть)).toEqual({отказ: НЕ_АБСОЛЮТНЫЙ, значение: '..'});
    expect(выборКорня(настройки('My_code/bimcore-blog'), есть)).toEqual({отказ: НЕ_АБСОЛЮТНЫЙ, значение: 'My_code/bimcore-blog'});
  });

  it('папки из настроек нет на диске — отказ «нет папки»', () => {
    expect(выборКорня(настройки('C:/нет-такой'), есть)).toEqual({отказ: НЕТ_ПАПКИ, значение: 'C:/нет-такой'});
  });

  it('папка есть, а папок контента в ней нет — отказ «не материалы»', () => {
    expect(выборКорня(настройки('C:/пусто'), мир('C:/пусто'))).toEqual({отказ: НЕ_МАТЕРИАЛЫ, значение: 'C:/пусто'});
  });
});

describe('отказ доходит до человека, а верный корень — до программы', () => {
  const отказы = {
    [НЕ_ЗАДАН]: 'Не указана папка материалов',
    [НЕ_АБСОЛЮТНЫЙ]: 'Нужен полный путь от буквы диска',
    [НЕТ_ПАПКИ]: 'Папки материалов нет на диске',
    [НЕ_МАТЕРИАЛЫ]: 'В папке нет контента сайта',
  };

  it('текст отказа берётся из настроек и называет неверное значение', () => {
    const бросок = (корень, мирок) => {
      try {
        материалыВладельца(настройки(корень, отказы), мирок);
        return null;
      } catch (error) {
        return error.message;
      }
    };

    expect(бросок('', мир())).toBe('Не указана папка материалов');
    expect(бросок('..', мир())).toBe('Нужен полный путь от буквы диска: ..');
    expect(бросок('C:/нет-такой', мир())).toBe('Папки материалов нет на диске: C:/нет-такой');
    expect(бросок('C:/пусто', мир('C:/пусто'))).toBe('В папке нет контента сайта: C:/пусто');
  });

  it('верный корень отдаётся в родном для системы виде: его ждут склейка и сравнение путей', () => {
    const есть = мир('C:/My_code/bimcore-blog', 'C:/My_code/bimcore-blog/docs');
    expect(материалыВладельца(настройки('C:/My_code/bimcore-blog/', отказы), есть))
      .toBe(path.resolve('C:/My_code/bimcore-blog'));
  });
});

describe('закреплённый запуск: настоящие настройки называют папку материалов владельца', () => {
  it('в settings.json задан абсолютный корень материалов, и он существует вместе с папками контента', () => {
    expect(материалыВладельца(настоящие)).toBe(path.resolve(настоящие['материалы']['корень']));
  });

  it('у каждого кода отказа есть свои слова в настройках', () => {
    for (const код of [НЕ_ЗАДАН, НЕ_АБСОЛЮТНЫЙ, НЕТ_ПАПКИ, НЕ_МАТЕРИАЛЫ]) {
      expect(настоящие['материалы']['отказы'][код]).toBeTruthy();
    }
  });

  it('сервер не выводит корень материалов из места своего файла', () => {
    // Предохранитель от возврата найденного дефекта (SPEC 5.2.1): поведение старта сервера
    // тестом не отыграть — он поднимает порт и Vite, — а вернуть одну строку легко.
    const server = fs.readFileSync(path.join(EDITOR, 'server.mjs'), 'utf8');

    expect(server).toContain('материалыВладельца(readSettings())');
    expect(server).not.toContain("path.resolve(EDITOR_DIR, '..')");
  });
});
