// Настоящие GIF заданного веса — для проверок предела анимации.
//
// Вес набирается служебным блоком комментария (`0x21 0xFE`), который формат разрешает и который
// картинку не меняет: файл остаётся целым для любого просмотрщика и для правил самой программы.
// Ровно поэтому «ровно 5 МБ» и «на байт больше» проверяются настоящими файлами, а не числами.

const ОПИСАНИЕ_ЭКРАНА = Buffer.from([2, 0, 2, 0, 0x80, 0, 0]);
const ПАЛИТРА = Buffer.from([0, 0, 0, 0xff, 0xff, 0xff]);
const КАДР = Buffer.from([0x2c, 0, 0, 0, 0, 2, 0, 2, 0, 0, 2, 2, 0x44, 1, 0]);
const КОНЕЦ = Buffer.from([0x3b]);

/** Самый маленький целый GIF: сигнатура, экран, палитра, кадр и метка конца. */
export const ГИФ = Buffer.concat([Buffer.from('GIF89a', 'binary'), ОПИСАНИЕ_ЭКРАНА, ПАЛИТРА, КАДР, КОНЕЦ]);

/**
 * Целый GIF ровно заданного веса. Меньше самого короткого файла не бывает, и такой заказ —
 * ошибка теста, а не случай программы.
 *
 * Комментарий пишется под-блоками: перед каждым куском стоит его длина одним байтом, поэтому
 * длиннее 255 знаков кусок быть не может, а весь блок закрывается нулём.
 */
export function гифВесом(байт) {
  const служебные = 2 + 1; // метка комментария (2 байта) и ноль, закрывающий блок
  const надо = байт - ГИФ.length - служебные;
  if (надо < 0 || надо === 1) throw new Error(`GIF ровно в ${байт} Б этим способом не собрать`);

  const куски = [Buffer.from([0x21, 0xfe])];
  let осталось = надо;
  while (осталось > 0) {
    // Кусок стоит своей длины плюс байт заголовка. Хвост в один байт недопустим — заголовок
    // без тела не бывает, поэтому предыдущий кусок делается на байт короче.
    let тело = Math.min(осталось - 1, 255);
    if (осталось - (тело + 1) === 1) тело -= 1;
    куски.push(Buffer.from([тело]), Buffer.alloc(тело, 0x78));
    осталось -= тело + 1;
  }
  куски.push(Buffer.from([0]));

  const готово = Buffer.concat([
    Buffer.from('GIF89a', 'binary'), ОПИСАНИЕ_ЭКРАНА, ПАЛИТРА, КАДР, Buffer.concat(куски), КОНЕЦ,
  ]);
  if (готово.length !== байт) throw new Error(`вышло ${готово.length} Б вместо ${байт} Б`);

  return готово;
}
