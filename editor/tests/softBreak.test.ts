// Имя каждого теста повторяет формулировку правила.
// Мягкий перенос внутри обычного абзаца показывается пробелом, как на собранном сайте.
import {describe, expect, it} from 'vitest';
import {переносыАбзацев, строкаТолькоКартинка} from '../src/ui/livePreview/softBreak';

/** Текст статьи строками, как он лежит в файле. */
function строки(текст: string): string[] {
  return текст.split('\n');
}

describe('мягкий перенос обычного абзаца', () => {
  it('переносы внутри абзаца склеиваются, границы абзацев остаются', () => {
    const текст = строки([
      'Первая строка абзаца,',
      'вторая строка того же абзаца.',
      '',
      'Начало второго абзаца.',
    ].join('\n'));

    expect(переносыАбзацев(текст).мягкие).toEqual([0]);
  });

  it('первый абзац живой статьи читается непрерывно, а не шестью строками', () => {
    // Строки 16–21 русской версии блога `free-revit-family-websites` — образец из задания.
    const текст = строки([
      'Бесплатные семейства Revit в 2026 году проще всего искать в трёх местах:',
      'крупные BIM-каталоги, российские и международные библиотеки моделей, а также',
      'сайты производителей. Ниже — 31 источник: от BIMCORE и BIMLIB до BIMobject,',
      'Herman Miller, ERCO, Roca и Sub-Zero & Wolf. Все ссылки проверялись в июле 2026',
      'года. У каждого сайта своя польза: где-то удобнее брать мебель, где-то свет,',
      'сантехнику, двери, инженерные элементы или редкие пользовательские семейства.',
      '',
      '<truncate />',
    ].join('\n'));

    expect(переносыАбзацев(текст).мягкие).toEqual([0, 1, 2, 3, 4]);
  });

  it('одинокая строка абзацем не склеивается ни с чем', () => {
    expect(переносыАбзацев(строки('Одна строка.')).мягкие).toEqual([]);
  });

  it('заголовок не склеивается с соседями', () => {
    const текст = строки('## Быстрое сравнение\nТекст под заголовком,\nего продолжение.');
    expect(переносыАбзацев(текст).мягкие).toEqual([1]);
  });

  it('заголовок обрывает абзац и посреди прогона строк', () => {
    // Пустой строки между абзацем и заголовком может не быть — склеивать их всё равно нельзя.
    const текст = строки('Текст абзаца.\n## Заголовок\nСтрока после заголовка.');
    expect(переносыАбзацев(текст).мягкие).toEqual([]);
  });

  it('подчёркнутый заголовок не приклеивается к своему тексту', () => {
    expect(переносыАбзацев(строки('Заголовок\n=====')).мягкие).toEqual([]);
  });

  it('пункты списка не склеиваются между собой и с абзацем', () => {
    const текст = строки([
      'Перед списком:',
      '- первый пункт',
      '- второй пункт',
      '  1. вложенный пункт',
    ].join('\n'));

    expect(переносыАбзацев(текст).мягкие).toEqual([]);
  });

  it('строки таблицы не склеиваются', () => {
    const текст = строки('| Сайт | Что скачать |\n|---|---|\n| BIMCORE | Примеры |');
    expect(переносыАбзацев(текст).мягкие).toEqual([]);
  });

  it('строки огороженного кода не склеиваются, даже когда выглядят обычным текстом', () => {
    const текст = строки('```js\nпервая строка кода\nвторая строка кода\n```\nАбзац после кода,\nего продолжение.');
    expect(переносыАбзацев(текст).мягкие).toEqual([4]);
  });

  it('короткая ограда внутри длинной код не заканчивает', () => {
    const текст = строки('````\n```\nвсё ещё код\n````\nАбзац после кода,\nего продолжение.');
    expect(переносыАбзацев(текст).мягкие).toEqual([4]);
  });

  it('строки цитаты не склеиваются', () => {
    expect(переносыАбзацев(строки('> первая строка цитаты\n> вторая строка цитаты')).мягкие).toEqual([]);
  });

  it('отступной код не склеивается', () => {
    expect(переносыАбзацев(строки('    первая строка кода\n    вторая строка кода')).мягкие).toEqual([]);
  });

  it('многострочный JSX-блок статьи не склеивается ни в одной своей строке', () => {
    const текст = строки([
      '<ProductCard',
      '  name="Кресла для Revit"',
      '  eyebrow="Набор семейств Revit"',
      '/>',
    ].join('\n'));

    expect(переносыАбзацев(текст).мягкие).toEqual([]);
  });

  it('строки import из MDX не склеиваются', () => {
    const текст = строки("import productPreview from './product.jpg';\nimport second from './second.jpg';");
    expect(переносыАбзацев(текст).мягкие).toEqual([]);
  });

  it('одинокая картинка не склеивается с соседними строками абзаца', () => {
    const текст = строки('Текст перед картинкой.\n![Подпись](./img-01.png)\nТекст после картинки.');
    expect(переносыАбзацев(текст).мягкие).toEqual([]);
  });

  it('картинка в строке вместе с текстом склейку не отменяет', () => {
    const текст = строки('Текст и ![подпись](./img-01.png) в одной строке,\nпродолжение абзаца.');
    expect(переносыАбзацев(текст).мягкие).toEqual([0]);
  });

  it('жёсткий перенос двумя пробелами остаётся переносом', () => {
    expect(переносыАбзацев(строки('Строка с жёстким переносом  \nследующая строка.')).мягкие).toEqual([]);
  });

  it('жёсткий перенос обратной косой остаётся переносом, и косая прячется — даже перед пустой строкой', () => {
    const итог = переносыАбзацев(строки('Строка с жёстким переносом\\\nследующая строка.'));
    expect({мягкие: итог.мягкие, жёсткие: итог.жёсткие}).toEqual({мягкие: [], жёсткие: [0]});
    expect(переносыАбзацев(строки('Строка с переносом\\\n\nДальше.')).жёсткие).toEqual([0]);
  });

  it('продолжения абзаца одинаково считают мягкий перенос и оба жёстких', () => {
    // Слою переносов важно, ЧТО прятать, поэтому списки у него разные. Показу знаков и границам
    // пары важно только одно: строка и следующая — одна мысль. Ответ на это один на все три случая.
    const продолжения = (текст: string): number[] => [...переносыАбзацев(строки(текст)).продолжения];

    expect(продолжения('Мягкий перенос\nследующая строка.')).toEqual([0]);
    expect(продолжения('Жёсткий двумя пробелами  \nследующая строка.')).toEqual([0]);
    expect(продолжения('Жёсткий косой\\\nследующая строка.')).toEqual([0]);
    // Пустая строка абзац закрывает, и продолжать нечего — ни в одном из трёх случаев.
    expect(продолжения('Строка.\n\nДругой абзац.')).toEqual([]);
    expect(продолжения('Строка с переносом\\\n\nДругой абзац.')).toEqual([]);
    expect(продолжения('Строка с переносом  \n\nДругой абзац.')).toEqual([]);
    // Заголовок и пункт списка абзацу не продолжение даже через жёсткий перенос.
    expect(продолжения('Строка  \n## Заголовок')).toEqual([]);
    expect(продолжения('Строка  \n- пункт')).toEqual([]);
  });

  it('косая в конце заголовка и перед границей совета переносом не считается; внутри пункта списка — перенос', () => {
    expect(переносыАбзацев(строки('## Заголовок\\\nтекст')).жёсткие).toEqual([]);
    expect(переносыАбзацев(строки('- пункт\\\nещё')).жёсткие).toEqual([0]);
    expect(переносыАбзацев(строки(':::tip\nТекст\\\n:::')).жёсткие).toEqual([]);
  });

  it('косая перед пунктом списка, заголовком или блоком — буква, а не перенос; экранированная косая тоже', () => {
    expect(переносыАбзацев(строки('Первая\\\n- Вторая')).жёсткие).toEqual([]);
    expect(переносыАбзацев(строки('Первая\\\n1. Вторая')).жёсткие).toEqual([]);
    expect(переносыАбзацев(строки('Первая\\\n## Заголовок')).жёсткие).toEqual([]);
    expect(переносыАбзацев(строки('Первая\\\\\nВторая')).жёсткие).toEqual([]);
    expect(переносыАбзацев(строки('Первая\\\\\\\nВторая')).жёсткие).toEqual([0]);
  });

  it('строка только с картинкой узнаётся по всей строке, картинка рядом с текстом — нет', () => {
    expect(строкаТолькоКартинка('![подпись](./img-01.png)')).toBe(true);
    expect(строкаТолькоКартинка('Текст ![подпись](./img-01.png)')).toBe(false);
    expect(строкаТолькоКартинка('![a](./a.png) ![b](./b.png)')).toBe(false);
  });

  it('горизонтальная линия не склеивается с соседями', () => {
    expect(переносыАбзацев(строки('Текст абзаца.\n---\nТекст после линии.')).мягкие).toEqual([]);
  });

  it('пустой текст склеек не даёт', () => {
    expect(переносыАбзацев([]).мягкие).toEqual([]);
    expect(переносыАбзацев(строки('')).мягкие).toEqual([]);
  });
});
