// Имя каждого теста повторяет формулировку правила.
// Мягкий перенос внутри обычного абзаца показывается пробелом, как на собранном сайте.
import {describe, expect, it} from 'vitest';
import {мягкиеПереносы} from '../src/ui/livePreview/softBreak';

/** Текст статьи строками, как он лежит в файле. */
function строки(текст: string): string[] {
  return текст.split('\n');
}

describe('мягкий перенос обычного абзаца', () => {
  it('переносы внутри абзаца склеиваются, границы абзацев остаются', () => {
    const текст = строки([
      'Первая строка абзаца,',
      'вторая строка того же абзаца.',
      '',
      'Начало второго абзаца.',
    ].join('\n'));

    expect(мягкиеПереносы(текст)).toEqual([0]);
  });

  it('первый абзац живой статьи читается непрерывно, а не шестью строками', () => {
    // Строки 16–21 русской версии блога `free-revit-family-websites` — образец из задания.
    const текст = строки([
      'Бесплатные семейства Revit в 2026 году проще всего искать в трёх местах:',
      'крупные BIM-каталоги, российские и международные библиотеки моделей, а также',
      'сайты производителей. Ниже — 31 источник: от BIMCORE и BIMLIB до BIMobject,',
      'Herman Miller, ERCO, Roca и Sub-Zero & Wolf. Все ссылки проверялись в июле 2026',
      'года. У каждого сайта своя польза: где-то удобнее брать мебель, где-то свет,',
      'сантехнику, двери, инженерные элементы или редкие пользовательские семейства.',
      '',
      '<truncate />',
    ].join('\n'));

    expect(мягкиеПереносы(текст)).toEqual([0, 1, 2, 3, 4]);
  });

  it('одинокая строка абзацем не склеивается ни с чем', () => {
    expect(мягкиеПереносы(строки('Одна строка.'))).toEqual([]);
  });

  it('заголовок не склеивается с соседями', () => {
    const текст = строки('## Быстрое сравнение\nТекст под заголовком,\nего продолжение.');
    expect(мягкиеПереносы(текст)).toEqual([1]);
  });

  it('заголовок обрывает абзац и посреди прогона строк', () => {
    // Пустой строки между абзацем и заголовком может не быть — склеивать их всё равно нельзя.
    const текст = строки('Текст абзаца.\n## Заголовок\nСтрока после заголовка.');
    expect(мягкиеПереносы(текст)).toEqual([]);
  });

  it('подчёркнутый заголовок не приклеивается к своему тексту', () => {
    expect(мягкиеПереносы(строки('Заголовок\n====='))).toEqual([]);
  });

  it('пункты списка не склеиваются между собой и с абзацем', () => {
    const текст = строки([
      'Перед списком:',
      '- первый пункт',
      '- второй пункт',
      '  1. вложенный пункт',
    ].join('\n'));

    expect(мягкиеПереносы(текст)).toEqual([]);
  });

  it('строки таблицы не склеиваются', () => {
    const текст = строки('| Сайт | Что скачать |\n|---|---|\n| BIMCORE | Примеры |');
    expect(мягкиеПереносы(текст)).toEqual([]);
  });

  it('строки огороженного кода не склеиваются, даже когда выглядят обычным текстом', () => {
    const текст = строки('```js\nпервая строка кода\nвторая строка кода\n```\nАбзац после кода,\nего продолжение.');
    expect(мягкиеПереносы(текст)).toEqual([4]);
  });

  it('короткая ограда внутри длинной код не заканчивает', () => {
    const текст = строки('````\n```\nвсё ещё код\n````\nАбзац после кода,\nего продолжение.');
    expect(мягкиеПереносы(текст)).toEqual([4]);
  });

  it('строки цитаты не склеиваются', () => {
    expect(мягкиеПереносы(строки('> первая строка цитаты\n> вторая строка цитаты'))).toEqual([]);
  });

  it('отступной код не склеивается', () => {
    expect(мягкиеПереносы(строки('    первая строка кода\n    вторая строка кода'))).toEqual([]);
  });

  it('многострочный JSX-блок статьи не склеивается ни в одной своей строке', () => {
    const текст = строки([
      '<ProductCard',
      '  name="Кресла для Revit"',
      '  eyebrow="Набор семейств Revit"',
      '/>',
    ].join('\n'));

    expect(мягкиеПереносы(текст)).toEqual([]);
  });

  it('строки import из MDX не склеиваются', () => {
    const текст = строки("import productPreview from './product.jpg';\nimport second from './second.jpg';");
    expect(мягкиеПереносы(текст)).toEqual([]);
  });

  it('одинокая картинка не склеивается с соседними строками абзаца', () => {
    const текст = строки('Текст перед картинкой.\n![Подпись](./img-01.png)\nТекст после картинки.');
    expect(мягкиеПереносы(текст)).toEqual([]);
  });

  it('картинка в строке вместе с текстом склейку не отменяет', () => {
    const текст = строки('Текст и ![подпись](./img-01.png) в одной строке,\nпродолжение абзаца.');
    expect(мягкиеПереносы(текст)).toEqual([0]);
  });

  it('жёсткий перенос двумя пробелами остаётся переносом', () => {
    expect(мягкиеПереносы(строки('Строка с жёстким переносом  \nследующая строка.'))).toEqual([]);
  });

  it('жёсткий перенос обратной косой остаётся переносом', () => {
    expect(мягкиеПереносы(строки('Строка с жёстким переносом\\\nследующая строка.'))).toEqual([]);
  });

  it('горизонтальная линия не склеивается с соседями', () => {
    expect(мягкиеПереносы(строки('Текст абзаца.\n---\nТекст после линии.'))).toEqual([]);
  });

  it('пустой текст склеек не даёт', () => {
    expect(мягкиеПереносы([])).toEqual([]);
    expect(мягкиеПереносы(строки(''))).toEqual([]);
  });
});
