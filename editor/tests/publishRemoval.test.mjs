// Имя каждого теста повторяет формулировку правила.
// Что публикация делает с файлами, которых у человека больше нет. Без этого правила она умела бы
// только добавлять: удалённая картинка осталась бы на сайте навсегда, а переименованная лежала бы
// там дважды — под старым именем и под новым.
//
// Проверяется на настоящем git там, где речь о сайте: перечень каталога в закреплённой ветке — это
// вопрос к хранилищу, и подставной ответ подтверждал бы сам себя.
import {afterEach, describe, expect, it, vi} from 'vitest';
import fs from 'node:fs';
import path from 'node:path';

import {УДАЛЕНО, каркасПлана, публикацияВозможна} from '../src/core/publishPlan.mjs';
import {КАРТИНКА, СОСТОЯНИЕ} from '../src/core/release.mjs';
import {
  ВНЕ_КАНОНА, ИМЯ_КАТЕГОРИИ, КОРНЕВАЯ_СТРАНИЦА, СТАТЬЯ as ВИД_СТАТЬИ, СТРАНИЦА_КАТЕГОРИИ,
} from '../src/core/articleKind.mjs';
import {путиОсновыВПапке, фактыКаркаса} from '../src/adapters/publishFacts.mjs';
import {releaseRoute} from '../src/adapters/releaseRoute.mjs';
import {ЖДАТЬ_GIT} from './saveHarness.mjs';
import {EN, ES, RU, СТАТЬЯ, запрос, настройкиСервера, среда, убратьПесочницы} from './publishHarness.mjs';

vi.setConfig({testTimeout: ЖДАТЬ_GIT, hookTimeout: ЖДАТЬ_GIT});

afterEach(убратьПесочницы);

const ПАПКА = 'i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba';
const ОБЛОЖКА = `${ПАПКА}/cover.png`;
const СХЕМА = `${ПАПКА}/схема.png`;
const ГОТОВНОСТЬ = `${ПАПКА}/_state.json`;

describe('правило: пропавшее с диска уходит и с сайта', () => {
  const версия = (ещё = {}) => ({
    путь: RU, локаль: 'ru', вид: ВИД_СТАТЬИ, состояние: null, файлыПапки: [], статейВПапке: 1, ...ещё,
  });

  const язык = (локаль, путь, опубликован) => ({локаль, путь, опубликован, заглушка: `байты ${локаль}`});

  const план = (наСайтеВПапке, открытаяВерсия = версия()) => каркасПлана({
    открытаяВерсия,
    наСайте: true,
    языки: [язык('ru', RU, false), язык('en', EN, true), язык('es', ES, true)],
    наСайтеВПапке,
  });

  const убираемые = (итог) => итог.записи
    .filter((запись) => запись.источник === УДАЛЕНО)
    .map((запись) => запись.путь);

  const запись = (итог, путь) => итог.записи.find((строка) => строка.путь === путь);

  it('картинка есть на сайте и пропала с диска — она уходит и с сайта', () => {
    const итог = план([RU, ОБЛОЖКА]);

    expect(убираемые(итог)).toEqual([ОБЛОЖКА]);
    expect(запись(итог, ОБЛОЖКА).назначение).toBe(КАРТИНКА);
    expect(запись(итог, ОБЛОЖКА).текст).toBe(null);
    expect(публикацияВозможна(итог)).toBe(true);
  });

  it('картинка на месте — с сайта не уходит ничего', () => {
    expect(убираемые(план([RU, ОБЛОЖКА], версия({файлыПапки: [ОБЛОЖКА]})))).toEqual([]);
  });

  it('пропавшая готовность уходит своим назначением, а не как картинка', () => {
    // На диске её уже нет, поэтому `состояние` пусто; где она лежала бы, знает `местоГотовности`.
    const итог = план([RU, ГОТОВНОСТЬ], версия({местоГотовности: ГОТОВНОСТЬ}));

    expect(убираемые(итог)).toEqual([ГОТОВНОСТЬ]);
    expect(запись(итог, ГОТОВНОСТЬ).назначение).toBe(СОСТОЯНИЕ);
  });

  it('файл самой статьи с сайта не убирается никогда', () => {
    expect(убираемые(план([RU]))).toEqual([]);
  });

  it('на сайте в той же папке лежит вторая статья — разрыв, а не тихая публикация без уборки', () => {
    const итог = план([RU, `${ПАПКА}/вторая.mdx`, ОБЛОЖКА]);

    expect(убираемые(итог)).toEqual([]);
    expect(итог.разрывы).toEqual([{причина: 'папкаНеОдна', путь: RU, локаль: 'ru'}]);
    expect(публикацияВозможна(итог)).toBe(false);
  });

  it('вторая статья на сайте у страницы категории считается по её же границе', () => {
    // Дочерняя статья раздела лежит во вложенной папке и второй статьёй не считается: у страницы
    // категории свой только верхний уровень.
    const дочерняя = план([RU, `${ПАПКА}/внутри/index.mdx`, ОБЛОЖКА], версия({вид: СТРАНИЦА_КАТЕГОРИИ}));

    expect(дочерняя.разрывы).toEqual([]);
    expect(убираемые(дочерняя)).toEqual([ОБЛОЖКА]);
  });

  it('чужая папка сайта не трогается: убирается только то, что лежит внутри своей', () => {
    const чужая = 'i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba-2/cover.png';

    expect(убираемые(план([RU, чужая, ОБЛОЖКА]))).toEqual([ОБЛОЖКА]);
  });

  it('страница категории убирает только верхний уровень и никогда — сам файл категории', () => {
    const итог = план(
      [RU, `${ПАПКА}/${ИМЯ_КАТЕГОРИИ}`, ОБЛОЖКА, `${ПАПКА}/внутри/cover.png`],
      версия({вид: СТРАНИЦА_КАТЕГОРИИ}),
    );

    expect(убираемые(итог)).toEqual([ОБЛОЖКА]);
  });

  it('обычная статья убирает и вложенное: её каталог принадлежит ей вглубь', () => {
    expect(убираемые(план([RU, `${ПАПКА}/внутри/cover.png`]))).toEqual([`${ПАПКА}/внутри/cover.png`]);
  });

  it('корневая страница и запись вне канона своего каталога не имеют — не убирают ничего', () => {
    for (const вид of [КОРНЕВАЯ_СТРАНИЦА, ВНЕ_КАНОНА]) {
      expect(убираемые(план([RU, ОБЛОЖКА], версия({вид})))).toEqual([]);
    }
  });

  it('сайт про папку не спрошен — отказ, а не молчаливое «убирать нечего»', () => {
    const итог = план(null);

    expect(итог.отказ).toEqual({код: 'фактыНеизвестны', локали: ['ru'], чего: 'вПапке'});
    expect(публикацияВозможна(итог)).toBe(false);
  });

  it('несколько пропавших уходят все и лежат в общем порядке путей', () => {
    const итог = план([RU, СХЕМА, ОБЛОЖКА]);

    expect(убираемые(итог)).toEqual([ОБЛОЖКА, СХЕМА]);
    expect(итог.записи.map((строка) => строка.путь)).toEqual([...итог.записи].map((строка) => строка.путь).sort());
  });

  it('статья вне сайта не убирает ничего: опубликованной ветки у неё нет вовсе', () => {
    const итог = каркасПлана({открытаяВерсия: версия(), наСайте: false, языки: [], наСайтеВПапке: null});

    expect(убираемые(итог)).toEqual([]);
    expect(итог.отказ).toBe(null);
  });
});

// Что сайт знает про каталог версии — единственный источник правды о том, чего у человека больше
// нет. Спросить его не удалось — это «не знаю», а не «там пусто».
describe('каталог версии в закреплённой ветке', () => {
  it('перечисляются файлы каталога, включая вложенные, и ничего чужого', async () => {
    const чужая = 'docs/lessons/proba-2/cover.png';
    const место = await среда({
      [RU]: СТАТЬЯ, [EN]: СТАТЬЯ, [ES]: СТАТЬЯ,
      [ОБЛОЖКА]: 'картинка', [`${ПАПКА}/внутри/схема.png`]: 'схема', [чужая]: 'чужая',
    });

    expect((await путиОсновыВПапке(место.git, место.основа, ПАПКА)).sort())
      .toEqual([ОБЛОЖКА, RU, `${ПАПКА}/внутри/схема.png`].sort());
  });

  it('ветки такой нет — «не знаю», а не пустой перечень', async () => {
    const место = await среда();

    expect(await путиОсновыВПапке(место.git, 'f'.repeat(40), ПАПКА)).toBe(null);
  });

  it('каталога в ветке нет вовсе — там и вправду пусто', async () => {
    const место = await среда({[RU]: СТАТЬЯ, [EN]: СТАТЬЯ}, {вКоммите: [EN]});

    expect(await путиОсновыВПапке(место.git, место.основа, ПАПКА)).toEqual([]);
  });

  it('факты каркаса приносят этот перечень вместе с остальными', async () => {
    const место = await среда({[RU]: СТАТЬЯ, [EN]: СТАТЬЯ, [ES]: СТАТЬЯ, [ОБЛОЖКА]: 'картинка'});
    const факты = await фактыКаркаса({
      git: место.git, repo: место.repo, rel: RU, settings: настройкиСервера(), основа: место.основа,
    });

    expect(факты.наСайтеВПапке).toContain(ОБЛОЖКА);
  });
});

// Уход файла с сайта — единственное необратимое, что бывает в составе публикации. Человек обязан
// увидеть его отдельной строкой, а не среди уезжающих картинок: там он прочёл бы прямо обратное.
describe('план называет пропадающее с сайта', () => {
  const ручка = (место) => запрос(releaseRoute, место, '/api/release', {path: RU});

  it('удалённая у человека картинка названа убираемой и в уезжающие не попадает', async () => {
    const место = await среда({[RU]: СТАТЬЯ, [EN]: СТАТЬЯ, [ES]: СТАТЬЯ, [ОБЛОЖКА]: 'картинка'});
    fs.rmSync(path.join(место.repo, ОБЛОЖКА));

    const {payload} = await ручка(место);

    expect(payload.можно).toBe(true);
    expect(payload.файлы.find((файл) => файл.путь === ОБЛОЖКА).источник).toBe(УДАЛЕНО);
    expect(payload.итог.убираемые).toEqual([ОБЛОЖКА]);
    expect(payload.итог.картинки).toEqual([]);
    expect(payload.итог.естьЧтоПубликовать).toBe(true);
  });

  it('всё на месте — убирать нечего', async () => {
    const место = await среда({[RU]: СТАТЬЯ, [EN]: СТАТЬЯ, [ES]: СТАТЬЯ, [ОБЛОЖКА]: 'картинка'});

    expect((await ручка(место)).payload.итог.убираемые).toEqual([]);
  });
});
