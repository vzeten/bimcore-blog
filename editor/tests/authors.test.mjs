// Имя каждого теста повторяет формулировку правила.
// Кто автор правки: свой, машинный или посторонний. Чистое правило, без диска и без git.
import {describe, expect, it} from 'vitest';
import {видСлоя, приведиИмя} from '../src/core/authors.mjs';

const СПРАВОЧНИК = {Claude: 'prevAi', Codex: 'prevAi'};
const Я = 'vzeten';

describe('кто автор правки', () => {
  it('автор из справочника показывается машинным слоем', () => {
    expect(видСлоя('Claude', СПРАВОЧНИК, Я)).toBe('prevAi');
  });

  it('автор, совпавший с работающим за программой, показывается своим слоем', () => {
    expect(видСлоя('vzeten', СПРАВОЧНИК, Я)).toBe('prevHuman');
  });

  it('автор вне справочника и не совпавший с работающим за программой попадает в прочее', () => {
    expect(видСлоя('Коллега', СПРАВОЧНИК, Я)).toBe('prevOther');
  });

  it('автор из справочника остаётся машинным, даже если это имя работающего за программой', () => {
    // Иначе чужая работа спрячется под своей: подписался именем ИИ — правка машинная.
    expect(видСлоя('Claude', СПРАВОЧНИК, 'Claude')).toBe('prevAi');
  });

  it('справочник пуст — программа работает, всё чужое становится прочим', () => {
    expect(видСлоя('Claude', {}, Я)).toBe('prevOther');
    expect(видСлоя(Я, {}, Я)).toBe('prevHuman');
  });

  it('неизвестный автор — это прочее, а не мои правки', () => {
    // «Неизвестный» приходит от внешней правки файла: приписывать её себе нельзя.
    expect(видСлоя('Неизвестный', СПРАВОЧНИК, Я)).toBe('prevOther');
    expect(видСлоя('', СПРАВОЧНИК, Я)).toBe('prevOther');
    expect(видСлоя(null, СПРАВОЧНИК, Я)).toBe('prevOther');
  });

  it('имя находится в справочнике независимо от регистра', () => {
    expect(видСлоя('claude', СПРАВОЧНИК, Я)).toBe('prevAi');
    expect(видСлоя('CLAUDE', СПРАВОЧНИК, Я)).toBe('prevAi');
  });

  it('имя находится после того, как прошло через имя файла снимка', () => {
    // В истории имя лежит внутри имени файла: пробелы стали подчёркиваниями и вернулись обратно.
    expect(видСлоя('Claude Code', {'Claude Code': 'prevAi'}, Я)).toBe('prevAi');
    expect(видСлоя('Claude_Code', {'Claude Code': 'prevAi'}, Я)).toBe('prevAi');
    expect(видСлоя('  Claude   Code  ', {'Claude Code': 'prevAi'}, Я)).toBe('prevAi');
  });

  it('приведение имени убирает разницу подчёркиваний, пробелов и регистра', () => {
    expect(приведиИмя('Claude_Code')).toBe(приведиИмя(' claude code '));
  });
});
