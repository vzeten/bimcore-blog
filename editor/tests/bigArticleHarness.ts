/** Простой предсказуемый счётчик: текст обязан быть одинаковым при каждом запуске проверки. */
function поток(семя: number): () => number {
  let значение = семя;
  return () => {
    значение = (значение * 1103515245 + 12345) % 2147483648;
    return значение >>> 0;
  };
}

function абзац(следующее: () => number): string {
  const фразы: string[] = [];
  for (let i = 0; i < 3; i += 1) {
    фразы.push([
      НАЧАЛА[следующее() % НАЧАЛА.length],
      СЕРЕДИНЫ[следующее() % СЕРЕДИНЫ.length],
      КОНЦЫ[следующее() % КОНЦЫ.length],
    ].join(', '));
  }
  return `${фразы.join('. ')}.`;
}

/** Основа статьи блоками: заголовок, три абзаца и список на раздел — та же смесь, что в живом уроке. */
function блоки(разделов: number, семя: number): string[] {
  const следующее = поток(семя);
  const куски: string[] = [];

  for (let раздел = 0; раздел < разделов; раздел += 1) {
    куски.push(`## Раздел ${раздел + 1}: ${ТЕМЫ[раздел % ТЕМЫ.length]}`);
    for (let i = 0; i < 3; i += 1) куски.push(абзац(следующее));
    куски.push(ПУНКТЫ.map((пункт) => `- ${пункт}`).join('\n'));
  }

  return куски;
}

/** Переписать каждый n-й абзац заново: так выглядит проход по статье чужой рукой. */
function переписать(куски: string[], каждый: number, семя: number): string[] {
  const следующее = поток(семя);
  return куски.map((кусок, i) => (i % каждый === 1 && !кусок.startsWith('#') && !кусок.startsWith('-') ? абзац(следующее) : кусок));
}

const СОБРАТЬ = (куски: string[]): string => `${куски.join('\n\n')}\n`;

/**
 * Цепочка из четырёх состояний. ИИ переписал около четверти абзацев и добавил свой, человек прошёлся
 * по части оставшихся и убрал добавленный, в файле появилось выделение жирным и правка заголовка.
 */
export function слоиБольшойСтатьи(разделов = 19): {слои: Layer[]; файл: string} {
  const основа = блоки(разделов, 20260910);
  const сайт = СОБРАТЬ(основа);

  const переписанные = переписать(основа, 3, 77003);
  const ии = СОБРАТЬ([...переписанные.slice(0, 9), 'Короткий абзац, которого раньше не было.', ...переписанные.slice(9)]);

  const правленые = переписать(переписанные, 5, 5501).map((кусок, i) => (i === 12 ? `${кусок} Уточнение руками.` : кусок));
  const рукой = СОБРАТЬ(правленые);

  // Правки, оставшиеся в файле и ещё не попавшие в историю: выделение жирным и уточнённый заголовок.
  const файл = СОБРАТЬ(правленые.map((кусок, i) => {
    if (i === 0) return `${кусок} — практика`;
    return i === 2 ? `**${кусок}**` : кусок;
  }));

  return {
    слои: [
      {text: сайт, kind: 'site'},
      {text: ии, kind: 'prevAi'},
      {text: рукой, kind: 'prevHuman'},
      {text: файл, kind: 'prevHuman'},
    ],
    файл,
  };
}
