// Имя каждого теста повторяет формулировку правила.
// Откуда шапка открытой статьи берёт признаки версий и когда окно перечитывает их заново.
//
// Наблюдение владельца, ради которого правило заведено: красная точка правки появлялась только
// после ручного «Сохранить», а после подтверждённого автосохранения признаки не обновлялись.
import {describe, expect, it, vi} from 'vitest';

import {createAutosaveQueue, type DraftPayload} from '../src/ui/autosaveQueue';
import {записьПодтверждена, признакиИзСвода, скрытаИзСвода} from '../src/ui/localeFacts';
import {изменениеНеНаСайте} from '../src/ui/headFields';
import {признакиЛокали} from '../src/core/localeSigns.mjs';
import type {ArticleRow, ArticleVersion} from '../src/ui/articleTypes';
import type {SaveState} from '../src/ui/types';

/** Правка, ждущая записи в черновик. */
const правка = (over: Partial<DraftPayload> = {}): DraftPayload => ({
  path: 'blog/proba/index.mdx',
  body: 'набранный текст',
  frontmatterRaw: 'title: Проба',
  отпечатокБазы: 'ОТП1',
  ...over,
});

/** Запись черновика, подменённая на запоминающую: что ушло и с каким исходом. */
function хранилище(успех = true) {
  const запись = vi.fn(async (_данные: DraftPayload, effects: {ok: () => void; fail: (r: string) => void}) => {
    if (успех) effects.ok();
    else effects.fail('сервер недоступен');
  });

  return {запись: запись as never};
}

const ПУТИ = {
  ru: 'i18n/ru/docusaurus-plugin-content-blog/proba/index.mdx',
  en: 'blog/proba/index.mdx',
  es: 'i18n/es/docusaurus-plugin-content-blog/proba/index.mdx',
};

const ЛОКАЛИ = ['ru', 'en', 'es'];

const версия = (path: string, ещё: Partial<ArticleVersion> = {}): ArticleVersion => ({
  path,
  title: 'Проба',
  скрыта: false,
  готовность: null,
  опубликован: true,
  отличается: false,
  правкаВЧерновике: false,
  заглушка: false,
  черновикСайта: false,
  черновикВВетке: false,
  правил: null,
  когда: 0,
  позиция: null,
  ...ещё,
});

/** Свод глазами реестра: RU без изменений, EN с местной правкой, ES — заглушка. */
const свод = (versions: Record<string, ArticleVersion>): ArticleRow[] => [{
  key: 'blog:proba/index.mdx',
  kind: 'blog',
  наСайте: true,
  category: 'блог',
  section: {kind: 'blog', path: ''},
  folders: ['блог', 'proba'],
  title: 'Проба',
  titleFromOtherLocale: false,
  служебная: false,
  нетНаСайте: false,
  порядокМеню: null,
  versions,
}];

const ТРИ_ВЕРСИИ = {
  ru: версия(ПУТИ.ru),
  en: версия(ПУТИ.en, {отличается: true}),
  es: версия(ПУТИ.es, {заглушка: true}),
};

describe('признаки локалей в шапке считаются по тому же своду, что и в реестре', () => {
  it('признаки каждой версии совпадают с теми, что берёт реестр', () => {
    const из = признакиИзСвода(свод(ТРИ_ВЕРСИИ), ПУТИ.en, ЛОКАЛИ);

    // Реестр считает их тем же правилом ядра прямо из свода: второго расчёта быть не должно.
    expect(из).toEqual({
      ru: признакиЛокали(ТРИ_ВЕРСИИ.ru),
      en: признакиЛокали(ТРИ_ВЕРСИИ.en),
      es: признакиЛокали(ТРИ_ВЕРСИИ.es),
    });
    expect(из?.en.изменена).toBe(true);
    expect(из?.ru.изменена).toBe(false);
    expect(из?.es.изменена).toBe(false);
  });

  it('признаки берутся по любой версии статьи, а не только по основной', () => {
    const свежий = свод(ТРИ_ВЕРСИИ);

    expect(признакиИзСвода(свежий, ПУТИ.es, ЛОКАЛИ)).toEqual(признакиИзСвода(свежий, ПУТИ.ru, ЛОКАЛИ));
  });

  it('локали без файла называются наравне с существующими: «версии нет» — тоже состояние', () => {
    const из = признакиИзСвода(свод({ru: версия(ПУТИ.ru)}), ПУТИ.ru, ЛОКАЛИ);

    expect(Object.keys(из ?? {})).toEqual(ЛОКАЛИ);
    expect(из?.es).toEqual(признакиЛокали(null));
  });

  it('статьи в своде нет — прежние признаки остаются, выдуманных не появляется', () => {
    expect(признакиИзСвода(свод(ТРИ_ВЕРСИИ), 'blog/другая/index.mdx', ЛОКАЛИ)).toBe(null);
    expect(признакиИзСвода([], ПУТИ.ru, ЛОКАЛИ)).toBe(null);
  });
});

describe('свод перечитывается только после подтверждения сервера', () => {
  it('сервер подтвердил запись — и ручную, и автосохранением', () => {
    expect(записьПодтверждена('сохранено')).toBe(true);
    expect(записьПодтверждена('автосохранено')).toBe(true);
  });

  it('ещё не сохранённый текст и идущий запрос подтверждением не считаются', () => {
    expect(записьПодтверждена('естьНесохранённые')).toBe(false);
    expect(записьПодтверждена('сохраняем')).toBe(false);
  });

  it('запись не удалась — свод не перечитывается, ложной точки не появляется', () => {
    expect(записьПодтверждена('неУдалосьАвтосохранить')).toBe(false);
  });
});

describe('признаки версий обновляются после подтверждённого автосохранения', () => {
  // Признаки локалей считаются с диска, поэтому окно перечитывает их по состоянию очереди.
  // Что считать подтверждением — правило `записьПодтверждена`; здесь проверяется, что очередь
  // сообщает его ровно тогда, когда сервер принял запись.
  const подтверждения = (состояния: string[]): number =>
    состояния.filter((состояние) => записьПодтверждена(состояние as SaveState)).length;

  it('сервер принял черновик — очередь сообщает подтверждение записи', async () => {
    const {запись} = хранилище();
    const состояния: string[] = [];
    const очередь = createAutosaveQueue(() => 3, (state) => состояния.push(state), запись);

    очередь.запланировать(правка());
    await очередь.дописать();

    expect(состояния.at(-1)).toBe('автосохранено');
    expect(подтверждения(состояния)).toBe(1);
  });

  it('текст набран, но ещё не записан — подтверждения нет и признаки не трогаются', async () => {
    const {запись} = хранилище();
    const состояния: string[] = [];
    const очередь = createAutosaveQueue(() => 60, (state) => состояния.push(state), запись);

    очередь.запланировать(правка());

    expect(состояния).toEqual(['естьНесохранённые']);
    expect(подтверждения(состояния)).toBe(0);
    очередь.отменить();
  });

  it('запись не удалась — подтверждения нет, ложной точке взяться неоткуда', async () => {
    const {запись} = хранилище(false);
    const состояния: string[] = [];
    const очередь = createAutosaveQueue(() => 3, (state) => состояния.push(state), запись);

    очередь.запланировать(правка());
    await очередь.дописать();

    expect(состояния.at(-1)).toBe('неУдалосьАвтосохранить');
    expect(подтверждения(состояния)).toBe(0);
  });

  it('ответ «устарел» записью не считается: подтверждения по нему нет', async () => {
    const записано: DraftPayload[] = [];
    const запись = vi.fn(async (данные: DraftPayload, effects: {ok: (о?: unknown) => void; fail: (r: string) => void}) => {
      записано.push(данные);
      effects.ok({устарел: true});
    });
    const состояния: string[] = [];
    const очередь = createAutosaveQueue(() => 3, (state) => состояния.push(state), запись as never);

    очередь.запланировать(правка());
    await очередь.дописать();

    expect(состояния).not.toContain('автосохранено');
    expect(подтверждения(состояния)).toBe(0);
  });
});

describe('«изменение ещё не на сайте» после публикации', () => {
  it('видимость на сайте берётся из свежего свода: опубликовали «По ссылке» — надпись гаснет без перезагрузки', () => {
    // До публикации: на сайте версия видна всем, в окне выбрано «По ссылке» — надпись горит.
    const было = {скрытаНаСайте: скрытаИзСвода(свод({ru: версия(ПУТИ.ru, {скрыта: false})}), ПУТИ.ru) as boolean | null, веткаИзвестна: true};
    expect(изменениеНеНаСайте(было, true)).toBe(true);

    // После публикации свод перечитан: на сайте та же шапка, что в файле.
    const стало = {...было, скрытаНаСайте: скрытаИзСвода(свод({ru: версия(ПУТИ.ru, {скрыта: true})}), ПУТИ.ru) as boolean | null};
    expect(изменениеНеНаСайте(стало, true)).toBe(false);
  });

  it('версии в ветке нет — null; свод не знает ответа — прежнее значение не трогается', () => {
    expect(скрытаИзСвода(свод({ru: версия(ПУТИ.ru, {опубликован: false})}), ПУТИ.ru)).toBeNull();
    expect(скрытаИзСвода(свод({ru: версия(ПУТИ.ru, {опубликован: null})}), ПУТИ.ru)).toBeUndefined();
    expect(скрытаИзСвода(свод({ru: версия(ПУТИ.ru, {отличается: true})}), ПУТИ.ru)).toBeUndefined();
    expect(скрытаИзСвода(свод({ru: версия(ПУТИ.ru)}), 'нет/такого.mdx')).toBeUndefined();
  });
});
