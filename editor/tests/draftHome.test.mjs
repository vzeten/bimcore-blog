// Имя каждого теста повторяет формулировку правила.
// Чистые правила дома черновиков: диска здесь нет, только решения (SPEC 4.6, 7.1.5).
import {describe, expect, it} from 'vitest';
import path from 'node:path';

import {
  КОПИРОВАТЬ, СОВПАЛО, СПОР, ПАПКА_РЕДАКТОРА,
  имяСпора, исходФайла, нуженПеренос, одинПуть, префиксСпора,
} from '../src/core/draftHome.mjs';
import {хранилищеРедактора} from '../src/adapters/draftStore.mjs';
import {draftName} from '../src/core/drafts.mjs';

describe('где живут черновик и история', () => {
  it('хранилище считается от корня материалов, а не от папки запущенного кода', () => {
    const корень = 'C:/My_code/bimcore-blog';

    expect(хранилищеРедактора(корень)).toBe(path.join(корень, ПАПКА_РЕДАКТОРА));
  });

  it('два корня материалов дают два разных хранилища: испытательный не лезет к владельцу', () => {
    const владелец = хранилищеРедактора('C:/My_code/bimcore-blog');
    const испытательный = хранилищеРедактора('C:/Temp/проба');

    expect(владелец).not.toBe(испытательный);
  });
});

describe('один путь или два', () => {
  it('обратные косые и прямые — один путь: запуск на Windows пишет их как придётся', () => {
    expect(одинПуть('C:\\My_code\\bimcore-blog\\editor', 'C:/My_code/bimcore-blog/editor')).toBe(true);
  });

  it('разный регистр — один путь: Windows не различает буквы диска и папок', () => {
    expect(одинПуть('c:/my_code/bimcore-blog/editor', 'C:/My_code/bimcore-blog/EDITOR')).toBe(true);
  });

  it('косая на конце пути ничего не меняет', () => {
    expect(одинПуть('C:/My_code/bimcore-blog/editor/', 'C:/My_code/bimcore-blog/editor')).toBe(true);
  });

  it('соседняя папка — другой путь', () => {
    expect(одинПуть('C:/My_code/bimcore-blog/editor', 'C:/My_code/копия/editor')).toBe(false);
  });
});

describe('нужен ли перенос старого хранилища', () => {
  it('испытательный экземпляр не переносит ничего: его корень чужой', () => {
    const итог = нуженПеренос({
      хранилище: 'C:/Temp/проба/editor',
      наследие: 'C:/My_code/bimcore-blog/editor',
      испытательный: true,
    });

    expect(итог).toBe(false);
  });

  it('старое хранилище и есть общее — переносить нечего', () => {
    const итог = нуженПеренос({
      хранилище: 'C:/My_code/bimcore-blog/editor',
      наследие: 'C:\\My_code\\bimcore-blog\\editor',
      испытательный: false,
    });

    expect(итог).toBe(false);
  });

  it('код запущен из другой рабочей копии — перенос нужен', () => {
    const итог = нуженПеренос({
      хранилище: 'C:/My_code/bimcore-blog/editor',
      наследие: 'C:/My_code/bimcore-blog/editor/.coordination/worktrees/проба/editor',
      испытательный: false,
    });

    expect(итог).toBe(true);
  });
});

describe('судьба одного старого файла', () => {
  it('такие же байты уже лежат — переносить нечего, и повтор ничего не добавит', () => {
    expect(исходФайла({такиеЖеБайты: true, местоСвободно: false})).toBe(СОВПАЛО);
    expect(исходФайла({такиеЖеБайты: true, местоСвободно: true})).toBe(СОВПАЛО);
  });

  it('место свободно — просто кладём', () => {
    expect(исходФайла({такиеЖеБайты: false, местоСвободно: true})).toBe(КОПИРОВАТЬ);
  });

  it('под тем же именем лежит ДРУГОЙ текст — это спор, а не повод выбрать', () => {
    // Ни времени файла, ни длины пути в правиле нет намеренно: обе работы — человека.
    expect(исходФайла({такиеЖеБайты: false, местоСвободно: false})).toBe(СПОР);
  });
});

describe('имена отложенных вариантов', () => {
  const имя = draftName('i18n/ru/docusaurus-plugin-content-docs/current/beds/index.mdx');

  it('вариант узнаётся по началу имени своего черновика', () => {
    expect(имяСпора(имя, 'abcdef1234567890').startsWith(префиксСпора(имя))).toBe(true);
  });

  it('имя считается от самих байтов, поэтому повтор переноса даёт тот же файл', () => {
    expect(имяСпора(имя, 'abcdef1234567890')).toBe(имяСпора(имя, 'abcdef1234567890'));
  });

  it('разные байты — разные варианты: один не затирает другой', () => {
    expect(имяСпора(имя, 'aaaaaaaa11')).not.toBe(имяСпора(имя, 'bbbbbbbb22'));
  });

  it('вариант остаётся файлом черновика: читать его человеку тем же способом', () => {
    expect(имяСпора(имя, 'abcdef1234567890').endsWith('.json')).toBe(true);
  });
});
