// Имя каждого теста повторяет формулировку правила.
// Обработчики файлов медиа: медиаподготовка и переименование.
import {describe, expect, it} from 'vitest';

import {медиаподготовка, переименование, размерПоСтандарту, размерыКартинки} from '../src/core/refineFiles.mjs';
import {разница} from '../src/core/refine.mjs';
import {GIF, RU, WEBM, WEBP, НАСТРОЙКИ, инструменты, копия, jpg, png} from './refineHarness.mjs';

const ШАПКА = '---\ntitle: "Розетки"\nslug: /lessons/proba\n---\n\n';
const живые = (к) => [...к.файлы.entries()].filter(([, б]) => б !== null).map(([имя]) => имя).sort();

describe('размеры картинки', () => {
  it('размеры читаются из заголовков PNG и JPEG; чужие байты дают неизвестность', () => {
    expect(размерыКартинки(png(1200, 800), 'png')).toEqual({ширина: 1200, высота: 800});
    expect(размерыКартинки(jpg(640, 480), 'jpg')).toEqual({ширина: 640, высота: 480});
    expect(размерыКартинки(GIF, 'gif')).toBeNull();
  });

  it('размер по стандарту: уменьшает только ширина больше 1100 px, высота не ограничена', () => {
    expect(размерПоСтандарту({ширина: 1600, высота: 900})).toEqual({ширина: 1100, высота: 619});
    expect(размерПоСтандарту({ширина: 2000, высота: 1000})).toEqual({ширина: 1100, высота: 550});
    // Вертикальная схема высотой не уменьшается: ширина её в предел укладывается.
    expect(размерПоСтандарту({ширина: 1000, высота: 1750})).toEqual({ширина: 1000, высота: 1750});
    expect(размерПоСтандарту({ширина: 1100, высота: 4000})).toEqual({ширина: 1100, высота: 4000});
    expect(размерПоСтандарту({ширина: 300, высота: 200})).toEqual({ширина: 300, высота: 200});
  });
});

describe('медиаподготовка', () => {
  it('JPEG становится PNG под тем же именем, ссылки обновляются, старый файл уходит; GIF не читается', async () => {
    const к = копия(`${ШАПКА}![a](./img/photo.jpg)\n\n![b](./img/anim.gif)\n`, {'img/photo.jpg': jpg(1200, 800), 'img/anim.gif': GIF});
    const предложение = медиаподготовка.анализ(к, НАСТРОЙКИ);
    expect(предложение.отчёт.изменено).toEqual([{что: 'img/photo.jpg', было: '1200×800, JPG, 0 КБ', стало: 'img/photo.png: 1100×733, PNG'}]);
    expect(предложение.отчёт.оставлено).toEqual([{что: 'img/anim.gif', причина: 'анимация'}]);

    const инстр = инструменты(png(1100, 733));
    const {копия: итог, отчёт} = await медиаподготовка.применить(к, предложение, инстр);
    expect(инстр.вызовов).toBe(1);
    expect(итог.текст).toBe(`${ШАПКА}![a](./img/photo.png)\n\n![b](./img/anim.gif)\n`);
    expect(живые(итог)).toEqual(['img/anim.gif', 'img/photo.png']);
    expect(итог.файлы.get('img/anim.gif')).toBe(GIF);
    expect(отчёт.изменено[0].стало).toBe('img/photo.png: 1100×733, PNG, 0 КБ');
    expect(медиаподготовка.проверить(итог, предложение)).toBe(true);
  });

  it('вертикальная схема шириной до 1100 px в отчёте остаётся своих размеров: уменьшения не обещано', () => {
    const к = копия(`${ШАПКА}![a](./img/схема.jpg)
`, {'img/схема.jpg': jpg(1000, 1750)});
    const предложение = медиаподготовка.анализ(к, НАСТРОЙКИ);
    expect(предложение.отчёт.изменено).toEqual([{что: 'img/схема.jpg', было: '1000×1750, JPG, 0 КБ', стало: 'img/схема.png: 1000×1750, PNG'}]);
  });

  it('обложка из шапки готовится вместе с картинками тела, и запись в шапке обновляется', async () => {
    const к = копия(`${ШАПКА.replace('---\n\n', 'image: ./cover.jpg\n---\n\n')}Текст\n`, {'cover.jpg': jpg(50, 50)});
    const {копия: итог} = await медиаподготовка.применить(к, медиаподготовка.анализ(к, НАСТРОЙКИ), инструменты(png(50, 50)));
    expect(итог.текст).toContain('image: ./cover.png\n');
    expect(живые(итог)).toEqual(['cover.png']);
  });

  it('WebP по байтам — неподвижная картинка: становится PNG под тем же именем, ссылка обновляется', async () => {
    const к = копия(`${ШАПКА}![a](./a.webp)
`, {'a.webp': WEBP});
    const предложение = медиаподготовка.анализ(к, НАСТРОЙКИ);
    expect(предложение.отчёт.изменено).toEqual([{что: 'a.webp', было: 'WEBP, 0 КБ', стало: 'a.png: PNG'}]);
    const {копия: итог} = await медиаподготовка.применить(к, предложение, инструменты(png(4, 4)));
    expect(итог.текст).toBe(`${ШАПКА}![a](./a.png)
`);
    expect(живые(итог)).toEqual(['a.png']);
  });

  it('PNG проходит скрипт всегда: результат заменяет байты, даже если он не меньше исходного', async () => {
    const к = копия(`${ШАПКА}![a](./a.png)
`, {'a.png': png(10, 10)});
    const {копия: итог, отчёт} = await медиаподготовка.применить(к, медиаподготовка.анализ(к, НАСТРОЙКИ), инструменты(png(10, 10, 100)));
    expect(итог.файлы.get('a.png')).toEqual(png(10, 10, 100));
    expect(отчёт.изменено).toEqual([{что: 'a.png', было: '10×10, PNG, 0 КБ', стало: 'a.png: 10×10, PNG, 0 КБ'}]);
  });

  it('WebM из импорта ролика остаётся побайтово прежним и в разницу со снимком не попадает', async () => {
    const к = копия(`${ШАПКА}import v from './a.webm';

![a](./a.jpg)
`, {'a.webm': WEBM, 'a.jpg': jpg(10, 10)});
    const предложение = медиаподготовка.анализ(к, НАСТРОЙКИ);
    expect(предложение.отчёт.оставлено).toEqual([{что: 'a.webm', причина: 'анимация'}]);
    const {копия: итог} = await медиаподготовка.применить(к, предложение, инструменты(png(10, 10)));
    expect(итог.файлы.get('a.webm')).toBe(WEBM);
    expect(итог.текст).toContain("import v from './a.webm';");
    expect(разница(к, итог).файлы.map((ф) => ф.имя).sort()).toEqual(['a.jpg', 'a.png']);
  });

  it('имя .png, занятое другим файлом папки, не затирается: картинка отдаётся человеку', () => {
    const к = копия(`${ШАПКА}![a](./a.jpg)\n`, {'a.jpg': jpg(10, 10), 'a.png': png(1, 1)});
    const {цели, отчёт} = медиаподготовка.анализ(к, НАСТРОЙКИ);
    expect(цели).toEqual([]);
    expect(отчёт.человеку).toEqual([{что: 'a.jpg', причина: 'имяЗанято'}]);
  });

  for (const [пара, файлы] of [
    ['a.jpg и a.png', {'a.jpg': jpg(10, 10), 'a.png': png(1, 1)}],
    ['a.jpg и a.jpeg', {'a.jpg': jpg(10, 10), 'a.jpeg': jpg(2, 2)}],
  ]) {
    it(`два исходника с одной целью (${пара}) не схлопываются: оба уходят человеку, ничего не преобразуется`, async () => {
      const текст = `${ШАПКА}${Object.keys(файлы).map((имя) => `![](./${имя})`).join('\n\n')}\n`;
      const к = копия(текст, файлы);
      const предложение = медиаподготовка.анализ(к, НАСТРОЙКИ);
      expect(предложение.цели).toEqual([]);
      expect(предложение.отчёт.человеку).toEqual(Object.keys(файлы).map((что) => ({что, причина: 'имяЗанято'})));
      const инстр = инструменты(png(3, 3));
      const {копия: итог} = await медиаподготовка.применить(к, предложение, инстр);
      expect(итог.текст).toBe(текст);
      expect([...итог.файлы.entries()]).toEqual([...к.файлы.entries()]);
    });
  }

  it('картинка, уже лежащая на сайте, не трогается ничем: её адрес там зависит от содержимого', async () => {
    const к = копия(
      `${ШАПКА}![a](./img/photo.jpg)\n\n![b](./img/новая.jpg)\n`,
      {'img/photo.jpg': jpg(1200, 800), 'img/новая.jpg': jpg(1200, 800)},
      RU,
      new Set(['img/photo.jpg']),
    );
    const предложение = медиаподготовка.анализ(к, НАСТРОЙКИ);

    expect(предложение.отчёт.оставлено).toEqual([{что: 'img/photo.jpg', причина: 'наСайте'}]);
    expect(предложение.цели.map((ц) => ц.имя)).toEqual(['img/новая.jpg']);

    const {копия: итог} = await медиаподготовка.применить(к, предложение, инструменты(png(1100, 733)));
    expect(итог.файлы.get('img/photo.jpg')).toBe(к.файлы.get('img/photo.jpg'));
    expect(итог.текст).toContain('./img/photo.jpg');
  });

  it('про сайт ничего не известно — не трогается ни одна картинка: незнание не «там ничего нет»', () => {
    const к = копия(`${ШАПКА}![a](./img/photo.jpg)\n`, {'img/photo.jpg': jpg(1200, 800)}, RU, null);
    const предложение = медиаподготовка.анализ(к, НАСТРОЙКИ);

    expect(предложение.цели).toEqual([]);
    expect(предложение.отчёт.оставлено).toEqual([{что: 'img/photo.jpg', причина: 'сайтНеизвестен'}]);
  });

  it('файл уже по стандарту сайта — PNG с палитрой шириной до 1100 — второй раз не пересохраняется', async () => {
    const готовый = png(1100, 733, 0, 3);
    const к = копия(`${ШАПКА}![a](./img/img-01.png)\n`, {'img/img-01.png': готовый});
    const предложение = медиаподготовка.анализ(к, НАСТРОЙКИ);

    expect(предложение.цели).toEqual([]);
    expect(предложение.отчёт.оставлено).toEqual([{что: 'img/img-01.png', причина: 'ужеПоСтандарту'}]);

    // Скрипту такой файл не отдаётся вовсе: цели пусты, и на диск не ложится ни одного байта.
    const {копия: итог} = await медиаподготовка.применить(к, предложение, инструменты(png(1100, 733, 5, 3)));
    expect(итог.файлы.get('img/img-01.png')).toBe(готовый);
    expect(разница(к, итог).файлы).toEqual([]);
  });

  it('PNG с палитрой шире 1100 px по стандарту ещё не готов: ширину надо уменьшить', () => {
    const к = копия(`${ШАПКА}![a](./img/img-01.png)\n`, {'img/img-01.png': png(1600, 900, 0, 3)});
    const предложение = медиаподготовка.анализ(к, НАСТРОЙКИ);

    expect(предложение.цели.map((ц) => ц.имя)).toEqual(['img/img-01.png']);
    expect(предложение.отчёт.изменено[0].стало).toBe('img/img-01.png: 1100×619, PNG');
  });

  it('файл, на который версия не ссылается, обработчик не видит вовсе', () => {
    const к = копия(`${ШАПКА}Текст\n`, {'лишний.jpg': jpg(10, 10)});
    expect(медиаподготовка.анализ(к, НАСТРОЙКИ)).toBeNull();
  });
});

describe('переименование картинок', () => {
  it('картинки тела получают имена по шаблону и порядку в статье, ссылки и импорты обновляются', () => {
    const текст = `${ШАПКА}import p from './img/p.png';\n\n![a](./img/photo.jpg)\n\n![b](./img/anim.gif)\n\n<ProductCard name="К" image={p} />\n`;
    const к = копия(текст, {'img/photo.jpg': jpg(1, 1), 'img/anim.gif': GIF, 'img/p.png': png(1, 1)});
    const предложение = переименование.анализ(к, НАСТРОЙКИ);
    const {копия: итог} = переименование.применить(к, предложение);

    expect(итог.текст).toBe(`${ШАПКА}import p from './img/img-01.png';\n\n![a](./img/img-02.jpg)\n\n![b](./img/img-03.gif)\n\n<ProductCard name="К" image={p} />\n`);
    expect(живые(итог)).toEqual(['img/img-01.png', 'img/img-02.jpg', 'img/img-03.gif']);
    expect(переименование.проверить(итог, предложение)).toBe(true);
  });

  it('обмен имён безопасен: используемый img-05 становится img-01, а занятый им img-01 — img-02', () => {
    const к = копия(`${ШАПКА}![a](./img-05.png)\n\n![b](./img-01.png)\n`, {'img-05.png': png(5, 5), 'img-01.png': png(1, 1)});
    const {копия: итог} = переименование.применить(к, переименование.анализ(к, НАСТРОЙКИ));
    expect(итог.текст).toBe(`${ШАПКА}![a](./img-01.png)\n\n![b](./img-02.png)\n`);
    expect(итог.файлы.get('img-01.png')).toEqual(png(5, 5));
    expect(итог.файлы.get('img-02.png')).toEqual(png(1, 1));
  });

  it('обложка не становится картинкой тела; имя, занятое чужим файлом, не затирается; имя по шаблону остаётся', () => {
    const текст = `${ШАПКА.replace('---\n\n', 'image: ./cover.png\n---\n\n')}![a](./img-01.png)\n\n![b](./photo.png)\n`;
    const к = копия(текст, {'cover.png': png(1, 1), 'img-01.png': png(1, 1), 'photo.png': png(2, 2), 'img-02.png': png(3, 3)});
    const {цели, отчёт} = переименование.анализ(к, НАСТРОЙКИ);
    expect(цели).toEqual([]);
    expect(отчёт.оставлено).toEqual([{что: 'img-01.png', причина: 'тоЖеИмя'}]);
    expect(отчёт.человеку).toEqual([{что: 'photo.png', причина: 'имяЗанято'}]);
  });

  it('одна картинка, вставленная дважды, получает один номер и обе ссылки', () => {
    const к = копия(`${ШАПКА}![a](./photo.png)\n\n![b](./photo.png)\n`, {'photo.png': png(1, 1)});
    const {копия: итог} = переименование.применить(к, переименование.анализ(к, НАСТРОЙКИ));
    expect(итог.текст).toBe(`${ШАПКА}![a](./img-01.png)\n\n![b](./img-01.png)\n`);
    expect(живые(итог)).toEqual(['img-01.png']);
  });
});
