// Имя каждого теста повторяет формулировку правила.
// Значок «Сайт» (решение владельца 2026-09-18, п.5б): что показать по состоянию выкладки.
import {describe, expect, it} from 'vitest';

import {значокСайта} from '../src/ui/siteState';

describe('значок «Сайт»', () => {
  it('выкладка идёт — «обновляется», и так даже после «Понятно»', () => {
    expect(значокСайта({состояние: 'ждём'})).toBe('обновляется');
    expect(значокСайта({состояние: 'идёт', показано: true})).toBe('обновляется');
  });

  it('итог показывается, пока человек его не увидел', () => {
    expect(значокСайта({состояние: 'обновлён'})).toBe('обновлён');
    expect(значокСайта({состояние: 'сборкаУпала'})).toBe('неОбновился');
    expect(значокСайта({состояние: 'выкладкаУпала'})).toBe('неОбновился');
    expect(значокСайта({состояние: 'неВидно', причина: 'долго'})).toBe('неизвестно');
    expect(значокСайта({состояние: 'сборкаУпала', показано: true})).toBe('нет');
  });

  it('отправок не было или ответа нет — значка нет', () => {
    expect(значокСайта(null)).toBe('нет');
    expect(значокСайта({состояние: 'нет'})).toBe('нет');
  });

  it('сайт не на GitHub (учебный) — значка нет вовсе', () => {
    expect(значокСайта({состояние: 'неВидно', причина: 'неGitHub'})).toBe('нет');
  });
});
