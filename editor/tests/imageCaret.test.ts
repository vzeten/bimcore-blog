// Имя каждого теста повторяет формулировку правила.
// Курсор не встаёт в пустые карманы строки, где нет ничего кроме картинки.
import {describe, expect, it} from 'vitest';
import {курсорМимоКартинки} from '../src/ui/livePreview/imageCaret';

const КАРТИНКА = '![Подпись](./img-01.jpg)';

describe('курсор у одинокой картинки', () => {
  it('карман над картинкой уводит курсор в конец строки выше', () => {
    const текст = `текст\n${КАРТИНКА}\nниже`;
    const началоСтроки = текст.indexOf(КАРТИНКА);

    expect(курсорМимоКартинки(текст, началоСтроки)).toBe(началоСтроки - 1);
  });

  it('карман под картинкой уводит курсор в начало строки ниже', () => {
    const текст = `текст\n${КАРТИНКА}\nниже`;
    const конецСтроки = текст.indexOf(КАРТИНКА) + КАРТИНКА.length;

    expect(курсорМимоКартинки(текст, конецСтроки)).toBe(конецСтроки + 1);
  });

  it('картинка первая в статье — курсор уходит вниз, а не остаётся в кармане', () => {
    const текст = `${КАРТИНКА}\nниже`;

    expect(курсорМимоКартинки(текст, 0)).toBe(КАРТИНКА.length + 1);
  });

  it('картинка последняя в статье — курсор уходит вверх', () => {
    const текст = `выше\n${КАРТИНКА}`;
    const конец = текст.length;

    expect(курсорМимоКартинки(текст, конец)).toBe(текст.indexOf(КАРТИНКА) - 1);
  });

  it('в статье нет ничего кроме картинки — курсор остаётся где есть', () => {
    expect(курсорМимоКартинки(КАРТИНКА, 0)).toBeNull();
    expect(курсорМимоКартинки(КАРТИНКА, КАРТИНКА.length)).toBeNull();
  });

  it('рядом с картинкой в строке есть текст — карманы не закрываются', () => {
    // Так написаны живые статьи сайта: «текст, а сразу за ним картинка».
    const текст = `слова ${КАРТИНКА}`;

    expect(курсорМимоКартинки(текст, 0)).toBeNull();
    expect(курсорМимоКартинки(текст, текст.length)).toBeNull();
  });

  it('обычная строка курсор не двигает', () => {
    const текст = 'просто абзац';

    expect(курсорМимоКартинки(текст, 0)).toBeNull();
    expect(курсорМимоКартинки(текст, текст.length)).toBeNull();
  });

  it('позиция внутри строки картинки правилу не подчиняется: там атомарный виджет', () => {
    const текст = `выше\n${КАРТИНКА}\nниже`;

    expect(курсорМимоКартинки(текст, текст.indexOf(КАРТИНКА) + 4)).toBeNull();
  });

  it('строка с двумя картинками одинокой не считается', () => {
    const текст = `выше\n${КАРТИНКА}${КАРТИНКА}\nниже`;
    const начало = текст.indexOf(КАРТИНКА);

    expect(курсорМимоКартинки(текст, начало)).toBeNull();
  });
});
