// Имя каждого теста повторяет формулировку правила.
// Порт и опознание экземпляра: `4780` принадлежит обычному принятому редактору, любой другой
// запуск называет свой порт явно, а кто именно ответил — видно по одному опознанию.
import {describe, expect, it} from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

import {
  ВЕТКА_ПРИНЯТОГО, НЕВЕРНЫЙ_ПОРТ, НЕТ_ПОРТА, ПАПКА_ПРИНЯТОГО, ПОРТ_ВЛАДЕЛЬЦА,
  РОЛЬ_ИСПЫТАТЕЛЬНАЯ, РОЛЬ_ОБЫЧНАЯ, ЧУЖОЙ_ПОРТ, выборПорта, опознание, принятый,
} from '../src/core/runtimeIdentity.mjs';
import {ПОРТ_ЗАПУСКА, опознаниеЗапуска} from '../src/adapters/materialSource.mjs';
import {ПАПКА_ВЛАДЕЛЬЦА} from '../src/core/materialRoot.mjs';

const EDITOR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const настоящие = JSON.parse(fs.readFileSync(path.join(EDITOR, 'settings.json'), 'utf8'));

const слова = {
  [НЕТ_ПОРТА]: 'Назовите свой порт',
  [ЧУЖОЙ_ПОРТ]: 'Порт 4780 принадлежит обычному редактору. Указано',
  [НЕВЕРНЫЙ_ПОРТ]: 'Порт должен быть числом. Указано',
};

const настройки = () => ({'материалы': {'порт': слова}});

/**
 * Дверь к git, отвечающая заданной версией кода и чистотой дерева. Отказ — это git, который ничего
 * не сказал: тогда неизвестны и ветка, и чистота.
 */
const дверь = (ветка, коммит, хвосты = '') => ({
  raw: async (args) => {
    if (ветка === null) throw new Error('git молчит');
    if (args.includes('status')) return `${хвосты}\n`;
    return args.includes('--abbrev-ref') ? `${ветка}\n` : `${коммит}\n`;
  },
});

const ДОМА = {корень: 'C:\\My_code\\bimcore-blog', испытательный: false};
const ЧУЖОЕ = {корень: 'D:\\site', испытательный: true};

/** Место принятой рабочей копии в родном для Windows виде — так его и подаёт запуск. */
const ПРИНЯТАЯ_КОПИЯ = ПАПКА_ПРИНЯТОГО.split('/').join('\\');

const запуск = (источник, ветка, заявка, {код = ПРИНЯТАЯ_КОПИЯ, хвосты = ''} = {}) => опознаниеЗапуска({
  settings: настройки(), кодDir: код, git: дверь(ветка, '1234abc', хвосты), источник, заявка,
});

const отказом = async (...аргументы) => {
  try {
    await запуск(...аргументы);
    return null;
  } catch (error) {
    return error.message;
  }
};

describe('порт 4780 принадлежит обычному принятому редактору', () => {
  it('порт обычного окна задан кодом, а не настройками: настройки его не содержат вовсе', () => {
    // Тот же довод, что и у папки материалов: пока номер брался из `settings.json`, любая копия
    // программы со своим файлом настроек объявляла себя хозяйкой `4780`.
    expect(ПОРТ_ВЛАДЕЛЬЦА).toBe(4780);
    expect(настоящие['сервер']['порт']).toBeUndefined();
  });

  it('принятое окно из принятой рабочей копии получает 4780 само, без всякой заявки', () => {
    const принят = принятый({
      испытательный: false, ветка: ВЕТКА_ПРИНЯТОГО, чисто: true, код: ПАПКА_ПРИНЯТОГО,
    });

    expect(принят).toBe(true);
    expect(выборПорта({принятый: принят, заявка: null})).toEqual({порт: ПОРТ_ВЛАДЕЛЬЦА});
    expect(выборПорта({принятый: принят, заявка: '   '})).toEqual({порт: ПОРТ_ВЛАДЕЛЬЦА});
  });

  it('принятость доказывается четырьмя фактами сразу: материалы, папка кода, ветка и чистота', () => {
    // Имя ветки одно ничего не доказывает: `editor` берётся в любую копию, а рядом с ним держат
    // свои правки. Каждый из четырёх фактов проверяется отдельно, чтобы ни один не выпал молча.
    expect(ВЕТКА_ПРИНЯТОГО).toBe('editor');
    expect(ПАПКА_ПРИНЯТОГО).toBe('C:/My_code/bimcore-blog/editor/.coordination/worktrees/accepted-editor/editor');

    const принятое = {испытательный: false, ветка: ВЕТКА_ПРИНЯТОГО, чисто: true, код: ПАПКА_ПРИНЯТОГО};

    expect(принятый(принятое)).toBe(true);
    expect(принятый({...принятое, испытательный: true})).toBe(false);
    expect(принятый({...принятое, ветка: 'fix/editor-runtime-ports'})).toBe(false);
    expect(принятый({...принятое, чисто: false})).toBe(false);
    expect(принятый({...принятое, код: 'C:/My_code/bimcore-blog/editor'})).toBe(false);
    // Версия кода неизвестна или чистоту спросить не удалось — порт владельца не выдаётся.
    expect(принятый({...принятое, ветка: null})).toBe(false);
    expect(принятый({...принятое, чисто: undefined})).toBe(false);
  });

  it('та же папка, названная иначе по-виндовому, остаётся принятой рабочей копией', () => {
    const принятое = {испытательный: false, ветка: ВЕТКА_ПРИНЯТОГО, чисто: true};

    expect(принятый({...принятое, код: ПАПКА_ПРИНЯТОГО.split('/').join('\\')})).toBe(true);
    expect(принятый({...принятое, код: ПАПКА_ПРИНЯТОГО.toUpperCase()})).toBe(true);
    expect(принятый({...принятое, код: `${ПАПКА_ПРИНЯТОГО}/`})).toBe(true);
    // А соседняя папка с похожим именем принятой не становится.
    expect(принятый({...принятое, код: `${ПАПКА_ПРИНЯТОГО}-копия`})).toBe(false);
  });
});

describe('любой другой экземпляр называет свой порт явно', () => {
  it('без явного порта такой запуск не поднимается вовсе, а не занимает 4780', () => {
    expect(выборПорта({принятый: false, заявка: null})).toEqual({отказ: НЕТ_ПОРТА, значение: ''});
    expect(выборПорта({принятый: false, заявка: ''})).toEqual({отказ: НЕТ_ПОРТА, значение: ''});
  });

  it('явный свободный порт принимается и становится адресом экземпляра', () => {
    expect(выборПорта({принятый: false, заявка: '4791'})).toEqual({порт: 4791});
    expect(выборПорта({принятый: false, заявка: ' 4791 '})).toEqual({порт: 4791});
  });

  it('годится любой номер в границах портов, включая соседние по цифрам с 4780', () => {
    // Предохранитель от возврата дефекта: побочный порт горячей перезагрузки выводился формулой
    // из главного, и `4780`, `14780` и `24780` сходились в один номер — испытание на `24780`
    // рядом с обычным окном было невозможно. Теперь побочного порта нет вовсе (SPEC 7.1.6).
    for (const заявка of ['1', '4779', '4781', '14780', '24780', '24678', '65535']) {
      expect(выборПорта({принятый: false, заявка})).toEqual({порт: Number(заявка)});
    }
  });

  it('4780 не отдаётся непринятому экземпляру даже по явной заявке', () => {
    expect(выборПорта({принятый: false, заявка: '4780'})).toEqual({отказ: ЧУЖОЙ_ПОРТ, значение: '4780'});
  });

  it('не число, не целое и вне предела портов — отказ, а не молчаливое умолчание', () => {
    for (const заявка of ['abc', '4791abc', '0x10', '47.91', '-1', '0', '65536', '99999']) {
      expect(выборПорта({принятый: false, заявка})['отказ']).toBe(НЕВЕРНЫЙ_ПОРТ);
    }
  });

  it('переключатель порта — переменная среды на один запуск, а не строка в настройках', () => {
    expect(ПОРТ_ЗАПУСКА).toBe('EDITOR_PORT');

    const server = fs.readFileSync(path.join(EDITOR, 'server.mjs'), 'utf8');
    expect(server).toContain('заявка: process.env[ПОРТ_ЗАПУСКА]');
    expect(server).not.toContain("readSettings()['сервер']['порт']");
  });
});

describe('опознание — один источник фактов о запущенном экземпляре', () => {
  it('обычное принятое окно называет роль, версию кода, папку материалов и адрес', async () => {
    const о = await запуск(ДОМА, ВЕТКА_ПРИНЯТОГО, null);

    expect(о).toEqual({
      role: РОЛЬ_ОБЫЧНАЯ,
      accepted: true,
      branch: ВЕТКА_ПРИНЯТОГО,
      commit: '1234abc',
      clean: true,
      code: ПРИНЯТАЯ_КОПИЯ,
      materials: 'C:\\My_code\\bimcore-blog',
      port: 4780,
      pid: process.pid,
      url: 'http://localhost:4780',
    });
  });

  it('несохранённые правки в дереве кода видны признаком чистоты и снимают принятость', async () => {
    const о = await запуск(ДОМА, ВЕТКА_ПРИНЯТОГО, '4791', {хвосты: ' M editor/server.mjs'});

    expect(о['clean']).toBe(false);
    expect(о['accepted']).toBe(false);
    // Ветка и номер коммита при этом прежние — на них одних дефект было не увидеть.
    expect(о['branch']).toBe(ВЕТКА_ПРИНЯТОГО);
    expect(о['commit']).toBe('1234abc');
  });

  it('чужая копия с той же чистой веткой editor принятой не становится', async () => {
    const о = await запуск(ДОМА, ВЕТКА_ПРИНЯТОГО, '4791', {код: 'C:\\копия\\editor'});

    expect(о['branch']).toBe(ВЕТКА_ПРИНЯТОГО);
    expect(о['clean']).toBe(true);
    expect(о['accepted']).toBe(false);
    expect(о['code']).toBe('C:\\копия\\editor');
  });

  it('испытательный корень виден в опознании ролью и своей папкой материалов', async () => {
    const о = await запуск(ЧУЖОЕ, ВЕТКА_ПРИНЯТОГО, '4791');

    expect(о['role']).toBe(РОЛЬ_ИСПЫТАТЕЛЬНАЯ);
    expect(о['accepted']).toBe(false);
    expect(о['materials']).toBe('D:\\site');
    expect(о['url']).toBe('http://localhost:4791');
  });

  it('код не с принятой ветки виден в опознании версией и признаком «не принят»', async () => {
    const о = await запуск(ДОМА, 'fix/editor-runtime-ports', '4791');

    // Ложная личность: роль обычная и материалы настоящие, но открывать такое окно ярлыком нельзя.
    expect(о['role']).toBe(РОЛЬ_ОБЫЧНАЯ);
    expect(о['materials']).toBe('C:\\My_code\\bimcore-blog');
    expect(о['accepted']).toBe(false);
    expect(о['branch']).toBe('fix/editor-runtime-ports');
  });

  it('версия кода неизвестна — обе её части пусты, и экземпляр принятым не считается', async () => {
    const о = await запуск(ДОМА, null, '4791');

    expect(о['branch']).toBe(null);
    expect(о['commit']).toBe(null);
    expect(о['clean']).toBe(false);
    expect(о['accepted']).toBe(false);
  });

  it('опознание собрано без диска: поля называют то, что подано, и ничего не досочиняют', () => {
    expect(опознание({
      корень: ПАПКА_ВЛАДЕЛЬЦА, испытательный: false, ветка: ВЕТКА_ПРИНЯТОГО,
      коммит: 'abcdef1', чисто: true, код: ПАПКА_ПРИНЯТОГО, порт: 4780, номер: 777,
    })).toEqual({
      role: РОЛЬ_ОБЫЧНАЯ, accepted: true, branch: ВЕТКА_ПРИНЯТОГО, commit: 'abcdef1', clean: true,
      code: ПАПКА_ПРИНЯТОГО, materials: ПАПКА_ВЛАДЕЛЬЦА, port: 4780, pid: 777,
      url: 'http://localhost:4780',
    });
  });
});

describe('отказ по порту — слова из настроек, а не код правила', () => {
  it('непринятый запуск без порта получает совет назвать порт', async () => {
    expect(await отказом(ДОМА, 'fix/editor-runtime-ports', null)).toBe(слова[НЕТ_ПОРТА]);
    expect(await отказом(ЧУЖОЕ, ВЕТКА_ПРИНЯТОГО, null)).toBe(слова[НЕТ_ПОРТА]);
  });

  it('заявка на 4780 и неверный номер называются вместе с самим значением', async () => {
    expect(await отказом(ЧУЖОЕ, ВЕТКА_ПРИНЯТОГО, '4780')).toBe(`${слова[ЧУЖОЙ_ПОРТ]}: 4780`);
    expect(await отказом(ЧУЖОЕ, ВЕТКА_ПРИНЯТОГО, 'абв')).toBe(`${слова[НЕВЕРНЫЙ_ПОРТ]}: абв`);
  });

  it('у каждого кода отказа по порту есть свои слова в настоящих настройках', () => {
    for (const код of [НЕТ_ПОРТА, ЧУЖОЙ_ПОРТ, НЕВЕРНЫЙ_ПОРТ, 'занят']) {
      expect(настоящие['материалы']['порт'][код]).toBeTruthy();
    }
  });
});

describe('работающий сервер отдаёт опознание только на чтение', () => {
  it('ручка /api/identity отвечает тем же опознанием и ничего не меняет', () => {
    // Предохранитель от возврата дефекта (SPEC 5.2.1): поведение старта тестом не отыграть — он
    // поднимает порт и Vite, — а вернуть сервер, который отвечает ярлыку «жив» и молчит о себе,
    // очень легко. Живая проба ручки — в handoff операции.
    const server = fs.readFileSync(path.join(EDITOR, 'server.mjs'), 'utf8');

    expect(server).toContain("url.pathname === '/api/identity'");
    expect(server).toContain('send(res, 200, ОПОЗНАНИЕ)');
    // Второго описания «кто я» в сервере нет: ручка отдаёт ровно тот объект, что напечатан строками
    // запуска. Разойдись они — окно называло бы себя одним, а ярлыку отвечало другим.
    expect(server.match(/let ОПОЗНАНИЕ;/g)).toHaveLength(1);
    expect(server).toContain('опознание: ОПОЗНАНИЕ');
  });

  it('порт занят другой программой — сервер говорит об этом словами, а не стеком', () => {
    const server = fs.readFileSync(path.join(EDITOR, 'server.mjs'), 'utf8');

    expect(server).toContain("error?.code !== 'EADDRINUSE'");
    expect(server).toContain("readSettings()['материалы']['порт']['занят']");
  });

  it('у экземпляра ровно один порт: горячая перезагрузка живёт на нём же, второго номера нет', () => {
    // Предохранитель от возврата дефекта (SPEC 5.2.1): побочный порт выводился из главного формулой,
    // и разные главные порты сходились в один побочный. Поведение здесь — живая проба двух
    // экземпляров сразу (handoff операции); тестом ловится возвращение самой формулы.
    const server = fs.readFileSync(path.join(EDITOR, 'server.mjs'), 'utf8');

    expect(server).toContain('hmr: {server: сервер}');
    expect(server).not.toMatch(/hmr:\s*\{port/);
    expect(server).not.toContain('20000 +');
  });
});
