// Имя каждого теста повторяет формулировку правила.
// Удаление статьи: режим выбирает программа — корзина для опубликованного и неизвестного,
// с 2026-09-18 режим один — корзина, и причина нужна только для слов человеку.
import {describe, expect, it} from 'vitest';
import {решениеОбУдалении} from '../src/core/deleteArticle.mjs';

const RU = {
  path: 'i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba/index.mdx',
  состояние: 'i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba/_state.json',
  папка: 'i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba',
  локаль: 'ru',
  наСайте: true,
  опубликована: false,
  былаОпубликована: false,
  служебная: false,
  своя: true,
};

const EN = {
  path: 'docs/lessons/proba/index.mdx',
  состояние: null,
  папка: 'docs/lessons/proba',
  локаль: 'en',
  наСайте: true,
  опубликована: false,
  былаОпубликована: false,
  служебная: false,
  своя: true,
};

const решение = (правки = {}) => решениеОбУдалении({веткаИзвестна: true, версии: [RU, EN], ...правки});

describe('режим удаления', () => {
  it('ни одна версия никогда не выходила на сайт — всё равно корзина, все версии сразу', () => {
    expect(решение()).toMatchObject({режим: 'корзина', причина: 'неОпубликована', пути: [RU.path, EN.path], языки: ['ru', 'en']});
  });

  it('хотя бы одна версия сейчас на сайте — корзина', () => {
    expect(решение({версии: [RU, {...EN, опубликована: true}]})).toMatchObject({режим: 'корзина', причина: 'опубликована'});
  });

  it('версия когда-то была на сайте, хоть сейчас её в ветке нет, — корзина: адрес у неё уже был', () => {
    expect(решение({версии: [{...RU, былаОпубликована: true}, EN]})).toMatchObject({режим: 'корзина', причина: 'опубликована'});
  });

  it('опубликованную ветку прочитать не удалось — корзина, а не отказ и не стирание', () => {
    expect(решение({веткаИзвестна: false})).toMatchObject({режим: 'корзина', причина: 'неизвестно'});
  });

  it('историю ветки прочитать не удалось — тоже корзина', () => {
    expect(решение({версии: [{...RU, былаОпубликована: null}, EN]})).toMatchObject({режим: 'корзина', причина: 'неизвестно'});
  });

  it('песочница живёт вне сайта: причина «не публиковалась», но уходит она тоже в корзину', () => {
    const проба = {...RU, path: 'editor/sandbox/proba/index.mdx', папка: 'editor/sandbox/proba', наСайте: false, былаОпубликована: null};
    expect(решение({веткаИзвестна: false, версии: [проба]})).toMatchObject({режим: 'корзина', причина: 'неОпубликована'});
  });
});

describe('что уходит вместе со статьёй', () => {
  it('файл состояния уходит, отсутствующий в список не попадает', () => {
    expect(решение().файлы).toEqual([RU.path, RU.состояние, EN.path]);
  });

  it('своя папка статьи уходит: в ней лежали только её картинки', () => {
    expect(решение().папки).toEqual([RU.папка, EN.папка]);
  });

  it('общая папка со статьёй-файлом не уходит: соседи и общие картинки остаются', () => {
    const блог = {...RU, path: 'blog/2024-post.mdx', состояние: 'blog/_2024-post.state.json', папка: 'blog', своя: false};
    expect(решение({версии: [блог]})).toMatchObject({папки: [], файлы: ['blog/2024-post.mdx', 'blog/_2024-post.state.json']});
  });

  it('страница раздела не удаляется ни в каком режиме: под ней лежат другие статьи', () => {
    expect(решение({версии: [{...RU, служебная: true, опубликована: true}, EN]})).toEqual({ошибка: 'страницаРаздела'});
  });

  it('статьи нет вовсе — удалять нечего', () => {
    expect(решение({версии: []})).toEqual({ошибка: 'нетСтатьи'});
  });
});
