// Имя каждого теста повторяет формулировку правила.
// Удаление статьи: что можно стирать, что нельзя и что уходит вместе со статьёй.
import {describe, expect, it} from 'vitest';
import {решениеОбУдалении} from '../src/core/deleteArticle.mjs';

const RU = {
  path: 'i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba/index.mdx',
  состояние: 'i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba/_state.json',
  папка: 'i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba',
  наСайте: true,
  опубликована: false,
  служебная: false,
  соседи: 1,
};

const EN = {
  path: 'docs/lessons/proba/index.mdx',
  состояние: null,
  папка: 'docs/lessons/proba',
  наСайте: true,
  опубликована: false,
  служебная: false,
  соседи: 1,
};

const решение = (правки = {}) => решениеОбУдалении({веткаИзвестна: true, версии: [RU, EN], ...правки});

describe('что можно удалить', () => {
  it('ни одной версии нет на сайте — удаляются все версии сразу', () => {
    // Статья одна, языковые версии — её части: оставить половину значит оставить статью-калеку.
    expect(решение().пути).toEqual([RU.path, EN.path]);
  });

  it('вместе со статьёй уходит её файл состояния', () => {
    expect(решение().файлы).toContain(RU.состояние);
  });

  it('файла состояния нет — в список удаления он не попадает', () => {
    expect(решение().файлы.filter((файл) => файл === null)).toEqual([]);
  });

  it('папки статей уходят вместе с ними: в них лежали только их картинки', () => {
    expect(решение().папки).toEqual([RU.папка, EN.папка]);
  });

  it('хотя бы одна версия уже на сайте — не удаляется ничего', () => {
    // Удалить публичный адрес без переадресации нельзя (SPEC 2.5): это отдельное задание.
    const итог = решение({версии: [RU, {...EN, опубликована: true}]});

    expect(итог.ошибка).toBe('ужеНаСайте');
    expect(итог.файлы).toBeUndefined();
  });

  it('опубликованную ветку прочитать не удалось — удаление не идёт вовсе', () => {
    // «Не знаю» значит «может быть на сайте». Сбой git не должен выдавать живую статью
    // за неопубликованную.
    expect(решение({веткаИзвестна: false}).ошибка).toBe('ветканеизвестна');
  });

  it('песочница удаляется и без опубликованной ветки: сайта она не касается', () => {
    const проба = {...RU, наСайте: false, папка: 'editor/sandbox/proba', path: 'editor/sandbox/proba/index.mdx'};

    expect(решениеОбУдалении({веткаИзвестна: false, версии: [проба]}).пути).toEqual([проба.path]);
  });

  it('страница раздела не удаляется: под ней лежат другие статьи', () => {
    expect(решение({версии: [{...RU, служебная: true}, EN]}).ошибка).toBe('страницаРаздела');
  });

  it('в папке статьи лежит ещё одна статья — отказ, а не угадывание', () => {
    // Картинки и файл состояния там общие, разделить их нечем.
    expect(решение({версии: [{...RU, соседи: 2}, EN]}).ошибка).toBe('папкаНеОдна');
  });

  it('статьи нет вовсе — удалять нечего', () => {
    expect(решениеОбУдалении({веткаИзвестна: true, версии: []}).ошибка).toBe('нетСтатьи');
  });
});
