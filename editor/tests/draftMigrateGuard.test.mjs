// Имя каждого теста повторяет формулировку правила.
// Две гарантии переноса: черновик узнаётся по СТАТЬЕ, а не по имени файла, и беда чтения старого
// хранилища не выдаётся за отсутствие работы (SPEC 7.1.5).
import {afterEach, describe, expect, it} from 'vitest';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

import {перенестиХранилище} from '../src/adapters/draftMigrate.mjs';
import {loadDraft, saveDraft} from '../src/adapters/draftStore.mjs';
import {draftName, newDraft, writeDraft, староеИмяЧерновика} from '../src/core/drafts.mjs';

const REL = 'i18n/ru/docusaurus-plugin-content-docs/current/beds-for-revit/index.mdx';
const НАСТРОЙКИ = {
  хранение: {
    папкаЧерновиков: '.drafts', папкаСпоров: '.drafts-споры', папкаСнимков: '.history', снимковНаВерсию: 50,
  },
  материалы: {отказы: {переносЧтение: 'Не удалось прочитать старое хранилище черновиков'}},
  ошибкиСервера: {споренЧерновик: 'Разные старые черновики. Папка {папка}'},
};

const песочницы = [];
function песочница(имя) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), имя));
  песочницы.push(dir);
  return dir;
}

afterEach(() => {
  while (песочницы.length > 0) fs.rmSync(песочницы.pop(), {recursive: true, force: true});
});

const среда = () => ({корень: песочница('editor-repo-'), код: песочница('editor-code-')});
const запись = (тело) => writeDraft(newDraft({
  path: REL, frontmatterRaw: 'title: Кровати', body: тело, отпечатокБазы: 'ОТП', когда: '2026-09-07T22:28:28.000Z',
}));

/** Положить готовую запись черновика под точным именем: так пишут обе схемы имён программы. */
function положить(база, папка, имя, текст) {
  const dir = path.join(база, папка);
  fs.mkdirSync(dir, {recursive: true});
  fs.writeFileSync(path.join(dir, имя), текст, 'utf8');
}

const перенос = (с, диск = fs) => перенестиХранилище({
  repo: с.корень, кодDir: с.код, settings: НАСТРОЙКИ, диск,
});
const вХранилище = (с, папка) => {
  const dir = path.join(с.корень, 'editor', папка);
  return fs.existsSync(dir) ? fs.readdirSync(dir).sort() : [];
};
const черновики = (с) => вХранилище(с, НАСТРОЙКИ['хранение']['папкаЧерновиков']);
const споры = (с) => вХранилище(с, НАСТРОЙКИ['хранение']['папкаСпоров']);

describe('две схемы имён — один черновик статьи', () => {
  it('та же работа под прежним именем не удваивается: решает статья, а не имя файла', () => {
    const с = среда();
    const текст = запись('незавершённый текст владельца');
    положить(с.корень, path.join('editor', '.drafts'), draftName(REL), текст);
    положить(с.код, '.drafts', староеИмяЧерновика(REL), текст);

    const отчёт = перенос(с);

    expect([отчёт['черновиков'], отчёт['споров']]).toEqual([0, 0]);
    expect(черновики(с)).toEqual([draftName(REL)]);
    expect(споры(с)).toEqual([]);
  });

  it('разные тексты одной статьи под разными схемами имён — спор, а не второй черновик', () => {
    const с = среда();
    положить(с.корень, path.join('editor', '.drafts'), draftName(REL), запись('работа общего хранилища'));
    положить(с.код, '.drafts', староеИмяЧерновика(REL), запись('другая незаписанная работа'));

    const отчёт = перенос(с);

    expect(отчёт['споров']).toBe(1);
    // Обе версии целы: выбранная лежит в хранилище, отложенная — рядом отдельным вариантом.
    expect(черновики(с)).toEqual([draftName(REL)]);
    expect(loadDraft(с.корень, НАСТРОЙКИ, REL)['body']).toBe('работа общего хранилища');
    expect(споры(с)).toHaveLength(1);
    const вариант = fs.readFileSync(path.join(с.корень, 'editor', '.drafts-споры', споры(с)[0]), 'utf8');
    expect(вариант).toContain('другая незаписанная работа');
  });

  it('спор о черновике прежней схемы имён запирает запись этой статьи', () => {
    const с = среда();
    положить(с.корень, path.join('editor', '.drafts'), draftName(REL), запись('работа общего хранилища'));
    положить(с.код, '.drafts', староеИмяЧерновика(REL), запись('другая незаписанная работа'));
    перенос(с);

    const писать = () => saveDraft(с.корень, НАСТРОЙКИ, newDraft({
      path: REL, frontmatterRaw: 'title: Кровати', body: 'поверх спора', отпечатокБазы: 'ОТП',
      когда: '2026-09-08T10:00:00.000Z',
    }));

    expect(писать).toThrow(/Разные старые черновики/);
  });

  it('повтор при разных схемах имён ничего не добавляет, но спор называет снова', () => {
    const с = среда();
    положить(с.корень, path.join('editor', '.drafts'), draftName(REL), запись('работа общего хранилища'));
    положить(с.код, '.drafts', староеИмяЧерновика(REL), запись('другая незаписанная работа'));
    перенос(с);
    const было = споры(с);

    const второй = перенос(с);

    expect(второй['споров']).toBe(1);
    expect(споры(с)).toEqual(было);
  });

  it('черновик прежней схемы ложится в общее хранилище под нынешним именем', () => {
    const с = среда();
    положить(с.код, '.drafts', староеИмяЧерновика(REL), запись('незавершённый текст владельца'));

    const отчёт = перенос(с);

    expect(отчёт['черновиков']).toBe(1);
    expect(черновики(с)).toEqual([draftName(REL)]);
    expect(loadDraft(с.корень, НАСТРОЙКИ, REL)['body']).toBe('незавершённый текст владельца');
    expect(перенос(с)['черновиков']).toBe(0);
  });
});

describe('беда чтения старого хранилища', () => {
  /** Подмена чтения: настоящий диск, но названный путь отвечает бедой. Надёжнее прав доступа. */
  const сломанныйДиск = (жертва, код, дверь) => ({
    ...fs,
    [дверь]: (путь, ...прочее) => {
      if (path.resolve(String(путь)) === path.resolve(жертва)) {
        throw Object.assign(new Error(`${код}: доступ`), {code: код, path: жертва});
      }
      return fs[дверь](путь, ...прочее);
    },
  });

  it('нечитаемая папка старого хранилища останавливает перенос понятной ошибкой', () => {
    const с = среда();
    положить(с.код, '.drafts', draftName(REL), запись('незавершённый текст владельца'));
    const жертва = path.join(с.код, '.drafts');

    const ход = () => перенос(с, сломанныйДиск(жертва, 'EACCES', 'readdirSync'));

    expect(ход).toThrow(/Не удалось прочитать старое хранилище черновиков/);
    expect(ход).toThrow(new RegExp(жертва.replace(/[\\.]/g, '\\$&')));
    // Молчаливого «данных нет» не случилось: в общее хранилище ничего не легло.
    expect(черновики(с)).toEqual([]);
  });

  it('нечитаемый файл старого хранилища останавливает перенос понятной ошибкой', () => {
    const с = среда();
    положить(с.код, '.drafts', draftName(REL), запись('незавершённый текст владельца'));
    const жертва = path.join(с.код, '.drafts', draftName(REL));

    const ход = () => перенос(с, сломанныйДиск(жертва, 'EBUSY', 'readFileSync'));

    expect(ход).toThrow(/Не удалось прочитать старое хранилище черновиков/);
    expect(ход).toThrow(/EBUSY/);
    expect(черновики(с)).toEqual([]);
  });

  it('нечитаемая папка истории останавливает перенос так же, как папка черновиков', () => {
    const с = среда();
    положить(с.код, path.join('.history', 'какая-то-версия'), '2026-09-06T10-00-00-000Z__Хозяин.mdx', 'состояние');
    const жертва = path.join(с.код, '.history');

    const ход = () => перенос(с, сломанныйДиск(жертва, 'EPERM', 'readdirSync'));

    expect(ход).toThrow(/Не удалось прочитать старое хранилище черновиков/);
  });

  it('старого хранилища нет вовсе — это не беда, а отсутствие работы', () => {
    const с = среда();

    const отчёт = перенос(с);

    expect([отчёт['перенос'], отчёт['черновиков'], отчёт['снимков']]).toEqual([true, 0, 0]);
  });
});

describe('порядок запуска', () => {
  const server = fs.readFileSync(
    path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'server.mjs'), 'utf8',
  );

  it('перенос идёт до открытия сервера: иначе окно писало бы мимо неперенесённой работы', () => {
    expect(server.indexOf('перенестиХранилище(')).toBeGreaterThan(-1);
    expect(server.indexOf('перенестиХранилище(')).toBeLessThan(server.indexOf('.listen('));
  });

  it('сорвался перенос — сервер не поднимается и говорит причину словами', () => {
    const кусок = server.slice(server.indexOf('перенестиХранилище('), server.indexOf('.listen('));

    expect(кусок).toContain('console.error(error.message)');
    expect(кусок).toContain('process.exit(1)');
  });
});
