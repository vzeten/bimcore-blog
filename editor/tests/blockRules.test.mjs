// Имя каждого теста повторяет формулировку правила.
// Блоки внутри текста статьи глазами подготовки: о чём она говорит и о чём молчит.
import {describe, expect, it} from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {блокиТела, пустыеПоляБлоков} from '../src/core/blockRules.mjs';
import {проверитьМестные} from '../src/core/prepare.mjs';

const EDITOR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const НАСТРОЙКИ = JSON.parse(fs.readFileSync(path.join(EDITOR, 'settings.json'), 'utf8'));
const БЛОКИ = НАСТРОЙКИ['блоки'];

const RU = 'i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba/index.mdx';
const EN = 'docs/lessons/proba/index.mdx';
const НОМЕР = 'ifJtfM3LgGg';

const ЦЕЛОЕ = `<YouTube id="${НОМЕР}" title="Урок" uploadDate="2026-08-01" duration="330" />`;

const коды = (находки) => находки.map((находка) => находка.код);

describe('пустые поля известных блоков в теле статьи', () => {
  it('заполненный блок видео молчит: говорить о нём нечего', () => {
    expect(пустыеПоляБлоков(`Текст.\n\n${ЦЕЛОЕ}\n`, БЛОКИ)).toEqual([]);
  });

  it('видео без номера останавливает выпуск: на сайте его не будет вовсе', () => {
    const беды = пустыеПоляБлоков(`<YouTube id="" title="Урок" uploadDate="2026-08-01" duration="330" />`, БЛОКИ);

    expect(беды).toHaveLength(1);
    expect(беды[0]).toMatchObject({блок: 'YouTube', поле: 'id', уровень: 'блокер'});
  });

  it('свойства нет вовсе — это то же самое, что пустое: молчать нельзя', () => {
    const поля = пустыеПоляБлоков('<YouTube />', БЛОКИ).map((беда) => беда.поле);

    expect(поля).toContain('id');
    expect(поля).toContain('title');
    expect(поля).toContain('uploadDate');
    expect(поля).toContain('duration');
  });

  it('название, дата и длительность только предупреждают: сайт от них не ломается', () => {
    const беды = пустыеПоляБлоков(`<YouTube id="${НОМЕР}" />`, БЛОКИ);

    expect(беды.every((беда) => беда.поле === 'id' || беда.уровень === 'предупреждение')).toBe(true);
    expect(беды.some((беда) => беда.поле === 'id')).toBe(false);
  });

  it('описание не спрашивается вовсе: обязательным его никто не объявлял', () => {
    const поля = пустыеПоляБлоков('<YouTube />', БЛОКИ).map((беда) => беда.поле);

    expect(поля).not.toContain('description');
  });

  it('называется строка файла: «где-то в статье» человеку искать негде', () => {
    const тело = `Первая строка.\n\nВторая строка.\n\n<YouTube id="" />\n`;

    expect(пустыеПоляБлоков(тело, БЛОКИ)[0].строка).toBe(5);
  });

  it('незнакомый тег не трогается вовсе: программа его не понимает и потому о нём молчит', () => {
    expect(пустыеПоляБлоков('<Карусель items="" />', БЛОКИ)).toEqual([]);
  });

  it('блок без обязательных полей молчит: у границы анонса заполнять нечего', () => {
    expect(пустыеПоляБлоков('<truncate />\n<CTA type="guide" />', БЛОКИ)).toEqual([]);
  });

  it('каждое пустое видео говорит о себе само: два блока — две находки', () => {
    const тело = `<YouTube id="" title="А" uploadDate="2026-08-01" duration="10" />\n\n<YouTube id="" title="Б" uploadDate="2026-08-01" duration="10" />`;

    expect(пустыеПоляБлоков(тело, БЛОКИ)).toHaveLength(2);
  });

  it('тега в теле нет — правило ничего не находит и не падает на пустом теле', () => {
    expect(пустыеПоляБлоков('', БЛОКИ)).toEqual([]);
    expect(пустыеПоляБлоков(undefined, БЛОКИ)).toEqual([]);
  });

  it('реестра блоков в настройках нет — правило молчит, а не падает стеком', () => {
    expect(пустыеПоляБлоков('<YouTube />', undefined)).toEqual([]);
  });
});

describe('находка правила: этап, путь и слова человеку', () => {
  const версия = (тело) => ({путь: RU, тело});

  it('находка называет этап, файл и поле — по ним человек найдёт место сам', () => {
    const [находка] = блокиТела({версии: [версия('<YouTube />')], settings: НАСТРОЙКИ, этап: 'блокиТела'});

    expect(находка).toMatchObject({этап: 'блокиТела', путь: RU, поле: 'id', уровень: 'блокер'});
  });

  it('у каждого кода находки есть слова человеку в настройках', () => {
    const находки = блокиТела({версии: [версия('<YouTube />')], settings: НАСТРОЙКИ, этап: 'блокиТела'});

    for (const находка of находки) {
      expect(НАСТРОЙКИ['подготовка']['находки'][находка.код], находка.код).toBeTruthy();
    }
  });

  it('у этапа есть своя подпись: человеку показывают слова, а не код', () => {
    expect(НАСТРОЙКИ['подготовка']['этапы']['блокиТела']).toBeTruthy();
  });
});

describe('подготовка статьи целиком видит блоки её тела', () => {
  const снимок = (телоRU) => [
    {путь: RU, содержимое: `---\ntitle: "Проба"\nslug: /lessons/proba\ndescription: "Про пробу"\nkeywords: [розетки]\n---\n\n${телоRU}\n`},
    {путь: EN, содержимое: '---\ntitle: "Proba"\nslug: /lessons/proba\ndescription: "About proba"\nunlisted: true\n---\n\nText.\n'},
  ];

  it('видео без номера не даёт статье уйти на сайт молча', () => {
    const находки = проверитьМестные(снимок('<YouTube id="" title="Урок" />'), 'урок', НАСТРОЙКИ);

    expect(коды(находки)).toContain('блок:пустоОбязательное');
  });

  it('заполненное видео подготовке не мешает', () => {
    const находки = проверитьМестные(снимок(ЦЕЛОЕ), 'урок', НАСТРОЙКИ);

    expect(коды(находки).filter((код) => код.startsWith('блок:'))).toEqual([]);
  });

  it('статья без единого блока проверку блоков проходит молча', () => {
    const находки = проверитьМестные(снимок('Обычный текст статьи.'), 'урок', НАСТРОЙКИ);

    expect(коды(находки).some((код) => код.startsWith('блок:'))).toBe(false);
  });
});
