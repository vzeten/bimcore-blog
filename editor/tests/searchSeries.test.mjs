// Поиск Google для окна аналитики (ED-054, операция 2): ряды, охват, неполные дни, страницы 30/30.
import {describe, expect, it} from 'vitest';
import {путьСтраницы, языкСтраницы, вОхвате, началоШага, последнийПолный, ряд, страницы, сдвиг} from '../src/core/searchSeries.mjs';

const сайт = {языки: ['en', 'ru', 'es'], обязательный: 'en'};
const с = (день, страница, показы, переходы = 0, позиция = 5, неполный = 0) =>
  ({день, страница: `https://learn.bimcore.one${страница}`, показы, переходы, позиция, неполный});

describe('страница и охват', () => {
  it('путь без хоста и косой; язык по префиксу; охват сайта, языка и страницы', () => {
    expect(путьСтраницы('https://learn.bimcore.one/ru/blog/x/')).toBe('/ru/blog/x');
    expect(путьСтраницы('https://learn.bimcore.one/')).toBe('/');
    expect(языкСтраницы('/ru/blog/x', сайт.языки, 'en')).toBe('ru');
    expect(языкСтраницы('/lessons/a', сайт.языки, 'en')).toBe('en');
    expect(языкСтраницы('/russia', сайт.языки, 'en')).toBe('en');
    const строка = с('2026-09-01', '/es/lessons/a/', 1);
    expect(вОхвате(строка, 'сайт', сайт)).toBe(true);
    expect(вОхвате(строка, 'es', сайт)).toBe(true);
    expect(вОхвате(строка, 'ru', сайт)).toBe(false);
    expect(вОхвате(строка, {страница: '/es/lessons/a/'}, сайт)).toBe(true);
    expect(вОхвате(строка, {страница: '/lessons/a'}, сайт)).toBe(false);
  });
});

describe('ряды', () => {
  it('неделя с понедельника, месяц с первого числа', () => {
    expect(началоШага('2026-09-24', 'неделя')).toBe('2026-09-21');
    expect(началоШага('2026-09-21', 'неделя')).toBe('2026-09-21');
    expect(началоШага('2026-09-20', 'неделя')).toBe('2026-09-14');
    expect(началоШага('2026-09-24', 'месяц')).toBe('2026-09-01');
  });

  it('пустые шаги — нули, без пропусков; позиция средняя по показам; охват языка', () => {
    const строки = [с('2026-09-01', '/a/', 10, 1, 4), с('2026-09-02', '/a/', 30, 2, 8), с('2026-09-15', '/ru/a/', 5, 1, 2)];
    const недели = ряд(строки, {охват: 'сайт', шаг: 'неделя', с: '2026-08-31', по: '2026-09-20', сайт});
    expect(недели.map((т) => [т.начало, т.показы, т.переходы])).toEqual([['2026-08-31', 40, 3], ['2026-09-07', 0, 0], ['2026-09-14', 5, 1]]);
    expect(недели[0].позиция).toBe(7);
    // Части по языкам в сумме дают ровно столбик.
    expect(недели[0].языки).toEqual({en: {показы: 40, переходы: 3}});
    expect(недели[2].языки).toEqual({ru: {показы: 5, переходы: 1}});
    for (const т of недели) {
      expect(Object.values(т.языки).reduce((с, я) => с + я.показы, 0)).toBe(т.показы);
    }
    expect(недели[1].позиция).toBeNull();
    const русский = ряд(строки, {охват: 'ru', шаг: 'месяц', с: '2026-08-01', по: '2026-09-30', сайт});
    expect(русский.map((т) => [т.начало, т.показы])).toEqual([['2026-08-01', 0], ['2026-09-01', 5]]);
  });

  it('месяцы идут через границу года', () => {
    const месяцы = ряд([], {охват: 'сайт', шаг: 'месяц', с: '2025-11-10', по: '2026-02-01', сайт});
    expect(месяцы.map((т) => т.начало)).toEqual(['2025-11-01', '2025-12-01', '2026-01-01', '2026-02-01']);
  });

  it('неполный день помечает свой шаг и шаг, кончающийся позже последнего полного дня', () => {
    const строки = [с('2026-09-20', '/a/', 1), с('2026-09-22', '/a/', 1, 0, 5, 1), с('2026-09-23', '/a/', 1, 0, 5, 1)];
    expect(последнийПолный(строки)).toBe('2026-09-20');
    const дни = ряд(строки, {охват: 'сайт', шаг: 'день', с: '2026-09-20', по: '2026-09-23', сайт});
    expect(дни.map((т) => т.неполный)).toEqual([false, true, true, true]);
    const недели = ряд(строки, {охват: 'сайт', шаг: 'неделя', с: '2026-09-14', по: '2026-09-23', сайт});
    expect(недели.map((т) => т.неполный)).toEqual([false, true]);
  });
});

describe('страницы 30/30', () => {
  it('окно кончается последним полным днём; неполные дни не входят; разница в штуках', () => {
    const по = '2026-09-20';
    const строки = [
      с(по, '/a/', 10, 2, 3), с(сдвиг(по, -29), '/a/', 5, 1, 6), с(сдвиг(по, -30), '/a/', 40, 3), с(сдвиг(по, -60), '/a/', 999),
      с('2026-09-22', '/a/', 500, 50, 1, 1),
      с(по, '/ru/b/', 7),
    ];
    const итог = страницы(строки, {охват: 'сайт', сайт});
    expect(итог.по).toBe(по);
    const a = итог.страницы.find((стр) => стр.путь === '/a');
    expect(a).toEqual({путь: '/a', показы: 15, переходы: 3, ctr: 20, позиция: 4, разницаПоказов: -25, разницаПереходов: 0});
    expect(страницы(строки, {охват: 'ru', сайт}).страницы.map((стр) => стр.путь)).toEqual(['/ru/b']);
    expect(страницы([], {охват: 'сайт', сайт})).toEqual({по: null, страницы: []});
  });

  it('выбранный период сравнивается с предыдущим такой же длины: неделя с прошлой неделей', () => {
    const строки = [
      с('2026-08-10', '/a/', 10), с('2026-08-16', '/a/', 5), // выбранная неделя 10–16 авг.
      с('2026-08-03', '/a/', 4), с('2026-08-09', '/a/', 2), // прошлая неделя 3–9 авг.
      с('2026-08-02', '/a/', 100), с('2026-08-17', '/a/', 100), // вне обеих
      с('2026-09-20', '/a/', 1),
    ];
    const итог = страницы(строки, {охват: 'сайт', сайт, период: {с: '2026-08-10', по: '2026-08-16'}});
    expect(итог).toMatchObject({с: '2026-08-10', по: '2026-08-16'});
    expect(итог.страницы[0]).toMatchObject({путь: '/a', показы: 15, разницаПоказов: 9});
  });
});
