// Имя каждого теста повторяет формулировку правила.
// Видимость принадлежит языковой версии (SPEC 2.8): переключил в свойствах, нажал «Сохранить» —
// поменялось ТОЛЬКО в открытом файле. Соседние языковые версии сохранение не трогает ничем.
// Отдельной ручки видимости в программе нет.
// Обвязка — в `saveHarness.mjs`, общие правила записи файла — в `saveRoute.test.mjs`.
import {afterEach, describe, expect, it, vi} from 'vitest';
import fs from 'node:fs';
import path from 'node:path';

import {countSnapshots} from '../src/adapters/draftStore.mjs';
import {ЖДАТЬ_GIT, EN, ES, RU, НАСТРОЙКИ, подготовить, прочитать, сохранить, статья, убратьПесочницы} from './saveHarness.mjs';

// Проверки зовут настоящий git во временной папке; почему им нужен свой предел времени — в обвязке.
vi.setConfig({testTimeout: ЖДАТЬ_GIT, hookTimeout: ЖДАТЬ_GIT});

afterEach(() => {
  vi.restoreAllMocks();
  убратьПесочницы();
});

const состояниеСоседа = (среда, сосед) => path.join(среда.repo, path.dirname(сосед), '_state.json');

/**
 * Сохранение открытой версии под наблюдением за соседом. Байтового равенства файла мало:
 * файл можно переписать тем же содержимым, и проверка осталась бы зелёной. Поэтому здесь
 * собирается всё, чем сосед мог быть тронут, — запись по его пути, фиксация его внешней правки,
 * снимок в его истории, его файл состояния и сам файл.
 */
async function приСоседе(среда, сосед, запрос) {
  fs.writeFileSync(
    состояниеСоседа(среда, сосед),
    JSON.stringify({готовность: 'Готова к публикации', нити: []}),
    'utf8',
  );

  const былФайл = прочитать(среда, сосед);
  const былоСостояние = fs.readFileSync(состояниеСоседа(среда, сосед), 'utf8');
  const былоСнимков = countSnapshots(среда.editorDir, НАСТРОЙКИ, сосед);
  const папкаСоседа = path.join(среда.repo, path.dirname(сосед));

  const фиксации = [];
  const записи = [];
  const настоящая = fs.writeFileSync;
  vi.spyOn(fs, 'writeFileSync').mockImplementation((file, ...остальное) => {
    записи.push(String(file));
    return настоящая(file, ...остальное);
  });

  const ответ = await сохранить(среда, {
    ...запрос,
    фиксировать: async (rel) => {
      фиксации.push(rel);
    },
  });

  return {
    ответ,
    // Запись по пути соседа не вызывалась вовсе — ни файла, ни его состояния.
    записиКСоседу: записи.filter((file) => file.startsWith(папкаСоседа)),
    фиксацииСоседа: фиксации.filter((rel) => rel === сосед),
    приросСнимков: countSnapshots(среда.editorDir, НАСТРОЙКИ, сосед) - былоСнимков,
    состояниеПрежнее: fs.readFileSync(состояниеСоседа(среда, сосед), 'utf8') === былоСостояние,
    готовность: JSON.parse(fs.readFileSync(состояниеСоседа(среда, сосед), 'utf8'))['готовность'],
    файлПрежний: прочитать(среда, сосед) === былФайл,
  };
}

describe('видимость меняется обычным сохранением и только в открытой версии', () => {
  it('скрыл открытую версию — соседняя не тронута ничем: ни записью, ни фиксацией, ни историей, ни готовностью, ни байтом', async () => {
    // Сценарий владельца: русскую статью выпускают, английская заглушка «перевод пока не готов»
    // остаётся скрытой. Прежнее правило вытащило бы её в английское меню сайта.
    const среда = await подготовить({
      [RU]: статья('title: A'),
      [EN]: статья('title: A\nunlisted: true'),
    });

    const итог = await приСоседе(среда, EN, {rel: RU, шапка: 'title: A\nunlisted: true'});

    expect(итог.ответ.code).toBe(200);
    expect(прочитать(среда, RU)).toContain('unlisted: true');
    expect(итог.записиКСоседу).toEqual([]);
    expect(итог.фиксацииСоседа).toEqual([]);
    expect(итог.приросСнимков).toBe(0);
    expect(итог.состояниеПрежнее).toBe(true);
    expect(итог.готовность).toBe('Готова к публикации');
    expect(итог.файлПрежний).toBe(true);
  });

  it('открыл видимость у открытой версии — соседняя остаётся скрытой и не тронута ничем', async () => {
    // Второе направление обязательно: снятие скрытости с русской версии не снимает её с заглушки.
    const среда = await подготовить({
      [RU]: статья('title: A\nunlisted: true'),
      [EN]: статья('title: A\nunlisted: true'),
    });

    const итог = await приСоседе(среда, EN, {rel: RU, шапка: 'title: A'});

    expect(прочитать(среда, RU)).not.toContain('unlisted');
    expect(прочитать(среда, EN)).toContain('unlisted: true');
    expect(итог.записиКСоседу).toEqual([]);
    expect(итог.фиксацииСоседа).toEqual([]);
    expect(итог.приросСнимков).toBe(0);
    expect(итог.состояниеПрежнее).toBe(true);
    expect(итог.готовность).toBe('Готова к публикации');
    expect(итог.файлПрежний).toBe(true);
  });

  it('про соседние языковые версии ответ сохранения не говорит ничего: рассказывать нечего', async () => {
    // Поле `видимость` в ответе описывало переключение соседей. Механизма нет — нет и поля,
    // иначе окно продолжало бы ждать рассказ, которого не будет.
    const среда = await подготовить({[RU]: статья('title: A'), [EN]: статья('title: A')});

    const ответ = await сохранить(среда, {rel: RU, шапка: 'title: A\nunlisted: true'});

    expect(ответ.data['видимость']).toBeUndefined();
  });

  it('смешанная видимость — законное состояние: у трёх языков своя, и сохранение это не выравнивает', async () => {
    // Так уже живут три статьи сайта: русская версия в меню, английская скрыта.
    const среда = await подготовить({
      [RU]: статья('title: A'),
      [EN]: статья('title: A\nunlisted: true'),
      [ES]: статья('title: A'),
    });

    await сохранить(среда, {rel: RU, шапка: 'title: A\nunlisted: true'});

    expect(прочитать(среда, RU)).toContain('unlisted: true');
    expect(прочитать(среда, EN)).toContain('unlisted: true');
    expect(прочитать(среда, ES)).not.toContain('unlisted');
  });

  it('несуществующая языковая версия не создаётся: сохранение пишет ровно один открытый файл', async () => {
    // Испанской версии у новых статей нет вовсе, и это нормальное состояние сайта.
    const среда = await подготовить({[RU]: статья('title: A'), [EN]: статья('title: A')});

    await сохранить(среда, {rel: RU, шапка: 'title: A\nunlisted: true'});

    expect(fs.existsSync(path.join(среда.repo, ES))).toBe(false);
  });

  it('правка текста без смены видимости соседние версии не трогает ни записью, ни версией в истории', async () => {
    // Иначе «открыл и сохранил — ни байта» перестало бы держаться для соседей (SPEC 5.1).
    const среда = await подготовить({
      [RU]: статья('title: A\nunlisted: true'),
      [EN]: статья('title: A\nunlisted: true'),
    });
    const былоEN = прочитать(среда, EN);

    await сохранить(среда, {rel: RU, шапка: 'title: A\nunlisted: true', тело: '\nдругой текст\n'});

    // Текст человека обязан доехать до файла: сохранение пишет то, что в окне, а не то, что было.
    expect(прочитать(среда, RU)).toContain('другой текст');
    expect(прочитать(среда, EN)).toBe(былоEN);
    expect(countSnapshots(среда.editorDir, НАСТРОЙКИ, EN)).toBe(0);
  });

  it('версия без шапки получает видимость только собственным открытием и сохранением', async () => {
    // Шапки у файла нет вовсе — завести её может лишь правка человека в его собственном файле.
    // Сохранение соседней версии сделать этого не вправе, а своё — обязано.
    const безШапки = '# Заголовок\n\nтекст без шапки\n';
    const среда = await подготовить({[RU]: статья('title: A'), [EN]: безШапки});

    await сохранить(среда, {rel: RU, шапка: 'title: A\nunlisted: true'});
    expect(прочитать(среда, EN)).toBe(безШапки);

    await сохранить(среда, {rel: EN, шапка: 'title: A\nunlisted: true', тело: `\n${безШапки}`});
    expect(прочитать(среда, EN)).toContain('unlisted: true');
  });

  it('сохранение поверх внешней правки видимости трогает только открытый файл', async () => {
    // «Сохранить поверх» значит «моё окно главнее» — но главнее только для своей версии.
    const среда = await подготовить({
      [RU]: статья('title: A\nunlisted: true'),
      [EN]: статья('title: A\nunlisted: true'),
    });
    // Снаружи файл переписали, пока человек работал с открытой в окне версией.
    fs.writeFileSync(path.join(среда.repo, RU), статья('title: A\nunlisted: true', '\nчужая правка\n'), 'utf8');

    await сохранить(среда, {rel: RU, шапка: 'title: A', тело: '\nмой текст\n', поверх: true});

    expect(прочитать(среда, RU)).not.toContain('unlisted');
    expect(прочитать(среда, EN)).toContain('unlisted: true');
  });

  it('открыл и сохранил без правок — ни файл, ни соседние версии не меняются', async () => {
    for (const шапка of ['title: A', 'title: A\nunlisted: false', 'title: A\nunlisted: true']) {
      const среда = await подготовить({[RU]: статья(шапка), [EN]: статья(шапка)});
      const былоRU = прочитать(среда, RU);
      const былоEN = прочитать(среда, EN);

      const ответ = await сохранить(среда, {rel: RU, шапка});

      expect(ответ.data['untouched'], шапка).toBe(true);
      expect(прочитать(среда, RU), шапка).toBe(былоRU);
      expect(прочитать(среда, EN), шапка).toBe(былоEN);
    }
  });

  it('статья вне сайта живёт в одной локали: её сохранение тоже пишет один файл', async () => {
    const среда = await подготовить({'editor/sandbox/proba/index.mdx': статья('title: A')});

    const ответ = await сохранить(среда, {rel: 'editor/sandbox/proba/index.mdx', шапка: 'title: A\nunlisted: true'});

    expect(ответ.code).toBe(200);
    expect(прочитать(среда, 'editor/sandbox/proba/index.mdx')).toContain('unlisted: true');
  });
});
