// Имя каждого теста повторяет формулировку правила.
//
// Ради чего набор заведён: снимок подготовки обязан описывать РОВНО то, от чего зависит вердикт.
// Возьми он меньше — правка, меняющая вердикт, прошла бы незамеченной; возьми больше — обычная
// публикация вставала бы от чужой работы. Здесь проверяется и то, и другое: статья ПОД открытой
// версией снимок обрывает, статья РЯДОМ — нет; и то же самое внутри одного захода к серверу.
import {afterEach, beforeEach, describe, expect, it, vi} from 'vitest';
import fs from 'node:fs';
import path from 'node:path';

import {зафиксироватьИОтправить, проверитьИСобрать} from '../src/ui/publishRun';
import {запомнитьКоммит, запомнитьПоказ} from '../src/adapters/pushMemory.mjs';
import {запомнитьСборку} from '../src/adapters/buildMemory.mjs';
import {срезОднойВерсии} from '../src/adapters/prepareStamp.mjs';
import {ЖДАТЬ_GIT} from './saveHarness.mjs';
import {
  НАСТРОЙКИ, RU, СТАТЬЯ, дверь, наСервере, отпечатокПоказанного, среда, убратьПесочницы, ход,
} from './runHarness.mjs';

beforeEach(() => {
  запомнитьСборку(null);
  запомнитьКоммит(null);
  запомнитьПоказ(null);
});

afterEach(() => {
  запомнитьСборку(null);
  запомнитьКоммит(null);
  запомнитьПоказ(null);
  убратьПесочницы();
});

describe('снимок описывает ровно своё дерево', () => {
  /**
   * Статья ПОД открытой версией: она и только она меняет вход проверок — по ней страница становится
   * служебной страницей раздела, а у той свои требования к полям.
   *
   * Статья РЯДОМ на вердикт не влияет ничем, и снимок обязан её не замечать: иначе созданная где
   * угодно в той же локали статья обрывала бы чужую публикацию словами «статья изменилась».
   */
  const положитьДочернюю = (с) => {
    const дочерняя = path.join(с.repo, path.dirname(RU), 'дочерняя', 'index.mdx');
    fs.mkdirSync(path.dirname(дочерняя), {recursive: true});
    fs.writeFileSync(дочерняя, СТАТЬЯ, 'utf8');

    return дочерняя;
  };

  it('снимок доживает до записи: дочерняя статья, появившаяся после сборки, её останавливает', async () => {
    const с = await среда();
    fs.writeFileSync(path.join(с.repo, RU), `${СТАТЬЯ}Новая строка.\n`, 'utf8');
    const х = ход(дверь(с, []), []);
    const вопрос = await проверитьИСобрать(RU, false, х);
    expect(вопрос.вид).toBe('спрашиваю');
    const былоНаСервере = await наСервере(с.сервер);

    // В план публикации дочерняя не входит ничем: у неё своя папка. Не доживи снимок проверок до
    // записи, отпечаток плана этого не заметил бы, и статья уехала бы по правилам, которых на
    // момент записи уже нет.
    положитьДочернюю(с);

    const беда = await зафиксироватьИОтправить(RU, х, вопрос.отпечаток, вопрос.отпечатокПодготовки)
      .catch((ошибка) => ошибка);

    expect(беда.ответ?.код).toBe('статьяИзменилась');
    expect(await наСервере(с.сервер)).toBe(былоНаСервере);
  }, ЖДАТЬ_GIT);

  it('ВТОРОЙ потомок снимок не обесценивает: у служебной страницы категория уже своя', async () => {
    // Дерево в отпечаток не идёт, идёт только категория. Один потомок делает страницу служебной;
    // второй ничего не меняет, и убранный второй — тоже. Клади программа в снимок сам перечень
    // путей — обычная работа рядом обрывала бы публикацию, ничего в ней не меняя.
    const с = await среда();
    положитьДочернюю(с);
    const служебная = срезОднойВерсии(с.repo, RU, НАСТРОЙКИ);
    expect(служебная.категория).toBe(НАСТРОЙКИ['категорияСлужебной']);

    const вторая = path.join(с.repo, path.dirname(RU), 'вторая-дочерняя', 'index.mdx');
    fs.mkdirSync(path.dirname(вторая), {recursive: true});
    fs.writeFileSync(вторая, СТАТЬЯ, 'utf8');
    const сДвумя = срезОднойВерсии(с.repo, RU, НАСТРОЙКИ);
    fs.rmSync(path.dirname(вторая), {recursive: true, force: true});
    const сноваОдна = срезОднойВерсии(с.repo, RU, НАСТРОЙКИ);

    expect(сДвумя.отпечаток).toBe(служебная.отпечаток);
    expect(сноваОдна.отпечаток).toBe(служебная.отпечаток);

    // А вот последний потомок категорию возвращает — и снимок обязан это заметить.
    fs.rmSync(path.join(с.repo, path.dirname(RU), 'дочерняя'), {recursive: true, force: true});
    const безПотомков = срезОднойВерсии(с.repo, RU, НАСТРОЙКИ);
    expect(безПотомков.категория).not.toBe(НАСТРОЙКИ['категорияСлужебной']);
    expect(безПотомков.отпечаток).not.toBe(служебная.отпечаток);
  }, ЖДАТЬ_GIT);

  it('ПОСТОРОННЯЯ статья той же локали снимок не обесценивает: чужая работа публикацию не рвёт', async () => {
    const с = await среда();
    fs.writeFileSync(path.join(с.repo, RU), `${СТАТЬЯ}Новая строка.\n`, 'utf8');
    const х = ход(дверь(с, []), []);
    const вопрос = await проверитьИСобрать(RU, false, х);
    expect(вопрос.вид).toBe('спрашиваю');

    // Так выглядит обычная жизнь: человек во втором окне завёл СВОЮ, ничем не связанную статью в
    // другом разделе той же локали. Ни текст открытой версии, ни её категория от этого не меняются.
    const чужая = path.join(с.repo, path.dirname(path.dirname(RU)), 'vtoraya', 'index.mdx');
    fs.mkdirSync(path.dirname(чужая), {recursive: true});
    fs.writeFileSync(чужая, СТАТЬЯ, 'utf8');

    const итог = await зафиксироватьИОтправить(RU, х, вопрос.отпечаток, вопрос.отпечатокПодготовки);

    expect(итог.вид).toBe('готово');
    expect(await наСервере(с.сервер)).toBe((await с.git.raw(['rev-parse', 'HEAD'])).trim());
  }, ЖДАТЬ_GIT);
  /**
   * Появление статьи ПОД открытой версией меняет пути её дерева, а с ними категорию и требования к
   * полям. Сверка байтов самого файла этого не видит вовсе, поэтому отпечаток пересчитывается
   * целиком — и уже ПОСЛЕ того, как построен план.
   *
   * Гонка воспроизводится точно: дочерняя статья появляется ровно в тот миг, когда ручка дочитывает
   * открытую версию, то есть после снятия первого отпечатка и до построения плана.
   */
  const соседВПоследнийМиг = (с) => {
    const полный = path.join(с.repo, RU);
    const настоящее = fs.readFileSync;
    let первое = true;

    return vi.spyOn(fs, 'readFileSync').mockImplementation((цель, вид) => {
      const ответ = настоящее(цель, вид);
      if (первое && String(цель) === полный) {
        первое = false;
        положитьДочернюю(с);
      }

      return ответ;
    });
  };

  for (const адрес of ['/api/release', '/api/release/build', '/api/publish/commit']) {
    it(`смена своего дерева ВНУТРИ одного захода останавливает ручку: ${адрес}`, async () => {
      const с = await среда();
      fs.writeFileSync(path.join(с.repo, RU), `${СТАТЬЯ}Новая строка.\n`, 'utf8');
      // Дверь БЕЗ подстановки: оба отпечатка кладутся в тело сами и считаются ДО подмены. Дай их
      // подставить обвязке — она прочитала бы статью первой, сосед появился бы раньше входа в ручку,
      // и красным был бы заслон на входе, а не тот, что стоит после плана.
      const х = ход(дверь(с, [], {безСнимка: true}), []);
      const срез = срезОднойВерсии(с.repo, RU, НАСТРОЙКИ);
      const план = await отпечатокПоказанного({repo: с.repo, git: с.git, rel: RU});
      const былоНаСервере = await наСервере(с.сервер);
      const чтение = соседВПоследнийМиг(с);

      let беда;
      try {
        беда = await х.запрос(адрес, {
          path: RU, подтверждено: true, отпечаток: план, отпечатокПодготовки: срез.отпечаток,
        }).catch((ошибка) => ошибка);
      } finally {
        чтение.mockRestore();
      }

      expect(`${адрес}: ${беда.ответ?.код}`).toBe(`${адрес}: статьяИзменилась`);
      expect(await наСервере(с.сервер)).toBe(былоНаСервере);
    }, ЖДАТЬ_GIT);
  }
});
