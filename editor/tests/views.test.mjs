// Подсчёт просмотров статей по строкам отчёта Google Analytics (ED-024): чистые правила ядра.
import {describe, expect, it} from 'vitest';
import {
  адресСтраницы, владельцыАдресов, просмотрыСтатей, изменение, периодОтчёта, сдвигДня, адресаДляПросмотров,
} from '../src/core/views.mjs';

const сайт = {
  roots: [
    {папка: 'docs', род: 'docs', локаль: 'en', наСайте: true},
    {папка: 'i18n/ru/docusaurus-plugin-content-docs/current', род: 'docs', локаль: 'ru', наСайте: true},
    {папка: 'i18n/es/docusaurus-plugin-content-docs/current', род: 'docs', локаль: 'es', наСайте: true},
    {папка: 'blog', род: 'blog', локаль: 'en', наСайте: true},
  ],
  префиксБлога: '/blog',
  обязательный: 'en',
  локали: ['en', 'ru', 'es'],
};
const языки = ['ru', 'en', 'es'];
const статья = (key, пары) => ({key, адреса: new Map(пары)});

describe('адрес страницы', () => {
  it('без хвостовой косой, запроса и якоря; %xx раскрыты; корень остаётся корнем', () => {
    expect(адресСтраницы('/lessons/a/')).toBe('/lessons/a');
    expect(адресСтраницы('/lessons/a/?utm=1#top')).toBe('/lessons/a');
    expect(адресСтраницы('/ru/%D0%B0/')).toBe('/ru/а');
    expect(адресСтраницы('/')).toBe('/');
    expect(адресСтраницы('//x//y/')).toBe('/x/y');
  });
});

describe('владелец адреса', () => {
  it('спорный адрес не засчитывается никому, остальные — своим статьям', () => {
    const владельцы = владельцыАдресов([
      статья('a', [['/x', 'en'], ['/общий', 'en']]),
      статья('b', [['/y/', 'en'], ['/общий/', 'ru']]),
    ]);
    expect(владельцы.get('/x')).toEqual({key: 'a', локаль: 'en'});
    expect(владельцы.get('/y')).toEqual({key: 'b', локаль: 'en'});
    expect(владельцы.has('/общий')).toBe(false);
  });
});

describe('числа статьи', () => {
  const поДень = '20260922';

  it('30 дней против предыдущих 30 — границы включительно, будущее и чужое не считаются', () => {
    const строки = [
      ['/a/', '20260922', 5], // последний день
      ['/a/', '20260824', 7], // первый из 30 (22.09 − 29)
      ['/a/', '20260823', 11], // последний из прежних 30
      ['/a/', '20260725', 13], // первый из прежних 30 (22.09 − 59)
      ['/a/', '20260724', 17], // раньше обоих периодов
      ['/a/', '20260923', 1000], // после «по день» — не бывает, но и не засчитывается
      ['/чужой/', '20260922', 99],
    ];
    const итог = просмотрыСтатей({строки, статьи: [статья('a', [['/a', 'en']])], поДень, месяцев: 12, языки});
    expect(итог.a.за30).toBe(12);
    expect(итог.a.прежние30).toBe(24);
    // За всё время — все строки отчёта по «по день» включительно, и старше обоих периодов тоже.
    expect(итог.a.всего).toBe(53);
  });

  it('языки за 30 дней по адресу, месяцы — 12 полных плюс текущий, от старого к новому', () => {
    const строки = [['/a', '20260901', 3], ['/ru/a/', '20260915', 4], ['/es/a', '20250910', 6], ['/a', '20250831', 100]];
    const итог = просмотрыСтатей({
      строки, статьи: [статья('a', [['/a', 'en'], ['/ru/a', 'ru'], ['/es/a', 'es']])], поДень, месяцев: 12, языки,
    });
    expect(итог.a.языки).toEqual({ru: 4, en: 3, es: 0});
    expect(итог.a.месяцы).toHaveLength(13);
    expect(итог.a.месяцы[0]).toEqual({месяц: '202509', просмотры: 6, языки: {ru: 0, en: 0, es: 6}});
    expect(итог.a.месяцы[12]).toEqual({месяц: '202609', просмотры: 7, языки: {ru: 4, en: 3, es: 0}});
    expect(итог.a.всего).toBe(113);
  });

  it('статья без засчитанного адреса в ответ не попадает (прочерк, а не ноль)', () => {
    const итог = просмотрыСтатей({
      строки: [], статьи: [статья('a', [['/общий', 'en']]), статья('b', [['/общий', 'en']]), статья('c', [])],
      поДень, месяцев: 12, языки,
    });
    expect(итог).toEqual({});
  });

  it('статья с адресом, но без просмотров, получает нули', () => {
    const итог = просмотрыСтатей({строки: [], статьи: [статья('a', [['/a', 'en']])], поДень, месяцев: 12, языки});
    expect(итог.a.за30).toBe(0);
  });
});

describe('период и изменение', () => {
  it('период запроса покрывает и год по месяцам, и 60 дней сравнения', () => {
    expect(периодОтчёта('20260922', 12)).toEqual({с: '20250901', по: '20260922'});
    expect(периодОтчёта('20260922', 1)).toEqual({с: сдвигДня('20260922', -59), по: '20260922'});
    // «За всё время» начинается с дня настройки, если он раньше года и 60 дней.
    expect(периодОтчёта('20260922', 12, '20200101')).toEqual({с: '20200101', по: '20260922'});
    expect(периодОтчёта('20260922', 12, '20260901')).toEqual({с: '20250901', по: '20260922'});
  });

  it('изменение в процентах; сравнивать не с чем — null', () => {
    expect(изменение(150, 100)).toBe(50);
    expect(изменение(50, 100)).toBe(-50);
    expect(изменение(10, 0)).toBeNull();
  });
});

describe('адреса статьи', () => {
  it('нынешние версии, язык без своего файла — адрес английской под своим префиксом', () => {
    const адреса = адресаДляПросмотров(
      [
        {путь: 'docs/lessons/a.mdx', текст: '---\ntitle: A\n---\n'},
        {путь: 'i18n/ru/docusaurus-plugin-content-docs/current/lessons/a.mdx', текст: '---\nslug: a-ru\n---\n'},
      ],
      [],
      сайт,
    );
    expect([...адреса]).toEqual([['/lessons/a', 'en'], ['/es/lessons/a', 'es'], ['/ru/lessons/a-ru', 'ru']]);
  });

  it('прежний путь и прежний slug одного файла дают прежний адрес', () => {
    const адреса = адресаДляПросмотров(
      [{путь: 'blog/new-name/index.mdx', текст: '---\ntitle: B\n---\n'}],
      [{путь: 'blog/old-name/index.mdx', текст: '---\nslug: old-slug\n---\n'}],
      сайт,
    );
    expect(адреса.get('/blog/new-name')).toBe('en');
    expect(адреса.get('/blog/old-slug')).toBe('en');
    expect(адреса.get('/ru/blog/old-slug')).toBe('ru');
    expect(адреса.has('/blog/old-name')).toBe(false);
  });
});
