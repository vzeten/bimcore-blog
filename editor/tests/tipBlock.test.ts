// Имя каждого теста повторяет формулировку правила.
// Смысловые блоки статьи: программа знает границы пяти штатных директив Docusaurus, показывает их
// цельными и вставляет сама.
import {describe, expect, it} from 'vitest';
import {вставкаСовета, границыСоветов, названияБлоков, советы} from '../src/core/tipBlock';
import {EditorSelection, EditorState} from '@codemirror/state';
import {tipLayer} from '../src/ui/livePreview/tip';
import {ensureSyntaxTree} from '@codemirror/language';
import {markdown} from '@codemirror/lang-markdown';
import {мягкиеПереносы, внутриОграды} from '../src/ui/livePreview/softBreak';
import {точкаВОбычномАбзаце} from '../src/ui/editor/paragraphKeys';

/** Текст статьи строками, как он лежит в файле. */
function строки(текст: string): string[] {
  return текст.split('\n');
}

/** Советы текста с тем же учётом ограды кода, каким пользуется показ. */
function найти(текст: string) {
  const список = строки(текст);
  return советы(список, внутриОграды(список));
}

/** Пять штатных типов Docusaurus: их и только их программа знает в лицо. */
const ТИПЫ = ['note', 'tip', 'info', 'warning', 'danger'];

describe('границы блока', () => {
  it('закрытая пара `:::tip` … `:::` считается блоком', () => {
    const найдены = найти('Текст.\n\n:::tip\nСовет читателю.\n:::\n\nДальше.');
    expect(найдены).toEqual([{тип: 'tip', открытие: 2, закрытие: 4, заголовок: null}]);
  });

  it('все пять штатных типов узнаются одним правилом', () => {
    const найдены = ТИПЫ.map((тип) => найти(`:::${тип}\nТекст.\n:::`)[0]);
    expect(найдены.map((блок) => блок?.тип)).toEqual(ТИПЫ);
    expect(найдены.map((блок) => [блок?.открытие, блок?.закрытие])).toEqual(ТИПЫ.map(() => [0, 2]));
  });

  it('собственный заголовок сохраняется у каждого штатного типа', () => {
    expect(ТИПЫ.map((тип) => найти(`:::${тип}[Своё]\nТекст.\n:::`)[0].заголовок))
      .toEqual(ТИПЫ.map(() => 'Своё'));
  });

  it('тип вне пяти штатных блоком не считается', () => {
    expect(найти(':::caution\nСтарое имя типа.\n:::')).toEqual([]);
    expect(найти(':::свой\nЧужой тип.\n:::')).toEqual([]);
  });

  it('собственный заголовок в квадратных скобках сохраняется', () => {
    expect(найти(':::tip[Совет]\nТекст.\n:::')[0].заголовок).toBe('Совет');
  });

  it('пустые скобки считаются отсутствием своего заголовка', () => {
    expect(найти(':::tip[]\nТекст.\n:::')[0].заголовок).toBeNull();
  });

  it('незакрытый блок советом не считается', () => {
    expect(найти(':::tip\nТекст без закрытия.')).toEqual([]);
  });

  it('чужая директива внутри пары делает границы неоднозначными, и блок не показывается', () => {
    expect(найти(':::tip\nТекст.\n:::note\nДругое.\n:::')).toEqual([]);
  });

  it('пример с `:::tip` внутри огороженного кода остаётся кодом', () => {
    expect(найти('```md\n:::tip\nПример.\n:::\n```')).toEqual([]);
  });

  it('два блока разных типов подряд находятся оба', () => {
    const найдены = найти(':::note\nПервый.\n:::\n\n:::danger[Своё]\nВторой.\n:::');
    expect(найдены.map((блок) => [блок.тип, блок.открытие, блок.закрытие]))
      .toEqual([['note', 0, 2], ['danger', 4, 6]]);
  });

  it('границами совета считаются только его служебные строки', () => {
    const список = строки('Текст.\n\n:::tip\nСовет.\n:::');
    expect([...границыСоветов(список, внутриОграды(список))].sort()).toEqual([2, 4]);
  });
});

describe('названия типов', () => {
  const названия = {ru: {tip: 'Совет', danger: 'Опасность'}, es: {tip: 'Consejo', danger: 'Peligro'}};

  it('берутся по языку статьи', () => {
    expect(названияБлоков(названия, 'es', 'ru')).toEqual({tip: 'Consejo', danger: 'Peligro'});
  });

  it('для статьи вне известных языков берётся основной язык сайта', () => {
    expect(названияБлоков(названия, null, 'ru').tip).toBe('Совет');
  });

  it('язык без слов в настройках не выдумывает названий', () => {
    expect(названияБлоков(названия, 'de', 'fr')).toEqual({});
  });
});

describe('вставка блока', () => {
  it('вставляет закрытую пару с заголовком языка и ставит курсор внутрь блока', () => {
    const текст = 'Абзац.';
    const правка = вставкаСовета(текст, {from: 6, to: 6}, 'tip', 'Совет');

    expect(правка?.insert).toBe('\n\n:::tip[Совет]\n\n:::');
    const итог = текст.slice(0, правка!.from) + правка!.insert + текст.slice(правка!.to);
    expect(итог).toBe('Абзац.\n\n:::tip[Совет]\n\n:::');

    // Курсор — на пустой строке между границами: человек сразу пишет текст блока.
    const место = правка!.from + (правка!.caret ?? 0);
    expect(итог.slice(0, место)).toBe('Абзац.\n\n:::tip[Совет]\n');
  });

  it('каждый штатный тип вставляется своей директивой и сразу читается как блок', () => {
    for (const тип of ТИПЫ) {
      const правка = вставкаСовета('Абзац.', {from: 6, to: 6}, тип, 'Имя');
      expect(правка?.insert).toBe(`\n\n:::${тип}[Имя]\n\n:::`);
      expect(найти('Абзац.' + правка!.insert))
        .toEqual([{тип, открытие: 2, закрытие: 4, заголовок: 'Имя'}]);
    }
  });

  it('незнакомый тип не вставляется вовсе, чтобы в статью не попала поломанная директива', () => {
    expect(вставкаСовета('', {from: 0, to: 0}, 'caution', 'Имя')).toBeNull();
    expect(вставкаСовета('', {from: 0, to: 0}, 'tip[чужое]', 'Имя')).toBeNull();
    expect(вставкаСовета('', {from: 0, to: 0}, '', 'Имя')).toBeNull();
  });

  it('заголовок со скобкой не пишется вовсе, чтобы не оборвать директиву', () => {
    const правка = вставкаСовета('', {from: 0, to: 0}, 'warning', 'Со[вет]');
    expect(правка?.insert).toBe(':::warning\n\n:::');
  });

  it('пустая строка получает блок без лишних переводов строк', () => {
    expect(вставкаСовета('', {from: 0, to: 0}, 'info', 'Информация')?.insert)
      .toBe(':::info[Информация]\n\n:::');
  });
});

describe('блок и склейка мягких переносов', () => {
  it('служебные строки блока не склеиваются с соседним текстом', () => {
    // Без этого правила абзац приклеился бы к `:::tip`, и блок в окне разорвался бы.
    const текст = строки('Абзац перед.\n:::tip[Совет]\nТекст совета.\n:::\nАбзац после.');
    expect(мягкиеПереносы(текст)).toEqual([]);
  });

  it('строки внутри совета склеиваются, как обычный абзац', () => {
    const текст = строки(':::tip[Совет]\nПервая строка совета,\nвторая строка совета.\n:::');
    expect(мягкиеПереносы(текст)).toEqual([1]);
  });

  it('чужая строка с двоеточиями остаётся обычным текстом и склеивается', () => {
    // Пара незакрыта, значит совета нет: гасить склейку не за что.
    const текст = строки('Строка про :::tip,\nи её продолжение.');
    expect(мягкиеПереносы(текст)).toEqual([0]);
  });
});


describe('блок и клавиши абзаца', () => {
  /** Состояние редактора с разобранным деревом markdown: тест живёт без окна. */
  function состояние(текст: string, курсор: number): EditorState {
    const state = EditorState.create({
      doc: текст,
      selection: EditorSelection.single(курсор),
      extensions: [markdown()],
    });
    ensureSyntaxTree(state, state.doc.length, 1_000);
    return state;
  }

  it('клавиши абзаца внутри блока работают, как в обычном тексте', () => {
    const текст = ':::tip[Совет]\nТекст совета.\n:::';
    const место = текст.indexOf('\n:::', 5);
    expect(точкаВОбычномАбзаце(состояние(текст, место))).toBe(место);
  });

  it('появление блока не меняет поведение клавиш на служебной строке', () => {
    // Доказательство «клавиши не тронуты»: закрытая пара делает строку блоком, незакрытая — нет,
    // а раскладка абзаца отвечает на обеих одинаково, потому что смотрит только на текст.
    const блок = 'Абзац.\n\n:::tip[Совет]\nТекст совета.\n:::';
    const неБлок = 'Абзац.\n\n:::tip[Совет]\nТекст совета.';
    const место = блок.indexOf(':::tip') + 6;

    expect(точкаВОбычномАбзаце(состояние(блок, место)))
      .toBe(точкаВОбычномАбзаце(состояние(неБлок, место)));
  });
});

describe('показ блока в редакторе', () => {
  /** Названия типов на языке открытой статьи, как их отдаёт `названияБлоков`. */
  const имена = Object.fromEntries(ТИПЫ.map((тип) => [тип, `Имя ${тип}`]));

  /** Что слой показа сделал с текстом: по одной записи на украшенный кусок. */
  function показ(текст: string): {от: number; до: number; класс: string | null; замена: boolean}[] {
    const слой = tipLayer(имена);
    const state = EditorState.create({doc: текст, extensions: [слой]});
    const записи: {от: number; до: number; класс: string | null; замена: boolean}[] = [];

    state.field(слой).between(0, state.doc.length, (от, до, значение) => {
      записи.push({
        от,
        до,
        класс: (значение.spec as {class?: string}).class ?? null,
        замена: значение.spec.widget !== undefined || (от !== до && значение.spec.class === undefined),
      });
    });

    return записи;
  }

  it('строки блока получают класс своего типа, и цвет типа приходит из него', () => {
    for (const тип of ТИПЫ) {
      const классы = показ(`:::${тип}\nТекст.\n:::`).map((з) => з.класс).filter(Boolean);
      expect(классы).toEqual([
        `md-tip md-tip-${тип} md-tip-head`,
        `md-tip md-tip-${тип}`,
        `md-tip md-tip-${тип} md-tip-foot`,
      ]);
    }
  });

  /** Что написано на полосе вместо служебной строки открытия. */
  function полосы(текст: string): string[] {
    const слой = tipLayer(имена);
    const state = EditorState.create({doc: текст, extensions: [слой]});
    const надписи: string[] = [];

    state.field(слой).between(0, state.doc.length, (_от, _до, значение) => {
      const widget = значение.spec.widget as {название?: string} | undefined;
      if (widget?.название !== undefined) надписи.push(widget.название);
    });

    return надписи;
  }

  it('без своего заголовка на полосе стоит название типа на языке статьи', () => {
    expect(ТИПЫ.flatMap((тип) => полосы(`:::${тип}\nТекст.\n:::`))).toEqual(ТИПЫ.map((тип) => `Имя ${тип}`));
  });

  it('свой заголовок из скобок перебивает обычное название типа', () => {
    expect(полосы(':::danger[Своё]\nТекст.\n:::')).toEqual(['Своё']);
  });

  it('служебные строки блока закрыты, а строки блока получают рамку', () => {
    const текст = 'Абзац.\n\n:::tip[Совет]\nТекст совета.\n:::';
    const записи = показ(текст);

    // Три строки блока в рамке: открытие, текст, закрытие.
    expect(записи.filter((з) => з.класс?.includes('md-tip')).length).toBe(3);
    // Обе служебные строки закрыты от глаз: вместо открытия — название, закрытие пустое.
    expect(записи.filter((з) => з.замена).length).toBe(2);
  });

  it('обычный текст без совета ничем не украшается', () => {
    expect(показ('Просто абзац.\n\nВторой абзац.')).toEqual([]);
  });

  it('незакрытая пара блоком не показывается', () => {
    expect(показ(':::tip\nТекст без закрытия.')).toEqual([]);
  });
});
