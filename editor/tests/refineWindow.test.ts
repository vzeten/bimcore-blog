// Имя каждого теста повторяет формулировку правила.
// Состояния окна «Доработать»: чистые переходы хука без React — новый план забывает старый сразу,
// ошибка планирования не оставляет применимого предпросмотра, «изменений нет» не требует применения.
import {describe, expect, it} from 'vitest';

import {ЗАКРЫТО, кПлану, можноПрименить, можноПроверить, планНеУдался, планПолучен, type Состояние} from '../src/ui/useRefine';
import type {ОтчётОбработчика, ПланДоработки} from '../src/ui/refineTypes';

const обработчик = (код: string, выбран: boolean, изменено = 0): ОтчётОбработчика => ({
  код, выбран, применимо: true, изменено: Array.from({length: изменено}, () => ({что: 'x'})), оставлено: [], человеку: [],
});
const план = (отпечаток: string, работа = 1): ПланДоработки => ({
  path: 'a', отпечаток, обработчики: [обработчик('подписиМедиа', true, работа), обработчик('переименование', false, 1)],
});

describe('окно «Доработать»', () => {
  it('новый запрос плана сразу забывает прежний план и его отпечаток: применить старое нельзя', () => {
    const было = планПолучен(ЗАКРЫТО, план('старый'));
    expect(можноПрименить(было)).toBe(true);

    const ждёт = кПлану({...было, выбранные: ['подписиМедиа', 'переименование']});
    expect(ждёт.окно).toBe('план');
    expect(ждёт.план).toBeNull();
    expect(можноПрименить(ждёт)).toBe(false);
    expect(можноПроверить(ждёт)).toBe(false);
  });

  it('ошибка нового планирования не показывает и не даёт применить старый предпросмотр ни с каким набором', () => {
    const ждёт = кПлану(планПолучен(ЗАКРЫТО, план('старый')));
    const сбой = планНеУдался(ждёт, 'сервер не ответил');

    expect(сбой).toMatchObject({окно: 'выбор', план: null, ошибка: 'сервер не ответил'});
    for (const выбранные of [null, [], ['подписиМедиа'], ['подписиМедиа', 'переименование']]) {
      expect(можноПрименить({...сбой, выбранные})).toBe(false);
    }
    // Следующий удачный план — уже новый, со своим отпечатком.
    const снова = планПолучен(кПлану(сбой), план('новый'));
    expect(снова.план?.отпечаток).toBe('новый');
    expect(можноПрименить(снова)).toBe(true);
  });

  it('выбранные обработчики без изменений: применить нельзя, проверить статью можно без фиктивного применения', () => {
    const с = планПолучен(ЗАКРЫТО, план('п', 0));
    expect(можноПрименить(с)).toBe(false);
    expect(можноПроверить(с)).toBe(true);
    // Невыбранный обработчик с работой применение не открывает: считаются только выбранные.
    expect(с.план?.обработчики.find((з) => з.код === 'переименование')?.изменено).toHaveLength(1);
  });

  it('итог «не применено» показывается честно: окно готово, проверка доступна, применение — нет', () => {
    const с: Состояние = {...планПолучен(ЗАКРЫТО, план('п')), окно: 'готово', итог: {path: 'a', применено: false, обработчики: [], предупреждения: []}};
    expect(можноПроверить(с)).toBe(true);
    expect(можноПрименить(с)).toBe(false);
  });

  it('умолчания флажков берутся из первого плана и не перезаписываются следующими планами', () => {
    const первый = планПолучен(ЗАКРЫТО, план('1'));
    expect(первый.выбранные).toEqual(['подписиМедиа']);
    const второй = планПолучен(кПлану({...первый, выбранные: ['переименование']}), план('2'));
    expect(второй.выбранные).toEqual(['переименование']);
  });
});
