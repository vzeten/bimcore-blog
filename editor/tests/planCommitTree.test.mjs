// Имя каждого теста повторяет формулировку правила.
//
// Заслон дерева записи вместо сверки с деревом местной сборки (решение владельца 2026-09-18: сборки на
// компьютере нет). git сам называет (`diff-tree`), чем сложенное дерево отличается от основы, и это
// обязано совпасть с путями плана, меняющими сайт. Лишний путь, попавший в дерево мимо перечня, иначе
// уехал бы на сайт. Проверяется на настоящем git: подставной ответ доказал бы сам себя.
import {afterEach, describe, expect, it, vi} from 'vitest';
import path from 'node:path';

import {деревоКакПлан} from '../src/adapters/planCommit.mjs';
import {деревоПлана} from '../src/adapters/gitCommit.mjs';
import {готовыйПлан} from '../src/adapters/readyPlan.mjs';
import {ЖДАТЬ_GIT} from './saveHarness.mjs';
import {RU, СТАТЬЯ, настройкиСервера, среда, убратьПесочницы} from './publishHarness.mjs';

vi.setConfig({testTimeout: ЖДАТЬ_GIT, hookTimeout: ЖДАТЬ_GIT});
afterEach(() => убратьПесочницы());

/** План открытой версии и дерево, сложенное из переданных записей. */
async function сложить(место, записиДерева) {
  const план = await готовыйПлан({git: место.git, repo: место.repo, settings: настройкиСервера(), rel: RU, основа: место.основа});
  const дерево = await деревоПлана({
    repo: место.repo, основа: место.основа, записи: записиДерева(план.записи),
    времянка: path.join(место.editorDir, 'укладка'), индексныйФайл: path.join(место.editorDir, 'индекс'),
  });
  const сверка = (дерево) => деревоКакПлан({git: место.git, основа: место.основа, дерево, записи: план.записи, времянка: path.join(место.editorDir, 'сверка')});
  return {план, дерево, сверка};
}

describe('заслон дерева записи', () => {
  it('дерево ровно из плана — совпадает с планом', async () => {
    const место = await среда();
    место.положить(RU, `${СТАТЬЯ}Новая строка.\n`);
    const {дерево, сверка} = await сложить(место, (записи) => записи);

    expect(await сверка(дерево)).toBe(true);
  });

  it('лишний путь в дереве мимо плана — расхождение', async () => {
    const место = await среда();
    место.положить(RU, `${СТАТЬЯ}Новая строка.\n`);
    const {дерево, сверка} = await сложить(место, (записи) => [
      ...записи,
      {путь: 'docs/чужое.mdx', назначение: 'версия', локаль: 'en', источник: 'диск', режим: '100644', байты: Buffer.from('чужое\n')},
    ]);

    expect(await сверка(дерево)).toBe(false);
  });

  it('изменение из плана до дерева не дошло — расхождение', async () => {
    const место = await среда();
    место.положить(RU, `${СТАТЬЯ}Новая строка.\n`);
    const {дерево, сверка} = await сложить(место, () => []);

    expect(await сверка(дерево)).toBe(false);
  });

  it('git не ответил про дерево — расхождение, а не молчаливое «совпало»', async () => {
    const место = await среда();
    место.положить(RU, `${СТАТЬЯ}Новая строка.\n`);
    const {сверка} = await сложить(место, (записи) => записи);

    expect(await сверка('0'.repeat(40))).toBe(false);
  });
});
