// Имя каждого теста повторяет формулировку правила.
// Досылка прежней записи: чем кончается ход, когда коммит уже уехал на сайт. Настоящих ручек тут
// нет намеренно — проверяется порядок и итог самого хода в положении, которого диск сегодня не
// даёт, а ветка кода живёт и обязана говорить правду.
import {describe, expect, it} from 'vitest';

import {проверить} from '../src/ui/publishRun';
import {RU} from './runHarness.mjs';

/**
 * Подставная дверь к серверу: ответы задаются проверкой, а не настоящими ручками.
 *
 * Здесь это законно и нужно. Проверяется ПОРЯДОК И ИТОГ хода в положении, которого настоящий диск
 * сегодня не даёт: прежняя запись ждёт отправки, а нового на диске — один лишний файл. Настоящие
 * ручки в такое положение не заводят (появление файла снимает ждущую запись), но ветка кода живёт,
 * и соври она — человек прочёл бы «Не опубликовано» о статье, которая в эту минуту на сайте.
 */
function подставнаяДверь(ответы, адреса) {
  return async (адрес, тело) => {
    адреса.push(адрес);
    const ответ = ответы[адрес];
    const значение = typeof ответ === 'function' ? ответ(тело) : ответ;
    if (значение instanceof Error) throw значение;
    return значение ?? {};
  };
}

/** Ход с подставной дверью: записи окна всегда удаются, шаги никуда не показываются. */
const подставнойХод = (дверьСервера) => ({
  запрос: дверьСервера,
  сохранить: async () => true,
  поставитьДату: async () => true,
  поставитьОбложку: async () => true,
  поставитьДоступность: async () => true,
  шаг: () => undefined,
  жива: () => true,
});

describe('досылка прошлой записи', () => {
  it('прежний коммит уехал, а нового только лишний файл — это успех, и слова называют оба факта', async () => {
    const адреса = [];
    const СИРОТА = 'i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba/сирота.png';
    let заходов = 0;
    const х = подставнойХод(подставнаяДверь({
      '/api/publish/date': {нужна: null, вФайле: null},
      '/api/publish/cover': {нужна: null, создана: false, предупреждение: null},
      '/api/prepare': {находки: [], прошла: true, невыполненные: [], отпечаток: 'снимок'},
      '/api/publish/plan': {sha: 'a'.repeat(40), коммиты: [{sha: 'a'.repeat(40), заголовок: 'статья', файлов: 1}], файлы: [], уже: false},
      '/api/publish/push': {отправлено: true},
      '/api/publish/tidy': {убрано: [СИРОТА], корзина: 'запись'},
      // Первый заход: прежняя запись ждёт отправки. Второй: публиковать нечего, но лишнее названо.
      '/api/release': () => {
        заходов += 1;
        if (заходов === 1) return Object.assign(new Error('есть неотправленное'), {ответ: {код: 'естьНеотправленное'}});
        return {
          path: RU, можно: true, файлы: [], разрывы: [], находки: [], отпечаток: 'план',
          лишние: [{путь: RU, файлы: ['сирота.png']}],
          итог: {версии: [], картинки: [], убираемые: [], естьЧтоПубликовать: false, служебных: 0},
        };
      },
    }, адреса));

    const итог = await проверить(RU, false, х);

    expect(итог.вид).toBe('готово');
    expect(итог.коммит).toBe('a'.repeat(7));
    expect(итог.убрано).toEqual(['сирота.png']);
    // Уборка и вправду была позвана, и была она ПОСЛЕ отправки прежней записи.
    expect(адреса.indexOf('/api/publish/tidy')).toBeGreaterThan(адреса.indexOf('/api/publish/push'));
  });

  it('прежний коммит уехал, а нового нет вовсе — тоже успех, и убирать нечего', async () => {
    const адреса = [];
    let заходов = 0;
    const х = подставнойХод(подставнаяДверь({
      '/api/publish/date': {нужна: null, вФайле: null},
      '/api/publish/cover': {нужна: null, создана: false, предупреждение: null},
      '/api/prepare': {находки: [], прошла: true, невыполненные: [], отпечаток: 'снимок'},
      '/api/publish/plan': {sha: 'b'.repeat(40), коммиты: [], файлы: [], уже: false},
      '/api/publish/push': {отправлено: true},
      '/api/release': () => {
        заходов += 1;
        if (заходов === 1) return Object.assign(new Error('есть неотправленное'), {ответ: {код: 'естьНеотправленное'}});
        return {
          path: RU, можно: true, файлы: [], разрывы: [], находки: [], отпечаток: 'план', лишние: [],
          итог: {версии: [], картинки: [], убираемые: [], естьЧтоПубликовать: false, служебных: 0},
        };
      },
    }, адреса));

    const итог = await проверить(RU, false, х);

    expect(итог.вид).toBe('готово');
    expect(итог.убрано).toEqual([]);
    expect(адреса).not.toContain('/api/publish/tidy');
  });
});
