// Имя каждого теста повторяет формулировку правила.
// Что человек видит возле букв языковой версии: рисуется настоящий компонент реестра и шапки,
// а проверяется его разметка, а не строки в исходнике (SPEC 5.2.1).
//
// Наблюдение владельца, ради которого правило заведено: серая пустая точка заглушки стояла рядом
// с красной точкой правки и читалась вторым состоянием выпуска, которым не является.
import {describe, expect, it} from 'vitest';
import {renderToStaticMarkup} from 'react-dom/server';

import {LocaleMark} from '../src/ui/zones/LocaleMark';
import {признакиЛокали} from '../src/core/localeSigns.mjs';
import type {ПризнакиЛокали} from '../src/ui/articleTypes';

/** Версия в своде: по умолчанию опубликована и совпадает с веткой. */
const версия = (ещё: Record<string, unknown> = {}) => ({
  path: 'blog/proba/index.mdx',
  опубликован: true,
  отличается: false,
  заглушка: false,
  черновикСайта: false,
  скрыта: false,
  ...ещё,
});

const нарисовать = (признаки: ПризнакиЛокали, code = 'es'): string => renderToStaticMarkup(
  <LocaleMark code={code} признаки={признаки} подсказка="подсказка" onClick={() => undefined} />,
);

/** Сколько точек над буквами нарисовано и каких. */
const точки = (html: string): string[] => (html.match(/lang-точка-[^"]+/g) ?? []);

describe('обозначение языковой версии', () => {
  it('версия осталась заглушкой — своего знака у неё нет ни одного', () => {
    const html = нарисовать(признакиЛокали(версия({заглушка: true})));

    expect(точки(html)).toEqual([]);
    // Пустая строка признаков остаётся: она держит высоту, иначе буквы соседних языков разъезжались бы.
    expect(html).toContain('<span class="lang-сверху"></span>');
  });

  it('опубликованный файл есть, а местная версия отличается — над буквами красная точка', () => {
    expect(точки(нарисовать(признакиЛокали(версия({отличается: true}))))).toEqual(['lang-точка-изменена']);
  });

  it('заглушка вместе с местной правкой — точка ровно одна, и это точка правки', () => {
    // Прежде их было две, и вторая читалась вторым состоянием выпуска.
    expect(точки(нарисовать(признакиЛокали(версия({отличается: true, заглушка: true}))))).toEqual(['lang-точка-изменена']);
  });

  it('заглушка не гасит соседние признаки своей же версии', () => {
    // Версия выпущена скрытой: значок ссылки говорит про сайт, и неопубликованной он не даётся.
    const html = нарисовать(признакиЛокали(версия({
      заглушка: true, черновикСайта: true, скрыта: true,
    })));

    expect(html).toContain('lang-цвет-черновик');
    expect(html).toContain('lang-ссылка');
    expect(точки(html)).toEqual([]);
  });

  it('возле букв нет старой точки возраста версии ни в одном состоянии', () => {
    // Наблюдение владельца: справа от EN и ES стояли точки «•» со словами «правился раньше
    // основной версии». Это возраст версии, а не состояние выпуска: рядом с красной точкой и
    // значком ссылки он читался третьим состоянием. Убран из обозначения совсем.
    const состояния = [
      версия(),
      версия({отличается: true}),
      версия({скрыта: true}),
      версия({заглушка: true, черновикСайта: true}),
      версия({опубликован: false}),
    ];

    for (const состояние of [...состояния.map(признакиЛокали), признакиЛокали(null)]) {
      const html = нарисовать(состояние);

      expect(html).not.toContain('•');
      expect(html).not.toContain('lang-mark');
    }
  });

  it('файла локали нет — ни точки, ни значка ссылки, буквы бледные', () => {
    const html = нарисовать(признакиЛокали(null));

    expect(точки(html)).toEqual([]);
    expect(html).toContain('lang-цвет-нет');
    expect(html).not.toContain('lang-ссылка');
  });
});
