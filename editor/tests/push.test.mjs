// Имя каждого теста повторяет формулировку правила.
// Правила отправки статьи на сайт: чистая функция, поэтому проверяется фактами без git и сети.
import {describe, expect, it} from 'vitest';

import {отпечатокНабора, решениеОбОтправке} from '../src/core/push.mjs';

const СТАТЬЯ = ['docs/lessons/proba/index.mdx'];

/** Годные факты: ветка рабочая, сервер прочитан, впереди один коммит с файлом статьи. */
function факты(правки = {}) {
  return {
    ветка: 'main',
    головаSha: 'a'.repeat(40),
    удалённыйSha: 'b'.repeat(40),
    отставание: 0,
    коммиты: [{sha: 'a'.repeat(40), родителей: 1, файлы: [...СТАТЬЯ]}],
    разрешённыеПути: СТАТЬЯ,
    ...правки,
  };
}

describe('правило отправки на сайт', () => {
  it('на рабочей ветке с прочитанным сервером отправляется ровно то, что показано', () => {
    const решение = решениеОбОтправке(факты());

    expect(решение.ошибка).toBeUndefined();
    expect(решение.коммиты).toEqual(['a'.repeat(40)]);
    expect(решение.файлы).toEqual(СТАТЬЯ);
  });

  it('не та ветка — отправки нет', () => {
    expect(решениеОбОтправке(факты({ветка: 'proba'})).ошибка).toBe('неТаВетка');
  });

  it('состояние сервера прочитать не удалось — отправки нет: вслепую не отправляем', () => {
    expect(решениеОбОтправке(факты({удалённыйSha: null})).ошибка).toBe('удалённыйНеизвестен');
  });

  it('отставание сосчитать не удалось — это «не знаю», а не ноль', () => {
    expect(решениеОбОтправке(факты({отставание: null})).ошибка).toBe('удалённыйНеизвестен');
  });

  it('перечень уезжающих коммитов прочитать не удалось — отправки нет', () => {
    expect(решениеОбОтправке(факты({коммиты: null})).ошибка).toBe('удалённыйНеизвестен');
  });

  it('на сайте есть чужие изменения — программа их не сливает, отправки нет', () => {
    expect(решениеОбОтправке(факты({отставание: 2})).ошибка).toBe('ветвиРазошлись');
  });

  it('этот коммит на сайте уже есть — это успех, а не отказ', () => {
    const решение = решениеОбОтправке(факты({удалённыйSha: 'a'.repeat(40)}));

    expect(решение.ошибка).toBeUndefined();
    expect(решение.уже).toBe(true);
  });

  it('впереди нет ни одного коммита — отправлять нечего', () => {
    expect(решениеОбОтправке(факты({коммиты: []})).ошибка).toBe('нечегоОтправлять');
  });

  it('среди уезжающих есть слияние — что оно везёт, доказать нечем, отправки нет', () => {
    const слияние = [{sha: 'a'.repeat(40), родителей: 2, файлы: []}];

    expect(решениеОбОтправке(факты({коммиты: слияние})).ошибка).toBe('слияниеВпереди');
  });

  it('вместе со статьёй уехал бы файл чужой статьи — отправки нет, файл назван', () => {
    const чужой = [{sha: 'a'.repeat(40), родителей: 1, файлы: [...СТАТЬЯ, 'docs/lessons/чужая/index.mdx']}];
    const решение = решениеОбОтправке(факты({коммиты: чужой}));

    expect(решение.ошибка).toBe('чужиеФайлы');
    expect(решение.чужие).toEqual(['docs/lessons/чужая/index.mdx']);
  });

  it('файл настроек самого сайта отправку останавливает: сборкой статьи он не проверялся', () => {
    const конфиг = [{sha: 'a'.repeat(40), родителей: 1, файлы: ['docusaurus.config.js']}];

    expect(решениеОбОтправке(факты({коммиты: конфиг})).ошибка).toBe('чужиеФайлы');
  });

  it('коммит с работой над самой программой отправку останавливает', () => {
    const программа = [{sha: 'c'.repeat(40), родителей: 1, файлы: ['editor/SPEC.md']}];
    const решение = решениеОбОтправке(факты({коммиты: [...факты().коммиты, ...программа]}));

    expect(решение.ошибка).toBe('чужиеФайлы');
    expect(решение.чужие).toEqual(['editor/SPEC.md']);
  });

  it('правила помощникам в корне репозитория отправку тоже останавливают', () => {
    const правила = [{sha: 'c'.repeat(40), родителей: 1, файлы: ['CLAUDE.md']}];

    expect(решениеОбОтправке(факты({коммиты: правила})).ошибка).toBe('чужиеФайлы');
  });

  it('путь, совпадающий с составом только после обрезки пробелов, разрешённым не считается', () => {
    const скраю = [{sha: 'a'.repeat(40), родителей: 1, файлы: [`${СТАТЬЯ[0]} `]}];

    expect(решениеОбОтправке(факты({коммиты: скраю})).ошибка).toBe('чужиеФайлы');
  });

  it('файл в составе статьи разрешён, даже когда лежит в папке с картинками', () => {
    const картинки = ['docs/lessons/proba/index.mdx', 'docs/lessons/proba/img/один.jpg'];
    const решение = решениеОбОтправке(факты({
      разрешённыеПути: картинки,
      коммиты: [{sha: 'a'.repeat(40), родителей: 1, файлы: картинки}],
    }));

    expect(решение.ошибка).toBeUndefined();
    expect(решение.файлы).toEqual(картинки);
  });
});

describe('правило отправки: согласие относится к показанному', () => {
  /** Те же годные факты плюс включённая сверка согласия. */
  const согласие = (правки = {}) => решениеОбОтправке(факты({
    сверятьСогласие: true,
    ожидаемыйSha: 'a'.repeat(40),
    нашКоммит: 'a'.repeat(40),
    показанныйSha: 'a'.repeat(40),
    показанныйНабор: 'набор',
    наборСейчас: 'набор',
    ...правки,
  }));

  it('согласие пришло на другой коммит, чем лежит сейчас, — отправки нет', () => {
    expect(согласие({ожидаемыйSha: 'f'.repeat(40)}).ошибка).toBe('головаСместилась');
  });

  it('согласие без названного коммита не принимается вовсе', () => {
    expect(согласие({ожидаемыйSha: null}).ошибка).toBe('головаСместилась');
  });

  it('коммит сделан не программой — отправки нет: проверок он не проходил', () => {
    expect(согласие({нашКоммит: 'd'.repeat(40)}).ошибка).toBe('неНашКоммит');
  });

  it('показа не было вовсе — отправки нет: согласие относилось бы неизвестно к чему', () => {
    expect(согласие({показанныйSha: null}).ошибка).toBe('показаНеБыло');
  });

  it('после показа набор изменился — отправки нет, согласие спрашивается заново', () => {
    expect(согласие({наборСейчас: 'другой набор'}).ошибка).toBe('показУстарел');
  });

  it('показывали другой коммит — отправки нет', () => {
    expect(согласие({показанныйSha: 'e'.repeat(40)}).ошибка).toBe('показУстарел');
  });

  it('показ совпал с сегодняшним состоянием — отправка разрешена', () => {
    expect(согласие().ошибка).toBeUndefined();
  });
});

describe('отпечаток показанного набора', () => {
  it('разные наборы дают разные отпечатки', () => {
    const один = отпечатокНабора([{sha: 'a', файлы: ['docs/a.mdx']}]);
    const другой = отпечатокНабора([{sha: 'a', файлы: ['docs/b.mdx']}]);

    expect(один).not.toBe(другой);
  });

  it('тот же набор даёт тот же отпечаток', () => {
    const набор = [{sha: 'a', файлы: ['docs/a.mdx', 'docs/b.mdx']}];

    expect(отпечатокНабора(набор)).toBe(отпечатокНабора(набор));
  });
});
