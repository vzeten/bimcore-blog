// Имя каждого теста повторяет формулировку правила.
// Цепочка слоёв цвета: какие снимки читаются с диска и чем становятся.
import {afterEach, describe, expect, it} from 'vitest';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

import {historyLayers} from '../src/adapters/layerChain.mjs';
import {historyFolder, snapshotName} from '../src/core/history.mjs';

const НАСТРОЙКИ = {
  хранение: {папкаЧерновиков: '.drafts', папкаСнимков: '.history', слоёвИстории: 3, снимковНаВерсию: 50},
  слоиПоАвторам: {Claude: 'prevAi'},
};

const REL = 'docs/a/index.mdx';
const Я = 'vzeten';

const песочницы = [];
function песочница() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'editor-store-'));
  песочницы.push(dir);
  return dir;
}

afterEach(() => {
  while (песочницы.length > 0) fs.rmSync(песочницы.pop(), {recursive: true, force: true});
});

/** Снимок статьи: шапка и тело складываются в файл, как это делает сама программа. */
function снимок(editorDir, {время, автор, шапка = 'title: A', тело}) {
  const папка = path.join(editorDir, НАСТРОЙКИ['хранение']['папкаСнимков'], historyFolder(REL));
  fs.mkdirSync(папка, {recursive: true});
  fs.writeFileSync(path.join(папка, snapshotName(время, автор)), `---\n${шапка}\n---\n${тело}`, 'utf8');
}

const слои = (editorDir, публикацияОт = null) => historyLayers({
  editorDir, settings: НАСТРОЙКИ, rel: REL, публикацияОт, ктоЯ: Я,
});

describe('слои цвета из истории', () => {
  it('в цвет идёт тело статьи без шапки', () => {
    // Снимок хранит файл целиком: сравнение шапки с текстом сдвинуло бы все отрезки цвета.
    const dir = песочница();
    снимок(dir, {время: '2026-08-06T10:00:00.000Z', автор: 'Claude', тело: '\nтекст ИИ\n'});

    expect(слои(dir)).toEqual([{text: '\nтекст ИИ\n', kind: 'prevAi'}]);
  });

  it('автор снимка становится видом слоя по справочнику настроек', () => {
    const dir = песочница();
    снимок(dir, {время: '2026-08-06T10:00:00.000Z', автор: 'Claude', тело: '\nа\n'});
    снимок(dir, {время: '2026-08-06T11:00:00.000Z', автор: Я, тело: '\nб\n'});
    снимок(dir, {время: '2026-08-06T12:00:00.000Z', автор: 'Неизвестный', тело: '\nв\n'});

    expect(слои(dir).map((с) => с.kind)).toEqual(['prevAi', 'prevHuman', 'prevOther']);
  });

  it('снимок, где менялась только шапка, слоем не становится', () => {
    // Так выглядит переключение видимости: тексту оно ничего не даёт, а место в пределе заняло бы
    // и вытеснило настоящую правку — текст ИИ достался бы чужому цвету.
    const dir = песочница();
    снимок(dir, {время: '2026-08-06T10:00:00.000Z', автор: 'Claude', тело: '\nтекст ИИ\n'});
    снимок(dir, {время: '2026-08-06T11:00:00.000Z', автор: Я, шапка: 'title: A\nunlisted: true', тело: '\nтекст ИИ\n'});

    expect(слои(dir)).toEqual([{text: '\nтекст ИИ\n', kind: 'prevAi'}]);
  });

  it('слоёв больше предела — лишние отбрасываются с самых старых', () => {
    const dir = песочница();
    for (const [час, тело] of [['10', 'а'], ['11', 'б'], ['12', 'в'], ['13', 'г']]) {
      снимок(dir, {время: `2026-08-06T${час}:00:00.000Z`, автор: `автор${час}`, тело: `\n${тело}\n`});
    }

    expect(слои(dir).map((с) => с.text)).toEqual(['\nб\n', '\nв\n', '\nг\n']);
  });

  it('снимок старше опубликованного состояния в цвет не идёт', () => {
    const dir = песочница();
    снимок(dir, {время: '2026-08-06T10:00:00.000Z', автор: 'Claude', тело: '\nстарое\n'});
    снимок(dir, {время: '2026-08-06T12:00:00.000Z', автор: 'Claude', тело: '\nновое\n'});

    expect(слои(dir, '2026-08-06T11:00:00.000Z')).toEqual([{text: '\nновое\n', kind: 'prevAi'}]);
  });

  it('свежий снимок без изменения текста не забирает цвет даже при полном пределе', () => {
    // Предел набран уже первым прочитанным снимком, но текста он не менял: оставить цвет за ним
    // значило бы приписать правку ИИ переключению видимости.
    const dir = песочница();
    снимок(dir, {время: '2026-08-06T10:00:00.000Z', автор: 'Claude', тело: '\nтекст ИИ\n'});
    снимок(dir, {время: '2026-08-06T11:00:00.000Z', автор: Я, шапка: 'title: A\nunlisted: true', тело: '\nтекст ИИ\n'});

    const однимСлоем = historyLayers({
      editorDir: dir,
      settings: {...НАСТРОЙКИ, хранение: {...НАСТРОЙКИ['хранение'], слоёвИстории: 1}},
      rel: REL,
      публикацияОт: null,
      ктоЯ: Я,
    });

    expect(однимСлоем).toEqual([{text: '\nтекст ИИ\n', kind: 'prevAi'}]);
  });

  it('истории нет — слоёв нет, и это не ошибка', () => {
    expect(слои(песочница())).toEqual([]);
  });
});
