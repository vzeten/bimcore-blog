// Имя каждого теста повторяет формулировку правила.
// Одна кнопка ставит и снимает знаки разметки. Проверяется всё вместе: что легло в файл, что
// увидит разборщик markdown и не осталось ли одиноких звёздочек — расхождение между этим и было
// бедой. Курсив и жирное проверяются рядом: примитив у них один.
import {describe, expect, it} from 'vitest';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {commonmarkLanguage, markdown} from '@codemirror/lang-markdown';
import {EditorSelection, EditorState} from '@codemirror/state';
import {поверхностьРедактирования} from '../src/ui/editor/structureGuard';
import type {Button, Edit, Selection} from '../src/core/commands';
import {decideEdit} from '../src/ui/editor/SelectionToolbar';

const settings = JSON.parse(readFileSync(fileURLToPath(new URL('../settings.json', import.meta.url)), 'utf8')) as {
  вставки: Button[];
};
const КНОПКА = (подпись: string): Button => settings.вставки.find((item) => item.подпись === подпись)!;
const ЖИРНЫЙ = КНОПКА('Жирный');
const КУРСИВ = КНОПКА('Курсив');

/** Нажатие кнопки панели: новый текст файла и что после правки выделено или где курсор. */
function нажать(button: Button, text: string, at: Selection): {текст: string; выделено: string} {
  const edit = decideEdit(button, text, at, {settings: {} as never, articlePath: ''}) as Edit;
  const текст = `${text.slice(0, edit.from)}${edit.insert}${text.slice(edit.to)}`;
  const выделено = edit.select ? edit.insert.slice(edit.select.from, edit.select.to) : '';
  return {текст, выделено};
}

/** Что из текста получил бы сайт: разметка по штатному разбору markdown, а не по виду знаков. */
function разметка(text: string): string[] {
  const найдено: string[] = [];
  commonmarkLanguage.parser.parse(text).iterate({
    enter: (node) => {
      if (node.name === 'StrongEmphasis') найдено.push(`жирный:${text.slice(node.from, node.to).replace(/\*/g, '')}`);
      if (node.name === 'Emphasis') найдено.push(`курсив:${text.slice(node.from, node.to).replace(/\*/g, '')}`);
    },
  });
  return найдено;
}

/** Где в тексте лежит кусок — выделение человека, сделанное по видимому слову. */
function место(text: string, кусок: string): Selection {
  const from = text.indexOf(кусок);
  return {from, to: from + кусок.length};
}

const ФАЙЛ = 'Параметр Ушки по бокам включаются к любому изголовью.\n';

describe('повторное нажатие снимает ровно свою обёртку', () => {
  it('«Жирный» на уже жирном куске убирает пару `**` и оставляет текст нетронутым', () => {
    const жирно = нажать(ЖИРНЫЙ, ФАЙЛ, место(ФАЙЛ, 'Ушки по бокам')).текст;
    expect(жирно).toBe('Параметр **Ушки по бокам** включаются к любому изголовью.\n');

    const снято = нажать(ЖИРНЫЙ, жирно, место(жирно, 'Ушки по бокам')).текст;
    expect(снято).toBe(ФАЙЛ);
    expect(разметка(снято)).toEqual([]);
  });

  it('«Курсив» на уже наклонном куске убирает пару `*` и не оставляет одиночной звёздочки', () => {
    const курсивом = нажать(КУРСИВ, ФАЙЛ, место(ФАЙЛ, 'Ушки по бокам')).текст;
    expect(курсивом).toBe('Параметр *Ушки по бокам* включаются к любому изголовью.\n');

    const снято = нажать(КУРСИВ, курсивом, место(курсивом, 'Ушки по бокам')).текст;
    expect(снято).toBe(ФАЙЛ);
    expect(снято.includes('*')).toBe(false);
  });

  it('снятие берёт кусок и тогда, когда человек выделил его вместе со служебными знаками', () => {
    const жирно = 'Параметр **Ушки по бокам** включаются к любому изголовью.\n';
    expect(нажать(ЖИРНЫЙ, жирно, место(жирно, '**Ушки по бокам**')).текст).toBe(ФАЙЛ);
  });

  it('после снятия выделен сам текст: следующее нажатие возвращает оформление тому же куску', () => {
    const жирно = нажать(ЖИРНЫЙ, ФАЙЛ, место(ФАЙЛ, 'Ушки по бокам')).текст;
    const {текст, выделено} = нажать(ЖИРНЫЙ, жирно, место(жирно, 'Ушки по бокам'));
    expect(выделено).toBe('Ушки по бокам');
    expect(нажать(ЖИРНЫЙ, текст, место(текст, выделено)).текст).toBe(жирно);
  });

  it('поставить и снять — файл возвращается байт в байт', () => {
    const туда = нажать(ЖИРНЫЙ, ФАЙЛ, место(ФАЙЛ, 'бокам')).текст;
    expect(нажать(ЖИРНЫЙ, туда, место(туда, 'бокам')).текст).toBe(ФАЙЛ);
  });
});

describe('кнопки не путают жирное с курсивом', () => {
  const жирно = 'Параметр **Ушки** включаются.\n';

  it('«Курсив» на жирном куске добавляет свой знак, а не отрывает половину чужой пары', () => {
    const {текст} = нажать(КУРСИВ, жирно, место(жирно, 'Ушки'));
    expect(текст).toBe('Параметр ***Ушки*** включаются.\n');
    expect(разметка(текст).sort()).toEqual(['жирный:Ушки', 'курсив:Ушки']);
  });

  it('«Курсив» на жирном и наклонном куске снимает только курсив, жирность остаётся', () => {
    const оба = 'Параметр ***Ушки*** включаются.\n';
    const {текст} = нажать(КУРСИВ, оба, место(оба, 'Ушки'));
    expect(текст).toBe(жирно);
    expect(разметка(текст)).toEqual(['жирный:Ушки']);
  });

  it('«Жирный» на жирном и наклонном куске снимает только жирность, курсив остаётся', () => {
    const оба = 'Параметр ***Ушки*** включаются.\n';
    const {текст} = нажать(ЖИРНЫЙ, оба, место(оба, 'Ушки'));
    expect(текст).toBe('Параметр *Ушки* включаются.\n');
    expect(разметка(текст)).toEqual(['курсив:Ушки']);
  });
});

describe('края выделения и смешанный кусок не рвут markdown', () => {
  it('пробел по краю выделения остаётся снаружи знаков — иначе пара не закроется', () => {
    const {текст} = нажать(ЖИРНЫЙ, ФАЙЛ, {from: 8, to: 23});
    expect(текст).toBe('Параметр **Ушки по бокам** включаются к любому изголовью.\n');
    expect(разметка(текст)).toEqual(['жирный:Ушки по бокам']);
  });

  it('выделение с уже жирным куском внутри оформляется целиком, без вложенных пар', () => {
    const было = 'Параметр **Ушки** по бокам.\n';
    const {текст} = нажать(ЖИРНЫЙ, было, место(было, '**Ушки** по бокам'));
    expect(текст).toBe('Параметр **Ушки по бокам**.\n');
    expect(разметка(текст)).toEqual(['жирный:Ушки по бокам']);
  });

  it('выделение, разрезающее пару, забирает её целиком — одинокой звёздочки не остаётся', () => {
    const было = 'Параметр **Ушки** по бокам.\n';
    const {текст} = нажать(ЖИРНЫЙ, было, {from: 4, to: 15});
    expect(текст.replace(/\*/g, '')).toBe('Параметр Ушки по бокам.\n');
    expect((текст.match(/\*/g) ?? []).length).toBe(4);
    expect(разметка(текст)).toEqual(['жирный:метр Ушки']);
  });

  it('два жирных куска через пробел считаются оформленными: нажатие снимает оба', () => {
    const было = '**Ушки** **по бокам** включаются.\n';
    const {текст} = нажать(ЖИРНЫЙ, было, место(было, '**Ушки** **по бокам**'));
    expect(текст).toBe('Ушки по бокам включаются.\n');
  });

  it('звёздочка человека без пары остаётся на месте: это его текст, а не разметка', () => {
    const было = 'Ширина 2 * 3 метра.\n';
    const {текст} = нажать(КУРСИВ, было, место(было, '2 * 3'));
    expect(текст).toBe('Ширина *2 * 3* метра.\n');
    expect(текст.replace(/^Ширина \*|\* метра/g, '')).toContain('2 * 3');
  });
});

describe('правка доходит до окна, а не только до чистого правила', () => {
  /** Настоящее состояние редактора с картой поверхности — тем же фильтром, что стоит в окне. */
  function вОкне(text: string, at: Selection, button: Button): {текст: string; выделено: string} {
    const state = EditorState.create({
      doc: text,
      selection: EditorSelection.range(at.from, at.to),
      extensions: [markdown({addKeymap: false}), поверхностьРедактирования({})],
    });
    const edit = decideEdit(button, text, at, {settings: {} as never, articlePath: ''}) as Edit;
    const итог = state.update({
      changes: {from: edit.from, to: edit.to, insert: edit.insert},
      selection: edit.select
        ? {anchor: edit.from + edit.select.from, head: edit.from + edit.select.to}
        : {anchor: edit.from + (edit.caret ?? edit.insert.length)},
    }).state;
    const {from, to} = итог.selection.main;
    return {текст: итог.doc.toString(), выделено: итог.doc.sliceString(from, to)};
  }

  it('снятие жирности проходит фильтр поверхности: знаки уходят из текста окна', () => {
    const жирно = 'Параметр **Ушки по бокам** включаются.\n';
    const итог = вОкне(жирно, место(жирно, 'Ушки по бокам'), ЖИРНЫЙ);
    expect(итог.текст).toBe('Параметр Ушки по бокам включаются.\n');
    expect(итог.выделено).toBe('Ушки по бокам');
  });

  it('снятие жирности внутри блока-совета не рушит его границы', () => {
    const блок = ':::tip\nПараметр **Ушки** включаются.\n:::\n';
    const итог = вОкне(блок, место(блок, 'Ушки'), ЖИРНЫЙ);
    expect(итог.текст).toBe(':::tip\nПараметр Ушки включаются.\n:::\n');
  });
});

describe('пара знаков переживает перенос строки внутри абзаца', () => {
  // Абзац из двух строк: сайт склеит их в одну, и пара знаков законно живёт через перенос.
  const АБЗАЦ = 'Ушки по бокам\nвключаются к изголовью.\n';

  it('«Жирный» на двух строках абзаца пишет одну пару знаков', () => {
    const {текст} = нажать(ЖИРНЫЙ, АБЗАЦ, место(АБЗАЦ, 'Ушки по бокам\nвключаются к изголовью.'));
    expect(текст).toBe('**Ушки по бокам\nвключаются к изголовью.**\n');
    expect(разметка(текст)).toEqual(['жирный:Ушки по бокам\nвключаются к изголовью.']);
  });

  it('повторный «Жирный» по одной строке снимает пару целиком, а не пишет вторую', () => {
    const жирно = нажать(ЖИРНЫЙ, АБЗАЦ, место(АБЗАЦ, 'Ушки по бокам\nвключаются к изголовью.')).текст;
    const {текст} = нажать(ЖИРНЫЙ, жирно, место(жирно, 'Ушки по бокам'));
    expect(текст).toBe(АБЗАЦ);
    expect(текст.includes('*')).toBe(false);
  });

  it('повторный «Курсив» по одной строке снимает пару целиком и не оставляет одиночной звёздочки', () => {
    const курсивом = нажать(КУРСИВ, АБЗАЦ, место(АБЗАЦ, 'Ушки по бокам\nвключаются к изголовью.')).текст;
    expect(курсивом).toBe('*Ушки по бокам\nвключаются к изголовью.*\n');
    const {текст} = нажать(КУРСИВ, курсивом, место(курсивом, 'включаются к изголовью.'));
    expect(текст).toBe(АБЗАЦ);
    expect(текст.includes('*')).toBe(false);
  });

  it('снятие по второй строке возвращает выделенным весь кусок пары', () => {
    const жирно = '**Ушки по бокам\nвключаются к изголовью.**\n';
    const {выделено} = нажать(ЖИРНЫЙ, жирно, место(жирно, 'включаются'));
    expect(выделено).toBe('Ушки по бокам\nвключаются к изголовью.');
  });

  it('пустая строка абзац закрывает: соседний абзац своей парой не считается', () => {
    const два = '**Ушки** по бокам.\n\nДругой абзац **тут**.\n';
    const {текст} = нажать(ЖИРНЫЙ, два, место(два, 'по бокам'));
    expect(текст).toBe('**Ушки** **по бокам**.\n\nДругой абзац **тут**.\n');
    expect(разметка(текст)).toEqual(['жирный:Ушки', 'жирный:по бокам', 'жирный:тут']);
  });

  it('звёздочки внутри огороженного кода не считаются парой соседнего абзаца', () => {
    const скод = 'Текст **жирный** тут.\n```\na ** b\n```\n';
    const {текст} = нажать(ЖИРНЫЙ, скод, место(скод, 'жирный'));
    expect(текст).toBe('Текст жирный тут.\n```\na ** b\n```\n');
  });
});
