// Имя каждого теста повторяет формулировку правила.
// Начало одной языковой версии у статьи, которая уже есть: что и куда ляжет. Диска здесь нет.
import {describe, expect, it} from 'vitest';
import matter from 'gray-matter';

import {планЛокали} from '../src/core/localeVersion.mjs';
import {ES, EN, RU, НАСТРОЙКИ} from './newArticleHarness.mjs';

const СТАТЬЯ = `${RU}/lessons/uskorit-revit/index.mdx`;
const план = (правки = {}) => планЛокали({
  путь: СТАТЬЯ,
  локаль: 'es',
  slug: '/lessons/uskorit-revit',
  название: 'Как ускорить Revit',
  дата: '',
  settings: НАСТРОЙКИ,
  ...правки,
});

describe('начало языковой версии', () => {
  it('версия ложится в папку своего языка по тому же пути внутри раздела', () => {
    // Реестр сшивает языки ПО ПУТИ: разойдись он на букву — программа покажет две статьи.
    expect(план().path).toBe(`${ES}/lessons/uskorit-revit/index.mdx`);
    expect(план({локаль: 'en'}).path).toBe(`${EN}/lessons/uskorit-revit/index.mdx`);
  });

  it('адрес берётся у существующей версии и не пересчитывается из названия', () => {
    // У старых статей адрес давно свой: посчитай его заново — переключатель языков на сайте
    // увёл бы читателя в пустоту, а менять адрес живой страницы нельзя вовсе (SPEC 2.5).
    const {text} = план({slug: '/lessons/staryy-adres-2019', название: 'Совсем другое название'});

    expect(matter(text).data.slug).toBe('/lessons/staryy-adres-2019');
  });

  it('новая версия рождается скрытой заглушкой на своём языке, а не копией чужого текста', () => {
    // Текст одной локали не копируется в другую и не выдаётся за перевод молча.
    const {text} = план();
    const шапка = matter(text);

    expect(шапка.data.unlisted).toBe(true);
    expect(шапка.data.title).toBe('Marcador de traducción: Как ускорить Revit');
    expect(шапка.data.description).toBe('Página marcador.');
    expect(text).toContain('Marcador.');
  });

  it('версия начинается вместе со своим состоянием: половины работы не остаётся', () => {
    const {состояние} = план();

    expect(состояние.path).toBe(`${ES}/lessons/uskorit-revit/_state.json`);
    expect(JSON.parse(состояние.text).готовность).toBe('Черновик');
  });

  it('начать можно и от соседней заглушки: её пометка в название новой не переезжает', () => {
    // Иначе вышло бы «Marcador de traducción: Translation placeholder: Название».
    const {text} = планЛокали({
      путь: `${EN}/lessons/uskorit-revit/index.mdx`,
      локаль: 'es',
      slug: '/lessons/uskorit-revit',
      название: 'Как ускорить Revit',
      дата: '',
      settings: НАСТРОЙКИ,
    });

    expect(matter(text).data.title).toBe('Marcador de traducción: Как ускорить Revit');
  });

  it('свой же язык версией не считается: это открытие того, что уже открыто', () => {
    expect(план({локаль: 'ru'})).toEqual({ошибка: 'локальУжеЕсть'});
  });

  it('языка нет у этого рода — отказ, а не запись в выдуманную папку', () => {
    // Так живёт песочница: она вне сайта и знает один язык.
    expect(планЛокали({
      путь: 'editor/sandbox/proba/index.mdx', локаль: 'es', slug: 'proba',
      название: 'Проба', дата: '', settings: НАСТРОЙКИ,
    })).toEqual({ошибка: 'нетЯзыкаВРазделе'});
  });

  it('текста заглушки для языка нет — не создаётся ничего, вместо чужого языка в файле', () => {
    const безИспанской = {
      ...НАСТРОЙКИ,
      заглушкиПеревода: {ru: НАСТРОЙКИ.заглушкиПеревода.ru, en: НАСТРОЙКИ.заглушкиПеревода.en},
    };

    expect(план({settings: безИспанской})).toEqual({ошибка: 'нетШаблонаЗаглушки'});
  });

  it('у существующей версии нет адреса — строка адреса не пишется, а не выдумывается', () => {
    // Так живут страницы разделов: Docusaurus выводит их адрес из пути, а путь у языковых версий
    // один и тот же. Вписать сюда придуманный адрес значило бы сменить адрес живой страницы,
    // а отказать — оставить человека без входа в локаль у двенадцати статей сайта.
    const {text, ошибка} = план({slug: ''});

    expect(ошибка).toBe(undefined);
    expect(text).not.toContain('slug:');
  });

  it('автор записи блога переносится из исходной версии, а не берётся из настроек', () => {
    // Иначе перевод чужой записи молча вышел бы за подписью того, кто её не писал.
    const {text} = планЛокали({
      путь: 'i18n/ru/docusaurus-plugin-content-blog/kak-uskorit/index.mdx',
      локаль: 'es', slug: 'kak-uskorit', название: 'Как ускорить',
      дата: '2026-07-17', авторы: '[maria, oleg]', settings: НАСТРОЙКИ,
    });

    expect(text).toContain('authors: [maria, oleg]');
    expect(text).not.toContain('[ivan]');
  });

  it('автора у исходной версии нет — берётся умолчание настроек, а не пустая строка', () => {
    const {text} = планЛокали({
      путь: 'i18n/ru/docusaurus-plugin-content-blog/kak-uskorit/index.mdx',
      локаль: 'es', slug: 'kak-uskorit', название: 'Как ускорить',
      дата: '2026-07-17', авторы: '', settings: НАСТРОЙКИ,
    });

    expect(text).toContain('authors: [ivan]');
  });

  it('файл не из известных корней соседей не имеет, и версия по нему не начинается', () => {
    expect(планЛокали({
      путь: 'README.md', локаль: 'es', slug: 'readme', название: 'Про репозиторий',
      дата: '', settings: НАСТРОЙКИ,
    })).toEqual({ошибка: 'неПутьСтатьи'});
  });

  it('дата записи блога берётся у существующей версии, а не ставится сегодняшняя', () => {
    // Своя дата у перевода развела бы языковые версии одной записи по разным дням ленты.
    const {text} = планЛокали({
      путь: 'i18n/ru/docusaurus-plugin-content-blog/kak-uskorit/index.mdx',
      локаль: 'es', slug: 'kak-uskorit', название: 'Как ускорить',
      дата: '2026-07-17', settings: НАСТРОЙКИ,
    });

    expect(text).toContain('date: 2026-07-17');
  });
});
