// Имя каждого теста повторяет формулировку правила.
// Уровень пункта списка клавишами: `Tab` вкладывает, `Shift+Tab` возвращает наружу.
import {describe, expect, it} from 'vitest';
import {вложить, поднять, вСписке} from '../src/core/listIndent';

/** Применяет правку к тексту так же, как это делает окно. */
function применить(текст: string, правка: {from: number; to: number; insert: string} | null): string {
  if (!правка) return текст;
  return текст.slice(0, правка.from) + правка.insert + текст.slice(правка.to);
}

/** Позиция конца названной строки — курсор человека стоит там, где он допечатал пункт. */
function конец(текст: string, строка: string): number {
  return текст.indexOf(строка) + строка.length;
}

const курсор = (текст: string, строка: string) => ({from: конец(текст, строка), to: конец(текст, строка)});

describe('вложение пункта маркированного списка', () => {
  const текст = '- первый пункт\n- второй пункт\n- третий пункт\n';

  it('пункт встаёт в колонку содержимого предыдущего пункта, а не на выбранное число пробелов', () => {
    expect(применить(текст, вложить(текст, курсор(текст, '- второй пункт'))))
      .toBe('- первый пункт\n  - второй пункт\n- третий пункт\n');
  });

  it('возврат наружу ставит пункт обратно на уровень родителя', () => {
    const вложено = '- первый пункт\n  - второй пункт\n- третий пункт\n';
    expect(применить(вложено, поднять(вложено, курсор(вложено, '  - второй пункт'))))
      .toBe(текст);
  });

  it('первый пункт списка вложить не во что — текст остаётся прежним', () => {
    expect(вложить(текст, курсор(текст, '- первый пункт'))).toBeNull();
  });

  it('пункт без отступа возвращать некуда — текст остаётся прежним', () => {
    expect(поднять(текст, курсор(текст, '- второй пункт'))).toBeNull();
  });

  it('уже вложенный первый ребёнок глубже не уходит', () => {
    const вложено = '- первый пункт\n  - второй пункт\n';
    expect(вложить(вложено, курсор(вложено, '  - второй пункт'))).toBeNull();
  });
});

describe('вложение пункта нумерованного списка', () => {
  const текст = '1. один\n2. два\n3. три\n';

  it('вложенный пункт встаёт в колонку содержимого нумерованного родителя', () => {
    expect(применить(текст, вложить(текст, курсор(текст, '2. два'))))
      .toBe('1. один\n   1. два\n3. три\n');
  });

  // Номер один здесь обязателен: вложенный список открывается внутри абзаца родителя, и в
  // CommonMark открыть его может только пункт с номером один. С двойкой строка осталась бы
  // простым текстом внутри первого пункта, а не вложенным списком.
  it('ставший первым на новом уровне пункт получает номер один, соседние номера не меняются', () => {
    const вышло = применить(текст, вложить(текст, курсор(текст, '2. два')));
    expect(вышло).toContain('   1. два');
    expect(вышло).toContain('3. три');
  });

  it('пункт, вставший вторым на новом уровне, свой номер сохраняет', () => {
    const текст = '1. один\n   1. вложенный\n2. два\n';
    expect(применить(текст, вложить(текст, курсор(текст, '2. два'))))
      .toBe('1. один\n   1. вложенный\n   2. два\n');
  });

  it('колонка широкого маркера считается по нему самому, а не по одному пробелу', () => {
    const текст = '10. десять\n11. одиннадцать\n';
    expect(применить(текст, вложить(текст, курсор(текст, '11. одиннадцать'))))
      .toBe('10. десять\n    1. одиннадцать\n');
  });

  it('возврат наружу номер пункта не переписывает', () => {
    const текст = '1. один\n   1. два\n';
    expect(применить(текст, поднять(текст, курсор(текст, '   1. два'))))
      .toBe('1. один\n1. два\n');
  });
});

describe('пункт вместе со своим поддеревом', () => {
  it('вложение уводит за пунктом вложенные под ним пункты', () => {
    const текст = '- первый\n- второй\n  - под вторым\n- третий\n';
    expect(применить(текст, вложить(текст, курсор(текст, '- второй'))))
      .toBe('- первый\n  - второй\n    - под вторым\n- третий\n');
  });

  it('возврат наружу уводит за пунктом продолжение его текста', () => {
    const текст = '- первый\n  - второй\n    вторая строка пункта\n- третий\n';
    expect(применить(текст, поднять(текст, курсор(текст, '  - второй'))))
      .toBe('- первый\n- второй\n  вторая строка пункта\n- третий\n');
  });

  it('соседний пункт того же уровня поддеревом не считается', () => {
    const текст = '- первый\n- второй\n- третий\n';
    expect(применить(текст, вложить(текст, курсор(текст, '- второй'))))
      .toBe('- первый\n  - второй\n- третий\n');
  });
});

describe('границы правила', () => {
  it('пустой пункт двигается наравне с заполненным', () => {
    const текст = '- первый\n- \n';
    const пустой = текст.lastIndexOf('- ') + 2;
    expect(применить(текст, вложить(текст, {from: пустой, to: пустой})))
      .toBe('- первый\n  - \n');
  });

  it('строка обычного текста правилу не подчиняется', () => {
    const текст = 'обычный абзац\nещё строка\n';
    expect(вложить(текст, курсор(текст, 'ещё строка'))).toBeNull();
    expect(вСписке(текст, курсор(текст, 'ещё строка'))).toBe(false);
  });

  it('похожая на пункт строка внутри огороженного кода не двигается', () => {
    const текст = '```\n- первый\n- второй\n```\n';
    expect(вложить(текст, курсор(текст, '- второй'))).toBeNull();
    expect(вСписке(текст, курсор(текст, '- второй'))).toBe(false);
  });

  it('короткая ограда внутри длинной код не заканчивает, и строки за ней остаются кодом', () => {
    const текст = '````\n```\n- первый\n- второй\n```\n````\n';
    expect(вложить(текст, курсор(текст, '- второй'))).toBeNull();
    expect(поднять(текст, курсор(текст, '- второй'))).toBeNull();
    expect(вСписке(текст, курсор(текст, '- второй'))).toBe(false);
  });

  it('похожая на пункт строка отступного кода не двигается: отступ там и есть сам код', () => {
    const текст = 'Обычный абзац:\n\n    - строка кода\n    - вторая строка кода\n';
    expect(поднять(текст, курсор(текст, '    - вторая строка кода'))).toBeNull();
    expect(вложить(текст, курсор(текст, '    - вторая строка кода'))).toBeNull();
    expect(вСписке(текст, курсор(текст, '    - строка кода'))).toBe(false);
  });

  it('пункт с тем же отступом внутри списка отступным кодом не считается', () => {
    const текст = '- первый\n  - второй\n  - третий\n';
    expect(применить(текст, вложить(текст, курсор(текст, '  - третий'))))
      .toBe('- первый\n  - второй\n    - третий\n');
  });

  it('дефис без пробела пунктом не считается', () => {
    const текст = '- первый\n-второй\n';
    expect(вложить(текст, курсор(текст, '-второй'))).toBeNull();
  });

  it('список после обычного абзаца не считает старшим пунктом строку выше абзаца', () => {
    const текст = '- чужой список\n\nабзац между списками\n\n- первый\n- второй\n';
    expect(применить(текст, вложить(текст, курсор(текст, '- второй'))))
      .toBe('- чужой список\n\nабзац между списками\n\n- первый\n  - второй\n');
    expect(вложить(текст, курсор(текст, '- первый'))).toBeNull();
  });

  it('отступ табуляцией правило не пересчитывает', () => {
    const текст = '- первый\n\t- второй\n';
    expect(поднять(текст, курсор(текст, '\t- второй'))).toBeNull();
  });

  it('курсор остаётся в том же месте текста пункта', () => {
    const текст = '- первый пункт\n- второй пункт\n';
    const правка = вложить(текст, курсор(текст, '- второй'))!;
    const вышло = применить(текст, правка);
    const позиция = правка.from + (правка.caret ?? 0);
    expect(вышло.slice(0, позиция)).toBe('- первый пункт\n  - второй');
  });
});
