// Имя каждого теста повторяет формулировку правила.
// Правила первого коммита статьи: заслон перед единственным местом, которое меняет git.
import {describe, expect, it} from 'vitest';

import {ВЕТКА_ВЫПУСКА, индексВПеречне, решениеОКоммите} from '../src/core/publish.mjs';

const RU = 'i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba/index.mdx';
const EN = 'docs/lessons/proba/index.mdx';

const СОСТАВ = {файлы: [{путь: EN, назначение: 'версия'}, {путь: RU, назначение: 'версия'}], разрывы: []};

const годно = (ещё = {}) => ({
  ветка: ВЕТКА_ВЫПУСКА,
  индекс: [],
  состав: СОСТАВ,
  сборкаЗелёная: true,
  отпечатокСборки: 'abc',
  отпечатокСейчас: 'abc',
  ...ещё,
});

describe('решение о коммите статьи', () => {
  it('всё сошлось — коммит разрешён ровно по путям состава', () => {
    expect(решениеОКоммите(годно())).toEqual({пути: [EN, RU]});
  });

  it('ветка не та — отказ: переключать ветки программа не смеет', () => {
    expect(решениеОКоммите(годно({ветка: 'proba'}))).toMatchObject({ошибка: 'неТаВетка', ветка: 'proba'});
  });

  it('в индексе лежит чужая работа — отказ до всякой операции', () => {
    const решение = решениеОКоммите(годно({индекс: ['docs/чужое.mdx']}));

    expect(решение).toMatchObject({ошибка: 'индексНеПуст'});
    expect(решение.пути).toBeUndefined();
  });

  it('состав не доказан — коммита нет: в него уехало бы то, чего человеку не показывали', () => {
    const сРазрывом = {файлы: СОСТАВ.файлы, разрывы: [{причина: 'папкаНеОдна'}]};

    expect(решениеОКоммите(годно({состав: сРазрывом}))).toMatchObject({ошибка: 'составНеДоказан'});
    expect(решениеОКоммите(годно({состав: {файлы: [], разрывы: []}}))).toMatchObject({ошибка: 'составНеДоказан'});
  });

  it('без зелёной полной сборки коммита нет', () => {
    expect(решениеОКоммите(годно({сборкаЗелёная: false}))).toMatchObject({ошибка: 'нетЗелёнойСборки'});
    expect(решениеОКоммите(годно({сборкаЗелёная: undefined}))).toMatchObject({ошибка: 'нетЗелёнойСборки'});
  });

  it('статья изменилась после сборки — коммита нет: зелёная сборка отвечает за прежний текст', () => {
    expect(решениеОКоммите(годно({отпечатокСейчас: 'другой'}))).toMatchObject({ошибка: 'статьяИзменилась'});
    // Отпечатка сборки нет вовсе — то же самое: сверять не с чем.
    expect(решениеОКоммите(годно({отпечатокСборки: null}))).toMatchObject({ошибка: 'статьяИзменилась'});
  });

  it('ветка проверяется раньше всего: на чужой ветке не спрашивают даже про сборку', () => {
    const решение = решениеОКоммите(годно({ветка: 'proba', сборкаЗелёная: false, индекс: ['чужое']}));

    expect(решение.ошибка).toBe('неТаВетка');
  });
});

describe('сверка индекса с утверждённым перечнем', () => {
  it('индекс, совпавший с перечнем, лишнего не показывает', () => {
    expect(индексВПеречне([EN, RU], [EN, RU])).toEqual([]);
  });

  it('индекс уже перечня — это не беда: неизменившийся файл в индекс не попадает', () => {
    expect(индексВПеречне([RU], [EN, RU])).toEqual([]);
  });

  it('лишний путь в индексе назван поимённо: в коммит уехало бы чужое', () => {
    expect(индексВПеречне([RU, 'docs/чужое.mdx'], [EN, RU])).toEqual(['docs/чужое.mdx']);
  });
});
