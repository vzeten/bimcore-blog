// Имя каждого теста повторяет формулировку правила.
// Трёхстороннее сведение единиц: ни файлов, ни git — только правило.
import {describe, expect, it} from 'vitest';

import {свестиЕдиницы, собратьЕдиницы, споров} from '../src/core/mergeUnits.mjs';

/** Короткая запись: свести три стороны и собрать итог без единого ответа человека. */
const свести = (база, мои, внешние) => {
  const части = свестиЕдиницы(база, мои, внешние);
  return {части, споров: споров(части), итог: собратьЕдиницы(части, {})};
};

describe('сведение непересекающихся правок', () => {
  it('стороны тронули разные места — обе правки в итоге, спора нет', () => {
    const {споров: споры, итог} = свести(['а', 'б', 'в'], ['МОЁ', 'б', 'в'], ['а', 'б', 'ВНЕШНЕЕ']);

    expect(споры).toBe(0);
    expect(итог).toEqual(['МОЁ', 'б', 'ВНЕШНЕЕ']);
  });

  it('одна сторона дописала в конец, другая правила начало — обе правки целы', () => {
    const {споров: споры, итог} = свести(['а', 'б'], ['МОЁ', 'б'], ['а', 'б', 'НОВОЕ']);

    expect(споры).toBe(0);
    expect(итог).toEqual(['МОЁ', 'б', 'НОВОЕ']);
  });

  it('одна сторона удалила единицу, другая её не трогала — удаление остаётся', () => {
    const {споров: споры, итог} = свести(['а', 'б', 'в'], ['а', 'б', 'в'], ['а', 'в']);

    expect(споры).toBe(0);
    expect(итог).toEqual(['а', 'в']);
  });

  it('никто ничего не менял — итог равен базе', () => {
    expect(свести(['а', 'б'], ['а', 'б'], ['а', 'б']).итог).toEqual(['а', 'б']);
  });
});

describe('порядок правок берётся у базы, а не у сторон', () => {
  it('внешняя правка стоит РАНЬШЕ человеческой — обе встают на свои места', () => {
    // Начни разбор всегда с человеческой правки — более ранняя внешняя осталась бы позади уже
    // пройденного места и вышла бы в итог не туда, где она на самом деле.
    const {споров: споры, итог} = свести(
      ['первая', 'вторая'],
      ['первая', 'МОЯ'],
      ['ВНЕШНЯЯ', 'вторая'],
    );

    expect(споры).toBe(0);
    expect(итог).toEqual(['ВНЕШНЯЯ', 'МОЯ']);
  });

  it('порядок не зависит от того, чья правка раньше: зеркальный случай даёт то же самое', () => {
    const {итог} = свести(
      ['первая', 'вторая'],
      ['МОЯ', 'вторая'],
      ['первая', 'ВНЕШНЯЯ'],
    );

    expect(итог).toEqual(['МОЯ', 'ВНЕШНЯЯ']);
  });

  it('правки чередуются по всей базе — каждая остаётся на своём месте', () => {
    const {споров: споры, итог} = свести(
      ['а', 'б', 'в', 'г'],
      ['а', 'Б2', 'в', 'Г2'],
      ['А1', 'б', 'В1', 'г'],
    );

    expect(споры).toBe(0);
    expect(итог).toEqual(['А1', 'Б2', 'В1', 'Г2']);
  });
});

describe('одинаковый итог не считается расхождением', () => {
  it('обе стороны привели одно место к одному значению — спора нет', () => {
    const {споров: споры, итог} = свести(['а'], ['ОДНО'], ['ОДНО']);

    expect(споры).toBe(0);
    expect(итог).toEqual(['ОДНО']);
  });

  it('обе стороны удалили одну и ту же единицу — спора нет', () => {
    expect(свести(['а', 'б'], ['а'], ['а']).споров).toBe(0);
  });
});

describe('пересечение решает человек, а не программа', () => {
  it('стороны правили одно место по-разному — это спор, и сборки без ответа нет', () => {
    const {части, споров: споры, итог} = свести(['а'], ['МОЁ'], ['ВНЕШНЕЕ']);

    expect(споры).toBe(1);
    expect(итог).toBeNull();
    expect(части[0]).toEqual({вид: 'спор', база: ['а'], мои: ['МОЁ'], внешние: ['ВНЕШНЕЕ']});
  });

  it('обе стороны вставили своё в одно и то же место — это спор, а не склейка по порядку', () => {
    // Сложи программа обе вставки подряд, порядок выбрала бы она, а не человек.
    expect(свести(['а', 'б'], ['а', 'МОЁ', 'б'], ['а', 'ВНЕШНЕЕ', 'б']).споров).toBe(1);
  });

  it('одна сторона удалила единицу, другая её правила — это спор', () => {
    expect(свести(['а', 'б'], ['а', 'МОЁ'], ['а']).споров).toBe(1);
  });

  it('ответ человека по спорному месту собирает выбранную сторону', () => {
    const части = свестиЕдиницы(['а', 'б'], ['МОЁ', 'б'], ['ВНЕШНЕЕ', 'б']);

    expect(собратьЕдиницы(части, {0: 'мои'})).toEqual(['МОЁ', 'б']);
    expect(собратьЕдиницы(части, {0: 'внешние'})).toEqual(['ВНЕШНЕЕ', 'б']);
  });

  it('спорных мест несколько — без ответа на каждое сборки нет', () => {
    // Между спорами стоит нетронутая единица: иначе два соседних пересечения — одно место,
    // и спрашивать о них порознь значило бы дробить один и тот же выбор.
    const части = свестиЕдиницы(['а', 'тихо', 'б'], ['М1', 'тихо', 'М2'], ['В1', 'тихо', 'В2']);

    expect(споров(части)).toBe(2);
    expect(собратьЕдиницы(части, {0: 'мои'})).toBeNull();
    expect(собратьЕдиницы(части, {0: 'мои', 1: 'внешние'})).toEqual(['М1', 'тихо', 'В2']);
  });

  it('два соседних пересечения без тихого места между ними — один спор, а не два', () => {
    expect(споров(свестиЕдиницы(['а', 'б'], ['М1', 'М2'], ['В1', 'В2']))).toBe(1);
  });
});
