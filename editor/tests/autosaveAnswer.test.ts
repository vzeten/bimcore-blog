// Имя каждого теста повторяет формулировку правила.
// Ответ сервера на автосохранение: когда он годится окну, а когда уже устарел.
// Отдельным файлом от остальной очереди пределом размера (SPEC 4.9): правило про ответ выросло
// в свой круг проверок, а очередь и без него полна.
import {describe, expect, it, vi} from 'vitest';
import {createAutosaveQueue, type DraftPayload} from '../src/ui/autosaveQueue';

const правка = (over: Partial<DraftPayload> = {}): DraftPayload => ({
  path: 'docs/a/index.mdx',
  body: 'набранный текст',
  frontmatterRaw: 'title: A',
  отпечатокБазы: 'ОТП1',
  ...over,
});

describe('ответ сервера окну отдаётся, только пока он не устарел', () => {
  /** Запись, которая отвечает не сразу: каждый запрос ждёт отдельного разрешения. */
  function поЗапросам() {
    const вызовы: {данные: DraftPayload; ответить: () => void}[] = [];

    const запись = vi.fn((данные: DraftPayload, effects: {ok: (ответ?: unknown) => void}) => (
      new Promise<void>((готово) => {
        вызовы.push({
          данные,
          ответить: () => {
            effects.ok({path: данные.path, сведено: {body: 'сведено сервером', frontmatterRaw: 'title: A'}});
            готово();
          },
        });
      })
    ));

    return {вызовы, запись: запись as never};
  }

  const подождать = () => new Promise((r) => setTimeout(r, 10));

  it('человек набрал во время автосохранения — ответ прежней записи в окно не идёт', async () => {
    // Ответ не видел последней буквы. Подставь его окно — буква была бы заменена старым текстом
    // и вытеснена из свежего черновика.
    const ответы: unknown[] = [];
    const {вызовы, запись} = поЗапросам();
    const очередь = createAutosaveQueue(() => 0, () => undefined, запись, (ответ) => ответы.push(ответ));

    очередь.запланировать(правка());
    await подождать();
    очередь.запланировать(правка({body: 'новая буква'}));
    вызовы[0].ответить();
    await подождать();

    expect(ответы).toHaveLength(0);
  });

  it('за время записи ничего не набрали — ответ доходит до окна целиком', async () => {
    const ответы: unknown[] = [];
    const {вызовы, запись} = поЗапросам();
    const очередь = createAutosaveQueue(() => 0, () => undefined, запись, (ответ) => ответы.push(ответ));

    очередь.запланировать(правка());
    await подождать();
    вызовы[0].ответить();
    await подождать();

    expect(ответы).toHaveLength(1);
  });

  it('правка во время ухода из статьи тоже обесценивает ответ прежней записи', async () => {
    const ответы: unknown[] = [];
    const {вызовы, запись} = поЗапросам();
    const очередь = createAutosaveQueue(() => 3, () => undefined, запись, (ответ) => ответы.push(ответ));

    очередь.запланировать(правка());
    const уход = очередь.дописать();
    await подождать();
    очередь.запланировать(правка({body: 'набрал во время ухода'}));
    вызовы[0].ответить();
    await подождать();

    expect(ответы).toHaveLength(0);

    // Свежую правку дописывание всё равно увозит, и её ответ окну уже годится.
    вызовы[1].ответить();
    await уход;
    expect(ответы).toHaveLength(1);
  });
});

describe('уход из статьи не теряет правку, набранную во время записи', () => {
  /** Запись, у которой каждый запрос ждёт своего ответа, а ответ выбирает вызывающий. */
  function поОтветам() {
    const вызовы: {данные: DraftPayload; ответить: (ответ?: unknown) => void}[] = [];

    const запись = vi.fn((данные: DraftPayload, effects: {ok: (ответ?: unknown) => void}) => (
      new Promise<void>((готово) => {
        вызовы.push({
          данные,
          ответить: (ответ) => {
            effects.ok(ответ);
            готово();
          },
        });
      })
    ));

    return {вызовы, запись: запись as never};
  }

  const тик = () => new Promise((r) => setTimeout(r, 10));

  it('старый запрос ответил «устарел», а пока он шёл, набралась новая правка — уезжает новая', async () => {
    // Перештампованная старая правка встала бы на место свежей, и уход сказал бы «всё записано»
    // про букву, которой нет ни в файле, ни в черновике.
    const {вызовы, запись} = поОтветам();
    const очередь = createAutosaveQueue(() => 3, () => undefined, запись);

    очередь.запланировать(правка());
    const уход = очередь.дописать();
    await тик();
    очередь.запланировать(правка({body: 'новая буква'}));

    let ушёл: boolean | null = null;
    void уход.then((итог) => {
      ушёл = итог;
    });

    вызовы[0].ответить({устарел: true});
    await тик();

    // Ложного успеха до записи новой правки нет: уход всё ещё ждёт.
    expect(ушёл).toBeNull();
    expect(вызовы).toHaveLength(2);
    expect(вызовы[1].данные.body).toBe('новая буква');

    вызовы[1].ответить({автосохранено: '2026-09-11T10:00:00.000Z'});
    expect(await уход).toBe(true);
    expect(вызовы.map((в) => в.данные.body)).toEqual(['набранный текст', 'новая буква']);
  });

  it('за время записи ничего не набрали — «устарел» пробуется ещё раз той же правкой', async () => {
    // Правило повтора не отменяется: своя метка строго возрастает, и второй заход окажется свежее.
    const {вызовы, запись} = поОтветам();
    const очередь = createAutosaveQueue(() => 3, () => undefined, запись);

    очередь.запланировать(правка());
    const уход = очередь.дописать();
    await тик();
    вызовы[0].ответить({устарел: true});
    await тик();

    expect(вызовы).toHaveLength(2);
    expect(вызовы[1].данные.body).toBe('набранный текст');
    expect(String(вызовы[1].данные.правкаОт) > String(вызовы[0].данные.правкаОт)).toBe(true);

    вызовы[1].ответить({автосохранено: '2026-09-11T10:00:00.000Z'});
    expect(await уход).toBe(true);
  });
});
