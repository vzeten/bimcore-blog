// Имя каждого теста повторяет формулировку правила.
// Клавиши поверхности на настоящем состоянии редактора с картой: команды раскладки применяются
// как транзакции, и проверяется итоговый текст с положением курсора.
import {describe, expect, it} from 'vitest';
import {EditorSelection, EditorState, type TransactionSpec} from '@codemirror/state';
import type {EditorView} from '@codemirror/view';
import {ensureSyntaxTree} from '@codemirror/language';
import {markdown} from '@codemirror/lang-markdown';
import {блокВ, поверхностьРедактирования} from '../src/ui/editor/structureGuard';
import {клавишиПоверхности} from '../src/ui/editor/surfaceKeys';
import type {ОписаниеБлока} from '../src/ui/types';

const БЛОКИ: Record<string, ОписаниеБлока> = {
  ProductCard: {подпись: 'Товар', поля: []},
  YouTube: {подпись: 'Видео', поля: []},
};

const КАРТОЧКА = [
  "import productPreview from './product.jpg';",
  '',
  'Текст.',
  '',
  '<ProductCard',
  '  name="Кресла"',
  '  image={productPreview}',
  '/>',
  '',
  'После.',
].join('\n');

function состояние(текст: string, курсор: number, конец = курсор, толькоЧтение = false): EditorState {
  const state = EditorState.create({
    doc: текст,
    selection: EditorSelection.single(курсор, конец),
    extensions: [markdown(), поверхностьРедактирования(БЛОКИ), ...(толькоЧтение ? [EditorState.readOnly.of(true)] : [])],
  });
  ensureSyntaxTree(state, state.doc.length, 1_000);
  return state;
}

/** Нажатие клавиши: команда раскладки на настоящем состоянии, транзакция применяется как в окне. */
function нажать(клавиша: string, state: EditorState) {
  const правило = клавишиПоверхности.find((b) => b.key === клавиша);
  if (!правило?.run) throw new Error(`клавиша ${клавиша} не назначена`);

  let итог = state;
  const view = {state, dispatch: (spec: TransactionSpec) => { итог = state.update(spec).state; }} as unknown as EditorView;
  const сработала = правило.run(view);
  const главное = итог.selection.main;
  return {сработала, текст: итог.doc.toString(), курсор: главное.head, выбор: [главное.from, главное.to]};
}

describe('Enter создаёт ровно один следующий абзац, и курсор сразу в нём', () => {
  it('посреди абзаца текст делится на два абзаца, курсор — в начале второго', () => {
    expect(нажать('Enter', состояние('Первый абзац.', 7))).toMatchObject({текст: 'Первый \n\nабзац.', курсор: 9});
  });

  it('в конце абзаца перед следующим появляется пустой абзац, курсор в нём', () => {
    expect(нажать('Enter', состояние('Абзац.\n\nВторой.', 6))).toMatchObject({текст: 'Абзац.\n\n\n\nВторой.', курсор: 8});
  });

  it('в конце последнего абзаца перед последней пустой строкой хватает одного перевода', () => {
    expect(нажать('Enter', состояние('Абзац.\n', 6))).toMatchObject({текст: 'Абзац.\n\n', курсор: 8});
    expect(нажать('Enter', состояние('Абзац.', 6))).toMatchObject({текст: 'Абзац.\n\n', курсор: 8});
  });

  it('после заголовка начинается обычный абзац, даже если текст стоит вплотную', () => {
    expect(нажать('Enter', состояние('## Заголовок\nТекст', 12))).toMatchObject({текст: '## Заголовок\n\n\n\nТекст', курсор: 14});
  });

  it('в конце строки абзаца с мягким переносом делит абзац без пустого абзаца между', () => {
    expect(нажать('Enter', состояние('Первая строка,\nвторая строка.', 14))).toMatchObject({текст: 'Первая строка,\n\n\nвторая строка.', курсор: 17});
  });

  it('в примечании создаёт следующий абзац; из последнего пустого абзаца выводит под блок', () => {
    const внутри = нажать('Enter', состояние(':::tip\nТекст\n:::\n\nПосле.', 12));
    expect(внутри).toMatchObject({текст: ':::tip\nТекст\n\n\n:::\n\nПосле.', курсор: 14});

    // Под закрытием — разделитель и пустой абзац: текст под примечанием не прилипает к рамке.
    const выход = нажать('Enter', состояние(внутри.текст, внутри.курсор));
    expect(выход).toMatchObject({текст: ':::tip\nТекст\n:::\n\n\n\nПосле.', курсор: 18});
    expect(нажать('Enter', состояние(':::tip\nТекст\n\n\n:::', 14))).toMatchObject({текст: ':::tip\nТекст\n:::\n\n', курсор: 18});
    expect(нажать('Enter', состояние(':::tip\nТекст\n\n\n:::\nВплотную.', 14))).toMatchObject({текст: ':::tip\nТекст\n:::\n\n\n\nВплотную.', курсор: 18});
  });

  it('примечание без текста при выходе свою пустую строку сохраняет', () => {
    expect(нажать('Enter', состояние(':::tip\n\n:::', 7))).toMatchObject({текст: ':::tip\n\n:::\n\n', курсор: 13});
  });

  it('на пустой строке после жёсткого переноса косая уступает место абзацу', () => {
    expect(нажать('Enter', состояние('Строка\\\n', 8))).toMatchObject({текст: 'Строка\n\n', курсор: 8});
  });

  it('в списке, таблице, коде, с выделением и при запрете правки молчит', () => {
    expect(нажать('Enter', состояние('- пункт', 7)).сработала).toBe(false);
    expect(нажать('Enter', состояние('| а | б |\n|---|---|', 9)).сработала).toBe(false);
    expect(нажать('Enter', состояние('```\nкод\n```', 7)).сработала).toBe(false);
    expect(нажать('Enter', состояние('Абзац.', 1, 3)).сработала).toBe(false);
    expect(нажать('Enter', состояние('Абзац.', 6, 6, true)).сработала).toBe(false);
  });
});

describe('Shift+Enter — перенос внутри абзаца', () => {
  it('вставляет косую с переводом, курсор на новой строке того же абзаца; вне абзаца молчит', () => {
    expect(нажать('Shift-Enter', состояние('Абзац.', 6))).toMatchObject({текст: 'Абзац.\\\n', курсор: 8});
    expect(нажать('Shift-Enter', состояние('## Заголовок', 12)).сработала).toBe(false);
  });
});

describe('удаление у цельного блока: первое нажатие выбирает блок, выбранный удаляется целиком', () => {
  const текст = 'До.\n\n![a](./a.png)\n\nПосле.';
  const картинка = [текст.indexOf('![a]'), текст.indexOf('![a]') + '![a](./a.png)'.length] as const;

  it('Backspace под блоком и Delete над блоком выбирают блок и не трогают текст', () => {
    expect(нажать('Backspace', состояние(текст, текст.indexOf('После.')))).toMatchObject({сработала: true, текст, выбор: [...картинка]});
    expect(нажать('Delete', состояние(текст, 3))).toMatchObject({текст, выбор: [...картинка]});
  });

  it('выбранный блок уходит вместе со своим разделителем, абзацы остаются разделёнными', () => {
    expect(нажать('Backspace', состояние(текст, ...картинка))).toMatchObject({текст: 'До.\n\nПосле.', курсор: 5});
    expect(нажать('Delete', состояние(текст, ...картинка))).toMatchObject({текст: 'До.\n\nПосле.', курсор: 5});
  });

  it('блок в конце статьи уходит вместе с пустой строкой над ним', () => {
    const конец = 'До.\n\n![a](./a.png)';
    expect(нажать('Delete', состояние(конец, 5, конец.length))).toMatchObject({текст: 'До.\n', курсор: 3});
  });

  it('картинка внутри строки уходит ровно своим узлом, соседний текст и вторая картинка целы', () => {
    const строка = 'Текст ![b](./b.png) и ![c](./c.png).';
    const узел = блокВ(состояние(строка, 0), 8);
    expect(узел).toEqual({вид: 'блок', from: 6, to: 6 + '![b](./b.png)'.length});
    expect(нажать('Backspace', состояние(строка, узел!.from, узел!.to))).toMatchObject({текст: 'Текст  и ![c](./c.png).', курсор: 6});
  });

  it('видео на своей строке выбирается и удаляется так же, как картинка', () => {
    const видео = 'До.\n\n<YouTube id="x" />\n\nПосле.';
    const блок = [5, 5 + '<YouTube id="x" />'.length] as const;
    expect(нажать('Backspace', состояние(видео, видео.indexOf('После.'))).выбор).toEqual([...блок]);
    expect(нажать('Delete', состояние(видео, ...блок)).текст).toBe('До.\n\nПосле.');
  });

  it('единственная карточка товара забирает с собой скрытый импорт', () => {
    const карточка = [КАРТОЧКА.indexOf('<ProductCard'), КАРТОЧКА.indexOf('/>') + 2] as const;
    expect(нажать('Backspace', состояние(КАРТОЧКА, ...карточка))).toMatchObject({текст: 'Текст.\n\nПосле.'});
  });

  it('выделение, не равное блоку, удаляет штатная команда', () => {
    expect(нажать('Backspace', состояние(текст, 0, 2)).сработала).toBe(false);
  });
});

describe('удаление у разделителя и служебных строк', () => {
  it('у разделителя между абзацами с текстом клавиша молчит: штатная команда склеивает абзацы', () => {
    expect(нажать('Backspace', состояние('Первый.\n\nВторой.', 9)).сработала).toBe(false);
  });

  it('пустой абзац исчезает по Backspace и по Delete, курсор уходит к соседнему тексту', () => {
    const текст = 'Первый.\n\n\n\nВторой.';
    expect(нажать('Backspace', состояние(текст, 9))).toMatchObject({текст: 'Первый.\n\n\nВторой.', курсор: 7});
    expect(нажать('Delete', состояние(текст, 9))).toMatchObject({текст: 'Первый.\n\n\nВторой.', курсор: 10});
  });

  it('у границы примечания и у скрытого импорта удаление поглощается и ничего не меняет', () => {
    const совет = 'До.\n\n:::tip\nТекст\n:::\n\nПосле.';
    expect(нажать('Backspace', состояние(совет, совет.indexOf('Текст')))).toMatchObject({сработала: true, текст: совет});
    expect(нажать('Delete', состояние(совет, совет.indexOf('Текст') + 5))).toMatchObject({сработала: true, текст: совет});
    expect(нажать('Delete', состояние(совет, 3))).toMatchObject({сработала: true, текст: совет});
    expect(нажать('Backspace', состояние(КАРТОЧКА, КАРТОЧКА.indexOf('Текст.')))).toMatchObject({сработала: true, текст: КАРТОЧКА});
  });

  it('после спрятанного жёсткого переноса и посреди текста удаляет штатная команда', () => {
    expect(нажать('Backspace', состояние('Строка\\\nдальше', 8)).сработала).toBe(false);
    expect(нажать('Backspace', состояние('Абзац.', 3)).сработала).toBe(false);
    expect(нажать('Delete', состояние('Абзац.', 3)).сработала).toBe(false);
  });
});
