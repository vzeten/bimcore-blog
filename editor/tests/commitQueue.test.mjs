// Имя каждого теста повторяет формулировку правила.
// Схема записи очереди коммитов: она — единственное доказательство, что коммит сделала программа,
// и половина такого доказательства доказательством не является.
import {afterEach, describe, expect, it, vi} from 'vitest';
import fs from 'node:fs';
import path from 'node:path';

import {записатьОчередь, прочитатьОчередь} from '../src/adapters/commitQueue.mjs';
import {ЖДАТЬ_GIT} from './saveHarness.mjs';
import {EN, ES, RU, среда, убратьПесочницы, настройкиСервера} from './publishHarness.mjs';

vi.setConfig({testTimeout: ЖДАТЬ_GIT, hookTimeout: ЖДАТЬ_GIT});

afterEach(убратьПесочницы);

const очередь = (место) => прочитатьОчередь(место.editorDir, настройкиСервера());

describe('схема записи очереди', () => {
  const годная = (правки = {}) => ({
    sha: 'c'.repeat(40),
    пути: [RU],
    созданные: [],
    удалённые: [],
    основа: 'd'.repeat(40),
    когда: '2026-08-23T00:00:00.000Z',
    состояние: 'сделан',
    ...правки,
  });

  const прочитать = (место, записи) => {
    fs.mkdirSync(path.join(место.editorDir, '.publish'), {recursive: true});
    fs.writeFileSync(
      path.join(место.editorDir, '.publish', 'commits.json'),
      `${JSON.stringify({записи})}\n`,
      'utf8',
    );

    return очередь(место);
  };

  it('годная запись читается', async () => {
    const место = await среда();

    expect(прочитать(место, [годная()]).записи).toHaveLength(1);
  });

  const плохие = [
    ['без основы', годная({основа: undefined})],
    ['с короткой основой', годная({основа: 'abc'})],
    ['без времени', годная({когда: ''})],
    ['с чужим состоянием', годная({состояние: 'непонятно'})],
    ['с пустым перечнем путей', годная({пути: []})],
    ['с повтором пути', годная({пути: [RU, RU]})],
    ['с созданным вне путей', годная({созданные: [ES]})],
    ['без перечня убранного', годная({удалённые: undefined})],
    ['с убранным вне путей', годная({удалённые: [ES]})],
    ['с одним путём разом созданным и убранным', годная({пути: [RU, EN], созданные: [EN], удалённые: [EN]})],
  ];
  for (const [чем, запись] of плохие) {
    it(`запись ${чем} делает очередь недоказуемой, а не пустой`, async () => {
      const место = await среда();

      expect(прочитать(место, [запись]).ошибка).toBe('очередьБитая');
    });
  }

  it('один SHA дважды — очередь недоказуема: какая запись правда, неизвестно', async () => {
    const место = await среда();

    expect(прочитать(место, [годная(), годная({пути: [EN]})]).ошибка).toBe('очередьБитая');
  });
});

// Очередь — единственное доказательство происхождения коммита, и записывается она ДО сдвига ветки.
// Обычной атомарности переименования тут мало: имя атомарно, а содержимое может остаться в кэше.
describe('очередь ложится на диск, а не в кэш', () => {
  it('байты сбрасываются на диск до переименования, а каталог трогается только после', async () => {
    const место = await среда();
    const каталог = path.join(место.editorDir, '.publish');
    const сброс = vi.spyOn(fs, 'fsyncSync');
    const переименование = vi.spyOn(fs, 'renameSync');
    const открытие = vi.spyOn(fs, 'openSync');
    let порядок;

    try {
      expect(записатьОчередь(место.editorDir, настройкиСервера(), [])).toBe(true);
      // Слепок снимается ДО возврата подмен: `mockRestore` заодно стирает записанные вызовы.
      порядок = {
        сброс: [...сброс.mock.invocationCallOrder],
        переименование: [...переименование.mock.invocationCallOrder],
        каталог: открытие.mock.calls
          .map((вызов, номер) => ({путь: вызов[0], когда: открытие.mock.invocationCallOrder[номер]}))
          .find((вызов) => вызов.путь === каталог),
      };
    } finally {
      сброс.mockRestore();
      переименование.mockRestore();
      открытие.mockRestore();
    }

    // Сброс файла случился раньше переименования: имя атомарно, содержимое — нет.
    expect(порядок.сброс[0]).toBeLessThan(порядок.переименование[0]);
    // К каталогу программа обращается уже после переименования. Сбросить его удаётся не везде —
    // на Windows он отвечает отказом, и это законно; важно, что попытка идёт в правильном порядке.
    expect(порядок.каталог).toBeTruthy();
    expect(порядок.каталог.когда).toBeGreaterThan(порядок.переименование[0]);
  });

  it('не удалось сбросить байты — отказ, и прежняя очередь остаётся побайтово прежней', async () => {
    const место = await среда();
    записатьОчередь(место.editorDir, настройкиСервера(), []);
    const файл = path.join(место.editorDir, '.publish', 'commits.json');
    const было = fs.readFileSync(файл);
    // Так это выглядит, когда диск отказал ровно на сбросе.
    const сброс = vi.spyOn(fs, 'fsyncSync').mockImplementation((дескриптор) => {
      throw Object.assign(new Error('сброс не удался'), {code: 'EIO', дескриптор});
    });

    try {
      expect(записатьОчередь(место.editorDir, настройкиСервера(), [{sha: 'a'.repeat(40)}])).toBe(false);
    } finally {
      сброс.mockRestore();
    }

    expect(fs.readFileSync(файл)).toEqual(было);
    // Временного файла после отказа не остаётся.
    const рядом = fs.readdirSync(path.join(место.editorDir, '.publish'));
    expect(рядом.filter((имя) => имя.endsWith('.tmp'))).toEqual([]);
  });

  it('отказ сброса каталога публикацию не запрещает: на Windows он законен', async () => {
    const место = await среда();
    let первый = true;
    // Файл сбрасывается, каталог — нет: ровно так отвечает Windows.
    const сброс = vi.spyOn(fs, 'fsyncSync').mockImplementation(() => {
      if (первый) {
        первый = false;
        return undefined;
      }

      throw Object.assign(new Error('каталог не сбрасывается'), {code: 'EPERM'});
    });

    try {
      expect(записатьОчередь(место.editorDir, настройкиСервера(), [])).toBe(true);
    } finally {
      сброс.mockRestore();
    }
  });
});
