// Имя каждого теста повторяет формулировку правила.
// Каркас снятия статьи с сайта: что уходит из опубликованной ветки и какие соседи получают правку.
import {describe, expect, it} from 'vitest';

import {ОСНОВА, СОСЕД, каркасСнятия, снятиеВозможно} from '../src/core/retirePlan.mjs';

const EN = 'docs/lessons/proba/index.mdx';
const RU = 'i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba/index.mdx';
const версия = (путь, локаль) => ({путь, локаль, состояние: путь.replace('index.mdx', '_state.json')});
const сосед = {путь: 'docs/lessons/other/index.mdx', локаль: 'en', текст: 'без ссылки'};

describe('каркас снятия', () => {
  it('каждая версия в основе уходит целиком: файл, состояние и файлы её каталога', () => {
    const каркас = каркасСнятия({
      версии: [версия(EN, 'en'), версия(RU, 'ru')],
      вид: 'статья',
      вОснове: new Set([EN, RU, 'docs/lessons/proba/_state.json']),
      вПапках: new Map([
        [EN, [EN, 'docs/lessons/proba/_state.json', 'docs/lessons/proba/img/a.png']],
        [RU, [RU]],
      ]),
    });
    expect(каркас.отказ).toBeNull();
    expect(каркас.записи.map((запись) => [запись.путь, запись.назначение, запись.источник])).toEqual([
      ['docs/lessons/proba/_state.json', 'состояние', 'удалено'],
      ['docs/lessons/proba/img/a.png', 'картинка', 'удалено'],
      [EN, 'версия', 'удалено'],
      [RU, 'версия', 'удалено'],
    ]);
    expect(снятиеВозможно(каркас)).toBe(true);
  });

  it('вторая статья в тех же границах — разрыв: чьи там картинки, по путям не видно', () => {
    const каркас = каркасСнятия({
      версии: [версия(EN, 'en')], вид: 'статья', вОснове: new Set([EN]),
      вПапках: new Map([[EN, [EN, 'docs/lessons/proba/sub/index.mdx']]]),
    });
    expect(каркас.разрывы).toEqual([{причина: 'папкаНеОдна', путь: EN, локаль: 'en'}]);
    expect(снятиеВозможно(каркас)).toBe(false);
  });

  it('каталог на сайте спросить не удалось — отказ, а не «там пусто»', () => {
    const каркас = каркасСнятия({версии: [версия(EN, 'en')], вид: 'статья', вОснове: new Set([EN]), вПапках: new Map([[EN, null]])});
    expect(каркас.отказ).toMatchObject({код: 'фактыНеизвестны', чего: 'вПапке'});
  });

  it('запись вне канона уносит только свой файл и своё состояние, соседей по общей папке не трогает', () => {
    const пост = 'blog/2024-01-01-post.mdx';
    const каркас = каркасСнятия({
      версии: [{путь: пост, локаль: 'en', состояние: 'blog/_2024-01-01-post.state.json'}],
      вид: 'внеКанона', вОснове: new Set([пост, 'blog/_2024-01-01-post.state.json']), вПапках: new Map(),
    });
    expect(каркас.записи.map((запись) => запись.путь)).toEqual(['blog/2024-01-01-post.mdx', 'blog/_2024-01-01-post.state.json']);
  });

  it('сосед получает правку ссылок текстом из основы; уходящий с сайта сосед правке не подлежит', () => {
    const каркас = каркасСнятия({
      версии: [версия(EN, 'en')], вид: 'статья', вОснове: new Set([EN]), вПапках: new Map([[EN, [EN]]]),
      соседи: [сосед, {путь: EN, локаль: 'en', текст: 'x'}],
    });
    expect(каркас.записи).toContainEqual({путь: сосед.путь, назначение: СОСЕД, локаль: 'en', источник: ОСНОВА, режим: '100644', текст: 'без ссылки'});
    expect(каркас.записи.filter((запись) => запись.путь === EN)).toHaveLength(1);
  });

  it('непонятная ссылка у соседа — разрыв снятия', () => {
    const каркас = каркасСнятия({
      версии: [версия(EN, 'en')], вид: 'статья', вОснове: new Set([EN]), вПапках: new Map([[EN, [EN]]]),
      разрывыСоседей: [{причина: 'ссылкаНеРазобрана', путь: сосед.путь}],
    });
    expect(снятиеВозможно(каркас)).toBe(false);
  });

  it('путь с выходом наружу — отказ до единой записи', () => {
    const каркас = каркасСнятия({версии: [{путь: '../x/index.mdx', локаль: 'en'}], вид: 'статья', вОснове: new Set(), вПапках: new Map()});
    expect(каркас).toMatchObject({записи: [], отказ: {код: 'фактыНеизвестны'}});
  });
});
