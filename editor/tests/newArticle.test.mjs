// Имя каждого теста повторяет формулировку правила.
// Создание статьи: адрес из названия и план записи. Диска здесь нет — только решение, что писать.
import {describe, expect, it} from 'vitest';
import matter from 'gray-matter';
import {адресГоден, адресИзНазвания, планСоздания, языкиРаздела} from '../src/core/newArticle.mjs';

const НАСТРОЙКИ = {
  обязательныйЯзык: 'en',
  // Новая статья рождается скрытой: файлы попадают в репозиторий сразу, и недописанная
  // статья не должна оказаться в меню сайта. Значение — настройка, а не хардкод (SPEC 4.4).
  видимость: {новаяСкрыта: true},
  основнойЯзык: 'ru',
  локали: {en: 'English', ru: 'Русский', es: 'Español'},
  статусы: ['Черновик', 'Готова к публикации', 'Опубликована'],
  хранение: {файлСостояния: '_state.json'},
  заглушкаПеревода: {
    заголовок: 'Translation placeholder:',
    тело: 'This English page is a placeholder.',
    описание: 'Placeholder page, translation is not ready yet.',
  },
  поляСоздания: {
    docs: {порядок: ['title', 'slug', 'sidebar_label', 'sidebar_position', 'description', 'image', 'unlisted'], значения: {description: ''}},
    blog: {порядок: ['title', 'slug', 'description', 'date', 'authors', 'tags', 'keywords', 'image', 'unlisted'], значения: {description: '', authors: '[ivan]', tags: '[]', keywords: '[]'}},
    проба: {порядок: ['title', 'slug', 'unlisted'], значения: {}},
  },
  контент: [
    {локаль: 'en', род: 'docs', папка: 'docs', наСайте: true},
    {локаль: 'en', род: 'blog', папка: 'blog', наСайте: true},
    {локаль: 'ru', род: 'docs', папка: 'i18n/ru/docusaurus-plugin-content-docs/current', наСайте: true},
    {локаль: 'ru', род: 'blog', папка: 'i18n/ru/docusaurus-plugin-content-blog', наСайте: true},
    {локаль: 'ru', род: 'проба', папка: 'editor/sandbox', наСайте: false},
  ],
};

const РАЗДЕЛ = 'docs/lessons';
const план = (правки = {}) => планСоздания({
  раздел: РАЗДЕЛ, название: 'Как ускорить Revit', адрес: '', settings: НАСТРОЙКИ, ...правки,
});

describe('адрес из названия', () => {
  it('русское название превращается в латинский адрес', () => {
    expect(адресИзНазвания('Как ускорить Revit')).toBe('kak-uskorit-revit');
  });

  it('знаки и пробелы становятся дефисами, лишние дефисы убираются', () => {
    expect(адресИзНазвания('  Щи, борщ — и «ёж»!  ')).toBe('schi-borsch-i-ezh');
  });

  it('название из одних знаков адреса не даёт — выдумывать имя нельзя', () => {
    // Выдуманный адрес остался бы в сайте навсегда: менять его после публикации нельзя.
    expect(адресИзНазвания('!!! ??? ...')).toBe('');
    expect(адресГоден('')).toBe(false);
  });

  it('годным считается только латиница, цифры и одиночные дефисы', () => {
    expect(адресГоден('kak-uskorit-revit')).toBe(true);
    expect(адресГоден('Kak-Uskorit')).toBe(false);
    expect(адресГоден('как-ускорить')).toBe(false);
    expect(адресГоден('two--dashes')).toBe(false);
    expect(адресГоден('-edge')).toBe(false);
  });
});

describe('языки раздела', () => {
  it('в разделе документации доступны все языки этого рода', () => {
    expect(языкиРаздела('docs/lessons', НАСТРОЙКИ, null)).toEqual(['en', 'ru']);
  });

  it('в песочнице язык только один — предлагать остальные значит обещать невозможное', () => {
    // Сервер откажет с причиной «нет языка в разделе», а окно показало бы выбор как доступный.
    expect(языкиРаздела('проба', НАСТРОЙКИ, null)).toEqual(['ru']);
  });

  it('раздел не выбран — языков нет вовсе', () => {
    expect(языкиРаздела(null, НАСТРОЙКИ, null)).toEqual([]);
  });

  it('род, которого нет в настройках контента, языков не даёт', () => {
    expect(языкиРаздела('выдумка/раздел', НАСТРОЙКИ, null)).toEqual([]);
  });

  it('порядок языков — тот же, что во всём окне', () => {
    // Список локалей один на программу; свой порядок здесь развёл бы окно с самим собой.
    expect(языкиРаздела('blog', НАСТРОЙКИ, null)).toEqual(['en', 'ru']);
  });

  it('раздел заполнен только по-английски — русскую статью в нём завести нельзя', () => {
    // Сервер не заводит пустых папок раздела: русская статья легла бы в раздел, которого
    // по-русски не существует, и создание сорвалось бы уже после нажатия «Создать».
    expect(языкиРаздела('docs/help', НАСТРОЙКИ, ['en'])).toEqual(['en']);
  });

  it('раздел есть на обоих языках — доступны оба', () => {
    expect(языкиРаздела('docs/help', НАСТРОЙКИ, ['en', 'ru'])).toEqual(['en', 'ru']);
  });

  it('раздел есть только по-русски — английская заглушка ложиться некуда, и русский язык закрыт', () => {
    // Русская статья тянет за собой английскую заглушку: без раздела в её языке отказ придёт
    // из-за второго файла, а человек нажимал бы «Создать» в полной уверенности.
    expect(языкиРаздела('docs/help', НАСТРОЙКИ, ['ru'])).toEqual([]);
  });

  it('в песочнице заглушки нет, и раздел судится только по своему языку', () => {
    // Песочница живёт вне сайта: правило обязательного английского её не касается.
    expect(языкиРаздела('проба', НАСТРОЙКИ, ['ru'])).toEqual(['ru']);
  });
});

describe('план создания статьи', () => {
  it('в документации создаются две версии: русская и английская заглушка', () => {
    // Русская статья без английского двойника не попадает в сборку вообще, молча (SPEC 2.4).
    const {файлы} = план();

    expect(файлы.map((ф) => ф.локаль)).toEqual(['en', 'ru']);
    expect(файлы.filter((ф) => ф.заглушка)).toHaveLength(1);
  });

  it('обе версии ложатся по одному пути внутри своих корней', () => {
    // Реестр сшивает языки ПО ПУТИ: разойдись он на букву — программа покажет две статьи.
    const {файлы} = план();
    const хвост = (path) => path.split('/').slice(-3).join('/');

    expect(хвост(файлы[0].path)).toBe(хвост(файлы[1].path));
    expect(файлы.map((ф) => хвост(ф.path))).toEqual(['lessons/kak-uskorit-revit/index.mdx', 'lessons/kak-uskorit-revit/index.mdx']);
  });

  it('видимость новой статьи задаётся настройкой, а не строкой в коде', () => {
    // Строку `unlisted` пишет одно правило ядра, и решает её значение владелец настройкой,
    // а не переделка программы (SPEC 4.3, 4.4). Поменял настройку — статья рождается в меню.
    const вМеню = планСоздания({
      раздел: 'docs/lessons',
      название: 'Как ускорить Revit',
      settings: {...НАСТРОЙКИ, видимость: {новаяСкрыта: false}},
    });

    for (const файл of вМеню.файлы) expect(файл.text).not.toContain('unlisted');
    for (const файл of план().файлы) expect(файл.text).toContain('unlisted: true');
  });

  it('в шапке новой статьи есть название, адрес и видимость только по ссылке, а обложки нет вовсе', () => {
    // Отсутствие `image` — нормальное состояние статьи: общую картинку подставляет сам сайт
    // из своего конфига. Записывать её путь в статью нельзя, а пустое `image` роняет сборку
    // (SPEC 2.1) — значит поля просто нет.
    for (const файл of план().файлы) {
      expect(файл.text).toContain('unlisted: true');
      expect(файл.text).not.toMatch(/^image:/m);
      // Пустое описание допустимо: его заполняет человек.
      expect(файл.text.startsWith('---\n')).toBe(true);
    }
  });

  it('поля новой статьи берутся из настроек рода, а не из кода', () => {
    // У блога своя шапка: дата, автор и теги; у песочницы — только самое необходимое.
    const блог = планСоздания({раздел: 'blog', название: 'Пост о Revit', адрес: '', settings: НАСТРОЙКИ});
    const свой = блог.файлы.find((ф) => ф.локаль === 'ru');

    expect(свой.text).toContain('authors: [ivan]');
    expect(свой.text).toMatch(/date: \d{4}-\d{2}-\d{2}/);
    // Пустые списки в шапку не пишутся: `keywords: []` роняет сборку сайта, а `tags: []`
    // ничего не сообщает. Поле появится, как только человек его заполнит.
    expect(свой.text).not.toContain('tags: []');
    expect(свой.text).not.toContain('sidebar_position');
  });

  it('статью можно создать сразу на английском, и тогда заглушка не нужна', () => {
    const {файлы} = план({язык: 'en'});

    expect(файлы).toHaveLength(1);
    expect(файлы[0].локаль).toBe('en');
    expect(файлы[0].заглушка).toBe(false);
    // Описание заглушки достаётся заглушке, а не языку: английская статья, написанная человеком,
    // остаётся без описания, как любая своя версия, — его пишет он сам. Переедь условие с признака
    // заглушки на локаль — оно тихо вписало бы человеку текст про неготовый перевод.
    expect(matter(файлы[0].text).data.description).toBe(undefined);
    expect(файлы[0].text).not.toContain('description:');
  });

  it('адрес документации абсолютный, с разделом и без локали, и одинаковый у версий', () => {
    const {файлы} = план();
    const адреса = файлы.map((ф) => /slug: (.+)/.exec(ф.text)[1]);

    expect(адреса).toEqual(['/lessons/kak-uskorit-revit', '/lessons/kak-uskorit-revit']);
  });

  it('английская заглушка помечена и не выглядит готовым переводом', () => {
    const заглушка = план().файлы.find((ф) => ф.заглушка);

    expect(заглушка.text).toContain('Translation placeholder:');
    expect(заглушка.text).toContain('This English page is a placeholder.');
  });

  it('в песочнице создаётся только своя версия: она живёт вне сайта', () => {
    const {файлы} = планСоздания({
      раздел: 'проба', название: 'Проба пера', адрес: '', settings: НАСТРОЙКИ,
    });

    expect(файлы).toHaveLength(1);
    expect(файлы[0].локаль).toBe('ru');
  });

  it('название пустое — плана нет, а не статья без имени', () => {
    expect(план({название: '   '}).ошибка).toBe('нетНазвания');
  });

  it('адрес из названия не вывелся — просим адрес, а не выдумываем', () => {
    expect(план({название: '!!!'}).ошибка).toBe('нетАдреса');
  });

  it('адрес, введённый человеком, важнее рассчитанного', () => {
    expect(план({адрес: 'revit-speed'}).slug).toBe('revit-speed');
  });

  it('негодный адрес от человека отклоняется, а не чинится молча', () => {
    expect(план({адрес: 'Как Ускорить'}).ошибка).toBe('нетАдреса');
  });

  it('раздел вне контента — плохой запрос, а не запись куда попало', () => {
    // Для чужого рода нет описания полей — это дефект настроек, и он назван прямо.
    expect(планСоздания({раздел: 'scripts', название: 'X', адрес: '', settings: НАСТРОЙКИ}).ошибка)
      .toBe('нетПолейРода');
  });

  it('план ничего не пишет: он только говорит, что и куда положить', () => {
    // Проверки идут до записи, потому что неверно созданная статья роняет сборку всего сайта.
    const результат = план();

    expect(Object.keys(результат).sort()).toEqual(['slug', 'локаль', 'состояния', 'файлы']);
    for (const файл of результат.файлы) expect(Object.keys(файл).sort()).toEqual(['path', 'text', 'заглушка', 'локаль']);
  });

  it('раздел выбран в английской папке — статья всё равно создаётся русской, с заглушкой', () => {
    // Человек создаёт статью, а не файл в конкретной папке: иначе выбор английского раздела дал бы
    // английский файл с русским заголовком и без русской версии вовсе.
    const {файлы} = план({раздел: 'docs/lessons'});

    expect(файлы.map((ф) => ф.локаль).sort()).toEqual(['en', 'ru']);
    expect(файлы.find((ф) => ф.локаль === 'ru').заглушка).toBe(false);
    expect(файлы.find((ф) => ф.локаль === 'en').заглушка).toBe(true);
  });

  it('у каждой созданной версии планируется состояние «черновик»', () => {
    // Иначе реестр покажет «Неизвестный» у статьи, которую человек только что создал сам.
    const {файлы, состояния} = план();

    expect(состояния).toHaveLength(файлы.length);
    for (const состояние of состояния) {
      expect(состояние.path.endsWith('/_state.json')).toBe(true);
      expect(JSON.parse(состояние.text).готовность).toBe('Черновик');
    }
  });

  it('адрес новой статьи блога из одних цифр остаётся текстом, а не числом', () => {
    const {файлы} = план({раздел: 'blog', название: '2026', адрес: '2026'});

    for (const файл of файлы) {
      expect(matter(файл.text).data.slug, файл.path).toBe('2026');
    }
  });

  it('новая статья блога создаётся без пустых списков, которые роняют сборку', () => {
    // `keywords: []` Docusaurus не принимает вовсе: полю нужно хотя бы одно значение.
    // Найдено репетицией выпуска 2026-08-10 — первая же блог-статья не собиралась.
    const {файлы} = план({раздел: 'blog', название: 'Проба блога', адрес: 'proba-bloga'});

    for (const файл of файлы) {
      const шапка = matter(файл.text).data;
      expect(Object.keys(шапка), файл.path).not.toContain('keywords');
      expect(Object.keys(шапка), файл.path).not.toContain('tags');
      // Автор задан настройками и пустым не бывает: он остаётся на месте.
      expect(шапка.authors, файл.path).toEqual(['ivan']);
    }
  });

  it('пустого описания в файле не бывает вовсе, а у английской заглушки оно своё, из настроек', () => {
    // Прежнее правило писало своей версии `description: ""` — отменено разбором шапки 2026-08-10.
    // Пустых ключей не бывает: голое `description:` разбирается как `null` и роняет сборку, а
    // `description: ""` сборку проходит, но оставляет страницу вовсе без мета-описания.
    // Описание обязательно у каждой языковой версии, и заглушку пишет программа, а не человек:
    // своё описание она обязана принести с собой из настроек, иначе статья не выйдет из-за неё.
    // Описание своей версии программа при этом не выдумывает — его пишет человек.
    const {файлы} = план();
    const свой = файлы.find((файл) => файл.заглушка !== true);

    expect(matter(свой.text).data.description).toBe(undefined);
    expect(свой.text).not.toContain('description:');
    expect(matter(файлы.find((файл) => файл.заглушка === true).text).data.description)
      .toBe('Placeholder page, translation is not ready yet.');
  });

  it('название с кавычками и слешем даёт разбираемую шапку, а не сломанный YAML', () => {
    const {файлы} = план({название: 'Путь C:\\Revit и «кавычки»', адрес: 'revit-path'});
    const свой = файлы.find((ф) => ф.локаль === 'ru');

    expect(свой.text).toContain('title: "Путь C:\\\\Revit и «кавычки»"');
    expect(свой.text.split('\n').filter((строка) => строка === '---')).toHaveLength(2);
  });
});
