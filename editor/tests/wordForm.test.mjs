// Имя каждого теста повторяет формулировку правила.
// Слово при числе по-русски: «Ссылки уберутся в 1 статье / в 3 статьях / в 5 статьях / в 21 статье»
// (добавка ВК к этапу 2). Формы берутся из настоящих настроек.
import {describe, expect, it} from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

import {формаЧисла} from '../src/core/wordForm.mjs';

const EDITOR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const НАСТРОЙКИ = JSON.parse(fs.readFileSync(path.join(EDITOR, 'settings.json'), 'utf8'));
const ФОРМЫ = НАСТРОЙКИ['склонения']['вСтатьях'];
const фраза = (n) => НАСТРОЙКИ['подписи']['удалениеСсылки'].replace('{n}', n).replace('{статьях}', формаЧисла(n, ФОРМЫ));

describe('слово при числе', () => {
  it('1 и 21 — «в 1 статье», «в 21 статье»', () => {
    expect(фраза(1)).toBe('Ссылки уберутся в 1 статье.');
    expect(фраза(21)).toBe('Ссылки уберутся в 21 статье.');
    expect(фраза(101)).toBe('Ссылки уберутся в 101 статье.');
  });

  it('2–4 — «в 3 статьях»; 5 и больше — «в 5 статьях»', () => {
    expect(фраза(3)).toBe('Ссылки уберутся в 3 статьях.');
    expect(фраза(24)).toBe('Ссылки уберутся в 24 статьях.');
    expect(фраза(5)).toBe('Ссылки уберутся в 5 статьях.');
    expect(фраза(20)).toBe('Ссылки уберутся в 20 статьях.');
  });

  it('11–14 — всегда «много», хотя кончаются на 1–4', () => {
    const формы = {один: 'статья', несколько: 'статьи', много: 'статей'};
    expect([11, 12, 13, 14, 111].map((n) => формаЧисла(n, формы))).toEqual(['статей', 'статей', 'статей', 'статей', 'статей']);
    expect([1, 2, 5, 22, 25].map((n) => формаЧисла(n, формы))).toEqual(['статья', 'статьи', 'статей', 'статьи', 'статей']);
  });

  it('окно публикации говорит той же формой', () => {
    const окно = НАСТРОЙКИ['публикация']['ссылкиУберутся'];
    expect(окно.replace('{n}', 1).replace('{статьях}', формаЧисла(1, ФОРМЫ))).toBe('Ссылки на статью уберутся в 1 статье.');
    expect(окно.replace('{n}', 7).replace('{статьях}', формаЧисла(7, ФОРМЫ))).toBe('Ссылки на статью уберутся в 7 статьях.');
  });
});
