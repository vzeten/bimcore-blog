// Имя каждого теста повторяет формулировку правила.
//
// Сквозная проверка публикации: ход окна разговаривает с НАСТОЯЩИМИ ручками сервера, а те — с
// настоящим git во временном репозитории и настоящим «сервером сайта» рядом. Подставлены только
// правила подготовки (у них свои проверки). Всё остальное — тот самый код, который работает в окне;
// полной сборки сайта на компьютере нет (решение владельца 2026-09-18).
//
// Ради чего эта проверка заведена: согласие человека терялось между кнопкой «Да, опубликовать» и
// ручкой коммита, потому что окно не клало его в тело запроса. Машина этого не видела вовсе.
import {afterEach, beforeEach, describe, expect, it} from 'vitest';
import fs from 'node:fs';
import path from 'node:path';

import {зафиксироватьИОтправить, опубликовать, проверить} from '../src/ui/publishRun';
import {запомнитьКоммит, запомнитьПоказ} from '../src/adapters/pushMemory.mjs';
import {ЖДАТЬ_GIT} from './saveHarness.mjs';
import {EN, НАСТРОЙКИ, RU, СТАТЬЯ, дверь, наСервере, среда, убратьПесочницы, ход} from './runHarness.mjs';

/** Брошенная картинка в папке русской версии: на неё не ссылается ни один язык. */
const СИРОТА = 'i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba/сирота.png';

beforeEach(() => {
  запомнитьКоммит(null);
  запомнитьПоказ(null);
});

afterEach(() => {
  запомнитьКоммит(null);
  запомнитьПоказ(null);
  убратьПесочницы();
});

describe('публикация от нажатия до сайта', () => {
  it('правка статьи доходит от кнопки до сервера сайта одним ходом', async () => {
    const с = await среда();
    fs.writeFileSync(path.join(с.repo, RU), `${СТАТЬЯ}\nНовая строка.\n`, 'utf8');
    const записка = [];
    const шаги = [];
    const х = ход(дверь(с, записка), шаги);
    const былоНаСервере = await наСервере(с.сервер);

    // Нажали «Опубликовать».
    const вопрос = await проверить(RU, false, х);

    expect(вопрос.вид).toBe('проверено');
    expect(вопрос.итог.версии.find((версия) => версия.локаль === 'ru').состояние).toBe('изменилась');
    expect(вопрос.итог.версии.find((версия) => версия.локаль === 'en').состояние).toBe('неМенялась');
    // До согласия человека репозиторий не тронут ничем.
    expect(await наСервере(с.сервер)).toBe(былоНаСервере);
    expect((await с.git.raw(['-c', 'core.quotepath=false', 'diff', '--cached', '--name-only'])).trim()).toBe('');

    // Нажали «Да, опубликовать». Согласие едет вместе с отпечатком показанного плана — так же,
    // как его везёт окно.
    const итог = await зафиксироватьИОтправить(RU, х, вопрос.отпечаток, вопрос.отпечатокПодготовки);

    expect(итог.вид).toBe('готово');
    expect(итог.коммит).toMatch(/^[0-9a-f]{7,}$/);
    // Работа на сервере сайта, и в ней ровно файл статьи.
    const наСайте = await наСервере(с.сервер);
    expect(наСайте).not.toBe(былоНаСервере);
    // Коммит публикации уехал на сайт, а ветка человека осталась на месте.
    expect(наСайте.startsWith(итог.коммит)).toBe(true);
    expect((await с.git.raw(['rev-parse', 'HEAD'])).trim()).toBe(былоНаСервере);
    const вКоммите = (await с.git.raw(['show', '--name-only', '--format=', наСайте]))
      .split(/\r?\n/).map((строка) => строка.trim()).filter(Boolean);
    expect(вКоммите).toEqual([RU]);
  }, ЖДАТЬ_GIT);

  it('согласие человека едет и в коммит, и в отправку: без него сервер отказывает', async () => {
    const с = await среда();
    fs.writeFileSync(path.join(с.repo, RU), `${СТАТЬЯ}\nНовая строка.\n`, 'utf8');
    const записка = [];
    const х = ход(дверь(с, записка), []);

    const вопрос = await проверить(RU, false, х);
    await зафиксироватьИОтправить(RU, х, вопрос.отпечаток, вопрос.отпечатокПодготовки);

    const меняющие = записка.filter((шаг) => ['/api/publish/commit', '/api/publish/push'].includes(шаг.адрес));
    expect(меняющие).toHaveLength(2);
    for (const шаг of меняющие) expect(шаг.тело['подтверждено']).toBe(true);
  }, ЖДАТЬ_GIT);

  it('порядок шагов тот же, что человек видит на экране', async () => {
    const с = await среда();
    fs.writeFileSync(path.join(с.repo, RU), `${СТАТЬЯ}\nНовая строка.\n`, 'utf8');
    const записка = [];
    const шаги = [];
    const х = ход(дверь(с, записка), шаги);

    const вопрос = await проверить(RU, true, х);
    await зафиксироватьИОтправить(RU, х, вопрос.отпечаток, вопрос.отпечатокПодготовки);

    expect(шаги).toEqual(['сохраняю', 'проверяю', 'сверяю', 'публикую']);
    // Подготовка спрашивается срезом одной открытой версии: соседний перевод в решении о
    // публикации не участвует, и забытый признак потерял бы это молча.
    expect(записка.find((шаг) => шаг.адрес === '/api/prepare').тело).toEqual({path: RU, толькоОткрытая: true});
    expect(записка.map((шаг) => шаг.адрес)).toEqual([
      // Дата записи блога спрашивается первой и до проверок: у документации она всегда пуста,
      // но сам вопрос задаётся одинаково — правило одно на все роды (`core/publishDate.mjs`).
      '/api/publish/date',
      // Обложка — сразу после даты и тоже до проверок: у статьи без картинок писать нечего.
      '/api/publish/cover',
      '/api/prepare',
      '/api/release',
      '/api/publish/commit',
      '/api/publish/plan',
      '/api/publish/push',
    ]);
  }, ЖДАТЬ_GIT);

  it('доступность из окна вопроса ложится в файл до даты и проверок и уезжает на сайт', async () => {
    const с = await среда();
    const записка = [];
    const порядок = [];
    const запрос = дверь(с, записка);
    const х = ход(async (адрес, тело) => {
      порядок.push(адрес);
      return запрос(адрес, тело);
    }, [], undefined, undefined, async (режим) => {
      порядок.push(`доступность:${режим}`);
      const полный = path.join(с.repo, RU);
      fs.writeFileSync(полный, fs.readFileSync(полный, 'utf8').replace('---\n\n', 'unlisted: true\n---\n\n'), 'utf8');
      return true;
    });

    const итог = await опубликовать(RU, false, х, 'поСсылке');

    expect(итог.вид).toBe('готово');
    expect(порядок.slice(0, 2)).toEqual(['доступность:поСсылке', '/api/publish/date']);
    expect(await с.git.raw(['show', `${await наСервере(с.сервер)}:${RU}`])).toContain('unlisted: true');
  }, ЖДАТЬ_GIT);

  it('на сайте уже ровно это — публикация останавливается, репозиторий не тронут', async () => {
    const с = await среда();
    const записка = [];
    const х = ход(дверь(с, записка), []);
    const былоНаСервере = await наСервере(с.сервер);

    const исход = await проверить(RU, false, х);

    expect(исход.вид).toBe('остановка');
    expect(исход.ключ).toBe('нечегоПубликовать');
    // До записи дело не дошло: записывать ради ничего незачем.
    expect(записка.map((шаг) => шаг.адрес)).not.toContain('/api/publish/commit');
    expect(await наСервере(с.сервер)).toBe(былоНаСервере);
  }, ЖДАТЬ_GIT);

  it('публиковать нечего, но в папке лежит лишний файл — он молча уходит в корзину, слова прежние', async () => {
    const с = await среда();
    // Файла нет ни на сайте, ни в тексте: публикация его не меняет ничем, и до записи ход не
    // дойдёт. Но окно его человеку назвало — значит он обязан уйти (блокер контролёра 2026-09-20).
    fs.writeFileSync(path.join(с.repo, СИРОТА), 'брошенная картинка', 'utf8');
    const записка = [];
    const х = ход(дверь(с, записка), []);
    const былоНаСервере = await наСервере(с.сервер);

    const исход = await проверить(RU, false, х);

    expect(исход.вид).toBe('остановка');
    // Чистка молчаливая (решение владельца 2026-09-21): человек читает обычное «публиковать нечего».
    expect(исход.ключ).toBe('нечегоПубликовать');
    expect(записка.map((шаг) => шаг.адрес)).toContain('/api/publish/tidy');
    expect(fs.existsSync(path.join(с.repo, СИРОТА))).toBe(false);
    // Записи и отправки не было: убирать с сайта нечего, там этого файла и не лежало.
    expect(записка.map((шаг) => шаг.адрес)).not.toContain('/api/publish/commit');
    expect(await наСервере(с.сервер)).toBe(былоНаСервере);
  }, ЖДАТЬ_GIT);

  it('публиковать нечего и лишнего нет — прежние слова, уборка не зовётся вовсе', async () => {
    const с = await среда();
    const записка = [];

    const исход = await проверить(RU, false, ход(дверь(с, записка), []));

    expect(исход.вид).toBe('остановка');
    expect(исход.ключ).toBe('нечегоПубликовать');
    expect(записка.map((шаг) => шаг.адрес)).not.toContain('/api/publish/tidy');
  }, ЖДАТЬ_GIT);

  it('работа над программой в местной ветке публикации не мешает и на сайт не уезжает', async () => {
    const с = await среда();
    await с.git.raw(['checkout', '-b', 'feature/editor-proba']);
    fs.mkdirSync(path.join(с.repo, 'editor'), {recursive: true});
    fs.writeFileSync(path.join(с.repo, 'editor/SPEC.md'), 'правила\n', 'utf8');
    await с.git.raw(['add', '--', 'editor/SPEC.md']);
    await с.git.raw(['commit', '-m', 'editor: правила']);
    fs.writeFileSync(path.join(с.repo, RU), `${СТАТЬЯ}\nНовая строка.\n`, 'utf8');
    const х = ход(дверь(с, []), []);
    const былаГолова = (await с.git.raw(['rev-parse', 'HEAD'])).trim();

    const вопрос = await проверить(RU, false, х);
    expect(вопрос.вид).toBe('проверено');
    const итог = await зафиксироватьИОтправить(RU, х, вопрос.отпечаток, вопрос.отпечатокПодготовки);

    expect(итог.вид).toBe('готово');
    const наСайте = await наСервере(с.сервер);
    expect(await с.git.raw(['show', '--name-only', '--format=', наСайте])).not.toContain('editor/SPEC.md');
    expect((await с.git.raw(['rev-parse', 'HEAD'])).trim()).toBe(былаГолова);
    expect((await с.git.raw(['rev-parse', '--abbrev-ref', 'HEAD'])).trim()).toBe('feature/editor-proba');
  }, ЖДАТЬ_GIT);

  it('уход из статьи во время проверок отменяет попытку: до записи дело не доходит', async () => {
    const с = await среда();
    fs.writeFileSync(path.join(с.repo, RU), `${СТАТЬЯ}\nНовая строка.\n`, 'utf8');
    const записка = [];
    let живо = true;
    const х = {...ход(дверь(с, записка), []), жива: () => живо};

    // Человек ушёл в другую статью сразу после сохранения.
    const исход = await проверить(RU, true, {...х, сохранить: async () => {
      живо = false;
      return true;
    }});

    expect(исход.вид).toBe('прервано');
    expect(записка).toHaveLength(0);
  }, ЖДАТЬ_GIT);
});
