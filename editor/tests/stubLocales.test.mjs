// Имя каждого теста повторяет формулировку правила.
// Заглушки языков у новой статьи: кто их получает, на каком языке они написаны и когда программа
// отказывается создавать статью вовсе. Отдельно от остальных правил создания — их набралось на
// свой файл, а предел размера файла общий (SPEC 4.9).
import {describe, expect, it} from 'vitest';

import {планСоздания} from '../src/core/newArticle.mjs';
import {шаблонЗаглушки, этоЗаглушка} from '../src/core/stubText.mjs';
import {НАСТРОЙКИ} from './newArticleHarness.mjs';

const план = (правки = {}) => планСоздания({
  раздел: 'docs/lessons', название: 'Как ускорить Revit', адрес: '', settings: НАСТРОЙКИ, ...правки,
});

describe('заглушки языков у новой статьи', () => {
  it('новая статья получает свою версию и скрытые заглушки всех остальных языков сайта', () => {
    // Английская обязательна: без неё статьи на сайте нет вовсе, молча (SPEC 2.4). Остальные —
    // потому что язык без своего файла показывает под своим адресом английский текст и выдаёт
    // его за перевод (проверено сборкой сайта 2026-08-20).
    const {файлы} = план();

    expect(файлы.map((ф) => ф.локаль).sort()).toEqual(['en', 'es', 'ru']);
    expect(файлы.filter((ф) => ф.заглушка).map((ф) => ф.локаль).sort()).toEqual(['en', 'es']);
  });

  it('исходной может быть любая версия, и заглушки получают остальные языки, а не только английский', () => {
    for (const язык of ['ru', 'en', 'es']) {
      const {файлы} = план({язык});
      const свои = файлы.filter((ф) => !ф.заглушка);

      expect(свои).toHaveLength(1);
      expect(свои[0].локаль).toBe(язык);
      expect(файлы.filter((ф) => ф.заглушка).map((ф) => ф.локаль).sort())
        .toEqual(['en', 'es', 'ru'].filter((код) => код !== язык));
      // Описание заглушки достаётся заглушке, а не языку: своя версия, написанная человеком,
      // остаётся без описания — его пишет он сам. Переедь условие с признака заглушки на локаль —
      // оно тихо вписало бы человеку текст про неготовый перевод.
      expect(свои[0].text).not.toContain('description:');
    }
  });

  it('заглушка написана на языке своей страницы и не выглядит готовым переводом', () => {
    // Испанец, попавший на испанский адрес, обязан прочесть по-испански, что перевода ещё нет:
    // английское извинение на испанской странице — та же подмена языка, только короче.
    const {файлы} = план();

    expect(файлы.find((ф) => ф.локаль === 'es').text).toContain('Marcador de traducción:');
    expect(файлы.find((ф) => ф.локаль === 'es').text).not.toContain('Translation placeholder:');
    expect(файлы.find((ф) => ф.локаль === 'en').text).toContain('Translation placeholder:');
  });

  it('языки заглушек берутся из настроек, а не из списка в коде', () => {
    // Четвёртый язык обязан заработать дописыванием строки в «контент» и «заглушкиПеревода».
    const сЧетвёртым = {
      ...НАСТРОЙКИ,
      локали: {...НАСТРОЙКИ.локали, de: 'Deutsch'},
      заглушкиПеревода: {
        ...НАСТРОЙКИ.заглушкиПеревода,
        de: {заголовок: 'Platzhalter:', тело: 'Noch keine Übersetzung.', описание: 'Platzhalterseite.'},
      },
      контент: [...НАСТРОЙКИ.контент,
        {локаль: 'de', род: 'docs', папка: 'i18n/de/docusaurus-plugin-content-docs/current', наСайте: true}],
    };
    const {файлы} = план({settings: сЧетвёртым});

    expect(файлы.map((ф) => ф.локаль).sort()).toEqual(['de', 'en', 'es', 'ru']);
    expect(файлы.find((ф) => ф.локаль === 'de').text).toContain('Noch keine Übersetzung.');
  });

  it('языку сайта не задан текст заглушки — не создаётся ничего, вместо чужого языка в файле', () => {
    // Умолчание в коде подставило бы испанцу английскую строку молча (SPEC 4.4.1).
    const безИспанской = {
      ...НАСТРОЙКИ,
      заглушкиПеревода: {ru: НАСТРОЙКИ.заглушкиПеревода.ru, en: НАСТРОЙКИ.заглушкиПеревода.en},
    };

    expect(план({settings: безИспанской})).toEqual({ошибка: 'нетШаблонаЗаглушки'});
  });

  it('строки нет у языка, на котором пишут, — отказ тот же: настройка чинится сразу, а не через раз', () => {
    // Иначе статья на языке без строки создавалась бы, а на соседнем — нет, и человек искал бы
    // разницу между двумя нажатиями вместо одной недостающей строки настроек.
    const безРусской = {
      ...НАСТРОЙКИ,
      заглушкиПеревода: {en: НАСТРОЙКИ.заглушкиПеревода.en, es: НАСТРОЙКИ.заглушкиПеревода.es},
    };

    expect(план({settings: безРусской, язык: 'ru'})).toEqual({ошибка: 'нетШаблонаЗаглушки'});
    expect(план({settings: безРусской, язык: 'en'})).toEqual({ошибка: 'нетШаблонаЗаглушки'});
  });

  it('папке вне сайта заглушки не нужны, и отсутствие их строк её не останавливает', () => {
    // В песочнице живёт одна версия: правило обязательного языка её не касается.
    const безСтрок = {...НАСТРОЙКИ, заглушкиПеревода: {}};
    const {файлы} = планСоздания({
      раздел: 'проба', название: 'Проба пера', адрес: '', settings: безСтрок,
    });

    expect(файлы).toHaveLength(1);
    expect(файлы[0].заглушка).toBe(false);
  });

  it('текста заглушки для языка нет — шаблон не выдумывается, а отсутствует', () => {
    expect(шаблонЗаглушки('es', НАСТРОЙКИ)).not.toBe(null);
    expect(шаблонЗаглушки('de', НАСТРОЙКИ)).toBe(null);
    // Половина шаблона — тот же случай: файл вышел бы без описания и остановил бы выпуск статьи.
    const половина = {...НАСТРОЙКИ, заглушкиПеревода: {es: {заголовок: 'Marcador:', тело: 'Texto.'}}};
    expect(шаблонЗаглушки('es', половина)).toBe(null);
  });

  it('заглушкой считается версия с текстом заглушки любого языка, а не только английского', () => {
    // Мерка одна с той, которой заглушку пишут: вторая разошлась бы с первой в тот день,
    // когда владелец поправит слова заглушки в настройках.
    expect(этоЗаглушка('Marcador.', НАСТРОЙКИ)).toBe(true);
    expect(этоЗаглушка('Placeholder.', НАСТРОЙКИ)).toBe(true);
    expect(этоЗаглушка('Настоящий перевод статьи.', НАСТРОЙКИ)).toBe(false);
  });
});
