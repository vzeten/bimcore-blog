// Имя каждого теста повторяет формулировку правила.
// Реестр и оркестрация «Доработать»: порядок, выборочность, план без записи, разница со снимком.
import {describe, expect, it} from 'vitest';

import {ИНСТРУМЕНТЫ_ПЛАНА, ОБРАБОТЧИКИ, ПО_УМОЛЧАНИЮ, выполнить} from '../src/core/refine.mjs';
import {НАСТРОЙКИ, инструменты, копия, jpg, png} from './refineHarness.mjs';

const ТЕКСТ = '---\ntitle: "Проба"\nslug: /lessons/proba\ndescription: "Описание"\n---\n\n![](./img-01.jpg)\n';

describe('реестр обработчиков', () => {
  it('реестр задаёт порядок: подписи, поля шапки, медиа, переименование, обложка', () => {
    expect(ОБРАБОТЧИКИ.map((з) => з.код)).toEqual(['подписиМедиа', 'поляШапки', 'медиа', 'переименование', 'обложка']);
  });

  it('по умолчанию выбраны подписи, поля шапки и медиа; переименование и обложка выключены', () => {
    expect(ПО_УМОЛЧАНИЮ).toEqual(['подписиМедиа', 'поляШапки', 'медиа']);
  });

  it('у каждого обработчика единый договор: анализ, применить, проверить', () => {
    for (const {обработчик} of ОБРАБОТЧИКИ) {
      expect(typeof обработчик.анализ).toBe('function');
      expect(typeof обработчик.применить).toBe('function');
      expect(typeof обработчик.проверить).toBe('function');
    }
  });

  it('у каждого кода реестра есть подпись в настройках окна', () => {
    for (const {код} of ОБРАБОТЧИКИ) expect(typeof НАСТРОЙКИ['доработка']['обработчики'][код]).toBe('string');
  });
});

describe('оркестрация', () => {
  it('план ничего не пишет: инструменты плана байты не считают, снимок остаётся прежним', async () => {
    const снимок = копия(ТЕКСТ, {'img-01.jpg': jpg(1200, 800)});
    const {изменения} = await выполнить(снимок, ПО_УМОЛЧАНИЮ, НАСТРОЙКИ, ИНСТРУМЕНТЫ_ПЛАНА);

    expect(снимок.текст).toBe(ТЕКСТ);
    expect(снимок.файлы.get('img-01.jpg')).toEqual(jpg(1200, 800));
    expect(изменения.текст).toContain('![Проба: изображение 1](./img-01.png)');
  });

  it('применение одного флажка не запускает остальные: невыбранные только анализируются', async () => {
    const инстр = инструменты();
    const {копия: итог, отчёт, изменения} = await выполнить(копия(ТЕКСТ, {'img-01.jpg': jpg(10, 10)}), ['подписиМедиа'], НАСТРОЙКИ, инстр);

    expect(инстр.вызовов).toBe(0);
    expect(итог.текст).toContain('![Проба: изображение 1](./img-01.jpg)');
    expect(итог.текст).not.toContain('sidebar_label');
    expect(изменения.файлы).toEqual([]);
    expect(отчёт.find((з) => з.код === 'поляШапки')).toMatchObject({выбран: false, применимо: true});
    expect(отчёт.find((з) => з.код === 'поляШапки').изменено.map((з) => з.что)).toEqual(['sidebar_label']);
  });

  it('пустой набор ничего не меняет, но отчёт по каждому обработчику всё равно есть', async () => {
    const {изменения, отчёт} = await выполнить(копия(ТЕКСТ, {'img-01.jpg': jpg(10, 10)}), [], НАСТРОЙКИ, инструменты());

    expect(изменения).toEqual({текст: null, файлы: []});
    expect(отчёт.map((з) => з.код)).toEqual(ОБРАБОТЧИКИ.map((з) => з.код));
  });

  it('зависимые обработчики видят копию после предыдущих: переименование идёт по уже сжатому .png', async () => {
    const текст = ТЕКСТ.replace('img-01.jpg', 'photo.jpg');
    const {копия: итог} = await выполнить(копия(текст, {'photo.jpg': jpg(10, 10)}), ['медиа', 'переименование'], НАСТРОЙКИ, инструменты(png(10, 10)));

    expect(итог.текст).toContain('](./img-01.png)');
    expect([...итог.файлы.entries()].filter(([, б]) => б !== null).map(([имя]) => имя)).toEqual(['img-01.png']);
  });

  it('разница со снимком называет только изменённые байты и удаления', async () => {
    const {изменения} = await выполнить(копия(ТЕКСТ, {'img-01.jpg': jpg(10, 10)}), ['медиа'], НАСТРОЙКИ, инструменты(Buffer.alloc(2)));

    expect(изменения.файлы).toEqual([{имя: 'img-01.jpg', байты: null}, {имя: 'img-01.png', байты: Buffer.alloc(2)}]);
  });

  it('обработчик, не прошедший свою проверку, останавливает всю операцию ошибкой', async () => {
    const сломанный = {код: 'подписиМедиа', обработчик: {...ОБРАБОТЧИКИ[0].обработчик, проверить: () => false}};
    const прежний = ОБРАБОТЧИКИ[0];
    ОБРАБОТЧИКИ[0] = сломанный;
    try {
      await expect(выполнить(копия(ТЕКСТ, {}), ['подписиМедиа'], НАСТРОЙКИ, инструменты())).rejects.toThrow('подписиМедиа');
    } finally {
      ОБРАБОТЧИКИ[0] = прежний;
    }
  });
});
