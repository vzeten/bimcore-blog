// Имя каждого теста повторяет формулировку правила.
// Ручка сохранения: работа человека доезжает до файла, чужая правка не затирается молча.
// Обвязка — в `saveHarness.mjs`, видимость языковых версий — в `saveVisibility.test.mjs`.
import {afterEach, describe, expect, it} from 'vitest';
import fs from 'node:fs';
import path from 'node:path';

import {EN, RU, подготовить, прочитать, сохранить, статья, убратьПесочницы} from './saveHarness.mjs';

afterEach(убратьПесочницы);

describe('сохранение записывает работу человека', () => {
  it('в файл уходит текст из окна, а не тот, что лежал на диске', async () => {
    // Найдено живой проверкой 2026-08-10 при переносе ручки сохранения в свой модуль: сборка
    // файла брала тело у самого файла, и правка текста молча не доезжала до диска. Серверного
    // теста у сохранения до этого не было вовсе — только проверки окна с подменённым запросом.
    const среда = await подготовить({[RU]: статья('title: A', '\nстарый текст\n')});

    await сохранить(среда, {rel: RU, шапка: 'title: A', тело: '\nновый текст\n'});

    expect(прочитать(среда, RU)).toContain('новый текст');
    expect(прочитать(среда, RU)).not.toContain('старый текст');
  });

  it('правка шапки доезжает до файла вместе с текстом', async () => {
    const среда = await подготовить({[RU]: статья('title: A')});

    await сохранить(среда, {rel: RU, шапка: 'title: "Б"', тело: '\nтекст статьи\n'});

    expect(прочитать(среда, RU)).toContain('title: "Б"');
  });

  it('переводы строк файла сохраняются: windows-файл остаётся windows-файлом', async () => {
    const среда = await подготовить({[RU]: '---\r\ntitle: A\r\n---\r\n\r\nстарый текст\r\n'});

    await сохранить(среда, {rel: RU, шапка: 'title: A', тело: '\nновый текст\n'});

    expect(прочитать(среда, RU)).toBe('---\r\ntitle: A\r\n---\r\n\r\nновый текст\r\n');
  });

  it('невидимая метка в начале файла остаётся на месте после сохранения', async () => {
    const метка = '﻿';
    const среда = await подготовить({[RU]: `${метка}${статья('title: A', '\nстарый текст\n')}`});

    await сохранить(среда, {rel: RU, шапка: 'title: A', тело: '\nновый текст\n'});

    expect(прочитать(среда, RU).startsWith(метка)).toBe(true);
  });

  it('открыл и сохранил без правок — файл не переписывается вовсе', async () => {
    const среда = await подготовить({[RU]: статья('title: A')});
    const было = прочитать(среда, RU);

    const ответ = await сохранить(среда, {rel: RU, шапка: 'title: A'});

    expect(ответ.data['untouched']).toBe(true);
    expect(прочитать(среда, RU)).toBe(было);
  });

  it('файл изменён снаружи — конфликт не трогает ни открытую версию, ни соседние', async () => {
    const среда = await подготовить({[RU]: статья('title: A'), [EN]: статья('title: A')});
    const былоRU = прочитать(среда, RU);
    const былоEN = прочитать(среда, EN);

    const ответ = await сохранить(среда, {rel: RU, шапка: 'title: A\nunlisted: true', отпечаток: 'ЧУЖОЙ'});

    expect(ответ.code).toBe(409);
    expect(прочитать(среда, RU)).toBe(былоRU);
    expect(прочитать(среда, EN)).toBe(былоEN);
  });

  it('нет такой статьи — понятный отказ, а не падение ручки', async () => {
    const среда = await подготовить({[RU]: статья('title: A')});
    fs.rmSync(path.join(среда.repo, RU));

    const ответ = await сохранить(среда, {rel: RU, шапка: 'title: A', отпечаток: 'любой'});

    expect(ответ.code).toBe(404);
  });
});
