// Имя каждого теста повторяет формулировку правила.
// Обработчики шапки: пустые технические поля и обложка из первой картинки.
import {describe, expect, it} from 'vitest';

import {дописатьПоля, заменитьШапку, обложка, полеПишетсяСтрокой, поляШапки} from '../src/core/refineHead.mjs';
import {BLOG, GIF, НАСТРОЙКИ, RU, инструменты, копия, jpg, png} from './refineHarness.mjs';

const анализ = (текст, файлы = {}, путь = RU) => поляШапки.анализ(копия(текст, файлы, путь), НАСТРОЙКИ);
const применить = (текст, путь = RU) => поляШапки.применить(копия(текст, {}, путь), анализ(текст, {}, путь)).копия.текст;

describe('пустые технические поля шапки', () => {
  it('короткое имя берётся из заголовка, адрес из пути; строка встаёт по порядку рода', () => {
    const текст = '---\ntitle: "Розетки"\ndescription: "Описание"\n---\n\nТекст\n';
    expect(применить(текст)).toBe('---\ntitle: "Розетки"\nslug: /lessons/proba\nsidebar_label: "Розетки"\ndescription: "Описание"\n---\n\nТекст\n');
  });

  it('автор блога из настроек создания пишется той же строкой, что при создании статьи', () => {
    const текст = '---\ntitle: "Розетки"\nslug: proba\ndescription: "Описание"\ndate: 2026-09-06\n---\n\nТекст\n';
    expect(применить(текст, BLOG)).toBe('---\ntitle: "Розетки"\nslug: proba\ndescription: "Описание"\ndate: 2026-09-06\nauthors: [ivan]\n---\n\nТекст\n');
  });

  it('готовые поля не меняются ни знаком, даже записанные иначе, чем пишет программа', () => {
    const текст = "---\ntitle: 'Розетки'\nslug: /lessons/proba\nsidebar_label: Розетки\ndescription: Описание\nkeywords:\n  - розетки\n---\n\nТекст\n";
    expect(применить(текст)).toBe(текст);
    expect(анализ(текст).отчёт.изменено).toEqual([]);
  });

  it('поле, записанное несколькими строками, строкой не переписывается: продолжение значения не теряется', () => {
    // Строкой заменяется весь кусок поля. У многострочного значения так пропало бы продолжение —
    // тихая потеря текста; такую шапку правит человек.
    expect(полеПишетсяСтрокой('title: "Розетки"\ndate: 2026-09-16\n', 'date')).toBe(true);
    expect(полеПишетсяСтрокой('title: "Розетки"\n', 'date')).toBe(true);
    expect(полеПишетсяСтрокой('title: "Розетки"\ndate: >\n  2026-09-16\n', 'date')).toBe(false);
  });

  it('описание, ключевые слова и метки без источника остаются человеку; дату доработка не просит', () => {
    // Дата записи блога — не просьба к человеку: её ставит первая публикация (`core/publishDate.mjs`).
    const {отчёт} = анализ('---\ntitle: "Розетки"\nslug: proba\n---\n\nТекст\n', {}, BLOG);
    expect(отчёт.человеку.map((з) => з.что)).toEqual(['description', 'tags', 'keywords']);
    expect(отчёт.изменено.map((з) => з.что)).toEqual(['authors']);
  });

  it('пустая запись поля (голый ключ, пустые кавычки, пустой список) считается пустой и заменяется', () => {
    const текст = '---\ntitle: "Розетки"\nslug: /lessons/proba\nsidebar_label: ""\n---\n\nТекст\n';
    expect(применить(текст)).toBe('---\ntitle: "Розетки"\nslug: /lessons/proba\nsidebar_label: "Розетки"\n---\n\nТекст\n');
  });

  it('переводы строк Windows и невидимая метка файла сохраняются', () => {
    const текст = '﻿---\r\ntitle: "Розетки"\r\n---\r\n\r\nТекст\r\n';
    expect(применить(текст)).toBe('﻿---\r\ntitle: "Розетки"\r\nslug: /lessons/proba\r\nsidebar_label: "Розетки"\r\n---\r\n\r\nТекст\r\n');
  });

  it('род без набора полей — обработчик неприменим', () => {
    expect(анализ('---\ntitle: "A"\n---\n', {}, 'чужое/index.mdx')).toBeNull();
  });

  it('дописывание строк в шапку не трогает прочие куски, включая многострочные списки', () => {
    const шапка = 'title: "A"\nkeywords:\n  - a\n  - b\n';
    expect(дописатьПоля(шапка, [{ключ: 'slug', строка: 'slug: /a'}], ['title', 'slug', 'keywords'])).toBe('title: "A"\nslug: /a\nkeywords:\n  - a\n  - b\n');
    expect(заменитьШапку('---\nx: 1\n---\nтело', 'y: 2')).toBe('---\ny: 2\n---\nтело');
  });
});

describe('обложка из первой картинки', () => {
  const ТЕКСТ = '---\ntitle: "Розетки"\nslug: /lessons/proba\n---\n\n![a](./img/anim.gif)\n\n![b](./img/photo.jpg)\n\n![c](./img/second.png)\n';
  const ФАЙЛЫ = {'img/anim.gif': GIF, 'img/photo.jpg': jpg(20, 10), 'img/second.png': png(5, 5)};

  it('при пустом поле и без своей обложки первая неподвижная картинка становится обложкой, исходник остаётся', async () => {
    const к = копия(ТЕКСТ, ФАЙЛЫ);
    const предложение = обложка.анализ(к, НАСТРОЙКИ);
    expect(предложение.источник).toBe('img/photo.jpg');
    expect(предложение.отчёт.изменено[0].стало).toBe('./cover.png или ./cover.jpg');

    const {копия: итог} = await обложка.применить(к, предложение, инструменты(png(20, 10)));
    expect(итог.текст).toContain('title: "Розетки"\nslug: /lessons/proba\nimage: ./cover.png\n---');
    expect(итог.файлы.get('cover.png')).toEqual(png(20, 10));
    expect(итог.файлы.get('img/photo.jpg')).toEqual(jpg(20, 10));
    expect(обложка.проверить(итог, предложение)).toBe(true);
  });

  it('имя обложки берётся по роду итоговых байтов: JPEG ложится в cover.jpg, а не в cover.png', async () => {
    // Дефект, найденный проверкой 2026-08-20: обработанные байты ложились под заранее назначенным
    // расширением, и JPEG оказывался в cover.png — обложка с чужим содержимым роняет сборку сайта.
    const к = копия(ТЕКСТ, ФАЙЛЫ);
    const предложение = обложка.анализ(к, НАСТРОЙКИ);
    const {копия: итог} = await обложка.применить(к, предложение, инструменты(jpg(20, 10)));
    expect(итог.текст).toContain('image: ./cover.jpg\n');
    expect(итог.файлы.get('cover.jpg')).toEqual(jpg(20, 10));
    expect(итог.файлы.has('cover.png')).toBe(false);
    expect(обложка.проверить(итог, предложение)).toBe(true);
  });

  it('выигрыш мал — обложкой становится сама картинка под своим расширением', async () => {
    const к = копия(ТЕКСТ, ФАЙЛЫ);
    const предложение = обложка.анализ(к, НАСТРОЙКИ);
    const итоги = [{итог: 'оставить', причина: 'выигрышМал', было: 1, лучший: 1, лучшийРод: 'png'}];
    const {копия: итог} = await обложка.применить(к, предложение, инструменты(null, итоги));
    expect(итог.текст).toContain('image: ./cover.jpg\n');
    expect(итог.файлы.get('cover.jpg')).toEqual(jpg(20, 10));
    expect(обложка.проверить(итог, предложение)).toBe(true);
  });

  it('существующая обложка в шапке не заменяется', () => {
    const {цель, отчёт} = обложка.анализ(копия(ТЕКСТ.replace('slug: /lessons/proba', 'slug: /lessons/proba\nimage: ./my.png'), ФАЙЛЫ), НАСТРОЙКИ);
    expect(цель).toBeNull();
    expect(отчёт.оставлено).toEqual([{что: 'image', значение: './my.png', причина: 'заполнено'}]);
  });

  it('файл обложки рядом со статьёй при пустом поле тоже останавливает обработчик', () => {
    const {цель, отчёт} = обложка.анализ(копия(ТЕКСТ, {...ФАЙЛЫ, 'cover.jpg': jpg(1, 1)}), НАСТРОЙКИ);
    expect(цель).toBeNull();
    expect(отчёт.оставлено[0].причина).toBe('естьОбложка');
  });

  it('GIF и видео обложкой не становятся: без неподвижной картинки поле остаётся человеку', () => {
    const {цель, отчёт} = обложка.анализ(копия('---\ntitle: "A"\n---\n\n![a](./img/anim.gif)\n', {'img/anim.gif': GIF}), НАСТРОЙКИ);
    expect(цель).toBeNull();
    expect(отчёт.человеку).toEqual([{что: 'image', причина: 'нетКартинки'}]);
  });
});
