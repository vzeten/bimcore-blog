// Имя каждого теста повторяет формулировку правила.
// Галочки языков в окне публикации (этап 3, решение владельца 2026-09-18, п.2).
import {describe, expect, it} from 'vitest';
import {кПубликации, переключить, ссылокВОтмеченных, строкиЯзыков} from '../src/ui/publishLangs';
import type {PublishState} from '../src/ui/publishTypes';

const RU = 'i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba/index.mdx';
const EN = 'docs/lessons/proba/index.mdx';
const ES = 'i18n/es/docusaurus-plugin-content-docs/current/lessons/proba/index.mdx';
const версия = (локаль: string, путь: string, ещё = {}) => ({
  локаль, путь, файлЕсть: true, наСайте: true, доступность: 'всем', черновикЖдёт: false, ссылок: 0, статьи: [], ...ещё,
});
const СОСТОЯНИЕ: PublishState = {path: RU, основаИзвестна: true, локали: [
  версия('ru', RU, {статьи: ['a', 'b']}),
  версия('en', EN, {файлЕсть: false, наСайте: false, доступность: null}),
  версия('es', ES, {статьи: ['b', 'c']}),
]};

describe('галочки языков', () => {
  it('сайт ещё не спрошен — одна строка открытого языка, отмеченная по умолчанию', () => {
    expect(строкиЯзыков(null, RU, [RU])).toEqual([{путь: RU, локаль: null, можноОтметить: true, отмечен: true, версия: null}]);
  });

  it('пока сайт не спрошен, языки берутся из свода статьи: без путей, галочка только у существующих', () => {
    const строки = строкиЯзыков(null, RU, [RU], {ru: RU, es: ES}, ['ru', 'en', 'es']);

    expect(строки.map((строка) => [строка.локаль, строка.можноОтметить, строка.отмечен])).toEqual([
      ['ru', true, true], ['en', false, false], ['es', true, false],
    ]);
    expect(переключить(строки, [RU], ES)).toEqual([RU, ES]);
  });

  it('строка есть у каждого языка сайта, галочка — только у версии с файлом', () => {
    const строки = строкиЯзыков(СОСТОЯНИЕ, RU, [RU]);

    expect(строки.map((строка) => [строка.локаль, строка.можноОтметить, строка.отмечен])).toEqual([
      ['ru', true, true], ['en', false, false], ['es', true, false],
    ]);
  });

  it('версию без файла отметить нельзя, даже если попросить', () => {
    const строки = строкиЯзыков(СОСТОЯНИЕ, RU, [RU]);

    expect(переключить(строки, [RU], EN)).toEqual([RU]);
    expect(кПубликации(строкиЯзыков(СОСТОЯНИЕ, RU, [RU, EN]))).toEqual([RU]);
  });

  it('открытый язык снять можно; сняты все — публиковать нечего', () => {
    const строки = строкиЯзыков(СОСТОЯНИЕ, RU, [RU]);
    const сняли = переключить(строки, [RU], RU);

    expect(сняли).toEqual([]);
    expect(кПубликации(строкиЯзыков(СОСТОЯНИЕ, RU, сняли))).toEqual([]);
    expect(кПубликации(строкиЯзыков(СОСТОЯНИЕ, RU, переключить(строки, сняли, ES)))).toEqual([ES]);
  });

  it('ссылки считаются по всем отмеченным живым версиям, общая статья — один раз', () => {
    expect(ссылокВОтмеченных(строкиЯзыков(СОСТОЯНИЕ, RU, [RU]))).toBe(2);
    expect(ссылокВОтмеченных(строкиЯзыков(СОСТОЯНИЕ, RU, [RU, ES]))).toBe(3);
  });
});
