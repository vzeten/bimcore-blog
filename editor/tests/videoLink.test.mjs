// Имя каждого теста повторяет формулировку правила.
// Ссылка на видео: что программа принимает от человека и что кладёт в статью.
import {describe, expect, it} from 'vitest';
import {номерВидео, обложкаВидео, ссылкаВидео} from '../src/core/videoLink.mjs';

const НОМЕР = 'ifJtfM3LgGg';

describe('номер видео из того, что человек вставил', () => {
  const свои = [
    `https://www.youtube.com/watch?v=${НОМЕР}`,
    `http://www.youtube.com/watch?v=${НОМЕР}`,
    `www.youtube.com/watch?v=${НОМЕР}`,
    `youtube.com/watch?v=${НОМЕР}&t=42s`,
    `https://m.youtube.com/watch?v=${НОМЕР}`,
    `https://youtu.be/${НОМЕР}`,
    `https://youtu.be/${НОМЕР}?t=42`,
    `https://www.youtube.com/embed/${НОМЕР}`,
    `https://www.youtube-nocookie.com/embed/${НОМЕР}`,
    `  https://www.youtube.com/watch?v=${НОМЕР}  `,
  ];

  for (const ссылка of свои) {
    it(`обычная ссылка даёт номер видео: ${ссылка.trim()}`, () => {
      expect(номерВидео(ссылка)).toEqual({номер: НОМЕР});
    });
  }

  it('голый номер принимается: он и лежит в уже вставленном блоке, отказывать в нём нелепо', () => {
    expect(номерВидео(НОМЕР)).toEqual({номер: НОМЕР});
  });

  const чужие = [
    ['', 'пусто'],
    ['   ', 'пусто'],
    ['совсем не ссылка', 'неСсылка'],
    ['ютуб', 'неСсылка'],
    ['https://youtube com/watch?v=abc', 'неСсылка'],
    ['https://vimeo.com/76979871', 'чужаяСсылка'],
    ['https://rutube.ru/video/abc/', 'чужаяСсылка'],
    ['https://www.youtube.com/@bimcore', 'нетНомера'],
    ['https://www.youtube.com/watch?v=коротко', 'нетНомера'],
    ['https://www.youtube.com/playlist?list=PLabc', 'нетНомера'],
  ];

  for (const [ввод, причина] of чужие) {
    it(`неверная ссылка не даёт номера и называет причину «${причина}»: ${JSON.stringify(ввод)}`, () => {
      // Отказ обязан называть причину: «не получилось» человек не знает, как чинить.
      expect(номерВидео(ввод)).toEqual({ошибка: причина});
    });
  }
});

describe('ссылка и обложка собираются из номера', () => {
  it('ссылка человеку собирается в одном виде, каким бы способом её ни вставили', () => {
    expect(ссылкаВидео(НОМЕР)).toBe(`https://www.youtube.com/watch?v=${НОМЕР}`);
  });

  it('пустой номер не даёт ссылки-обрубка', () => {
    expect(ссылкаВидео('')).toBe('');
  });

  it('обложка берётся у номера, и это мелкий кадр: он есть у каждого видео', () => {
    expect(обложкаВидео(НОМЕР)).toBe(`https://i.ytimg.com/vi/${НОМЕР}/hqdefault.jpg`);
  });

  it('у непонятного номера обложки нет вовсе: битый адрес показывать нечем', () => {
    expect(обложкаВидео('')).toBeNull();
    expect(обложкаВидео('коротко')).toBeNull();
  });
});
