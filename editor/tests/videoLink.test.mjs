// Имя каждого теста повторяет формулировку правила.
// Ссылка на видео и его длительность: что программа принимает от человека и что кладёт в статью.
import {describe, expect, it} from 'vitest';
import {
  длительностьВСекундах, номерВидео, обложкаВидео, разборДлительности, ссылкаВидео,
} from '../src/core/videoLink.mjs';

const НОМЕР = 'ifJtfM3LgGg';

describe('номер видео из того, что человек вставил', () => {
  const свои = [
    `https://www.youtube.com/watch?v=${НОМЕР}`,
    `http://www.youtube.com/watch?v=${НОМЕР}`,
    `www.youtube.com/watch?v=${НОМЕР}`,
    `youtube.com/watch?v=${НОМЕР}&t=42s`,
    `https://m.youtube.com/watch?v=${НОМЕР}`,
    `https://youtu.be/${НОМЕР}`,
    `https://youtu.be/${НОМЕР}?t=42`,
    `https://www.youtube.com/embed/${НОМЕР}`,
    `https://www.youtube-nocookie.com/embed/${НОМЕР}`,
    `  https://www.youtube.com/watch?v=${НОМЕР}  `,
  ];

  for (const ссылка of свои) {
    it(`обычная ссылка даёт номер видео: ${ссылка.trim()}`, () => {
      expect(номерВидео(ссылка)).toEqual({номер: НОМЕР});
    });
  }

  it('голый номер принимается: он и лежит в уже вставленном блоке, отказывать в нём нелепо', () => {
    expect(номерВидео(НОМЕР)).toEqual({номер: НОМЕР});
  });

  const чужие = [
    ['', 'пусто'],
    ['   ', 'пусто'],
    ['совсем не ссылка', 'неСсылка'],
    ['ютуб', 'неСсылка'],
    ['https://youtube com/watch?v=abc', 'неСсылка'],
    ['https://vimeo.com/76979871', 'чужаяСсылка'],
    ['https://rutube.ru/video/abc/', 'чужаяСсылка'],
    ['https://www.youtube.com/@bimcore', 'нетНомера'],
    ['https://www.youtube.com/watch?v=коротко', 'нетНомера'],
    ['https://www.youtube.com/playlist?list=PLabc', 'нетНомера'],
  ];

  for (const [ввод, причина] of чужие) {
    it(`неверная ссылка не даёт номера и называет причину «${причина}»: ${JSON.stringify(ввод)}`, () => {
      // Отказ обязан называть причину: «не получилось» человек не знает, как чинить.
      expect(номерВидео(ввод)).toEqual({ошибка: причина});
    });
  }
});

describe('ссылка и обложка собираются из номера', () => {
  it('ссылка человеку собирается в одном виде, каким бы способом её ни вставили', () => {
    expect(ссылкаВидео(НОМЕР)).toBe(`https://www.youtube.com/watch?v=${НОМЕР}`);
  });

  it('пустой номер не даёт ссылки-обрубка', () => {
    expect(ссылкаВидео('')).toBe('');
  });

  it('обложка берётся у номера, и это мелкий кадр: он есть у каждого видео', () => {
    expect(обложкаВидео(НОМЕР)).toBe(`https://i.ytimg.com/vi/${НОМЕР}/hqdefault.jpg`);
  });

  it('у непонятного номера обложки нет вовсе: битый адрес показывать нечем', () => {
    expect(обложкаВидео('')).toBeNull();
    expect(обложкаВидео('коротко')).toBeNull();
  });
});

describe('длительность человеческими минутами и секундами', () => {
  it('число секунд из статьи читается минутами и секундами', () => {
    expect(разборДлительности('330')).toEqual({минуты: '5', секунды: '30'});
    expect(разборДлительности('62')).toEqual({минуты: '1', секунды: '2'});
    expect(разборДлительности('45')).toEqual({минуты: '0', секунды: '45'});
  });

  it('старая запись PT читается тоже: её мог оставить человек или прежний редактор', () => {
    expect(разборДлительности('PT5M30S')).toEqual({минуты: '5', секунды: '30'});
    expect(разборДлительности('PT5M')).toEqual({минуты: '5', секунды: '0'});
    expect(разборДлительности('PT90S')).toEqual({минуты: '1', секунды: '30'});
    expect(разборДлительности('PT1H2M3S')).toEqual({минуты: '62', секунды: '3'});
  });

  it('пустая длительность — это пустые поля, а не ноль минут', () => {
    expect(разборДлительности('')).toEqual({минуты: '', секунды: ''});
    expect(разборДлительности(undefined)).toEqual({минуты: '', секунды: ''});
  });

  it('непонятная запись не выдумывается заново: о ней говорится, а не молчится', () => {
    expect(разборДлительности('пять минут')).toBeNull();
    expect(разборДлительности('PT')).toBeNull();
    expect(разборДлительности('5:30')).toBeNull();
  });

  it('минуты и секунды складываются обратно в число секунд — договор компонента сайта', () => {
    expect(длительностьВСекундах('5', '30')).toBe('330');
    expect(длительностьВСекундах('', '45')).toBe('45');
    expect(длительностьВСекундах('2', '')).toBe('120');
  });

  it('оба поля пустые дают пустое значение: длительность необязательна, ноль вместо неё — враньё', () => {
    expect(длительностьВСекундах('', '')).toBe('');
  });

  it('явный ноль остаётся нулём: это ответ человека, а не пустое поле', () => {
    expect(длительностьВСекундах('0', '0')).toBe('0');
  });

  it('не-число отвергается целиком, а не превращается в ноль секунд', () => {
    expect(длительностьВСекундах('пять', '30')).toBeNull();
    expect(длительностьВСекундах('5', '-30')).toBeNull();
    expect(длительностьВСекундах('5', '3,5')).toBeNull();
  });

  it('круг «прочитали — записали» не меняет числа: 330 секунд остаются 330', () => {
    const {минуты, секунды} = разборДлительности('330');

    expect(длительностьВСекундах(минуты, секунды)).toBe('330');
  });
});
