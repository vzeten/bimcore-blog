// Настоящие картинки для тестов: с ними работают ручки, а не с набором верных байтов.
//
// Прежде тесты подсовывали «скелеты» — сигнатуру формата и пару меток целости. Программа их
// принимала, потому что дальше сигнатур не смотрела. Теперь картинка ещё и разбирается, и такой
// скелет честно отвергается: это не изображение, и на сайте оно не открылось бы. Значит проверять
// приём картинок скелетами больше нельзя — нужны настоящие файлы.

import sharp from 'sharp';

/**
 * Настоящий PNG заданного размера. `шум` делает картинку несжимаемой — только так получается
 * файл, который и правда весит сотни килобайт: ровная заливка ужимается в считаные байты,
 * и «тяжёлым» её не сделать никаким размером.
 */
export async function png({ширина = 40, высота = 30, шум = false, зерно = 1, прозрачность = false} = {}) {
  const каналов = прозрачность ? 4 : 3;

  return sharp(пиксели({ширина, высота, шум, зерно, каналов}), {raw: {width: ширина, height: высота, channels: каналов}})
    .png({compressionLevel: шум ? 0 : 9})
    .toBuffer();
}

/**
 * Картинка, похожая на фотографию: плавные переходы с мелкой рябью. Такую JPG сжимает в разы
 * лучше палитры — на ней и проверяется правило «формат меняется сам, когда так легче».
 */
export async function фото({ширина = 800, высота = 600, альфа = null} = {}) {
  // `альфа`: null — картинка без канала прозрачности; 255 — канал есть, но всё непрозрачно
  // (так делает Figma); меньшее число — настоящая прозрачность в углу.
  const каналов = альфа === null ? 3 : 4;
  const данные = Buffer.alloc(ширина * высота * каналов);

  for (let y = 0; y < высота; y += 1) {
    for (let x = 0; x < ширина; x += 1) {
      const п = (y * ширина + x) * каналов;
      if (каналов === 4) данные[п + 3] = x < 20 && y < 20 ? альфа : 255;
      const волна = Math.sin(x / 40) * Math.cos(y / 55);
      данные[п] = Math.round(128 + 90 * волна + (x % 3));
      данные[п + 1] = Math.round(120 + 80 * Math.sin((x + y) / 70) + (y % 3));
      данные[п + 2] = Math.round(140 + 70 * Math.cos(x / 90) + ((x + y) % 3));
    }
  }

  return sharp(данные, {raw: {width: ширина, height: высота, channels: каналов}})
    .png({compressionLevel: 9})
    .toBuffer();
}

/** Настоящий JPEG заданного размера. Тот же шум делает файл по-настоящему тяжёлым. */
export async function jpg({ширина = 40, высота = 30, шум = false, зерно = 1, качество = 100} = {}) {
  return sharp(пиксели({ширина, высота, шум, зерно}), {raw: {width: ширина, height: высота, channels: 3}})
    .jpeg({quality: качество, chromaSubsampling: '4:4:4'})
    .toBuffer();
}

/** Размеры готовой картинки — ими тесты доказывают, что длинная сторона и правда уменьшилась. */
export async function размеры(bytes) {
  const {width, height} = await sharp(bytes).metadata();
  return {ширина: width, высота: height};
}

/**
 * Та же картинка ровно заданного веса. Нужна для проверки границ: «ровно 200 КБ остаётся байт
 * в байт» доказывается только файлом ровно в 200 КБ, а не «примерно».
 *
 * Вес добирается служебной записью внутри файла — комментарием, который картинку не меняет:
 * у PNG это чанк `tEXt`, у JPEG сегмент `COM`. Оба формата их разрешают, и картинка остаётся
 * целой для любого просмотрщика.
 */
export function доВеса(картинка, сколько) {
  const формат = картинка[0] === 0x89 ? 'png' : 'jpg';
  const добавка = сколько - картинка.length;
  const наименьшая = формат === 'png' ? 12 : 4;
  if (добавка < наименьшая) throw new Error(`картинка уже ${картинка.length} Б, ровно ${сколько} Б не выйдет`);

  return формат === 'png' ? сТекстомPng(картинка, добавка) : сКомментариемJpg(картинка, добавка);
}

/** Вставить в PNG служебный текстовый чанк ровно нужной длины — перед меткой конца файла. */
function сТекстомPng(картинка, добавка) {
  const данные = Buffer.alloc(добавка - 12, 0x78);
  const тело = Buffer.concat([Buffer.from('tEXt', 'latin1'), данные]);
  const длина = Buffer.alloc(4);
  длина.writeUInt32BE(данные.length, 0);
  const сумма = Buffer.alloc(4);
  сумма.writeUInt32BE(crc32(тело), 0);

  // `IEND` — последние 12 байт файла: длина, тип, пустые данные и контрольная сумма.
  const конец = картинка.length - 12;
  return Buffer.concat([картинка.subarray(0, конец), длина, тело, сумма, картинка.subarray(конец)]);
}

/**
 * Вставить в JPEG сегменты комментария сразу за меткой начала файла. Длина одного сегмента
 * записывается двумя байтами, поэтому большой вес набирается несколькими сегментами подряд.
 */
function сКомментариемJpg(картинка, добавка) {
  const куски = [картинка.subarray(0, 2)];
  let осталось = добавка;

  while (осталось > 0) {
    const тело = Math.min(осталось - 4, 65533);
    if (тело < 0) throw new Error('такой вес одним комментарием не набрать');
    const голова = Buffer.alloc(4);
    голова.writeUInt16BE(0xfffe, 0);
    голова.writeUInt16BE(тело + 2, 2);
    куски.push(голова, Buffer.alloc(тело, 0x78));
    осталось -= тело + 4;
  }

  куски.push(картинка.subarray(2));
  return Buffer.concat(куски);
}

/**
 * Тот же PNG, объявленный анимированным: перед данными картинки встаёт чанк `acTL`, которым
 * формат APNG объявляет число кадров. Настоящих кадров тут нет — проверяется правило «программу
 * анимация не декодирует», а не сама анимация.
 */
export function сАнимациейPng(картинка) {
  const данные = Buffer.alloc(8);
  данные.writeUInt32BE(2, 0);
  данные.writeUInt32BE(0, 4);
  const тело = Buffer.concat([Buffer.from('acTL', 'latin1'), данные]);
  const длина = Buffer.alloc(4);
  длина.writeUInt32BE(данные.length, 0);
  const сумма = Buffer.alloc(4);
  сумма.writeUInt32BE(crc32(тело), 0);

  // Чанк обязан стоять до первых данных картинки (`IDAT`), иначе он ничего не объявляет.
  const место = картинка.indexOf(Buffer.from('IDAT', 'latin1')) - 4;
  return Buffer.concat([картинка.subarray(0, место), длина, тело, сумма, картинка.subarray(место)]);
}

/** Точки картинки: либо ровная заливка, либо несжимаемый шум с предсказуемым зерном. */
function пиксели({ширина, высота, шум, зерно, каналов = 3}) {
  const данные = Buffer.alloc(ширина * высота * каналов);
  let число = зерно;

  for (let i = 0; i < данные.length; i += 1) {
    // Прозрачность делается частичной: сплошь непрозрачную альфу библиотека выбрасывает,
    // и проверка «для прозрачной картинки JPG не готовится» ничего бы не доказала.
    if (каналов === 4 && (i + 1) % 4 === 0) {
      данные[i] = i % 8 === 3 ? 128 : 255;
      continue;
    }
    if (!шум) {
      // Ровная заливка: такая картинка ужимается в считаные байты, и файл выходит заведомо лёгким.
      данные[i] = 128;
      continue;
    }
    // Простой предсказуемый датчик: один и тот же тест обязан давать один и тот же файл.
    число = (число * 1103515245 + 12345) & 0x7fffffff;
    данные[i] = (число >> 16) & 0xff;
  }

  return данные;
}

/** Контрольная сумма чанка PNG — того же вида, что считает сам формат. */
function crc32(байты) {
  let сумма = 0xffffffff;

  for (const байт of байты) {
    сумма ^= байт;
    for (let бит = 0; бит < 8; бит += 1) {
      сумма = (сумма >>> 1) ^ (0xedb88320 & -(сумма & 1));
    }
  }

  return (сумма ^ 0xffffffff) >>> 0;
}
