// Имя каждого теста повторяет формулировку правила.
// Дата записи блога: чистое правило — какой `date` обязан стоять у открытой версии.
import {describe, expect, it} from 'vitest';

import {датаРасходится, нужнаяДата} from '../src/core/publishDate.mjs';

const СЕГОДНЯ = '2026-09-16';

describe('дата записи блога', () => {
  it('записи на сайте ещё нет — ставится сегодняшний день: это и есть день первой публикации', () => {
    expect(нужнаяДата({род: 'blog', своя: null, соседи: [], сегодня: СЕГОДНЯ})).toBe(СЕГОДНЯ);
  });

  it('опубликован соседний язык — берётся его дата: языковые версии стоят в ленте одним днём', () => {
    expect(нужнаяДата({род: 'blog', своя: null, соседи: [{дата: '2026-07-12'}], сегодня: СЕГОДНЯ}))
      .toBe('2026-07-12');
  });

  it('версия уже на сайте — остаётся дата сайта, даже когда в файле стоит другая или её нет вовсе', () => {
    // Так чинится и заглушка, которую публикация создала с датой, а на диске её нет,
    // и ручная правка даты уже вышедшей записи.
    expect(нужнаяДата({род: 'blog', своя: {дата: '2026-01-05'}, соседи: [], сегодня: СЕГОДНЯ}))
      .toBe('2026-01-05');
  });

  it('версия на сайте есть, а даты у неё там нет — программа даты не касается', () => {
    // Выдумать день выхода уже вышедшей записи нельзя: он сдвинул бы её в ленте и в карте сайта.
    expect(нужнаяДата({род: 'blog', своя: {дата: null}, соседи: [{дата: '2026-07-12'}], сегодня: СЕГОДНЯ}))
      .toBeNull();
  });

  it('у документации и песочницы даты не бывает вовсе', () => {
    expect(нужнаяДата({род: 'docs', своя: null, соседи: [], сегодня: СЕГОДНЯ})).toBeNull();
    expect(нужнаяДата({род: 'проба', своя: null, соседи: [], сегодня: СЕГОДНЯ})).toBeNull();
  });

  it('пустая дата соседа датой не считается: берётся следующий опубликованный язык', () => {
    expect(нужнаяДата({род: 'blog', своя: null, соседи: [{дата: '   '}, {дата: '2026-02-03'}], сегодня: СЕГОДНЯ}))
      .toBe('2026-02-03');
  });

  it('расхождение считается по нужной дате: её отсутствие правкой файла не является', () => {
    expect(датаРасходится({нужна: СЕГОДНЯ, вФайле: null})).toBe(true);
    expect(датаРасходится({нужна: СЕГОДНЯ, вФайле: '2026-01-05'})).toBe(true);
    expect(датаРасходится({нужна: СЕГОДНЯ, вФайле: СЕГОДНЯ})).toBe(false);
    expect(датаРасходится({нужна: null, вФайле: '2026-01-05'})).toBe(false);
  });
});
