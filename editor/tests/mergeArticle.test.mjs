// Имя каждого теста повторяет формулировку правила.
// Сведение статьи из трёх сторон: тело строками, шапка кусками полей. Диска здесь нет.
import {describe, expect, it} from 'vitest';

import {выборИзОтветов, свестиСтатью, собрать, спорЦеликом} from '../src/core/mergeArticle.mjs';

const пара = (шапка, тело) => ({frontmatterRaw: шапка, body: тело});

describe('сведение тела статьи', () => {
  it('человек правил один абзац, внешний ИИ — другой: в итоге обе правки', () => {
    const {сведено, спорные} = свестиСтатью({
      база: пара('title: A', '\nпервый\n\nвторой\n'),
      мои: пара('title: A', '\nМОЙ\n\nвторой\n'),
      внешние: пара('title: A', '\nпервый\n\nВНЕШНИЙ\n'),
    });

    expect(спорные).toEqual([]);
    expect(сведено.body).toBe('\nМОЙ\n\nВНЕШНИЙ\n');
  });

  it('оба правили один абзац по-разному — спор с тремя сторонами, а не тихий выбор', () => {
    const {сведено, спорные} = свестиСтатью({
      база: пара('title: A', '\nтекст\n'),
      мои: пара('title: A', '\nмой текст\n'),
      внешние: пара('title: A', '\nвнешний текст\n'),
    });

    expect(сведено).toBeNull();
    expect(спорные).toEqual([{место: 'тело', номер: 0, база: 'текст', мои: 'мой текст', внешние: 'внешний текст'}]);
  });

  it('значимые пробелы и пустые строки — часть текста, а не шум', () => {
    const {сведено} = свестиСтатью({
      база: пара('title: A', '\nа\n'),
      мои: пара('title: A', '\nа  \n'),
      внешние: пара('title: A', '\nа\n'),
    });

    expect(сведено.body).toBe('\nа  \n');
  });

  it('неразрывный пробел вместо обычного — настоящая правка, и она не теряется', () => {
    const {сведено} = свестиСтатью({
      база: пара('title: A', '\nдва слова\n'),
      мои: пара('title: A', '\nдва слова\n'),
      внешние: пара('title: A', '\nдва слова\n'),
    });

    expect(сведено.body).toBe('\nдва слова\n');
  });

  it('переводы строк вида файла расхождением не считаются', () => {
    const {сведено, спорные} = свестиСтатью({
      база: пара('title: A', '\r\nа\r\nб\r\n'),
      мои: пара('title: A', '\nа\nБ\n'),
      внешние: пара('title: A', '\r\nа\r\nб\r\n'),
    });

    expect(спорные).toEqual([]);
    expect(сведено.body).toBe('\nа\nБ\n');
  });

  it('внешний ИИ поправил абзац ВЫШЕ человеческого — оба абзаца на своих местах', () => {
    const {сведено, спорные} = свестиСтатью({
      база: пара('title: A', '\nпервый\n\nвторой\n'),
      мои: пара('title: A', '\nпервый\n\nМОЙ\n'),
      внешние: пара('title: A', '\nВНЕШНИЙ\n\nвторой\n'),
    });

    expect(спорные).toEqual([]);
    expect(сведено.body).toBe('\nВНЕШНИЙ\n\nМОЙ\n');
  });
});

describe('сведение шапки статьи', () => {
  it('разные поля правили разные стороны — обе правки в шапке', () => {
    const {сведено, спорные} = свестиСтатью({
      база: пара('title: A\ndescription: старое', '\nт\n'),
      мои: пара('title: МОЁ\ndescription: старое', '\nт\n'),
      внешние: пара('title: A\ndescription: ВНЕШНЕЕ', '\nт\n'),
    });

    expect(спорные).toEqual([]);
    expect(сведено.frontmatterRaw).toBe('title: МОЁ\ndescription: ВНЕШНЕЕ');
  });

  it('одно поле привели к одному значению обе стороны — расхождения нет', () => {
    const {сведено, спорные} = свестиСтатью({
      база: пара('title: A', '\nт\n'),
      мои: пара('title: Общее', '\nт\n'),
      внешние: пара('title: Общее', '\nт\n'),
    });

    expect(спорные).toEqual([]);
    expect(сведено.frontmatterRaw).toBe('title: Общее');
  });

  it('список в шапке правили обе стороны — спор целым полем, без склейки по догадке', () => {
    // Блочный список — один кусок правки. Свести его построчно значит решить за человека,
    // какие элементы он хотел оставить.
    const список = (хвост) => `title: A\nkeywords:\n  - один\n  - ${хвост}`;
    const {сведено, спорные} = свестиСтатью({
      база: пара(список('два'), '\nт\n'),
      мои: пара(список('моё'), '\nт\n'),
      внешние: пара(список('внешнее'), '\nт\n'),
    });

    expect(сведено).toBeNull();
    expect(спорные).toHaveLength(1);
    expect(спорные[0].место).toBe('шапка');
    expect(спорные[0].мои).toContain('- моё');
    expect(спорные[0].внешние).toContain('- внешнее');
  });

  it('внешняя сторона добавила поле, человек его не трогал — поле остаётся', () => {
    const {сведено} = свестиСтатью({
      база: пара('title: A', '\nт\n'),
      мои: пара('title: A', '\nМОЁ\n'),
      внешние: пара('title: A\nimage: ./cover.png', '\nт\n'),
    });

    expect(сведено.frontmatterRaw).toBe('title: A\nimage: ./cover.png');
    expect(сведено.body).toBe('\nМОЁ\n');
  });
});

describe('ответы человека собирают итог', () => {
  it('выбранная сторона спорного места попадает в собранный текст', () => {
    const {части} = свестиСтатью({
      база: пара('title: A', '\nтекст\n'),
      мои: пара('title: A', '\nмой\n'),
      внешние: пара('title: A', '\nвнешний\n'),
    });

    expect(собрать(части, выборИзОтветов([{место: 'тело', номер: 0, сторона: 'внешние'}])).body)
      .toBe('\nвнешний\n');
    expect(собрать(части, выборИзОтветов([{место: 'тело', номер: 0, сторона: 'мои'}])).body)
      .toBe('\nмой\n');
  });

  it('ответ не про то место и не про ту сторону сборку не открывает', () => {
    const {части} = свестиСтатью({
      база: пара('title: A', '\nтекст\n'),
      мои: пара('title: A', '\nмой\n'),
      внешние: пара('title: A', '\nвнешний\n'),
    });

    expect(собрать(части, выборИзОтветов([{место: 'нигде', номер: 0, сторона: 'мои'}]))).toBeNull();
    expect(собрать(части, выборИзОтветов([{место: 'тело', номер: 0, сторона: 'чужое'}]))).toBeNull();
  });
});

describe('спор целиком, когда базы нет', () => {
  it('обе стороны целы и выбираются одним ответом на каждое место', () => {
    const части = спорЦеликом(пара('title: МОЁ', '\nмой\n'), пара('title: ВНЕШНЕЕ', '\nвнешний\n'));
    const выбор = выборИзОтветов([
      {место: 'тело', номер: 0, сторона: 'внешние'},
      {место: 'шапка', номер: 0, сторона: 'мои'},
    ]);

    expect(собрать(части, выбор)).toEqual(пара('title: МОЁ', '\nвнешний\n'));
  });
});
