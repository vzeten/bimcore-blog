// Имя каждого теста повторяет формулировку правила.
// Состояние КАЖДОЙ языковой версии видно возле её букв: признаки независимы, складываются и не
// заменяют друг друга, а общего слова готовности у статьи больше нет.
// Наблюдение владельца, ради которого правило заведено: «RU опубликована, EN изменена, ES
// заглушка» показывалось одним словом «Опубликована», и правка EN пропадала из виду.
import {describe, expect, it} from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

import {
  признакиЛокали, подсказкаЛокали, путиЗаВидимостью, скрытаНаСайте, цветЛокали, черновикСайта,
} from '../src/core/localeSigns.mjs';

const EDITOR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const НАСТРОЙКИ = JSON.parse(fs.readFileSync(path.join(EDITOR, 'settings.json'), 'utf8'));

/** Запись версии в своде: по умолчанию опубликована и совпадает с веткой. */
const версия = (ещё = {}) => ({
  path: 'docs/lessons/walls/index.mdx',
  опубликован: true,
  отличается: false,
  заглушка: false,
  черновикСайта: false,
  скрыта: false,
  скрытаВВетке: null,
  ...ещё,
});

describe('признаки языковой версии', () => {
  it('версия опубликована и совпадает с веткой — буквы обычные, ни одного знака рядом', () => {
    const п = признакиЛокали(версия());

    expect(п).toEqual({
      есть: true, черновик: false, неПубликовалась: false, изменена: false, заглушка: false, поСсылке: false,
    });
    expect(цветЛокали(п)).toBe('обычная');
  });

  it('существующая версия ещё ни разу не публиковалась — буквы синие', () => {
    const п = признакиЛокали(версия({опубликован: false, отличается: false}));

    expect(п.неПубликовалась).toBe(true);
    expect(цветЛокали(п)).toBe('новая');
  });

  it('файла локали нет — буквы бледные, и ни один другой признак не выдумывается', () => {
    const п = признакиЛокали(null);

    expect(п).toEqual({
      есть: false, черновик: false, неПубликовалась: false, изменена: false, заглушка: false, поСсылке: false,
    });
    expect(цветЛокали(п)).toBe('нет');
  });

  it('в шапке версии стоит draft: true — буквы красные, и это важнее синего цвета', () => {
    const п = признакиЛокали(версия({опубликован: false, черновикСайта: true}));

    // Оба признака остаются правдой; спорят они только за цвет, и там побеждает `draft`.
    expect(п.черновик).toBe(true);
    expect(п.неПубликовалась).toBe(true);
    expect(цветЛокали(п)).toBe('черновик');
  });

  it('опубликованный файл есть, но местная версия отличается — красная точка сверху', () => {
    const п = признакиЛокали(версия({опубликован: true, отличается: true}));

    expect(п.изменена).toBe(true);
    // Цвет при этом обычный: версия опубликована, изменение показывает точка, а не буквы.
    expect(цветЛокали(п)).toBe('обычная');
  });

  it('версии в опубликованной ветке нет — точки «изменена» не бывает', () => {
    // Иначе новая статья, которой на сайте нет вовсе, получила бы знак неуехавшей правки.
    expect(признакиЛокали(версия({опубликован: false, отличается: true})).изменена).toBe(false);
  });

  it('про публикацию не известно ничего — программа молчит, а не говорит «не публиковалась»', () => {
    // Ветку прочитать не удалось: `null` — это не «нет». Ложное «ещё не публиковалась» было бы
    // новым враньём вместо прежнего (SPEC 4.5.2, тем же порядком живёт `publishFacts`).
    const п = признакиЛокали(версия({опубликован: null, отличается: null}));

    expect(п.неПубликовалась).toBe(false);
    expect(п.изменена).toBe(false);
    expect(цветЛокали(п)).toBe('обычная');
  });

  it('существующая версия является заглушкой — свой признак у неё есть, своего знака нет', () => {
    // Факт заглушки ядро считает по-прежнему: он нужен подсказке словами и правилам программы.
    // Отдельной точки в интерфейсе у него нет — решение владельца 2026-09-07 (`tests/localeMark`).
    expect(признакиЛокали(версия({заглушка: true})).заглушка).toBe(true);
  });

  it('опубликованная версия скрыта на сайте — значок ссылки снизу', () => {
    // Файл совпадает с веткой, значит его собственная шапка и есть опубликованная.
    expect(признакиЛокали(версия({скрыта: true})).поСсылке).toBe(true);
  });

  it('признаки складываются и не стирают друг друга', () => {
    const п = признакиЛокали(версия({
      опубликован: true, отличается: true, заглушка: true, черновикСайта: true,
      скрыта: true, скрытаВВетке: true,
    }));

    expect(п).toEqual({
      есть: true, черновик: true, неПубликовалась: false, изменена: true, заглушка: true, поСсылке: true,
    });
    expect(цветЛокали(п)).toBe('черновик');
  });
});

describe('значок «только по ссылке» отвечает про сайт, а не про файл', () => {
  it('опубликованная версия скрыта на сайте — значок есть', () => {
    expect(скрытаНаСайте(версия({отличается: true, скрыта: true, скрытаВВетке: true}))).toBe(true);
    expect(признакиЛокали(версия({отличается: true, скрыта: true, скрытаВВетке: true})).поСсылке).toBe(true);
  });

  it('опубликована скрытой, а локально флаг снят — значок остаётся до публикации', () => {
    const п = признакиЛокали(версия({отличается: true, скрыта: false, скрытаВВетке: true}));

    expect(п.поСсылке).toBe(true);
    // Снятый флаг — неопубликованная правка, и показывает её точка, а не исчезнувший значок.
    expect(п.изменена).toBe(true);
  });

  it('опубликована обычной, а локально флаг поставлен — значка до публикации нет', () => {
    const п = признакиЛокали(версия({отличается: true, скрыта: true, скрытаВВетке: false}));

    expect(п.поСсылке).toBe(false);
    expect(п.изменена).toBe(true);
  });

  it('опубликована обычной и не менялась — значка нет', () => {
    expect(скрытаНаСайте(версия({скрыта: false}))).toBe(false);
    expect(признакиЛокали(версия({скрыта: false})).поСсылке).toBe(false);
  });

  it('версия ещё не публиковалась — местный unlisted значка не создаёт', () => {
    expect(скрытаНаСайте(версия({опубликован: false, скрыта: true}))).toBe(false);
    expect(признакиЛокали(версия({опубликован: false, скрыта: true})).поСсылке).toBe(false);
  });

  it('про опубликованную шапку не известно ничего — значок молчит, а не выдумывается', () => {
    expect(скрытаНаСайте(версия({отличается: true, скрыта: true}))).toBe(null);
    expect(признакиЛокали(версия({отличается: true, скрыта: true})).поСсылке).toBe(false);
    // Ветку не прочитали вовсе — тем же порядком.
    expect(скрытаНаСайте(версия({опубликован: null, отличается: null, скрыта: true}))).toBe(false);
  });

  it('у ветки спрашивают только те статьи, что расходятся с ней', () => {
    const опубликованные = new Set(['blog/a/index.mdx', 'blog/b/index.mdx', 'blog/a/foto.jpg']);

    expect(путиЗаВидимостью(опубликованные, new Set(['blog/a/index.mdx', 'blog/a/foto.jpg'])))
      .toEqual(['blog/a/index.mdx']);
    // Новой версии в ветке нет — спрашивать про неё нечего.
    expect(путиЗаВидимостью(опубликованные, new Set(['blog/novaya/index.mdx']))).toEqual([]);
    // Сравнить не удалось — не спрашивается никто: догадка хуже молчания.
    expect(путиЗаВидимостью(опубликованные, null)).toEqual([]);
  });
});

describe('draft в шапке версии', () => {
  it('draft: true читается как черновик сайта', () => {
    expect(черновикСайта('title: Стены\ndraft: true')).toBe(true);
  });

  it('draft: false и отсутствие поля означают одинаковое отсутствие красной окраски', () => {
    expect(черновикСайта('title: Стены\ndraft: false')).toBe(false);
    expect(черновикСайта('title: Стены')).toBe(false);
    expect(цветЛокали(признакиЛокали(версия({черновикСайта: false})))).toBe('обычная');
  });

  it('регистр YAML не важен: True и TRUE — тот же черновик', () => {
    expect(черновикСайта('draft: True')).toBe(true);
    expect(черновикСайта('draft: TRUE')).toBe(true);
  });

  it('чужое поле, начинающееся на draft, черновиком не считается', () => {
    expect(черновикСайта('drafted: true')).toBe(false);
  });
});

describe('подсказка про языковую версию', () => {
  it('цвет не единственное объяснение: каждый сложившийся признак назван словами', () => {
    const текст = подсказкаЛокали(
      'en',
      признакиЛокали(версия({
        опубликован: true, отличается: true, заглушка: true, черновикСайта: true,
        скрыта: true, скрытаВВетке: true,
      })),
      НАСТРОЙКИ,
    );

    for (const слова of [
      НАСТРОЙКИ['подписи']['локальЧерновик'],
      НАСТРОЙКИ['подписи']['локальИзменена'],
      НАСТРОЙКИ['подписи']['локальЗаглушка'],
      НАСТРОЙКИ['видимость']['поСсылке'],
    ]) {
      expect(текст).toContain(слова);
    }
  });

  it('у спокойной версии подсказка — одно имя языка, без пустого перечня', () => {
    expect(подсказкаЛокали('ru', признакиЛокали(версия()), НАСТРОЙКИ)).toBe(НАСТРОЙКИ['локали']['ru']);
  });

  it('отсутствующая локаль называется словами, а не молчит бледным цветом', () => {
    expect(подсказкаЛокали('es', признакиЛокали(null), НАСТРОЙКИ)).toContain(НАСТРОЙКИ['подписи']['версииНет']);
  });

  it('слова зовущего добавляются к признакам, а не вместо них', () => {
    const текст = подсказкаЛокали('en', признакиЛокали(версия({скрыта: true})), НАСТРОЙКИ, ['правился раньше']);

    expect(текст).toContain(НАСТРОЙКИ['видимость']['поСсылке']);
    expect(текст).toContain('правился раньше');
  });
});

describe('сводных слов о состоянии статьи больше нет', () => {
  it('в реестре не осталось столбцов «Готовность» и «Видимость»', () => {
    const ключи = НАСТРОЙКИ['реестр']['колонки'].map((столбец) => столбец['ключ']);

    expect(ключи).toContain('переводы');
    expect(ключи).not.toContain('готовность');
    expect(ключи).not.toContain('видимость');
  });

  it('шапка открытой статьи не показывает одно слово готовности', () => {
    // Предохранитель от возврата (SPEC 5.2.1): поведение окна машина здесь не запускает, а
    // возвращённое слово стало бы той же ложью про три независимые версии.
    const шапка = fs.readFileSync(path.join(EDITOR, 'src/ui/zones/TopBar.tsx'), 'utf8');

    expect(шапка).not.toContain('{props.article.готовность}');
  });
});
