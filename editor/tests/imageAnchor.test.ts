// Имя каждого теста повторяет формулировку правила.
// Зрительный якорь картинки: поправка берётся остатком от того, что редактор подвинул сам.
import {describe, expect, it} from 'vitest';
import {обёрткаКартинки, остаток} from '../src/ui/editor/imageAnchor';

describe('зрительный якорь картинки', () => {
  it('картинка осталась на прежнем месте — двигать нечего', () => {
    expect(остаток(300, 300)).toBe(0);
  });

  it('картинка уехала вниз — поправка возвращает её вверх ровно на разницу', () => {
    // Замер владельца: верх картинки был на 293 px, после замены стал 373 px.
    expect(остаток(293, 373)).toBe(80);
  });

  it('картинка уехала вверх — поправка тоже возвращает её на место', () => {
    expect(остаток(400, 250)).toBe(-150);
  });

  it('редактор подвинул содержимое сам — поправка равна остатку, а не всей разнице', () => {
    // Редактор уже вернул картинку почти на место: остаётся дотянуть два пикселя.
    expect(остаток(300, 302)).toBe(2);
  });

  it('разница меньше пикселя движением не считается', () => {
    expect(остаток(300, 300.4)).toBe(0);
    expect(остаток(300, 299.7)).toBe(0);
  });

  it('прежнего места не знаем — экран не дёргается вовсе', () => {
    expect(остаток(null, 500)).toBe(0);
  });
});

describe('какую картинку держит якорь', () => {
  /** Узел показа: столько, сколько нужно правилу — настоящего браузера здесь нет. */
  const картинка = (имя: string) => ({
    classList: {contains: (класс: string) => класс === 'md-image'},
    имя,
  });
  const текст = () => ({classList: {contains: () => false}});

  it('в строке с двумя картинками держится та, на которую указывает смещение', () => {
    // Иначе замена второй картинки уводила бы экран и панель к первой.
    const строка = {
      classList: {contains: () => false},
      childNodes: [картинка('первая'), текст(), картинка('вторая')],
    };

    expect(обёрткаКартинки(строка as never, 0)).toMatchObject({имя: 'первая'});
    expect(обёрткаКартинки(строка as never, 2)).toMatchObject({имя: 'вторая'});
  });

  it('смещение показывает на место сразу за картинкой — держится она же', () => {
    // Так бывает, когда позиция пришлась на конец узла картинки.
    const строка = {
      classList: {contains: () => false},
      childNodes: [картинка('своя'), текст()],
    };

    expect(обёрткаКартинки(строка as never, 1)).toMatchObject({имя: 'своя'});
  });

  it('позиция пришлась внутрь самой картинки — держится её обёртка', () => {
    const обёртка = картинка('своя');
    const внутри = {classList: {contains: () => false}, parentElement: обёртка};

    expect(обёрткаКартинки(внутри as never, 0)).toMatchObject({имя: 'своя'});
  });

  it('в этом месте картинки нет вовсе — держать нечего', () => {
    const строка = {classList: {contains: () => false}, childNodes: [текст(), текст()]};

    expect(обёрткаКартинки(строка as never, 0)).toBeNull();
  });
});
