// Имя каждого теста повторяет формулировку правила.
// Обход всего свода статей: правка правила пути состояния не меняет ни одного пути, кроме заранее
// объяснённых, и не меняет готовность ни у одной живой статьи. Контракт этого обхода записан в
// `CURRENT_TASK.md`, раздел 4: единица обхода — файл версии; прежний путь считается формулой
// СТАРОГО правила, записанной здесь же (иначе после удаления старого кода сравнивать не с чем);
// пустой обход красный наравне с расхождением — «расхождений нет» не должно быть неотличимо от
// «ничего не обошлось». Обе меры накрывают и пути, и готовность.
import {describe, expect, it} from 'vitest';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

import {initialReadiness, readState, путьФайлаСостояния} from '../src/core/articleState.mjs';
import {readinessOf, walk} from '../src/adapters/library.mjs';

const EDITOR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const REPO = path.resolve(EDITOR, '..');
const НАСТРОЙКИ = JSON.parse(fs.readFileSync(path.join(EDITOR, 'settings.json'), 'utf8'));

/** Формула старого правила: имя из настройки в папке файла версии. Живёт только здесь. */
const прежнийПуть = (rel) => `${path.posix.dirname(rel)}/${НАСТРОЙКИ['хранение']['файлСостояния']}`;

/** Все файлы версий свода тем же обходом, каким их видит программа. */
function свод() {
  const файлы = [];

  for (const корень of НАСТРОЙКИ['контент']) {
    for (const файл of walk(path.join(REPO, корень['папка']))) {
      файлы.push(path.relative(REPO, файл).split(path.sep).join('/'));
    }
  }

  return файлы.sort();
}

/**
 * Готовность, посчитанная по ПРЕЖНЕМУ пути: те же правила ядра, что и у программы, только текст
 * состояния берётся по старой формуле. Второго правила готовности здесь не заводится (SPEC 4.3).
 */
function прежняяГотовность(rel, опубликованные, корень = REPO) {
  const файл = path.join(корень, прежнийПуть(rel));
  const raw = fs.existsSync(файл) ? fs.readFileSync(файл, 'utf8') : '';

  return raw.trim() !== ''
    ? readState(raw, НАСТРОЙКИ)['готовность']
    : initialReadiness(опубликованные.has(rel), НАСТРОЙКИ);
}

describe('обход всего свода: правка не двигает пути состояния и не меняет готовность', () => {
  const файлы = свод();

  it('обход не пуст: иначе «расхождений нет» означало бы «ничего не смотрели»', () => {
    expect(файлы.length).toBeGreaterThan(0);
  });

  it('вычисленный путь состояния меняется только у файлов версий, лежащих не под именем index', () => {
    const разошлись = файлы.filter((rel) => путьФайлаСостояния(rel, НАСТРОЙКИ) !== прежнийПуть(rel));
    const необъяснённые = разошлись.filter((rel) => /^index\.mdx?$/.test(path.posix.basename(rel)));

    expect(необъяснённые).toEqual([]);
  });

  it('у статьи, лежащей папкой, путь состояния совпадает с прежним — переносить нечего', () => {
    const папкой = файлы.filter((rel) => /^index\.mdx?$/.test(path.posix.basename(rel)));

    expect(папкой.length).toBeGreaterThan(0);
    for (const rel of папкой) {
      expect(путьФайлаСостояния(rel, НАСТРОЙКИ)).toBe(прежнийПуть(rel));
    }
  });

  // Сколько физических файлов состояния лежит во своде, здесь НЕ проверяется, и это решено
  // намеренно: они коммитятся вместе со статьёй (пояснение в `settings.json`, ключ «хранение»), то
  // есть первое же сохранение живой статьи — правильная работа программы — сделало бы такую
  // проверку красной. «Сегодня их ноль» — разовое измерение для записки (`CURRENT_TASK.md`,
  // раздел 3), а не вечное правило. Сохранность существующих файлов доказывается стендом с
  // подложенным файлом в `statePath.test.mjs`, где перечень папки сверяется до и после.

  // Набор опубликованных задаётся здесь, а не спрашивается у git: сравниваются два способа
  // посчитать путь при одинаковом входе, и внешний ответ сделал бы прогон разным от запуска к запуску.
  for (const [имя, доля] of [['ни одна статья не опубликована', () => false], ['опубликованы все', () => true]]) {
    it(`готовность каждой статьи одна и та же по старому и новому пути: ${имя}`, () => {
      const опубликованные = new Set(файлы.filter(доля));
      let сверено = 0;

      for (const rel of файлы) {
        expect(readinessOf(REPO, rel, НАСТРОЙКИ, опубликованные))
          .toBe(прежняяГотовность(rel, опубликованные));
        сверено += 1;
      }

      expect(сверено).toBe(файлы.length);
      expect(сверено).toBeGreaterThan(0);
    });
  }

  /**
   * Мера чувствительности самого сличения, а не правила.
   *
   * Пока во своде нет ни одного файла состояния, обе стороны сравнения выше выводят готовность из
   * факта публикации, и путь в них не участвует вовсе: сверка верна, но промолчала бы при любой
   * поломке правила. Поэтому рядом стоит стенд, где расхождение обязано быть, — если и он покажет
   * совпадение, значит сличение сломано и верхнюю сверку читать нельзя.
   */
  it('сличение готовности видит расхождение там, где оно обязано быть', () => {
    const repo = fs.mkdtempSync(path.join(os.tmpdir(), 'editor-sweep-'));

    try {
      fs.mkdirSync(path.join(repo, 'docs/lessons'), {recursive: true});
      fs.writeFileSync(path.join(repo, 'docs/lessons/index.mdx'), '---\ntitle: Раздел\n---\n', 'utf8');
      fs.writeFileSync(path.join(repo, 'docs/lessons/a.mdx'), '---\ntitle: Файлом\n---\n', 'utf8');
      // Состояние лежит по СТАРОМУ пути — общее на папку. Ровно та болезнь, которую правка лечит.
      fs.writeFileSync(path.join(repo, 'docs/lessons/_state.json'), '{"готовность":"Готова к публикации"}', 'utf8');

      const пусто = new Set();

      // У статьи-файла старая формула читает чужое состояние, новая — своё, которого нет.
      expect(прежняяГотовность('docs/lessons/a.mdx', пусто, repo)).toBe('Готова к публикации');
      expect(readinessOf(repo, 'docs/lessons/a.mdx', НАСТРОЙКИ, пусто)).toBe('Черновик');

      // А у статьи папкой обе стороны читают один и тот же файл — здесь расхождения быть не должно.
      expect(readinessOf(repo, 'docs/lessons/index.mdx', НАСТРОЙКИ, пусто))
        .toBe(прежняяГотовность('docs/lessons/index.mdx', пусто, repo));
    } finally {
      fs.rmSync(repo, {recursive: true, force: true, maxRetries: 10, retryDelay: 100});
    }
  });
});
