// Имя каждого теста повторяет формулировку правила.
// Панель экземпляров: два риска, ради которых она вообще проверяется машиной, — остановить не тот
// процесс и показать устаревшее состояние как нынешнее.
import {describe, expect, it} from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

import {
  ВИД_МАТЕРИАЛЫ, ВИД_РАБОЧИЙ, НЕТ_ВЛАДЕЛЬЦА, НЕТ_ОПОЗНАНИЯ, НЕЧЕГО_ЗАПУСКАТЬ, НЕ_ТОТ_ПРОЦЕСС,
  ОСТАНОВЛЕН, ПОРТ_ЗАНЯТ, ПОРТ_ПАНЕЛИ, РАБОТАЕТ, УЖЕ_РАБОТАЕТ, ЧУЖОЙ, ЧУЖОЙ_ОТВЕТ,
  СМЕНИЛСЯ_ВЛАДЕЛЕЦ, вид, назвалНомер, опознаниеЛи, принадлежитКоду, решениеЗапуска,
  решениеОстановки, строки,
} from '../src/core/instanceControl.mjs';
import {ПОРТ_ВЛАДЕЛЬЦА, РОЛЬ_ИСПЫТАТЕЛЬНАЯ, РОЛЬ_ОБЫЧНАЯ} from '../src/core/runtimeIdentity.mjs';
import {порты, сПамятьюОРабочем} from '../src/adapters/panelRoute.mjs';

const EDITOR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const настоящие = JSON.parse(fs.readFileSync(path.join(EDITOR, 'settings.json'), 'utf8'));

const КОД_ИСПЫТАНИЯ = 'C:\\My_code\\bimcore-blog\\editor\\.coordination\\worktrees\\feature-x\\editor';

/** Живое опознание испытательного экземпляра на названном порту. */
const опознание = (порт, {код = КОД_ИСПЫТАНИЯ, роль = РОЛЬ_ИСПЫТАТЕЛЬНАЯ, принят = false} = {}) => ({
  role: роль, accepted: принят, branch: 'feature/x', commit: 'abc1234', clean: true,
  code: код, materials: 'D:\\проба', port: порт, url: `http://localhost:${порт}`,
});

const наш = (порт, что) => ({опознание: опознание(порт, что)});
const чужой = {чужой: true};

/** Командная строка настоящего запуска: node с полным путём до `server.mjs` папки кода. */
const командная = (код) => `"C:\\Program Files\\nodejs\\node.exe" "${код}\\server.mjs"`;

describe('панель не останавливает не тот процесс', () => {
  it('на порту отвечает не наш редактор — останавливать нечего, чужая программа не завершается', () => {
    expect(решениеОстановки({
      порт: 4781, ответ: чужой, владелец: {номер: 4242, командная: 'chrome.exe'},
    })).toEqual({отказ: НЕТ_ОПОЗНАНИЯ});
  });

  it('на порту тихо — останавливать нечего, даже если номер процесса откуда-то известен', () => {
    expect(решениеОстановки({
      порт: 4781, ответ: null, владелец: {номер: 4242, командная: командная(КОД_ИСПЫТАНИЯ)},
    })).toEqual({отказ: НЕТ_ОПОЗНАНИЯ});
  });

  it('сервер называет чужой номер порта — сверка не сходится, и ничего не завершается', () => {
    // Такой ответ означает пересказ соседа или подставленный номер: сам себя сервер называет иначе.
    expect(решениеОстановки({
      порт: 4781, ответ: наш(4782), владелец: {номер: 4242, командная: командная(КОД_ИСПЫТАНИЯ)},
    })).toEqual({отказ: ЧУЖОЙ_ОТВЕТ});
  });

  it('система не назвала владельца порта — без номера процесса остановки не бывает', () => {
    expect(решениеОстановки({порт: 4781, ответ: наш(4781), владелец: null})).toEqual({отказ: НЕТ_ВЛАДЕЛЬЦА});
    expect(решениеОстановки({порт: 4781, ответ: наш(4781), владелец: {номер: 0, командная: 'x'}}))
      .toEqual({отказ: НЕТ_ВЛАДЕЛЬЦА});
  });

  it('порт держит другой процесс ТОЙ ЖЕ папки кода — совпадение пути остановку не разрешает', () => {
    // Гонка между живым опознанием и завершением: ответил процесс 111, а порт к этому мигу держит
    // уже 222 — например, экземпляр перезапустили из той же рабочей копии. Путь до `server.mjs` у
    // обоих один, и пока он имел право голоса, панель завершала 222, то есть ЧУЖОЙ новый процесс
    // вместе с работой человека в нём. Названный сервером номер решает такие случаи один.
    const ответ = {опознание: {...опознание(4781), pid: 111}};
    const владелец = {номер: 222, командная: командная(КОД_ИСПЫТАНИЯ)};

    expect(решениеОстановки({порт: 4781, ответ, владелец})).toEqual({отказ: СМЕНИЛСЯ_ВЛАДЕЛЕЦ});
    // Тот же порт, тот же путь, тот же ответ — но номер сошёлся, и это уже не смена жильца.
    expect(решениеОстановки({порт: 4781, ответ, владелец: {...владелец, номер: 111}}))
      .toEqual({номер: 111});
  });

  it('связь порта с ответом доказывается и номером процесса: запуск командой npm пути не даёт', () => {
    // Запуск через `npm run` кладёт в командную строку относительное `server.mjs`, и папка кода им
    // не доказывается. Названный сервером номер от командной строки не зависит вовсе.
    const ответ = {опознание: {...опознание(4781), pid: 4242}};
    const владелец = {номер: 4242, командная: '"C:\\Program Files\\nodejs\\node.exe" server.mjs'};

    expect(решениеОстановки({порт: 4781, ответ, владелец})).toEqual({номер: 4242});
    expect(назвалНомер({pid: 4242})).toBe(true);
    expect(назвалНомер({pid: null})).toBe(false);
    expect(назвалНомер({pid: 0})).toBe(false);
    // Названный сервером чужой номер владельцем порта не является — остановки не будет.
    expect(решениеОстановки({порт: 4781, ответ: {опознание: {...опознание(4781), pid: 9999}}, владелец}))
      .toEqual({отказ: СМЕНИЛСЯ_ВЛАДЕЛЕЦ});
  });

  it('признаков нет обоих — путь относительный и номера в опознании нет, — решает сам обслуживший', () => {
    // Ровно то, на чём споткнулась проба владельца: принятый редактор поднят как `node .\server.mjs`
    // из своей же папки, поэтому папки кода в командной строке нет, а его код старше панели и своего
    // номера не называет. Живое принятое окно оказывалось неопознаваемым и не останавливалось.
    // Система при этом знает точно, какой процесс обслужил наш запрос, пока связь ещё открыта.
    const ответ = наш(4781);
    const относительная = '"C:\\Program Files\\nodejs\\node.exe" .\\server.mjs';

    expect(решениеОстановки({порт: 4781, ответ, владелец: {номер: 43220, командная: относительная}}))
      .toEqual({отказ: НЕ_ТОТ_ПРОЦЕСС});
    expect(решениеОстановки({
      порт: 4781, ответ, владелец: {номер: 43220, командная: относительная, ответил: 43220},
    })).toEqual({номер: 43220});
  });

  it('обслуживший запрос не совпал с владельцем порта — это та же смена жильца, и остановки нет', () => {
    // Прямое доказательство защиту от гонки не отменяет: обслужил один процесс, порт держит другой.
    expect(решениеОстановки({
      порт: 4781,
      ответ: наш(4781),
      владелец: {номер: 222, командная: командная(КОД_ИСПЫТАНИЯ), ответил: 111},
    })).toEqual({отказ: СМЕНИЛСЯ_ВЛАДЕЛЕЦ});

    // И слово сервера о себе сильнее: назвал номер — сверяется только он, обслуживший не спасает.
    expect(решениеОстановки({
      порт: 4781,
      ответ: {опознание: {...опознание(4781), pid: 111}},
      владелец: {номер: 222, командная: командная(КОД_ИСПЫТАНИЯ), ответил: 222},
    })).toEqual({отказ: СМЕНИЛСЯ_ВЛАДЕЛЕЦ});
  });

  it('чужая программа обслужила запрос — это по-прежнему не наш редактор, и её не трогают', () => {
    // Прямое доказательство отвечает только на вопрос «кто обслужил», а не «наш ли это редактор».
    // Ответ без опознания остаётся препятствием, каким бы точным ни был номер процесса.
    expect(решениеОстановки({
      порт: 4782, ответ: чужой, владелец: {номер: 777, командная: 'chrome.exe', ответил: 777},
    })).toEqual({отказ: НЕТ_ОПОЗНАНИЯ});
  });

  it('процесс на порту запущен не из той папки кода, что назвал сервер, — он не трогается', () => {
    // Опознание без номера бывает только у сервера, поднятого кодом старше панели: сверять нечем,
    // и единственным доказательством остаётся путь. Он же и отсекает соседнюю программу.
    expect(решениеОстановки({
      порт: 4781,
      ответ: наш(4781),
      владелец: {номер: 4242, командная: '"C:\\Program Files\\nodejs\\node.exe" "C:\\чужое\\server.mjs"'},
    })).toEqual({отказ: НЕ_ТОТ_ПРОЦЕСС});

    // И «просто node» без пути тоже не годится: он не доказывает ни папки, ни программы.
    expect(решениеОстановки({
      порт: 4781, ответ: наш(4781), владелец: {номер: 4242, командная: 'node server.mjs'},
    })).toEqual({отказ: НЕ_ТОТ_ПРОЦЕСС});
  });

  it('остановка сервера без номера в опознании держится на одном совпадении папки кода', () => {
    expect(решениеОстановки({
      порт: 4781, ответ: наш(4781), владелец: {номер: 4242, командная: командная(КОД_ИСПЫТАНИЯ)},
    })).toEqual({номер: 4242});
  });

  it('одна папка Windows зовётся по-разному: вид косых и регистр сверке не мешают', () => {
    const косыми = 'c:/my_code/bimcore-blog/editor/.coordination/worktrees/feature-x/editor';
    expect(принадлежитКоду(командная(КОД_ИСПЫТАНИЯ), косыми)).toBe(true);
    expect(принадлежитКоду('', КОД_ИСПЫТАНИЯ)).toBe(false);
    expect(принадлежитКоду(командная(КОД_ИСПЫТАНИЯ), '')).toBe(false);
  });

  it('ответ без обязательных полей опознанием не считается: старый сервер и чужая программа равны', () => {
    expect(опознаниеЛи(опознание(4781))).toBe(true);
    expect(опознаниеЛи({error: 'неизвестный запрос'})).toBe(false);
    expect(опознаниеЛи({...опознание(4781), port: '4781'})).toBe(false);
    expect(опознаниеЛи({...опознание(4781), code: ''})).toBe(false);
    expect(опознаниеЛи(null)).toBe(false);
    expect(опознаниеЛи('привет')).toBe(false);
  });
});

describe('панель не выдаёт устаревшую запись за работающий сервер', () => {
  const память = {
    4781: {вид: ВИД_МАТЕРИАЛЫ, ветка: 'feature/x', коммит: 'abc1234', чисто: true,
      код: КОД_ИСПЫТАНИЯ, материалы: 'D:\\проба'},
  };

  it('порт молчит — строка остановлена, её состав помечен не живым, и остановить её нельзя', () => {
    const [строка] = строки({порты: [4781], ответы: {}, память});

    expect(строка.состояние).toBe(ОСТАНОВЛЕН);
    expect(строка.живое).toBe(false);
    expect(строка.действия).toEqual({открыть: false, запустить: true, остановить: false});
  });

  it('на порту посторонняя программа — препятствие без единого действия, и память в него не лезет', () => {
    const [строка] = строки({порты: [4781], ответы: {4781: чужой}, память});

    expect(строка.состояние).toBe(ЧУЖОЙ);
    expect(строка.живое).toBe(false);
    expect(строка.код).toBe(null);
    expect(строка.ветка).toBe(null);
    expect(строка.действия).toEqual({открыть: false, запустить: false, остановить: false});
  });

  it('живой ответ — единственный источник фактов строки: запись памяти в неё не подмешивается', () => {
    const свежий = наш(4781, {код: 'C:\\другая\\копия\\editor'});
    const [строка] = строки({порты: [4781], ответы: {4781: свежий}, память});

    expect(строка.состояние).toBe(РАБОТАЕТ);
    expect(строка.живое).toBe(true);
    expect(строка.код).toBe('C:\\другая\\копия\\editor');
    expect(строка.действия).toEqual({открыть: true, запустить: false, остановить: true});
  });

  it('порт без ответа и без памяти не показывается вовсе: пустой строки о нём не бывает', () => {
    expect(строки({порты: [4782], ответы: {}, память})).toEqual([]);
  });

  it('строка рабочего окна остаётся в таблице и остановленной, а состав ей даёт код', () => {
    const [строка] = строки({
      порты: [ПОРТ_ВЛАДЕЛЬЦА], ответы: {}, память: сПамятьюОРабочем({}),
    });

    expect(строка.состояние).toBe(ОСТАНОВЛЕН);
    expect(строка.вид).toBe(ВИД_РАБОЧИЙ);
    expect(строка.действия.запустить).toBe(true);
    expect(строка.ветка).toBe(null);
  });

  it('запуск не идёт поверх работающего и поверх посторонней программы', () => {
    const запуск = {код: КОД_ИСПЫТАНИЯ, материалы: 'D:\\проба'};

    expect(решениеЗапуска({ответ: наш(4781), запуск})).toEqual({отказ: УЖЕ_РАБОТАЕТ});
    expect(решениеЗапуска({ответ: чужой, запуск})).toEqual({отказ: ПОРТ_ЗАНЯТ});
    expect(решениеЗапуска({ответ: null, запуск: null})).toEqual({отказ: НЕЧЕГО_ЗАПУСКАТЬ});
    expect(решениеЗапуска({ответ: null, запуск})).toEqual(запуск);
  });
});

describe('рабочее окно не спутать с испытательным', () => {
  it('рабочий — только принятый код на своём 4780; принятый код на другом порту рабочим не зовётся', () => {
    expect(вид(опознание(ПОРТ_ВЛАДЕЛЬЦА, {роль: РОЛЬ_ОБЫЧНАЯ, принят: true}))).toBe(ВИД_РАБОЧИЙ);
    expect(вид(опознание(4791, {роль: РОЛЬ_ОБЫЧНАЯ, принят: true}))).not.toBe(ВИД_РАБОЧИЙ);
    expect(вид(опознание(4791, {роль: РОЛЬ_ОБЫЧНАЯ, принят: false}))).not.toBe(ВИД_РАБОЧИЙ);
    expect(вид(опознание(4791))).toBe(ВИД_МАТЕРИАЛЫ);
  });

  it('панель наблюдает только порт рабочего окна, что бы ни лежало в настройках', () => {
    const сИспытаниями = {панель: {...настоящие['панель'], портыИспытаний: [4781, 4782]}};

    expect(порты()).toEqual([ПОРТ_ВЛАДЕЛЬЦА]);
    expect(порты(настоящие)).toEqual([ПОРТ_ВЛАДЕЛЬЦА]);
    expect(порты(сИспытаниями)).toEqual([ПОРТ_ВЛАДЕЛЬЦА]);
    expect(порты()).not.toContain(ПОРТ_ПАНЕЛИ);
  });

  it('у каждого отказа панели есть свои слова в настоящих настройках', () => {
    const коды = [
      НЕТ_ОПОЗНАНИЯ, ЧУЖОЙ_ОТВЕТ, НЕТ_ВЛАДЕЛЬЦА, НЕ_ТОТ_ПРОЦЕСС, НЕЧЕГО_ЗАПУСКАТЬ,
      УЖЕ_РАБОТАЕТ, ПОРТ_ЗАНЯТ, СМЕНИЛСЯ_ВЛАДЕЛЕЦ, 'всёЕщёОтвечает', 'неПоднялся', 'неНаблюдается',
    ];

    for (const код of коды) expect(настоящие['панель']['отказы'][код]).toBeTruthy();
    for (const состояние of [РАБОТАЕТ, ОСТАНОВЛЕН, ЧУЖОЙ]) {
      expect(настоящие['панель']['состояния'][состояние]).toBeTruthy();
    }
    for (const имя of [ВИД_РАБОЧИЙ, ВИД_МАТЕРИАЛЫ, 'испытательныйКод']) {
      expect(настоящие['панель']['виды'][имя]).toBeTruthy();
    }
  });
});
