// Имя каждого теста повторяет формулировку правила.
//
// Ради чего набор заведён: отпечаток доказывает, что судят ОДИН И ТОТ ЖЕ вход, но ничего не говорит
// о том, каким вышел вердикт. Прежде вердикт выносило окно: сервер видел только отпечаток и записывал
// статью, у которой подготовка красная. Тело запроса пишет не окно, и «окно бы такого не прислало»
// защитой не является.
import {afterEach, beforeEach, describe, expect, it} from 'vitest';
import fs from 'node:fs';
import path from 'node:path';

import {проверить} from '../src/ui/publishRun';
import {запомнитьКоммит, запомнитьПоказ} from '../src/adapters/pushMemory.mjs';
import {срезОднойВерсии} from '../src/adapters/prepareStamp.mjs';
import {ЖДАТЬ_GIT} from './saveHarness.mjs';
import {EN, ES, НАСТРОЙКИ, RU, СТАТЬЯ, дверь, наСервере, среда, убратьПесочницы, ход} from './runHarness.mjs';

beforeEach(() => {
  запомнитьКоммит(null);
  запомнитьПоказ(null);
});

afterEach(() => {
  запомнитьКоммит(null);
  запомнитьПоказ(null);
  убратьПесочницы();
});

describe('зелёная подготовка доказывается сервером, а не окном', () => {
  const БЕЗ_ОПИСАНИЯ = '---\ntitle: "Проба"\nslug: /lessons/proba\n---\n\nТекст статьи.\n';

  it('верный отпечаток КРАСНОГО отчёта не проходит ни одной ручки хода', async () => {
    const с = await среда({файлы: {[RU]: БЕЗ_ОПИСАНИЯ, [EN]: СТАТЬЯ, [ES]: СТАТЬЯ}});
    const х = ход(дверь(с, []), []);
    const былоНаСервере = await наСервере(с.сервер);
    // Отпечаток НАСТОЯЩИЙ: он описывает ровно ту статью, что лежит на диске. Совпадёт он или нет —
    // вопрос отдельный от того, можно ли эту статью выпускать.
    const снимок = срезОднойВерсии(с.repo, RU, НАСТРОЙКИ).отпечаток;
    const ручки = [
      ['/api/release', {path: RU, отпечатокПодготовки: снимок}],
      ['/api/publish/commit', {path: RU, подтверждено: true, отпечатокПодготовки: снимок}],
    ];

    for (const [адрес, тело] of ручки) {
      const беда = await х.запрос(адрес, тело).catch((ошибка) => ошибка);
      expect(`${адрес}: ${беда.ответ?.код}`).toBe(`${адрес}: подготовкаНеПрошла`);
      expect(беда.ответ.находки.map((находка) => находка.код)).toContain('описаниеПусто');
    }

    expect(await наСервере(с.сервер)).toBe(былоНаСервере);
  }, ЖДАТЬ_GIT);

  it('ход публикации со статьёй-препятствием до записи не доходит', async () => {
    // Обвязка отвечает на подготовку готовым успехом — ровно так же выглядит окно, решившее, что
    // препятствий нет, или запрос, посланный мимо окна. Останавливает ход сам сервер.
    const с = await среда({файлы: {[RU]: БЕЗ_ОПИСАНИЯ, [EN]: СТАТЬЯ, [ES]: СТАТЬЯ}});
    const записка = [];
    const х = ход(дверь(с, записка), []);
    const былоНаСервере = await наСервере(с.сервер);

    const беда = await проверить(RU, false, х).catch((ошибка) => ошибка);

    expect(беда.ответ?.код).toBe('подготовкаНеПрошла');
    // До записи дело не дошло: статью выпускать нельзя.
    expect(записка.some((шаг) => шаг.адрес === '/api/publish/commit')).toBe(false);
    expect(await наСервере(с.сервер)).toBe(былоНаСервере);
  }, ЖДАТЬ_GIT);

  it('исправная статья тем же путём проходит: заслон стоит на препятствии, а не на всех', async () => {
    const с = await среда();
    fs.writeFileSync(path.join(с.repo, RU), `${СТАТЬЯ}Новая строка.\n`, 'utf8');
    const х = ход(дверь(с, []), []);

    const вопрос = await проверить(RU, false, х);

    expect(вопрос.вид).toBe('проверено');
  }, ЖДАТЬ_GIT);
});
