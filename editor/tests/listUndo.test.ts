// Имя каждого теста повторяет формулировку правила.
// Структурное действие над списком — одна запись истории: набор -> действие -> набор -> Undo/Redo
// проходят точные состояния, уплотнение и слияние соседей отменяются вместе с действием, а не
// цепочкой отмен. Слияние, частичное выделение и зазоры проверяются снаружи и внутри note и tip.
import {describe, expect, it} from 'vitest';
import type {EditorState} from '@codemirror/state';
import {кнопкаНа, набрать, нажать, состояние} from './listHarness';

/** Цепочка состояний и проверка, что Undo и Redo проходят её точно, шаг за шагом. */
function история(шаги: EditorState[]): void {
  let state = шаги[шаги.length - 1];
  for (let i = шаги.length - 2; i >= 0; i -= 1) {
    const итог = нажать('Mod-z', state);
    expect(итог.текст).toBe(шаги[i].doc.toString());
    state = итог.state;
  }
  for (let i = 1; i < шаги.length; i += 1) {
    const итог = нажать('Mod-y', state);
    expect(итог.текст).toBe(шаги[i].doc.toString());
    state = итог.state;
  }
}

const обёртки: [string, (тело: string) => string][] = [
  ['снаружи', (тело) => тело],
  ['в note', (тело) => `:::note[Примечание]\n${тело}\n:::`],
  ['в tip', (тело) => `:::tip\n${тело}\n:::`],
];

describe('Enter в списке отменяется одной отменой вместе с уплотнением', () => {
  it.each(обёртки)('набор, Enter в разреженном списке, набор: Undo и Redo проходят точные состояния %s', (_, обернуть) => {
    const исходный = обернуть('- Раз\n\n- Два');
    const s0 = состояние(исходный, исходный.indexOf('Два') + 3);
    const s1 = набрать(s0, 'x');
    const s2 = нажать('Enter', s1).state;
    expect(s2.doc.toString()).toBe(обернуть('- Раз\n- Дваx\n- '));
    const s3 = набрать(s2, 'y');
    expect(s3.doc.toString()).toBe(обернуть('- Раз\n- Дваx\n- y'));
    история([s0, s1, s2, s3]);
  });

  it.each(обёртки)('Backspace через зазор — одна запись истории %s', (_, обернуть) => {
    const исходный = обернуть('- Раз\n\n- Два');
    const s0 = состояние(исходный, исходный.indexOf('- Два'));
    const s1 = нажать('Backspace', s0).state;
    expect(s1.doc.toString()).toBe(обернуть('- Раз\n- Два'));
    const s2 = набрать(s1, 'z');
    история([s0, s1, s2]);
  });
});

describe('кнопка списка отменяется одной отменой вместе со слиянием соседей', () => {
  it.each(обёртки)('абзацы рядом со списком: слияние с соседом, набор, Undo и Redo точные %s', (_, обернуть) => {
    const исходный = обернуть('Раз\n\nДва\n\n- Сосед');
    const s0 = состояние(исходный, исходный.indexOf('Два') + 3);
    const s1 = набрать(s0, '!');
    const s2 = кнопкаНа(s1, исходный.indexOf('Раз'), исходный.indexOf('Два') + 4, 'точки');
    expect(s2.doc.toString()).toBe(обернуть('- Раз\n- Два!\n- Сосед'));
    const s3 = набрать(s2, '?');
    история([s0, s1, s2, s3]);
  });

  it.each(обёртки)('частичное выделение разреженного списка меняет вид только задетых пунктов и отменяется одной отменой %s', (_, обернуть) => {
    const исходный = обернуть('- Раз\n\n- Два\n\n- Три');
    const s0 = состояние(исходный, 0);
    const s1 = кнопкаНа(s0, исходный.indexOf('Раз'), исходный.indexOf('Два') + 3, 'числа');
    expect(s1.doc.toString()).toBe(обернуть('1. Раз\n2. Два\n\n- Три'));
    const s2 = набрать(s1, '.');
    история([s0, s1, s2]);
  });

  it.each(обёртки)('снятие списка отменяется одной отменой %s', (_, обернуть) => {
    const исходный = обернуть('- Раз\n- Два');
    const s0 = состояние(исходный, 0);
    const s1 = кнопкаНа(s0, исходный.indexOf('Раз'), исходный.indexOf('Два') + 3, 'точки');
    expect(s1.doc.toString()).toBe(обернуть('Раз\n\nДва'));
    история([s0, s1]);
  });
});
