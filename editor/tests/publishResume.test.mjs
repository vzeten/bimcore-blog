// Имя каждого теста повторяет формулировку правила.
//
// Что окно делает с незаконченной публикацией: доводит начатое до конца, а неоконченное называет
// вслух. Проверяется тем же способом, что и обычный ход, — настоящими ручками и настоящим git:
// именно здесь обрыв питания оставлял человека с записанной, но не уехавшей статьёй, и выбраться
// из этого он не мог.
import {afterEach, beforeEach, describe, expect, it} from 'vitest';
import fs from 'node:fs';
import path from 'node:path';

import {зафиксироватьИОтправить, проверитьИСобрать} from '../src/ui/publishRun';
import {запомнитьКоммит, запомнитьПоказ} from '../src/adapters/pushMemory.mjs';
import {запомнитьСборку} from '../src/adapters/buildMemory.mjs';
import {ЖДАТЬ_GIT} from './saveHarness.mjs';
import {EN, ES, RU, СТАТЬЯ, дверь, наСервере, среда, убратьПесочницы, ход} from './runHarness.mjs';

beforeEach(() => {
  запомнитьСборку(null);
  запомнитьКоммит(null);
  запомнитьПоказ(null);
});

afterEach(() => {
  запомнитьСборку(null);
  запомнитьКоммит(null);
  запомнитьПоказ(null);
  убратьПесочницы();
});

/** Сколько раз ход просил сервер записать статью. Второй записи быть не должно ни при каких бедах. */
const записей = (записка) => записка.filter((шаг) => шаг.адрес === '/api/publish/commit').length;

/**
 * Довести человека до записанной, но НЕ отправленной статьи — ровно то, что оставляет выключение
 * компьютера между записью и отправкой. Запись делается тем же запросом, каким её делает окно.
 */
async function записаноНоНеУехало(с, х) {
  fs.writeFileSync(path.join(с.repo, RU), `${СТАТЬЯ}\nНовая строка.\n`, 'utf8');
  await проверитьИСобрать(RU, false, х);

  return х.запрос('/api/publish/commit', {path: RU, подтверждено: true});
}

describe('прошлая запись не уехала на сайт', () => {
  it('повторное «Опубликовать» досылает её и второй записи не делает', async () => {
    const с = await среда();
    const записка = [];
    const х = ход(дверь(с, записка), []);
    const запись = await записаноНоНеУехало(с, х);
    const былоЗаписей = записей(записка);

    const исход = await проверитьИСобрать(RU, false, х);

    expect(исход.вид).toBe('готово');
    // Статья на сайте, и это тот самый коммит, а не новый.
    expect(await наСервере(с.сервер)).toBe(запись.sha);
    expect(записей(записка)).toBe(былоЗаписей);
    // Ветка человека не двигалась: коммит публикации живёт отдельно и уехал только на сайт.
    expect((await с.git.raw(['rev-list', '--count', 'HEAD'])).trim()).toBe('1');
  }, ЖДАТЬ_GIT);

  it('после досылки новые правки публикуются обычным ходом, а не молчат', async () => {
    const с = await среда();
    const записка = [];
    const х = ход(дверь(с, записка), []);
    await записаноНоНеУехало(с, х);
    // Человек успел написать ещё строку уже после той записи.
    fs.writeFileSync(path.join(с.repo, RU), `${СТАТЬЯ}\nНовая строка.\nИ ещё одна.\n`, 'utf8');
    const былоЗаписей = записей(записка);

    const исход = await проверитьИСобрать(RU, false, х);

    // Прошлое уехало, а про новое человека спрашивают как обычно — и записи для него ещё не было.
    expect(исход.вид).toBe('спрашиваю');
    expect(исход.итог.версии.find((версия) => версия.локаль === 'ru').состояние).toBe('изменилась');
    expect(записей(записка)).toBe(былоЗаписей);
  }, ЖДАТЬ_GIT);

  it('панель закрыли, пока сервер отвечал, — досылки не будет: крестик обещал отмену', async () => {
    const с = await среда();
    const записка = [];
    const базовая = дверь(с, записка);
    await записаноНоНеУехало(с, ход(базовая, []));
    записка.length = 0;
    const былоНаСервере = await наСервере(с.сервер);

    // Человек закрывает панель ровно в тот миг, когда приходит ответ про неотправленную запись.
    let живо = true;
    const сОтменой = async (адрес, тело) => {
      try {
        return await базовая(адрес, тело);
      } finally {
        if (адрес === '/api/release') живо = false;
      }
    };

    const исход = await проверитьИСобрать(RU, false, {...ход(сОтменой, []), жива: () => живо});

    expect(исход.вид).toBe('прервано');
    expect(записка.map((шаг) => шаг.адрес)).not.toContain('/api/publish/plan');
    expect(записка.map((шаг) => шаг.адрес)).not.toContain('/api/publish/push');
    expect(записей(записка)).toBe(0);
    expect(await наСервере(с.сервер)).toBe(былоНаСервере);
  }, ЖДАТЬ_GIT);

  it('досылка идёт до сборки: собирать сайт заново ради уже проверенной записи незачем', async () => {
    const с = await среда();
    const записка = [];
    const х = ход(дверь(с, записка), []);
    await записаноНоНеУехало(с, х);
    записка.length = 0;

    await проверитьИСобрать(RU, false, х);

    expect(записка.map((шаг) => шаг.адрес)).toEqual([
      // Дата записи спрашивается в начале каждого хода: у документации она всегда пуста.
      '/api/publish/date',
      '/api/prepare',
      '/api/release',
      '/api/publish/plan',
      '/api/publish/push',
      // Дальше обычный ход: он и убедится, что публиковать больше нечего.
      '/api/publish/date',
      '/api/prepare',
      '/api/release',
    ]);
  }, ЖДАТЬ_GIT);
});

describe('диск человека сайту не принадлежит', () => {
  it('папка на месте соседнего языка публикации не мешает: заглушка уезжает, диск не трогается', async () => {
    // Испанского на сайте нет — программа создаст заглушку в коммите. А на диске его путь занят
    // папкой: прежде программа дописывала заглушку на диск и здесь останавливалась. Теперь диск
    // принадлежит ветке человека, и сайт про него ничего не решает.
    const с = await среда({файлы: {[RU]: СТАТЬЯ, [EN]: СТАТЬЯ}});
    fs.mkdirSync(path.join(с.repo, ES), {recursive: true});
    fs.writeFileSync(path.join(с.repo, RU), `${СТАТЬЯ}\nНовая строка.\n`, 'utf8');
    const записка = [];
    const х = ход(дверь(с, записка), []);

    const вопрос = await проверитьИСобрать(RU, false, х);
    expect(вопрос.вид).toBe('спрашиваю');
    const исход = await зафиксироватьИОтправить(RU, х, вопрос.отпечаток, вопрос.отпечатокПодготовки);

    expect(исход.вид).toBe('готово');
    expect(fs.statSync(path.join(с.repo, ES)).isDirectory()).toBe(true);
    const наСайте = await наСервере(с.сервер);
    expect(await с.git.raw(['ls-tree', '--name-only', наСайте, '--', ES])).toContain(ES);
  }, ЖДАТЬ_GIT);
});

describe('состав не доказан', () => {
  it('человеку называется причина, а не просто запрет', async () => {
    const вторая = 'i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba/вторая.mdx';
    const с = await среда({файлы: {[RU]: СТАТЬЯ, [EN]: СТАТЬЯ, [ES]: СТАТЬЯ, [вторая]: СТАТЬЯ}});
    fs.writeFileSync(path.join(с.repo, RU), `${СТАТЬЯ}\nНовая строка.\n`, 'utf8');
    const записка = [];

    const исход = await проверитьИСобрать(RU, false, ход(дверь(с, записка), []));

    expect(исход.вид).toBe('остановка');
    expect(исход.ключ).toBe('составНеДоказан');
    expect(исход.разрывы.map((разрыв) => разрыв.причина)).toEqual(['папкаНеОдна']);
    expect(записка.map((шаг) => шаг.адрес)).not.toContain('/api/release/build');
  }, ЖДАТЬ_GIT);

  it('одну и ту же причину видят два правила — человек читает её один раз', async () => {
    // Вторая статья лежит и на диске, и на сайте: её называют своим разрывом и состав, и уборка.
    const вторая = 'i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba/вторая.mdx';
    const с = await среда({файлы: {[RU]: СТАТЬЯ, [EN]: СТАТЬЯ, [ES]: СТАТЬЯ, [вторая]: СТАТЬЯ}});
    fs.writeFileSync(path.join(с.repo, RU), `${СТАТЬЯ}\nНовая строка.\n`, 'utf8');

    const исход = await проверитьИСобрать(RU, false, ход(дверь(с, []), []));

    expect(исход.разрывы).toHaveLength(1);
  }, ЖДАТЬ_GIT);
});
