// Имя каждого теста повторяет формулировку правила.
// Правила значений полей шапки: длина описания и «порядок в меню — число».
import {describe, expect, it} from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

import {БЛОКЕР, ПРЕДУПРЕЖДЕНИЕ, проверитьМестные} from '../src/core/prepare.mjs';

const EDITOR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const НАСТРОЙКИ = JSON.parse(fs.readFileSync(path.join(EDITOR, 'settings.json'), 'utf8'));
const ПРЕДЕЛ = НАСТРОЙКИ['пределОписания'];

const RU = 'i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba/index.mdx';
const EN = 'docs/lessons/proba/index.mdx';
const RU_БЛОГ = 'i18n/ru/docusaurus-plugin-content-blog/proba/index.mdx';
const EN_БЛОГ = 'blog/proba/index.mdx';

const снимок = (шапки) => Object.entries(шапки)
  .map(([путь, шапка]) => ({путь, содержимое: `---\n${шапка}\n---\n\nТекст статьи.\n`}));

const проверить = (шапки, категория = 'урок') => проверитьМестные(снимок(шапки), категория, НАСТРОЙКИ);
const поКоду = (шапки, код, категория = 'урок') => проверить(шапки, категория)
  .filter((находка) => находка.код === код);

/** Статья документации с описанием заданной длины и, если нужно, с порядком в меню. */
const статья = (описание, порядок = null) => ({
  [RU]: [
    'title: "Проба"',
    'slug: /lessons/proba',
    `description: "${описание}"`,
    'keywords: [розетки]',
    порядок === null ? null : `sidebar_position: ${порядок}`,
  ].filter((строка) => строка !== null).join('\n'),
  [EN]: 'title: "Заглушка"\nslug: /lessons/proba\ndescription: "Placeholder"\nunlisted: true',
});

describe('подготовка статьи: длина описания', () => {
  it('описание длиной ровно в предел находки не даёт', () => {
    expect(поКоду(статья('я'.repeat(ПРЕДЕЛ)), 'описаниеДлинное')).toHaveLength(0);
  });

  it('описание длиннее предела предупреждает, а выпуск не останавливает', () => {
    const находки = поКоду(статья('я'.repeat(ПРЕДЕЛ + 1)), 'описаниеДлинное');

    expect(находки).toHaveLength(1);
    expect(находки[0]).toMatchObject({
      уровень: ПРЕДУПРЕЖДЕНИЕ, путь: RU, поле: 'description', длина: ПРЕДЕЛ + 1, предел: ПРЕДЕЛ,
    });
  });

  it('кавычки в длину описания не входят: считается само описание, а не запись в файле', () => {
    // В файле эта строка занимает предел + 2 знака вместе с кавычками; описание — ровно предел.
    expect(поКоду(статья('я'.repeat(ПРЕДЕЛ)), 'описаниеДлинное')).toHaveLength(0);
    expect(поКоду(статья('я'.repeat(ПРЕДЕЛ - 1)), 'описаниеДлинное')).toHaveLength(0);
  });

  for (const [имя, запись] of [['списком', '\n  - раз\n  - два'], ['да-нет', ' true']]) {
    it(`описание, записанное ${имя}, останавливает выпуск: сайт ждёт в нём строку`, () => {
      const чужойВид = {
        [RU]: `title: "Проба"\nslug: /lessons/proba\ndescription:${запись}\nkeywords: [розетки]`,
        [EN]: 'title: "Заглушка"\nslug: /lessons/proba\ndescription: "Placeholder"\nunlisted: true',
      };
      const находки = поКоду(чужойВид, 'описаниеНеСтрока');

      expect(находки).toHaveLength(1);
      expect(находки[0]).toMatchObject({уровень: БЛОКЕР, путь: RU, поле: 'description'});
      // Длину такого значения мерить нечего: на сайт оно не уедет вовсе.
      expect(поКоду(чужойВид, 'описаниеДлинное')).toHaveLength(0);
    });
  }

  it('комментарий в конце строки в длину описания не входит: на сайт он не уезжает', () => {
    const сПометкой = {
      [RU]: [
        'title: "Проба"',
        'slug: /lessons/proba',
        `description: "${'я'.repeat(ПРЕДЕЛ - 10)}" # поправить перед выпуском`,
        'keywords: [розетки]',
      ].join('\n'),
      [EN]: 'title: "Заглушка"\nslug: /lessons/proba\ndescription: "Placeholder"\nunlisted: true',
    };

    expect(поКоду(сПометкой, 'описаниеДлинное')).toHaveLength(0);
  });

  it('пустое описание про длину молчит: о нём уже сказано своим блокером', () => {
    const пустое = {
      [RU]: 'title: "Проба"\nslug: /lessons/proba\ndescription: ""\nkeywords: [розетки]',
      [EN]: 'title: "Заглушка"\nslug: /lessons/proba\ndescription: "Placeholder"\nunlisted: true',
    };

    expect(поКоду(пустое, 'описаниеДлинное')).toHaveLength(0);
    expect(поКоду(пустое, 'описаниеПусто')[0]).toMatchObject({уровень: БЛОКЕР, путь: RU});
  });
});

describe('подготовка статьи: сломанный предел длины описания', () => {
  const сНастройкой = (предел) => {
    const настройки = {...НАСТРОЙКИ};
    if (предел === undefined) delete настройки['пределОписания'];
    else настройки['пределОписания'] = предел;

    return проверитьМестные(снимок(статья('Короткое описание')), 'урок', настройки);
  };

  for (const [имя, предел] of [['ключа нет вовсе', undefined], ['слово вместо числа', 'сто'], ['ноль', 0]]) {
    it(`предел длины описания сломан (${имя}) — подготовка останавливается на настройке, а не проверяет статью`, () => {
      const находки = сНастройкой(предел);

      expect(находки.every((находка) => находка.этап === 'настройки')).toBe(true);
      expect(находки.some((находка) => находка.код === 'пределОписанияНеЧисло')).toBe(true);
      expect(находки.every((находка) => находка.уровень === БЛОКЕР)).toBe(true);
      // Главное: ни одного предупреждения о длине. Сравнение с пустотой всегда ложно, и без этой
      // проверки жалобу получило бы каждое непустое описание на сайте.
      expect(находки.some((находка) => находка.код === 'описаниеДлинное')).toBe(false);
    });
  }
});

describe('подготовка статьи: адрес версии читается так, как его прочитает сайт', () => {
  const адреса = (ru, en) => проверитьМестные(снимок({
    [RU]: `title: "Проба"\n${ru}\ndescription: "Есть"\nkeywords: [розетки]`,
    [EN]: `title: "Заглушка"\n${en}\ndescription: "Placeholder"\nunlisted: true`,
  }), 'урок', НАСТРОЙКИ).map((находка) => находка.код);

  it('комментарий в конце строки адреса версии не разводит: сайт его отбрасывает', () => {
    // Найдено воротами блока Б2: адрес брался сырой строкой файла, поэтому одинаковые адреса
    // с пометкой человека в конце строки объявлялись разными, и человеку показывали адрес вместе
    // с комментарием — то есть не тот, что лежит на сайте.
    const коды = адреса('slug: /lessons/proba # оставлен с прошлого раза', 'slug: /lessons/proba');

    expect(коды).not.toContain('адресаВерсийРазные');
  });

  it('версия с пустым адресом образцом сравнения не становится: здоровому файлу выдуманный адрес не показывают', () => {
    // Найдено воротами блока Б2: у основной версии ключ адреса стоит без значения — это её беда
    // и своя находка. Прежде эта же версия бралась образцом, и соседняя, где адрес записан верно,
    // получала блокер «адреса разные» с адресом, которого нет ни в одном файле.
    const коды = адреса('slug:', 'slug: /lessons/drugoy');

    expect(коды).toContain('адресПуст');
    expect(коды).not.toContain('адресаВерсийРазные');
  });

  it('адрес, записанный списком, называется своей бедой и образцом сравнения не становится', () => {
    // Тот же дефект, что и у пустого адреса, но на значении другой формы: склеенный список
    // выглядел непустой строкой, проходил в образцы и обвинял здоровую соседнюю версию.
    const коды = адреса('slug:\n  - /a\n  - /b', 'slug: /lessons/proba');

    expect(коды).toContain('адресНеСтрока');
    expect(коды).not.toContain('адресаВерсийРазные');
  });
});

describe('подготовка статьи: порядок в меню — число', () => {
  // Годное и негодное сверено с настоящей схемой Docusaurus. Экзотические записи чисел (`0x10`,
  // `0o17`, `2_0`, `017`, `1:30`) сюда не входят намеренно: программа и сайт разбирают шапку
  // разными версиями YAML и на таких записях расходятся. Щель названа хвостом в `PLAN.md`.
  const годные = ['2', '"2"', '0002', '2.5', '-1', '+2', '2 # первый в разделе'];
  for (const значение of годные) {
    it(`порядок в меню, записанный как ${значение}, находки не даёт: сайт читает его числом`, () => {
      expect(поКоду(статья('Понятное описание', значение), 'порядокВМенюНеЧисло')).toHaveLength(0);
    });
  }

  const негодные = ['два', '2a', 'true', '', '[2, 3]'];
  for (const значение of негодные) {
    it(`порядок в меню, записанный как «${значение}», останавливает выпуск: от него падает сборка`, () => {
      const находки = поКоду(статья('Понятное описание', значение), 'порядокВМенюНеЧисло');

      expect(находки).toHaveLength(1);
      expect(находки[0]).toMatchObject({уровень: БЛОКЕР, путь: RU, поле: 'sidebar_position'});
    });
  }

  it('порядок в меню, записанный списком строками, останавливает выпуск', () => {
    const блочный = {
      ...статья('Понятное описание'),
      [RU]: 'title: "Проба"\nslug: /lessons/proba\ndescription: "Есть"\nsidebar_position:\n  - 2',
    };
    const находки = поКоду(блочный, 'порядокВМенюНеЧисло');

    expect(находки).toHaveLength(1);
    expect(находки[0]).toMatchObject({уровень: БЛОКЕР, путь: RU});
  });

  it('порядка в меню в шапке нет вовсе — находки нет: расстановкой занимается сайт', () => {
    expect(поКоду(статья('Понятное описание'), 'порядокВМенюНеЧисло')).toHaveLength(0);
  });

  it('порядок в меню с комментарием в конце строки находки не даёт: комментарий сайт отбрасывает', () => {
    const сКомментарием = поКоду(
      статья('Понятное описание', '2 # первый в разделе'), 'порядокВМенюНеЧисло',
    );

    expect(сКомментарием).toHaveLength(0);
  });

  it('у статьи блога порядок в меню не спрашивается: этого поля нет в её принятых полях', () => {
    const блог = {
      [RU_БЛОГ]: 'title: "Проба"\nslug: proba\ndescription: "Есть"\nsidebar_position: два',
      [EN_БЛОГ]: 'title: "Заглушка"\nslug: proba\ndescription: "Placeholder"\nunlisted: true',
    };

    expect(поКоду(блог, 'порядокВМенюНеЧисло', 'блог')).toHaveLength(0);
  });
});
