// Имя каждого теста повторяет формулировку правила.
// Цепочка слоёв окна и цвет, который из неё выходит: кто трогал текст последним.
import {describe, expect, it} from 'vitest';
import {colorize, type Layer} from '../src/core/colorize';
import {слоиОкна} from '../src/ui/layerColors';

const САЙТ = 'Первый абзац.\n';
const ИИ = 'Первый абзац.\nАбзац от ИИ.\n';
const РУКОЙ = 'Первый абзац.\nАбзац от ИИ, поправленный рукой.\n';

/** Каким слоем помечен кусок текста в готовой цепочке. */
function цвет(слои: Layer[], кусок: string): string | undefined {
  const текст = слои.at(-1)?.text ?? '';
  const {segments} = colorize(слои);
  const at = текст.indexOf(кусок);
  return segments.find((s) => s.from <= at && at < s.to)?.kind;
}

describe('цепочка слоёв окна', () => {
  it('файл идёт последним перед текущим текстом, а история — между сайтом и файлом', () => {
    // Порядок — это время: раскраска красит по последнему, кто трогал кусок.
    const цепочка = слоиОкна({
      published: САЙТ,
      body: РУКОЙ,
      слои: [{text: ИИ, kind: 'prevAi'}],
    });

    expect(цепочка.map((слой) => слой.kind)).toEqual(['site', 'prevAi', 'prevHuman']);
  });

  it('истории нет — цепочка прежняя: сайт и файл', () => {
    expect(слоиОкна({published: САЙТ, body: РУКОЙ}).map((с) => с.kind)).toEqual(['site', 'prevHuman']);
  });

  it('статьи ещё нет на сайте — цепочка начинается с самого старого состояния истории', () => {
    // Иначе статья, целиком написанная ИИ и не вышедшая, показалась бы полностью своей.
    const цепочка = слоиОкна({published: null, body: ИИ, слои: [{text: ИИ, kind: 'prevAi'}]});

    expect(цепочка.map((с) => с.kind)).toEqual(['prevAi', 'prevHuman']);
  });

  it('ни сайта, ни истории — остаётся один слой файла', () => {
    expect(слоиОкна({published: null, body: РУКОЙ}).map((с) => с.kind)).toEqual(['prevHuman']);
  });

  it('в окне продолжен черновик — цепочка кончается телом файла, а не показанным текстом', () => {
    // Иначе незаписанная работа окрасилась бы как уже сохранённая правка, хотя в файле её нет.
    const черновик = `${РУКОЙ}Незаписанная строка.\n`;
    const цепочка = слоиОкна({published: САЙТ, body: черновик, телоФайла: РУКОЙ});

    expect(цепочка.at(-1)?.text).toBe(РУКОЙ);
  });

  it('незаписанная работа из черновика окрашена текущим слоем, а не моей прошлой правкой', () => {
    const черновик = `${РУКОЙ}Незаписанная строка.\n`;
    const слои = [...слоиОкна({published: САЙТ, body: черновик, телоФайла: РУКОЙ}),
      {text: черновик, kind: 'current'} as Layer];

    expect(цвет(слои, 'Незаписанная строка')).toBe('current');
  });
});

describe('цвет по автору', () => {
  it('текст, добавленный ИИ и не вышедший на сайт, окрашен слоем правок ИИ', () => {
    const слои = [...слоиОкна({published: САЙТ, body: ИИ, слои: [{text: ИИ, kind: 'prevAi'}]}),
      {text: ИИ, kind: 'current'} as Layer];

    expect(цвет(слои, 'Абзац от ИИ')).toBe('prevAi');
    expect(цвет(слои, 'Первый абзац')).toBe('site');
  });

  it('правка человека поверх текста ИИ окрашена как его собственная', () => {
    // Цвет показывает того, кто трогал последним, иначе своя работа спрячется под машинной.
    const слои = [...слоиОкна({published: САЙТ, body: РУКОЙ, слои: [{text: ИИ, kind: 'prevAi'}]}),
      {text: РУКОЙ, kind: 'current'} as Layer];

    expect(цвет(слои, 'поправленный рукой')).toBe('prevHuman');
    expect(цвет(слои, 'Абзац от ИИ')).toBe('prevAi');
  });

  it('правка постороннего автора отличается и от своих, и от машинных', () => {
    const снаружи = 'Первый абзац.\nАбзац снаружи.\n';
    const слои = [...слоиОкна({published: САЙТ, body: снаружи, слои: [{text: снаружи, kind: 'prevOther'}]}),
      {text: снаружи, kind: 'current'} as Layer];

    expect(цвет(слои, 'Абзац снаружи')).toBe('prevOther');
  });

  it('набранное прямо сейчас окрашено текущим слоем, а не авторским', () => {
    const сейчас = `${РУКОЙ}Только что набрано.\n`;
    const слои = [...слоиОкна({published: САЙТ, body: РУКОЙ, слои: [{text: ИИ, kind: 'prevAi'}]}),
      {text: сейчас, kind: 'current'} as Layer];

    expect(цвет(слои, 'Только что набрано')).toBe('current');
  });
});
