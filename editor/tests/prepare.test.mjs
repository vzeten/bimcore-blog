// Имя каждого теста повторяет формулировку правила.
// Правила подготовки статьи к выпуску: что считается бедой, что предупреждением и в каком порядке.
import {describe, expect, it} from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

import {БЛОКЕР, ПРЕДУПРЕЖДЕНИЕ, подготовкаПрошла, проверитьМестные} from '../src/core/prepare.mjs';

const EDITOR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const НАСТРОЙКИ = JSON.parse(fs.readFileSync(path.join(EDITOR, 'settings.json'), 'utf8'));

const RU = 'i18n/ru/docusaurus-plugin-content-docs/current/lessons/proba/index.mdx';
const EN = 'docs/lessons/proba/index.mdx';

/** Статья из шапок: тело правилам этого блока не нужно, но снимок несёт файл целиком. */
const снимок = (шапки) => Object.entries(шапки)
  .map(([путь, шапка]) => ({путь, содержимое: `---\n${шапка}\n---\n\nТекст статьи.\n`}));

const ЦЕЛАЯ = {
  [RU]: 'title: "Проба"\nslug: /lessons/proba\ndescription: "Понятное описание"\nkeywords: [розетки]',
  [EN]: 'title: "Translation placeholder: Проба"\nslug: /lessons/proba\ndescription: "Placeholder page. The English translation of this article is not ready yet."\nunlisted: true',
};

const проверить = (шапки, категория = 'урок') => проверитьМестные(снимок(шапки), категория, НАСТРОЙКИ);
const коды = (находки) => находки.map((находка) => находка.код);

describe('подготовка статьи: свои правила', () => {
  it('чистая статья с английской заглушкой проходит: заглушка выпуск не блокирует', () => {
    const находки = проверить(ЦЕЛАЯ);

    expect(подготовкаПрошла(находки)).toBe(true);
    // Про заглушку сказано: у неё нет ключевых слов и описание шаблонное. Но это предупреждения.
    expect(находки.every((находка) => находка.уровень === ПРЕДУПРЕЖДЕНИЕ)).toBe(true);
  });

  it('пустое описание останавливает выпуск у любой версии, в том числе у скрытой', () => {
    const скрытая = {
      ...ЦЕЛАЯ,
      [EN]: 'title: "Заглушка"\nslug: /lessons/proba\nunlisted: true',
    };
    const находки = проверить(скрытая).filter((находка) => находка.код === 'описаниеПусто');

    expect(находки).toHaveLength(1);
    expect(находки[0]).toMatchObject({уровень: БЛОКЕР, путь: EN, поле: 'description'});
  });

  it('описание, совпавшее с шаблоном заглушки, предупреждает, а не останавливает', () => {
    const находки = проверить(ЦЕЛАЯ).filter((находка) => находка.код === 'описаниеШаблонное');

    expect(находки).toHaveLength(1);
    expect(находки[0]).toMatchObject({уровень: ПРЕДУПРЕЖДЕНИЕ, путь: EN});
  });

  it('обязательное поле категории, которого нет в шапке, предупреждает у видимой версии, а не останавливает выпуск', () => {
    const безСлов = {...ЦЕЛАЯ, [RU]: 'title: "Проба"\nslug: /lessons/proba\ndescription: "Есть"'};
    const находки = проверить(безСлов).filter((находка) => находка.код === 'полеКатегорииПусто');

    expect(находки.find((находка) => находка.путь === RU))
      .toMatchObject({уровень: ПРЕДУПРЕЖДЕНИЕ, поле: 'keywords'});
    expect(подготовкаПрошла(проверить(безСлов))).toBe(true);
  });

  it('то же поле у скрытой версии предупреждает так же: правило одно для любой видимости', () => {
    const находки = проверить(ЦЕЛАЯ).filter((находка) => находка.код === 'полеКатегорииПусто');

    expect(находки).toHaveLength(1);
    expect(находки[0]).toMatchObject({уровень: ПРЕДУПРЕЖДЕНИЕ, путь: EN, поле: 'keywords'});
  });

  it('пустой список ключевых слов останавливает выпуск у любой версии: от такой записи падает сборка', () => {
    const пустойСписок = {
      [RU]: 'title: "Проба"\nslug: /lessons/proba\ndescription: "Есть"\nkeywords: []',
      [EN]: 'title: "Заглушка"\nslug: /lessons/proba\ndescription: "Есть"\nkeywords: []\nunlisted: true',
    };
    const находки = проверить(пустойСписок)
      .filter((находка) => находка.код === 'пустыеКлючевыеСлова');

    expect(находки.map((находка) => находка.путь).sort()).toEqual([EN, RU].sort());
    expect(находки.every((находка) => находка.уровень === БЛОКЕР)).toBe(true);
    // Одна строка отчёта на одну строку файла: правило про отсутствующее поле молчит там,
    // где о поле уже сказано разбором шапки.
    expect(коды(проверить(пустойСписок))).not.toContain('полеКатегорииПусто');
  });

  it('список из пустых значений считается пустым полем, а не заполненным', () => {
    // Показанный вид тут врёт: `keywords: ["", ""]` выглядит строкой с запятой и кажется
    // заполненным. Заполненность спрашивается тем же правилом, каким защитная проверка решает,
    // убрать ли строку, — иначе у правила пустоты списка появилась бы третья запись.
    const пустые = {...ЦЕЛАЯ, [RU]: 'title: "Проба"\nslug: /lessons/proba\ndescription: "Есть"\nkeywords: ["", ""]'};
    const находки = проверить(пустые).filter((найдено) => найдено.путь === RU);

    expect(подготовкаПрошла(находки)).toBe(false);
  });

  it('пустой список ключевых слов у скрытой версии останавливает выпуск, хотя их отсутствие — нет', () => {
    // Асимметрия на глаз выглядит ошибкой, поэтому закреплена тестом. Предупреждение — про
    // отсутствующее поле; блокер — про поле, присутствующее в виде, от которого падает сборка,
    // а падает она независимо от того, видна версия или скрыта.
    const пустой = {...ЦЕЛАЯ, [EN]: `${ЦЕЛАЯ[EN]}\nkeywords: []`};
    const находки = проверить(пустой).filter((находка) => находка.путь === EN);

    expect(коды(находки)).toContain('пустыеКлючевыеСлова');
    expect(находки.find((находка) => находка.код === 'пустыеКлючевыеСлова').уровень).toBe(БЛОКЕР);
    expect(подготовкаПрошла(находки)).toBe(false);
    // И ровно одна строка отчёта про одну строку файла: разбор шапки уже про неё сказал.
    expect(коды(находки).filter((код) => код === 'полеКатегорииПусто')).toEqual([]);
  });

  it('с категории, которой нет в настройке обязательных полей, они не спрашиваются вовсе', () => {
    const безСлов = {...ЦЕЛАЯ, [RU]: 'title: "Проба"\nslug: /lessons/proba\ndescription: "Есть"'};

    expect(коды(проверить(безСлов, 'страница раздела'))).not.toContain('полеКатегорииПусто');
  });

  it('русская статья без английской версии останавливает выпуск: сайт не соберёт её вовсе', () => {
    const находки = проверить({[RU]: ЦЕЛАЯ[RU]});

    expect(находки.find((находка) => находка.код === 'нетОбязательнойВерсии'))
      .toMatchObject({уровень: БЛОКЕР, путь: null, локаль: 'en'});
  });

  it('статья вне сайта английской версии не требует: правила сайта её не касаются', () => {
    const песочница = {'editor/sandbox/proba/index.mdx': 'title: "Проба"\ndescription: "Есть"'};

    expect(коды(проверить(песочница, 'проба'))).not.toContain('нетОбязательнойВерсии');
  });
});

describe('подготовка статьи: находки, взятые у существующих правил', () => {
  it('шапка, которую защитная проверка поправила бы, даёт находки сухим прогоном', () => {
    const битая = {
      ...ЦЕЛАЯ,
      [RU]: 'title: "Проба"\nslug: proba\ndescription: "Есть"\nkeywords: [розетки]\nimage: ',
    };
    const находки = проверить(битая).filter((находка) => находка.путь === RU);

    expect(коды(находки)).toEqual(expect.arrayContaining(['пустаяОбложка', 'адресПоПравилу']));
    expect(находки.every((находка) => находка.этап === 'шапка')).toBe(true);
  });

  it('адрес без кавычек предупреждает, а не останавливает: схема сайта принимает и число', () => {
    // Адрес блога относительный, поэтому `slug: 2026` правилу раздела не противоречит — переписывать
    // его незачем. Беда только в записи: без кавычек YAML прочитает его числом, а сайт ждёт строку.
    const числом = {
      'i18n/ru/docusaurus-plugin-content-blog/2026/index.mdx': 'title: "Проба"\nslug: 2026\ndescription: "Есть"\nkeywords: [a]',
      'blog/2026/index.mdx': 'title: "A"\nslug: 2026\ndescription: "Есть"\nkeywords: [a]\nunlisted: true',
    };
    const находки = проверить(числом, 'блог');
    const находка = находки.find((найдено) => найдено.код === 'адресВКавычки');

    expect(находка).toMatchObject({уровень: ПРЕДУПРЕЖДЕНИЕ, поле: 'slug'});
    expect(подготовкаПрошла(находки)).toBe(true);
  });

  it('поле, стоящее в шапке дважды, останавливает выпуск: так статья не соберётся', () => {
    const дважды = {...ЦЕЛАЯ, [RU]: `${ЦЕЛАЯ[RU]}\ntitle: "Второй"`};
    const находки = проверить(дважды).filter((найдено) => найдено.код === 'поле:ключДважды');

    expect(находки.length).toBeGreaterThan(0);
    expect(находки[0]).toMatchObject({уровень: БЛОКЕР, путь: RU, поле: 'title'});
  });

  it('запятая внутри значения находкой не считается: файл исправен, сборка зелёная', () => {
    const запятая = {...ЦЕЛАЯ, [RU]: 'title: "Проба"\nslug: /lessons/proba\ndescription: "Есть"\nkeywords: ["розетки, вилки", быт]'};

    expect(коды(проверить(запятая)).filter((код) => код.startsWith('поле:'))).toEqual([]);
  });

  it('адреса языковых версий сравниваются приведёнными к правилу, а не записанными в файле', () => {
    // У английской версии адрес записан без раздела. Это уже находка сухого прогона, и второй
    // строки отчёта про ту же строку файла быть не должно.
    const разные = {...ЦЕЛАЯ, [EN]: ЦЕЛАЯ[EN].replace('slug: /lessons/proba', 'slug: proba')};
    const находки = проверить(разные);

    expect(коды(находки)).toContain('адресПоПравилу');
    expect(коды(находки)).not.toContain('адресаВерсийРазные');
  });

  it('версия без записанного адреса выпуск не останавливает: адрес ей даёт путь файла', () => {
    // Найдено воротами: сравнение отсутствующего адреса с записанным давало блокирующую находку
    // с пустой строкой вместо адреса. Адрес такой версии выводится из пути её файла, как это
    // делает и сам Docusaurus, а путь внутри раздела у языковых версий одинаков.
    const безАдреса = {...ЦЕЛАЯ, [EN]: ЦЕЛАЯ[EN].replace('slug: /lessons/proba\n', '')};
    const находки = проверить(безАдреса);

    expect(коды(находки)).not.toContain('адресаВерсийРазные');
    expect(подготовкаПрошла(находки)).toBe(true);
  });

  it('адрес, записанный только у одной версии и не совпавший с путём соседней, ловится', () => {
    // Вторая половина того же правила, и без неё оно теряет смысл: выброси мы версии без записи
    // из сравнения — русская страница уехала бы на свой адрес, английская осталась бы на прежнем,
    // переключатель языка повёл бы в никуда, а подготовка промолчала бы.
    const однобокий = {
      [RU]: 'title: "Проба"\nslug: /lessons/drugoy\ndescription: "Есть"\nkeywords: [a]',
      [EN]: 'title: "A"\ndescription: "Есть"\nkeywords: [a]\nunlisted: true',
    };
    const находка = проверить(однобокий).find((найдено) => найдено.код === 'адресаВерсийРазные');

    expect(находка).toMatchObject({
      уровень: БЛОКЕР, путь: EN, образец: '/lessons/drugoy', адрес: '/lessons/proba',
    });
  });

  it('пустая строка адреса называется своей бедой, а не расхождением версий', () => {
    // `slug:` без значения YAML читает пустотой, и сборка падает на нём. Сказать здесь «адреса
    // версий разные» значит послать человека сверять версии вместо того, чтобы заполнить строку.
    const пустой = {...ЦЕЛАЯ, [EN]: ЦЕЛАЯ[EN].replace('slug: /lessons/proba', 'slug:')};
    const находки = проверить(пустой);

    expect(находки.find((найдено) => найдено.код === 'адресПуст'))
      .toMatchObject({уровень: БЛОКЕР, путь: EN, поле: 'slug'});
    expect(коды(находки)).not.toContain('адресаВерсийРазные');
  });

  it('поле, стоящее в шапке дважды, даёт одну строку отчёта, а не по строке на каждую запись', () => {
    const дважды = {...ЦЕЛАЯ, [RU]: `${ЦЕЛАЯ[RU]}\ntitle: "Второй"`};

    expect(коды(проверить(дважды)).filter((код) => код === 'поле:ключДважды')).toHaveLength(1);
  });

  it('версии-файлы не в своей папке и без записанного адреса ложного расхождения не дают', () => {
    // Статья, лежащая файлом в корне раздела, и без записанного адреса: по прежнему правилу он
    // выводился из имени папки НАД файлом — `/docs` у английской версии и `/current` у русской
    // (служебная папка плагина локализации), — и здоровая статья получала блокер с адресами,
    // которых на сайте не бывает. На живом сайте так лежит «Добро пожаловать», но у неё адрес
    // записан (`slug: /`), поэтому её эта ветка не задевала. Ни один из двадцати тестов
    // подготовки файла не в папке не проверял вовсе — потому находка и не покраснела машиной.
    const файлами = {
      'i18n/ru/docusaurus-plugin-content-docs/current/intro.mdx': 'title: "Начало"\ndescription: "Есть"\nkeywords: [a]',
      'docs/intro.mdx': 'title: "Intro"\ndescription: "Есть"\nkeywords: [a]\nunlisted: true',
    };
    const находки = проверить(файлами);

    expect(коды(находки)).not.toContain('адресаВерсийРазные');
    expect(подготовкаПрошла(находки)).toBe(true);
  });

  it('настоящее расхождение адресов у версий-файлов ловится, а не схлопывается по разделу', () => {
    // Зеркальная половина той же беды: у обеих версий адрес выводился из имени папки раздела,
    // поэтому записанный не тот адрес сходился бы с выведенным и проходил молча.
    const однобокий = {
      'i18n/ru/docusaurus-plugin-content-docs/current/intro.mdx': 'title: "Начало"\nslug: /drugoy\ndescription: "Есть"\nkeywords: [a]',
      'docs/intro.mdx': 'title: "Intro"\ndescription: "Есть"\nkeywords: [a]\nunlisted: true',
    };
    const находка = проверить(однобокий).find((найдено) => найдено.код === 'адресаВерсийРазные');

    expect(находка).toMatchObject({
      уровень: БЛОКЕР, путь: 'docs/intro.mdx', образец: '/drugoy', адрес: '/intro',
    });
  });

  it('адрес, стоящий в шапке дважды, даёт одну строку правки, а не две с разными «стало»', () => {
    // Две записи ключа давали по находке каждая, и вместе они обещали человеку несовместимое:
    // «адрес будет исправлен на /lessons/proba» и «на /lessons/drugoy» разом. Обе записи здесь
    // намеренно не по правилу раздела: правку даёт только такая, и с абсолютным адресом в первой
    // строке тест был бы зелёным и до починки — он ничего бы не доказывал.
    const дважды = {...ЦЕЛАЯ, [RU]: `${ЦЕЛАЯ[RU].replace('slug: /lessons/proba', 'slug: proba')}\nslug: drugoy`};
    const находки = проверить(дважды).filter((найдено) => найдено.путь === RU);

    expect(коды(находки).filter((код) => код === 'адресПоПравилу')).toHaveLength(1);
    // Блокер про задвоенный ключ рядом остаётся: выпуск останавливает он.
    expect(находки.find((найдено) => найдено.код === 'поле:ключДважды'))
      .toMatchObject({уровень: БЛОКЕР, поле: 'slug'});
  });

  it('по-настоящему разные адреса версий останавливают выпуск: сломается переключатель языка', () => {
    const разные = {...ЦЕЛАЯ, [EN]: ЦЕЛАЯ[EN].replace('/lessons/proba', '/lessons/other')};
    const находка = проверить(разные).find((найдено) => найдено.код === 'адресаВерсийРазные');

    // Не «было и стало»: там эти слова значат «программа перепишет», а здесь переписывать никто
    // ничего не собирается — показаны образец и то, что стоит в этом файле.
    expect(находка).toMatchObject({
      уровень: БЛОКЕР, путь: EN, поле: 'slug', образец: '/lessons/proba', адрес: '/lessons/other',
    });
    expect(находка.было).toBe(undefined);
  });
});

