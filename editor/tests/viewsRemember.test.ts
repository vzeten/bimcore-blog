// Запомненные в браузере цифры просмотров (решение владельца 2026-09-24): при обновлении страницы
// окно показывает последние цифры сразу, а не прочерки, пока сервер отвечает.
import {describe, expect, it} from 'vitest';
import {запомненныеПросмотры, запомнитьПросмотры, КЛЮЧ_ЗАПОМНЕННЫХ, type Просмотры} from '../src/ui/useViews';

function хранилище(начало: Record<string, string> = {}) {
  const данные = {...начало};
  return {
    данные,
    getItem: (ключ: string) => данные[ключ] ?? null,
    setItem: (ключ: string, значение: string) => {
      данные[ключ] = значение;
    },
  };
}

const числа = {всего: 10, за30: 4, прежние30: 2, языки: {ru: 4}, месяцы: []};
const ответ: Просмотры = {статьи: {a: числа}, поДень: '20260922', надпись: null};

describe('запомненные просмотры', () => {
  it('ответ с цифрами запоминается и читается обратно тем же', () => {
    const х = хранилище();
    запомнитьПросмотры(х, ответ);
    expect(запомненныеПросмотры(х)).toEqual(ответ);
  });

  it('ответ без цифр прежние запомненные не затирает', () => {
    const х = хранилище();
    запомнитьПросмотры(х, ответ);
    запомнитьПросмотры(х, {статьи: {}, поДень: null, надпись: 'нет ключа'});
    expect(запомненныеПросмотры(х)?.статьи.a).toEqual(числа);
  });

  it('старая надпись сервера из запомненного не показывается', () => {
    const х = хранилище();
    запомнитьПросмотры(х, {...ответ, надпись: 'Цифры не обновились'});
    expect(запомненныеПросмотры(х)?.надпись).toBeNull();
  });

  it('нет хранилища, пусто, испорчено или бросает — как будто ничего не запомнено', () => {
    expect(запомненныеПросмотры(null)).toBeNull();
    expect(запомненныеПросмотры(хранилище())).toBeNull();
    expect(запомненныеПросмотры(хранилище({[КЛЮЧ_ЗАПОМНЕННЫХ]: '{битое'}))).toBeNull();
    expect(запомненныеПросмотры(хранилище({[КЛЮЧ_ЗАПОМНЕННЫХ]: '{"статьи":null,"поДень":"20260922"}'}))).toBeNull();
    const бросает = {getItem: () => {
      throw new Error('запрещено');
    }, setItem: () => {
      throw new Error('переполнено');
    }};
    expect(запомненныеПросмотры(бросает)).toBeNull();
    expect(() => запомнитьПросмотры(бросает, ответ)).not.toThrow();
  });
});
