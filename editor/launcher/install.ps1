# Включение нового ярлыка — только когда новый принятый редактор УЖЕ РАБОТАЕТ и сам это доказал.
#
# Порядок после переноса операции в `editor` (иначе установка откажет):
#   1. обновить принятую копию `accepted-editor` до принятого кода;
#   2. запустить её прямым проверенным способом — прежним ярлыком или `node server.mjs`
#      в папке принятой копии, — чтобы на 4780 работал именно новый принятый редактор;
#   3. эта установка сама убедится, что `http://localhost:4780/api/identity` отвечает и совпадает;
#   4. только тогда ярлык заменяется одним движением, прежний сохраняется рядом.
#
# Почему проверяется живой ответ, а не текст исходника: на 4780 может работать прежний принятый
# сервер, который про себя ничего не отвечает (404). Файл кода на диске уже новый, а работает
# старое. Заменённый в этот миг ярлык отказался бы открывать вполне рабочее окно, то есть сломал бы
# владельцу привычный запуск. Живой ответ — единственное доказательство, что новый порядок
# заработает сразу после подмены.
#
# Ожидаемая личность собирается из НЕЗАВИСИМЫХ фактов git о принятой копии — ветка, короткий коммит
# и чистота дерева, — а не из слов самого сервера: признак `accepted` в ответе напишет кто угодно.
# Сверяются все поля: род, принятость, чистота, ветка, коммит, папка кода, папка материалов, порт.
#
# Логика живёт в PowerShell, а не в самом .bat: имя ярлыка написано кириллицей, а командный файл
# читается в кодовой странице консоли, и путь там превращается в мусор. Здесь имя вообще не
# набирается — ярлык находится единственным .bat в своей папке.

$ErrorActionPreference = 'Stop'

$принятая = 'C:\My_code\bimcore-blog\editor\.coordination\worktrees\accepted-editor'
$кодDir = Join-Path $принятая 'editor'
$кандидат = Join-Path $кодDir 'launcher\BIMCORE-Editor.bat'
$папкаЯрлыка = Join-Path $env:USERPROFILE 'Documents\BIMCORE Editor'
$материалы = 'C:\My_code\bimcore-blog'
$порт = 4780
$адрес = "http://localhost:$порт/api/identity"
$git = 'C:\Program Files\Git\cmd\git.exe'

$ПОРЯДОК = @(
  'Что сделать по порядку:',
  '  1) обновить принятую копию accepted-editor до принятого кода;',
  "  2) запустить её прямым способом: прежним ярлыком или командой node server.mjs в папке $кодDir;",
  "  3) проверить, что $адрес отвечает;",
  '  4) запустить эту установку снова.'
)

function Стоп {
  param([string]$сообщение, [switch]$СПорядком)

  Write-Host $сообщение
  if ($СПорядком) { $ПОРЯДОК | ForEach-Object { Write-Host $_ } }
  Write-Host 'Ничего не изменено: ни ярлык, ни его резерв.'
  exit 1
}

# Одна папка, названная по-разному, остаётся одной папкой: вид косых и регистр Windows не различает.
function ПутьРавен {
  param([string]$первый, [string]$второй)

  $ровно = { param([string]$п) ($п -replace '/', '\').TrimEnd('\').ToLower() }
  return (& $ровно $первый) -eq (& $ровно $второй)
}

if (-not (Test-Path -LiteralPath $кандидат)) {
  Стоп "Кандидата ярлыка в принятой копии ещё нет: $кандидат" -СПорядком
}

# Независимые факты о принятой копии. Именно с ними, а не со словами сервера, сверяется ответ.
$ветка = (& $git -C $принятая branch --show-current 2>$null | Select-Object -First 1)
if ($ветка -ne 'editor') {
  Стоп "Принятая копия стоит на ветке `"$ветка`", а не на `"editor`"." -СПорядком
}

if (& $git -C $принятая status --porcelain 2>$null) {
  Стоп "В принятой копии есть несохранённые правки: $принятая" -СПорядком
}

$коммит = (& $git -C $принятая rev-parse --short HEAD 2>$null | Select-Object -First 1)
if (-not $коммит) { Стоп "Не удалось прочитать коммит принятой копии: $принятая" }

# Живой ответ работающего сервера. Молчание и 404 — это один и тот же случай: на порту либо никого,
# либо прежний редактор, который про себя не отвечает. Оба означают, что подменять ярлык рано.
$ответ = $null
try {
  $ответ = Invoke-WebRequest -UseBasicParsing -TimeoutSec 5 $адрес
} catch {
  $код = $null
  if ($_.Exception.Response) { $код = [int]$_.Exception.Response.StatusCode }
  if ($код) {
    Стоп "На $порт отвечает сервер, но про себя молчит (код $код). Похоже, это прежний редактор." -СПорядком
  }
  Стоп "На $порт никто не отвечает: новый принятый редактор ещё не запущен." -СПорядком
}

try {
  $и = $ответ.Content | ConvertFrom-Json
} catch {
  Стоп "Ответ на $адрес не разобрать: это не опознание редактора."
}

$несовпадения = @()
if ($и.role -ne 'owner') { $несовпадения += "род `"$($и.role)`" вместо `"owner`"" }
if ($и.accepted -ne $true) { $несовпадения += 'сервер сам себя принятым не считает' }
if ($и.clean -ne $true) { $несовпадения += 'в дереве кода запущенного сервера есть правки' }
if ($и.branch -ne $ветка) { $несовпадения += "ветка `"$($и.branch)`" вместо `"$ветка`"" }
if ($и.commit -ne $коммит) { $несовпадения += "коммит `"$($и.commit)`" вместо `"$коммит`"" }
if ([int]$и.port -ne $порт) { $несовпадения += "порт `"$($и.port)`" вместо `"$порт`"" }
if (-not (ПутьРавен $и.code $кодDir)) { $несовпадения += "папка кода `"$($и.code)`" вместо `"$кодDir`"" }
if (-not (ПутьРавен $и.materials $материалы)) { $несовпадения += "материалы `"$($и.materials)`" вместо `"$материалы`"" }

if ($несовпадения.Count -gt 0) {
  Write-Host "На $порт отвечает не тот редактор, для которого делается этот ярлык:"
  $несовпадения | ForEach-Object { Write-Host "  - $_" }
  Стоп 'Такой ярлык не открывал бы работающее окно.' -СПорядком
}

$ярлыки = @(Get-ChildItem -LiteralPath $папкаЯрлыка -Filter '*.bat' -File)
if ($ярлыки.Count -ne 1) {
  Стоп "В папке $папкаЯрлыка должен лежать ровно один .bat, а их $($ярлыки.Count)."
}
$ярлык = $ярлыки[0].FullName

$резерв = "$ярлык.bak"
if (-not (Test-Path -LiteralPath $резерв)) { Copy-Item -LiteralPath $ярлык -Destination $резерв }

# Замена одним движением: сначала полная копия рядом, потом переименование поверх. Оборвись
# копирование на середине — рабочий ярлык остаётся прежним, а не превращается в обрубок.
$временный = "$ярлык.new"
Copy-Item -LiteralPath $кандидат -Destination $временный -Force
Move-Item -LiteralPath $временный -Destination $ярлык -Force

Write-Host "Готово. На $порт сейчас работает принятый редактор $ветка $коммит, и ярлык открывает только его."
Write-Host "Прежний ярлык сохранён: $резерв"
