# Сделать панель экземпляров основным ярлыком владельца — и только когда она уже РАБОТАЕТ и сама
# это доказала. Довод тот же, что и у соседней установки ярлыка редактора: файл на диске бывает уже
# новым, когда на порту никого нет, и подменённый в этот миг ярлык оставил бы владельца вовсе без
# входа. Живой ответ панели — единственное доказательство, что новый порядок заработает сразу.
#
# Прежний ярлык редактора не удаляется и не переписывается: он остаётся рядом рабочим запасным
# входом. Меняется только то, что владелец запускает первым.
#
# Порядок: перенести операцию в `editor`, обновить принятую копию, запустить панель её ярлыком
# `BIMCORE-Panel.vbs` из принятой копии, убедиться, что окно открылось, и лишь затем запустить
# этот файл.

$ErrorActionPreference = 'Stop'

$принятая = 'C:\My_code\bimcore-blog\editor\.coordination\worktrees\accepted-editor'
$кодDir = Join-Path $принятая 'editor'
$папкаЯрлыка = Join-Path $env:USERPROFILE 'Documents\BIMCORE Editor'
$порт = 4779
$адрес = "http://localhost:$порт/api/panel/whoami"
$файлы = @('BIMCORE-Panel.vbs', 'panel-open.ps1')

function Стоп {
  param([string]$сообщение)

  Write-Host $сообщение
  Write-Host 'Ничего не изменено: ни ярлыки, ни их резервы.'
  exit 1
}

# Одна папка, названная по-разному, остаётся одной папкой: вид косых и регистр Windows не различает.
function ПутьРавен {
  param([string]$первый, [string]$второй)

  $ровно = { param([string]$п) ($п -replace '/', '\').TrimEnd('\').ToLower() }
  return (& $ровно $первый) -eq (& $ровно $второй)
}

foreach ($имя in $файлы) {
  $путь = Join-Path $кодDir "launcher\$имя"
  if (-not (Test-Path -LiteralPath $путь)) { Стоп "В принятой копии нет файла ярлыка: $путь" }
}

if (-not (Test-Path -LiteralPath $папкаЯрлыка)) { Стоп "Нет папки ярлыков владельца: $папкаЯрлыка" }

$ответ = $null
try {
  $ответ = Invoke-WebRequest -UseBasicParsing -TimeoutSec 5 $адрес
} catch {
  if ($_.Exception.Response) {
    Стоп "На $порт отвечает сервер, но панелью себя не называет. Похоже, это посторонняя программа."
  }
  Стоп "На $порт никто не отвечает: панель ещё не запущена из принятой копии."
}

try {
  $о = $ответ.Content | ConvertFrom-Json
} catch {
  Стоп "Ответ на $адрес не разобрать: это не панель экземпляров."
}

if ($о.panel -ne $true) { Стоп "Сервер на $порт панелью себя не считает." }
if ([int]$о.port -ne $порт) { Стоп "Панель называет порт $($о.port) вместо $порт." }
if (-not (ПутьРавен $о.code $кодDir)) {
  Стоп "На $порт работает панель из папки $($о.code), а ярлык делается для $кодDir."
}

# Замена одним движением на каждый файл: сначала полная копия рядом, потом переименование поверх.
foreach ($имя in $файлы) {
  $откуда = Join-Path $кодDir "launcher\$имя"
  $куда = Join-Path $папкаЯрлыка $имя
  $резерв = "$куда.bak"
  if ((Test-Path -LiteralPath $куда) -and -not (Test-Path -LiteralPath $резерв)) {
    Copy-Item -LiteralPath $куда -Destination $резерв
  }
  $временный = "$куда.new"
  Copy-Item -LiteralPath $откуда -Destination $временный -Force
  Move-Item -LiteralPath $временный -Destination $куда -Force
}

Write-Host "Готово. Основной вход теперь здесь: $(Join-Path $папкаЯрлыка 'BIMCORE-Panel.vbs')"
Write-Host 'Прежний ярлык редактора оставлен рядом рабочим запасным входом.'
