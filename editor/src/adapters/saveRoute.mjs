// Ручка сохранения статьи: запись файла человека и служебные шаги после неё.
// Вынесено из сервера, чтобы он оставался в пределах лимита размера файла (SPEC 4.9).
// Правил здесь нет: они в `core` — сборка файла, сведение сторон, защитные правила шапки.
//
// Пишется ровно один файл — тот, что открыт в окне. Видимость принадлежит языковой версии
// (SPEC 2.8), поэтому соседние версии сохранение не трогает ничем: ни записью, ни снимком
// в истории, ни готовностью.
//
// Записи поверх чужой правки здесь больше нет вовсе. Внешняя правка сводится с работой человека,
// а неразрешимое пересечение останавливает запись ЭТОЙ версии и уходит в спор со всеми сторонами.

import fs from 'node:fs';
import path from 'node:path';

import {buildHead, joinArticle, nothingChanged, splitArticle} from '../core/articleFile.mjs';
import {safeFrontmatter} from '../core/safeFrontmatter.mjs';
import {afterEdit, состояниеДляОкна} from '../core/articleState.mjs';
import {newDraft, базаЧерновика, позже, свежееЧерновика} from '../core/drafts.mjs';
import {badFields} from './httpBody.mjs';
import {dropDraft, fingerprint, loadDraft, saveDraft, saveSnapshot} from './draftStore.mjs';
import {убратьСпор} from './conflictStore.mjs';
import {записатьСверив, отложитьСпор, сверитьСДиском} from './mergeGate.mjs';
import {ответСпора, знакомаяВерсия} from './mergeAnswer.mjs';
import {gitAuthor} from './gitFile.mjs';
import {loadState, saveState} from './library.mjs';

// Сколько раз пробовать записать, если файл успел смениться между сведением и записью.
// Величина алгоритма, а не настройка: человеку решать нечего, а без предела ручка крутилась бы,
// пока кто-то снаружи пишет в файл без остановки.
const ПОПЫТОК = 3;

/**
 * Служебный шаг после того, как файл статьи уже записан. Его сбой пишется в консоль сервера,
 * но не отменяет соседние шаги и не выдаётся человеку за неудачу сохранения: текст на диске.
 */
function безСрыва(шаг, предупреждения, код) {
  try {
    шаг();
  } catch (error) {
    console.error(error);
    // Молчать нельзя: человеку скажут «сохранено», а версия или готовность на диск не легли.
    // Код — внутренний договор сервера и окна; человеческий текст живёт в настройках.
    предупреждения.push(код);
  }
}

/**
 * Собрать текст файла из новой шапки и нового тела. Переводы строк и невидимая метка берутся
 * у самого файла: у каждой языковой версии они свои, и запись чужими переписала бы весь файл
 * вместо изменённых строк (SPEC 3.5, 5.1).
 *
 * Тело передаётся явно и всегда: это текст из окна. Возьми функция тело сама у файла — правка
 * человека молча не доехала бы до диска.
 *
 * Наружу отдана ради корпусного прогона: он повторяет путь «программа открыла и сохранила»
 * по всем статьям сайта, и повтори он сборку у себя — сравнивал бы не с тем, что пишет сервер.
 */
export function собрать(current, frontmatterRaw, body) {
  const toEol = (text) => (current.eol === '\r\n'
    ? text.replace(/\r?\n/g, '\r\n')
    : text.replace(/\r\n/g, '\n'));

  return joinArticle({
    head: buildHead({frontmatterRaw: toEol(frontmatterRaw), eol: current.eol, метка: current.метка}),
    body: toEol(body),
  });
}

/**
 * Обрабатывает `/api/article/save`. Возвращает true, если запрос был к ней.
 *
 * `фиксировать` — сохранение внешней правки версией: файл могли изменить, пока человек правил,
 * и чужая работа обязана попасть в историю до записи.
 * `последняяПравка` — время последней принятой правки по каждой статье: по нему запоздавший
 * запрос не стирает черновик, написанный уже после его отправки.
 */
export async function saveRoute({
  req, res, url, repo, settings, git, publishedRef, тело, insideRepo, send, фиксировать, последняяПравка,
}) {
  if (url.pathname !== '/api/article/save' || req.method !== 'POST') return false;

  const payload = await тело(req);
  // Поля проверяются до работы с путями: без этого не-строка роняет `path.join` внутренней
  // ошибкой вместо понятного «неверный запрос» (SPEC 6.4). Пустое тело — законно, поэтому
  // у него проверяется только тип: статья без текста бывает, статья без пути — нет.
  const тексты = settings['ошибкиСервера'];
  const плохое = badFields(payload, ['path'], тексты)
    ?? (typeof payload.body === 'string' ? null : {status: 400, error: тексты['плохойЗапрос']})
    ?? (typeof payload.отпечатокБазы === 'string' && payload.отпечатокБазы !== ''
      ? null
      : {status: 400, error: тексты['плохойЗапрос']});
  if (плохое) {
    send(res, плохое.status, {error: плохое.error});
    return true;
  }

  const rel = payload.path;
  const file = path.join(repo, rel);
  if (!insideRepo(file) || (!fs.existsSync(file) && !знакомаяВерсия(repo, settings, rel))) {
    send(res, 404, {error: тексты['нетСтатьи']});
    return true;
  }

  /** Убрать черновик после настоящего сохранения — но только если он не новее самого сохранения. */
  const убратьЧерновик = () => {
    const черновик = loadDraft(repo, settings, rel);
    if (черновик === null || свежееЧерновика(payload.правкаОт, черновик)) dropDraft(repo, settings, rel);
    // Порог свежести остаётся в памяти и после удаления черновика: без него поздний запрос
    // автосохранения воскресил бы черновик поверх только что сохранённой работы.
    последняяПравка.set(rel, позже(payload.правкаОт ?? new Date().toISOString(), последняяПравка.get(rel)));
  };

  for (let попытка = 0; попытка < ПОПЫТОК; попытка += 1) {
    // Шапки в запросе нет — человек её не трогал; тогда его сторона равна тому, что лежит в файле,
    // и после сведения там останется внешняя шапка, как и было до этого запроса.
    const внешняяШапка = () => (fs.existsSync(file) ? splitArticle(fs.readFileSync(file, 'utf8')).frontmatterRaw : '');
    const мои = {body: payload.body, frontmatterRaw: payload.frontmatterRaw ?? внешняяШапка()};

    const итог = await сверитьСДиском({
      repo, settings, rel, мои, отпечатокБазы: payload.отпечатокБазы, git, ref: publishedRef?.(),
      фиксировать: (путь) => фиксировать(путь, true),
    });

    if (итог.исход === 'неуспеть') break;

    // Спор, отсутствие базы и пропажа файла: запись ЭТОЙ версии останавливается, все стороны
    // ложатся на диск, решает человек. Соседние языковые версии продолжают работать.
    if (итог.исход !== 'нетВнешней' && итог.исход !== 'сведено') {
      отложитьСпор({repo, settings, rel, итог, мои, когда: new Date().toISOString()});
      сохранитьСторонуЧеловека({repo, settings, rel, payload, мои, база: итог.база});
      send(res, 409, {error: тексты['файлИзменёнСнаружи'], конфликт: true, ...ответСпора(repo, settings, rel)});
      return true;
    }

    const работа = итог.исход === 'сведено' ? итог.сведено : мои;
    // Защитные правила применяются к тому, что действительно ляжет в файл: через сохранение
    // проходит любая правка шапки, в том числе пришедшая со стороны и сведённая с нашей.
    const safe = safeFrontmatter(rel, работа.frontmatterRaw, settings['контент']);
    const записано = {frontmatterRaw: safe.frontmatterRaw, body: работа.body};
    const current = splitArticle(итог.raw);

    // Ничего не изменилось — файл не трогаем вовсе. Так «открыл и сохранил» не портит статью.
    // Черновик при этом всё равно убираем: продолжать нечего, текст и так совпадает с файлом.
    if (nothingChanged(итог.внешняя, записано)) {
      убратьЧерновик();
      убратьСпор(repo, settings, rel);
      send(res, 200, {saved: true, untouched: true, отпечаток: итог.отпечатокВнешней, записано});
      return true;
    }

    const текст = собрать(current, safe.frontmatterRaw, работа.body);
    // Последняя сверка перед заменой файла: между чтением и записью могла лечь ещё одна внешняя
    // правка, и запись поверх стёрла бы версию, которой нет ни в истории, ни где-либо ещё.
    if (!записатьСверив({file, ожидаемыйОтпечаток: итог.отпечатокВнешней, текст})) continue;

    await отдать({текст, записано});
    return true;
  }

  send(res, 409, {error: тексты['файлМеняется'], конфликт: true});
  return true;

  /** Файл записан. Дальше идёт служебное: версия в истории, уборка черновика и спора, готовность. */
  async function отдать({текст, записано}) {
    // Каждый шаг отдельно: сбой одного не отменяет остальные и не превращает удавшееся сохранение
    // в «ничего не сохранилось». Иначе, например, упавший снимок оставлял бы старый черновик,
    // и при следующем открытии человек получал бы ложный выбор.
    // Автор известен: файл пишем мы, и подпись берётся у того, кто работает за программой.
    const автор = (await gitAuthor(git)) ?? settings['реестр']['неизвестныйАвтор'];
    const сейчас = new Date().toISOString();
    const state = afterEdit(loadState(repo, rel, settings), settings);

    const предупреждения = [];
    безСрыва(() => saveSnapshot(repo, settings, rel, текст, автор, сейчас), предупреждения, 'история');
    безСрыва(убратьЧерновик, предупреждения, 'черновик');
    безСрыва(() => убратьСпор(repo, settings, rel), предупреждения, 'черновик');
    // Правка после подготовки возвращает версию в черновик.
    безСрыва(() => saveState(repo, rel, settings, state), предупреждения, 'состояние');

    // Окну отдаём готовность ОТКРЫТОЙ версии, и только если она действительно легла на диск
    // (правило — в ядре).
    send(res, 200, {
      saved: true,
      state: состояниеДляОкна(state, предупреждения),
      отпечаток: fingerprint(текст),
      записано,
      предупреждения,
    });
  }
}

/**
 * Работа человека ложится в черновик своей версии прежде, чем ручка ответит спором.
 * Без этого отказ записи оставил бы набранное только в окне, а окно закрывают.
 */
function сохранитьСторонуЧеловека({repo, settings, rel, payload, мои, база}) {
  const когда = new Date().toISOString();
  saveDraft(repo, settings, newDraft({
    path: rel,
    ...мои,
    отпечатокБазы: payload.отпечатокБазы,
    когда,
    правкаОт: typeof payload.правкаОт === 'string' ? payload.правкаОт : когда,
    база: база ?? базаЧерновика(loadDraft(repo, settings, rel)),
  }));
}
