// Запоминание просмотров на диске: `<материалы>/editor/.views/` (в `.gitignore`, в публикацию не входит).
//
// Хранится только нужное для чисел: строки `[адрес, день, просмотры]`, по какой день они и когда
// спрошены. Ни ключа, ни пропуска, ни ответа Google целиком здесь нет (условие контролёра Codex).
//
// Предел запросов общий для ВСЕХ экземпляров редактора на этой машине: они делят одну папку
// материалов. Кто спрашивает Google, сперва занимает отметку `захват` (создание файла, которое
// удаётся только одному); остальные в это время берут прежний снимок. Снимок и итог попытки
// пишутся атомарной заменой: чтение не увидит половину файла.

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const СНИМОК = 'снимок.json';
const ПОПЫТКА = 'попытка.json';
const ЗАХВАТ = 'захват';

export const папкаПросмотров = (repo) => path.join(repo, 'editor', '.views');

/**
 * Создать папку запоминания, которая сама себя прячет от Git: правило в корневом `.gitignore`
 * приходит в основную папку только с выпуском кода, а до того папка лежала бы там неучтённой и
 * могла уехать общим `git add`. Свой `.gitignore` со звёздочкой прячет её в любой ветке.
 */
function готоваяПапка(repo) {
  const папка = папкаПросмотров(repo);
  fs.mkdirSync(папка, {recursive: true});
  const правило = path.join(папка, '.gitignore');
  if (!fs.existsSync(правило)) fs.writeFileSync(правило, '*\n');
  return папка;
}

function прочитать(файл) {
  try {
    return JSON.parse(fs.readFileSync(файл, 'utf8'));
  } catch {
    return null;
  }
}

function записать(папка, имя, данные) {
  const временный = path.join(папка, `.${имя}.${process.pid}.${Date.now()}.tmp`);
  fs.writeFileSync(временный, JSON.stringify(данные));
  fs.renameSync(временный, path.join(папка, имя));
}

/** Сохранённый снимок `{запрошено, поДень, строки}` или `null`: нет или испорчен — как не было. */
export function прочитатьСнимок(repo) {
  const снимок = прочитать(path.join(папкаПросмотров(repo), СНИМОК));
  return снимок && typeof снимок.поДень === 'string' && Array.isArray(снимок.строки) ? снимок : null;
}

/** Итог последней попытки `{когда, итог}`: `итог` — `есть` или код причины из `ga4Client.mjs`. */
export function прочитатьПопытку(repo) {
  const попытка = прочитать(path.join(папкаПросмотров(repo), ПОПЫТКА));
  return попытка && Number.isFinite(попытка.когда) ? попытка : null;
}

/** Местный день `YYYYMMDD` момента `когда`. */
export function деньМестный(когда) {
  const д = new Date(когда);
  return `${д.getFullYear()}${String(д.getMonth() + 1).padStart(2, '0')}${String(д.getDate()).padStart(2, '0')}`;
}

/** Беды, найденные у себя, до обращения к Google: предела Google они не тратят. */
const СВОИ_БЕДЫ = ['нетПапки', 'ключВGit', 'нетКлюча', 'многоКлючей', 'неКлюч'];

/**
 * Пора ли спрашивать Google. Нет — если сегодня удачный снимок уже получен: данные GA4 обновляются
 * раз в сутки. После неудачи, дошедшей до Google, — не раньше чем через `паузаЧасов`: так сбой сети
 * утром не оставляет без чисел до завтра, а предел Google не сжигается частыми повторами. Беда с
 * ключом у себя паузы не ждёт: Google не спрашивался, а человек, поправив ключ, увидит числа сразу.
 */
export function пораСпросить({снимок, попытка, сейчас, паузаЧасов}) {
  if (снимок && деньМестный(Date.parse(снимок.запрошено)) === деньМестный(сейчас)) return false;
  const неудачаУGoogle = попытка && попытка.итог !== 'есть' && !СВОИ_БЕДЫ.includes(попытка.итог);
  if (неудачаУGoogle && сейчас - попытка.когда < паузаЧасов * 3600 * 1000) return false;
  return true;
}

/**
 * Занять право спросить Google. Ответ — метка этого захода (ею же право и отдаётся) или `null`:
 * спрашивает другой экземпляр. Отметка хранит время и метку владельца. Брошенная отметка
 * (экземпляр упал посреди запроса) старше `срокМс` снимается, но только если за время проверки
 * её никто не сменил: снимающий сперва уносит её под своё имя и сверяет, ту ли унёс.
 */
export function занять(repo, срокМс, сейчас = Date.now()) {
  const файл = path.join(готоваяПапка(repo), ЗАХВАТ);
  const метка = `${сейчас}|${process.pid}|${crypto.randomUUID()}`;
  for (let попытка = 0; попытка < 2; попытка += 1) {
    try {
      fs.writeFileSync(файл, метка, {flag: 'wx'});
      return метка;
    } catch (error) {
      if (error?.code !== 'EEXIST') return null;
      // Возраст — по времени, записанному в самой отметке, теми же часами, что и `сейчас`.
      // Пустая или испорченная отметка (её только что создают или запись оборвалась) судится по
      // времени файла: иначе оборванная запись заперла бы запросы навсегда.
      let прочитано;
      let возраст;
      try {
        прочитано = fs.readFileSync(файл, 'utf8');
        const когда = Number(прочитано.split('|')[0]);
        возраст = когда > 0 ? сейчас - когда : Date.now() - fs.statSync(файл).mtimeMs;
      } catch {
        continue;
      }
      if (!(возраст >= срокМс) || !снятьЕслиТа(файл, прочитано, метка)) return null;
    }
  }
  return null;
}

/**
 * Снять отметку, только если в ней по-прежнему `ожидается`. Отметка уносится под своё имя одной
 * операцией (переименование удаётся только одному), затем сверяется; чужая возвращается на место.
 */
function снятьЕслиТа(файл, ожидается, метка) {
  const унесено = `${файл}.${метка.split('|')[2]}`;
  try {
    fs.renameSync(файл, унесено);
  } catch {
    return false;
  }
  try {
    if (fs.readFileSync(унесено, 'utf8') === ожидается) {
      fs.rmSync(унесено, {force: true});
      return true;
    }
    // Унесли свежую чужую отметку: вернуть её, если место свободно.
    fs.linkSync(унесено, файл);
  } catch {
    // Место уже заняли заново — чужая отметка там и стоит, наша копия лишняя.
  }
  fs.rmSync(унесено, {force: true});
  return false;
}

/** Отдать право спросить, ничего не записывая: снимается только своя отметка. */
export function отдать(repo, метка) {
  снятьЕслиТа(path.join(папкаПросмотров(repo), ЗАХВАТ), метка, метка);
}

/**
 * Записать итог захода и отдать право спросить. Удачный заход кладёт и новый снимок. Отдаётся
 * только своя отметка: чужую, занятую после снятия нашей просроченной, этот заход не трогает.
 */
export function завершить(repo, {метка, когда, итог, снимок}) {
  const папка = готоваяПапка(repo);
  try {
    if (снимок) записать(папка, СНИМОК, снимок);
    записать(папка, ПОПЫТКА, {когда, итог});
  } finally {
    отдать(repo, метка);
  }
}
