// Запоминание просмотров на диске: `<материалы>/editor/.views/` (в `.gitignore`, в публикацию не входит).
//
// Хранится только нужное для чисел: строки `[адрес, день, просмотры]`, по какой день они и когда
// спрошены. Ни ключа, ни пропуска, ни ответа Google целиком здесь нет (условие контролёра Codex).
//
// Предел запросов общий для ВСЕХ экземпляров редактора на этой машине: они делят одну папку
// материалов. Кто спрашивает Google, сперва занимает отметку `захват` (создание файла, которое
// удаётся только одному); остальные в это время берут прежний снимок. Снимок и итог попытки
// пишутся атомарной заменой: чтение не увидит половину файла.

import fs from 'node:fs';
import path from 'node:path';

const СНИМОК = 'снимок.json';
const ПОПЫТКА = 'попытка.json';
const ЗАХВАТ = 'захват';

export const папкаПросмотров = (repo) => path.join(repo, 'editor', '.views');

function прочитать(файл) {
  try {
    return JSON.parse(fs.readFileSync(файл, 'utf8'));
  } catch {
    return null;
  }
}

function записать(папка, имя, данные) {
  fs.mkdirSync(папка, {recursive: true});
  const временный = path.join(папка, `.${имя}.${process.pid}.${Date.now()}.tmp`);
  fs.writeFileSync(временный, JSON.stringify(данные));
  fs.renameSync(временный, path.join(папка, имя));
}

/** Сохранённый снимок `{запрошено, поДень, строки}` или `null`: нет или испорчен — как не было. */
export function прочитатьСнимок(repo) {
  const снимок = прочитать(path.join(папкаПросмотров(repo), СНИМОК));
  return снимок && typeof снимок.поДень === 'string' && Array.isArray(снимок.строки) ? снимок : null;
}

/** Итог последней попытки `{когда, итог}`: `итог` — `есть` или код причины из `ga4Client.mjs`. */
export function прочитатьПопытку(repo) {
  const попытка = прочитать(path.join(папкаПросмотров(repo), ПОПЫТКА));
  return попытка && Number.isFinite(попытка.когда) ? попытка : null;
}

/** Местный день `YYYYMMDD` момента `когда`. */
export function деньМестный(когда) {
  const д = new Date(когда);
  return `${д.getFullYear()}${String(д.getMonth() + 1).padStart(2, '0')}${String(д.getDate()).padStart(2, '0')}`;
}

/**
 * Пора ли спрашивать Google. Нет — если сегодня снимок уже получен или последняя попытка (удачная
 * или нет) была меньше `паузаЧасов` назад: данные GA4 обновляются раз в сутки, а частые запросы
 * сжигают суточный предел ресурса без новых чисел.
 */
export function пораСпросить({снимок, попытка, сейчас, паузаЧасов}) {
  if (снимок && деньМестный(Date.parse(снимок.запрошено)) === деньМестный(сейчас)) return false;
  if (попытка && сейчас - попытка.когда < паузаЧасов * 3600 * 1000) return false;
  return true;
}

/**
 * Занять право спросить Google. `true` — занято этим экземпляром; `false` — спрашивает другой.
 * Брошенная отметка (экземпляр упал посреди запроса) старше `срокМс` снимается.
 */
export function занять(repo, срокМс, сейчас = Date.now()) {
  const папка = папкаПросмотров(repo);
  const файл = path.join(папка, ЗАХВАТ);
  fs.mkdirSync(папка, {recursive: true});
  for (let попытка = 0; попытка < 2; попытка += 1) {
    try {
      fs.writeFileSync(файл, String(сейчас), {flag: 'wx'});
      return true;
    } catch (error) {
      if (error?.code !== 'EEXIST') return false;
      // Возраст — по времени, записанному в самой отметке, теми же часами, что и `сейчас`.
      // Пустая или испорченная отметка (её только что создают или запись оборвалась) судится по
      // времени файла: иначе оборванная запись заперла бы запросы навсегда.
      let возраст;
      try {
        const занята = Number(fs.readFileSync(файл, 'utf8'));
        возраст = занята > 0 ? сейчас - занята : Date.now() - fs.statSync(файл).mtimeMs;
      } catch {
        continue;
      }
      if (!(возраст >= срокМс)) return false;
      try {
        fs.rmSync(файл, {force: true});
      } catch {
        return false;
      }
    }
  }
  return false;
}

/** Записать итог захода и освободить право спросить. Удачный заход кладёт и новый снимок. */
export function завершить(repo, {когда, итог, снимок}) {
  const папка = папкаПросмотров(repo);
  try {
    if (снимок) записать(папка, СНИМОК, снимок);
    записать(папка, ПОПЫТКА, {когда, итог});
  } finally {
    fs.rmSync(path.join(папка, ЗАХВАТ), {force: true});
  }
}
