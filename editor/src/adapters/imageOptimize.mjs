// Конвертер картинок — единственный алгоритм обработки картинок сайта (решение владельца 2026-09-16).
// Здесь живёт библиотека обработки; правила — в ядре (`core/imagePolicy.mjs`), порода — там же
// (`core/imageType.mjs`). Основа — проверенный на живых картинках владельца код 2026-08-20 (архив
// `b0205304`), теперь вызываемый из «Доработать», а не при вставке.
//
// Работа идёт целиком в памяти и заканчивается ДО первой записи на диск: падение декодера не должно
// оставить ни половины файла, ни хвоста в служебной папке, ни правки в статье.

import {выигрышСтоитЗамены, килобайты, палитраГодится, рецепты} from '../core/imagePolicy.mjs';
import {типКартинки} from '../core/imageType.mjs';

/** Мегапиксель — миллион точек. Техническая величина формата, а не настройка (SPEC 4.4). */
const В_МЕГАПИКСЕЛЕ = 1e6;

/**
 * Библиотека грузится один раз и лениво: она нативная, и её загрузка стоит времени. `null` —
 * загрузить не удалось (программу перенесли без установки, установка оборвалась). Это состояние
 * машины, а не беда человека.
 */
let обработчик;

/**
 * Обработка идёт по одной за раз. Каждая держит в памяти распакованную картинку целиком —
 * несколько разом на слабой машине съели бы всю память и уронили программу вместе с работой
 * человека в окне.
 */
let очередь = Promise.resolve();

/** Есть ли на этой машине библиотека обработки. Спрашивается до всякой работы с файлами. */
export async function обработкаДоступна() {
  return (await библиотека()) !== null;
}

/**
 * Привести одну неподвижную картинку к стандарту сайта. `род` — `png`, `jpg` или `webp`, узнанный
 * по байтам зовущим. Возвращает одно из трёх:
 *
 * - `{итог: 'заменить', байты, род, было, стало}` — новые байты легче или картинку нужно было
 *   привести к стандарту;
 * - `{итог: 'оставить', причина: 'выигрышМал', было, лучший, лучшийРод}` — узкая картинка, у которой
 *   ни одно качественное представление не дало заметного выигрыша: файл человека остаётся как был;
 * - `{итог: 'отказ', причина: 'картинкаНеОбработалась'}` — файл не читается или непомерен; решает
 *   человек, остальные картинки операции это не останавливает.
 *
 * Библиотеки нет — бросает: без неё выбрать лучшее представление нечем, и зовущий обязан остановить
 * всю операцию до первой записи, а не выдать нетронутые файлы за обработанные.
 */
export async function подготовитьКартинку({bytes, род, settings}) {
  const sharp = await библиотека();
  if (sharp === null) throw new Error('библиотека обработки картинок не загружена');

  return поочерёдно(() => обработать({bytes, род, sharp, settings}));
}

/**
 * Пересборка картинки: приведение к ширине страницы и качественные представления, из которых
 * берётся самое лёгкое. Всё в памяти.
 */
async function обработать({bytes, род, sharp, settings}) {
  const правила = settings['картинки'];
  const было = bytes.length;

  let свойства;
  try {
    свойства = await читатель(sharp, bytes, правила).metadata();
  } catch {
    // Заголовок не читается или картинка непомерна: файл не тот, за кого себя выдаёт.
    return {итог: 'отказ', причина: 'картинкаНеОбработалась'};
  }

  // Страховка за разбором байтов: многокадровую картинку (анимированный WebP или PNG) декодер свёл бы
  // к первому кадру, и на сайт молча ушла бы застывшая картинка. Такая остаётся как была.
  if ((свойства.pages ?? 1) > 1) return {итог: 'оставить', причина: 'анимация'};

  const узкая = ширинаПоказа(свойства) <= правила['ширинаПикселей'];
  const прозрачная = await естьПрозрачность({bytes, sharp, правила, свойства});

  let кандидаты;
  try {
    кандидаты = await приготовить({bytes, sharp, правила, прозрачная, настройки: settings});
  } catch {
    return {итог: 'отказ', причина: 'картинкаНеОбработалась'};
  }

  const лучший = кандидаты.reduce((а, б) => (б.bytes.length < а.bytes.length ? б : а));
  // Библиотеке верят на слово ровно до этого места: то, что она вернула, обязано быть целой
  // картинкой того рода, который заказан. Иначе на диск легла бы ссылка на файл, который не откроется.
  if (типКартинки(лучший.bytes) !== лучший.формат) return {итог: 'отказ', причина: 'картинкаНеОбработалась'};

  // Картинку шире страницы и WebP менять надо в любом случае: правило ширины от веса не зависит,
  // а WebP форматом результата на сайте не бывает. Узкую PNG или JPG меняем только ради заметного
  // выигрыша — перекодировать ради процента незачем, и именно это делает повтор бездейственным.
  const обязательно = !узкая || род === 'webp';
  const стоит = обязательно
    || выигрышСтоитЗамены({былоБайт: было, сталоБайт: лучший.bytes.length, настройки: settings});

  if (!стоит) {
    return {
      итог: 'оставить',
      причина: 'выигрышМал',
      было: килобайты(было),
      лучший: килобайты(лучший.bytes.length),
      лучшийРод: лучший.формат,
    };
  }

  return {
    итог: 'заменить',
    байты: лучший.bytes,
    род: лучший.формат,
    было: килобайты(было),
    стало: килобайты(лучший.bytes.length),
  };
}

/**
 * Приготовить представления картинки по рецептам ядра. Каждое считается ОТ ИСХОДНЫХ БАЙТОВ, а не
 * от соседнего представления: пережимать уже пережатое значит терять качество дважды.
 */
async function приготовить({bytes, sharp, правила, прозрачная, настройки}) {
  const готовые = [];

  for (const рецепт of рецепты({прозрачная, настройки})) {
    const шаг = кШиринеСтраницы({bytes, sharp, правила});
    const байты = await закодировать(шаг, рецепт);

    // PNG с палитрой проверяется по качеству: на плавных цветных переходах он даёт зерно и полосы.
    // Не годится — его место занимает PNG без потерь, и выбор по весу идёт уже между честными вариантами.
    if (рецепт.формат === 'png') {
      const близостьДб = await близость({sharp, bytes, правила, результат: байты});
      if (!палитраГодится({близостьДб, настройки})) {
        готовые.push({формат: 'png', bytes: await кШиринеСтраницы({bytes, sharp, правила}).png({compressionLevel: 9, adaptiveFiltering: true}).toBuffer()});
        continue;
      }
    }

    готовые.push({формат: рецепт.формат, bytes: байты});
  }

  return готовые;
}

/**
 * Насколько приготовленная картинка близка к исходнику, приведённому к ширине страницы: отношение
 * сигнала к шуму в децибелах (чем больше, тем ближе; одинаковые — бесконечность). Цвет каждой точки
 * умножается на её непрозрачность: невидимые точки на качество не влияют. Канал прозрачности
 * сравнивается наравне с цветом — ступеньки у мягкой тени тоже заметны глазу.
 */
async function близость({sharp, bytes, правила, результат}) {
  const эталон = await кШиринеСтраницы({bytes, sharp, правила}).ensureAlpha().raw().toBuffer();
  const проверяемый = await читатель(sharp, результат, правила).ensureAlpha().raw().toBuffer();
  if (эталон.length !== проверяемый.length) return 0;

  let сумма = 0;
  for (let i = 0; i < эталон.length; i += 4) {
    const а = эталон[i + 3] / 255;
    const б = проверяемый[i + 3] / 255;
    for (let k = 0; k < 3; k += 1) {
      const разница = эталон[i + k] * а - проверяемый[i + k] * б;
      сумма += разница * разница;
    }
    const разницаПрозрачности = эталон[i + 3] - проверяемый[i + 3];
    сумма += разницаПрозрачности * разницаПрозрачности;
  }

  const среднее = сумма / эталон.length;
  return среднее === 0 ? Infinity : 10 * Math.log10((255 * 255) / среднее);
}

/** Одно представление картинки по своему рецепту. Формат задаёт рецепт, а не имя файла. */
function закодировать(шаг, рецепт) {
  if (рецепт.формат === 'png') {
    return шаг.png({
      palette: true,
      quality: рецепт.качество,
      effort: рецепт.усилие,
      dither: рецепт.размывка,
      compressionLevel: 9,
    }).toBuffer();
  }

  // `mozjpeg` включает разом всё, что бережёт края букв: сглаживание звона, оптимизацию таблиц
  // и послойную запись. Полная цветность — чтобы не расплывались цветные подписи на снимках.
  return шаг.jpeg({
    quality: рецепт.качество,
    mozjpeg: true,
    progressive: true,
    chromaSubsampling: '4:4:4',
  }).toBuffer();
}

/**
 * Приведение к ширине страницы: поворот по метке камеры, приведение цвета к `sRGB` и сам размер.
 *
 * Ограничивается ТОЛЬКО ширина. Высота свободна: у вертикальной схемы ограничение по высоте ужимало
 * бы и ширину, а вместе с ней — мелкий текст, который человек как раз и хотел показать. Уменьшение —
 * `lanczos3` без быстрой предварительной ужимки: на снимках экрана мелкий текст и тонкие рамки от неё
 * покрываются рябью.
 */
function кШиринеСтраницы({bytes, sharp, правила}) {
  return читатель(sharp, bytes, правила)
    .autoOrient()
    .toColourspace('srgb')
    .resize({
      width: правила['ширинаПикселей'],
      fit: 'inside',
      withoutEnlargement: true,
      kernel: 'lanczos3',
      fastShrinkOnLoad: false,
    });
}

/**
 * Есть ли у картинки настоящая прозрачность. Одного канала альфы мало: редакторы (например, Figma)
 * кладут его и в полностью непрозрачные снимки, и по такому признаку программа зря отказывалась бы
 * от JPG — самого лёгкого представления для фотографического материала.
 *
 * Смотрится сам канал: прозрачна картинка только тогда, когда хоть одна точка не полностью
 * непрозрачна. Не прочиталось — считаем прозрачной: терять прозрачность опаснее, чем вес.
 */
async function естьПрозрачность({bytes, sharp, правила, свойства}) {
  if (свойства.hasAlpha !== true) return false;

  try {
    return (await читатель(sharp, bytes, правила).stats()).isOpaque !== true;
  } catch {
    return true;
  }
}

/**
 * Ширина такой, какой её увидит читатель. У снимка с телефона в файле записана метка поворота,
 * и ширина с высотой в нём стоят наоборот: без учёта метки правило ширины решало бы про лежащую
 * на боку картинку.
 */
function ширинаПоказа(свойства) {
  const ширина = свойства.width ?? 0;
  const высота = свойства.height ?? 0;
  // Метки 5–8 означают поворот на четверть: стороны меняются местами.
  return (свойства.orientation ?? 1) >= 5 ? высота : ширина;
}

/**
 * Чтение картинки под общими заслонами: предел размера в точках и предел времени на шаг. Без них
 * непомерная картинка заняла бы память и время в обход настроек.
 */
function читатель(sharp, bytes, правила) {
  return sharp(bytes, {limitInputPixels: правила['пределМегапикселей'] * В_МЕГАПИКСЕЛЕ})
    .timeout({seconds: правила['пределОбработкиСекунд']});
}

/** Загрузка библиотеки обработки. `null` — её на этой машине нет, и это не беда человека. */
async function библиотека() {
  if (обработчик !== undefined) return обработчик;

  try {
    const модуль = await import('sharp');
    // Загрузка без ошибки ещё не значит, что библиотека есть: оборванная установка оставляет пустой
    // модуль, и программа приняла бы пустоту за рабочий кодировщик.
    обработчик = typeof модуль.default === 'function' ? модуль.default : null;
  } catch {
    обработчик = null;
  }

  return обработчик;
}

/** Пропустить работу через общую очередь: разом идёт только одна распакованная картинка. */
function поочерёдно(работа) {
  const итог = очередь.then(работа, работа);
  // Очередь помнит только очередь: ошибка одной работы не должна ронять следующую.
  очередь = итог.then(() => undefined, () => undefined);
  return итог;
}

/**
 * Подмена библиотеки для проверок: без неё поведение «библиотеки нет» не воспроизвести на машине,
 * где она установлена. В работе программы не зовётся.
 */
export function подменитьБиблиотекуДляПроверки(значение) {
  обработчик = значение;
}
