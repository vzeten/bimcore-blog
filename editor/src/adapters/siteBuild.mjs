// Полная сборка сайта — окончательная защитная проверка перед публикацией.
//
// Дочерний процесс запускается **самим `node`, без оболочки и прямым путём к сборщику**: строка,
// уходящая в оболочку, зависит от того, какая оболочка стоит у человека, и от пробелов в пути.
// Ключа `--locale` нет намеренно: `docusaurus build` без него собирает все известные локали сайта
// (`en`, `ru`, `es`), а второй перечень языков в программе разошёлся бы с конфигом сайта молча.
//
// **Собираемое дерево и дерево зависимостей — разные доводы.** Сборка плана идёт по временной копии
// сайта, а зависимости у неё свои не заводятся: они берутся из настоящего корня проекта, как их и
// берёт сам Node, поднимаясь по дереву папок. Поэтому сборщик ищется в названном корне зависимостей,
// а не рядом с собираемыми файлами.
//
// **Зависимости проверяются прямо здесь, вторым рубежом.** Первый стоит раньше, до создания копии;
// этот нужен потому, что между проверкой и запуском проходит время, а запуск сборщика без своих
// зависимостей даёт человеку чужой текст про ненайденный модуль вместо понятного отказа.
//
// Сборка ничего не решает и ничего не пишет в статьи: её дело — упасть там, где упал бы сайт.
// Складывает она собранный сайт в свою обычную папку, которая и так не уезжает в репозиторий.

import {execFile} from 'node:child_process';

import {проверитьЗависимости, путьСборщика, средаБезNODE_PATH} from './rootDeps.mjs';

export {путьСборщика};

/**
 * Запустить полную сборку. Возвращает `{зелёная, код, вывод, времяМс, оборвана}`, а при негодных
 * корневых зависимостях — `{зелёная: false, зависимости: {ошибка, подробность}}` без запуска.
 *
 * `запуск` подменяется в проверках: настоящая сборка идёт минутами, и гонять её в машинных
 * проверках значило бы получить набор, которого никто не дожидается.
 *
 * Дочерний процесс всегда завершается: по своему концу или по пределу времени, и второй случай —
 * честный ответ «сборка не уложилась», а не тишина.
 */
export async function собратьСайт({repo, кореньЗависимостей = repo, пределМинут, запуск = execFile}) {
  const начало = Date.now();
  const предел = Math.max(1, Number(пределМинут) || 1) * 60 * 1000;

  // Своих зависимостей нет — сборщик не запускается вовсе. Ответ отдельным полем, а не красной
  // сборкой: «сайт не собрался» и «собирать было нечем» — разные беды и чинятся по-разному.
  const зависимости = проверитьЗависимости(кореньЗависимостей);
  if (зависимости.ошибка) {
    return {зелёная: false, код: 0, оборвана: false, вывод: '', времяМс: 0, зависимости};
  }

  return new Promise((resolve) => {
    const ребёнок = запуск(
      process.execPath,
      [путьСборщика(кореньЗависимостей), 'build'],
      {
        cwd: repo,
        timeout: предел,
        maxBuffer: 64 * 1024 * 1024,
        windowsHide: true,
        // `NODE_PATH` убирается у дочернего процесса: с ним сборка добрала бы недостающее в чужом
        // дереве и зелёным итогом доказала бы работоспособность соседа, а не этого проекта.
        env: средаБезNODE_PATH(process.env),
      },
      (ошибка, stdout, stderr) => {
        const вывод = `${stdout ?? ''}${stderr ?? ''}`;
        // Убит по пределу времени — это находка, а не зелёная сборка и не молчание.
        const оборвана = Boolean(ошибка) && (ошибка.killed === true || ошибка.signal !== null && ошибка.signal !== undefined);

        resolve({
          зелёная: !ошибка,
          код: ошибка?.code ?? 0,
          оборвана,
          вывод,
          времяМс: Date.now() - начало,
        });
      },
    );

    // Ребёнок не запустился вовсе (нет node, нет прав) — это тоже ответ, а не зависание.
    ребёнок?.on?.('error', () => {});
  });
}

/**
 * Короткая причина падения для человека: последние значащие строки вывода сборщика.
 * Полный вывод при этом сохраняется целиком — разбирать чужой вывод в структурные находки
 * программа не берётся (отказ записан в `TASKS.md`, задание З2).
 */
export function причинаПадения(вывод, строк = 12) {
  return String(вывод ?? '')
    .split(/\r?\n/)
    .map((строка) => строка.trimEnd())
    .filter((строка) => строка.trim() !== '')
    .slice(-строк)
    .join('\n');
}
