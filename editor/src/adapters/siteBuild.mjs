// Полная сборка сайта — окончательная защитная проверка перед публикацией.
//
// Дочерний процесс запускается **самим `node`, без оболочки и прямым путём к сборщику**: строка,
// уходящая в оболочку, зависит от того, какая оболочка стоит у человека, и от пробелов в пути.
// Ключа `--locale` нет намеренно: `docusaurus build` без него собирает все известные локали сайта
// (`en`, `ru`, `es`), а второй перечень языков в программе разошёлся бы с конфигом сайта молча.
//
// Сборка ничего не решает и ничего не пишет в статьи: её дело — упасть там, где упал бы сайт.
// Складывает она собранный сайт в свою обычную папку, которая и так не уезжает в репозиторий.

import {execFile} from 'node:child_process';
import path from 'node:path';

/** Путь к сборщику внутри репозитория. Своей копии сборщика у программы нет и быть не должно. */
export const путьСборщика = (repo) => path.join(repo, 'node_modules', '@docusaurus', 'core', 'bin', 'docusaurus.mjs');

/**
 * Запустить полную сборку. Возвращает `{зелёная, код, вывод, времяМс, оборвана}`.
 *
 * `запуск` подменяется в проверках: настоящая сборка идёт минутами, и гонять её в машинных
 * проверках значило бы получить набор, которого никто не дожидается.
 *
 * Дочерний процесс всегда завершается: по своему концу или по пределу времени, и второй случай —
 * честный ответ «сборка не уложилась», а не тишина.
 */
export async function собратьСайт({repo, пределМинут, запуск = execFile}) {
  const начало = Date.now();
  const предел = Math.max(1, Number(пределМинут) || 1) * 60 * 1000;

  return new Promise((resolve) => {
    const ребёнок = запуск(
      process.execPath,
      [путьСборщика(repo), 'build'],
      {cwd: repo, timeout: предел, maxBuffer: 64 * 1024 * 1024, windowsHide: true},
      (ошибка, stdout, stderr) => {
        const вывод = `${stdout ?? ''}${stderr ?? ''}`;
        // Убит по пределу времени — это находка, а не зелёная сборка и не молчание.
        const оборвана = Boolean(ошибка) && (ошибка.killed === true || ошибка.signal !== null && ошибка.signal !== undefined);

        resolve({
          зелёная: !ошибка,
          код: ошибка?.code ?? 0,
          оборвана,
          вывод,
          времяМс: Date.now() - начало,
        });
      },
    );

    // Ребёнок не запустился вовсе (нет node, нет прав) — это тоже ответ, а не зависание.
    ребёнок?.on?.('error', () => {});
  });
}

/**
 * Короткая причина падения для человека: последние значащие строки вывода сборщика.
 * Полный вывод при этом сохраняется целиком — разбирать чужой вывод в структурные находки
 * программа не берётся (отказ записан в `TASKS.md`, задание З2).
 */
export function причинаПадения(вывод, строк = 12) {
  return String(вывод ?? '')
    .split(/\r?\n/)
    .map((строка) => строка.trimEnd())
    .filter((строка) => строка.trim() !== '')
    .slice(-строк)
    .join('\n');
}
