// Материализация каркаса: превращение рецепта в ОКОНЧАТЕЛЬНЫЙ план — те самые байты, которые
// увидит сборка, отпечаток и хранилище.
//
// **Диск читается здесь и больше нигде.** Каждый собственный файл читается ровно один раз, и дальше
// сборка, отпечаток и укладка работают с одними и теми же байтами. Прочитай их кто-то ещё раз —
// сборка проверила бы одно содержимое, а уехало бы другое, и доказать разницу было бы нечем.
//
// **Байты у всех записей одного вида.** Каркас различает `диск` и `создано`, окончательный план —
// нет: у каждой записи `Buffer`, и зовущему не приходится доразбирать, откуда что взялось. Признак
// источника остаётся для человека и для укладки в хранилище, но на чтение байтов уже не влияет.

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

import {ДИСК, УДАЛЕНО} from '../core/publishPlan.mjs';

/**
 * Окончательный план из каркаса. Возвращает `{записи, отказ}`.
 *
 * Файл исчез или не читается между показом и материализацией — отказ, а не пропуск: план без файла
 * означал бы, что сайт соберут без него, а человеку показали обратное.
 */
export function материализовать({repo, каркас}) {
  const записи = [];

  for (const запись of каркас.записи) {
    // Уходящему с сайта пути байты не нужны и взяться им неоткуда: файла у человека больше нет.
    // Признак «байтов нет» один на всю дорогу — по нему укладка, отпечаток и сверка узнают уход.
    if (запись.источник === УДАЛЕНО) {
      записи.push({...запись, текст: undefined, байты: null});
      continue;
    }

    if (запись.источник !== ДИСК) {
      записи.push({...запись, текст: undefined, байты: Buffer.from(String(запись.текст), 'utf8')});
      continue;
    }

    let байты;
    try {
      байты = fs.readFileSync(path.join(repo, запись.путь));
    } catch {
      return {записи: [], отказ: {код: 'фактыНеизвестны', локали: [запись.локаль].filter(Boolean), чего: 'байты'}};
    }

    записи.push({...запись, текст: undefined, байты});
  }

  return {записи, отказ: null};
}

/**
 * Отпечаток плана: по нему видно, тот ли это план, который видела сборка.
 *
 * В отпечаток идёт ВСЁ, от чего зависит будущее дерево: закреплённая основа, будущий родитель и
 * каждая запись целиком — путь, назначение, локаль, режим, источник и байты. Одних байтов мало:
 * переименование, смена назначения и сдвиг основы дали бы другое дерево при тех же байтах.
 *
 * **Куски отделяются длиной, а не знаком-разделителем.** Разделитель годится, только если его нет
 * внутри кусков, а содержимое картинки двоичное: любой знак, включая нулевой байт, встречается там
 * законно. Со знаком-разделителем два разных плана дали бы один поток — то есть сборка
 * «подтвердила» бы содержимое, которого не видела.
 */
export function отпечатокПлана({основа, родитель, записи, режим}) {
  const хеш = crypto.createHash('sha1');

  кусок(хеш, Buffer.from(String(основа ?? ''), 'utf8'));
  кусок(хеш, Buffer.from(String(родитель ?? ''), 'utf8'));
  // Режим записи (снятие статьи с сайта) — свой кусок: согласие на снятие не годится для публикации
  // и наоборот. У публикации режима нет, и её отпечаток остаётся прежним.
  if (режим !== undefined) кусок(хеш, Buffer.from(`режим:${режим}`, 'utf8'));

  for (const запись of записи) {
    for (const поле of ['путь', 'назначение', 'локаль', 'режим', 'источник']) {
      кусок(хеш, Buffer.from(String(запись[поле] ?? ''), 'utf8'));
    }

    // Уход пути с сайта отмечается отдельным знаком, а не пустыми байтами: пустой файл и уход дают
    // разные деревья, и отпечаток обязан их различать.
    if (!Buffer.isBuffer(запись.байты)) {
      хеш.update('-', 'utf8');
      continue;
    }

    хеш.update('+', 'utf8');
    кусок(хеш, запись.байты);
  }

  return хеш.digest('hex');
}

/** Кусок в отпечаток: сначала длина в байтах, потом сами байты. Границу задаёт длина. */
function кусок(хеш, байты) {
  хеш.update(`${байты.length}:`, 'utf8');
  хеш.update(байты);
}
