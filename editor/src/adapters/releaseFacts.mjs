// Факты о выпуске статьи: годен ли путь, какие у статьи файлы и каково их содержимое сейчас.
//
// Один модуль на двоих: их спрашивает и показ состава со сборкой, и коммит. Посчитай коммит состав
// своим кодом — и однажды он зафиксировал бы не то, что человеку показали.

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

import {articlePlace, isUnlisted} from '../core/frontmatterRules.mjs';
import {путиДругихВерсий, файлСтатьи} from '../core/articles.mjs';
import {ИМЯ_КАТЕГОРИИ, границаСостава, видВерсии} from '../core/articleKind.mjs';
import {readField, splitArticle} from '../core/articleFile.mjs';
import {этоЗаглушка} from '../core/newArticle.mjs';
import {категорияРядом, statePath} from './library.mjs';

/**
 * Годен ли путь для выпуска. Три условия сразу: это файл статьи · он лежит в известном корне
 * контента · записан ровно так, как лежит на диске — без `..`, без `.` и без обратных косых.
 *
 * Последнее не придирка к виду: `docs/../static` указывает наружу корней контента, а строка с
 * `..` попала бы в `git add` не тем путём, под которым файл записан в репозитории.
 */
export function годныйПуть(rel, settings) {
  if (typeof rel !== 'string' || rel === '' || rel.includes('\\')) return false;
  if (rel.split('/').some((кусок) => кусок === '..' || кусок === '.' || кусок === '')) return false;
  if (!файлСтатьи(rel)) return false;

  return articlePlace(rel, settings['контент']).locale !== null;
}

/**
 * Факты о версиях статьи для правила состава. Языки берутся правилом ядра `путиДругихВерсий`,
 * а не перечнем в коде: четвёртая локаль заработает без правки программы.
 */
export function версииСтатьи(repo, rel, settings) {
  const roots = settings['контент'];

  return [rel, ...путиДругихВерсий(rel, roots)]
    .filter((путь) => файлНаМесте(repo, путь))
    .map((путь) => {
      const папка = path.posix.dirname(путь);
      const место = articlePlace(путь, roots);
      const вид = видВерсии(путь, {
        категорияРядом: категорияРядом(repo, путь, settings),
        // Файл лежит прямо в корне рода: каталога у него нет, есть весь корень.
        вКорнеРода: !место.inside.includes('/'),
        // Роль корневой страницы даёт её собственная шапка, а не имя файла.
        адресКорня: адресСтраницы(repo, путь) === '/',
      });
      const рядом = собственныеФайлы(repo, папка, вид);
      const состояние = путьСостояния(repo, путь, settings);

      return {
        путь,
        вид,
        локаль: articlePlace(путь, roots).locale,
        состояние,
        // Соседняя статья на своём уровне делает файлы общими, и чьи они — по путям не видно.
        // Считается по тем же файлам, которые вид объявил своими: у обычной статьи это весь её
        // каталог вглубь, у страницы категории — только верхний уровень, поэтому её дочерние
        // статьи, лежащие в подкаталогах, соседями не считаются и разрыва не дают. У корневой
        // страницы и записи вне канона своего каталога нет вовсе — считать не по чему.
        статейВПапке: рядом.length === 0 ? 1 : рядом.filter((файл) => файлСтатьи(файл)).length,

        файлыПапки: рядом.filter((файл) => !файлСтатьи(файл) && файл !== состояние),
      };
    });
}

/**
 * Локали, версия которых до сих пор заглушка перевода. Правило «что считать заглушкой» здесь не
 * пишется — оно там же, где заглушка создаётся; здесь только чтение файлов с диска.
 */
export function заглушкиВерсий(repo, версии, settings) {
  return (версии ?? [])
    .filter((версия) => {
      try {
        const {body} = splitArticle(fs.readFileSync(path.join(repo, версия.путь), 'utf8'));
        return этоЗаглушка(body, settings);
      } catch {
        // Прочитать не удалось — заглушкой не объявляем: догадка тут хуже молчания.
        return false;
      }
    })
    .map((версия) => версия.локаль);
}

/**
 * Локали, версия которых на сайте скрыта (в меню её нет, живёт только по прямой ссылке).
 *
 * Признак читается тем же правилом, что и везде в программе, и он доказан шапкой файла — в отличие
 * от заглушки, написанной человеком руками: такую от настоящего перевода отличить нечем, а
 * догадываться о ней программа не станет. Зато скрытость человеку про язык говорит многое.
 */
export function скрытыеВерсии(repo, версии) {
  return (версии ?? [])
    .filter((версия) => {
      try {
        const {frontmatterRaw} = splitArticle(fs.readFileSync(path.join(repo, версия.путь), 'utf8'));
        return isUnlisted(frontmatterRaw);
      } catch {
        return false;
      }
    })
    .map((версия) => версия.локаль);
}

/**
 * Отпечаток содержимого состава: по нему видно, тот ли это текст, который видела сборка.
 * Считается по путям И по байтам: переименование, правка и пропажа файла обязаны его менять.
 *
 * **Куски отделяются длиной, а не знаком-разделителем.** Разделитель годится, только если его нет
 * внутри кусков, а внутри тут бывает что угодно: содержимое картинки — двоичное, и любой знак,
 * включая нулевой байт, встречается в нём законно. Со знаком-разделителем один файл с телом
 * `NUL b NUL` дал бы тот же поток, что два пустых файла `a` и `b`, — разные составы с одним
 * отпечатком, то есть сборка «подтвердила» бы содержимое, которого не видела. Перед каждым куском
 * пишется его длина в байтах, поэтому разбор потока однозначен, а сам поток остаётся без
 * управляющих знаков — и исходник этого файла остаётся обычным текстом, читаемым в отличиях.
 */
export function отпечатокСостава(repo, файлы) {
  const хеш = crypto.createHash('sha1');

  for (const файл of файлы) {
    кусок(хеш, Buffer.from(файл.путь, 'utf8'));

    let тело = null;
    try {
      тело = fs.readFileSync(path.join(repo, файл.путь));
    } catch {
      тело = null;
    }

    // Файл исчез между показом и сверкой — это тоже изменение, и отпечаток обязан разойтись.
    // Признак пишется отдельным знаком, а не текстом-заменителем: файл, чьё содержимое совпало бы
    // с таким текстом, иначе выглядел бы как пропавший.
    if (тело === null) {
      хеш.update('-', 'utf8');
      continue;
    }

    хеш.update('+', 'utf8');
    кусок(хеш, тело);
  }

  return хеш.digest('hex');
}

/** Кусок в отпечаток: сначала длина в байтах, потом сами байты. Границу задаёт длина. */
function кусок(хеш, байты) {
  хеш.update(`${байты.length}:`, 'utf8');
  хеш.update(байты);
}

/**
 * Собственные файлы версии — по её виду, а не по именам файлов.
 * Обычная статья владеет своим каталогом целиком и вглубь; страница категории — только файлами
 * верхнего уровня своего каталога, без `_category_.json` и без дочерних каталогов; запись вне
 * канона собственных файлов не имеет вовсе — её каталог принадлежит не ей.
 */
function собственныеФайлы(repo, папка, вид) {
  const граница = границаСостава(вид);
  // «Нечего» — состав не доказан вовсе; «толькоФайл» — корневая страница, у неё собственный файл
  // один, она сама, и его состав добавляет отдельным правилом.
  if (граница === 'нечего' || граница === 'толькоФайл') return [];
  if (граница === 'верхнийУровень') {
    return верхнийУровень(repo, папка).filter((файл) => !файл.endsWith(`/${ИМЯ_КАТЕГОРИИ}`));
  }

  return файлыПапки(repo, папка);
}

/** Файлы верхнего уровня каталога: вложенные папки не обходятся — они чужие. */
function верхнийУровень(repo, папка) {
  try {
    return fs.readdirSync(path.join(repo, папка), {withFileTypes: true})
      .filter((вход) => вход.isFile())
      .map((вход) => `${папка}/${вход.name}`)
      .sort();
  } catch {
    return [];
  }
}

/** Адрес из шапки версии. Прочитать не удалось — считаем, что своего адреса нет. */
function адресСтраницы(repo, rel) {
  try {
    const {frontmatterRaw} = splitArticle(fs.readFileSync(path.join(repo, rel), 'utf8'));
    return String(readField(frontmatterRaw, 'slug') ?? '').trim().replace(/^["']|["']$/g, '');
  } catch {
    return '';
  }
}

/** Файл ли это на самом деле: папка с именем статьи составом не считается. */
function файлНаМесте(repo, rel) {
  try {
    return fs.statSync(path.join(repo, rel)).isFile();
  } catch {
    return false;
  }
}

/**
 * Все файлы папки версии, **включая вложенные папки**. Картинки статей часто лежат в отдельной
 * папке рядом с текстом — у живой статьи блога их там тридцать на язык. Обойди программа только
 * верхний уровень, и статья уехала бы в коммит без своих картинок, а сборка при этом осталась бы
 * зелёной: файлы-то на диске лежат. Молчаливая потеря хуже отказа.
 *
 * Обход библиотеки (`walk`) здесь не годится: он отдаёт только файлы статей — картинок в его
 * ответе нет по его же контракту, и позвать его значило бы потерять ровно то, что ищем.
 */
function файлыПапки(repo, папка) {
  const обход = (папкаНаДиске, накопитель = []) => {
    for (const вход of fs.readdirSync(папкаНаДиске, {withFileTypes: true})) {
      const полный = path.join(папкаНаДиске, вход.name);
      if (вход.isDirectory()) обход(полный, накопитель);
      else if (вход.isFile()) накопитель.push(полный);
    }

    return накопитель;
  };

  try {
    return обход(path.join(repo, папка))
      .map((файл) => path.relative(path.join(repo, папка), файл).split(path.sep).join('/'))
      .map((имя) => `${папка}/${имя}`)
      .sort();
  } catch {
    return [];
  }
}

/** Путь файла состояния версии — правилом библиотеки; нет на диске, значит и в составе его нет. */
function путьСостояния(repo, rel, settings) {
  const полный = statePath(repo, rel, settings);
  if (!fs.existsSync(полный)) return null;

  return path.relative(repo, полный).split(path.sep).join('/');
}
