// Замок публикации: пока идёт запись или отправка, второй такой же заход не начинается.
//
// **Одного «индекс обязан быть пуст» мало.** Два запроса, пришедшие почти одновременно, оба увидят
// пустой индекс, оба начнут в него укладывать, и в коммит уедет смесь двух планов. Тем же способом
// они перезапишут друг другу временный файл очереди — и происхождение коммита перестанет быть
// доказанным.
//
// Замок один на сервер и охватывает весь опасный участок: сверку, укладку, коммит, сдвиг ветки,
// запись происхождения и отправку. Признак, а не очередь ожидания: второй заход получает честный
// отказ, а не молча ждёт неизвестно чего.

let занято = false;

/** Взять замок. `false` — он уже у кого-то, и звать опасную работу нельзя. */
export function взятьЗамок() {
  if (занято) return false;
  занято = true;

  return true;
}

/** Отпустить замок. Зовётся только в `finally` того же захода, который его взял. */
export function отпустить() {
  занято = false;
}

/** Идёт ли опасная работа прямо сейчас. Нужен проверкам: подглядывать за замком иначе нечем. */
export const замокВзят = () => занято;
