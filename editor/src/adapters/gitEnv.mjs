// Единственная дверь программы к git и единственное место, где чистится её среда.
//
// **Почему среду вообще приходится чистить.** Библиотека доступа к git отказывается запускаться,
// если в переданной ей среде есть переменная, способная подсунуть git чужую команду или чужие
// настройки: редактор, постраничный просмотрщик, спрашивалку пароля, подменённый файл настроек,
// внешнюю программу сравнения. Отказ приходит не там, где переменная стоит, а на первой же команде
// такой двери, и выглядит поломкой программы: у человека с `GIT_PAGER` в среде укладка плана
// публикации падала на `read-tree`, хотя ни к чему из этого отношения не имела.
//
// **Чинить это в команде запуска нельзя.** Программу запускают из разных мест — из ярлыка, из
// оболочки, из окна разработчика, — и среда там своя у каждого. Правило живёт внутри программы, и
// тогда оно действует везде.
//
// **Чистка — не только про запуск.** Переменные вроде `GIT_CONFIG_GLOBAL` и `GIT_EXTERNAL_DIFF`
// меняют сами ответы git, а на этих ответах держатся основа публикации, состав, происхождение
// коммита и решение об отправке. Поэтому дверью пользуются все чтения программы, а не одна укладка.

import path from 'node:path';
import {simpleGit} from 'simple-git';

/**
 * Имена, которых в среде git-команд быть не должно.
 *
 * Перечень взят у самой библиотеки (`@simple-git/argv-parser`) и назван здесь целиком, а не
 * вычислен из неё: её внутреннее устройство — не договор, и молчаливая смена этого списка при
 * обновлении зависимости прошла бы мимо проверок. Рядом `VISUAL`: сама библиотека его не ловит, но
 * git по нему открывает редактор, а редактор в программе без консоли — это зависание навсегда.
 *
 * Сравнение идёт в нижнем регистре: в Windows имена переменных регистр не различают, и `Git_Pager`
 * дошёл бы до git ровно так же, как `GIT_PAGER`.
 */
export const ЗАПРЕЩЁННЫЕ = [
  'editor', 'visual',
  'git_editor', 'git_sequence_editor',
  'pager', 'git_pager',
  'git_askpass', 'ssh_askpass',
  'git_ssh', 'git_ssh_command',
  // Имена ПОДМЕНЫ НАСТРОЕК. `GIT_CONFIG_PARAMETERS` — самое опасное из них: git читает оттуда
  // готовые пары `ключ=значение` и ставит их выше всех файлов настроек. Одной такой переменной
  // подменяется `remote.origin.pushurl`, и отправка уезжает по чужому адресу, а программа при этом
  // честно рапортует об успехе. `GIT_CONFIG_NOSYSTEM` рядом: он не подставляет своё, но убирает
  // общесистемные настройки, на которых у человека может держаться связь с сервером сайта.
  'git_config', 'git_config_global', 'git_config_system', 'git_config_count',
  'git_config_parameters', 'git_config_nosystem',
  'git_exec_path', 'git_external_diff', 'git_proxy_command', 'git_template_dir',
  'prefix',
  // Имя не из git-именника, но опаснее многих: по нему библиотека связи выкладывает в файл секреты
  // сеанса TLS. Сама отправка при этом уходит куда надо и выглядит успешной, а перехваченный
  // разговор с сервером сайта потом расшифровывается целиком. Своего назначения в программе у него
  // нет никакого.
  'sslkeylogfile',
  // Имена МЕСТА. Их нет в перечне библиотеки, и они опаснее всех прочих: `GIT_DIR` уводит каждое
  // чтение, запись и отправку в чужой репозиторий, а унаследованный `GIT_INDEX_FILE` подсовывает
  // посторонний индекс проверке «индекс пуст» — после которой программа заменяет настоящий индекс
  // человека. Свой индекс укладка плана назначает себе сама, отдельной дверью и абсолютным путём.
  'git_dir', 'git_work_tree', 'git_common_dir',
  'git_object_directory', 'git_alternate_object_directories',
  'git_namespace', 'git_ceiling_directories', 'git_discovery_across_filesystem',
  'git_index_file', 'git_index_version',
];

/**
 * Что из этого следует и о чём надо знать. Подмена, заданная ПЕРЕМЕННОЙ СРЕДЫ, для команд программы
 * не действует: связь по `GIT_SSH_COMMAND`, спрашивалка пароля и подставленный файл настроек. Обычные
 * настройки git при этом читаются как всегда — убираются только переменные-подмены. Иначе нельзя:
 * библиотека с такой переменной не запускается вовсе, и выбор стоит не между «с ней и без неё», а
 * между «программа работает» и «первая же команда падает». Настройки связи поэтому должны жить в
 * обычных настройках git и SSH, а не в среде запуска.
 */

/**
 * ГРАНИЦА ДОВЕРИЯ: имена, которые остаются в среде НАМЕРЕННО, и почему обещание «никакая переменная
 * не уведёт отправку» было бы неправдой.
 *
 * Все они описывают не подмену, а самого человека и его машину. `PATH` — где лежит сам git;
 * `HOME`, `HOMEDRIVE`, `HOMEPATH`, `USERPROFILE` и `XDG_CONFIG_HOME` — где лежат ЕГО СОБСТВЕННЫЕ
 * настройки git: имя автора, ключи, помощник пароля, адрес сервера сайта. Вычеркни их — и программа
 * перестанет находить git либо потеряет учётные данные человека, то есть сломается на ровном месте
 * у всех.
 *
 * `HOMEDRIVE` и `HOMEPATH` названы отдельно не для полноты списка: в Windows именно они и работают.
 * `HOME` там обычно пуст вовсе, и git собирает домашний каталог из этой пары, а `USERPROFILE`
 * спрашивает следом. Забудь их — и перечень выглядел бы полным, оставаясь дырявым ровно на той
 * системе, где программа и живёт.
 *
 * Из этого прямо следует: тот, кто задаёт среду запуска программы, может увести отправку. Через
 * `HOME` он подставит свой файл настроек с чужим `remote.origin.pushurl`; через `PATH` — и вовсе
 * свою программу вместо git, после чего никакая чистка среды уже ничего не решает. Граница проходит
 * здесь, и обойти её нельзя в принципе: программа обязана пользоваться профилем человека.
 *
 * Поэтому вычеркивается ВЕСЬ git-именник (см. `ПРОСТРАНСТВО_GIT`) и названные поимённо чужие
 * переменные-подмены. Всё прочее — общие имена машины: `TEMP`, `SYSTEMROOT`, языки, адрес
 * посредника сети. Их не трогают намеренно: без них git не работает, а увести отправку они сами по
 * себе не могут — проверка сертификата остаётся включённой, потому что снимающая её переменная
 * живёт как раз в git-именнике и до git не доходит.
 *
 * Вычеркнуты и пространства САМИХ БИБЛИОТЕК связи (см. `ЗАПРЕЩЁННЫЕ_НАЧАЛА`): git загружает libcurl
 * и OpenSSL в свой процесс, и их имена начинаются не с `GIT_`. Рядом одно имя поимённо —
 * `SSLKEYLOGFILE`: по нему библиотека связи выкладывает секреты сеанса TLS в файл, и адрес отправки
 * при этом верный, отправка успешна, а расшифровывается потом перехваченный разговор.
 *
 * Посредник сети остаётся: он законен, задаётся не для подмены, и без снятой проверки сертификата
 * и без подменённых корней доверия сервер сайта не подменяет.
 *
 * Этот перечень — НЕ фильтр: он называет то, что остаётся намеренно и с объяснением, и потому не
 * должен молча вырасти. Человеку обещание говорится узко: среда не подменяет НАСТРОЙКИ команды,
 * а не «не может увести программу никуда».
 */
export const ГРАНИЦА_ДОВЕРИЯ = [
  'path', 'home', 'homedrive', 'homepath', 'userprofile', 'xdg_config_home',
];

/**
 * ГЛАВНОЕ ПРАВИЛО: из среды уходит ВЕСЬ git-именник, а не перечисленные имена.
 *
 * Перечень выше — чёрный список, и жил он ровно до первого имени, о котором забыли подумать. А
 * забыть есть о чём: `GIT_SSL_NO_VERIFY` снимает проверку сертификата при отправке, `GIT_SSL_CAINFO`
 * подменяет доверенные корни — обе не подменяют настройки команды и в прежний перечень не попадали,
 * зато обе открывают дорогу чужому серверу под видом своего. Держись защита на памяти о каждом
 * будущем имени — она держалась бы недолго.
 *
 * Своих переменных этого пространства программе не нужно НИ ОДНОЙ: единственную, которая ей нужна
 * по делу, — `GIT_INDEX_FILE` — она назначает себе сама, отдельной дверью и после чистки. Поэтому
 * правило простое и полное: имя начинается на `GIT_` — оно до git не доходит.
 *
 * Перечень имён при этом не выброшен: он остаётся названным и объяснённым подмножеством — и потому,
 * что часть опасных имён (`EDITOR`, `PAGER`, `VISUAL`, `SSH_ASKPASS`, `PREFIX`) в это пространство
 * не входит вовсе.
 */
export const ПРОСТРАНСТВО_GIT = 'git_';

/**
 * Запрещённые НАЧАЛА имён вне git-именника: пространства библиотек, которыми git и разговаривает
 * с сервером сайта.
 *
 * Git не делает связь сам — он загружает в свой процесс libcurl и OpenSSL, а у тех свои имена, и
 * `GIT_` в них нет. Через `OPENSSL_CONF` настройка велит OpenSSL загрузить названный ею модуль,
 * то есть чужой код прямо в процесс git; `SSL_CERT_FILE` и `SSL_CERT_DIR` подменяют корни доверия,
 * после чего чужой сервер предъявляет «правильный» сертификат; `CURL_SSL_BACKEND` и `CURL_CA_BUNDLE`
 * меняют, чем и чему верить при отправке.
 *
 * Правило снова взято КЛАССОМ, а не именами: у этих библиотек имён много, они пополняются, и список
 * жил бы до первого забытого. Своё доверенное хранилище задаётся обычной настройкой git
 * (`http.sslCAInfo`) — там же, где живут остальные настройки связи, и по тому же правилу: среда
 * запуска настроек не задаёт.
 */
export const ЗАПРЕЩЁННЫЕ_НАЧАЛА = ['openssl_', 'curl_', 'ssl_cert_'];

const запрещено = new Set(ЗАПРЕЩЁННЫЕ);

/**
 * Среда для git: копия данной среды без запрещённых имён.
 *
 * Исходная среда не меняется ни одним байтом — правится копия: `process.env` принадлежит всему
 * процессу, и вычеркнуть из него переменную значило бы поменять поведение всей программы.
 * Всё остальное сохраняется как есть, включая названные в `ГРАНИЦА_ДОВЕРИЯ`: без них git не
 * найдётся или потеряет собственные настройки человека.
 */
export function средаДляGit(среда = process.env) {
  const копия = {};

  for (const [ключ, значение] of Object.entries(среда)) {
    const имя = ключ.toLowerCase();
    // Пространство целиком — первым: перечень имён после него лишь называет и объясняет часть.
    if (имя.startsWith(ПРОСТРАНСТВО_GIT)) continue;
    if (запрещено.has(имя)) continue;
    if (ЗАПРЕЩЁННЫЕ_НАЧАЛА.some((начало) => имя.startsWith(начало))) continue;
    if (значение === undefined) continue;
    копия[ключ] = String(значение);
  }

  return копия;
}

/**
 * Обычная дверь к git: чистая среда и ничего сверх неё.
 *
 * Общей добавки у этой двери нет намеренно. Была она — и любой зовущий мог бы вернуть в среду
 * `GIT_DIR`, то есть отменить главную защиту одной строкой на стороне вызова. Нужна особая
 * переменная — нужна и своя названная дверь, как у укладки плана.
 */
export function дверьGit(repo) {
  return simpleGit(repo).env(средаДляGit());
}

/**
 * Дверь укладки плана: та же чистая среда плюс СВОЙ файл индекса.
 *
 * Порядок именно такой: сперва из унаследованной среды вычёркивается чужой `GIT_INDEX_FILE`, и
 * только потом назначается наш. Иначе унаследованный индекс дошёл бы до git первым.
 * Путь обязан быть абсолютным: относительный git прочитал бы от своего рабочего каталога.
 */
export function дверьИндекса(repo, индексныйФайл) {
  if (!path.isAbsolute(индексныйФайл)) throw new Error('файл индекса задаётся полным путём');

  return simpleGit(repo).env({...средаДляGit(), GIT_INDEX_FILE: индексныйФайл});
}
