// Хранилище спора сведения — по ОДНОЙ языковой версии. Лежит в папке редактора внутри материалов,
// рядом с черновиками и снимками, вне контента и вне git.
//
// Спор принадлежит версии, а не статье и не программе: пока русская версия ждёт решения человека,
// английская и испанская обязаны открываться и сохраняться как обычно. Поэтому имя файла спора —
// то же плоское имя пути версии, что и у её черновика, а общего запрета на запись здесь нет.
//
// Правил здесь нет: что такое спор — в `core/mergeArticle.mjs`, здесь только файлы.

import fs from 'node:fs';
import path from 'node:path';

import {draftName} from '../core/drafts.mjs';
import {ApiError} from './httpBody.mjs';
import {хранилищеРедактора} from './draftStore.mjs';

const папкаСпоров = (repo, settings) => path.join(хранилищеРедактора(repo), settings['хранение']['папкаСведения']);

/** Путь к записи спора этой языковой версии. */
export function путьСпора(repo, settings, rel) {
  return path.join(папкаСпоров(repo, settings), draftName(rel));
}

/**
 * Записать спор вместе со всеми сторонами. Сначала во временный файл, потом переименованием:
 * оборванная на середине запись оставила бы половину сторон, то есть молча потерянную работу.
 *
 * Сбой не проглатывается: спор — единственное место, где после отказа записи лежат и база, и работа
 * человека, и внешняя версия. Не записался он — писать дальше нельзя вообще.
 */
export function записатьСпор(repo, settings, спор) {
  const dir = папкаСпоров(repo, settings);
  const файл = путьСпора(repo, settings, спор['path']);
  const временный = `${файл}.tmp`;

  try {
    fs.mkdirSync(dir, {recursive: true});
    fs.writeFileSync(временный, `${JSON.stringify(спор, null, 2)}\n`, 'utf8');
    fs.renameSync(временный, файл);
  } catch (error) {
    console.error(error);
    fs.rmSync(временный, {force: true});
    throw new ApiError(500, settings['ошибкиСервера']['спорНеЗаписан']);
  }
}

/**
 * Прочитать спор этой версии. Нет файла или он битый — спора нет: падать из-за нечитаемой
 * служебной записи нельзя, иначе одна порча заперла бы статью целиком.
 */
export function прочитатьСпор(repo, settings, rel) {
  try {
    const разобрано = JSON.parse(fs.readFileSync(путьСпора(repo, settings, rel), 'utf8'));
    // Запись обязана принадлежать той версии, о которой спрашивают, и называть свой вид:
    // чужая или безымянная показала бы человеку стороны не его статьи.
    const свой = разобрано?.['path'] === rel && typeof разобрано?.['вид'] === 'string';
    return свой ? разобрано : null;
  } catch {
    return null;
  }
}

/** Убрать спор: человек его разрешил либо внешняя сторона исчезла сама. */
export function убратьСпор(repo, settings, rel) {
  fs.rmSync(путьСпора(repo, settings, rel), {force: true});
}

/**
 * Что из спора отдаётся окну. Разобранные части остаются на диске: окну нужны стороны спорных
 * мест, а не весь текст статьи трижды.
 */
export function спорДляОкна(спор) {
  if (спор === null) return null;

  return {
    вид: спор['вид'],
    когда: спор['когда'],
    спорные: спор['спорные'] ?? [],
    мои: спор['мои'] ?? null,
    внешние: спор['внешние'] ?? null,
    база: спор['база'] ?? null,
  };
}
