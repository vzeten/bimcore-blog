// Перенос старого хранилища в общее. Зовётся один раз при запуске, ДО того как сервер открыт на
// запись: иначе окно успело бы писать черновик мимо ещё не перенесённой работы.
//
// Старое хранилище только ЧИТАЕТСЯ. Ни один его файл не удаляется и не переписывается, предел
// числа снимков во время переноса не применяется: перенос — не уборка, и обрезать историю по
// дороге значит потерять состояние, за которым человек однажды вернётся.
//
// Повтор безопасен: решение принимается по БАЙТАМ, поэтому второй запуск ничего не добавляет.
// Байты — единственный допустимый признак «это одно и то же»; выбирать между разными текстами по
// времени файла или по длине пути программа не вправе (правила — в `core/draftHome.mjs`).
//
// Черновик узнаётся по СТАТЬЕ, а не по имени файла: программа знает две схемы имён одного и того
// же черновика, и до всякого решения обе сводятся к пути статьи внутри записи. Иначе один черновик,
// названный по-старому и по-новому, лёг бы в хранилище дважды и разошёлся бы сам с собой.
//
// Беда чтения старого хранилища — не «данных нет». Папки нет вовсе — переносить нечего; всё
// остальное (нет доступа, файл занят, на месте папки файл) останавливает запуск понятной строкой:
// работать над текстом, судьба которого неизвестна, хуже отказа запуститься.

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

import {КОПИРОВАТЬ, СОВПАЛО, имяСпора, исходФайла, нуженПеренос, префиксСпора} from '../core/draftHome.mjs';
import {draftName, readDraft, староеИмяЧерновика} from '../core/drafts.mjs';
import {parseSnapshotName, свободноеИмя} from '../core/history.mjs';
import {папкаСнимковВ, папкаСпоровВ, папкаЧерновиковВ, хранилищеРедактора} from './draftStore.mjs';

/** Имя беды чтения: по нему верхний уровень отличает её от беды записи и даёт человеку свой текст. */
export const БЕДА_ЧТЕНИЯ = 'БедаЧтенияХранилища';

/** Беда чтения с путём и причиной: молча считать её пустой папкой нельзя. */
function бедаЧтения(error, путь) {
  const своя = new Error(`${error?.code ?? error?.message ?? 'ошибка'}: ${путь}`);
  своя.name = БЕДА_ЧТЕНИЯ;
  своя.путь = путь;
  своя.причина = error?.code ?? String(error?.message ?? '');
  return своя;
}

/** Записи папки нужного вида. Папки нет — данных нет; любая другая беда чтения — отказ. */
function перечень(dir, диск, вид) {
  try {
    return диск.readdirSync(dir, {withFileTypes: true})
      .filter((з) => (вид === 'файл' ? з.isFile() : з.isDirectory()))
      .map((з) => з.name)
      .sort();
  } catch (error) {
    if (error?.code === 'ENOENT') return [];
    throw бедаЧтения(error, dir);
  }
}

const файлы = (dir, диск) => перечень(dir, диск, 'файл');

/** Имена подпапок папки: у истории каждая версия статьи лежит в своей. */
const подпапки = (dir, диск) => перечень(dir, диск, 'папка');

/**
 * Байты файла. Файл перечислен, но не читается — это беда, а не отсутствие работы: пропустив его,
 * программа объявила бы незаписанный текст человека несуществующим.
 */
function байты(файл, диск) {
  try {
    return диск.readFileSync(файл);
  } catch (error) {
    throw бедаЧтения(error, файл);
  }
}

/**
 * Какой СТАТЬЕ принадлежит файл черновика: путь берётся из самой записи, а не из имени файла.
 * Запись не разобралась — статьи у файла нет, и дальше он живёт под собственным именем.
 */
function чьяРабота(буфер) {
  try {
    const draft = readDraft(буфер.toString('utf8'));
    return draft !== null && typeof draft['path'] === 'string' && draft['path'] !== '' ? draft['path'] : null;
  } catch {
    return null;
  }
}

const отпечаток = (буфер) => crypto.createHash('sha1').update(буфер).digest('hex');

/** Положить байты новым файлом. Папка создаётся при первой записи. */
function положить(файл, буфер) {
  fs.mkdirSync(path.dirname(файл), {recursive: true});
  fs.writeFileSync(файл, буфер);
}

/**
 * Черновики. Ключ — СТАТЬЯ, а не имя файла: обе схемы имён одного черновика сводятся к пути статьи
 * до всякого решения, и в общее хранилище работа ложится под нынешним именем. Поэтому черновик,
 * названный по-старому, не разъезжается с собой же, названным по-новому.
 *
 * Дальше решают только байты. Другой текст той же статьи не выбирается и не сливается: он ложится
 * отдельным вариантом рядом, а запись черновика этой статьи до разбора спора отклоняется
 * (`draftStore.saveDraft`).
 */
function черновики(отДир, кДир, спорДир, диск) {
  const итог = {перенесено: 0, совпало: 0, спорные: []};
  const названо = new Set();
  // Спор называется поимённо и ровно один раз: разбирать его человеку руками, и «сколько-то
  // споров» тут мало, а две строки про один файл — тем более.
  const отметить = (статья, вариант) => {
    if (названо.has(вариант)) return;
    названо.add(вариант);
    итог.спорные.push({статья, вариант});
  };

  for (const имя of файлы(отДир, диск)) {
    const буфер = байты(path.join(отДир, имя), диск);
    const rel = чьяРабота(буфер);
    // Статья не узнана (файл не запись черновика) — он живёт под своим именем и ни с чьей
    // работой не путается.
    const свои = rel === null ? [имя] : [draftName(rel), староеИмяЧерновика(rel)];
    const отложенные = варианты(спорДир, свои, диск);
    const рядом = [...свои.map((своё) => path.join(кДир, своё)), ...отложенные];
    const исход = исходФайла({
      такиеЖеБайты: рядом.some((файл) => совпали(файл, буфер, диск)),
      местоСвободно: !свои.some((своё) => fs.existsSync(path.join(кДир, своё))),
    });

    // Неразобранные варианты этой статьи называются при ЛЮБОМ исходе. Иначе повтор переноса
    // сходился бы по байтам с уже отложенным вариантом, отчитывался «совпало» и выглядел успехом,
    // хотя спор стоит на месте и запись черновика этой статьи всё ещё заперта.
    for (const файл of отложенные) отметить(rel, path.basename(файл));

    if (исход === СОВПАЛО) {
      if (отложенные.length === 0) итог.совпало += 1;
      continue;
    }
    if (исход === КОПИРОВАТЬ) {
      положить(path.join(кДир, свои[0]), буфер);
      итог.перенесено += 1;
      continue;
    }

    // Имя варианта считается от самих байтов, поэтому повтор переноса даёт тот же файл.
    const вариант = имяСпора(свои[0], отпечаток(буфер));
    положить(path.join(спорДир, вариант), буфер);
    отметить(rel, вариант);
  }

  return итог;
}

/** Уже отложенные варианты этой статьи — по любому из её имён. */
function варианты(спорДир, свои, диск) {
  const начала = свои.map((своё) => префиксСпора(своё));
  return файлы(спорДир, диск)
    .filter((файл) => начала.some((начало) => файл.startsWith(начало)))
    .map((файл) => path.join(спорДир, файл));
}

/** Тот же файл байт в байт. Файла нет — не совпали; файл есть и не читается — беда, а не «нет». */
function совпали(файл, буфер, диск) {
  return fs.existsSync(файл) && байты(файл, диск).equals(буфер);
}

/**
 * Снимки истории. Совпавшие по байтам не переносятся вовсе — на этом держится повтор.
 * Занятое имя не перезаписывается никогда: снимок с разбираемым именем ложится рядом под свободным
 * (время и автор в имени остаются его собственными), а файл с посторонним именем остаётся лежать
 * в старом хранилище и назван в отчёте: молча стереть чужое имя программа не станет.
 */
function история(отДир, кДир, диск) {
  const итог = {перенесено: 0, совпало: 0, пропущено: []};

  for (const папка of подпапки(отДир, диск)) {
    const цельДир = path.join(кДир, папка);
    const занятые = файлы(цельДир, диск);
    const тела = занятые.map((имя) => байты(path.join(цельДир, имя), диск));

    for (const имя of файлы(path.join(отДир, папка), диск)) {
      const буфер = байты(path.join(отДир, папка, имя), диск);
      if (тела.some((своё) => своё.equals(буфер))) {
        итог.совпало += 1;
        continue;
      }

      const свободно = !занятые.includes(имя);
      const разобрано = свободно ? null : parseSnapshotName(имя);
      if (!свободно && разобрано === null) {
        итог.пропущено.push(`${папка}/${имя}`);
        continue;
      }

      const куда = свободно ? имя : свободноеИмя(занятые, разобрано.iso, разобрано.author);
      положить(path.join(цельДир, куда), буфер);
      занятые.push(куда);
      тела.push(буфер);
      итог.перенесено += 1;
    }
  }

  return итог;
}

/**
 * Перенести хранилище из папки `кодDir` в общее хранилище материалов `repo`. Слов для человека
 * здесь нет: беда чтения уходит наверх помеченной (`БЕДА_ЧТЕНИЯ`), и текст ей подбирает тот, кто
 * знает, чей это источник — запуск сервера или одноразовая команда.
 *
 * `кодDir` для сервера — папка редактора запущенного кода: до этого правила черновики и снимки
 * лежали именно там. Испытательный экземпляр не переносит ничего: его корень чужой, и перенос стал
 * бы дорогой, по которой работа владельца ушла бы на чужое дерево.
 */
export function перенестиСырьём({repo, кодDir, settings, испытательный = false, диск = fs}) {
  const хранилище = хранилищеРедактора(repo);
  if (!нуженПеренос({хранилище, наследие: кодDir, испытательный})) {
    return {хранилище, перенос: false, черновиков: 0, совпало: 0, споров: 0, спорные: [], снимков: 0, пропущено: []};
  }

  const свои = черновики(
    папкаЧерновиковВ(кодDir, settings),
    папкаЧерновиковВ(хранилище, settings),
    папкаСпоровВ(хранилище, settings),
    диск,
  );
  const снимки = история(папкаСнимковВ(кодDir, settings), папкаСнимковВ(хранилище, settings), диск);

  return {
    хранилище,
    перенос: true,
    черновиков: свои.перенесено,
    совпало: свои.совпало + снимки.совпало,
    споров: свои.спорные.length,
    спорные: свои.спорные,
    снимков: снимки.перенесено,
    пропущено: снимки.пропущено,
  };
}

/**
 * Перенос для ЗАПУСКА сервера: та же работа, но беда чтения одевается в текст настроек про
 * хранилище запущенной копии кода. Одноразовой команде этот текст не годится — у неё источник
 * назван человеком, и слова она подбирает свои, поэтому она зовёт `перенестиСырьём`.
 */
export function перенестиХранилище(вход) {
  try {
    return перенестиСырьём(вход);
  } catch (error) {
    // Беду чтения человек должен понять с первой строки: она называет путь и причину.
    // Беда записи говорит за себя сама и уходит наверх как есть.
    if (error?.name !== БЕДА_ЧТЕНИЯ) throw error;
    const текст = вход['settings']['материалы']['отказы']['переносЧтение'];
    throw new Error(`${текст}: ${error.путь} (${error.причина})`);
  }
}

/** Строки отчёта о переносе для первых строк запуска. Переносить было нечего — строк нет. */
export function строкиПереноса(отчёт, settings) {
  const надписи = settings['материалы']['запуск'];
  const строки = [`  ${надписи['хранилище']}: ${отчёт['хранилище']}`];
  if (!отчёт['перенос']) return строки;

  строки.push(`  ${надписи['перенос']}: ${отчёт['черновиков']} / ${отчёт['снимков']}`);
  if (отчёт['споров'] > 0) строки.push(`  ${надписи['спорныеЧерновики']}: ${отчёт['споров']}`);
  for (const имя of отчёт['пропущено']) строки.push(`  ${надписи['непонятныйСнимок']}: ${имя}`);
  return строки;
}
