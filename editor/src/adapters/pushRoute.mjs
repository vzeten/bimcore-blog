// Ручки отправки статьи на сайт: `/api/publish/plan` — что уедет, `/api/publish/push` — отправка.
//
// Разделены намеренно. Отправка в `main` = публикация (SPEC 1.2), а человек обязан увидеть точный
// набор ДО согласия (SPEC 5.4). Одна ручка на оба дела означала бы «покажи и сразу отправь».
//
// **Уезжает ожидающий коммит из очереди программы, а не `HEAD`.** Коммит публикации построен от
// свежей основы сервера и в местные ветки не попадает; текущая ветка человека и его `HEAD` здесь
// не спрашиваются вовсе. Оба захода заново спрашивают сервер о состоянии удалённой ветки и заново
// разбирают очередь: пока человек читал перечень, туда могли толкнуть с другой машины.
//
// **Все факты снимаются от одной основы.** Она читается один раз, и от неё же считаются разбор
// очереди, отставание, перечень коммитов и сама отправка: иначе показать можно было бы одно
// состояние, а отправить другое.

import path from 'node:path';
import fs from 'node:fs';

import {ВЕТКА_ВЫПУСКА} from '../core/publish.mjs';
import {отпечатокНабора, решениеОбОтправке} from '../core/push.mjs';
import {годныйПуть} from './releaseFacts.mjs';
import {закреплённаяОснова} from './publishBase.mjs';
import {разобратьОчередь} from './publishRepair.mjs';
import {взятьЗамок, отпустить} from './publishLock.mjs';
import {коммитыВпереди, отправить, отставание, положениеВИстории, удалённаяВетка} from './gitPush.mjs';
import {запомнитьПоказ, последнийПоказ} from './pushMemory.mjs';
import {badFields, badPath} from './httpBody.mjs';

/** Обрабатывает обе ручки отправки. Возвращает true, если запрос был к одной из них. */
export async function pushRoute({req, res, url, repo, editorDir, settings, git, тело, insideRepo, send}) {
  const план = url.pathname === '/api/publish/plan';
  const отправка = url.pathname === '/api/publish/push';
  if ((!план && !отправка) || req.method !== 'POST') return false;

  const payload = await тело(req);

  const плохоеТело = badFields(payload, отправка ? ['sha'] : [], settings['ошибкиСервера']);
  if (плохоеТело) {
    send(res, плохоеТело.status, {error: плохоеТело.error});
    return true;
  }

  const rel = payload.path;
  const bad = badPath(
    [rel],
    (p) => insideRepo(path.join(repo, p)),
    (p) => fs.existsSync(path.join(repo, p)),
    settings['ошибкиСервера'],
  );
  if (bad) {
    send(res, bad.status, {error: bad.error});
    return true;
  }

  if (!годныйПуть(rel, settings)) {
    send(res, 400, {error: settings['ошибкиСервера']['неПутьСтатьи']});
    return true;
  }

  // Согласие приходит отдельным признаком и относится к показанному коммиту. Без него ручка не
  // отправляет ничего: случайный повтор запроса не должен превращаться в публикацию.
  if (отправка && payload['подтверждено'] !== true) {
    send(res, 400, {error: settings['ошибкиСервера']['нетПодтверждения']});
    return true;
  }

  // **Замок берётся до всякой работы с хранилищем.** Показ и отправка читают и правят одну и ту же
  // очередь, а отправка ещё и двигает ветку на сервере: два захода разом перепутали бы и то, и другое.
  if (!взятьЗамок()) {
    send(res, 409, {error: settings['отказыКоммита']['идётЗапись'], код: 'идётЗапись'});
    return true;
  }

  try {
    return await повезти({rel, план, отправка, payload, editorDir, settings, git, res, send});
  } finally {
    отпустить();
  }
}

/** Сам показ и сама отправка. Вынесены из ручки, чтобы замок брался ровно вокруг них. */
async function повезти({rel, план, отправка, payload, editorDir, settings, git, res, send}) {
  const стоп = (код, ещё = {}) => {
    send(res, 409, {error: отказ(код, settings), код, чужие: [], неНаши: [], ...ещё});
    return true;
  };

  const основа = await закреплённаяОснова({git, settings});
  if (основа.ошибка) return стоп(основа.ошибка);

  // Очередь разбирается против свежей основы ДО решения: доехавшее снимается, устаревшее снимается,
  // остаётся то, что и вправду ждёт отправки. Битая очередь — «не знаю», и это отказ.
  const очередь = await разобратьОчередь({git, editorDir, settings, основа: основа.основа});
  if (очередь.ошибка) return стоп(очередь.ошибка);

  // **Ожидающих нет — везти нечего, и это не всегда отказ.** Согласие на коммит, который сервер
  // уже принял (потерянный ответ прошлой отправки), — успех, и спрашивается это у самого сервера,
  // а не у очереди: запись могла сняться ещё прошлым заходом. Разбор только что снял устаревшее —
  // человеку об этом говорится прямо, а не «всё на сайте». Всё остальное — устаревший план.
  const ожидающий = очередь.ожидающие.at(-1) ?? null;
  if (ожидающий === null) {
    if (план) {
      if (очередь.устаревшие.length > 0) return стоп('основаУстарела');
      запомнитьПоказ({sha: основа.основа, набор: отпечатокНабора([])});
      send(res, 200, {path: rel, sha: основа.основа, коммиты: [], файлы: [], уже: true});
      return true;
    }

    const где = await положениеВИстории(git, payload['sha'], основа.основа);
    if (где === 'неизвестно') return стоп('состояниеНеизвестно');
    if (где === 'нет') return стоп('основаУстарела');

    send(res, 200, {path: rel, sha: payload['sha'], отправлено: false, уже: true, коммиты: [], файлы: []});
    return true;
  }

  const нашиКоммиты = new Map(очередь.ожидающие.map((запись) => [запись.sha, запись.пути]));
  const удалённый = settings['отправка']['удалённый'];
  const коммиты = await коммитыВпереди(git, ожидающий.sha, основа.основа);
  const наборСейчас = отпечатокНабора(коммиты);
  const показ = последнийПоказ();

  // **Принадлежность доказывает ЗАПИСЬ о коммите, а не сегодняшний диск.** Коммит уже сделан, и его
  // состав проверен и собран тогда. Пересчитай программа состав по диску сейчас — картинка, которую
  // человек после записи удалил или переименовал, стала бы «посторонним файлом», и своя же работа
  // застряла бы навсегда. По той же причине состав не годится и когда прошлая запись сделана для
  // одной статьи, а досылку человек начинает из другой: пути там законно разные.
  const решение = решениеОбОтправке({
    коммитSha: ожидающий.sha,
    удалённыйSha: основа.основа,
    отставание: await отставание(git, ожидающий.sha, основа.основа),
    коммиты,
    разрешённыеПути: ожидающий.пути,
    нашиКоммиты,
    сверятьСогласие: отправка,
    ожидаемыйSha: отправка ? payload['sha'] : null,
    показанныйSha: показ?.sha ?? null,
    показанныйНабор: показ?.набор ?? null,
    наборСейчас,
  });

  if (решение.ошибка) {
    // Согласие относится к устаревшему показу — прежний показ стирается: следующее согласие
    // человек даёт заново и уже по сегодняшнему перечню.
    if (решение.ошибка === 'показУстарел') запомнитьПоказ(null);
    return стоп(решение.ошибка, {чужие: решение.чужие ?? [], неНаши: решение.неНаши ?? []});
  }

  const перечень = (коммиты ?? [])
    .filter((коммит) => решение.коммиты.includes(коммит.sha))
    .map((коммит) => ({sha: коммит.sha, заголовок: коммит.заголовок, файлов: коммит.файлы.length}));

  if (план) {
    // Показ запоминается целиком: и коммит, и сам набор. Согласие человека будет относиться
    // именно к нему, а не к тому, чем очередь станет через минуту.
    запомнитьПоказ({sha: ожидающий.sha, набор: наборСейчас});
    send(res, 200, {path: rel, sha: ожидающий.sha, коммиты: перечень, файлы: решение.файлы, уже: false});
    return true;
  }

  try {
    // Отправляется точный SHA в точную ветку, и только если сервер всё ещё стоит на основе: сдвинулся
    // — отправка останавливается сама, чужой коммит не перезаписывается.
    await отправить(git, ожидающий.sha, основа.основа, удалённый, ВЕТКА_ВЫПУСКА);
  } catch (ошибка) {
    const итог = await разборНеудачи({git, удалённый, sha: ожидающий.sha, ошибка, settings, rel});
    // Отправка всё-таки дошла — это успех, а не отказ, хотя ответа мы не дождались. Очередь тогда
    // тоже прибирается: коммит на сайте, доказывать его происхождение больше незачем.
    if (итог.error === undefined) await прибратьОчередь({git, editorDir, settings, удалённый});
    send(res, итог.error === undefined ? 200 : 409, итог);
    return true;
  }

  // Записи об уехавших коммитах снимаются только по ДОКАЗАННОМУ присутствию в свежей удалённой
  // ветке. Молча забыть свой неотправленный коммит значит запретить его отправку навсегда.
  await прибратьОчередь({git, editorDir, settings, удалённый});

  send(res, 200, {path: rel, sha: ожидающий.sha, отправлено: true, уже: false, коммиты: перечень, файлы: решение.файлы});
  return true;
}

/**
 * Прибрать очередь после отправки: сервер спрашивается ЗАНОВО, и снимается только доказанно
 * доехавшее. Спросить не удалось — очередь остаётся как есть, следующий заход разберёт её сам.
 */
async function прибратьОчередь({git, editorDir, settings, удалённый}) {
  const теперь = await удалённаяВетка(git, удалённый, ВЕТКА_ВЫПУСКА);
  if (теперь === null) return;

  await разобратьОчередь({git, editorDir, settings, основа: теперь});
}

/**
 * Отправка не удалась — но что именно случилось, по одному сообщению git не решить: сервер мог
 * принять её и потерять ответ. Поэтому исход выясняется у самого сервера, а не гаданием по тексту:
 * спрашиваем ветку заново.
 *
 * Наш коммит оказался в истории ветки — отправка дошла, и врать «не удалось» нельзя. Спрашивается
 * именно история, а не совпадение вершин: сервер мог принять наш коммит, ответ потерять, а следом
 * кто-то добавил поверх свой. Положение спрашивается ответом, а не кодом возврата: у команды-признака
 * «не предок» и «git не смог ответить» неразличимы, и ложный успех прятался бы ровно там. Коммита в
 * истории нет, а ветка ушла вперёд — основа устарела, и чужой коммит остался нетронутым. Ветка на
 * месте — не дошла, и человеку показывается ответ git как есть. Спросить не удалось вовсе —
 * единственный честный ответ «неизвестно».
 */
async function разборНеудачи({git, удалённый, sha, ошибка, settings, rel}) {
  const теперь = await удалённаяВетка(git, удалённый, ВЕТКА_ВЫПУСКА);
  const вывод = String(ошибка?.message ?? '');
  const где = теперь === null ? 'неизвестно' : await положениеВИстории(git, sha, теперь);

  if (где === 'есть') return {path: rel, sha, отправлено: true, уже: false, коммиты: [], файлы: []};
  if (где === 'неизвестно') {
    return {error: settings['отказыОтправки']['исходНеясен'], код: 'исходНеясен', sha, вывод};
  }
  if (await отставание(git, sha, теперь) > 0) {
    return {error: settings['отказыОтправки']['основаУстарела'], код: 'основаУстарела', sha, вывод};
  }

  return {error: settings['отказыОтправки']['отправкаНеУдалась'], код: 'отправкаНеУдалась', sha, вывод};
}

/** Слова человеку по коду отказа. Кода без своей фразы быть не должно; молчать о нём тоже нельзя. */
function отказ(код, settings) {
  const своя = settings['отказыОтправки'][код];

  return typeof своя === 'string' ? своя : `${settings['ошибкиСервера']['внутренняя']} (${код})`;
}
