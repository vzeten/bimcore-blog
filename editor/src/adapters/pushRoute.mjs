// Ручки отправки статьи на сайт: `/api/publish/plan` — что уедет, `/api/publish/push` — отправка.
//
// Разделены намеренно. Отправка в `main` = публикация (SPEC 1.2), а человек обязан увидеть точный
// набор ДО согласия (SPEC 5.4). Одна ручка на оба дела означала бы «покажи и сразу отправь».
//
// **Оба захода считают всё заново и оба спрашивают сервер о состоянии удалённой ветки.** Пока
// человек читал перечень, туда могли толкнуть с другой машины, и прежний ответ уже ничего не
// обещает. Согласие человека относится к показанному набору: с ним и сверяется отправка.
//
// **Все факты снимаются от одной головы.** Она читается один раз, и от неё же считаются отставание,
// перечень коммитов и сама отправка: иначе показать можно было бы одно состояние, а отправить другое.

import path from 'node:path';
import fs from 'node:fs';

import {выпускВозможен, составВыпуска} from '../core/release.mjs';
import {ВЕТКА_ВЫПУСКА} from '../core/publish.mjs';
import {отпечатокНабора, решениеОбОтправке} from '../core/push.mjs';
import {годныйПуть, версииСтатьи} from './releaseFacts.mjs';
import {текущаяВетка} from './gitCommit.mjs';
import {естьВИстории, головаSha, коммитыВпереди, отправить, отставание, удалённаяВетка} from './gitPush.mjs';
import {запомнитьПоказ, нашПоследнийКоммит, последнийПоказ} from './pushMemory.mjs';
import {badFields, badPath} from './httpBody.mjs';

/** Обрабатывает обе ручки отправки. Возвращает true, если запрос был к одной из них. */
export async function pushRoute({req, res, url, repo, settings, git, тело, insideRepo, send}) {
  const план = url.pathname === '/api/publish/plan';
  const отправка = url.pathname === '/api/publish/push';
  if ((!план && !отправка) || req.method !== 'POST') return false;

  const payload = await тело(req);

  const плохоеТело = badFields(payload, отправка ? ['sha'] : [], settings['ошибкиСервера']);
  if (плохоеТело) {
    send(res, плохоеТело.status, {error: плохоеТело.error});
    return true;
  }

  const rel = payload.path;
  const bad = badPath(
    [rel],
    (p) => insideRepo(path.join(repo, p)),
    (p) => fs.existsSync(path.join(repo, p)),
    settings['ошибкиСервера'],
  );
  if (bad) {
    send(res, bad.status, {error: bad.error});
    return true;
  }

  if (!годныйПуть(rel, settings)) {
    send(res, 400, {error: settings['ошибкиСервера']['неПутьСтатьи']});
    return true;
  }

  // Согласие приходит отдельным признаком и относится к показанному коммиту. Без него ручка не
  // отправляет ничего: случайный повтор запроса не должен превращаться в публикацию.
  if (отправка && payload['подтверждено'] !== true) {
    send(res, 400, {error: settings['ошибкиСервера']['нетПодтверждения']});
    return true;
  }

  // Состав считается заново: он задаёт, какие пути в уезжающих коммитах считаются «этой статьёй».
  const состав = составВыпуска({версии: версииСтатьи(repo, rel, settings)});
  if (!выпускВозможен(состав)) {
    send(res, 409, {error: settings['отказыКоммита']['составНеДоказан'], код: 'составНеДоказан'});
    return true;
  }

  const удалённый = settings['отправка']['удалённый'];
  const ветка = await текущаяВетка(git);
  const голова = await головаSha(git);
  const удалённыйSha = await удалённаяВетка(git, удалённый, ВЕТКА_ВЫПУСКА);
  const коммиты = голова === null || удалённыйSha === null ? null : await коммитыВпереди(git, голова, удалённыйSha);
  const наборСейчас = отпечатокНабора(коммиты);
  const показ = последнийПоказ();

  const решение = решениеОбОтправке({
    ветка,
    головаSha: голова,
    удалённыйSha,
    отставание: голова === null || удалённыйSha === null ? null : await отставание(git, голова, удалённыйSha),
    коммиты,
    разрешённыеПути: состав.файлы.map((файл) => файл.путь),
    сверятьСогласие: отправка,
    ожидаемыйSha: отправка ? payload['sha'] : null,
    нашКоммит: нашПоследнийКоммит(),
    показанныйSha: показ?.sha ?? null,
    показанныйНабор: показ?.набор ?? null,
    наборСейчас,
  });

  if (решение.ошибка) {
    // Согласие относится к устаревшему показу — прежний показ стирается: следующее согласие
    // человек даёт заново и уже по сегодняшнему перечню.
    if (решение.ошибка === 'показУстарел') запомнитьПоказ(null);
    send(res, 409, {error: отказ(решение.ошибка, settings), код: решение.ошибка, чужие: решение.чужие ?? []});
    return true;
  }

  const перечень = (коммиты ?? [])
    .filter((коммит) => решение.коммиты.includes(коммит.sha))
    .map((коммит) => ({sha: коммит.sha, заголовок: коммит.заголовок, файлов: коммит.файлы.length}));

  if (план) {
    // Показ запоминается целиком: и голова, и сам набор. Согласие человека будет относиться
    // именно к нему, а не к тому, чем репозиторий станет через минуту.
    запомнитьПоказ({sha: голова, набор: наборСейчас});
    send(res, 200, {path: rel, sha: голова, коммиты: перечень, файлы: решение.файлы, уже: решение.уже});
    return true;
  }

  // Этот коммит на сайте уже есть: так выглядит повтор после оборванной связи, когда сервер
  // запрос всё-таки принял. Второй отправки не делается, и человеку говорится правда.
  if (решение.уже) {
    send(res, 200, {path: rel, sha: голова, отправлено: false, уже: true, коммиты: перечень, файлы: решение.файлы});
    return true;
  }

  try {
    await отправить(git, голова, удалённыйSha, удалённый, ВЕТКА_ВЫПУСКА);
  } catch (ошибка) {
    const итог = await разборНеудачи({git, удалённый, голова, ошибка, settings, rel});
    // Отправка всё-таки дошла — это успех, а не отказ, хотя ответа мы не дождались.
    send(res, итог.error === undefined ? 200 : 409, итог);
    return true;
  }

  send(res, 200, {path: rel, sha: голова, отправлено: true, уже: false, коммиты: перечень, файлы: решение.файлы});
  return true;
}

/**
 * Отправка не удалась — но что именно случилось, по одному сообщению git не решить: сервер мог
 * принять её и потерять ответ. Поэтому исход выясняется у самого сервера, а не гаданием по тексту:
 * спрашиваем ветку заново.
 *
 * Наш коммит оказался в истории ветки — отправка дошла, и врать «не удалось» нельзя. Спрашивается
 * именно история, а не совпадение голов: сервер мог принять наш коммит, ответ потерять, а следом
 * кто-то добавил поверх свой. Коммита в истории нет — не дошла, и человеку показывается ответ git
 * как есть: разбирать чужой вывод программа не берётся, но и прятать его нельзя. Спросить не
 * удалось вовсе — единственный честный ответ «неизвестно».
 */
async function разборНеудачи({git, удалённый, голова, ошибка, settings, rel}) {
  const теперь = await удалённаяВетка(git, удалённый, ВЕТКА_ВЫПУСКА);
  const вывод = String(ошибка?.message ?? '');

  if (теперь !== null && await естьВИстории(git, голова, теперь)) {
    return {path: rel, sha: голова, отправлено: true, уже: false, коммиты: [], файлы: []};
  }
  if (теперь === null) {
    return {error: settings['отказыОтправки']['исходНеясен'], код: 'исходНеясен', sha: голова, вывод};
  }

  return {error: settings['отказыОтправки']['отправкаНеУдалась'], код: 'отправкаНеУдалась', sha: голова, вывод};
}

/** Слова человеку по коду отказа. Кода без своей фразы быть не должно; молчать о нём тоже нельзя. */
function отказ(код, settings) {
  const своя = settings['отказыОтправки'][код];

  return typeof своя === 'string' ? своя : `${settings['ошибкиСервера']['внутренняя']} (${код})`;
}
