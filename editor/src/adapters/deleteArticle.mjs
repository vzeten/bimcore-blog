// Удаление статьи с диска: сбор фактов, решение и исполнение. Правила — в `core/deleteArticle.mjs`,
// корзина — в `trashStore.mjs`.
//
// Порядок жёсткий: сначала собираются все факты и решение принимается целиком, и только потом
// идёт первое действие. Иначе отказ на середине оставил бы половину статьи — русскую версию без
// английской, то есть статью, которую сборка сайта не примет.

import fs from 'node:fs';
import path from 'node:path';

import {решениеОбУдалении} from '../core/deleteArticle.mjs';
import {articlePlace} from '../core/frontmatterRules.mjs';
import {dropDraft, dropHistory} from './draftStore.mjs';
import {опубликованные, statePath, walk} from './library.mjs';
import {вКорзину, составАрхива} from './trashStore.mjs';

/**
 * Все языковые версии статьи, лежащие на диске: тот же путь внутри своего корня.
 * Версии сшиваются по пути, как и в реестре (SPEC 3.4), — второго правила связи языков нет.
 */
export function версииСтатьи(repo, rel, settings) {
  const место = articlePlace(rel, settings['контент']);
  if (место.kind === 'вне контента') return [];

  return settings['контент']
    .filter((root) => root['род'] === место.kind)
    .map((root) => ({корень: root, path: `${root['папка']}/${место.inside}`}))
    .filter((версия) => fs.existsSync(path.join(repo, версия.path)))
    .map(({корень, path: файл}) => ({
      path: файл,
      локаль: корень['локаль'],
      наСайте: корень['наСайте'] === true,
      папка: path.posix.dirname(файл),
      состояние: путьСостояния(repo, файл, settings),
    }));
}

/**
 * Была ли версия когда-либо в опубликованной ветке. Текущего дерева мало: снятая с сайта статья
 * в нём отсутствует, а адрес у неё уже был. `null` — узнать не удалось, и решать это будет ядро.
 */
async function былаОпубликована(git, ref, rel) {
  try {
    return (await git.raw(['log', '-1', '--format=%H', ref, '--', rel])).trim() !== '';
  } catch {
    return null;
  }
}

/**
 * Полна ли история репозитория. В неполной (shallow) копии пустой `git log` по пути ничего не
 * доказывает: публикация могла быть за границей среза, и режим считается неизвестным.
 */
async function историяПолная(git) {
  try {
    return (await git.raw(['rev-parse', '--is-shallow-repository'])).trim() === 'false';
  } catch {
    return false;
  }
}

/** Решение об удалении со всеми фактами; ничего на диске не меняет. */
export async function решитьУдаление({repo, settings, git, ref, rel}) {
  const версии = версииСтатьи(repo, rel, settings);
  const ветка = await опубликованные(git, ref);
  const полная = await историяПолная(git);

  const факты = [];
  for (const версия of версии) {
    const папка = path.join(repo, версия.папка);
    факты.push({
      ...версия,
      опубликована: ветка.файлы.has(версия.path),
      былаОпубликована: !версия.наСайте || ветка.файлы.has(версия.path) ? ветка.файлы.has(версия.path)
        : полная ? await былаОпубликована(git, ref, версия.path) : null,
      служебная: статейВПапке(папка, true) > 0,
      // Своя папка: статья лежит в ней индексом и других статей рядом и глубже нет. Статья-файл
      // в общей папке (блог) уносит только свои файлы, соседей и общие картинки не трогает.
      своя: /^index\.mdx?$/.test(path.basename(версия.path)) && walk(папка).length === 1,
    });
  }

  return решениеОбУдалении({веткаИзвестна: ветка.известна, версии: факты});
}

/**
 * Исполнить решение. Корзина — перенос по заранее посчитанному составу; навсегда — стирание.
 * Возвращает `{ошибка}` либо `{удалено: [пути], режим, корзина?}`.
 */
export function исполнитьУдаление({repo, editorDir, settings, решение, статья}) {
  if (решение.режим === 'корзина') {
    let состав;
    try {
      состав = составАрхива({repo, editorDir, settings, решение});
      const запись = вКорзину({repo, editorDir, settings, статья: {...статья, пути: решение.пути, языки: решение.языки, папки: решение.папки}, состав});
      return {удалено: решение.пути, режим: 'корзина', корзина: запись.id, удаленоКогда: запись.удалено};
    } catch (error) {
      console.error(error);
      return {ошибка: error.message === 'ссылкаВПути' ? 'ссылкаВПути' : 'переносНеЗавершён'};
    }
  }

  // Файлы стираются первыми, служебные следы — за ними: остаток истории без статьи безвреден,
  // а статья без истории — нет. Тот же порядок, что и при записи (SPEC 5.3).
  // Отменить удаление на середине нечем: стёртого файла не вернуть. Поэтому сбой не выдаётся
  // за успех — человеку говорят, что удалено не всё, и он видит в реестре, что осталось.
  const стёрто = [];
  for (const файл of решение.файлы) {
    const полный = path.join(repo, файл);
    try {
      if (fs.existsSync(полный)) fs.rmSync(полный, {force: true});
      стёрто.push(файл);
    } catch (error) {
      console.error(error);
      return {ошибка: 'удалилосьНеВсё', стёрто};
    }
  }

  // Черновики, история и папка — служебный хвост. Их сбой удаления не отменяет: файлы статьи
  // уже стёрты, и объявлять неудачу значило бы соврать в другую сторону.
  const предупреждения = [];
  for (const версия of решение.пути) {
    try {
      dropDraft(editorDir, settings, версия);
      dropHistory(editorDir, settings, версия);
    } catch (error) {
      console.error(error);
      предупреждения.push(settings['ошибкиУдаления']['остатки']);
    }
  }

  // Папка статьи уходит вместе с ней со всем, что в ней осталось: там лежали только её картинки.
  // Это самое разрушительное место программы, поэтому оно стоит после заслонов: путь проверен
  // на выход за репозиторий, папка целиком своя. Корень контента не трогается никогда.
  for (const папка of решение.папки) {
    if (!убратьПапкуСтатьи(repo, папка, settings)) предупреждения.push(settings['ошибкиУдаления']['осталисьКартинки']);
  }

  return предупреждения.length > 0
    ? {удалено: решение.пути, режим: 'навсегда', предупреждения}
    : {удалено: решение.пути, режим: 'навсегда'};
}

/** Путь файла состояния рядом со статьёй, если он есть. */
function путьСостояния(repo, rel, settings) {
  const полный = statePath(repo, rel, settings);
  const свой = path.relative(repo, полный).split(path.sep).join('/');
  return fs.existsSync(полный) ? свой : null;
}

/** Сколько статей лежит в этой папке. `глубже` — считать только вложенные, не саму папку. */
function статейВПапке(dir, глубже = false) {
  let записи;
  try {
    записи = fs.readdirSync(dir, {withFileTypes: true});
  } catch {
    return 0;
  }

  let счёт = 0;
  for (const запись of записи) {
    if (запись.isFile() && /^index\.mdx?$/.test(запись.name) && !глубже) счёт += 1;
    if (запись.isDirectory()) счёт += статейВПапке(path.join(dir, запись.name));
  }

  return счёт;
}

function убратьПапкуСтатьи(repo, папка, settings) {
  const корень = settings['контент'].some((root) => root['папка'] === папка);
  if (корень || папка === '' || папка === '.') return true;

  try {
    fs.rmSync(path.join(repo, папка), {recursive: true, force: true});
    return true;
  } catch (error) {
    console.error(error);
    return false;
  }
}
