// Аналитика изменений (ED-054): GET `/api/analytics`, POST `/api/analytics/manual`, POST `/api/analytics/describe`.
//
// **Приватно.** Функция есть только там, где лежит ключ владельца: ключ проверяется ДО открытия базы, и
// без него ответ — просто «функции нет», без надписей об ошибке (у сотрудника так и должно быть).
//
// Обновление общее для всех экземпляров: право обновлять решает сама база (`analyticsStore.mjs`), сеть
// идёт вне её транзакций. События с сервера проверяются не чаще `событияМинут`, Поиск Google — когда
// снимку больше `обновлениеЧасов` и не раньше `паузаЧасов` после неудачи. Сбой любой части не мешает
// ни другой части, ни работе со статьями: ответ отдаёт то, что лежит в базе.

import {badFields} from './httpBody.mjs';
import {найтиКлюч, получитьПропуск} from './ga4Client.mjs';
import {строкиПоиска} from './searchConsole.mjs';
import {серверныйКоммит, разобратьНовые} from './changeEvents.mjs';
import {открыть, занять, отдать, прочитатьСостояние, сохранитьСостояние, добавитьРучное, описать, заменитьДни, сводка} from './analyticsStore.mjs';
import {сведенияСайта} from './linkFacts.mjs';
import {деньМестный} from './viewsStore.mjs';
import {сдвигДня} from '../core/views.mjs';

const ДЕНЬ_ISO = /^\d{4}-\d{2}-\d{2}$/;
const вISO = (день) => `${день.slice(0, 4)}-${день.slice(4, 6)}-${день.slice(6, 8)}`;

/** Обрабатывает ручки аналитики. true, если запрос её. */
export async function analyticsRoute({req, res, url, repo, settings, git, тело, send}) {
  const ручки = ['/api/analytics', '/api/analytics/manual', '/api/analytics/describe'];
  if (!ручки.includes(url.pathname)) return false;
  const а = settings['аналитика'];

  // Ключа нет — функции нет: ни базы, ни надписей.
  const найден = найтиКлюч(settings['просмотры']['папкаКлюча']);
  const база = найден.ключ ? await открыть(repo) : null;
  if (!база) {
    if (req.method === 'GET') send(res, 200, {есть: false});
    else send(res, 404, {error: а['нетФункции']});
    return true;
  }

  try {
    if (req.method === 'GET' && url.pathname === '/api/analytics') {
      await обновить({repo, settings, git, база, ключ: найден.ключ, сейчас: Date.now()});
      send(res, 200, {есть: true, ...сводка(база), поиск: прочитатьСостояние(база, 'поиск.итог')});
      return true;
    }
    if (req.method !== 'POST') {
      send(res, 404, {error: settings['ошибкиСервера']['неизвестныйЗапрос']});
      return true;
    }

    const payload = await тело(req);
    if (url.pathname === '/api/analytics/manual') {
      const плохо = badFields(payload, ['дата', 'текст'], settings['ошибкиСервера']);
      if (плохо || !ДЕНЬ_ISO.test(payload.дата) || (payload.адрес !== undefined && typeof payload.адрес !== 'string')) {
        send(res, 400, {error: settings['ошибкиСервера']['плохойЗапрос']});
        return true;
      }
      send(res, 200, {ид: добавитьРучное(база, {дата: payload.дата, текст: payload.текст, адрес: payload.адрес})});
      return true;
    }

    // Описание пишет ИИ сразу после публикации: сперва подтянуть свежие события, иначе записи ещё нет.
    const плохо = badFields(payload, ['коммит', 'путь', 'описание'], settings['ошибкиСервера']);
    if (плохо) {
      send(res, плохо.status, {error: плохо.error});
      return true;
    }
    await обновить({repo, settings, git, база, ключ: найден.ключ, сейчас: Date.now(), толькоСобытия: true, сразу: true});
    if (описать(база, payload.коммит, payload.путь, payload.описание)) send(res, 200, {описано: true});
    else send(res, 404, {error: а['нетСобытия']});
    return true;
  } finally {
    база.close();
  }
}

/** Обновить события и Поиск Google, если пора и право обновлять у этого экземпляра. Наружу не бросает. */
async function обновить({repo, settings, git, база, ключ, сейчас, толькоСобытия = false, сразу = false}) {
  const а = settings['аналитика'];
  const срокМс = а['срокСекунд'] * 1000;
  let метка = null;
  try {
    метка = занять(база, срокМс * 30, сейчас);
  } catch {
    return;
  }
  if (метка === null) return;

  try {
    const проверены = Number(прочитатьСостояние(база, 'события.проверены'));
    if (сразу || !(сейчас - проверены < а['событияМинут'] * 60_000)) {
      const вершина = await серверныйКоммит(git);
      if (вершина) {
        await разобратьНовые({
          git, база, вершина, сайт: сведенияСайта(repo, settings), предел: а['коммитовЗаЗаход'],
          пределДельтыБайт: а['пределДельтыКБ'] * 1024, пометкаОбреза: а['пометкаОбреза'], сейчас,
        });
      }
      сохранитьСостояние(база, {'события.проверены': сейчас});
    }
    if (!толькоСобытия) await обновитьПоиск({база, а, ключ, сейчас, срокМс});
  } catch {
    // Сбой git или базы — числа останутся прежними; подробности могли бы нести пути и тексты.
  } finally {
    try {
      отдать(база, метка);
    } catch {
      // База недоступна — отметка снимется по сроку.
    }
  }
}

async function обновитьПоиск({база, а, ключ, сейчас, срокМс}) {
  const запрошено = Number(прочитатьСостояние(база, 'поиск.запрошено'));
  const итог = прочитатьСостояние(база, 'поиск.итог');
  if (сейчас - запрошено < (итог === 'есть' ? а['обновлениеЧасов'] : а['паузаЧасов']) * 3600_000) return;

  // Сеть — вне транзакций базы; в базу — только полный ответ.
  const по = сдвигДня(деньМестный(сейчас), -1);
  const последний = база.prepare('SELECT max(день) AS д FROM поиск').get().д;
  const с = последний ? сдвигДня(последний.replaceAll('-', ''), -7) : сдвигДня(по, -Math.round(а['месяцевПоиска'] * 30.4));
  const пропуск = await получитьПропуск(ключ, срокМс, сейчас, 'поиск');
  const ответ = пропуск.пропуск
    ? await строкиПоиска({пропуск: пропуск.пропуск, ресурс: а['ресурсПоиска'], с: вISO(с), по: вISO(по), срокМс})
    : пропуск;

  if (ответ.строки) заменитьДни(база, {с: вISO(с), по: вISO(по), строки: ответ.строки, неполныйС: ответ.неполныйС});
  сохранитьСостояние(база, {'поиск.запрошено': сейчас, 'поиск.итог': ответ.строки ? 'есть' : ответ.причина});
}
