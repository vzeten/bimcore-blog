// Запись готового плана в хранилище: дерево в отдельном индексе поверх основы, коммит с родителем-
// основой, служебная ссылка и запись в очередь. Один код на обе записи программы — публикацию
// статьи (`publishRoute.mjs`) и снятие статьи с сайта (`retireRoute.mjs`): разойдись они, одна из
// записей однажды потеряла бы заслон, который другая держит.
//
// **Репозиторий человека не меняется ничем.** Ветка, `HEAD`, рабочее дерево и общий индекс остаются
// как были; коммит живёт в объектной базе и в очереди программы до самой отправки.
//
// Замок публикации держит зовущий: запись идёт только под ним. Отправки здесь нет.

import path from 'node:path';

import {СОЗДАНО, УДАЛЕНО} from '../core/publishPlan.mjs';
import {владелецСсылок, деревоПлана, закрепитьКоммит, отпуститьКоммит, создатьКоммит} from './gitCommit.mjs';
import {деревоКоммита, путиКоммита} from './gitFile.mjs';
import {записатьНамерение, подтвердить} from './commitQueue.mjs';
import {запомнитьПоказ} from './pushMemory.mjs';

/**
 * Записать план. `сверитьДерево(дерево)` — заслон зовущего над сложенным деревом (у публикации это
 * сверка с деревом зелёной сборки); `ещё` — поля, которые лягут в запись очереди рядом с
 * обязательными (у снятия — `режим`).
 *
 * Возвращает `{коммит, пути}` либо `{ошибка}` с кодом отказа.
 */
export async function записатьПлан({
  git, repo, editorDir, settings, основа, записи, rel, отпечаток, источники, сообщение,
  сверитьДерево = () => true, ещё = {},
}) {
  const своё = path.join(editorDir, settings['хранение']['папкаПубликаций']);

  // **Дерево складывается в ОТДЕЛЬНОМ индексе поверх основы, а не в индексе человека.** Его индекс
  // принадлежит его ветке и к сайту отношения не имеет; обрыв в любой миг оставляет мусором только
  // временный файл программы.
  let дерево;
  try {
    дерево = await деревоПлана({
      repo, основа, записи,
      времянка: path.join(своё, 'укладка'),
      индексныйФайл: path.join(своё, 'индекс'),
    });
  } catch (ошибка) {
    console.error(ошибка);
    return {ошибка: 'коммитНеУдался'};
  }

  if (!сверитьДерево(дерево)) return {ошибка: 'деревоРазошлось'};

  // Дерево совпало с тем, что уже лежит на сайте: менять нечего. Пустой коммит здесь не «почти
  // ничего», а запись, которая потом уедет на сайт и ничего там не изменит.
  if (дерево === await деревоКоммита(git, основа)) return {ошибка: 'нечегоФиксировать'};

  // Родитель коммита — сама основа: уезжает ровно один коммит поверх сегодняшнего сайта, и отправка
  // докажет это, потребовав, чтобы сервер всё ещё стоял на ней.
  let коммит;
  try {
    коммит = await создатьКоммит(git, {дерево, родитель: основа, сообщение});
  } catch (ошибка) {
    console.error(ошибка);
    return {ошибка: 'коммитНеУдался'};
  }
  // Служебная ссылка держит коммит до отправки: без неё он ни с чего не достижим, и уборка git
  // стёрла бы его раньше повтора. Исход закрепления неясен — ссылка снимается по возможности; что
  // осталось, снимет ближайший разбор как сироту.
  const владелец = владелецСсылок(editorDir);
  try {
    await закрепитьКоммит(git, владелец, коммит.полный);
  } catch (ошибка) {
    console.error(ошибка);
    await отпуститьКоммит(git, владелец, коммит.полный);
    return {ошибка: 'коммитНеУдался'};
  }

  // **Ссылка принадлежит заходу, пока запись очереди не легла на диск.** Любой отказ или сбой до
  // этого отпускает её в `finally`: иначе исключение между ссылкой и записью оставило бы коммит
  // закреплённым, но никому не известным. После записи ссылкой владеет очередь.
  let уОчереди = false;
  try {
    // Пути берутся у самого коммита, а не из плана: в коммит попадает только изменившееся, и запись
    // обязана описывать его таким, какой он есть.
    const путиЗаписи = await путиКоммита(git, коммит.полный);
    const ушедшие = new Set(путиЗаписи);
    const своиПути = (источник) => записи
      .filter((запись) => запись.источник === источник && ушедшие.has(запись.путь))
      .map((запись) => запись.путь);
    const запись = {
      ...ещё,
      sha: коммит.полный,
      пути: путиЗаписи,
      основа,
      путь: rel,
      отпечаток,
      источники,
      созданные: своиПути(СОЗДАНО),
      удалённые: своиПути(УДАЛЕНО),
      когда: new Date().toISOString(),
    };
    // Намерение и подтверждение — две записи одной очереди: обрыв между ними оставляет намерение,
    // которое разбор снимет как недоказанное.
    if (!записатьНамерение(editorDir, settings, запись) || !подтвердить(editorDir, settings, коммит.полный)) {
      return {ошибка: 'происхождениеНеЗаписано'};
    }
    уОчереди = true;

    // Новая запись обесценивает прежний показ отправки: человеку показывали другое.
    запомнитьПоказ(null);
    return {коммит, пути: путиЗаписи};
  } catch (ошибка) {
    console.error(ошибка);
    return {ошибка: 'коммитНеУдался'};
  } finally {
    if (!уОчереди) await отпуститьКоммит(git, владелец, коммит.полный);
  }
}
