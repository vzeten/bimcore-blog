// Ручка обложки при публикации: у открытой версии без `image` положить рядом `cover.*` из первой
// подходящей картинки тела и ответить адресом для шапки.
//
// **Правило владельца (2026-09-16, уточнено им же):** если это возможно, обложку ВСЕГДА делает
// программа — не сделать её при годной картинке значит ошибиться. Если невозможно — публикация НЕ
// останавливается: статья уходит с общей обложкой сайта. Картинок нет или годится только анимация —
// это законно (страницы разделов и т.п.), без слова человеку. Техническая неудача (картинка не
// обработалась, негодный cover рядом, многострочное поле) — тоже без остановки, но с предупреждением
// в вопросе о публикации: человек решает сам, ставить ли свою обложку.
//
// **Текст статьи ручка не пишет.** Поле `image` ставит окно тем же сохранением, что и дату записи
// блога: второго писателя файла статьи в программе нет, и статья не открывается заново посреди
// публикации. Ручка кладёт только НОВЫЙ файл обложки — как ручная загрузка обложки в свойствах.
//
// Обрыв между файлом и полем излечивается сам: при следующем нажатии готовый `cover.*` найдётся
// здесь же, и ответом будет его адрес, а не второй файл.

import fs from 'node:fs';
import path from 'node:path';

import {readField, splitArticle} from '../core/articleFile.mjs';
import {СТАТЬЯ, СТРАНИЦА_КАТЕГОРИИ} from '../core/articleKind.mjs';
import {isEmptyImage} from '../core/frontmatterRules.mjs';
import {обложка, полеПишетсяСтрокой} from '../core/refineHead.mjs';
import {обложкойМожно, типКартинки} from '../core/imageType.mjs';
import {ссылкиМедиа} from '../core/refineText.mjs';
import {записатьНовый, папкаСтатьи, цельВнутриСтатьи} from './assetGuards.mjs';
import {badFields, badPath} from './httpBody.mjs';
import {инструментыМедиа} from './imagePrep.mjs';
import {собратьСнимок} from './refineRoute.mjs';
import {годныйПуть, фактыВерсии} from './releaseFacts.mjs';

/** Имя поля задал Docusaurus — чужой формат, не настройка (SPEC 4.4). */
const ОБЛОЖКА = 'image';

/** Обрабатывает `/api/publish/cover`. Возвращает true, если запрос был к ней. */
export async function publishCoverRoute({req, res, url, repo, settings, тело, insideRepo, send}) {
  if (url.pathname !== '/api/publish/cover' || req.method !== 'POST') return false;

  const ошибки = settings['ошибкиСервера'];
  const payload = await тело(req);
  const плохоеТело = badFields(payload, [], ошибки);
  if (плохоеТело) {
    send(res, плохоеТело.status, {error: плохоеТело.error});
    return true;
  }

  const rel = payload.path;
  const bad = badPath(
    [rel],
    (p) => insideRepo(path.join(repo, p)),
    (p) => fs.existsSync(path.join(repo, p)),
    ошибки,
  );
  if (bad) {
    send(res, bad.status, {error: bad.error});
    return true;
  }
  // Заслон пути стоит здесь, а не в окне: ответ ручки станет строкой в шапке статьи.
  const dir = годныйПуть(rel, settings) ? папкаСтатьи(repo, rel, insideRepo) : null;
  if (dir === null) {
    send(res, 400, {error: ошибки['неПутьСтатьи']});
    return true;
  }

  const итог = await обложкаДляПубликации({repo, rel, dir, settings});
  send(res, 200, {
    path: rel,
    нужна: итог.нужна ?? null,
    создана: итог.создана === true,
    предупреждение: итог.предупреждение ?? null,
  });
  return true;
}

/**
 * Что ответить: `{нужна}` — адрес для шапки; `{нужна: null}` — остаётся общая обложка сайта;
 * `{предупреждение}` — код находки, почему обложку сделать не удалось. Остановки нет ни в одном случае.
 */
async function обложкаДляПубликации({repo, rel, dir, settings}) {
  // **Обложка кладётся только туда, что уедет вместе со статьёй.** Состав забирает папку лишь у
  // статьи и страницы категории; файл рядом с корневой страницей или записью вне канона остался бы
  // на диске, а поле в шапке указало бы в пустоту — и сборка краснела бы при каждом нажатии.
  const вид = фактыВерсии(repo, rel, settings)?.вид;
  if (вид !== СТАТЬЯ && вид !== СТРАНИЦА_КАТЕГОРИИ) return {нужна: null};

  const текст = fs.readFileSync(path.join(repo, rel), 'utf8');
  const {frontmatterRaw} = splitArticle(текст);
  if (!isEmptyImage(readField(frontmatterRaw, ОБЛОЖКА))) return {нужна: null};
  // Картинок в теле нет — обложку делать не из чего, статья уходит с общей обложкой сайта.
  const естьКартинки = ссылкиМедиа(текст).some((ссылка) => ссылка.вид === 'картинка');

  const готовая = готоваяОбложка(dir, settings);
  // Годный cover рядом вписывается и без картинок в теле: файл уже есть, и обложка ему законна.
  // Негодный говорит о себе только там, где обложку можно было сделать.
  if (!естьКартинки && готовая?.нужна === undefined) return {нужна: null};
  // Поле записано несколькими строками: окно не перепишет его строкой, не потеряв продолжение.
  // Причина называется до создания файла, чтобы в папке не осталось обложки без ссылки.
  if (!полеПишетсяСтрокой(frontmatterRaw, ОБЛОЖКА)) return естьКартинки ? {предупреждение: 'обложкаНеВписана'} : {нужна: null};
  if (готовая !== null) return готовая;

  // Выбор картинки и имя по роду итоговых байтов — правило обработчика «обложка» у «Доработать»:
  // разойдись они, публикация и доработка назначали бы одной статье разные обложки. Картинки в теле
  // есть, но ни одна не годится (только анимация) — обложку сделать невозможно, это не ошибка.
  const снимок = собратьСнимок(repo, rel, dir, null);
  const предложение = обложка.анализ(снимок, settings);
  if (предложение.цель === null) return {нужна: null};

  try {
    const после = await обложка.применить(снимок, предложение, инструментыМедиа({settings}));
    // Отказ конвертера приходит только отчётом: без этой проверки неудача прошла бы молча.
    const имя = предложение.итог;
    if ((после.отчёт?.человеку.length ?? 0) > 0 || имя === undefined) return {предупреждение: 'обложкаНеОбработалась'};

    const байты = после.копия.файлы.get(имя);
    const место = цельВнутриСтатьи(dir, `./${имя}`);
    if (!обложкойМожно(типКартинки(байты)) || место === null) return {предупреждение: 'обложкаНеОбработалась'};

    // Имя заняли между поиском и записью — параллельная доработка или второе окно той же статьи.
    // Поверх не пишем: берётся то, что теперь лежит, по тем же правилам годности.
    if (!записатьНовый(repo, место.target, байты)) return готоваяОбложка(dir, settings) ?? {предупреждение: 'обложкаНеГодна'};

    return {нужна: `./${имя}`, создана: true};
  } catch (ошибка) {
    // Нет библиотеки обработки, сбой записи и прочие технические беды публикацию не держат:
    // «если это возможно» владельца. Причина уходит в журнал сервера, человеку — предупреждение.
    if (ошибка?.name !== 'ApiError') console.error(ошибка);
    return {предупреждение: 'обложкаНеОбработалась'};
  }
}

/**
 * Обложка, которая уже лежит рядом со статьёй: файл верхнего уровня с основой имени обложки.
 * Годна, если род по байтам берётся в обложку и совпадает с расширением — имя может лгать, а
 * обложка чужого формата роняет сборку сайта уже после публикации.
 *
 * `null` — таких файлов нет; `{нужна}` — первая годная по порядку имён; `{предупреждение}` — есть, но ни одна не годна.
 */
function готоваяОбложка(dir, settings) {
  const основа = String(settings['картинки']['имяОбложки']).toLowerCase();
  const свои = fs.readdirSync(dir, {withFileTypes: true})
    .filter((вход) => вход.isFile() && path.parse(вход.name).name.toLowerCase() === основа && path.extname(вход.name) !== '')
    .map((вход) => вход.name)
    .sort();
  if (свои.length === 0) return null;

  const годная = свои.find((имя) => {
    const род = типКартинки(fs.readFileSync(path.join(dir, имя)));
    const расширение = path.extname(имя).slice(1).toLowerCase().replace('jpeg', 'jpg');
    return род !== null && обложкойМожно(род) && род === расширение;
  });

  return годная === undefined ? {предупреждение: 'обложкаНеГодна'} : {нужна: `./${годная}`};
}
