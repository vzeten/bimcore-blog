// Тонкий адаптер к внешнему миру для фактов запуска: спрашивает наличие папок и версию кода у git,
// превращает отказ правила в текст для человека и собирает строки, которыми запуск называет себя.
// Сами правила — в ядре (`materialRoot.mjs`, `runtimeIdentity.mjs`) и здесь не повторяются
// (SPEC 4.3, 4.7).

import fs from 'node:fs';
import path from 'node:path';

import {выборКорня} from '../core/materialRoot.mjs';
import {РОЛЬ_ИСПЫТАТЕЛЬНАЯ, выборПорта, опознание, принятый} from '../core/runtimeIdentity.mjs';

/**
 * Переключатель испытательного режима: имя переменной среды. Это внутренний договор между
 * запуском и программой, а не настройка владельца (SPEC 4.4). Переменная задаётся на один запуск,
 * поэтому испытательный корень не может остаться включённым «сам собой», как остался бы в файле.
 */
export const ПЕРЕКЛЮЧАТЕЛЬ = 'EDITOR_TRIAL_ROOT';

/**
 * Переменная среды, которой запуск называет свой порт. Тоже договор на один запуск: порт, забытый
 * в файле настроек, увёл бы обычное окно с `4780` молча.
 */
export const ПОРТ_ЗАПУСКА = 'EDITOR_PORT';

/** Папка на месте. Нечитаемый путь и файл вместо папки — это «нет папки», а не падение. */
function папкаЕсть(путь) {
  try {
    return fs.statSync(путь).isDirectory();
  } catch {
    return false;
  }
}

/** Отказ правила словами человека: текст из настроек и само неверное значение рядом. */
function отказом(текст, значение) {
  throw new Error(значение ? `${текст}: ${значение}` : текст);
}

/**
 * Папка материалов и признак испытательного экземпляра. Путь — в родном для системы виде: его
 * ждут `path.join` и сравнение путей.
 *
 * Настройка неверна — бросается ошибка с готовым текстом из настроек и с самим значением, чтобы
 * человек увидел, что именно он написал. Молча взять соседнюю папку нельзя: программа правит
 * настоящие статьи, и работа не над теми материалами хуже отказа запуститься.
 */
export function материалыВладельца(settings, испытательный = null, спросить = папкаЕсть) {
  const итог = выборКорня(settings, спросить, испытательный);

  if (итог['отказ']) {
    отказом(settings['материалы']?.['отказы']?.[итог['отказ']] ?? итог['отказ'], итог['значение']);
  }

  return {корень: path.resolve(итог['корень']), испытательный: итог['испытательный']};
}

/**
 * Версия запущенного КОДА, а не материалов: ветка, короткий номер коммита и чистота той копии, из
 * которой поднят сервер. Спрашивается отдельной дверью, потому что дерево кода и дерево материалов
 * теперь разные, и назвать надо именно код. Чистота идёт рядом с номером намеренно: правка в
 * рабочем дереве меняет поведение программы, не меняя ни ветки, ни коммита, и без неё «принят»
 * доказывался бы именем, а не кодом. Не удалось спросить — всё пусто и грязно, и экземпляр от
 * этого перестаёт быть принятым: непроверяемая личность порт владельца не получает.
 */
export async function версияКода(git) {
  try {
    const ветка = (await git.raw(['rev-parse', '--abbrev-ref', 'HEAD'])).trim();
    const коммит = (await git.raw(['rev-parse', '--short', 'HEAD'])).trim();
    const хвосты = (await git.raw(['status', '--porcelain'])).trim();
    return {ветка, коммит, чисто: хвосты === ''};
  } catch (error) {
    console.error(error);
    return {ветка: null, коммит: null, чисто: false};
  }
}

/**
 * Кто поднялся и на каком порту — единственный сбор фактов о запущенном экземпляре. Порт не годится
 * (обычного окна из этого кода не выходит, а свой номер не назван) — запуск отказывается словами,
 * а не занимает `4780` за чужой счёт.
 */
export async function опознаниеЗапуска({settings, кодDir, git, источник, заявка}) {
  const {ветка, коммит, чисто} = await версияКода(git);
  const испытательный = источник['испытательный'];
  const выбор = выборПорта({принятый: принятый({испытательный, ветка, чисто, код: кодDir}), заявка});

  if (выбор['отказ']) {
    отказом(settings['материалы']?.['порт']?.[выбор['отказ']] ?? выбор['отказ'], выбор['значение']);
  }

  return опознание({
    корень: источник['корень'], испытательный, ветка, коммит, чисто, код: кодDir,
    порт: выбор['порт'], номер: process.pid,
  });
}

/**
 * Все факты запуска одним заходом: откуда материалы и кто именно поднялся. Собраны здесь, а не по
 * месту вызова, потому что порядок обязателен — корень выясняется до опознания, а опознание до
 * тяжёлой работы вроде сборки окна: отказ должен случиться раньше, чем занят порт.
 */
export async function фактыЗапуска({settings, кодDir, git, испытательный, заявка}) {
  const источник = материалыВладельца(settings, испытательный);
  return {источник, опознание: await опознаниеЗапуска({settings, кодDir, git, источник, заявка})};
}

/**
 * Чем запуск называет себя: род экземпляра, версия кода, фактическая папка материалов и адрес.
 * Все строки обязательны в любом случае: экземпляр на чужом дереве не должен выглядеть как обычное
 * окно, обычное окно должно доказывать свой корень само, а код не с принятой ветки обязан сказать
 * об этом прямо — материалы у него настоящие, и одной папкой его от обычного окна не отличить.
 */
export function строкиЗапуска({settings, опознание: о, наСайте}) {
  const надписи = settings['материалы']['запуск'];
  const род = о['role'] === РОЛЬ_ИСПЫТАТЕЛЬНАЯ ? 'испытательный' : (о['accepted'] ? 'обычный' : 'непринятый');
  const версия = о['branch'] ? `${о['branch']} ${о['commit']}` : надписи['версияНеизвестна'];

  return [
    надписи[род],
    `  ${надписи['код']}: ${о['code']} (${версия})`,
    `  ${надписи['материалы']}: ${о['materials']}`,
    `  ${надписи['адрес']}: ${о['url']}`,
    `  ${надписи['наСайте']}: ${наСайте ?? надписи['веткаНеизвестна']}`,
  ];
}
