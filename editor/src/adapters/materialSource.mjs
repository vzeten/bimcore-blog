// Тонкий адаптер к диску для корня материалов: спрашивает наличие папок и превращает отказ
// правила в текст для человека. Само правило — в ядре и здесь не повторяется (SPEC 4.3, 4.7).

import fs from 'node:fs';
import path from 'node:path';

import {выборКорня} from '../core/materialRoot.mjs';

/** Папка на месте. Нечитаемый путь и файл вместо папки — это «нет папки», а не падение. */
function папкаЕсть(путь) {
  try {
    return fs.statSync(путь).isDirectory();
  } catch {
    return false;
  }
}

/**
 * Папка материалов владельца в родном для системы виде: её ждут `path.join` и сравнение путей.
 *
 * Настройка неверна — бросается ошибка с готовым текстом из настроек и с самим значением, чтобы
 * человек увидел, что именно он написал. Молча взять соседнюю папку нельзя: программа правит
 * настоящие статьи, и работа не над теми материалами хуже отказа запуститься.
 */
export function материалыВладельца(settings, спросить = папкаЕсть) {
  const итог = выборКорня(settings, спросить);
  if (итог['корень']) return path.resolve(итог['корень']);

  const текст = settings['материалы']?.['отказы']?.[итог['отказ']] ?? итог['отказ'];
  throw new Error(итог['значение'] ? `${текст}: ${итог['значение']}` : текст);
}
