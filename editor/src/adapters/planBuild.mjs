// Полная сборка ПЛАНА, а не рабочего дерева.
//
// **Раньше сборка проверяла файлы компьютера, а уезжало не то.** Соседний язык мог лежать на диске
// начатым переводом, а на сайт уходила заглушка; сломанный чужой черновик красил сборку и запрещал
// публиковать готовую статью, которая к нему отношения не имеет. Поэтому сборка идёт по точной
// копии будущего сайта: опубликованная ветка на закреплённом SHA, поверх неё байты плана, и ничего
// больше.
//
// Копия — отдельное рабочее дерево git во временной папке. Зависимости не ставятся заново: на
// `node_modules` кладётся связь-соединение, и она снимается ПЕРВОЙ, чтобы уборка временной папки
// никогда не пошла по ней внутрь настоящих зависимостей.
//
// Здесь же строится ожидаемое дерево: сложенный индекс копии — это ровно то, что обязан дать
// коммит. Сверять коммит по отдельным путям нельзя: лишний путь, попавший в индекс мимо перечня,
// такой сверкой не ловится.

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

import {собратьСайт} from './siteBuild.mjs';

/** Имя папки зависимостей. Задано не нами — так их зовёт npm, настройкой это не бывает. */
const ЗАВИСИМОСТИ = 'node_modules';

/**
 * Собрать план. Возвращает `{зелёная, оборвана, времяМс, вывод, дерево}` либо `{ошибка}`.
 *
 * `основа` — закреплённый SHA опубликованной ветки, `записи` — окончательный план с байтами.
 * `дерево` — SHA ожидаемого дерева: с ним сверится будущий коммит.
 */
export async function собратьПлан({git, repo, основа, записи, пределМинут, запуск}) {
  const копия = fs.mkdtempSync(path.join(os.tmpdir(), 'editor-plan-'));
  const связь = path.join(копия, ЗАВИСИМОСТИ);
  let деревоСоздано = false;
  let итог;

  try {
    await git.raw(['worktree', 'add', '--detach', '--force', копия, основа]);
    деревоСоздано = true;

    if (разложить(копия, записи) === null) {
      итог = {ошибка: 'путьЗаПределами'};
    } else {
      // Дерево считается ДО сборки: после неё в копии лежат и вывод сборщика, и связь к
      // зависимостям, и любой из них мог бы попасть в индекс.
      const дерево = await ожидаемоеДерево(git, копия, записи);
      итог = {...await собрать({repo, копия, связь, пределМинут, запуск}), дерево};
    }
  } catch (ошибка) {
    итог = {ошибка: 'копияНеУдалась', вывод: String(ошибка?.message ?? ошибка)};
  }

  // Уборка — часть результата, а не приписка к нему. Не снялась связь — рекурсивно удалять нельзя
  // вовсе, иначе удаление пошло бы по ней внутрь настоящих зависимостей репозитория. И тогда
  // зелёный итог отменяется: сборка, после которой в системе остался мусор, зелёной не считается.
  const уборка = await убрать({git, копия, связь, деревоСоздано});

  return уборка.ошибка ? {ошибка: уборка.ошибка, вывод: уборка.вывод ?? ''} : итог;
}

/** Сборка в копии. Связь к зависимостям кладётся перед самым запуском и снимается уборкой. */
async function собрать({repo, копия, связь, пределМинут, запуск}) {
  fs.symlinkSync(path.join(repo, ЗАВИСИМОСТИ), связь, видСвязи());

  return собратьСайт({repo: копия, пределМинут, запуск});
}

/**
 * Ожидаемое дерево будущего коммита.
 *
 * **Режим кладётся явно, а не берётся у `git add`.** `add` наследует режим того, что уже лежит в
 * основе: файл, однажды ставший исполняемым, остался бы таким и в новом дереве, хотя план обещает
 * обычный файл. Тогда ожидаемое дерево разошлось бы с тем, что уложит коммит, — на пустом месте и
 * молча. Поэтому объект пишется `hash-object`, а место в индексе занимается `update-index` с
 * режимом из плана.
 */
async function ожидаемоеДерево(git, копия, записи) {
  for (const запись of записи) {
    if (!Buffer.isBuffer(запись.байты)) {
      await git.raw(['-C', копия, '--literal-pathspecs', 'update-index', '--force-remove', '--', запись.путь]);
      continue;
    }

    const sha = (await git.raw(['-C', копия, 'hash-object', '-w', '--', запись.путь])).trim();
    await git.raw(['-C', копия, 'update-index', '--add', '--cacheinfo', `${запись.режим},${sha},${запись.путь}`]);
  }

  return (await git.raw(['-C', копия, 'write-tree'])).trim();
}

/**
 * Разложить байты плана по копии. Возвращает перечень путей либо `null`, если хоть один из них
 * уводит за пределы копии.
 *
 * Проверка стоит здесь, а не только в правиле: перечень станет и именами файлов, и аргументами
 * `git add`, и «из правила такой путь не приходит» защитой не является.
 */
export function разложить(копия, записи) {
  const пути = [];
  const корень = fs.realpathSync(копия);

  for (const запись of записи) {
    const полный = path.resolve(копия, запись.путь);
    if (!внутри(полный, копия)) return null;

    // Путь уходит с сайта: в копии его быть не должно, иначе сборка проверила бы сайт с файлом,
    // которого там уже не будет. Папки под него не создаются — создавать нечего.
    if (!Buffer.isBuffer(запись.байты)) {
      if (!настоящееМестоВнутри(полный, корень)) return null;
      fs.rmSync(полный, {force: true});
      пути.push(запись.путь);
      continue;
    }

    // Папки создаются по одной, и каждая ступень проверяется ДО спуска на следующую. Обычный
    // `mkdir -p` тут не годится: для пути `мимо/новая/файл`, где `мимо` — соединение наружу, он
    // создал бы `новая` за пределами копии ещё до того, как программа успела бы отказаться.
    if (!создатьСтупени(копия, запись.путь)) return null;
    if (!настоящееМестоВнутри(полный, корень)) return null;

    fs.writeFileSync(полный, запись.байты);
    пути.push(запись.путь);
  }

  return пути;
}

/**
 * Создать папки пути по одной, отказавшись на первой же ступени, которая не своя.
 *
 * Своя ступень — та, которой ещё нет либо которая уже есть и является обычной папкой, а не ссылкой.
 * Вынесено наружу: тем же способом дописывает восстановленную заглушку восстановление после обрыва,
 * а обычный `mkdir -p` создал бы папку за пределами корня ещё до отказа.
 */
export function создатьСтупени(копия, отн) {
  const куски = отн.split('/').slice(0, -1);
  let текущий = копия;

  for (const кусок of куски) {
    текущий = path.join(текущий, кусок);

    let есть = null;
    try {
      есть = fs.lstatSync(текущий);
    } catch {
      есть = null;
    }

    if (есть === null) {
      fs.mkdirSync(текущий);
      continue;
    }

    if (есть.isSymbolicLink() || !есть.isDirectory()) return false;
  }

  return true;
}

/**
 * Настоящее место файла внутри корня. Лексической проверки мало: в опубликованном дереве может
 * лежать ссылка или соединение каталогов, и путь, который по буквам не выходит за копию, физически
 * уводит наружу. Место папки спрашивается у файловой системы уже после её создания, а сам файл не
 * должен быть ссылкой: запись по ссылке ушла бы туда, куда она смотрит.
 */
export function настоящееМестоВнутри(полный, корень) {
  try {
    if (!внутри(fs.realpathSync(path.dirname(полный)), корень)) return false;
  } catch {
    return false;
  }

  return !ссылка(полный);
}

/** Лежит ли путь внутри папки. Сама папка своим содержимым не считается. */
const внутри = (путь, папка) => путь.startsWith(папка + path.sep);

/** Ссылка ли это (символическая или соединение каталогов). Нет файла — не ссылка. */
function ссылка(полный) {
  try {
    return fs.lstatSync(полный).isSymbolicLink();
  } catch {
    return false;
  }
}

/**
 * Каким видом связи класть зависимости. На Windows обычная символическая ссылка требует особых
 * прав, а соединение каталогов (`junction`) — нет; на прочих системах соединений не бывает.
 */
const видСвязи = () => (process.platform === 'win32' ? 'junction' : 'dir');

/**
 * Уборка целиком. Возвращает `{}` либо `{ошибка}`.
 *
 * Порядок строгий: сперва связь, потом всё остальное. Пока связь не снята ДОКАЗАННО, рекурсивное
 * удаление запрещено вовсе — иначе оно пошло бы по ней внутрь настоящих зависимостей репозитория и
 * стёрло бы их. Такой отказ важнее любого зелёного итога сборки, поэтому он его и отменяет.
 */
async function убрать({git, копия, связь, деревоСоздано}) {
  if (!снятьСвязь(связь)) return {ошибка: 'связьНеСнята', вывод: связь};

  let снято = !деревоСоздано;
  if (деревоСоздано) {
    try {
      await git.raw(['worktree', 'remove', '--force', копия]);
      снято = true;
    } catch (ошибка) {
      console.error(ошибка);
    }
  }

  // Дерево могло не сняться средствами git — тогда папка убирается обычным удалением. Связи в ней
  // уже нет, поэтому рекурсия никуда наружу не уйдёт.
  try {
    fs.rmSync(копия, {recursive: true, force: true});
  } catch (ошибка) {
    return {ошибка: 'копияНеУбрана', вывод: String(ошибка?.message ?? ошибка)};
  }

  if (!деревоСоздано) return {};

  // Учёт git обязан сойтись. В запасной ветке — когда `worktree remove` не удался — успех `prune`
  // не пожелание, а условие: иначе программа вернула бы зелёный итог, оставив в git запись про
  // папку, которой уже нет, и следующая сборка того же плана упёрлась бы в неё.
  try {
    await git.raw(['worktree', 'prune']);
  } catch (ошибка) {
    if (!снято) return {ошибка: 'копияНеУбрана', вывод: String(ошибка?.message ?? ошибка)};
    console.error(ошибка);
  }

  return {};
}

/**
 * Снять связь, не тронув то, на что она указывает. Возвращает `true`, только если её доказанно нет.
 *
 * `rmdir` снимает соединение и символическую ссылку на каталог, не заходя внутрь; `unlink` остаётся
 * запасным путём. Если на месте связи оказалось что-то другое — настоящая папка с содержимым, — обе
 * попытки провалятся, и это честное «не снял».
 */
function снятьСвязь(связь) {
  for (const снять of [fs.rmdirSync, fs.unlinkSync]) {
    try {
      снять(связь);
      return true;
    } catch (ошибка) {
      if (ошибка?.code === 'ENOENT') return true;
    }
  }

  return false;
}
