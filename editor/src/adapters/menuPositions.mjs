// Позиции каталогов сайта с диска и готовый номер статьи в боковом меню.
// Правил здесь нет — только внешний мир. Сам порядок живёт в `core/menuOrder.mjs`.

import fs from 'node:fs';
import path from 'node:path';

import {articlePlace} from '../core/frontmatterRules.mjs';
import {ИМЯ_КАТЕГОРИИ} from '../core/articleKind.mjs';
import {путьВерсии} from '../core/articles.mjs';
import {ключКаталога, расставитьПоМеню} from '../core/menuOrder.mjs';

/**
 * Число `position` из `_category_.json` каталога. Нет файла, нет поля или в нём не число — `null`,
 * и тогда позицию каталога объявит его индексная страница (правило в ядре).
 *
 * Смотрятся все корни рода по порядку настройки, и берётся ПЕРВЫЙ, где файл нашёлся: у переводов
 * своего `_category_.json` нет, категорию объявляет основное дерево сайта — тем же правилом живёт
 * и признак `категорияРядом`. Спроси программа только свой корень, и порядок русского раздела
 * разошёлся бы с меню сайта на ровном месте.
 *
 * Метка порядка байтов в начале файла снимается: её оставляют редакторы Windows, а `JSON.parse`
 * на ней падает — и тогда каталог с живой позицией считался бы каталогом без неё.
 */
function позицияКатегории(repo, род, внутри, roots) {
  for (const root of roots.filter((корень) => корень['род'] === род)) {
    const файл = path.join(repo, путьВерсии(root, `${внутри}/${ИМЯ_КАТЕГОРИИ}`));
    if (!fs.existsSync(файл)) continue;

    try {
      const число = JSON.parse(fs.readFileSync(файл, 'utf8').replace(/^﻿/, ''))['position'];
      return typeof число === 'number' && Number.isFinite(число) ? число : null;
    } catch (error) {
      // Испорченный `_category_.json` роняет сборку сайта сам, и реестр за неё не отвечает:
      // список статей обязан открыться, просто каталог встанет в конец своего уровня.
      console.error(error);
      return null;
    }
  }

  return null;
}

/**
 * Позиция каждого каталога, над которым лежит хоть одна статья. Обход берётся из уже собранных
 * путей: второй проход по диску ради тех же папок ничего бы не добавил.
 */
export function позицииКаталогов(repo, пути, settings) {
  const roots = settings['контент'] ?? [];
  const позиции = new Map();

  for (const rel of пути) {
    const место = articlePlace(rel, roots);
    if (место.kind === 'вне контента') continue;

    const папки = String(место.inside ?? '').split('/').filter(Boolean).slice(0, -1);

    for (let i = 1; i <= папки.length; i += 1) {
      const ключ = ключКаталога(место.kind, папки.slice(0, i));
      if (позиции.has(ключ)) continue;

      позиции.set(ключ, позицияКатегории(repo, место.kind, папки.slice(0, i).join('/'), roots));
    }
  }

  return позиции;
}

/**
 * Статьи с готовым номером в боковом меню сайта (`порядокМеню`). Окно по файлам не ходит: ему
 * достаётся одно число на статью, и весь порядок раздела документации получается сортировкой
 * по нему. У статей ленты номера нет — `null`, меню у блога не бывает.
 */
export function сПорядкомМеню(repo, статьи, пути, settings) {
  const номера = расставитьПоМеню(статьи, позицииКаталогов(repo, пути, settings), settings);

  return статьи.map((статья) => ({...статья, порядокМеню: номера.get(статья.key) ?? null}));
}
