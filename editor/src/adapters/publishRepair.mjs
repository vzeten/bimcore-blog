// Восстановление после обрыва: что стало с записями очереди, когда сервер сайта спрошен заново.
//
// Публикационный коммит строится от свежей основы `origin/main` и никуда, кроме сервера, не
// уезжает: ни ветку, ни рабочее дерево, ни индекс человека он не трогает. Поэтому после обрыва —
// между записью и отправкой, во время отправки, при потерянном ответе — у каждой записи очереди
// ровно три исхода, и все три различаются одним вопросом к серверу:
//
// - **коммит уже на сервере** — работа доехала, запись больше ничего не доказывает и снимается;
// - **сервер не изменился** (основа записи равна сегодняшней основе) — коммит ждёт повтора отправки,
//   и повтор везёт ТОТ ЖЕ коммит, а не делает второй;
// - **сервер ушёл вперёд** — коммит устарел: его родитель уже не вершина ветки, и отправить его без
//   перезаписи чужой работы нельзя. Запись снимается, а статья публикуется заново новым планом.
//
// **Ни `HEAD`, ни имя ветки здесь не спрашиваются.** Человек мог после обрыва уйти куда угодно —
// восстановление от этого не зависит ничем и на диск не пишет ни байта.

import {НАМЕРЕНИЕ, записатьОчередь, прочитатьОчередь} from './commitQueue.mjs';
import {положениеВИстории} from './gitPush.mjs';

/**
 * Разобрать очередь против закреплённой основы. Зовётся перед всякой опасной работой и после
 * отправки; безвредна, когда разбирать нечего.
 *
 * `основа` — свежий SHA опубликованной ветки на сервере. Возвращает `{ожидающие, доехавшие,
 * устаревшие, недоказанные}` либо `{ошибка}`: `ожидающие` — записи, чей коммит можно и нужно
 * дослать; остальные три — SHA снятых записей, по ним отправка называет исход человеку.
 */
export async function разобратьОчередь({git, editorDir, settings, основа}) {
  const очередь = прочитатьОчередь(editorDir, settings);
  if (очередь.ошибка) return очередь;
  if (очередь.записи.length === 0) return {ожидающие: [], доехавшие: [], устаревшие: [], недоказанные: []};

  const ожидающие = [];
  const доехавшие = [];
  const устаревшие = [];
  const недоказанные = [];

  for (const запись of очередь.записи) {
    const где = await положениеВИстории(git, запись.sha, основа);
    // Git не смог ответить — очередь не трогается ВООБЩЕ. Прими программа «не знаю» за «коммита
    // нет», она выбросила бы запись о коммите, который на самом деле ждёт отправки.
    if (где === 'неизвестно') return {ошибка: 'состояниеНеизвестно'};

    if (где === 'есть') {
      доехавшие.push(запись.sha);
      continue;
    }

    // Намерение без подтверждения — след обрыва внутри самой записи: коммит не признан своим до
    // конца, и доказать его происхождение нечем. Такая запись снимается, статью публикуют заново.
    if (запись.состояние === НАМЕРЕНИЕ) {
      недоказанные.push(запись.sha);
      continue;
    }

    // Сервер ушёл вперёд: родитель коммита уже не вершина ветки. Досылать его нельзя — отправка
    // перезаписала бы чужую работу, а сливать программа не берётся. Нужен новый план.
    if (запись.основа !== основа) {
      устаревшие.push(запись.sha);
      continue;
    }

    ожидающие.push(запись);
  }

  // На диске остаются только ожидающие: снятая запись, вернись она при следующем заходе, снова
  // потребовала бы вопроса к серверу, а ответ на него уже известен.
  if (ожидающие.length !== очередь.записи.length) записатьОчередь(editorDir, settings, ожидающие);

  return {ожидающие, доехавшие, устаревшие, недоказанные};
}
