// Восстановление после обрыва: что стало с записями очереди, когда сервер сайта спрошен заново.
//
// Публикационный коммит строится от свежей основы `origin/main` и никуда, кроме сервера, не
// уезжает: ни ветку, ни рабочее дерево, ни индекс человека он не трогает. Поэтому после обрыва —
// между записью и отправкой, во время отправки, при потерянном ответе — у каждой записи очереди
// ровно три исхода, и все три различаются одним вопросом к серверу:
//
// - **коммит уже на сервере** — работа доехала, запись больше ничего не доказывает и снимается;
// - **сервер не изменился** (основа записи равна сегодняшней основе) — коммит ждёт повтора отправки,
//   и повтор везёт ТОТ ЖЕ коммит, а не делает второй;
// - **сервер ушёл вперёд** — коммит устарел: его родитель уже не вершина ветки, и отправить его без
//   перезаписи чужой работы нельзя. Запись снимается, а статья публикуется заново новым планом.
//
// Ожидающий коммит вдобавок обязан быть ЦЕЛ и ТЕМ ЖЕ: объект лежит в хранилище (его держит
// служебная ссылка, но уборка git и чужая рука сильнее), а статья на диске даёт ровно тот план,
// который человеку показали и который он подтвердил. Пропавший или изменившийся — снимается.
//
// **Ни `HEAD`, ни имя ветки здесь не спрашиваются.** Человек мог после обрыва уйти куда угодно —
// восстановление от этого не зависит ничем и на диск, кроме самой очереди, не пишет ни байта.
//
// **Разбор идёт только под замком публикации.** Чтение, проверка и запись очереди — одна операция:
// разбор без замка мог бы дописать поверх очереди свой устаревший снимок и стереть запись, которую
// в этот миг сделал другой заход.

import {НАМЕРЕНИЕ, записатьОчередь, прочитатьОчередь} from './commitQueue.mjs';
import {коммитВХранилище, отпуститьКоммит} from './gitCommit.mjs';
import {положениеВИстории} from './gitPush.mjs';
import {готовыйПлан} from './publishFacts.mjs';
import {отпечатокПлана} from './planBytes.mjs';
import {замокВзят} from './publishLock.mjs';

/**
 * Разобрать очередь против закреплённой основы. Зовётся перед всякой опасной работой и после
 * отправки, только под замком; безвредна, когда разбирать нечего.
 *
 * `основа` — свежий SHA опубликованной ветки на сервере. Возвращает `{ожидающие, доехавшие,
 * устаревшие, недоказанные, пропавшие, изменившиеся}` либо `{ошибка}`: `ожидающие` — записи, чей
 * коммит можно и нужно дослать; остальные — SHA снятых записей, по ним отправка называет исход.
 */
export async function разобратьОчередь({git, repo, editorDir, settings, основа}) {
  if (!замокВзят()) return {ошибка: 'идётЗапись'};

  const очередь = прочитатьОчередь(editorDir, settings);
  if (очередь.ошибка) return очередь;

  const итог = {ожидающие: [], доехавшие: [], устаревшие: [], недоказанные: [], пропавшие: [], изменившиеся: []};
  if (очередь.записи.length === 0) return итог;

  for (const запись of очередь.записи) {
    const где = await положениеВИстории(git, запись.sha, основа);
    // Git не смог ответить — очередь не трогается ВООБЩЕ. Прими программа «не знаю» за «коммита
    // нет», она выбросила бы запись о коммите, который на самом деле ждёт отправки.
    if (где === 'неизвестно') return {ошибка: 'состояниеНеизвестно'};

    if (где === 'есть') {
      итог.доехавшие.push(запись.sha);
      continue;
    }

    // Намерение без подтверждения — след обрыва внутри самой записи: коммит не признан своим до
    // конца, и доказать его происхождение нечем. Запись старого вида без пути и отпечатка тоже
    // недоказуема: сверить её с показанным нечем. Такие снимаются, статью публикуют заново.
    if (запись.состояние === НАМЕРЕНИЕ || !непусто(запись.путь) || !непусто(запись.отпечаток)) {
      итог.недоказанные.push(запись.sha);
      continue;
    }

    // Сервер ушёл вперёд: родитель коммита уже не вершина ветки. Досылать его нельзя — отправка
    // перезаписала бы чужую работу, а сливать программа не берётся. Нужен новый план.
    if (запись.основа !== основа) {
      итог.устаревшие.push(запись.sha);
      continue;
    }

    // Объекта нет в хранилище — досылать нечего, и ждать его вечно нельзя.
    const цел = await коммитВХранилище(git, запись.sha);
    if (цел === null) return {ошибка: 'состояниеНеизвестно'};
    if (цел === false) {
      итог.пропавшие.push(запись.sha);
      continue;
    }

    // Статья на диске обязана давать ровно показанный план: изменилась — согласие человека к
    // этому коммиту больше не относится.
    if (await отпечатокСейчас({git, repo, settings, запись, основа}) !== запись.отпечаток) {
      итог.изменившиеся.push(запись.sha);
      continue;
    }

    итог.ожидающие.push(запись);
  }

  const снятые = new Set([
    ...итог.доехавшие, ...итог.устаревшие, ...итог.недоказанные, ...итог.пропавшие, ...итог.изменившиеся,
  ]);
  if (снятые.size === 0) return итог;

  // Пишется не свой снимок, а сегодняшняя очередь без снятого: запись, добавленная после чтения,
  // остаётся на месте. Ссылки снятых коммитов отпускаются — держать их больше незачем.
  const сейчас = прочитатьОчередь(editorDir, settings);
  if (сейчас.ошибка) return сейчас;
  if (!записатьОчередь(editorDir, settings, сейчас.записи.filter((запись) => !снятые.has(запись.sha)))) {
    return {ошибка: 'состояниеНеизвестно'};
  }
  for (const sha of снятые) await отпуститьКоммит(git, sha);

  return итог;
}

/** Отпечаток плана, который дала бы статья записи сегодня. Плана нет — пустая строка, не отпечаток. */
async function отпечатокСейчас({git, repo, settings, запись, основа}) {
  const план = await готовыйПлан({git, repo, settings, rel: запись.путь, основа});
  if (план.ошибка || !Array.isArray(план.записи)) return '';

  return отпечатокПлана({основа, родитель: основа, записи: план.записи});
}

const непусто = (значение) => typeof значение === 'string' && значение !== '';
