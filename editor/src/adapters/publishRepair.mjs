// Восстановление после обрыва: доведение до конца того, что программа начала, но не закончила.
//
// Опасных мгновений в записи два, и оба переживаются только тем, что происхождение коммита ложится
// на диск ДО сдвига ветки.
//
// - **Обрыв между коммитом и сдвигом ветки.** В очереди остаётся намерение, коммита в ветке выпуска
//   нет. Такая запись ничего не доказывает и снимается.
// - **Обрыв между сдвигом ветки и записью созданных заглушек на диск.** Коммит есть, а файла на
//   диске нет, и человек видит его удалённым. Файл восстанавливается из самого коммита — оттуда,
//   где он теперь единственно и есть.
//
// Поэтому запись очереди нельзя снимать раньше восстановления: снятая запись — это потерянный
// адрес того, что надо дописать.
//
// **Индекс человека восстановление не трогает.** Из его состояния происхождение не выводится:
// намеренный возврат к основе выглядит точно так же, как наш отставший индекс. Приводит его сама
// запись, сразу после сдвига ветки, пока происхождение ещё известно.
//
// **Смотрят на ВЕТКУ ВЫПУСКА, а не на `HEAD`.** Человек мог после обрыва уйти на другую ветку, и
// по `HEAD` наш коммит выглядел бы несуществующим — тогда программа выбросила бы запись о коммите,
// который на самом деле лежит в `main`.

import fs from 'node:fs';
import path from 'node:path';

import {ВЕТКА_ВЫПУСКА} from '../core/publish.mjs';
import {годныйПутьПлана} from '../core/publishPlan.mjs';
import {НАМЕРЕНИЕ, СДЕЛАН, записатьОчередь, прочитатьОчередь} from './commitQueue.mjs';
import {текущаяВетка} from './gitCommit.mjs';
import {разницаСИндексом, файлИзКоммита} from './gitFile.mjs';
import {положениеВИстории} from './gitPush.mjs';
import {настоящееМестоВнутри, создатьСтупени} from './planBuild.mjs';

/**
 * Довести незаконченное. Зовётся перед всякой опасной работой; безвредна, когда доводить нечего.
 *
 * Возвращает `{записи, невосстановленные}` либо `{ошибка}`. `невосстановленные` — пути, которые
 * программа обещала дописать и не смогла: пока они есть, отправлять и прибирать очередь нельзя.
 */
export async function довестиНезаконченное({git, repo, editorDir, settings}) {
  const очередь = прочитатьОчередь(editorDir, settings);
  if (очередь.ошибка) return очередь;
  if (очередь.записи.length === 0) return {записи: [], невосстановленные: []};

  // **Чужая ветка не трогается ни одним байтом.** Человек мог после обрыва уйти на другую ветку, где
  // опубликованной заглушки и не должно быть. Восстанови программа её там — она положила бы файл из
  // `main` в чужое рабочее дерево. Поэтому отказ идёт ДО любой записи, а не после неё.
  if (await текущаяВетка(git) !== ВЕТКА_ВЫПУСКА) return {ошибка: 'неТаВетка'};

  // Ветка выпуска читается один раз и до всякой правки очереди. Прочитать не удалось — это «не
  // знаю», а не «коммита нет»: продолжать с недоказанным состоянием нельзя.
  const ветка = await веткаВыпуска(git);
  if (ветка === null) return {ошибка: 'состояниеНеизвестно'};

  const остаток = [];
  const невосстановленные = [];

  for (const запись of очередь.записи) {
    const где = await положениеВИстории(git, запись.sha, ветка);
    // Git не смог ответить — очередь не трогается ВООБЩЕ. Прими программа «не знаю» за «коммита
    // нет», она выбросила бы запись о коммите, который на самом деле лежит в ветке, и отправить его
    // потом стало бы нечем.
    if (где === 'неизвестно') return {ошибка: 'состояниеНеизвестно'};

    // Намерение без коммита в ветке — след обрыва до её сдвига. Коммит не состоялся.
    if (где === 'нет' && запись.состояние === НАМЕРЕНИЕ) continue;

    if (где === 'есть') {
      const дописано = await дописатьСозданные({git, repo, запись, времянка: времянкаВосстановления(editorDir, settings)});
      // **Прежний запрет не выводится заново, а лежит в самой записи.** Файл, которого нет на диске,
      // виден при каждом заходе, а вот «индекс привести не удалось» после перезапуска сервера
      // доказать уже нечем: происхождение его состояния к тому времени неизвестно. Не храни
      // программа этот запрет, следующее нажатие «Опубликовать» дослало бы коммит, забыв отказ.
      const итог = [...new Set([...await уцелевший(git, запись), ...дописано.невосстановленные])];
      невосстановленные.push(...итог);

      // **Индекс здесь не приводится.** Из его состояния нельзя узнать происхождение: человек мог
      // намеренно вернуть его ровно к основе, и такой возврат неотличим от нашего отставшего.
      // Восстановление занимается только файлами; индекс приводит сама запись, сразу после сдвига
      // ветки, где происхождение ещё известно.
      остаток.push({...запись, состояние: СДЕЛАН, невосстановленные: итог});
      continue;
    }

    остаток.push(запись);
  }

  if (изменилась(очередь.записи, остаток)) записатьОчередь(editorDir, settings, остаток);

  return {записи: остаток, невосстановленные: [...new Set(невосстановленные)]};
}

/**
 * Дописать на диск созданные заглушки, которых там нет, взяв их из САМОГО КОММИТА.
 *
 * Из коммита, а не из настроек: заглушка могла быть написана прежним текстом настроек, и новый
 * текст разошёлся бы с тем, что лежит на сайте. Восстанавливается ровно опубликованное.
 *
 * Возвращает `{невосстановленные}`. Молчать о неудаче нельзя: файл, который в хранилище есть, а на
 * диске нет, оставляет дерево грязным, и отправлять такую статью программа не должна.
 *
 * `времянка` — где писать байты до их появления по настоящему адресу. Лежит она в служебной папке
 * программы, а не рядом со статьёй: см. `положитьЕслиНет`.
 */
export async function дописатьСозданные({git, repo, запись, времянка}) {
  const невосстановленные = [];

  for (const rel of запись.созданные ?? []) {
    if (!годныйПутьПлана(rel)) {
      невосстановленные.push(rel);
      continue;
    }

    const место = наМесте(repo, rel);
    // Обычный файл на месте — восстанавливать нечего. Папка или ссылка на его месте — беда: молча
    // писать поверх такого нельзя, и считать восстановленным тоже.
    if (место === 'файл') continue;
    if (место === 'чужое') {
      невосстановленные.push(rel);
      continue;
    }

    const содержимое = await файлИзКоммита(git, запись.sha, rel);
    if (содержимое === null) {
      невосстановленные.push(rel);
      continue;
    }

    if (!положитьЕслиНет(repo, rel, Buffer.from(содержимое, 'utf8'), времянка)) невосстановленные.push(rel);
  }

  return {невосстановленные};
}

/**
 * Записать файл, только если его нет. Возвращает признак «файл на месте и он наш».
 *
 * **Байты не пишутся по настоящему адресу ни разу.** Прежде программа открывала окончательный путь
 * с `wx` и писала в него; уборку недописанного делал `catch`, а при пропаже питания его не бывает.
 * На диске оставалась половина заглушки, и следующее восстановление считало путь целым: оно
 * смотрело только на то, что по пути лежит обычный файл. Сверять байты с коммитом взамен нельзя —
 * между записью и отправкой человек ЗАКОННО правит опубликованную заглушку, начиная перевод, и
 * сверка объявила бы его работу невосстановленной.
 *
 * Поэтому запись идёт во временный файл ВНЕ содержимого сайта, со сбросом на диск, а по настоящему
 * адресу файл появляется одной жёсткой ссылкой. Ссылка атомарна: она либо есть целиком, либо её нет
 * вовсе. Исключительность при этом не теряется — на занятый путь она отвечает `EEXIST`, а не
 * затирает появившийся файл человека, как сделало бы переименование. Не поддержаны ссылки —
 * отказ; возврата к прямой записи нет, иначе беда вернулась бы там, где её труднее всего заметить.
 *
 * Времянка лежит вне корней содержимого намеренно: положи её программа рядом со статьёй, состав
 * публикации счёл бы её картинкой человека и увёз на сайт. Обрыв питания оставляет там мусорный
 * файл — безвредный и переписываемый по имени при следующем заходе.
 *
 * Папки создаются по одной с проверкой каждой ступени, а не `mkdir -p`: обычная рекурсия успела бы
 * создать папку за пределами репозитория ещё до отказа.
 */
export function положитьЕслиНет(repo, rel, байты, времянка) {
  const полный = path.join(repo, rel);
  const временный = path.join(времянка, `заглушка-${process.pid}`);
  let открыт = null;

  try {
    if (!создатьСтупени(repo, rel)) return false;
    if (!настоящееМестоВнутри(полный, fs.realpathSync(repo))) return false;

    fs.mkdirSync(времянка, {recursive: true});
    открыт = fs.openSync(временный, 'w');
    fs.writeFileSync(открыт, байты);
    // Сброс на диск ДО появления файла по настоящему адресу: без него ссылка могла бы указать на
    // содержимое, которого на диске ещё нет.
    fs.fsyncSync(открыт);
    fs.closeSync(открыт);
    открыт = null;

    fs.linkSync(временный, полный);

    return true;
  } catch (ошибка) {
    // Между проверкой и записью по пути что-то появилось. Это не поломка, а состояние мира — но
    // считать успехом можно только обычный файл: папкой или ссылкой могла оказаться и она.
    if (ошибка?.code === 'EEXIST') return наМесте(repo, rel) === 'файл';

    console.error(ошибка);

    return false;
  } finally {
    if (открыт !== null) {
      try {
        fs.closeSync(открыт);
      } catch (ошибка) {
        console.error(ошибка);
      }
    }
    убратьВремянку(временный);
  }
}

/** Что лежит по пути: `нет`, `файл` (обычный) либо `чужое` (папка, ссылка, что угодно ещё). */
function наМесте(repo, rel) {
  try {
    const сведения = fs.lstatSync(path.join(repo, rel));

    return сведения.isFile() ? 'файл' : 'чужое';
  } catch {
    return 'нет';
  }
}

/** Убрать временный файл. Остался — беды не делает, но и лежать ему незачем. */
function убратьВремянку(путь) {
  try {
    fs.rmSync(путь, {force: true});
  } catch (ошибка) {
    console.error(ошибка);
  }
}

/** Полное имя ветки выпуска, если она есть. Не спросили — `null`, и очередь не трогается. */
async function веткаВыпуска(git) {
  try {
    await git.raw(['rev-parse', '--verify', `refs/heads/${ВЕТКА_ВЫПУСКА}`]);

    return `refs/heads/${ВЕТКА_ВЫПУСКА}`;
  } catch {
    return null;
  }
}

/**
 * Что осталось от СОХРАНЁННОГО запрета этой записи.
 *
 * Снимается он целиком и только по доказательству: индекс совпал с нашим коммитом до последнего
 * пути. Ровно это программа и не сумела сделать тогда, когда запрет появился, — значит сегодня
 * работа доведена до конца, кем бы она ни была доведена. Спросить git не удалось — запрет остаётся:
 * «не знаю» здесь не «всё в порядке». Новая работа человека в индексе совпадения не даёт, и запрет
 * тоже остаётся — но это не новый тупик: обычная запись при непустом индексе и так отказывает.
 */
async function уцелевший(git, запись) {
  const сохранённые = Array.isArray(запись.невосстановленные) ? запись.невосстановленные : [];
  if (сохранённые.length === 0) return [];

  const разница = await разницаСИндексом(git, запись.sha);

  return Array.isArray(разница) && разница.length === 0 ? [] : сохранённые;
}

/**
 * Изменилась ли очередь: писать файл заново без нужды не стоит. Сравнивается и перечень
 * невосстановленного — снятый запрет обязан лечь на диск, иначе он вернулся бы при следующем заходе.
 */
const изменилась = (было, стало) => было.length !== стало.length
  || стало.some((запись, номер) => запись.состояние !== было[номер].состояние
    || переченьСтрокой(запись.невосстановленные) !== переченьСтрокой(было[номер].невосстановленные));

/** Перечень одной строкой для сравнения. Порядок сохраняется: он у обоих один и тот же. */
const переченьСтрокой = (перечень) => (Array.isArray(перечень) ? перечень : []).join('\0');

/**
 * Где программа пишет байты до их появления по настоящему адресу. Служебная папка публикаций — то
 * же место, где живут очередь и отдельный индекс: содержимым сайта она не является, и состав
 * публикации её не видит.
 */
export function времянкаВосстановления(editorDir, settings) {
  return path.join(editorDir, settings['хранение']['папкаПубликаций'], 'восстановление');
}
