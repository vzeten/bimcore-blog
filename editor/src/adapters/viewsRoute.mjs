// Просмотры статей для реестра: GET `/api/views`.
//
// Окно спрашивает эту ручку ОТДЕЛЬНО от реестра, и ничто в работе со статьёй её не ждёт: сбой или
// медленный Google оставляет прочерки, а открыть, сохранить, опубликовать и удалить статью можно как
// раньше (условие контролёра Codex, 2026-09-23). Google спрашивается не чаще, чем разрешает общий для
// всех экземпляров предел (`viewsStore.mjs`); в остальное время числа считаются по снимку на диске.
//
// Ответ — только числа и понятная надпись. Причина беды приходит кодом из `ga4Client.mjs`, слова к
// нему — из настроек; ни исключение, ни ответ Google в журнал сервера не пишутся.

import fs from 'node:fs';
import path from 'node:path';

import {найтиКлюч, получитьПропуск, отчётПросмотров} from './ga4Client.mjs';
import {прочитатьСнимок, прочитатьПопытку, пораСпросить, занять, завершить, деньМестный} from './viewsStore.mjs';
import {прежниеСостояния} from './viewHistory.mjs';
import {сведенияСайта} from './linkFacts.mjs';
import {showFile} from './gitFile.mjs';
import {адресаДляПросмотров, просмотрыСтатей, периодОтчёта, сдвигДня} from '../core/views.mjs';

/** Обрабатывает GET `/api/views`. true, если запрос её. */
export async function viewsRoute({req, res, url, repo, settings, git, publishedRef, articles, send}) {
  if (req.method !== 'GET' || url.pathname !== '/api/views') return false;

  const п = settings['просмотры'];
  const сейчас = Date.now();
  await обновить(repo, п, сейчас);

  const снимок = прочитатьСнимок(repo);
  const попытка = прочитатьПопытку(repo);
  const беда = попытка && попытка.итог !== 'есть' ? попытка.итог : null;
  const надпись = беда ? (п['причины'][беда] ?? п['причины']['сбойGoogle']).replace('{папка}', п['папкаКлюча']) : null;

  if (!снимок) {
    send(res, 200, {статьи: {}, поДень: null, надпись: надпись ?? п['ещёНет']});
    return true;
  }

  const статьи = await адресаСтатей(repo, settings, git, publishedRef(), await articles(), снимок.поДень, п['месяцев']);
  const языки = Object.keys(settings['локали']);
  send(res, 200, {
    статьи: просмотрыСтатей({строки: снимок.строки, статьи, поДень: снимок.поДень, месяцев: п['месяцев'], языки}),
    поДень: снимок.поДень,
    // Старые числа честно названы старыми: новые не пришли, но и не выдуманы.
    надпись: беда ? п['устарело'].replace('{причина}', надпись) : null,
  });
  return true;
}

/** Спросить Google, если пора и право спросить досталось этому экземпляру. Бросать наружу нечего. */
async function обновить(repo, п, сейчас) {
  if (!пораСпросить({снимок: прочитатьСнимок(repo), попытка: прочитатьПопытку(repo), сейчас, паузаЧасов: п['паузаЧасов']})) return;

  const срокМс = п['срокСекунд'] * 1000;
  // Право спросить держится дольше одного запроса: отчёт идёт страницами.
  if (!занять(repo, срокМс * 4, сейчас)) return;

  let итог = 'сбойGoogle';
  let снимок = null;
  try {
    const поДень = сдвигДня(деньМестный(сейчас), -1);
    const найден = найтиКлюч(п['папкаКлюча']);
    const пропуск = найден.ключ ? await получитьПропуск(найден.ключ, срокМс, сейчас) : найден;
    const {с, по} = периодОтчёта(поДень, п['месяцев']);
    const отчёт = пропуск.пропуск
      ? await отчётПросмотров({пропуск: пропуск.пропуск, ресурс: п['ресурс'], поток: п['поток'], с, по, срокМс})
      : пропуск;

    if (отчёт.строки) {
      итог = 'есть';
      снимок = {запрошено: new Date(сейчас).toISOString(), поДень, строки: отчёт.строки};
    } else {
      итог = отчёт.причина;
    }
  } catch {
    // Неожиданное остаётся общим «сбоем Google»: подробности могли бы нести ключ или пропуск.
  } finally {
    try {
      завершить(repo, {когда: сейчас, итог, снимок});
    } catch {
      // Папка запоминания недоступна: числа не обновятся, но работа со статьями не страдает.
    }
  }
}

/**
 * Статьи сайта с адресами, под которыми сайт показывал их страницы. Статья, ни одна версия которой
 * не выходила на сайт, чисел не получает: окно ставит прочерк, а не ноль.
 */
async function адресаСтатей(repo, settings, git, ref, свод, поДень, месяцев) {
  const сайт = сведенияСайта(repo, settings);
  const {с} = периодОтчёта(поДень, месяцев);
  const пути = new Set(свод.flatMap((статья) => Object.values(статья.versions).map((версия) => версия.path)));
  const прежние = await прежниеСостояния(git, ref, {
    корни: сайт.корни,
    с: `${с.slice(0, 4)}-${с.slice(4, 6)}-${с.slice(6, 8)}`,
    есть: (путь) => пути.has(путь),
  });

  const итог = [];
  for (const статья of свод) {
    const версии = Object.values(статья.versions);
    if (!статья.наСайте || !версии.some((версия) => версия.опубликован !== false)) continue;

    const нынешние = [];
    const былые = [];
    for (const версия of версии) {
      // Версия, которой нет в опубликованной ветке, на сайте не живёт: под адресом её языка сайт
      // показывает текст обязательного языка, и этот адрес статье даёт уже он.
      if (версия.опубликован === false) continue;
      нынешние.push({путь: версия.path, текст: читать(repo, версия.path)});
      былые.push(...(прежние.get(версия.path) ?? []));
      // Правка ещё не на сайте: живой адрес — у опубликованного текста, а не у местного.
      if (версия.отличается === true) {
        const выпущенный = await showFile(git, ref, версия.path);
        if (выпущенный !== null) былые.push({путь: версия.path, текст: выпущенный});
      }
    }
    итог.push({key: статья.key, адреса: адресаДляПросмотров(нынешние, былые, сайт)});
  }
  return итог;
}

function читать(repo, rel) {
  try {
    return fs.readFileSync(path.join(repo, rel), 'utf8');
  } catch {
    return '';
  }
}
