// Ручка подготовки статьи к выпуску: собирает снимок её языковых версий и зовёт готовое ядро.
// Вынесено из сервера, чтобы он оставался в пределах лимита размера файла (SPEC 4.9).
//
// **Ручка ничего не пишет.** Ни файла статьи, ни состояния, ни черновика, ни истории. Это не
// осторожность на будущее, а условие среза: пока подготовка только читает, ей не нужны ни барьер
// сохранения, ни отпечатки — конфликтовать нечему, и один и тот же вход всегда даёт один ответ.
// Появится автоправка механического (З4) — вместе с ней придут и барьер, и отпечатки (З1б).
//
// Правил проверки здесь нет ни одного: снимок собирается адаптером, судит о нём ядро.

import fs from 'node:fs';
import path from 'node:path';

import {articleFacts} from './articleFacts.mjs';
import {ЭТАПЫ_ВСЕЙ_СТАТЬИ, подготовкаПрошла, проверитьМестные} from '../core/prepare.mjs';
import {подготовкаОткрытой} from './prepareStamp.mjs';
import {badFields, badPath} from './httpBody.mjs';

/**
 * Обрабатывает `/api/prepare`. Возвращает true, если запрос был к ней.
 * `articles` приходит готовым: свод статей собирает сервер, как и для открытия статьи.
 *
 * Ключ — путь ОТКРЫТОЙ версии. У отдельного шага «Что мешает выпуску» проверяется вся статья
 * целиком: правила судят о её составе и о совпадении адресов версий, и по одной версии на эти
 * вопросы не ответить.
 *
 * **`толькоОткрытая: true` — режим хода публикации.** Там соседний перевод не читается ВООБЩЕ:
 * ни его файл, ни свод статей, который открывает каждую статью репозитория и спрашивает git.
 * Испорченный сосед не имеет права остановить публикацию открытой локали — по правилу владельца
 * отсутствующий на сайте язык закрывает заглушка в плане, а не отказ подготовки. Признак включается
 * только точным `=== true`: чужое значение в теле запроса не должно случайно снимать проверки.
 */
export async function prepareRoute({req, res, url, repo, settings, тело, insideRepo, send, articles}) {
  if (url.pathname !== '/api/prepare' || req.method !== 'POST') return false;

  const payload = await тело(req);

  const плохоеТело = badFields(payload, [], settings['ошибкиСервера']);
  if (плохоеТело) {
    send(res, плохоеТело.status, {error: плохоеТело.error});
    return true;
  }

  const rel = payload.path;
  const bad = badPath(
    [rel],
    (p) => insideRepo(path.join(repo, p)),
    (p) => fs.existsSync(path.join(repo, p)),
    settings['ошибкиСервера'],
  );
  if (bad) {
    send(res, bad.status, {error: bad.error});
    return true;
  }

  const однаВерсия = payload['толькоОткрытая'] === true;

  // **Срез одной версии считается ТЕМ ЖЕ кодом, каким его потом пересчитывает сервер.** Состав
  // и запись доказывают зелёную подготовку заново, и посчитай эта ручка вердикт по-своему —
  // человек получил бы «препятствий нет», а запись отказала бы «подготовка не прошла».
  const целиком = однаВерсия ? подготовкаОткрытой(repo, rel, settings) : null;
  const состав = однаВерсия
    ? целиком?.срез ?? null
    : всейСтатьёй(articleFacts(await articles(), rel, settings));

  // Статьи нет — отвечаем как на отсутствующую, а не зелёным вердиктом по пустоте.
  if (состав === null) {
    send(res, 404, {error: settings['ошибкиСервера']['нетСтатьи']});
    return true;
  }

  // Снимок — один заход чтения. Файл могли стереть между сводом и чтением: пропущенная версия
  // придёт в ядро пустым содержимым, и правила скажут о ней своё, а не свалятся стеком.
  const находки = однаВерсия
    ? целиком.находки
    : проверитьМестные(
      состав.пути
        .map((версия) => ({путь: версия, содержимое: прочитать(repo, версия)}))
        .sort((a, b) => a.путь.localeCompare(b.путь)),
      состав.категория,
      settings,
      {однаВерсия},
    );

  send(res, 200, {
    path: rel,
    находки,
    прошла: подготовкаПрошла(находки),
    // Какие этапы в этом срезе не выполнялись вовсе. Молчание о них было бы обманом: человек
    // прочёл бы «препятствий нет» как «сборка сайта это переживёт», а собирает сайт GitHub.
    // Этапы всей статьи называются здесь по той же причине: в ходе публикации они не выполнялись.
    невыполненные: [...(однаВерсия ? ЭТАПЫ_ВСЕЙ_СТАТЬИ : []), 'качество', 'сборкаНаGitHub'],
    // Отпечаток входов этой проверки. Ход публикации везёт его следующему заходу, и тот отказывает,
    // если вход изменился: иначе правка между проверками и составом прошла бы мимо проверок.
    отпечаток: состав.отпечаток ?? null,
  });
  return true;
}

/** Вся статья: пути всех её версий и категория — обе из уже собранного свода. */
function всейСтатьёй(факты) {
  const пути = Object.values(факты.versions);

  return пути.length === 0 ? null : {пути, категория: факты.category};
}

/** Содержимое версии; исчезнувший между сводом и чтением файл — пустая строка, а не падение. */
function прочитать(repo, rel) {
  try {
    return fs.readFileSync(path.join(repo, rel), 'utf8');
  } catch {
    return '';
  }
}
