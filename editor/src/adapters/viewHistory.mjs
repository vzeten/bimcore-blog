// Прежние состояния статей для просмотров: под какими адресами сайт показывал их за отчётный период.
//
// Спрашивается ОПУБЛИКОВАННАЯ ветка, а не местная голова: публикация редактора двигает `origin/main`,
// а местная ветка владельца об этом не знает (условие контролёра Codex, 2026-09-23). Адрес меняют
// только два события — переименование файла и смена `slug`; каждое берётся из истории ветки за период,
// и у каждого читается состояние файла ДО него: путь и `slug` одного и того же файла вместе.
//
// Ответ запоминается по SHA ветки и началу периода: ветка сдвинулась — история читается заново.

/** Разделитель коммитов в выводе git. Внутренний договор с git, а не настройка. */
const КОММИТ = '@';

const запомнено = new Map();

/**
 * Прежние состояния нынешних файлов статей: `Map<нынешний путь, [{путь, текст}]>`.
 * `с` — начало периода `YYYY-MM-DD`; `корни` — папки контента из настроек; `есть(путь)` — лежит ли
 * такой файл статьи сейчас. Нет ветки или git — пустой ответ: просмотры тогда считаются только по
 * нынешним адресам, а не выдумываются.
 */
export async function прежниеСостояния(git, ref, {корни, с, есть}) {
  if (!ref) return new Map();

  let sha;
  try {
    sha = (await git.raw(['rev-parse', '--verify', `${ref}^{commit}`])).trim();
  } catch {
    return new Map();
  }

  const ключ = `${sha}|${с}`;
  if (!запомнено.has(ключ)) {
    запомнено.clear();
    запомнено.set(ключ, собрать(git, sha, корни, с).catch(() => []));
  }

  const итог = new Map();
  for (const запись of await запомнено.get(ключ)) {
    const нынешний = нынешнийПуть(запись.путь, запись.переименования);
    if (!есть(нынешний)) continue;
    if (!итог.has(нынешний)) итог.set(нынешний, []);
    итог.get(нынешний).push({путь: запись.путь, текст: запись.текст});
  }
  return итог;
}

/** Прежние состояния за период одним заходом: переименования и смены `slug`, каждое — файлом «до». */
async function собрать(git, sha, корни, с) {
  const общее = ['-c', 'core.quotepath=false', 'log', sha, `--since=${с}`, `--format=${КОММИТ}%H`];

  const [переименования, сменыАдреса] = await Promise.all([
    git.raw([...общее, '-M', '--diff-filter=R', '--name-status', '--', ...корни]),
    git.raw([...общее, '-G^slug:', '--name-only', '--', ...корни]),
  ]);

  const шаги = разобратьПереименования(переименования);
  const события = [
    ...шаги.map((шаг) => ({коммит: шаг.коммит, путь: шаг.было})),
    ...разобратьПути(сменыАдреса),
  ];

  const записи = [];
  const прочитано = new Set();
  for (const событие of события) {
    const где = `${событие.коммит}^:${событие.путь}`;
    if (прочитано.has(где)) continue;
    прочитано.add(где);
    try {
      записи.push({путь: событие.путь, текст: await git.show([где]), переименования: шаги});
    } catch {
      // Файла у родителя нет (новая статья в этом же коммите) — прежнего адреса у него и не было.
    }
  }
  return записи;
}

/** Строки `R100\tбыло\tстало` по коммитам; git выдаёт коммиты от новых к старым. */
export function разобратьПереименования(вывод) {
  const шаги = [];
  let коммит = null;
  for (const строка of String(вывод ?? '').split('\n')) {
    if (строка.startsWith(КОММИТ)) коммит = строка.slice(1).trim();
    else if (/^R\d*\t/.test(строка) && коммит) {
      const [, было, стало] = строка.split('\t');
      шаги.push({коммит, было: было.trim(), стало: стало.trim()});
    }
  }
  return шаги;
}

/** Пути по коммитам из вывода `--name-only`. */
export function разобратьПути(вывод) {
  const пути = [];
  let коммит = null;
  for (const строка of String(вывод ?? '').split('\n')) {
    const текст = строка.trim();
    if (текст.startsWith(КОММИТ)) коммит = текст.slice(1);
    else if (текст !== '' && коммит) пути.push({коммит, путь: текст});
  }
  return пути;
}

/**
 * Куда файл уехал в итоге: по цепочке переименований до нынешнего пути. Цепочка идёт от старых шагов
 * к новым, а петля (файл вернули под старое имя) обрывается на первом повторе.
 */
export function нынешнийПуть(путь, шаги) {
  let текущий = путь;
  const пройдено = new Set([текущий]);
  for (const шаг of [...(шаги ?? [])].reverse()) {
    if (шаг.было !== текущий) continue;
    текущий = шаг.стало;
    if (пройдено.has(текущий)) break;
    пройдено.add(текущий);
  }
  return текущий;
}
