// Срез подготовки одной открытой версии и его отпечаток.
//
// **Зачем отпечаток.** Ход публикации спрашивает сервер четыре раза: проверки, состав, полная сборка
// и запись. Между заходами файл может поменять кто угодно — второе окно программы, внешний редактор,
// сама сборка сайта. Без общего снимка человек соглашался бы на один перечень, а сборка и коммит
// согласованно обработали бы другой; правка обязательного поля после проверок и вовсе прошла бы мимо
// них. Отпечаток связывает заходы в один снимок: каждый следующий отказывает, если вход предыдущего
// изменился.
//
// **Что в него входит.** Ровно те входы, от которых зависит вердикт подготовки открытой версии:
// её путь, её байты, её КАТЕГОРИЯ и НАСТРОЙКИ САМИХ ПРОВЕРОК. Возьми программа меньше — правка,
// меняющая вердикт, прошла бы незамеченной; возьми больше — ход ломался бы от чужой работы.
//
// Дерева статей в отпечатке нет намеренно, хотя категория считается по нему: всё, что дерево о
// вердикте говорит, уже сказано самой категорией. Клади программа туда перечень путей — публикация
// вставала бы «статья изменилась» от статьи, заведённой где угодно в той же локали, и даже от
// второго потомка у страницы, которая и так служебная.
//
// **Настройки в снимке — не перестраховка.** Сервер читает их заново на каждый запрос: поправленный
// `settings.json` меняет вердикт проверок, не меняя в статье ни байта. Без них человек получал бы
// вопрос по одним правилам, а запись шла бы по другим, и «проверки пройдены» относилось бы к
// правилам, которых на момент записи уже нет.
//
// Живёт отдельным файлом, потому что спрашивают его четверо: сама подготовка, состав выпуска,
// полная сборка и запись — каждый обязан доказать, что судит тот же снимок. Живи правило в ручке
// подготовки, остальные однажды написали бы себе своё.

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

import {категорияПоПутям} from '../core/articles.mjs';
import {articlePlace} from '../core/frontmatterRules.mjs';
import {БЛОКЕР, подготовкаПрошла, проверитьМестные} from '../core/prepare.mjs';
import {годныйПуть} from './releaseFacts.mjs';
import {путиСтатей} from './library.mjs';

/**
 * ПОЛ снимка: настройки, которые входят в отпечаток всегда, даже если на этом пути правил их никто
 * не спросил.
 *
 * Перечень назван явно, а не взят целиком: сложи в снимок весь `settings.json` — и публикация
 * вставала бы от правки слова в окне, к проверкам отношения не имеющего.
 *
 * Полнотой снимка он при этом НЕ является и являться не обязан: что правила прочитали на самом деле,
 * программа видит сама (см. `подготовкаОткрытой`) и добавляет к этому перечню. Держись полнота на
 * одном списке — она держалась бы на памяти того, кто правил правила.
 */
export const НАСТРОЙКИ_ПРОВЕРОК = [
  'заглушкиПеревода',
  'категорииПоПути',
  'категорииПоРоду',
  'категорияСлужебной',
  'контент',
  'локали',
  'обязательныеПоля',
  'обязательныйЯзык',
  'основнойЯзык',
  'поляСоздания',
  'пределОписания',
];

/**
 * Срез ОДНОЙ открытой версии: что читает подготовка в ходе публикации и чем это доказывается.
 *
 * Возвращает `{пути, категория, отпечаток}` либо `null` — путь не годится для статьи.
 * `пути` — всегда ровно открытая версия: соседний перевод в этом срезе не читается ничем.
 *
 * Категория считается по путям только СВОЕЙ локали и СВОЕГО рода. Обойди программа все корни,
 * дочерняя статья, живущая лишь в чужом переводе, сделала бы открытую версию страницей раздела и
 * сменила бы требования к её полям: сосед решал бы за открытую локаль, не будучи прочитанным.
 */
export function срезОднойВерсии(repo, rel, settings) {
  return подготовкаОткрытой(repo, rel, settings)?.срез ?? null;
}

/**
 * Подготовка ОДНОЙ открытой версии целиком: срез, находки правил и вердикт.
 *
 * Одно место на всю программу. Этим ручка подготовки отвечает человеку, и этим же состав, сборка и
 * запись доказывают, что подготовка и вправду прошла: решению окна веры нет — тело запроса пишет не
 * окно, а тот, кто его послал. Считай каждый сам — и «проверки пройдены» означало бы в четырёх
 * местах четыре разных вещи.
 *
 * **Отпечаток снимается ПОСЛЕ правил, а не до них.** Настройки, попадающие в снимок, не берутся из
 * одного лишь перечня: программа смотрит, что правила прочитали на самом деле. Перечень остаётся
 * полом — то, что входит в отпечаток всегда, — но новый ключ, прочитанный любой веткой правил и
 * любой записью (`settings.новый`, разбор в переменные, чужой вспомогательный модуль), попадает в
 * снимок сам. Иначе полнота держалась бы на памяти того, кто правил правила: перечень отстал бы
 * молча, настройка меняла бы вердикт, а отпечаток этого не замечал.
 *
 * Возвращает `null`, когда путь не годится для статьи.
 */
export function подготовкаОткрытой(repo, rel, settings) {
  const прочитанные = new Set();
  // Смотрит только ВЕРХНИЕ ключи: снимок описывает разделы настроек целиком, и следить за каждым
  // значением внутри незачем — раздел уже целиком в отпечатке.
  const заметить = (ключ) => {
    if (typeof ключ === 'string') прочитанные.add(ключ);
  };
  const наблюдаемые = new Proxy(settings, {
    get(цель, ключ, приёмник) {
      заметить(ключ);

      // Через `Reflect.get` с приёмником: настройка, заданная вычисляемым значением, читает соседние
      // ключи через тот же наблюдаемый объект, а не мимо него.
      return Reflect.get(цель, ключ, приёмник);
    },
    // **Спросить настройку можно не только чтением.** `'ключ' in settings` идёт мимо `get`, как и
    // `Object.hasOwn`, и разбор дескриптора, и перечисление ключей. Правило, решающее по НАЛИЧИЮ
    // ключа, меняло бы вердикт при прежнем отпечатке — а это ровно то, ради чего наблюдение и
    // заведено. Поэтому наблюдаются все четыре способа спросить.
    has(цель, ключ) {
      заметить(ключ);

      return Reflect.has(цель, ключ);
    },
    getOwnPropertyDescriptor(цель, ключ) {
      заметить(ключ);

      return Reflect.getOwnPropertyDescriptor(цель, ключ);
    },
    // Перечисление показывает разом ВСЁ, и ответ его зависит от каждого ключа настроек: значит в
    // снимок идут все. Сегодня правила ничего не перечисляют, и снимок остаётся узким сам собой.
    ownKeys(цель) {
      const все = Reflect.ownKeys(цель);
      for (const ключ of все) заметить(ключ);

      return все;
    },
  });

  if (!годныйПуть(rel, наблюдаемые)) return null;

  const место = articlePlace(rel, наблюдаемые['контент']);
  const своиКорни = наблюдаемые['контент']
    .filter((корень) => корень['локаль'] === место.locale && корень['род'] === место.kind);
  // Пути дерева нужны, чтобы посчитать категорию, — и только для этого. В сам ОТПЕЧАТОК они не
  // идут: всё, что дерево о вердикте говорит, уже сказано категорией. Клади программа туда сам
  // перечень — обычная публикация вставала бы «статья изменилась» от заведённой где угодно чужой
  // статьи и даже от второго потомка у страницы, которая и так служебная.
  const путиДерева = путиСтатей(repo, наблюдаемые, своиКорни);
  const категория = категорияПоПутям(rel, путиДерева, наблюдаемые);
  // **Байты читаются РОВНО один раз и отдаются зовущему.** Прочитай их отпечаток и правила порознь —
  // и правка между двумя чтениями разорвала бы снимок внутри одного захода: отпечаток отвечал бы за
  // одни байты, а вердикт выносился бы по другим.
  const байты = прочитать(repo, rel);
  const снимок = [{путь: rel, содержимое: байты?.toString('utf8') ?? ''}];
  const находки = проверитьМестные(снимок, категория, наблюдаемые, {однаВерсия: true});

  const ключи = [...new Set([...НАСТРОЙКИ_ПРОВЕРОК, ...прочитанные])].sort();
  const срез = {
    пути: [rel],
    категория,
    байты,
    ключи,
    отпечаток: отпечаток(rel, категория, байты, settings, ключи),
  };

  return {срез, находки, прошла: подготовкаПрошла(находки)};
}

/**
 * Заслон снимка подготовки: отпечаток обязателен, обязан совпасть и обязан быть зелёным.
 *
 * Стоит у ВСЕХ ручек хода публикации — состава, полной сборки и записи. Стой он у одной, снимок
 * держался бы до первого же запроса мимо окна: следующие две ручки принимали бы что угодно.
 *
 * **Зелёная подготовка доказывается здесь заново, а не берётся у зовущего.** Прежде решение о
 * препятствиях принимало окно: сервер видел только отпечаток и записывал статью, у которой
 * подготовка красная, — достаточно было прислать тело запроса самому. Проверки судят по тем же
 * входам, которые отпечаток и описывает, поэтому пересчёт ничего не стоит и ничему не противоречит.
 *
 * Порядок отказов именно такой. Нет отпечатка — запрос пришёл мимо окна, доказывать нечем.
 * Не совпал — вход проверок изменился, и прежний вердикт больше ничего не обещает. Совпал, но
 * подготовка красная — проверки и вправду нашли препятствие, и это отказ по существу, а не подмена.
 *
 * Возвращает `{код, подготовка, блокеры}`: `код === null` — путь открыт.
 */
export function сверитьПодготовку({repo, rel, settings, ждали}) {
  if (typeof ждали !== 'string' || ждали === '') {
    return {код: 'нетСнимка', подготовка: null, блокеры: []};
  }

  const подготовка = подготовкаОткрытой(repo, rel, settings);
  if (подготовка === null || ждали !== подготовка.срез.отпечаток) {
    return {код: 'статьяИзменилась', подготовка, блокеры: []};
  }

  if (!подготовка.прошла) {
    return {
      код: 'подготовкаНеПрошла',
      подготовка,
      блокеры: подготовка.находки.filter((находка) => находка.уровень === БЛОКЕР),
    };
  }

  return {код: null, подготовка, блокеры: []};
}

/** Байты открытой версии. Файла нет на месте — `null`, и отпечаток отметит это своим знаком. */
function прочитать(repo, rel) {
  try {
    return fs.readFileSync(path.join(repo, rel));
  } catch {
    return null;
  }
}

/**
 * Отпечаток входов подготовки.
 *
 * Куски отделяются длиной, а не знаком: путь файла может содержать любой знак, а байты статьи —
 * тем более. Со знаком-разделителем два разных снимка дали бы один поток, то есть подготовка
 * «подтвердила» бы то, чего не видела.
 *
 * Файла нет на месте — в отпечаток идёт отдельный знак, а не пустые байты: пустой файл и пропавший
 * файл дают разные вердикты, и различать их отпечаток обязан.
 */
function отпечаток(rel, категория, байты, settings, ключи) {
  const хеш = crypto.createHash('sha1');

  кусок(хеш, Buffer.from(rel, 'utf8'));
  кусок(хеш, Buffer.from(String(категория ?? ''), 'utf8'));

  // Настройки проверок идут в отпечаток постоянным порядком и в ровном виде: порядок строк в файле
  // решением человека не является, и перестановка их не должна выглядеть сменой правил. Сам перечень
  // ключей тоже идёт в отпечаток: прочитай правила в другой раз другой набор — это уже другой снимок,
  // и молча совпасть с прежним он не должен.
  for (const ключ of ключи) кусок(хеш, Buffer.from(`${ключ}${видКлюча(settings, ключ)}`, 'utf8'));
  хеш.update('|', 'utf8');

  if (Buffer.isBuffer(байты)) {
    хеш.update('+', 'utf8');
    кусок(хеш, байты);
  } else {
    хеш.update('-', 'utf8');
  }

  return хеш.digest('hex');
}

/**
 * Настройка в отпечатке: НАЛИЧИЕ ключа и только потом его значение.
 *
 * Спросить настройку можно тремя разными вопросами, и ответы у них разные. Ключа нет вовсе; ключ
 * есть, но пуст; ключ есть со значением. Правило, решающее по `'ключ' in settings` или по
 * `Object.hasOwn`, различает их все, а значение у первых двух одинаково никакое. Слепи программа их
 * в один вид — вердикт менялся бы при прежнем отпечатке, и наблюдение за наличием ключа теряло бы
 * смысл, едва его завели.
 *
 * Своё и унаследованное тоже разведены: `in` отвечает «да» и на ключ из прототипа, а `Object.hasOwn`
 * — нет.
 */
function видКлюча(settings, ключ) {
  const дом = settings === null || settings === undefined ? {} : Object(settings);
  const свой = Object.hasOwn(дом, ключ);
  const есть = ключ in дом;

  if (!есть) return '·нет';
  if (дом[ключ] === undefined) return свой ? '·пусто' : '·пустоЧужое';

  return `${свой ? '=' : '~'}${JSON.stringify(ровныйВид(дом[ключ]))}`;
}

/**
 * Значение настройки в ровном виде: ключи объектов по алфавиту, всё остальное как есть.
 *
 * Порядок ключей внутри `settings.json` смысла не несёт — от перестановки строк ни одно правило не
 * меняется. Считай программа отпечаток от сырого вида, такая перестановка останавливала бы
 * публикацию словами «статья изменилась», хотя человек не трогал ни статью, ни правила.
 */
function ровныйВид(значение) {
  if (Array.isArray(значение)) return значение.map(ровныйВид);
  if (значение !== null && typeof значение === 'object') {
    return Object.fromEntries(Object.keys(значение).sort().map((ключ) => [ключ, ровныйВид(значение[ключ])]));
  }

  return значение;
}

/** Кусок в отпечаток: сначала длина в байтах, потом сами байты. Границу задаёт длина. */
function кусок(хеш, байты) {
  хеш.update(`${байты.length}:`, 'utf8');
  хеш.update(байты);
}
