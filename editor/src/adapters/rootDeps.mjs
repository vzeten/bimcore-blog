// Собственные корневые зависимости проекта: есть ли они на самом деле и те ли они.
//
// **Проверка ранняя и честная.** Сборщик, запущенный без зависимостей, падает где-то в середине
// чужим текстом про ненайденный модуль, и человек читает это как поломку своей статьи. Поэтому
// зависимости проверяются ДО создания копии, коммита и запуска сборщика, а отказ говорит словами.
//
// **Успехом считаются только СВОИ зависимости.** Чужая рабочая копия, вышестоящая папка и
// `NODE_PATH` зачёту не подлежат: сборка, которая прошла на них, доказывает работоспособность
// чужого дерева, а не этого. Поэтому каталог обязан быть настоящим каталогом внутри самого корня,
// а не соединением наружу, и каждая объявленная зависимость обязана лежать физически в нём.
//
// Полнота проверяется по ПРЯМЫМ зависимостям корня: их список задан самим проектом, а обход всего
// дерева установленных пакетов стоил бы секунд на каждой сборке и ничего сверх этого не доказал.

import fs from 'node:fs';
import path from 'node:path';

/** Имя папки зависимостей. Задано не нами — так их зовёт npm, настройкой это не бывает. */
const ЗАВИСИМОСТИ = 'node_modules';

/** Имя сборщика сайта. Чужой формат: так пакет назван его авторами. */
const СБОРЩИК = '@docusaurus/core';

/** Путь к сборщику внутри дерева зависимостей. Своей копии сборщика у программы нет и быть не должно. */
export const путьСборщика = (корень) =>
  path.join(корень, ЗАВИСИМОСТИ, ...СБОРЩИК.split('/'), 'bin', 'docusaurus.mjs');

/**
 * Проверить корневые зависимости. Возвращает `{версия}` либо `{ошибка, подробность}`.
 *
 * `корень` — папка проекта, в которой обязаны лежать СВОИ зависимости. Для сборки плана это
 * настоящий репозиторий, а не временная копия: копия зависимостей не заводит и берёт их подъёмом
 * по дереву, как это делает сам Node.
 */
export function проверитьЗависимости(корень) {
  const описание = прочитатьJson(path.join(корень, 'package.json'));
  if (описание === null) return {ошибка: 'нетКорня', подробность: корень};

  const место = своёМесто(корень);
  if (место.ошибка) return место;

  const объявленные = описание.dependencies ?? {};
  const нехватка = Object.keys(объявленные).filter((имя) => !установлена(место.путь, имя));
  if (нехватка.length > 0) return {ошибка: 'зависимостиНеполны', подробность: перечислить(нехватка)};

  return проверитьСборщик(место.путь, объявленные[СБОРЩИК]);
}

/**
 * Копия среды без `NODE_PATH` в любом написании.
 *
 * Переменная заставляет Node искать модули в постороннем дереве. Оставить её — значит разрешить
 * сборке добрать недостающее у соседа и объявить это своим успехом. Регистр не учитывается: в
 * Windows переменные среды регистронезависимы, и `Node_Path` сработал бы точно так же.
 */
export function средаБезNODE_PATH(среда = process.env) {
  const чистая = {};

  for (const [ключ, значение] of Object.entries(среда)) {
    if (ключ.toUpperCase() === 'NODE_PATH') continue;
    чистая[ключ] = значение;
  }

  return чистая;
}

/**
 * Настоящее место дерева зависимостей. Возвращает `{путь}` либо `{ошибка, подробность}`.
 *
 * Соединение каталогов (`junction`) и символическая ссылка отклоняются до всякого чтения: по такой
 * связи живут зависимости другой рабочей копии, а её уборка или переустановка меняют то, чем
 * собирается этот проект. Пустая папка — это «зависимостей нет», а не «есть»: именно так выглядит
 * каталог, из которого их вычистили.
 */
function своёМесто(корень) {
  const каталог = path.join(корень, ЗАВИСИМОСТИ);

  let сведения = null;
  try {
    сведения = fs.lstatSync(каталог);
  } catch {
    return {ошибка: 'зависимостейНет', подробность: каталог};
  }

  if (сведения.isSymbolicLink()) return {ошибка: 'зависимостиСсылка', подробность: каталог};
  if (!сведения.isDirectory()) return {ошибка: 'зависимостейНет', подробность: каталог};

  let настоящий = null;
  let свой = null;
  try {
    настоящий = fs.realpathSync(каталог);
    свой = path.join(fs.realpathSync(корень), ЗАВИСИМОСТИ);
  } catch {
    return {ошибка: 'зависимостейНет', подробность: каталог};
  }

  if (настоящий !== свой) return {ошибка: 'зависимостиЧужие', подробность: настоящий};

  try {
    if (fs.readdirSync(настоящий).length === 0) return {ошибка: 'зависимостейНет', подробность: каталог};
  } catch {
    return {ошибка: 'зависимостейНет', подробность: каталог};
  }

  return {путь: настоящий};
}

/**
 * Стоит ли пакет на самом деле: своя папка с описанием ВНУТРИ дерева зависимостей.
 *
 * Одного существования папки мало. Пакет, подложенный ссылкой на другую рабочую копию, выглядит
 * установленным, а обновляется и удаляется вместе с чужим деревом.
 */
function установлена(дерево, имя) {
  const папка = path.join(дерево, ...имя.split('/'));
  if (прочитатьJson(path.join(папка, 'package.json')) === null) return false;

  try {
    const настоящая = fs.realpathSync(папка);
    return настоящая === папка || настоящая.startsWith(дерево + path.sep);
  } catch {
    return false;
  }
}

/**
 * Тот ли сборщик установлен. Возвращает `{версия}` либо `{ошибка, подробность}`.
 *
 * Точно названная версия обязана совпасть до знака: проект закрепил её нарочно, и собранный другой
 * версией сайт — это не проверка этого сайта. У записи с допуском (`^`, `~`) сверяется старший
 * номер: именно он отделяет несовместимый выпуск от обычного обновления.
 */
function проверитьСборщик(дерево, объявлено) {
  const описание = прочитатьJson(path.join(дерево, ...СБОРЩИК.split('/'), 'package.json'));
  if (описание === null) return {ошибка: 'сборщикаНет', подробность: СБОРЩИК};

  const установленная = String(описание.version ?? '');
  if (объявлено !== undefined && !версияГодится(String(объявлено), установленная)) {
    return {ошибка: 'сборщикНеТот', подробность: `нужен ${объявлено}, стоит ${установленная || 'неизвестно'}`};
  }

  const файл = path.join(дерево, ...СБОРЩИК.split('/'), 'bin', 'docusaurus.mjs');
  let настоящий = null;
  try {
    настоящий = fs.realpathSync(файл);
  } catch {
    return {ошибка: 'сборщикаНет', подробность: файл};
  }

  if (настоящий !== файл && !настоящий.startsWith(дерево + path.sep)) {
    return {ошибка: 'сборщикЧужой', подробность: настоящий};
  }

  return {версия: установленная};
}

/** Годится ли установленная версия под объявленную запись. */
function версияГодится(объявлено, установлена) {
  if (/^\d+\.\d+\.\d+/.test(объявлено)) return установлена === объявлено;

  const чистая = объявлено.replace(/^[^\d]*/, '');
  if (чистая === '') return установлена !== '';

  return установлена.split('.')[0] === чистая.split('.')[0];
}

/** Прочитать JSON-описание. Нет файла или он битый — `null`: и то и другое значит «пакета нет». */
function прочитатьJson(файл) {
  try {
    return JSON.parse(fs.readFileSync(файл, 'utf8'));
  } catch {
    return null;
  }
}

/** Короткий перечень для человека: первые имена и счёт остальных, а не простыня в сотню строк. */
function перечислить(имена, сколько = 5) {
  const начало = имена.slice(0, сколько).join(', ');
  return имена.length > сколько ? `${начало} и ещё ${имена.length - сколько}` : начало;
}
