// Запись набора изменений «Доработать»: статья и файлы её папки либо целиком, либо никак.
//
// Многофайловой атомарности у диска нет, поэтому она делается откатом: каждый шаг знает, как
// вернуть прежние байты, и любой сбой раскручивает сделанное в обратном порядке из байтов снимка.
// Порядок шагов выбран так, чтобы промежуточное состояние было безопаснее: сначала появляются
// новые файлы (занятое имя — отказ до единой правки статьи), потом статья, удаления — последними.
// Записи идут через служебную папку редактора теми же правилами, что у замены картинки.

import fs from 'node:fs';
import path from 'node:path';

import {ApiError} from './httpBody.mjs';
import {записатьНовый, записатьПоверх} from './assetGuards.mjs';

/**
 * Записать разницу со снимком. `снимок.байтыТекста` и `снимок.файлы` — прежние байты для отката.
 * Бросает ошибку шага после полного отката; частичных байтов на диске не остаётся.
 */
export function записатьНабор({repo, dir, файлСтатьи, изменения, снимок, ошибки}) {
  const откат = [];
  const шаг = (вперёд, назад) => {
    вперёд();
    откат.push(назад);
  };

  try {
    for (const {имя, байты} of изменения.файлы.filter((ф) => ф.байты !== null)) {
      const цель = path.join(dir, имя);
      const было = снимок.файлы.get(имя) ?? null;
      if (было !== null) {
        шаг(() => записатьПоверх(repo, цель, байты), () => записатьПоверх(repo, цель, было));
      } else {
        // Файла в снимке не было — значит его нет и на диске; появился — операция устарела.
        шаг(() => {
          if (!записатьНовый(repo, цель, байты)) throw new ApiError(409, ошибки['доработкаСнимокУстарел']);
        }, () => fs.rmSync(цель, {force: true}));
      }
    }

    if (изменения.текст !== null) {
      шаг(
        () => записатьПоверх(repo, файлСтатьи, Buffer.from(изменения.текст, 'utf8')),
        () => записатьПоверх(repo, файлСтатьи, снимок.байтыТекста),
      );
    }

    for (const {имя} of изменения.файлы.filter((ф) => ф.байты === null)) {
      const цель = path.join(dir, имя);
      const было = снимок.файлы.get(имя);
      шаг(() => fs.rmSync(цель), () => записатьПоверх(repo, цель, было));
    }
  } catch (ошибка) {
    for (const назад of откат.reverse()) {
      try {
        назад();
      } catch (сбойОтката) {
        console.error(сбойОтката);
      }
    }
    throw ошибка;
  }
}
