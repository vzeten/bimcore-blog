// Запись набора изменений «Доработать»: статья и файлы её папки — одна файловая операция.
//
// Многофайловой атомарности у диска нет, поэтому она делается откатом: каждый шаг знает, как
// вернуть прежние байты, и любой сбой раскручивает сделанное в обратном порядке из байтов снимка.
// Порядок: новые файлы (занятое имя — отказ до единой правки статьи), перезаписи, статья, удаления.
// Сбой самого отката не прячется: наружу уходит авария с перечнем невосстановленных файлов.
// `диск` подставляется проверками; в работе это те же записи через служебную папку редактора.

import fs from 'node:fs';
import path from 'node:path';

import {ApiError} from './httpBody.mjs';
import {записатьНовый, записатьПоверх} from './assetGuards.mjs';

export class АварияОтката extends ApiError {
  constructor(текст, невосстановлено) {
    super(500, текст);
    this.невосстановлено = невосстановлено;
  }
}

export function дискРедактора(repo) {
  return {
    поверх: (цель, байты) => записатьПоверх(repo, цель, байты),
    новый: (цель, байты) => записатьНовый(repo, цель, байты),
    удалить: (цель) => fs.rmSync(цель),
  };
}

/** Записать разницу со снимком; `снимок.байтыТекста` и `снимок.файлы` — прежние байты для отката. */
export function записатьНабор({repo, dir, файлСтатьи, изменения, снимок, ошибки, диск = дискРедактора(repo)}) {
  const откат = [];
  const шаг = (вперёд, назад) => {
    вперёд();
    откат.push(назад);
  };

  try {
    for (const {имя, байты} of изменения.файлы.filter((ф) => ф.байты !== null)) {
      const цель = path.join(dir, имя);
      const было = снимок.файлы.get(имя) ?? null;
      if (было !== null) шаг(() => диск.поверх(цель, байты), {цель, назад: () => диск.поверх(цель, было)});
      else {
        // Файла в снимке не было — нет и на диске; появился — операция устарела.
        шаг(() => {
          if (!диск.новый(цель, байты)) throw new ApiError(409, ошибки['доработкаСнимокУстарел']);
        }, {цель, назад: () => диск.удалить(цель)});
      }
    }
    if (изменения.текст !== null) {
      шаг(() => диск.поверх(файлСтатьи, Buffer.from(изменения.текст, 'utf8')), {цель: файлСтатьи, назад: () => диск.поверх(файлСтатьи, снимок.байтыТекста)});
    }
    for (const {имя} of изменения.файлы.filter((ф) => ф.байты === null)) {
      const цель = path.join(dir, имя);
      const было = снимок.файлы.get(имя);
      шаг(() => диск.удалить(цель), {цель, назад: () => диск.поверх(цель, было)});
    }
  } catch (ошибка) {
    const невосстановлено = [];
    for (const {цель, назад} of откат.reverse()) {
      try {
        назад();
      } catch (сбой) {
        console.error(сбой);
        невосстановлено.push(path.relative(repo, цель).split(path.sep).join('/'));
      }
    }
    if (невосстановлено.length > 0) {
      throw new АварияОтката(ошибки['доработкаАвария'].replace('{файлы}', невосстановлено.join(', ')), невосстановлено);
    }
    throw ошибка;
  }
}
