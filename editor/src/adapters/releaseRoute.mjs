/** Обрабатывает `/api/release`: состав и быстрые проверки. Возвращает true, если запрос был к ней. */
export async function releaseRoute({req, res, url, repo, editorDir, settings, git, тело, insideRepo, send}) {
  if (url.pathname !== '/api/release' || req.method !== 'POST') return false;

  const payload = await тело(req);

  const плохоеТело = badFields(payload, [], settings['ошибкиСервера']);
  if (плохоеТело) {
    send(res, плохоеТело.status, {error: плохоеТело.error});
    return true;
  }

  const rel = payload.path;
  const bad = badPath(
    [rel],
    (p) => insideRepo(path.join(repo, p)),
    (p) => fs.existsSync(path.join(repo, p)),
    settings['ошибкиСервера'],
  );
  if (bad) {
    send(res, bad.status, {error: bad.error});
    return true;
  }

  // Заслон пути стоит здесь, а не в окне: перечень этой ручки станет источником записи в git, и
  // «из окна такой путь не приходит» защитой не является.
  if (!годныйПуть(rel, settings)) {
    send(res, 400, {error: settings['ошибкиСервера']['неПутьСтатьи']});
    return true;
  }
  // Отмеченные в окне языки (этап 3). Каждая версия проверяется тем же заслоном пути, что и открытая.
  const отмечены = отмеченныеВерсии({payload, rel, repo, settings, insideRepo});
  if (отмечены.ошибка) {
    send(res, 400, {error: отмечены.ошибка});
    return true;
  }
  const {версии} = отмечены;
  const ждали = ждатьПодготовки(payload, rel);

  // Основа закрепляется первой: без неё неизвестно, чем сайт является сейчас, а значит и чем он
  // станет. Это свежий `origin/main`; ни `HEAD`, ни ветка человека подменой не служат.
  //
  // Свой коммит, который ждёт отправки от этой же основы, надо дослать, а не строить рядом второй
  // план: два коммита от одной вершины вместе не уезжают. Окно по этому коду досылает его само.
  // Разбор очереди — чтение, проверка и запись — идёт под общим замком публикации, тем же, что у
  // записи и отправки: иначе он мог бы стереть запись, которую в этот миг делает другой заход.
  // Проверки под замком не идут: он отпускается сразу после разбора.
  const основа = await подЗамком(() => закрепитьОснову({git, repo, editorDir, settings}));
  if (основа.ошибка) {
    send(res, 409, {error: отказОсновы(основа.ошибка, settings), код: основа.ошибка});
    return true;
  }

  // **Снимок один на весь ход, и спрашивают его ОБЕ ручки — состав и запись.** Проверки судили о
  // том, что лежало на диске тогда; если файл или правила проверок с тех пор изменились — чужим
  // окном, внешним редактором, правкой настроек, — их вердикт больше ничего не обещает, и считать
  // по нему состав значит показать человеку перечень, за который никто не отвечал.
  //
  // Отпечаток обязателен, а не «сверяется, если пришёл»: необязательная сверка снимается пустой
  // строкой, то есть отменяется первым же запросом мимо окна.
  //
  // Зелёная подготовка доказывается ЗДЕСЬ, а не берётся у окна: тело запроса пишет не окно. Снимок
  // у каждой отмеченной версии свой, и сверяется каждый.
  const снимок = сверитьВерсии({repo, settings, версии, ждали});
  if (снимок.код !== null) {
    send(res, 409, {
      error: settings['отказыКоммита'][снимок.код],
      код: снимок.код,
      находки: снимок.блокеры,
    });
    return true;
  }

  // **Дата записи блога сверяется с той же закреплённой основой.** Окно проставило её до проверок по
  // основе, закреплённой тогда; пока человек читал, сайт мог уйти вперёд — например, туда уехал
  // соседний язык этой же записи. Считать состав по дате от вчерашнего сайта значит
  // обещать одно, а зафиксировать другое. Расхождение — отказ с честным кодом, а не молчаливая правка.
  const датаНеТа = await датыВерсий({git, repo, settings, основа: основа.основа, срезы: снимок.срезы});
  if (датаНеТа) {
    send(res, 409, {error: settings['отказыКоммита'][датаНеТа], код: датаНеТа});
    return true;
  }

  const план = await готовыйПлан({git, repo, settings, rel, основа: основа.основа, версии});
  if (план.ошибка) {
    send(res, 409, {error: settings['ошибкиСервера']['нетФайла'], код: план.ошибка});
    return true;
  }

  // Отпечаток плана считается ОДИН раз на заход и от того же плана, что уходит человеку и в запись.
  const отпечатокСейчас = отпечатокПлана({основа: основа.основа, родитель: основа.основа, записи: план.записи});

  // **Снимок держится и ВНУТРИ одного захода.** Отпечаток входов снят раньше, чем построен план, и
  // между этими чтениями поменяться мог не только сам файл. Появившаяся рядом статья меняет пути
  // СВОЕГО дерева, а с ними категорию и требования к полям: сверка байтов открытой версии этого не
  // видит вовсе. Поэтому отпечаток пересчитывается ЦЕЛИКОМ, а байты сверяются вдобавок — они
  // единственное, что план и снимок обязаны иметь общим побайтно.
  const снова = сверитьВерсии({repo, settings, версии, ждали});
  if (снова.код !== null) {
    send(res, 409, {error: settings['отказыКоммита'][снова.код], код: снова.код, находки: снова.блокеры});
    return true;
  }

  if (публикацияВозможна(план) && !тежеБайтыВерсий(план.записи, снимок.срезы)) {
    send(res, 409, {error: settings['отказыКоммита']['статьяИзменилась'], код: 'статьяИзменилась'});
    return true;
  }

  const времянка = path.join(editorDir, settings['хранение']['папкаПубликаций'], 'сверка');
  const возможна = публикацияВозможна(план);
  const изменённые = возможна
    ? await изменённыеПротивОсновы({git, основа: основа.основа, записи: план.записи, времянка})
    : [];
  // Быстрые проверки судят о том, что ИЗМЕНИТ сайт: то, что там уже лежит, собрано и живо.
  const находки = возможна && изменённые !== null
    ? (await быстрыеПроверки({git, repo, settings, основа: основа.основа, записи: план.записи, изменённые})).находки
    : [];

  send(res, 200, {
    path: rel,
    // Отпечаток показанного плана. Запись примет его обратно и откажет, если план с тех пор стал
    // другим: человек соглашается на конкретный перечень, а не на «то, что будет потом».
    отпечаток: отпечатокСейчас,
    файлы: план.записи.map((запись) => ({
      путь: запись.путь, назначение: запись.назначение, локаль: запись.локаль, источник: запись.источник,
    })),
    разрывы: план.разрывы,
    отказ: план.отказ,
    // Что уберётся из папок отмеченных версий. По этому перечню ход решает, звать ли уборку, когда
    // публиковать больше нечего: список человеку уже показан, и файл обязан уйти.
    лишние: (план.лишние ?? []).map((своя) => ({путь: своя.путь, файлы: своя.файлы.map(имяФайла)})),
    находки,
    можно: возможна && !находки.some((находка) => находка.уровень === БЛОКЕР),
    // Страница версии уходит с сайта («Недоступно» у живой версии) и в скольких статьях уберутся
    // ссылки на неё: после отправки ход убирает их и на компьютере.
    ссылкиВСтатьях: план.ссылкиВСтатьях ?? 0,
    версияУходит: план.версияУходит === true,
    уходят: план.уходят ?? [],
    // Спросить хранилище не удалось — итога нет вовсе: «ничего не меняется» здесь было бы враньём.
    итог: изменённые === null ? null : итогВыпуска({
      файлы: план.записи,
      изменённые,
      // Заглушку человек не писал: её надо назвать своим именем, а не «изменилась».
      заглушки: план.записи.filter((запись) => запись.источник === СОЗДАНО).map((запись) => запись.локаль),
      скрытые: скрытыеВПлане(план.записи),
      всеЛокали: Object.keys(settings['локали']),
      // Языки, которые уже лежат на сайте. Без них язык, давно там живущий и в план не попавший,
      // выглядел бы как «версии нет» — то есть программа соврала бы про готовый перевод.
      наСайте: план.языки.filter((язык) => язык.опубликован === true).map((язык) => язык.локаль),
    }),
  });
  return true;
}

/**
 * Какие языковые версии плана скрыты на сайте: в меню их нет, живут только по прямой ссылке.
 * Считается по БАЙТАМ ПЛАНА, а не по файлу с диска: уедет именно то, что в плане.
 */
function скрытыеВПлане(записи) {
  return записи
    .filter((запись) => запись.назначение === ВЕРСИЯ && Buffer.isBuffer(запись.байты))
    .filter((запись) => isUnlisted(splitArticle(запись.байты.toString('utf8')).frontmatterRaw))
    .map((запись) => запись.локаль);
}

/** Закрепить основу и разобрать очередь против неё. Возвращает `{основа}` либо `{ошибка}`. */
async function закрепитьОснову({git, repo, editorDir, settings}) {
  const основа = await закреплённаяОснова({git, settings});
  if (основа.ошибка) return основа;

  const очередь = await разобратьОчередь({git, repo, editorDir, settings, основа: основа.основа});
  if (очередь.ошибка) return очередь;
  if (очередь.ожидающие.length > 0) return {ошибка: 'естьНеотправленное'};

  return основа;
}

/** Выполнить под замком публикации. Замок занят — отказ тем же кодом, что у записи и отправки. */
async function подЗамком(дело) {
  if (!взятьЗамок()) return {ошибка: 'идётЗапись'};

  try {
    return await дело();
  } finally {
    отпустить();
  }
}

/** Слова человеку про отказ основы и очереди. Коды общие с отправкой: человек читает знакомые фразы. */
const отказОсновы = (код, settings) => settings['отказыОтправки'][код]
  ?? settings['отказыКоммита'][код]
  ?? код;
