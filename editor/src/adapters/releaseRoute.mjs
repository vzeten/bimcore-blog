// Ручки предварительного выпуска: что уедет на сайт и переживёт ли это полная сборка.
//
// **Git не меняется ничем:** ни индексом, ни объектной базой, ни коммитом, ни отправкой. Эти две
// ручки только считают план и проверяют его сборкой. Запись живёт отдельным модулем
// (`publishRoute.mjs`) и считает план тем же кодом, что и здесь.
//
// **Показывается ПЛАН, а не рабочее дерево.** Уезжает не то, что лежит на диске: у соседнего языка
// там может быть начатый человеком перевод, а на сайт уйдёт заглушка. Поэтому и «что изменится»
// считается сравнением байтов плана с закреплённой основой, а не разницей дерева с веткой.

import path from 'node:path';
import fs from 'node:fs';

import {ВЕРСИЯ, СОЗДАНО, публикацияВозможна} from '../core/publishPlan.mjs';
import {итогВыпуска} from '../core/releaseSummary.mjs';
import {годныйПуть} from './releaseFacts.mjs';
import {сверитьПодготовку} from './prepareStamp.mjs';
import {закреплённаяОснова} from './publishBase.mjs';
import {разобратьОчередь} from './publishRepair.mjs';
import {взятьЗамок, отпустить} from './publishLock.mjs';
import {готовыйПлан, изменённыеПротивОсновы} from './publishFacts.mjs';
import {отпечатокПлана} from './planBytes.mjs';
import {собратьПлан} from './planBuild.mjs';
import {запомнитьСборку} from './buildMemory.mjs';
import {причинаПадения} from './siteBuild.mjs';
import {isUnlisted} from '../core/frontmatterRules.mjs';
import {splitArticle} from '../core/articleFile.mjs';
import {badFields, badPath} from './httpBody.mjs';

/**
 * Идёт ли сборка прямо сейчас. Две полные сборки мешают друг другу: они пишут в одно место, и чей
 * ответ получит человек, предсказать нельзя. Признак один на сервер — сборка и так одна на весь сайт.
 */
let сборкаИдёт = false;

/**
 * Обрабатывает `/api/release` (состав) и `/api/release/build` (полная сборка).
 * Возвращает true, если запрос был к одной из них.
 */
export async function releaseRoute({req, res, url, repo, editorDir, settings, git, тело, insideRepo, send, запуск}) {
  const это = url.pathname === '/api/release' || url.pathname === '/api/release/build';
  if (!это || req.method !== 'POST') return false;

  const payload = await тело(req);

  const плохоеТело = badFields(payload, [], settings['ошибкиСервера']);
  if (плохоеТело) {
    send(res, плохоеТело.status, {error: плохоеТело.error});
    return true;
  }

  const rel = payload.path;
  const bad = badPath(
    [rel],
    (p) => insideRepo(path.join(repo, p)),
    (p) => fs.existsSync(path.join(repo, p)),
    settings['ошибкиСервера'],
  );
  if (bad) {
    send(res, bad.status, {error: bad.error});
    return true;
  }

  // Заслон пути стоит здесь, а не в окне: перечень этой ручки станет источником записи в git, и
  // «из окна такой путь не приходит» защитой не является.
  if (!годныйПуть(rel, settings)) {
    send(res, 400, {error: settings['ошибкиСервера']['неПутьСтатьи']});
    return true;
  }

  // Основа закрепляется первой: без неё неизвестно, чем сайт является сейчас, а значит и чем он
  // станет. Это свежий `origin/main`; ни `HEAD`, ни ветка человека подменой не служат.
  //
  // Свой коммит, который ждёт отправки от этой же основы, надо дослать, а не строить рядом второй
  // план: два коммита от одной вершины вместе не уезжают. Окно по этому коду досылает его само.
  // Разбор очереди — чтение, проверка и запись — идёт под общим замком публикации, тем же, что у
  // записи и отправки: иначе он мог бы стереть запись, которую в этот миг делает другой заход.
  // Сборка сайта под замком не идёт: он отпускается сразу после разбора.
  const основа = await подЗамком(() => закрепитьОснову({git, repo, editorDir, settings}));
  if (основа.ошибка) {
    send(res, 409, {error: отказОсновы(основа.ошибка, settings), код: основа.ошибка});
    return true;
  }

  // **Снимок один на весь ход, и спрашивают его ОБЕ ручки.** Проверки судили о том, что лежало на
  // диске тогда; если файл или правила проверок с тех пор изменились — чужим окном, внешним
  // редактором, правкой настроек, — их вердикт больше ничего не обещает, и считать по нему состав
  // значит показать человеку перечень, за который никто не отвечал. Сборка идёт минуты и обязана
  // спросить то же самое: снимок, который держится до неё и обрывается на ней, снимком не является.
  //
  // Отпечаток обязателен, а не «сверяется, если пришёл»: необязательная сверка снимается пустой
  // строкой, то есть отменяется первым же запросом мимо окна.
  //
  // Зелёная подготовка доказывается ЗДЕСЬ, а не берётся у окна: тело запроса пишет не окно.
  const снимок = сверитьПодготовку({repo, rel, settings, ждали: payload['отпечатокПодготовки']});
  if (снимок.код !== null) {
    send(res, 409, {
      error: settings['отказыКоммита'][снимок.код],
      код: снимок.код,
      находки: снимок.блокеры,
    });
    return true;
  }
  const срез = снимок.подготовка.срез;

  const план = await готовыйПлан({git, repo, settings, rel, основа: основа.основа});
  if (план.ошибка) {
    send(res, 409, {error: settings['ошибкиСервера']['нетФайла'], код: план.ошибка});
    return true;
  }

  // Отпечаток плана считается ОДИН раз на заход и от того же плана, что уходит человеку и в сборку.
  const отпечатокСейчас = отпечатокПлана({основа: основа.основа, родитель: основа.основа, записи: план.записи});

  // **Снимок держится и ВНУТРИ одного захода.** Отпечаток входов снят раньше, чем построен план, и
  // между этими чтениями поменяться мог не только сам файл. Появившаяся рядом статья меняет пути
  // СВОЕГО дерева, а с ними категорию и требования к полям: сверка байтов открытой версии этого не
  // видит вовсе. Поэтому отпечаток пересчитывается ЦЕЛИКОМ, а байты сверяются вдобавок — они
  // единственное, что план и снимок обязаны иметь общим побайтно.
  const снова = сверитьПодготовку({repo, rel, settings, ждали: payload['отпечатокПодготовки']});
  if (снова.код !== null) {
    send(res, 409, {error: settings['отказыКоммита'][снова.код], код: снова.код, находки: снова.блокеры});
    return true;
  }

  const своя = план.записи.find((запись) => запись.путь === rel);
  const тежеБайты = Buffer.isBuffer(своя?.байты) && Buffer.isBuffer(срез?.байты)
    && своя.байты.equals(срез.байты);
  if (публикацияВозможна(план) && !тежеБайты) {
    send(res, 409, {error: settings['отказыКоммита']['статьяИзменилась'], код: 'статьяИзменилась'});
    return true;
  }

  const времянка = path.join(editorDir, settings['хранение']['папкаПубликаций'], 'сверка');

  if (url.pathname === '/api/release') {
    const изменённые = публикацияВозможна(план)
      ? await изменённыеПротивОсновы({git, основа: основа.основа, записи: план.записи, времянка})
      : [];

    send(res, 200, {
      path: rel,
      // Отпечаток показанного плана. Сборка и запись примут его обратно и откажут, если план с тех
      // пор стал другим: человек соглашается на конкретный перечень, а не на «то, что будет потом».
      отпечаток: отпечатокСейчас,
      файлы: план.записи.map((запись) => ({
        путь: запись.путь, назначение: запись.назначение, локаль: запись.локаль, источник: запись.источник,
      })),
      разрывы: план.разрывы,
      отказ: план.отказ,
      можно: публикацияВозможна(план),
      // Спросить хранилище не удалось — итога нет вовсе: «ничего не меняется» здесь было бы враньём.
      итог: изменённые === null ? null : итогВыпуска({
        файлы: план.записи,
        изменённые,
        // Заглушку человек не писал: её надо назвать своим именем, а не «изменилась».
        заглушки: план.записи.filter((запись) => запись.источник === СОЗДАНО).map((запись) => запись.локаль),
        скрытые: скрытыеВПлане(план.записи),
        всеЛокали: Object.keys(settings['локали']),
        // Языки, которые уже лежат на сайте. Без них язык, давно там живущий и в план не попавший,
        // выглядел бы как «версии нет» — то есть программа соврала бы про готовый перевод.
        наСайте: план.языки.filter((язык) => язык.опубликован === true).map((язык) => язык.локаль),
      }),
    });
    return true;
  }

  // Сборка запускается только тогда, когда план доказан целиком: собирать сайт ради статьи, состава
  // которой мы не знаем, значит обещать проверку, которой не было.
  if (!публикацияВозможна(план)) {
    send(res, 409, {
      error: settings['ошибкиСервера']['составНеДоказан'],
      разрывы: план.разрывы,
      отказ: план.отказ,
    });
    return true;
  }

  // Собирается ровно тот план, который человеку показали. Разошёлся — сборка проверяла бы одно, а
  // согласие относилось бы к другому. Отпечаток обязателен: без него сборка не начинается вовсе.
  const показанный = payload['отпечаток'];
  if (typeof показанный !== 'string' || показанный === '') {
    send(res, 409, {error: settings['отказыКоммита']['нетСнимка'], код: 'нетСнимка'});
    return true;
  }
  if (показанный !== отпечатокСейчас) {
    send(res, 409, {error: settings['отказыКоммита']['статьяИзменилась'], код: 'статьяИзменилась'});
    return true;
  }

  if (сборкаИдёт) {
    send(res, 409, {error: settings['ошибкиСервера']['сборкаУжеИдёт']});
    return true;
  }

  // Отпечаток снимается ДО сборки: сборка отвечает за тот план, который видела на входе.
  const отпечаток = отпечатокСейчас;

  сборкаИдёт = true;
  let итог;
  try {
    итог = await собратьПлан({
      git, repo, основа: основа.основа, записи: план.записи,
      пределМинут: settings['сборка']['пределМинут'], запуск,
    });
  } finally {
    сборкаИдёт = false;
  }

  if (итог.ошибка) {
    запомнитьСборку(null);
    send(res, 409, {error: settings['ошибкиСервера']['составНеДоказан'], код: итог.ошибка, вывод: итог.вывод ?? ''});
    return true;
  }

  // Память живёт до перезапуска сервера и хранит всё, чем коммит докажет своё право: ту же статью,
  // тот же план, ту же основу и то самое дерево, которое собиралось.
  запомнитьСборку(итог.зелёная
    ? {путь: rel, отпечаток, основа: основа.основа, дерево: итог.дерево}
    : null);

  send(res, 200, {
    path: rel,
    зелёная: итог.зелёная,
    оборвана: итог.оборвана,
    времяМс: итог.времяМс,
    причина: итог.зелёная ? '' : причинаПадения(итог.вывод),
    вывод: итог.вывод,
  });
  return true;
}

/**
 * Какие языковые версии плана скрыты на сайте: в меню их нет, живут только по прямой ссылке.
 * Считается по БАЙТАМ ПЛАНА, а не по файлу с диска: уедет именно то, что в плане.
 */
function скрытыеВПлане(записи) {
  return записи
    .filter((запись) => запись.назначение === ВЕРСИЯ && Buffer.isBuffer(запись.байты))
    .filter((запись) => isUnlisted(splitArticle(запись.байты.toString('utf8')).frontmatterRaw))
    .map((запись) => запись.локаль);
}

/** Закрепить основу и разобрать очередь против неё. Возвращает `{основа}` либо `{ошибка}`. */
async function закрепитьОснову({git, repo, editorDir, settings}) {
  const основа = await закреплённаяОснова({git, settings});
  if (основа.ошибка) return основа;

  const очередь = await разобратьОчередь({git, repo, editorDir, settings, основа: основа.основа});
  if (очередь.ошибка) return очередь;
  if (очередь.ожидающие.length > 0) return {ошибка: 'естьНеотправленное'};

  return основа;
}

/** Выполнить под замком публикации. Замок занят — отказ тем же кодом, что у записи и отправки. */
async function подЗамком(дело) {
  if (!взятьЗамок()) return {ошибка: 'идётЗапись'};

  try {
    return await дело();
  } finally {
    отпустить();
  }
}

/** Слова человеку про отказ основы и очереди. Коды общие с отправкой: человек читает знакомые фразы. */
const отказОсновы = (код, settings) => settings['отказыОтправки'][код]
  ?? settings['отказыКоммита'][код]
  ?? код;
