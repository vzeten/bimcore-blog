// Ручки предварительного выпуска: состав файлов статьи и полная сборка сайта.
//
// **Git не трогается ничем:** ни индексом, ни коммитом, ни отправкой. Эти две ручки только
// показывают человеку, что уедет, и проверяют, переживёт ли это сборка сайта. Запись в git живёт
// отдельным модулем (`publishRoute.mjs`) и спрашивает состав тем же кодом, что и здесь.

import path from 'node:path';

import {выпускВозможен, составВыпуска} from '../core/release.mjs';
import {итогВыпуска} from '../core/releaseSummary.mjs';
import {годныйПуть, версииСтатьи, заглушкиВерсий, отпечатокСостава, скрытыеВерсии} from './releaseFacts.mjs';
import {расхождениеССайтом} from './gitFile.mjs';
import {запомнитьСборку} from './buildMemory.mjs';
import {причинаПадения, собратьСайт} from './siteBuild.mjs';
import {badFields, badPath} from './httpBody.mjs';
import fs from 'node:fs';

/**
 * Идёт ли сборка прямо сейчас. Две полные сборки в одной папке мешают друг другу: они пишут в одно
 * место, и чей ответ получит человек, предсказать нельзя. Признак один на сервер — сборка и так
 * одна на весь сайт.
 */
let сборкаИдёт = false;

/**
 * Обрабатывает `/api/release` (состав) и `/api/release/build` (полная сборка).
 * Возвращает true, если запрос был к одной из них.
 */
export async function releaseRoute({req, res, url, repo, settings, git, publishedRef, тело, insideRepo, send, запуск}) {
  const это = url.pathname === '/api/release' || url.pathname === '/api/release/build';
  if (!это || req.method !== 'POST') return false;

  const payload = await тело(req);

  const плохоеТело = badFields(payload, [], settings['ошибкиСервера']);
  if (плохоеТело) {
    send(res, плохоеТело.status, {error: плохоеТело.error});
    return true;
  }

  const rel = payload.path;
  const bad = badPath(
    [rel],
    (p) => insideRepo(path.join(repo, p)),
    (p) => fs.existsSync(path.join(repo, p)),
    settings['ошибкиСервера'],
  );
  if (bad) {
    send(res, bad.status, {error: bad.error});
    return true;
  }

  // Заслон пути стоит здесь, а не в окне: перечень этой ручки станет источником `git add`, и
  // «из окна такой путь не приходит» защитой не является.
  if (!годныйПуть(rel, settings)) {
    send(res, 400, {error: settings['ошибкиСервера']['неПутьСтатьи']});
    return true;
  }

  const версии = версииСтатьи(repo, rel, settings);
  const состав = составВыпуска({версии});

  if (url.pathname === '/api/release') {
    // Вместе с составом считается человеческий итог: что действительно изменится на сайте.
    // Перечень путей остаётся в ответе для технических подробностей, но решение человек принимает
    // по итогу, а не по списку файлов.
    const изменённые = await расхождениеССайтом(git, publishedRef, состав.файлы.map((файл) => файл.путь));

    send(res, 200, {
      path: rel,
      ...состав,
      можно: выпускВозможен(состав),
      // Спросить git не удалось — итога нет вовсе: «ничего не меняется» здесь было бы враньём.
      итог: изменённые === null ? null : итогВыпуска({
        файлы: состав.файлы,
        изменённые,
        заглушки: заглушкиВерсий(repo, версии, settings),
        скрытые: скрытыеВерсии(repo, версии),
        всеЛокали: Object.keys(settings['локали']),
      }),
    });
    return true;
  }

  // Сборка запускается только тогда, когда состав доказан целиком: собирать сайт ради статьи,
  // состава которой мы не знаем, значит обещать проверку, которой не было.
  if (!выпускВозможен(состав)) {
    send(res, 409, {error: settings['ошибкиСервера']['составНеДоказан'], разрывы: состав.разрывы});
    return true;
  }

  // Вторая сборка поверх первой — это две программы в одной папке: пишут они в одно место, и чей
  // ответ увидит человек, предсказать нельзя.
  if (сборкаИдёт) {
    send(res, 409, {error: settings['ошибкиСервера']['сборкаУжеИдёт']});
    return true;
  }

  // Отпечаток снимается ДО сборки: сборка отвечает за то содержимое, которое видела на входе.
  const отпечаток = отпечатокСостава(repo, состав.файлы);

  сборкаИдёт = true;
  let итог;
  try {
    итог = await собратьСайт({repo, пределМинут: settings['сборка']['пределМинут'], запуск});
  } finally {
    сборкаИдёт = false;
  }

  // Память о сборке живёт до перезапуска сервера и только для одной статьи: коммит спросит её и
  // сверит отпечаток. Перезапустили сервер — сборки нет, и это честнее, чем зелёный ответ из ниоткуда.
  запомнитьСборку(итог.зелёная ? {путь: rel, отпечаток} : null);

  send(res, 200, {
    path: rel,
    зелёная: итог.зелёная,
    оборвана: итог.оборвана,
    времяМс: итог.времяМс,
    причина: итог.зелёная ? '' : причинаПадения(итог.вывод),
    вывод: итог.вывод,
  });
  return true;
}
