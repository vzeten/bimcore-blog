// Ручка предварительного выпуска: что уедет на сайт и что говорят о нём быстрые проверки.
//
// **Git не меняется ничем:** ни индексом, ни объектной базой, ни коммитом, ни отправкой. Ручка только
// считает план и проверяет его. Запись живёт отдельным модулем (`publishRoute.mjs`) и считает план
// тем же кодом, что и здесь.
//
// **Полной сборки сайта на компьютере нет** (решение владельца 2026-09-18). Сайт собирает GitHub, при
// неудаче живой сайт остаётся прежним; здесь вместо сборки — быстрые проверки того, что на деле её
// роняло (`fastChecks.mjs`). Блокер быстрой проверки делает публикацию невозможной: `можно: false`.
//
// **Показывается ПЛАН, а не рабочее дерево.** Уезжает не то, что лежит на диске: у соседнего языка
// там может быть начатый человеком перевод, а на сайт уйдёт заглушка. Поэтому и «что изменится»
// считается сравнением байтов плана с закреплённой основой, а не разницей дерева с веткой.

