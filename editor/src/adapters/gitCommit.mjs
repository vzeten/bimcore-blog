// Единственное место программы, которое ПИШЕТ в git. До этого файла git только читался.
//
// Здесь нет ни одной широкой команды. Запрещены и не вызываются: `git add .`, `git add -A`,
// добавление папки, `reset --hard`, `clean`, `stash`, `rebase`, `merge`, `push`. Каждый путь
// добавляется своей командой и поимённо: одна опечатка в широкой команде уносит в коммит
// публикации чужую работу, а этого не отменить кнопкой в окне.
//
// Правил здесь нет — они в `core/publish.mjs`. Здесь только внешний мир (SPEC 4.6).

import fs from 'node:fs';
import path from 'node:path';
import {дверьИндекса} from './gitEnv.mjs';
import {разницаСИндексом} from './gitFile.mjs';

/** Текущая ветка. Не удалось спросить — `null`, и правило ответит отказом. */
export async function текущаяВетка(git) {
  try {
    return (await git.raw(['rev-parse', '--abbrev-ref', 'HEAD'])).trim() || null;
  } catch {
    return null;
  }
}

/** Что уже лежит в индексе. Пустой список — индекс чист; отказ читается как «не знаю». */
export async function путиИндекса(git) {
  const сырое = await git.raw(['-c', 'core.quotepath=false', 'diff', '--cached', '--name-only']);

  return сырое.split(/\r?\n/).map((строка) => строка.trim()).filter(Boolean);
}

/**
 * Добавить пути в индекс — каждый своей командой и явно, через `--`.
 * `--` обязателен: путь, начинающийся с дефиса, иначе был бы прочитан как ключ команды.
 */
export async function добавитьПоимённо(git, пути) {
  for (const путь of пути) {
    await git.raw(['add', '--', путь]);
  }
}

/**
 * Снять пути с индекса, вернув его в исходное состояние. **Рабочие файлы не трогаются:**
 * это `reset` без `--hard`, он двигает только индекс. Зовётся при любом отказе после добавления.
 */
export async function снятьСИндекса(git, пути) {
  if (пути.length === 0) return;

  // `--literal-pathspecs`: без него путь со знаком шаблона в имени снялся бы не тот, и в индексе
  // осталось бы то, что программа считает снятым.
  await git.raw(['--literal-pathspecs', 'reset', '--quiet', 'HEAD', '--', ...пути]);
}

/**
 * Коммит того, что уже лежит в индексе, — после сверки индекса с утверждённым перечнем.
 *
 * Возвращает обе записи SHA одним чтением: короткая — человеку на экран, полная — отправке, которая
 * по ней докажет, что везёт именно этот коммит. Двумя чтениями их брать нельзя: между ними голова
 * успела бы сместиться, и человек увидел бы один коммит, а уехал бы другой.
 */
export async function зафиксировать(git, сообщение) {
  await git.raw(['commit', '-m', сообщение]);
  const полный = (await git.raw(['rev-parse', 'HEAD'])).trim();

  return {полный, короткий: полный.slice(0, ДЛИНА_КОРОТКОГО)};
}

// Сколько знаков SHA показывать человеку. Не настройка: это привычная запись самого git, а не
// решение владельца о поведении программы.
const ДЛИНА_КОРОТКОГО = 7;

/**
 * Уложить ТОЧНЫЕ байты плана в ОТДЕЛЬНЫЙ индекс и вернуть дерево, которое он описывает.
 *
 * **Индекс человека не трогается вовсе.** Прежде программа складывала план в общий индекс и убирала
 * за собой в `finally`. При выключении компьютера `finally` не выполняется, и человек оставался с
 * заполненным индексом, из-за которого следующая публикация упиралась в «чужую работу», которой
 * нет. Отдельный файл индекса (`GIT_INDEX_FILE`) снимает этот случай целиком: обрыв в любой миг
 * оставляет мусором только временный файл, а рабочий индекс всё это время чист.
 *
 * Ни `add`, ни рабочий файл здесь не участвуют, и это второе главное. `add` берёт то, что лежит на
 * диске, — а на диске у соседнего языка лежит начатый человеком перевод, публиковать который никто
 * не просил. `add` ещё и наследует режим у прежней записи. Поэтому объект пишется из байтов плана,
 * а место в индексе занимается с режимом плана.
 *
 * Байты попадают в git через временный файл ВНЕ репозитория: `hash-object --path` применяет к нему
 * те же преобразования, что применил бы к настоящему пути, а рабочее дерево при этом не трогается
 * ни на байт.
 */
export async function деревоПлана({repo, основа, записи, времянка, индексныйФайл}) {
  fs.mkdirSync(path.dirname(индексныйФайл), {recursive: true});
  fs.rmSync(индексныйФайл, {force: true});
  fs.mkdirSync(времянка, {recursive: true});

  // Своя дверь к git со своим индексом. Общий `git` при этом не меняется ничем: подмешай мы среду
  // ему, отдельный индекс достался бы и всем остальным чтениям сервера.
  const свой = своейДверью(repo, индексныйФайл);

  try {
    // Отдельный индекс начинается с опубликованной основы: план накладывается поверх неё, а не
    // поверх пустоты, иначе дерево вышло бы из одних только файлов статьи.
    await свой.raw(['read-tree', основа]);

    for (const [номер, запись] of записи.entries()) {
      // Путь уходит с сайта: его место в индексе снимается, а байтов у него нет и не бывает.
      if (!Buffer.isBuffer(запись.байты)) {
        await свой.raw(['--literal-pathspecs', 'update-index', '--force-remove', '--', запись.путь]);
        continue;
      }

      const временный = path.join(времянка, `план-${номер}`);
      fs.writeFileSync(временный, запись.байты);
      const sha = (await свой.raw(['hash-object', '-w', '--path', запись.путь, '--', временный])).trim();
      await свой.raw([
        '--literal-pathspecs', 'update-index', '--add', '--cacheinfo',
        `${запись.режим},${sha},${запись.путь}`,
      ]);
    }

    return (await свой.raw(['write-tree'])).trim();
  } finally {
    убрать(времянка);
    убрать(индексныйФайл);
  }
}

/** Убрать за собой, не роняя работу: остаток временного файла беды не делает, но и лежать не должен. */
function убрать(путь) {
  try {
    fs.rmSync(путь, {recursive: true, force: true});
  } catch (ошибка) {
    console.error(ошибка);
  }
}

/**
 * Создать коммит из готового дерева и сдвинуть ветку атомарно.
 *
 * `commit` здесь не годится: между его проверкой и записью ветку может сдвинуть кто-то ещё, и наш
 * коммит лёг бы поверх чужой работы. `update-ref` со СТАРЫМ значением поручает эту защиту самому
 * git: не совпало — записи не произошло вовсе.
 *
 * Разделено на два шага намеренно: между ними программа записывает намерение в свою очередь. Иначе
 * обрыв оставил бы коммит, происхождение которого доказать нечем.
 */
export async function создатьКоммит(git, {дерево, родитель, сообщение}) {
  const полный = (await git.raw(['commit-tree', дерево, '-p', родитель, '-m', сообщение])).trim();

  return {полный, короткий: полный.slice(0, ДЛИНА_КОРОТКОГО)};
}

/** Сдвинуть ветку выпуска на названный коммит, только если она всё ещё стоит на прежнем. */
export async function сдвинутьВетку(git, {ветка, новый, прежний}) {
  await git.raw(['update-ref', `refs/heads/${ветка}`, новый, прежний]);
}

/**
 * Своя дверь к git с отдельным файлом индекса: общий индекс такие команды не трогают вовсе.
 * Среда чистится там же, где у всех остальных дверей программы (`gitEnv.mjs`), — второго правила
 * о запрещённых переменных рядом с этим быть не должно.
 */
const своейДверью = (repo, индексныйФайл) => дверьИндекса(repo, индексныйФайл);

/** SHA содержимого, записанного в индексе по этому пути. Записи нет — `null`. */
export async function вИндексе(git, rel) {
  try {
    const строка = (await git.raw(['--literal-pathspecs', 'ls-files', '-s', '--', rel])).trim();
    if (строка === '') return null;

    return строка.split(/\s+/)[1] ?? null;
  } catch {
    return null;
  }
}

/** SHA содержимого файла в названном снимке. Файла там нет — `null`. */
export async function блобВСнимке(git, ref, rel) {
  try {
    return (await git.raw(['--literal-pathspecs', 'rev-parse', `${ref}:${rel}`])).trim() || null;
  } catch {
    return null;
  }
}

/**
 * Заменить индекс содержимым названного снимка — но только если он ДОКАЗАННО не тронут, и так, чтобы
 * между доказательством и заменой в него не успел вмешаться посторонний git.
 *
 * **Замок берётся не свой, а git-овский.** Собственный признак на сервере ловит только второй запрос
 * этой же программы; обычная команда `git add`, набранная человеком в терминале, его не видит.
 * А вот файл `index.lock` видят все: пока он существует, git отказывается менять индекс кому угодно.
 * Поэтому проверка и замена происходят внутри него, и вмешаться между ними уже нельзя.
 *
 * Замена идёт по собственному порядку git: новое содержимое пишется в `index.lock` и переименовывается
 * поверх индекса. Само содержимое считает сам git (`read-tree --index-output`), формат индекса
 * программа не сочиняет.
 *
 * Возвращает `{привели, чужое}`. `чужое` не пусто — индекс не тронут ни на байт.
 */
export async function заменитьИндекс({git, repo, основа, снимок}) {
  const служебная = path.resolve(repo, (await git.raw(['rev-parse', '--git-dir'])).trim());
  const замок = path.join(служебная, 'index.lock');
  const временный = path.join(служебная, 'index.publish.tmp');

  // Содержимое нового индекса считается ЗАРАНЕЕ, до взятия замка: сам `read-tree` тоже берёт замок
  // индекса, и под нашим он просто не запустится. Со своим файлом индекса он общий не трогает.
  try {
    fs.rmSync(временный, {force: true});
    await своейДверью(repo, временный).raw(['read-tree', снимок]);
  } catch (ошибка) {
    console.error(ошибка);
    убрать(временный);

    return {привели: false, чужое: ['?']};
  }

  let открыт = null;
  try {
    открыт = fs.openSync(замок, 'wx');
  } catch {
    // Замок уже у кого-то: индекс прямо сейчас меняет другой git. Ждать и гадать не будем.
    убрать(временный);

    return {привели: false, чужое: ['?']};
  }

  try {
    const своё = await разницаСИндексом(git, основа);
    if (своё === null) return {привели: false, чужое: ['?']};
    if (своё.length > 0) return {привели: false, чужое: своё};

    fs.writeFileSync(открыт, fs.readFileSync(временный));
    fs.closeSync(открыт);
    открыт = null;
    fs.renameSync(замок, path.join(служебная, 'index'));

    // Индекс, собранный `read-tree`, содержимое знает, а сведений о файлах на диске — нет, и до их
    // обновления git считает изменившимся вообще всё. Обновление правит только эти сведения:
    // содержимого оно не трогает и на своё несовпадение отвечает кодом возврата, а не бедой.
    try {
      await git.raw(['update-index', '-q', '--refresh']);
    } catch (ошибка) {
      console.error(ошибка);
    }

    return {привели: true, чужое: []};
  } catch (ошибка) {
    console.error(ошибка);

    return {привели: false, чужое: ['?']};
  } finally {
    убрать(временный);
    if (открыт !== null) {
      fs.closeSync(открыт);
      убрать(замок);
    }
  }
}
