// Ручка записи статьи в хранилище — единственное место, где программа создаёт коммит.
//
// Порядок жёсткий и весь состоит из заслонов: основа закрепляется заново · очередь разбирается
// против неё · план считается ЗАНОВО (экрану веры нет) · сборка спрашивается у памяти сервера и
// сверяется отпечатком · ТОЧНЫЕ байты плана укладываются в ОТДЕЛЬНЫЙ индекс поверх основы ·
// сложенное дерево целиком сверяется с тем, которое собиралось · коммит создаётся от этого дерева с
// родителем-основой · происхождение записывается в очередь.
//
// **Репозиторий человека не меняется ничем.** Текущая ветка, `HEAD`, рабочее дерево, общий индекс и
// местная `main` остаются такими, какими были: человек публикует из любой рабочей ветки, ничего не
// переключая и не пряча. Коммит живёт в объектной базе и в очереди программы до самой отправки.
//
// **Рабочий файл человека не читается и не переписывается ни разу.** Начатый им перевод соседнего
// языка остаётся на диске байт в байт; на сайт уезжает заглушка, написанная программой, и на диск
// она не кладётся — диск человека принадлежит его ветке, а не сайту.
//
// Отправки (`push`) здесь нет.

