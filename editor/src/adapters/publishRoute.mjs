// Ручка записи статьи в хранилище — единственное место, где программа создаёт коммит.
//
// Порядок жёсткий и весь состоит из заслонов: основа закрепляется заново · очередь разбирается
// против неё · план считается ЗАНОВО (экрану веры нет) и сверяется с показанным отпечатком ·
// быстрые проверки повторяются по нему же · ТОЧНЫЕ байты плана укладываются в ОТДЕЛЬНЫЙ индекс
// поверх основы · git называет, чем дерево отличается от основы, и это обязано совпасть с планом
// (`planCommit.mjs`) · коммит создаётся от этого дерева с родителем-основой · происхождение
// записывается в очередь. Полной сборки сайта на компьютере нет (решение владельца 2026-09-18).
//
// **Репозиторий человека не меняется ничем.** Текущая ветка, `HEAD`, рабочее дерево, общий индекс и
// местная `main` остаются такими, какими были: человек публикует из любой рабочей ветки, ничего не
// переключая и не пряча. Коммит живёт в объектной базе и в очереди программы до самой отправки.
//
// **Рабочий файл человека не читается и не переписывается ни разу.** Начатый им перевод соседнего
// языка остаётся на диске байт в байт; на сайт уезжает заглушка, написанная программой, и на диск
// она не кладётся — диск человека принадлежит его ветке, а не сайту.
//
// Отправки (`push`) здесь нет.

import path from 'node:path';
import fs from 'node:fs';

import {публикацияВозможна} from '../core/publishPlan.mjs';
import {годныйПуть, отпечатокИсточников} from './releaseFacts.mjs';
import {сверитьПодготовку} from './prepareStamp.mjs';
import {датаРазошлась} from './publishDateFacts.mjs';
import {закреплённаяОснова} from './publishBase.mjs';
import {готовыйПлан, изменённыеПротивОсновы} from './publishFacts.mjs';
import {отпечатокПлана} from './planBytes.mjs';
import {быстрыеПроверки} from './fastChecks.mjs';
import {БЛОКЕР} from '../core/prepareRules.mjs';
import {записатьПлан} from './planCommit.mjs';
import {разобратьОчередь} from './publishRepair.mjs';
import {взятьЗамок, отпустить} from './publishLock.mjs';
import {badFields, badPath} from './httpBody.mjs';

/** Обрабатывает `/api/publish/commit`. Возвращает true, если запрос был к ней. */
export async function publishRoute({req, res, url, repo, editorDir, settings, git, тело, insideRepo, send}) {
  if (url.pathname !== '/api/publish/commit' || req.method !== 'POST') return false;

  const payload = await тело(req);
  const отказ = (код, ещё = {}) => {
    send(res, 409, {error: settings['отказыКоммита'][код] ?? settings['отказыОтправки'][код] ?? код, код, ...ещё});
    return true;
  };

  const плохоеТело = badFields(payload, [], settings['ошибкиСервера']);
  if (плохоеТело) {
    send(res, плохоеТело.status, {error: плохоеТело.error});
    return true;
  }

  const rel = payload.path;
  const bad = badPath(
    [rel],
    (p) => insideRepo(path.join(repo, p)),
    (p) => fs.existsSync(path.join(repo, p)),
    settings['ошибкиСервера'],
  );
  if (bad) {
    send(res, bad.status, {error: bad.error});
    return true;
  }

  if (!годныйПуть(rel, settings)) {
    send(res, 400, {error: settings['ошибкиСервера']['неПутьСтатьи']});
    return true;
  }

  // Согласие человека приходит отдельным признаком. Без него ручка не записывает ничего: случайный
  // повтор запроса не должен превращаться в публикацию.
  if (payload['подтверждено'] !== true) {
    send(res, 400, {error: settings['ошибкиСервера']['нетПодтверждения']});
    return true;
  }

  // **Снимок обязателен и спрашивается до всякой работы.** Запрос без него пришёл мимо окна, и
  // доказать, что проверялось то же самое, что показано, нечем.
  if (typeof payload['отпечаток'] !== 'string' || payload['отпечаток'] === '') {
    send(res, 409, {error: settings['отказыКоммита']['нетСнимка'], код: 'нетСнимка'});
    return true;
  }

  // **Снимок подготовки доходит и сюда, и зелёная подготовка доказывается заново.** Отпечаток плана
  // выше отвечает за состав; за то, что статья вообще годна к выпуску, отвечают проверки — а их
  // вердикт прежде выносило окно. Тело запроса пишет не окно: с одним лишь отпечатком плана до
  // записи доходила статья с пустым описанием, и на сайт уезжало то, что проверки запрещают.
  const снимок = сверитьПодготовку({repo, rel, settings, ждали: payload['отпечатокПодготовки']});
  if (снимок.код !== null) {
    send(res, 409, {error: settings['отказыКоммита'][снимок.код], код: снимок.код, находки: снимок.блокеры});
    return true;
  }

  // **Замок берётся до всякой работы с хранилищем.** Два запроса, пришедшие почти одновременно,
  // оба разобрали бы очередь и оба сделали бы по коммиту от одной основы — а дослать можно только
  // один. Отпускается он в `finally` этого же захода.
  if (!взятьЗамок()) return отказ('идётЗапись');

  try {
    return await записатьСтатью({rel, payload, repo, editorDir, settings, git, res, send, отказ});
  } finally {
    отпустить();
  }
}

/** Сама запись. Вынесена из ручки, чтобы замок брался и отпускался ровно вокруг неё. */
async function записатьСтатью({rel, payload, repo, editorDir, settings, git, res, send, отказ}) {
  const основа = await закреплённаяОснова({git, settings});
  if (основа.ошибка) return отказ(основа.ошибка);

  // Очередь разбирается против свежей основы ДО новой работы. Свой коммит, который ждёт отправки от
  // этой же основы, надо дослать, а не делать рядом второй: два коммита от одной вершины вместе не
  // уезжают. Доехавшие и устаревшие записи разбор снимает сам.
  const очередь = await разобратьОчередь({git, repo, editorDir, settings, основа: основа.основа});
  if (очередь.ошибка) return отказ(очередь.ошибка);
  if (очередь.ожидающие.length > 0) return отказ('естьНеотправленное');

  // **Отпечаток местных источников снимается ДО плана, синхронно, и дальше не переснимается.**
  // Ровно это значение ляжет в очередь: последний заслон перед отправкой сверит с ним диск. Сними
  // его позже — после асинхронного построения плана или создания коммита — и файл, появившийся в
  // этот промежуток, попал бы в отпечаток, но не в дерево, а заслон счёл бы источники неизменными.
  const источники = отпечатокИсточников(repo, rel, settings);

  // План считается заново и тем же кодом, что и показ. Экран мог устареть, пока человек читал.
  const план = await готовыйПлан({git, repo, settings, rel, основа: основа.основа});

  // **Снимок сверяется ВТОРОЙ раз, уже после построения плана.** Между сверкой на входе и этим
  // местом статья и её дерево могли измениться: появившаяся рядом статья меняет пути, категорию и
  // требования к полям, а сверка байтов одного файла этого не видит. Стоит она ДО первой записи в
  // объектную базу и РАНЬШЕ отказа о составе: разорванный снимок объясняет и недоказанный состав.
  const снова = сверитьПодготовку({repo, rel, settings, ждали: payload['отпечатокПодготовки']});
  if (снова.код !== null) {
    send(res, 409, {error: settings['отказыКоммита'][снова.код], код: снова.код, находки: снова.блокеры});
    return true;
  }

  // Дата записи блога сверяется с этой же закреплённой основой и по байтам того же снимка проверок:
  // в коммит обязана уехать ровно та дата, которую видели проверки.
  const датаНеТа = await датаРазошлась({
    git, repo, rel, settings, основа: основа.основа, срез: снова.подготовка.срез,
  });
  if (датаНеТа) return отказ(датаНеТа);

  if (план.ошибка || !публикацияВозможна(план)) {
    return отказ('составНеДоказан', {отказ: план.отказ ?? null, разрывы: план.разрывы ?? []});
  }

  // Согласие человека относится к показанному плану: отпечаток приезжает вместе с ним. Основа, байты
  // или состав с тех пор другие — это другой план, и записывать его без показа нельзя.
  const отпечаток = отпечатокПлана({основа: основа.основа, родитель: основа.основа, записи: план.записи});
  if (payload['отпечаток'] !== отпечаток) return отказ('статьяИзменилась');

  // **Быстрые проверки повторяются здесь, а не берутся у окна:** тело запроса пишет не окно. Они
  // зависят только от основы и байтов плана, а оба закреплены отпечатком выше, — поэтому это
  // секунды, а не новая сборка. Блокер — отказ с находками.
  const времянка = path.join(editorDir, settings['хранение']['папкаПубликаций'], 'сверка');
  const изменённые = await изменённыеПротивОсновы({git, основа: основа.основа, записи: план.записи, времянка});
  if (изменённые === null) return отказ('составНеДоказан', {отказ: null, разрывы: []});
  const {находки} = await быстрыеПроверки({git, repo, settings, основа: основа.основа, записи: план.записи, изменённые});
  const блокеры = находки.filter((находка) => находка.уровень === БЛОКЕР);
  if (блокеры.length > 0) return отказ('подготовкаНеПрошла', {находки: блокеры});
  // Источники обязаны быть теми же, что до плана: изменились за время его построения — коммит от
  // такого плана описывал бы не сегодняшний диск, и запись с прежним отпечатком была бы ложью.
  if (отпечатокИсточников(repo, rel, settings) !== источники) return отказ('статьяИзменилась');

  // Дерево, коммит, служебная ссылка и запись очереди — общим кодом с записью снятия
  // (`planCommit.mjs`). Сверяется ДЕРЕВО ЦЕЛИКОМ, а не отдельные пути: лишний путь, попавший в
  // дерево мимо перечня, поштучной сверкой не ловится, а в коммит уехал бы.
  const итог = await записатьПлан({
    git, repo, editorDir, settings, основа: основа.основа, записи: план.записи, rel, отпечаток, источники,
    сообщение: сообщение(rel, settings),
  });
  if (итог.ошибка) return отказ(итог.ошибка);

  send(res, 200, {
    path: rel, коммит: итог.коммит.короткий, sha: итог.коммит.полный, пути: итог.пути,
    ссылкиВСтатьях: план.ссылкиВСтатьях ?? 0,
  });
  return true;
}

/** Сообщение коммита из настройки, а не из кода: слова человеку в коде не живут (SPEC 4.4). */
function сообщение(rel, settings) {
  return String(settings['выпуск']['сообщениеКоммита']).replace('{статья}', rel);
}
