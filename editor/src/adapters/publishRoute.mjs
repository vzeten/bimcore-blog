/** Обрабатывает `/api/publish/commit`. Возвращает true, если запрос был к ней. */
export async function publishRoute({req, res, url, repo, editorDir, settings, git, тело, insideRepo, send}) {
  if (url.pathname !== '/api/publish/commit' || req.method !== 'POST') return false;

  const payload = await тело(req);
  const отказ = (код, ещё = {}) => {
    send(res, 409, {error: settings['отказыКоммита'][код] ?? settings['отказыОтправки'][код] ?? код, код, ...ещё});
    return true;
  };

  const плохоеТело = badFields(payload, [], settings['ошибкиСервера']);
  if (плохоеТело) {
    send(res, плохоеТело.status, {error: плохоеТело.error});
    return true;
  }

  const rel = payload.path;
  const bad = badPath(
    [rel],
    (p) => insideRepo(path.join(repo, p)),
    (p) => fs.existsSync(path.join(repo, p)),
    settings['ошибкиСервера'],
  );
  if (bad) {
    send(res, bad.status, {error: bad.error});
    return true;
  }

  if (!годныйПуть(rel, settings)) {
    send(res, 400, {error: settings['ошибкиСервера']['неПутьСтатьи']});
    return true;
  }

  // Согласие человека приходит отдельным признаком. Без него ручка не записывает ничего: случайный
  // повтор запроса не должен превращаться в публикацию.
  if (payload['подтверждено'] !== true) {
    send(res, 400, {error: settings['ошибкиСервера']['нетПодтверждения']});
    return true;
  }

  // **Снимок обязателен и спрашивается до всякой работы.** Запрос без него пришёл мимо окна, и
  // доказать, что проверялось и собиралось то же самое, нечем. Проверять это позже отказов о
  // сборке нельзя: человек прочёл бы «нет зелёной сборки» там, где беда совсем другая.
  if (typeof payload['отпечаток'] !== 'string' || payload['отпечаток'] === '') {
    send(res, 409, {error: settings['отказыКоммита']['нетСнимка'], код: 'нетСнимка'});
    return true;
  }

  // **Снимок подготовки доходит и сюда, и зелёная подготовка доказывается заново.** Отпечаток плана
  // выше отвечает за состав; за то, что статья вообще годна к выпуску, отвечают проверки — а их
  // вердикт прежде выносило окно. Тело запроса пишет не окно: с одним лишь отпечатком плана до
  // записи доходила статья с пустым описанием, и на сайт уезжало то, что проверки запрещают.
  // Сверка идёт по тем же входам, что и отпечаток, поэтому лишнего отказа она не создаёт.
  const снимок = сверитьПодготовку({repo, rel, settings, ждали: payload['отпечатокПодготовки']});
  if (снимок.код !== null) {
    send(res, 409, {
      error: settings['отказыКоммита'][снимок.код],
      код: снимок.код,
      находки: снимок.блокеры,
    });
    return true;
  }

  // **Замок берётся до всякой работы с хранилищем.** Два запроса, пришедшие почти одновременно,
  // оба увидели бы пустой индекс, оба начали бы в него укладывать, и в коммит уехала бы смесь двух
  // планов. Отпускается он в `finally` этого же захода.
  if (!взятьЗамок()) return отказ('идётЗапись');

  try {
    return await записатьСтатью({rel, payload, repo, editorDir, settings, git, res, send, отказ});
  } finally {
    отпустить();
  }
}

/** Сама запись. Вынесена из ручки, чтобы замок брался и отпускался ровно вокруг неё. */
async function записатьСтатью({rel, payload, repo, editorDir, settings, git, res, send, отказ}) {
  // Незаконченное с прошлого раза доводится до конца ДО новой работы: иначе программа считала бы
  // план поверх дерева, в котором не хватает уже опубликованного файла.
  const незаконченное = await довестиНезаконченное({git, repo, editorDir, settings});
  if (незаконченное.ошибка) return отказ(незаконченное.ошибка);
  // Незакрытый хвост прошлой публикации: файл есть в хранилище и нет на диске. Пока он не
  // восстановлен, план поверх такого дерева считать нельзя — он вышел бы неверным.
  if (незаконченное.невосстановленные.length > 0) {
    return отказ('невосстановлено', {чужие: незаконченное.невосстановленные});
  }

  const основа = await закреплённаяОснова({git, settings});
  if (основа.ошибка) return отказ(основа.ошибка);

  // План считается заново и тем же кодом, что и показ. Экран мог устареть, пока человек читал.
  const план = await готовыйПлан({git, repo, settings, rel, основа: основа.основа});

  // **Снимок сверяется ВТОРОЙ раз, и здесь это не перестраховка.** Между сверкой на входе и этим
  // местом ручка успела довести до конца незаконченное с прошлого раза, а восстановление кладёт на
  // диск файлы — в том числе такие, что меняют пути своего дерева, категорию статьи и требования к
  // её полям. План после этого считается по новому дереву, и без второй сверки запись ушла бы по
  // правилам, которых человеку не показывали. Стоит она ДО первой записи в git: дальше отменять
  // уже нечего.
  //
  // Спрашивается она РАНЬШЕ отказа о составе, и так же, как у состава и сборки. Разорванный снимок
  // объясняет и сам недоказанный состав: под статьёй мог появиться новый файл. Скажи программа
  // «состав не доказан», человек искал бы беду в статье — а надо просто начать заново.
  const послеВосстановления = сверитьПодготовку({repo, rel, settings, ждали: payload['отпечатокПодготовки']});
  if (послеВосстановления.код !== null) {
    send(res, 409, {
      error: settings['отказыКоммита'][послеВосстановления.код],
      код: послеВосстановления.код,
      находки: послеВосстановления.блокеры,
    });
    return true;
  }

  if (план.ошибка || !публикацияВозможна(план)) {
    return отказ('составНеДоказан', {отказ: план.отказ ?? null, разрывы: план.разрывы ?? []});
  }

  // Сборка отвечает за тот план, который видела. Разошлось что угодно — основа, родитель, байты,
  // назначение, порядок — обещание сборки больше не действует.
  const сборка = зелёнаяСборка();
  const отпечаток = отпечатокПлана({основа: основа.основа, родитель: основа.голова, записи: план.записи});
  if (сборка?.путь !== rel || сборка?.основа !== основа.основа) return отказ('нетЗелёнойСборки');
  if (сборка.отпечаток !== отпечаток) return отказ('статьяИзменилась');
  // **Три значения обязаны совпасть, а не два.** Память сборки одна на сервер: второе окно, собравшее
  // другой план той же статьи, заменило бы её собой, и согласие человека уехало бы на чужой перечень.
  // Поэтому сверяется и то, что показали ЕМУ, — отпечаток приезжает вместе с его согласием.
  if (payload['отпечаток'] !== отпечаток) return отказ('статьяИзменилась');

  // Чужая работа в индексе: разобрать, что там наше, а что нет, программа не берётся.
  const былоВИндексе = await путиИндекса(git);
  if (былоВИндексе.length > 0) return отказ('индексНеПуст', {индекс: былоВИндексе});

  const пути = план.записи.map((запись) => запись.путь);
  const своё = path.join(editorDir, settings['хранение']['папкаПубликаций']);

  // **Дерево складывается в ОТДЕЛЬНОМ индексе, а не в индексе человека.** Прежде программа убирала
  // за собой в `finally`, но при выключении компьютера `finally` не выполняется, и человек оставался
  // с заполненным индексом. Со своим индексом убирать нечего: обрыв в любой миг оставляет мусором
  // только временный файл.
  let дерево;
  try {
    дерево = await деревоПлана({
      repo,
      основа: основа.голова,
      записи: план.записи,
      времянка: path.join(своё, 'укладка'),
      индексныйФайл: path.join(своё, 'индекс'),
    });
  } catch (ошибка) {
    console.error(ошибка);
    return отказ('коммитНеУдался');
  }

  // Сверяется ДЕРЕВО ЦЕЛИКОМ, а не отдельные пути. Лишний путь, попавший в дерево мимо перечня,
  // поштучной сверкой не ловится, а в коммит уехал бы.
  if (дерево !== сборка.дерево) return отказ('деревоРазошлось');

  // Дерево совпало с тем, что уже лежит на сайте: менять нечего. Пустой коммит здесь не «почти
  // ничего», а запись, которая потом уедет на сайт и ничего там не изменит.
  if (дерево === await деревоКоммита(git, основа.голова)) return отказ('нечегоФиксировать');

  const коммит = await создатьКоммит(git, {
    дерево,
    родитель: основа.голова,
    сообщение: сообщение(rel, settings),
  });

  // Происхождение записывается ДО сдвига ветки. Иначе обрыв между ними оставил бы коммит, который
  // программа не признаёт своим, и отправить его было бы нечем.
  // Пути берутся у самого коммита, а не из плана: в коммит попадает только изменившееся, и запись
  // о происхождении обязана описывать его таким, какой он есть.
  const созданные = план.записи
    .filter((запись) => запись.источник === СОЗДАНО)
    .map((запись) => запись.путь);
  const путиЗаписи = await путиКоммита(git, коммит.полный);
  // Убранные пути записываются рядом с созданными: на диске их нет ни до, ни после, и отправке
  // иначе нечем доказать, что они принадлежат этой статье. В запись идут только те, что и вправду
  // ушли в коммите: путь, ничего не изменивший, описывал бы работу, которой не было.
  const ушедшие = new Set(путиЗаписи);
  const удалённые = план.записи
    .filter((запись) => запись.источник === УДАЛЕНО && ушедшие.has(запись.путь))
    .map((запись) => запись.путь);
  const намерение = записатьНамерение(editorDir, settings, {
    sha: коммит.полный,
    пути: путиЗаписи,
    основа: основа.основа,
    созданные,
    удалённые,
    когда: new Date().toISOString(),
  });
  if (!намерение) return отказ('происхождениеНеЗаписано');

  try {
    await сдвинутьВетку(git, {ветка: ВЕТКА_ВЫПУСКА, новый: коммит.полный, прежний: основа.голова});
  } catch (ошибка) {
    console.error(ошибка);
    return отказ('веткаСместилась');
  }

  // Индекс приводится СРАЗУ после сдвига ветки, следующей же командой. Здесь и только здесь
  // происхождение его состояния ещё известно: минуту назад он был доказанно пуст, замок держим мы, а
  // коммит только что сделали сами. После обрыва этого знания уже нет, и там индекс не трогают вовсе.
  //
  // Ссылка ветки в записи не участвует — только закреплённый SHA коммита: ветку могли сдвинуть
  // между сравнением и записью. Сама проверка и замена идут под замком git, поэтому вмешаться
  // между ними не может и команда, набранная человеком в терминале.
  const индекс = await заменитьИндекс({git, repo, основа: основа.голова, снимок: коммит.полный});

  // Зелёная сборка израсходована: следующая запись потребует новой.
  запомнитьСборку(null);
  // Новая запись обесценивает прежний показ отправки: человеку показывали другое.
  запомнитьПоказ(null);

  // Созданные заглушки дописываются на диск, и неудача здесь не молчит: файл, который на сайте есть,
  // а на диске нет, делает дерево грязным, и человеку про это надо сказать. Отправка такую статью
  // не повезёт, пока файл не восстановится.
  const дописано = await дописатьСозданные({
    git,
    repo,
    запись: {sha: коммит.полный, созданные},
    времянка: времянкаВосстановления(editorDir, settings),
  });

  // **Итог этой работы ложится в очередь, а не остаётся в ответе.** Ответ живёт до перезагрузки
  // окна, а очередь — на диске: не запиши программа сюда неприведённое, следующее нажатие
  // «Опубликовать» ушло бы в досылку и отказ забылся бы. Подтверждение одной записью снимает
  // намерение и кладёт точный перечень: два отдельных шага оставили бы между собой миг, в котором
  // коммит уже разрешён к отправке, а запрет ещё не записан.
  const неприведённое = [...дописано.невосстановленные, ...индекс.чужое];
  const записано = подтвердить(editorDir, settings, коммит.полный, неприведённое);

  send(res, 200, {
    path: rel,
    коммит: коммит.короткий,
    sha: коммит.полный,
    пути,
    // Не записали итог — на диске остался самый строгий запрет намерения, и человеку говорится он
    // же: иначе окно показало бы успех, а отправка после перезапуска всё равно отказала бы.
    невосстановленные: записано ? неприведённое : [...new Set([НЕЯСНО, ...неприведённое])],
  });
  return true;
}

/** Сообщение коммита из настройки, а не из кода: слова человеку в коде не живут (SPEC 4.4). */
function сообщение(rel, settings) {
  return String(settings['выпуск']['сообщениеКоммита']).replace('{статья}', rel);
}
