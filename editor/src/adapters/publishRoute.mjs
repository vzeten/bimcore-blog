/** Обрабатывает `/api/publish/commit`. Возвращает true, если запрос был к ней. */
export async function publishRoute({req, res, url, repo, editorDir, settings, git, тело, insideRepo, send}) {
  if (url.pathname !== '/api/publish/commit' || req.method !== 'POST') return false;

  const payload = await тело(req);
  const отказ = (код, ещё = {}) => {
    send(res, 409, {error: settings['отказыКоммита'][код] ?? settings['отказыОтправки'][код] ?? код, код, ...ещё});
    return true;
  };

  const плохоеТело = badFields(payload, [], settings['ошибкиСервера']);
  if (плохоеТело) {
    send(res, плохоеТело.status, {error: плохоеТело.error});
    return true;
  }

  const rel = payload.path;
  const bad = badPath(
    [rel],
    (p) => insideRepo(path.join(repo, p)),
    (p) => fs.existsSync(path.join(repo, p)),
    settings['ошибкиСервера'],
  );
  if (bad) {
    send(res, bad.status, {error: bad.error});
    return true;
  }

  if (!годныйПуть(rel, settings)) {
    send(res, 400, {error: settings['ошибкиСервера']['неПутьСтатьи']});
    return true;
  }

  // Согласие человека приходит отдельным признаком. Без него ручка не записывает ничего: случайный
  // повтор запроса не должен превращаться в публикацию.
  if (payload['подтверждено'] !== true) {
    send(res, 400, {error: settings['ошибкиСервера']['нетПодтверждения']});
    return true;
  }

  // **Снимок обязателен и спрашивается до всякой работы.** Запрос без него пришёл мимо окна, и
  // доказать, что проверялось и собиралось то же самое, нечем. Проверять это позже отказов о
  // сборке нельзя: человек прочёл бы «нет зелёной сборки» там, где беда совсем другая.
  if (typeof payload['отпечаток'] !== 'string' || payload['отпечаток'] === '') {
    send(res, 409, {error: settings['отказыКоммита']['нетСнимка'], код: 'нетСнимка'});
    return true;
  }

  // **Снимок подготовки доходит и сюда, и зелёная подготовка доказывается заново.** Отпечаток плана
  // выше отвечает за состав; за то, что статья вообще годна к выпуску, отвечают проверки — а их
  // вердикт прежде выносило окно. Тело запроса пишет не окно: с одним лишь отпечатком плана до
  // записи доходила статья с пустым описанием, и на сайт уезжало то, что проверки запрещают.
  const снимок = сверитьПодготовку({repo, rel, settings, ждали: payload['отпечатокПодготовки']});
  if (снимок.код !== null) {
    send(res, 409, {error: settings['отказыКоммита'][снимок.код], код: снимок.код, находки: снимок.блокеры});
    return true;
  }

  // **Замок берётся до всякой работы с хранилищем.** Два запроса, пришедшие почти одновременно,
  // оба разобрали бы очередь и оба сделали бы по коммиту от одной основы — а дослать можно только
  // один. Отпускается он в `finally` этого же захода.
  if (!взятьЗамок()) return отказ('идётЗапись');

  try {
    return await записатьСтатью({rel, payload, repo, editorDir, settings, git, res, send, отказ});
  } finally {
    отпустить();
  }
}

/** Сама запись. Вынесена из ручки, чтобы замок брался и отпускался ровно вокруг неё. */
async function записатьСтатью({rel, payload, repo, editorDir, settings, git, res, send, отказ}) {
  const основа = await закреплённаяОснова({git, settings});
  if (основа.ошибка) return отказ(основа.ошибка);

  // Очередь разбирается против свежей основы ДО новой работы. Свой коммит, который ждёт отправки от
  // этой же основы, надо дослать, а не делать рядом второй: два коммита от одной вершины вместе не
  // уезжают. Доехавшие и устаревшие записи разбор снимает сам.
  const очередь = await разобратьОчередь({git, repo, editorDir, settings, основа: основа.основа});
  if (очередь.ошибка) return отказ(очередь.ошибка);
  if (очередь.ожидающие.length > 0) return отказ('естьНеотправленное');

  // План считается заново и тем же кодом, что и показ. Экран мог устареть, пока человек читал.
  const план = await готовыйПлан({git, repo, settings, rel, основа: основа.основа});

  // **Снимок сверяется ВТОРОЙ раз, уже после построения плана.** Между сверкой на входе и этим
  // местом статья и её дерево могли измениться: появившаяся рядом статья меняет пути, категорию и
  // требования к полям, а сверка байтов одного файла этого не видит. Стоит она ДО первой записи в
  // объектную базу и РАНЬШЕ отказа о составе: разорванный снимок объясняет и недоказанный состав.
  const снова = сверитьПодготовку({repo, rel, settings, ждали: payload['отпечатокПодготовки']});
  if (снова.код !== null) {
    send(res, 409, {error: settings['отказыКоммита'][снова.код], код: снова.код, находки: снова.блокеры});
    return true;
  }

  if (план.ошибка || !публикацияВозможна(план)) {
    return отказ('составНеДоказан', {отказ: план.отказ ?? null, разрывы: план.разрывы ?? []});
  }

  // Сборка отвечает за тот план, который видела: та же статья, та же основа, те же байты. Ушла
  // вперёд основа — сайт уже не тот, который проверяла сборка, и это называется своим именем, а не
  // «нет сборки».
  const сборка = зелёнаяСборка();
  const отпечаток = отпечатокПлана({основа: основа.основа, родитель: основа.основа, записи: план.записи});
  if (сборка?.путь !== rel) return отказ('нетЗелёнойСборки');
  if (сборка.основа !== основа.основа) return отказ('основаУстарела');
  if (сборка.отпечаток !== отпечаток) return отказ('статьяИзменилась');
  // **Три значения обязаны совпасть, а не два.** Память сборки одна на сервер: второе окно, собравшее
  // другой план той же статьи, заменило бы её собой, и согласие человека уехало бы на чужой перечень.
  // Поэтому сверяется и то, что показали ЕМУ, — отпечаток приезжает вместе с его согласием.
  if (payload['отпечаток'] !== отпечаток) return отказ('статьяИзменилась');

  const своё = path.join(editorDir, settings['хранение']['папкаПубликаций']);

  // **Дерево складывается в ОТДЕЛЬНОМ индексе поверх основы, а не в индексе человека.** Его индекс
  // принадлежит его ветке и к сайту отношения не имеет; обрыв в любой миг оставляет мусором только
  // временный файл программы.
  let дерево;
  try {
    дерево = await деревоПлана({
      repo,
      основа: основа.основа,
      записи: план.записи,
      времянка: path.join(своё, 'укладка'),
      индексныйФайл: path.join(своё, 'индекс'),
    });
  } catch (ошибка) {
    console.error(ошибка);
    return отказ('коммитНеУдался');
  }

  // Сверяется ДЕРЕВО ЦЕЛИКОМ, а не отдельные пути. Лишний путь, попавший в дерево мимо перечня,
  // поштучной сверкой не ловится, а в коммит уехал бы.
  if (дерево !== сборка.дерево) return отказ('деревоРазошлось');

  // Дерево совпало с тем, что уже лежит на сайте: менять нечего. Пустой коммит здесь не «почти
  // ничего», а запись, которая потом уедет на сайт и ничего там не изменит.
  if (дерево === await деревоКоммита(git, основа.основа)) return отказ('нечегоФиксировать');

  // Родитель коммита — сама основа: уезжает ровно один коммит поверх сегодняшнего сайта, и отправка
  // докажет это, потребовав, чтобы сервер всё ещё стоял на ней.
  let коммит;
  try {
    коммит = await создатьКоммит(git, {дерево, родитель: основа.основа, сообщение: сообщение(rel, settings)});
    // Служебная ссылка держит коммит до отправки: без неё он ни с чего не достижим, и уборка git
    // стёрла бы его раньше повтора. Ветки, `HEAD` и индекс от неё не меняются.
    await закрепитьКоммит(git, коммит.полный);
  } catch (ошибка) {
    console.error(ошибка);
    return отказ('коммитНеУдался');
  }

  // Происхождение записывается сразу за коммитом: запись очереди — единственное, чем программа
  // потом докажет, что этот коммит её и прошёл проверки. Пути берутся у самого коммита, а не из
  // плана: в коммит попадает только изменившееся, и запись обязана описывать его таким, какой он есть.
  const путиЗаписи = await путиКоммита(git, коммит.полный);
  const ушедшие = new Set(путиЗаписи);
  const созданные = план.записи
    .filter((запись) => запись.источник === СОЗДАНО && ушедшие.has(запись.путь))
    .map((запись) => запись.путь);
  const удалённые = план.записи
    .filter((запись) => запись.источник === УДАЛЕНО && ушедшие.has(запись.путь))
    .map((запись) => запись.путь);
  // Путь открытой локали и отпечаток показанного плана едут в запись: по ним отправка перед самой
  // досылкой заново докажет, что статья с тех пор не изменилась.
  const запись = {
    sha: коммит.полный,
    пути: путиЗаписи,
    основа: основа.основа,
    путь: rel,
    отпечаток,
    созданные,
    удалённые,
    когда: new Date().toISOString(),
  };
  // Намерение и подтверждение — две записи одной очереди: обрыв между ними оставляет намерение,
  // которое разбор снимет как недоказанное. Не легло на диск — ссылка отпускается, коммит остаётся
  // в объектной базе безвредным мусором до уборки.
  if (!записатьНамерение(editorDir, settings, запись) || !подтвердить(editorDir, settings, коммит.полный)) {
    await отпуститьКоммит(git, коммит.полный);
    return отказ('происхождениеНеЗаписано');
  }

  // Зелёная сборка израсходована: следующая запись потребует новой.
  запомнитьСборку(null);
  // Новая запись обесценивает прежний показ отправки: человеку показывали другое.
  запомнитьПоказ(null);

  send(res, 200, {path: rel, коммит: коммит.короткий, sha: коммит.полный, пути: путиЗаписи});
  return true;
}

/** Сообщение коммита из настройки, а не из кода: слова человеку в коде не живут (SPEC 4.4). */
function сообщение(rel, settings) {
  return String(settings['выпуск']['сообщениеКоммита']).replace('{статья}', rel);
}
