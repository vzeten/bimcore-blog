// Ручка записи статьи в хранилище — единственное место, где программа меняет git.
//
// Порядок жёсткий и весь состоит из заслонов: основа закрепляется заново · план считается ЗАНОВО
// (экрану веры нет) · сборка спрашивается у памяти сервера и сверяется отпечатком · индекс обязан
// быть пуст · в индекс укладываются ТОЧНЫЕ байты плана, а не файлы с диска · сложенное дерево
// целиком сверяется с тем, которое собиралось · коммит создаётся от этого дерева · происхождение
// записывается ДО сдвига ветки · ветка сдвигается атомарно, со сверкой прежнего значения.
//
// **Рабочий файл человека не читается и не переписывается ни разу.** Начатый им перевод соседнего
// языка остаётся на диске байт в байт; на сайт уезжает заглушка, написанная программой.
//
// Отправки (`push`) здесь нет.

