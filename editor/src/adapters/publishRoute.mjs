// Ручка коммита статьи — первое и единственное место, где программа меняет git.
//
// Порядок жёсткий и весь состоит из заслонов: состав считается ЗАНОВО (экрану веры нет) · сборка
// спрашивается у памяти сервера и сверяется отпечатком с сегодняшним содержимым · ветка обязана
// быть рабочей · индекс обязан быть пуст · каждый путь добавляется поимённо · перед коммитом
// индекс сверяется с утверждённым перечнем · любое расхождение снимает индекс и отменяет коммит.
//
// Отправки (`push`) здесь нет и в этом срезе не будет.

import path from 'node:path';
import fs from 'node:fs';

import {выпускВозможен, составВыпуска} from '../core/release.mjs';
import {индексВПеречне, решениеОКоммите} from '../core/publish.mjs';
import {годныйПуть, версииСтатьи, отпечатокСостава} from './releaseFacts.mjs';
import {зелёнаяСборка, запомнитьСборку} from './buildMemory.mjs';
import {добавитьПоимённо, зафиксировать, путиИндекса, снятьСИндекса, текущаяВетка} from './gitCommit.mjs';
import {запомнитьКоммит} from './pushMemory.mjs';
import {badFields, badPath} from './httpBody.mjs';

/** Обрабатывает `/api/publish/commit`. Возвращает true, если запрос был к ней. */
export async function publishRoute({req, res, url, repo, settings, git, тело, insideRepo, send}) {
  if (url.pathname !== '/api/publish/commit' || req.method !== 'POST') return false;

  const payload = await тело(req);

  const плохоеТело = badFields(payload, [], settings['ошибкиСервера']);
  if (плохоеТело) {
    send(res, плохоеТело.status, {error: плохоеТело.error});
    return true;
  }

  const rel = payload.path;
  const bad = badPath(
    [rel],
    (p) => insideRepo(path.join(repo, p)),
    (p) => fs.existsSync(path.join(repo, p)),
    settings['ошибкиСервера'],
  );
  if (bad) {
    send(res, bad.status, {error: bad.error});
    return true;
  }

  if (!годныйПуть(rel, settings)) {
    send(res, 400, {error: settings['ошибкиСервера']['неПутьСтатьи']});
    return true;
  }

  // Согласие человека приходит отдельным признаком. Без него ручка не фиксирует ничего: случайный
  // повтор запроса не должен превращаться в коммит.
  if (payload['подтверждено'] !== true) {
    send(res, 400, {error: settings['ошибкиСервера']['нетПодтверждения']});
    return true;
  }

  // Состав считается заново. Экран мог устареть, пока человек читал перечень.
  const состав = составВыпуска({версии: версииСтатьи(repo, rel, settings)});
  const сборка = зелёнаяСборка();

  const решение = решениеОКоммите({
    ветка: await текущаяВетка(git),
    индекс: await путиИндекса(git),
    состав: выпускВозможен(состав) ? состав : null,
    сборкаЗелёная: сборка?.путь === rel,
    отпечатокСборки: сборка?.путь === rel ? сборка.отпечаток : null,
    отпечатокСейчас: отпечатокСостава(repo, состав.файлы),
  });

  if (решение.ошибка) {
    send(res, 409, {error: settings['отказыКоммита'][решение.ошибка] ?? решение.ошибка, код: решение.ошибка});
    return true;
  }

  await добавитьПоимённо(git, решение.пути);

  // Сверка индекса с утверждённым перечнем. Индекс вправе быть уже перечня: неизменившийся файл
  // в него не попадает. Шире перечня — беда: в коммит уехало бы то, чего человеку не показывали.
  const индекс = await путиИндекса(git);
  const лишние = индексВПеречне(индекс, решение.пути);

  if (лишние.length > 0) {
    // Индекс возвращается в исходное состояние. Рабочие файлы не трогаются: это `reset` без `--hard`.
    await снятьСИндекса(git, индекс);
    send(res, 409, {error: settings['отказыКоммита']['индексРазошёлся'], код: 'индексРазошёлся', лишние});
    return true;
  }

  if (индекс.length === 0) {
    await снятьСИндекса(git, решение.пути);
    send(res, 409, {error: settings['отказыКоммита']['нечегоФиксировать'], код: 'нечегоФиксировать'});
    return true;
  }

  let коммит;
  try {
    коммит = await зафиксировать(git, сообщение(rel, settings));
  } catch (ошибка) {
    // Коммит не состоялся — индекс возвращается пустым, как и был. Рабочие файлы целы.
    await снятьСИндекса(git, индекс);
    send(res, 409, {error: settings['отказыКоммита']['коммитНеУдался'], код: 'коммитНеУдался'});
    return true;
  }

  // Зелёная сборка израсходована: следующий коммит потребует новой.
  запомнитьСборку(null);
  // Отправка вправе везти только коммит, сделанный самой программой: он один прошёл проверки и
  // полную сборку на наших глазах.
  запомнитьКоммит(коммит.полный);

  // Полный SHA нужен отправке: по нему она сверяет, что везёт именно этот коммит, а не то, чем
  // стала ветка потом. Короткий остаётся для человека — его он видит на экране.
  send(res, 200, {path: rel, коммит: коммит.короткий, sha: коммит.полный, пути: индекс});
  return true;
}

/** Сообщение коммита из настройки, а не из кода: слова человеку в коде не живут (SPEC 4.4). */
function сообщение(rel, settings) {
  return String(settings['выпуск']['сообщениеКоммита']).replace('{статья}', rel);
}
