// Запись новой статьи на диск. Правила — в `core/newArticle.mjs`, здесь только файлы.
// Это первая операция программы, которая создаёт файлы сайта: неверно созданная статья роняет
// сборку целиком, поэтому сначала проверяется всё, и только потом пишется первый байт.

import fs from 'node:fs';
import path from 'node:path';

import {readField, splitArticle} from '../core/articleFile.mjs';
import {normalizeSlug} from '../core/frontmatterRules.mjs';
import {планСоздания} from '../core/newArticle.mjs';

/** Адрес, под которым статья окажется на сайте. Сравниваем именно его: папки могут быть разными. */
function адресаСайта(repo, roots) {
  // Корни нужны и для нормализации адреса: правило зависит от рода раздела.
  const адреса = new Map();

  for (const корень of roots) {
    if (корень['наСайте'] !== true) continue;
    собрать(path.join(repo, корень['папка']), корень, адреса, repo, roots);
  }

  return адреса;
}

function собрать(dir, корень, адреса, repo, roots) {
  let записи;
  try {
    записи = fs.readdirSync(dir, {withFileTypes: true});
  } catch {
    return; // корня может не быть: программа обязана работать и на неполном репозитории
  }

  for (const запись of записи) {
    const полный = path.join(dir, запись.name);
    if (запись.isDirectory()) {
      собрать(полный, корень, адреса, repo, roots);
      continue;
    }
    if (!запись.name.endsWith('.mdx') && !запись.name.endsWith('.md')) continue;

    try {
      const rel = path.relative(repo, полный).split(path.sep).join('/');
      const сырой = readField(splitArticle(fs.readFileSync(полный, 'utf8')).frontmatterRaw, 'slug');
      if (сырой === '') continue;
      // Сравнивается ИТОГОВЫЙ адрес сайта, а не то, как он записан в шапке: у документации
      // `lessons/foo` и `/lessons/foo` — один и тот же адрес, и конфликт между ними настоящий.
      const ключ = `${корень['род']}|${корень['локаль']}|${normalizeSlug(rel, сырой, roots)}`;
      if (!адреса.has(ключ)) адреса.set(ключ, path.relative(repo, полный).split(path.sep).join('/'));
    } catch {
      // Нечитаемый файл не должен мешать создавать статью: он и так сломан сам по себе.
    }
  }
}

/**
 * Создать статью по плану. Возвращает `{ошибка}` либо `{path, slug}` созданной основной версии.
 *
 * Порядок жёсткий: расчёт, все проверки, запись. Иначе можно оставить статью-калеку — русскую
 * без английской, — а такой статьи для сайта не существует вовсе, и человек этого не увидит.
 * Сбой на любом файле откатывает уже созданное: удаляются только те файлы и папки, что создали мы.
 */
export function createArticle({repo, settings, раздел, название, адрес, язык}) {
  const план = планСоздания({раздел, название, адрес, язык, settings});
  if (план.ошибка) return {ошибка: план.ошибка};

  const roots = settings['контент'];
  const всеФайлы = [...план.файлы, ...план.состояния];

  // Занятый путь — остановка. Дописать «-2» к адресу нельзя: адрес после публикации
  // не меняется без переадресации, и молчаливый суффикс останется в сайте навсегда.
  // Проверяются ВСЕ файлы плана, включая состояния: иначе занятый `_state.json` уронил бы запись
  // уже на середине, и вместо понятного «путь занят» человек получил бы «не записалось».
  for (const файл of всеФайлы) {
    if (fs.existsSync(path.join(repo, файл.path))) return {ошибка: 'путьЗанят', занято: файл.path};
  }

  // И во всех остальных локалях того же рода — даже там, где мы ничего не создаём. Занятый путь
  // в испанской папке значит, что такая статья уже существует: создавать вторую нельзя,
  // человеку надо открыть имеющуюся.
  const внутри = план.файлы[0].path.slice(
    (roots.find((корень) => план.файлы[0].path.startsWith(`${корень['папка']}/`))?.['папка'].length ?? 0) + 1,
  );
  const род = roots.find((корень) => план.файлы[0].path.startsWith(`${корень['папка']}/`))?.['род'];
  for (const корень of roots.filter((к) => к['род'] === род)) {
    const чужой = path.join(repo, корень['папка'], внутри);
    if (fs.existsSync(чужой)) {
      return {ошибка: 'путьЗанят', занято: `${корень['папка']}/${внутри}`};
    }
  }

  // Тот же адрес в другом месте сайта — конфликт: две страницы с одним адресом сайт не соберёт.
  const занятые = адресаСайта(repo, roots);
  for (const файл of план.файлы) {
    const место = roots.find((корень) => файл.path.startsWith(`${корень['папка']}/`));
    if (!место || место['наСайте'] !== true) continue;

    const slug = readField(splitArticle(файл.text).frontmatterRaw, 'slug');
    const ключ = `${место['род']}|${место['локаль']}|${slug}`;
    if (занятые.has(ключ)) return {ошибка: 'адресЗанят', занято: занятые.get(ключ)};
  }

  // Раздел обязан существовать и быть именно разделом. Признак тот же, из которого строится
  // дерево: в разделе уже лежат статьи, то есть подпапки со своим index.mdx. Папка одной статьи
  // разделом не считается — иначе новая статья уехала бы внутрь чужой и превратила бы её
  // в служебную страницу раздела. Новый раздел не создаётся: пустой роняет сборку (Б15).
  for (const файл of план.файлы) {
    if (!разделСоСтатьями(path.dirname(path.dirname(path.join(repo, файл.path))))) {
      return {ошибка: 'нетРаздела', занято: null};
    }
  }

  const созданныеФайлы = [];
  const созданныеПапки = [];

  try {
    for (const файл of всеФайлы) {
      const полный = path.join(repo, файл.path);
      создатьПапки(path.dirname(полный), созданныеПапки);
      // Флаг «только если файла нет»: между проверкой и записью файл мог появиться,
      // и затирать чужую статью нельзя ни при каких условиях.
      fs.writeFileSync(полный, файл.text, {encoding: 'utf8', flag: 'wx'});
      созданныеФайлы.push(полный);
    }
  } catch (error) {
    console.error(error);
    откатить(созданныеФайлы, созданныеПапки);
    return {ошибка: 'неЗаписалось'};
  }

  const свой = план.файлы.find((файл) => файл.локаль === план.локаль);
  // Заглушка создаётся не всегда: у английской статьи её нет вовсе, и говорить о ней человеку
  // значит врать про то, чего не было.
  return {path: свой.path, slug: план.slug, заглушка: план.файлы.some((файл) => файл.заглушка)};
}

/**
 * Есть ли внутри папки хотя бы одна статья — на любой глубине. Тот же признак, по которому
 * строится дерево разделов: узел `docs/guides` существует и тогда, когда все его статьи лежат
 * в подразделах. Проверять только прямые подпапки значило бы завести второе правило «что такое
 * раздел» и запретить создание в половине настоящих разделов сайта.
 */
function разделСоСтатьями(dir) {
  let записи;
  try {
    записи = fs.readdirSync(dir, {withFileTypes: true});
  } catch {
    return false;
  }

  return записи.some((запись) => запись.isDirectory()
    && (fs.existsSync(path.join(dir, запись.name, 'index.mdx')) || разделСоСтатьями(path.join(dir, запись.name))));
}

/** Папки создаются по одной: при откате надо знать, какие из них появились именно сейчас. */
function создатьПапки(dir, созданные) {
  if (fs.existsSync(dir)) return;
  создатьПапки(path.dirname(dir), созданные);
  fs.mkdirSync(dir);
  созданные.push(dir);
}

/** Убрать за собой ровно то, что создали сами: чужие файлы и папки не трогаются. */
function откатить(файлы, папки) {
  for (const файл of файлы) {
    try {
      fs.rmSync(файл);
    } catch (error) {
      console.error(error);
    }
  }

  for (const папка of [...папки].reverse()) {
    try {
      if (fs.readdirSync(папка).length === 0) fs.rmdirSync(папка);
    } catch (error) {
      console.error(error);
    }
  }
}
