// Память сервера о последней зелёной сборке: какая статья и с каким содержимым её прошла.
//
// Одна запись на весь сервер, живёт до его перезапуска. Больше и не нужно: сборка одна на весь
// сайт, а коммит спрашивает её ровно об одном — та ли это статья и то ли содержимое.
//
// **Перезапустили сервер — сборки нет.** Это честнее, чем считать зелёным то, чего никто не видел:
// коммит откажет и позовёт собрать заново.

let последняя = null;

/** Запомнить зелёную сборку. `null` стирает память: упавшая сборка ничего не разрешает. */
export function запомнитьСборку(факты) {
  последняя = факты ?? null;
}

/** Что известно о последней зелёной сборке. `null` — не было или сервер перезапускали. */
export function зелёнаяСборка() {
  return последняя;
}
