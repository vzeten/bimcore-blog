// Факты снятия статьи с сайта и готовый план снятия. Правило каркаса — `core/retirePlan.mjs`,
// ссылки соседей — `linkFacts.mjs`. Один вызов на всех, кто про снятие спрашивает: и показ
// вопроса человеку, и запись. Посчитай каждый по-своему — и человеку показали бы один состав, а
// зафиксировали другой.

import fs from 'node:fs';
import path from 'node:path';

import {articlePlace} from '../core/frontmatterRules.mjs';
import {путьВерсии} from '../core/articles.mjs';
import {путьФайлаСостояния} from '../core/articleState.mjs';
import {адресаСтатьи} from '../core/siteRoutes.mjs';
import {каркасСнятия} from '../core/retirePlan.mjs';
import {материализовать} from './planBytes.mjs';
import {естьВОснове, локалиРода, путиОсновыВПапке} from './publishFacts.mjs';
import {фактыВерсии} from './releaseFacts.mjs';
import {showFile} from './gitFile.mjs';
import {сведенияСайта, ссылкиВОснове} from './linkFacts.mjs';
import {закреплённаяОснова} from './publishBase.mjs';

/**
 * Пути всех языковых версий статьи на сайте — тем же правилом, каким их сшивает реестр: род тот же,
 * путь внутри раздела тот же, различается корень языка.
 */
export function путиВерсийНаСайте(rel, settings) {
  const roots = settings['контент'];
  const место = articlePlace(rel, roots);
  return локалиРода(место.kind, roots).map((локаль) => {
    const корень = roots.find((root) => root['род'] === место.kind && root['локаль'] === локаль);
    return {локаль, путь: путьВерсии(корень, место.inside)};
  });
}

/**
 * Адреса и файлы статьи на сайте — цели уборки ссылок. Считаются по всем её версиям: лежащим у
 * человека и лежащим в основе (`основа` может быть `null` — тогда только по диску).
 */
export async function целиСтатьи({git, repo, settings, rel, основа = null}) {
  const сайт = сведенияСайта(repo, settings);
  const версии = [];
  const файлы = new Set();
  for (const {путь} of путиВерсийНаСайте(rel, settings)) {
    файлы.add(путь);
    try {
      версии.push({путь, текст: fs.readFileSync(path.join(repo, путь), 'utf8')});
    } catch {
      // Версии на диске нет — её адрес возьмётся из основы, если она там есть.
    }
    const сервер = основа === null ? null : await showFile(git, основа, путь);
    if (сервер !== null) версии.push({путь, текст: сервер});
  }

  return {адреса: адресаСтатьи(версии, сайт), файлы};
}

/**
 * Снимки сайта, по которым уборка ссылок на диске узнаёт ОПУБЛИКОВАННЫЕ адреса статьи (условие
 * контролёра Codex 2026-09-19): сегодняшняя ветка сайта и её состояние ДО последней записи, тронувшей
 * файлы статьи. Уборка идёт после отправки: снятие или «Недоступно» уже на сайте, и в ветке прежнего
 * адреса больше нет, — а сменил человек `slug` локально, диск знает только новый адрес, и ссылки на
 * прежний остались бы у соседей. Спросить сайт не удалось — пусто: уборка останется по диску.
 */
export async function основыУборки({git, settings, пути}) {
  const сайт = await закреплённаяОснова({git, settings});
  if (сайт.ошибка) return [];
  const основы = [сайт.основа];
  try {
    const последняя = (await git.raw(['rev-list', '-1', сайт.основа, '--', ...пути])).trim();
    const до = последняя === '' ? '' : (await git.raw(['rev-parse', '--verify', '--quiet', `${последняя}^`])).trim();
    if (/^[0-9a-f]{40,64}$/.test(до)) основы.push(до);
  } catch {
    // Истории не спросить — остаётся сегодняшняя ветка.
  }
  return основы;
}

/**
 * Цели уборки по нескольким снимкам сайта сразу: адреса статьи с диска и из каждого снимка.
 */
export async function целиПоОсновам({git, repo, settings, rel, основы}) {
  const цели = {адреса: new Set(), файлы: new Set()};
  for (const основа of [null, ...основы]) {
    const свои = await целиСтатьи({git, repo, settings, rel, основа});
    for (const адрес of свои.адреса) цели.адреса.add(адрес);
    for (const файл of свои.файлы) цели.файлы.add(файл);
  }
  return цели;
}

/**
 * Готовый план снятия от закреплённой основы. Возвращает `{наСайте: false}` — ни одной версии в
 * основе нет, снимать нечего; `{наСайте: true, записи, разрывы, отказ, статей}` — план с байтами;
 * `{ошибка}` — спросить git не удалось.
 */
export async function планСнятия({git, repo, settings, rel, основа}) {
  const место = articlePlace(rel, settings['контент']);
  if (место.наСайте !== true) return {наСайте: false};

  const пути = путиВерсийНаСайте(rel, settings).map((версия) => ({
    ...версия,
    состояние: путьФайлаСостояния(версия.путь, settings),
  }));
  const ответ = await естьВОснове(git, основа, пути.flatMap((версия) => [версия.путь, версия.состояние]));
  if (ответ === null) return {ошибка: 'сайтНеизвестен'};
  // По точному пути в основе лежит не обычный файл: что это за страница, программа не знает.
  if (пути.some((версия) => ответ.чужие.has(версия.путь))) return {ошибка: 'составНеДоказан'};

  const вОснове = new Set(ответ.файлы.keys());
  const версии = пути.filter((версия) => вОснове.has(версия.путь));
  if (версии.length === 0) return {наСайте: false};

  const вид = фактыВерсии(repo, rel, settings)?.вид ?? null;
  const вПапках = new Map();
  for (const версия of версии) {
    вПапках.set(версия.путь, await путиОсновыВПапке(git, основа, path.posix.dirname(версия.путь)));
  }

  const предварительный = каркасСнятия({версии, вид, вОснове, вПапках});
  const свои = new Set([...пути.map((версия) => версия.путь), ...предварительный.записи.map((запись) => запись.путь)]);
  const цели = await целиСтатьи({git, repo, settings, rel, основа});
  const ссылки = await ссылкиВОснове({git, repo, settings, основа, цели, свои});
  if (ссылки === null) return {ошибка: 'сайтНеизвестен'};

  const каркас = каркасСнятия({версии, вид, вОснове, вПапках, соседи: ссылки.соседи, разрывыСоседей: ссылки.разрывы});
  if (каркас.отказ !== null || каркас.разрывы.length > 0) {
    return {наСайте: true, записи: каркас.записи, разрывы: каркас.разрывы, отказ: каркас.отказ, статей: ссылки.статей};
  }

  const {записи, отказ} = материализовать({repo, каркас});
  return {наСайте: true, записи, разрывы: [], отказ, статей: ссылки.статей};
}
