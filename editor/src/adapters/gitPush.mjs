// Единственное место программы, которое ОТПРАВЛЯЕТ в удалённый репозиторий. Всё остальное про git
// живёт в `gitCommit.mjs` (запись в местный репозиторий) и `gitFile.mjs` (чтение).
//
// Команд, переписывающих чужую работу, здесь нет ни одной: ни `--force`, ни `--tags`, ни `--all`,
// ни `--mirror`, ни `--delete`. Отправляется ровно один названный коммит в одну названную ветку.
//
// **Про `--force-with-lease`.** Ключ выглядит как сила, но работает как замок: отправка проходит
// только если удалённая ветка ровно там, где программа её видела при проверке. Без него между
// проверкой и отправкой ветку успели бы откатить или удалить, и обычный `push` спокойно увёз бы
// историю, которой человеку не показывали. Сила здесь ничего не переписывает: отправляемый коммит —
// потомок того же снимка, это проверено правилом до вызова.
//
// Правил здесь нет — они в `core/push.mjs`. Здесь только внешний мир (SPEC 4.6).

/**
 * Спросить у сервера, где сейчас удалённая ветка, и вернуть её полный SHA. Не удалось — `null`,
 * и правило ответит отказом: старому ответу веры нет.
 *
 * Читается `FETCH_HEAD`, а не `refs/remotes/...`: именно он гарантированно указывает на то, что
 * сервер отдал прямо сейчас, тогда как локальный след удалённой ветки зависит от настроек репозитория.
 */
export async function удалённаяВетка(git, удалённый, ветка) {
  try {
    await git.raw(['fetch', '--no-tags', удалённый, ветка]);

    return (await git.raw(['rev-parse', 'FETCH_HEAD'])).trim() || null;
  } catch {
    return null;
  }
}

/** Полный SHA текущего HEAD. Короткого здесь мало: по нему нельзя ни сверить, ни отправить. */
export async function головаSha(git) {
  try {
    return (await git.raw(['rev-parse', 'HEAD'])).trim() || null;
  } catch {
    return null;
  }
}

/**
 * На сколько коммитов удалённая ветка ушла вперёд названного коммита. Не удалось спросить — `null`,
 * и правило считает это незнанием, а не нулём.
 *
 * Считается от названного SHA, а не от `HEAD`: голова могла сместиться между двумя вызовами, и
 * тогда показ относился бы к одному состоянию, а отправка — к другому.
 */
export async function отставание(git, голова, отSha) {
  try {
    const число = Number((await git.raw(['rev-list', '--count', `${голова}..${отSha}`])).trim());

    return Number.isNaN(число) ? null : число;
  } catch {
    return null;
  }
}

/**
 * Коммиты, которые уедут, — каждый со своим заголовком, числом родителей и своими путями.
 * Не удалось прочитать — `null`: пустой список означал бы «уезжает ничего».
 *
 * Смотрится **каждый коммит диапазона**, а не итоговая разница деревьев: файл могли изменить и
 * вернуть обратно, и в разнице его не видно, а в отправленной истории он есть.
 *
 * Пути читаются с разделителем `NUL` (`-z`): необычное имя файла иначе исказило бы перечень.
 * Обнаружение переименований намеренно не включается — тогда переименованный файл называется
 * обоими своими путями, и оба попадают под проверку.
 */
export async function коммитыВпереди(git, голова, отSha) {
  try {
    const строки = (await git.raw(['rev-list', '--parents', `${отSha}..${голова}`]))
      .split(/\r?\n/).map((строка) => строка.trim()).filter(Boolean);

    const коммиты = [];
    for (const строка of строки) {
      const части = строка.split(/\s+/);
      const sha = части[0];
      // Имена берутся как есть, без обрезки краёв: пробел на конце имени — законная часть пути,
      // а обрезав его, программа сравнивала бы с составом не тот путь, который уедет.
      const файлы = (await git.raw([
        '-c', 'core.quotepath=false', 'diff-tree', '-r', '-z', '--no-commit-id', '--name-only', sha,
      ])).split('\0').filter((путь) => путь !== '' && путь !== '\n');
      // Заголовок коммита — единственное, по чему человек узнаёт уезжающую работу: набор из
      // семи цифр и букв ему ничего не говорит.
      const заголовок = (await git.raw(['show', '-s', '--format=%s', sha])).trim();

      коммиты.push({sha, заголовок, родителей: части.length - 1, файлы});
    }

    return коммиты;
  } catch {
    return null;
  }
}

/**
 * Есть ли коммит в истории названной ветки. Спрашивается после неудачной отправки: сравнивать
 * головы напрямую мало — сервер мог принять наш коммит, ответ потерять, а следом кто-то добавил
 * поверх свой. Коммит при этом на сайте уже есть, и «отправка не прошла» было бы неправдой.
 */
export async function естьВИстории(git, sha, где) {
  try {
    await git.raw(['merge-base', '--is-ancestor', sha, где]);

    return true;
  } catch {
    return false;
  }
}

/**
 * Отправить названный коммит в названную ветку сервера, но только если она всё ещё там, где её
 * видела проверка (`былоНаСервере`).
 *
 * Отправляется именно SHA, а не имя местной ветки: между проверкой и этой строкой местная ветка
 * могла уехать вперёд, и `push origin main` увёз бы то, чего человеку не показывали. Повтор после
 * оборванной связи по той же причине безопасен — он везёт тот же коммит.
 */
export async function отправить(git, sha, былоНаСервере, удалённый, ветка) {
  await git.raw([
    'push',
    `--force-with-lease=refs/heads/${ветка}:${былоНаСервере}`,
    удалённый,
    `${sha}:refs/heads/${ветка}`,
  ]);
}
