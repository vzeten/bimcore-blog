// Слежение за выкладкой сайта на GitHub после отправки (решение владельца 2026-09-18, п.5б).
//
// Сборки на компьютере больше нет: сайт собирает GitHub Actions, и при неудаче живой сайт остаётся
// прежним. Человек обязан это узнать — значок «Сайт» в верхней строке говорит, идёт ли выкладка,
// прошла ли она и на каком шаге упала. Состояние читается через открытый API GitHub
// (`/actions/runs?head_sha=…`, `/actions/runs/{id}/jobs`): репозиторий публичный, ключ не нужен.
//
// **Запись одна и лежит на диске** (`deploy.json` рядом с очередью коммитов): перезапуск сервера не
// теряет незаконченную выкладку. Новая отправка заменяет запись. Опрос на сервер один.
//
// **Бережно к лимиту** (60 запросов в час без ключа): повтор ответа спрашивается с `If-None-Match` —
// неизменившийся ответ лимит не тратит; остаток меньше пяти — ждём до сброса.
//
// **Учебный git честно не виден.** Удалённый не на GitHub — запись сразу «выкладку не видно», без
// единого запроса в сеть.

import fs from 'node:fs';
import path from 'node:path';

import {имяНаGitHub} from '../core/remoteName.mjs';

/** Состояния записи. Слова человеку — в настройках (`выкладка`), здесь только признаки. */
export const ЖДЁМ = 'ждём';
export const ИДЁТ = 'идёт';
export const ОБНОВЛЁН = 'обновлён';
export const СБОРКА_УПАЛА = 'сборкаУпала';
export const ВЫКЛАДКА_УПАЛА = 'выкладкаУпала';
export const НЕ_ВИДНО = 'неВидно';

/** Незаконченные состояния: за ними ещё следят. */
export const незакончена = (запись) => запись !== null && [ЖДЁМ, ИДЁТ].includes(запись?.состояние);

const файлЗаписи = (editorDir, settings) => path.join(editorDir, settings['хранение']['папкаПубликаций'], 'deploy.json');

/** Прочитать запись. Нет или битая — `null`: следить не за чем. */
export function прочитатьВыкладку(editorDir, settings) {
  try {
    const запись = JSON.parse(fs.readFileSync(файлЗаписи(editorDir, settings), 'utf8'));
    return typeof запись?.sha === 'string' && typeof запись?.состояние === 'string' ? запись : null;
  } catch {
    return null;
  }
}

/** Записать атомарно: временный файл, сброс на диск, замена. Приёмом очереди коммитов. */
export function записатьВыкладку(editorDir, settings, запись) {
  const файл = файлЗаписи(editorDir, settings);
  const временный = `${файл}.${process.pid}.tmp`;
  fs.mkdirSync(path.dirname(файл), {recursive: true});
  const открыт = fs.openSync(временный, 'w');
  try {
    fs.writeFileSync(открыт, `${JSON.stringify(запись, null, 2)}\n`, 'utf8');
    fs.fsyncSync(открыт);
  } finally {
    fs.closeSync(открыт);
  }
  fs.renameSync(временный, файл);
}

/**
 * Запомнить отправку: какую статью и какие языки она везла. Владелец и имя репозитория — из адреса
 * удалённого; не GitHub — сразу «не видно» с причиной `неGitHub`. Сбой записи отправку не отменяет:
 * она уже прошла, и человеку об этом скажут, — поэтому здесь ничего не бросается.
 */
export async function запомнитьВыкладку({git, editorDir, settings, sha, путь, локали, сейчас = new Date()}) {
  let адрес = '';
  try {
    адрес = (await git.raw(['remote', 'get-url', settings['отправка']['удалённый']])).trim();
  } catch {
    адрес = '';
  }
  const где = имяНаGitHub(адрес);
  const запись = {
    sha, путь, локали, когда: сейчас.toISOString(),
    состояние: где === null ? НЕ_ВИДНО : ЖДЁМ,
    причина: где === null ? 'неGitHub' : null,
    владелец: где?.владелец ?? null, имя: где?.имя ?? null,
    runId: null, runUrl: null, шаг: null, etag: null, показано: false,
  };
  try {
    записатьВыкладку(editorDir, settings, запись);
  } catch (ошибка) {
    console.error(ошибка);
  }
  return запись;
}

/** Человек увидел итог: значок гаснет. Запись о другой отправке не трогается. */
export function отметитьПоказ(editorDir, settings, sha) {
  const запись = прочитатьВыкладку(editorDir, settings);
  if (запись === null || запись.sha !== sha) return false;
  записатьВыкладку(editorDir, settings, {...запись, показано: true});
  return true;
}

/**
 * Что говорит ответ `/actions/runs?head_sha=…`: `{состояние, runId, runUrl, завершён}`. Запусков ещё
 * нет — «ждём»: GitHub заводит его не сразу. Берётся самый свежий запуск.
 */
export function итогЗапусков(ответ) {
  const запуски = Array.isArray(ответ?.workflow_runs) ? [...ответ.workflow_runs] : [];
  if (запуски.length === 0) return {состояние: ЖДЁМ, runId: null, runUrl: null, завершён: false};
  const свежий = запуски.sort((a, b) => Number(b.id) - Number(a.id))[0];
  const общее = {runId: свежий.id ?? null, runUrl: свежий.html_url ?? null};
  if (свежий.status !== 'completed') return {...общее, состояние: ИДЁТ, завершён: false, вОчереди: свежий.status !== 'in_progress'};
  return {...общее, состояние: свежий.conclusion === 'success' ? ОБНОВЛЁН : СБОРКА_УПАЛА, завершён: true};
}

/**
 * Какой шаг упал по ответу `/actions/runs/{id}/jobs`: работа `deploy` — «GitHub не выложил сайт»,
 * любая другая (`build`) — «не прошла сборка». Возвращает `{состояние, шаг}`.
 */
export function итогРабот(ответ) {
  const работы = Array.isArray(ответ?.jobs) ? ответ.jobs : [];
  const упала = работы.find((работа) => работа.conclusion && !['success', 'skipped'].includes(работа.conclusion)) ?? null;
  const шаг = упала?.steps?.find((ш) => ш.conclusion === 'failure')?.name ?? null;
  const выкладка = /deploy/i.test(String(упала?.name ?? ''));
  return {состояние: выкладка ? ВЫКЛАДКА_УПАЛА : СБОРКА_УПАЛА, шаг};
}

/**
 * Один опрос GitHub по записи. Возвращает `{запись, ждатьМс}`: обновлённую запись и через сколько
 * спросить снова (`null` — больше не спрашивать). `fetch` подаётся снаружи: в проверках — записанные
 * ответы настоящего GitHub, в сети — настоящий.
 */
export async function опросить({запись, fetch, опрос, сейчас = Date.now()}) {
  const прошло = сейчас - Date.parse(запись.когда);
  if (прошло > опрос['пределМинут'] * 60_000) return {запись: {...запись, состояние: НЕ_ВИДНО, причина: 'долго'}, ждатьМс: null};

  const база = `https://api.github.com/repos/${запись.владелец}/${запись.имя}/actions/runs`;
  const заголовки = {Accept: 'application/vnd.github+json', 'User-Agent': 'bimcore-editor'};
  let ответ;
  try {
    ответ = await fetch(`${база}?head_sha=${запись.sha}&per_page=3`, {
      headers: запись.etag ? {...заголовки, 'If-None-Match': запись.etag} : заголовки,
    });
  } catch {
    return {запись, ждатьМс: опрос['ждётСек'] * 1000};
  }
  const ждатьЛимит = доСброса(ответ, сейчас);
  if (ответ.status === 304) return {запись, ждатьМс: Math.max(паузаПо(запись, опрос), ждатьЛимит)};
  if (!ответ.ok) return {запись, ждатьМс: Math.max(опрос['ждётСек'] * 1000, ждатьЛимит)};

  const итог = итогЗапусков(await ответ.json());
  let новая = {...запись, состояние: итог.состояние, runId: итог.runId, runUrl: итог.runUrl, etag: ответ.headers.get('etag')};
  if (итог.завершён && итог.состояние !== ОБНОВЛЁН) {
    try {
      const работы = await fetch(`${база}/${итог.runId}/jobs`, {headers: заголовки});
      if (работы.ok) новая = {...новая, ...итогРабот(await работы.json())};
    } catch {
      // Шаг не узнан — остаётся «не прошла сборка»: итог запуска уже известен и без него.
    }
  }
  if (итог.завершён) return {запись: новая, ждатьМс: null};
  const пауза = итог.состояние === ИДЁТ && !итог.вОчереди ? опрос['идётСек'] : опрос['ждётСек'];
  return {запись: новая, ждатьМс: Math.max(пауза * 1000, ждатьЛимит)};
}

/** Пауза по состоянию: идущий запуск спрашивается чаще, чем ждущий в очереди. */
const паузаПо = (запись, опрос) => (запись.состояние === ИДЁТ ? опрос['идётСек'] : опрос['ждётСек']) * 1000;

/** Остаток лимита меньше пяти — ждать до его сброса (`X-RateLimit-Reset`, секунды эпохи). */
function доСброса(ответ, сейчас) {
  const остаток = Number(ответ.headers?.get?.('x-ratelimit-remaining'));
  const сброс = Number(ответ.headers?.get?.('x-ratelimit-reset'));
  if (!Number.isFinite(остаток) || остаток >= 5 || !Number.isFinite(сброс)) return 0;
  return Math.max(0, сброс * 1000 - сейчас);
}

/**
 * Опрос на весь сервер: один таймер, запись читается с диска на каждом шаге — новая отправка,
 * заменившая запись, опрашивается следующим же шагом. `разбудить` безопасно звать сколько угодно:
 * при идущем таймере второго не заводит.
 */
export function слежение({editorDir, настройки, fetch = globalThis.fetch}) {
  let таймер = null;

  const поставить = (мс) => {
    if (таймер === null) таймер = setTimeout(() => void шаг().catch((ошибка) => console.error(ошибка)), мс);
  };

  // Первый вопрос — не раньше, чем через `первыйСек` после отправки: GitHub заводит запуск не сразу.
  const разбудить = () => {
    const settings = настройки();
    const запись = прочитатьВыкладку(editorDir, settings);
    if (!незакончена(запись)) return;
    поставить(Math.max(0, Date.parse(запись.когда) + settings['выкладка']['опрос']['первыйСек'] * 1000 - Date.now()));
  };

  const шаг = async () => {
    таймер = null;
    const settings = настройки();
    const запись = прочитатьВыкладку(editorDir, settings);
    if (!незакончена(запись)) return;
    const {запись: новая, ждатьМс} = await опросить({запись, fetch, опрос: settings['выкладка']['опрос']});
    // Пока шёл запрос, отправили новое: старый ответ ложится мимо, опрос идёт по новой записи.
    if (прочитатьВыкладку(editorDir, settings)?.sha !== запись.sha) return разбудить();
    записатьВыкладку(editorDir, settings, новая);
    if (ждатьМс !== null) поставить(ждатьМс);
  };

  return {разбудить};
}
