// Стирание записи корзины насовсем — единственное необратимое действие программы, поэтому оно
// живёт отдельным модулем, а не среди переносов и возвратов (SPEC 4.9: файл кода не длиннее
// 300 строк, и одно правило в одном месте читается лучше).

import fs from 'node:fs';
import path from 'node:path';

import {ИМЯ_ЗАПИСИ, корзинаНастоящая, настоящаяПапка, прочитатьОпись} from './trashStore.mjs';

/**
 * Стереть запись корзины насовсем: единственное место программы, где данные уходят без возврата,
 * и только по прямому нажатию человека (решение владельца 2026-09-18).
 *
 * Стирается лишь `готово` (архив полный, оригиналов нет) и `перенос` (оригиналы ещё целы). На
 * `скопировано` и `возврат` архив — ЕДИНСТВЕННАЯ копия части файлов, и ответ один: сначала
 * повторите удаление или возврат, программа доведёт начатое.
 */
export function стеретьЗапись({repo, settings, id}) {
  if (!ИМЯ_ЗАПИСИ.test(String(id))) return {ошибка: 'нетЗаписи'};
  let dir;
  try {
    const папка = корзинаНастоящая(repo, settings);
    if (папка === null || !fs.existsSync(path.join(папка, id))) return {ошибка: 'нетЗаписи'};
    dir = настоящаяПапка(path.join(папка, id));
  } catch {
    return {ошибка: 'ссылкаВПути'};
  }

  const опись = прочитатьОпись(dir);
  if (опись === null) return {ошибка: 'нетЗаписи'};
  if (опись.состояние !== 'готово' && опись.состояние !== 'перенос') {
    return {ошибка: 'записьНезавершена', состояние: опись.состояние};
  }

  // Ссылка внутри записи снимается как ссылка: рекурсия по ней стёрла бы чужую папку.
  fs.rmSync(dir, {recursive: true, force: true});
  return {стёрто: опись.id, статья: опись.статья};
}
