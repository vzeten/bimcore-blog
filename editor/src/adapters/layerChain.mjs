// Цепочка слоёв цвета для открытой статьи: кто и когда трогал текст между публикацией и сейчас.
// Вынесено из сервера, чтобы он оставался в пределах лимита размера файла (SPEC 4.9).
// Правил здесь нет: что считать слоем — в `core/history.mjs`, кто есть кто — в `core/authors.mjs`.

import {splitArticle} from '../core/articleFile.mjs';
import {видСлоя} from '../core/authors.mjs';
import {слоиИзИмён} from '../core/history.mjs';
import {listSnapshots, snapshotText} from './draftStore.mjs';

/**
 * Состояния статьи из истории, готовые для раскраски.
 *
 * Сначала по одним ИМЕНАМ решается, какие снимки станут слоями, и только потом читаются их тексты:
 * снимок — это полный файл статьи, и прочитать всю историю ради двух слоёв значит зря перелопатить
 * диск на длинной статье.
 *
 * В цвет идёт только ТЕЛО статьи: снимок хранит файл вместе с шапкой, и сравнение шапки с текстом
 * сдвинуло бы все отрезки — цвет соврал бы по всей статье.
 *
 * Снимок, который не читается (пропал, битый), просто пропускается: цвет — не то, ради чего стоит
 * ронять открытие статьи.
 */
export function historyLayers({editorDir, settings, rel, публикацияОт, ктоЯ}) {
  const выбранные = слоиИзИмён(listSnapshots(editorDir, settings, rel), {публикацияОт});
  const предел = settings['хранение']['слоёвИстории'];

  // Идём от свежих к старым: предел — предохранитель, и отбрасывать он должен самое старое,
  // как самое близкое к тому, что и так видно на сайте.
  const слои = [];
  // Потолок числа прочитанных снимков. Один сверх предела читается всегда — иначе не понять,
  // менял ли свежий снимок текст вообще. Запас нужен для цепочки снимков с одним и тем же телом
  // (подряд переключали видимость): без потолка такая серия увела бы чтение вглубь истории.
  // Двойной предел — техническая величина алгоритма, а не настройка: человеку решать нечего,
  // на глаз она не влияет, а меняется только вместе с самим правилом чтения.
  const потолокЧтения = предел * 2;
  let прочитано = 0;

  for (let i = выбранные.length - 1; i >= 0 && прочитано < потолокЧтения; i -= 1) {
    прочитано += 1;
    const текст = snapshotText(editorDir, settings, rel, выбранные[i]['имя']);
    // Снимок пропал или нечитаем — цвет не то, ради чего стоит ронять открытие статьи.
    if (текст === null) continue;

    const body = splitArticle(текст).body;
    const kind = видСлоя(выбранные[i]['author'], settings['слоиПоАвторам'], ктоЯ);

    // Предел набран — дальше читаем только пока тело повторяется: это уточнение автора самого
    // старого слоя, а не новый слой. Остановиться раньше значило бы оставить цвет за тем, кто
    // текста не менял, — например, за переключением видимости.
    if (слои.length >= предел && слои[0].text !== body) break;

    // Тело не изменилось — значит этот снимок текста не трогал. Так выглядит переключение
    // видимости: в нём поменялась одна шапка. Отдельным слоем он не станет (занял бы место
    // в пределе и вытеснил настоящую правку), но и цвет забирать себе не должен: текст в этом
    // месте написал тот, кто правил раньше, — за ним запись и остаётся.
    if (слои.length > 0 && слои[0].text === body) {
      слои[0] = {text: body, kind};
      continue;
    }

    слои.unshift({text: body, kind});
  }

  return слои;
}
