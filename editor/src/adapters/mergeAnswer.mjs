// Общие мелочи ответа про сведение: что окно узнаёт о споре и знакома ли программе версия.
// Вынесено отдельно, потому что этим пользуются три ручки сразу — открытие, автосохранение
// и сохранение, — а второй такой же расчёт означал бы три разных ответа об одном споре.

import {countSnapshots, loadDraft} from './draftStore.mjs';
import {прочитатьСпор, спорДляОкна} from './conflictStore.mjs';

/**
 * Знает ли программа эту языковую версию: у неё есть черновик или хоть один снимок истории.
 *
 * Нужно ровно для одного случая — файла на диске нет. У знакомой версии это внешнее удаление,
 * и работа человека обязана уцелеть; у незнакомой это просто неверный адрес, и заводить по нему
 * служебные записи нельзя.
 */
export function знакомаяВерсия(repo, settings, rel) {
  return loadDraft(repo, settings, rel) !== null || countSnapshots(repo, settings, rel) > 0;
}

/** Спор этой версии в виде для окна. Спора нет — поле приходит пустым, а не отсутствует. */
export function ответСпора(repo, settings, rel) {
  return {спор: спорДляОкна(прочитатьСпор(repo, settings, rel))};
}
