// Готовый план публикации: факты → каркас → окончательные байты → правка ссылок на версии, которые
// становятся недоступными (`draftLinks.mjs`). Один вызов на всех, кто про план спрашивает: показ и
// запись. Посчитай каждый по-своему — и человеку показали бы один состав, а зафиксировали другой.
//
// Отдельным файлом от фактов (`publishFacts.mjs`): тот упёрся в предел размера (SPEC 4.9).

import {каркасПлана, публикацияВозможна} from '../core/publishPlan.mjs';
import {материализовать} from './planBytes.mjs';
import {фактыКаркаса} from './publishFacts.mjs';
import {ссылкиНаНедоступную} from './draftLinks.mjs';

/**
 * Готовый план. `rel` — открытая версия, `версии` — отмеченные в окне (по умолчанию одна открытая).
 *
 * Возвращает `{записи, разрывы, отказ, языки, лишние, ссылкиВСтатьях, версияУходит, уходят}` либо
 * `{ошибка}`; `языки` — факты про сайт по каждому языку статьи, `лишние` — файлы папок отмеченных
 * версий, на которые не ссылается ни один язык статьи (их состав уже не содержит, а с сайта их
 * уберут записи `УДАЛЕНО`), `уходят` — пути отмеченных версий, чья страница уходит с сайта этой
 * публикацией («Недоступно» у живой версии).
 */
export async function готовыйПлан({git, repo, settings, rel, основа, версии = [rel]}) {
  const факты = await фактыКаркаса({git, repo, rel, settings, основа, версии});
  if (факты.ошибка) return {ошибка: факты.ошибка};

  const каркас = каркасПлана(факты);
  // Публиковать нельзя — байты не читаются вовсе, но записи отдаются: человеку надо увидеть, о
  // каких файлах речь. Байтов у них нет, и зовущий их не получит: он сперва спрашивает
  // `публикацияВозможна`, и та скажет «нет».
  if (!публикацияВозможна(каркас)) {
    return {записи: каркас.записи, разрывы: каркас.разрывы, отказ: каркас.отказ, языки: факты.языки, лишние: факты.лишние};
  }

  const {записи, отказ} = материализовать({repo, каркас});
  if (отказ !== null) {
    return {записи, разрывы: каркас.разрывы, отказ, языки: факты.языки, лишние: факты.лишние, ссылкиВСтатьях: 0, версияУходит: false, уходят: []};
  }

  const снятие = await ссылкиНаНедоступную({git, repo, settings, основа, записи, версии});
  return {
    записи: снятие.записи, разрывы: [...каркас.разрывы, ...снятие.разрывы], отказ: снятие.отказ,
    языки: факты.языки, лишние: факты.лишние, ссылкиВСтатьях: снятие.статей, версияУходит: снятие.уходят.length > 0, уходят: снятие.уходят,
  };
}
