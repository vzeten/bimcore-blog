// Общая дверь «сверься с диском»: одна на автосохранение и на настоящее сохранение.
// Здесь внешний мир — диск, история, черновик; правила сведения живут в `core/mergeArticle.mjs`.
//
// Порядок шагов обязателен и сокращению не подлежит:
// 1. Прочитать файл и сравнить его с базой человека.
// 2. Разошёлся — положить содержимое файла в историю ОТДЕЛЬНОЙ версией и убедиться, что на диске
//    после этого лежит ровно то, что попало в историю. Иначе чужая работа исчезнет насовсем.
// 3. Найти доказанную базу. Не нашлась — автоматического сведения нет вовсе.
// 4. Свести. Спор — ничего не писать; сведено — писать только после ПОВТОРНОЙ сверки файла.

import fs from 'node:fs';
import path from 'node:path';

import {nothingChanged, splitArticle} from '../core/articleFile.mjs';
import {базаЧерновика} from '../core/drafts.mjs';
import {версииИзИмён} from '../core/history.mjs';
import {естьСпор, свестиСтатью, спорЦеликом, спорныеМеста} from '../core/mergeArticle.mjs';
import {fingerprint, listSnapshots, loadDraft, snapshotText} from './draftStore.mjs';
import {записатьСпор} from './conflictStore.mjs';
import {showFile} from './gitFile.mjs';

// Сколько раз подряд пробовать поймать файл неподвижным. Величина алгоритма, а не настройка:
// человеку решать нечего, а без предела ручка крутилась бы вечно, пока кто-то пишет в файл.
const КРУГОВ = 3;

/** Пара «шапка + тело» из сырого текста файла: стороны сведения живут только в этом виде. */
const пара = (raw) => {
  const {frontmatterRaw, body} = splitArticle(raw);
  return {frontmatterRaw, body};
};

/**
 * Содержимое файла, про которое ДОКАЗАНО, что оно уже попало в историю.
 *
 * Сначала чтение, потом фиксация, потом повторное чтение: фиксация читает файл сама, и позови мы её
 * раньше, в историю легла бы одна версия, а в сведение — другая. `null` означает, что файл меняется
 * быстрее, чем мы успеваем его закрепить, — писать в такой файл нельзя.
 */
async function внешняяСИсторией({file, rel, отпечатокБазы, фиксировать}) {
  for (let круг = 0; круг < КРУГОВ; круг += 1) {
    const raw = fs.readFileSync(file, 'utf8');
    const отпечаток = fingerprint(raw);
    if (отпечаток === отпечатокБазы) return {raw, отпечаток, разошёлся: false};

    // Требование к записи версии ставит зовущий: перед записью файла оно обязательное
    // (не легла версия — писать нельзя), при открытии статьи — нет, чтение ничего не теряет.
    await фиксировать(rel);
    if (fingerprint(fs.readFileSync(file, 'utf8')) === отпечаток) {
      return {raw, отпечаток, разошёлся: true};
    }
  }

  return null;
}

/**
 * Текст базы, от которой человек оттолкнулся. Доказательств три, и все точные: у найденного текста
 * ТОТ ЖЕ отпечаток, что заявило окно, — значит это именно та версия, а не похожая на неё.
 *
 * Первое — сам черновик: он хранит базу текстом с тех пор, как её начали записывать.
 * Второе — история: снимок с совпавшим отпечатком и есть та самая версия.
 * Третье — опубликованная ветка. Без неё оставался бы обычный случай без сведения вовсе: у только
 * что склонированной статьи файл совпадает с веткой, поэтому своего снимка у неё нет, и до первого
 * автосохранения программа не знала бы, от чего человек отталкивался.
 *
 * Ни одного — базы нет. Подставлять вместо неё текущий файл запрещено: тогда вся работа человека
 * выглядела бы его собственной правкой поверх чужой, и чужая молча исчезла бы из сведения.
 */
export async function найтиБазу({repo, settings, rel, отпечатокБазы, черновик, git, ref}) {
  const своя = базаЧерновика(черновик);
  if (своя !== null && черновик['отпечатокБазы'] === отпечатокБазы) return своя;

  const снимки = версииИзИмён(listSnapshots(repo, settings, rel));
  for (let i = снимки.length - 1; i >= 0; i -= 1) {
    const текст = snapshotText(repo, settings, rel, снимки[i]['имя']);
    if (текст !== null && fingerprint(текст) === отпечатокБазы) return пара(текст);
  }

  // Сбой git — не доказательство: молчаливое «базы нет» честнее выдуманной базы.
  const вВетке = git ? await showFile(git, ref, rel).catch(() => null) : null;
  return вВетке !== null && fingerprint(вВетке) === отпечатокБазы ? пара(вВетке) : null;
}

/**
 * Сверить работу человека с тем, что лежит на диске, и свести их.
 *
 * Исходы: `нетФайла` — версию удалили снаружи; `неуспеть` — файл меняется прямо сейчас;
 * `нетВнешней` — файл тот же, сводить нечего; `сведено` — стороны объединены целиком;
 * `спор` — есть пересечение, решать человеку; `безБазы` — сводить не от чего.
 */
export async function сверитьСДиском({repo, settings, rel, мои, отпечатокБазы, фиксировать, git, ref}) {
  const file = path.join(repo, rel);
  if (!fs.existsSync(file)) return {исход: 'нетФайла'};

  const снаружи = await внешняяСИсторией({file, rel, отпечатокБазы, фиксировать});
  if (снаружи === null) return {исход: 'неуспеть'};

  const внешняя = пара(снаружи.raw);
  const общее = {внешняя, отпечатокВнешней: снаружи.отпечаток, raw: снаружи.raw};
  // Работа человека уже слово в слово равна файлу — сводить нечего, какой бы ни была база и
  // менялся ли файл снаружи. Без этой проверки недоказуемая база превращала бы в спор два
  // одинаковых текста, а окно с устаревшим отпечатком получало бы его на каждой букве.
  if (!снаружи.разошёлся || nothingChanged(внешняя, мои)) return {исход: 'нетВнешней', ...общее};

  const черновик = loadDraft(repo, settings, rel);
  const база = await найтиБазу({repo, settings, rel, отпечатокБазы, черновик, git, ref});
  if (база === null) return {исход: 'безБазы', ...общее};

  const {части, сведено} = свестиСтатью({база, мои, внешние: внешняя});
  if (естьСпор(части)) {
    return {исход: 'спор', ...общее, база, части, спорные: спорныеМеста(части)};
  }

  return {исход: 'сведено', ...общее, база, сведено};
}

/**
 * Что открывать, когда файл разошёлся с автосохранением. Выбора «целый черновик или целый файл»
 * здесь больше нет: стороны сводятся, и человека спрашивают только про пересечение.
 *
 * Диск при открытии не меняется, кроме истории: черновик остаётся прежним, а его база сдвинется
 * сама при ближайшей записи — окно уже знает новый отпечаток файла.
 */
export async function свестиПриОткрытии({repo, settings, rel, черновик, фиксировать, git, ref}) {
  const мои = {body: черновик['body'], frontmatterRaw: черновик['frontmatterRaw']};
  const итог = await сверитьСДиском({
    repo, settings, rel, мои, отпечатокБазы: черновик['отпечатокБазы'], фиксировать, git, ref,
  });

  if (итог.исход === 'сведено') return {работа: итог.сведено};
  if (итог.исход === 'нетВнешней' || итог.исход === 'неуспеть') return {работа: мои};

  отложитьСпор({repo, settings, rel, итог, мои, когда: new Date().toISOString()});
  return {работа: мои};
}

/**
 * Записать текст статьи, ещё раз убедившись, что файл не сменился после сведения.
 * Отвечает `false`, если сменился: писать поверх в этот миг значило бы потерять версию,
 * появившуюся между чтением и записью.
 */
export function записатьСверив({file, ожидаемыйОтпечаток, текст}) {
  if (fingerprint(fs.readFileSync(file, 'utf8')) !== ожидаемыйОтпечаток) return false;
  fs.writeFileSync(file, текст, 'utf8');
  return true;
}

/**
 * Отложить спор: все стороны надёжно ложатся на диск, и только после этого ручка отвечает.
 * Пока спор лежит, эта языковая версия ждёт решения человека, а соседние работают как обычно —
 * запись спора трогает файл одной версии.
 */
export function отложитьСпор({repo, settings, rel, итог, мои, когда}) {
  // Базу доказать не удалось — стороны идут в спор целиком: выбрать между ними человек может,
  // а свести их программа не вправе. Разбор частей тот же, поэтому и отвечает человек так же.
  const части = итог.части
    ?? (итог.исход === 'безБазы' ? спорЦеликом(мои, итог.внешняя) : null);

  записатьСпор(repo, settings, {
    path: rel,
    когда,
    вид: итог.исход,
    отпечатокВнешней: итог.отпечатокВнешней ?? null,
    база: итог.база ?? null,
    мои,
    внешние: итог.внешняя ?? null,
    части,
    спорные: части === null ? [] : спорныеМеста(части),
  });
}
