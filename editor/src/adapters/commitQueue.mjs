// Очередь коммитов, сделанных самой программой: единственное доказательство их происхождения.
//
// **Память процесса тут не годится.** Прежде программа помнила свой последний коммит до перезапуска
// сервера, и после перезапуска отправлять его было нечем: коммит есть, а доказать, что он наш,
// невозможно. Человек оставался с записанной, но не уехавшей статьёй, и выбраться из этого сам не
// мог. Поэтому очередь лежит на диске — вне git, рядом с черновиками и снимками.
//
// **Запись атомарна.** Сперва временный файл рядом, потом переименование: оборвись запись на
// середине, на месте останется прежний целый файл, а не половина нового.
//
// **Битый файл — это «не знаю», а не «пусто».** Пустая очередь означала бы «своих коммитов нет» и
// разрешила бы отправку считать чужой работой всё подряд. Поэтому нечитаемый файл поднимает беду, и
// отправка отказывает.

import fs from 'node:fs';
import path from 'node:path';

/** Состояния записи. `намерение` — коммит создан, но ветка ещё не сдвинута. */
export const НАМЕРЕНИЕ = 'намерение';
export const СДЕЛАН = 'сделан';

/**
 * Знак «состояние пути в хранилище осталось неясным». Стоит в перечне невосстановленного там, где
 * назвать конкретные пути нечем: программа не сумела ни привести индекс к своему коммиту, ни
 * доказать, что с ним что-то не так. Пустой перечень значил бы «всё в порядке», а это неправда.
 */
export const НЕЯСНО = '?';

const папка = (editorDir, settings) => path.join(editorDir, settings['хранение']['папкаПубликаций']);
const файлОчереди = (editorDir, settings) => path.join(папка(editorDir, settings), 'commits.json');

/**
 * Прочитать очередь. Файла нет — пустая очередь: до первой публикации это правда.
 * Файл есть, но не читается — беда: `{ошибка: 'очередьБитая'}`.
 */
export function прочитатьОчередь(editorDir, settings) {
  const файл = файлОчереди(editorDir, settings);
  if (!fs.existsSync(файл)) return {записи: []};

  try {
    const разобрано = JSON.parse(fs.readFileSync(файл, 'utf8'));
    const записи = Array.isArray(разобрано?.записи) ? разобрано.записи : null;
    if (записи === null || !записи.every(годнаяЗапись)) return {ошибка: 'очередьБитая'};
    // Один SHA дважды — это две разные записи об одном коммите, и какая из них правда, неизвестно.
    if (new Set(записи.map((запись) => запись.sha)).size !== записи.length) return {ошибка: 'очередьБитая'};

    return {записи};
  } catch {
    return {ошибка: 'очередьБитая'};
  }
}

/**
 * Записать очередь целиком. Возвращает `true`, только если новый файл доказанно лёг на место.
 *
 * **Байты сбрасываются на диск ДО переименования.** Одного `rename` мало: он атомарен для имени, но
 * не обещает, что содержимое уже покинуло кэш. Пропажа питания сразу после успешного возврата могла
 * оставить очередь старой, пустой или битой — притом что ветка к этому времени уже сдвинута. А
 * очередь тут единственное доказательство происхождения коммита: потеряв её, программа не может
 * доказать, что коммит её, и обещанная досылка становится невозможной.
 *
 * Не удалось сбросить — отказ, и прежняя очередь остаётся целой: зовущий на отказе ветку не двигает.
 * Каталог сбрасывается ПОСЛЕ переименования и только по возможности: Windows на такой сброс отвечает
 * отказом, и превращать его в запрет публикации нельзя. Обещания абсолютной стойкости имени это не
 * даёт — и не должно.
 */
export function записатьОчередь(editorDir, settings, записи) {
  const каталог = папка(editorDir, settings);
  const файл = файлОчереди(editorDir, settings);
  const временный = `${файл}.${process.pid}.tmp`;
  let открыт = null;

  try {
    fs.mkdirSync(каталог, {recursive: true});
    открыт = fs.openSync(временный, 'w');
    fs.writeFileSync(открыт, `${JSON.stringify({записи}, null, 2)}\n`, 'utf8');
    fs.fsyncSync(открыт);
    fs.closeSync(открыт);
    открыт = null;

    fs.renameSync(временный, файл);
    сбросКаталога(каталог);

    return true;
  } catch (ошибка) {
    console.error(ошибка);

    return false;
  } finally {
    if (открыт !== null) {
      try {
        fs.closeSync(открыт);
      } catch (ошибка) {
        console.error(ошибка);
      }
    }
    try {
      fs.rmSync(временный, {force: true});
    } catch (уборка) {
      console.error(уборка);
    }
  }
}

/** Сброс каталога после переименования. Лучшая попытка: Windows на него отвечает отказом. */
function сбросКаталога(каталог) {
  let открыт = null;
  try {
    открыт = fs.openSync(каталог, 'r');
    fs.fsyncSync(открыт);
  } catch (ошибка) {
    console.error(ошибка);
  } finally {
    if (открыт !== null) {
      try {
        fs.closeSync(открыт);
      } catch (ошибка) {
        console.error(ошибка);
      }
    }
  }
}

/**
 * Записать намерение: коммит уже создан, но ветка ещё не сдвинута.
 *
 * Порядок именно такой и другим быть не может. Запиши программа очередь ПОСЛЕ сдвига ветки — обрыв
 * между ними оставил бы коммит, который никто не признаёт своим. Запиши ДО создания коммита — в
 * очереди появился бы SHA, которого нет. Намерение с известным SHA — единственный порядок, из
 * которого восстанавливаются оба исхода: коммит либо оказался в ветке, либо нет.
 */
export function записатьНамерение(editorDir, settings, запись) {
  const очередь = прочитатьОчередь(editorDir, settings);
  if (очередь.ошибка) return false;

  return записатьОчередь(editorDir, settings, [
    ...очередь.записи.filter((своя) => своя.sha !== запись.sha),
    // **Намерение пишется с самым строгим запретом, а не с пустым перечнем.** Между сдвигом ветки и
    // подтверждением программа приводит индекс и дописывает заглушки, и обрыв там оставил бы на
    // диске запись, по которой отправлять можно, хотя привести ничего не успели. Запрет снимает
    // только подтверждение — то есть доказанный итог этой работы.
    {...запись, состояние: НАМЕРЕНИЕ, невосстановленные: [НЕЯСНО]},
  ]);
}

/**
 * Подтвердить, что ветка сдвинута и работа после неё закончена: намерение стало сделанным коммитом,
 * а перечень невосстановленного — точным.
 *
 * Оба поля меняются ОДНОЙ записью файла. Пиши программа их по очереди, обрыв между записями оставил
 * бы сделанный коммит без запрета — то есть разрешил бы отправку того, что она не сумела привести
 * в порядок. Не удалось записать — прежнее намерение остаётся на диске вместе со своим `?`.
 */
export function подтвердить(editorDir, settings, sha, невосстановленные = []) {
  const очередь = прочитатьОчередь(editorDir, settings);
  if (очередь.ошибка) return false;

  return записатьОчередь(
    editorDir,
    settings,
    очередь.записи.map((запись) => (запись.sha === sha
      ? {...запись, состояние: СДЕЛАН, невосстановленные: [...new Set(невосстановленные)]}
      : запись)),
  );
}

/**
 * Годна ли запись очереди. Чужой или испорченный вид — та же беда, что и нечитаемый файл.
 *
 * Проверяются ВСЕ поля, а не только SHA. Запись очереди — единственное доказательство, что коммит
 * сделала программа, и половина такого доказательства не доказательство: без `основа` не сказать,
 * поверх чего он лёг, без `созданные` — какие файлы придётся восстановить после обрыва, без
 * `удалённые` — чем доказать принадлежность пути, которого на диске нет ни до, ни после, а повтор
 * пути внутри записи означал бы, что перечень уже кем-то испорчен. Отсутствовать могут только
 * `невосстановленные` (пустота законна) и пара `путь`/`отпечаток` у записей старого вида.
 */
function годнаяЗапись(запись) {
  if (запись === null || typeof запись !== 'object') return false;
  if (!SHA.test(String(запись.sha ?? ''))) return false;
  if (!SHA.test(String(запись.основа ?? ''))) return false;
  if (typeof запись.когда !== 'string' || запись.когда === '') return false;
  if (![НАМЕРЕНИЕ, СДЕЛАН].includes(запись.состояние)) return false;
  if (!переченьПутей(запись.пути)) return false;
  if (!переченьПутей(запись.созданные, {пустойМожно: true})) return false;
  if (!переченьПутей(запись.удалённые, {пустойМожно: true})) return false;
  // Перечня невосстановленного может не быть вовсе: его отсутствие означает «восстанавливать нечего»,
  // и это обычное состояние записи, а не половина доказательства. Битым он считается только испорченным.
  if (запись.невосстановленные !== undefined && !переченьПутей(запись.невосстановленные, {пустойМожно: true})) {
    return false;
  }
  // Путь открытой локали и отпечаток показанного плана: по ним отправка заново доказывает, что
  // статья с тех пор не изменилась. Записи старого вида их не имеют — читаются, но досылке не
  // подлежат: сверить их не с чем. Испорченные — битые.
  for (const поле of ['путь', 'отпечаток']) {
    if (запись[поле] !== undefined && (typeof запись[поле] !== 'string' || запись[поле] === '')) return false;
  }

  // Созданное и убранное — части путей коммита, а не что-то помимо них.
  const пути = new Set(запись.пути);
  if (запись.созданные.some((путь) => !пути.has(путь))) return false;
  // Один путь не бывает разом созданным и убранным: такая запись описывает две разные работы.
  const созданные = new Set(запись.созданные);

  return запись.удалённые.every((путь) => пути.has(путь) && !созданные.has(путь));
}

/** SHA коммита в полном виде. Короткий здесь не годится: по нему ничего не сверить. */
const SHA = /^[0-9a-f]{40}$/;

/** Перечень путей: непустые строки без повторов. */
function переченьПутей(значение, {пустойМожно = false} = {}) {
  if (!Array.isArray(значение)) return false;
  if (значение.length === 0) return пустойМожно;
  if (!значение.every((путь) => typeof путь === 'string' && путь !== '')) return false;

  return new Set(значение).size === значение.length;
}
