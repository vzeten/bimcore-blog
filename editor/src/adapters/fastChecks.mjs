// Быстрые проверки публикации: факты о будущем сайте для правил `core/fastRules.mjs` и разбор MDX.
//
// **Будущий сайт — это закреплённая основа плюс план.** Диск человека сюда не заглядывает: на сайт
// уедут байты плана, а всё остальное там уже лежит таким, каким его знает основа. Поэтому файлы
// сайта берутся одним `ls-tree` основы, шапки статей — одним `git grep` по основе, а записи плана
// кладутся поверх.
//
// **Разборщик MDX — тот, которым собирает сайт.** `@mdx-js/mdx` лежит в зависимостях сайта, а не
// редактора, и берётся оттуда динамически только чтением. Его нет — предупреждение `mdxНеПроверен`,
// а не отказ: сайт всё равно соберёт GitHub, и живой сайт при неудаче останется прежним.
//
// Git здесь только читается.

import fs from 'node:fs';
import path from 'node:path';
import {pathToFileURL} from 'node:url';

import {readField, splitArticle} from '../core/articleFile.mjs';
import {файлСтатьи} from '../core/articles.mjs';
import {черновикСайта} from '../core/localeSigns.mjs';
import {ВЕРСИЯ, УДАЛЕНО} from '../core/publishPlan.mjs';
import {БЛОКЕР, ПРЕДУПРЕЖДЕНИЕ, находка} from '../core/prepareRules.mjs';
import {
  ключиКомпонентов, проверитьКартинки, проверитьКомпоненты, проверитьСсылки, проверитьШапку, страницыСайта,
} from '../core/fastRules.mjs';
import {showFile} from './gitFile.mjs';
import {сведенияСайта} from './linkFacts.mjs';

/** Где у сайта лежат глобальные компоненты MDX и где — перечень самой темы, который они расширяют. */
const КОМПОНЕНТЫ_САЙТА = 'src/theme/MDXComponents.js';
const КОМПОНЕНТЫ_ТЕМЫ = ['node_modules', '@docusaurus', 'theme-classic', 'lib', 'theme', 'MDXComponents', 'index.js'];
const РАЗБОРЩИК = ['node_modules', '@mdx-js', 'mdx', 'index.js'];

/**
 * Быстрые проверки плана. `изменённые` — пути плана, расходящиеся с основой: разбирать и сверять
 * заново то, что уже лежит на живом сайте, незачем — он собран. Возвращает `{находки}`.
 */
export async function быстрыеПроверки({git, repo, settings, основа, записи, изменённые}) {
  const сайт = сведенияСайта(repo, settings);
  const вОснове = await файлыОсновы(git, основа);
  if (вОснове === null) {
    return {находки: [находка({код: 'сайтНеПрочитан', уровень: ПРЕДУПРЕЖДЕНИЕ, этап: 'ссылки'})]};
  }

  const уходят = new Set(записи.filter((запись) => запись.источник === УДАЛЕНО).map((запись) => запись.путь));
  const файлы = new Set([...вОснове, ...записи.filter((запись) => Buffer.isBuffer(запись.байты)).map((запись) => запись.путь)]);
  for (const путь of уходят) файлы.delete(путь);
  const естьФайл = (путь) => путь !== null && файлы.has(путь);

  const менялись = new Set(изменённые ?? []);
  const документы = записи
    .filter((запись) => запись.назначение === ВЕРСИЯ && Buffer.isBuffer(запись.байты) && менялись.has(запись.путь))
    .map((запись) => ({путь: запись.путь, текст: запись.байты.toString('utf8')}));
  if (документы.length === 0) return {находки: []};

  // Статья основы без шапки вовсе в ответ `git grep` не попадает, но страницу даёт: адрес ей даёт путь.
  const шапки = new Map([...вОснове].filter(файлСтатьи).map((путь) => [путь, {slug: '', черновик: false}]));
  for (const [путь, шапка] of await шапкиОсновы(git, основа, сайт.корни)) шапки.set(путь, шапка);
  for (const запись of записи) {
    if (!файлСтатьи(запись.путь)) continue;
    if (!Buffer.isBuffer(запись.байты)) шапки.delete(запись.путь);
    else шапки.set(запись.путь, шапкаТекста(запись.байты.toString('utf8')));
  }
  const страницы = страницыСайта([...шапки].map(([путь, шапка]) => ({путь, ...шапка})), сайт);
  const известные = await известныеКомпоненты(git, repo, основа);

  return {
    находки: [
      ...проверитьШапку(документы),
      ...проверитьКартинки(документы, естьФайл),
      ...проверитьСсылки(документы, страницы, сайт),
      ...проверитьКомпоненты(документы, известные, естьФайл),
      ...await разобратьMdx(repo, документы),
    ],
  };
}

/** Все обычные файлы основы. Спросить не удалось — `null`. */
async function файлыОсновы(git, основа) {
  try {
    const сырое = await git.raw(['-c', 'core.quotepath=false', 'ls-tree', '-r', '--name-only', '-z', основа]);
    return new Set(сырое.split('\0').filter(Boolean));
  } catch {
    return null;
  }
}

/** `slug` и `draft` по готовому тексту — тем же чтением поля, что у всей программы. */
function шапкаТекста(текст) {
  const шапка = splitArticle(текст).frontmatterRaw;
  return {slug: readField(шапка, 'slug'), черновик: черновикСайта(шапка)};
}

/**
 * `slug` и `draft` всех статей основы одним `git grep`: строки-заборы и строки двух полей с номерами.
 * Полем шапки считается строка между первым и вторым забором, если первый стоит в первой строке —
 * так шапку отделяет и сам разбор (`splitArticle`). Не удалось спросить — пустая карта.
 */
async function шапкиОсновы(git, основа, корни) {
  const карта = new Map();
  if (корни.length === 0) return карта;
  let сырое = '';
  try {
    сырое = await git.raw([
      '-c', 'core.quotepath=false', 'grep', '-I', '-n', '-z', '-E',
      '-e', '^---[[:space:]]*$', '-e', '^(slug|draft):', основа, '--', ...корни,
    ]);
  } catch {
    // Совпадений нет или git не ответил: статьи основы останутся без шапок, а ссылки на них —
    // непроверенными, но не ложными блокерами (правило судит только о том, что знает).
    return карта;
  }

  const поФайлам = new Map();
  for (const запись of сырое.split('\n')) {
    const [где, номер, строка] = запись.split('\0');
    if (номер === undefined) continue;
    const путь = где.startsWith(`${основа}:`) ? где.slice(основа.length + 1) : где;
    if (!файлСтатьи(путь)) continue;
    if (!поФайлам.has(путь)) поФайлам.set(путь, []);
    поФайлам.get(путь).push({номер: Number(номер), строка: String(строка ?? '').replace(/\r$/, '')});
  }
  for (const [путь, строки] of поФайлам) {
    const заборы = строки.filter((с) => /^---\s*$/.test(с.строка)).map((с) => с.номер);
    const конец = заборы[0] === 1 ? заборы[1] ?? 0 : 0;
    const поля = строки.filter((с) => с.номер < конец && !/^---/.test(с.строка)).map((с) => с.строка).join('\n');
    карта.set(путь, {slug: readField(поля, 'slug'), черновик: черновикСайта(поля)});
  }
  return карта;
}

/**
 * Имена глобальных компонентов сайта: ключи его файла компонентов в основе, а если он расширяет
 * перечень темы — ещё и ключи темы из зависимостей сайта. Чего-то прочитать не удалось — `null`.
 */
async function известныеКомпоненты(git, repo, основа) {
  const свой = await showFile(git, основа, КОМПОНЕНТЫ_САЙТА);
  if (свой === null) return null;
  const сайта = ключиКомпонентов(свой);
  if (!сайта.распространяет) return сайта.имена;
  try {
    const темы = ключиКомпонентов(fs.readFileSync(path.join(repo, ...КОМПОНЕНТЫ_ТЕМЫ), 'utf8'));
    return new Set([...сайта.имена, ...темы.имена]);
  } catch {
    return null;
  }
}

/** Разборщик MDX сайта по его корню: один на процесс, а нет его — `null`. */
const разборщики = new Map();
function разборщик(repo) {
  if (!разборщики.has(repo)) {
    const файл = path.join(repo, ...РАЗБОРЩИК);
    разборщики.set(repo, fs.existsSync(файл)
      ? import(pathToFileURL(файл).href).then((модуль) => модуль.compile ?? null, () => null)
      : Promise.resolve(null));
  }
  return разборщики.get(repo);
}

/**
 * Разобрать тело каждого документа тем MDX, каким собирает сайт (`future.v4` отключает у него
 * старые поблажки вроде `{#id}` у заголовков — сентябрьская сборка 2026 упала ровно на этом).
 * Ошибка разбора — блокер `mdxОшибка` со строкой тела.
 */
export async function разобратьMdx(repo, документы) {
  const compile = await разборщик(repo);
  if (compile === null) return [находка({код: 'mdxНеПроверен', уровень: ПРЕДУПРЕЖДЕНИЕ, этап: 'mdx'})];

  const найдено = [];
  for (const документ of документы) {
    try {
      await compile(splitArticle(документ.текст).body, {format: 'mdx'});
    } catch (ошибка) {
      найдено.push(находка({
        код: 'mdxОшибка', уровень: БЛОКЕР, этап: 'mdx', путь: документ.путь,
        строка: Number.isInteger(ошибка?.line) ? ошибка.line : null,
        значение: String(ошибка?.reason ?? ошибка?.message ?? ''),
      }));
    }
  }
  return найдено;
}
