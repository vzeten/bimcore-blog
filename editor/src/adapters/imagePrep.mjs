// Медиаподготовка: инструмент «Доработать», который приводит картинки к стандарту сайта.
//
// Алгоритм один — конвертер редактора (`imageOptimize.mjs`, решение владельца 2026-09-16); прежний
// запуск `scripts/image-prep.py` отсюда убран. Инструмент ничего не пишет: он отдаёт итог по каждой
// картинке, а запись делает общая операция «Доработать» одним набором.

import {ApiError} from './httpBody.mjs';
import {обработкаДоступна, подготовитьКартинку} from './imageOptimize.mjs';

/**
 * `подготовить(набор)` принимает `[{байты, род}]`, отдаёт итоги в том же порядке (см.
 * `подготовитьКартинку`). Библиотеки обработки нет — отказ всей операции словами ДО первой записи:
 * молча оставить файлы и назвать это доработкой значило бы соврать человеку.
 */
export function инструментыМедиа({settings}) {
  return {
    async подготовить(набор) {
      if (набор.length === 0) return [];
      if (!(await обработкаДоступна())) {
        throw new ApiError(500, settings['ошибкиСервера']['сжатиеНедоступно']);
      }

      const итоги = [];
      for (const {байты, род} of набор) итоги.push(await подготовитьКартинку({bytes: байты, род, settings}));
      return итоги;
    },
  };
}
