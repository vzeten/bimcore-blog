// Ручка начала языковой версии у существующей статьи. Правило — в `core/localeVersion.mjs`.
// Отдельным модулем, как и остальные ручки: сервер иначе выходит за предел размера файла (SPEC 4.9).

import fs from 'node:fs';
import path from 'node:path';

import {readField, splitArticle} from '../core/articleFile.mjs';
import {планЛокали} from '../core/localeVersion.mjs';
import {адресаСайта} from './createArticle.mjs';
import {articlePlace, normalizeSlug} from '../core/frontmatterRules.mjs';
import {этоЗаглушка} from '../core/stubText.mjs';
import {годныйПуть} from './releaseFacts.mjs';
import {badFields} from './httpBody.mjs';
import {saveSnapshot} from './draftStore.mjs';
import {gitAuthor} from './gitFile.mjs';

/**
 * Обрабатывает `/api/article/locale`. Возвращает true, если запрос был к ней.
 *
 * Ручка пишет ДВА файла — версию и её состояние — и делает это либо целиком, либо никак: версия
 * без состояния показала бы в реестре автора «Неизвестный» у статьи, которую человек только что
 * начал сам.
 *
 * Путь новой версии сервер считает сам из существующей статьи и настройки «контент». Принимать его
 * готовым от окна нельзя: тогда запись пошла бы туда, куда скажет клиент.
 */
export async function localeRoute({req, res, url, repo, editorDir, settings, git, тело, send}) {
  if (url.pathname !== '/api/article/locale' || req.method !== 'POST') return false;

  const payload = await тело(req);
  const плохоеТело = badFields(payload, ['path', 'локаль'], settings['ошибкиСервера']);
  if (плохоеТело) {
    send(res, плохоеТело.status, {error: плохоеТело.error});
    return true;
  }

  const rel = payload['path'];
  // Путь проверяется до любой работы с файлами: `..` увёл бы запись за пределы репозитория,
  // а картинка внутри папки статьи не должна сходить за языковую версию.
  if (!годныйПуть(rel, settings)) {
    send(res, 400, {error: settings['ошибкиСервера']['неПутьСтатьи']});
    return true;
  }

  let исходный;
  try {
    исходный = fs.readFileSync(path.join(repo, rel), 'utf8');
  } catch {
    // Статью могли удалить или перенести, пока окно было открыто.
    send(res, 404, {error: settings['ошибкиСервера']['нетФайла']});
    return true;
  }

  // Адрес, название и дата берутся у существующей версии: адрес общий у всех языков и менять его
  // нельзя (SPEC 2.5), а дата держит языковые версии одной записи блога в одном дне ленты.
  const шапка = splitArticle(исходный).frontmatterRaw;
  const план = планЛокали({
    путь: rel,
    локаль: payload['локаль'],
    slug: readField(шапка, 'slug'),
    название: названиеБезПометки(readField(шапка, 'title'), исходный, settings),
    дата: readField(шапка, 'date'),
    авторы: readField(шапка, 'authors'),
    settings,
  });

  if (план.ошибка) {
    const код = план.ошибка === 'локальУжеЕсть' ? 409 : 400;
    send(res, код, {error: settings['ошибкиСоздания'][план.ошибка] ?? план.ошибка, причина: план.ошибка});
    return true;
  }

  // Тот же адрес в другом месте целевого языка — конфликт: две страницы с одним адресом сайт
  // не соберёт вовсе. Правило и его карта общие с созданием статьи: заведи здесь своё, и они
  // разошлись бы при первой же правке (SPEC 4.3). Обход диска идёт после всех дешёвых отказов.
  const занятыйАдрес = чужойАдрес(repo, план, settings);
  if (занятыйАдрес) {
    send(res, 409, {
      error: `${settings['ошибкиСоздания']['адресЗанят']} ${занятыйАдрес}`,
      причина: 'адресЗанят',
      занято: занятыйАдрес,
    });
    return true;
  }

  const итог = записать(repo, план);
  if (итог.ошибка) {
    const код = итог.ошибка === 'путьЗанят' ? 409 : 500;
    send(res, код, {
      error: итог.занято
        ? `${settings['ошибкиСоздания'][итог.ошибка]} ${итог.занято}`
        : settings['ошибкиСоздания'][итог.ошибка],
      причина: итог.ошибка,
    });
    return true;
  }

  // Кто начал версию, известно точно: её начали мы. Без снимка реестр покажет автором
  // «Неизвестный» — автора он берёт из git, а незакоммиченный файл git ещё не знает.
  try {
    const автор = (await gitAuthor(git)) ?? settings['реестр']['неизвестныйАвтор'];
    saveSnapshot(editorDir, settings, план.path, план.text, автор, new Date().toISOString());
  } catch (error) {
    // История — служебный шаг: версия уже создана, и отменять её из-за этого нельзя.
    console.error(error);
  }

  send(res, 200, {path: план.path, локаль: план.локаль});
  return true;
}

/**
 * Название статьи без пометки заглушки. Начинают версию и от исходной статьи, и от соседней
 * заглушки; во втором случае в заголовке уже стоит пометка, и без её снятия у новой версии
 * получилось бы «Заглушка перевода: Translation placeholder: Название».
 *
 * Пометка снимается ТОЛЬКО у настоящей заглушки — той, чьё тело программа сама и написала.
 * По одному заголовку судить нельзя: живая статья, названная «Translation placeholder: …»,
 * потеряла бы начало собственного названия.
 */
function названиеБезПометки(title, исходный, settings) {
  let имя = String(title ?? '').trim();
  if (!этоЗаглушка(исходный, settings)) return имя;

  for (const шаблон of Object.values(settings['заглушкиПеревода'] ?? {})) {
    const пометка = String(шаблон?.['заголовок'] ?? '').trim();
    if (пометка !== '' && имя.startsWith(пометка)) имя = имя.slice(пометка.length).trim();
  }

  return имя;
}

/**
 * Занят ли итоговый адрес новой версии другой статьёй того же языка. Возвращает путь занявшего
 * файла либо `null`.
 *
 * Сравнивается ИТОГОВЫЙ адрес сайта, а не запись в шапке: `lessons/foo` и `/lessons/foo` — один
 * и тот же адрес, и конфликт между ними настоящий.
 */
function чужойАдрес(repo, план, settings) {
  const roots = settings['контент'];
  const место = articlePlace(план.path, roots);
  const корень = roots.find((root) => root['род'] === место.kind && root['локаль'] === план.локаль);
  // Папка вне сайта адресов не имеет вовсе: сталкиваться там нечему.
  if (!корень || корень['наСайте'] !== true) return null;

  const slug = readField(splitArticle(план.text).frontmatterRaw, 'slug');
  // Адреса нет в шапке — его выведет сам сайт из пути, а путь занят быть не может: файла по нему
  // нет, это проверено раньше.
  if (slug === '') return null;

  const занятые = адресаСайта(repo, roots);
  return занятые.get(`${место.kind}|${план.локаль}|${normalizeSlug(план.path, slug, roots)}`) ?? null;
}

/**
 * Запись версии и её состояния. Либо оба файла появились, либо ни одного: файл версии без
 * состояния — половина работы, и убрать её за программу человеку нечем.
 *
 * Файл заводится пустым «только если его нет» и с этой же секунды считается нашим: оборвись
 * запись на середине, откат обязан убрать и полупустой файл. Чужой файл в откат не попадёт —
 * на нём заведение и обрывается.
 */
function записать(repo, план) {
  const файлы = [{path: план.path, text: план.text}, план.состояние];

  for (const файл of файлы) {
    if (fs.existsSync(path.join(repo, файл.path))) return {ошибка: 'путьЗанят', занято: файл.path};
  }

  const созданныеФайлы = [];
  const созданныеПапки = [];

  try {
    for (const файл of файлы) {
      const полный = path.join(repo, файл.path);
      создатьПапки(path.dirname(полный), созданныеПапки);
      const дескриптор = fs.openSync(полный, 'wx');
      созданныеФайлы.push(полный);
      try {
        fs.writeFileSync(дескриптор, файл.text, {encoding: 'utf8'});
      } finally {
        fs.closeSync(дескриптор);
      }
    }
  } catch (error) {
    console.error(error);
    откатить(созданныеФайлы, созданныеПапки);
    // Файл появился между проверкой и записью — это не поломка, а состояние мира: второй такой же
    // запрос уже успел его создать. Человеку надо сказать «версия уже есть», а не «не записалось».
    if (error?.code === 'EEXIST') return {ошибка: 'путьЗанят', занято: error.path ?? null};
    return {ошибка: 'неЗаписалось'};
  }

  return {path: план.path};
}

/** Папки создаются по одной: при откате надо знать, какие из них появились именно сейчас. */
function создатьПапки(dir, созданные) {
  if (fs.existsSync(dir)) return;
  создатьПапки(path.dirname(dir), созданные);
  fs.mkdirSync(dir);
  созданные.push(dir);
}

/** Убрать за собой ровно то, что создали сами: чужие файлы и папки не трогаются. */
function откатить(файлы, папки) {
  for (const файл of файлы) {
    try {
      fs.rmSync(файл);
    } catch (error) {
      console.error(error);
    }
  }

  for (const папка of [...папки].reverse()) {
    try {
      if (fs.readdirSync(папка).length === 0) fs.rmdirSync(папка);
    } catch (error) {
      console.error(error);
    }
  }
}
