// Память сервера об отправке: какой коммит программа сделала сама и какой набор показала человеку.
//
// Две записи на весь сервер, живут до его перезапуска. Нужны они против одного и того же — против
// отправки, о которой человека не спрашивали:
//
// - **свой коммит.** Отправляется только тот коммит, который программа создала сама, пройдя
//   проверки и полную сборку. Чужой или вчерашний коммит с похожими путями отправить нельзя;
// - **показанный набор.** Согласие человека относится к тому перечню, который он читал. Изменился
//   перечень — согласие к нему уже не относится, и его спрашивают заново.
//
// **Перезапустили сервер — памяти нет.** Отправка откажет и попросит посмотреть заново; это честнее,
// чем везти на сайт то, чего в этой жизни программы никто не показывал.

let нашКоммит = null;
let показ = null;

/** Запомнить коммит, который программа только что создала. `null` стирает память. */
export function запомнитьКоммит(sha) {
  нашКоммит = sha ?? null;
  // Новый коммит обесценивает прежний показ: человеку показывали другое.
  показ = null;
}

/** SHA коммита, созданного этой программой. `null` — не было или сервер перезапускали. */
export function нашПоследнийКоммит() {
  return нашКоммит;
}

/** Запомнить, что именно показали человеку перед согласием. */
export function запомнитьПоказ(факты) {
  показ = факты ?? null;
}

/** Что показали человеку в последний раз. `null` — показа не было. */
export function последнийПоказ() {
  return показ;
}
