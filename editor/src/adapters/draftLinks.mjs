// «Недоступно» у опубликованной версии: её страница уходит с сайта той же публикацией, поэтому и
// ссылки на неё в других статьях убираются той же записью (правило ВК, решение владельца 2026-09-18,
// п.7). Иначе сайт с этой публикацией не собрался бы вовсе: `onBrokenLinks: 'throw'`.
//
// Правка ссылок строится так же, как у снятия статьи (`linkFacts.mjs`): из СЕРВЕРНОЙ версии соседа,
// по правилу `core/siteRoutes.mjs`. Неопубликованная работа человека над соседом не уезжает.

import {articlePlace} from '../core/frontmatterRules.mjs';
import {путьВерсии} from '../core/articles.mjs';
import {splitArticle} from '../core/articleFile.mjs';
import {черновикСайта} from '../core/localeSigns.mjs';
import {адресВерсии, адресВЯзыке} from '../core/siteRoutes.mjs';
import {ВЕРСИЯ, РЕЖИМ_ФАЙЛА} from '../core/publishPlan.mjs';
import {ОСНОВА, СОСЕД} from '../core/retirePlan.mjs';
import {естьВОснове, локалиРода} from './publishFacts.mjs';
import {сведенияСайта, ссылкиВОснове} from './linkFacts.mjs';
import {showFile} from './gitFile.mjs';

/**
 * Дополнить готовый план правкой ссылок на отмеченные `версии`, которые план делает недоступными,
 * а на сайте они сейчас есть. Цели всех таких версий собираются вместе, и соседи правятся одной
 * записью: статья, ссылающаяся на две уходящие версии, получает одну правку и считается один раз.
 *
 * Возвращает `{записи, разрывы, отказ, статей, уходят}`: записи плана вместе с соседями (по путям,
 * как у каркаса), разрывы `ссылкаНеРазобрана`, отказ «сайт не спрошен», число статей, получивших
 * правку, и пути версий, чья страница уходит с сайта. Ничего не меняется — те же записи и ноль.
 */
export async function ссылкиНаНедоступную({git, repo, settings, основа, записи, версии}) {
  const ничего = {записи, разрывы: [], отказ: null, статей: 0, уходят: []};
  const цели = {адреса: new Set(), файлы: new Set()};
  const уходят = [];

  for (const rel of версии) {
    const своя = записи.find((запись) => запись.путь === rel && запись.назначение === ВЕРСИЯ);
    if (!Buffer.isBuffer(своя?.байты)) continue;
    const текст = своя.байты.toString('utf8');
    if (!черновикСайта(splitArticle(текст).frontmatterRaw)) continue;

    const свои = await целиНедоступной({git, settings, repo, rel, текст, основа, записи});
    if (свои === null) return {...ничего, отказ: {код: 'фактыНеизвестны', локали: [своя.локаль], чего: 'ссылки'}};
    if (свои.адреса.size === 0) continue;
    уходят.push(rel);
    for (const адрес of свои.адреса) цели.адреса.add(адрес);
    for (const файл of свои.файлы) цели.файлы.add(файл);
  }
  if (уходят.length === 0) return ничего;

  const ссылки = await ссылкиВОснове({git, repo, settings, основа, цели, свои: new Set(записи.map((запись) => запись.путь))});
  if (ссылки === null) {
    const локали = записи.filter((запись) => уходят.includes(запись.путь)).map((запись) => запись.локаль);
    return {...ничего, отказ: {код: 'фактыНеизвестны', локали, чего: 'ссылки'}};
  }

  const соседи = ссылки.соседи.map((сосед) => ({
    путь: сосед.путь, назначение: СОСЕД, локаль: сосед.локаль, источник: ОСНОВА, режим: РЕЖИМ_ФАЙЛА,
    байты: Buffer.from(сосед.текст, 'utf8'),
  }));
  return {
    записи: [...записи, ...соседи].sort((a, b) => (a.путь < b.путь ? -1 : a.путь > b.путь ? 1 : 0)),
    разрывы: ссылки.разрывы,
    отказ: null,
    статей: ссылки.статей,
    уходят,
  };
}

/**
 * Цели уборки: адрес версии в её языке — если страница там сейчас есть. Есть она, когда свой файл
 * языка лежит на сайте и не черновик, а своего нет — когда на сайте живёт версия обязательного
 * языка: сайт показывает её текст под адресом этого языка. У обязательного языка целями становятся
 * ещё и адреса языков без своего файла: их страницы уходят вместе с ним. Не спросилось — `null`.
 */
export async function целиНедоступной({git, settings, repo, rel, текст, основа, записи}) {
  const сайт = сведенияСайта(repo, settings);
  const место = articlePlace(rel, сайт.roots);
  const корень = (локаль) => сайт.roots.find((root) => root['род'] === место.kind && root['локаль'] === локаль);
  const файлы = new Set([rel]);

  let своя = await живаяВерсия(git, основа, rel);
  if (своя === 'нет' && место.locale !== сайт.обязательный) {
    своя = await живаяВерсия(git, основа, путьВерсии(корень(сайт.обязательный), место.inside));
  }
  if (своя === null) return null;
  const адреса = new Set();
  const свой = адресВерсии(rel, текст, сайт);
  if (своя !== true || свой === '') return {адреса, файлы};

  адреса.add(свой);
  // Свой адрес обязательного языка — без префикса, поэтому годится основой для адресов соседей.
  if (место.locale === сайт.обязательный) {
    for (const локаль of локалиРода(место.kind, сайт.roots)) {
      if (локаль === место.locale) continue;
      const путь = путьВерсии(корень(локаль), место.inside);
      const есть = await естьВОснове(git, основа, [путь]);
      if (есть === null) return null;
      if (!есть.файлы.has(путь) && !записи.some((запись) => запись.путь === путь)) адреса.add(адресВЯзыке(свой, локаль, сайт.обязательный));
    }
  }
  return {адреса, файлы};
}

/** Версия в основе: `true` — живая страница, `false` — черновик, `'нет'` — файла нет, `null` — не спросилось. */
async function живаяВерсия(git, основа, путь) {
  const есть = await естьВОснове(git, основа, [путь]);
  if (есть === null) return null;
  if (!есть.файлы.has(путь)) return 'нет';
  const было = await showFile(git, основа, путь);
  return было === null ? null : !черновикСайта(splitArticle(было).frontmatterRaw);
}
