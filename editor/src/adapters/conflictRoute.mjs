// Ручка разрешения спора: человек ответил по каждому спорному месту, какую сторону оставить.
// Вынесено из сервера, чтобы он оставался в пределах лимита размера файла (SPEC 4.9).
// Правил здесь нет: сборка по ответам — в `core/mergeArticle.mjs`, стороны — в хранилище спора.
//
// Файл статьи эта ручка НЕ пишет. Ответ человека становится его незаписанной работой с доказанной
// базой — той самой внешней версией, про которую он и отвечал. Настоящая запись идёт обычной
// дорогой сохранения: она ещё раз сверится с диском, а к этому мигу файл могли сменить снова.

import path from 'node:path';

import {собрать, выборИзОтветов} from '../core/mergeArticle.mjs';
import {newDraft} from '../core/drafts.mjs';
import {saveDraft} from './draftStore.mjs';
import {прочитатьСпор, убратьСпор} from './conflictStore.mjs';
import {badFields} from './httpBody.mjs';

/**
 * Обрабатывает `/api/article/conflict`. Возвращает true, если запрос был к ней.
 * `последняяПравка` — общая память о порядке правок: разрешение спора такая же правка,
 * и запоздавшее автосохранение не должно её перебить.
 */
export async function conflictRoute({req, res, url, repo, settings, тело, insideRepo, send, последняяПравка}) {
  if (url.pathname !== '/api/article/conflict' || req.method !== 'POST') return false;

  const тексты = settings['ошибкиСервера'];
  const payload = await тело(req);
  const плохое = badFields(payload, ['path'], тексты);
  if (плохое) {
    send(res, плохое.status, {error: плохое.error});
    return true;
  }

  const rel = payload.path;
  if (!insideRepo(path.join(repo, rel))) {
    send(res, 400, {error: тексты['неверныйАдрес']});
    return true;
  }

  const спор = прочитатьСпор(repo, settings, rel);
  // Спора нет или его нечем решать: удалённую снаружи версию программа заново не создаёт
  // и возврата не обещает — она только сберегает работу человека.
  if (спор === null || спор['части'] === null || спор['внешние'] === null) {
    send(res, 404, {error: тексты['нетСпора']});
    return true;
  }

  const решено = собрать(спор['части'], выборИзОтветов(payload['ответы']));
  // Хоть одно место без ответа — сборки нет: выбирать за человека программа не вправе.
  if (решено === null) {
    send(res, 400, {error: тексты['плохойЗапрос']});
    return true;
  }

  const когда = new Date().toISOString();
  // База черновика — внешняя версия: именно её человек видел в панели и про неё отвечал.
  // Следующее сведение отсчитывается от неё, а не от того, что было до спора.
  saveDraft(repo, settings, newDraft({
    path: rel,
    ...решено,
    отпечатокБазы: спор['отпечатокВнешней'],
    когда,
    правкаОт: когда,
    база: спор['внешние'],
  }));

  // Спор убирается только после того, как ответ лёг в черновик: обратный порядок оставил бы
  // человека без обеих сторон, если запись не удастся.
  убратьСпор(repo, settings, rel);
  последняяПравка.set(rel, когда);

  send(res, 200, {решено, отпечаток: спор['отпечатокВнешней'], правкаОт: когда});
  return true;
}
