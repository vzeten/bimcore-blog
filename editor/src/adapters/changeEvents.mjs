// События «Действия» из серверной `main` (ED-054): и публикации владельца, и публикации сотрудника — всё,
// что дошло до сервера. Правила разбора — `core/changes.mjs`; здесь только вопросы к git и запись в базу.
//
// **Публикации это не касается никак.** Где сейчас ветка на сервере, спрашивается `ls-remote`, а её
// коммиты скачиваются `fetch` без записи `FETCH_HEAD` и без сдвига каких-либо ссылок (`--refmap=`): след
// `origin/main`, `FETCH_HEAD` и замок, на которых держится отправка, остаются нетронутыми (условие
// контролёра Codex, 2026-09-24). Сервера нет — берётся уже известный след `origin/main`.
//
// Разбор идёт по первой линии `main` от отметки «разобрано до»; каждый коммит записывается вместе со
// сдвигом отметки одной транзакцией, поэтому обрыв посреди не теряет и не удваивает событий.

import {РАЗДЕЛИТЕЛЬ, разобратьЛог, счётСтрок, короче} from '../core/changes.mjs';
import {адресВерсии} from '../core/siteRoutes.mjs';
import {articlePlace} from '../core/frontmatterRules.mjs';
import {прочитатьСостояние, записатьКоммит} from './analyticsStore.mjs';

/** Где серверная `main` сейчас: полный SHA, скачанный к себе, или `null`. */
export async function серверныйКоммит(git, удалённый = 'origin', ветка = 'main') {
  try {
    const строка = (await git.raw(['ls-remote', удалённый, `refs/heads/${ветка}`])).trim().split(/\s+/)[0];
    if (/^[0-9a-f]{40,64}$/.test(строка)) {
      await git.raw(['fetch', '--no-tags', '--no-write-fetch-head', '--refmap=', удалённый, `refs/heads/${ветка}`]);
      await git.raw(['cat-file', '-e', `${строка}^{commit}`]);
      return строка;
    }
  } catch {
    // Сервер не ответил — ниже берётся известный след.
  }
  try {
    return (await git.raw(['rev-parse', '--verify', `refs/remotes/${удалённый}/${ветка}^{commit}`])).trim() || null;
  } catch {
    return null;
  }
}

/**
 * Разобрать новые коммиты первой линии до `вершина` и записать события. `предел` — сколько коммитов за
 * один заход: первый разбор всей истории делится на части, остальное дойдёт следующими заходами.
 * Ответ — сколько коммитов разобрано.
 */
export async function разобратьНовые({git, база, вершина, сайт, предел, пределДельтыБайт, пометкаОбреза, сейчас = Date.now()}) {
  const было = прочитатьСостояние(база, 'события.разобраноДо');
  // Отметка не предок вершины (историю на сервере переписали) — разбор с начала; дубли отсечёт ключ записи.
  let от = null;
  if (было) {
    try {
      await git.raw(['merge-base', '--is-ancestor', было, вершина]);
      от = было;
    } catch {
      от = null;
    }
  }

  const порядок = (await git.raw(['rev-list', '--first-parent', '--reverse', от ? `${от}..${вершина}` : вершина]))
    .split('\n').map((строка) => строка.trim()).filter(Boolean).slice(0, предел);

  let разобрано = 0;
  for (const коммит of порядок) {
    // `show`, а не `log -1`: `log` с путями ищет ближайший коммит, ТРОНУВШИЙ эти пути, и у коммита кода
    // показал бы изменения предыдущего — события приписались бы не тому коммиту (проба 2026-09-24).
    const лог = await git.raw(['-c', 'core.quotepath=false', 'show', '--diff-merges=first-parent', '-M', '--name-status',
      `--format=@%H${РАЗДЕЛИТЕЛЬ}%an${РАЗДЕЛИТЕЛЬ}%cI`, коммит, '--', ...сайт.корни]);
    const [запись] = разобратьЛог(лог, сайт.roots);
    if (запись && запись.коммит !== коммит) throw new Error('git показал не тот коммит');
    const события = [];
    for (const изменение of запись?.изменения ?? []) {
      события.push(await событие(git, коммит, запись, изменение, сайт, пределДельтыБайт, пометкаОбреза, сейчас));
    }
    записатьКоммит(база, события, коммит);
    разобрано += 1;
  }
  return разобрано;
}

/** Первый родитель коммита или `null` у самого первого коммита истории. */
async function родитель(git, коммит) {
  try {
    return (await git.raw(['rev-parse', '--verify', `${коммит}^1`])).trim();
  } catch {
    return null;
  }
}

/**
 * Текст файла в коммите или `null`. `cat-file blob`, а не `show`: `show` сперва ищет на диске файл с именем
 * `<коммит>:<путь>`, и на Windows длинное имя роняет его ошибкой «Filename too long» (проба 2026-09-24).
 */
async function текст(git, коммит, путь) {
  if (!коммит || !путь) return null;
  try {
    return await git.raw(['cat-file', 'blob', `${коммит}:${путь}`]);
  } catch {
    return null;
  }
}

async function событие(git, коммит, запись, изменение, сайт, пределБайт, пометка, сейчас) {
  const предок = await родитель(git, коммит);
  const прежний = изменение.прежнийПуть ?? (изменение.вид === 'добавление' ? null : изменение.путь);
  const новый = изменение.вид === 'удаление' ? null : изменение.путь;

  // Разница против первого родителя; у первого коммита истории родителя нет — сравнение с пустым деревом.
  const пути = [...new Set([прежний, новый].filter(Boolean))];
  const разница = await git.raw(предок
    ? ['-c', 'core.quotepath=false', 'diff', '-M', предок, коммит, '--', ...пути]
    : ['-c', 'core.quotepath=false', 'show', '--format=', коммит, '--', ...пути]);

  const адрес = async (где, путь) => {
    const содержимое = await текст(git, где, путь);
    return содержимое === null ? null : адресВерсии(путь, содержимое, сайт) || null;
  };

  return {
    коммит,
    путь: изменение.путь,
    вид: изменение.вид,
    прежнийПуть: изменение.прежнийПуть,
    локаль: articlePlace(изменение.путь, сайт.roots).locale,
    адрес: новый ? await адрес(коммит, новый) : null,
    прежнийАдрес: прежний && предок ? await адрес(предок, прежний) : null,
    дата: запись.дата,
    увидено: new Date(сейчас).toISOString(),
    автор: запись.автор,
    дельта: короче(разница, пределБайт, пометка),
    ...счётСтрок(разница),
  };
}
