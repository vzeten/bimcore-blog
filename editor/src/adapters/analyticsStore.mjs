// Хранилище аналитики изменений (ED-054): единственная дверь к SQLite. Потребители видят только функции
// ниже, поэтому базу можно будет заменить серверной, не трогая их.
//
// Файл лежит при материалах, `<материалы>/editor/.analytics/`, в папке со своим `.gitignore`: в Git и в
// публикацию он не попадает ни в какой ветке. Здесь нет ни ключа, ни пропуска — только события и числа.
//
// Встроенный `node:sqlite` подключается лениво: в Node без него функции просто нет, а редактор работает.
// Несколько экземпляров пишут в один файл: журнал WAL, ожидание чужой записи (`busy_timeout`) и короткие
// транзакции `BEGIN IMMEDIATE` с откатом; сеть внутри транзакции не ждётся никогда (условие контролёра).

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const ФАЙЛ = 'аналитика.sqlite';

export const папкаАналитики = (repo) => path.join(repo, 'editor', '.analytics');

const СХЕМА = `
CREATE TABLE IF NOT EXISTS события (
  коммит TEXT NOT NULL, путь TEXT NOT NULL, вид TEXT NOT NULL, прежний_путь TEXT, локаль TEXT,
  адрес TEXT, прежний_адрес TEXT, дата TEXT, увидено TEXT NOT NULL, автор TEXT, дельта TEXT,
  добавлено INTEGER, убрано INTEGER, описание TEXT, PRIMARY KEY (коммит, путь));
CREATE TABLE IF NOT EXISTS ручные (
  ид INTEGER PRIMARY KEY AUTOINCREMENT, дата TEXT NOT NULL, текст TEXT NOT NULL, адрес TEXT, создано TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS поиск (
  день TEXT NOT NULL, страница TEXT NOT NULL, показы INTEGER, переходы INTEGER, ctr REAL, позиция REAL,
  неполный INTEGER NOT NULL DEFAULT 0, PRIMARY KEY (день, страница));
CREATE TABLE IF NOT EXISTS состояние (ключ TEXT PRIMARY KEY, значение TEXT);
`;

/**
 * Открыть базу. `null` — функции здесь нет: Node без `node:sqlite` или папку нельзя создать. Отказ не
 * бросается: аналитика не должна ронять редактор.
 */
export async function открыть(repo, ждатьМс = 5000) {
  let модуль;
  try {
    модуль = await import('node:sqlite');
  } catch {
    return null;
  }
  try {
    const папка = папкаАналитики(repo);
    fs.mkdirSync(папка, {recursive: true});
    const правило = path.join(папка, '.gitignore');
    if (!fs.existsSync(правило)) fs.writeFileSync(правило, '*\n');
    const база = new модуль.DatabaseSync(path.join(папка, ФАЙЛ));
    // В Node 22.14 у конструктора ещё нет срока ожидания — он задаётся самой базе.
    база.exec(`PRAGMA busy_timeout = ${Number(ждатьМс) | 0}; PRAGMA journal_mode = WAL;`);
    база.exec(СХЕМА);
    return база;
  } catch {
    return null;
  }
}

/** Короткая транзакция записи: всё или ничего. Внутри — только работа с базой, никакой сети. */
export function вТранзакции(база, работа) {
  база.exec('BEGIN IMMEDIATE');
  try {
    const итог = работа();
    база.exec('COMMIT');
    return итог;
  } catch (error) {
    try {
      база.exec('ROLLBACK');
    } catch {
      // Откатывать уже нечего — транзакция не началась.
    }
    throw error;
  }
}

export function прочитатьСостояние(база, ключ) {
  return база.prepare('SELECT значение FROM состояние WHERE ключ = ?').get(ключ)?.значение ?? null;
}

function записатьСостояние(база, ключ, значение) {
  база.prepare('INSERT INTO состояние (ключ, значение) VALUES (?, ?) ON CONFLICT(ключ) DO UPDATE SET значение = excluded.значение')
    .run(ключ, значение === null ? null : String(значение));
}

export function сохранитьСостояние(база, пары) {
  вТранзакции(база, () => {
    for (const [ключ, значение] of Object.entries(пары)) записатьСостояние(база, ключ, значение);
  });
}

/**
 * Занять право обновлять: `метка` или `null`, если обновляет другой экземпляр и его отметка моложе
 * `срокМс`. Решается одной транзакцией в самой базе — общей для всех экземпляров.
 */
export function занять(база, срокМс, сейчас = Date.now()) {
  const метка = `${сейчас}|${process.pid}|${crypto.randomUUID()}`;
  return вТранзакции(база, () => {
    const было = прочитатьСостояние(база, 'захват');
    const когда = Number(String(было ?? '').split('|')[0]);
    if (было && Number.isFinite(когда) && сейчас - когда < срокМс) return null;
    записатьСостояние(база, 'захват', метка);
    return метка;
  });
}

/** Отдать право — только своё: чужую отметку, занятую после снятия нашей просроченной, не трогать. */
export function отдать(база, метка) {
  вТранзакции(база, () => {
    if (прочитатьСостояние(база, 'захват') === метка) записатьСостояние(база, 'захват', null);
  });
}

/**
 * Записать события одного коммита и продвинуть отметку «разобрано до». Повтор ничего не удваивает:
 * ключ (коммит, путь), уже записанная строка не меняется, описание не затирается.
 */
export function записатьКоммит(база, события, разобраноДо) {
  const вставка = база.prepare(`INSERT OR IGNORE INTO события (коммит, путь, вид, прежний_путь, локаль, адрес,
    прежний_адрес, дата, увидено, автор, дельта, добавлено, убрано) VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?)`);
  вТранзакции(база, () => {
    for (const с of события) {
      вставка.run(с.коммит, с.путь, с.вид, с.прежнийПуть, с.локаль, с.адрес, с.прежнийАдрес, с.дата, с.увидено,
        с.автор, с.дельта, с.добавлено, с.убрано);
    }
    записатьСостояние(база, 'события.разобраноДо', разобраноДо);
  });
}

/** Описание события. `false` — такого события нет. Пишет его только ИИ (слово владельца 2026-09-24). */
export function описать(база, коммит, путь, описание) {
  return вТранзакции(база, () => база.prepare('UPDATE события SET описание = ? WHERE коммит = ? AND путь = ?')
    .run(описание, коммит, путь).changes > 0);
}

/** Ручное SEO-событие: отдельная таблица, с публикациями не смешивается. Ответ — его номер. */
export function добавитьРучное(база, {дата, текст, адрес}, сейчас = Date.now()) {
  return вТранзакции(база, () => Number(база.prepare('INSERT INTO ручные (дата, текст, адрес, создано) VALUES (?,?,?,?)')
    .run(дата, текст, адрес ?? null, new Date(сейчас).toISOString()).lastInsertRowid));
}

/**
 * Заменить дни поиска `с`…`по` целиком: удалить срез и положить новый одной транзакцией. Страница, пропавшая
 * из нового ответа, из базы уходит; обрыв посреди — откат, прежние дни целы.
 */
export function заменитьДни(база, {с, по, строки, неполныйС}) {
  const вставка = база.prepare('INSERT INTO поиск (день, страница, показы, переходы, ctr, позиция, неполный) VALUES (?,?,?,?,?,?,?)');
  вТранзакции(база, () => {
    база.prepare('DELETE FROM поиск WHERE день >= ? AND день <= ?').run(с, по);
    for (const [день, страница, показы, переходы, ctr, позиция] of строки) {
      вставка.run(день, страница, показы, переходы, ctr, позиция, неполныйС && день >= неполныйС ? 1 : 0);
    }
  });
}

/** Короткая сводка для проверки и окна: сколько чего лежит. */
export function сводка(база) {
  const одно = (sql) => база.prepare(sql).get();
  return {
    событий: одно('SELECT count(*) AS n FROM события').n,
    ручных: одно('SELECT count(*) AS n FROM ручные').n,
    днейПоиска: одно('SELECT count(DISTINCT день) AS n FROM поиск').n,
    последнийДеньПоиска: одно('SELECT max(день) AS д FROM поиск').д ?? null,
    последнееСобытие: одно('SELECT max(дата) AS д FROM события').д ?? null,
  };
}
