// Тонкий адаптер к git по одному файлу: содержимое из ветки, признак незакоммиченного, автор коммита.
// Вынесено из сервера, чтобы он оставался в пределах лимита размера файла (SPEC 4.9).
// Правил здесь нет — только внешний мир; правило авторства живёт в `core/externalEdit.mjs`.

import fs from 'node:fs';
import path from 'node:path';

import {splitArticle} from '../core/articleFile.mjs';
import {isUnlisted} from '../core/frontmatterRules.mjs';
import {черновикСайта} from '../core/localeSigns.mjs';
import {parseGitStatus} from '../core/gitLog.mjs';

/**
 * Какая ветка считается опубликованной. Нет связи с сервером или удалённой ветки —
 * программа обязана работать дальше, просто сравнивая с текущим состоянием репозитория.
 */
export async function detectPublishedRef(git) {
  try {
    await git.revparse(['--verify', 'origin/main']);
    return 'origin/main';
  } catch {
    return 'HEAD';
  }
}

/** Содержимое файла в ветке. Файла там нет (новая статья) — `null`, а не ошибка. */
export async function showFile(git, ref, rel) {
  try {
    return await git.show([`${ref}:${rel}`]);
  } catch {
    return null;
  }
}

/**
 * Опубликованная шапка названных версий в двух ответах: путь → `{скрыта, черновик}`, прочитанные
 * у файла из опубликованной ветки. И значок «только по ссылке», и красный цвет букв обещают
 * поведение ЖИВОЙ страницы, поэтому местная шапка на эти вопросы не отвечает: до публикации она
 * говорит лишь о том, что человек готовит.
 *
 * Оба признака берутся из ОДНОГО чтения: спрашивать ветку дважды об одной и той же шапке значило
 * бы удвоить обращения к git и завести второй источник того же факта.
 *
 * Спрашиваются ровно те пути, которые назвало правило (`путиЗаОпубликованнойШапкой`), а не все
 * статьи: у версии, совпадающей с веткой, опубликованная шапка и лежит на диске. Путь, которого
 * в ветке нет или который прочитать не удалось, в ответ не попадает вовсе — «не знаю» здесь
 * не подделывается под «не скрыта» и «не черновик».
 *
 * Читается тем же разбором, каким программа читает любую шапку: вторые правила `unlisted` и
 * `draft` разошлись бы с первыми (SPEC 2.8, 4.3).
 */
export async function шапкиВВетке(git, ref, пути) {
  const карта = new Map();

  for (const путь of пути ?? []) {
    const raw = await showFile(git, ref, путь);
    if (raw === null) continue;
    const {frontmatterRaw} = splitArticle(raw);
    карта.set(путь, {скрыта: isUnlisted(frontmatterRaw), черновик: черновикСайта(frontmatterRaw)});
  }

  return карта;
}

/**
 * Сколько путей уходит в один вызов git. Техническая величина алгоритма, а не настройка (SPEC 4.4):
 * её задаёт предел длины командной строки, а не решение человека.
 */
const ПУТЕЙ_ЗА_РАЗ = 100;

/** Тот же вопрос git частями: длинный перечень путей в одну команду не помещается. */
async function частями(пути, спросить) {
  for (let i = 0; i < пути.length; i += ПУТЕЙ_ЗА_РАЗ) await спросить(пути.slice(i, i + ПУТЕЙ_ЗА_РАЗ));
}

/**
 * Пути, у которых содержимое МОЖЕТ отличаться от ветки. Это отбор подозреваемых, а не ответ: `diff`
 * знает про файлы под наблюдением git, `status` — про неотслеживаемые, и оба говорят про индекс
 * ТЕКУЩЕЙ ветки. Папка материалов, стоящая на другой ветке, из-за этого называет «удалённым» файл,
 * который лежит на диске, и «новым» тот, что на сайте давно есть.
 */
async function подозреваемые(git, ref, пути) {
  const тронутые = (await git.raw([
    '-c', 'core.quotepath=false', 'diff', '--name-only', '-z', ref, '--', ...пути,
  ])).split('\0');
  const неотслеживаемые = (await git.raw([
    '-c', 'core.quotepath=false', 'status', '--porcelain', '--untracked-files=all', '-z', '--', ...пути,
  ])).split('\0')
    .filter((строка) => строка.startsWith('?? '))
    .map((строка) => строка.slice(3));

  return [...new Set([...тронутые, ...неотслеживаемые])].filter((путь) => путь !== '' && путь !== '\n');
}

/** Отпечаток содержимого каждого названного пути в ветке. Нет пути в ветке — нет и записи. */
async function отпечаткиВетки(git, ref, пути) {
  const карта = new Map();

  await частями(пути, async (кусок) => {
    const сырое = await git.raw(['-c', 'core.quotepath=false', 'ls-tree', '-r', '-z', ref, '--', ...кусок]);

    for (const запись of сырое.split('\0')) {
      const таб = запись.indexOf('\t');
      if (таб < 0) continue;
      const [, тип, отпечаток] = запись.slice(0, таб).split(' ');
      // Дерево и подмодуль содержимым файла не являются: сравнивать по ним нечего.
      if (тип === 'blob') карта.set(запись.slice(таб + 1), отпечаток);
    }
  });

  return карта;
}

/**
 * Отпечаток того, что лежит на диске, — ровно такой, каким его увидел бы коммит: `hash-object`
 * применяет те же преобразования git, поэтому разные переводы строк не выдаются за правку текста.
 * Файла на диске нет — нет и записи: это удаление, а не совпадение.
 */
async function отпечаткиДиска(git, корень, пути) {
  const карта = new Map();
  const живые = пути.filter((путь) => fs.statSync(path.join(корень, путь), {throwIfNoEntry: false})?.isFile());

  await частями(живые, async (кусок) => {
    const строки = (await git.raw(['hash-object', '--', ...кусок.map((путь) => path.join(корень, путь))]))
      .split('\n').map((строка) => строка.trim()).filter((строка) => строка !== '');

    // Ответ идёт по порядку заданных путей; сбилась длина — сопоставлять молча нельзя.
    if (строки.length !== кусок.length) throw new Error('git hash-object ответил не про те файлы');
    кусок.forEach((путь, i) => карта.set(путь, строки[i]));
  });

  return карта;
}

/**
 * Какие из названных путей расходятся с тем, что лежит на сайте. Остальные там уже ровно такие:
 * их не надо ни называть уезжающими, ни переписывать.
 *
 * Считается по СОДЕРЖИМОМУ против опубликованной ветки, а не по служебному состоянию git: человека
 * интересует, что изменится НА САЙТЕ, а не на какой ветке стоит папка материалов и что в ней ещё не
 * закоммичено. Поэтому у каждого подозреваемого пути сравниваются два отпечатка — из ветки и с
 * диска; равные отпечатки означают совпадение, и признак изменения не появляется. Пути нет с одной
 * из сторон — это расхождение: новая либо удалённая версия.
 *
 * Спрашивается разом по всем путям — по файлу за раз получилось бы под сотню вызовов git у статьи
 * с картинками.
 *
 * Не удалось спросить — `null`, а не пустой перечень: «ничего не меняется» и «не знаю» для человека
 * разные ответы, и выдавать второе за первое нельзя.
 */
export async function расхождениеССайтом(git, ref, пути) {
  if (!Array.isArray(пути) || пути.length === 0) return [];

  try {
    const спорные = await подозреваемые(git, ref, пути);
    if (спорные.length === 0) return [];

    // Пути git называет от корня репозитория, и на диск надо смотреть оттуда же, а не из места,
    // откуда запущена программа: материалы владельца лежат не рядом с кодом операции.
    const корень = (await git.raw(['rev-parse', '--show-toplevel'])).trim();
    const вВетке = await отпечаткиВетки(git, ref, спорные);
    const наДиске = await отпечаткиДиска(git, корень, спорные);

    return спорные.filter((путь) => (вВетке.get(путь) ?? null) !== (наДиске.get(путь) ?? null));
  } catch {
    return null;
  }
}

/**
 * Имя человека за клавиатурой — для подписи снимка, который делает сам редактор.
 * Это не догадка об авторе чужой правки (так делать запрещено, см. `DECISIONS.md`):
 * здесь известно, что файл пишем мы, и остаётся только узнать, как зовут того, кто работает.
 */
export async function gitAuthor(git) {
  try {
    return (await git.raw(['config', 'user.name'])).trim() || null;
  } catch {
    return null;
  }
}

/**
 * Когда файл в опубликованной ветке стал таким, какой он там сейчас.
 * Нужно, чтобы отсечь снимки истории, сделанные ДО публикации: иначе после «того, что на сайте»
 * встанет состояние, которое было до него, и уже вышедший текст перекрасится в черновые правки.
 * Времени нет (файл не публиковался, git недоступен) — `null`: тогда в цвет идёт вся история.
 */
export async function publishedAt(git, ref, rel) {
  try {
    const сырое = (await git.raw(['log', '-1', '--format=%cI', ref, '--', rel])).trim();
    // Git отдаёт время со своим сдвигом часового пояса («+02:00»), а сравнивается оно с временем
    // снимков — а те записаны в UTC. Без приведения сравнение строк молча провалилось бы,
    // и отсечка просто не сработала бы: в цвет пошла бы вся история, включая уже опубликованное.
    const мс = Date.parse(сырое);
    return Number.isFinite(мс) ? new Date(мс).toISOString() : null;
  } catch {
    return null;
  }
}

/**
 * Что git знает про один путь: изменён ли он без коммита и кто автор последнего коммита.
 * Git недоступен — считаем файл незакоммиченным без автора: выдумывать подпись хуже, чем её не иметь.
 * Лог спрашивается только у чистого файла: у грязного он всё равно ничего не доказывает.
 */
export async function gitFacts(git, rel) {
  let грязный;

  try {
    const status = await git.raw(['-c', 'core.quotepath=false', 'status', '--porcelain', '--', rel]);
    грязный = parseGitStatus(status).size > 0;
  } catch {
    return {грязный: true, авторКоммита: null};
  }

  if (грязный) return {грязный, авторКоммита: null};

  try {
    return {грязный, авторКоммита: (await git.raw(['log', '-1', '--format=%an', '--', rel])).trim() || null};
  } catch {
    return {грязный, авторКоммита: null};
  }
}

/**
 * Что фактически лежит в коммите. Спрашивается у самого git, а не берётся из плана: в коммит
 * попадают только изменившиеся файлы, и запись о происхождении обязана описывать коммит таким,
 * какой он есть, — иначе отправка сочтёт его переписанным и откажет.
 */
export async function путиКоммита(git, sha) {
  const сырое = await git.raw(['-c', 'core.quotepath=false', 'show', '--name-only', '--format=', '-z', sha]);

  // Обрезать пробелы у пути нельзя: в имени файла они законны, и обрезанный путь описывал бы не тот
  // файл. Отбрасываются только пустые куски и перевод строки, который git ставит перед перечнем.
  return сырое.split('\0').filter((путь) => путь !== '' && путь !== '\n');
}

/** Дерево названного коммита. По нему видно, отличается ли от него то, что сложил индекс. */
export async function деревоКоммита(git, sha) {
  return (await git.raw(['rev-parse', `${sha}^{tree}`])).trim();
}
