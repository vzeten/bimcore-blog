// Тонкий адаптер к git по одному файлу: содержимое из ветки, признак незакоммиченного, автор коммита.
// Вынесено из сервера, чтобы он оставался в пределах лимита размера файла (SPEC 4.9).
// Правил здесь нет — только внешний мир; правило авторства живёт в `core/externalEdit.mjs`.

import {splitArticle} from '../core/articleFile.mjs';
import {isUnlisted} from '../core/frontmatterRules.mjs';
import {parseGitStatus} from '../core/gitLog.mjs';

/**
 * Какая ветка считается опубликованной. Нет связи с сервером или удалённой ветки —
 * программа обязана работать дальше, просто сравнивая с текущим состоянием репозитория.
 */
export async function detectPublishedRef(git) {
  try {
    await git.revparse(['--verify', 'origin/main']);
    return 'origin/main';
  } catch {
    return 'HEAD';
  }
}

/** Содержимое файла в ветке. Файла там нет (новая статья) — `null`, а не ошибка. */
export async function showFile(git, ref, rel) {
  try {
    return await git.show([`${ref}:${rel}`]);
  } catch {
    return null;
  }
}

/**
 * Видимость названных версий такой, какой её видит САМ САЙТ: путь → стоит ли `unlisted: true` в
 * шапке файла из опубликованной ветки. Значок «только по ссылке» обещает поведение живой страницы,
 * поэтому местная шапка на этот вопрос не отвечает.
 *
 * Спрашиваются ровно те пути, которые назвало правило (`путиЗаВидимостью`), а не все статьи: у
 * версии, совпадающей с веткой, опубликованная шапка и лежит на диске. Путь, которого в ветке нет
 * или который прочитать не удалось, в ответ не попадает вовсе — «не знаю» здесь не подделывается
 * под «не скрыта».
 *
 * Читается тем же разбором, каким программа читает любую шапку: второе правило `unlisted`
 * разошлось бы с первым (SPEC 2.8).
 */
export async function видимостьВВетке(git, ref, пути) {
  const карта = new Map();

  for (const путь of пути ?? []) {
    const raw = await showFile(git, ref, путь);
    if (raw === null) continue;
    карта.set(путь, isUnlisted(splitArticle(raw).frontmatterRaw));
  }

  return карта;
}

/**
 * Какие из названных путей расходятся с тем, что лежит на сайте. Остальные там уже ровно такие:
 * их не надо ни называть уезжающими, ни переписывать.
 *
 * Спрашивается разом по всем путям — по файлу за раз получилось бы под сотню вызовов git у статьи
 * с картинками. Считается против опубликованной ветки, а не против последнего коммита: человека
 * интересует, что изменится НА САЙТЕ.
 *
 * Не удалось спросить — `null`, а не пустой перечень: «ничего не меняется» и «не знаю» для человека
 * разные ответы, и выдавать второе за первое нельзя.
 */
export async function расхождениеССайтом(git, ref, пути) {
  if (!Array.isArray(пути) || пути.length === 0) return [];

  try {
    const тронутые = (await git.raw([
      '-c', 'core.quotepath=false', 'diff', '--name-only', '-z', ref, '--', ...пути,
    ])).split('\0').filter((путь) => путь !== '' && путь !== '\n');
    // Файла нет в ветке вовсе (новая картинка, новая версия) — `diff` его покажет как добавленный
    // только если он под наблюдением git. Неотслеживаемый спрашивается отдельно.
    const новые = (await git.raw([
      '-c', 'core.quotepath=false', 'status', '--porcelain', '--untracked-files=all', '-z', '--', ...пути,
    ])).split('\0')
      .filter((строка) => строка.startsWith('?? '))
      .map((строка) => строка.slice(3));

    return [...new Set([...тронутые, ...новые])];
  } catch {
    return null;
  }
}

/**
 * Имя человека за клавиатурой — для подписи снимка, который делает сам редактор.
 * Это не догадка об авторе чужой правки (так делать запрещено, см. `DECISIONS.md`):
 * здесь известно, что файл пишем мы, и остаётся только узнать, как зовут того, кто работает.
 */
export async function gitAuthor(git) {
  try {
    return (await git.raw(['config', 'user.name'])).trim() || null;
  } catch {
    return null;
  }
}

/**
 * Когда файл в опубликованной ветке стал таким, какой он там сейчас.
 * Нужно, чтобы отсечь снимки истории, сделанные ДО публикации: иначе после «того, что на сайте»
 * встанет состояние, которое было до него, и уже вышедший текст перекрасится в черновые правки.
 * Времени нет (файл не публиковался, git недоступен) — `null`: тогда в цвет идёт вся история.
 */
export async function publishedAt(git, ref, rel) {
  try {
    const сырое = (await git.raw(['log', '-1', '--format=%cI', ref, '--', rel])).trim();
    // Git отдаёт время со своим сдвигом часового пояса («+02:00»), а сравнивается оно с временем
    // снимков — а те записаны в UTC. Без приведения сравнение строк молча провалилось бы,
    // и отсечка просто не сработала бы: в цвет пошла бы вся история, включая уже опубликованное.
    const мс = Date.parse(сырое);
    return Number.isFinite(мс) ? new Date(мс).toISOString() : null;
  } catch {
    return null;
  }
}

/**
 * Что git знает про один путь: изменён ли он без коммита и кто автор последнего коммита.
 * Git недоступен — считаем файл незакоммиченным без автора: выдумывать подпись хуже, чем её не иметь.
 * Лог спрашивается только у чистого файла: у грязного он всё равно ничего не доказывает.
 */
export async function gitFacts(git, rel) {
  let грязный;

  try {
    const status = await git.raw(['-c', 'core.quotepath=false', 'status', '--porcelain', '--', rel]);
    грязный = parseGitStatus(status).size > 0;
  } catch {
    return {грязный: true, авторКоммита: null};
  }

  if (грязный) return {грязный, авторКоммита: null};

  try {
    return {грязный, авторКоммита: (await git.raw(['log', '-1', '--format=%an', '--', rel])).trim() || null};
  } catch {
    return {грязный, авторКоммита: null};
  }
}

/**
 * Что фактически лежит в коммите. Спрашивается у самого git, а не берётся из плана: в коммит
 * попадают только изменившиеся файлы, и запись о происхождении обязана описывать коммит таким,
 * какой он есть, — иначе отправка сочтёт его переписанным и откажет.
 */
export async function путиКоммита(git, sha) {
  const сырое = await git.raw(['-c', 'core.quotepath=false', 'show', '--name-only', '--format=', '-z', sha]);

  // Обрезать пробелы у пути нельзя: в имени файла они законны, и обрезанный путь описывал бы не тот
  // файл. Отбрасываются только пустые куски и перевод строки, который git ставит перед перечнем.
  return сырое.split('\0').filter((путь) => путь !== '' && путь !== '\n');
}

/** Дерево названного коммита. По нему видно, отличается ли от него то, что сложил индекс. */
export async function деревоКоммита(git, sha) {
  return (await git.raw(['rev-parse', `${sha}^{tree}`])).trim();
}
