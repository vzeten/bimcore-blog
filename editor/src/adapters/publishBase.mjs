// Закреплённая основа публикации: тот самый снимок сайта, поверх которого считается план.
//
// **Основа — это опубликованная ветка на сервере, и только она.** Ни `HEAD`, ни текущая ветка, ни
// местная `main` здесь не спрашиваются вовсе: человек публикует статью из любой рабочей ветки, и
// состояние его репозитория к тому, чем является сайт, отношения не имеет. План обещает, чем
// станет САЙТ, а сайт — это `origin/main` в эту минуту.
//
// Ветку спрашивают у сервера, а не у местной копии: пока человек работал, туда могли толкнуть с
// другой машины, и прежний ответ уже ничего не обещает. Спросить не удалось — отказ, а не подмена
// чем-нибудь местным.

import {ВЕТКА_ВЫПУСКА} from '../core/publish.mjs';
import {удалённаяВетка} from './gitPush.mjs';

/**
 * Закрепить основу. Возвращает `{основа}` — полный SHA опубликованной ветки на сервере — либо
 * `{ошибка: 'удалённыйНеизвестен'}`.
 */
export async function закреплённаяОснова({git, settings}) {
  const основа = await удалённаяВетка(git, settings['отправка']['удалённый'], ВЕТКА_ВЫПУСКА);
  if (typeof основа !== 'string' || основа === '') return {ошибка: 'удалённыйНеизвестен'};

  return {основа};
}
