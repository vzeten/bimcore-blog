// Закреплённая основа публикации: тот самый снимок сайта, поверх которого считается план.
//
// **`HEAD` опубликованную ветку не подменяет.** Раньше программа при отсутствии связи бралась
// сравнивать с `HEAD`, и это годилось для показа цвета, но не годится здесь: план обещает, чем
// станет САЙТ, и брать вместо сайта своё же незакоммиченное состояние значит обещать неправду.
// Общий `detectPublishedRef` поэтому не меняется — публикация спрашивает ветку сама и строго.
//
// **Новый выпуск не начинается, пока голова не равна основе.** Иначе сборка проверяла бы дерево,
// собранное поверх опубликованной ветки, а уехала бы цепочка коммитов, которой в этом дереве нет.
// Есть свой неотправленный коммит — человеку предлагается повторить отправку, а не копить второй.

import {ВЕТКА_ВЫПУСКА} from '../core/publish.mjs';
import {головаSha, отставание, удалённаяВетка} from './gitPush.mjs';
import {текущаяВетка} from './gitCommit.mjs';

/**
 * Закрепить основу. Возвращает `{основа, голова}` либо `{ошибка}`.
 *
 * Коды отказа те же, какими программа уже говорит об отправке, — человек читает знакомые слова:
 * `неТаВетка`, `удалённыйНеизвестен`, `головаНеизвестна`, `ветвиРазошлись`, `естьНеотправленное`.
 */
export async function закреплённаяОснова({git, settings}) {
  const ветка = await текущаяВетка(git);
  if (ветка !== ВЕТКА_ВЫПУСКА) return {ошибка: 'неТаВетка', ветка};

  const голова = await головаSha(git);
  if (typeof голова !== 'string' || голова === '') return {ошибка: 'головаНеизвестна'};

  // Ветку спрашиваем у сервера, а не у местной копии: пока человек работал, туда могли толкнуть
  // с другой машины, и прежний ответ уже ничего не обещает.
  const основа = await удалённаяВетка(git, settings['отправка']['удалённый'], ВЕТКА_ВЫПУСКА);
  if (основа === null) return {ошибка: 'удалённыйНеизвестен'};

  if (основа === голова) return {основа, голова};

  // Голова и основа разошлись. Что именно случилось, решает направление: ветка на сервере ушла
  // вперёд — это чужая работа, и сливать её молча программа не станет; впереди мы сами — значит
  // прошлая публикация записана, но не уехала.
  const назад = await отставание(git, голова, основа);
  if (typeof назад !== 'number' || Number.isNaN(назад)) return {ошибка: 'удалённыйНеизвестен'};
  if (назад > 0) return {ошибка: 'ветвиРазошлись', отставание: назад};

  return {ошибка: 'естьНеотправленное', голова, основа};
}
