// Факты для правила даты записи блога: что про эту статью знает САЙТ.
//
// Правило (`core/publishDate.mjs`) решает, какая дата обязана стоять у открытой версии, но само
// ничего не читает. Здесь собираются его входы: дата этой же версии в закреплённой основе и даты
// опубликованных соседних языков. Диск человека не спрашивается ни разу: на диске лежит то, что он
// готовит, а дата записи принадлежит ленте сайта.
//
// Спрашивается ОСНОВА — закреплённый SHA опубликованной ветки, тот же, по которому считается план
// публикации. Спросить не удалось — это отказ у зовущего, а не «дат нет»: приняв незнание за
// отсутствие, программа поставила бы сегодняшний день записи, которая на сайте уже год.

import {articlePlace} from '../core/frontmatterRules.mjs';
import {readField, splitArticle} from '../core/articleFile.mjs';
import {РОД_БЛОГА, датаРасходится, нужнаяДата} from '../core/publishDate.mjs';
import {фактыКаркаса} from './publishFacts.mjs';
import {showFile} from './gitFile.mjs';

/**
 * Какая дата обязана стоять у открытой версии по закреплённой основе.
 *
 * Возвращает `{нужна}` — строку `ГГГГ-ММ-ДД` либо `null`, когда программа даты не касается
 * (не блог; либо версия на сайте есть, а даты у неё там нет), — или `{ошибка}`, когда факты
 * собрать не удалось.
 *
 * `сегодня` приходит снаружи одной величиной: два вычисления «сегодня» в одном ходе публикации
 * разошлись бы около полуночи, и проверенные байты отличались бы от записанных.
 */
export async function датаПоОснове({git, repo, rel, settings, основа, сегодня}) {
  const род = articlePlace(rel, settings['контент']).kind;
  if (род === null) return {ошибка: 'неПутьСтатьи'};
  // Дата живёт только у блога. Спрашивать сайт про статью документации незачем: такого поля у неё
  // нет вовсе, и лишний вопрос к git ничего бы не решил.
  if (род !== РОД_БЛОГА) return {нужна: null};

  const факты = await фактыКаркаса({git, repo, rel, settings, основа});
  if (факты.ошибка) return {ошибка: факты.ошибка};

  // Перечень языков — единственный источник путей и признака «лежит ли на сайте». Признак строго
  // логический: «не знаю» здесь означает отказ, а не «не опубликован».
  const свой = (факты.языки ?? []).find((язык) => язык.путь === rel);
  if (свой === undefined || свой.опубликован === null) return {ошибка: 'фактыНеизвестны'};

  let своя = null;
  if (свой.опубликован === true) {
    const ответ = await датаВОснове(git, основа, rel);
    // Файл в основе есть — значит прочитать его обязано получиться. Не получилось — это незнание, а
    // не «даты там нет»: второе разрешило бы публиковать дальше по выдуманной дате.
    if (ответ.ошибка) return {ошибка: 'фактыНеизвестны'};
    своя = {дата: ответ.дата};
  }

  const соседи = [];
  for (const язык of факты.языки ?? []) {
    if (язык.путь === rel) continue;
    if (язык.опубликован === null) return {ошибка: 'фактыНеизвестны'};
    if (язык.опубликован !== true) continue;
    const ответ = await датаВОснове(git, основа, язык.путь);
    if (ответ.ошибка) return {ошибка: 'фактыНеизвестны'};
    соседи.push({дата: ответ.дата});
  }

  return {нужна: нужнаяДата({род, своя, соседи, сегодня})};
}

/**
 * Заслон для состава, сборки и записи: расходится ли дата в проверенных БАЙТАХ с той, что обязана
 * стоять по этой же закреплённой основе. Возвращает код отказа либо `null`.
 *
 * Сравниваются байты снимка проверок, а не сегодняшний файл с диска: проверки, сборка и коммит
 * отвечают за один снимок, и читать здесь диск заново значило бы сверять не то, что уедет.
 *
 * `фактыНеизвестны` не подделывается под «совпало»: не сумев спросить сайт, программа отказывает.
 */
export async function датаРазошлась({git, repo, rel, settings, основа, срез}) {
  const итог = await датаПоОснове({
    git, repo, rel, settings, основа, сегодня: сегодняшнийДень(),
  });
  if (итог.ошибка) return 'составНеДоказан';
  if (итог.нужна === null) return null;

  const байты = срез?.байты;
  // Байтов снимка нет — сверять нечего, и выдумывать согласие нельзя: у зовущего свои проверки
  // снимка стоят раньше этой, и до сюда такой случай доходить не должен.
  if (!Buffer.isBuffer(байты)) return 'датаУстарела';

  const вФайле = readField(splitArticle(байты.toString('utf8')).frontmatterRaw, 'date');
  return датаРасходится({нужна: итог.нужна, вФайле}) ? 'датаУстарела' : null;
}

/**
 * Дата в шапке файла, лежащего в основе: `{дата}` либо `{ошибка: true}`.
 *
 * Зовётся только для путей, про которые уже известно, что они в основе ЕСТЬ. Поэтому пустой ответ
 * git здесь означает не «файла нет», а «прочитать не удалось», и выдавать его за отсутствие даты
 * нельзя: по такому ответу программа поставила бы сегодняшний день записи, живущей на сайте давно.
 */
async function датаВОснове(git, основа, путь) {
  const сырое = await showFile(git, основа, путь);
  if (сырое === null) return {ошибка: true};

  return {дата: readField(splitArticle(сырое).frontmatterRaw, 'date') || null};
}

/**
 * Сегодняшний день по календарю человека. Тот же счёт, что у создания статьи: по UTC около полуночи
 * вышел бы вчерашний день, а день выхода записи человек видит по своим часам.
 */
export function сегодняшнийДень() {
  const сейчас = new Date();
  const два = (число) => String(число).padStart(2, '0');
  return `${сейчас.getFullYear()}-${два(сейчас.getMonth() + 1)}-${два(сейчас.getDate())}`;
}
