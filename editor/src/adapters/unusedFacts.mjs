// Факты о лишних файлах статьи и их уборка в корзину редактора.
//
// Правило «что считать лишним» здесь не пишется — оно в `core/unusedFiles.mjs`; здесь только чтение
// диска и перенос в корзину (`trashStore.mjs`).
//
// **Счёт ссылок общий по всей статье, а уборка — по папке каждой версии.** Тексты читаются у ВСЕХ
// языковых версий сразу: файл, нужный испанской версии, не становится лишним оттого, что русская о
// нём молчит. Убирается при этом только то, что лежит в папке названной версии, — чужую папку
// публикация одного языка не трогает.
//
// **На файл ссылается и ЧУЖАЯ статья.** Картинку соседней папки берут записью `@site/...`, обычным
// относительным путём и свойством карточки товара; считай программа ссылки только по своей статье —
// она унесла бы в корзину файл, на котором стоит чужая страница, и уронила бы сборку сайта. Поэтому
// у кандидатов, не названных своей статьёй, имя ищется ещё раз — по текстам ВСЕХ статей всех корней.
// Проход этот делается ТОЛЬКО когда кандидаты вообще есть: у обычной статьи их нет, и лишнего
// чтения диска не случается (замечание контролёра 2026-09-20).
//
// **Сбой чтения означает «не убирать ничего».** Не удалось прочитать текст локали, узнать про её
// файл или обойти статьи сайта — доказать, что на файл никто не ссылается, нечем, и правило не
// зовётся вовсе: молчаливая потеря картинки человека хуже оставленного лишнего файла. «Файла нет»
// (`ENOENT`) — это ответ, а не сбой, и только он разрешает идти дальше без этого языка.

import fs from 'node:fs';
import path from 'node:path';

import {readField, splitArticle} from '../core/articleFile.mjs';
import {путиДругихВерсий} from '../core/articles.mjs';
import {ВИД_ЛИШНИХ, лишниеФайлы} from '../core/unusedFiles.mjs';
import {фактыВерсии} from './releaseFacts.mjs';
import {путиСтатей} from './library.mjs';
import {вКорзину, составАрхива} from './trashStore.mjs';

/**
 * Лишние файлы по каждой названной версии.
 *
 * `версии` — пути языковых версий ОДНОЙ статьи (отмеченные в окне). Возвращает карту «путь версии →
 * пути её лишних файлов» либо `null` — фактов собрать не удалось.
 *
 * Вторая статья в папке версии отменяет уборку в ней: чьи там файлы, по путям не видно, и ровно это
 * положение состав выпуска давно называет разрывом `папкаНеОдна` (`core/release.mjs`).
 */
export function лишниеВерсий({repo, settings, версии}) {
  const свои = Array.isArray(версии) ? версии.filter((путь) => typeof путь === 'string' && путь !== '') : [];
  const карта = new Map();
  if (свои.length === 0) return карта;

  const тексты = текстыСтатьи(repo, свои[0], settings);
  if (тексты === null) return null;

  const имяОбложки = settings['картинки']['имяОбложки'];
  for (const путь of свои) {
    const факты = фактыВерсии(repo, путь, settings);
    if (факты === null) return null;
    if (Number(факты.статейВПапке ?? 1) > 1) {
      карта.set(путь, []);
      continue;
    }
    карта.set(путь, лишниеФайлы({пути: факты.файлыПапки, тексты, имяОбложки}));
  }

  // Своя статья о них молчит — но молчит ли весь сайт? Второй проход идёт только при кандидатах.
  if ([...карта.values()].every((файлы) => файлы.length === 0)) return карта;

  const весьСайт = текстыСтатейСайта(repo, settings);
  if (весьСайт === null) return null;
  for (const [путь, файлы] of карта) {
    карта.set(путь, лишниеФайлы({пути: файлы, тексты: весьСайт, имяОбложки}));
  }

  return карта;
}

/**
 * Тексты ВСЕХ статей всех корней контента. Корни берутся целиком, включая те, что вне сайта:
 * ссылка из песочницы файл тоже удерживает, а сомнение толкуется в пользу сохранения.
 *
 * `null` — обойти папки или прочитать файл не удалось. Пустой ответ при сбое означал бы «никто ни
 * на что не ссылается», то есть разрешал бы унести в корзину всю папку статьи.
 */
function текстыСтатейСайта(repo, settings) {
  try {
    return путиСтатей(repo, settings).map((путь) => fs.readFileSync(path.join(repo, путь), 'utf8'));
  } catch (ошибка) {
    console.error(ошибка);
    return null;
  }
}

/**
 * Тексты ВСЕХ языковых версий статьи, какие есть на диске. Языки берутся тем же правилом, каким
 * реестр сшивает версии (`путиДругихВерсий`), — второго правила связи языков в программе нет.
 *
 * `null` — про какой-то язык узнать не удалось: ни его файл, ни его текст.
 *
 * **«Файла нет» и «спросить не удалось» — разные ответы, и путать их нельзя.** Первый доказан
 * системой (`ENOENT`) и законен: такого перевода у человека просто ещё нет. Второй — отказ диска в
 * доступе, занятый файл, обрыв сети на сетевом диске; прими его программа за «файла нет», и
 * картинка, нужная ТОЛЬКО этому языку, ушла бы в корзину и с сайта (блокер контролёра 2026-09-20).
 */
function текстыСтатьи(repo, rel, settings) {
  const тексты = [];

  for (const путь of [rel, ...путиДругихВерсий(rel, settings['контент'])]) {
    const полный = path.join(repo, путь);
    let есть;
    try {
      есть = fs.statSync(полный).isFile();
    } catch (ошибка) {
      // `ENOTDIR` — тот же ответ: на месте папки языка лежит файл, значит версии там нет.
      if (ошибка?.code === 'ENOENT' || ошибка?.code === 'ENOTDIR') continue;
      console.error(ошибка);
      return null;
    }
    if (!есть) continue;
    try {
      тексты.push(fs.readFileSync(полный, 'utf8'));
    } catch {
      return null;
    }
  }

  return тексты;
}

/**
 * Убрать лишние файлы отмеченных версий в корзину редактора.
 *
 * Возвращает `{убрано, корзина}` либо `{ошибка}`. Убирать нечего — пустой перечень и `null`.
 * Стирания насовсем здесь нет: запись корзины человек возвращает целиком одним нажатием, а исчезает
 * она только по его прямому слову (решение владельца 2026-09-18).
 *
 * **Состав архива собирается общим правилом корзины** (`составАрхива`): им же проверяется каждый
 * путь — относительный, без `..`, внутри репозитория, без подмены ссылкой. Свой перечень путей,
 * минующий эту проверку, однажды унёс бы файл за пределами материалов.
 */
export function убратьЛишнее({repo, editorDir, settings, версии}) {
  const карта = лишниеВерсий({repo, settings, версии});
  // Фактов нет — не убирается ничего, и это не отказ: публикация идёт своим ходом.
  if (карта === null) return {убрано: [], корзина: null};

  const файлы = [...карта.values()].flat();
  if (файлы.length === 0) return {убрано: [], корзина: null};

  try {
    const состав = составАрхива({repo, settings, решение: {файлы, папки: [], пути: []}});
    const запись = вКорзину({
      repo,
      editorDir,
      settings,
      состав,
      // Языков и папок у такой записи нет: она не статья, а её файлы. Имя записи человек читает
      // строкой настройки, а не путём — корзина показывает `название`, если оно есть. `вид`
      // отличает её от записи удалённой статьи: возврат обязан сказать про файлы, а не про статью.
      статья: {
        вид: ВИД_ЛИШНИХ,
        название: имяЗаписи(settings, названиеСтатьи(repo, версии[0])),
        пути: файлы,
        языки: [],
        папки: [],
      },
    });
    return {убрано: файлы, корзина: запись.id};
  } catch (error) {
    console.error(error);
    return {ошибка: 'лишниеНеУбраны'};
  }
}

/** Имя записи корзины — из настройки, а не из кода: слова человеку в коде не живут (SPEC 4.4). */
const имяЗаписи = (settings, название) => String(settings['выпуск']['лишниеВКорзине'])
  .replace('{статья}', String(название ?? '').trim());

/** Название статьи из её шапки — им запись корзины называется человеку. Не прочиталось — пусто. */
function названиеСтатьи(repo, rel) {
  try {
    const {frontmatterRaw} = splitArticle(fs.readFileSync(path.join(repo, rel), 'utf8'));
    return String(readField(frontmatterRaw, 'title') ?? '');
  } catch {
    return '';
  }
}
