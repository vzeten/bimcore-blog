// Приём новой картинки в статью в два шага: сначала файл едет в служебный карантин, и только
// потом, отдельным запросом, ложится рядом со статьёй под свободным именем.
//
// Зачем два шага. Операция связывает две вещи — файл на диске и ссылку в тексте статьи, — а текст
// правит окно. Клади программа файл сразу рядом со статьёй, любой обрыв между записью и правкой
// текста (человек ушёл в другую статью, открыл просмотр версии, закрыл вкладку) оставлял бы
// в папке статьи картинку, на которую никто не ссылается: она уехала бы в публикацию как чужой
// файл. В карантине же брошенный файл никому не мешает — папка служебная, в сборку и в коммит
// не попадает — и убирается по возрасту.
//
// Обратный порядок «сначала ссылка, потом файл» отвергнут: отказ записи оставил бы в статье
// битую ссылку, а от неё падает сборка всего сайта (SPEC 2.3).

import fs from 'node:fs';
import path from 'node:path';

import {badFields} from './httpBody.mjs';
import {занятьИмя, записатьНовый, папкаСтатьи, цельВнутриСтатьи} from './assetGuards.mjs';
import {годныйПуть} from './releaseFacts.mjs';
import {типКартинки} from '../core/imageType.mjs';
import {файлИспользуется} from '../core/imageFormat.mjs';
import {номерКартинки} from '../core/imageName.mjs';

/** Имя карантинного файла целиком задаёт сервер: latin, цифры, дефис и расширение. */
const ЖЕТОН = /^[a-z0-9-]+\.[a-z0-9]+$/;

/**
 * Какой статье принадлежит подготовленный файл. Жетон сам по себе разрешением не является:
 * без этой связи знающий жетон уложил бы чужую подготовленную картинку в другую статью.
 * Живёт в памяти сервера: после перезапуска подготовка просто повторяется человеком заново,
 * а карантин убирается по возрасту.
 */
const подготовленные = new Map();

/** Обрабатывает POST `/api/asset/prepare`, `/place` и `/withdraw`. true, если запрос её. */
export async function assetIntakeRoute({req, res, url, repo, settings, тело, insideRepo, send}) {
  const ручки = ['/api/asset/prepare', '/api/asset/place', '/api/asset/withdraw'];
  if (req.method !== 'POST' || !ручки.includes(url.pathname)) return false;

  const payload = await тело(req);
  const ошибки = settings['ошибкиСервера'];
  const поля = {
    '/api/asset/prepare': ['article', 'base64'],
    '/api/asset/place': ['article', 'жетон'],
    '/api/asset/withdraw': ['article', 'src'],
  }[url.pathname];
  const плохо = badFields(payload, поля, ошибки);
  if (плохо) {
    send(res, плохо.status, {error: плохо.error});
    return true;
  }

  // Путь обязан быть путём статьи сайта, а не любым существующим файлом: иначе `package.json`
  // сошёл бы за статью и картинка легла бы в корень репозитория. Правило общее с выпуском.
  if (!годныйПуть(payload.article, settings)) {
    send(res, 400, {error: ошибки['неПутьСтатьи']});
    return true;
  }

  // Папка статьи берётся тем же заслоном, что у замены: ссылка-папка в пути увела бы запись
  // за пределы репозитория, оставаясь текстуально внутри.
  const dir = папкаСтатьи(repo, payload.article, insideRepo);
  if (dir === null) {
    send(res, 404, {error: ошибки['нетСтатьи']});
    return true;
  }

  if (url.pathname === '/api/asset/prepare') подготовить({payload, repo, settings, send, res});
  else if (url.pathname === '/api/asset/place') уложить({payload, repo, dir, settings, send, res});
  else вернуть({payload, repo, dir, settings, send, res});

  return true;
}

/** Шаг первый: проверить формат по байтам и положить файл в карантин под своим жетоном. */
function подготовить({payload, repo, settings, send, res}) {
  const ошибки = settings['ошибкиСервера'];
  const bytes = Buffer.from(payload.base64, 'base64');

  // Формат решают байты, а не тип от браузера и не имя файла: браузер берёт тип из того же
  // имени, а картинка чужого формата роняет сборку сайта уже после публикации.
  const ext = типКартинки(bytes);
  if (ext === null) {
    send(res, 400, {error: ошибки['неверныйТипКартинки']});
    return;
  }

  убратьБрошенные(repo, settings);

  const жетон = `${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 10)}.${ext}`;
  if (!записатьНовый(repo, path.join(карантин(repo), жетон), bytes)) {
    send(res, 500, {error: ошибки['внутренняя']});
    return;
  }

  подготовленные.set(жетон, payload.article);
  send(res, 200, {жетон, ...вес(bytes, settings)});
}

/**
 * Шаг второй: перенести подготовленный файл в папку статьи под первым свободным именем.
 * Имя даёт программа: имя человеческого файла бывает кириллическим или с пробелами, а такое
 * имя роняет сборку сайта (SPEC 2.2).
 */
function уложить({payload, repo, dir, settings, send, res}) {
  const ошибки = settings['ошибкиСервера'];
  const источник = path.join(карантин(repo), payload.жетон);
  // Жетон годится только для той статьи, для которой готовился, и только один раз: иначе им
  // можно было бы утащить чужую подготовленную картинку в другую статью.
  const чей = подготовленные.get(payload.жетон);
  if (чей !== payload.article || !ЖЕТОН.test(payload.жетон)
    || !fs.existsSync(источник) || !fs.lstatSync(источник).isFile()) {
    send(res, 404, {error: ошибки['картинкаНеГотова']});
    return;
  }

  // Формат проверяется второй раз, уже перед укладкой: между шагами файл мог смениться,
  // а имя на диске получает расширение по содержимому, а не по жетону.
  const bytes = fs.readFileSync(источник);
  const ext = типКартинки(bytes);
  if (ext === null) {
    send(res, 400, {error: ошибки['неверныйТипКартинки']});
    return;
  }

  const имя = занятьИмя({repo, dir, bytes, settings, расширение: ext});
  if (имя === null) {
    send(res, 400, {error: ошибки['имяНеПодобрано']});
    return;
  }

  // Карантинный файл убирается только после того, как он лёг рядом со статьёй: обратный
  // порядок при сбое оставил бы человека вообще без картинки. Неудача самой уборки ошибкой
  // не считается — картинка уже на месте, а брошенный карантинный файл уйдёт по возрасту.
  подготовленные.delete(payload.жетон);
  try {
    fs.rmSync(источник, {force: true});
  } catch {
    // Файл занят другой программой: это не беда человека и не повод объявлять вставку неудачной.
  }

  send(res, 200, {src: `./${имя}`, ...вес(bytes, settings)});
}

/**
 * Отмена уже уложенной картинки: файл уезжает обратно в карантин. Нужна ровно одному случаю —
 * пока картинка ехала, окно сменилось (человек ушёл в другую статью или открыл старую версию),
 * и ссылку на неё дописывать некуда. Без отмены такая картинка осталась бы в папке статьи
 * бесхозной и уехала бы в публикацию.
 *
 * Ничего не удаляет: файл переносится в служебную папку, откуда его убирает уборка по возрасту.
 * Забрать можно только картинку, названную самой программой по шаблону, и только пока в файле
 * статьи на неё нет ни одной ссылки: сомнение толкуется в пользу сохранения.
 */
function вернуть({payload, repo, dir, settings, send, res}) {
  const ошибки = settings['ошибкиСервера'];
  const место = цельВнутриСтатьи(dir, payload.src);
  if (место === null || !место.есть) {
    send(res, 404, {error: ошибки['нетКартинки']});
    return;
  }

  const имя = path.basename(место.target);
  if (номерКартинки(имя, settings['картинки']['шаблонИмени']) === null) {
    send(res, 400, {error: ошибки['неСвояКартинка']});
    return;
  }

  if (файлИспользуется(fs.readFileSync(path.join(repo, payload.article), 'utf8'), имя)) {
    send(res, 409, {error: ошибки['картинкаУжеВСтатье']});
    return;
  }

  fs.renameSync(место.target, path.join(карантин(repo), `${Date.now().toString(36)}-${имя}`));
  send(res, 200, {withdrawn: true});
}

/** Служебная папка карантина. Она же служит времянкой атомарной записи и в сборку не попадает. */
function карантин(repo) {
  const папка = path.join(repo, 'editor', '.tmp');
  fs.mkdirSync(папка, {recursive: true});
  return папка;
}

/**
 * Убрать из карантина файлы старше срока из настроек. Брошенными они становятся сами собой:
 * человек выбрал картинку и передумал, ушёл в другую статью или закрыл программу.
 * Уборка молчаливая: это служебные файлы программы, работы человека среди них нет.
 */
function убратьБрошенные(repo, settings) {
  const предел = settings['картинки']['карантинМинут'] * 60 * 1000;
  const папка = карантин(repo);

  for (const имя of fs.readdirSync(папка)) {
    const файл = path.join(папка, имя);
    try {
      if (Date.now() - fs.statSync(файл).mtimeMs > предел) fs.rmSync(файл, {force: true});
    } catch {
      // Файл уже унесла другая уборка или он занят: это не беда человека и не повод падать.
    }
  }

  // Вместе с файлами уходят и записи о них: иначе память сервера росла бы от каждого выбора
  // картинки, который человек начал и бросил.
  for (const жетон of подготовленные.keys()) {
    if (!fs.existsSync(path.join(папка, жетон))) подготовленные.delete(жетон);
  }
}

/** Вес файла для показа: тяжёлая картинка — предупреждение, а не отказ. Решает человек. */
function вес(bytes, settings) {
  return {
    тяжёлая: bytes.length > settings['картинки']['максимумКилобайт'] * 1024,
    килобайт: Math.round(bytes.length / 1024),
  };
}
