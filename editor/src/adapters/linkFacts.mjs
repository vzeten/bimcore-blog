// Ссылки на снимаемую статью в опубликованной ветке: кто на неё ссылается и каким станет его текст.
// Правило уборки — в `core/siteRoutes.mjs`; здесь только вопросы к git.
//
// **Спрашивается сервер, а не диск.** Правка ссылок уезжает на сайт вместе со снятием, и строится
// она из ТОЙ версии соседа, что лежит в закреплённой основе: неопубликованная работа человека над
// соседом в снятие не попадает ни байтом.
//
// **Искать одной командой, читать только найденное.** `git grep` по основе отбирает файлы, где
// вообще встречается последняя часть адреса статьи; целиком читаются только они. Отбор грубый
// намеренно: относительная ссылка `../proba/` полного адреса не содержит, а часть имени — содержит.

import fs from 'node:fs';
import path from 'node:path';

import {articlePlace} from '../core/frontmatterRules.mjs';
import {файлСтатьи} from '../core/articles.mjs';
import {адресВерсии, безСсылок} from '../core/siteRoutes.mjs';
import {адресСайта} from '../core/siteConfig.mjs';
import {showFile} from './gitFile.mjs';

/**
 * Что сайт знает о своих адресах: корни контента, языки, префикс блога и хост из конфига сайта.
 * Хоста нет (конфиг не прочитан) — ссылки полным адресом не узнаются и уходят в непонятные.
 */
export function сведенияСайта(repo, settings) {
  const roots = settings['контент'];
  let хост = null;
  try {
    const адрес = адресСайта(fs.readFileSync(path.join(repo, 'docusaurus.config.js'), 'utf8'));
    хост = адрес ? new URL(адрес).host : null;
  } catch {
    хост = null;
  }

  return {
    roots,
    корни: roots.filter((root) => root['наСайте'] === true).map((root) => root['папка']),
    локали: [...new Set(roots.filter((root) => root['наСайте'] === true).map((root) => root['локаль']))],
    обязательный: settings['обязательныйЯзык'],
    префиксБлога: settings['адресаСайта']['префиксБлога'],
    хост,
  };
}

/** Документ, откуда ссылаются: его путь, язык и собственный адрес — от него считаются относительные. */
export function откудаСсылка(путь, текст, сайт) {
  return {
    путь,
    локаль: articlePlace(путь, сайт.roots).locale,
    адрес: адресВерсии(путь, текст, сайт),
    хост: сайт.хост,
    обязательный: сайт.обязательный,
    локали: сайт.локали,
  };
}

/** Части адресов, по которым грубо отбираются кандидаты: последний кусок адреса и папка файла. */
export function образцыЦелей(цели) {
  const части = new Set();
  for (const адрес of цели.адреса) {
    const хвост = адрес.split('/').filter(Boolean).pop();
    if (хвост) части.add(хвост);
  }
  for (const файл of цели.файлы) {
    const куски = файл.split('/');
    const имя = /^index\.mdx?$/.test(куски.at(-1)) ? куски.at(-2) : куски.at(-1)?.replace(/\.mdx?$/, '');
    if (имя) части.add(имя);
  }
  return [...части];
}

/**
 * Правки ссылок в опубликованной ветке. `цели` — `{адреса, файлы}` снимаемой статьи, `свои` — пути,
 * которые уходят с сайта вместе с ней (их не правят). Возвращает `{соседи, разрывы, статей}` либо
 * `null` — спросить git не удалось, и это отказ, а не «ссылок нет».
 *
 * `соседи` — `{путь, локаль, текст}` с новым текстом из основы; `разрывы` — `ссылкаНеРазобрана` у
 * файла, где после уборки ещё осталось похожее на снятый адрес; `статей` — сколько статей получат
 * правку (языковые версии одной статьи считаются одной статьёй).
 */
export async function ссылкиВОснове({git, repo, settings, основа, цели, свои}) {
  const сайт = сведенияСайта(repo, settings);
  const части = образцыЦелей(цели);
  if (части.length === 0 || сайт.корни.length === 0) return {соседи: [], разрывы: [], статей: 0};

  let вывод;
  try {
    вывод = await git.raw([
      '-c', 'core.quotepath=false', 'grep', '-I', '-l', '-z', '--fixed-strings',
      ...части.flatMap((часть) => ['-e', часть]), основа, '--', ...сайт.корни,
    ]);
  } catch {
    return null;
  }

  const кандидаты = вывод.split('\0')
    .filter(Boolean)
    .map((строка) => (строка.startsWith(`${основа}:`) ? строка.slice(основа.length + 1) : строка))
    .filter((путь) => файлСтатьи(путь) && !свои.has(путь));

  const соседи = [];
  const разрывы = [];
  for (const путь of кандидаты) {
    const текст = await showFile(git, основа, путь);
    if (текст === null) return null;

    const итог = безСсылок(текст, цели, откудаСсылка(путь, текст, сайт));
    if (итог.непонятные.length > 0) разрывы.push({причина: 'ссылкаНеРазобрана', путь, локаль: articlePlace(путь, сайт.roots).locale});
    else if (итог.заменено > 0) соседи.push({путь, локаль: articlePlace(путь, сайт.roots).locale, текст: итог.текст});
  }

  const ключи = ключиСтатей(соседи.map((сосед) => сосед.путь), сайт.roots);
  return {соседи, разрывы, статей: ключи.length, ключи};
}

/**
 * Разные статьи среди путей — их ключи: версии сшиваются по роду и пути внутри раздела (SPEC 3.4).
 * По ключам окно считает статьи сразу по нескольким отмеченным версиям, не считая одну дважды.
 */
export function ключиСтатей(пути, roots) {
  return [...new Set(пути.map((путь) => {
    const место = articlePlace(путь, roots);
    return `${место.kind}|${место.inside}`;
  }))];
}

/** Сколько разных статей среди путей. */
export const числоСтатей = (пути, roots) => ключиСтатей(пути, roots).length;
