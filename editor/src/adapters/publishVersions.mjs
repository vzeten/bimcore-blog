// Отмеченные версии одной публикации (этап 3, решение владельца 2026-09-18, п.2): какие языки человек
// отметил галочками в окне и чем доказывается, что каждая из них та же, что прошла проверки.
//
// Один модуль на показ состава (`releaseRoute.mjs`), запись (`publishRoute.mjs`) и серверную запись
// полей неоткрытых версий (`publishVersionsRoute.mjs`): разойдись они в перечне отмеченных, человеку
// показали бы одни языки, а зафиксировали другие.

import fs from 'node:fs';
import path from 'node:path';

import {годныйПуть} from './releaseFacts.mjs';
import {путиВерсийНаСайте} from './retireFacts.mjs';
import {сверитьПодготовку} from './prepareStamp.mjs';
import {датаРазошлась} from './publishDateFacts.mjs';

/**
 * Отмеченные версии из тела запроса. Поля нет — одна открытая `rel`, как до этапа 3.
 *
 * Каждая обязана быть файлом статьи на месте, внутри репозитория и версией ЭТОЙ статьи (тем же
 * правилом, каким реестр сшивает языки): иначе галочкой можно было бы увезти на сайт чужой файл.
 * Возвращает `{версии}` либо `{ошибка}` — текст отказа.
 */
export function отмеченныеВерсии({payload, rel, repo, settings, insideRepo}) {
  const сырые = payload['версии'] === undefined ? [rel] : payload['версии'];
  const нельзя = {ошибка: settings['ошибкиСервера']['неПутьСтатьи']};
  if (!Array.isArray(сырые) || сырые.length === 0 || new Set(сырые).size !== сырые.length) return нельзя;

  const своиПути = new Set([rel, ...путиВерсийНаСайте(rel, settings).map((версия) => версия.путь)]);
  for (const путь of сырые) {
    if (typeof путь !== 'string' || !своиПути.has(путь) || !годныйПуть(путь, settings)) return нельзя;
    const полный = path.join(repo, путь);
    if (!insideRepo(полный) || !файлЕсть(полный)) return нельзя;
  }
  return {версии: сырые};
}

/**
 * Отпечаток подготовки, которого ждут для версии. У открытой — прежнее поле `отпечатокПодготовки`,
 * у остальных отмеченных — `подготовки` по пути. Нет — `undefined`, и заслон снимка откажет.
 */
export const ждатьПодготовки = (payload, rel) => (путь) => {
  if (путь === rel && payload['отпечатокПодготовки'] !== undefined) return payload['отпечатокПодготовки'];
  const свои = payload['подготовки'];
  return свои !== null && typeof свои === 'object' ? свои[путь] : undefined;
};

/**
 * Заслон снимка подготовки по КАЖДОЙ отмеченной версии (`сверитьПодготовку`). Возвращает
 * `{код, блокеры, срезы}`: `код === null` — все версии те же, что прошли проверки; `срезы` — срез
 * каждой версии по её пути.
 */
export function сверитьВерсии({repo, settings, версии, ждали}) {
  const срезы = new Map();
  for (const путь of версии) {
    const снимок = сверитьПодготовку({repo, rel: путь, settings, ждали: ждали(путь)});
    if (снимок.код !== null) return {код: снимок.код, блокеры: снимок.блокеры, срезы};
    срезы.set(путь, снимок.подготовка.срез);
  }
  return {код: null, блокеры: [], срезы};
}

/** Дата записи блога у каждой отмеченной версии — по той же основе и байтам её снимка. */
export async function датыВерсий({git, repo, settings, основа, срезы}) {
  for (const [путь, срез] of срезы) {
    const код = await датаРазошлась({git, repo, rel: путь, settings, основа, срез});
    if (код) return код;
  }
  return null;
}

/** Байты каждой отмеченной версии в плане те же, что видели проверки. */
export function тежеБайтыВерсий(записи, срезы) {
  return [...срезы].every(([путь, срез]) => {
    const своя = записи.find((запись) => запись.путь === путь);
    return Buffer.isBuffer(своя?.байты) && Buffer.isBuffer(срез?.байты) && своя.байты.equals(срез.байты);
  });
}

function файлЕсть(полный) {
  try {
    return fs.statSync(полный).isFile();
  } catch {
    return false;
  }
}
