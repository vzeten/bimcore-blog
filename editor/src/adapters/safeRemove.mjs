// Уборка временной рабочей копии, которая не может утащить за собой чужой каталог.
//
// **Почему модуль вообще есть.** Удаление рабочей копии, внутри которой лежало соединение каталогов
// на настоящие зависимости репозитория, вычистило эти зависимости: удаляющий пошёл ПО ссылке
// внутрь. Обычные средства этого не обещают — ни `git worktree remove`, ни рекурсивное удаление не
// дают гарантии, что связь будет снята, а не пройдена насквозь.
//
// **Порядок обязателен и сокращению не подлежит:** сначала доказать, что путь вообще разрешён к
// удалению, затем обойти дерево, НИ РАЗУ не заходя по ссылкам, снять каждую найденную связь, не
// трогая того, на что она смотрит, убедиться, что связей не осталось, и только потом удалять. Любая
// неоднозначность — отказ: каталог остаётся на месте, и человек разбирается сам. Оставшийся мусор
// чинится за минуту, стёртое чужое дерево — нет.
//
// Частичный отказ возможен: если первая связь снята, а вторая не снялась, вернуть первую нельзя.
// Свойство, которое обязано держаться, другое — то, на что связи смотрели, цело, а никакого
// рекурсивного удаления не начиналось.

import fs from 'node:fs';
import path from 'node:path';

/**
 * Убрать временную рабочую копию. Возвращает `{убрана: true, снятые}` либо `{ошибка, подробность}`.
 *
 * `корни` — папки, внутри которых удаление вообще разрешено. Проверка стоит здесь, а не у
 * вызывающего: команда с чужим доводом не должна получить рекурсивное удаление по одному лишь
 * совпадению имени.
 *
 * `вУчётеGit` — известна ли копия git. Обычный путь — да, и тогда её присутствие в `worktree list`
 * обязательно: так каталог, который просто похож на рабочую копию, не будет удалён.
 */
export async function убратьКопию({git, путь, корни, вУчётеGit = true}) {
  const цель = канонический(путь);
  if (цель === null) return {ошибка: 'путьНеПонят', подробность: String(путь)};

  const разрешение = разрешено(цель, корни);
  if (разрешение.ошибка) return разрешение;

  if (!существует(цель)) {
    await прибратьУчёт(git);
    return {убрана: true, снятые: [], нечего: true};
  }

  if (ссылка(цель)) return {ошибка: 'копияСсылка', подробность: цель};

  if (вУчётеGit) {
    const учёт = await сверитьУчёт(git, цель);
    if (учёт.ошибка) return учёт;
  }

  const разрыв = разорватьВсе(цель);
  if (разрыв.ошибка) return разрыв;

  // Второй обход — не перестраховка. Между первым обходом и снятием связь могла появиться заново,
  // а рекурсивное удаление запускается только над доказанно чистым деревом.
  const остаток = найтиСсылки(цель);
  if (остаток.ошибка) return остаток;
  if (остаток.ссылки.length > 0) return {ошибка: 'ссылкаОсталась', подробность: остаток.ссылки[0]};

  return удалить({git, цель, вУчётеGit, снятые: разрыв.снятые});
}

/**
 * Все связи внутри дерева. Возвращает `{ссылки}` либо `{ошибка, подробность}`.
 *
 * Обход идёт только через `lstat`: он рассказывает о самой связи, а не о том, на что она смотрит.
 * Внутрь связи обход не спускается никогда — там чужое дерево. Любая беда чтения прекращает работу
 * целиком: «я не смог посмотреть, что там» и «там ничего опасного» — разные ответы, и подменять
 * первый вторым перед рекурсивным удалением нельзя.
 */
export function найтиСсылки(корень) {
  const ссылки = [];
  const очередь = [корень];

  while (очередь.length > 0) {
    const папка = очередь.pop();

    let записи = null;
    try {
      записи = fs.readdirSync(папка, {withFileTypes: true});
    } catch (ошибка) {
      return {ошибка: 'обходНеПолон', подробность: `${папка}: ${ошибка?.code ?? ошибка}`};
    }

    for (const запись of записи) {
      const полный = path.join(папка, запись.name);

      let сведения = null;
      try {
        сведения = fs.lstatSync(полный);
      } catch (ошибка) {
        return {ошибка: 'обходНеПолон', подробность: `${полный}: ${ошибка?.code ?? ошибка}`};
      }

      if (сведения.isSymbolicLink()) {
        ссылки.push(полный);
        continue;
      }

      if (сведения.isDirectory()) очередь.push(полный);
    }
  }

  return {ссылки};
}

/**
 * Снять одну связь, не тронув того, на что она смотрит. Возвращает `{цель}` либо `{ошибка}`.
 *
 * `rmdir` снимает соединение каталогов и ссылку на каталог, не заходя внутрь; `unlink` остаётся для
 * ссылки на файл. После попытки обязательно доказывается, что объекта больше нет: молчаливый успех
 * системного вызова доказательством не является.
 *
 * Сохранность цели проверяется только у связи, которая смотрела на существующее место: битой она
 * могла быть и до нас, и объявлять это своей бедой — врать.
 */
export function разорвать(связь) {
  let куда = null;
  try {
    куда = fs.readlinkSync(связь);
  } catch (ошибка) {
    return {ошибка: 'цельНеЧитается', подробность: `${связь}: ${ошибка?.code ?? ошибка}`};
  }

  const цель = path.resolve(path.dirname(связь), куда);
  const былаЦель = fs.existsSync(цель);

  for (const снять of [fs.rmdirSync, fs.unlinkSync]) {
    try {
      снять(связь);
      break;
    } catch {
      // Следующая попытка. Итог решает не она, а проверка ниже.
    }
  }

  if (существует(связь)) return {ошибка: 'ссылкаНеСнята', подробность: связь};
  if (былаЦель && !fs.existsSync(цель)) return {ошибка: 'цельПропала', подробность: цель};

  return {цель};
}

/** Снять все связи дерева. Возвращает `{снятые}` либо `{ошибка, подробность, снятые}`. */
function разорватьВсе(цель) {
  const найдено = найтиСсылки(цель);
  if (найдено.ошибка) return найдено;

  const снятые = [];
  for (const связь of найдено.ссылки) {
    const итог = разорвать(связь);
    if (итог.ошибка) return {...итог, снятые};
    снятые.push({связь, цель: итог.цель});
  }

  return {снятые};
}

/** Удаление уже чистого дерева: сперва средствами git, затем обычным удалением. */
async function удалить({git, цель, вУчётеGit, снятые}) {
  let снято = false;

  if (вУчётеGit) {
    try {
      await git.raw(['worktree', 'remove', '--force', цель]);
      снято = true;
    } catch (ошибка) {
      console.error(ошибка);
    }
  }

  if (существует(цель)) {
    try {
      fs.rmSync(цель, {recursive: true, force: true});
    } catch (ошибка) {
      return {ошибка: 'копияНеУбрана', подробность: String(ошибка?.message ?? ошибка), снятые};
    }
  }

  // Учёт git обязан сойтись: запись про папку, которой уже нет, упрёт следующую сборку того же
  // плана в несуществующую копию.
  const учёт = await прибратьУчёт(git);
  if (!учёт && !снято) return {ошибка: 'копияНеУбрана', подробность: цель, снятые};

  return {убрана: true, снятые};
}

/** Прибрать учёт рабочих копий. Возвращает `true`, если git ответил успехом. */
async function прибратьУчёт(git) {
  try {
    await git.raw(['worktree', 'prune']);
    return true;
  } catch (ошибка) {
    console.error(ошибка);
    return false;
  }
}

/**
 * Разрешён ли путь к удалению. Возвращает `{}` либо `{ошибка, подробность}`.
 *
 * Три отказа сразу: путь вне названных корней, путь, внутри которого идёт сама работа, и путь,
 * совпавший с корнем. Последнее отдельно: `корни` — это места для временных копий, а не сами
 * временные копии, и удаление такого места унесло бы вместе с ним всё остальное.
 */
function разрешено(цель, корни) {
  const свои = (корни ?? []).map((корень) => канонический(корень)).filter((корень) => корень !== null);
  if (свои.length === 0) return {ошибка: 'путьНеРазрешён', подробность: цель};

  if (!свои.some((корень) => внутри(цель, корень))) return {ошибка: 'путьНеРазрешён', подробность: цель};

  const здесь = канонический(process.cwd());
  if (здесь !== null && (здесь === цель || внутри(здесь, цель))) {
    return {ошибка: 'путьЗанят', подробность: цель};
  }

  return {};
}

/**
 * Есть ли копия в учёте git и не главная ли она. Возвращает `{}` либо `{ошибка, подробность}`.
 *
 * Главная рабочая копия идёт в перечне первой — это сам репозиторий, и удалять его нельзя ни при
 * каком доводе. Отсутствие пути в перечне тоже отказ: значит, удалять просят не рабочую копию, а
 * просто похожий каталог.
 */
async function сверитьУчёт(git, цель) {
  let вывод = '';
  try {
    вывод = await git.raw(['worktree', 'list', '--porcelain']);
  } catch (ошибка) {
    return {ошибка: 'учётНеПрочитан', подробность: String(ошибка?.message ?? ошибка)};
  }

  const копии = String(вывод)
    .split(/\r?\n/)
    .filter((строка) => строка.startsWith('worktree '))
    .map((строка) => канонический(строка.slice('worktree '.length).trim()))
    .filter((путь) => путь !== null);

  if (копии.length > 0 && тотЖе(копии[0], цель)) return {ошибка: 'этоГлавнаяКопия', подробность: цель};
  if (!копии.slice(1).some((путь) => тотЖе(путь, цель))) return {ошибка: 'копияНеУчтена', подробность: цель};

  return {};
}

/**
 * Канонический путь: настоящее место родителя плюс собственное имя. Возвращает `null`, если место
 * узнать нельзя.
 *
 * Разрешается именно родитель, а не сам путь: сам он может быть связью, и `realpath` по нему увёл
 * бы проверки на её цель — то есть ровно туда, куда ходить нельзя.
 */
function канонический(путь) {
  try {
    const полный = path.resolve(String(путь));
    const родитель = fs.realpathSync(path.dirname(полный));
    return path.join(родитель, path.basename(полный));
  } catch {
    return null;
  }
}

/** Один ли это путь. Windows не различает регистр имён, и сверка по буквам там соврала бы. */
const тотЖе = (один, другой) =>
  process.platform === 'win32' ? один.toLowerCase() === другой.toLowerCase() : один === другой;

/** Лежит ли путь внутри папки. Сама папка своим содержимым не считается. */
const внутри = (путь, папка) =>
  тотЖе(путь.slice(0, папка.length + 1), папка + path.sep) && путь.length > папка.length + 1;

/** Есть ли что-нибудь по этому пути. Про саму связь, а не про её цель. */
function существует(путь) {
  try {
    fs.lstatSync(путь);
    return true;
  } catch {
    return false;
  }
}

/** Связь ли это. Нет объекта — не связь. */
function ссылка(путь) {
  try {
    return fs.lstatSync(путь).isSymbolicLink();
  } catch {
    return false;
  }
}
