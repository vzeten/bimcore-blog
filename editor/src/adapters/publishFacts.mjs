// Факты, по которым правило строит каркас публикации: где живёт открытая версия, какие языки есть
// у её рода, лежит ли файл каждого языка в ЗАКРЕПЛЁННОЙ опубликованной ветке и каким текстом
// программа напишет недостающую заглушку.
//
// **Соседние файлы здесь не читаются ни разу.** Про соседа спрашивают только сайт (`git ls-tree` по
// закреплённому SHA), а его текст берут у того же генератора, что пишет заглушку при входе в новую
// локаль. Прочитай программа локального соседа — и появился бы соблазн отличить «нетронутую
// заглушку» от «начатого перевода», а именно на отказе от этого различия держится обещание, что
// недоделанный перевод не уезжает и не мешает.

import fs from 'node:fs';
import path from 'node:path';

import {articlePlace} from '../core/frontmatterRules.mjs';
import {путьВерсии} from '../core/articles.mjs';
import {readField, splitArticle} from '../core/articleFile.mjs';
import {названиеБезПометки} from '../core/stubText.mjs';
import {планЛокали} from '../core/localeVersion.mjs';
import {каркасПлана, публикацияВозможна} from '../core/publishPlan.mjs';
import {материализовать} from './planBytes.mjs';
import {фактыВерсии} from './releaseFacts.mjs';
import {ссылкиНаНедоступную} from './draftLinks.mjs';

/**
 * Факты для `каркасПлана`. `основа` — закреплённый SHA опубликованной ветки; подменять его `HEAD`
 * нельзя, поэтому сюда он приходит уже готовым и проверенным.
 *
 * Возвращает `{открытаяВерсия, наСайте, языки}` либо `{ошибка}`.
 */
export async function фактыКаркаса({git, repo, rel, settings, основа}) {
  const roots = settings['контент'];
  const место = articlePlace(rel, roots);
  if (место.locale === null) return {ошибка: 'неПутьСтатьи'};

  const открытаяВерсия = фактыВерсии(repo, rel, settings);
  if (открытаяВерсия === null) return {ошибка: 'нетФайла'};

  let исходный;
  try {
    исходный = fs.readFileSync(path.join(repo, rel), 'utf8');
  } catch {
    // Статью могли удалить или перенести, пока окно было открыто.
    return {ошибка: 'нетФайла'};
  }

  const шапка = splitArticle(исходный).frontmatterRaw;
  // Адрес, название, дата и авторы берутся у открытой версии: адрес общий у всех языков и менять
  // его нельзя (SPEC 2.5), дата держит языковые версии одной записи блога в одном дне ленты, а
  // автор принадлежит записи, а не набору полей.
  const общее = {
    slug: readField(шапка, 'slug'),
    название: названиеБезПометки(readField(шапка, 'title'), исходный, settings),
    дата: readField(шапка, 'date'),
    авторы: readField(шапка, 'authors'),
  };

  const свои = локалиРода(место.kind, roots);
  const пути = новыеПути({место, roots, локали: свои, rel});
  const наСайтеУже = await естьВОснове(git, основа, [...пути.values()]);
  // Каталог открытой версии на сайте спрашивается только тогда, когда сайт у статьи вообще есть:
  // в песочнице опубликованной ветки для неё не существует, и убирать оттуда нечего.
  const наСайтеВПапке = место.наСайте === true
    ? await путиОсновыВПапке(git, основа, path.posix.dirname(rel))
    : [];

  return {
    открытаяВерсия,
    наСайте: место.наСайте,
    наСайтеВПапке,
    языки: свои.map((локаль) => ({
      локаль,
      путь: пути.get(локаль) ?? '',
      опубликован: опубликованЛи(наСайтеУже, пути.get(локаль)),
      заглушка: локаль === место.locale ? '' : текстЗаглушки({rel, локаль, общее, settings}),
    })),
  };
}

/**
 * Языки рода, живущие на сайте. Берутся из настройки «контент», а не перечнем в коде: четвёртый
 * язык заработает без правки программы. Папки вне сайта в перечень не входят — заглушек там нет.
 */
export function локалиРода(род, roots) {
  return [...new Set(roots
    .filter((root) => root['род'] === род && root['наСайте'] === true)
    .map((root) => root['локаль']))];
}

/**
 * Что лежит в закреплённой ветке по названным путям. Возвращает `{файлы, чужие}` либо `null`;
 * `файлы` — карта «путь → SHA его содержимого», по ней же видно, изменится ли файл на сайте.
 *
 * `null` — спросить не удалось, и это НЕ «ничего не лежит»: приняв незнание за отсутствие, программа
 * переписала бы заглушкой живой перевод, который на сайте уже стоит.
 *
 * **Наличия объекта мало — сверяются тип и режим.** По тому же точному пути в дереве может лежать
 * каталог, ссылка, подмодуль или исполняемый файл. Все они существуют, но обычной страницей сайта
 * не являются: сочти программа их опубликованной версией — она промолчала бы там, где на сайте
 * лежит непонятно что, а сочти отсутствующими — положила бы заглушку поверх. Поэтому такой путь
 * уходит в `чужие`, и правило про него честно скажет «не знаю».
 *
 * Спрашивается одним вызовом по точным путям: `ls-tree` без путей отдал бы всё дерево, а по одному
 * пути за раз — столько же вызовов, сколько языков.
 */
export async function естьВОснове(git, основа, пути) {
  const свои = (пути ?? []).filter((путь) => typeof путь === 'string' && путь !== '');
  if (свои.length === 0) return {файлы: new Map(), чужие: new Set()};

  try {
    // `--literal-pathspecs` не украшение: без него git читает путь как ШАБЛОН. Имя с `[x]` внутри
    // тогда совпало бы с соседним файлом или не совпало бы с самим собой, и программа положила бы
    // заглушку поверх существующей на сайте страницы.
    const вывод = await git.raw([
      '-c', 'core.quotepath=false', '--literal-pathspecs', 'ls-tree', '-z', основа, '--', ...свои,
    ]);
    const файлы = new Map();
    const чужие = new Set();

    for (const строка of вывод.split('\0')) {
      if (строка === '') continue;
      // Формат строки задан git: «<режим> <тип> <sha>\t<путь>».
      const [сведения, путь] = разбитьПоТабуляции(строка);
      const [режим, тип, sha] = сведения.split(' ');

      if (режим === ОБЫЧНЫЙ_ФАЙЛ && тип === 'blob') файлы.set(путь, sha);
      else чужие.add(путь);
    }

    return {файлы, чужие};
  } catch {
    return null;
  }
}

/** Режим обычного файла. Значение задано git и настройкой не бывает. */
const ОБЫЧНЫЙ_ФАЙЛ = '100644';

/**
 * Обычные файлы каталога версии в закреплённой ветке — всё, что сайт про этот каталог знает.
 * Возвращает перечень путей либо `null` — «спросить не удалось».
 *
 * Ни одного соседнего языка сюда попасть не может: каталог версии лежит внутри корня её языка.
 * Что из этого перечня считать своим, решает правило, а не эта функция: здесь только чтение.
 *
 * Ссылки, подмодули и каталоги пропускаются. Убирать с сайта программа берётся лишь то, что сама
 * умеет туда положить, — обычный файл; про остальное она честно ничего не делает.
 */
export async function путиОсновыВПапке(git, основа, папка) {
  if (typeof папка !== 'string' || папка === '' || папка === '.') return [];

  try {
    const вывод = await git.raw([
      '-c', 'core.quotepath=false', '--literal-pathspecs', 'ls-tree', '-r', '-z', основа, '--', папка,
    ]);
    const пути = [];

    for (const строка of вывод.split('\0')) {
      if (строка === '') continue;
      // Формат строки задан git: «<режим> <тип> <sha>\t<путь>».
      const [сведения, путь] = разбитьПоТабуляции(строка);
      const [режим, тип] = сведения.split(' ');

      if (режим === ОБЫЧНЫЙ_ФАЙЛ && тип === 'blob') пути.push(путь);
    }

    return пути;
  } catch {
    return null;
  }
}

/** Опубликован ли путь: `true`, `false` либо `null` — «не знаю» (не спросилось или там не файл). */
function опубликованЛи(ответ, путь) {
  if (ответ === null || typeof путь !== 'string' || путь === '') return null;
  if (ответ.чужие.has(путь)) return null;

  return ответ.файлы.has(путь);
}

/** Путь отделён от сведений одной табуляцией; в самом пути табуляции быть не может. */
function разбитьПоТабуляции(строка) {
  const место = строка.indexOf('\t');
  return место < 0 ? [строка, ''] : [строка.slice(0, место), строка.slice(место + 1)];
}

/**
 * Пути версий по языкам. У открытого языка это его собственный путь, у остальных — путь, который
 * посчитал бы сам генератор заглушки: два разных счёта развели бы файл и его заглушку по разным
 * местам.
 */
function новыеПути({место, roots, локали, rel}) {
  const пути = new Map([[место.locale, rel]]);

  for (const локаль of локали) {
    if (пути.has(локаль)) continue;
    const корень = roots.find((root) => root['род'] === место.kind && root['локаль'] === локаль);
    if (корень) пути.set(локаль, путьВерсии(корень, место.inside));
  }

  return пути;
}

/**
 * Текст чистой заглушки для языка. Пишется тем же правилом, каким программа заводит заглушку при
 * входе в новую локаль: второй генератор разошёлся бы с первым при первой же правке настроек, и
 * программа перестала бы узнавать собственный текст.
 *
 * Не получилось — пустая строка, и правило откажется само. Выдумывать текст заглушки здесь нельзя.
 */
function текстЗаглушки({rel, локаль, общее, settings}) {
  const план = планЛокали({путь: rel, локаль, ...общее, settings});
  return план.ошибка ? '' : план.text;
}

/**
 * Какие записи плана изменят сайт: их содержимое расходится с закреплённой основой.
 *
 * Считается по СОДЕРЖИМОМУ, а не по рабочему дереву. Прежде программа спрашивала git, что в дереве
 * отличается от ветки, — но публикуется теперь не дерево, а план: у соседнего языка на диске лежит
 * начатый перевод, а уедет заглушка, и разница дерева сказала бы про них неправду.
 *
 * Объекты НЕ пишутся в хранилище: `hash-object` без `-w` только считает имя. До согласия человека
 * программа не меняет ни индекс, ни объектную базу.
 *
 * Не удалось спросить — `null`: «ничего не меняется» здесь было бы враньём.
 */
export async function изменённыеПротивОсновы({git, основа, записи, времянка}) {
  const вОснове = await естьВОснове(git, основа, записи.map((запись) => запись.путь));
  if (вОснове === null) return null;

  fs.mkdirSync(времянка, {recursive: true});

  try {
    const изменённые = [];

    for (const [номер, запись] of записи.entries()) {
      const было = вОснове.файлы.get(запись.путь) ?? null;

      // Запись без байтов — это уход пути с сайта. Изменением она считается ровно тогда, когда там
      // и вправду что-то лежит: иначе программа обещала бы человеку изменение, которого не будет.
      if (!Buffer.isBuffer(запись.байты)) {
        if (было !== null) изменённые.push(запись.путь);
        continue;
      }

      const временный = path.join(времянка, `сверка-${номер}`);
      fs.writeFileSync(временный, запись.байты);
      const стало = (await git.raw(['hash-object', '--path', запись.путь, '--', временный])).trim();

      if (было !== стало) изменённые.push(запись.путь);
    }

    return изменённые;
  } catch {
    return null;
  } finally {
    try {
      fs.rmSync(времянка, {recursive: true, force: true});
    } catch (ошибка) {
      console.error(ошибка);
    }
  }
}

/**
 * Готовый план публикации: факты → каркас → окончательные байты → правка ссылок, если версия
 * становится недоступной (`draftLinks.mjs`). Один вызов на всех, кто про план спрашивает: показ и
 * запись. Посчитай каждый по-своему — и человеку показали бы один состав, а зафиксировали другой.
 *
 * Возвращает `{записи, разрывы, отказ, языки, ссылкиВСтатьях, версияУходит}` либо `{ошибка}`;
 * `языки` — факты про сайт по каждому языку статьи.
 */
export async function готовыйПлан({git, repo, settings, rel, основа}) {
  const факты = await фактыКаркаса({git, repo, rel, settings, основа});
  if (факты.ошибка) return {ошибка: факты.ошибка};

  const каркас = каркасПлана(факты);
  // Публиковать нельзя — байты не читаются вовсе, но записи отдаются: человеку надо увидеть, о
  // каких файлах речь. Байтов у них нет, и зовущий их не получит: он сперва спрашивает
  // `публикацияВозможна`, и та скажет «нет».
  if (!публикацияВозможна(каркас)) {
    return {записи: каркас.записи, разрывы: каркас.разрывы, отказ: каркас.отказ, языки: факты.языки};
  }

  const {записи, отказ} = материализовать({repo, каркас});
  if (отказ !== null) return {записи, разрывы: каркас.разрывы, отказ, языки: факты.языки, ссылкиВСтатьях: 0, версияУходит: false};

  const снятие = await ссылкиНаНедоступную({git, repo, settings, rel, основа, записи});
  return {
    записи: снятие.записи, разрывы: [...каркас.разрывы, ...снятие.разрывы], отказ: снятие.отказ,
    языки: факты.языки, ссылкиВСтатьях: снятие.статей, версияУходит: снятие.уходит,
  };
}
