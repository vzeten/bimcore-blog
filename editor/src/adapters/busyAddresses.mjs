// Занят ли адрес другой статьёй: для уборки ссылок при смене адреса (`slug`) вместе со снятием или
// «Недоступно» (условие контролёра Codex 2026-09-19).
//
// Опубликованный собственный адрес статьи уходит с сайта всегда, и ссылки на него убираются. Новый,
// ещё не выпущенный адрес — только если он ничей: статья могла взять `slug`, который уже носит другая
// живая статья, и тогда ссылки на тот адрес ведут на неё, а не в никуда. Убрать их значило бы
// испортить чужую статью молча.

import fs from 'node:fs';
import path from 'node:path';

import {страницыСайта} from '../core/fastRules.mjs';
import {путиСтатей} from './library.mjs';
import {сведенияСайта} from './linkFacts.mjs';
import {файлыОсновы, шапкаТекста, шапкиОсновы} from './fastChecks.mjs';
import {файлСтатьи} from '../core/articles.mjs';

/**
 * Какие из `адреса` заняты статьями, кроме файлов `кроме` (версии самой статьи): в основе (страница
 * есть на сайте, живая или черновик) или на диске. `основа` — `null`: спрашивается только диск.
 * **Любой сбой чтения — заняты все** (условие контролёра Codex): файл диска, перечень основы,
 * шапки основы. Пустая шапка вместо непрочитанной сделала бы чужой адрес «свободным», и ссылки на
 * живую статью ушли бы.
 */
export async function занятыеАдреса({git, repo, settings, основа, кроме, адреса}) {
  const искомые = [...адреса].filter((адрес) => typeof адрес === 'string' && адрес !== '');
  if (искомые.length === 0) return new Set();
  const сайт = сведенияСайта(repo, settings);

  const все = new Set(искомые);
  const корни = settings['контент'].filter((root) => root['наСайте'] === true);
  let наДиске;
  try {
    наДиске = путиСтатей(repo, settings, корни).filter((путь) => !кроме.has(путь))
      .map((путь) => ({путь, ...шапкаТекста(fs.readFileSync(path.join(repo, путь), 'utf8'))}));
  } catch {
    return все;
  }
  const занятые = new Set(страницыСайта(наДиске, сайт).все);

  if (основа !== null) {
    const вОснове = await файлыОсновы(git, основа);
    if (вОснове === null) return все;
    const прочитанные = await шапкиОсновы(git, основа, сайт.корни, true);
    if (прочитанные === null) return все;
    const шапки = new Map([...вОснове].filter(файлСтатьи).map((путь) => [путь, {slug: '', черновик: false}]));
    for (const [путь, шапка] of прочитанные) шапки.set(путь, шапка);
    const чужие = [...шапки].filter(([путь]) => !кроме.has(путь)).map(([путь, шапка]) => ({путь, ...шапка}));
    for (const адрес of страницыСайта(чужие, сайт).все) занятые.add(адрес);
  }

  return new Set(искомые.filter((адрес) => занятые.has(адрес)));
}
