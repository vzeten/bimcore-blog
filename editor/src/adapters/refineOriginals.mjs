// Оригиналы доработки: файлы статьи, какими они были до того, как «Доработать» их изменила.
//
// Живут в служебном хранилище редактора при МАТЕРИАЛАХ (рядом с черновиками и историей): вне папки
// статьи, вне Git и вне сайта. Хранятся постоянно, без уборки по возрасту — это страховка, а не
// карантин (решение владельца 2026-09-16: оригинал сохраняется до обработки).
//
// Кладутся ДО первой записи в статью и сверяются по отпечатку: не легли — операции не будет. Рядом
// манифест операции: что было, что стало, отпечаток снимка после записи. По нему возврат (отдельная
// операция) докажет, что с тех пор в статье никто ничего не менял, и не затрёт чужую правку.

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

import {historyFolder} from '../core/history.mjs';
import {хранилищеРедактора} from './draftStore.mjs';

/** Имя манифеста операции. Техническое имя служебного файла, а не слово человеку. */
const МАНИФЕСТ = 'manifest.json';
/** Подпапка, куда ложатся исходные байты файлов статьи. Своя, чтобы имя манифеста не спорило с картинкой. */
const ФАЙЛЫ = 'files';
/** Имя, под которым ложится текст статьи до операции. */
const ТЕКСТ = 'article.mdx';

const отпечатокБайтов = (байты) => crypto.createHash('sha1').update(байты).digest('hex');

/** Папка одной операции: хранилище → папка оригиналов → статья → отметка времени операции. */
export function папкаОперации({repo, settings, rel, когда}) {
  return path.join(
    хранилищеРедактора(repo),
    settings['хранение']['папкаОригиналов'],
    historyFolder(rel),
    String(когда).replace(/[:.]/g, '-'),
  );
}

/**
 * Сохранить оригиналы перед записью. Синхронно: зовётся после последней сверки снимка, где до
 * истории и файлов не должно быть ни одного `await`.
 *
 * Сохраняется текст статьи до операции и каждый файл, чьи прежние байты операция заменит или
 * удалит. Новый файл без прежних байтов оригинала не имеет — ему нечего сохранять.
 *
 * Возвращает путь папки операции либо бросает: сохранить не вышло — записи быть не должно.
 */
export function сохранитьОригиналы({repo, settings, rel, снимок, изменения, когда}) {
  const папка = папкаОперации({repo, settings, rel, когда});
  const было = [];

  const положить = (куда, байты) => {
    fs.mkdirSync(path.dirname(куда), {recursive: true});
    fs.writeFileSync(куда, байты);
    // Читается заново и сверяется: запись без ошибки ещё не доказывает, что на диске те же байты.
    if (отпечатокБайтов(fs.readFileSync(куда)) !== отпечатокБайтов(байты)) {
      throw new Error(`оригинал не совпал после записи: ${куда}`);
    }
  };

  положить(path.join(папка, ТЕКСТ), снимок.байтыТекста);

  for (const {имя} of изменения.файлы) {
    const прежние = снимок.файлы.get(имя);
    if (!(прежние instanceof Uint8Array)) continue;
    положить(path.join(папка, ФАЙЛЫ, ...имя.split('/')), прежние);
    было.push({имя, отпечаток: отпечатокБайтов(прежние)});
  }

  const манифест = {
    статья: rel,
    когда,
    текстДо: отпечатокБайтов(снимок.байтыТекста),
    было,
    стало: изменения.файлы.map(({имя, байты}) => ({
      имя,
      отпечаток: байты instanceof Uint8Array ? отпечатокБайтов(байты) : null,
    })),
    отпечатокПосле: null,
  };
  положить(path.join(папка, МАНИФЕСТ), Buffer.from(`${JSON.stringify(манифест, null, 2)}\n`, 'utf8'));

  return папка;
}

/**
 * Дописать в манифест отпечаток снимка статьи ПОСЛЕ записи. Только по нему возврат докажет, что
 * с тех пор никто не менял ни текст, ни картинки папки: отпечатка одного текста для этого мало.
 */
export function записатьОтпечатокПосле({папка, отпечаток}) {
  const путь = path.join(папка, МАНИФЕСТ);
  const манифест = JSON.parse(fs.readFileSync(путь, 'utf8'));
  манифест.отпечатокПосле = отпечаток;
  fs.writeFileSync(путь, `${JSON.stringify(манифест, null, 2)}\n`, 'utf8');
}
