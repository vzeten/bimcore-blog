// Ручки панели экземпляров: показать живое состояние, поднять и остановить опознанный экземпляр.
// Решения принимает ядро (`instanceControl.mjs`), внешний мир трогают соседние адаптеры
// (`instanceProbe.mjs`, `instanceRun.mjs`), здесь — только порядок и слова из настроек
// (SPEC 4.3, 6.10).

import {ПАПКА_ВЛАДЕЛЬЦА} from '../core/materialRoot.mjs';
import {ПАПКА_ПРИНЯТОГО, ПОРТ_ВЛАДЕЛЬЦА} from '../core/runtimeIdentity.mjs';
import {
  ВИД_РАБОЧИЙ, ВСЁ_ЕЩЁ_ОТВЕЧАЕТ, НЕ_НАБЛЮДАЕТСЯ, НЕ_ПОДНЯЛСЯ, ОСТАНОВЛЕН, РАБОТАЕТ,
  решениеЗапуска, решениеОстановки, строки,
} from '../core/instanceControl.mjs';
import {дождаться, запомнить, наш, опрос, опросПорта, память, тихо} from './instanceProbe.mjs';
import {владелецПорта, завершить, поднять, словаЗапуска} from './instanceRun.mjs';

/** Сколько раз и с какой паузой ждать. Величины алгоритма: окно собирается на лету, и первый
 *  ответ приходит через секунды, а исчезновение процесса видно почти сразу. */
const ЖДАТЬ_ПОДЪЁМА = {попыток: 30, пауза: 700};
const ЖДАТЬ_ТИШИНЫ = {попыток: 20, пауза: 250};

/** Надписи панели одним местом: код своих слов не держит (SPEC 6.10). */
export const надписи = (settings) => settings['панель'];

/** Наблюдаемые порты: порт рабочего окна из кода и названные порты испытаний из настроек. */
export function порты(settings) {
  const испытания = (надписи(settings)['портыИспытаний'] ?? [])
    .map(Number)
    .filter((порт) => Number.isInteger(порт) && порт !== ПОРТ_ВЛАДЕЛЬЦА);
  return [ПОРТ_ВЛАДЕЛЬЦА, ...испытания];
}

/**
 * Чем поднимать этот порт. У рабочего окна состав известен из кода и памятью не подменяется:
 * запись о том, что вчера на `4780` отвечала какая-то копия, не должна решать, откуда поднимать
 * редактор владельца сегодня. Испытательный поднимается тем составом, каким его видели живым.
 */
export function запуском(порт, помнится) {
  if (Number(порт) === ПОРТ_ВЛАДЕЛЬЦА) return {код: ПАПКА_ПРИНЯТОГО, материалы: ПАПКА_ВЛАДЕЛЬЦА};
  const запись = помнится[порт];
  return запись ? {код: запись['код'], материалы: запись['материалы']} : null;
}

/**
 * Живое состояние всех наблюдаемых портов. Опрос идёт каждый раз заново: панель ничего не
 * показывает по памяти, память только дополняет остановленные строки последним известным составом.
 */
export function сПамятьюОРабочем(помнится) {
  if (помнится[ПОРТ_ВЛАДЕЛЬЦА]) return помнится;
  // Строка рабочего окна не пропадает никогда, даже если живым его на этой машине ещё не видели:
  // чем его поднимать, известно из кода, и владельцу нужна привычная строка, а не пустая панель.
  return {
    ...помнится,
    [ПОРТ_ВЛАДЕЛЬЦА]: {
      вид: ВИД_РАБОЧИЙ, ветка: null, коммит: null, чисто: false,
      код: ПАПКА_ПРИНЯТОГО, материалы: ПАПКА_ВЛАДЕЛЬЦА,
    },
  };
}

export async function состояние(settings) {
  const список = порты(settings);
  const ответы = await опрос(список);
  const помнится = сПамятьюОРабочем(запомнить(ответы));
  const таблица = строки({порты: список, ответы, память: помнится});

  return {
    строки: таблица.map((строка) => ({...строка, запуск: запуском(строка['порт'], помнится)})),
    портВладельца: ПОРТ_ВЛАДЕЛЬЦА,
  };
}

/** Отказ словами человека. Кода правила человек не видит никогда. */
const словами = (settings, код) => надписи(settings)['отказы'][код] ?? код;

/**
 * Поднять экземпляр. Порт опрашивается непосредственно перед запуском: занятый чужой программой
 * порт не освобождается сам, а второй сервер поверх работающего не нужен. Ответ отдаётся только
 * после того, как поднявшийся сервер сам себя назвал, — «запустили» без живого опознания было бы
 * тем же обещанием по памяти, от которого панель и уходит.
 */
export async function запустить(settings, порт) {
  const ответ = await опросПорта(порт);
  const решение = решениеЗапуска({ответ, запуск: запуском(порт, память())});
  if (решение['отказ']) return {получилось: false, беда: словами(settings, решение['отказ'])};

  поднять({порт, код: решение['код'], материалы: решение['материалы']});
  const стало = await дождаться(порт, наш, ЖДАТЬ_ПОДЪЁМА);
  if (!наш(стало)) {
    const слова = словаЗапуска(порт);
    const беда = словами(settings, НЕ_ПОДНЯЛСЯ);
    return {получилось: false, беда: слова ? `${беда}\n${слова}` : беда};
  }

  return {получилось: true, итог: надписи(settings)['итоги'][РАБОТАЕТ]};
}

/**
 * Остановить экземпляр. Три сверки подряд и ни одной по памяти: сервер называет себя живым
 * ответом, система называет владельца порта, командная строка владельца сходится с папкой кода из
 * того же ответа. Любое несовпадение — отказ, и ни один процесс не трогается.
 */
export async function остановить(settings, порт) {
  const ответ = await опросПорта(порт);
  const владелец = наш(ответ) ? await владелецПорта(порт) : null;
  const решение = решениеОстановки({порт, ответ, владелец});
  if (решение['отказ']) return {получилось: false, беда: словами(settings, решение['отказ'])};

  завершить(решение['номер']);
  const стало = await дождаться(порт, тихо, ЖДАТЬ_ТИШИНЫ);
  if (!тихо(стало)) return {получилось: false, беда: словами(settings, ВСЁ_ЕЩЁ_ОТВЕЧАЕТ)};

  return {получилось: true, итог: надписи(settings)['итоги'][ОСТАНОВЛЕН]};
}

/** Номер порта из тела запроса: только целое число, только из наблюдаемых. */
function номерПорта(settings, тело) {
  const порт = Number(тело && тело['порт']);
  return порты(settings).includes(порт) ? порт : null;
}

/**
 * Маршрут панели. Показ состояния — чтение, запуск и остановка — действие, и оба действия сначала
 * называют порт из наблюдаемых: порт, которого панель не наблюдает, она не трогает вовсе.
 */
export async function panelRoute({req, res, url, settings, тело, send}) {
  if (url.pathname === '/api/panel/state' && req.method === 'GET') {
    send(res, 200, await состояние(settings));
    return true;
  }

  const действие = {'/api/panel/start': запустить, '/api/panel/stop': остановить}[url.pathname];
  if (!действие || req.method !== 'POST') return false;

  const порт = номерПорта(settings, await тело(req));
  if (порт === null) {
    send(res, 400, {error: словами(settings, НЕ_НАБЛЮДАЕТСЯ)});
    return true;
  }

  const итог = await действие(settings, порт);
  send(res, 200, {...итог, ...(await состояние(settings))});
  return true;
}
