// Живой опрос портов и память панели. Тонкий адаптер: правила — в `instanceControl.mjs`,
// здесь только разговор с сетью и с диском (SPEC 4.3, 4.7).
//
// Опрос всегда идёт до самого действия и сразу после него: панель показывает не то, что она
// помнит, а то, что порт ответил только что. Память нужна ровно для одного — поднять обратно
// остановленный экземпляр тем же составом; работающим она никого не объявляет.

import fs from 'node:fs';
import http from 'node:http';
import path from 'node:path';

import {ПАПКА_ВЛАДЕЛЬЦА} from '../core/materialRoot.mjs';
import {ПАПКА_РЕДАКТОРА} from '../core/draftHome.mjs';
import {записьПамяти, опознаниеЛи} from '../core/instanceControl.mjs';

/**
 * Дом панели — рядом с черновиками и историей, внутри материалов владельца (SPEC 7.1.5): память о
 * запусках принадлежит машине владельца, а не копии кода, из которой панель подняли сегодня.
 */
export const ДОМ_ПАНЕЛИ = path.join(ПАПКА_ВЛАДЕЛЬЦА, ПАПКА_РЕДАКТОРА, '.panel');

/** Файл памяти: порт — последнее живое опознание того, кто на нём работал. */
export const ФАЙЛ_ПАМЯТИ = path.join(ДОМ_ПАНЕЛИ, 'instances.json');

/** Сколько ждать ответа порта. Величина алгоритма: местный сервер отвечает мгновенно, а панель
 *  опрашивает несколько портов подряд, и молчащий порт не должен подвешивать всю таблицу. */
const ЖДАТЬ_МС = 1500;

/** Ответ одного порта: наше опознание, чужая программа или молчание (`null`). */
export async function опросПорта(порт, ждать = ЖДАТЬ_МС) {
  let ответ;
  try {
    ответ = await fetch(`http://localhost:${порт}/api/identity`, {signal: AbortSignal.timeout(ждать)});
  } catch {
    // Отказ соединения и тишина — это «никого нет». Отличать их друг от друга незачем: ни в том,
    // ни в другом случае останавливать нечего, а запускать можно.
    return null;
  }

  let тело = null;
  try {
    тело = await ответ.json();
  } catch {
    тело = null;
  }

  // Ответил кто угодно, кроме нашего опознания, — препятствие. Сюда же попадает старый редактор,
  // который про себя молчит: раз он себя не называет, доказать, что это он, нечем.
  return опознаниеЛи(тело) ? {опознание: тело} : {чужой: true};
}

/**
 * Опрос порта с ЖИВОЙ связью: тот же ответ, что и обычный опрос, плюс номер нашего конца связи и
 * способ её закрыть. Пока связь открыта, система может назвать процесс, который этот самый запрос
 * обслужил, — прямее доказательства «отвечал вот этот процесс» не бывает.
 *
 * Нужен только на пути остановки, поэтому таблица его не зовёт: держать открытую связь с каждым
 * наблюдаемым портом ради обычного показа незачем.
 */
export function опросСоСвязью(порт, ждать = ЖДАТЬ_МС) {
  const дверь = new http.Agent({keepAlive: true, maxSockets: 1});
  const закрыть = () => дверь.destroy();

  return new Promise((готово) => {
    const запрос = http.get(
      {host: '127.0.0.1', port: порт, path: '/api/identity', agent: дверь, timeout: ждать},
      (ответ) => {
        let тело = '';
        ответ.setEncoding('utf8');
        ответ.on('data', (кусок) => {
          тело += кусок;
        });
        ответ.on('end', () => {
          let разобрано = null;
          try {
            разобрано = JSON.parse(тело);
          } catch {
            разобрано = null;
          }
          готово({
            ответ: опознаниеЛи(разобрано) ? {опознание: разобрано} : {чужой: true},
            свойПорт: запрос.socket ? запрос.socket.localPort : null,
            закрыть,
          });
        });
      },
    );

    // Молчание и обрыв — это «никого нет»: останавливать нечего, и связь закрывать уже незачем.
    запрос.on('timeout', () => запрос.destroy());
    запрос.on('error', () => {
      закрыть();
      готово({ответ: null, свойПорт: null, закрыть: () => {}});
    });
  });
}

/** Все наблюдаемые порты одним заходом: опрос идёт разом, а не по очереди. */
export async function опрос(порты) {
  const пары = await Promise.all(порты.map(async (порт) => [порт, await опросПорта(порт)]));
  return Object.fromEntries(пары);
}

/**
 * Память с диска. Битый или пропавший файл — это «панель ничего не помнит», а не отказ работать:
 * без памяти видно живое состояние, и только кнопка «Запустить» у остановленного пропадает.
 */
export function память() {
  try {
    const прочитано = JSON.parse(fs.readFileSync(ФАЙЛ_ПАМЯТИ, 'utf8'));
    return прочитано && typeof прочитано === 'object' ? прочитано : {};
  } catch {
    return {};
  }
}

/**
 * Запомнить то, что сейчас живо. Записи о портах, которые молчат или заняты чужим, не трогаются:
 * остановленный экземпляр должен остаться в списке, иначе поднять его обратно будет нечем.
 * Не удалось записать — беда памяти, а не работы: панель продолжает показывать живое состояние.
 */
export function запомнить(ответы) {
  const было = память();
  const стало = {...было};
  for (const [порт, ответ] of Object.entries(ответы)) {
    if (ответ && ответ['опознание']) стало[порт] = записьПамяти(ответ['опознание']);
  }

  try {
    fs.mkdirSync(ДОМ_ПАНЕЛИ, {recursive: true});
    fs.writeFileSync(ФАЙЛ_ПАМЯТИ, `${JSON.stringify(стало, null, 2)}\n`, 'utf8');
  } catch (error) {
    console.error(error);
  }

  return стало;
}

/**
 * Дождаться нужного состояния порта: после запуска — появления нашего опознания, после остановки —
 * тишины. Состояние проверяется тем же опросом, что и вся таблица: другого источника правды о том,
 * жив ли экземпляр, в программе нет.
 */
export async function дождаться(порт, годится, {попыток, пауза}) {
  let ответ = await опросПорта(порт);
  for (let n = 1; n < попыток && !годится(ответ); n += 1) {
    await new Promise((готово) => setTimeout(готово, пауза));
    ответ = await опросПорта(порт);
  }
  return ответ;
}

/** Порт ответил нашим опознанием. */
export const наш = (ответ) => Boolean(ответ && ответ['опознание']);

/** На порту тихо: никто не отвечает вовсе. */
export const тихо = (ответ) => ответ === null;
