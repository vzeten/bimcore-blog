// Публикация статьи глазами окна: одно нажатие, один вопрос, один ответ.
//
// **Человека не ведут по этапам.** «Опубликовать» само сохраняет несохранённое, само гоняет
// обязательные проверки, само сверяется с сайтом, само собирает сайт целиком — и только потом
// задаёт единственный вопрос. Согласился — программа сама фиксирует статью и отправляет её.
// Отдельных действий «выпуск», «зафиксировать», «отправить» у человека больше нет: это шаги
// программы, а не его работа.
//
// **Порядок шагов живёт не здесь, а в `publishRun.ts`** — там он проверяется машиной. Здесь только
// состояние окна: что показать, что погасить и когда попытка считается отменённой.

import {useEffect, useRef, useState} from 'react';
import {requestJson} from './api';
import {зафиксироватьИОтправить, проверитьИСобрать, type Исход, type ШагПубликации} from './publishRun';
import type {ИтогВыпуска, PrepareFinding, PushPlan, ReleaseComposition} from './publishTypes';

export type {ШагПубликации};

/**
 * Почему публикация остановлена. `ключ` — причина, которую назвало само окно (слова к ней лежат в
 * настройках); `текст` — причина, которую словами прислал сервер. Разом они не приходят.
 */
export interface Остановка {
  ключ: string | null;
  текст: string;
  находки: PrepareFinding[];
  чужие: string[];
  вывод: string;
}

export interface Публикация {
  шаг: ШагПубликации;
  остановка: Остановка | null;
  /** Неблокирующее: поправить стоит, но публиковать можно. */
  предупреждения: PrepareFinding[];
  итог: ИтогВыпуска | null;
  /** Только для необязательного раскрытия: пути и номера коммитов человеку не нужны. */
  подробности: {файлы: ReleaseComposition['файлы']; коммиты: PushPlan['коммиты']; коммит: string | null};
  начать: () => Promise<void>;
  подтвердить: () => Promise<void>;
  закрыть: () => void;
}

/**
 * `path` — путь открытой языковой версии; `dirty` — есть ли несохранённые правки; `заход` — номер
 * открытия статьи; `сохранить` — записать окно на диск и ответить, легла ли работа целиком.
 */
export function usePublish(
  path: string | null,
  dirty: boolean,
  заход: number,
  сохранить: () => Promise<boolean>,
): Публикация {
  const [шаг, setШаг] = useState<ШагПубликации>('нет');
  const [остановка, setОстановка] = useState<Остановка | null>(null);
  const [предупреждения, setПредупреждения] = useState<PrepareFinding[]>([]);
  const [итог, setИтог] = useState<ИтогВыпуска | null>(null);
  const [файлы, setФайлы] = useState<ReleaseComposition['файлы']>([]);
  const [коммиты, setКоммиты] = useState<PushPlan['коммиты']>([]);
  const [коммит, setКоммит] = useState<string | null>(null);
  // Что сейчас на экране и идёт ли работа — в ref: ответ, посланный минуты назад, обязан сверяться
  // с тем, что в окне СЕЙЧАС, а не с тем, что было при отправке запроса.
  const окно = useRef('');
  const идёт = useRef(false);
  // Попытку отменяют две вещи: правка статьи во время проверок и закрытие панели человеком.
  // Признак нужен отдельно от ключа окна: сама публикация меняет несохранённое на сохранённое,
  // и попытка обрывалась бы своим же первым шагом.
  const отменено = useRef<'' | 'правка' | 'закрыто'>('');

  // Ключ окна — статья и заход в неё. Признака несохранённого здесь нет намеренно (см. выше).
  окно.current = `${path ?? ''}|${заход}`;

  const закрыть = () => {
    // Закрыли панель посреди проверок — попытка отменяется: иначе ответ, пришедший через минуту,
    // снова раскрыл бы закрытую панель. После согласия человека отменять уже нечего — запись и
    // отправка доводятся до конца (см. ), и панель на это время закрыть не предлагает.
    if (идёт.current) отменено.current = 'закрыто';
    setШаг('нет');
    setОстановка(null);
    setПредупреждения([]);
    setИтог(null);
    setФайлы([]);
    setКоммиты([]);
    setКоммит(null);
  };

  // Правка статьи и переход к другой обесценивают всё показанное: проверки и сборка судили о том
  // тексте, которого в окне уже нет. Правка ВО ВРЕМЯ проверок отменяет текущую попытку — следующая
  // проверит заново; иначе человек получил бы вопрос про текст, которого уже нет. После согласия
  // правка попытку не останавливает: публикуется то, что лежит в файле и что прошло проверки.
  useEffect(() => {
    if (идёт.current) {
      if (dirty) отменено.current = 'правка';
      return;
    }
    закрыть();
  }, [path, заход, dirty]);

  /** Остановиться и назвать причину: либо своим ключом, либо словами сервера. */
  const стоп = (
    причина: {ключ?: string; текст?: string},
    находки: PrepareFinding[] = [],
    чужие: string[] = [],
    вывод = '',
  ) => {
    setОстановка({ключ: причина.ключ ?? null, текст: причина.текст ?? '', находки, чужие, вывод});
    setШаг('нет');
  };

  /** Отказ сервера: текст для человека и всё, что он к нему приложил. */
  const отказ = (error: unknown) => {
    const причина = error as {прервано?: boolean; message?: string; ответ?: {чужие?: string[]; вывод?: string}};
    if (причина?.прервано === true) return;

    стоп(
      {текст: причина?.message ?? ''},
      [],
      Array.isArray(причина?.ответ?.чужие) ? причина.ответ.чужие : [],
      typeof причина?.ответ?.вывод === 'string' ? причина.ответ.вывод : '',
    );
  };

  /** Ход публикации получает окно снаружи: сам он ни про React, ни про экран не знает. */
  const ход = (былоОкно: string) => ({
    запрос: <T>(адрес: string, тело: Record<string, unknown>): Promise<T> => requestJson<T>(адрес, {
      method: 'POST',
      headers: {'Content-Type': 'application/json'},
      body: JSON.stringify(тело),
    }),
    сохранить,
    шаг: setШаг,
    жива: () => окно.current === былоОкно && отменено.current === '',
  });

  /**
   * Показать исход. Отменённая попытка молчит, если человек ушёл или закрыл панель, и называет
   * причину, если он правил статью: там ему надо понять, почему публикация не идёт.
   */
  const показать = (исход: Исход) => {
    if (исход.вид === 'прервано') {
      if (отменено.current === 'правка') стоп({ключ: 'правкаВоВремя'});
      return;
    }
    if (исход.вид === 'остановка') return стоп({ключ: исход.ключ}, исход.находки);
    if (исход.вид === 'спрашиваю') {
      setИтог(исход.итог);
      setФайлы(исход.файлы);
      setПредупреждения(исход.предупреждения);
      setШаг('спрашиваю');
      return;
    }

    setКоммит(исход.коммит);
    setКоммиты(исход.коммиты);
    setШаг('готово');
  };

  /** Одна попытка: пока предыдущая не кончилась, вторая не начинается. */
  const попытка = async (дело: (былоОкно: string) => Promise<Исход>) => {
    if (path === null || идёт.current) return;

    const было = окно.current;
    идёт.current = true;
    отменено.current = '';
    setОстановка(null);
    try {
      показать(await дело(было));
    } catch (error) {
      if (окно.current === было && отменено.current === '') отказ(error);
    } finally {
      идёт.current = false;
    }
  };

  return {
    шаг,
    остановка,
    предупреждения,
    итог,
    подробности: {файлы, коммиты, коммит},
    начать: () => попытка(async (было) => {
      setПредупреждения([]);
      setИтог(null);
      setКоммит(null);

      return проверитьИСобрать(path as string, dirty, ход(было));
    }),
    подтвердить: () => попытка((было) => зафиксироватьИОтправить(path as string, ход(было))),
    закрыть,
  };
}
