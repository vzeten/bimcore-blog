// Публикация статьи глазами окна: одно нажатие, один вопрос, дальше программа идёт сама.
//
// **Вопрос задаётся сразу** (решение владельца 2026-09-18, п.2–4): «Опубликовать» открывает окно,
// где видно, что сейчас на сайте у каждого языка, отмечаются языки публикации (этап 3: по умолчанию
// один открытый) и выбирается доступность — одна на все отмеченные. После ответа ход идёт
// сам — сохраняет, ставит доступность, дату и обложку, проверяет, записывает и отправляет. Кнопка
// тем временем говорит «Публикуется…», а при отказе — «Не опубликовано»; по нажатию видна причина.
//
// **Порядок шагов живёт не здесь, а в `publishRun.ts`** — там он проверяется машиной. Здесь только
// состояние окна: что показать и когда попытка считается отменённой.

import {useEffect, useRef, useState} from 'react';
import {requestJson} from './api';
import {опубликовать, type Исход, type ШагПубликации} from './publishRun';
import {кПубликации, переключить, строкиЯзыков} from './publishLangs';
import type {PrepareFinding, PrepareReport, PublishState, Разрыв} from './publishTypes';

export type {ШагПубликации};

/** Доступность по умолчанию — «Доступно всем» (решение владельца 2026-09-18, п.2). */
const ПО_УМОЛЧАНИЮ = 'всем';

/**
 * Почему публикация остановлена. `ключ` — причина, которую назвало само окно (слова к ней лежат в
 * настройках); `текст` — причина, которую словами прислал сервер. Разом они не приходят.
 */
export interface Остановка {
  ключ: string | null;
  текст: string;
  /** Код отказа сервера, если он его назвал: по нему окно решает, правда ли «на сайт ничего не ушло». */
  код: string | null;
  /** Отказ пришёл на шаге записи и отправки без ответа сервера: что там случилось, неизвестно. */
  наОтправке: boolean;
  /** Неоткрытые языки, которые публикация уже переписала и вернуть не сумела. */
  изменены: string[];
  находки: PrepareFinding[];
  чужие: string[];
  /** Имена лишних файлов, убранных в корзину: причина называет их человеку. */
  убрано: string[];
  /** Чем именно состав не доказан. Повторов здесь нет: одну причину человек читает один раз. */
  разрывы: Разрыв[];
  /** Пути, которые не удалось привести в порядок после записи. Посторонними они не являются. */
  невосстановленные: string[];
  вывод: string;
}

/** Окно вопроса: что сейчас на сайте, выбор доступности и замечания проверки (если уже известны). */
export interface ОкноПубликации {
  состояние: PublishState | null;
  /** Спросить сайт не удалось — окно всё равно открыто: публикация сама скажет, что не так. */
  неУзнали: boolean;
  выбор: string;
  /** Отмеченные языки — пути версий (этап 3); по умолчанию один открытый. */
  отмечены: string[];
  /** Замечания обязательных проверок открытой версии; `null` — не проверялось (есть несохранённое). */
  находки: PrepareFinding[] | null;
}

export interface Публикация {
  шаг: ШагПубликации;
  окно: ОкноПубликации | null;
  остановка: Остановка | null;
  причинаОткрыта: boolean;
  открыть: () => void;
  выбрать: (режим: string) => void;
  отметить: (путь: string) => void;
  /** Идёт публикация какой-то статьи — второй не начать, пока не кончилась первая. */
  занята: boolean;
  начать: (название?: string) => Promise<void>;
  отмена: () => void;
  показатьПричину: () => void;
  скрытьПричину: () => void;
  понятно: () => void;
}

/** Идёт ли ход: у этих шагов кнопка говорит «Публикуется…» и не нажимается. */
export const идётПубликация = (шаг: ШагПубликации): boolean => ['сохраняю', 'проверяю', 'сверяю', 'публикую'].includes(шаг);

const запрос = <T>(адрес: string, тело: Record<string, unknown>): Promise<T> => requestJson<T>(адрес, {
  method: 'POST',
  headers: {'Content-Type': 'application/json'},
  body: JSON.stringify(тело),
});

/**
 * `path` — путь открытой языковой версии; `dirty` — есть ли несохранённые правки; `заход` — номер
 * открытия статьи; `запись` — умения окна записать себя на диск: всё, дата, обложка, доступность;
 * `сообщить` — сказать человеку словами то, что случилось уже после отправки; `вне` — публикация
 * не прошла, а человек уже на другом экране: сказать ему это там, где он сейчас.
 *
 * **Начатая публикация доходит до конца, куда бы человек ни ушёл** (проба владельца 2026-09-19):
 * хук живёт в шапке программы, которая не пропадает при переходах, а итог помнится по статье —
 * вернувшись в неё, человек видит «Не опубликовано» с той же причиной.
 */
export function usePublish(
  path: string | null,
  dirty: boolean,
  заход: number,
  запись: {
    сохранить: () => Promise<boolean>;
    дата: (дата: string) => Promise<boolean>;
    обложка: (адрес: string) => Promise<boolean>;
    доступность: (режим: string) => Promise<boolean>;
  },
  сообщить: (исход: Extract<Исход, {вид: 'готово'}>) => void,
  /** Языковые версии статьи по своду (язык → путь): галочки работают и до ответа сервера. */
  версииСвода: Record<string, string> = {},
  вне: (путь: string, название: string, остановка: Остановка) => void = () => undefined,
  /**
   * Какое окно статьи на экране прямо сейчас — по тем же ссылкам, что у сохранения (`тоЖеОкно` в
   * `useSaving.ts`). Переход переставляет их сразу, а `экран` ниже догоняет только при перерисовке:
   * ответ даты или обложки в эту щель записал бы шапку и тело новой статьи под путём прежней.
   */
  окноСейчас?: () => string,
): Публикация {
  const строки = (состояние: PublishState | null, отмечены: string[]) => (
    строкиЯзыков(состояние, path ?? '', отмечены, версииСвода, Object.keys(версииСвода))
  );
  // Какая статья публикуется и на каком шаге. Кнопка говорит «Публикуется…» только у неё.
  const [ход, setХод] = useState<{путь: string; шаг: ШагПубликации} | null>(null);
  const [окно, setОкно] = useState<ОкноПубликации | null>(null);
  // Причины отказа по статьям: итог помнится, пока человек его не прочтёт «Понятно».
  const [остановки, setОстановки] = useState<Record<string, Остановка>>({});
  const [причинаОткрыта, setПричинаОткрыта] = useState(false);
  const шаг: ШагПубликации = ход !== null && ход.путь === path ? ход.шаг : 'нет';
  const остановка = path === null ? null : остановки[path] ?? null;
  const путьСейчас = useRef(path);
  путьСейчас.current = path;
  const забыть = (путь: string) => setОстановки(({[путь]: _, ...прочие}) => прочие);
  // Что сейчас на экране — в ref: ответ, посланный секунды назад, обязан сверяться с тем, что в окне
  // СЕЙЧАС. Ключ — статья и заход в неё; признака несохранённого здесь нет: сама публикация пишет.
  const экран = useRef('');
  экран.current = `${path ?? ''}|${заход}`;
  const идёт = useRef(false);
  // Последний шаг хода: отказ без ответа сервера на шаге отправки — исход неясен.
  const последнийШаг = useRef<ШагПубликации>('нет');

  // Переход к другой статье закрывает окно вопроса и панель причины. Идущая публикация и итоги
  // статей остаются: итог принадлежит своей статье, а не экрану.
  useEffect(() => {
    setОкно(null);
    setПричинаОткрыта(false);
  }, [path, заход]);

  const открыть = () => {
    if (path === null || идёт.current) return;
    const было = экран.current;
    забыть(path);
    setПричинаОткрыта(false);
    setОкно({состояние: null, неУзнали: false, выбор: ПО_УМОЛЧАНИЮ, отмечены: [path], находки: null});
    const своё = (дело: (прежнее: ОкноПубликации) => ОкноПубликации) => {
      if (экран.current === было) setОкно((прежнее) => (прежнее === null ? null : дело(прежнее)));
    };
    // Что сейчас на сайте — до всякой проверки: окно показывает это сразу (п.2 решения владельца).
    void запрос<PublishState>('/api/publish/state', {path})
      .then((состояние) => своё((прежнее) => ({...прежнее, состояние})))
      .catch(() => своё((прежнее) => ({...прежнее, неУзнали: true})));
    // Замечания проверок — по записанному файлу: при несохранённом они говорили бы не о том тексте.
    if (!dirty) {
      void запрос<PrepareReport>('/api/prepare', {path, толькоОткрытая: true})
        .then((отчёт) => своё((прежнее) => ({...прежнее, находки: отчёт.находки})))
        .catch(() => undefined);
    }
  };

  /** Причина остановки по исходу хода; `null` — остановки нет (успех). */
  const остановкаИсхода = (исход: Исход): Остановка | null => {
    // Окно ушло к другой статье раньше, чем ход записал в него своё: публикация не прошла.
    if (исход.вид === 'прервано') return новаяОстановка({ключ: 'ушлиИзСтатьи'});
    if (исход.вид === 'остановка') {
      return новаяОстановка({ключ: исход.ключ}, {
        находки: исход.находки, чужие: исход.чужие, разрывы: исход.разрывы, невосстановленные: исход.невосстановленные,
        убрано: исход.убрано ?? [], наОтправке: исход.послеОтправки === true,
      });
    }
    if (исход.вид === 'готово') сообщить(исход);
    return null;
  };

  const новаяОстановка = (причина: {ключ?: string; текст?: string}, ещё: Partial<Остановка> = {}): Остановка => ({
    ключ: причина.ключ ?? null, текст: причина.текст ?? '', код: null, наОтправке: false, изменены: [],
    находки: [], чужие: [], разрывы: [], невосстановленные: [], убрано: [], вывод: '', ...ещё,
  });

  /** Отказ сервера: текст для человека и всё, что он к нему приложил. */
  const остановкаОтказа = (error: unknown): Остановка | null => {
    const причина = error as {прервано?: boolean; послеОтправки?: boolean; message?: string; ответ?: {код?: string; чужие?: string[]; вывод?: string; разрывы?: Разрыв[]; находки?: PrepareFinding[]; изменены?: string[]}};
    if (причина?.прервано === true) return null;
    const пути = Array.isArray(причина?.ответ?.чужие) ? причина.ответ.чужие : [];
    // Посторонний файл — чужая работа, непривёденный путь — наша незаконченная: слово у них разное.
    const непривёденные = причина?.ответ?.код === 'невосстановлено';
    return новаяОстановка({текст: причина?.message ?? ''}, {
      код: typeof причина?.ответ?.код === 'string' ? причина.ответ.код : null,
      наОтправке: причина?.послеОтправки === true || (причина?.ответ === undefined && последнийШаг.current === 'публикую'),
      изменены: Array.isArray(причина?.ответ?.изменены) ? причина.ответ.изменены : [],
      находки: Array.isArray(причина?.ответ?.находки) ? причина.ответ.находки : [],
      чужие: непривёденные ? [] : пути,
      невосстановленные: непривёденные ? пути : [],
      разрывы: Array.isArray(причина?.ответ?.разрывы) ? причина.ответ.разрывы : [],
      вывод: typeof причина?.ответ?.вывод === 'string' ? причина.ответ.вывод : '',
    });
  };

  /**
   * Итог хода. Отказ помнится по статье; человек в ней — причина открывается сама (решение владельца
   * 2026-09-19), ушёл — ему говорят там, где он сейчас. Удача ничего красного не показывает.
   */
  const завершить = (путь: string, название: string, итог: Остановка | null) => {
    setХод(null);
    if (итог === null) return забыть(путь);
    setОстановки((прочие) => ({...прочие, [путь]: итог}));
    if (путьСейчас.current === путь) setПричинаОткрыта(true);
    else вне(путь, название, итог);
  };

  const начать = async (название = '') => {
    if (path === null || идёт.current || окно === null) return;
    const путь = path;
    const наЭкране = () => окноСейчас?.() ?? экран.current;
    const было = наЭкране();
    const выбор = окно.выбор;
    const версии = кПубликации(строки(окно.состояние, окно.отмечены));
    // Без отмеченных языков публиковать нечего: кнопка окна тогда заперта, а сюда не доходит.
    if (версии.length === 0) return;
    setОкно(null);
    идёт.current = true;
    последнийШаг.current = 'нет';
    let итог: Остановка | null = null;
    try {
      итог = остановкаИсхода(await опубликовать(путь, dirty, {
        запрос,
        сохранить: запись.сохранить,
        поставитьДату: запись.дата,
        поставитьОбложку: запись.обложка,
        поставитьДоступность: запись.доступность,
        шаг: (новый) => {
          последнийШаг.current = новый;
          setХод({путь, шаг: новый});
        },
        // Окно нужно ходу только для своих записей: ушёл человек — запись легла бы в чужую статью.
        жива: () => наЭкране() === было,
      }, выбор, версии));
    } catch (error) {
      итог = остановкаОтказа(error);
    } finally {
      идёт.current = false;
    }
    завершить(путь, название, итог);
  };

  return {
    шаг,
    занята: ход !== null,
    окно,
    остановка,
    причинаОткрыта,
    открыть,
    выбрать: (режим) => setОкно((прежнее) => (прежнее === null ? null : {...прежнее, выбор: режим})),
    отметить: (путь) => setОкно((прежнее) => (прежнее === null || path === null ? прежнее : {
      ...прежнее, отмечены: переключить(строки(прежнее.состояние, прежнее.отмечены), прежнее.отмечены, путь),
    })),
    начать,
    отмена: () => setОкно(null),
    показатьПричину: () => setПричинаОткрыта(true),
    скрытьПричину: () => setПричинаОткрыта(false),
    понятно: () => {
      if (path !== null) забыть(path);
      setПричинаОткрыта(false);
    },
  };
}
