import {useRef, useState} from 'react';
import {loadSessions, openVersion} from './actions';
import type {ПросмотрВерсии, Сеанс, Версия} from './types';

/**
 * Лента версий и просмотр одной версии.
 * Просмотр — отдельное состояние окна, а не подмена текста в редакторе: подмена запустила бы
 * цепочку «правка → автосохранение → черновик», и старая версия молча легла бы поверх работы.
 */
export function useVersions(deps: {
  /**
   * Ждущая правка при входе в просмотр дописывается: таймер иначе сработает во время чтения версии,
   * а простая отмена потеряла бы набранное — оно осталось бы только в спрятанном редакторе.
   */
  дописатьАвтосохранение: () => Promise<boolean>;
  onОшибка: (текст: string) => void;
}) {
  const [сеансы, setСеансы] = useState<Сеанс[]>([]);
  const [просмотр, setПросмотр] = useState<ПросмотрВерсии | null>(null);
  // Версия запрошена, но ещё не пришла. Рабочий редактор прячется уже в этот момент, а не по ответу:
  // иначе в щель между нажатием и ответом можно успеть набрать букву, и она заведёт автосохранение
  // заново — уже после того, как его сняли, то есть черновик допишется во время просмотра.
  const [занято, setЗанято] = useState(false);
  // Что человек ждёт прямо сейчас. Поздний ответ по прошлому выбору не должен подменить показанное:
  // выбрали версию А, передумали, выбрали Б — ответ А приходит позже и уже никому не нужен.
  const ждём = useRef<string | null>(null);
  // Та же защита для самой ленты: ушли в другую статью — ответ по прошлой уже не наш.
  const лентаДля = useRef<string | null>(null);

  /** Перечитать ленту открытой языковой версии. */
  const обновить = async (path: string): Promise<void> => {
    лентаДля.current = path;

    await loadSessions<Сеанс>(path, {
      // Пока лента грузилась, человек мог уйти в другую статью: чужие версии показывать нельзя.
      актуально: () => лентаДля.current === path,
      ok: setСеансы,
      fail: (причина) => {
        setСеансы([]);
        deps.onОшибка(причина);
      },
    });
  };

  /** Открыть версию на просмотр. Ничего не пишется: ни файл, ни черновик, ни состояние. */
  const открыть = async (path: string, версия: Версия): Promise<void> => {
    const ключ = `${path}|${версия.имя}`;
    ждём.current = ключ;
    setЗанято(true);

    const начался = await openVersion({path, имя: версия.имя}, {
      доЗапроса: deps.дописатьАвтосохранение,
      актуально: () => ждём.current === ключ,
      ok: (снимок) => {
        setЗанято(false);
        setПросмотр({имя: версия.имя, когда: версия.iso, автор: версия.author, ...снимок});
      },
      fail: (причина) => {
        ждём.current = null;
        setЗанято(false);
        deps.onОшибка(причина);
      },
    });

    // Ждущую правку записать не удалось — в просмотр не уходим: незаписанная работа осталась бы
    // только в окне, а сохранение в просмотре заперто. Причину человек уже видит от автосохранения.
    if (!начался) {
      ждём.current = null;
      setЗанято(false);
    }
  };

  /** Вернуться к текущей работе. Несохранённые правки всё это время лежали нетронутыми. */
  const закрыть = (): void => {
    ждём.current = null;
    // Снимается и ожидание: ответ по брошенному выбору уже не придёт ни в `ok`, ни в `fail`.
    setЗанято(false);
    setПросмотр(null);
  };

  /** Сменилась статья или языковая версия — просмотр и лента относятся уже к другому файлу. */
  const сбросить = (): void => {
    закрыть();
    лентаДля.current = null;
    setСеансы([]);
  };

  return {сеансы, просмотр, занято, обновить, открыть, закрыть, сбросить};
}
