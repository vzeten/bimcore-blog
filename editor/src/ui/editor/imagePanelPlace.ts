// Мелкие правила панели свойств картинки: где она встаёт, чем метится состоявшаяся замена
// и какими словами описан её итог.
// Вынесено из самой панели, чтобы она держалась в пределе размера файла (SPEC 4.9);
// состояния здесь нет, только два коротких правила.

import type {КартинкаВОкне} from '../livePreview/inline';

/**
 * Токен уникален у каждой замены: счётчик после перезапуска программы начался бы заново
 * и совпал бы с тем, что уже лежит в кэше браузера.
 */
export function токенЗамены(): string {
  return `${Date.now().toString(36)}-${Math.random().toString(36).slice(2, 8)}`;
}

/** Панель встаёт у левого верхнего угла картинки и не выходит за края окна. */
export function положение(картинка: КартинкаВОкне): {left: number; top: number} {
  return {
    left: Math.max(8, Math.min(картинка.left + 8, window.innerWidth - 300)),
    top: Math.max(8, Math.min(картинка.top + 8, window.innerHeight - 200)),
  };
}

/** Ответ сервера в той части, которая описывает итог человеку. */
interface ИтогЗамены {
  тяжёлая?: boolean;
  килобайт?: number;
  старыйОставлен?: 'ссылки' | 'сбой' | null;
}

/** Хвост про вес: тяжёлый файл — предупреждение, а не отказ, картинка уже на месте. */
export function хвостВеса(подписи: Record<string, string>, ответ: ИтогЗамены): string {
  if (ответ.тяжёлая !== true) return '';
  return ` ${подписи.тяжёлаяКартинка.replace('{килобайт}', String(ответ.килобайт ?? 0))}`;
}

/**
 * Итог смены формата словами человека. Причина, по которой остался прежний файл, называется
 * своим словом: «на него ещё ссылаются» и «убрать не удалось» — для человека разные ответы.
 */
export function итогСмены(подписи: Record<string, string>, ответ: ИтогЗамены): string {
  const хвостСтарого = ответ.старыйОставлен === 'ссылки' ? ` ${подписи.старыйФайлОстался}`
    : ответ.старыйОставлен === 'сбой' ? ` ${подписи.старыйФайлНеУбран}` : '';

  return `${подписи.форматСменён}.${хвостСтарого}${хвостВеса(подписи, ответ)}`;
}

/** Что панель сообщает наверх после удачной операции: чей это выбор и чем стала картинка. */
export interface ПеременаКартинки {
  выбор: number;
  src: string;
  from: number;
  to: number;
  left: number;
  top: number;
}

/**
 * Перенести выбранную картинку на её новый адрес. Правило проверяет ЛИЧНОСТЬ выбора, а не только
 * наличие картинки: пока файл ехал, человек мог нажать другую, и поздний ответ прежней панели
 * иначе подменил бы адрес и границы у чужой картинки, оставив ей чужой alt.
 *
 * `было` возвращается без изменений, когда весть опоздала.
 */
export function перенестиВыбор<Т extends {src: string; from: number; to: number; left: number; top: number}>(
  было: Т | null,
  выбор: number,
  весть: ПеременаКартинки,
): Т | null {
  if (было === null || весть.выбор !== выбор) return было;

  return {...было, src: весть.src, from: весть.from, to: весть.to, left: весть.left, top: весть.top};
}
