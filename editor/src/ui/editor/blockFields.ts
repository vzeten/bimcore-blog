// Поля панели свойств блока: что показать в них при открытии и какими словами объяснить отказ.
//
// Отдельным модулем от самой панели по размеру файла (SPEC 4.9), а не по смыслу: там окно и запись
// в статью, здесь чистый перевод между тем, что лежит в теге, и тем, что видит человек.

import {значениеСвойства, type ПолеБлока} from '../../core/jsxBlocks';
import {длительностьВСекундах, номерВидео, разборДлительности, ссылкаВидео} from '../../core/videoLink.mjs';

/**
 * Что панель должна сделать с полем, из которого ушёл человек.
 *
 * `нечего` — писать не надо вовсе. Так отвечает поле, которого человек не трогал: он мог просто
 * пройти по свойствам взглядом, а запись превратила бы `PT1M2S` в `62`, а непонятную человеку
 * запись — в пустоту. Молчаливой правки статьи от простого просмотра быть не может.
 */
export type Решение = {вид: 'нечего'} | {вид: 'записать'; значение: string} | {вид: 'беда'; беда: string};

/**
 * Решение о поле по его виду. Здесь весь перевод «что человек набрал» в «что ложится в тег»:
 * ссылка становится номером, минуты и секунды — числом секунд, обычное поле идёт как есть.
 */
export function чтоЗаписать(
  поле: ПолеБлока,
  черновики: Record<string, string>,
  тронуто: (ключ: string) => boolean,
  п: Record<string, string>,
): Решение {
  if (!тронуто(поле.имя)) return {вид: 'нечего'};

  // Обязательное поле пустым не записывается: без названия сайт карточку не покажет вовсе, а
  // человек увидел бы вместо неё пустое место и не понял, куда делся его товар.
  if (поле.обязательно === true && (черновики[поле.имя] ?? '').trim() === '') {
    return {вид: 'беда', беда: п.блокПолеОбязательно.split('{поле}').join(поле.подпись)};
  }

  if (поле.вид === 'ссылкаВидео') {
    const разбор = номерВидео(черновики[поле.имя] ?? '') as {номер?: string; ошибка?: string};
    if (разбор.ошибка !== undefined) return {вид: 'беда', беда: отказСсылки(п, разбор.ошибка)};

    return {вид: 'записать', значение: разбор.номер as string};
  }

  if (поле.вид === 'длительность') {
    const секунды = длительностьВСекундах(
      черновики[`${поле.имя}:мин`] ?? '', черновики[`${поле.имя}:сек`] ?? '',
    ) as string | null;
    if (секунды === null) return {вид: 'беда', беда: п.блокДлительностьНеЧисло};

    return {вид: 'записать', значение: секунды};
  }

  return {вид: 'записать', значение: черновики[поле.имя] ?? ''};
}

/** Что показать в полях, когда панель только открылась: значения из самого тега статьи. */
export function начальные(текст: string, поля: ПолеБлока[]): Record<string, string> {
  const черновики: Record<string, string> = {};

  for (const поле of поля) {
    const записано = значениеСвойства(текст, поле.имя) ?? '';

    if (поле.вид === 'ссылкаВидео') {
      черновики[поле.имя] = записано === '' ? '' : ссылкаВидео(записано);
      continue;
    }

    if (поле.вид === 'длительность') {
      const разобрано = разборДлительности(записано) as {минуты: string; секунды: string} | null;
      // Непонятную длительность панель не выдумывает заново: поля остаются пустыми, и пока
      // человек их не заполнил, в статье лежит его собственная запись.
      черновики[`${поле.имя}:мин`] = разобрано?.минуты ?? '';
      черновики[`${поле.имя}:сек`] = разобрано?.секунды ?? '';
      continue;
    }

    черновики[поле.имя] = записано;
  }

  return черновики;
}

/**
 * О чём панель говорит сразу при открытии: длительность в статье записана так, что программа её
 * не понимает. Молчать нельзя — человек увидел бы пустые минуты и решил, что длительности нет.
 */
export function непонятное(текст: string, поля: ПолеБлока[], п: Record<string, string>): Record<string, string> {
  const беды: Record<string, string> = {};

  for (const поле of поля) {
    if (поле.вид !== 'длительность') continue;
    const записано = значениеСвойства(текст, поле.имя) ?? '';
    if (записано !== '' && разборДлительности(записано) === null) беды[поле.имя] = п.блокДлительностьНепонятна;
  }

  return беды;
}

/** Календарь показывается только той дате, которую он умеет показать: иначе поле стёрло бы её. */
export function датаПонятна(значение: string): boolean {
  return значение === '' || /^\d{4}-\d{2}-\d{2}$/.test(значение);
}

/**
 * Слова человеку по коду отказа. Подписи названы здесь поимённо, а не собраны из кода причины:
 * собранный ключ машинная проверка настроек не видит, и забытая строка настроек молча стала бы
 * пустым местом рядом с полем.
 */
export function отказСсылки(п: Record<string, string>, код: string): string {
  if (код === 'пусто') return п.блокСсылкаПусто;
  if (код === 'неСсылка') return п.блокСсылкаНеСсылка;
  if (код === 'чужаяСсылка') return п.блокСсылкаЧужая;
  if (код === 'нетНомера') return п.блокСсылкаБезНомера;

  return код;
}
