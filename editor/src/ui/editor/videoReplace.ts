// Замена файла у одного ролика: новый WebM едет той же дорогой, что при вставке (заслон, карантин,
// укладка под свободным именем), а в тексте меняется ровно то, что ведёт к файлу. Прежний файл
// остаётся на диске нетронутым: отмена возвращает текст, и старый ролик обязан снова играть.
//
// Два тега могут делить один импорт. Тогда чужой тег трогать нельзя: выбранный получает свой
// импорт с новой переменной, а прежний импорт остаётся при соседе.
import type {EditorView} from '@codemirror/view';
import type {EditorState} from '@codemirror/state';
import {label} from '../labels';
import {видеоТекста, импортВидео, местоИмпорта, свободнаяПеременная, упоминаетсяВне} from '../../core/videoFile.mjs';
import {поверхность} from './structureGuard';
import {забратьОбратно} from './images';
import {действиеВидео, принятьВидеофайл, type ПравилоВидео, type Правка, type ПризнакиОкна} from './videoInsert';
import {ИМЯ_БЛОКА_ВИДЕО} from '../../core/videoFile.mjs';
import type {ФайлБлока} from './BlockFile';

/** Тег ролика под панелью: его текст и границы в статье. */
export interface УзелРолика {
  текст: string;
  from: number;
  to: number;
}

/** Ролик, найденный ядром: переменная, границы тега и импорта. */
interface Ролик {
  переменная: string;
  адрес: string;
  импорт: {от: number; до: number};
  от: number;
  до: number;
}

/** Имя файла ролика, чей тег стоит на этих границах, — для подписи в панели. `null` — тега нет. */
export function имяФайлаРолика(state: EditorState, узел: {from: number; to: number}): string | null {
  const ролик = роликУзла(state, узел);
  return ролик === null ? null : ролик.адрес.split('/').pop() ?? ролик.адрес;
}

function роликУзла(state: EditorState, узел: {from: number; to: number}): Ролик | null {
  return (видеоТекста(state.doc.toString()) as Ролик[]).find((в) => в.от === узел.from && в.до === узел.to) ?? null;
}

/**
 * Правки текста для замены файла у ролика на этих границах. `null` — на границах нет понятного
 * ролика, менять нечего.
 *
 * Импорт принадлежит только этому тегу — меняется адрес в самой строке импорта, тег остаётся как
 * был. Правка накрывает скрытую область целиком (строку импорта с её пустой строкой): правку
 * внутрь скрытого поверхность редактора не пропускает, а накрывающую — да. Переменная упомянута
 * ещё где-то — прежний импорт остаётся соседу, а выбранный тег получает новый импорт со свободной
 * переменной и ссылается на неё.
 */
export function правкиЗамены(state: EditorState, узел: {from: number; to: number}, адрес: string): Правка[] | null {
  const текст = state.doc.toString();
  const ролик = роликУзла(state, узел);
  if (ролик === null) return null;

  const свойТолько = !упоминаетсяВне(текст, ролик.переменная, [
    {from: ролик.от, to: ролик.до}, {from: ролик.импорт.от, to: ролик.импорт.до},
  ]);
  if (свойТолько) {
    const скрытый = state.field(поверхность).карта
      .find((о) => о.вид === 'скрытый' && о.from <= ролик.импорт.от && ролик.импорт.от < о.to);
    const from = скрытый?.from ?? ролик.импорт.от;
    const to = скрытый?.to ?? ролик.импорт.до;
    const insert = текст.slice(from, ролик.импорт.от) + импортВидео(ролик.переменная, адрес) + текст.slice(ролик.импорт.до, to);
    return [{from, to, insert}];
  }

  const новая = свободнаяПеременная(текст, адрес) as string;
  const место = местоИмпорта(текст) as number;
  const кусок = текст.slice(ролик.от, ролик.до);
  const где = кусок.indexOf(`{${ролик.переменная}}`);
  if (где === -1) return null;
  const отИмени = ролик.от + где + 1;

  return [
    {from: место, to: место, insert: `${импортВидео(новая, адрес)}\n\n`},
    {from: отИмени, to: отИмени + ролик.переменная.length, insert: новая},
  ];
}

/** Чем кончилась замена: новый адрес, новые границы тега и имя файла для подписи. */
export interface ЗаменённыйРолик {
  src: string;
  узел: УзелРолика;
  имяФайла: string;
}

/**
 * Замена файла у ролика. `null` — замены не было и это не ошибка: окно сменилось, пока файл ехал.
 * Тег под панелью сверяется ПОСЛЕ ответа сервера: за это время человек мог удалить блок или
 * сдвинуть текст, и правка по старым границам легла бы не туда — тогда уложенный файл забирается
 * обратно, а человек узнаёт причину. `передПравкой` — знак окну, что правка своя, панели её не
 * закрывать.
 */
export async function заменитьВидеофайл(
  file: File,
  article: string,
  view: EditorView,
  правило: ПравилоВидео,
  узел: УзелРолика,
  актуально: () => boolean,
  передПравкой: () => void,
): Promise<ЗаменённыйРолик | null> {
  const уложено = await принятьВидеофайл(file, article, view, правило, актуально);
  if (уложено === null) return null;

  const тотЖе = view.state.sliceDoc(узел.from, узел.to) === узел.текст;
  const правки = тотЖе ? правкиЗамены(view.state, узел, уложено.src) : null;
  if (правки === null) {
    await забратьОбратно(article, уложено.src);
    throw new Error(label('видеоБлокИзменился'));
  }

  передПравкой();
  const tr = view.state.update({changes: правки});
  view.dispatch(tr);
  if (!tr.docChanged) {
    await забратьОбратно(article, уложено.src);
    throw new Error(label('ошибкаЗаменыВидео'));
  }

  // Границы тега после правки: импорт выше стал длиннее или короче, имя переменной в теге — тоже.
  const from = tr.changes.mapPos(узел.from, 1);
  const to = tr.changes.mapPos(узел.to, -1);
  const стало = {текст: view.state.sliceDoc(from, to), from, to};

  return {src: уложено.src, узел: стало, имяФайла: имяФайлаРолика(view.state, стало) ?? уложено.src};
}

/** Замена ролика, какой её знает окно: файл, живой редактор, тег под панелью и знак своей правки. */
export type ЗаменаВидео = (file: File, view: EditorView, узел: УзелРолика, передПравкой: () => void) => Promise<ЗаменённыйРолик | null>;

/**
 * Строка файла для панели свойств: только у блока ролика. Имя файла берётся из импорта по живому
 * тексту, замена идёт в тот же редактор.
 */
export function файлБлока(view: EditorView, блок: {имя: string; from: number; to: number}, заменить: ЗаменаВидео): ФайлБлока | undefined {
  if (блок.имя !== ИМЯ_БЛОКА_ВИДЕО) return undefined;

  return {
    имя: имяФайлаРолика(view.state, блок) ?? '',
    заменить: (file, узел, передПравкой) => заменить(file, view, узел, передПравкой),
  };
}

/** Замена ролика для окна — под тем же сторожем окна, что и вставка. */
export function makeVideoReplace(deps: ПризнакиОкна): ЗаменаВидео {
  return (file, view, узел, передПравкой) => действиеВидео(deps, 'ошибкаЗаменыВидео',
    (куда, правило, актуально) => заменитьВидеофайл(file, куда, view, правило, узел, актуально, передПравкой))();
}
