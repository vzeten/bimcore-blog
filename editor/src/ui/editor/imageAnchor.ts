// Зрительный якорь картинки: после замены файла человек остаётся у той же картинки.
//
// Новая картинка почти всегда другой высоты, и приходит она не сразу — сначала меняется разметка,
// потом браузер догружает файл. Редактор пересчитывает высоту строки дважды и сам двигает
// содержимое, поэтому выбранная картинка уезжает вниз или просмотр перескакивает вверх
// (наблюдение владельца 2026-08-18: до замены верх картинки был на 293 px, после — на 373 px).
//
// Правило здесь одно: верх выбранной картинки остаётся на том же месте экрана. Поправка берётся
// ОСТАТКОМ — сколько ещё не хватает после того, как редактор уже подвинул содержимое сам, —
// поэтому она не удваивает его работу и не даёт второго рывка.

import type {EditorView} from '@codemirror/view';

/**
 * Какой якорь у окна сейчас главный. Новая замена отменяет прежний: иначе поздняя загрузка
 * прошлой картинки дёргала бы экран уже под следующей операцией. Держится слабой картой —
 * закрытый редактор уходит вместе со своей записью.
 */
const главный = new WeakMap<EditorView, symbol>();

/**
 * Через сколько после загрузки картинки делается контрольная поправка. Техническая величина:
 * редактор пересчитывает высоту строки своим кругом, и первый пересчёт может породить второй.
 */
const КОНТРОЛЬНАЯ_ПОПРАВКА_МС = 150;

/** Где картинка на экране: панель свойств встаёт по этим же числам. */
export interface МестоКартинки {
  left: number;
  top: number;
}

/**
 * Запомнить экранное место картинки в этой позиции текста и вернуть возврат на место.
 * Возврат зовётся сразу после правки текста и ещё раз, когда новая картинка догрузилась:
 * до загрузки её настоящая высота неизвестна, а после первой поправки редактор может
 * пересчитать строку ещё раз.
 *
 * `наМесте` получает свежие координаты картинки — по ним переезжает панель её свойств.
 */
export function держатьМесто(
  view: EditorView,
  позиция: number,
): (наМесте?: (место: МестоКартинки) => void) => void {
  const верхДо = местоКартинки(view, позиция)?.top ?? null;
  const свой = Symbol('якорь картинки');
  главный.set(view, свой);

  return (наМесте) => {
    // Поправка считается по настоящим краям картинки на экране и применяется сразу, без
    // ожидания кадра отрисовки: в неактивной вкладке браузер кадров не выдаёт вовсе, и правка,
    // отложенная до кадра, не случилась бы никогда.
    const вернуть = (): void => {
      if (главный.get(view) !== свой || !view.dom.isConnected) return;

      const место = местоКартинки(view, позиция);
      if (место === null) return;

      const поправка = остаток(верхДо, место.top);
      if (поправка !== 0) view.scrollDOM.scrollTop += поправка;
      наМесте?.(местоКартинки(view, позиция) ?? место);
    };

    вернуть();

    // Настоящая высота новой картинки известна только после её загрузки, а редактор к этому
    // времени успевает подвинуть содержимое сам — поэтому место возвращается ещё раз по
    // загрузке и один контрольный раз следом: каждая поправка берётся остатком и не удваивает
    // предыдущую.
    const img = картинкаВПозиции(view, позиция);
    const позже = (): void => {
      вернуть();
      window.setTimeout(вернуть, КОНТРОЛЬНАЯ_ПОПРАВКА_МС);
    };

    if (img === null || img.complete) window.setTimeout(позже, 0);
    else {
      const приЗагрузке = (): void => {
        img.removeEventListener('load', приЗагрузке);
        img.removeEventListener('error', приЗагрузке);
        позже();
      };
      img.addEventListener('load', приЗагрузке);
      img.addEventListener('error', приЗагрузке);
    }
  };
}

/**
 * Сколько ещё не хватает, чтобы картинка вернулась на прежнее место экрана. Чистое правило:
 * берётся ОСТАТОК от того, что редактор подвинул сам, поэтому поправка не удваивает его работу.
 * Ноль — двигать нечего: разница меньше пикселя человеку не видна, а лишний сдвиг заметен.
 */
export function остаток(верхДо: number | null, верхСейчас: number): number {
  if (верхДо === null) return 0;
  const разница = верхСейчас - верхДо;

  return Math.abs(разница) < 1 ? 0 : разница;
}

/** Прямоугольник картинки в этой позиции текста; `null` — её на экране сейчас нет. */
function местоКартинки(view: EditorView, позиция: number): МестоКартинки | null {
  const img = картинкаВПозиции(view, позиция);
  if (img !== null) {
    const рамка = img.getBoundingClientRect();
    return {left: рамка.left, top: рамка.top};
  }

  // Виджет ещё не построен: берётся место самой позиции в тексте — лучше, чем ничего.
  const место = view.coordsAtPos(позиция);
  return место === null ? null : {left: место.left, top: место.top};
}

/**
 * Сам элемент картинки в этой позиции. Берётся не первая картинка строки, а та, что стоит
 * ровно здесь: в одной строке картинок бывает несколько, и якорь обязан держать выбранную.
 */
function картинкаВПозиции(view: EditorView, позиция: number): HTMLImageElement | null {
  if (позиция > view.state.doc.length) return null;

  const {node, offset} = view.domAtPos(позиция);
  const обёртка = обёрткаКартинки(node as unknown as УзелПоказа, offset);

  return (обёртка?.querySelector?.('img') ?? null) as HTMLImageElement | null;
}

/** Узел показа: ровно столько, сколько нужно правилу — оно проверяется без настоящего браузера. */
export interface УзелПоказа {
  childNodes?: ArrayLike<УзелПоказа>;
  parentElement?: УзелПоказа | null;
  classList?: {contains: (имя: string) => boolean};
  querySelector?: (селектор: string) => УзелПоказа | null;
}

/**
 * Обёртка картинки по узлу разметки и смещению внутри него. Смещение отбрасывать нельзя:
 * без него у строки с двумя картинками всегда находилась бы первая, и замена второй уводила бы
 * экран и панель к чужой картинке.
 */
export function обёрткаКартинки(узел: УзелПоказа, смещение: number): УзелПоказа | null {
  // Сначала то, на что указывает смещение, — сам узел или картинка внутри него: редактор
  // заворачивает виджет в свою обёртку, и картинка бывает не самим ребёнком, а его содержимым.
  const поСмещению = внутри(узел.childNodes?.[смещение] ?? null);
  if (поСмещению !== null) return поСмещению;

  // Смещение указывает на место ПОСЛЕ узла, когда позиция пришлась на конец картинки.
  const предыдущий = смещение > 0 ? внутри(узел.childNodes?.[смещение - 1] ?? null) : null;
  if (предыдущий !== null) return предыдущий;
  if (картинка(узел)) return узел;

  // Позиция пришлась на текстовый узел внутри самой картинки: поднимаемся к её обёртке.
  const владелец: УзелПоказа | null = узел.parentElement ?? null;
  if (картинка(владелец)) return владелец;

  // Последняя попытка: единственная картинка внутри самого узла. Дальше держать нечего.
  return узел.querySelector?.('.md-image') ?? null;
}

/** Сам узел — картинка либо картинка лежит внутри него. `null` — ни то ни другое. */
function внутри(узел: УзелПоказа | null): УзелПоказа | null {
  if (узел === null || узел === undefined) return null;
  if (картинка(узел)) return узел;

  return узел.querySelector?.('.md-image') ?? null;
}

/** Это обёртка картинки в показе статьи. */
function картинка(узел: УзелПоказа | null): boolean {
  return узел !== null && узел.classList?.contains('md-image') === true;
}
