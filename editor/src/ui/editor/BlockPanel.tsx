import {useEffect, useLayoutEffect, useRef, useState} from 'react';
import type {EditorView} from '@codemirror/view';
import {сменаСвойства, значениеСвойства, type ПолеБлока} from '../../core/jsxBlocks';
import {ссылкаВидео} from '../../core/videoLink.mjs';
import {типыВидео} from '../../core/imageType.mjs';
import {выбратьФайл} from './images';
import {датаПонятна, начальные, непонятное, чтоЗаписать} from './blockFields';
import type {БлокВОкне} from '../livePreview/blocks';
import type {Settings} from '../types';

/** Границы блока в тексте статьи. Меняются с каждой записью: тег становится длиннее или короче. */
interface Узел {
  текст: string;
  from: number;
  to: number;
}

/** Чем кончилась попытка записать свойство. Панель по этому решает, говорить ли человеку правду. */
type Итог = 'записано' | 'нечегоМенять' | 'знак' | 'устарело';

export function BlockPanel(props: {
  settings: Settings;
  блок: БлокВОкне;
  view: EditorView;
  /**
   * Панель открыта сразу после вставки блока. Тогда человека спрашивают об одном — о том, без чего
   * блока не существует, — и панель уходит сама. Прочие свойства он правит потом, нажав на готовый
   * блок: перегружать вставку видео пятью полями значит мешать обычному сценарию.
   */
  приВставке?: boolean;
  /** Правку в тег делает сама панель: окно по этому знаку не закрывает её как чужую. */
  onСвояПравка: () => void;
  /**
   * У блока есть файл, и его можно заменить: имя для подписи и сама замена. Она возвращает новые
   * границы тега и имя файла либо `null` — замены не было, причина уже показана человеку.
   */
  файл?: {
    имя: string;
    заменить: (file: File, узел: Узел, передПравкой: () => void) => Promise<{узел: Узел; имяФайла: string} | null>;
  };
  onClose: () => void;
}) {
  const п = props.settings.подписи;
  const описание = props.settings.блоки[props.блок.имя];

  // Границы тега держатся в состоянии панели, а не берутся из props каждый раз: человек правит
  // несколько полей подряд, и после первой же записи длина тега в статье стала другой.
  const [узел, setУзел] = useState<Узел>({текст: props.блок.текст, from: props.блок.from, to: props.блок.to});
  const [черновики, setЧерновики] = useState<Record<string, string>>(() => начальные(props.блок.текст, описание?.поля ?? []));
  const [беды, setБеды] = useState<Record<string, string>>(() => непонятное(props.блок.текст, описание?.поля ?? [], п));
  // Какие поля человек в этой панели трогал. Нетронутое поле не записывается вовсе: просмотр
  // свойств не должен переписывать статью — ни `PT1M2S` в секунды, ни непонятную запись в пустоту.
  const тронуто = useRef<Record<string, true>>({});
  const узелРеф = useRef(узел);
  узелРеф.current = узел;
  // Файл блока: пока едет замена, кнопка заперта — второй выбор поверх первого устроил бы гонку.
  const [имяФайла, setИмяФайла] = useState(props.файл?.имя ?? '');
  const [занято, setЗанято] = useState(false);
  // Поздний ответ замены не трогает снятую с экрана панель. Признак взводится в эффекте, а не в
  // начальном значении ref: StrictMode монтирует эффект дважды (правило панели картинки).
  const жив = useRef(true);
  useEffect(() => {
    жив.current = true;
    return () => {
      жив.current = false;
    };
  }, []);

  // Панель у блока внизу экрана иначе уезжает за его край вместе со всеми полями: у видео их
  // пять, и вниз она не помещается. Высота известна только после отрисовки, поэтому меряется она,
  // а не угадывается по числу полей.
  const корпус = useRef<HTMLDivElement>(null);
  const [высота, setВысота] = useState(0);
  useLayoutEffect(() => setВысота(корпус.current?.offsetHeight ?? 0));

  if (описание === undefined) return null;

  // Сокращается только блок, который сам назвал поле для вставки. У призыва к действию такого
  // поля нет вовсе, и урезать его нечем: человек увидел бы пустую панель вместо выбора заготовки.
  const дляВставки = описание.поля.filter((поле) => поле.приВставке === true);
  const поля = props.приВставке === true && дляВставки.length > 0 ? дляВставки : описание.поля;

  return (
    <div className="block-panel" ref={корпус} style={{left: место(props.блок.left), top: поВертикали(props.блок.top + 6, высота)}}>
      <div className="block-panel-head">
        <div className="block-panel-name">{описание.подпись}</div>
        <button className="block-panel-close" onClick={props.onClose} title={п.блокЗакрыть}>✕</button>
      </div>

      {props.файл !== undefined && (
        <div className="block-panel-file">
          <span className="block-panel-file-name" title={имяФайла}>{имяФайла}</span>
          <button onClick={() => выбратьФайл(типыВидео(), (file) => void заменитьФайл(file))} disabled={занято}>
            {занято ? п.картинкаЗаменяю : п.картинкаЗаменитьФайл}
          </button>
        </div>
      )}

      {поля.length === 0 && <div className="block-panel-empty">{п.блокБезСвойств}</div>}

      {поля.map((поле) => (
        <label className={поле.вид === 'флажок' ? 'block-panel-field block-panel-flag' : 'block-panel-field'} key={поле.имя}>
          <span>{поле.подпись}</span>
          {рисовать(поле)}
          {беды[поле.имя] !== undefined && <span className="block-panel-bad">{беды[поле.имя]}</span>}
        </label>
      ))}
    </div>
  );

  function рисовать(поле: ПолеБлока) {
    if (поле.вид === 'флажок') return флажок(поле);
    if (поле.вид === 'ссылкаВидео') return ссылка(поле);
    if (поле.вид === 'длительность') return длительность(поле);
    if (поле.вид === 'строка' || поле.вид === 'дата') return строка(поле);

    return выбор(поле);
  }

  /** Выбор из заготовок: панель после него закрывается, как и раньше, — выбирать больше нечего. */
  function выбор(поле: ПолеБлока) {
    const записано = значениеСвойства(узел.текст, поле.имя);
    const значения = поле.значения ?? {};

    return (
      <select
        value={записано ?? ''}
        onChange={(event) => {
          записать(поле.имя, event.target.value);
          props.onClose();
        }}
      >
        {записано === null && <option value="">—</option>}
        {записано !== null && значения[записано] === undefined && (
          <option value={записано}>{п.блокНеизвестен.split('{значение}').join(записано)}</option>
        )}
        {Object.entries(значения).map(([значение, подпись]) => (
          <option key={значение} value={значение}>{подпись}</option>
        ))}
      </select>
    );
  }

  /**
   * Признак тега (`muted`, `loop`): стоит — включён. Записывается сразу по нажатию — тут нечего
   * дописывать, — и панель остаётся открытой: рядом второй флажок и название.
   */
  function флажок(поле: ПолеБлока) {
    return (
      <input
        type="checkbox"
        checked={значениеСвойства(узел.текст, поле.имя) === 'true'}
        onChange={(event) => {
          тронуто.current[поле.имя] = true;
          записать(поле.имя, event.target.checked ? 'true' : '');
        }}
      />
    );
  }

  /**
   * Замена файла блока. Границы тега и имя файла после неё берутся у самой замены: импорт выше
   * стал другой длины, и старые границы указывали бы мимо тега. Панель на время заперта.
   */
  async function заменитьФайл(file: File): Promise<void> {
    if (props.файл === undefined || занято) return;
    setЗанято(true);
    try {
      const итог = await props.файл.заменить(file, узелРеф.current, props.onСвояПравка);
      if (!жив.current || итог === null) return;
      узелРеф.current = итог.узел;
      setУзел(итог.узел);
      setИмяФайла(итог.имяФайла);
    } finally {
      if (жив.current) setЗанято(false);
    }
  }

  /**
   * Обычное текстовое поле. Записывается по уходу из поля и по Enter, а не на каждую букву:
   * запись буквами клала бы в отмену по шагу на знак и мешала бы дописывать слово.
   */
  function строка(поле: ПолеБлока) {
    const датой = поле.вид === 'дата' && датаПонятна(черновики[поле.имя] ?? '');

    return (
      <input
        type={датой ? 'date' : 'text'}
        value={черновики[поле.имя] ?? ''}
        placeholder={поле.подсказка}
        onChange={(event) => правка(поле.имя, event.target.value)}
        onBlur={() => применить(поле)}
        onKeyDown={(event) => {
          if (event.key === 'Enter') применить(поле);
        }}
      />
    );
  }

  /**
   * Ссылка на видео. В статье лежит только номер — договор компонента сайта; человеку показывается
   * собранная из него ссылка. Непонятная ссылка объясняется рядом и статью не трогает: введённое
   * остаётся в поле, и человеку есть что править.
   */
  function ссылка(поле: ПолеБлока) {
    const уход = (): void => {
      // Поля, которого человек не трогал, уход не касается вовсе: иначе один взгляд на свойства
      // помечал бы его правленым, и следующий уход записал бы его уже по-настоящему.
      if (тронуто.current[поле.имя] !== true) return;

      const итог = применить(поле);
      if (итог !== 'записано' && итог !== 'нечегоМенять') return;

      // Ссылку показываем в одном виде независимо от того, как её вставили: иначе человек
      // не понимает, приняла программа его ввод или нет.
      const номер = значениеСвойства(узелРеф.current.текст, поле.имя) ?? '';
      правка(поле.имя, ссылкаВидео(номер));

      // При вставке спрашивать больше нечего: ссылка принята, и панель уходит сама.
      if (props.приВставке === true && номер !== '') props.onClose();
    };

    return (
      <input
        type="text"
        value={черновики[поле.имя] ?? ''}
        placeholder={поле.подсказка}
        onChange={(event) => правка(поле.имя, event.target.value)}
        onBlur={уход}
        onKeyDown={(event) => {
          if (event.key === 'Enter') уход();
        }}
      />
    );
  }

  /**
   * Длительность минутами и секундами. В статье лежит число секунд — договор компонента сайта.
   * Старую запись `PT5M30S` панель читает и показывает, но сама не переписывает: пока человек
   * её не тронул, в статье остаётся ровно то, что он туда положил.
   */
  function длительность(поле: ПолеБлока) {
    const поляРядом = (ключ: string, подпись: string) => (
      <span className="block-panel-pair" key={ключ}>
        <input
          type="text"
          inputMode="numeric"
          value={черновики[ключ] ?? ''}
          onChange={(event) => правка(ключ, event.target.value, поле.имя)}
          onBlur={() => применить(поле)}
          onKeyDown={(event) => {
            if (event.key === 'Enter') применить(поле);
          }}
        />
        <span>{подпись}</span>
      </span>
    );

    return (
      <span className="block-panel-duration">
        {поляРядом(`${поле.имя}:мин`, п.блокМинуты)}
        {поляРядом(`${поле.имя}:сек`, п.блокСекунды)}
      </span>
    );
  }

  /** Уход из поля: что записать, решает `чтоЗаписать`; нетронутое поле не пишется вовсе. */
  function применить(поле: ПолеБлока): Итог {
    const решение = чтоЗаписать(поле, черновики, (ключ) => тронуто.current[ключ] === true, п);
    if (решение.вид === 'нечего') return 'нечегоМенять';

    if (решение.вид === 'беда') {
      сказать(поле.имя, решение.беда);
      return 'знак';
    }

    return записать(поле.имя, решение.значение);
  }

  function правка(ключ: string, значение: string, поле = ключ): void {
    setЧерновики((было) => ({...было, [ключ]: значение}));
    тронуто.current[поле] = true;
    сказать(поле, undefined);
  }

  function сказать(поле: string, беда: string | undefined): void {
    setБеды((было) => {
      if (беда === undefined) {
        if (было[поле] === undefined) return было;
        const стало = {...было};
        delete стало[поле];
        return стало;
      }

      return {...было, [поле]: беда};
    });
  }

  /**
   * Запись одного свойства в статью. Незнакомые свойства и их порядок сохраняет `сменаСвойства`;
   * здесь стережётся только одно: не писать поверх текста, который под панелью уже другой.
   */
  function записать(имя: string, значение: string): Итог {
    const текущий = узелРеф.current;
    const вФайле = props.view.state.sliceDoc(текущий.from, текущий.to);

    // Позиция узла устарела: текст под панелью уже другой, и правка легла бы не туда.
    if (вФайле !== текущий.текст) {
      props.onClose();
      return 'устарело';
    }

    // Пустого свойства, которого в теге и не было, программа не заводит: пустой `title=""`
    // ничем не лучше отсутствующего, а тег от него становится длиннее и мутнее.
    if (значение === '' && значениеСвойства(текущий.текст, имя) === null) {
      сказать(имя, undefined);
      return 'нечегоМенять';
    }

    const новый = сменаСвойства(текущий.текст, имя, значение);
    if (новый === null) {
      сказать(имя, п.блокЗначениеСоЗнаком);
      return 'знак';
    }

    сказать(имя, undefined);
    if (новый === текущий.текст) return 'нечегоМенять';

    props.onСвояПравка();
    props.view.dispatch({changes: {from: текущий.from, to: текущий.to, insert: новый}});
    // Живое значение обновляется сразу, а не следующим отрисовыванием: правка второго поля
    // приходит раньше него и легла бы по старым границам тега.
    const стало = {текст: новый, from: текущий.from, to: текущий.from + новый.length};
    узелРеф.current = стало;
    setУзел(стало);

    return 'записано';
  }
}

function место(left: number): number {
  return Math.max(8, Math.min(left, window.innerWidth - 280));
}

/** Панель целиком на экране: не влезла под блоком — поднимается, но выше края экрана не уходит. */
function поВертикали(top: number, высота: number): number {
  if (высота === 0) return top;

  return Math.max(8, Math.min(top, window.innerHeight - высота - 8));
}
