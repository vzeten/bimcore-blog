// Что именно программа дописывает в статью, когда человек выбрал товар. Чистое правило без сети
// и без диска: адрес уже уложенной картинки приходит готовым, а на выходе — правки текста.
//
// Правок ровно две, и делаются они одной транзакцией: строка импорта картинки и сам тег карточки.
// Порознь их делать нельзя — тег без импорта роняет сборку сайта, импорт без тега оставляет
// в статье кусок кода ни к чему.
import {вставкаБлока} from '../../core/jsxBlocks';
import {ОПАСНЫЕ_ЗНАКИ, ВЫРАЖЕНИЕ, импортСтатьи} from '../../core/jsxTag.mjs';
import {СВОЙСТВА} from '../livePreview/productCard';
import type {Selection} from '../../core/commands';

/** Товар, каким его отдаёт каталог магазина. Названия и категория — по языкам, без подмены. */
export interface Товар {
  id: string;
  названия: Record<string, string>;
  адрес: string;
  картинка: string;
  категория: Record<string, string>;
  sku: string;
}

export interface Правка {
  from: number;
  to: number;
  insert: string;
}

/** Уже есть карточка: имя переменной картинки в статье одно, и второй такой же импорт её сломает. */
export function карточкаУжеЕсть(текст: string): boolean {
  return импортСтатьи(текст, ВЫРАЖЕНИЕ.имя) !== null;
}

/** Название товара на языке статьи. Пусто — человек вводит сам: подменять чужим языком нельзя. */
export function названиеТовара(товар: Товар, локаль: string | null): string {
  return (локаль === null ? '' : товар.названия[локаль] ?? '').trim();
}

/** Значение, которое нельзя записать в тег: после кавычки или угловой скобки он перестанет читаться. */
export function значениеГодно(значение: string): boolean {
  return !ОПАСНЫЕ_ЗНАКИ.test(значение);
}

/**
 * Тег карточки записывается столбиком — так записаны все карточки товара в статьях сайта, и так
 * их читает разбор (`jsxTag.mjs`). Одной строкой этот тег вышел бы длиной в четверть экрана.
 *
 * Пустое свойство не пишется вовсе: сайт подставляет свои умолчания сам, а пустая строка в теге
 * обещала бы человеку значение, которого он не вводил.
 */
export function тегКарточки(свойства: [string, string][]): string {
  const строки = свойства
    .filter(([, значение]) => значение !== '')
    .map(([имя, значение]) => `  ${имя}="${значение}"`);

  const картинка = `  ${СВОЙСТВА.картинка}={${ВЫРАЖЕНИЕ.имя}}`;
  return [`<${ВЫРАЖЕНИЕ.тег}`, ...строки, картинка, '/>'].join('\n');
}

/**
 * Полная вставка карточки: строка импорта в самое начало текста и тег на месте курсора.
 * Отступы вокруг тега ставит то же правило, что и у прочих блоков (`вставкаБлока`), — второго
 * правила отступов в программе не заводится.
 *
 * `null` — вставлять нельзя: карточка в статье уже есть либо в значении есть знак, после
 * которого программа перестала бы читать собственный тег. Статья при этом не меняется.
 */
export function вставкаКарточки(вход: {
  текст: string;
  at: Selection;
  товар: Товар;
  название: string;
  описание: string;
  локаль: string | null;
  src: string;
  кнопки: Record<string, string>;
}): {правки: Правка[]; курсор: number} | null {
  const {текст, товар, название, описание, локаль} = вход;
  if (карточкаУжеЕсть(текст) || название.trim() === '') return null;

  const надзаголовок = локаль === null ? '' : (товар.категория[локаль] ?? '').trim();
  const свойства: [string, string][] = [
    [СВОЙСТВА.название, название.trim()],
    [СВОЙСТВА.надзаголовок, надзаголовок],
    [СВОЙСТВА.описание, описание.trim()],
    [СВОЙСТВА.подписьКартинки, название.trim()],
    [СВОЙСТВА.адресТовара, товар.адрес],
    [СВОЙСТВА.кнопкаПокупки, вход.кнопки[СВОЙСТВА.кнопкаПокупки] ?? ''],
    [СВОЙСТВА.кнопкаМагазина, вход.кнопки[СВОЙСТВА.кнопкаМагазина] ?? ''],
    [СВОЙСТВА.кодТовара, товар.id],
    [СВОЙСТВА.артикул, товар.sku],
  ];
  if (свойства.some(([, значение]) => !значениеГодно(значение)) || !значениеГодно(вход.src)) return null;

  const импорт = `import ${ВЫРАЖЕНИЕ.имя} from '${вход.src}';\n\n`;
  const блок = вставкаБлока(текст, вход.at, тегКарточки(свойства));

  return {
    правки: [
      {from: 0, to: 0, insert: импорт},
      {from: блок.from, to: блок.to, insert: блок.insert},
    ],
    курсор: импорт.length + блок.from + (блок.caret ?? блок.insert.length),
  };
}
