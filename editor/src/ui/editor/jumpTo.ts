// «Показать ссылку» / «Показать место» из причины отказа публикации (решения владельца 2026-09-18,
// п.5а, и 2026-09-19): текст прокручивается к строке тела, где быстрая проверка нашла беду, и найденное
// выделяется целиком, если известно, где в строке оно начинается и сколько занимает.
//
// Отдельный маленький канал, а не свойство через всё окно: кнопка живёт в шапке, а редактор —
// глубоко в зоне статьи, и тянуть переход через окно значило бы переписывать его ради одного
// нажатия. Переход запоминается до той поры, пока его не возьмёт редактор НУЖНОЙ статьи: если она
// ещё не открыта, её редактор возьмёт переход при создании.

/** Куда перейти: строка тела с единицы и, если известно, начало в строке и длина найденного. */
export interface Место {
  строка: number;
  столбец?: number;
  длина?: number;
}

/** Ждущий переход: статья и место. Один на программу — новое нажатие заменяет старое. */
let ждёт: ({путь: string} & Место) | null = null;
const слушатели = new Set<() => void>();

/** Попросить редактор статьи `путь` показать место: строку тела и, если известно, найденное в ней. */
export function перейтиКСтроке(путь: string, строка: number, столбец?: number, длина?: number): void {
  ждёт = {путь, строка, столбец, длина};
  for (const слушатель of слушатели) слушатель();
}

/** Забрать переход для этой статьи, если он ждёт её. Взятый переход второй раз не отдаётся. */
export function взятьПереход(путь: string): Место | null {
  if (ждёт === null || ждёт.путь !== путь) return null;
  const {строка, столбец, длина} = ждёт;
  ждёт = null;
  return {строка, столбец, длина};
}

/**
 * Выделение для места в документе из строк: начало и конец. Столбец и длина неизвестны — курсор в
 * начале строки; выделение не выходит за конец документа.
 */
export function выделениеМеста(место: Место, строки: {lines: number; length: number; line: (n: number) => {from: number}}): {anchor: number; head: number} {
  const начало = строки.line(Math.min(Math.max(1, место.строка), строки.lines)).from;
  if (typeof место.столбец !== 'number' || typeof место.длина !== 'number' || место.длина <= 0) return {anchor: начало, head: начало};
  const от = Math.min(начало + место.столбец, строки.length);
  return {anchor: от, head: Math.min(от + место.длина, строки.length)};
}

/** Слушать новые просьбы о переходе. Возвращает отписку. */
export function слушатьПереход(слушатель: () => void): () => void {
  слушатели.add(слушатель);
  return () => void слушатели.delete(слушатель);
}
