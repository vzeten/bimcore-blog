// Заслон окна перед отправкой файла на сервер: слишком тяжёлая анимация дальше выбора не идёт.
//
// Заведён отдельным местом, потому что сторожит обе двери сразу — вставку новой картинки
// и замену существующей — и стоит в них раньше всего остального: раньше чтения файла, раньше
// определения породы и раньше первого запроса (SPEC 4.9: `images.ts` иначе перерастает предел).

import type {Settings} from '../types';
import {НАЧАЛЬНЫХ_БАЙТ, похожеНаГиф, типКартинки} from '../../core/imageType.mjs';
import {гифПеревесил, текстОтказаГиф} from '../../core/imageWeight.mjs';

/** Предел анимации и слова отказа: и то и другое — настройки, окну они приходят готовыми. */
export interface ПравилоГифа {
  пределМегабайт: number;
  отказ: string;
}

/**
 * Правило анимации из настроек: предел и слова отказа. `null` — настройки ещё не пришли, а без
 * них не открыта и статья: класть картинку некуда, и заслону нечего сторожить.
 */
export function правилоАнимации(settings: Settings | null): ПравилоГифа | null {
  if (settings === null) return null;

  return {
    пределМегабайт: settings.картинки.пределГифМегабайт,
    отказ: settings.ошибкиСервера.гифБольшеПредела,
  };
}

/**
 * Заслон окна перед любой отправкой: слишком тяжёлая анимация дальше выбора файла не идёт.
 *
 * Нужен потому, что сервер до своих проверок не доживает. Файл едет к нему текстом внутри JSON,
 * и стосемидесятимегабайтный GIF превращается в запрос на четверть гигабайта — тело такого
 * размера сервер обрывает раньше, чем успевает посмотреть байты, а человек видит «сервер
 * не отвечает» вместо понятного отказа (наблюдение владельца 2026-08-20).
 *
 * Читается только начало файла: породу выдаёт сигнатура, а вес берётся у самой файловой записи,
 * без чтения содержимого. Целиком такой файл не читается вовсе — ни в память, ни в текст.
 *
 * `null` — заслон пропускает: это не GIF либо он в пределе. Слово сервера при этом не отменяется,
 * он остаётся вторым, независимым заслоном и смотрит все байты.
 */
export async function отказТяжёлогоГифа(file: File, правило: ПравилоГифа | null): Promise<string | null> {
  if (правило === null) return null;

  const начало = new Uint8Array(await file.slice(0, НАЧАЛЬНЫХ_БАЙТ).arrayBuffer());
  if (!похожеНаГиф(начало)) return null;
  if (!гифПеревесил('gif', file.size, правило.пределМегабайт)) return null;

  return текстОтказаГиф(правило.отказ, правило.пределМегабайт);
}

/**
 * Какого рода выбранный файл — по его содержимому, тем же правилом, что и на сервере.
 * `null` — это не картинка статьи. Тип от браузера для этого не годится: он взят из имени файла,
 * а имя лжёт (JPEG в файле `.png`), и по нему окно выбрало бы не ту дорогу замены и показало бы
 * человеку неверный формат в вопросе о смене.
 */
export async function породаКартинки(file: File): Promise<string | null> {
  return типКартинки(new Uint8Array(await file.arrayBuffer()));
}
