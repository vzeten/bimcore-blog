// Вставка карточки товара: правило (что дописывается в статью) и запросы к своему серверу.
//
// Ecwid спрашивает сервер, токен в окно не уезжает. Картинка едет в статью той же защищённой
// дорогой, что и файл человека, — карантин, укладка рядом со статьёй, и только потом текст.
// Правок текста две, и делаются они одной транзакцией: тег без импорта роняет сборку сайта,
// импорт без тега оставляет в статье кусок кода ни к чему.
import type {EditorView} from '@codemirror/view';
import {вставкаБлока, сборкаТега} from '../../core/jsxBlocks';
import {ОПАСНЫЕ_ЗНАКИ, ВЫРАЖЕНИЕ, импортСтатьи} from '../../core/jsxTag.mjs';
import {местоИмпорта} from '../../core/videoFile.mjs';
import {requestJson} from '../api';
import {label} from '../labels';
import {забратьОбратно, уложитьПодготовленную} from './images';
import {СВОЙСТВА} from '../livePreview/productCard';
import type {Selection} from '../../core/commands';

/** Товар, каким его отдаёт каталог магазина. Названия и категория — по языкам, без подмены. */
export interface Товар {
  id: string;
  названия: Record<string, string>;
  адрес: string;
  картинка: string;
  категория: Record<string, string>;
  sku: string;
}

/** Уже есть карточка: имя переменной картинки в статье одно, и второй такой же импорт её сломает. */
export function карточкаУжеЕсть(текст: string): boolean {
  return импортСтатьи(текст, ВЫРАЖЕНИЕ.имя) !== null;
}

/** Название товара на языке статьи. Пусто — человек вводит сам: подменять чужим языком нельзя. */
export function названиеТовара(товар: Товар, локаль: string | null): string {
  return (локаль === null ? '' : товар.названия[локаль] ?? '').trim();
}

/** Значение, после которого программа перестанет читать собственный тег. */
export function значениеГодно(значение: string): boolean {
  return !ОПАСНЫЕ_ЗНАКИ.test(значение);
}

export interface Правка {
  from: number;
  to: number;
  insert: string;
}

/**
 * Строка импорта картинки у начала текста и тег карточки на месте курсора.
 *
 * Импорт встаёт тем же правилом, что импорт ролика (`местоИмпорта`): под уже стоящими импортами,
 * а не в самое начало. Импорт ролика показ прячет вместе с пустой строкой под ним, и правку внутрь
 * скрытого куска поверхность редактора отбрасывает целиком — карточка тогда не вставлялась вовсе.
 * Импорт не уходит ниже тега: курсор у самого начала статьи даёт одну правку — импорт и тег подряд.
 *
 * Тег пишется столбиком — так записаны все карточки товара в статьях сайта и так их читает разбор
 * (`jsxTag.mjs`); одной строкой он вышел бы длиной в четверть экрана. Отступы вокруг ставит общее
 * правило блоков, второго правила отступов не заводится. Пустое свойство не пишется вовсе:
 * умолчания подставит сам компонент сайта.
 *
 * `null` — вставлять нельзя: карточка в статье уже есть, нет названия либо в значении знак, после
 * которого тег перестанет читаться. Статья при этом не меняется.
 */
export function вставкаКарточки(вход: {
  текст: string;
  at: Selection;
  товар: Товар;
  название: string;
  описание: string;
  локаль: string | null;
  src: string;
  кнопки: Record<string, string>;
}): {правки: Правка[]; курсор: number} | null {
  const {текст, товар, название, локаль} = вход;
  if (карточкаУжеЕсть(текст) || название.trim() === '') return null;

  const свойства: [string, string][] = [
    [СВОЙСТВА.название, название.trim()],
    [СВОЙСТВА.надзаголовок, локаль === null ? '' : (товар.категория[локаль] ?? '').trim()],
    [СВОЙСТВА.описание, вход.описание.trim()],
    [СВОЙСТВА.подписьКартинки, название.trim()],
    [СВОЙСТВА.адресТовара, товар.адрес],
    [СВОЙСТВА.кнопкаПокупки, вход.кнопки[СВОЙСТВА.кнопкаПокупки] ?? ''],
    [СВОЙСТВА.кнопкаМагазина, вход.кнопки[СВОЙСТВА.кнопкаМагазина] ?? ''],
    [СВОЙСТВА.кодТовара, товар.id],
    [СВОЙСТВА.артикул, товар.sku],
  ];
  if (свойства.some(([, значение]) => !значениеГодно(значение)) || !значениеГодно(вход.src)) return null;

  // Тег собирает общий сборщик программы: второго сборщика JSX в ней не заводится.
  const тег = сборкаТега({
    имя: ВЫРАЖЕНИЕ.тег,
    свойства: [
      ...свойства.filter(([, значение]) => значение !== '').map(([имя, значение]) => ({имя, значение})),
      {имя: СВОЙСТВА.картинка, значение: ВЫРАЖЕНИЕ.имя, выражение: true},
    ],
  }, true);
  const импорт = `import ${ВЫРАЖЕНИЕ.имя} from '${вход.src}';\n\n`;
  const блок = вставкаБлока(текст, вход.at, тег);
  const место = местоИмпорта(текст) as number;
  const курсор = импорт.length + блок.from + (блок.caret ?? блок.insert.length);

  if (место >= блок.from) return {правки: [{from: блок.from, to: блок.to, insert: импорт + блок.insert}], курсор};
  return {правки: [{from: место, to: место, insert: импорт}, {from: блок.from, to: блок.to, insert: блок.insert}], курсор};
}

/** Каталог магазина. Отказ сервера доходит словами: вставлять товар нечего. */
export async function каталогТоваров(): Promise<Товар[]> {
  const ответ = await requestJson<{товары?: Товар[]}>('/api/products');
  return ответ.товары ?? [];
}


/**
 * Вставка карточки выбранного товара. `false` — вставки не было, и это не ошибка: окно сменилось,
 * пока картинка ехала, и уже уложенный файл забран обратно. Отказ правила после укладки забирает
 * файл тем же способом: иначе он уехал бы в публикацию картинкой, которой нет в статье.
 */
export async function вставитьТовар(вход: {
  article: string;
  view: EditorView;
  товар: Товар;
  название: string;
  описание: string;
  локаль: string | null;
  кнопки: Record<string, string>;
  актуально: () => boolean;
}): Promise<boolean> {
  const {article, view} = вход;
  if (карточкаУжеЕсть(view.state.doc.toString())) throw new Error(label('карточкаУжеЕсть'));

  const тоЖеОкно = (): boolean => вход.актуально() && view.dom.isConnected;
  const готово = await requestJson<{жетон?: string}>('/api/product/image', {
    method: 'POST',
    headers: {'Content-Type': 'application/json'},
    body: JSON.stringify({article, id: вход.товар.id}),
  });
  if (!готово.жетон) throw new Error(label('ошибкаКартинки'));
  if (!тоЖеОкно()) return false;

  // Укладка — общая с обычной вставкой картинки: своей копии этого шага здесь не заводится.
  const уложено = await уложитьПодготовленную(article, готово.жетон, тоЖеОкно);
  if (уложено === null) return false;

  // С этого места картинка уже лежит рядом со статьёй. Любой отказ дальше — отказ правила,
  // правка, которую не пропустила поверхность, или исключение при самой правке — обязан забрать
  // её обратно: иначе файл остался бы в папке статьи бесхозным и уехал бы в публикацию
  // картинкой, которой нет в статье (наблюдение владельца 2026-09-07).
  try {
    if (!вписатьКарточку(вход, уложено.src)) throw new Error(label('карточкаНеСобралась'));
  } catch (беда) {
    await забратьОбратно(article, уложено.src);
    throw беда;
  }
  view.focus();
  return true;
}

/**
 * Правка текста уже уложенной картинкой. `false` — карточка в текст не легла: правило вставки
 * отказало либо поверхность редактора не пропустила правку (тот же заслон, что у ролика).
 */
function вписатьКарточку(вход: {
  view: EditorView;
  товар: Товар;
  название: string;
  описание: string;
  локаль: string | null;
  кнопки: Record<string, string>;
}, src: string): boolean {
  const {view} = вход;
  const вставка = вставкаКарточки({
    текст: view.state.doc.toString(),
    at: {from: view.state.selection.main.from, to: view.state.selection.main.to},
    товар: вход.товар,
    название: вход.название,
    описание: вход.описание,
    локаль: вход.локаль,
    src,
    кнопки: вход.кнопки,
  });
  if (вставка === null) return false;

  const было = view.state.doc.toString();
  view.dispatch({changes: вставка.правки, selection: {anchor: вставка.курсор}, scrollIntoView: true});
  return view.state.doc.toString() !== было;
}
