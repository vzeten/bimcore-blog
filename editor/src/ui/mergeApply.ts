// Что окно делает с ответом автосохранения. Вынесено из окна отдельным правилом: автосохранение
// перестало быть односторонним, и разбор ответа — это уже правило, а не проводка (SPEC 4.9).
//
// Сервер перед каждой записью черновика сверяет файл с диском. Поэтому в ответе может прийти:
// сведённый с внешней правкой текст, новое содержимое файла с его отпечатком либо отложенное
// расхождение. Не подхвати окно это — человек продолжал бы работу от базы, которой на диске нет.

import type {Dispatch, MutableRefObject, SetStateAction} from 'react';
import type {Article, Пара, Спор} from './types';

interface ОтветАвтосохранения {
  path?: string;
  сведено?: Пара | null;
  файл?: Пара;
  отпечаток?: string;
  спор?: Спор | null;
}

export function makeОтветАвтосохранения(deps: {
  /** Какая статья открыта сейчас: ответ по прошлой статье не должен трогать новую. */
  статьяСейчас: MutableRefObject<string | null>;
  setArticle: Dispatch<SetStateAction<Article | null>>;
  /** Положить пару в окно с явной базой сравнения — ею становится новое содержимое файла. */
  положитьПару: (пара: Пара, база?: Пара) => void;
}) {
  return (сырой: unknown): void => {
    const ответ = сырой as ОтветАвтосохранения | null;
    // Ответ без пути — от старой ручки или не про статью: применять его вслепую нельзя.
    if (!ответ?.path || ответ.path !== deps.статьяСейчас.current) return;

    // Расхождение: панель со сторонами, и ни одной подстановки в текст. Выбирает человек.
    if (ответ.спор) {
      const спор = ответ.спор;
      deps.setArticle((было) => (было ? {...было, спор} : было));
      return;
    }

    const файл = ответ.файл;
    if (!файл || typeof ответ.отпечаток !== 'string') return;

    // База окна сдвигается на то, что лежит в файле сейчас: от неё считаются и признак
    // несохранённого, и отпечаток следующей правки, и цепочка слоёв цвета.
    deps.setArticle((было) => (было
      ? {...было, спор: null, отпечаток: ответ.отпечаток ?? было.отпечаток,
        body: файл.body, телоФайла: файл.body, frontmatterRaw: файл.frontmatterRaw}
      : было));

    // Текст в окне меняем ТОЛЬКО когда сервер действительно свёл стороны: без этого подстановка
    // дёргала бы редактор на каждом обычном автосохранении.
    if (ответ.сведено) deps.положитьПару(ответ.сведено, файл);
  };
}
