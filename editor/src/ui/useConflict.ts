// Расхождение с файлом: ответы человека по спорным местам и их отправка.
//
// Выбора «весь черновик или весь файл» здесь нет и быть не может: непересекающиеся правки сводит
// сервер, а человеку остаются только пересечения. Программа сама не решает ни одного из них.

import {useState} from 'react';
import type {Dispatch, SetStateAction} from 'react';
import {решитьСпор} from './conflictActions';
import type {ОтветыСпора} from './zones/ConflictPanel';
import type {Article, Пара} from './types';

export type {ОтветыСпора};

export function useConflict(deps: {
  article: Article | null;
  /** Та же статья и тот же заход в неё: поздний ответ чужого окна ничего не меняет. */
  актуально: (путь: string, заход: number) => boolean;
  setArticle: Dispatch<SetStateAction<Article | null>>;
  /** Положить решённую пару в окно: текст, свойства и признак несохранённого. */
  положитьПару: (пара: Пара) => void;
  setОшибка: (текст: string | null) => void;
  сПричиной: (ключ: string, причина: string) => string;
}) {
  const [ответы, setОтветы] = useState<ОтветыСпора>({});
  const [идёт, setИдёт] = useState(false);

  const ответить = (ключ: string, сторона: 'мои' | 'внешние'): void => {
    setОтветы((было) => ({...было, [ключ]: сторона}));
  };

  /**
   * Отправить ответы. Сервер собирает решённую пару и кладёт её в черновик этой версии с базой —
   * той самой внешней версией, про которую человек и отвечал. Файл статьи при этом не пишется:
   * настоящая запись идёт обычной кнопкой «Сохранить» и ещё раз сверяется с диском.
   */
  const применить = async (): Promise<void> => {
    const article = deps.article;
    if (!article || article.спор === null || идёт) return;

    const путь = article.path;
    const заход = article.заход ?? 0;
    const внешние = article.спор.внешние;
    const список = Object.entries(ответы).map(([ключ, сторона]) => {
      const [место, номер] = ключ.split('|');
      return {место, номер: Number(номер), сторона};
    });

    setИдёт(true);
    await решитьСпор({path: путь, ответы: список}, {
      ok: (ответ) => {
        // Пока запрос шёл, человек мог уйти в другую статью или открыть эту заново: на диске всё
        // сделано, а окно уже про другое, и трогать его нельзя.
        if (!deps.актуально(путь, заход) || !ответ?.решено) return;
        setОтветы({});
        deps.setОшибка(null);
        // База окна сдвигается на внешнюю версию: именно она лежит в файле, и от неё теперь
        // считаются и признак несохранённого, и следующее сведение.
        deps.setArticle((было) => (было
          ? {
            ...было,
            спор: null,
            отпечаток: ответ.отпечаток ?? было.отпечаток,
            body: внешние?.body ?? было.body,
            телоФайла: внешние?.body ?? было.телоФайла,
            frontmatterRaw: внешние?.frontmatterRaw ?? было.frontmatterRaw,
          }
          : было));
        deps.положитьПару(ответ.решено);
      },
      fail: (причина) => deps.setОшибка(deps.сПричиной('ошибкаСохранения', причина)),
    });
    setИдёт(false);
  };

  return {ответы, идёт, ответить, применить};
}
