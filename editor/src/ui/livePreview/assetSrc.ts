// Адрес картинки статьи для окна: одно место, где собирается запрос к ручке отдачи файла.
//
// Собирают его двое — показ картинки статьи и карточка товара. Разойдись они, вторая просила бы
// у сервера не тот файл, и человек видел бы в карточке пустое место при целой картинке на диске.
// Токен замены нужен только показу картинки: без него браузер отдал бы прежние байты из кэша.

export function адресКартинки(article: string, src: string, версия = ''): string {
  const метка = версия === '' ? '' : `&v=${encodeURIComponent(версия)}`;

  return `/api/asset?article=${encodeURIComponent(article)}&src=${encodeURIComponent(src)}${метка}`;
}
