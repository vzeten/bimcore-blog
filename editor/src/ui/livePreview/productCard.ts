// Карточка товара показана тем же видом, каким её увидит читатель: картинка, надзаголовок,
// название, описание и две кнопки на своих местах (`src/components/ProductCard.jsx`).
//
// Цены в окне нет вовсе. Её знает только сборка сайта: плагин `ecwid-prices` подставляет её по
// коду товара одним запросом на весь каталог. Нарисованное здесь число человек принял бы за
// правду, а оно было бы выдумкой окна.
//
// Надписи кнопок показываются ровно те, что записаны в теге. Не записаны — их ставит компонент
// сайта своим умолчанием, и второе такое же умолчание в окне однажды разошлось бы с ним молча
// (SPEC 4.3). Пустая надпись оставляет кнопку на её месте: место кнопки от этого не пропадает.
//
// Имена свойств названы поимённо: это имена чужого формата, заданные компонентом сайта, а не
// настройки (SPEC 4.4).
import {адресИмпорта} from '../../core/jsxTag.mjs';
import {адресКартинки} from './assetSrc';
import type {Свойство} from '../../core/jsxBlocks';

const СВОЙСТВА = {
  название: 'name',
  надзаголовок: 'eyebrow',
  описание: 'description',
  картинка: 'image',
  подписьКартинки: 'imageAlt',
  кнопкаПокупки: 'buyLabel',
  кнопкаМагазина: 'shopLabel',
};

export interface КарточкаТовара {
  название: string;
  надзаголовок: string;
  описание: string;
  подписьКартинки: string;
  /** Имя импорта: за ним в самой статье стоит адрес файла картинки. */
  переменнаяКартинки: string;
  /** Надписи двух кнопок так, как они записаны в теге. Пустая — надпись ставит сайт. */
  кнопки: string[];
}

/**
 * Карточка ли это. Признак — картинка, заданная импортом статьи: другого выражения программа не
 * понимает вовсе, а блок без картинки сайт не показывает и сам (`if (!name || !image) return null`),
 * поэтому обещать человеку вид карточки там было бы неправдой.
 */
export function карточкаТовара(свойства: Свойство[]): КарточкаТовара | null {
  const картинка = свойства.find((свойство) => свойство.имя === СВОЙСТВА.картинка && свойство.выражение);
  if (картинка === undefined) return null;

  const значение = (имя: string): string =>
    свойства.find((свойство) => свойство.имя === имя && !свойство.выражение)?.значение.trim() ?? '';

  return {
    название: значение(СВОЙСТВА.название),
    надзаголовок: значение(СВОЙСТВА.надзаголовок),
    описание: значение(СВОЙСТВА.описание),
    подписьКартинки: значение(СВОЙСТВА.подписьКартинки),
    переменнаяКартинки: картинка.значение,
    кнопки: [значение(СВОЙСТВА.кнопкаПокупки), значение(СВОЙСТВА.кнопкаМагазина)],
  };
}

/**
 * Адрес картинки карточки: имя переменной ведёт к импорту статьи, импорт — к файлу рядом с ней.
 * Не прочитан импорт или неизвестен путь статьи — адреса нет, и место картинки остаётся пустым.
 */
export function картинкаКарточки(
  текстСтатьи: string,
  путьСтатьи: string,
  переменная: string,
): string | null {
  const адрес = адресИмпорта(текстСтатьи, переменная) as string | null;
  if (адрес === null || путьСтатьи === '') return null;

  return адресКартинки(путьСтатьи, адрес);
}

/** Сам вид карточки. Пустое свойство места не занимает: сайт его тоже не покажет. */
export function видКарточки(карточка: КарточкаТовара, адрес: string | null): HTMLElement {
  const блок = document.createElement('div');
  блок.className = 'md-card';
  блок.append(место(карточка, адрес), тело(карточка));

  return блок;
}

/** Место картинки. Она грузится с диска, и не загрузилась — остаётся пустое место, а не поломка. */
function место(карточка: КарточкаТовара, адрес: string | null): HTMLElement {
  const место = document.createElement('div');
  место.className = 'md-card-media';
  if (адрес === null) return место;

  const картинка = document.createElement('img');
  картинка.alt = карточка.подписьКартинки;
  картинка.addEventListener('error', () => картинка.remove());
  картинка.src = адрес;
  место.append(картинка);

  return место;
}

function тело(карточка: КарточкаТовара): HTMLElement {
  const тело = document.createElement('div');
  тело.className = 'md-card-body';

  строка(тело, 'md-card-eyebrow', карточка.надзаголовок);
  строка(тело, 'md-card-title', карточка.название);
  строка(тело, 'md-card-desc', карточка.описание);

  const кнопки = document.createElement('div');
  кнопки.className = 'md-card-actions';
  карточка.кнопки.forEach((надпись, номер) => {
    const кнопка = document.createElement('span');
    кнопка.className = номер === 0 ? 'md-card-btn md-card-btn-main' : 'md-card-btn';
    кнопка.textContent = надпись;
    кнопки.append(кнопка);
  });
  тело.append(кнопки);

  return тело;
}

function строка(тело: HTMLElement, вид: string, текст: string): void {
  if (текст === '') return;

  const строка = document.createElement('span');
  строка.className = вид;
  строка.textContent = текст;
  тело.append(строка);
}
