// Одно правило: когда в окне видны служебные `**` жирного куска, и одна память к нему —
// куда курсор поставила сама кнопка оформления.
import {StateEffect, StateField} from '@codemirror/state';

/**
 * Кнопка оформления сообщает, куда она поставила курсор. Иначе клик человека сразу за жирным
 * куском и курсор, оставленный там же кнопкой, различить нечем: место в тексте у них одно.
 */
export const курсорПоставленКнопкой = StateEffect.define<number>();

/**
 * Место, куда курсор поставила кнопка, — пока человек его не тронул. Любая своя правка текста или
 * перемещение курсора метку снимают: дальше это уже выбор человека, а не след кнопки.
 */
export const курсорОтКнопки = StateField.define<number | null>({
  create: () => null,
  update(было, tr) {
    for (const эффект of tr.effects) if (эффект.is(курсорПоставленКнопкой)) return эффект.value;
    if (tr.docChanged || tr.selection) return null;
    return было;
  },
});

/**
 * Знаки открываются курсором или выделением ВНУТРИ куска и курсором сразу ЗА закрывающими знаками:
 * там человек их смотрит и убирает руками, и там же он ставит курсор кликом после жирного слова
 * (слово владельца 2026-09-09). Строки целиком для этого мало: кнопка «Жирный» оставляет курсор на
 * той же строке, и знаки показались бы поверх только что оформленного словосочетания.
 *
 * Единственное исключение — курсор, который кнопка сама только что поставила за закрывающие знаки:
 * оформление человек уже видит жирным, и открывать ему знаки поверх свежей правки незачем. Как
 * только курсор сдвинут или текст изменён, метка снимается и знаки открываются обычным правилом.
 */
export function знакиЖирногоВидны(
  кусок: {from: number; to: number},
  места: readonly {from: number; to: number}[],
  отКнопки: number | null = null,
): boolean {
  return места.some((место) => {
    if (место.from === место.to && место.from === кусок.to) return отКнопки !== кусок.to;
    return место.to > кусок.from && место.from < кусок.to;
  });
}
