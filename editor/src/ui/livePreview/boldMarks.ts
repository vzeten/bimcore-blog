// Одно правило: когда в окне видны служебные `**` жирного куска.

/**
 * Знаки открываются только курсором или выделением ВНУТРИ самого куска — там их правят руками.
 * Строки целиком для этого мало: кнопка «Жирный» оставляет курсор на той же строке, и знаки
 * показались бы поверх только что оформленного словосочетания. Край куска считается снаружи:
 * курсор после кнопки стоит сразу за закрывающими знаками.
 */
export function знакиЖирногоВидны(
  кусок: {from: number; to: number},
  места: readonly {from: number; to: number}[],
): boolean {
  return места.some((место) => место.to > кусок.from && место.from < кусок.to);
}
