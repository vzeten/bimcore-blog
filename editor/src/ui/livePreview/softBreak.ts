// Переносы обычного абзаца показываются как на сайте: мягкий — пробелом, жёсткий — без косой.
//
// В файле абзац живёт несколькими короткими строками, а на собранной странице читается сплошным
// текстом: markdown склеивает такие переносы пробелом. Склейка чисто зрительная: перенос
// закрывается заменой, а в файле остаётся на месте — сохранение без правок не меняет ни байта.
//
// Слой отдельный от `inline.ts` намеренно: замена, накрывающая перенос строки, объявляется только
// через состояние редактора, плагину это запрещено самим CodeMirror (SPEC 3.3).
import {Decoration, EditorView, WidgetType, type DecorationSet} from '@codemirror/view';
import {StateField, type EditorState, type Range} from '@codemirror/state';
import {границыСоветов} from '../../core/tipBlock';

// Синтаксис markdown — не настройка (SPEC 4.4): эти знаки задал не владелец, а сам формат.
// Отступ до трёх пробелов начало блока не отменяет, четыре — уже отступной код.
const ЗАГОЛОВОК = /^ {0,3}#{1,6}(\s|$)/;
const ЦИТАТА = /^ {0,3}>/;
const ПУНКТ = /^ {0,3}([-*+]|\d{1,9}[.)])(\s|$)/;
const ЛИНИЯ = /^ {0,3}([-*_])[ \t]*(\1[ \t]*){2,}$/;
const ТАБЛИЦА = /^ {0,3}\|/;
const ОТСТУПНЫЙ_КОД = /^(\x20{4}|\t)/;
/** Разметка MDX: тег компонента и строки `import`/`export` вокруг него. */
const РАЗМЕТКА_MDX = /^ {0,3}(<|import\s|export\s)/;
/** Ограда кода: три знака и больше, обратные кавычки или тильды. */
const ОГРАДА = /^ {0,3}(`{3,}|~{3,})/;
/** Подчёркивание заголовка следующей строкой: `===` под текстом делает его заголовком. */
const ПОДЧЁРК_ЗАГОЛОВКА = /^ {0,3}(=+|-+)[ \t]*$/;
/** Жёсткий перенос: два пробела или обратная косая в конце строки. Сайт рисует его переносом. */
const ЖЁСТКИЙ_ПЕРЕНОС = /( {2,}|\\)$/;
export const КАРТИНКА_В_СТРОКЕ = /!\[(?:\\.|[^\]\\])*\]\([^)\s]+\)/g;
const ОДИНОКАЯ_КАРТИНКА = new RegExp(`^${КАРТИНКА_В_СТРОКЕ.source}$`);

export function строкаТолькоКартинка(текстСтроки: string): boolean {
  return ОДИНОКАЯ_КАРТИНКА.test(текстСтроки);
}

/**
 * Переносы обычного абзаца, номера строк от нуля: мягкие склеиваются пробелом, у жёстких прячется косая.
 *
 * Чистое правило от одного текста: проверяется тестом без редактора и без DOM. Второго разборщика
 * markdown здесь не заводится — правило смотрит только на начало строки, как и уровень пункта
 * списка (`listIndent.ts`), и в спорном случае молчит: не склеить безопаснее, чем склеить чужое.
 *
 * Блоки бывают двух пород, и это единственная тонкость правила. Заголовок и горизонтальная линия
 * занимают свою строку и кончаются вместе с ней: абзац начинается прямо под ними. Список, цитата,
 * таблица, отступной код и разметка MDX тянутся до пустой строки, и их продолжение от обычного
 * текста ничем не отличается — `name="…"` внутри многострочного тега выглядит как абзац. Поэтому
 * такой блок гасит склейку до ближайшей пустой строки, а не до конца своей строки.
 */
export function переносыАбзацев(строки: string[]): {мягкие: number[]; жёсткие: number[]} {
  const код = внутриОграды(строки);
  // Служебные строки совета показаны собственным блоком, а не текстом: приклеить к ним соседний
  // абзац значило бы разорвать этот блок. Гасятся ровно границы закрытой пары `:::tip`, потому
  // что чужая строка с двоеточиями остаётся обычным текстом статьи.
  const границаСовета = границыСоветов(строки, код);
  const мягкие: number[] = [];
  const жёсткие: number[] = [];
  // Открыт ли блок, который тянется до пустой строки. Пустая строка и ограда кода его закрывают.
  let тянется = false;

  for (let i = 0; i < строки.length; i += 1) {
    if (код[i] || строки[i].trim() === '') {
      тянется = false;
      continue;
    }

    if (доПустойСтроки(строки[i])) тянется = true;
    if (тянется) continue;

    const следующая = i + 1;
    if (следующая >= строки.length || код[следующая]) continue;
    if (границаСовета.has(i) || границаСовета.has(следующая)) continue;
    // Косая прячется и перед пустой строкой: сразу после `Shift+Enter` продолжения ещё нет.
    if (строки[i].endsWith('\\') && строкаАбзаца(строки[i])) {
      жёсткие.push(i);
      continue;
    }
    if (строки[следующая].trim() === '') continue;
    if (склеить(строки[i], строки[следующая])) мягкие.push(i);
  }

  return {мягкие, жёсткие};
}

/**
 * Какие строки лежат внутри огороженного кода вместе со своими оградами.
 * Тем же ответом пользуется слой совета (`tip.ts`): пример с `:::tip` внутри кода блоком не
 * считается, и правило про ограду в программе остаётся одно.
 * Считается одним проходом сверху: закрыть ограду может только ограда того же знака и не короче,
 * поэтому по одной строке этого не видно.
 */
export function внутриОграды(строки: string[]): boolean[] {
  const внутри: boolean[] = new Array(строки.length).fill(false);
  let открыта: string | null = null;

  for (let i = 0; i < строки.length; i += 1) {
    const ограда = ОГРАДА.exec(строки[i]);

    if (открыта === null) {
      if (ограда) {
        открыта = ограда[1];
        внутри[i] = true;
      }
      continue;
    }

    внутри[i] = true;
    if (ограда && ограда[1][0] === открыта[0] && ограда[1].length >= открыта.length) открыта = null;
  }

  return внутри;
}

/** Открывает ли эта строка блок, который тянется до пустой строки, а не кончается сам собой. */
function доПустойСтроки(строка: string): boolean {
  return ПУНКТ.test(строка)
    || ЦИТАТА.test(строка)
    || ТАБЛИЦА.test(строка)
    || ОТСТУПНЫЙ_КОД.test(строка)
    || РАЗМЕТКА_MDX.test(строка);
}

/**
 * Обычная ли это строка абзаца, а не заголовок, список, таблица, цитата, картинка или MDX.
 * Экспортируется для клавиш абзаца (`surfaceKeys.ts`): что по строке не абзац, решается здесь
 * и больше нигде.
 */
export function строкаАбзаца(строка: string): boolean {
  return !ЗАГОЛОВОК.test(строка)
    && !ЛИНИЯ.test(строка)
    && !доПустойСтроки(строка)
    && !строкаТолькоКартинка(строка.trim());
}

/** Склеивается ли перенос между этими двумя соседними строками. */
function склеить(текущая: string, следующая: string): boolean {
  // Жёсткий перенос сайт показывает переносом — тут склеивать нечего.
  if (ЖЁСТКИЙ_ПЕРЕНОС.test(текущая)) return false;
  // Подчёркивание превращает строку выше в заголовок — вместе они не абзац.
  if (ПОДЧЁРК_ЗАГОЛОВКА.test(следующая)) return false;

  // Заголовок, линия, картинка и начало любого блока обрывают абзац с любой из двух сторон.
  return строкаАбзаца(текущая) && строкаАбзаца(следующая);
}

/**
 * Пробел вместо спрятанного переноса. Без него соседние слова слиплись бы в одно.
 * Все склейки одинаковы, поэтому виджет всегда равен другому и CodeMirror его переиспользует.
 */
class ПробелВместоПереноса extends WidgetType {
  eq(): boolean {
    return true;
  }

  toDOM(): HTMLElement {
    const пробел = document.createElement('span');
    пробел.className = 'md-soft-break';
    пробел.textContent = ' ';
    return пробел;
  }
}

const СКЛЕЙКА = Decoration.replace({widget: new ПробелВместоПереноса()});
const КОСАЯ_СПРЯТАНА = Decoration.replace({});

/**
 * Слой переносов абзаца. Живёт состоянием редактора, а не плагином: замена, накрывающая
 * перенос строки, меняет разбиение текста на строки, и CodeMirror обязан знать о ней заранее.
 */
export function softBreakLayer() {
  return StateField.define<DecorationSet>({
    create: (state) => построить(state),
    update: (value, tr) => (tr.docChanged ? построить(tr.state) : value),
    provide: (field) => EditorView.decorations.from(field),
  });
}

function построить(state: EditorState): DecorationSet {
  const строки: string[] = [];
  for (let номер = 1; номер <= state.doc.lines; номер += 1) строки.push(state.doc.line(номер).text);

  const list: Range<Decoration>[] = [];
  const {мягкие, жёсткие} = переносыАбзацев(строки);

  for (const индекс of мягкие) {
    // Прячется ровно перевод строки: от конца текущей строки до начала следующей.
    // Сам текст обеих строк не трогается, поэтому в файле перенос остаётся как был.
    list.push(СКЛЕЙКА.range(state.doc.line(индекс + 1).to, state.doc.line(индекс + 2).from));
  }

  for (const индекс of жёсткие) list.push(КОСАЯ_СПРЯТАНА.range(state.doc.line(индекс + 1).to - 1, state.doc.line(индекс + 1).to));

  return Decoration.set(list, true);
}
