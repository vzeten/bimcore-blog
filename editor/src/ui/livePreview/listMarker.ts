// Маркер пункта списка в окне: какой знак рисовать на каком уровне вложенности.
// Чистое правило без редактора и без DOM — его проверяет машина, а не глаз.
//
// Знаки взяты не на вкус: у `ul` сайт своего `list-style-type` не задаёт (`infima` правит только
// вложенные `ol`), поэтому маркеры рисует браузер по глубине вложенности — сплошная точка,
// пустой круг, дальше квадрат. Окно повторяет ровно этот ряд.

/** Узел синтаксического дерева в той малой части, которая здесь нужна. */
export interface Узел {
  name: string;
  parent: Узел | null;
}

const СПИСКИ = new Set(['BulletList', 'OrderedList']);

/**
 * Уровень пункта: сколько списков над ним, считая его собственный.
 * Считаются списки обеих пород: браузер тоже меняет знак от общей глубины, а не от числа
 * маркированных списков, поэтому пункт внутри нумерованного получает второй знак ряда.
 */
export function уровеньСписка(узел: Узел | null): number {
  let уровень = 0;
  for (let текущий = узел; текущий; текущий = текущий.parent) {
    if (СПИСКИ.has(текущий.name)) уровень += 1;
  }
  return уровень;
}

/** Знак маркера по уровню. Глубже третьего браузер знак не меняет — окно тоже. */
export function знакМаркера(уровень: number): string {
  if (уровень <= 1) return '•';
  if (уровень === 2) return '◦';
  return '▪';
}
