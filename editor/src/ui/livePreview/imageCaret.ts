// Курсор не встаёт в пустые карманы у одинокой картинки (слово владельца 2026-08-17).
//
// Картинка в файле — обычная строка `![подпись](адрес)`. Показ рисует её блоком, поэтому две
// позиции той же строки — перед разметкой и после неё — выглядят пустыми строчками над и под
// картинкой. Набранный там текст попадает в одну строку с картинкой; в разметке это законно
// (в живых статьях сайта есть «текст, а сразу за ним картинка»), поэтому карманы закрываются
// только там, где в строке нет ничего, кроме картинки, — там они человеку не нужны и только
// путают. В строке, где рядом с картинкой есть текст, всё остаётся как было.

import {EditorState, type Extension} from '@codemirror/state';

/** Строка целиком — одна картинка и ничего больше. */
const ОДИНОКАЯ_КАРТИНКА = /^!\[(?:\\.|[^\]\\])*\]\([^)\s]+\)$/;

/**
 * В строке нет ничего, кроме картинки. Одно правило на два поведения: у такой строки закрываются
 * карманы курсора и схлопывается лишняя высота строки (иначе вокруг картинки остаётся пустое
 * место, которого нет на сайте).
 */
export function строкаТолькоКартинка(текстСтроки: string): boolean {
  return ОДИНОКАЯ_КАРТИНКА.test(текстСтроки);
}

/**
 * Куда переставить курсор, попавший в карман одинокой картинки. `null` — оставить как есть:
 * это не карман, либо переставлять некуда (в документе нет ничего, кроме этой картинки).
 *
 * Чистое правило от текста и позиции: проверяется тестом без редактора и DOM.
 */
export function курсорМимоКартинки(текст: string, позиция: number): number | null {
  const начало = текст.lastIndexOf('\n', позиция - 1) + 1;
  const конецНайден = текст.indexOf('\n', позиция);
  const конец = конецНайден === -1 ? текст.length : конецНайден;

  // Карман — ровно граница строки. Внутри узла позиций нет: там атомарный виджет.
  if (позиция !== начало && позиция !== конец) return null;
  if (!ОДИНОКАЯ_КАРТИНКА.test(текст.slice(начало, конец))) return null;

  const естьПредыдущая = начало > 0;
  const естьСледующая = конец < текст.length;

  // Курсор над картинкой уходит в конец строки выше, под картинкой — в начало строки ниже.
  // Если соседней строки с нужной стороны нет (картинка первая или последняя), берётся другая:
  // иначе курсор остался бы в том самом кармане, который мы закрываем.
  if (позиция === начало) {
    if (естьПредыдущая) return начало - 1;
    return естьСледующая ? конец + 1 : null;
  }

  if (естьСледующая) return конец + 1;
  return естьПредыдущая ? начало - 1 : null;
}

/**
 * Расширение редактора: перед применением транзакции курсор уводится из кармана.
 *
 * Фильтр смотрит только на транзакции, которые САМИ ставят курсор (клик мышью, стрелки, Home/End):
 * при правке текста позиции пересчитываются картой изменений, и вмешиваться туда нельзя — курсор
 * уехал бы из места, где человек печатает. Выделенный диапазон тоже не трогается: он бывает нужен
 * целиком, вместе со строкой картинки.
 */
export function каретМимоКартинок(): Extension {
  return EditorState.transactionFilter.of((tr) => {
    if (tr.selection === undefined || !tr.newSelection.main.empty) return tr;

    const позиция = tr.newSelection.main.head;
    const куда = курсорМимоКартинки(tr.newDoc.toString(), позиция);
    if (куда === null) return tr;

    return [tr, {selection: {anchor: куда}, sequential: true}];
  });
}
