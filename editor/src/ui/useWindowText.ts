import {useRef, useState} from 'react';
import type {Dispatch, MutableRefObject, SetStateAction} from 'react';
import {buildFrontmatter, parseFrontmatter, порядокПолей, type Field} from './headFields';
import {nothingChanged} from '../core/articleFile.mjs';
import {isUnlisted} from '../core/frontmatterRules.mjs';
import type {Пара} from './restore';
import type {DraftPayload} from './useAutosave';
import type {Article, Root, SaveState, Settings} from './types';

/**
 * Пара «тело + шапка» в окне: обычная правка человека и подстановка целой пары (возврат к версии).
 * Вынесено из окна, чтобы правило «тело и шапка меняются вместе» лежало одним куском,
 * а окно не выходило за предел размера файла (SPEC 4.9).
 */
export function useWindowText(deps: {
  article: Article | null;
  roots: Root[];
  /** Общая картинка сайта: вписанная в статью, она показывается пустым полем. */
  общаяОбложка: string | null;
  текстСейчас: MutableRefObject<string>;
  шапкаСейчас: MutableRefObject<string>;
  автосохранение: {запланировать: (данные: DraftPayload) => void};
  setArticle: Dispatch<SetStateAction<Article | null>>;
  setFields: (fields: Field[]) => void;
  setDirty: (dirty: boolean) => void;
  setСостояние: (state: SaveState) => void;
  setКонфликтСохранения: (конфликт: boolean) => void;
}) {
  // Текст, который надо положить в редактор целиком, и номер подстановки. Номер нужен потому,
  // что подряд можно вернуть одну и ту же версию дважды: по одному тексту это не отличить.
  // Ключ окна хранится рядом: без него подстановка, сделанная в одной статье, досталась бы
  // редактору следующей — он пересоздаётся при переходе и на монтировании положил бы себе
  // чужое тело, оставив шапку и черновик своими.
  const [подстановка, setПодстановка] = useState<{текст: string; номер: number; ключ: string} | null>(null);
  const номер = useRef(0);
  const ключОкна = (): string => `${deps.article?.path ?? ''}|${deps.article?.заход ?? 0}`;

  /**
   * Правка уходит в очередь автосохранения; настоящий файл не трогается.
   * `отпечаток` передаётся, когда файл только что переписала сама программа (смена видимости):
   * состояние окна к этому мгновению ещё не перерисовано, и без него черновик уехал бы с базой
   * от прежнего файла — при следующем открытии человек получил бы ложный выбор «черновик или файл».
   */
  const вЧерновик = (
    body = deps.текстСейчас.current,
    frontmatterRaw = deps.шапкаСейчас.current,
    отпечаток?: string,
  ): void => {
    const article = deps.article;
    if (!article) return;
    deps.текстСейчас.current = body;
    deps.шапкаСейчас.current = frontmatterRaw;
    deps.автосохранение.запланировать({
      path: article.path,
      body,
      frontmatterRaw,
      отпечатокБазы: отпечаток ?? article.отпечаток,
    });
  };

  /**
   * Любая правка окна: текста или свойств. Несохранённость считается по паре «тело + шапка»
   * тем же правилом, что и на сервере: иначе возврат текста к исходному стёр бы признак
   * несохранённых свойств, и правка шапки молча потерялась бы.
   */
  const правка = (body: string, frontmatterRaw: string): void => {
    if (!deps.article) return;
    вЧерновик(body, frontmatterRaw);
    отметить({body, frontmatterRaw});
  };

  /**
   * Пересчитать признак несохранённого и надпись состояния по паре в окне — без записи.
   * Нужно там, где пара уже записана: возврат к версии пишет черновик сам, до подстановки,
   * и повторная постановка в очередь завела бы таймер, а он вернул бы надпись «Автосохранено»
   * поверх честного «Сохранено».
   */
  const отметить = (пара: Пара): void => {
    const article = deps.article;
    if (!article) return;

    const изменилось = !nothingChanged(
      {body: article.body, frontmatterRaw: article.frontmatterRaw},
      пара,
    );
    deps.setDirty(изменилось);
    // Окно снова слово в слово равно файлу — значит несохранённого нет, что бы ни говорила
    // очередь: она объявляет «есть несохранённые» на любую правку, не сравнивая с файлом.
    deps.setСостояние(изменилось ? 'естьНесохранённые' : 'сохранено');
  };

  /**
   * Положить в окно целую пару (возврат к версии или откат возврата).
   * Порядок жёсткий: сначала пара в ref и свойства, потом текст в редактор. Между двумя половинами
   * есть мгновение, и слушатель правок редактора успел бы сложить в черновик «тело версии
   * со старой шапкой» — смесь двух состояний.
   *
   * База сравнения (`article.body`, `article.frontmatterRaw`) не подменяется: это содержимое файла,
   * и по нему считаются признак несохранённого и отпечаток.
   */
  const положитьПару = (пара: Пара): void => {
    const article = deps.article;
    if (!article) return;

    deps.текстСейчас.current = пара.body;
    deps.шапкаСейчас.current = пара.frontmatterRaw;
    deps.setFields(parseFrontmatter(пара.frontmatterRaw, article.path, deps.roots, deps.общаяОбложка));
    // Видимость живёт в шапке, а кнопка читает признак окна: без обновления надпись говорила бы
    // одно, шапка другое, и следующее нажатие сделало бы не то, что человек видит.
    // Файл при этом не трогается — показывается то, что будет записано при сохранении.
    deps.setArticle((было) => (было ? {...было, скрыта: isUnlisted(пара.frontmatterRaw)} : было));
    // Прежний выбор «сохранить поверх» относился к другому содержимому окна.
    deps.setКонфликтСохранения(false);
    // Только отметка, без записи: пару уже записал возврат, до того как тронул окно.
    отметить(пара);

    номер.current += 1;
    setПодстановка({текст: пара.body, номер: номер.current, ключ: ключОкна()});
  };

  /**
   * Правка свойств: поля собираются обратно в шапку и уходят той же дорогой, что и текст.
   *
   * Образец сборки — шапка ОКНА, а не файла: нетронутые поля возвращаются из образца дословно,
   * и после возврата к версии сборка от файла выбросила бы поля, которых в нём уже нет,
   * и вернула бы выброшенные когда-то. База сравнения с файлом отвечает за другое и не меняется.
   */
  const правитьПоля = (fields: Field[], settings: Settings): void => {
    const article = deps.article;
    if (!article) return;

    deps.setFields(fields);
    const образец = deps.шапкаСейчас.current || article.frontmatterRaw;
    правка(deps.текстСейчас.current, buildFrontmatter(
      образец, fields, article.path, deps.roots,
      порядокПолей(settings, article.path) as string[],
      deps.общаяОбложка,
    ));
  };

  return {
    // Наружу уходит только подстановка своего окна: чужая молча превращается в её отсутствие.
    подстановка: подстановка !== null && подстановка.ключ === ключОкна() ? подстановка : null,
    вЧерновик,
    правка,
    правитьПоля,
    отметить,
    положитьПару,
  };
}
