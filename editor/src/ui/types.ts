import type {Layer, LayerKind} from '../core/colorize';

// Понятия, общие для всех зон окна.

/** Языковая версия статьи: свой файл, своё название, своя готовность и своя видимость. */
export interface ArticleVersion {
  path: string;
  title: string;
  скрыта: boolean;
  готовность: string | null;
  правил: string | null;
  когда: number;
}

/** Статья как одна сущность: несколько языковых версий под одним именем. */
export interface ArticleRow {
  key: string;
  kind: string;
  наСайте: boolean;
  category: string;
  section: {kind: string; path: string};
  folders: string[];
  title: string;
  titleFromOtherLocale: boolean;
  служебная: boolean;
  нетНаСайте: boolean;
  versions: Record<string, ArticleVersion>;
}

/** Автосохранённый черновик статьи, каким его отдаёт сервер. */
export interface Draft {
  когда: string;
  frontmatterRaw: string;
  body: string;
}

export interface Article {
  path: string;
  frontmatterRaw: string;
  body: string;
  published: string | null;
  /**
   * Тело файла на диске. Отличается от `body`, когда в окно подставлен черновик: цепочка слоёв
   * цвета кончается файлом, иначе незаписанная работа окрасилась бы как уже сохранённая.
   */
  телоФайла?: string;
  /**
   * Каким слоем показывать то, что записал сам человек за программой. Обычно «мои правки»,
   * но правило одно на всех: подписался именем из справочника — правка машинная.
   */
  мойСлой?: LayerKind;
  /**
   * Состояния статьи между публикацией и файлом, по одному на сеанс работы, с видом слоя
   * по автору. Приходят при открытии статьи: цвет выводится из истории, а не хранится где-то ещё.
   */
  слои?: Layer[];
  title: string;
  category: string;
  служебная: boolean;
  готовность: string | null;
  /**
   * Скрыта ли ОТКРЫТАЯ версия в опубликованной ветке. `null` — файла там нет вовсе.
   * Отдельного признака «скрыта» у статьи нет: видимость живёт в шапке и берётся из полей окна,
   * а это — то, что про неё знает сайт. Читается при открытии статьи.
   * Поле не необязательное: его отдаёт сервер всегда, и «поля нет» значило бы поломку договора,
   * а не «сказать нечего».
   */
  скрытаНаСайте: boolean | null;
  /**
   * Скрыта ли каждая существующая языковая версия по тому, что лежит на диске. По этой карте
   * шапка приглушает кнопки языков. Про открытую версию она может отставать: в окне флажок
   * уже переключён, а на диске ещё нет, поэтому свою версию шапка берёт из полей окна.
   */
  видимостьВерсий?: Record<string, boolean>;
  /** Отпечаток файла на момент открытия: по нему видно, менялся ли файл под черновиком. */
  отпечаток: string;
  черновикРешение: 'нет' | 'черновик' | 'конфликт';
  /**
   * Номер захода в статью. Нужен, чтобы повторное открытие той же статьи пересоздавало
   * редактор: иначе в спрятанной зоне остаётся текст прошлого захода и затирает внешнюю правку.
   */
  заход?: number;
  черновик: Draft | null;
  versions: Record<string, string>;
  states: Record<string, 'есть' | 'нет' | 'устарела'>;
  нетНаСайте: boolean;
  /**
   * Вышла ли статья на сайт хоть одной языковой версией. По этому признаку окно решает,
   * предлагать ли удаление: у вышедшей статьи есть публичный адрес, и убирать его без
   * переадресации нельзя. Последнее слово всё равно за сервером — он проверяет заново.
   */
  естьНаСайте?: boolean;
  /**
   * Удалось ли серверу прочитать опубликованную ветку. `false` — неизвестно, вышла ли статья,
   * и удаление не предлагается: «не знаю» здесь значит «может быть на сайте».
   */
  веткаИзвестна?: boolean;
  /** Статья живёт вне сайта (песочница): опубликованная ветка про неё ничего не решает. */
  внеСайта?: boolean;
}

/** Одна версия в ленте: имя снимка, время и автор. Имя — внутренний договор сервера и окна. */
export interface Версия {
  имя: string;
  iso: string;
  author: string;
}

/** Сеанс: подряд идущие сохранения одного автора, свёрнутые в одну отметку ленты. */
export interface Сеанс {
  author: string;
  from: string;
  to: string;
  snapshots: Версия[];
}

/** Версия, открытая на просмотр. Только чтение: правки и сохранения в этом состоянии нет. */
export interface ПросмотрВерсии {
  имя: string;
  когда: string;
  автор: string;
  frontmatterRaw: string;
  body: string;
}

/** Состояние автосохранения для шапки. */
export type SaveState = 'сохранено' | 'естьНесохранённые' | 'сохраняем' | 'автосохранено' | 'неУдалосьАвтосохранить';

export interface Button {
  группа: string;
  подпись: string;
  команда: string;
  уровень?: number;
  знак?: string;
  вид?: 'точки' | 'числа';
  столбцов?: number;
  строк?: number;
  текст?: string;
}

export interface Column {
  ключ: string;
  подпись: string;
}

export interface Root {
  локаль: string;
  род: string;
  папка: string;
  наСайте: boolean;
}

export interface Settings {
  слои: Record<string, {подпись: string; цвет: string; пояснение: string}>;
  локали: Record<string, string>;
  основнойЯзык: string;
  /** Вид времени версий. Меняется в настройках, в коде своего формата нет. */
  форматВремени: Intl.DateTimeFormatOptions;
  обязательныйЯзык: string;
  категорияСлужебной: string;
  вставки: Button[];
  призывПоРазделу: Record<string, string>;
  статусы: string[];
  подписи: Record<string, string>;
  /** Почему статья не создана: коды от сервера, слова человеку — здесь. */
  ошибкиСоздания: Record<string, string>;
  /** Почему поле шапки показано, но не правится: код причины — слова человеку. */
  полеЗаперто: Record<string, string>;
  /** `порогПеречня` — со скольких скрытых языков реестр показывает счёт вместо имён. */
  видимость: {вМеню: string; поСсылке: string; порогПеречня: number; новаяСкрыта: boolean};
  хранение: {
    файлСостояния: string;
    папкаЧерновиков: string;
    папкаСнимков: string;
    автосохранениеСек: number;
    черновикЖивётДней: number;
    снимковНаВерсию: number;
    /** Сколько сеансов истории показывать цветом. Предел показа, а не хранения. */
    слоёвИстории: number;
  };
  /** Кто есть кто: имя автора правки — вид слоя. Читается ядром при разборе истории. */
  слоиПоАвторам: Record<string, string>;
  категорииПоПути: Record<string, string>;
  категорииПоРоду: Record<string, string>;
  подписиПолей: Record<string, string>;
  названияРазделов: Record<string, string>;
  контент: Root[];
  /** Какие поля получает новая статья каждого рода. Порядок — он же порядок строк в шапке. */
  поляСоздания: Record<string, {порядок: string[]; значения: Record<string, string>}>;
  /**
   * Не настройка редактора, а факты самого сайта: сервер читает их из конфига Docusaurus.
   * `обложкаПоУмолчанию` — общая картинка сайта, которой он подменяет отсутствующую обложку
   * статьи. `null` — прочитать не удалось; выдумывать путь нельзя.
   */
  сайт?: {обложкаПоУмолчанию: string | null};
  /**
   * Слова окна подготовки. `находки`, `уровни` и `этапы` — карты по коду находки: код без своей
   * фразы показывается общей фразой вместе с кодом, а не проглатывается.
   */
  подготовка: {
    заголовок: string;
    чисто: string;
    закрыть: string;
    невыполненные: string;
    неизвестнаяНаходка: string;
    уровни: Record<string, string>;
    этапы: Record<string, string>;
    находки: Record<string, string>;
  };
  реестр: {
    колонки: Column[];
    сортировкаПоУмолчанию: string;
    всеРазделы: string;
    любая: string;
    толькоДыры: string;
    нетНаСайте: string;
    неизвестныйАвтор: string;
    разное: string;
  };
}

export type PanelMode = 'статьи' | 'версии' | null;

/** Одна находка подготовки, как её отдаёт ядро. Поля сверх кода и уровня не у всех находок. */
export interface PrepareFinding {
  код: string;
  уровень: string;
  этап: string;
  путь?: string;
  поле?: string;
  локаль?: string;
  значение?: string;
  длина?: number;
  предел?: number;
}

/** Ответ подготовки: находки, вердикт и честный перечень этапов, которые не выполнялись. */
export interface PrepareReport {
  path: string;
  находки: PrepareFinding[];
  прошла: boolean;
  невыполненные: string[];
}
