import {useEffect, useRef, useState} from 'react';
import type {MutableRefObject} from 'react';
import {вопросГоден, применитьПару, чтоДелать, type Пара} from './restore';
import type {Article} from './types';

/** Снимок работы, которую заменил возврат. Годен только для того окна, где возврат случился. */
interface Снимок {
  ключОкна: string;
  пара: Пара;
}

/**
 * Заданный человеку вопрос «заменить работу этой версией?».
 * Кроме окна помнит и саму версию: пока вопрос висит, можно выбрать в ленте другую отметку,
 * и согласие применило бы пару той версии, которой на экране уже нет.
 */
interface Вопрос extends Снимок {
  версия: string | null;
}

/**
 * Возврат к выбранной версии и откат возврата.
 * Правило записи живёт в `restore.ts` без React; здесь — только состояние окна:
 * ждём ли согласия человека, идёт ли запись и есть ли к чему откатиться.
 *
 * Почему откат вообще нужен: возврат меняет пару «тело + шапка», а история отмены редактора
 * знает только текст. Отмена вернула бы тело, оставив шапку от версии, — это смесь двух состояний.
 */
export function useVersionRestore(deps: {
  article: Article | null;
  /** Пара в окне прямо сейчас: читается в момент действия, а не при отрисовке. */
  текстСейчас: MutableRefObject<string>;
  шапкаСейчас: MutableRefObject<string>;
  /** Какая статья открыта и какой это заход в неё: снимок отката годен только своему окну. */
  статьяСейчас: MutableRefObject<string | null>;
  открытие: MutableRefObject<number>;
  /** Очередь автосохранения. Своего запроса у возврата нет — пишет она же. */
  автосохранение: {дописать: () => Promise<boolean>};
  /** Положить пару в очередь черновика (то же, что делает обычная правка окна). */
  вЧерновик: (body: string, frontmatterRaw: string) => void;
  /** Положить пару в окно: текст, свойства, видимость, признак несохранённого. */
  положитьПару: (пара: Пара) => void;
  /** Пересчитать признак несохранённого и надпись по паре в окне, без записи. */
  отметить: (пара: Пара) => void;
  /** Лента версий: чем занята и что открыто, плюс прекращение просмотра по успеху. */
  версии: {просмотр: {имя: string} | null; занято: boolean; закрыть: () => void};
  onОшибка: (ключ: string) => void;
}) {
  const ключОкна = (): string => `${deps.статьяСейчас.current ?? ''}|${deps.открытие.current}`;
  const окно = (): Пара => ({body: deps.текстСейчас.current, frontmatterRaw: deps.шапкаСейчас.current});
  // Пока идёт загрузка другой версии, на экране нет ни одной: вопрос про прежнюю снимается,
  // иначе согласие в эту щель применило бы версию, от которой человек уже ушёл.
  const версияСейчас = (): string | null => (deps.версии.занято ? null : deps.версии.просмотр?.имя ?? null);
  // Окно заперто вопросом «продолжить с черновика или взять файл»: до ответа правка запрещена,
  // и подставленную пару затёр бы любой из двух выборов.
  const запертоВыбором = (): boolean => deps.article?.черновикРешение === 'конфликт'
    && deps.article?.черновик !== null;

  /** Своего запроса у возврата нет: пишет та же очередь, что и обычная правка. */
  const записать = async (пара: Пара): Promise<boolean> => {
    deps.вЧерновик(пара.body, пара.frontmatterRaw);
    return deps.автосохранение.дописать();
  };

  /** Просмотр прекращается только по успеху: пока запись не удалась, человек остаётся там, где нажал. */
  const применить = (пара: Пара): void => {
    deps.положитьПару(пара);
    deps.версии.закрыть();
  };

  // Пара ждёт согласия человека: в окне есть несохранённая работа, и возврат её заменит.
  // Вместе с парой хранится ключ окна: вопрос заданный в одной статье, нельзя применить к другой —
  // иначе в чужое окно и в его черновик уехала бы пара из прошлой статьи.
  const [подтверждение, setПодтверждение] = useState<Вопрос | null>(null);
  const [снимок, setСнимок] = useState<Снимок | null>(null);
  // Запись в пути. На это время лента и кнопки просмотра заперты: иначе человек успел бы выбрать
  // другую версию, и на диске остался бы черновик от возврата, которого в окне нет.
  const [идёт, setИдёт] = useState(false);
  // Какой возврат человек ждёт сейчас. Ответ по брошенному выбору окно не подменяет.
  const ждём = useRef(0);

  // Вопрос относится к той версии, что открыта в это мгновение. Сменилось открытое — вопроса
  // больше нет: иначе он всплыл бы сам, без нажатия, стоит вернуться к той же версии, и согласие
  // заменило бы работу, набранную уже после того, как человек от возврата отказался.
  // Постановку вопроса это не гасит: она открытое не меняет, и эффект не срабатывает.
  const открытаСейчас = версияСейчас();
  useEffect(() => {
    setПодтверждение(null);
  }, [открытаСейчас]);

  const выполнить = async (новая: Пара): Promise<boolean> => {
    const вОкне = окно();
    const ключ = ключОкна();
    const моё = ждём.current + 1;
    ждём.current = моё;
    setИдёт(true);

    const вышло = await применитьПару({новая, вОкне}, {
      записать: записать,
      // То же окно и тот же возврат: статью могли закрыть, открыть заново или выбрать другую версию.
      актуально: () => моё === ждём.current && ключОкна() === ключ,
      применить: (пара) => {
        // Снимок ставится вместе с применением, а не при нажатии: возврат, который не дошёл
        // до окна, откатывать нечего и незачем.
        setСнимок({ключОкна: ключ, пара: вОкне});
        применить(пара);
      },
      отметить: deps.отметить,
      onОшибка: deps.onОшибка,
    });

    setИдёт(false);
    return вышло;
  };

  /**
   * Вернуть версию. Есть несохранённая работа — сначала спрашиваем: заменённая работа
   * в черновике не останется, и после закрытия программы её будет не вернуть.
   */
  const вернуть = async (пара: Пара, естьНесохранённые: boolean): Promise<void> => {
    const решение = чтоДелать({
      идёт, запертоВыбором: запертоВыбором(), естьНесохранённые, версияНаЭкране: версияСейчас() !== null,
    });
    if (решение === 'ничего') return;

    if (решение === 'спросить') {
      setПодтверждение({ключОкна: ключОкна(), версия: версияСейчас(), пара});
      return;
    }

    await выполнить(пара);
  };

  /**
   * Виден ли вопрос сейчас. Пока он висел, человек мог уйти в другую статью, открыть эту заново
   * или выбрать в ленте другую версию — тогда вопрос был про другое и на экране его нет.
   */
  const спрашиваем = (): boolean => вопросГоден(подтверждение, {ключОкна: ключОкна(), версия: версияСейчас()});

  const подтвердить = async (): Promise<void> => {
    const ждёт = подтверждение;
    setПодтверждение(null);
    if (!ждёт || !спрашиваем()) return;
    await выполнить(ждёт.пара);
  };

  /** Вернуть как было: та же дорога через запись, иначе откат сам стал бы дырой. */
  const откатить = async (): Promise<void> => {
    const было = снимок;
    if (!было || было.ключОкна !== ключОкна()) return;

    // Снимок стирается только по успеху: не записалось — кнопка обязана остаться,
    // иначе заменённая работа теряется вместе с единственным способом её вернуть.
    if (await выполнить(было.пара)) setСнимок(null);
  };

  /** Годен ли снимок для окна, которое открыто сейчас. */
  const откатДоступен = (): boolean => снимок !== null && снимок.ключОкна === ключОкна();

  /** Работа записана в файл — откатывать больше не к чему: на диске уже другое состояние. */
  const забытьСнимок = (): void => setСнимок(null);

  return {
    спрашиваем,
    идёт,
    // Кнопка возврата не должна выглядеть рабочей, когда возврат запрещён: пока идёт запись,
    // пока не сделан выбор «черновик или файл» и пока грузится другая версия — в эту щель
    // прежняя ещё видна, и нажатие положило бы в окно не то, что человек выбрал.
    недоступен: чтоДелать({
      идёт, запертоВыбором: запертоВыбором(), естьНесохранённые: false, версияНаЭкране: версияСейчас() !== null,
    }) === 'ничего',
    вернуть,
    подтвердить,
    отменитьПодтверждение: () => setПодтверждение(null),
    откатить,
    откатДоступен,
    забытьСнимок,
  };
}
