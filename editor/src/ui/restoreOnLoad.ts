// Обновление страницы возвращает в ту же статью.
//
// **Зачем.** Раньше запись истории при запуске сразу переписывалась на «реестр», и после F5
// открытая статья пропадала: человек оказывался в общем меню и искал её заново (ED-039).
// Состояние записи истории переживает обновление, поэтому восстанавливать есть из чего — надо
// только прочитать его РАНЬШЕ, чем оно затрётся.
//
// Правило вынесено из хука отдельными функциями, чтобы проверяться результатом, а не отрисовкой
// (SPEC 5.2.1): библиотеки для проверки React-хуков в программе нет, и заводить её ради одного
// правила — плата больше пользы (SPEC 4.10).

/** Состояние записи истории. Чужое или испорченное значение равно его отсутствию. */
export type СостояниеИстории = {вид?: unknown; path?: unknown} | null;

/** Путь статьи из состояния записи; `null` — это не статья и открывать нечего. */
export function статьяИзИстории(состояние: СостояниеИстории): string | null {
  if (состояние === null || typeof состояние !== 'object') return null;
  const {вид, path} = состояние as {вид?: unknown; path?: unknown};
  return вид === 'статья' && typeof path === 'string' && path !== '' ? path : null;
}

/** Что ходу восстановления нужно снаружи: само состояние и два действия окна. */
export interface ХодВосстановления {
  состояние: СостояниеИстории;
  /** Открыть статью без нового шага истории. `false` — открыть не вышло (причину показал открыватель). */
  открыть: (path: string) => Promise<boolean>;
  /** Пометить запись истории как реестр: отсюда «назад» и следующее обновление ведут в общее меню. */
  поставитьРеестр: () => void;
}

/**
 * Что делать на запуске окна. Возвращает путь восстановленной статьи либо `null`.
 *
 * Порядок жёсткий:
 * 1. Не статья в состоянии — сразу реестр, как было до правки.
 * 2. Статья — открываем её и НЕ трогаем запись истории: она уже описывает эту статью, и переписать
 *    её на реестр значило бы снова потерять статью при следующем обновлении.
 * 3. Открыть не вышло (статью удалили, переименовали, файл не читается) — причину человек уже видит
 *    от открывателя, и только теперь запись переводится в реестр. Молча в меню не выбрасываем.
 */
export async function восстановитьПриЗапуске(ход: ХодВосстановления): Promise<string | null> {
  const path = статьяИзИстории(ход.состояние);
  if (path === null) {
    ход.поставитьРеестр();
    return null;
  }

  if (await ход.открыть(path)) return path;

  ход.поставитьРеестр();
  return null;
}
