// Поля шапки статьи как понятия окна: разбор, сборка и показ.
// Вынесено из Properties.tsx ради предела размера файла (SPEC 4.9); правил это не меняет.

import {СПИСКИ, местоПоля, readFields, writeFields} from '../core/frontmatterFields.mjs';
import {
  ПОЛЕ_ВИДИМОСТИ, articlePlace, isUnlisted, setUnlisted, строковоеПоле,
} from '../core/frontmatterRules.mjs';
import type {Root, Settings} from './types';

/** Поле шапки в человеческом виде: списки без скобок, строки без кавычек, адрес короткий. */
export interface Field {
  key: string;
  raw: string;
  kind: string;
  display: string;
  /** Почему поле показано, но не правится. Есть только у вида `заперто`; слова — в настройках. */
  причина?: string;
}

/**
 * Наружу уходят только настоящие поля статьи. Показанная пустая обложка — вещь экрана: попади она
 * в состояние окна, у статьи появилось бы поле, которого в файле нет, и окно разошлось бы с файлом.
 * Заполненная обложка — уже настоящая правка человека и уходит как есть.
 */
export function безПоказанных(свои: Field[], показанные: Field[]): Field[] {
  return показанные.filter((поле) => свои.some((своё) => своё.key === поле.key)
    || String(поле.display ?? '').trim() !== '');
}

/**
 * Принятый порядок полей шапки для этого рода статей. Из него берётся место строки, которой
 * в шапке ещё нет: у одинаковых статей шапка обязана выглядеть одинаково.
 */
export function порядокПолей(settings: Settings, path: string): string[] {
  const род = articlePlace(path, settings.контент).kind as string;
  return settings.поляСоздания[род]?.порядок ?? [];
}

/**
 * Поля для показа: к полям шапки добавляются все остальные поля принятого порядка своего рода,
 * даже когда строки в файле нет. Пустыми они в шапке не живут вовсе (пустых ключей не бывает:
 * пустая обложка и пустой список роняют сборку сайта, видимая статья живёт без строки `unlisted`,
 * а пустое описание не даёт странице мета-описания), поэтому единственное место, где человек может
 * о них узнать и их заполнить, — это окно.
 *
 * Именного списка здесь больше нет, и это не мелочь. Пока он был, очищенное поле вне списка
 * исчезало из окна навсегда: строка уходила из файла по правилу «пустых ключей не бывает», а
 * показать поле было некому — человек стирал заголовок и не мог вписать его обратно. Принятый
 * порядок рода уже отвечает на вопрос «какие поля бывают у такой статьи», и второй список рядом
 * с ним только расходился бы с ним при первом же изменении.
 *
 * Названный остаток: поле, которого в принятом порядке НЕТ вовсе, после очистки исчезнет из окна
 * так же — места в шапке ему никто не назначал, и выдумывать его окно не вправе. Сегодня таких
 * полей в статьях сайта нет ни одного (весь корпус обходится известными ключами), поэтому боли
 * нет; появится чужое поле — его место назовут в настройках вместе с ним.
 *
 * В файл пустое поле при этом не попадает — за этим следит `безПоказанных` и сборка шапки.
 */
export function показанныеПоля(fields: Field[], порядок: string[]): Field[] {
  let итог = fields;

  for (const key of порядок) {
    if (итог.some((field) => field.key === key)) continue;

    // Место берётся тем же правилом, каким строка ляжет в файл. Считай окно по-своему —
    // после сохранения поле прыгало бы на другое место, и человек видел бы не то, что записал.
    //
    // Видимость — исключение, и оно не наше: строку `unlisted`, которой в шапке ещё нет, `setUnlisted`
    // дописывает в конец. Считай мы ей место общим правилом, окно показывало бы флажок посреди полей,
    // а в файле строка легла бы последней — то самое расхождение, ради которого правило и заведено.
    //
    // Речь только про отсутствующую строку. Существующую `setUnlisted` заменяет на месте, и сюда
    // такое поле не попадает вовсе: оно уже в списке, на своём месте из файла. Так живут три статьи
    // сайта, где `unlisted` стоит пятой строкой, и флажок в окне честно стоит там же.
    const место = key === ПОЛЕ_ВИДИМОСТИ
      ? итог.length
      : (местоПоля(итог.map((field) => field.key), порядок, key) as number);

    const пустое: Field = {key, raw: '', kind: видПустого(key), display: ''};
    итог = [...итог.slice(0, место), пустое, ...итог.slice(место)];
  }

  return итог;
}

/**
 * Скрыта ли статья по тому, что сейчас в окне. Видимость — обычное поле шапки, и другого места
 * у неё нет: заведи окно отдельный признак рядом — он разошёлся бы с полем при первой же правке.
 */
export function скрытаВОкне(fields: Field[]): boolean {
  return fields.find((поле) => поле.key === ПОЛЕ_ВИДИМОСТИ)?.display === 'true';
}

/** Что окно знает про статью, когда решает, говорить ли «изменение ещё не на сайте». */
export interface СтатьяДляСайта {
  /** Скрыта ли открытая версия в опубликованной ветке. `null` — её там нет вовсе. */
  скрытаНаСайте?: boolean | null;
  /** Удалось ли прочитать опубликованную ветку. `false` — сказать про сайт нечего. */
  веткаИзвестна?: boolean;
  /** Статья живёт вне сайта (песочница): опубликованная ветка про неё ничего не решает. */
  внеСайта?: boolean;
}

/**
 * Говорить ли «изменение ещё не на сайте». Правило живёт здесь, а не в зоне окна, чтобы
 * проверяться результатом: отрисовать окно в тесте нечем (SPEC 4.10, 5.2.1).
 *
 * Расхождение считается по ОТКРЫТОЙ версии: видимость принадлежит версии (SPEC 2.8), и
 * соседняя версия про эту ничего не решает. Названная плата: не уехавшая английская версия
 * статус больше не зажигает — чтобы увидеть её расхождение, надо её открыть.
 * Версии нет в опубликованной ветке вовсе (`null`) — сайт про неё ничего не знает, и это
 * такое же «ещё не на сайте».
 *
 * Молчим в трёх случаях. Статья живёт вне сайта — говорить про сайт нечего. Ветку прочитать
 * не удалось — «не знаю» и «ещё не на сайте» разные вещи, и выдавать первое за второе значит
 * врать про сайт ровно там, где статус обязан не врать (правило то же, каким живёт удаление);
 * порядок здесь важен, потому что чтение ветки отвечает `null` и на сбой git тоже. Признака
 * нет вовсе (`undefined`) — сервер его не прислал, и это поломка договора, а не факт про сайт.
 */
export function изменениеНеНаСайте(статья: СтатьяДляСайта | null, скрыта: boolean): boolean {
  if (статья === null || статья.внеСайта === true || статья.веткаИзвестна === false) return false;
  if (статья.скрытаНаСайте === undefined) return false;

  return статья.скрытаНаСайте === null || статья.скрытаНаСайте !== скрыта;
}

/**
 * Каким видом показать поле, которого в шапке нет вовсе. Вид тот же, каким его прочитал бы разбор
 * строки: иначе поле, появившееся из окна, вело бы себя не так, как то же поле из файла.
 */
function видПустого(key: string): string {
  if (key === ПОЛЕ_ВИДИМОСТИ) return 'флаг';
  // Адрес — не простая строка: у документации к нему приписывается раздел, и вид решает, каким
  // правилом значение уедет в файл.
  if (key === 'slug') return 'slug';
  if ((СПИСКИ as string[]).includes(key)) return 'list';
  // Всё остальное — обычный текст. Прими окно описание за список, и первое же введённое описание
  // уехало бы в файл строкой вида `description: ["текст"]`.
  return (строковоеПоле as (key: string) => boolean)(key) ? 'text' : 'plain';
}

/**
 * Что станет с полями после выбора файла. `null` — не меняем ничего.
 *
 * Правило одно и главное: поле принимает путь ТОЛЬКО после ответа сервера (SPEC 6.6). Покажи мы
 * путь заранее, при сбое в шапке осталась бы ссылка на несуществующий файл — а это падение сборки
 * всего сайта (SPEC 2.1). И путь берётся от сервера, а не из имени выбранного файла: имя с
 * кириллицей или пробелом сборку тоже роняет (SPEC 2.2).
 */
export async function полеПослеЗагрузки(
  поляСейчас: () => Field[],
  key: string,
  file: File | undefined,
  загрузить: ((file: File) => Promise<string | null>) | undefined,
  занято: boolean,
): Promise<Field[] | null> {
  // Пока идёт прошлая загрузка, вторую не начинаем: ответы пришли бы вразнобой, и в шапке остался
  // бы путь от первого выбора, а в папке статьи лежали бы обе картинки.
  if (!file || !загрузить || занято) return null;

  const src = await загрузить(file);
  if (!src) return null;

  // Поля берутся ЗАНОВО, уже после ответа сервера, и меняется только обложка. Возьми мы снимок,
  // сделанный при выборе файла, — правка описания или заголовка, набранная пока шла загрузка,
  // молча откатилась бы вместе с записью пути.
  const fields = поляСейчас();
  const index = fields.findIndex((field) => field.key === key);
  // Поля с таким именем в шапке уже нет — писать некуда, а дописывать его сюда не наше дело.
  if (index < 0) return null;

  const next = [...fields];
  next[index] = {...fields[index], display: src};
  return next;
}

/**
 * Разбор шапки в человеческие поля. Путь и корни нужны для короткого адреса.
 *
 * `общая` — путь общей картинки сайта. Если он же стоит в поле обложки, поле показывается пустым:
 * своей обложки у статьи нет, сайт и так возьмёт общую, и написанный путь ничего не добавляет.
 * Само значение в файле при этом остаётся: строка стоит в опубликованной статье, и переписывать
 * её без действия человека нельзя.
 */
export function parseFrontmatter(raw: string, path: string, roots: Root[], общая?: string | null): Field[] {
  return (readFields(raw, path, roots) as Field[])
    .map((поле) => (своя(поле, общая) ? поле : {...поле, display: ''}));
}

/** Своя ли это обложка. Общая картинка сайта, вписанная в статью, своей обложкой не считается. */
function своя(поле: Field, общая?: string | null): boolean {
  if (поле.key !== 'image' || !общая) return true;
  return поле.display.trim() !== общая.trim();
}

/**
 * Сборка обратно: нетронутые поля возвращаются дословно.
 * `порядок` — принятый порядок полей рода: по нему кладётся строка, которой в шапке не было.
 */
export function buildFrontmatter(
  raw: string,
  fields: Field[],
  path: string,
  roots: Root[],
  порядок: string[] = [],
  общая?: string | null,
): string {
  // Поле, показанное пустым только потому, что в статье вписана общая картинка сайта, возвращается
  // со своим прежним значением: человек его не трогал, а значит и файл трогать нечего.
  //
  // Что стоит в статье, спрашивается у самой шапки, которая сейчас уйдёт в файл, а не у значения,
  // с которым статью открыли. Между открытием и сохранением человек мог поставить свою обложку —
  // и старое значение вернуло бы общую картинку в файл вместо того, чтобы убрать строку.
  //
  // Разбирает шапку тот же `readFields`, что и везде: кавычки, CRLF, хвостовой `\r` и невидимая
  // метка живут в одном месте, а своя регулярка развела бы эти правила по двум.
  const вШапке = общая === null || общая === undefined
    ? null
    : (readFields(raw, path, roots) as Field[]).find((поле) => поле.key === 'image')?.display ?? null;

  const свои = fields.map((поле) => {
    if (поле.key !== 'image' || поле.display !== '' || вШапке === null) return поле;
    return вШапке.trim() === (общая as string).trim() ? {...поле, display: вШапке} : поле;
  });

  const собрано = writeFields(raw, свои, path, roots, порядок) as string;

  // Видимость пишет одно правило ядра, а не общий сбор полей (SPEC 4.3). И только тогда, когда
  // флажок разошёлся с шапкой: нетронутое поле обязано вернуться дословно, иначе одно лишь
  // открытие и сохранение переписывало бы файл — например, убирало бы чужое `unlisted: false`
  // (SPEC 5.1).
  const флажок = свои.find((поле) => поле.key === ПОЛЕ_ВИДИМОСТИ);
  if (флажок === undefined) return собрано;

  const скрыть = флажок.display === 'true';
  return isUnlisted(собрано) === скрыть ? собрано : (setUnlisted(собрано, скрыть) as string);
}
