// Откуда окно берёт признаки языковых версий и когда перечитывает их заново.
//
// Признаки считаются с диска (файл версии, сравнение с опубликованной веткой, её шапка), поэтому
// у окна их два потребителя — реестр и шапка открытой статьи — и ровно один источник, общий свод
// `/api/articles`. Шапка держала снимок момента открытия: работа уходила в файл, список это
// показывал, а буквы `RU`, `EN`, `ES` над редактором молчали до повторного открытия статьи.

import {признакиЛокали} from '../core/localeSigns.mjs';
import type {ArticleRow, ПризнакиЛокали} from './articleTypes';
import type {SaveState} from './types';

/**
 * Признаки локалей открытой статьи по свежему своду — тем же правилом ядра и из того же свода,
 * какими их берёт реестр. Второго расчёта тех же фактов здесь нет: разойдись он, список и шапка
 * сказали бы про одну версию разное.
 *
 * `null` — статьи в своде нет (её только что удалили, свод не прочитался): прежние признаки тогда
 * честнее выдуманных. Отсутствующая локаль называется наравне с существующими: «версии нет» —
 * тоже её состояние.
 */
export function признакиИзСвода(
  свод: ArticleRow[],
  путь: string,
  локали: string[],
): Record<string, ПризнакиЛокали> | null {
  const своя = строкаСвода(свод, путь);
  if (!своя) return null;

  return Object.fromEntries(локали.map((код) => [код, признакиЛокали(своя.versions[код] ?? null)]));
}

/**
 * Пути языковых версий по свежему своду.
 *
 * Держать их снимком момента открытия нельзя: внешний ИИ мог завести или убрать версию, пока
 * статья открыта. Тогда буквы над редактором говорили бы «версия есть», а идти было бы некуда —
 * нажатие молча не делало ничего. `null` — статьи в своде нет, и прежние пути честнее выдуманных.
 */
export function путиИзСвода(свод: ArticleRow[], путь: string): Record<string, string> | null {
  const своя = строкаСвода(свод, путь);
  if (!своя) return null;

  return Object.fromEntries(Object.entries(своя.versions).map(([код, версия]) => [код, версия.path]));
}

/** Строка свода, которой принадлежит эта языковая версия. */
function строкаСвода(свод: ArticleRow[], путь: string) {
  return свод.find((строка) => Object.values(строка.versions).some((версия) => версия.path === путь));
}

/**
 * Пора ли перечитывать свод: сервер подтвердил запись. Подтверждений два и они равны в этом —
 * ответ на «Сохранить» и ответ на автосохранение черновика.
 *
 * Ни ошибка, ни ещё не сохранённый текст поводом не являются. Признаки говорят о том, что лежит
 * на диске, и перечитанный после неудачи свод показал бы ровно то же, а нарисованная по окну
 * точка обещала бы сайту правку, которой в файле нет.
 */
export function записьПодтверждена(состояние: SaveState): boolean {
  return состояние === 'сохранено' || состояние === 'автосохранено';
}
