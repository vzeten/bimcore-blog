// Возврат к версии и откат возврата — без React, чтобы правило проверялось тестом, а не руками.
// Главное здесь одно: окно меняется ТОЛЬКО после того, как пара «тело + шапка» записана
// в черновик. Обратный порядок оставил бы в окне версию, а на диске — прежний черновик,
// и при следующем открытии всплыло бы состояние, которого человек не принимал.

/** Что живёт в окне и что уходит в черновик: тело и шапка всегда вместе. */
export interface Пара {
  body: string;
  frontmatterRaw: string;
}

export interface ВозвратЭффекты {
  /**
   * Записать пару в черновик немедленно, через очередь автосохранения.
   * `true` — сервер подтвердил запись. Своего запроса у возврата нет: очередь держит единые
   * часы правок и одну запись за раз, а все уходы из статьи её уже дожидаются.
   */
  записать: (пара: Пара) => Promise<boolean>;
  /**
   * Нужен ли ещё результат: та же статья, тот же заход, тот же возврат.
   * Не нужен — на диск пара уже легла, это и есть то, о чём человек просил; окно не трогаем.
   */
  актуально: () => boolean;
  /** Применить пару к окну: текст, свойства, видимость, признак несохранённого. */
  применить: (пара: Пара) => void;
  /**
   * Привести признак несохранённого и надпись состояния к паре, которая в окне, — без записи.
   * Нужно после неудачи: лечебная запись прогоняет через очередь пару окна, а очередь объявляет
   * «Автосохранено» на любую удачную запись, даже когда окно слово в слово равно файлу.
   */
  отметить: (пара: Пара) => void;
  /** Показать причину. Ключ надписи, а не текст: человеческие слова живут в настройках. */
  onОшибка: (ключ: string) => void;
}

/**
 * Положить пару в окно, предварительно записав её в черновик.
 * Возвращает `true`, если запись удалась (окно при этом могло уже уехать в другое место).
 *
 * Отказ не означает, что на диск ничего не легло: ответ мог пропасть уже после того, как сервер
 * принял запись. Поэтому пара окна дописывается немедленно — одной повторной попыткой, не циклом.
 * Не вышло и это — человеку говорят прямо, что состояние на диске могло разойтись с окном:
 * молчание здесь обещало бы сохранность, которой нет.
 */
export async function применитьПару(
  {новая, вОкне}: {новая: Пара; вОкне: Пара},
  effects: ВозвратЭффекты,
): Promise<boolean> {
  if (await effects.записать(новая)) {
    if (effects.актуально()) effects.применить(новая);
    return true;
  }

  const спасено = await effects.записать(вОкне);
  // Пара окна осталась ждущей в очереди — это свойство самой очереди при отказе, второго
  // механизма возврата правки заводить не нужно.
  // Надпись состояния возвращается к тому, что в окне: возврат не состоялся, и говорить
  // «Автосохранено» про версию, которую человек не принял, нельзя.
  effects.отметить(вОкне);
  effects.onОшибка(спасено ? 'возвратНеУдался' : 'возвратНеУдалсяДискРазошёлся');
  return false;
}

/** Совпадает ли пара с тем, что лежит в файле: тогда возвращать нечего и менять нечего. */
export function параРавна(a: Пара, b: Пара): boolean {
  return a.body === b.body && a.frontmatterRaw === b.frontmatterRaw;
}

/**
 * Что делать по нажатию «Вернуть эту версию». Правило вынесено из окна, чтобы проверяться
 * тестом: запустить хук нечем — рендерера в зависимостях нет и добавлять его запрещено (SPEC 4.10).
 *
 * `ничего` — возврат запрещён: идёт запись прошлого возврата либо человек ещё не решил,
 * продолжать с черновика или взять файл (до решения правка запрещена, и подставленную пару
 * затёр бы любой из двух выборов).
 * `спросить` — в окне есть несохранённая работа: заменять её молча нельзя.
 */
export function чтоДелать(состояние: {
  идёт: boolean;
  запертоВыбором: boolean;
  естьНесохранённые: boolean;
  /**
   * На экране действительно открыта версия. В щели между нажатием на другую отметку и ответом
   * сервера прежняя версия ещё видна, и возврат в этот миг положил бы в окно не ту, которую
   * человек выбрал.
   */
  версияНаЭкране: boolean;
}): 'ничего' | 'спросить' | 'вернуть' {
  if (состояние.идёт || состояние.запертоВыбором || !состояние.версияНаЭкране) return 'ничего';
  return состояние.естьНесохранённые ? 'спросить' : 'вернуть';
}

/**
 * Относится ли заданный вопрос к тому, что человек видит сейчас.
 * Пока вопрос висел, можно было уйти в другую статью, открыть эту заново или выбрать другую
 * версию — тогда согласие применило бы пару, о которой человека уже не спрашивали.
 */
export function вопросГоден(
  вопрос: {ключОкна: string; версия: string | null} | null,
  сейчас: {ключОкна: string; версия: string | null},
): boolean {
  return вопрос !== null && вопрос.ключОкна === сейчас.ключОкна && вопрос.версия === сейчас.версия;
}
