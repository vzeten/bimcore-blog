// Очередь автосохранения без React: правило «когда пишем черновик и что делаем с ждущей правкой»
// живёт здесь, поэтому проверяется тестом, а не только руками в браузере.
// Хук `useAutosave` — тонкая обёртка над этой очередью.

import {autosaveDraft} from './actions';
import type {SaveState} from './types';

/** Что уходит в черновик: текст, шапка и отпечаток файла, от которого человек отталкивался. */
export interface DraftPayload {
  path: string;
  body: string;
  frontmatterRaw: string;
  отпечатокБазы: string;
  /**
   * Когда правка появилась в окне. По нему сервер держит порядок: прерванный браузером запрос
   * мог быть принят сервером, и старая правка не должна затирать уже записанную свежую.
   * Проставляется очередью, вызывающим об этом думать не нужно.
   */
  правкаОт?: string;
}

/**
 * `интервалСек` — функция, а не число: настройки приходят с сервера уже после первой отрисовки,
 * и очередь, запомнившая ноль, писала бы черновик на каждую букву.
 */
export function createAutosaveQueue(
  интервалСек: () => number,
  onState: (state: SaveState) => void,
  запись: typeof autosaveDraft = autosaveDraft,
) {
  // Последняя правка, ждущая записи. Пишем не на каждую букву, а раз в интервал из настроек:
  // иначе диск дёргается на каждый символ.
  let ждёт: DraftPayload | null = null;
  let таймер: ReturnType<typeof setTimeout> | null = null;
  // Поколение растёт при каждой отмене и каждой новой правке. Ответ запроса, начатого раньше,
  // приходит с устаревшим поколением и не должен менять статус: иначе после «Сохранено»
  // мелькнёт «Автосохранено» от запроса, который уже никому не нужен.
  let поколение = 0;
  // Уже отправленный запрос прерываем по-настоящему: гасить только статус мало — поздний запрос
  // иначе допишет черновик уже после того, как работа сохранена в файл.
  let прерыватель: AbortController | null = null;
  // Идущее принудительное дописывание: второй вызов ждёт его, а не начинает своё.
  let идёт: Promise<boolean> | null = null;
  // Метка последней правки: следующая обязана быть строго позже, даже в ту же миллисекунду.
  let последняяМетка = '';

  /**
   * Метка времени правки, строго возрастающая. Две правки могут случиться в одну миллисекунду,
   * а порядок черновиков держится на этой метке: при равных метках сервер не смог бы отличить
   * запоздавшую старую запись от новой и принял бы её поверх свежей.
   */
  const метка = (): string => {
    const прошлое = Date.parse(последняяМетка);
    const мс = Number.isFinite(прошлое) ? Math.max(Date.now(), прошлое + 1) : Date.now();
    последняяМетка = new Date(мс).toISOString();
    return последняяМетка;
  };

  const снять = (): void => {
    if (таймер !== null) clearTimeout(таймер);
    таймер = null;
  };

  const оборвать = (): void => {
    поколение += 1;
    прерыватель?.abort();
    прерыватель = null;
  };

  const записать = async (моё: number): Promise<void> => {
    const данные = ждёт;
    if (!данные || моё !== поколение) return;

    onState('сохраняем');
    // Предыдущий запрос обрываем перед стартом нового: иначе живых запросов становится несколько,
    // и «Сохранить» прервёт только последний, а прежний допишет черновик уже после сохранения.
    прерыватель?.abort();
    const свой = new AbortController();
    прерыватель = свой;

    let успех = false;

    await запись(данные, {
      // Пока запрос шёл, работу могли записать по кнопке — тогда этот ответ уже неактуален.
      ok: () => {
        успех = true;
        if (моё === поколение) onState('автосохранено');
      },
      // Признак несохранённого не снимается — правки в окне остаются, человек видит, что не вышло.
      fail: () => {
        if (моё === поколение) onState('неУдалосьАвтосохранить');
      },
    }, undefined, свой.signal);

    // Записанное перестаёт быть ждущим: иначе уход из статьи или вход в просмотр послал бы
    // тот же черновик второй раз. Сверяем по самой правке: пока шёл запрос, могла прийти новая.
    if (успех && ждёт === данные) ждёт = null;
  };

  /** Правка ждёт записи: заводим таймер заново, чтобы писать по затиханию правок. */
  const запланировать = (данные: DraftPayload): void => {
    ждёт = {...данные, правкаОт: метка()};
    onState('естьНесохранённые');
    снять();
    // Новая правка обесценивает уже идущий запрос: его ответ не должен сказать «Автосохранено»
    // про текст, которого он не видел. Поэтому поколение растёт и здесь, а не только при отмене.
    поколение += 1;
    const моё = поколение;
    таймер = setTimeout(() => void записать(моё), интервалСек() * 1000);
  };

  /**
   * Забыть ждущую правку: работа уже записана в настоящий файл, продолжать нечего.
   * Идущий запрос прерываем по-настоящему — иначе он допишет черновик уже после сохранения.
   */
  const отменить = (): void => {
    снять();
    ждёт = null;
    оборвать();
  };

  /**
   * Дописать ждущую правку НЕМЕДЛЕННО и только потом забыть её.
   * Нужно там, где окно статьи перестаёт существовать: уход в другую статью, закрытие статьи.
   * Между последней буквой и срабатыванием таймера лежат секунды, и в них умещается уход из статьи —
   * если просто отменить очередь, набранное не попадёт ни в файл, ни в черновик и исчезнет совсем.
   * Возвращает `false`, если записать не удалось: тогда уходить из статьи нельзя, работа только в окне.
   * При отказе правка остаётся ждущей — иначе вторая попытка уйти сказала бы «всё записано»
   * и увела человека из статьи с пустым черновиком.
   */
  const дописать = (): Promise<boolean> => {
    // Второй уход, начатый пока идёт первый, не шлёт вторую запись: он ждёт тот же результат.
    // Иначе быстрые два нажатия отправляли бы две записи одной и той же правки.
    идёт ??= записатьВсё().finally(() => {
      идёт = null;
    });

    return идёт;
  };

  const записатьВсё = async (): Promise<boolean> => {
    let перештампована = false;

    // Пока шла запись, человек мог набрать ещё — эта правка попадает в очередь и обязана уехать
    // следующим кругом. Круг заканчивается, когда во время записи ничего нового не пришло.
    while (ждёт !== null) {
      const данные = ждёт;
      снять();
      // Прежний запрос мог нести устаревший текст: его ответ, придя позже нашего, вернул бы
      // черновик назад. Обрываем до записи.
      оборвать();

      let получилось = true;
      let устарела = false;
      await запись(данные, {
        ok: (ответ) => {
          // 200 с пометкой «устарел» — это НЕ запись: на диске лежит что-то новее, и наша правка
          // никуда не легла. Считать это успехом значит отпустить человека из статьи впустую.
          устарела = ответ?.['устарел'] === true;
          onState(устарела ? 'естьНесохранённые' : 'автосохранено');
        },
        fail: () => {
          получилось = false;
          onState('неУдалосьАвтосохранить');
        },
      });

      if (!получилось) return false;

      if (устарела) {
        // Один раз переставляем метку и пробуем снова: наши часы строго возрастают, поэтому
        // повтор окажется свежее того, что на диске. Бесконечно не крутим — иначе уход из статьи
        // может застрять навсегда, если кто-то пишет туда без остановки.
        if (перештампована) return false;
        перештампована = true;
        ждёт = {...данные, правкаОт: метка()};
        continue;
      }

      // Стираем только то, что записали: в очереди уже может лежать более свежая правка.
      if (ждёт === данные) ждёт = null;
    }

    return true;
  };

  // `метка` отдаётся наружу: ручное сохранение обязано брать время из тех же часов, иначе
  // две записи могут получить одинаковую метку и сервер не отличит запоздавшую от свежей.
  return {запланировать, отменить, дописать, метка};
}
