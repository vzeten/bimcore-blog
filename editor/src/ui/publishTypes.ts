// Понятия маршрута публикации: подготовка статьи, состав выпуска, полная сборка и отправка
// на сайт. Отдельным файлом от общих понятий окна — их файл упёрся в предел размера (SPEC 4.9),
// а маршрут публикации живёт своей группой: его типы читают только зоны и хуки публикации.

/** Одна находка подготовки, как её отдаёт ядро. Поля сверх кода и уровня не у всех находок. */
export interface PrepareFinding {
  код: string;
  уровень: string;
  этап: string;
  путь?: string;
  поле?: string;
  локаль?: string;
  значение?: string;
  длина?: number;
  предел?: number;
}

/** Один файл состава выпуска: что это и к какой языковой версии относится. */
export interface ReleaseFile {
  путь: string;
  назначение: string;
  локаль: string | null;
}

/** Что стало с одной языковой версией: изменилась, осталась как была, заглушка или её нет вовсе. */
export interface ВерсияИтога {
  локаль: string;
  состояние: 'изменилась' | 'неМенялась' | 'заглушка' | 'нетВерсии';
  путь: string | null;
  /** Версия скрыта на сайте: в меню её нет, живёт только по прямой ссылке. */
  скрыта: boolean;
}

/**
 * Итог выпуска человеческим языком: что действительно изменится на сайте. Перечень путей решения
 * не заменяет — человек читает статью, а не список файлов.
 */
export interface ИтогВыпуска {
  /** По записи на КАЖДЫЙ язык сайта: молчание о языке за «всё хорошо» сойти не должно. */
  версии: ВерсияИтога[];
  /** Только изменившиеся картинки. Неизменённые не называются вовсе. */
  картинки: string[];
  естьЧтоПубликовать: boolean;
  служебных: number;
}

/** Состав выпуска: доказанные файлы, недоказанное, можно ли выпускать и человеческий итог. */
export interface ReleaseComposition {
  path: string;
  файлы: ReleaseFile[];
  разрывы: {причина: string; путь?: string; локаль?: string | null}[];
  можно: boolean;
  /** `null` — спросить git не удалось: обещать «ничего не меняется» в этом случае нельзя. */
  итог?: ИтогВыпуска | null;
}

/** Итог полной сборки сайта. Вывод сборщика хранится целиком: разбирать его программа не берётся. */
export interface ReleaseBuild {
  path: string;
  зелёная: boolean;
  оборвана: boolean;
  времяМс: number;
  причина: string;
  вывод: string;
}

/** Один коммит, уезжающий на сайт: чем он назван и сколько в нём файлов. */
export interface PushCommit {
  sha: string;
  заголовок: string;
  файлов: number;
}

/** Что уедет на сайт, а после отправки — что уехало. `уже` — этот коммит там уже есть. */
export interface PushPlan {
  path: string;
  sha: string;
  коммиты: PushCommit[];
  файлы: string[];
  уже: boolean;
  отправлено?: boolean;
}

/** Ответ подготовки: находки, вердикт и честный перечень этапов, которые не выполнялись. */
export interface PrepareReport {
  path: string;
  находки: PrepareFinding[];
  прошла: boolean;
  невыполненные: string[];
}
