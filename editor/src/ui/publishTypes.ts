// Понятия маршрута публикации: подготовка статьи, состав выпуска с быстрыми проверками, состояние
// версий на сайте, отправка и выкладка на GitHub. Отдельным файлом от общих понятий окна — их файл упёрся в предел размера (SPEC 4.9),
// а маршрут публикации живёт своей группой: его типы читают только зоны и хуки публикации.

/** Одна находка подготовки, как её отдаёт ядро. Поля сверх кода и уровня не у всех находок. */
export interface PrepareFinding {
  код: string;
  уровень: string;
  этап: string;
  путь?: string | null;
  поле?: string | null;
  /** Строка ТЕЛА статьи с единицы: по ней окно переходит к месту. */
  строка?: number | null;
  локаль?: string;
  значение?: string;
  /** Видимый текст ссылки: им причина называет ссылку человеку. */
  текст?: string;
  /** Где в строке начинается найденное и сколько знаков занимает: окно выделяет его целиком. */
  столбец?: number;
  знаков?: number;
  длина?: number;
  предел?: number;
}

/** Один файл состава выпуска: что это и к какой языковой версии относится. */
export interface ReleaseFile {
  путь: string;
  назначение: string;
  локаль: string | null;
  /** Откуда возьмётся содержимое. `удалено` — файла у человека больше нет, и он уйдёт с сайта. */
  источник?: string;
}

/** Почему состав не доказан: причина и, если известно, к какому файлу и языку она относится. */
export interface Разрыв {
  причина: string;
  путь?: string;
  локаль?: string | null;
}

/** Что стало с одной языковой версией: изменилась, осталась как была, заглушка или её нет вовсе. */
export interface ВерсияИтога {
  локаль: string;
  состояние: 'изменилась' | 'неМенялась' | 'заглушка' | 'нетВерсии';
  путь: string | null;
  /** Версия скрыта на сайте: в меню её нет, живёт только по прямой ссылке. */
  скрыта: boolean;
}

/**
 * Итог выпуска человеческим языком: что действительно изменится на сайте. Перечень путей решения
 * не заменяет — человек читает статью, а не список файлов.
 */
export interface ИтогВыпуска {
  /** По записи на КАЖДЫЙ язык сайта: молчание о языке за «всё хорошо» сойти не должно. */
  версии: ВерсияИтога[];
  /** Только изменившиеся картинки. Неизменённые не называются вовсе. */
  картинки: string[];
  /** Что пропадёт с сайта: файлы, которых у человека больше нет. Единственное необратимое в составе. */
  убираемые: string[];
  естьЧтоПубликовать: boolean;
  служебных: number;
}

/** Состав выпуска: доказанные файлы, недоказанное, можно ли выпускать и человеческий итог. */
export interface ReleaseComposition {
  path: string;
  файлы: ReleaseFile[];
  разрывы: Разрыв[];
  можно: boolean;
  /** Отпечаток проверенного плана: запись примет его обратно и сверит со своим. */
  отпечаток?: string | null;
  /** `null` — спросить git не удалось: обещать «ничего не меняется» в этом случае нельзя. */
  итог?: ИтогВыпуска | null;
  /** Находки быстрых проверок: ссылки, картинки, MDX, компоненты, шапка. Блокер — `можно: false`. */
  находки?: PrepareFinding[];
  /** В скольких статьях план убирает ссылки на версию, которая становится недоступной. */
  ссылкиВСтатьях?: number;
  /** Страница версии уходит с сайта этой публикацией («Недоступно» у живой версии). */
  версияУходит?: boolean;
  /** Пути отмеченных версий, чья страница уходит с сайта этой публикацией (этап 3). */
  уходят?: string[];
}

/** Одна языковая версия глазами сайта: лежит ли там и с какой доступностью. `null` — не узнали. */
export interface ВерсияНаСайте {
  локаль: string | null;
  путь: string;
  файлЕсть: boolean;
  наСайте: boolean | null;
  доступность: string | null;
  черновикЖдёт: boolean;
  /** Сколько статей сайта ссылаются на эту версию: столько правок даст «Недоступно». */
  ссылок: number;
  /** Ключи этих статей: по ним окно считает статьи сразу по всем отмеченным языкам (этап 3). */
  статьи?: string[];
}

/** Лишние файлы одной версии: её путь и ИМЕНА файлов её папки, на которые никто не ссылается. */
export interface ЛишниеВерсии {
  путь: string;
  файлы: string[];
}

/** Ответ `/api/publish/state`: состояние версий статьи на сайте по опубликованной основе. */
export interface PublishState {
  path: string;
  основаИзвестна: boolean;
  локали: ВерсияНаСайте[];
  /** Что уберётся из папки каждой версии при публикации. Нет поля — сервер прежний, уборки нет. */
  лишние?: ЛишниеВерсии[];
}

/** Один коммит, уезжающий на сайт: чем он назван и сколько в нём файлов. */
export interface PushCommit {
  sha: string;
  заголовок: string;
  файлов: number;
}

/** Что уедет на сайт, а после отправки — что уехало. `уже` — этот коммит там уже есть. */
export interface PushPlan {
  path: string;
  sha: string;
  коммиты: PushCommit[];
  файлы: string[];
  уже: boolean;
  отправлено?: boolean;
  /** Коды того, что быстрые проверки при записи проверить не смогли. */
  непроверено?: string[];
}

/**
 * Ответ ручки даты записи блога: какая дата обязана стоять по сегодняшнему сайту и какая стоит в
 * файле. `нужна` равна `null`, когда программа даты не касается вовсе (не блог либо запись на сайте
 * есть, а даты у неё там нет).
 */
export interface PublishDate {
  path: string;
  нужна: string | null;
  вФайле: string | null;
}

/**
 * Ответ ручки обложки: адрес `cover.*` рядом со статьёй, который окно впишет в `image`, либо `null` —
 * остаётся общая обложка сайта (поле заполнено, годной картинки нет, папка не уезжает со статьёй).
 * `создана` — файл положен этим запросом, а не найден готовым; `предупреждение` — код находки, почему
 * обложку сделать не удалось. Остановки публикации ручка не требует никогда.
 */
export interface PublishCover {
  path: string;
  нужна: string | null;
  создана: boolean;
  предупреждение: string | null;
}

/** Ответ подготовки: находки, вердикт и честный перечень этапов, которые не выполнялись. */
export interface PrepareReport {
  path: string;
  находки: PrepareFinding[];
  прошла: boolean;
  невыполненные: string[];
  /** Отпечаток входов этой проверки: по нему следующий заход докажет, что судит тот же снимок. */
  отпечаток?: string | null;
}
