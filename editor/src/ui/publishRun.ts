// Ход публикации: что за чем спрашивается у сервера и чем это кончается.
//
// Отдельно от React намеренно. Порядок шагов и состав каждого запроса — это поведение программы, и
// проверяться оно обязано машиной, а не только глазами: одно забытое поле в теле запроса (согласие
// человека) уже стоило целой живой пробы владельца. Компонентных тестов в проекте нет и не будет
// (SPEC 4.10), поэтому проверяемым делается сам ход, а окно остаётся тонкой оболочкой.
//
// **Вопрос один и задаётся ДО хода** (решение владельца 2026-09-18, п.4): окно публикации спросило,
// с какой доступностью публиковать, и дальше программа идёт сама — сохраняет, ставит доступность,
// дату и обложку, проверяет, записывает и отправляет. Полной сборки сайта на компьютере нет: вместо
// неё быстрые проверки сервера (`/api/release`), а сайт собирает GitHub.
//
// Правил проверки здесь нет: их знает сервер. Здесь только порядок и честный ответ, чем кончилось.

import type {PrepareFinding, PrepareReport, PublishCover, PublishDate, PushPlan, ReleaseComposition} from './publishTypes';
import {записать, кодОтказа, остановка, type Исход, type Ход, type Отмеченные} from './publishSteps';

export type {Исход, Ход, Отмеченные, ШагПубликации} from './publishSteps';

/**
 * От ответа человека до записи: сохранить несохранённое, поставить доступность, дату и обложку,
 * прогнать обязательные проверки и быстрые проверки сервера, узнать, что изменится на сайте.
 *
 * `версии` — отмеченные в окне языки (этап 3, решение владельца 2026-09-18, п.2); по умолчанию один
 * открытый. Открытому доступность, дату и обложку ставит окно своим сохранением, остальным отмеченным
 * дату и доступность пишет сервер (`/api/publish/versions`) — у них окна нет.
 *
 * Ошибки сервера не ловятся здесь — их ловит окно: у него есть и текст для человека, и всё, что
 * сервер приложил к отказу.
 */
export async function проверить(
  path: string,
  dirty: boolean,
  ход: Ход,
  доступность: string | null = null,
  ужеДослали = false,
  датуПереставили = false,
  версии: string[] = [path],
): Promise<Исход> {
  const своя = версии.includes(path);
  // **Второй проход** (после досылки прошлой записи или после «дата устарела»): доступность уже в
  // файле первым проходом, и заново её не пишут. Дату и обложку пишут, только если окно всё ещё этой
  // статьи: ушёл человек — запись пропускается, и сервер сам честно скажет, если без неё нельзя.
  // Иначе уход во время досылки давал ложное «вы ушли», хотя работа уже уехала на сайт.
  const второй = ужеДослали || датуПереставили;
  const окном = (запись: () => Promise<boolean>) => (второй && !ход.жива() ? Promise.resolve(null) : записать(ход, запись));
  if (dirty) {
    const стоп = await записать(ход, ход.сохранить);
    if (стоп) return стоп;
  }
  if (доступность !== null && своя && !второй) {
    const стоп = await записать(ход, () => ход.поставитьДоступность(доступность));
    if (стоп) return стоп;
  }
  if (версии.some((версия) => версия !== path)) {
    ход.шаг('сохраняю');
    await ход.запрос('/api/publish/versions', {path, версии, доступность});
  }

  // **Дата записи блога ставится здесь — до обязательных проверок.** Дата блога это день ПЕРВОЙ
  // публикации (решение владельца 2026-09-16), и раньше этого места такого дня не существует.
  // Ставится она обычным сохранением окна, поэтому дальше проверки, состав и коммит видят один и
  // тот же файл. Что ставить, решает сервер по сегодняшнему сайту. Обложка — тоже до проверок и тем
  // же сохранением; не вышло — публикация идёт с общей обложкой сайта, причина — в предупреждения.
  const находкиОбложки: PrepareFinding[] = [];
  if (своя) {
    const дата = await ход.запрос<PublishDate>('/api/publish/date', {path});
    if (дата.нужна !== null && дата.нужна !== дата.вФайле) {
      const стоп = await окном(() => ход.поставитьДату(дата.нужна as string));
      if (стоп) return стоп;
    }

    const обложка = await ход.запрос<PublishCover>('/api/publish/cover', {path});
    if (обложка.предупреждение) {
      находкиОбложки.push({код: обложка.предупреждение, уровень: 'предупреждение', этап: 'обложка', путь: path});
    }
    if (обложка.нужна !== null) {
      const стоп = await окном(() => ход.поставитьОбложку(обложка.нужна as string));
      if (стоп) return стоп;
    }
  }

  ход.шаг('проверяю');
  // **Проверяются только отмеченные версии, каждая сама по себе.** Неотмеченный перевод в решении о
  // публикации не участвует ничем: его незаконченность — работа человека, а не препятствие выпуску.
  const подготовки: Record<string, string> = {};
  const находки: PrepareFinding[] = [];
  for (const версия of [...версии].sort((a, b) => Number(b === path) - Number(a === path))) {
    const отчёт = await ход.запрос<PrepareReport>('/api/prepare', {path: версия, толькоОткрытая: true});
    находки.push(...отчёт.находки);
    подготовки[версия] = отчёт.отпечаток ?? '';
  }
  const блокеры = находки.filter((находка) => находка.уровень === 'блокер');
  if (блокеры.length > 0) return остановка('естьПрепятствия', {находки: блокеры});

  ход.шаг('сверяю');
  let состав: ReleaseComposition;
  try {
    // Отпечатки входов проверок едут дальше: состав считается только по тому же снимку, который
    // эти проверки видели. Изменился файл между заходами — сервер откажет, а не промолчит.
    состав = await ход.запрос<ReleaseComposition>('/api/release', {
      path, версии, подготовки, отпечатокПодготовки: подготовки[path] ?? '',
    });
  } catch (ошибка) {
    const код = кодОтказа(ошибка);
    // Сайт ушёл вперёд, пока шли проверки: дата посчитана по прежней основе. Ход начинается заново —
    // ОДИН раз: второй такой отказ означает уже не гонку, и человек читает его словами сервера.
    if (код === 'датаУстарела' && !датуПереставили) {
      return проверить(path, false, ход, доступность, ужеДослали, true, версии);
    }
    // Прошлая публикация записана, но на сайт не уехала: повторное «Опубликовать» её ДОСЫЛАЕТ, а не
    // делает вторую запись. Второй раз сюда не заходим: это уже не наш незаконченный ход.
    if (ужеДослали || код !== 'естьНеотправленное') throw ошибка;

    return дослатьИПродолжить(path, ход, доступность, версии);
  }
  // Быстрые проверки сервера (ссылки, картинки, MDX, компоненты, шапка) вместо сборки на компьютере.
  const быстрые = состав.находки ?? [];
  const блокерыСайта = быстрые.filter((находка) => находка.уровень === 'блокер');
  if (блокерыСайта.length > 0) return остановка('естьПрепятствия', {находки: блокерыСайта});
  // Почему состав не доказан, человеку говорится прямо: без причины он видит запрет без объяснения.
  if (!состав.можно) return остановка('составНеДоказан', {разрывы: состав.разрывы});
  // Итога нет — не удалось узнать, что именно изменится на сайте. Публиковать вслепую нельзя.
  if (состав.итог == null) return остановка('итогНеизвестен');
  // Предупреждения едут и с «публиковать нечего»: после досылки это успех, и о непроверенном говорят.
  if (состав.итог.естьЧтоПубликовать === false) {
    const предупреждения = [...находкиОбложки, ...находки, ...быстрые];
    // **Лишнее убирается и здесь.** Файла, на который никто не ссылается и которого нет на сайте,
    // публикация не меняет ничем — до записи ход не дойдёт. Но окно его человеку уже назвало, и
    // промолчи программа, её слово разошлось бы с делом. Не вышло убрать — прежние слова: ложного
    // обещания при этом не остаётся.
    const убрано = await прибрать(path, ход, версии, состав);
    if (убрано.length > 0) return остановка('лишнееУбрано', {убрано, предупреждения});
    return остановка('нечегоПубликовать', {предупреждения});
  }

  return {
    вид: 'проверено',
    итог: состав.итог,
    файлы: состав.файлы,
    предупреждения: [...находкиОбложки, ...находки, ...быстрые],
    отпечаток: состав.отпечаток ?? null,
    отпечатокПодготовки: подготовки[path] ?? null,
    версияУходит: состав.версияУходит === true,
    отмечены: {версии, подготовки, уходят: состав.уходят ?? []},
  };
}

/**
 * Убрать лишние файлы, названные показом состава, когда публиковать больше нечего. Возвращает их
 * имена; ничего не названо или уборка не удалась — пустой перечень, и ход говорит прежнее.
 */
async function прибрать(path: string, ход: Ход, версии: string[], состав: ReleaseComposition): Promise<string[]> {
  if ((состав.лишние ?? []).every((своя) => своя.файлы.length === 0)) return [];

  try {
    const итог = await ход.запрос<{убрано: string[]}>('/api/publish/tidy', {path, версии, подтверждено: true});
    return (итог.убрано ?? []).map((путь) => путь.slice(путь.lastIndexOf('/') + 1));
  } catch {
    return [];
  }
}

/**
 * Дослать прошлую запись и продолжить обычным ходом. **Второй записи здесь не делается:** коммит уже
 * есть, человек на него уже согласился — не хватает только доставки. Если новых правок нет, обычный
 * ход скажет «публиковать нечего» — но это НЕ отказ: работа только что уехала на сайт.
 */
async function дослатьИПродолжить(path: string, ход: Ход, доступность: string | null, версии: string[]): Promise<Исход> {
  ход.шаг('публикую');
  const план = await ход.запрос<PushPlan>('/api/publish/plan', {path});
  const отправка = await ход.запрос<PushPlan>('/api/publish/push', {path, sha: план.sha, подтверждено: true});
  if (отправка.отправлено !== true && отправка.уже !== true) return остановка('неОтправилось');

  // С этого места на сайт уже ушло: никакая остановка дальше не вправе сказать «ничего не ушло».
  let дальше: Исход;
  try {
    дальше = await проверить(path, false, ход, доступность, true, false, версии);
  } catch (ошибка) {
    throw Object.assign(ошибка instanceof Object ? ошибка : new Error(String(ошибка)), {послеОтправки: true});
  }
  // **Работа уехала на сайт — значит это успех, чем бы ни кончился второй проход.** Кроме отказа по
  // существу, второй проход даёт два безобидных исхода: публиковать больше нечего и «нечего, но
  // лишнее убрано в корзину». Сочти программа второй отказом — человек прочёл бы «Не опубликовано»
  // о статье, которая в эту самую минуту на сайте (блокер контролёра 2026-09-20). Убранное при этом
  // не теряется: оно едет в успех и называется человеку вместе с самой публикацией.
  if (дальше.вид === 'прервано'
    || (дальше.вид === 'остановка' && ['нечегоПубликовать', 'лишнееУбрано'].includes(дальше.ключ))) {
    return {
      вид: 'готово', коммит: план.sha.slice(0, 7), коммиты: план.коммиты, ссылкиНеУбраны: [],
      убрано: дальше.вид === 'остановка' ? дальше.убрано ?? [] : [],
      предупреждения: [
        ...(отправка.непроверено ?? []).map((код) => ({код, уровень: 'предупреждение', этап: 'сайт'})),
        ...(дальше.вид === 'остановка' ? дальше.предупреждения ?? [] : []),
      ],
    };
  }
  return дальше.вид === 'остановка' ? {...дальше, послеОтправки: true} : дальше;
}

/**
 * Записать и отправить проверенный план.
 *
 * **Согласие едет в каждом запросе, который меняет репозиторий.** Сервер без него не фиксирует и не
 * отправляет: случайный повтор запроса не должен превращаться в публикацию.
 *
 * **С этого места попытка не отменяется:** остановка между записью и отправкой оставила бы статью
 * зафиксированной, но не уехавшей. Уход из статьи лишь перестаёт показывать итог.
 *
 * `убратьСсылки` — версия стала недоступной: после отправки ссылки на неё убираются и на компьютере,
 * в файлах и черновиках соседей (`/api/links/sweep`). Не вышло — публикация всё равно состоялась,
 * и пути называются человеку, а не прячутся. `отмечены` — языки этой публикации (этап 3): без них
 * записывается одна открытая версия.
 */
export async function зафиксироватьИОтправить(
  path: string,
  ход: Ход,
  отпечаток: string | null = null,
  отпечатокПодготовки: string | null = null,
  убратьСсылки = false,
  отмечены: Отмеченные | null = null,
): Promise<Исход> {
  ход.шаг('публикую');

  const запись = await ход.запрос<{коммит: string; sha: string; невосстановленные?: string[]; убрано?: string[]}>('/api/publish/commit', {
    path, подтверждено: true, отпечаток: отпечаток ?? '', отпечатокПодготовки: отпечатокПодготовки ?? '',
    ...(отмечены === null ? {} : {версии: отмечены.версии, подготовки: отмечены.подготовки}),
  });
  // Запись сделана, но какие-то пути программа не сумела привести в порядок: дальше ход не идёт,
  // отправка увезла бы на сайт то, что с диском уже разошлось.
  const невосстановленные = Array.isArray(запись.невосстановленные) ? запись.невосстановленные : [];
  if (невосстановленные.length > 0) return остановка('невосстановлено', {невосстановленные});

  // Показ набора и отправка — шаги программы, а не человека: он уже ответил на свой вопрос.
  const план = await ход.запрос<PushPlan>('/api/publish/plan', {path});
  const отправка = await ход.запрос<PushPlan>('/api/publish/push', {path, sha: запись.sha, подтверждено: true});

  // «Этот коммит на сайте уже есть» — тоже успех: работа там, второй раз её везти незачем.
  if (отправка.отправлено !== true && отправка.уже !== true) return остановка('неОтправилось');

  let ссылкиНеУбраны: string[] = [];
  if (убратьСсылки) {
    const уходят = отмечены !== null && отмечены.уходят.length > 0 ? отмечены.уходят : [path];
    try {
      const уборка = await ход.запрос<{невосстановленные: string[]}>('/api/links/sweep', {path, толькоВерсия: true, версии: уходят});
      ссылкиНеУбраны = уборка.невосстановленные ?? [];
    } catch {
      ссылкиНеУбраны = уходят;
    }
  }
  // Что запись унесла в корзину, едет с успехом: человек вернёт файл одним нажатием, а узнать о
  // нём он обязан там же, где узнаёт о самой публикации.
  return {
    вид: 'готово', коммит: запись.коммит, коммиты: план.коммиты, ссылкиНеУбраны,
    убрано: (запись.убрано ?? []).map((путь) => путь.slice(путь.lastIndexOf('/') + 1)),
  };
}

/**
 * Весь ход после ответа человека: проверки, запись, отправка. Доступность и отмеченные языки
 * приходят из окна вопроса. Начатая публикация доходит до конца, куда бы человек ни ушёл (проба
 * владельца 2026-09-19): окно нужно ходу только для своих записей (сохранение, доступность, дата,
 * обложка), и только их уход из статьи отменяет — запись легла бы в чужую статью (`записать`).
 */
export async function опубликовать(
  path: string, dirty: boolean, ход: Ход, доступность: string, версии: string[] = [path],
): Promise<Исход> {
  const проверка = await проверить(path, dirty, ход, доступность, false, false, версии);
  if (проверка.вид !== 'проверено') return проверка;

  // Страница уходит с сайта («Недоступно» у живой версии, правило ВК п.7) — ссылки на неё уберутся
  // и на компьютере. Не было её на сайте — и убирать нечего: ссылки на неё и так никуда не ведут.
  const итог = await зафиксироватьИОтправить(
    path, ход, проверка.отпечаток, проверка.отпечатокПодготовки, проверка.версияУходит, проверка.отмечены,
  );
  // Предупреждения проверок доходят до человека и после успеха: «не проверено» молчанием не становится.
  return итог.вид === 'готово' ? {...итог, предупреждения: проверка.предупреждения} : итог;
}
