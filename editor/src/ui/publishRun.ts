// Ход публикации: что за чем спрашивается у сервера и чем это кончается.
//
// Отдельно от React намеренно. Порядок шагов и состав каждого запроса — это поведение программы, и
// проверяться оно обязано машиной, а не только глазами: одно забытое поле в теле запроса (согласие
// человека) уже стоило целой живой пробы владельца. Компонентных тестов в проекте нет и не будет
// (SPEC 4.10), поэтому проверяемым делается сам ход, а окно остаётся тонкой оболочкой.
//
// **Вопрос один и задаётся ДО хода** (решение владельца 2026-09-18, п.4): окно публикации спросило,
// с какой доступностью публиковать, и дальше программа идёт сама — сохраняет, ставит доступность,
// дату и обложку, проверяет, записывает и отправляет. Полной сборки сайта на компьютере нет: вместо
// неё быстрые проверки сервера (`/api/release`), а сайт собирает GitHub.
//
// Правил проверки здесь нет: их знает сервер. Здесь только порядок и честный ответ, чем кончилось.

import type {
  ИтогВыпуска, PrepareFinding, PrepareReport, PublishCover, PublishDate, PushCommit, PushPlan,
  ReleaseComposition, Разрыв,
} from './publishTypes';

/** Где сейчас публикация. Человеку показывается словом из настроек, в коде — только признак. */
export type ШагПубликации = 'нет' | 'сохраняю' | 'проверяю' | 'сверяю' | 'публикую' | 'готово';

/** Чем кончился ход. `прервано` — попытку отменили уходом из статьи, говорить не о чем. */
export type Исход =
  | {
      вид: 'проверено';
      итог: ИтогВыпуска;
      файлы: ReleaseComposition['файлы'];
      предупреждения: PrepareFinding[];
      /** Отпечаток проверенного плана: согласие человека относится именно к нему. */
      отпечаток: string | null;
      /** Отпечаток входов проверок: он едет до самой записи, иначе снимок обрывается на ней. */
      отпечатокПодготовки: string | null;
      /** Страница версии уходит с сайта: после отправки ссылки на неё убираются и на компьютере. */
      версияУходит: boolean;
    }
  | {
      вид: 'остановка';
      ключ: string;
      находки: PrepareFinding[];
      чужие: string[];
      разрывы: Разрыв[];
      /** Пути, которые не удалось привести в порядок после записи: они не «посторонние». */
      невосстановленные: string[];
    }
  | {вид: 'прервано'}
  | {вид: 'готово'; коммит: string; коммиты: PushCommit[]; ссылкиНеУбраны: string[]};

/** Всё, что ходу нужно снаружи: дверь к серверу, запись на диск, показ шага и признак «попытка жива». */
export interface Ход {
  запрос: <T>(адрес: string, тело: Record<string, unknown>) => Promise<T>;
  сохранить: () => Promise<boolean>;
  /**
   * Поставить дату записи блога в шапку окна и записать её ТЕМ ЖЕ сохранением, что и любую правку
   * человека: второго писателя файлов статьи в программе нет, а история версий, отпечаток проверок
   * и запись обязаны увидеть ровно тот файл, который уедет на сайт.
   */
  поставитьДату: (дата: string) => Promise<boolean>;
  /** Вписать адрес обложки в `image` и записать тем же сохранением — по той же причине, что дату. */
  поставитьОбложку: (адрес: string) => Promise<boolean>;
  /**
   * Поставить выбранную в окне доступность (`draft`/`unlisted`) и записать тем же сохранением.
   * Совпала с тем, что уже в шапке, — ничего не пишется. Доступность назначается только публикацией
   * (решение владельца 2026-09-18, п.3), и в файл она ложится до проверок: проверяется то, что уедет.
   */
  поставитьДоступность: (режим: string) => Promise<boolean>;
  шаг: (шаг: ШагПубликации) => void;
  жива: () => boolean;
}

/** Записать что-то окном и остановиться, если попытку тем временем отменили или запись не легла. */
async function записать(ход: Ход, запись: () => Promise<boolean>): Promise<Исход | null> {
  ход.шаг('сохраняю');
  const легло = await запись();
  // Запись идёт секунды, и за это время человек мог уйти в другую статью. Сама запись при этом
  // законна — он нажал публикацию.
  if (!ход.жива()) return {вид: 'прервано'};
  return легло ? null : остановка('неСохранилось');
}

/**
 * От ответа человека до записи: сохранить несохранённое, поставить доступность, дату и обложку,
 * прогнать обязательные проверки и быстрые проверки сервера, узнать, что изменится на сайте.
 *
 * Ошибки сервера не ловятся здесь — их ловит окно: у него есть и текст для человека, и всё, что
 * сервер приложил к отказу.
 */
export async function проверить(
  path: string,
  dirty: boolean,
  ход: Ход,
  доступность: string | null = null,
  ужеДослали = false,
  датуПереставили = false,
): Promise<Исход> {
  if (dirty) {
    const стоп = await записать(ход, ход.сохранить);
    if (стоп) return стоп;
  }
  if (доступность !== null) {
    const стоп = await записать(ход, () => ход.поставитьДоступность(доступность));
    if (стоп) return стоп;
  }

  // **Дата записи блога ставится здесь — до обязательных проверок.** Дата блога это день ПЕРВОЙ
  // публикации (решение владельца 2026-09-16), и раньше этого места такого дня не существует.
  // Ставится она обычным сохранением окна, поэтому дальше проверки, состав и коммит видят один и
  // тот же файл. Что ставить, решает сервер по сегодняшнему сайту.
  const дата = await ход.запрос<PublishDate>('/api/publish/date', {path});
  if (!ход.жива()) return {вид: 'прервано'};
  if (дата.нужна !== null && дата.нужна !== дата.вФайле) {
    const стоп = await записать(ход, () => ход.поставитьДату(дата.нужна as string));
    if (стоп) return стоп;
  }

  // **Обложка — тоже до проверок и тем же сохранением** (решение владельца 2026-09-16). Сделать
  // обложку не вышло — публикация идёт дальше с общей обложкой сайта, а причина встаёт в
  // предупреждения: решать, ставить ли свою, человеку.
  const обложка = await ход.запрос<PublishCover>('/api/publish/cover', {path});
  if (!ход.жива()) return {вид: 'прервано'};
  const находкиОбложки: PrepareFinding[] = обложка.предупреждение
    ? [{код: обложка.предупреждение, уровень: 'предупреждение', этап: 'обложка', путь: path}]
    : [];
  if (обложка.нужна !== null) {
    const стоп = await записать(ход, () => ход.поставитьОбложку(обложка.нужна as string));
    if (стоп) return стоп;
  }

  ход.шаг('проверяю');
  // **Проверяется только открытая локаль.** Соседний перевод в решении о публикации не участвует
  // ничем: его незаконченность — работа человека, а не препятствие выпуску готовой версии.
  const отчёт = await ход.запрос<PrepareReport>('/api/prepare', {path, толькоОткрытая: true});
  if (!ход.жива()) return {вид: 'прервано'};
  const блокеры = отчёт.находки.filter((находка) => находка.уровень === 'блокер');
  if (блокеры.length > 0) return остановка('естьПрепятствия', {находки: блокеры});

  ход.шаг('сверяю');
  let состав: ReleaseComposition;
  try {
    // Отпечаток входов проверок едет дальше: состав считается только по тому же снимку, который
    // эти проверки видели. Изменился файл между заходами — сервер откажет, а не промолчит.
    состав = await ход.запрос<ReleaseComposition>('/api/release', {path, отпечатокПодготовки: отчёт.отпечаток ?? ''});
  } catch (ошибка) {
    const код = кодОтказа(ошибка);
    // Сайт ушёл вперёд, пока шли проверки: дата посчитана по прежней основе. Ход начинается заново —
    // ОДИН раз: второй такой отказ означает уже не гонку, и человек читает его словами сервера.
    if (код === 'датаУстарела' && !датуПереставили) {
      if (!ход.жива()) return {вид: 'прервано'};
      return проверить(path, false, ход, доступность, ужеДослали, true);
    }
    // Прошлая публикация записана, но на сайт не уехала: повторное «Опубликовать» её ДОСЫЛАЕТ, а не
    // делает вторую запись. Второй раз сюда не заходим: это уже не наш незаконченный ход.
    if (ужеДослали || код !== 'естьНеотправленное') throw ошибка;
    if (!ход.жива()) return {вид: 'прервано'};

    return дослатьИПродолжить(path, ход, доступность);
  }
  if (!ход.жива()) return {вид: 'прервано'};
  // Быстрые проверки сервера (ссылки, картинки, MDX, компоненты, шапка) вместо сборки на компьютере.
  const быстрые = состав.находки ?? [];
  const блокерыСайта = быстрые.filter((находка) => находка.уровень === 'блокер');
  if (блокерыСайта.length > 0) return остановка('естьПрепятствия', {находки: блокерыСайта});
  // Почему состав не доказан, человеку говорится прямо: без причины он видит запрет без объяснения.
  if (!состав.можно) return остановка('составНеДоказан', {разрывы: состав.разрывы});
  // Итога нет — не удалось узнать, что именно изменится на сайте. Публиковать вслепую нельзя.
  if (состав.итог == null) return остановка('итогНеизвестен');
  if (состав.итог.естьЧтоПубликовать === false) return остановка('нечегоПубликовать');

  return {
    вид: 'проверено',
    итог: состав.итог,
    файлы: состав.файлы,
    предупреждения: [...находкиОбложки, ...отчёт.находки, ...быстрые],
    отпечаток: состав.отпечаток ?? null,
    отпечатокПодготовки: отчёт.отпечаток ?? null,
    версияУходит: состав.версияУходит === true,
  };
}

/**
 * Дослать прошлую запись и продолжить обычным ходом. **Второй записи здесь не делается:** коммит уже
 * есть, человек на него уже согласился — не хватает только доставки. Если новых правок нет, обычный
 * ход скажет «публиковать нечего» — но это НЕ отказ: работа только что уехала на сайт.
 */
async function дослатьИПродолжить(path: string, ход: Ход, доступность: string | null): Promise<Исход> {
  ход.шаг('публикую');
  const план = await ход.запрос<PushPlan>('/api/publish/plan', {path});
  const отправка = await ход.запрос<PushPlan>('/api/publish/push', {path, sha: план.sha, подтверждено: true});
  if (!ход.жива()) return {вид: 'прервано'};
  if (отправка.отправлено !== true && отправка.уже !== true) return остановка('неОтправилось');

  const дальше = await проверить(path, false, ход, доступность, true);
  if (дальше.вид === 'остановка' && дальше.ключ === 'нечегоПубликовать') {
    return {вид: 'готово', коммит: план.sha.slice(0, 7), коммиты: план.коммиты, ссылкиНеУбраны: []};
  }
  return дальше;
}

/**
 * Записать и отправить проверенный план.
 *
 * **Согласие едет в каждом запросе, который меняет репозиторий.** Сервер без него не фиксирует и не
 * отправляет: случайный повтор запроса не должен превращаться в публикацию.
 *
 * **С этого места попытка не отменяется:** остановка между записью и отправкой оставила бы статью
 * зафиксированной, но не уехавшей. Уход из статьи лишь перестаёт показывать итог.
 *
 * `убратьСсылки` — версия стала недоступной: после отправки ссылки на неё убираются и на компьютере,
 * в файлах и черновиках соседей (`/api/links/sweep`). Не вышло — публикация всё равно состоялась,
 * и пути называются человеку, а не прячутся.
 */
export async function зафиксироватьИОтправить(
  path: string,
  ход: Ход,
  отпечаток: string | null = null,
  отпечатокПодготовки: string | null = null,
  убратьСсылки = false,
): Promise<Исход> {
  ход.шаг('публикую');

  const запись = await ход.запрос<{коммит: string; sha: string; невосстановленные?: string[]}>(
    '/api/publish/commit',
    {path, подтверждено: true, отпечаток: отпечаток ?? '', отпечатокПодготовки: отпечатокПодготовки ?? ''},
  );
  // Запись сделана, но какие-то пути программа не сумела привести в порядок: дальше ход не идёт,
  // отправка увезла бы на сайт то, что с диском уже разошлось.
  const невосстановленные = Array.isArray(запись.невосстановленные) ? запись.невосстановленные : [];
  if (невосстановленные.length > 0) return остановка('невосстановлено', {невосстановленные});

  // Показ набора и отправка — шаги программы, а не человека: он уже ответил на свой вопрос.
  const план = await ход.запрос<PushPlan>('/api/publish/plan', {path});
  const отправка = await ход.запрос<PushPlan>('/api/publish/push', {path, sha: запись.sha, подтверждено: true});

  // «Этот коммит на сайте уже есть» — тоже успех: работа там, второй раз её везти незачем.
  if (отправка.отправлено !== true && отправка.уже !== true) return остановка('неОтправилось');

  let ссылкиНеУбраны: string[] = [];
  if (убратьСсылки) {
    try {
      const уборка = await ход.запрос<{невосстановленные: string[]}>('/api/links/sweep', {path, толькоВерсия: true});
      ссылкиНеУбраны = уборка.невосстановленные ?? [];
    } catch {
      ссылкиНеУбраны = [path];
    }
  }
  return {вид: 'готово', коммит: запись.коммит, коммиты: план.коммиты, ссылкиНеУбраны};
}

/**
 * Весь ход после ответа человека: проверки, запись, отправка. Доступность приходит из окна вопроса.
 * До записи уход из статьи отменяет попытку; после — нет (см. `зафиксироватьИОтправить`).
 */
export async function опубликовать(path: string, dirty: boolean, ход: Ход, доступность: string): Promise<Исход> {
  const проверка = await проверить(path, dirty, ход, доступность);
  if (проверка.вид !== 'проверено') return проверка;
  if (!ход.жива()) return {вид: 'прервано'};

  // Страница уходит с сайта («Недоступно» у живой версии, правило ВК п.7) — ссылки на неё уберутся
  // и на компьютере. Не было её на сайте — и убирать нечего: ссылки на неё и так никуда не ведут.
  return зафиксироватьИОтправить(path, ход, проверка.отпечаток, проверка.отпечатокПодготовки, проверка.версияУходит);
}

type Подробности = {
  находки?: PrepareFinding[];
  чужие?: string[];
  разрывы?: Разрыв[];
  невосстановленные?: string[];
};

/** Остановка с её причиной. Подробности приходят по имени: их четыре вида, и путать их нельзя. */
const остановка = (ключ: string, ещё: Подробности = {}): Исход => ({
  вид: 'остановка',
  ключ,
  находки: [],
  чужие: [],
  разрывы: [],
  невосстановленные: [],
  ...ещё,
});

/** Код отказа сервера, если он его назвал. По коду ход решает, а по тексту говорит окно. */
function кодОтказа(ошибка: unknown): string | null {
  const ответ = (ошибка as {ответ?: {код?: unknown}})?.ответ;

  return typeof ответ?.код === 'string' ? ответ.код : null;
}
