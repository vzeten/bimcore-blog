// Ход публикации: что за чем спрашивается у сервера и чем это кончается.
//
// Отдельно от React намеренно. Порядок шагов и состав каждого запроса — это поведение программы, и
// проверяться оно обязано машиной, а не только глазами: одно забытое поле в теле запроса (согласие
// человека) уже стоило целой живой пробы владельца. Компонентных тестов в проекте нет и не будет
// (SPEC 4.10), поэтому проверяемым делается сам ход, а окно остаётся тонкой оболочкой.
//
// Правил проверки здесь нет: их знает сервер. Здесь только порядок и честный ответ, чем кончилось.

import type {
  ИтогВыпуска, PrepareFinding, PrepareReport, PublishCover, PublishDate, PushCommit, PushPlan, ReleaseBuild,
  ReleaseComposition, Разрыв,
} from './publishTypes';

/** Где сейчас публикация. Человеку показывается словом из настроек, в коде — только признак. */
export type ШагПубликации = 'нет' | 'сохраняю' | 'проверяю' | 'сверяю' | 'собираю' | 'спрашиваю' | 'публикую' | 'готово';

/** Чем кончился ход. `прервано` — попытку отменили правкой или закрытием, говорить не о чем. */
export type Исход =
  | {
      вид: 'спрашиваю';
      итог: ИтогВыпуска;
      файлы: ReleaseComposition['файлы'];
      предупреждения: PrepareFinding[];
      /** Отпечаток ПОКАЗАННОГО плана: согласие человека относится именно к нему. */
      отпечаток: string | null;
      /** Отпечаток входов проверок: он едет до самой записи, иначе снимок обрывается на сборке. */
      отпечатокПодготовки: string | null;
    }
  | {
      вид: 'остановка';
      ключ: string;
      находки: PrepareFinding[];
      чужие: string[];
      разрывы: Разрыв[];
      /** Пути, которые не удалось привести в порядок после записи: они не «посторонние». */
      невосстановленные: string[];
    }
  | {вид: 'прервано'}
  | {вид: 'готово'; коммит: string; коммиты: PushCommit[]};

/** Всё, что ходу нужно снаружи: дверь к серверу, запись на диск, показ шага и признак «попытка жива». */
export interface Ход {
  запрос: <T>(адрес: string, тело: Record<string, unknown>) => Promise<T>;
  сохранить: () => Promise<boolean>;
  /**
   * Поставить дату записи блога в шапку окна и записать её ТЕМ ЖЕ сохранением, что и любую правку
   * человека: второго писателя файлов статьи в программе нет, а история версий, отпечаток проверок
   * и сборка обязаны увидеть ровно тот файл, который уедет на сайт.
   */
  поставитьДату: (дата: string) => Promise<boolean>;
  /** Вписать адрес обложки в `image` и записать тем же сохранением — по той же причине, что дату. */
  поставитьОбложку: (адрес: string) => Promise<boolean>;
  шаг: (шаг: ШагПубликации) => void;
  жива: () => boolean;
}

/**
 * От нажатия до вопроса: сохранить несохранённое, прогнать обязательные проверки, узнать, что
 * изменится на сайте, убедиться, что вместе со статьёй не уедет чужая работа, и собрать сайт целиком.
 *
 * Ошибки сервера не ловятся здесь — их ловит окно: у него есть и текст для человека, и всё, что
 * сервер приложил к отказу.
 */
export async function проверитьИСобрать(
  path: string,
  dirty: boolean,
  ход: Ход,
  ужеДослали = false,
  датуПереставили = false,
): Promise<Исход> {
  if (dirty) {
    ход.шаг('сохраняю');
    const легло = await ход.сохранить();
    // Запись идёт секунды, и за это время попытку могли отменить: закрыть панель или уйти в другую
    // статью. Сама запись при этом законна — человек нажал публикацию.
    if (!ход.жива()) return {вид: 'прервано'};
    if (!легло) return остановка('неСохранилось');
  }

  // **Дата записи блога ставится здесь — до обязательных проверок.** Дата блога это день ПЕРВОЙ
  // публикации (решение владельца 2026-09-16), и раньше этого места такого дня не существует.
  // Ставится она обычным сохранением окна, поэтому дальше проверки, состав, сборка и коммит видят
  // один и тот же файл. Поставь её позже — собранное и проверенное разошлось бы с записанным.
  //
  // Что именно ставить, решает сервер по сегодняшнему сайту: у опубликованной записи он вернёт её
  // же дату с сайта (в том числе заглушке, у которой на диске даты нет), у неопубликованной —
  // дату опубликованного соседнего языка или сегодняшний день.
  const дата = await ход.запрос<PublishDate>('/api/publish/date', {path});
  if (!ход.жива()) return {вид: 'прервано'};
  if (дата.нужна !== null && дата.нужна !== дата.вФайле) {
    ход.шаг('сохраняю');
    const легло = await ход.поставитьДату(дата.нужна);
    if (!ход.жива()) return {вид: 'прервано'};
    if (!легло) return остановка('неСохранилось');
  }

  // **Обложка — тоже до проверок и тем же сохранением** (решение владельца 2026-09-16: без обложки
  // статья не выходит). Файл `cover.*` из первой картинки кладёт сервер, поле пишет окно; статья при
  // этом не открывается заново, и попытка остаётся той же. Создать обложку нельзя — сервер
  // отказывает словами, и публикация останавливается, а не уходит без обложки молча.
  const обложка = await ход.запрос<PublishCover>('/api/publish/cover', {path});
  if (!ход.жива()) return {вид: 'прервано'};
  if (обложка.нужна !== null) {
    ход.шаг('сохраняю');
    const легло = await ход.поставитьОбложку(обложка.нужна);
    if (!ход.жива()) return {вид: 'прервано'};
    if (!легло) return остановка('неСохранилось');
  }

  ход.шаг('проверяю');
  // **Проверяется только открытая локаль.** Соседний перевод в решении о публикации не участвует
  // ничем: его незаконченность — работа человека, а не препятствие выпуску готовой версии. Без
  // этого признака подготовка собрала бы весь свод статей и прочла бы каждый соседний файл, и
  // пустое описание в чужой заглушке останавливало бы публикацию.
  const отчёт = await ход.запрос<PrepareReport>('/api/prepare', {path, толькоОткрытая: true});
  if (!ход.жива()) return {вид: 'прервано'};
  const блокеры = отчёт.находки.filter((находка) => находка.уровень === 'блокер');
  if (блокеры.length > 0) return остановка('естьПрепятствия', {находки: блокеры});

  ход.шаг('сверяю');
  let состав: ReleaseComposition;
  try {
    // Отпечаток входов проверок едет дальше: состав считается только по тому же снимку, который
    // эти проверки видели. Изменился файл между заходами — сервер откажет, а не промолчит.
    состав = await ход.запрос<ReleaseComposition>('/api/release', {
      path,
      отпечатокПодготовки: отчёт.отпечаток ?? '',
    });
  } catch (ошибка) {
    // Прошлая публикация записана, но на сайт не уехала: выключение компьютера или обрыв сети между
    // записью и отправкой. Настройки обещают человеку, что повторное «Опубликовать» её ДОШЛЁТ, а не
    // сделает вторую запись, — и обещание должно быть правдой. Второй раз сюда не заходим: если и
    // после досылки основа не закреплена, это уже не наш незаконченный ход.
    const код = кодОтказа(ошибка);
    // Сайт ушёл вперёд, пока шли проверки: например, туда уехал соседний язык этой же записи, и
    // дата посчитана по прежней основе. Ход начинается заново — ОДИН раз: второй такой отказ
    // означает уже не гонку, и человек читает его словами сервера.
    if (код === 'датаУстарела' && !датуПереставили) {
      if (!ход.жива()) return {вид: 'прервано'};
      return проверитьИСобрать(path, false, ход, ужеДослали, true);
    }
    if (ужеДослали || код !== 'естьНеотправленное') throw ошибка;
    // **Жизнь попытки спрашивается ДО досылки, а не после.** Пока сервер отвечал, человек мог
    // закрыть панель, и крестик обещал ему отмену проверки. Досылка — отправка на сайт: начни она
    // после закрытия, слова разошлись бы с делом.
    if (!ход.жива()) return {вид: 'прервано'};

    return дослатьИПродолжить(path, ход);
  }
  if (!ход.жива()) return {вид: 'прервано'};
  // Почему состав не доказан, человеку говорится прямо: без причины он видит запрет без объяснения.
  if (!состав.можно) return остановка('составНеДоказан', {разрывы: состав.разрывы});
  // Итога нет — не удалось узнать, что именно изменится. Спрашивать согласие, не сумев сказать,
  // что публикация изменит, нельзя: это согласие вслепую.
  if (состав.итог == null) return остановка('итогНеизвестен');
  if (состав.итог.естьЧтоПубликовать === false) return остановка('нечегоПубликовать');

  ход.шаг('собираю');
  // Собирается ровно показанный план: тот же отпечаток едет и в сборку, и потом в запись. Рядом с
  // ним едет и отпечаток проверок: сборка идёт минуты, и снимок обязан держаться сквозь неё, а не
  // обрываться на её пороге.
  const сборка = await ход.запрос<ReleaseBuild>('/api/release/build', {
    path,
    отпечаток: состав.отпечаток ?? '',
    отпечатокПодготовки: отчёт.отпечаток ?? '',
  });
  if (!ход.жива()) return {вид: 'прервано'};
  if (!сборка.зелёная) return остановка(сборка.оборвана ? 'сборкаОборвана' : 'сборкаКрасная');

  return {
    вид: 'спрашиваю',
    итог: состав.итог,
    файлы: состав.файлы,
    предупреждения: отчёт.находки,
    отпечаток: состав.отпечаток ?? null,
    отпечатокПодготовки: отчёт.отпечаток ?? null,
  };
}

/**
 * Дослать прошлую запись и продолжить обычным ходом.
 *
 * **Второй записи здесь не делается ни при каких условиях.** Коммит уже есть, человек на него уже
 * согласился — не хватает только доставки. Спрашивать согласие заново не о чем: вопрос был задан
 * тогда, а нажатие «Опубликовать» сейчас и есть его повторное «да».
 *
 * После досылки ход идёт заново: у человека могли появиться новые правки, и они публикуются как
 * обычно. Если правок нет, обычный ход скажет «публиковать нечего» — но это НЕ отказ: работа только
 * что уехала на сайт, и человек обязан увидеть успех, а не запрет.
 */
async function дослатьИПродолжить(path: string, ход: Ход): Promise<Исход> {
  ход.шаг('публикую');
  const план = await ход.запрос<PushPlan>('/api/publish/plan', {path});
  const отправка = await ход.запрос<PushPlan>('/api/publish/push', {path, sha: план.sha, подтверждено: true});
  if (!ход.жива()) return {вид: 'прервано'};
  if (отправка.отправлено !== true && отправка.уже !== true) return остановка('неОтправилось');

  const дальше = await проверитьИСобрать(path, false, ход, true);
  if (дальше.вид === 'остановка' && дальше.ключ === 'нечегоПубликовать') {
    return {вид: 'готово', коммит: план.sha.slice(0, 7), коммиты: план.коммиты};
  }

  return дальше;
}

/**
 * После согласия человека: зафиксировать статью и отправить её на сайт.
 *
 * **Согласие едет в каждом запросе, который меняет репозиторий.** Сервер без него не фиксирует и не
 * отправляет — и правильно делает: случайный повтор запроса не должен превращаться в публикацию.
 * Забыть этот признак означает потерять ответ человека молча, между кнопкой и сервером.
 *
 * **С этого места попытка не отменяется.** Отмена возможна только ДО согласия; после него закрытие
 * панели, переход к другой статье и правка текста доводят начатое до конца и лишь перестают
 * показывать итог. Так честнее: остановка между записью и отправкой оставила бы статью
 * зафиксированной, но не уехавшей — состояние, из которого человеку самому не выбраться. Панель
 * поэтому и не предлагает закрытие, пока идёт отправка.
 */
export async function зафиксироватьИОтправить(
  path: string,
  ход: Ход,
  отпечаток: string | null = null,
  отпечатокПодготовки: string | null = null,
): Promise<Исход> {
  ход.шаг('публикую');

  const запись = await ход.запрос<{коммит: string; sha: string; невосстановленные?: string[]}>(
    '/api/publish/commit',
    // Согласие человека едет вместе с отпечатком того плана, который ему показали: память сборки
    // одна на сервер, и без этого второе окно подменило бы перечень между вопросом и ответом.
    // Рядом едет отпечаток проверок: запись обязана доказать не только состав, но и то, что
    // подготовка этой статьи прошла — и по тем же правилам, что были при вопросе человеку.
    {path, подтверждено: true, отпечаток: отпечаток ?? '', отпечатокПодготовки: отпечатокПодготовки ?? ''},
  );

  // Запись сделана, но какие-то пути программа не сумела привести в порядок: то ли файла, который
  // теперь есть на сайте, нет на диске, то ли состояние пути в хранилище так и осталось неясным.
  // Дальше ход не идёт: отправка увезла бы на сайт то, что с диском уже разошлось, и промолчала бы
  // об этом. Человеку это показывается прямо, а не прячется за успехом.
  const невосстановленные = Array.isArray(запись.невосстановленные) ? запись.невосстановленные : [];
  if (невосстановленные.length > 0) return остановка('невосстановлено', {невосстановленные});

  // Показ набора и отправка — шаги программы, а не человека: он уже ответил на свой вопрос.
  const план = await ход.запрос<PushPlan>('/api/publish/plan', {path});

  const отправка = await ход.запрос<PushPlan>('/api/publish/push', {
    path,
    sha: запись.sha,
    подтверждено: true,
  });
  if (!ход.жива()) return {вид: 'прервано'};

  // «Этот коммит на сайте уже есть» — тоже успех: работа там, второй раз её везти незачем.
  if (отправка.отправлено === true || отправка.уже === true) {
    return {вид: 'готово', коммит: запись.коммит, коммиты: план.коммиты};
  }

  return остановка('неОтправилось');
}

type Подробности = {
  находки?: PrepareFinding[];
  чужие?: string[];
  разрывы?: Разрыв[];
  невосстановленные?: string[];
};

/** Остановка с её причиной. Подробности приходят по имени: их четыре вида, и путать их нельзя. */
const остановка = (ключ: string, ещё: Подробности = {}): Исход => ({
  вид: 'остановка',
  ключ,
  находки: [],
  чужие: [],
  разрывы: [],
  невосстановленные: [],
  ...ещё,
});

/** Код отказа сервера, если он его назвал. По коду ход решает, а по тексту говорит окно. */
function кодОтказа(ошибка: unknown): string | null {
  const ответ = (ошибка as {ответ?: {код?: unknown}})?.ответ;

  return typeof ответ?.код === 'string' ? ответ.код : null;
}
