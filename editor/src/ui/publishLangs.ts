// Галочки языков в окне публикации (этап 3, решение владельца 2026-09-18, п.2) — чистые правила, чтобы
// проверять их машиной: окно отрисовать в проверках нечем (SPEC 4.10).
//
// - Строка есть у каждого языка сайта, и у каждой — его нынешнее состояние НА САЙТЕ.
// - Галочка — только у версии, чей файл лежит у человека: публиковать то, чего нет, нечем.
// - По умолчанию отмечен один открытый язык; его можно снять, но не все разом: без отмеченных
//   кнопка «Опубликовать» заперта.

import type {PublishState, ВерсияНаСайте} from './publishTypes';

/** Одна строка блока «Языки». `версия` — `null`, пока сайт не спрошен. */
export interface СтрокаЯзыка {
  путь: string;
  локаль: string | null;
  можноОтметить: boolean;
  отмечен: boolean;
  версия: ВерсияНаСайте | null;
}

/**
 * Строки языков. Пока состояние не пришло, языки берутся из свода статьи (`версии` — язык → путь, в
 * порядке `порядок`): окно открывается сразу, не дожидаясь сайта, и пути человеку не показывает
 * никогда (проба владельца 2026-09-19). Свода нет — строка одна, открытый язык.
 */
export function строкиЯзыков(
  состояние: PublishState | null, path: string, отмечены: string[], версии: Record<string, string> = {}, порядок: string[] = [],
): СтрокаЯзыка[] {
  if (состояние === null) {
    const свои = порядок.filter((код) => typeof версии[код] === 'string');
    if (свои.length === 0) return [{путь: path, локаль: null, можноОтметить: true, отмечен: отмечены.includes(path), версия: null}];
    return порядок.map((код) => {
      const путь = версии[код] ?? `:${код}`;
      const есть = typeof версии[код] === 'string';
      return {путь, локаль: код, можноОтметить: есть, отмечен: есть && отмечены.includes(путь), версия: null};
    });
  }
  return состояние.локали.map((версия) => ({
    путь: версия.путь,
    локаль: версия.локаль,
    можноОтметить: версия.файлЕсть === true,
    отмечен: версия.файлЕсть === true && отмечены.includes(версия.путь),
    версия,
  }));
}

/** Снять или поставить галочку. Версию без файла отметить нельзя вовсе. */
export function переключить(строки: СтрокаЯзыка[], отмечены: string[], путь: string): string[] {
  if (!строки.some((строка) => строка.путь === путь && строка.можноОтметить)) return отмечены;
  return отмечены.includes(путь) ? отмечены.filter((свой) => свой !== путь) : [...отмечены, путь];
}

/** Что уйдёт на публикацию: отмеченные версии с файлом, по порядку строк. Пусто — кнопка заперта. */
export function кПубликации(строки: СтрокаЯзыка[]): string[] {
  return строки.filter((строка) => строка.отмечен).map((строка) => строка.путь);
}

/**
 * В скольких статьях уберутся ссылки, если отмеченные версии станут недоступными: по всем
 * отмеченным. Какие статьи у каждой версии, сервер считает правилом самой публикации (у версии без
 * страницы на сайте их нет). Статья, ссылающаяся на две такие версии, считается одной — как её
 * считает и сама публикация (`ссылкиВСтатьях`).
 */
export function ссылокВОтмеченных(строки: СтрокаЯзыка[]): number {
  const статьи = new Set<string>();
  for (const {отмечен, версия} of строки) {
    if (!отмечен || версия === null) continue;
    for (const ключ of версия.статьи ?? []) статьи.add(ключ);
  }
  return статьи.size;
}
