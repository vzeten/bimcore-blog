// Ход удаления статьи: что за чем спрашивается у сервера и чем это кончается.
//
// Отдельно от React по той же причине, что и ход публикации (`publishRun.ts`): порядок шагов и
// состав запросов — поведение программы, и проверять его обязана машина, а не только глаза.
//
// **Вопрос один и задаётся до всякой записи** (решение владельца 2026-09-18). До него ход только
// дописывает черновик и спрашивает сервер, что снимется; после «Удалить» идёт сам до конца:
// статья, бывшая на сайте, сначала снимается оттуда (запись, отправка), затем ссылки на неё убираются
// на диске, и только потом все языки уходят в корзину. Порядок вынужден: каждый заслон записи и
// отправки сверяет файлы статьи на диске, а после корзины их там нет.
//
// Полной сборки сайта в этом ходе нет: снятие только убирает файлы и превращает ссылки в текст,
// а сайт собирает GitHub.

/** Что сервер говорит о снятии до вопроса. */
export interface Снятие {
  наСайте: boolean;
  /** Сколько статей получат правку ссылок. */
  статей: number;
  /** Отпечаток показанного плана снятия: согласие человека относится к нему. */
  отпечаток: string | null;
  /** Название статьи, как в реестре (по основному языку), и её версии на компьютере — коды языков. */
  название?: string;
  языки?: string[];
}

export type ИсходВопроса =
  | {вид: 'спрашиваю'; снятие: Снятие}
  | {вид: 'остановка'; текст: string}
  | {вид: 'прервано'};

export type ИсходУдаления = {вид: 'удалено'} | {вид: 'остановка'; текст: string};

/** Всё, что ходу нужно снаружи: дверь к серверу, дописывание черновика, слова и признак окна. */
export interface ХодУдаления {
  запрос: <T>(адрес: string, тело: Record<string, unknown>) => Promise<T>;
  /** Дописать ждущую правку в черновик: корзина уносит его вместе со статьёй. */
  дописать: () => Promise<boolean>;
  /** То же ли окно: сменилось — вопрос не задаётся. */
  жива: () => boolean;
  слово: (ключ: string, значения?: Record<string, string | number>) => string;
}

type Отказ = {message?: string; ответ?: {код?: string; разрывы?: {путь?: string}[]}};

/** Текст отказа сервера и пути, которые он назвал: человеку надо знать, где именно беда. */
function словаОтказа(ошибка: unknown): string {
  const отказ = ошибка as Отказ;
  const пути = (отказ?.ответ?.разрывы ?? []).map((разрыв) => разрыв.путь).filter(Boolean);
  return [отказ?.message ?? '', ...пути].filter(Boolean).join(' ');
}

const кодОтказа = (ошибка: unknown): string | null => (ошибка as Отказ)?.ответ?.код ?? null;

/**
 * До вопроса: дописать черновик, убедиться, что статью можно удалить, и узнать у сервера, была ли
 * она на сайте и сколько статей получат правку ссылок. Своё прошлое снятие, записанное, но не
 * уехавшее, досылается здесь же — один раз: согласие на него человек уже дал.
 */
export async function спроситьУдаление(path: string, ход: ХодУдаления, ужеДослали = false): Promise<ИсходВопроса> {
  if (!ужеДослали) {
    // Набранное, но не ушедшее в черновик, дописывается первым: иначе оно осталось бы только в
    // очереди окна, которое удаление закроет.
    if (!(await ход.дописать())) return {вид: 'остановка', текст: ход.слово('удалениеБезЧерновика')};
    if (!ход.жива()) return {вид: 'прервано'};
  }

  try {
    // Можно ли удалить вообще: страница раздела и чужой путь отказываются до вопроса.
    const состав = await ход.запрос<{название?: string; языки?: string[]}>('/api/article/delete', {path});
    const снятие = await ход.запрос<Снятие>('/api/retire', {path});
    if (!ход.жива()) return {вид: 'прервано'};
    return {вид: 'спрашиваю', снятие: {...снятие, название: состав?.название, языки: состав?.языки}};
  } catch (ошибка) {
    if (кодОтказа(ошибка) !== 'снятиеНеДослано' || ужеДослали) return {вид: 'остановка', текст: словаОтказа(ошибка)};
  }

  try {
    if (!(await дослать(path, ход))) return {вид: 'остановка', текст: ход.слово('удалениеНеОтправилось')};
  } catch (ошибка) {
    return {вид: 'остановка', текст: словаОтказа(ошибка)};
  }
  return спроситьУдаление(path, ход, true);
}

/** Дослать ожидающую запись общими ручками отправки. Отвечает, на сайте ли она теперь. */
async function дослать(path: string, ход: ХодУдаления): Promise<boolean> {
  const план = await ход.запрос<{sha: string}>('/api/publish/plan', {path});
  const отправка = await ход.запрос<{отправлено?: boolean; уже?: boolean}>(
    '/api/publish/push',
    {path, sha: план.sha, подтверждено: true},
  );
  return отправка.отправлено === true || отправка.уже === true;
}

/**
 * После «Удалить»: снять с сайта (если статья там была), убрать ссылки на диске, унести в корзину.
 * С этого места ход не отменяется — остановка между отправкой и корзиной оставила бы статью снятой,
 * но на месте, и повтор удаления это доведёт.
 */
export async function провестиУдаление(path: string, снятие: Снятие, ход: ХодУдаления): Promise<ИсходУдаления> {
  try {
    if (снятие.наСайте) {
      await ход.запрос('/api/retire/commit', {path, подтверждено: true, отпечаток: снятие.отпечаток ?? ''});
      if (!(await дослать(path, ход))) return {вид: 'остановка', текст: ход.слово('удалениеНеОтправилось')};
    }

    const уборка = await ход.запрос<{изменены: string[]; невосстановленные: string[]}>('/api/links/sweep', {path});
    if (уборка.невосстановленные.length > 0) {
      return {вид: 'остановка', текст: [ход.слово('удалениеСсылкиНеУбраны'), ...уборка.невосстановленные].join(' ')};
    }

    await ход.запрос('/api/article/delete', {path, подтверждено: 'корзина'});
    return {вид: 'удалено'};
  } catch (ошибка) {
    return {вид: 'остановка', текст: словаОтказа(ошибка)};
  }
}
