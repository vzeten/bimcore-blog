import {useState} from 'react';
import {requestJson} from './api';
import {label} from './labels';
import {провестиУдаление, спроситьУдаление, type Снятие, type ХодУдаления} from './retireRun';

/** Что сервер сказал о снятии — для этого окна статьи. Сменилось окно — вопрос не показывается. */
export interface Предложение extends Снятие {
  окно: string;
}

export interface Удаление {
  идёт: boolean;
  предложение: Предложение | null;
  спросить: () => Promise<void>;
  удалить: () => Promise<void>;
  отменить: () => void;
}

/**
 * Удаление открытой статьи: одно нажатие «Удалить статью», один вопрос, дальше программа идёт сама
 * (порядок — в `retireRun.ts`). Здесь только состояние окна: что показать и когда статья закрыта.
 *
 * Окно меняется только после ответа сервера: до него статья ещё на диске, и убрать её с экрана
 * значило бы соврать человеку. Реестр перечитывается после любого исхода: список статей обязан
 * показывать диск, а не то, что было до нажатия.
 */
export function useDelete(deps: {
  путь: () => string | null;
  /** Номер захода в статью: та же статья, открытая заново, — уже другое окно. */
  заход: () => number;
  /** Очередь черновика: перед вопросом ждущая правка дописывается, чтобы уехать в корзину вместе со статьёй. */
  автосохранение: {отменить: () => void; дописать: () => Promise<boolean>};
  обновить: () => Promise<void>;
  закрытьСтатью: () => Promise<void> | void;
  onОшибка: (текст: string) => void;
  onУдалено: (текст: string) => void;
}): Удаление {
  const [идёт, setИдёт] = useState(false);
  const [предложение, setПредложение] = useState<Предложение | null>(null);
  const окно = (): string => `${deps.путь()}|${deps.заход()}`;

  const ход = (своё: string): ХодУдаления => ({
    запрос: <T>(адрес: string, тело: Record<string, unknown>) => requestJson<T>(адрес, {
      method: 'POST',
      headers: {'Content-Type': 'application/json'},
      body: JSON.stringify(тело),
    }),
    дописать: deps.автосохранение.дописать,
    жива: () => окно() === своё,
    слово: label,
  });

  const спросить = async (): Promise<void> => {
    const путь = deps.путь();
    if (путь === null || идёт) return;
    setИдёт(true);
    const своё = окно();
    const исход = await спроситьУдаление(путь, ход(своё));
    if (исход.вид === 'спрашиваю') setПредложение({...исход.снятие, окно: своё});
    if (исход.вид === 'остановка') {
      deps.onОшибка(исход.текст);
      await deps.обновить();
    }
    setИдёт(false);
  };

  const удалить = async (): Promise<void> => {
    const путь = deps.путь();
    // Пока ход идёт, второе нажатие ничего не запускает: второе снятие той же статьи ответило бы
    // отказом о том, что всё как раз получилось.
    if (путь === null || идёт || предложение === null) return;
    const своё = окно();
    if (предложение.окно !== своё) {
      setПредложение(null);
      return;
    }
    setИдёт(true);
    const исход = await провестиУдаление(путь, предложение, ход(своё));
    setПредложение(null);
    await deps.обновить();
    if (исход.вид === 'удалено') {
      // Закрывать статью и гасить автосохранение можно только в том окне, где удаление и
      // начиналось: иначе закрыли бы чужую статью и выбросили бы её правку.
      if (окно() === своё) {
        deps.автосохранение.отменить();
        await deps.закрытьСтатью();
        deps.onУдалено(label('статьяВКорзине'));
      }
    } else {
      deps.onОшибка(исход.текст);
    }
    setИдёт(false);
  };

  // Пока ход идёт, отменить нечего: после «Удалить» программа доводит начатое до конца.
  return {идёт, предложение, спросить, удалить, отменить: () => (идёт ? undefined : setПредложение(null))};
}
