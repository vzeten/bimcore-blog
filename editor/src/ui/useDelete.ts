import {useState} from 'react';
import {deleteArticle} from './actions';
import {label} from './labels';

/**
 * Удаление открытой статьи. Вынесено из окна, чтобы оно не выходило за предел размера файла
 * (SPEC 4.9), а правило «удалено — значит уходим в реестр» лежало одним куском.
 *
 * Окно меняется только после ответа сервера: до него статья ещё на диске, и убрать её с экрана
 * значило бы соврать человеку. Ждущая правка при этом не дописывается — файла, в который её
 * писать, больше нет, и попытка записи вернула бы удалённую статью на диск.
 */
export function useDelete(deps: {
  путь: () => string | null;
  /** Номер захода в статью: та же статья, открытая заново, — уже другое окно. */
  заход: () => number;
  автосохранение: {отменить: () => void};
  обновить: () => Promise<void>;
  закрытьСтатью: () => Promise<void> | void;
  onОшибка: (текст: string) => void;
  onУдалено: (текст: string) => void;
}) {
  const [идёт, setИдёт] = useState(false);

  const удалить = async (): Promise<void> => {
    const путь = deps.путь();
    // Пока сервер не ответил, второе нажатие ничего не запускает: два удаления подряд дали бы
    // вторым ответом «нет такой статьи» — ошибку о том, что всё как раз получилось.
    if (путь === null || идёт) return;
    setИдёт(true);

    const окно = `${путь}|${deps.заход()}`;
    const тоЖеОкно = (): boolean => `${deps.путь()}|${deps.заход()}` === окно;

    await deleteArticle(путь, {
      ok: async (итог) => {
        // Реестр перечитывается всегда: статьи на диске больше нет, и список обязан это показать,
        // на каком бы экране человек сейчас ни был.
        await deps.обновить();
        // А вот закрывать статью и гасить автосохранение можно только в том окне, где удаление
        // и начиналось. Успел уйти в другую статью — закрыли бы её и выбросили бы её правку:
        // это тихая потеря чужой работы из-за удаления соседа.
        if (!тоЖеОкно()) return;

        deps.автосохранение.отменить();
        await deps.закрытьСтатью();
        // Предупреждения сервера говорятся вместе с успехом: статья удалена, но её черновик,
        // история или картинки могли остаться на диске, и знать об этом человек должен.
        const хвосты = итог.предупреждения ?? [];
        deps.onУдалено([label('статьяУдалена'), ...хвосты].join(' '));
      },
      // Отказ — обычный путь: статью, уже вышедшую на сайт, программа не удаляет. Статья
      // остаётся открытой, работа человека на месте.
      //
      // Реестр перечитывается и здесь: отказ бывает и после того, как часть файлов уже стёрта
      // (сбой посреди удаления). Список статей обязан показывать диск, а не то, что было до
      // нажатия, — иначе человек ищет статью, которой уже нет.
      fail: async (текст, стёрто) => {
        // Что уже исчезло — часть причины: в списке статей видно только статьи, а стёртые
        // картинки человек иначе не найдёт вовсе.
        deps.onОшибка(стёрто.length > 0 ? `${текст} ${стёрто.join(', ')}` : текст);
        await deps.обновить();
      },
    });

    setИдёт(false);
  };

  return {идёт, удалить};
}
