import {useState} from 'react';
import {deleteArticle, type DeletePreview, type DeleteResult} from './actions';
import {label} from './labels';

/** Предложение сервера: режим и состав для этого окна статьи. Сменилось окно — предложение не показывается. */
export interface Предложение extends DeletePreview {
  окно: string;
}

export interface Удаление {
  идёт: boolean;
  предложение: Предложение | null;
  спросить: () => Promise<void>;
  удалить: () => Promise<void>;
  отменить: () => void;
}

/**
 * Удаление открытой статьи двумя заходами: сначала сервер говорит, что статья уйдёт в корзину и
 * была ли она на сайте, и окно показывает это словами, потом человек подтверждает. Вынесено из окна, чтобы
 * оно не выходило за предел размера файла (SPEC 4.9), а правило «удалено — значит уходим в реестр»
 * лежало одним куском.
 *
 * Окно меняется только после ответа сервера: до него статья ещё на диске, и убрать её с экрана
 * значило бы соврать человеку. Ждущая правка при этом не дописывается — файла, в который её
 * писать, больше нет, и попытка записи вернула бы удалённую статью на диск.
 */
/**
 * Ход удаления после подтверждения, без React: сперва дописать ждущий черновик, и только если он
 * записан и окно то же самое — удалить. Не записан — удаления нет: набранное осталось бы только в
 * очереди окна, которое сейчас закроется. Сменилось окно — старое предложение не исполняется.
 */
export async function провестиУдаление(шаг: {
  дописать: () => Promise<boolean>;
  окно: () => string;
  своё: string;
  удалить: () => Promise<void>;
  onОшибка: (текст: string) => void;
}): Promise<'удалено' | 'черновикНеЗаписан' | 'окноСменилось'> {
  const записан = await шаг.дописать();
  if (!записан) {
    шаг.onОшибка(label('удалениеБезЧерновика'));
    return 'черновикНеЗаписан';
  }
  if (шаг.окно() !== шаг.своё) return 'окноСменилось';
  await шаг.удалить();
  return 'удалено';
}

export function useDelete(deps: {
  путь: () => string | null;
  /** Номер захода в статью: та же статья, открытая заново, — уже другое окно. */
  заход: () => number;
  /** Очередь черновика: перед удалением ждущая правка дописывается, чтобы уехать в корзину вместе со статьёй. */
  автосохранение: {отменить: () => void; дописать: () => Promise<boolean>};
  обновить: () => Promise<void>;
  закрытьСтатью: () => Promise<void> | void;
  onОшибка: (текст: string) => void;
  onУдалено: (текст: string) => void;
}): Удаление {
  const [идёт, setИдёт] = useState(false);
  const [предложение, setПредложение] = useState<Предложение | null>(null);
  const окно = (): string => `${deps.путь()}|${deps.заход()}`;

  const спросить = async (): Promise<void> => {
    const путь = deps.путь();
    if (путь === null || идёт) return;
    setИдёт(true);
    const своё = окно();
    await deleteArticle<DeletePreview>(путь, null, {
      ok: (итог) => setПредложение({...итог, окно: своё}),
      fail: (текст) => deps.onОшибка(текст),
    });
    setИдёт(false);
  };

  const удалить = async (): Promise<void> => {
    const путь = deps.путь();
    // Пока сервер не ответил, второе нажатие ничего не запускает: два удаления подряд дали бы
    // вторым ответом «нет такой статьи» — ошибку о том, что всё как раз получилось.
    if (путь === null || идёт || предложение === null) return;
    setИдёт(true);
    const своё = окно();
    const тоЖеОкно = (): boolean => окно() === своё;

    // Набранное, но ещё не ушедшее в черновик, сначала дописывается: корзина уносит черновик с
    // диска, и правка, застрявшая в очереди окна, иначе пропала бы вместе с закрытием статьи.
    const итог = await провестиУдаление({
      дописать: deps.автосохранение.дописать,
      окно,
      своё,
      onОшибка: deps.onОшибка,
      удалить: () => deleteArticle<DeleteResult>(путь, предложение.режим, {
      ok: async () => {
        setПредложение(null);
        // Реестр перечитывается всегда: статьи на диске больше нет, и список обязан это показать.
        await deps.обновить();
        // Закрывать статью и гасить автосохранение можно только в том окне, где удаление и
        // начиналось: иначе закрыли бы чужую статью и выбросили бы её правку.
        if (!тоЖеОкно()) return;
        deps.автосохранение.отменить();
        await deps.закрытьСтатью();
        deps.onУдалено(label('статьяВКорзине'));
      },
      // Отказ — обычный путь: статья успела измениться или перенос оборвался. Реестр
      // перечитывается и здесь: список статей обязан показывать диск, а не то, что было до нажатия.
      fail: async (текст, стёрто) => {
        setПредложение(null);
        deps.onОшибка(стёрто.length > 0 ? `${текст} ${стёрто.join(', ')}` : текст);
        await deps.обновить();
      },
      }),
    });
    if (итог !== 'удалено') setПредложение(null);
    setИдёт(false);
  };

  return {идёт, предложение, спросить, удалить, отменить: () => setПредложение(null)};
}
