import {useState} from 'react';
import {startLocale} from './actions';
import {label} from './labels';

/** Вопрос, заданный в окне: про какой язык спросили и в какой статье. */
export type ВопросЛокали = {локаль: string; окно: string | null} | null;

/**
 * Какой язык предложено начать в ЭТОМ окне. Чужой вопрос не показывается и не действует.
 *
 * Правило вынесено из хука отдельной функцией, чтобы его можно было проверить результатом, а не
 * отрисовкой (SPEC 5.2.1): библиотеки для проверки React-хуков в программе нет, и заводить её
 * ради одного правила — плата больше пользы (SPEC 4.10).
 */
export function вопросОкна(вопрос: ВопросЛокали, окно: string | null): string | null {
  return вопрос !== null && вопрос.окно === окно ? вопрос.локаль : null;
}

/** Что нужно ходу начала версии. Всё снаружи — сам ход ни о чём не знает, кроме порядка шагов. */
export type ХодНачала = {
  путь: string;
  локаль: string;
  /** Окно на момент нажатия и способ спросить, то же ли оно сейчас. */
  окноБыло: string | null;
  окноСейчас: () => string | null;
  сохранить: () => Promise<boolean>;
  обновить: () => Promise<void>;
  открыть: (path: string) => Promise<boolean>;
  запрос: (тело: {path: string; локаль: string}) => Promise<{path: string}>;
  onОшибка: (текст: string) => void;
  onНачато: (текст: string) => void;
};

/**
 * Ход начала версии по шагам. Отдельно от хука: порядок шагов — правило, и проверяться он должен
 * результатом, а не отрисовкой (SPEC 5.2.1). Возвращает `true`, если вопрос пора убирать с экрана.
 *
 * Порядок жёсткий и сокращению не подлежит:
 * 1. Несохранённое ложится на диск. Название и адрес новой версии сервер берёт из ФАЙЛА исходной:
 *    не запиши окно раньше запроса, переименованная, но не сохранённая статья дала бы соседу
 *    старое название и старый адрес. Не легло — не создаём ничего.
 * 2. Запрос к серверу. Отказ — ничего не создано, и делать вид, что создано, нельзя.
 * 3. Реестр перечитывается: созданной версии в списке ещё нет.
 * 4. Ушли в другую статью, пока шёл запрос, — версия создана, но окно человека не трогаем и об
 *    открытии не рассказываем: он читает уже другое.
 * 5. Переход мог не состояться (не легла ждущая правка, файл не прочитался). Тогда «версия
 *    открыта» — враньё, да ещё и поверх настоящей причины отказа.
 */
export async function провестиНачало(ход: ХодНачала): Promise<boolean> {
  if (!(await ход.сохранить())) return false;

  let созданная: {path: string} | null = null;
  try {
    созданная = await ход.запрос({path: ход.путь, локаль: ход.локаль});
  } catch (error) {
    ход.onОшибка(error instanceof Error ? error.message : String(error));
    return false;
  }

  await ход.обновить();
  if (ход.окноСейчас() !== ход.окноБыло) return true;
  if (await ход.открыть(созданная.path)) ход.onНачато(label('версияНачата'));

  return true;
}

/**
 * Начало языковой версии из вкладки языка. Вынесено из окна, чтобы оно не выходило за предел
 * размера файла (SPEC 4.9), а правило «спросили — записали окно — создали — открыли» лежало
 * одним куском.
 *
 * Главное правило здесь одно: до явного согласия человека не пишется ни один файл. Нажатие на
 * вкладку отсутствующего языка только задаёт вопрос; отмена не отправляет на сервер ничего.
 */
export function useLocaleStart(deps: {
  путь: () => string | null;
  /**
   * Какая статья открыта прямо сейчас: путь и номер захода в неё. Вопрос принадлежит своему окну.
   * Без этого спросили бы про испанскую версию одной статьи, ушли в другую — и «Начать версию»
   * завело бы файл у соседа, которого человек об этом не просил.
   */
  окно: () => string | null;
  /** Записать окно на диск, если в нём есть несохранённая правка. Отвечает, легла ли работа. */
  сохранить: () => Promise<boolean>;
  обновить: () => Promise<void>;
  /** Открыть созданную версию. Отвечает, состоялся ли переход. */
  открыть: (path: string) => Promise<boolean>;
  onОшибка: (текст: string) => void;
  onНачато: (текст: string) => void;
}) {
  // Какой язык человек предложил начать и в каком окне. `null` — вопрос не задан.
  const [вопрос, setВопрос] = useState<ВопросЛокали>(null);
  const [идёт, setИдёт] = useState(false);
  // Вопрос из чужого окна не показывается и не действует: он относился к другой статье.
  const спрошено = вопросОкна(вопрос, deps.окно());

  const начать = async (локаль: string): Promise<void> => {
    const путь = deps.путь();
    // Спрашивали про другую статью — не делаем ничего: окно успело смениться.
    if (спрошено !== локаль) return;
    // Пока сервер не ответил, второе нажатие ничего не запускает: второй запрос вернул бы
    // «путь занят» — отказ о том, что всё как раз получилось.
    if (путь === null || идёт) return;

    setИдёт(true);
    const убрать = await провестиНачало({
      путь,
      локаль,
      окноБыло: deps.окно(),
      окноСейчас: deps.окно,
      сохранить: deps.сохранить,
      обновить: deps.обновить,
      открыть: deps.открыть,
      запрос: (тело) => new Promise((готово, беда) => {
        void startLocale(тело, {ok: готово, fail: (причина) => беда(new Error(причина))});
      }),
      onОшибка: deps.onОшибка,
      onНачато: deps.onНачато,
    });

    if (убрать) setВопрос(null);
    setИдёт(false);
  };

  return {
    спрошено,
    идёт,
    спросить: (локаль: string) => setВопрос({локаль, окно: deps.окно()}),
    отменить: () => setВопрос(null),
    начать,
  };
}
