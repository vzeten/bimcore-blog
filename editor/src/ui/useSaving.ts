import type {Dispatch, MutableRefObject, SetStateAction} from 'react';
import {autosaveDraft, saveArticle} from './actions';
import {label} from './labels';
import {buildFrontmatter, порядокПолей, type Field} from './headFields';
import type {DraftPayload} from './useAutosave';
import type {Article, SaveState, Settings, Спор} from './types';

/**
 * Служебные шаги сохранения, которые могли не пройти. Слева — код от сервера (внутренний договор),
 * справа — имя надписи в настройках: человеческий текст в коде не живёт.
 */
const ПРЕДУПРЕЖДЕНИЯ: Record<string, string> = {
  история: 'историяНеЗаписана',
  черновик: 'черновикНеУбран',
  состояние: 'состояниеНеЗаписано',
};

/**
 * Что делать с окном после удачной записи. Три исхода, и третий — тот, ради которого правило
 * вынесено сюда: сервер СВЁЛ нашу работу с внешней правкой, а человек всё это время печатал.
 *
 * `сдвинуть` — в файле ровно то, что послало окно: база двигается на записанное, текст не трогаем.
 * `подставить` — сервер свёл стороны, но человек больше ничего не набрал: в окно кладётся то, что
 * действительно лежит в файле, иначе окно показывало бы не файл, называя это «Сохранено».
 * `оставить` — сервер свёл стороны, и человек продолжил печатать. База окна НЕ двигается: набранное
 * им не знает про внешнюю правку, и уйди оно на сервер с отпечатком нового файла — сервер не увидел
 * бы расхождения и молча стёр бы внешнее изменение. Со старой базой он сведёт всё заново.
 */
export function исходЗаписи(
  {свелось, печаталДальше}: {свелось: boolean; печаталДальше: boolean},
): 'сдвинуть' | 'подставить' | 'оставить' {
  if (!свелось) return 'сдвинуть';
  return печаталДальше ? 'оставить' : 'подставить';
}

/**
 * Что окно помнит о своих удачных записях в одном заходе в статью: от каких отпечатков файла оно уже
 * ушло своими записями и какой отпечаток вернул сервер последним.
 */
export interface ПамятьЗаписей {
  путь: string;
  заход: number;
  пройденные: string[];
  последний: string;
}

/**
 * От какого отпечатка файла идёт запись.
 *
 * **Зачем это правило.** Ход публикации держит обработчики окна с того мгновения, когда человек нажал
 * «Опубликовать», и пишет файл несколько раз подряд: доступность, дату блога, обложку. Статья в этих
 * обработчиках — того же мгновения, и каждая следующая запись уходила с отпечатком файла ДО первой.
 * Сервер видел расхождение, доказать такую базу не мог и отвечал «файл изменён снаружи» — публикация
 * кончалась «Не удалось сохранить изменения» (проба владельца 2026-09-21).
 *
 * Подстановка узкая намеренно. Отпечаток меняется, только если он ПРОЙДЕН собственной удачной записью
 * этого же захода, и только на тот, что вернул сервер после неё. Настоящая внешняя правка после
 * нашей записи даёт файлу другой отпечаток — сервер её по-прежнему видит и сводит. Любой другой
 * отпечаток (открытие, возврат к версии, решение спора) идёт как есть.
 */
export function базаЗаписи(отпечаток: string, путь: string, заход: number, память: ПамятьЗаписей | null): string {
  if (память === null || память.путь !== путь || память.заход !== заход) return отпечаток;
  return память.пройденные.includes(отпечаток) ? память.последний : отпечаток;
}

/** Запомнить удачную запись: `от` — отпечатки, с которыми она ушла, `стало` — что вернул сервер. */
export function запомнитьЗапись(
  память: ПамятьЗаписей | null, {путь, заход, от, стало}: {путь: string; заход: number; от: string[]; стало: string},
): ПамятьЗаписей {
  const свои = память !== null && память.путь === путь && память.заход === заход ? память.пройденные : [];
  return {путь, заход, пройденные: [...new Set([...свои, ...от])].filter((отпечаток) => отпечаток !== стало), последний: стало};
}

/**
 * Запись на диск: сохранение статьи.
 * Вынесено из окна, чтобы правило «состояние меняется только после подтверждения сервера»
 * лежало одним куском, а окно не выходило за предел размера файла (SPEC 4.9).
 */
export function useSaving(deps: {
  article: Article | null;
  /** Настройки могут быть ещё не загружены: тогда писать нечем и незачем. */
  settings: Settings | null;
  /** Поля шапки — запасной путь: обычно шапку берём из ref, он свежее состояния. */
  fields: Field[];
  /** Что в окне прямо сейчас: пока запрос идёт, человек печатает дальше. */
  текстСейчас: MutableRefObject<string>;
  шапкаСейчас: MutableRefObject<string>;
  /** Какая статья открыта сейчас: ответ по прошлой статье не должен трогать новую. */
  статьяСейчас: MutableRefObject<string | null>;
  /** Номер открытия статьи: та же статья, открытая заново, — уже другое окно. */
  открытие: MutableRefObject<number>;
  /**
   * Память удачных записей этого окна (`базаЗаписи`). Ref, а не состояние: ход публикации держит
   * обработчики одного мгновения, и узнать о своей предыдущей записи он может только отсюда.
   */
  последняяЗапись: MutableRefObject<ПамятьЗаписей | null>;
  автосохранение: {
    запланировать: (данные: DraftPayload) => void;
    отменить: () => void;
    /** Общие с очередью часы правок: метки строго возрастают, поэтому порядок записей известен. */
    метка: () => string;
  };
  setArticle: Dispatch<SetStateAction<Article | null>>;
  setDirty: (dirty: boolean) => void;
  setОшибка: (текст: string | null) => void;
  /** Отложенное сервером расхождение этой версии: показывается панелью со сторонами. */
  setСпор: (спор: Спор | null) => void;
  setСостояние: (state: SaveState) => void;
  refresh: () => Promise<void>;
  сПричиной: (ключ: string, причина: string, хвост?: string) => string;
  /** Вернуть в очередь автосохранения то, что уже в окне: сохранение не прошло. */
  вЧерновик: () => void;
  /**
   * Положить в окно то, что сервер записал в файл, вместе с новой базой сравнения.
   * Нужно, когда он свёл нашу работу с внешней правкой: в файле тогда не то, что послало окно.
   */
  положитьЗаписанное: (пара: {body: string; frontmatterRaw: string}) => void;
  /**
   * Работа записана в файл. Откатывать возврат к версии после этого не к чему: на диске
   * уже другое состояние, и кнопка «Вернуть как было» обещала бы несуществующее.
   */
  послеЗаписи: () => void;
}) {
  /**
   * Сервер работу не принял, а окно уже ушло в другую статью: показывать ошибку там бессмысленно,
   * но и бросать работу нельзя — в окне её больше нет. Пишем прямо в черновик той статьи,
   * которую сохраняли, минуя очередь: очередь держит одну правку и затёрла бы правку новой статьи.
   */
  const спасти = (путь: string, тело: string, шапка: string, отпечаток: string, правкаОт: string): void => {
    // Время берётся с момента начала сохранения, а не ответа: за время запроса человек мог
    // вернуться в статью и набрать новее — тогда сервер эту спасённую правку отклонит как старую.
    void autosaveDraft(
      {path: путь, body: тело, frontmatterRaw: шапка, отпечатокБазы: отпечаток, правкаОт},
      {
        // Сказать надо и про удачу: окно с этой работой уже закрыто или переоткрыто, человек её
        // не видит и должен знать, что она лежит в черновике и статью надо открыть заново.
        // Сервер мог и отклонить её как устаревшую — тогда она не спасена, и это тоже правда.
        ok: (ответ) => deps.setОшибка(label(ответ?.устарел === true ? 'работаНеСпасена' : 'работаВЧерновике')),
        // Не вышло и это — работа не спасена нигде, и человек обязан об этом узнать:
        // окно с ней уже закрыто, и молчание означало бы тихую потерю.
        fail: () => deps.setОшибка(label('работаНеСпасена')),
      },
    );
  };

  /**
   * «Сохранено» — только после успеха сервера. Записи поверх чужой правки здесь нет: внешнюю
   * правку сервер сводит с работой человека сам, а пересечение возвращает расхождением.
   *
   * Отвечает, легла ли работа на диск целиком. Ответ нужен публикации: она судит о файле, а не об
   * экране, и права начинать проверки только тогда, когда в файле лежит ровно то, что видит человек.
   * Обычным нажатием кнопки ответ не читается — там о судьбе записи говорят состояние и полоса ошибок.
   */
  const save = async (): Promise<boolean> => {
    const article = deps.article;
    if (!article || !deps.settings) return false;
    let записано = false;

    const путь = article.path;
    // Текст и шапку берём из ref, а не из состояния: последняя буква могла ещё не дойти до
    // перерисовки, и сохранение записало бы текст без неё, попутно сняв очередь черновика с ней.
    const тело = deps.текстСейчас.current;
    const шапка = deps.шапкаСейчас.current
      || buildFrontmatter(article.frontmatterRaw, deps.fields, путь, deps.settings.контент,
        порядокПолей(deps.settings, путь), deps.settings.сайт?.обложкаПоУмолчанию ?? null);
    // Время правки, которую сохраняем. По нему сервер отличает запоздавшее сохранение от свежего
    // и не удаляет черновик, написанный уже после начала этого запроса. Часы общие с очередью:
    // две записи с одинаковой меткой сервер не смог бы упорядочить.
    const правкаОт = deps.автосохранение.метка();
    // То же окно — это та же статья И тот же заход в неё: статью могли закрыть и открыть заново,
    // и тогда в окне уже другой текст, а работу этого запроса надо спасать, а не подменять.
    const заход = deps.открытие.current;
    const тоЖеОкно = (): boolean => deps.статьяСейчас.current === путь && deps.открытие.current === заход;
    // Статья в этом замыкании могла устареть собственной записью окна (ход публикации пишет файл
    // несколько раз подряд) — тогда запись идёт от отпечатка, который вернул сервер после неё.
    const отпечатокБазы = базаЗаписи(article.отпечаток, путь, заход, deps.последняяЗапись.current);
    deps.текстСейчас.current = тело;
    deps.шапкаСейчас.current = шапка;
    // Снимаем ждущее автосохранение ДО запроса: поздний ответ воскресил бы черновик после записи.
    deps.автосохранение.отменить();

    await saveArticle(
      {path: путь, body: тело, frontmatterRaw: шапка, отпечатокБазы, правкаОт},
      {
        ok: (ответ) => {
          void deps.refresh();
          // Файл записан, но служебный шаг мог не пройти. Молчать нельзя: человек считал бы,
          // что версия в истории есть и готовность обновилась, а на диске этого нет.
          // Показываем и когда окно уже ушло в другую статью: предупреждение относится к работе,
          // а не к экрану, и терять его нельзя. Про соседние языковые версии здесь не говорится
          // ничего: сохранение их не трогает, видимость принадлежит версии (SPEC 2.8).
          const беда = (ответ?.предупреждения ?? [])
            .map((код) => label(ПРЕДУПРЕЖДЕНИЯ[код] ?? 'ошибкаЗапроса'));
          if (беда.length > 0) deps.setОшибка(беда.join(' '));

          // Пока запрос шёл, могли открыть другую статью: её состояние трогать нельзя.
          if (!тоЖеОкно()) return;
          // Файл записан — снимок для отката возврата больше не отражает диск. Строго после
          // проверки окна: поздний ответ прошлой статьи иначе снял бы кнопку «Вернуть как было»
          // у той статьи, что открыта сейчас.
          deps.послеЗаписи();
          if (беда.length === 0) deps.setОшибка(null);
          deps.setСпор(null);
          deps.setСостояние('сохранено');
          const новыйОтпечаток = ответ?.отпечаток;
          // Что на самом деле легло в файл. Сервер мог свести нашу работу с внешней правкой —
          // тогда это не то, что послало окно.
          const вФайле = ответ?.записано ?? {body: тело, frontmatterRaw: шапка};
          const свелось = вФайле.body !== тело || вФайле.frontmatterRaw !== шапка;
          // Человек мог печатать дальше: сохранён старый снимок, новая правка уходит в черновик.
          const печаталДальше = deps.текстСейчас.current !== тело || deps.шапкаСейчас.current !== шапка;
          const исход = исходЗаписи({свелось, печаталДальше});
          // База окна сдвинулась — запоминаем, от каких отпечатков мы ушли. «Оставить» базу не
          // двигает намеренно (см. `исходЗаписи`), и помнить там нечего.
          if (исход !== 'оставить' && typeof новыйОтпечаток === 'string') {
            deps.последняяЗапись.current = запомнитьЗапись(deps.последняяЗапись.current, {
              путь, заход, от: [article.отпечаток, отпечатокБазы], стало: новыйОтпечаток,
            });
          }

          // Готовность приходит с сервера уже посчитанной и записанной: правка после подготовки
          // возвращает версию в черновик. Своего правила перехода статусов окно не заводит —
          // оно бы разошлось с файлом состояния при первом же расхождении.
          // Состояния в ответе нет (сбой записи, старый ответ) — надпись остаётся прежней:
          // пустая готовность врала бы сильнее устаревшей.
          const готовность = ответ?.state?.готовность;
          deps.setArticle((было) => (было
            ? {
              ...было,
              готовность: готовность ?? было.готовность,
              // База сравнения двигается только там, где в файле доказанно лежит показанное.
              // Иначе она остаётся прежней, и ждущая правка уедет со СТАРЫМ отпечатком — сервер
              // увидит расхождение и сведёт её с внешней правкой, вместо того чтобы стереть её.
              ...(исход === 'оставить' ? {} : {
                body: вФайле.body,
                // Цепочка слоёв цвета кончается телом файла, а оно только что стало этим текстом.
                // Без этого своя правка осталась бы «набранной сейчас», хотя она уже на диске.
                телоФайла: вФайле.body,
                frontmatterRaw: вФайле.frontmatterRaw,
                отпечаток: новыйОтпечаток ?? было.отпечаток,
              }),
            }
            : было));

          // Работа легла на диск целиком только если человек не печатал дальше: иначе в файле не
          // всё, что он видит, и публикации об этом надо знать.
          записано = !печаталДальше;
          deps.setDirty(печаталДальше);
          if (исход === 'подставить') deps.положитьЗаписанное(вФайле);
          if (печаталДальше) {
            deps.автосохранение.запланировать({
              path: путь,
              body: deps.текстСейчас.current,
              frontmatterRaw: deps.шапкаСейчас.current,
              отпечатокБазы: исход === 'оставить' ? отпечатокБазы : (новыйОтпечаток ?? отпечатокБазы),
            });
          }
        },
        // Свести не вышло: ничего не записано, все стороны лежат на диске, решает человек.
        // Работа человека при этом уже сохранена сервером в черновик этой версии.
        conflict: (_причина, ответ) => {
          if (!тоЖеОкно()) return;
          deps.setСпор((ответ as {спор?: Спор | null})?.спор ?? null);
        },
        // dirty НЕ снимается — правки в окне не теряются, причину сервера показываем.
        fail: (reason) => {
          if (!тоЖеОкно()) return спасти(путь, тело, шапка, отпечатокБазы, правкаОт);
          deps.setОшибка(deps.сПричиной('ошибкаСохранения', reason, 'измененияНаМесте'));
          deps.вЧерновик();
        },
      },
    );

    // Ушли в другую статью, пока запрос шёл, — про эту работу здесь сказать нечего: она спасена
    // в черновик, но в файле её нет, и публиковать по ней нельзя.
    return записано && тоЖеОкно();
  };

  return {save};
}
