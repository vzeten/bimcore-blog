// Настройки программы, какими их отдаёт сервер окну. Отделены от понятий окна пределом размера
// файла (SPEC 4.9): смысл не менялся, и правил здесь нет — только вид справочника.
//
// Сам справочник живёт в `settings.json` и читается человеком целиком (SPEC 4.9.1).

import type {Button} from '../core/commands';
import type {ОписаниеБлока} from '../core/jsxBlocks';
import type {НастройкиДоработки} from './refineTypes';

export interface Column {
  ключ: string;
  подпись: string;
}

export interface Root {
  локаль: string;
  род: string;
  папка: string;
  наСайте: boolean;
}

export interface Settings {
  слои: Record<string, {подпись: string; цвет: string; пояснение: string}>;
  локали: Record<string, string>;
  основнойЯзык: string;
  /** Вид времени версий. Меняется в настройках, в коде своего формата нет. */
  форматВремени: Intl.DateTimeFormatOptions;
  обязательныйЯзык: string;
  категорияСлужебной: string;
  вставки: Button[];
  блоки: Record<string, ОписаниеБлока>;
  названияБлоков: Record<string, Record<string, string>>;
  призывПоРазделу: Record<string, string>;
  статусы: string[];
  подписи: Record<string, string>;
  /** Почему статья не создана: коды от сервера, слова человеку — здесь. */
  ошибкиСоздания: Record<string, string>;
  /** Почему поле шапки показано, но не правится: код причины — слова человеку. */
  полеЗаперто: Record<string, string>;
  видимость: {вМеню: string; поСсылке: string; новаяСкрыта: boolean};
  /** Слова выбора доступности: подпись поля и по строке на каждый из трёх ответов. */
  доступность: Record<string, string>;
  хранение: {
    файлСостояния: string;
    папкаЧерновиков: string;
    папкаСнимков: string;
    автосохранениеСек: number;
    черновикЖивётДней: number;
    снимковНаВерсию: number;
    /** Сколько сеансов истории показывать цветом. Предел показа, а не хранения. */
    слоёвИстории: number;
  };
  /** Кто есть кто: имя автора правки — вид слоя. Читается ядром при разборе истории. */
  слоиПоАвторам: Record<string, string>;
  категорииПоПути: Record<string, string>;
  категорииПоРоду: Record<string, string>;
  подписиПолей: Record<string, string>;
  названияРазделов: Record<string, string>;
  контент: Root[];
  /** Какие поля получает новая статья каждого рода. Порядок — он же порядок строк в шапке. */
  поляСоздания: Record<string, {порядок: string[]; значения: Record<string, string>}>;
  /**
   * Не настройка редактора, а факты самого сайта: сервер читает их из конфига Docusaurus.
   * `обложкаПоУмолчанию` — общая картинка сайта, которой он подменяет отсутствующую обложку
   * статьи. `null` — прочитать не удалось; выдумывать путь нельзя.
   */
  сайт?: {обложкаПоУмолчанию: string | null};
  /**
   * Правила картинок. Окну из них нужен один предел: анимацию тяжелее него оно не отправляет
   * вовсе — такой файл не доезжает до сервера, и человек видел бы «сервер не отвечает».
   */
  картинки: {пределГифМегабайт: number; пределWebmМегабайт: number};
  /** Карточка товара: слова окна выбора, предел описания и подписи кнопок по языку СТАТЬИ. */
  товары: {пределОписания: number; слова: Record<string, string>; кнопки: Record<string, Record<string, string>>};
  /** Слова сервера об отказах. Окну нужен отказ по весу анимации: его же показывает и заслон окна. */
  ошибкиСервера: Record<string, string>;
  /** Почему коммит статьи не сделан: код отказа — слова человеку. */
  отказыКоммита: Record<string, string>;
  /** Почему статья не отправлена на сайт: код отказа — слова человеку. */
  отказыОтправки: Record<string, string>;
  /**
   * Слова публикации статьи. `шаги`, `версии` и `причины` — карты по признаку и коду, а не
   * поимённо: код без своей фразы показывается вместе с кодом, а не проглатывается.
   */
  публикация: {
    заголовок: string;
    языки: string;
    сейчас: string;
    /** Нынешнее состояние версии на сайте: по доступности, «нет», «узнаю», «неизвестно». */
    состояния: Record<string, string>;
    ссылкиУберутся: string;
    /** Заголовок списка файлов, которые публикация уберёт в корзину и с сайта. */
    лишние: string;
    замечания: string;
    даПубликовать: string;
    неПубликовать: string;
    публикуется: string;
    неОпубликовано: string;
    ничегоНеУшло: string;
    перейтиКМесту: string;
    /** Кнопка перехода, когда причина — ссылка: «Показать ссылку». */
    показатьСсылку: string;
    понятно: string;
    ещё: string;
    ссылкиНеУбраны: string;
    /** Публикация прошла и заодно унесла в корзину лишние файлы папки: оба факта разом. */
    опубликованоИУбрано: string;
    /** Публикация не прошла, а человек на другом экране: «Статья «{название}» не опубликована: {причина}». */
    неОпубликованаСтатья: string;
    открытьСтатью: string;
    /** Кнопка «Опубликовать» заперта: идёт публикация другой статьи. */
    другаяСтатья: string;
    /** Неоткрытые языки уже переписаны публикацией, а вернуть их не вышло: `{пути}`. */
    неВернулись: string;
    подробности: string;
    постороннего: string;
    неПривелось: string;
    шаги: Record<string, string>;
    причины: Record<string, string>;
  };
  /** Значок «Сайт»: слова, пауза гашения, как часто окно и сервер спрашивают о выкладке. */
  выкладка: {
    обновляется: string;
    обновлён: string;
    неОбновился: string;
    неизвестно: string;
    прежняяВерсия: string;
    сбойGitHub: string;
    подробности: string;
    понятно: string;
    окноСек: number;
    гаснетСек: number;
    опрос: {первыйСек: number; идётСек: number; ждётСек: number; пределМинут: number};
  };
  /** Формы слова при числе («в 1 статье», «в 3 статьях»): `{один, несколько, много}`. */
  склонения: Record<string, {один: string; несколько: string; много: string}>;
  /** Сообщения коммитов публикации и снятия; `разрывы` — карта по признаку, а не поимённо. */
  выпуск: {
    сообщениеКоммита: string;
    сообщениеСнятия: string;
    разрывы: Record<string, string>;
  };
  /**
   * Слова окна подготовки. `находки`, `уровни` и `этапы` — карты по коду находки: код без своей
   * фразы показывается общей фразой вместе с кодом, а не проглатывается.
   */
  доработка: НастройкиДоработки;
  подготовка: {
    заголовок: string;
    чисто: string;
    закрыть: string;
    невыполненные: string;
    неизвестнаяНаходка: string;
    уровни: Record<string, string>;
    этапы: Record<string, string>;
    находки: Record<string, string>;
  };
  /**
   * Слова панели расхождения. `места` — карта по имени места, а не поимённо: место без своей
   * подписи показывается вместе с кодом, а не проглатывается.
   */
  сведение: {
    заголовок: string;
    спор: string;
    безБазы: string;
    нетФайла: string;
    было: string;
    'моё': string;
    внешнее: string;
    'оставитьМоё': string;
    оставитьВнешнее: string;
    применить: string;
    неВсёВыбрано: string;
    пусто: string;
    места: Record<string, string>;
  };
  реестр: {
    колонки: Column[];
    сортировкаПоУмолчанию: string;
    всеРазделы: string;
    любая: string;
    толькоДыры: string;
    нетНаСайте: string;
    неизвестныйАвтор: string;
    разное: string;
  };
}
