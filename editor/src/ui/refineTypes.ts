// Понятия действия «Доработать»: договор сервера с окном и вид его настроек.
// Отдельным файлом от общих понятий окна: тот файл у предела размера (SPEC 4.9).

/** Одна строка итога обработчика: что, было и стало либо причина, почему оставлено. */
export interface ЗаписьИтога {
  что: string;
  было?: string;
  стало?: string;
  значение?: string;
  причина?: string;
}

/** Отчёт одного обработчика реестра: выбран ли, применим ли и три списка итога. */
export interface ОтчётОбработчика {
  код: string;
  выбран: boolean;
  применимо: boolean;
  изменено: ЗаписьИтога[];
  оставлено: ЗаписьИтога[];
  человеку: ЗаписьИтога[];
}

/** План: что сделал бы каждый обработчик при текущем наборе; отпечаток снимка — для применения. */
export interface ПланДоработки {
  path: string;
  отпечаток: string;
  обработчики: ОтчётОбработчика[];
}

/** Итог применения. `применено: false` — выбранные действия ничего не нашли, диск не тронут. */
export interface ИтогДоработки {
  path: string;
  применено: boolean;
  обработчики: ОтчётОбработчика[];
  предупреждения: string[];
}

export interface НастройкиДоработки {
  заголовок: string;
  пояснение: string;
  смотрю: string;
  применить: string;
  применяю: string;
  отмена: string;
  закрыть: string;
  нечегоПрименять: string;
  нечегоНеИзменилось: string;
  готово: string;
  неПеречитана: string;
  неприменимо: string;
  подробности: string;
  итог: {изменено: string; оставлено: string; человеку: string};
  обработчики: Record<string, string>;
  причины: Record<string, string>;
}
