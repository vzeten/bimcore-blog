// Подготовка статьи глазами окна: запрос, состояние кнопки и судьба показанного отчёта.
//
// Отдельным модулем, а не внутри шапки окна: там уже живут название, языки, сохранение и удаление,
// и файл упёрся бы в предел размера (SPEC 4.9). Правил проверки здесь нет ни одного — их знает
// ядро; окно только зовёт ручку и показывает ответ.
//
// **Отчёт всегда описывает то, что лежит на диске.** Подготовка судит о файле, а не об экране,
// поэтому отчёт гаснет от первой же новой правки и при переходе к другой статье, а кнопка заперта,
// пока есть несохранённое. Простое предсказуемое правило вместо отпечатков и барьера: показанное
// либо верно сейчас, либо не показано вовсе.
//
// Ошибка живёт здесь же, рядом с отчётом, а не в общей полосе ошибок окна: она относится к одному
// нажатию и гаснет вместе с ним, а окно ради этого не переделывается.
//
// **Ответ принадлежит нажатию, а не окну.** Пока запрос идёт, человек может уйти в другую статью
// и нажать там снова. Сравнивать путь из ответа бесполезно: сервер эхом возвращает тот путь, что
// ушёл в запросе, и поздний ответ старой статьи всегда «совпадал». Поэтому каждое нажатие берёт
// номер, смена статьи или правка выдаёт новый, и ответ применяется, только если его номер всё ещё
// текущий. Занятость при этом тоже принадлежит номеру: смена статьи снимает её сразу, иначе кнопка
// новой статьи ждала бы ответа старой, а поздний finally старого запроса снимал бы занятость нового.

import {useEffect, useRef, useState} from 'react';
import {requestJson} from './api';
import type {PrepareReport} from './publishTypes';

export interface Подготовка {
  отчёт: PrepareReport | null;
  ошибка: string | null;
  идёт: boolean;
  запустить: () => Promise<void>;
  закрыть: () => void;
}

/** `path` — путь открытой языковой версии; null — статья закрыта. */
export function usePrepare(path: string | null, dirty: boolean): Подготовка {
  const [отчёт, setОтчёт] = useState<PrepareReport | null>(null);
  const [ошибка, setОшибка] = useState<string | null>(null);
  const [идёт, setИдёт] = useState(false);
  // Номер актуальности: растёт при смене статьи и при новой правке. Ответ с другим номером — чужой.
  const номер = useRef(0);
  // Номер запроса, который сейчас в пути; null — свободно. Ref, а не состояние: двойное нажатие
  // до перерисовки не должно породить второй запрос.
  const вПути = useRef<number | null>(null);

  // Сменилась статья или появилась новая правка — прежний ответ больше не про то, что на диске,
  // и идущий запрос больше никому не нужен: его ответ, ошибку и finally окно проигнорирует.
  useEffect(() => {
    номер.current += 1;
    вПути.current = null;
    setОтчёт(null);
    setОшибка(null);
    setИдёт(false);
  }, [path, dirty]);

  async function запустить(): Promise<void> {
    if (path === null || вПути.current !== null) return;

    const мой = номер.current;
    вПути.current = мой;
    setИдёт(true);
    setОшибка(null);
    try {
      const ответ = await requestJson<PrepareReport>('/api/prepare', {
        method: 'POST',
        headers: {'Content-Type': 'application/json'},
        body: JSON.stringify({path}),
      });
      if (мой === номер.current) setОтчёт(ответ);
    } catch (error) {
      const причина = error as {прервано?: boolean; message?: string};
      if (мой === номер.current && причина?.прервано !== true) setОшибка(причина?.message ?? '');
    } finally {
      // Освобождает только своё нажатие: занятость нового запроса старому не принадлежит.
      if (мой === номер.current && вПути.current === мой) {
        вПути.current = null;
        setИдёт(false);
      }
    }
  }

  return {
    отчёт,
    ошибка,
    идёт,
    запустить,
    закрыть: () => {
      setОтчёт(null);
      setОшибка(null);
    },
  };
}
