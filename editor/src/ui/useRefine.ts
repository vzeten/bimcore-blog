// «Доработать» глазами окна: план, выбор флажков, применение и что делать после.
// Содержание решает сервер: список обработчиков, умолчания и предпросмотр приходят из плана; флажок
// меняет набор сразу и просит план заново. Переходы состояния — чистые функции: их проверяет машина,
// а хук только зовёт сервер. Смена статьи или правка закрывают окно: план описывал другой диск.

import {useEffect, useRef, useState} from 'react';
import {requestJson} from './api';
import type {ИтогДоработки, ОтчётОбработчика, ПланДоработки} from './refineTypes';

export type ОкноДоработки = 'закрыто' | 'план' | 'выбор' | 'применяю' | 'готово';

export interface Состояние {
  окно: ОкноДоработки;
  план: ПланДоработки | null;
  /** Набор флажков окна: меняется сразу по щелчку, план подтягивается следом. `null` — ещё не задан. */
  выбранные: string[] | null;
  итог: ИтогДоработки | null;
  ошибка: string | null;
  /** Окно не сумело перечитать статью после записи. */
  неПеречитана: boolean;
}

export const ЗАКРЫТО: Состояние = {окно: 'закрыто', план: null, выбранные: null, итог: null, ошибка: null, неПеречитана: false};

/** Новый запрос плана: прежний план и его отпечаток забываются сразу, применить их больше нельзя. */
export const кПлану = (с: Состояние): Состояние => ({...с, окно: 'план', план: null, итог: null, ошибка: null});
export const планПолучен = (с: Состояние, план: ПланДоработки): Состояние => ({
  ...с, окно: 'выбор', план, выбранные: с.выбранные ?? план.обработчики.filter((з) => з.выбран).map((з) => з.код),
});
export const планНеУдался = (с: Состояние, ошибка: string): Состояние => ({...с, окно: 'выбор', план: null, ошибка});
export const выбран = (с: Состояние, з: ОтчётОбработчика): boolean => (с.выбранные ?? []).includes(з.код);
/** Применить можно только свежий план, в котором выбранные обработчики нашли работу. */
export const можноПрименить = (с: Состояние): boolean => с.окно === 'выбор' && с.план !== null
  && с.план.обработчики.some((з) => з.применимо && выбран(с, з) && з.изменено.length > 0);
/** Прежние проверки статьи доступны из окна всегда, когда идёт выбор или показан итог: они ничего не пишут. */
export const можноПроверить = (с: Состояние): boolean => с.окно === 'выбор' || с.окно === 'готово';

export interface Доработка extends Состояние {
  открыть: () => void;
  закрыть: () => void;
  переключить: (код: string) => void;
  применить: () => Promise<void>;
  проверить: () => void;
}

const post = (тело: unknown): RequestInit => ({method: 'POST', headers: {'Content-Type': 'application/json'}, body: JSON.stringify(тело)});

/** `перечитать` — открыть статью заново с диска; `проверить` — запустить прежние проверки «Доработать». */
export function useRefine(path: string | null, dirty: boolean, после: {перечитать: (path: string) => Promise<boolean>; проверить: () => void}): Доработка {
  const [с, setС] = useState<Состояние>(ЗАКРЫТО);
  // Номер актуальности: ответ с другим номером принадлежит другой статье и не показывается.
  const номер = useRef(0);
  const сбросить = () => {
    номер.current += 1;
    setС(ЗАКРЫТО);
  };
  useEffect(сбросить, [path, dirty]);

  async function планировать(набор: string[] | null): Promise<void> {
    if (path === null) return;
    const мой = номер.current;
    setС((было) => кПлану({...было, выбранные: набор}));
    try {
      const ответ = await requestJson<ПланДоработки>('/api/refine/plan', post({path, выбранные: набор}));
      if (мой === номер.current) setС((было) => планПолучен(было, ответ));
    } catch (error) {
      if (мой === номер.current) setС((было) => планНеУдался(было, (error as Error).message));
    }
  }

  async function применить(): Promise<void> {
    if (path === null || !можноПрименить(с) || с.план === null) return;
    const мой = номер.current;
    setС((было) => ({...было, окно: 'применяю', ошибка: null}));
    try {
      const ответ = await requestJson<ИтогДоработки>('/api/refine/apply', post({path, выбранные: с.выбранные, отпечаток: с.план.отпечаток}));
      if (мой !== номер.current) return;
      let неПеречитана = false;
      if (ответ.применено) {
        // Файл на диске новый — окно перечитывает его, затем идут прежние проверки по новому тексту.
        неПеречитана = !(await после.перечитать(path));
        if (мой !== номер.current) return;
        после.проверить();
      }
      setС((было) => ({...было, окно: 'готово', итог: ответ, неПеречитана}));
    } catch (error) {
      if (мой === номер.current) setС((было) => ({...было, окно: 'выбор', ошибка: (error as Error).message}));
    }
  }

  return {
    ...с,
    открыть: () => void планировать(null),
    закрыть: сбросить,
    переключить: (код) => {
      if (с.выбранные === null) return;
      void планировать(с.выбранные.includes(код) ? с.выбранные.filter((к) => к !== код) : [...с.выбранные, код]);
    },
    применить,
    проверить: () => {
      if (можноПроверить(с)) после.проверить();
    },
  };
}
