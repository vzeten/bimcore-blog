// Одна строка панели: кто на этом порту, чем он доказан и что с ним можно сделать.
// Правил здесь нет — что доступно, решил сервер (`instanceControl.mjs`), окно только показывает.

import {ЗначокЖив, ЗначокЗапустить, ЗначокОстановить, ЗначокОткрыть, ЗначокПрепятствие, ЗначокТихо} from './Icons';
import type {Надписи, Строка} from './types';

interface Свойства {
  строка: Строка;
  надписи: Надписи;
  /** Действие, которое сейчас идёт на этом порту: пока оно идёт, кнопки строки заперты. */
  идёт: string | null;
  /** Порт, для которого показан вопрос «точно остановить?». Вопрос задаётся только рабочему окну. */
  спрошено: boolean;
  открыть: () => void;
  запустить: () => void;
  остановить: () => void;
  ответить: (да: boolean) => void;
}

/** Значок состояния: он же цвет всей карточки. */
function Значок(props: {состояние: string}) {
  if (props.состояние === 'работает') return <ЗначокЖив className="значок" />;
  if (props.состояние === 'чужой') return <ЗначокПрепятствие className="значок" />;
  return <ЗначокТихо className="значок" />;
}

/** Строка фактов. Пустое значение не показывается вовсе: прочерк ничего не объясняет. */
function Факт(props: {имя: string; значение: string | null}) {
  if (!props.значение) return null;
  return (
    <div className="факт">
      <dt>{props.имя}</dt>
      <dd title={props.значение}>{props.значение}</dd>
    </div>
  );
}

export function Card(props: Свойства) {
  const {строка: с, надписи: н} = props;
  const версия = с.ветка ? `${с.ветка} · ${с.коммит ?? ''}`.trim() : null;
  const имя = с.вид ? н.виды[с.вид] : н.виды['неизвестно'];
  const заперто = props.идёт !== null;

  return (
    <article className={`карточка карточка--${с.состояние} ${с.вид === 'рабочий' ? 'карточка--рабочая' : ''}`}>
      <header className="шапка">
        <Значок состояние={с.состояние} />
        <span className="имя">{имя}</span>
        <span className="порт">{н.поля['порт']} {с.порт}</span>
        <span className="состояние">{н.состояния[с.состояние]}</span>
      </header>

      {с.состояние === 'чужой' ? (
        <p className="пояснение">{н.пояснения['чужой']}</p>
      ) : (
        <>
          {!с.живое && (
            <p className="пояснение">
              {с.ветка ? н.пояснения['остановлен'] : н.пояснения['остановленНеВиделись']}
            </p>
          )}
          <dl className="факты">
            <Факт имя={н.поля['ветка']} значение={версия} />
            <Факт имя={н.поля['код']} значение={с.код} />
            <Факт имя={н.поля['материалы']} значение={с.материалы} />
          </dl>
          {с.живое && !с.чисто && <p className="пояснение пояснение--тревога">{н.пояснения['грязно']}</p>}
        </>
      )}

      {props.спрошено ? (
        <footer className="действия действия--вопрос">
          <span className="вопрос">{н.подтверждение.вопрос}</span>
          <button type="button" className="кнопка кнопка--опасная" onClick={() => props.ответить(true)}>
            {н.подтверждение.да}
          </button>
          <button type="button" className="кнопка" onClick={() => props.ответить(false)}>
            {н.подтверждение.нет}
          </button>
        </footer>
      ) : (
        <footer className="действия">
          <button
            type="button"
            className="кнопка"
            disabled={!с.действия.открыть || заперто}
            onClick={props.открыть}
          >
            <ЗначокОткрыть className="значок-кнопки" />
            {н.действия['открыть']}
          </button>
          <button
            type="button"
            className="кнопка"
            disabled={!с.действия.запустить || заперто}
            onClick={props.запустить}
          >
            <ЗначокЗапустить className="значок-кнопки" />
            {н.действия['запустить']}
          </button>
          <button
            type="button"
            className="кнопка"
            disabled={!с.действия.остановить || заперто}
            onClick={props.остановить}
          >
            <ЗначокОстановить className="значок-кнопки" />
            {н.действия['остановить']}
          </button>
          {props.идёт && <span className="идёт">{н.ждём[props.идёт]}</span>}
        </footer>
      )}
    </article>
  );
}
