// Договор между сервером панели и её окном. Внутренний договор одной программы, поэтому имена
// полей русские, как и всюду в окне, а надписи приходят из настроек, а не живут в коде (SPEC 4.4).

/** Что панель увидела на порту прямо сейчас. Память сюда не подмешивается никогда. */
export type Состояние = 'работает' | 'остановлен' | 'чужой';

/** Вид экземпляра. Рабочий отделён от испытательных, чтобы их нельзя было спутать. */
export type Вид = 'рабочий' | 'испытательныйКод' | 'испытательныйМатериалы';

export interface Действия {
  открыть: boolean;
  запустить: boolean;
  остановить: boolean;
}

export interface Строка {
  порт: number;
  состояние: Состояние;
  /** Факты строки взяты у живого сервера, а не из памяти панели. */
  живое: boolean;
  вид: Вид | null;
  ветка: string | null;
  коммит: string | null;
  чисто: boolean;
  код: string | null;
  материалы: string | null;
  адрес: string | null;
  действия: Действия;
  запуск: {код: string; материалы: string} | null;
}

export interface Надписи {
  заголовок: string;
  подзаголовок: string;
  обновить: string;
  обновлено: string;
  пусто: string;
  виды: Record<string, string>;
  состояния: Record<string, string>;
  действия: Record<string, string>;
  поля: Record<string, string>;
  итоги: Record<string, string>;
  ждём: Record<string, string>;
  пояснения: Record<string, string>;
  подтверждение: {вопрос: string; да: string; нет: string};
}

/** Ответ ручек панели: свежая таблица и, для действий, его исход словами. */
export interface Ответ {
  строки: Строка[];
  портВладельца: number;
  получилось?: boolean;
  итог?: string;
  беда?: string;
}

declare global {
  interface Window {
    /** Надписи и подписи, вложенные в саму страницу: первая же ошибка сети должна быть словами. */
    ПАНЕЛЬ: {надписи: Надписи; подписи: Record<string, string>};
  }
}
