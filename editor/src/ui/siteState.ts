// Правило значка «Сайт»: что показать по состоянию выкладки последней отправки (решение владельца
// 2026-09-18, п.5б). Чистая функция — её проверяет машина; окно только рисует ответ.

/** Состояние выкладки, как его отдаёт `/api/site/state`. */
export interface СостояниеСайта {
  состояние: string;
  sha?: string;
  путь?: string;
  локали?: string[];
  причина?: string | null;
  шаг?: string | null;
  runUrl?: string | null;
  показано?: boolean;
}

/**
 * Какой значок (решение владельца 2026-09-19): `нет` — показывать нечего (публикаций не было, итог уже
 * увиден, сайт не на GitHub — учебный); `обновляется` — выкладка идёт; `обновлён` — прошла (зелёный,
 * потом гаснет); `неОбновился` — упала сборка или выкладка (красный, пока человек не нажмёт
 * «Понятно»); `неизвестно` — GitHub так и не сказал, чем кончилось. Идущая выкладка видна всегда.
 */
export type ВидЗначка = 'нет' | 'обновляется' | 'обновлён' | 'неОбновился' | 'неизвестно';

export function значокСайта(сайт: СостояниеСайта | null): ВидЗначка {
  if (сайт === null) return 'нет';
  if (сайт.состояние === 'ждём' || сайт.состояние === 'идёт') return 'обновляется';
  if (сайт.показано === true) return 'нет';
  if (сайт.состояние === 'обновлён') return 'обновлён';
  if (сайт.состояние === 'сборкаУпала' || сайт.состояние === 'выкладкаУпала') return 'неОбновился';
  // Сайт не на GitHub (учебный) — следить не за чем, и значка нет вовсе.
  if (сайт.состояние === 'неВидно' && сайт.причина !== 'неGitHub') return 'неизвестно';
  return 'нет';
}
