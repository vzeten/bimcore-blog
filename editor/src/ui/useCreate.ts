import {useState} from 'react';
import {createArticle} from './actions';
import {label} from './labels';

/**
 * Создание статьи: форма и один запрос. Вынесено из окна, чтобы оно не выходило за предел
 * размера файла (SPEC 4.9), а правило «создано — значит открываем» лежало одним куском.
 */
export function useCreate(deps: {
  открыть: (path: string) => Promise<void>;
  /** Перечитать список статей: созданной в нём ещё нет. */
  обновить: () => Promise<void>;
  onОшибка: (текст: string) => void;
  onСоздано: (текст: string) => void;
}) {
  // В каком разделе создаём. `undefined` — форма закрыта; `null` — открыта, но раздел не выбран.
  const [раздел, setРаздел] = useState<string | null | undefined>(undefined);
  const [идёт, setИдёт] = useState(false);

  const создать = async (название: string, адрес: string): Promise<void> => {
    if (раздел === undefined || идёт) return;
    setИдёт(true);

    await createArticle({раздел: раздел ?? '', название, адрес}, {
      // Статья создана — сразу открываем её: человек начал писать, а не заводить файлы.
      ok: async (созданная) => {
        setРаздел(undefined);
        // Сначала открываем, потом говорим: открытие статьи гасит показанные сообщения,
        // и сказанное раньше человек бы не увидел — а знать про английскую заглушку он должен.
        // Реестр перечитывается с диска: созданной статьи в его списке ещё нет.
        await deps.обновить();
        await deps.открыть(созданная.path);
        deps.onСоздано(label('статьяСоздана'));
      },
      // Ничего не создано, и делать вид, что создано, нельзя: форма остаётся с введённым текстом.
      fail: deps.onОшибка,
    });

    setИдёт(false);
  };

  return {раздел, идёт, начать: setРаздел, закрыть: () => setРаздел(undefined), создать};
}
