// Просмотры статей для реестра: один отдельный вопрос серверу при открытии реестра.
// Реестр его не ждёт. Пока ответ идёт, окно показывает последние цифры, запомненные в браузере при
// прошлом показе (решение владельца 2026-09-24: без прочерков при обновлении страницы, раз цифры за
// это время измениться не могли); свежие встают на их место, когда придут. Прочерк — только у статьи,
// чисел которой ещё не было ни разу.

import {useEffect, useState} from 'react';
import {requestJson} from './api';

/** Числа одной статьи; месяцы — `YYYYMM` от старого к текущему, у каждого — разбивка по языкам. */
export interface ПросмотрыСтатьи {
  всего: number;
  за30: number;
  прежние30: number;
  языки: Record<string, number>;
  месяцы: {месяц: string; просмотры: number; языки: Record<string, number>}[];
}

/** Ответ сервера: числа по ключу статьи, последний день в них и надпись, если что-то не так. */
export interface Просмотры {
  статьи: Record<string, ПросмотрыСтатьи>;
  поДень: string | null;
  надпись: string | null;
}

/** Где окно хранит последние показанные цифры. Только числа и дата — секретов в ответе нет. */
export const КЛЮЧ_ЗАПОМНЕННЫХ = 'редактор.просмотры';

/** Хранилище браузера, как его видит окно: достаточно двух дверей, чтобы проверить правило без браузера. */
export interface Хранилище {
  getItem(ключ: string): string | null;
  setItem(ключ: string, значение: string): void;
}

/**
 * Последние запомненные цифры или `null`. Хранилище недоступно (частное окно, запрет браузера) или
 * запись испорчена — как будто её нет: окно просто покажет прочерки до ответа сервера.
 */
export function запомненныеПросмотры(хранилище: Хранилище | null): Просмотры | null {
  try {
    const запись = JSON.parse(хранилище?.getItem(КЛЮЧ_ЗАПОМНЕННЫХ) ?? 'null');
    return запись && typeof запись.статьи === 'object' && запись.статьи !== null && typeof запись.поДень === 'string'
      ? {статьи: запись.статьи, поДень: запись.поДень, надпись: null}
      : null;
  } catch {
    return null;
  }
}

/** Запомнить ответ сервера. Без цифр (нет ключа, сбой) прежние запомненные не затираются. */
export function запомнитьПросмотры(хранилище: Хранилище | null, ответ: Просмотры): void {
  if (!ответ.поДень) return;
  try {
    хранилище?.setItem(КЛЮЧ_ЗАПОМНЕННЫХ, JSON.stringify({статьи: ответ.статьи, поДень: ответ.поДень}));
  } catch {
    // Хранилище переполнено или запрещено — в следующий раз окно просто подождёт ответа сервера.
  }
}

function хранилищеБраузера(): Хранилище | null {
  try {
    return window.localStorage;
  } catch {
    return null;
  }
}

export function useViews(): Просмотры | null {
  const [просмотры, setПросмотры] = useState<Просмотры | null>(() => запомненныеПросмотры(хранилищеБраузера()));

  useEffect(() => {
    let жив = true;
    requestJson<Просмотры>('/api/views')
      .then((ответ) => {
        if (!жив) return;
        запомнитьПросмотры(хранилищеБраузера(), ответ);
        // Ответ сервера главнее запомненного: и свежие числа, и честная надпись, если их нет.
        setПросмотры(ответ);
      })
      // Сервер не ответил — колонка остаётся с прочерками: числа не выдумываются.
      .catch(() => undefined);
    return () => {
      жив = false;
    };
  }, []);

  return просмотры;
}

/** День `YYYYMMDD` словами окна: `22.09.2026`. */
export function деньСловами(день: string, язык: string): string {
  const дата = new Date(Number(день.slice(0, 4)), Number(день.slice(4, 6)) - 1, Number(день.slice(6, 8)));
  return дата.toLocaleDateString(язык);
}

/** Месяц `YYYYMM` коротким словом: `сент. 2026`. */
export function месяцСловами(месяц: string, язык: string): string {
  const дата = new Date(Number(месяц.slice(0, 4)), Number(месяц.slice(4, 6)) - 1, 1);
  return дата.toLocaleDateString(язык, {month: 'short', year: 'numeric'});
}
