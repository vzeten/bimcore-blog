import {useRef} from 'react';
import {autosaveDraft} from './actions';
import type {SaveState} from './types';

/** Что уходит в черновик: текст, шапка и отпечаток файла, от которого человек отталкивался. */
export interface DraftPayload {
  path: string;
  body: string;
  frontmatterRaw: string;
  отпечатокБазы: string;
}

/**
 * Автосохранение черновика по таймеру.
 * Пишем не на каждую букву, а раз в интервал из настроек: иначе диск дёргается на каждый символ.
 * Настоящий `.mdx` не трогается — сервер пишет только служебный черновик.
 */
export function useAutosave(интервалСек: number, onState: (state: SaveState) => void) {
  // Последняя правка в ref, а не в state: таймер должен видеть свежее значение, а не то,
  // с которым его создали.
  const ждётЗаписи = useRef<DraftPayload | null>(null);
  const таймер = useRef<number | null>(null);
  // Поколение растёт при каждой отмене. Ответ запроса, начатого до отмены, приходит с устаревшим
  // поколением — такой ответ не должен менять статус: иначе после «Сохранено» мелькнёт
  // «Автосохранено» от запроса, который уже никому не нужен.
  const поколение = useRef(0);
  // Уже отправленный запрос прерываем по-настоящему: гасить только статус мало — поздний запрос
  // иначе допишет черновик уже после того, как работа сохранена в файл.
  const прерыватель = useRef<AbortController | null>(null);

  const снять = (): void => {
    if (таймер.current !== null) window.clearTimeout(таймер.current);
    таймер.current = null;
  };

  /**
   * Забыть ждущую правку: статья сменилась или работа уже записана в настоящий файл.
   * Идущий запрос прерываем по-настоящему — иначе он допишет черновик уже после сохранения.
   * При обычной правке этого не делаем: там достаточно поколения, а рвать полезную запись незачем.
   */
  const отменить = (): void => {
    снять();
    ждётЗаписи.current = null;
    поколение.current += 1;
    прерыватель.current?.abort();
    прерыватель.current = null;
  };

  const записать = async (моё: number): Promise<void> => {
    const данные = ждётЗаписи.current;
    if (!данные || моё !== поколение.current) return;

    onState('сохраняем');
    // Предыдущий запрос обрываем перед стартом нового: иначе живых запросов становится несколько,
    // и «Сохранить» прервёт только последний, а прежний допишет черновик уже после сохранения.
    прерыватель.current?.abort();
    const свой = new AbortController();
    прерыватель.current = свой;
    await autosaveDraft(данные, {
      // Пока запрос шёл, работу могли записать по кнопке — тогда этот ответ уже неактуален.
      ok: () => {
        if (моё === поколение.current) onState('автосохранено');
      },
      // Признак несохранённого не снимается — правки в окне остаются, человек видит, что не вышло.
      fail: () => {
        if (моё === поколение.current) onState('неУдалосьАвтосохранить');
      },
    }, undefined, свой.signal);
  };

  /** Правка ждёт записи: заводим таймер заново, чтобы писать по затиханию правок. */
  const запланировать = (данные: DraftPayload): void => {
    ждётЗаписи.current = данные;
    onState('естьНесохранённые');
    снять();
    // Новая правка обесценивает уже идущий запрос: его ответ не должен сказать «Автосохранено»
    // про текст, которого он не видел. Поэтому поколение растёт и здесь, а не только при отмене.
    поколение.current += 1;
    const моё = поколение.current;
    таймер.current = window.setTimeout(() => void записать(моё), интервалСек * 1000);
  };

  return {запланировать, отменить};
}
