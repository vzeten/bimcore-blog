import {изменениеНеНаСайте, скрытаВОкне, type Field} from '../headFields';
import {DeleteAsk} from './DeleteAsk';
import {PrepareReport} from './PrepareReport';
import {PublishButton} from './PublishButton';
import {SiteBadge} from './SiteBadge';
import {RefinePanel} from './RefinePanel';
import {usePrepare} from '../usePrepare';
import {useRefine} from '../useRefine';
import {useLocaleStart} from '../useLocaleStart';
import {признакиЛокали, подсказкаЛокали} from '../../core/localeSigns.mjs';
import {LocaleMark} from './LocaleMark';
import type {Удаление} from '../useDelete';
import type {Article, SaveState, Settings} from '../types';

export function TopBar(props: {
  settings: Settings;
  article: Article | null;
  title: string;
  dirty: boolean;
  состояниеСохранения: SaveState;
  colors: boolean;
  /**
   * Открыть языковую версию. Отвечает промисом: начало новой версии обязано дождаться открытия,
   * иначе слова о ней гаснут — переход в статью гасит показанное сообщение, и человек не узнаёт,
   * что именно произошло.
   */
  onOpen: (path: string) => void | Promise<boolean | void>;
  onColors: (value: boolean) => void;
  /** Записать окно на диск. Отвечает, легла ли работа целиком: это нужно публикации. */
  onSave: () => Promise<boolean>;
  /**
   * Поставить дату записи блога в шапку окна и записать её. Зовётся только публикацией и только
   * до обязательных проверок: дата блога — это день первой публикации, и ставит её программа.
   */
  onДата: (дата: string) => Promise<boolean>;
  /** Вписать адрес обложки, положенной публикацией, в `image` и записать — так же, как дату. */
  onОбложка: (адрес: string) => Promise<boolean>;
  /** Поставить доступность, выбранную в окне публикации, и записать — так же, как дату. */
  onДоступность: (режим: string) => Promise<boolean>;
  /** Поля шапки в окне: из них берётся видимость — своего признака у шапки окна нет. */
  fields: Field[];
  /** Удаление статьи: сервер называет, что снимется с сайта, окно задаёт единственный вопрос. */
  удаление: Удаление;
  /** Идёт просмотр старой версии: писать на диск нельзя ничем, включая видимость. */
  просмотр: boolean;
  /** Перечитать реестр: у статьи прибавилась языковая версия, и список обязан это показать. */
  onОбновить: () => Promise<void>;
  /** Сказать человеку словами: версия начата либо начать её не вышло. */
  onСообщить: (текст: string) => void;
}) {
  const п = props.settings.подписи;
  const в = props.settings.видимость;
  // Вместе с вопросом удаления запоминается не только статья, но и заход в неё: перешли на другую —
  // нажатие «Удалить» относилось бы уже к ней. Заход нужен и там, где путь тот же: статью удалили
  // и тут же создали заново с тем же адресом, и над новой статьёй висел бы чужой вопрос.
  const окно = props.article === null ? null : `${props.article.path}|${props.article.заход ?? 0}`;

  // Начало отсутствующей языковой версии живёт рядом со своими вкладками, как подготовка и
  // публикация — рядом со своими кнопками. До согласия человека оно ничего не пишет и ни о чём
  // не спрашивает сервер.
  const началоЛокали = useLocaleStart({
    путь: () => props.article?.path ?? null,
    // Окно то же, что помнит вопрос об удалении: путь плюс номер захода в статью.
    окно: () => окно,
    // Несохранённое кладём на диск сами: сервер берёт название и адрес новой версии из файла
    // исходной. Записывать нечего — считаем, что всё уже легло.
    сохранить: async () => (props.dirty ? props.onSave() : true),
    обновить: props.onОбновить,
    открыть: async (path) => (await props.onOpen(path)) === true,
    onОшибка: props.onСообщить,
    onНачато: props.onСообщить,
  });

  const скрыта = скрытаВОкне(props.fields);
  const неНаСайте = изменениеНеНаСайте(props.article, скрыта);
  // Подготовка живёт рядом со своей кнопкой: она ничего не пишет и никого, кроме отчёта под
  // шапкой, не касается — тянуть её через всю сборку окна незачем.
  const подготовка = usePrepare(props.article?.path ?? null, props.dirty);
  // «Доработать» — окно выбора автоматизаций; после применения перечитывает статью и зовёт подготовку.
  const доработка = useRefine(props.article?.path ?? null, props.dirty, {
    перечитать: async (path) => (await props.onOpen(path)) === true,
    проверить: () => void подготовка.запустить(),
  });

  return (
    <>
    <header className="topbar">
      <div className="topbar-name">
        <span className="topbar-title">{props.article ? props.title : п.программа}</span>
        {props.article && (
          <span className="topbar-path">
            {props.article.category} · {props.article.path}
          </span>
        )}
      </div>

      {props.article && (
        <div className="topbar-locales">
          {Object.keys(props.settings.локали).map((code) => {
            const path = props.article!.versions[code];
            const here = path === props.article!.path;
            // Признаки берутся из свода у ВСЕХ версий, включая открытую. Прежде у своей версии
            // значок ссылки подменялся флажком окна — и снова обещал сайту настройку, которой
            // там ещё нет; ровно это правило и чинилось в ядре (решение владельца 2026-09-07).
            // Будущее значение показывают сам флажок в свойствах и надпись «изменение ещё не на
            // сайте», а сохранённую, но не уехавшую правку — красная точка.
            const признаки = props.article!.признакиЛокалей?.[code] ?? признакиЛокали(null);
            // Нет обязательного языка — статьи нет на сайте вовсе. Это ошибка, а не дыра в переводах.
            const срыв = !признаки.есть && code === props.settings.обязательныйЯзык && props.article!.нетНаСайте;

            // Языка нет — вкладка не заперта, а предлагает его начать. Запертая вкладка была
            // тупиком: человек видел дыру в переводах и ничего не мог с ней сделать в программе.
            // Нажатие только задаёт вопрос — ни одного файла до ответа не появляется.
            const нет = !признаки.есть;

            return (
              <LocaleMark
                key={code}
                code={code}
                признаки={признаки}
                срыв={срыв}
                открыта={here}
                подсказка={срыв ? props.settings.реестр.нетНаСайте : подсказкаЛокали(code, признаки, props.settings)}
                // Просмотр старой версии ничего не пишет: на это время начало версии заперто,
                // как и остальные пишущие кнопки шапки.
                disabled={нет && (props.просмотр || началоЛокали.идёт)}
                onClick={() => (нет ? началоЛокали.спросить(code) : path && props.onOpen(path))}
              />
            );
          })}

          {/* Вопрос стоит рядом со вкладками, а не отдельным окном: человек видит, про какой
              язык спрашивают, и обе кнопки сразу. «Не начинать» не отправляет на сервер ничего,
              и на диске после отказа не остаётся ни одного файла. */}
          {началоЛокали.спрошено !== null && !props.просмотр && (
            <span className="lang-ask">
              <span className="topbar-ask">
                {props.settings.локали[началоЛокали.спрошено] ?? началоЛокали.спрошено}
                {': '}
                {п.локальНачатьСпросить}
              </span>
              <button
                className="ghost"
                disabled={началоЛокали.идёт}
                onClick={() => void началоЛокали.начать(началоЛокали.спрошено!)}
              >
                {началоЛокали.идёт ? п.локальНачинается : п.локальНачать}
              </button>
              <button
                className="ghost"
                disabled={началоЛокали.идёт}
                onClick={началоЛокали.отменить}
              >
                {п.локальНеНачинать}
              </button>
            </span>
          )}
        </div>
      )}

      <div className="topbar-actions">
        {/* Выкладка на GitHub видна с любого экрана, в том числе в реестре (решение владельца 2026-09-18). */}
        <SiteBadge settings={props.settings} />

        <button
          className={props.colors ? 'ghost ghost-on' : 'ghost'}
          title={props.colors ? п.цветаВыкл : п.цветаВкл}
          onClick={() => props.onColors(!props.colors)}
        >
          ◐
        </button>

        {props.article && (
          <>
            {/* Общего слова готовности здесь нет с 2026-09-07: одним словом три независимые
                языковые версии не описываются, и «Опубликована» прятало правку соседней версии.
                Состояние каждой версии стоит возле её букв слева (`LocaleMark`).

                Видимость — не кнопка: назначает её публикация (окно «Опубликовать», решение
                владельца 2026-09-18). Здесь только шапка открытой версии и пометка, что сайт этого
                ещё не видит: у соседних версий видимость своя (SPEC 2.8). */}
            <span className={скрыта ? 'visibility visibility-off' : 'visibility'} title={п.видимость}>
              {скрыта ? в.поСсылке : в.вМеню}
              {/* Файл изменён, но сайт этого ещё не видит: обещать «скрыто» было бы враньём. */}
              {неНаСайте && <span className="visibility-pending">{п.неНаСайте}</span>}
            </span>
          </>
        )}

        {/* Состояние автосохранения: человек видит, что работа не потеряется, ещё до кнопки. */}
        {props.article && (
          <span
            className={props.состояниеСохранения === 'неУдалосьАвтосохранить' ? 'autosave autosave-fail' : 'autosave'}
            title={props.article.спор !== null ? п.файлИзменёнСнаружи : ''}
          >
            {props.article.спор !== null ? п.файлИзменёнСнаружи : п[props.состояниеСохранения]}
          </span>
        )}

        {/* В просмотре версии непонятно, что сохранять — увиденное или набранное. Кнопка заперта. */}
        <button
          className="ghost"
          disabled={!props.dirty || props.просмотр}
          title={props.просмотр ? п.идётПросмотр : ''}
          onClick={() => void props.onSave()}
        >
          {props.dirty ? п.сохранить : п.сохранено}
        </button>

        {/* «Доработать» — необязательное действие: человек может открыть его заранее и посмотреть,
            что стоит поправить. Разрешением на публикацию оно не является, и публикация его не
            требует. Судит оно о том, что записано в файл, поэтому с несохранёнными правками
            заперто — иначе говорило бы не о том, что человек видит на экране. */}
        <button
          className="ghost"
          disabled={подготовка.идёт || доработка.окно !== 'закрыто' || props.dirty || props.просмотр || !props.article}
          title={заперта(props, п)}
          onClick={доработка.открыть}
        >
          {подготовка.идёт ? п.подготовкаИдёт : п.подготовить}
        </button>

        {/* Удаление предлагается у любой обычной статьи. Вопрос один и задаётся окном поверх
            программы (`DeleteAsk`): что снимется с сайта и сколько статей получат правку ссылок,
            сервер называет до него. Страница раздела не удаляется, просмотр версии не пишет. */}
        {props.article && !props.article.служебная && !props.просмотр && (
          <button className="ghost" disabled={props.удаление.идёт} onClick={() => void props.удаление.спросить()}>
            {props.удаление.идёт && props.удаление.предложение === null ? п.удалениеСпрашиваю : п.удалитьСтатью}
          </button>
        )}

        {/* Главное действие человека: одно нажатие, один вопрос, дальше программа сама
            (`PublishButton`). Заперто оно только там, где писать нельзя, — в просмотре версии. */}
        <PublishButton
          settings={props.settings}
          article={props.article}
          dirty={props.dirty}
          просмотр={props.просмотр}
          onSave={props.onSave}
          onДата={props.onДата}
          onОбложка={props.onОбложка}
          onДоступность={props.onДоступность}
          onOpen={props.onOpen}
          onСообщить={props.onСообщить}
        />
      </div>
    </header>

    {props.удаление.предложение !== null && props.удаление.предложение.окно === окно && !props.просмотр && (
      <DeleteAsk
        settings={props.settings}
        название={props.title}
        предложение={props.удаление.предложение}
        идёт={props.удаление.идёт}
        onУдалить={() => void props.удаление.удалить()}
        onОтмена={props.удаление.отменить}
      />
    )}
    <RefinePanel settings={props.settings} доработка={доработка} />
    <PrepareReport
      settings={props.settings}
      отчёт={подготовка.отчёт}
      ошибка={подготовка.ошибка}
      onЗакрыть={подготовка.закрыть}
    />
    </>
  );
}

/**
 * Почему кнопка подготовки заперта. Молчаливо запертая кнопка выглядит поломкой: человек видит
 * «Подготовить» и не понимает, отчего оно не нажимается.
 */
function заперта(
  props: {dirty: boolean; просмотр: boolean; article: Article | null},
  п: Settings['подписи'],
): string {
  if (props.просмотр) return п.идётПросмотр;
  if (props.article && props.dirty) return п.сначалаСохранитеДляПодготовки;

  return '';
}
