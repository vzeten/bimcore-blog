import type {Публикация} from '../usePublish';
import type {PrepareFinding} from '../publishTypes';
import type {Settings} from '../types';

/**
 * Публикация одной статьи: ход, единственный вопрос и ответ.
 *
 * **Панель стоит там, где человек нажал.** Она выпадает прямо под кнопкой «Опубликовать» и остаётся
 * узкой: полоса во всю ширину окна не показывала, откуда она взялась, и терялась среди статьи.
 * Внутри всё выровнено влево — читается это как обычный текст, — а действия прижаты вправо, к той
 * же стороне, где кнопка.
 *
 * **Здесь нет ни номеров записей, ни списка путей на виду.** Последнюю содержательную проверку
 * человек уже сделал, когда читал статью; ему остаётся понять, что именно изменится на сайте и на
 * каких языках. Техническое лежит в свёрнутом «Сведения для диагностики» и на решение не влияет.
 */
export function PublishPanel(props: {settings: Settings; публикация: Публикация}) {
  const п = props.settings.публикация;
  const {шаг, остановка, итог} = props.публикация;

  if (шаг === 'нет' && остановка === null) return null;

  return (
    <section className="publish" aria-label={п.заголовок}>
      <div className="publish-head">
        <strong>{заголовок(props.публикация, п)}</strong>
        <button
          type="button"
          className="publish-close"
          aria-label={подсказкаЗакрытия(props.публикация, п)}
          title={подсказкаЗакрытия(props.публикация, п)}
          disabled={шаг === 'публикую'}
          onClick={props.публикация.закрыть}
        >
          ✕
        </button>
      </div>

      {идёт(шаг) && <p className="publish-quiet">{п.шаги[шаг] ?? шаг}</p>}
      {/* Почему крестик не нажимается — словами, а не только подсказкой: у отключённой кнопки
          подсказка достаётся не всякому и не всяким способом. */}
      {шаг === 'публикую' && <p className="publish-quiet">{п.отменитьНельзя}</p>}

      {остановка && <Причина остановка={остановка} settings={props.settings} />}

      {шаг === 'спрашиваю' && итог && <Итог итог={итог} settings={props.settings} />}

      {шаг === 'спрашиваю' && props.публикация.предупреждения.length > 0 && (
        <>
          <p className="publish-quiet">{п.стоитПоправить}</p>
          <Находки список={props.публикация.предупреждения} settings={props.settings} />
        </>
      )}

      {шаг === 'готово' && <p className="publish-ok">{п.опубликовано}</p>}

      {шаг === 'спрашиваю' && (
        <div className="publish-actions">
          <button type="button" className="ghost ghost-main" onClick={() => void props.публикация.подтвердить()}>
            {п.даПубликовать}
          </button>
          <button type="button" className="ghost" onClick={props.публикация.закрыть}>{п.неПубликовать}</button>
        </div>
      )}

      {(шаг === 'спрашиваю' || шаг === 'готово') && (
        <Диагностика подпись={п.подробности}>
          <Подробности публикация={props.публикация} settings={props.settings} />
        </Диагностика>
      )}
    </section>
  );
}

/**
 * Свёрнутые сведения для диагностики. Нативное раскрытие, а не кнопка: кнопка выглядит как действие,
 * которое человек обязан совершить, а это ровно наоборот — то, что ему обычно не нужно.
 */
function Диагностика(props: {подпись: string; children: React.ReactNode}) {
  return (
    <details className="publish-tech">
      <summary>{props.подпись}</summary>
      {props.children}
    </details>
  );
}

/** Что изменится на сайте: по строке на каждый язык статьи и отдельная строка про картинки. */
function Итог(props: {итог: NonNullable<Публикация['итог']>; settings: Settings}) {
  const п = props.settings.публикация;

  return (
    <>
      <ul className="publish-list">
        {props.итог.версии.map((версия) => (
          <li key={версия.локаль} className="publish-item">
            <span className="publish-label">{props.settings.локали[версия.локаль] ?? версия.локаль}</span>
            <span>{п.версии[версия.состояние] ?? версия.состояние}</span>
            {версия.скрыта && <span className="publish-quiet-inline">{п.скрыта}</span>}
          </li>
        ))}
      </ul>
      <p className="publish-quiet">
        {props.итог.картинки.length === 0
          ? п.картинкиНеМенялись
          : `${п.картинкиИзменились} ${props.итог.картинки.length}`}
      </p>
    </>
  );
}

/** Почему публикация остановлена: причина словами, потом всё, что к ней приложено. */
function Причина(props: {остановка: NonNullable<Публикация['остановка']>; settings: Settings}) {
  const п = props.settings.публикация;
  const {находки, чужие, вывод} = props.остановка;

  return (
    <>
      {находки.length > 0 && <Находки список={находки} settings={props.settings} />}

      {/* Сами посторонние пути — техническая подробность и на виду не лежат: человеку хватает
          того, что публикация остановлена и сколько лишнего в неё попало бы. */}
      {чужие.length > 0 && (
        <>
          <p className="publish-quiet">{п.постороннего} {чужие.length}</p>
          <Диагностика подпись={п.подробности}>
            <ul className="publish-list">
              {чужие.map((файл) => (
                <li key={файл} className="publish-item publish-block">
                  <span>{файл}</span>
                </li>
              ))}
            </ul>
          </Диагностика>
        </>
      )}

      {вывод !== '' && (
        <Диагностика подпись={п.ответСборки}>
          <pre className="publish-log">{вывод}</pre>
        </Диагностика>
      )}
    </>
  );
}

/** Находки проверок словами человека; код без своей фразы называется прямо, а не проглатывается. */
function Находки(props: {список: PrepareFinding[]; settings: Settings}) {
  const п = props.settings.подготовка;

  return (
    <ul className="publish-list">
      {props.список.map((находка, номер) => (
        <li
          key={`${находка.код}|${находка.путь ?? ''}|${номер}`}
          className={находка.уровень === 'блокер' ? 'publish-item publish-block' : 'publish-item'}
        >
          <span className="publish-label">{п.уровни[находка.уровень] ?? находка.уровень}</span>
          <span>{п.находки[находка.код] ?? `${п.неизвестнаяНаходка} ${находка.код}`}</span>
        </li>
      ))}
    </ul>
  );
}

/** Техническое: файлы, записи, их номера. Показывается только по желанию и решения не заменяет. */
function Подробности(props: {публикация: Публикация; settings: Settings}) {
  const в = props.settings.выпуск;
  const {файлы, коммиты, коммит} = props.публикация.подробности;

  return (
    <>
      {коммит !== null && <p className="publish-quiet">{props.settings.публикация.номерЗаписи} {коммит}</p>}
      <ul className="publish-list">
        {файлы.map((файл) => (
          <li key={файл.путь} className="publish-item">
            <span className="publish-label">{в.назначения[файл.назначение] ?? файл.назначение}</span>
            <span>{файл.путь}</span>
          </li>
        ))}
        {коммиты.map((запись) => (
          <li key={запись.sha} className="publish-item">
            <span className="publish-label">{запись.sha.slice(0, 7)}</span>
            <span>{запись.заголовок}</span>
          </li>
        ))}
      </ul>
    </>
  );
}

/** Идёт ли работа прямо сейчас: у этих шагов человеку показывается, чем программа занята. */
function идёт(шаг: Публикация['шаг']): boolean {
  return ['сохраняю', 'проверяю', 'сверяю', 'собираю', 'публикую'].includes(шаг);
}

/**
 * Что делает крестик прямо сейчас. У каждого состояния свой ответ, и он честный.
 *
 * Остановка — тоже результат, а не идущая проверка: отменять там уже нечего, крестик просто убирает
 * панель с глаз. Обещать «отменю проверку» после отказа значило бы говорить неправду.
 */
function подсказкаЗакрытия(публикация: Публикация, п: Settings['публикация']): string {
  if (публикация.шаг === 'публикую') return п.закрытьНельзя;
  if (публикация.шаг === 'готово' || публикация.остановка !== null) return п.закрытьПосле;

  return п.закрытьДо;
}

/** Заголовок панели: причина остановки, вопрос или итог — человек читает его первым. */
function заголовок(публикация: Публикация, п: Settings['публикация']): string {
  if (публикация.остановка !== null) {
    const {ключ, текст} = публикация.остановка;

    return ключ === null ? текст : (п.причины[ключ] ?? ключ);
  }
  if (публикация.шаг === 'спрашиваю') return п.вопрос;
  if (публикация.шаг === 'готово') return п.готово;

  return п.заголовок;
}
