/**
 * Экран до загрузки настроек. Надписи здесь — единственные в программе, что живут в коде:
 * показывать их приходится ровно тогда, когда настройки прочитать не удалось.
 * Белый экран недопустим (SPEC 4.11), поэтому причина пишется словами.
 */
export function Boot(props: {ошибка: string | null}) {
  if (props.ошибка) {
    return <div className="crash"><h1>Редактор не открылся</h1><pre>{props.ошибка}</pre></div>;
  }

  return <div className="loading">Загрузка…</div>;
}
