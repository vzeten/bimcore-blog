import {useState} from 'react';
import {адресГоден, адресИзНазвания, языкиРаздела} from '../../core/newArticle.mjs';
import {локалиРаздела, разделыДляСоздания} from '../../core/registry.mjs';
import type {ArticleRow, Settings} from '../types';

/**
 * Создание статьи: человек выбирает раздел, вводит название и видит будущий адрес.
 *
 * Раздел выбирается здесь же, а не только в дереве: форма закрывает весь экран, и подсказка
 * «выберите раздел в дереве слева» была невыполнимой — дерево оставалось под ней.
 *
 * Адрес показывается ДО создания и правится здесь же: после публикации его нельзя менять
 * без переадресации, поэтому момент выбора один, и он тут.
 */
export function NewArticle(props: {
  settings: Settings;
  /** Статьи реестра: из них берутся разделы — те же, что в дереве, второго списка нет. */
  articles: ArticleRow[];
  /** Раздел, выбранный в дереве до открытия формы. Он же выбран здесь. */
  раздел: string | null;
  занято: boolean;
  onСоздать: (раздел: string, название: string, адрес: string, язык: string) => void;
  onЗакрыть: () => void;
}) {
  const п = props.settings.подписи;
  const [название, setНазвание] = useState('');
  const [адрес, setАдрес] = useState('');
  const [правлюАдрес, setПравлюАдрес] = useState(false);
  // Язык статьи: по умолчанию основной. Выбрали английский — заглушка не нужна, статья и есть
  // английская; выбрали любой другой — английская заглушка создаётся вместе с ней.
  const [язык, setЯзык] = useState(props.settings.основнойЯзык);
  const [выбран, setВыбран] = useState<string | null>(props.раздел);

  const разделы = разделыДляСоздания(props.articles, props.settings) as {id: string; label: string; depth: number}[];
  // Раздел мог исчезнуть, пока форма была открыта: реестр перечитывается после создания статьи.
  // Отправлять его вслепую нельзя — сервер откажет, а окно обещало бы создание там, где нечего.
  const раздел = разделы.some((узел) => узел.id === выбран) ? выбран : null;

  // Языки ограничены выбранным разделом: в песочнице живёт только один, а в разделе, который
  // заполнен лишь по-английски, русскую статью класть некуда — сервер откажет, потому что
  // пустых разделов не заводит. Показывать выбор, который потом отвергнут, нельзя.
  const языки = языкиРаздела(раздел, props.settings, локалиРаздела(props.articles, раздел)) as string[];
  const наЯзыке = языки.includes(язык) ? язык : (языки[0] ?? '');

  // Пока человек не тронул адрес руками, он идёт из названия: владелец не должен придумывать
  // адреса, но и подменять его выбор, если он уже написал своё, программа не вправе.
  const итоговый = правлюАдрес ? адрес : адресИзНазвания(название);
  // Годность адреса проверяется тем же правилом, что и на сервере: иначе кнопка звала бы создать
  // статью с адресом, который сервер тут же отвергнет.
  const беда = чегоНеХватает({разделы: разделы.length, раздел, языки: языки.length, название, адрес: итоговый}, п);
  const готово = беда === null && !props.занято;

  return (
    <div className="newarticle" role="dialog">
      <div className="newarticle-body">
        <label>
          <span>{п.разделСтатьи}</span>
          <select value={раздел ?? ''} onChange={(event) => setВыбран(event.target.value || null)}>
            <option value="">{п.разделНеВыбран}</option>
            {разделы.map((узел) => (
              // Вложенность видна отступом: разделы одного уровня иначе неотличимы друг от друга.
              <option key={узел.id} value={узел.id}>{' '.repeat(узел.depth * 3)}{узел.label}</option>
            ))}
          </select>
        </label>

        <label>
          <span>{п.названиеСтатьи}</span>
          <input
            autoFocus
            value={название}
            onChange={(event) => setНазвание(event.target.value)}
            onKeyDown={(event) => {
              if (event.key === 'Enter' && готово) props.onСоздать(раздел!, название, итоговый, наЯзыке);
              if (event.key === 'Escape') props.onЗакрыть();
            }}
          />
        </label>

        <label>
          <span>{п.адресСтатьи}</span>
          <input
            value={итоговый}
            onChange={(event) => {
              setПравлюАдрес(true);
              setАдрес(event.target.value);
            }}
          />
        </label>

        <label>
          <span>{п.языкСтатьи}</span>
          <select value={наЯзыке} disabled={языки.length === 0} onChange={(event) => setЯзык(event.target.value)}>
            {языки.map((код) => (
              <option key={код} value={код}>{props.settings.локали[код]}</option>
            ))}
          </select>
        </label>

        <p className="newarticle-hint">
          {беда ?? `${п.статьяЛяжет} ${раздел}`}
        </p>

        <div className="newarticle-buttons">
          <button className="ghost" disabled={!готово} onClick={() => props.onСоздать(раздел!, название, итоговый, наЯзыке)}>
            {п.создать}
          </button>
          <button className="ghost" onClick={props.onЗакрыть}>{п.неСоздавать}</button>
        </div>
      </div>
    </div>
  );
}

/**
 * Чего не хватает для создания. `null` — всё на месте.
 *
 * Одно место и для кнопки, и для подсказки: разойдись они, человек видел бы неактивную кнопку
 * и слова «Ляжет в раздел…» под ней, то есть программа сообщала бы, что всё в порядке,
 * и отказывалась работать. Порядок проверок — порядок полей формы сверху вниз.
 */
function чегоНеХватает(
  поля: {разделы: number; раздел: string | null; языки: number; название: string; адрес: string},
  п: Settings['подписи'],
): string | null {
  if (поля.разделы === 0) return п.нетРазделов;
  if (поля.раздел === null) return п.выберитеРаздел;
  if (поля.языки === 0) return п.нетЯзыковРаздела;
  if (поля.название.trim() === '') return п.нетНазвания;
  // Адрес судится тем же правилом, что и на сервере: латиница, цифры и дефис (SPEC 2.2).
  if (!адресГоден(поля.адрес)) return п.плохойАдрес;

  return null;
}
