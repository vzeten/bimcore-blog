import {ErrorBar} from './ErrorBar';
import type {Действие} from '../useMessage';
import {ConflictPanel, type ОтветыСпора} from './ConflictPanel';
import {RestoreBars} from './RestoreBar';
import type {Article, Settings} from '../types';

/**
 * Всё, что стоит над статьёй, в одном месте и в постоянном порядке: ошибка, расхождение с файлом,
 * возврат к версии. Собрано вместе, чтобы окно не решало, что из этого видно,
 * и не выходило за предел размера файла (SPEC 4.9).
 */
export function Bars(props: {
  settings: Settings;
  article: Article | null;
  ошибка: string | null;
  /** Сообщение об удаче: полоса нейтральная, без красного. */
  удача: boolean;
  /** Кнопка в полосе сообщения («Открыть статью»). */
  действие?: Действие | null;
  onЗакрытьОшибку: () => void;
  /** Ответы человека по спорным местам и их отправка: сама панель правил не знает. */
  расхождение: {
    ответы: ОтветыСпора;
    идёт: boolean;
    ответить: (ключ: string, сторона: 'мои' | 'внешние') => void;
    применить: () => Promise<void>;
  };
  /**
   * Идёт просмотр версии. Панель расхождения прячется целиком: её выбор меняет рабочий текст,
   * а просмотр не меняет ничего. Решение ждёт возврата к работе.
   */
  просмотрИдёт: boolean;
  /** Открыт реестр: полосы работы со статьёй к нему не относятся. */
  реестр: boolean;
  спрашиваемВозврат: boolean;
  откатДоступен: boolean;
  onПодтвердитьВозврат: () => void;
  onОтменитьВозврат: () => void;
  onОткатить: () => void;
}) {
  return (
    <>
      <ErrorBar settings={props.settings} текст={props.ошибка} удача={props.удача} действие={props.действие} onЗакрыть={props.onЗакрытьОшибку} />

      {!props.просмотрИдёт && props.article?.спор && (
        <ConflictPanel
          settings={props.settings}
          спор={props.article.спор}
          ответы={props.расхождение.ответы}
          идёт={props.расхождение.идёт}
          onОтвет={props.расхождение.ответить}
          onПрименить={() => void props.расхождение.применить()}
        />
      )}

      {!props.реестр && (
        <RestoreBars
          settings={props.settings}
          спрашиваем={props.спрашиваемВозврат}
          откатДоступен={props.откатДоступен}
          onПодтвердить={props.onПодтвердитьВозврат}
          onОтменить={props.onОтменитьВозврат}
          onОткатить={props.onОткатить}
        />
      )}
    </>
  );
}
