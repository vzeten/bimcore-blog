import {цветЛокали} from '../../core/localeSigns.mjs';
import type {ПризнакиЛокали} from '../types';

/**
 * Обозначение одной языковой версии: её буквы и её собственные признаки. Один компонент на
 * реестр и на шапку открытой статьи — иначе список и шапка рисовали бы одну версию по-разному.
 *
 * Признаки независимы, поэтому у каждого своё место и они не спорят: точка над буквами, значок
 * ссылки под ними, цвет — у самих букв. Что значит каждый признак, решает ядро
 * (`core/localeSigns.mjs`); здесь только показ. Знака заглушки среди них нет: её признак ядро
 * по-прежнему считает и называет словами, а собственной точки в интерфейсе у неё больше не будет.
 */
export function LocaleMark(props: {
  code: string;
  признаки: ПризнакиЛокали;
  /** Слова про эту версию: цвет не имеет права быть единственным объяснением. */
  подсказка: string;
  /** Эта версия открыта в окне. Отмечается оправой, а не заливкой: заливка съела бы цвет букв. */
  открыта?: boolean;
  /** Обязательного языка нет, а статья на сайте: это не состояние версии, а беда статьи. */
  срыв?: boolean;
  disabled?: boolean;
  onClick: () => void;
}) {
  const классы = ['lang', `lang-цвет-${цветЛокали(props.признаки)}`];
  if (props.срыв) классы.push('lang-срыв');
  if (props.открыта) классы.push('lang-on');

  return (
    <button
      className={классы.join(' ')}
      title={props.подсказка}
      disabled={props.disabled}
      onClick={props.onClick}
    >
      {/* Знак здесь ровно один: правка, которой ещё нет на сайте. Заглушка своего знака не
          получает — решение владельца 2026-09-07: она видна словами в подсказке, а вторая точка
          рядом с первой читалась бы вторым состоянием выпуска, которым не является. */}
      <span className="lang-сверху">
        {props.признаки.изменена && <span className="lang-точка lang-точка-изменена" />}
      </span>

      {/* Возле букв стоят только признаки выпуска. Прежняя точка справа означала возраст
          версии (правилась раньше основной) и читалась третьим состоянием выпуска, которым
          не является; владелец просил убрать её и оставить шапку как главное меню. */}
      <span className="lang-код">{props.code.toUpperCase()}</span>

      <span className="lang-снизу">{props.признаки.поСсылке && <ЗначокСсылки />}</span>
    </button>
  );
}

/**
 * Знак «только по ссылке»: звено цепи. Рисуется линиями своего цвета, а не картинкой и не
 * эмодзи — эмодзи в семь точек высотой превращается в цветное пятно.
 */
function ЗначокСсылки() {
  return (
    <svg className="lang-ссылка" viewBox="0 0 14 14" aria-hidden="true" focusable="false">
      <g fill="none" stroke="currentColor" strokeWidth="1.6" strokeLinecap="round">
        <path d="M5.4 8.6 L8.6 5.4" />
        <path d="M8.2 4.4 L9.3 3.3 a2.4 2.4 0 0 1 3.4 3.4 L11.6 7.8" />
        <path d="M5.8 9.6 L4.7 10.7 a2.4 2.4 0 0 1-3.4-3.4 L2.4 6.2" />
      </g>
    </svg>
  );
}
