import type {Остановка} from '../usePublish';
import type {PrepareFinding} from '../publishTypes';
import type {Settings} from '../types';

/**
 * Почему не опубликовано — открывается само при неудаче и снова по нажатию на «Не опубликовано»
 * (решения владельца 2026-09-18, п.5а, и 2026-09-19): одна строка причины словами человека, «На сайт
 * ничего не ушло» (если это правда), [Показать ссылку] или [Показать место] (если место известно)
 * и [Понятно]. Всё остальное, что сервер приложил к отказу, — свёрнутые подробности.
 */
export function PublishReason(props: {
  settings: Settings;
  остановка: Остановка;
  onПерейти: (место: {путь: string; строка: number}) => void;
  onПонятно: () => void;
}) {
  const п = props.settings.публикация;
  const {находки, чужие, разрывы, невосстановленные, вывод} = props.остановка;
  const место = местоОстановки(props.остановка);

  return (
    <section className="publish" aria-live="polite">
      <p className="publish-block">{строкаПричины(props.остановка, props.settings)}</p>
      {ничегоНеУшло(props.остановка) && <p className="publish-quiet">{п.ничегоНеУшло}</p>}
      {props.остановка.изменены.length > 0 && <p className="publish-block">{п.неВернулись.replace('{пути}', props.остановка.изменены.join(', '))}</p>}
      <div className="publish-actions">
        {место !== null && (
          <button type="button" className="ghost ghost-main" onClick={() => props.onПерейти(место)}>
            {ССЫЛОЧНЫЕ.includes(место.код) ? п.показатьСсылку : п.перейтиКМесту}
          </button>
        )}
        <button type="button" className="ghost" onClick={props.onПонятно}>{п.понятно}</button>
      </div>

      {(находки.length > 1 || разрывы.length > 0 || чужие.length > 0 || невосстановленные.length > 0 || вывод !== '') && (
        <details className="publish-tech">
          <summary>{п.подробности}</summary>
          {находки.length > 1 && <Находки список={находки} settings={props.settings} />}
          {разрывы.length > 0 && <Пути список={разрывы.map((разрыв) => `${props.settings.выпуск.разрывы[разрыв.причина] ?? разрыв.причина}${разрыв.путь ? `: ${разрыв.путь}` : ''}`)} />}
          {/* Посторонний файл — чужая работа, непривёденный путь — наша незаконченная. */}
          {невосстановленные.length > 0 && <><p className="publish-quiet">{п.неПривелось} {невосстановленные.length}</p><Пути список={невосстановленные} /></>}
          {чужие.length > 0 && <><p className="publish-quiet">{п.постороннего} {чужие.length}</p><Пути список={чужие} /></>}
          {вывод !== '' && <pre className="publish-log">{вывод}</pre>}
        </details>
      )}
    </section>
  );
}

/** Находки проверок словами человека; код без своей фразы называется прямо, а не проглатывается. */
export function Находки(props: {список: PrepareFinding[]; settings: Settings}) {
  return (
    <ul className="publish-list">
      {props.список.map((находка, номер) => (
        <li
          key={`${находка.код}|${находка.путь ?? ''}|${номер}`}
          className={находка.уровень === 'блокер' ? 'publish-item publish-block' : 'publish-item'}
        >
          <span>{словаНаходки(находка, props.settings)}</span>
        </li>
      ))}
    </ul>
  );
}

/** Просто перечень строк: техническая подробность, которая на решение не влияет. */
function Пути(props: {список: string[]}) {
  return (
    <ul className="publish-list">
      {props.список.map((путь, номер) => <li key={`${путь}|${номер}`} className="publish-item publish-block"><span>{путь}</span></li>)}
    </ul>
  );
}

/**
 * Фраза находки словами человека (решение владельца 2026-09-19): что случилось и что сделать. Адрес,
 * имя блока или файла подставляются туда, где фраза их называет (`{текст}`, `{значение}`); поле —
 * `«{поле}»` — называется его подписью из свойств статьи, как её видит человек, а неизвестное поле
 * из фразы просто уходит. Номера строки в тексте нет — к месту ведёт кнопка.
 */
export function словаНаходки(находка: PrepareFinding, settings: Settings): string {
  const п = settings.подготовка;
  const фраза = п.находки[находка.код];
  if (фраза === undefined) return `${п.неизвестнаяНаходка} ${находка.код}`;
  const значение = находка.значение ?? '';
  const поле = находка.поле ? (settings.подписиПолей[находка.поле] ?? находка.поле) : '';
  const сПолем = поле === '' ? фраза.replace(/ ?«\{поле\}»/g, '') : фраза.split('{поле}').join(поле);
  return сПолем.split('{текст}').join(находка.текст || значение).split('{значение}').join(значение);
}

/** Находки про ссылку: кнопка перехода к ним называется «Показать ссылку». */
const ССЫЛОЧНЫЕ = ['ссылкаВНикуда', 'ссылкаНеПроверена'];

/**
 * Одна строка причины: первая находка словами (со счётом остальных) либо причина окна, либо слова
 * сервера. Человек читает одну строку — остальное свёрнуто в сведения.
 */
export function строкаПричины(остановка: Остановка, settings: Settings): string {
  const п = settings.публикация;
  if (остановка.находки.length > 0) {
    const ещё = остановка.находки.length - 1;
    const первая = словаНаходки(остановка.находки[0], settings);
    return ещё > 0 ? `${первая} ${п.ещё.replace('{n}', String(ещё))}` : первая;
  }
  if (остановка.ключ === null) return остановка.текст;
  // Состав не доказан — человеку называется сама причина, а не общее «не удалось понять».
  const разрыв = остановка.разрывы[0];
  if (разрыв !== undefined) return settings.выпуск.разрывы[разрыв.причина] ?? п.причины[остановка.ключ] ?? остановка.ключ;
  return п.причины[остановка.ключ] ?? остановка.ключ;
}

/**
 * Правда ли «На сайт ничего не ушло» (замечание контролёра этапа 2). Не печатается, когда исход
 * отправки неясен (сервер мог её принять; в том числе когда сам запрос записи или отправки оборвался
 * без ответа) и когда статья уже записана, но не отправлена или не приведена в порядок: там слова
 * причины сами говорят, что случилось, а обещание было бы неправдой.
 */
export function ничегоНеУшло(остановка: Остановка): boolean {
  if (остановка.наОтправке) return false;
  if (остановка.код !== null && ['исходНеясен', 'невосстановлено'].includes(остановка.код)) return false;
  return остановка.ключ === null || !['неОтправилось', 'невосстановлено'].includes(остановка.ключ);
}

/** Место в статье, куда можно перейти: первая находка, у которой известны файл и строка тела. */
export function местоОстановки(остановка: Остановка): {путь: string; строка: number; код: string} | null {
  const находка = остановка.находки.find((н) => typeof н.путь === 'string' && н.путь !== '' && typeof н.строка === 'number');
  return находка ? {путь: находка.путь as string, строка: находка.строка as number, код: находка.код} : null;
}
