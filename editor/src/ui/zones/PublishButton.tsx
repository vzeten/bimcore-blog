import {usePublish, идётПубликация} from '../usePublish';
import {перейтиКСтроке} from '../editor/jumpTo';
import {PublishAsk} from './PublishAsk';
import {PublishReason, строкаПричины} from './PublishReason';
import type {Действие} from '../useMessage';
import type {Article, Settings} from '../types';

/**
 * Главное действие человека: «Опубликовать» (решение владельца 2026-09-18, п.2–5, макет одобрен).
 *
 * Нажатие открывает единственный вопрос (`PublishAsk`); после ответа программа идёт сама, а кнопка
 * говорит «Публикуется…». Отказ быстрой проверки или отправки — «Не опубликовано»; по нажатию видна
 * причина (`PublishReason`). Заперта кнопка только там, где писать нельзя, — в просмотре старой
 * версии, — и пока идёт сам ход.
 *
 * Панель причины стоит в одной опоре с кнопкой и выпадает прямо под ней: полоса во всю ширину окна
 * не показывала бы, откуда она взялась.
 */
export function PublishButton(props: {
  settings: Settings;
  article: Article | null;
  dirty: boolean;
  просмотр: boolean;
  onSave: () => Promise<boolean>;
  onДата: (дата: string) => Promise<boolean>;
  onОбложка: (адрес: string) => Promise<boolean>;
  onДоступность: (режим: string) => Promise<boolean>;
  onOpen: (path: string) => void | Promise<boolean | void>;
  onОбновить: () => Promise<void>;
  окноСейчас?: () => string;
  onСообщить: (текст: string, действие?: Действие) => void;
}) {
  const п = props.settings.публикация;
  const публикация = usePublish(
    props.article?.path ?? null,
    props.dirty,
    props.article?.заход ?? 0,
    {сохранить: props.onSave, дата: props.onДата, обложка: props.onОбложка, доступность: props.onДоступность},
    // После успеха человеку говорится только то, что требует его действия (решение владельца
    // 2026-09-19): ссылки на компьютере убрать не вышло. Непроверенное молчит — если сайт не
    // соберётся, это скажет значок «Сайт».
    (исход) => {
      // Сайт и файлы изменились: реестр, буквы языков и надписи шапки перечитываются сразу, без
      // перезагрузки окна (проба владельца 2026-09-19).
      void props.onОбновить();
      if (исход.ссылкиНеУбраны.length > 0) props.onСообщить(`${п.ссылкиНеУбраны} ${исход.ссылкиНеУбраны.join(', ')}`);
    },
    props.article?.versions ?? {},
    // Публикация не прошла, а человек уже на другом экране: полоса ошибки там, где он сейчас, с
    // кнопкой «Открыть статью» (проба владельца 2026-09-19).
    (путь, название, остановка) => props.onСообщить(
      п.неОпубликованаСтатья.replace('{название}', название).replace('{причина}', сМалой(строкаПричины(остановка, props.settings))),
      {подпись: п.открытьСтатью, сделать: () => void props.onOpen(путь)},
    ),
    props.окноСейчас,
  );
  const идёт = идётПубликация(публикация.шаг);
  const неВышло = публикация.остановка !== null;
  // Публикуется другая статья: вторую не начать, и кнопка говорит почему.
  const другая = публикация.занята && !идёт && !неВышло;

  // «Показать ссылку» / «Показать место»: окно причины закрывается (кнопка «Не опубликовано»
  // остаётся и открывает его снова), переход ждёт редактор нужной статьи — открытой или той, что
  // откроется, — и найденное там выделяется целиком.
  const перейти = async (место: {путь: string; строка: number; столбец?: number; длина?: number}) => {
    публикация.скрытьПричину();
    перейтиКСтроке(место.путь, место.строка, место.столбец, место.длина);
    if (место.путь !== props.article?.path) await props.onOpen(место.путь);
  };

  return (
    <div className="publish-anchor">
      <button
        className={неВышло ? 'ghost publish-failed' : 'ghost ghost-main'}
        disabled={идёт || другая || props.просмотр || !props.article}
        title={props.просмотр ? props.settings.подписи.идётПросмотр : (идёт ? (п.шаги[публикация.шаг] ?? '') : '')}
        onClick={неВышло ? публикация.показатьПричину : публикация.открыть}
      >
        {идёт ? п.публикуется : неВышло ? п.неОпубликовано : другая ? п.другаяСтатья : props.settings.подписи.опубликовать}
      </button>

      {неВышло && публикация.причинаОткрыта && (
        <PublishReason
          settings={props.settings}
          остановка={публикация.остановка!}
          onПерейти={(место) => void перейти(место)}
          onПонятно={публикация.понятно}
        />
      )}

      {публикация.окно !== null && props.article && !props.просмотр && (
        <PublishAsk
          settings={props.settings}
          path={props.article.path}
          окно={публикация.окно}
          onВыбрать={публикация.выбрать}
          версии={props.article.versions}
          onОтметить={публикация.отметить}
          onОпубликовать={() => void публикация.начать(props.article?.title ?? '')}
          onОтмена={публикация.отмена}
        />
      )}
    </div>
  );
}

/**
 * Причина после двоеточия во фразе — со строчной буквы: «…не опубликована: ссылка «…» ведёт…».
 * Имена собственные (English, GitHub) не трогаются: опускается только обычное русское слово.
 */
export const сМалой = (текст: string): string => (/^[А-ЯЁ][а-яё]/.test(текст) ? текст.charAt(0).toLowerCase() + текст.slice(1) : текст);
