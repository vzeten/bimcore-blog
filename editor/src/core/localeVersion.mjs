// Начало одной языковой версии у статьи, которая уже есть.
//
// Отдельно от `newArticle.mjs`: там статья заводится целиком и адрес ещё выбирается, здесь статья
// уже живёт на сайте, а её адрес трогать нельзя вовсе (SPEC 2.5). Так живут старые статьи, у
// которых испанского файла нет, и новые, где заглушку однажды убрали.
//
// Чистое правило: диска здесь нет. Что и куда положить, решается целиком до первой записи —
// иначе на диске останется файл версии без своего состояния.

import {articlePlace} from './frontmatterRules.mjs';
import {путьВерсии} from './articles.mjs';
import {путьФайлаСостояния} from './articleState.mjs';
import {шаблонЗаглушки} from './stubText.mjs';
import {черновикВерсии, шапкаВерсии} from './newArticle.mjs';

/**
 * План начала языковой версии. Возвращает `{ошибка}` либо `{path, состояние, локаль}`.
 *
 * `путь` — файл существующей версии, от которой отсчитываются место и адрес.
 * `локаль` — язык, который человек попросил начать.
 * `slug` и `название` читаются адаптером из существующей версии: адрес общий у всех языков, и
 * пересчитывать его из названия здесь нельзя — у старых статей он давно свой и менять его
 * означало бы сменить адрес живой страницы.
 *
 * Версия рождается заглушкой на своём языке, а не пустым файлом: пустая страница на сайте выглядит
 * поломкой, а заглушка честно говорит читателю, что перевода пока нет. Дальше человек пишет поверх
 * неё перевод — это та же правка текста, что и в любой другой версии.
 */
export function планЛокали({путь, локаль, slug, название, дата, авторы, settings}) {
  const roots = settings['контент'];
  const место = articlePlace(путь, roots);

  // Файл не из известных корней: где лежит его сосед на другом языке, сказать нечем.
  if (место.locale === null) return {ошибка: 'неПутьСтатьи'};
  // Своя же локаль — не начало версии, а открытие того, что уже открыто.
  if (место.locale === локаль) return {ошибка: 'локальУжеЕсть'};

  const корень = roots.find((root) => root['род'] === место.kind && root['локаль'] === локаль);
  // Языка нет у этого рода вовсе — например, песочница живёт на одном языке.
  if (!корень) return {ошибка: 'нетЯзыкаВРазделе'};

  const шаблон = шаблонЗаглушки(локаль, settings);
  // Текста заглушки для языка не задано. Подставить чужой язык значит соврать читателю, а
  // умолчание в коде завело бы второй источник правды рядом с настройкой (SPEC 4.4.1).
  if (!шаблон) return {ошибка: 'нетШаблонаЗаглушки'};

  const имя = String(название ?? '').trim();
  if (имя === '') return {ошибка: 'нетНазвания'};

  // Адрес берётся у существующей версии как есть. Его может не быть вовсе — так живут страницы
  // разделов: Docusaurus выводит их адрес из пути, а путь у языковых версий один и тот же, значит
  // адреса совпадут сами. Вписать сюда придуманный адрес значило бы сменить адрес живой страницы,
  // а отказать — оставить человека без входа в локаль у двенадцати статей сайта.
  const адрес = String(slug ?? '').trim();

  const path = путьВерсии(корень, место.inside);

  return {
    path,
    локаль,
    text: шапкаВерсии({
      род: место.kind,
      title: `${шаблон['заголовок']} ${имя}`,
      slug: адрес,
      settings,
      // Дата берётся у существующей версии: запись блога без даты Docusaurus не соберёт, а своя
      // дата у перевода развела бы языковые версии одной записи по разным дням ленты.
      сегодня: дата,
      // Автор принадлежит записи, а не набору полей новой статьи: возьми его из настроек —
      // и перевод чужой записи молча вышел бы за подписью того, кто её не писал.
      перенос: авторы ? {authors: авторы} : {},
      описание: шаблон['описание'],
    }) + `\n${шаблон['тело']}\n`,
    состояние: {
      path: путьФайлаСостояния(path, settings),
      // Начатая версия — черновик: на сайте её ещё никто не видел. Правило состояния одно на
      // программу, чтобы созданная и начатая версии не расходились в служебном файле.
      text: черновикВерсии(settings),
    },
  };
}
