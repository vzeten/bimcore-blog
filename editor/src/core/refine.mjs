// «Доработать»: реестр обработчиков и одна оркестрация поверх рабочей копии статьи.
//
// Реестр — данные: порядок применения, умолчание флажка, реализация. Окно и ручка берут перечень
// отсюда и имён не знают: новая автоматизация — один обработчик и одна строка здесь.
// Договор обработчика: `анализ(копия, settings)` → предложение с отчётом либо `null` (неприменимо);
// `применить(копия, предложение, инструменты)` → `{копия, отчёт?}`; `проверить(копия, предложение,
// settings)`. Зависимость выражена только порядком: каждый видит копию после предыдущих выбранных.
// Рабочая копия: `{путь, текст, файлы: Map<имя, байты | null>, имена: Set}`; `null` — удаление.

import {подписиМедиа} from './refineText.mjs';
import {обложка, поляШапки} from './refineHead.mjs';
import {медиаподготовка, переименование} from './refineFiles.mjs';

/** Порядок обязателен: переименование видит уже сжатые файлы, обложка — итоговые имена. */
export const ОБРАБОТЧИКИ = [
  {код: 'подписиМедиа', поУмолчанию: true, обработчик: подписиМедиа},
  {код: 'поляШапки', поУмолчанию: true, обработчик: поляШапки},
  {код: 'медиа', поУмолчанию: true, обработчик: медиаподготовка},
  {код: 'переименование', поУмолчанию: false, обработчик: переименование},
  {код: 'обложка', поУмолчанию: true, обработчик: обложка},
];

export const ПО_УМОЛЧАНИЮ = ОБРАБОТЧИКИ.filter((з) => з.поУмолчанию).map((з) => з.код);

/**
 * Инструменты плана: ничего не считают. Какой формат окажется легче, до настоящей обработки не знает
 * никто, поэтому план честно получает итог «план», а не выдуманные байты.
 */
export const ИНСТРУМЕНТЫ_ПЛАНА = {
  подготовить: async (набор) => набор.map(() => ({итог: 'план'})),
};

/**
 * Пройти реестр по порядку над снимком: выбранные применяются и проверяются, невыбранные только
 * анализируются (предпросмотр при текущем наборе). Диска здесь нет.
 */
export async function выполнить(снимок, выбранные, settings, инструменты) {
  let копия = {...снимок, файлы: new Map(снимок.файлы)};
  const отчёт = [];
  for (const {код, обработчик} of ОБРАБОТЧИКИ) {
    const выбран = выбранные.includes(код);
    const предложение = обработчик.анализ(копия, settings);
    if (предложение === null) {
      отчёт.push({код, выбран, применимо: false, изменено: [], оставлено: [], человеку: []});
      continue;
    }
    let итог = предложение.отчёт;
    if (выбран) {
      const после = await обработчик.применить(копия, предложение, инструменты);
      копия = после.копия;
      итог = после.отчёт ?? итог;
      if (!обработчик.проверить(копия, предложение, settings)) throw new Error(`доработка: проверка не прошла у ${код}`);
    }
    отчёт.push({код, выбран, применимо: true, ...итог});
  }
  return {копия, отчёт, изменения: разница(снимок, копия)};
}

/** Что легло бы на диск: новый текст (или `null`) и файлы, чьи байты отличаются от снимка. */
export function разница(снимок, копия) {
  const файлы = [];
  for (const [имя, байты] of копия.файлы) {
    const было = снимок.файлы.get(имя) ?? null;
    if (байты === было || (байты !== null && было !== null && равны(байты, было))) continue;
    файлы.push({имя, байты});
  }
  return {текст: копия.текст === снимок.текст ? null : копия.текст, файлы};
}

/** Побайтовое сравнение без Buffer: ядро общее для сервера и окна (SPEC 4.10.1). */
function равны(a, b) {
  return a.length === b.length && a.every((байт, i) => байт === b[i]);
}
