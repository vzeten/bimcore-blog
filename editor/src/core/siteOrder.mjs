// Порядок реестра «как на сайте» и «последние правки» (решение владельца 2026-09-21).
// Чистые правила: даты и номера меню приходят готовыми от сервера, окно по файлам не ходит.
//
// Правило ленты чужое — его задал Docusaurus (`plugin-content-blog/src/blogUtils.ts`): записи
// идут по `date` из шапки по убыванию, и сортируется каждый язык сайта своими файлами. Реестр
// показывает одну строку на все языки, поэтому дату объявляет основное дерево ленты — английское,
// язык сайта по умолчанию: ровно так стоит лента по адресу `/blog/`.

import {readField} from './articleFile.mjs';
import {ЛЕНТА} from './menuOrder.mjs';

/** Ключ режима «как на сайте». Колонкой таблицы он не является: щёлкать не по чему. */
export const КАК_НА_САЙТЕ = 'какНаСайте';

/** Два режима переключателя порядка. Первый — порядок, с которым реестр открывается всегда. */
export const РЕЖИМЫ_ПОРЯДКА = ['сайт', 'правки'];

/**
 * Сортировка, которую даёт режим. «Последние правки» — это прежняя колонка «Когда» по убыванию:
 * заголовок колонки при этом подсвечен, и человек видит, откуда порядок взялся.
 */
export function порядокРежима(режим) {
  return режим === 'правки'
    ? {колонка: 'когда', сторона: 'вниз'}
    : {колонка: КАК_НА_САЙТЕ, сторона: 'вверх'};
}

/**
 * `date` из шапки версии числом (миллисекунды) либо `null`, если поля нет или оно не дата.
 *
 * Читается так же, как читает Docusaurus: строка без часового пояса считается временем по UTC
 * (он приписывает к ней `Z`), а голая дата `2026-09-04` в YAML и есть полночь по UTC. Иначе
 * одна и та же дата на компьютере в Москве и на сервере сборки дала бы разный порядок.
 */
export function датаШапки(frontmatterRaw) {
  const сырое = String(readField(frontmatterRaw, 'date') ?? '').trim().replace(/^["']|["']$/g, '');
  if (сырое === '') return null;

  const безПояса = !/(Z|[+-]\d{2}:?\d{2})$/i.test(сырое);
  const строка = /^\d{4}-\d{1,2}-\d{1,2}$/.test(сырое)
    ? `${сырое}T00:00:00Z`
    : (безПояса ? `${сырое.replace(' ', 'T')}Z` : сырое);
  const число = Date.parse(строка);

  return Number.isFinite(число) ? число : null;
}

/** Локаль основного дерева рода: первый корень этого рода в настройках (так же и у меню). */
function основнаяЛокаль(род, settings) {
  return (settings['контент'] ?? []).find((root) => root['род'] === род)?.['локаль'] ?? null;
}

/**
 * Дата записи ленты по английской версии. Нет её — `null`: в английской ленте такой записи нет
 * вовсе, и подставлять дату перевода значило бы поставить её туда, где читатель её не увидит.
 */
export function датаЛенты(article, settings) {
  const код = основнаяЛокаль(article.kind, settings);
  return (код && article.versions?.[код]?.дата) ?? null;
}

/**
 * Группа статьи в «Всех статьях». Документация и лента на сайте — два разных места с разными
 * правилами порядка, и смешать их одной шкалой честно нельзя: номер меню и дата не сравниваются.
 * Поэтому группы идут как в шапке сайта: сначала документация (она и есть главная страница),
 * потом лента, а в конце то, чего на сайте нет вовсе (песочница).
 */
function группа(article) {
  if (article.наСайте !== true) return 2;
  return article.kind === ЛЕНТА ? 1 : 0;
}

/** Пустое значение уходит вниз, а равные разводит следующий ключ. */
function сравнитьЧисла(одно, другое, знак) {
  const пустоОдно = одно === null || одно === undefined;
  const пустоДругое = другое === null || другое === undefined;

  if (пустоОдно || пустоДругое) return пустоОдно === пустоДругое ? 0 : (пустоОдно ? 1 : -1);
  return одно === другое ? 0 : (одно < другое ? -знак : знак);
}

/**
 * Сравнение двух статей «как на сайте». Равные даты ленты разводит путь по кодам символов:
 * сам Docusaurus держит у равных дат порядок обхода папок, а он на живой ленте алфавитный.
 * Путь же — последний ключ везде: порядок не зависит от того, в каком виде сервер отдал список.
 */
export function сравнитьКакНаСайте(одна, другая, settings) {
  const группы = группа(одна) - группа(другая);
  if (группы !== 0) return группы;

  const поСути = одна.kind === ЛЕНТА && другая.kind === ЛЕНТА
    ? сравнитьЧисла(датаЛенты(одна, settings), датаЛенты(другая, settings), -1)
    : сравнитьЧисла(одна.порядокМеню, другая.порядокМеню, 1);
  if (поСути !== 0) return поСути;

  if (одна.key === другая.key) return 0;
  return одна.key < другая.key ? -1 : 1;
}
