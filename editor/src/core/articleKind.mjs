// Что это за файл: статья, страница категории или запись вне канона.
//
// Единственное место правила на всю программу. Реестр, состав выпуска, удаление и будущий архив
// обязаны считать статьёй одно и то же: разойдись они хоть на признак — статья была бы видна
// в реестре, но не существовала бы для выпуска, а `_category_.json` категории уехал бы в коммит
// как «файл статьи».
//
// **Канон проекта (слово владельца 2026-08-14):**
// - одна языковая версия статьи — это её КАТАЛОГ целиком, а основной файл всегда `index.mdx`;
// - категория — каталог с `_category_.json`; `index.mdx` рядом с ним — страница-описание категории;
// - отдельный файл вроде `lessons/proba.mdx` и `index.md` статьями не считаются.
//
// Возможности Docusaurus шире, но программа обслуживает контракт этого проекта. Второй формат
// статьи здесь не заводится: то, что вне канона, так и называется — вне канона.

/** Имя основного файла статьи. Иное имя — не статья, а запись вне канона. */
export const ИМЯ_СТАТЬИ = 'index.mdx';

/** Имя файла, которым Docusaurus объявляет каталог категорией. */
export const ИМЯ_КАТЕГОРИИ = '_category_.json';

export const СТАТЬЯ = 'статья';
export const СТРАНИЦА_КАТЕГОРИИ = 'страницаКатегории';
export const КОРНЕВАЯ_СТРАНИЦА = 'корневаяСтраница';
export const ВНЕ_КАНОНА = 'внеКанона';

/**
 * Вид языковой версии по её пути и одному факту с диска.
 *
 * `категорияРядом` — лежит ли `_category_.json` в том же каталоге. Факт собирает адаптер: правило
 * диска не знает (SPEC 4.6). У переводов своего `_category_.json` нет — категорию объявляет
 * основное дерево, поэтому адаптер смотрит тот же путь во всех корнях одного рода.
 */
export function видВерсии(путь, факты = {}) {
  const {категорияРядом, вКорнеРода, адресКорня} = совместимость(факты);

  // Корневая страница контента: лежит прямо в корне дерева и объявляет себя корнем сайта своим
  // `slug: /`. Роль даёт расположение и шапка, а не имя файла: `intro` — обычное историческое имя,
  // и специальным правилом в коде оно не становится. Каталог такой страницы — весь корень рода,
  // и владеть им она не может; собственных файлов у неё ровно один — она сама.
  if (вКорнеРода === true) return адресКорня === true ? КОРНЕВАЯ_СТРАНИЦА : ВНЕ_КАНОНА;

  if (имяФайла(путь) !== ИМЯ_СТАТЬИ) return ВНЕ_КАНОНА;

  return категорияРядом === true ? СТРАНИЦА_КАТЕГОРИИ : СТАТЬЯ;
}

/** Прежний вызов передавал один признак вторым доводом; принимаем оба вида записи. */
function совместимость(факты) {
  return typeof факты === 'boolean' ? {категорияРядом: факты} : (факты ?? {});
}

/**
 * Откуда брать собственные файлы версии — то, что уедет вместе с ней.
 *
 * `каталогРекурсивно` — обычная статья: ВЕСЬ её каталог, включая вложенные папки и файлы, имён
 * которых программа не знает. Список допустимых имён здесь не появляется никогда: завтра в каталоге
 * заведутся `product.jpg`, комментарии и метаданные, и выбирать знакомое значило бы терять новое.
 *
 * `верхнийУровень` — страница категории: файлы того же каталога, кроме `_category_.json`, и БЕЗ
 * вложенных папок. Вложенные папки категории — это её дочерние статьи и подкатегории, чужое добро;
 * забрать их значило бы уносить в коммит одной страницы весь раздел.
 *
 * `толькоФайл` — корневая страница контента: её каталог — весь корень рода, поэтому собственным
 * у неё остаётся один файл, она сама. Соседние статьи и категории корня в состав не входят.
 *
 * `нечего` — запись вне канона: одиночный MDX не в своём каталоге и без роли корневой страницы.
 * Доказать её состав нечем, и программа говорит об этом прямо, а не угадывает.
 */
export function границаСостава(вид) {
  if (вид === СТАТЬЯ) return 'каталогРекурсивно';
  if (вид === СТРАНИЦА_КАТЕГОРИИ) return 'верхнийУровень';
  // Корневая страница владеет только собой: её файл состояния состав добавляет отдельным правилом.
  if (вид === КОРНЕВАЯ_СТРАНИЦА) return 'толькоФайл';

  return 'нечего';
}

/** Имя файла из пути. Пути в программе всегда со стрелкой вперёд — так их отдаёт обход папок. */
function имяФайла(путь) {
  return String(путь ?? '').split('/').pop() ?? '';
}
