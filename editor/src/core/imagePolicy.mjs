// Что делать с выбранной картинкой. Чистое правило без файлов, без `Buffer` и без библиотек
// обработки — одно на все дороги загрузки (вставка, замена, обложка).
//
// Правило простое намеренно (решение владельца 2026-08-20, проверено на его настоящих картинках):
// программа готовит два качественных представления картинки и берёт то, которое весит меньше
// всего. Никаких лестниц качества, повторных пережатий и распознавания «фото или снимок экрана»:
// они давали непредсказуемый вес и не окупали сложности.

/** Килобайт и мегабайт считаются по 1024, как их считает проводник Windows. */
const В_КИЛОБАЙТЕ = 1024;

/**
 * Решение по картинке. Возвращает `{действие, причина}`:
 * `оставить` — байты идут на диск нетронутыми (чужой формат программе не по зубам);
 * `обработать` — картинка приводится к ширине страницы и пересобирается кандидатами;
 * `отказать` — файл не принимается вовсе, и причина названа кодом.
 *
 * Анимация решается первой: анимированную картинку (GIF, APNG) программа не декодирует ни при
 * каком весе — от неё остался бы один кадр.
 */
export function решениеПоКартинке({формат, анимация, байтов, настройки}) {
  if (анимация) {
    const предел = настройки['картинки']['пределГифМегабайт'] * В_КИЛОБАЙТЕ * В_КИЛОБАЙТЕ;
    // Строгое «больше»: файл ровно в предел принимается. Граница названа словом «до 5 МБ»,
    // и человек, ужавший файл ровно в неё, обязан получить приём, а не отказ.
    return байтов > предел
      ? {действие: 'отказать', причина: 'анимацияТяжёлая'}
      : {действие: 'оставить', причина: null};
  }

  return формат === 'jpg' || формат === 'png'
    ? {действие: 'обработать', причина: null}
    : {действие: 'оставить', причина: null};
}

/**
 * Какие представления картинки готовить. Всегда качественный PNG; JPG — только для непрозрачной
 * картинки: он прозрачности не хранит вовсе, и вырезанный предмет получил бы чёрный фон.
 *
 * Числа рецептов живут в настройках: это те две проверенные точки качества, которыми программа
 * и обходится. Третьего рецепта нет намеренно — выбор идёт весом, а не перебором качества.
 */
export function рецепты({прозрачная, настройки}) {
  const правила = настройки['картинки'];
  const png = {
    формат: 'png',
    качество: правила['качествоPng'],
    усилие: правила['усилиеПалитры'],
    размывка: правила['размывкаPng'],
  };

  return прозрачная ? [png] : [png, {формат: 'jpg', качество: правила['качествоJpg']}];
}

/**
 * Стоит ли менять файл человека на приготовленный. Перекодировать ради пары процентов незачем:
 * человек принёс свой файл, и подменять его почти таким же — лишний риск без выгоды.
 *
 * Оба условия сразу: и доля, и абсолютная разница. Доля бережёт маленькие файлы (десятая часть
 * от 30 КБ — это три килобайта, ради них трогать картинку не стоит), килобайты — большие.
 */
export function выигрышСтоитЗамены({былоБайт, сталоБайт, настройки}) {
  const правила = настройки['картинки'];
  const выигрыш = былоБайт - сталоБайт;

  return выигрыш >= былоБайт * (правила['выигрышПроцентов'] / 100)
    && выигрыш >= правила['выигрышКилобайт'] * В_КИЛОБАЙТЕ;
}

/** Вес файла в килобайтах для показа человеку. Одно место счёта на все сообщения программы. */
export function килобайты(байтов) {
  return Math.round(байтов / В_КИЛОБАЙТЕ);
}
