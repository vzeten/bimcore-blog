// Правила записи статьи: ветка выпуска и сверка индекса с утверждённым перечнем. Решение «можно ли
// фиксировать» с зелёной полной сборкой снято вместе со сборкой на компьютере (решение владельца
// 2026-09-18): заслоны записи живут в `publishRoute.mjs` и `planCommit.mjs`.
//
// Чистые правила: на входе факты, собранные адаптером, на выходе решение. Ни git, ни диска здесь
// нет (SPEC 4.6). Это первое место программы, которое вообще меняет git, поэтому правило написано
// как заслон, а не как помощник: любой невыясненный признак — отказ.
//
// **Отказ дешевле ошибки.** Лишний файл в коммите публикации уезжает на сайт вместе со статьёй, а
// недостающий делает статью битой. Ни то, ни другое не лечится отменой в окне.

/** Ветка, в которую программа вправе коммитить. Другая — отказ; переключать ветки она не смеет. */
export const ВЕТКА_ВЫПУСКА = 'main';

/**
 * Совпал ли индекс с утверждённым перечнем. Индекс вправе быть УЖЕ перечня: файл, не изменившийся
 * с прошлого коммита, добавлением в индекс не попадает — это не беда, а обычное дело.
 * Лишний путь в индексе — беда: значит в коммит уедет то, чего человеку не показывали.
 */
export function индексВПеречне(индекс, пути) {
  const разрешено = new Set(пути);

  return (индекс ?? []).filter((путь) => !разрешено.has(путь));
}
