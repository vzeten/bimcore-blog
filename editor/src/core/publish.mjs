// Правила первого коммита статьи: можно ли фиксировать и что именно.
//
// Чистые правила: на входе факты, собранные адаптером, на выходе решение. Ни git, ни диска здесь
// нет (SPEC 4.6). Это первое место программы, которое вообще меняет git, поэтому правило написано
// как заслон, а не как помощник: любой невыясненный признак — отказ.
//
// **Отказ дешевле ошибки.** Лишний файл в коммите публикации уезжает на сайт вместе со статьёй, а
// недостающий делает статью битой. Ни то, ни другое не лечится отменой в окне.

/** Ветка, в которую программа вправе коммитить. Другая — отказ; переключать ветки она не смеет. */
export const ВЕТКА_ВЫПУСКА = 'main';

/**
 * Можно ли делать коммит и какие пути в него войдут.
 *
 * `ветка` — текущая ветка репозитория, `индекс` — пути, уже лежащие в индексе (чужая работа),
 * `состав` — заново посчитанный состав выпуска, `сборкаЗелёная` — прошла ли полная сборка,
 * `отпечатокСборки` — отпечаток содержимого состава на момент сборки,
 * `отпечатокСейчас` — отпечаток того же состава сейчас.
 *
 * Возвращает `{ошибка}` либо `{пути}` — перечень, который будет добавлен поимённо.
 */
export function решениеОКоммите({ветка, индекс, состав, сборкаЗелёная, отпечатокСборки, отпечатокСейчас}) {
  if (ветка !== ВЕТКА_ВЫПУСКА) return {ошибка: 'неТаВетка', ветка};

  // Чужая работа в индексе: разобрать, что там наше, а что нет, программа не берётся. Отказ до
  // всякой операции — единственный ответ, который ничего не портит.
  if ((индекс ?? []).length > 0) return {ошибка: 'индексНеПуст', индекс};

  if (!состав || состав.разрывы?.length > 0) return {ошибка: 'составНеДоказан'};

  const пути = (состав.файлы ?? []).map((файл) => файл.путь);
  if (пути.length === 0) return {ошибка: 'составНеДоказан'};

  if (сборкаЗелёная !== true) return {ошибка: 'нетЗелёнойСборки'};

  // Сборка отвечает за то содержимое, которое она видела. Изменилось хоть что-то из состава —
  // зелёная сборка больше ничего не обещает, и коммит по ней был бы обещанием задним числом.
  if (!отпечатокСборки || отпечатокСборки !== отпечатокСейчас) return {ошибка: 'статьяИзменилась'};

  return {пути};
}

/**
 * Совпал ли индекс с утверждённым перечнем. Индекс вправе быть УЖЕ перечня: файл, не изменившийся
 * с прошлого коммита, добавлением в индекс не попадает — это не беда, а обычное дело.
 * Лишний путь в индексе — беда: значит в коммит уедет то, чего человеку не показывали.
 */
export function индексВПеречне(индекс, пути) {
  const разрешено = new Set(пути);

  return (индекс ?? []).filter((путь) => !разрешено.has(путь));
}
