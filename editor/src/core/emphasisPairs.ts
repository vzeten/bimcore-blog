// Одно место правила: где в тексте лежат ПАРНЫЕ знаки одного вида разметки (`*`, `**`).
// Разбора markdown здесь нет и не нужно: кнопке хватает самих знаков в пределах затронутых строк,
// а перенос строки пару закрывает — незакрытые знаки парой не считаются вовсе.

/** Пара знаков одного вида: где сами знаки и где текст между ними. */
export interface Пара {
  /** Начало открывающих знаков. */
  from: number;
  /** Конец закрывающих знаков. */
  to: number;
  /** Начало текста между знаками. */
  contentFrom: number;
  /** Конец текста между знаками. */
  contentTo: number;
}

/** Буква, а не пробел и не край текста: этим отличается знак-открывашка от знака-закрывашки. */
function буква(char: string | undefined): boolean {
  return char !== undefined && !/\s/.test(char);
}

/**
 * Держит ли ряд из `длина` звёздочек знак длиной `n`. Ряд — это не один знак: `***слово***` несёт
 * сразу жирность и курсив. Жирность живёт в ряду от двух знаков, курсив — в ряду нечётной длины
 * (`**` — только жирность, `***` — жирность и курсив). Знак другого вида (не звёздочка) считается
 * по длине ряда, как жирность: своих правил у него нет.
 */
function рядДержитЗнак(длина: number, n: number): boolean {
  return n === 1 ? длина % 2 === 1 : длина >= n;
}

/**
 * Пары знаков в границах `bounds`, слева направо. Открывающим считается ряд, за которым идёт
 * буква, закрывающим — ряд, перед которым буква: иначе `2 * 3 * 4` из статьи человека сошло бы за
 * курсив, и кнопка съела бы его звёздочки. Из длинного ряда паре достаются ровно `n` знаков,
 * ближних к тексту, — остальные принадлежат другому виду разметки и остаются на месте.
 */
export function парыЗнаков(text: string, bounds: {from: number; to: number}, sign: string): Пара[] {
  const знак = sign[0];
  const n = sign.length;
  const пары: Пара[] = [];
  let открытая: {from: number; contentFrom: number} | null = null;

  let at = bounds.from;
  while (at < bounds.to) {
    if (text[at] !== знак) {
      at += 1;
      continue;
    }
    let end = at;
    while (end < bounds.to && text[end] === знак) end += 1;

    if (рядДержитЗнак(end - at, n)) {
      if (открытая !== null && буква(text[at - 1])) {
        пары.push({from: открытая.from, contentFrom: открытая.contentFrom, contentTo: at, to: at + n});
        открытая = null;
      } else if (открытая === null && буква(text[end])) {
        открытая = {from: end - n, contentFrom: end};
      }
    }
    at = end;
  }
  return пары;
}

/** Знаки пары — то, что кнопка снимает; всё остальное внутри неё это текст человека. */
export function знакиПары(пара: Пара): {from: number; to: number}[] {
  return [{from: пара.from, to: пара.contentFrom}, {from: пара.contentTo, to: пара.to}];
}
