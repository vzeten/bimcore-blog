// Что редактор знает о конфигурации самого сайта. Чистые функции: текст на входе, значение на выходе.
//
// Конфиг НЕ исполняется. Импорт `docusaurus.config.js` потянул бы плагины, чтение `.env.local`
// и сетевые обращения — побочные действия внутри локальной программы правки статей (SPEC 4.7).
// Поэтому текст разбирается сканером: он умеет ровно то, что нужно, и молчит, когда не уверен.

/** Символы строкового литерала в JS. Синтаксис чужого языка, а не наша настройка (SPEC 4.4). */
const КАВЫЧКИ = ['\'', '"', '`'];

/**
 * Общая обложка сайта: `themeConfig.image` из конфига Docusaurus. Именно она показывается
 * у статьи, в шапке которой поля `image` нет (SPEC 2.1: пустого поля не бывает, бывает
 * отсутствие поля).
 *
 * `null` — значение не найдено. Врать выдуманным умолчанием нельзя: путь к обложке живёт
 * в конфиге сайта, и второй его источник в программе разошёлся бы с первым молча.
 *
 * Путь приводится к виду сайта: в конфиге он пишется без ведущей косой (`img/social-card.jpg`),
 * а адресом и в статике служит `/img/social-card.jpg`.
 */
export function обложкаСайта(текстКонфига) {
  const найдено = полеБлока(String(текстКонфига ?? ''), 'themeConfig', 'image');
  if (найдено === null || найдено.trim() === '') return null;

  const путь = найдено.trim();
  return путь.startsWith('/') ? путь : `/${путь}`;
}

/**
 * Строковое значение поля `имя`, лежащего прямо в объекте `блок`, а не в его вложенных частях.
 * Без этого `image` из комментария, из навбара или из футера выдал бы себя за обложку сайта.
 *
 * Уровень считается по фигурным скобкам: круглые не в счёт, потому что объект настроек темы
 * обёрнут в скобки вместе с подсказкой типа — `themeConfig: /** @type ... *\/ ({ image: ... })`.
 */
function полеБлока(текст, блок, имя) {
  const старт = послеИмени(текст, блок);
  if (старт < 0) return null;

  let уровень = 0;
  let i = старт;

  while (i < текст.length) {
    const шаг = пропуск(текст, i);
    if (шаг > i) {
      i = шаг;
      continue;
    }

    if (текст[i] === '{') уровень += 1;
    else if (текст[i] === '}') {
      уровень -= 1;
      // Объект блока закрылся, поля так и не встретилось: дальше идёт чужой текст.
      if (уровень <= 0) return null;
    } else if (уровень === 1 && полеЗдесь(текст, i, имя)) {
      return строкаПосле(текст, i + имя.length);
    }

    i += 1;
  }

  return null;
}

/** Позиция сразу за объявлением `имя:`. `-1` — такого поля в тексте нет. */
function послеИмени(текст, имя) {
  let i = 0;

  while (i < текст.length) {
    const шаг = пропуск(текст, i);
    if (шаг > i) {
      i = шаг;
      continue;
    }

    if (полеЗдесь(текст, i, имя)) return i + имя.length;
    i += 1;
  }

  return -1;
}

/** Стоит ли здесь объявление поля `имя:` — целым словом, а не хвостом другого имени. */
function полеЗдесь(текст, i, имя) {
  if (!текст.startsWith(имя, i)) return false;
  if (i > 0 && /[\w$]/.test(текст[i - 1])) return false;

  return /^\s*:/.test(текст.slice(i + имя.length));
}

/** Значение строкового литерала сразу после двоеточия. `null` — там не строка. */
function строкаПосле(текст, i) {
  const найдено = /^\s*:\s*(['"`])([^'"`\n]*)\1/.exec(текст.slice(i));
  return найдено ? найдено[2] : null;
}

/**
 * Сколько занимает то, что читать не надо: комментарии и строковые литералы могут содержать
 * что угодно, включая скобки и слово `image`. Возвращает позицию за пропущенным куском
 * или ту же позицию, если пропускать нечего.
 */
function пропуск(текст, i) {
  if (текст.startsWith('//', i)) {
    const конец = текст.indexOf('\n', i);
    return конец < 0 ? текст.length : конец;
  }

  if (текст.startsWith('/*', i)) {
    const конец = текст.indexOf('*/', i + 2);
    return конец < 0 ? текст.length : конец + 2;
  }

  if (КАВЫЧКИ.includes(текст[i])) return конецСтроки(текст, i);
  return i;
}

/** Конец строкового литерала, начатого в позиции `i`. Экранированная кавычка его не закрывает. */
function конецСтроки(текст, i) {
  const кавычка = текст[i];
  let j = i + 1;

  while (j < текст.length) {
    if (текст[j] === '\\') {
      j += 2;
      continue;
    }
    if (текст[j] === кавычка) return j + 1;
    j += 1;
  }

  return текст.length;
}
