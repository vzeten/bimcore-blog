// Трёхстороннее сведение списка единиц: что было (база), что сделал человек, что сделали снаружи.
// Единица — неделимый кусок: строка тела статьи либо целый кусок шапки (поле со всеми его строками).
// Ни файлов, ни интерфейса: правило обязано проверяться без диска.
//
// Почему единица, а не знак. Внутри куска шапки живёт список (`keywords:` и строки `- слово`).
// Свести такой список построчно значит угадать за человека, какие элементы он хотел оставить,
// а этого правило делать не вправе: неоднозначное место идёт в спор целиком.

import {diffArrays} from 'diff';

/**
 * Правки одной стороны относительно базы: каждая — замена куска базы `[от, до)` новыми единицами.
 * Чистая вставка — это `от === до`, чистое удаление — пустые `единицы`.
 */
export function правкиОтБазы(база, сторона) {
  const правки = [];
  let вБазе = 0;
  let текущая = null;

  for (const часть of diffArrays(база, сторона)) {
    if (!часть.added && !часть.removed) {
      if (текущая !== null) правки.push(текущая);
      текущая = null;
      вБазе += часть.value.length;
      continue;
    }

    текущая ??= {от: вБазе, до: вБазе, единицы: []};
    if (часть.removed) {
      вБазе += часть.value.length;
      текущая.до = вБазе;
    } else {
      текущая.единицы.push(...часть.value);
    }
  }

  if (текущая !== null) правки.push(текущая);
  return правки;
}

/**
 * Пересекаются ли две правки разных сторон.
 *
 * Отрезки полуоткрытые, поэтому обычное пересечение — `a.от < b.до && b.от < a.до`. Отдельным
 * случаем идут две ЧИСТЫЕ вставки в одно и то же место: длины у них нулевые, обычная проверка их
 * не поймает, а сложить два разных текста в одну точку без спроса программа не вправе — порядок
 * выбрала бы она, а не человек.
 */
function пересекаются(a, b) {
  if (a.от < b.до && b.от < a.до) return true;
  return a.от === b.от && a.от === a.до && b.от === b.до;
}

/** Кусок базы с применёнными правками одной стороны. Правки обязаны лежать внутри `[от, до)`. */
function применить(база, от, до, правки) {
  const итог = [];
  let место = от;

  for (const правка of правки) {
    итог.push(...база.slice(место, правка.от));
    итог.push(...правка.единицы);
    место = правка.до;
  }

  итог.push(...база.slice(место, до));
  return итог;
}

/** Одинаковы ли две стороны куска. Сравниваются сами единицы, а не их происхождение. */
function равны(a, b) {
  return a.length === b.length && a.every((единица, i) => единица === b[i]);
}

/**
 * Свести три стороны в список частей по порядку базы.
 *
 * `общее` — базы никто не трогал; `правка` — тронула одна сторона (или обе одинаково), и её
 * результат берётся молча; `спор` — обе стороны тронули одно место по-разному, и выбрать за
 * человека нельзя.
 *
 * Одинаковый итог спором не считается: два помощника, приведшие поле к одному значению,
 * не создали расхождения, о котором стоит спрашивать.
 */
export function свестиЕдиницы(база, мои, внешние) {
  const моиПравки = правкиОтБазы(база, мои);
  const внешниеПравки = правкиОтБазы(база, внешние);

  const части = [];
  let место = 0;
  let i = 0;
  let j = 0;

  while (i < моиПравки.length || j < внешниеПравки.length) {
    // Группа — все правки обеих сторон, сцепленные пересечениями: ответ по одной из них
    // нельзя дать, не решив остальные.
    const группа = {от: Infinity, до: -Infinity, мои: [], внешние: []};
    let растёт = true;

    while (растёт) {
      растёт = false;
      for (const [список, указатель, куда] of [[моиПравки, () => i, 'мои'], [внешниеПравки, () => j, 'внешние']]) {
        const k = указатель();
        const правка = список[k];
        if (правка === undefined) continue;
        // Первая правка группы задаёт её границы; следующая входит, только если пересекается
        // с уже набранным — иначе она относится к другому месту и ждёт своей очереди.
        const первая = группа.до < группа.от;
        if (!первая && !пересекаются(правка, группа)) continue;

        группа.от = Math.min(группа.от, правка.от);
        группа.до = Math.max(группа.до, правка.до, правка.от);
        группа[куда].push(правка);
        if (куда === 'мои') i += 1; else j += 1;
        растёт = true;
      }
    }

    if (группа.от > место) части.push({вид: 'общее', единицы: база.slice(место, группа.от)});

    const мояСторона = применить(база, группа.от, группа.до, группа.мои);
    const внешняяСторона = применить(база, группа.от, группа.до, группа.внешние);
    const тронулиОбе = группа.мои.length > 0 && группа.внешние.length > 0;

    if (!тронулиОбе || равны(мояСторона, внешняяСторона)) {
      части.push({вид: 'правка', единицы: группа.мои.length > 0 ? мояСторона : внешняяСторона});
    } else {
      части.push({
        вид: 'спор',
        база: база.slice(группа.от, группа.до),
        мои: мояСторона,
        внешние: внешняяСторона,
      });
    }

    место = группа.до;
  }

  if (место < база.length) части.push({вид: 'общее', единицы: база.slice(место)});
  return части;
}

/** Сколько спорных мест в разобранных частях. Ноль означает, что сведение состоялось целиком. */
export function споров(части) {
  return части.filter((часть) => часть.вид === 'спор').length;
}

/**
 * Собрать единицы обратно. `выбор` отвечает на каждое спорное место стороной, которую назвал
 * человек: `мои` или `внешние`. Неотвеченный спор — не повод угадывать, сборка отказывается.
 */
export function собратьЕдиницы(части, выбор = {}) {
  const итог = [];
  let номер = 0;

  for (const часть of части) {
    if (часть.вид !== 'спор') {
      итог.push(...часть.единицы);
      continue;
    }

    const сторона = выбор[номер];
    номер += 1;
    if (сторона !== 'мои' && сторона !== 'внешние') return null;
    итог.push(...часть[сторона]);
  }

  return итог;
}
