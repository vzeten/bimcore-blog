// Смена формата картинки: чистые правила, общие для сервера и окна (SPEC 4.6, 4.10.1).
//
// Операция меняет сразу две вещи — файл картинки и ссылку в тексте статьи, — поэтому обе стороны
// обязаны считать одно и то же одним правилом: разойдись подсчёт вхождений у окна и сервера,
// сервер заменил бы не то место текста.

/**
 * Адрес картинки после смены формата: основа имени та же, расширение — новое.
 * `null` — адрес не похож на файл с расширением, менять нечего.
 */
export function адресНовогоФормата(src, расширение) {
  const точка = String(src ?? '').lastIndexOf('.');
  if (точка <= 0) return null;

  return `${String(src).slice(0, точка)}.${расширение}`;
}

/**
 * Номер вхождения точного текста узла в тексте до названной позиции. Первый номер — 1.
 * Считается по полному тексту узла `![alt](src)`, а не по хвосту `](src)`: полный текст
 * сам доказывает, что это картинка, и не путается с обычной ссылкой на тот же файл.
 */
export function номерВхождения(текст, узел, позицияУзла) {
  if (узел === '') return 0;

  let номер = 0;
  let от = 0;
  while (от <= позицияУзла) {
    const где = текст.indexOf(узел, от);
    if (где === -1 || где > позицияУзла) break;
    номер += 1;
    от = где + 1;
  }

  return номер;
}

/**
 * Заменить K-е вхождение точного текста узла. `null` — вхождений меньше K, текст не тронут:
 * статья на диске не совпала с тем, что видело окно, и менять наугад нельзя.
 */
export function заменитьВхождение(текст, узел, номер, новыйУзел) {
  if (узел === '' || номер < 1) return null;

  let счёт = 0;
  let от = 0;
  while (true) {
    const где = текст.indexOf(узел, от);
    if (где === -1) return null;
    счёт += 1;
    if (счёт === номер) return текст.slice(0, где) + новыйУзел + текст.slice(где + узел.length);
    от = где + 1;
  }
}

/**
 * Используется ли ещё файл картинки в тексте. Ищется само имя файла, а не форма ссылки:
 * `./img-01.jpg`, `img-01.jpg` и запись в шапке (`image:`) содержат имя одинаково.
 * При любом найденном вхождении файл считается нужным — сомнение толкуется в пользу сохранения.
 */
export function файлИспользуется(текст, имяФайла) {
  return имяФайла !== '' && String(текст ?? '').includes(имяФайла);
}
