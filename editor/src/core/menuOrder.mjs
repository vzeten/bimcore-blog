// Порядок статей в боковом меню сайта. Чистое правило: диск здесь не спрашивается,
// позиции каталогов подаются снаружи готовыми числами (SPEC 4.6, 4.7).
//
// Правило чужое — его задал Docusaurus, и настройкой оно не бывает. Меню собирает
// `DefaultSidebarItemsGenerator`: файлы раскладываются в дерево папок, и каждый уровень
// сортируется одним `sortBy` по паре «позиция, имя» (`position`, `source`). Значит:
// - позиция каталога — `position` из его `_category_.json`, а нет файла или поля — позиция
//   того файла, который Docusaurus считает индексом этой папки;
// - позиция статьи — `sidebar_position` из её шапки;
// - позиции нет ни у кого — вниз уровня, и равные позиции разводит имя файла или папки;
// - индекс своей папки отдельной строкой в меню не стоит: он и ЕСТЬ эта папка (её ссылка),
//   а вложенные статьи идут под ним.
//
// Числовой префикс имени (`01-стены`) правило намеренно не повторяет: в материалах владельца
// таких имён нет, а расхождение по остальным конвенциям Docusaurus уже названо в `PLAN.md`.

import {readField} from './articleFile.mjs';
import {articlePlace, индексПапки} from './frontmatterRules.mjs';

/** Род ленты. Своего бокового меню у блога нет вовсе: записи идут по дате. */
export const ЛЕНТА = 'blog';

/** Ключ сортировки «как в меню сайта». Колонкой таблицы он не является: щёлкать не по чему. */
export const ПОРЯДОК_МЕНЮ = 'порядокМеню';

/** Один ключ каталога на всю программу: род и путь папок под ним. */
export function ключКаталога(род, папки) {
  return [род, ...папки].join('/');
}

/** `sidebar_position` из шапки версии: число или `null`, если поля нет или в нём не число. */
export function позицияШапки(frontmatterRaw) {
  const сырое = String(readField(frontmatterRaw, 'sidebar_position') ?? '').trim();
  if (сырое === '') return null;

  const число = Number(сырое);
  return Number.isFinite(число) ? число : null;
}

/** Есть ли у статьи место в боковом меню. У ленты его нет, и номера она не получает. */
export function вМеню(article) {
  return article?.kind !== ЛЕНТА && article?.kind !== 'вне контента';
}

/** Локаль основного дерева сайта для этого рода: первый корень рода в настройках. */
function основнаяЛокаль(род, settings) {
  return (settings['контент'] ?? []).find((root) => root['род'] === род)?.['локаль'] ?? null;
}

/**
 * `sidebar_position` статьи. Меню у сайта своё на каждый язык, а строка реестра одна на все
 * версии, поэтому позицию объявляет основное дерево — тем же правилом, каким из него берётся
 * и `_category_.json`. Своей версии в основном дереве нет — берём первую существующую по
 * порядку языков: иначе статья без английской версии молча уехала бы в конец раздела.
 */
function позицияСтатьи(article, settings) {
  const порядок = [основнаяЛокаль(article.kind, settings), ...Object.keys(settings['локали'] ?? {})];
  const код = порядок.find((имя) => имя !== null && article.versions?.[имя]);

  return код ? (article.versions[код].позиция ?? null) : null;
}

/**
 * Разбор пути версии для меню: папки над файлом, имя файла с расширением (именно им Docusaurus
 * разводит равные позиции) и признак «файл — индекс своей папки».
 *
 * Путь берётся у любой версии: он одинаков у всех языков, на том и держится сшивание статьи.
 */
function разбор(article, settings) {
  const путь = Object.values(article.versions ?? {})[0]?.path ?? '';
  const место = articlePlace(путь, settings['контент'] ?? []);
  const части = String(место.inside ?? '').split('/').filter(Boolean);
  const имя = части[части.length - 1] ?? '';
  const папки = части.slice(0, -1);

  return {
    род: место.kind,
    папки,
    имя,
    // В корне рода индексом быть нечему: `docs/intro.mdx` для Docusaurus обычная страница уровня.
    индекс: папки.length > 0 && индексПапки(имя.replace(/\.[^./]+$/, ''), папки[папки.length - 1], место.kind),
  };
}

/** Каталог, которым статья является в меню, — или `null`, если она обычная страница уровня. */
export function собственныйКаталог(article, settings) {
  const {род, папки, индекс} = разбор(article, settings);
  return индекс ? ключКаталога(род, папки) : null;
}

/**
 * Позиции каталогов, дополненные позициями их индексных страниц: `_category_.json` сильнее,
 * а нет его или поля в нём — каталог наследует позицию своей индексной страницы, ровно как
 * это делает сам Docusaurus (`categoryMetadata?.position ?? categoryLinkedDoc?.position`).
 */
function позицииСИндексами(articles, позицииКаталогов, settings) {
  const карта = new Map(позицииКаталогов);

  for (const article of articles) {
    const свой = собственныйКаталог(article, settings);
    if (свой === null || (карта.get(свой) !== null && карта.get(свой) !== undefined)) continue;
    карта.set(свой, позицияСтатьи(article, settings));
  }

  return карта;
}

/**
 * Путь статьи по меню: по шагу на каждый уровень, сверху вниз. Сравнивать их можно только
 * целиком — позиция уровня значит что-то лишь внутри своего каталога.
 */
export function шагиМеню(article, позиции, settings) {
  const {род, папки, имя, индекс} = разбор(article, settings);

  const шаги = папки.map((имяПапки, i) => ({
    позиция: позиции.get(ключКаталога(род, папки.slice(0, i + 1))) ?? null,
    имя: имяПапки,
  }));

  if (индекс) return шаги;

  return [...шаги, {позиция: позицияСтатьи(article, settings), имя}];
}

/**
 * Сравнение двух шагов одного уровня. Без позиции — вниз уровня, равные позиции разводит имя.
 * Имена сравниваются по кодам символов, а не по-русски: так их сравнивает сам Docusaurus, и
 * «правильнее» здесь значило бы «не так, как на сайте».
 */
function сравнитьШаг(один, два) {
  if (один.позиция !== два.позиция) {
    if (один.позиция === null) return 1;
    if (два.позиция === null) return -1;
    return один.позиция < два.позиция ? -1 : 1;
  }

  if (один.имя === два.имя) return 0;
  return один.имя < два.имя ? -1 : 1;
}

/**
 * Сравнение двух путей по меню. Короткий путь, совпавший началом с длинным, идёт выше:
 * это страница самого каталога, и в меню она стоит над своими статьями.
 */
export function сравнитьМеню(одни, другие) {
  const предел = Math.min(одни.length, другие.length);

  for (let i = 0; i < предел; i += 1) {
    const шаг = сравнитьШаг(одни[i], другие[i]);
    if (шаг !== 0) return шаг;
  }

  return одни.length - другие.length;
}

/**
 * Номер каждой статьи в боковом меню сайта: готовое число, по которому окно сортирует список,
 * ни о чём больше не спрашивая. Статьи ленты номера не получают вовсе — меню у них нет.
 */
export function расставитьПоМеню(articles, позицииКаталогов, settings) {
  const карта = позицииСИндексами(articles, позицииКаталогов, settings);

  const записи = articles
    .filter((article) => вМеню(article))
    .map((article) => ({ключ: article.key, шаги: шагиМеню(article, карта, settings)}))
    .sort((одна, другая) => сравнитьМеню(одна.шаги, другая.шаги));

  return new Map(записи.map((запись, номер) => [запись.ключ, номер]));
}
