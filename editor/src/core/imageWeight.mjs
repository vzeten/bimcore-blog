// Что программа думает про вес выбранной картинки. Чистые правила, одно место на все дороги:
// вставку новой картинки, замену байтов и замену со сменой формата.
//
// Правил два, и они разные по силе.
//
// 1. GIF тяжелее предела не принимается вовсе. Пережать анимацию программа не умеет и не будет
//    (решение владельца 2026-08-20), а класть рядом со статьёй файл, который потом придётся
//    выковыривать руками, — хуже, чем честно отказать сразу.
// 2. Всё остальное принимается всегда, а про заметный вес человеку говорится словом
//    «стоит сжать»: это совет, а не отказ, и решает человек.
//
// У GIF совета про вес нет намеренно: сжимать его человеку нечем, кроме сторонней программы,
// и напоминание про полтора мегабайта анимации было бы шумом, на который нельзя ответить.
//
// WebM живёт по правилу GIF со своим пределом (слово владельца 2026-09-05): ролик программа
// тоже не пережимает, тяжелее предела не принимает, а совета про вес ему не даёт.

/** В мегабайте столько байт, сколько их считает проводник Windows. */
const В_МЕГАБАЙТЕ = 1024 * 1024;

/** В килобайте — столько же по той же мерке. */
const В_КИЛОБАЙТЕ = 1024;

/** Форматы, которые программа не пережимает: их вес либо отказ, либо не обсуждается вовсе. */
const БЕЗ_ПЕРЕЖАТИЯ = new Set(['gif', 'webm']);

/**
 * Перевесил ли GIF свой предел. Предел включительный: файл ровно в предел — это ещё «до предела».
 * Для других форматов правило молчит: их вес отказом не бывает.
 */
export function гифПеревесил(формат, байт, пределМегабайт) {
  if (формат !== 'gif') return false;

  return байт > пределМегабайт * В_МЕГАБАЙТЕ;
}

/**
 * Перевесил ли WebM свой предел — тем же включительным правилом, что и GIF. Предел меньше
 * предела тела запроса намеренно: файл едет текстом base64 и тяжелеет на треть, и десять
 * мегабайт ролика укладываются в двадцать пять мегабайт запроса с запасом на остальные поля.
 */
export function webmПеревесил(формат, байт, пределМегабайт) {
  if (формат !== 'webm') return false;

  return байт > пределМегабайт * В_МЕГАБАЙТЕ;
}

/**
 * Что сказать окну про вес принятого файла. `тяжёлая` — только совет сжать перед публикацией;
 * у GIF и WebM его не бывает вовсе: анимация и ролик не тревожат человека тем, чего он не поправит.
 */
export function весКартинки(формат, байт, максимумКилобайт) {
  return {
    тяжёлая: !БЕЗ_ПЕРЕЖАТИЯ.has(формат) && байт > максимумКилобайт * В_КИЛОБАЙТЕ,
    килобайт: Math.round(байт / В_КИЛОБАЙТЕ),
  };
}

/**
 * Текст отказа с подставленным пределом — один на GIF и WebM. Число живёт одной настройкой и
 * подставляется в текст, а не переписывается в него руками: разойдись они — программа отвергала
 * бы файл по одному числу, а человеку называла другое.
 */
export function текстОтказаГиф(шаблон, пределМегабайт) {
  return String(шаблон ?? '').split('{мегабайт}').join(String(пределМегабайт));
}
