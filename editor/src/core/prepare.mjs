// Порядок подготовки статьи к выпуску и вердикт «прошла или нет».
//
// Здесь оркестратор: что за чем идёт, что считать концом и в каком виде правила получают статью.
// Сами проверки живут в `prepareRules.mjs`, проверка настройки — в `prepareSettings.mjs`.
//
// Диска модуль не знает: на входе снимок, снятый адаптером одним чтением. Отпечатки для сверки
// считаются от ТОГО ЖЕ снимка — прочитай адаптер файлы второй раз, и готовность легла бы на байты,
// которых проверки не видели.

import {headGroups, splitArticle} from './articleFile.mjs';
import {readFields} from './frontmatterFields.mjs';
import {articlePlace, isUnlisted} from './frontmatterRules.mjs';
import {файлСтатьи} from './articles.mjs';
import {
  БЛОКЕР, ЭТАПЫ, адресаВерсий, находка, настройки, поляПоиска, составСтатьи, шапкиВерсий,
} from './prepareRules.mjs';

export {БЛОКЕР, ПРЕДУПРЕЖДЕНИЕ, ЭТАПЫ} from './prepareRules.mjs';

/** Правило каждого местного этапа по его коду: порядок берётся из `ЭТАПЫ`, а не пишется заново. */
const ПРАВИЛА = {
  настройки,
  шапка: шапкиВерсий,
  составСтатьи,
  поляПоиска,
  адресаВерсий,
};

/** Прошла ли подготовка. Одно место правила: его же спрашивает публикация перед коммитом. */
export function подготовкаПрошла(находки) {
  return !находки.some((находка) => находка.уровень === БЛОКЕР);
}

/**
 * Проверки, которым не нужен ни диск, ни дочерние процессы.
 *
 * `снимок` — всё, что адаптер прочитал за ОДИН заход: файлы языковых версий и рядом с ними
 * служебные файлы статьи. Правила берут из него только файлы статей; отпечатки блок В снимает
 * со всего снимка, потому что готовность обещает за файлы целиком, а не за одни шапки.
 *
 * `категория` — берётся из того же свода статей, каким живёт реестр. Посчитай её здесь заново,
 * и служебная страница раздела потребовала бы ключевых слов: её признак структурный и виден
 * только по всему своду.
 */
export function проверитьМестные(снимок, категория, settings) {
  const версии = снимок
    .filter((версия) => файлСтатьи(версия.путь))
    .map((версия) => разобрать(версия, settings));

  // Проверять нечего — это сбой того, кто собирал снимок, а не чистая статья. Зелёный вердикт
  // здесь означал бы «готова к публикации» для пустоты.
  if (версии.length === 0) {
    return [находка({код: 'нечегоПроверять', уровень: БЛОКЕР, этап: 'составСтатьи'})];
  }

  const найдено = [];

  for (const этап of ЭТАПЫ) {
    if (этап.внешний) break;
    найдено.push(...ПРАВИЛА[этап.код]({версии, категория, settings, найдено, этап: этап.код}));
    // Настройка сломана — дальше идти незачем: правило, по которому спрашивают поля, само неверно,
    // и зелёный отчёт был бы обманом.
    if (этап.код === 'настройки' && найдено.length > 0) break;
  }

  return найдено;
}

/** Версия статьи в том виде, в каком её читают правила: шапка разобрана один раз на всех. */
function разобрать({путь, содержимое}, settings) {
  // Записи без содержимого быть не должно, но падать на ней ядру нельзя: пустой файл — это статья
  // без шапки, и правила скажут о ней своё, а не свалятся стеком (SPEC 4.12).
  const {frontmatterRaw} = splitArticle(содержимое ?? '');
  const roots = settings['контент'];
  const место = articlePlace(путь, roots);

  return {
    путь,
    frontmatterRaw,
    поля: readFields(frontmatterRaw, путь, roots),
    группы: headGroups(frontmatterRaw),
    скрыта: isUnlisted(frontmatterRaw),
    локаль: место.locale,
    род: место.kind,
    наСайте: место.наСайте,
  };
}
