// Правила подготовки статьи к выпуску: что проверяется, в каком порядке и что считается бедой.
//
// Модуль — оркестратор и переводчик находок, а не движок правил. Ни одной проверки, которая уже
// где-то есть, он не содержит: шапку разбирают куски (`articleFile`), защитные правила живут в
// `safeFrontmatter`, состав статьи — в `articles`, пустота значения — в `frontmatterRules`.
// Своими здесь становятся только правила, которых нет нигде: «описание заполнено» и
// «обязательные поля категории заполнены».
//
// Диска модуль не знает: на входе снимок, снятый адаптером одним чтением. Отпечатки для сверки
// считаются от ТОГО ЖЕ снимка — прочитай адаптер файлы второй раз, и готовность легла бы на байты,
// которых проверки не видели.

import {splitArticle, безКавычек} from './articleFile.mjs';
import {readFields} from './frontmatterFields.mjs';
import {articlePlace, isUnlisted, normalizeSlug, пустоеЗначение} from './frontmatterRules.mjs';
import {safeFrontmatter} from './safeFrontmatter.mjs';
import {missingOnSite} from './articles.mjs';

/**
 * Уровни находок. Перечень открытый: круг 4 добавит сюда «исправлено», когда подготовка начнёт
 * править механическое сама, и форма записи от этого не изменится.
 */
export const БЛОКЕР = 'блокер';
export const ПРЕДУПРЕЖДЕНИЕ = 'предупреждение';

/**
 * Этапы подготовки по порядку: дешёвое раньше дорогого. Перечень — данные, а не хвост кода:
 * блок В подставит исполнителей внешних этапов по коду, не переписывая оркестратор.
 *
 * `внешний` — этап идёт дочерним процессом и живёт в адаптере. Ядро только называет ему место.
 */
export const ЭТАПЫ = [
  {код: 'настройки', внешний: false},
  {код: 'шапка', внешний: false},
  {код: 'составСтатьи', внешний: false},
  {код: 'поляПоиска', внешний: false},
  {код: 'адресаВерсий', внешний: false},
  {код: 'contentCheck', внешний: true},
  {код: 'сборка', внешний: true},
];

/**
 * Какие причины запрета правки поля считаются бедой, а какие нет. «Заперто» означает «программа
 * не может записать значение обратно», а не «не может его прочитать»: у большинства причин
 * значение прочитано и проверкам доступно.
 *
 * Здесь только те, при которых сборка сайта падает или проверить нечем. Список с запятой внутри
 * значения, многострочное значение и список записями с полями — исправный файл, и говорить о нём
 * в отчёте значит шуметь про то, что чинить не нужно.
 *
 * Полноту сторожит машина: причина, заведённая в настройках и забытая здесь, даёт красный тест.
 * Неизвестная причина считается предупреждением, а не тишиной, — молчать о непонятом нельзя.
 */
const УРОВЕНЬ_ЗАПРЕТА = {
  ключДважды: БЛОКЕР,
  этоНеСписок: БЛОКЕР,
  неПрочитано: БЛОКЕР,
  запятаяВЭлементе: null,
  многострочное: null,
  сложныйСписок: null,
  неПравитсяЗдесь: null,
};

/** Прошла ли подготовка. Одно место правила: его же спрашивает публикация перед коммитом. */
export function подготовкаПрошла(находки) {
  return !находки.some((находка) => находка.уровень === БЛОКЕР);
}

/**
 * Находка: запись для программы, а не фраза для человека. Слова заводятся в настройках вместе
 * с окном отчёта — разбирай оно готовую фразу, рядом с правилом появился бы второй его источник.
 *
 * `путь` необязателен: у отсутствующей английской версии файла нет вовсе, а красная сборка
 * говорит про весь сайт. `подробности` — чужой текст, который принесут внешние этапы: сообщение
 * проверки качества, хвост лога сборки. Разбирать его в структурные находки мы не будем.
 */
function находка({код, уровень, этап, путь = null, поле = null, строка = null, ...прочее}) {
  return {код, уровень, этап, путь, поле, строка, ...прочее};
}

/**
 * Проверки, которым не нужен ни диск, ни дочерние процессы.
 *
 * `снимок` — версии статьи вида `{путь, содержимое}`, прочитанные адаптером ОДИН раз.
 * `категория` — берётся из того же свода статей, каким живёт реестр: посчитай её здесь заново,
 * и служебная страница раздела потребовала бы ключевых слов.
 */
export function проверитьМестные(снимок, категория, settings) {
  const беды = проверитьНастройки(категория, settings);
  // Настройка сломана — дальше идти незачем: правило, по которому спрашивают поля, само неверно,
  // и зелёный отчёт был бы обманом.
  if (беды.length > 0) return беды;

  const версии = снимок.map((версия) => разобрать(версия, settings));

  return [
    ...версии.flatMap((версия) => шапкаВерсии(версия, settings)),
    ...составСтатьи(версии, settings),
    ...версии.flatMap((версия) => поляПоиска(версия, категория, settings)),
    ...адресаВерсий(версии, settings),
  ];
}

/** Версия статьи в том виде, в каком её читают правила: шапка разобрана один раз на всех. */
function разобрать({путь, содержимое}, settings) {
  const {frontmatterRaw} = splitArticle(содержимое);
  const roots = settings['контент'];

  return {
    путь,
    frontmatterRaw,
    поля: readFields(frontmatterRaw, путь, roots),
    скрыта: isUnlisted(frontmatterRaw),
    локаль: articlePlace(путь, roots).locale,
  };
}

/**
 * Настройка обязательных полей сверяется с категориями САМОЙ подготовкой, а не только тестом.
 * Настройки правит владелец и тестов при этом не запускает: переименуй он категорию — требование
 * молча испарилось бы, и статья уехала бы на сайт без полей, о которых её обещали спросить.
 * Сломанная проверка обязана кричать, а не молчать.
 */
export function проверитьНастройки(категория, settings) {
  const известные = new Set([
    ...Object.values(settings['категорииПоПути']),
    ...Object.values(settings['категорииПоРоду']),
    settings['категорияСлужебной'],
  ]);
  const порядки = Object.values(settings['поляСоздания']).flatMap((род) => род['порядок']);
  const беды = [];

  for (const [имя, поля] of Object.entries(settings['обязательныеПоля'])) {
    if (!известные.has(имя)) {
      беды.push(находка({код: 'настройкаНеЗнаетКатегорию', уровень: БЛОКЕР, этап: 'настройки', поле: имя}));
    }

    for (const поле of поля) {
      // Описание обязательно у каждой версии, видимой и скрытой (слово владельца), а у полей
      // категории есть поблажка для скрытых. Пусти мы описание сюда — слово владельца молча
      // обошлось бы через настройку.
      if (поле === 'description') {
        беды.push(находка({код: 'описаниеНеПолеКатегории', уровень: БЛОКЕР, этап: 'настройки', поле}));
      }
      // Поле, которому не назначено место в шапке, окно не покажет: находка «заполните его»
      // повела бы человека туда, где заполнять нечего.
      if (!порядки.includes(поле)) {
        беды.push(находка({код: 'полюНегдеСтоять', уровень: БЛОКЕР, этап: 'настройки', поле}));
      }
    }
  }

  return беды;
}

/**
 * Шапка версии: сухой прогон защитных правил плюс поля, которые программа не может записать
 * обратно. Сухой прогон ничего не меняет — он отвечает на вопрос «а поправила бы программа
 * этот файл, если бы его сохранили». У файла, прошедшего через окно, находок не будет вовсе:
 * защитные правила применяются при каждом сохранении. Появятся они у файла, правленного мимо.
 */
function шапкаВерсии(версия, settings) {
  const {fixed} = safeFrontmatter(версия.путь, версия.frontmatterRaw, settings['контент']);

  const защитные = fixed.map((правка) => находка({
    ...правка,
    // Адрес без кавычек сборку не роняет: схема Docusaurus принимает и число. Прочие правки
    // роняют сборку или необратимо ломают адрес статьи, а он после публикации не меняется
    // без переадресации.
    уровень: правка['код'] === 'адресВКавычки' ? ПРЕДУПРЕЖДЕНИЕ : БЛОКЕР,
    этап: 'шапка',
    путь: версия.путь,
  }));

  const запертые = версия.поля
    .filter((поле) => поле.kind === 'заперто')
    .map((поле) => ({поле, уровень: уровеньЗапрета(поле.причина)}))
    .filter(({уровень}) => уровень !== null)
    .map(({поле, уровень}) => находка({
      код: `поле:${поле.причина}`,
      уровень,
      этап: 'шапка',
      путь: версия.путь,
      поле: поле.key,
    }));

  return [...защитные, ...запертые];
}

/** Причина запрета, которой нет в карте, — не повод молчать: программа скажет о ней осторожно. */
function уровеньЗапрета(причина) {
  return причина in УРОВЕНЬ_ЗАПРЕТА ? УРОВЕНЬ_ЗАПРЕТА[причина] : ПРЕДУПРЕЖДЕНИЕ;
}

/**
 * Состав статьи: без английской версии Docusaurus не соберёт статью вовсе и промолчит (SPEC 2.4).
 * Считается по снимку — какие локали в нём есть; существование файлов решает адаптер, не правило.
 */
function составСтатьи(версии, settings) {
  const статья = {
    наСайте: версии.some((версия) => articlePlace(версия.путь, settings['контент']).наСайте),
    versions: Object.fromEntries(версии.map((версия) => [версия.локаль, версия])),
  };

  if (!missingOnSite(статья, settings)) return [];

  return [находка({
    код: 'нетОбязательнойВерсии',
    уровень: БЛОКЕР,
    этап: 'составСтатьи',
    локаль: settings['обязательныйЯзык'],
  })];
}

/**
 * Поля, без которых статью не найдут в поиске. Требование владельца, а не Docusaurus: движок
 * не требует ни одного поля шапки вовсе.
 *
 * Описание обязательно у КАЖДОЙ версии, видимой и скрытой: слово владельца дословно. Английская
 * заглушка его проходит, потому что описание у неё своё, из настроек. Обязательные поля категории
 * у скрытой версии только предупреждают: странице, которой поиск не видит, их отсутствие сегодня
 * не вредит, а завтра, когда её откроют, навредит — молчать нельзя, останавливать незачем.
 */
function поляПоиска(версия, категория, settings) {
  const беды = [];
  const описание = значениеПоля(версия, 'description');

  if (пустоеЗначение(описание)) {
    беды.push(находка({код: 'описаниеПусто', уровень: БЛОКЕР, этап: 'поляПоиска', путь: версия.путь, поле: 'description'}));
  } else if (описание.trim() === String(settings['заглушкаПеревода']['описание']).trim()) {
    // Человек, доводя заглушку до настоящего перевода, заменит заголовок и тело — они кричат
    // о себе, — а описание спрятано в свойствах и останется прежним: в поиске у переведённой
    // статьи будет «перевод пока не готов». Сравнение идёт с настройкой, поэтому спецслучая
    // про заглушки в коде нет.
    беды.push(находка({код: 'описаниеШаблонное', уровень: ПРЕДУПРЕЖДЕНИЕ, этап: 'поляПоиска', путь: версия.путь, поле: 'description'}));
  }

  for (const поле of settings['обязательныеПоля'][категория] ?? []) {
    if (!пустоеЗначение(значениеПоля(версия, поле))) continue;

    беды.push(находка({
      код: 'полеКатегорииПусто',
      уровень: версия.скрыта ? ПРЕДУПРЕЖДЕНИЕ : БЛОКЕР,
      этап: 'поляПоиска',
      путь: версия.путь,
      поле,
    }));
  }

  return беды;
}

/** Показанное значение поля: пустая строка и у поля, которого в шапке нет вовсе. */
function значениеПоля(версия, ключ) {
  return версия.поля.find((поле) => поле.key === ключ)?.display ?? '';
}

/**
 * Адреса языковых версий обязаны совпадать, иначе ломается переключатель языка (SPEC 2.5).
 *
 * Сравниваются адреса, приведённые к правилу раздела, а не записанные в файле: адрес не по правилу
 * уже дал находку сухого прогона, и сырое сравнение выдало бы вторую строку отчёта про ту же
 * строку файла. Расходятся приведённые — это отдельная настоящая беда.
 */
function адресаВерсий(версии, settings) {
  if (версии.length < 2) return [];

  const адреса = версии.map((версия) => ({путь: версия.путь, адрес: приведённыйАдрес(версия, settings)}));
  // За образец берётся основной язык: у него адрес пишет человек, у прочих он повторяется.
  const свой = адреса.find((версия) => версия.путь === основная(версии, settings)?.путь) ?? адреса[0];

  return адреса
    .filter((версия) => версия.адрес !== свой.адрес)
    .map((версия) => находка({
      код: 'адресаВерсийРазные',
      уровень: БЛОКЕР,
      этап: 'адресаВерсий',
      путь: версия.путь,
      поле: 'slug',
      было: свой.адрес,
      стало: версия.адрес,
    }));
}

/** Версия на основном языке: с ней сверяются остальные. Нет её — сверка идёт с первой попавшейся. */
function основная(версии, settings) {
  return версии.find((версия) => версия.локаль === settings['основнойЯзык']) ?? версии[0];
}

/**
 * Адрес версии так, как он ляжет в файл по правилу раздела: без кавычек и с префиксом.
 * Сравнивать сырые записи нельзя — адрес не по правилу уже дал находку сухого прогона,
 * и сырое сравнение выдало бы вторую строку отчёта про ту же строку файла.
 */
function приведённыйАдрес(версия, settings) {
  const запись = версия.поля.find((поле) => поле.key === 'slug');
  if (запись === undefined) return '';

  return normalizeSlug(версия.путь, безКавычек(String(запись.raw ?? '').trim()), settings['контент']);
}
