// Какого рода картинка лежит в байтах. Чистая функция, единое место правила.
//
// Решает содержимое файла, а не его имя и не тип, который назвал браузер: имя переименовывается
// одним движением, а тип браузер берёт из того же имени. Обложка с чужим содержимым внутри
// роняет сборку сайта уже после публикации, когда искать причину дороже всего.

/**
 * Сигнатуры и строение чужих форматов — технические величины, а не настройка (SPEC 4.4):
 * их задали авторы форматов. Расширение рядом с каждым — то имя, под которым файл ляжет
 * на диск: у JPEG оно одно (`jpg`), сколько бы имён ни носил сам формат.
 *
 * Одной сигнатуры мало: восемь верных байтов подряд бывают и у обрубка, который картинкой
 * уже не откроется. Поэтому у каждого формата проверяется ещё и признак целого файла.
 *
 * Признак `обложка` отделяет «программа знает этот формат» от «этим можно быть обложкой».
 * Обложкой остаются только PNG и JPG (решение владельца): у обложки постоянное имя и своя
 * дорога, и анимации там не место. В теле статьи GIF законен и анимацию обязан сохранять.
 *
 * Признак `видео` отделяет видеофайл от картинки: WebM (слово владельца 2026-09-05, только этот
 * формат) принимается лишь дверью вставки видео и не бывает ни обложкой, ни картинкой тела — ни
 * вставкой, ни заменой: `![](…webm)` сайт картинкой не покажет.
 */
const ФОРМАТЫ = [
  {
    расширение: 'png',
    тип: 'image/png',
    обложка: true,
    сигнатура: [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a],
    // У целого PNG есть начало (`IHDR` сразу за сигнатурой) и конец (`IEND` в хвосте),
    // а между ними — сами данные изображения (`IDAT`). Файл без них картинкой не откроется.
    целый: (данные) => метка(данные, 12, [0x49, 0x48, 0x44, 0x52])
      && найти(данные, [0x49, 0x44, 0x41, 0x54])
      && найти(данные, [0x49, 0x45, 0x4e, 0x44]),
  },
  {
    расширение: 'jpg',
    тип: 'image/jpeg',
    обложка: true,
    сигнатура: [0xff, 0xd8, 0xff],
    // У целого JPEG есть метка начала данных (`FFDA`) и метка конца изображения в хвосте.
    целый: (данные) => найти(данные, [0xff, 0xda])
      && метка(данные, данные.length - 2, [0xff, 0xd9]),
  },
  {
    расширение: 'gif',
    тип: 'image/gif',
    обложка: false,
    // Обе живые версии формата: `GIF87a` и `GIF89a`. Анимация бывает только у второй,
    // но принимаются обе — файл не преобразуется, и решать за человека тут нечего.
    сигнатура: [0x47, 0x49, 0x46, 0x38],
    целый: (данные) => версияGif(данные) && строениеGif(данные),
  },
  {
    расширение: 'webm',
    тип: 'video/webm',
    обложка: false,
    видео: true,
    // Заголовок EBML — общий у WebM и Matroska; WebM отличает объявленный тип документа.
    сигнатура: [0x1a, 0x45, 0xdf, 0xa3],
    целый: (данные) => заголовокWebm(данные),
  },
];

/** Тип документа `webm` (элемент DocType с длиной 4) и начало сегмента (элемент Segment). */
const ТИП_ДОКУМЕНТА_WEBM = [0x42, 0x82, 0x84, 0x77, 0x65, 0x62, 0x6d];
const СЕГМЕНТ_WEBM = [0x18, 0x53, 0x80, 0x67];
/**
 * Заголовок EBML короткий, и тип документа с началом сегмента лежат в первых десятках байтов:
 * дальше идут сами данные, и искать там метки — принимать за видео что попало.
 */
const ОКНО_ЗАГОЛОВКА_WEBM = 256;

/** Целый заголовок WebM: сигнатура EBML, объявленный тип `webm` и начало сегмента в окне заголовка. */
function заголовокWebm(данные) {
  return найти(данные, ТИП_ДОКУМЕНТА_WEBM, ОКНО_ЗАГОЛОВКА_WEBM) && найти(данные, СЕГМЕНТ_WEBM, ОКНО_ЗАГОЛОВКА_WEBM);
}

/**
 * Обе живые версии формата, каждая своими двумя байтами сразу за `GIF8`. Одно место на две
 * проверки: узнавание файла целиком и узнавание по одному его началу.
 */
function версияGif(данные) {
  return метка(данные, 4, [0x37, 0x61]) || метка(данные, 4, [0x39, 0x61]);
}

/** Сигнатура (6) плюс описание логического экрана (7) — короче целого GIF не бывает. */
const ДЛИНА_ЗАГОЛОВКА_GIF = 13;

/**
 * Расширение файла по его содержимому. `null` — это не PNG, не JPEG, не GIF и не WebM: ни SVG,
 * ни WebP, ни текстовый файл с картиночным именем, ни обрубок картинки. Что из узнанного куда
 * годится, решают списки ниже: обложка, тело статьи, видео.
 *
 * Пустые и слишком короткие байты тоже дают `null`: битый base64 превращается в мусор
 * молча, и без этой проверки на диск легла бы пустая «обложка».
 */
export function типКартинки(bytes) {
  const данные = bytes ?? [];

  for (const формат of ФОРМАТЫ) {
    if (данные.length < формат.сигнатура.length) continue;
    if (!метка(данные, 0, формат.сигнатура)) continue;

    return формат.целый(данные) ? формат.расширение : null;
  }

  return null;
}

/**
 * Похоже ли начало файла на GIF. Смотрит ТОЛЬКО сигнатуру — те первые байты, которые есть
 * у любого GIF, — и потому годится там, где файла целиком ещё нет: окно читает начало
 * выбранного файла, чтобы не тащить в память стосемидесятимегабайтную анимацию ради того,
 * чтобы потом её отвергнуть (наблюдение владельца 2026-08-20).
 *
 * Это не признание файла картинкой и не замена `типКартинки`: целость по началу не видна,
 * и последнее слово остаётся за сервером, который смотрит все байты.
 */
export function похожеНаГиф(началоБайтов) {
  const данные = началоБайтов ?? [];
  const формат = ФОРМАТЫ.find((вид) => вид.расширение === 'gif');

  // Версия проверяется вместе с сигнатурой: одних букв `GIF8` мало — с них может начинаться
  // и чужой файл, и его отвергли бы словами про анимацию (находка ворот 2026-08-20).
  return метка(данные, 0, формат.сигнатура) && версияGif(данные);
}

/** Сколько байт от начала файла хватает, чтобы узнать сигнатуру любого известного формата. */
export const НАЧАЛЬНЫХ_БАЙТ = Math.max(...ФОРМАТЫ.map((формат) => формат.сигнатура.length));

/** Сколько байт от начала файла хватает, чтобы узнать WebM по его заголовку. */
export const НАЧАЛЬНЫХ_БАЙТ_ВИДЕО = ОКНО_ЗАГОЛОВКА_WEBM;

/**
 * Похоже ли начало файла на WebM — тем же заголовком, каким его узнаёт `типКартинки`, но по
 * одному началу файла: окно не читает десять мегабайт ролика ради того, чтобы его отвергнуть.
 * Последнее слово, как и у GIF, остаётся за сервером.
 */
export function похожеНаВидео(началоБайтов) {
  const данные = началоБайтов ?? [];
  const формат = ФОРМАТЫ.find((вид) => вид.видео === true);

  return метка(данные, 0, формат.сигнатура) && заголовокWebm(данные);
}

/**
 * Есть ли у картинки анимация. Такую картинку программа не пережимает вовсе: любой перегон
 * через декодер оставил бы от неё один кадр, и человек увидел бы застывшую картинку вместо
 * движущейся — молча, уже на сайте.
 *
 * GIF анимируемый по своей природе: кадры в нём лежат один за другим, и отличить один кадр
 * от многих можно только полным разбором блоков. Дешевле и честнее считать анимируемым весь род.
 * У PNG анимация — отдельное расширение формата (APNG): её объявляет чанк `acTL` до первого
 * блока данных. Ищется он разбором чанков, а не поиском четырёх букв где попало: те же буквы
 * встречаются внутри сжатых данных обычной картинки.
 */
export function анимированная(bytes) {
  const данные = bytes ?? [];
  // WebP общий разбор не знает (на сайте его нет), но пережимать анимированный WebP так же нельзя:
  // от него остался бы один кадр. Анимацию объявляет расширенный заголовок `VP8X` флагом 0x02
  // в первом байте своих данных — двадцать первом байте файла.
  if (метка(данные, 0, [0x52, 0x49, 0x46, 0x46]) && метка(данные, 8, [0x57, 0x45, 0x42, 0x50])) {
    return метка(данные, 12, [0x56, 0x50, 0x38, 0x58]) && данные.length > 20 && (данные[20] & 0x02) !== 0;
  }
  const род = типКартинки(данные);
  if (род === 'gif') return true;
  if (род !== 'png') return false;

  // Чанк PNG: длина (4), тип (4), данные, контрольная сумма (4). Первый идёт сразу за сигнатурой.
  let место = 8;
  while (место + 8 <= данные.length) {
    const длина = (данные[место] << 24 | данные[место + 1] << 16 | данные[место + 2] << 8 | данные[место + 3]) >>> 0;
    if (метка(данные, место + 4, [0x61, 0x63, 0x54, 0x4c])) return true;
    // Данные картинки начались — объявления анимации после них уже не бывает.
    if (метка(данные, место + 4, [0x49, 0x44, 0x41, 0x54])) return false;
    место += 12 + длина;
  }

  return false;
}

/** Годится ли этот род картинки в обложку статьи. Правило одно и живёт рядом с форматами. */
export function обложкойМожно(расширение) {
  return ФОРМАТЫ.some((формат) => формат.расширение === расширение && формат.обложка);
}

/**
 * Годится ли этот род картинки в тело статьи. Один набор на вставку и на замену: любое из этих
 * изображений можно заменить любым другим (решение владельца 2026-08-18), и разойдись эти списки —
 * окно предлагало бы файл, который сервер отвергнет.
 */
export function теломМожно(расширение) {
  return картинки().some((формат) => формат.расширение === расширение);
}

/** Годится ли этот род файла в видео статьи. Список один на окно выбора файла и на приём сервером. */
export function видеоМожно(расширение) {
  return ФОРМАТЫ.some((формат) => формат.расширение === расширение && формат.видео === true);
}

/** Картинки — всё известное, что не видео. */
function картинки() {
  return ФОРМАТЫ.filter((формат) => формат.видео !== true);
}

/**
 * Что предлагать человеку в окне выбора файла обложки. Список берётся отсюда же, где решается,
 * какой файл будет принят: разойдись они — окно прятало бы файл, который сервер берёт,
 * или предлагало тот, который он отвергнет.
 */
export function типыОбложки() {
  return ФОРМАТЫ.filter((формат) => формат.обложка).map((формат) => формат.тип).join(',');
}

/** То же для картинки в теле статьи — и для вставки новой, и для замены существующей. */
export function типыТелаСтатьи() {
  return картинки().map((формат) => формат.тип).join(',');
}

/** То же для видеофайла статьи: окно выбора предлагает ровно то, что примет сервер. */
export function типыВидео() {
  return ФОРМАТЫ.filter((формат) => формат.видео === true).map((формат) => формат.тип).join(',');
}

/** Стоят ли в этом месте именно такие байты. Выход за пределы файла — не совпадение. */
function метка(данные, откуда, байты) {
  if (откуда < 0 || откуда + байты.length > данные.length) return false;
  return байты.every((байт, индекс) => данные[откуда + индекс] === байт);
}

/**
 * Строение GIF, а не поиск нужного байта где попало: за заголовком идёт описание экрана, в нём
 * записано, есть ли общая палитра и какого она размера, и ровно за палитрой обязан начинаться
 * первый блок — кадр (`0x2C`) или расширение (`0x21`). Последний байт целого файла — метка
 * конца (`0x3B`).
 *
 * Без разбора палитры «верное начало плюс верный конец» пропускало бы мусор между ними,
 * а объявленную, но отсутствующую палитру принимало бы за картинку.
 */
function строениеGif(данные) {
  if (данные.length < ДЛИНА_ЗАГОЛОВКА_GIF + 1) return false;
  if (данные[данные.length - 1] !== 0x3b) return false;

  // Признаки экрана: старший бит — есть общая палитра, три младших — её размер.
  const признаки = данные[10];
  const палитра = (признаки & 0x80) === 0 ? 0 : 3 * 2 ** ((признаки & 0x07) + 1);
  const первыйБлок = ДЛИНА_ЗАГОЛОВКА_GIF + палитра;
  if (первыйБлок >= данные.length) return false;

  return данные[первыйБлок] === 0x2c || данные[первыйБлок] === 0x21;
}

/** Встречаются ли такие байты где-нибудь в файле — или, с пределом, в его начале. */
function найти(данные, байты, предел = данные.length) {
  for (let i = 0; i + байты.length <= Math.min(предел, данные.length); i += 1) {
    if (метка(данные, i, байты)) return true;
  }

  return false;
}
