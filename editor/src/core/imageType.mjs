// Какого рода картинка лежит в байтах. Чистая функция, единое место правила.
//
// Решает содержимое файла, а не его имя и не тип, который назвал браузер: имя переименовывается
// одним движением, а тип браузер берёт из того же имени. Обложка с чужим содержимым внутри
// роняет сборку сайта уже после публикации, когда искать причину дороже всего.

/**
 * Сигнатуры и строение чужих форматов — технические величины, а не настройка (SPEC 4.4):
 * их задали авторы форматов. Расширение рядом с каждым — то имя, под которым файл ляжет
 * на диск: у JPEG оно одно (`jpg`), сколько бы имён ни носил сам формат.
 *
 * Одной сигнатуры мало: восемь верных байтов подряд бывают и у обрубка, который картинкой
 * уже не откроется. Поэтому у каждого формата проверяется ещё и признак целого файла.
 *
 * Признак `обложка` отделяет «программа знает этот формат» от «этим можно быть обложкой».
 * Обложкой остаются только PNG и JPG (решение владельца): у обложки постоянное имя и своя
 * дорога, и анимации там не место. В теле статьи GIF законен и анимацию обязан сохранять.
 */
const ФОРМАТЫ = [
  {
    расширение: 'png',
    тип: 'image/png',
    обложка: true,
    сигнатура: [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a],
    // У целого PNG есть начало (`IHDR` сразу за сигнатурой) и конец (`IEND` в хвосте),
    // а между ними — сами данные изображения (`IDAT`). Файл без них картинкой не откроется.
    целый: (данные) => метка(данные, 12, [0x49, 0x48, 0x44, 0x52])
      && найти(данные, [0x49, 0x44, 0x41, 0x54])
      && найти(данные, [0x49, 0x45, 0x4e, 0x44]),
  },
  {
    расширение: 'jpg',
    тип: 'image/jpeg',
    обложка: true,
    сигнатура: [0xff, 0xd8, 0xff],
    // У целого JPEG есть метка начала данных (`FFDA`) и метка конца изображения в хвосте.
    целый: (данные) => найти(данные, [0xff, 0xda])
      && метка(данные, данные.length - 2, [0xff, 0xd9]),
  },
  {
    расширение: 'gif',
    тип: 'image/gif',
    обложка: false,
    // Обе живые версии формата: `GIF87a` и `GIF89a`. Анимация бывает только у второй,
    // но принимаются обе — файл не преобразуется, и решать за человека тут нечего.
    сигнатура: [0x47, 0x49, 0x46, 0x38],
    целый: (данные) => (метка(данные, 4, [0x37, 0x61]) || метка(данные, 4, [0x39, 0x61]))
      && строениеGif(данные),
  },
];

/** Сигнатура (6) плюс описание логического экрана (7) — короче целого GIF не бывает. */
const ДЛИНА_ЗАГОЛОВКА_GIF = 13;

/**
 * Расширение картинки по её содержимому. `null` — это не PNG, не JPEG и не GIF: ни SVG,
 * ни WebP, ни текстовый файл с картиночным именем, ни обрубок картинки.
 *
 * Пустые и слишком короткие байты тоже дают `null`: битый base64 превращается в мусор
 * молча, и без этой проверки на диск легла бы пустая «обложка».
 */
export function типКартинки(bytes) {
  const данные = bytes ?? [];

  for (const формат of ФОРМАТЫ) {
    if (данные.length < формат.сигнатура.length) continue;
    if (!метка(данные, 0, формат.сигнатура)) continue;

    return формат.целый(данные) ? формат.расширение : null;
  }

  return null;
}

/** Годится ли этот род картинки в обложку статьи. Правило одно и живёт рядом с форматами. */
export function обложкойМожно(расширение) {
  return ФОРМАТЫ.some((формат) => формат.расширение === расширение && формат.обложка);
}

/**
 * Годится ли этот род картинки в тело статьи. Один набор на вставку и на замену: любое из этих
 * изображений можно заменить любым другим (решение владельца 2026-08-18), и разойдись эти списки —
 * окно предлагало бы файл, который сервер отвергнет.
 */
export function теломМожно(расширение) {
  return ФОРМАТЫ.some((формат) => формат.расширение === расширение);
}

/**
 * Что предлагать человеку в окне выбора файла обложки. Список берётся отсюда же, где решается,
 * какой файл будет принят: разойдись они — окно прятало бы файл, который сервер берёт,
 * или предлагало тот, который он отвергнет.
 */
export function типыОбложки() {
  return ФОРМАТЫ.filter((формат) => формат.обложка).map((формат) => формат.тип).join(',');
}

/** То же для картинки в теле статьи — и для вставки новой, и для замены существующей. */
export function типыТелаСтатьи() {
  return ФОРМАТЫ.map((формат) => формат.тип).join(',');
}

/** Стоят ли в этом месте именно такие байты. Выход за пределы файла — не совпадение. */
function метка(данные, откуда, байты) {
  if (откуда < 0 || откуда + байты.length > данные.length) return false;
  return байты.every((байт, индекс) => данные[откуда + индекс] === байт);
}

/**
 * Строение GIF, а не поиск нужного байта где попало: за заголовком идёт описание экрана, в нём
 * записано, есть ли общая палитра и какого она размера, и ровно за палитрой обязан начинаться
 * первый блок — кадр (`0x2C`) или расширение (`0x21`). Последний байт целого файла — метка
 * конца (`0x3B`).
 *
 * Без разбора палитры «верное начало плюс верный конец» пропускало бы мусор между ними,
 * а объявленную, но отсутствующую палитру принимало бы за картинку.
 */
function строениеGif(данные) {
  if (данные.length < ДЛИНА_ЗАГОЛОВКА_GIF + 1) return false;
  if (данные[данные.length - 1] !== 0x3b) return false;

  // Признаки экрана: старший бит — есть общая палитра, три младших — её размер.
  const признаки = данные[10];
  const палитра = (признаки & 0x80) === 0 ? 0 : 3 * 2 ** ((признаки & 0x07) + 1);
  const первыйБлок = ДЛИНА_ЗАГОЛОВКА_GIF + палитра;
  if (первыйБлок >= данные.length) return false;

  return данные[первыйБлок] === 0x2c || данные[первыйБлок] === 0x21;
}

/** Встречаются ли такие байты где-нибудь в файле. */
function найти(данные, байты) {
  for (let i = 0; i + байты.length <= данные.length; i += 1) {
    if (метка(данные, i, байты)) return true;
  }

  return false;
}
