// Какого рода картинка лежит в байтах. Чистая функция, единое место правила.
//
// Решает содержимое файла, а не его имя и не тип, который назвал браузер: имя переименовывается
// одним движением, а тип браузер берёт из того же имени. Обложка с чужим содержимым внутри
// роняет сборку сайта уже после публикации, когда искать причину дороже всего.

/**
 * Сигнатуры и строение чужих форматов — технические величины, а не настройка (SPEC 4.4):
 * их задали авторы форматов. Расширение рядом с каждым — то имя, под которым файл ляжет
 * на диск: у JPEG оно одно (`jpg`), сколько бы имён ни носил сам формат.
 *
 * Одной сигнатуры мало: восемь верных байтов подряд бывают и у обрубка, который картинкой
 * уже не откроется. Поэтому у каждого формата проверяется ещё и признак целого файла.
 */
const ФОРМАТЫ = [
  {
    расширение: 'png',
    тип: 'image/png',
    сигнатура: [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a],
    // У целого PNG есть начало (`IHDR` сразу за сигнатурой) и конец (`IEND` в хвосте),
    // а между ними — сами данные изображения (`IDAT`). Файл без них картинкой не откроется.
    целый: (данные) => метка(данные, 12, [0x49, 0x48, 0x44, 0x52])
      && найти(данные, [0x49, 0x44, 0x41, 0x54])
      && найти(данные, [0x49, 0x45, 0x4e, 0x44]),
  },
  {
    расширение: 'jpg',
    тип: 'image/jpeg',
    сигнатура: [0xff, 0xd8, 0xff],
    // У целого JPEG есть метка начала данных (`FFDA`) и метка конца изображения в хвосте.
    целый: (данные) => найти(данные, [0xff, 0xda])
      && метка(данные, данные.length - 2, [0xff, 0xd9]),
  },
];

/**
 * Расширение картинки по её содержимому. `null` — это не PNG и не JPEG: ни SVG, ни WebP,
 * ни GIF, ни текстовый файл с картиночным именем, ни обрубок картинки.
 *
 * Пустые и слишком короткие байты тоже дают `null`: битый base64 превращается в мусор
 * молча, и без этой проверки на диск легла бы пустая «обложка».
 */
export function типКартинки(bytes) {
  const данные = bytes ?? [];

  for (const формат of ФОРМАТЫ) {
    if (данные.length < формат.сигнатура.length) continue;
    if (!метка(данные, 0, формат.сигнатура)) continue;

    return формат.целый(данные) ? формат.расширение : null;
  }

  return null;
}

/**
 * Что предлагать человеку в окне выбора файла. Список берётся отсюда же, где решается,
 * какой файл будет принят: разойдись они — окно прятало бы файл, который сервер берёт,
 * или предлагало тот, который он отвергнет.
 */
export function типыОбложки() {
  return ФОРМАТЫ.map((формат) => формат.тип).join(',');
}

/** Стоят ли в этом месте именно такие байты. Выход за пределы файла — не совпадение. */
function метка(данные, откуда, байты) {
  if (откуда < 0 || откуда + байты.length > данные.length) return false;
  return байты.every((байт, индекс) => данные[откуда + индекс] === байт);
}

/** Встречаются ли такие байты где-нибудь в файле. */
function найти(данные, байты) {
  for (let i = 0; i + байты.length <= данные.length; i += 1) {
    if (метка(данные, i, байты)) return true;
  }

  return false;
}
