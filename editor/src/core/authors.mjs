// Кто автор правки: свой, машинный или посторонний.
// Одно правило на всю программу — цвет слоёв сейчас, разговор с ИИ в вехе 2.
// Чистые функции: ни файлов, ни git, ни интерфейса.

// Виды слоя — внутренний договор программы, а не настройка: их знают и раскраска, и стили.
// Человеку в настройках достаются цвета, подписи и справочник имён (SPEC 4.4).
const МОИ = 'prevHuman';
const ПРОЧЕЕ = 'prevOther';

/**
 * Приведение имени автора к сравнимому виду.
 * Имя проходит долгий путь: человек пишет его в git и в справочнике настроек, а в истории оно
 * лежит внутри имени файла, где всё лишнее заменено подчёркиванием и вернулось пробелами.
 * Без единого приведения справочник просто не найдёт «Claude», и слой не появится —
 * отказ, который ничем себя не выдаёт.
 */
export function приведиИмя(имя) {
  // Разделителем считается всё, что не буква и не цифра: имя снимка заменяет подчёркиванием
  // любой такой знак, поэтому «Claude-Code» возвращается оттуда как «Claude Code». Учитывай
  // только пробел и подчёркивание — и справочник с дефисом молча перестал бы находиться.
  return String(имя ?? '')
    .replace(/[^\p{L}\p{N}]+/gu, ' ')
    .trim()
    .toLowerCase();
}

/**
 * Каким слоем показывать правку этого автора.
 *
 * Справочник сильнее совпадения с собой: если владелец однажды подпишется именем ИИ,
 * вернее показать правку машинной — иначе чужая работа спрячется под своей.
 * Пустой справочник — не поломка: всё, кроме своих правок, становится «прочим».
 */
export function видСлоя(автор, справочник, ктоЯ) {
  const имя = приведиИмя(автор);
  if (имя === '') return ПРОЧЕЕ;

  for (const [ключ, вид] of Object.entries(справочник ?? {})) {
    if (приведиИмя(ключ) === имя) return вид;
  }

  const своё = приведиИмя(ктоЯ);
  return своё !== '' && имя === своё ? МОИ : ПРОЧЕЕ;
}
