// Состав выпуска: какие файлы уедут на сайт вместе с этой статьёй и почему каждый из них.
//
// Чистое правило: на входе факты, собранные адаптером с диска, на выходе — перечень с причиной у
// каждой строки. Диска и git здесь нет (SPEC 4.6).
//
// **Правило узкое намеренно.** Состав считается только по путям самой статьи — по её языковым
// версиям, их файлам состояния и картинкам их папок. Ничего «похожего» и ничего «из того же
// раздела» сюда не попадает: в коммит публикации не должен уехать ни один чужой файл, а широкий
// обход рабочего дерева — самый короткий путь к этому.
//
// **Чего доказать нельзя, то не угадывается.** В папке версии лежит вторая статья — принадлежность
// картинок этой не доказать (у соседей общая папка), и правило говорит о разрыве вместо того, чтобы
// приписать статье чужие файлы или молча их потерять.

import {ВНЕ_КАНОНА} from './articleKind.mjs';

/** Назначения строк состава. Слова человеку живут в настройках, здесь только признаки. */
export const ВЕРСИЯ = 'версия';
export const СОСТОЯНИЕ = 'состояние';
export const КАРТИНКА = 'картинка';

/**
 * Состав выпуска по фактам о версиях.
 *
 * `версии` — по одной записи на СУЩЕСТВУЮЩУЮ языковую версию статьи:
 * `путь` — файл версии, `локаль` — её язык, `состояние` — путь файла состояния рядом с ней либо
 * `null`, если его на диске нет, `файлыПапки` — прочие файлы её папки (картинки и всё остальное),
 * `статейВПапке` — сколько статей лежит в той же папке.
 *
 * Возвращает `{файлы, разрывы}`. Разрыв не отменяет остальной состав: человек видит и то, что
 * программа доказала, и то, чего доказать не смогла.
 */
export function составВыпуска({версии}) {
  const свои = Array.isArray(версии) ? версии : [];
  if (свои.length === 0) return {файлы: [], разрывы: [{причина: 'нетВерсий'}]};

  const файлы = [];
  const разрывы = [];

  for (const версия of свои) {
    файлы.push({путь: версия.путь, назначение: ВЕРСИЯ, локаль: версия.локаль});

    // Запись вне канона: файл статьи лежит не в своём каталоге (так живут три корневые страницы
    // документации). Её каталог принадлежит не ей, и доказать состав нечем — это разрыв, а не
    // повод забрать соседей. Канон и план переноса — в `DECISIONS.md` и `CURRENT_TASK.md`.
    if (версия.вид === ВНЕ_КАНОНА) {
      разрывы.push({причина: 'внеКанона', путь: версия.путь, локаль: версия.локаль});
      continue;
    }

    if (типа(версия.состояние)) {
      файлы.push({путь: версия.состояние, назначение: СОСТОЯНИЕ, локаль: версия.локаль});
    }

    // Соседняя статья в той же папке делает картинки общими, и чьи они — по путям не видно.
    if (Number(версия.статейВПапке ?? 1) > 1) {
      разрывы.push({причина: 'папкаНеОдна', путь: версия.путь, локаль: версия.локаль});
      continue;
    }

    for (const файл of версия.файлыПапки ?? []) {
      файлы.push({путь: файл, назначение: КАРТИНКА, локаль: версия.локаль});
    }
  }

  return {файлы: файлы.sort((a, b) => a.путь.localeCompare(b.путь)), разрывы};
}

/** Можно ли выпускать: состав доказан целиком и в нём есть хотя бы одна языковая версия. */
export function выпускВозможен({файлы, разрывы}) {
  return разрывы.length === 0 && файлы.some((файл) => файл.назначение === ВЕРСИЯ);
}

const типа = (значение) => typeof значение === 'string' && значение !== '';
