// Видеофайл статьи: одна безопасная запись, взятая с диска, а не из головы.
//
// Так записан ролик в `blog/free-revit-families-risks/index.mdx` и его русском двойнике:
// строкой выше по статье — `import sofaVideo from './img/sofa-parameters.webm';`, а на месте —
// тег `<video …>` с единственным `<source src={sofaVideo} type="video/webm" />` и закрытием на
// своей строке. Разбор узнаёт ровно эту форму и ничего не исполняет: свойства тега читаются
// как текст, выражение в `src` — как имя переменной, за которым обязан стоять импорт `.webm`.
//
// Что программа не поняла — чужой тег, импорт без ролика, второй источник, — остаётся текстом
// статьи как есть: спрятать половину понятого хуже, чем показать всё.

import {импортСтатьи, ОПАСНЫЕ_ЗНАКИ} from './jsxTag.mjs';

/** Тип источника, который задал сам формат, а не мы. */
export const ТИП_ВИДЕО = 'video/webm';
/** Расширение файла ролика: под таким именем он лежит рядом со статьёй. */
export const РАСШИРЕНИЕ_ВИДЕО = 'webm';

const ИМЯ = '[A-Za-z_$][A-Za-z0-9_$]*';
/** Фигурные скобки: в строке свойства разбор их не принимает — там начиналось бы выражение. */
const ЗНАКИ_ВЫРАЖЕНИЯ = /[{}]/;
const ПРИЗНАК = '[A-Za-z][A-Za-z0-9-]*';
/** Свойство тега: слово без значения (`controls`), строка в кавычках, объект стиля без вложений. */
const СВОЙСТВО = `(?:${ПРИЗНАК}="[^"<>{}]*"|style=\{\{[^{}<>]*\}\}|${ПРИЗНАК})`;
const ОТКРЫТИЕ = `<video(?:[ \t]+${СВОЙСТВО})*[ \t]*>`;
/** Источник: ровно два свойства — выражение `src` и тип `video/webm`, в любом порядке. */
const ИСТОЧНИК = `[ \t]*<source[ \t]+(?:src=\{(${ИМЯ})\}[ \t]+type="${ТИП_ВИДЕО}"|type="${ТИП_ВИДЕО}"[ \t]+src=\{(${ИМЯ})\})[ \t]*\/>`;
const ЗАКРЫТИЕ = '[ \t]*<\/video>';
/** Тег целиком: три строки подряд, открытие с начала строки. */
const БЛОК = new RegExp(`^${ОТКРЫТИЕ}\r?\n${ИСТОЧНИК}\r?\n${ЗАКРЫТИЕ}$`, 'gm');

/**
 * Все понятные видеофайлы статьи по порядку: границы тега, имя переменной, адрес и границы
 * импорта. Тег без импорта или с импортом не на `.webm` не отдаётся вовсе — сайт такой ролик
 * не покажет, и блоком его обещать нельзя.
 */
export function видеоТекста(текст) {
  const найденные = [];

  for (const совпадение of текст.matchAll(БЛОК)) {
    const переменная = совпадение[1] ?? совпадение[2];
    const импорт = импортСтатьи(текст, переменная);
    if (импорт === null || !импорт.адрес.toLowerCase().endsWith(`.${РАСШИРЕНИЕ_ВИДЕО}`)) continue;

    найденные.push({
      переменная,
      адрес: импорт.адрес,
      импорт: {от: импорт.от, до: импорт.до},
      от: совпадение.index,
      до: совпадение.index + совпадение[0].length,
    });
  }

  return найденные;
}

/**
 * Новый тег ролика — той же записью, что у образца на диске: кнопки управления, без звука,
 * по кругу, без автозапуска (`autoplay` не пишется), во всю ширину текста. Название для
 * доступности берётся у статьи и не ставится вовсе, если в нём знак, ломающий разбор.
 */
export function новыйВидеоТег(переменная, название) {
  // Ярлык живёт по правилу собственного разбора: кавычки, угловые и фигурные скобки в значении
  // свойства он не читает, и тег с ними перестал бы быть блоком. Такое название не ставится вовсе.
  const слова = String(название ?? '').trim();
  const ярлык = слова !== '' && !ОПАСНЫЕ_ЗНАКИ.test(слова) && !ЗНАКИ_ВЫРАЖЕНИЯ.test(слова) ? ` aria-label="${слова}"` : '';

  return [
    `<video controls muted loop playsInline style={{width: '100%', height: 'auto'}}${ярлык}>`,
    `  <source src={${переменная}} type="${ТИП_ВИДЕО}" />`,
    '</video>',
  ].join('\n');
}

/** Строка импорта ролика — той же записью, какой её читает `импортСтатьи`. */
export function импортВидео(переменная, адрес) {
  return `import ${переменная} from '${адрес}';`;
}

/**
 * Куда встаёт строка импорта: в начало первой строки статьи, которая не пустая и не импорт.
 * Пустые строки сверху — отступ человека, и его не трогают; уже стоящие импорты (картинки
 * карточки, другого ролика) остаются выше — они спрятаны показом вместе со своей пустой
 * строкой, и вклиниться перед ними значило бы писать внутрь скрытого куска.
 */
export function местоИмпорта(текст) {
  const строки = текст.split('\n');
  let место = 0;
  for (const строка of строки) {
    if (строка.trim() !== '' && !/^[ \t]*import[ \t]/.test(строка)) return место;
    место += строка.length + 1;
  }
  return текст.length;
}

/**
 * Свободное имя переменной для нового ролика: имя файла латиницей плюс `Video`, как у образца
 * (`sofaVideo`). Занятое в тексте имя получает номер: два импорта с одним именем ломают сборку.
 */
export function свободнаяПеременная(текст, адрес) {
  const файл = адрес.split('/').pop().replace(/\.[^.]*$/, '');
  const куски = файл.split(/[^A-Za-z0-9]+/).filter((кусок) => кусок !== '');
  const основа = куски.map((кусок, i) => (i === 0 ? кусок : кусок[0].toUpperCase() + кусок.slice(1))).join('');
  const корень = `${/^[A-Za-z_$]/.test(основа) ? основа : `v${основа}`}Video`;

  let имя = корень;
  for (let номер = 2; упоминаетсяВне(текст, имя, []); номер += 1) имя = `${корень}${номер}`;
  return имя;
}

/**
 * Упоминается ли имя переменной в тексте где-то ещё, кроме названных кусков. Так решается
 * судьба импорта при удалении блока: ролик, на который ссылается ещё один тег, свой импорт
 * оставляет. Сравнение по целому слову, чтобы `sofaVideo` не совпал с `sofaVideo2`.
 */
export function упоминаетсяВне(текст, имя, куски) {
  const остаток = [...куски].sort((а, б) => б.from - а.from)
    .reduce((т, кусок) => т.slice(0, кусок.from) + т.slice(кусок.to), текст);
  // Знак доллара законен в имени и особый в регулярном выражении: экранируется, иначе `a$b`
  // читалось бы как конец строки и импорт двух блоков терялся бы при удалении одного.
  const слово = имя.replace(/[$]/g, '\\$&');

  return new RegExp(`(?:^|[^A-Za-z0-9_$])${слово}(?![A-Za-z0-9_$])`).test(остаток);
}
