// Медиа открытой версии в её тексте и обработчик «технические подписи медиа».
//
// Чистые правила без диска. Здесь одно место, где текст статьи спрашивают «на какие файлы рядом
// ты ссылаешься»: по нему адаптер собирает снимок, медиаподготовка и переименование правят адреса,
// обложка ищет первую картинку. Разойдись эти четверо в разборе — один переименовал бы файл,
// а другой оставил бы старую ссылку, и сборка сайта упала бы на битом адресе (SPEC 2.3).
//
// Разбор тегов не свой: JSX через `jsxTag.mjs`, ролик через `videoFile.mjs`. Своя только
// markdown-картинка и строка импорта — той записью, какой их пишет сама программа.

import {splitArticle, readField} from './articleFile.mjs';
import {ОПАСНЫЕ_ЗНАКИ, тегиТекста} from './jsxTag.mjs';
import {видеоТекста, свойствоВидео, сменаСвойстваВидео} from './videoFile.mjs';

/** Имена чужого формата (компонент сайта и его свойства) — не настройка (SPEC 4.4). */
const ТЕГ_ВИДЕО = 'YouTube';
const ТЕГ_КАРТОЧКИ = 'ProductCard';
const ДАТА_ВИДЕО = 'uploadDate';
const ЯРЛЫК_РОЛИКА = 'aria-label';

const КАРТИНКА = /!\[([^\]\n]*)\]\(([^)\s]+)((?:[ \t]+"[^"\n]*")?)\)/g;
const ИМПОРТ = /^[ \t]*import[ \t]+[A-Za-z_$][\w$]*[ \t]+from[ \t]+(['"])([^'"\n]+)\1[ \t]*;?[ \t]*$/gm;
/** Обложка в шапке: только начало значения, до пробела или комментария. */
const ОБЛОЖКА = /^(image:[ \t]*)([^\s#]+)/m;

/** Знаки, от которых markdown-подпись ломает разметку или становится JSX: свои, не JSX-овые. */
const ЗНАКИ_ALT = /[[\]<>{}\r\n]/;
/** Значение свойства JSX: кавычки и угловые скобки ломают тег, фигурные начинают выражение. */
const ЗНАКИ_СВОЙСТВА = /[{}]/;

/**
 * Ссылки на медиа в теле статьи по порядку: markdown-картинки и строки импорта.
 * У каждой — границы адреса (их правит переименование) и у картинки границы подписи.
 */
export function ссылкиМедиа(текст) {
  const найденные = [];

  for (const м of текст.matchAll(КАРТИНКА)) {
    const altОт = м.index + 2;
    const адресОт = altОт + м[1].length + 2;
    найденные.push({
      вид: 'картинка', адрес: м[2], alt: м[1], от: м.index,
      altОт, altДо: altОт + м[1].length, адресОт, адресДо: адресОт + м[2].length,
    });
  }
  for (const м of текст.matchAll(ИМПОРТ)) {
    const адресОт = м.index + м[0].indexOf(м[2], м[0].indexOf('from'));
    найденные.push({вид: 'импорт', адрес: м[2], от: м.index, адресОт, адресДо: адресОт + м[2].length});
  }

  return найденные.sort((a, b) => a.от - b.от);
}

/** Адрес обложки из шапки; пусто — обложки нет. */
export function обложкаШапки(текст) {
  return readField(splitArticle(текст).frontmatterRaw, 'image');
}

/**
 * Имя файла рядом со статьёй по адресу из текста: `./img/a.jpg` → `img/a.jpg`.
 * `null` — адрес ведёт не в папку статьи: общая папка сайта, корень, сеть, выход наружу.
 */
export function локальноеИмя(адрес) {
  const текст = String(адрес ?? '').trim();
  if (текст === '' || /^[a-z]+:|^[/@#\\]|\.\.|[\\?#]/i.test(текст)) return null;

  return текст.startsWith('./') ? текст.slice(2) : текст;
}

/** Все имена файлов рядом со статьёй, о которых говорит открытая версия: тело и обложка. */
export function именаМедиа(текст) {
  const адреса = [...ссылкиМедиа(текст).map((ссылка) => ссылка.адрес), обложкаШапки(текст)];

  return [...new Set(адреса.map(локальноеИмя).filter((имя) => имя !== null))];
}

/**
 * Заменить адреса по карте «старое имя → новое имя» во всех ссылках тела и в обложке шапки.
 * Форма записи адреса (`./` или без) сохраняется: меняется только имя.
 */
export function заменитьАдреса(текст, карта) {
  if (карта.size === 0) return текст;
  const новый = (адрес) => {
    const имя = локальноеИмя(адрес);
    if (имя === null || !карта.has(имя)) return null;
    return адрес.slice(0, адрес.length - имя.length) + карта.get(имя);
  };

  let итог = текст;
  for (const ссылка of ссылкиМедиа(текст).sort((a, b) => b.адресОт - a.адресОт)) {
    const адрес = новый(ссылка.адрес);
    if (адрес !== null) итог = итог.slice(0, ссылка.адресОт) + адрес + итог.slice(ссылка.адресДо);
  }

  const {head} = splitArticle(итог);
  const шапка = head.replace(ОБЛОЖКА, (всё, ключ, адрес) => `${ключ}${новый(адрес) ?? адрес}`);
  return шапка + итог.slice(head.length);
}

/** Шаблон с подстановками `{ключ}`; пустая подстановка делает пустым весь результат. */
function заполнить(шаблон, значения) {
  let пусто = false;
  const итог = String(шаблон ?? '').replace(/\{([^{}]+)\}/g, (всё, ключ) => {
    const значение = String(значения[ключ] ?? '').trim();
    if (значение === '') пусто = true;
    return значение;
  });

  return пусто ? '' : итог.trim();
}

/** Обработчик 1: пустые технические подписи по шаблонам из настроек. Готовое не трогается. */
export const подписиМедиа = {
  анализ(копия, settings) {
    const шаблоны = settings['доработка']['шаблоныПодписей'];
    const {текст} = копия;
    const title = readField(splitArticle(текст).frontmatterRaw, 'title');
    const правки = [];
    const отчёт = {изменено: [], оставлено: [], человеку: []};
    let нашлось = false;

    const предложить = (что, было, значение, знаки, правка) => {
      нашлось = true;
      if (String(было ?? '').trim() !== '') return отчёт.оставлено.push({что, значение: было, причина: 'заполнено'});
      if (значение === '') return отчёт.человеку.push({что, причина: 'нетИсточника'});
      if (знаки.test(значение) || ОПАСНЫЕ_ЗНАКИ.test(значение)) return отчёт.человеку.push({что, причина: 'опасныеЗнаки'});
      правки.push(правка(значение));
      return отчёт.изменено.push({что, было: '', стало: значение});
    };

    let картинка = 0;
    for (const ссылка of ссылкиМедиа(текст)) {
      if (ссылка.вид !== 'картинка') continue;
      картинка += 1;
      предложить(ссылка.адрес, ссылка.alt, заполнить(шаблоны['картинка'], {title, номер: картинка}), ЗНАКИ_ALT,
        (значение) => ({от: ссылка.altОт, до: ссылка.altДо, вставка: значение}));
    }

    const ролики = [
      ...тегиТекста(текст).filter((тег) => тег.имя === ТЕГ_ВИДЕО).map((тег) => ({от: тег.от, тег})),
      ...видеоТекста(текст).map((видео) => ({от: видео.от, видео})),
    ].sort((a, b) => a.от - b.от);
    ролики.forEach(({тег, видео}, i) => {
      const значение = заполнить(шаблоны['ролик'], {title, номер: i + 1});
      if (тег !== undefined) {
        const дата = свойство(тег, ДАТА_ВИДЕО);
        // Название вместе с датой уходит в структурные данные ролика: шаблонное слово там —
        // подмена смысла, а не техническая подпись. Это работа человека.
        if (свойство(тег, 'title') === '' && дата !== '') {
          нашлось = true;
          return отчёт.человеку.push({что: `${ТЕГ_ВИДЕО} ${i + 1}`, причина: 'естьДата'});
        }
        return предложить(`${ТЕГ_ВИДЕО} ${i + 1}`, свойство(тег, 'title'), значение, ЗНАКИ_СВОЙСТВА, (з) => правкаСвойства(тег, 'title', з));
      }
      const ярлык = свойствоВидео(текст.slice(видео.от, видео.до), ЯРЛЫК_РОЛИКА) ?? '';
      return предложить(`video ${i + 1}`, ярлык, значение, ЗНАКИ_СВОЙСТВА, (з) => ({
        от: видео.от, до: видео.до, вставка: сменаСвойстваВидео(текст.slice(видео.от, видео.до), ЯРЛЫК_РОЛИКА, з),
      }));
    });

    for (const тег of тегиТекста(текст).filter((т) => т.имя === ТЕГ_КАРТОЧКИ)) {
      const значение = заполнить(шаблоны['карточка'], {название: свойство(тег, 'name')});
      предложить(`${ТЕГ_КАРТОЧКИ} ${свойство(тег, 'name')}`, свойство(тег, 'imageAlt'), значение, ЗНАКИ_СВОЙСТВА,
        (з) => правкаСвойства(тег, 'imageAlt', з));
    }

    return нашлось ? {правки, отчёт} : null;
  },

  применить(копия, предложение) {
    let текст = копия.текст;
    for (const {от, до, вставка} of [...предложение.правки].sort((a, b) => b.от - a.от)) {
      if (вставка === null) continue;
      текст = текст.slice(0, от) + вставка + текст.slice(до);
    }
    return {копия: {...копия, текст}};
  },

  /** После правки заполнять больше нечего: повторный анализ не предлагает ни одной подписи. */
  проверить(копия, предложение, settings) {
    return (подписиМедиа.анализ(копия, settings)?.отчёт.изменено.length ?? 0) === 0;
  },
};

function свойство(тег, имя) {
  return тег.свойства.find((с) => с.имя === имя)?.значение ?? '';
}

/** Правка одного свойства тега той же формой, что и панель свойств: ровно значение или дописка. */
function правкаСвойства(тег, имя, значение) {
  const было = тег.свойства.find((с) => с.имя === имя);
  if (было === undefined) {
    return {от: тег.от + тег.конец, до: тег.от + тег.конец, вставка: `${тег.отступ}${имя}="${значение}"`};
  }
  return {от: тег.от + было.от + 1, до: тег.от + было.до - 1, вставка: значение};
}
