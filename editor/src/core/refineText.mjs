// Медиа открытой версии в её тексте и обработчик «технические подписи медиа». Чистые правила.
// Одно место, где текст спрашивают «на какие файлы рядом ты ссылаешься»: им живут снимок,
// медиаподготовка, переименование и обложка. Теги разбирают `jsxTag.mjs` и `videoFile.mjs`;
// своя только markdown-картинка и строка импорта — той записью, какой их пишет программа.

import {splitArticle, readField} from './articleFile.mjs';
import {ОПАСНЫЕ_ЗНАКИ, тегиТекста} from './jsxTag.mjs';
import {видеоТекста, свойствоВидео, сменаСвойстваВидео} from './videoFile.mjs';

/** Имена чужого формата (компонент сайта и его свойства) — не настройка (SPEC 4.4). */
const ТЕГ_ВИДЕО = 'YouTube';
const ТЕГ_КАРТОЧКИ = 'ProductCard';
const ДАТА_ВИДЕО = 'uploadDate';
const ЯРЛЫК_РОЛИКА = 'aria-label';

const КАРТИНКА = /!\[([^\]\n]*)\]\(([^)\s]+)((?:[ \t]+"[^"\n]*")?)\)/g;
const ИМПОРТ = /^[ \t]*import[ \t]+[A-Za-z_$][\w$]*[ \t]+from[ \t]+(['"])([^'"\n]+)\1[ \t]*;?[ \t]*$/gm;
const ОБЛОЖКА = /^(image:[ \t]*)([^\s#]+)/m;
/** Markdown-подпись ломают скобки и перевод строки; значение JSX — фигурные скобки (кавычки и `<>` общие). */
const ЗНАКИ_ALT = /[[\]<>{}\r\n]/;
const ЗНАКИ_СВОЙСТВА = /[{}]/;

/** Кодовые ограды (три и больше ` или ~; закрывает та же ограда не короче; незакрытая — до конца). */
export function оградыКода(текст) {
  const ограды = [];
  let открыта = null;
  let от = 0;
  for (const строка of текст.split('\n')) {
    const м = /^[ \t]{0,3}(`{3,}|~{3,})/.exec(строка);
    if (открыта === null) {
      if (м) открыта = {знак: м[1][0], длина: м[1].length, от};
    } else if (м && м[1][0] === открыта.знак && м[1].length >= открыта.длина && строка.slice(м[0].length).trim() === '') {
      ограды.push({от: открыта.от, до: от + строка.length});
      открыта = null;
    }
    от += строка.length + 1;
  }
  if (открыта !== null) ограды.push({от: открыта.от, до: текст.length});
  return ограды;
}

/** Предикат «место вне кодовых оград»: пример в огороженном коде медиа не считается и не правится. */
function внеОград(текст) {
  const ограды = оградыКода(текст);
  return (место) => !ограды.some((о) => место >= о.от && место < о.до);
}

/** Ссылки тела по порядку: markdown-картинки и импорты с границами адреса (и подписи у картинки). */
export function ссылкиМедиа(текст) {
  const найденные = [];
  const снаружи = внеОград(текст);
  for (const м of текст.matchAll(КАРТИНКА)) {
    const altОт = м.index + 2;
    const адресОт = altОт + м[1].length + 2;
    найденные.push({вид: 'картинка', адрес: м[2], alt: м[1], от: м.index, altОт, altДо: altОт + м[1].length, адресОт, адресДо: адресОт + м[2].length});
  }
  for (const м of текст.matchAll(ИМПОРТ)) {
    const адресОт = м.index + м[0].indexOf(м[2], м[0].indexOf('from'));
    найденные.push({вид: 'импорт', адрес: м[2], от: м.index, адресОт, адресДо: адресОт + м[2].length});
  }
  return найденные.filter((с) => снаружи(с.от)).sort((a, b) => a.от - b.от);
}

/** Адрес обложки из шапки; пусто — обложки нет. */
export function обложкаШапки(текст) {
  return readField(splitArticle(текст).frontmatterRaw, 'image');
}

/** Имя файла рядом со статьёй по адресу (`./img/a.jpg` → `img/a.jpg`); `null` — адрес ведёт не в папку статьи. */
export function локальноеИмя(адрес) {
  const текст = String(адрес ?? '').trim();
  if (текст === '' || /^[a-z]+:|^[/@#\\]|\.\.|[\\?#]/i.test(текст)) return null;
  return текст.startsWith('./') ? текст.slice(2) : текст;
}

/** Все имена файлов рядом со статьёй, о которых говорит открытая версия: тело и обложка. */
export function именаМедиа(текст) {
  const адреса = [...ссылкиМедиа(текст).map((с) => с.адрес), обложкаШапки(текст)];
  return [...new Set(адреса.map(локальноеИмя).filter((имя) => имя !== null))];
}

/** Заменить имена по карте во всех ссылках тела и в обложке шапки; форма записи адреса сохраняется. */
export function заменитьАдреса(текст, карта) {
  if (карта.size === 0) return текст;
  const новый = (адрес) => {
    const имя = локальноеИмя(адрес);
    return имя !== null && карта.has(имя) ? адрес.slice(0, адрес.length - имя.length) + карта.get(имя) : null;
  };
  let итог = текст;
  for (const с of ссылкиМедиа(текст).sort((a, b) => b.адресОт - a.адресОт)) {
    const адрес = новый(с.адрес);
    if (адрес !== null) итог = итог.slice(0, с.адресОт) + адрес + итог.slice(с.адресДо);
  }
  const {head} = splitArticle(итог);
  return head.replace(ОБЛОЖКА, (всё, ключ, адрес) => `${ключ}${новый(адрес) ?? адрес}`) + итог.slice(head.length);
}

/** Шаблон с подстановками `{ключ}`; пустая подстановка делает пустым весь результат. */
function заполнить(шаблон, значения) {
  let пусто = false;
  const итог = String(шаблон ?? '').replace(/\{([^{}]+)\}/g, (всё, ключ) => {
    const значение = String(значения[ключ] ?? '').trim();
    if (значение === '') пусто = true;
    return значение;
  });
  return пусто ? '' : итог.trim();
}

const свойство = (тег, имя) => тег.свойства.find((с) => с.имя === имя)?.значение ?? '';

/** Правка одного свойства тега той же формой, что панель свойств: ровно значение либо дописка. */
function правкаСвойства(тег, имя, значение) {
  const было = тег.свойства.find((с) => с.имя === имя);
  if (было === undefined) return {от: тег.от + тег.конец, до: тег.от + тег.конец, вставка: `${тег.отступ}${имя}="${значение}"`};
  return {от: тег.от + было.от + 1, до: тег.от + было.до - 1, вставка: значение};
}

/** Обработчик 1: пустые технические подписи по шаблонам из настроек. Готовое не трогается. */
export const подписиМедиа = {
  анализ(копия, settings) {
    const шаблоны = settings['доработка']['шаблоныПодписей'];
    const {текст} = копия;
    const снаружи = внеОград(текст);
    const title = readField(splitArticle(текст).frontmatterRaw, 'title');
    const правки = [];
    const отчёт = {изменено: [], оставлено: [], человеку: []};
    let нашлось = false;

    const предложить = (что, было, значение, знаки, правка) => {
      нашлось = true;
      if (String(было ?? '').trim() !== '') return отчёт.оставлено.push({что, значение: было, причина: 'заполнено'});
      if (значение === '') return отчёт.человеку.push({что, причина: 'нетИсточника'});
      if (знаки.test(значение) || ОПАСНЫЕ_ЗНАКИ.test(значение)) return отчёт.человеку.push({что, причина: 'опасныеЗнаки'});
      правки.push(правка(значение));
      return отчёт.изменено.push({что, было: '', стало: значение});
    };

    ссылкиМедиа(текст).filter((с) => с.вид === 'картинка').forEach((с, i) => предложить(
      с.адрес, с.alt, заполнить(шаблоны['картинка'], {title, номер: i + 1}), ЗНАКИ_ALT,
      (значение) => ({от: с.altОт, до: с.altДо, вставка: значение}),
    ));

    const теги = тегиТекста(текст).filter((тег) => снаружи(тег.от));
    const ролики = [
      ...теги.filter((тег) => тег.имя === ТЕГ_ВИДЕО).map((тег) => ({от: тег.от, тег})),
      ...видеоТекста(текст).filter((видео) => снаружи(видео.от)).map((видео) => ({от: видео.от, видео})),
    ].sort((a, b) => a.от - b.от);
    ролики.forEach(({тег, видео}, i) => {
      const значение = заполнить(шаблоны['ролик'], {title, номер: i + 1});
      if (тег !== undefined) {
        // Название вместе с датой уходит в структурные данные ролика: это смысл, а не техническая подпись.
        if (свойство(тег, 'title') === '' && свойство(тег, ДАТА_ВИДЕО) !== '') {
          нашлось = true;
          return отчёт.человеку.push({что: `${ТЕГ_ВИДЕО} ${i + 1}`, причина: 'естьДата'});
        }
        return предложить(`${ТЕГ_ВИДЕО} ${i + 1}`, свойство(тег, 'title'), значение, ЗНАКИ_СВОЙСТВА, (з) => правкаСвойства(тег, 'title', з));
      }
      const тегРолика = текст.slice(видео.от, видео.до);
      return предложить(`video ${i + 1}`, свойствоВидео(тегРолика, ЯРЛЫК_РОЛИКА) ?? '', значение, ЗНАКИ_СВОЙСТВА,
        (з) => ({от: видео.от, до: видео.до, вставка: сменаСвойстваВидео(тегРолика, ЯРЛЫК_РОЛИКА, з)}));
    });

    for (const тег of теги.filter((т) => т.имя === ТЕГ_КАРТОЧКИ)) {
      предложить(`${ТЕГ_КАРТОЧКИ} ${свойство(тег, 'name')}`, свойство(тег, 'imageAlt'),
        заполнить(шаблоны['карточка'], {название: свойство(тег, 'name')}), ЗНАКИ_СВОЙСТВА, (з) => правкаСвойства(тег, 'imageAlt', з));
    }

    return нашлось ? {правки, отчёт} : null;
  },

  применить(копия, предложение) {
    let текст = копия.текст;
    for (const {от, до, вставка} of [...предложение.правки].sort((a, b) => b.от - a.от)) {
      if (вставка !== null) текст = текст.slice(0, от) + вставка + текст.slice(до);
    }
    return {копия: {...копия, текст}};
  },

  /** После правки заполнять больше нечего: повторный анализ не предлагает ни одной подписи. */
  проверить(копия, предложение, settings) {
    return (подписиМедиа.анализ(копия, settings)?.отчёт.изменено.length ?? 0) === 0;
  },
};
