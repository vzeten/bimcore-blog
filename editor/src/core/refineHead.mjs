// Обработчики шапки: «пустые технические поля» и «обложка из первой картинки». Чистые правила.
// Шапка читается общими кусками (`articleFile.mjs`); строка поля пишется ТОЙ ЖЕ записью, что при
// создании статьи (`newArticle.mjs`): автор блога из настроек ложится как `authors: [ivan]`.
// Место новой строки — общее правило `местоПоля`; готовые куски возвращаются в файл дословно.

import {dominantEol, headGroups, readField, splitArticle, значениеКуска} from './articleFile.mjs';
import {местоПоля, флаговоеПоле} from './frontmatterFields.mjs';
import {
  адресБезSlug, адресВШапку, articlePlace, isEmptyImage, вКавычках, списокБезЗначений, строковоеПоле,
} from './frontmatterRules.mjs';
import {обложкойМожно, типКартинки} from './imageType.mjs';
import {локальноеИмя, обложкаШапки, ссылкиМедиа} from './refineText.mjs';

/** Имена полей задал Docusaurus — чужой формат, не настройка (SPEC 4.4). */
const ОБЛОЖКА = 'image';
const КОРОТКОЕ_ИМЯ = 'sidebar_label';
const АДРЕС = 'slug';
const ДАТА = 'date';

/** Пусто ли поле по существу: куска нет, список без значений или прочитанная пустота. */
function пусто(группа) {
  if (группа === undefined || списокБезЗначений(группа)) return true;
  const {вид, текст} = значениеКуска(группа);
  return (вид === 'нет' || вид === 'строка') && текст === '';
}

/** Строка поля — записью создания статьи: адрес по правилу шапки, строковое поле в кавычках. */
function строкаПоля(поле, сырое) {
  return `${поле}: ${поле === АДРЕС ? адресВШапку(сырое) : строковоеПоле(поле) ? вКавычках(сырое) : сырое}`;
}

/** Дописать или заменить строки полей в сырой шапке по принятому порядку; прочие куски не трогаются. */
export function дописатьПоля(frontmatterRaw, записи, порядок) {
  const куски = headGroups(frontmatterRaw);
  for (const {ключ, строка} of записи) {
    const свой = куски.findIndex((кусок) => кусок.ключ === ключ);
    if (свой >= 0) {
      куски[свой] = {...куски[свой], строки: [строка]};
      continue;
    }
    const ключиКусков = куски.map((кусок) => кусок.ключ);
    const ключи = ключиКусков.filter((к) => к !== null);
    const среди = местоПоля(ключи, порядок, ключ);
    const место = среди < 0 || среди >= ключи.length
      ? (ключи.length === 0 ? 0 : ключиКусков.lastIndexOf(ключи[ключи.length - 1]) + 1)
      : ключиКусков.indexOf(ключи[среди]);
    куски.splice(место, 0, {ключ, значение: null, строки: [строка]});
  }
  return куски.flatMap((кусок) => кусок.строки).join('\n');
}

/**
 * Можно ли записать это поле одной строкой, ничего не потеряв. `false` — поле в шапке уже есть и
 * записано несколькими строками (продолжение значения, список из строк): запись строкой заменяет
 * кусок целиком, и такое продолжение пропало бы молча. Такую шапку правит человек.
 */
export function полеПишетсяСтрокой(frontmatterRaw, ключ) {
  const свой = headGroups(frontmatterRaw).find((кусок) => кусок.ключ === ключ);
  return свой === undefined || свой.строки.length === 1;
}

/** Текст статьи с новой сырой шапкой: метка, переводы строк и тело остаются как были. */
export function заменитьШапку(текст, новаяШапка) {
  const {head, frontmatterRaw, метка} = splitArticle(текст);
  const eol = dominantEol(текст);
  const от = head.indexOf(frontmatterRaw, метка.length + 3);
  const шапка = eol === '\r\n' ? новаяШапка.replace(/\r?\n/g, eol) : новаяШапка;
  return текст.slice(0, от) + шапка + текст.slice(от + frontmatterRaw.length);
}

const порядокРода = (путь, settings) => settings['поляСоздания'][articlePlace(путь, settings['контент']).kind]?.['порядок'] ?? null;

/** Обработчик 2: пустые поля с явным источником. Смысловые поля остаются человеку. */
export const поляШапки = {
  анализ(копия, settings) {
    const roots = settings['контент'];
    const набор = settings['поляСоздания'][articlePlace(копия.путь, roots).kind];
    if (набор === undefined) return null;
    const {frontmatterRaw} = splitArticle(копия.текст);
    const группы = headGroups(frontmatterRaw);
    const title = readField(frontmatterRaw, 'title');
    const записи = [];
    const отчёт = {изменено: [], оставлено: [], человеку: []};

    for (const поле of набор['порядок']) {
      // Видимость пишет своё правило ядра; обложку заполняет свой обработчик. Черновик — такое же
      // поле доступности: доработка не вправе ни ставить его, ни звать человека его заполнять.
      //
      // Дата записи блога тоже не дело доработки и не просьба человеку: её ставит первая публикация
      // (`core/publishDate.mjs`, решение владельца 2026-09-16). Позови её отчёт заполнить дату — и
      // человек вписал бы день, который публикация всё равно перепишет своим.
      if (флаговоеПоле(поле) || поле === ОБЛОЖКА || поле === ДАТА) continue;
      if (!пусто(группы.find((г) => г.ключ === поле))) continue;
      const сырое = String(набор['значения']?.[поле]
        ?? (поле === КОРОТКОЕ_ИМЯ ? title : поле === АДРЕС ? адресБезSlug(копия.путь, roots) : '')).trim();
      if (сырое === '') {
        отчёт.человеку.push({что: поле, причина: 'нетИсточника'});
        continue;
      }
      записи.push({ключ: поле, строка: строкаПоля(поле, сырое)});
      отчёт.изменено.push({что: поле, было: '', стало: сырое});
    }
    return {записи, порядок: набор['порядок'], отчёт};
  },

  применить(копия, предложение) {
    const шапка = дописатьПоля(splitArticle(копия.текст).frontmatterRaw, предложение.записи, предложение.порядок);
    return {копия: {...копия, текст: заменитьШапку(копия.текст, шапка)}};
  },

  проверить(копия, предложение, settings) {
    return (поляШапки.анализ(копия, settings)?.отчёт.изменено.length ?? 0) === 0;
  },
};

/** Обработчик 5: обложка из первой неподвижной картинки тела, только при пустом поле и без своей. */
export const обложка = {
  анализ(копия, settings) {
    const имяОбложки = String(settings['картинки']['имяОбложки']);
    const отчёт = {изменено: [], оставлено: [], человеку: []};
    const запись = readField(splitArticle(копия.текст).frontmatterRaw, ОБЛОЖКА);
    const отказ = (список, запись1) => {
      отчёт[список].push(запись1);
      return {цель: null, отчёт};
    };

    if (!isEmptyImage(запись)) return отказ('оставлено', {что: ОБЛОЖКА, значение: запись, причина: 'заполнено'});
    const своя = живыеИмена(копия).find((имя) => !имя.includes('/') && имя.replace(/\.[^.]+$/, '').toLowerCase() === имяОбложки.toLowerCase());
    if (своя !== undefined) return отказ('оставлено', {что: своя, причина: 'естьОбложка'});

    const первая = ссылкиМедиа(копия.текст).filter((с) => с.вид === 'картинка').map((с) => локальноеИмя(с.адрес))
      .find((имя) => имя !== null && обложкойМожно(типКартинки(копия.файлы.get(имя) ?? null)));
    if (первая === undefined) return отказ('человеку', {что: ОБЛОЖКА, причина: 'нетКартинки'});

    // Расширение обложки заранее не известно: конвертер возьмёт то представление, что легче. Поэтому
    // заняты не должны быть оба возможных имени — иначе результат лёг бы поверх чужого файла.
    const возможные = ['png', 'jpg'].map((род) => `${имяОбложки}.${род}`);
    отчёт.изменено.push({что: ОБЛОЖКА, было: '', стало: возможные.map((имя) => `./${имя}`).join(' или '), из: первая});
    return {источник: первая, цель: имяОбложки, порядок: порядокРода(копия.путь, settings) ?? [ОБЛОЖКА], отчёт};
  },

  async применить(копия, предложение, инструменты) {
    if (предложение.цель === null) return {копия};
    const исходник = копия.файлы.get(предложение.источник);
    const родИсходника = типКартинки(исходник);
    const [итог] = await инструменты.подготовить([{байты: исходник, род: родИсходника}]);
    // План формат не угадывает — и файла не пишет.
    if (итог.итог === 'план') return {копия};
    if (итог.итог === 'отказ') {
      return {копия, отчёт: {изменено: [], оставлено: [], человеку: [{что: ОБЛОЖКА, причина: итог.причина}]}};
    }
    // **Имя обложки берётся из рода ИТОГОВЫХ байтов, а не назначается заранее.** Иначе JPEG-байты
    // легли бы в `cover.png` — дефект, найденный проверкой 2026-08-20: обложка с чужим содержимым
    // роняет сборку сайта уже после публикации.
    const байты = итог.итог === 'заменить' ? итог.байты : исходник;
    const род = итог.итог === 'заменить' ? итог.род : родИсходника;
    const цель = `${предложение.цель}.${род}`;
    предложение.итог = цель;
    const файлы = new Map(копия.файлы).set(цель, байты);
    const запись = {ключ: ОБЛОЖКА, строка: строкаПоля(ОБЛОЖКА, `./${цель}`)};
    const шапка = дописатьПоля(splitArticle(копия.текст).frontmatterRaw, [запись], предложение.порядок);
    return {копия: {...копия, файлы, текст: заменитьШапку(копия.текст, шапка)}};
  },

  проверить(копия, предложение) {
    if (предложение.цель === null || предложение.итог === undefined) return true;
    const байты = копия.файлы.get(предложение.итог);
    return локальноеИмя(обложкаШапки(копия.текст)) === предложение.итог && байты instanceof Uint8Array
      && `${предложение.цель}.${типКартинки(байты)}` === предложение.итог;
  },
};

/** Имена файлов, которые будут лежать в папке после операции: снимок папки плюс рабочая копия. */
export function живыеИмена(копия) {
  const имена = new Set([...копия.имена].filter((имя) => копия.файлы.get(имя) !== null));
  for (const [имя, байты] of копия.файлы) if (байты !== null) имена.add(имя);
  return [...имена];
}
