// Сведение статьи из трёх сторон: база (от чего отталкивался человек), его работа и внешняя
// правка файла. Здесь только правила — ни диска, ни git, ни интерфейса.
//
// Мест сведения два и они независимы: тело сводится строками, шапка — кусками полей
// (`headGroups`: поле и все его строки). Второго разбора шапки здесь не заводится намеренно:
// резать шапку на единицы правки вправе ровно одно место программы (SPEC 4.3).

import {headGroups, сравнимый} from './articleFile.mjs';
import {свестиЕдиницы, собратьЕдиницы, споров} from './mergeUnits.mjs';

/** Где случилось расхождение. Два места, и у каждого свой способ резать текст на единицы. */
export const МЕСТА = ['тело', 'шапка'];

const строки = (текст) => сравнимый(текст).split('\n');
const куски = (шапка) => headGroups(сравнимый(шапка)).map((группа) => группа.строки.join('\n'));

const разрезать = {тело: строки, шапка: куски};

/**
 * Свести три стороны статьи.
 *
 * Возвращает разбор по местам (`части`), собранный текст (`сведено`, либо `null`, когда есть
 * неразрешённый спор) и перечень спорных мест для человека. Стороны — пары «шапка + тело»,
 * ровно в том виде, в каком их знает окно и хранит черновик.
 */
export function свестиСтатью({база, мои, внешние}) {
  const части = {};
  for (const место of МЕСТА) {
    части[место] = свестиЕдиницы(
      разрезать[место](база[поле(место)]),
      разрезать[место](мои[поле(место)]),
      разрезать[место](внешние[поле(место)]),
    );
  }

  return {части, спорные: спорныеМеста(части), сведено: собрать(части, {})};
}

/** Имя поля стороны для этого места: тело статьи и сырая шапка лежат в паре порознь. */
function поле(место) {
  return место === 'тело' ? 'body' : 'frontmatterRaw';
}

/**
 * Собрать пару «шапка + тело» из разобранных частей и ответов человека.
 * `выбор` — по месту и номеру спора сторона: `мои` или `внешние`.
 * Хоть один спор без ответа — сборки нет вовсе: угадывать за человека нечего.
 */
export function собрать(части, выбор = {}) {
  const пара = {};

  for (const место of МЕСТА) {
    const единицы = собратьЕдиницы(части[место], выбор[место] ?? {});
    if (единицы === null) return null;
    пара[поле(место)] = единицы.join('\n');
  }

  return пара;
}

/**
 * Спорные места для показа человеку: где, какой по счёту, и три стороны текстом.
 * База отдаётся вместе с остальными: без «что было» выбор между двумя правками слепой.
 */
export function спорныеМеста(части) {
  const итог = [];

  for (const место of МЕСТА) {
    let номер = 0;
    for (const часть of части[место]) {
      if (часть.вид !== 'спор') continue;
      итог.push({
        место,
        номер,
        база: часть.база.join('\n'),
        мои: часть.мои.join('\n'),
        внешние: часть.внешние.join('\n'),
      });
      номер += 1;
    }
  }

  return итог;
}

/**
 * Спор из двух сторон целиком, без базы. Так выглядит расхождение, для которого базу доказать
 * не удалось: сводить не от чего, но обе стороны целы, и человек выбирает между ними сам.
 * Части складываются тем же видом, что и обычное сведение, поэтому сборка по ответам у них одна.
 */
export function спорЦеликом(мои, внешние) {
  const части = {};

  for (const место of МЕСТА) {
    части[место] = [{
      вид: 'спор',
      база: [],
      мои: разрезать[место](мои[поле(место)]),
      внешние: разрезать[место](внешние[поле(место)]),
    }];
  }

  return части;
}

/** Есть ли неразрешённые споры хоть в одном месте. */
export function естьСпор(части) {
  return МЕСТА.some((место) => споров(части[место]) > 0);
}

/**
 * Ответы человека в вид, понятный сборке: список выборов превращается в карту по месту и номеру.
 * Посторонние места и стороны отбрасываются: сборка откажется сама, и это честнее, чем принять
 * ответ, которого человек не давал.
 */
export function выборИзОтветов(ответы) {
  const выбор = {};

  for (const ответ of Array.isArray(ответы) ? ответы : []) {
    const {место, номер, сторона} = ответ ?? {};
    if (!МЕСТА.includes(место)) continue;
    if (!Number.isInteger(номер) || номер < 0) continue;
    if (сторона !== 'мои' && сторона !== 'внешние') continue;

    выбор[место] ??= {};
    выбор[место][номер] = сторона;
  }

  return выбор;
}
