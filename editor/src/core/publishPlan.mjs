// Каркас публикации: чем станет сайт, когда человек опубликует ОДНУ открытую языковую версию.
//
// Чистое правило: на входе факты, собранные адаптером, на выходе перечень записей. Ни диска, ни git
// здесь нет (SPEC 4.6). Байтов здесь тоже нет: это КАРКАС, то есть рецепт будущего дерева, а не оно
// само. Байты кладёт отдельный шаг материализации в адаптере, и после него у каждой записи байты
// одного вида — иначе сборка, отпечаток и укладка в git получили бы объект, который надо
// доразбирать, и каждый доразбирал бы его по-своему.
//
// **Публикуется открытый язык, и только он.** Соседние языки входят в каркас не своей работой, а
// технической защитой адреса, и решает это ОДИН факт: лежит ли файл этого языка в опубликованной
// ветке. Лежит — записи нет, на сайте он уже есть и трогать его нельзя. Не лежит — в каркас идёт
// чистая скрытая заглушка, которую пишет сама программа.
//
// **Локальных соседних переводов правило не видит вовсе.** На вход подаётся ОДНА открытая версия, а
// не список версий статьи: список был бы приглашением прочитать соседей, а любая попытка отличить
// «нетронутую заглушку» от «начатого перевода» кончалась тем, что недоделанный сосед либо уезжал на
// сайт, либо запрещал публиковать готовую статью. Ни того, ни другого быть не должно.
//
// Почему заглушки вообще нужны — доказано сборкой сайта 2026-08-23: статья без файла обязательного
// языка не попадает на сайт ВООБЩЕ при зелёной сборке, а язык без своего файла отдаёт под своим
// адресом английский текст и уезжает с ним в карту сайта и в поиск.

import {ВЕРСИЯ, КАРТИНКА, СОСТОЯНИЕ, составВыпуска} from './release.mjs';
import {ИМЯ_КАТЕГОРИИ, границаСостава} from './articleKind.mjs';
import {годныйПутьПлана} from './planPath.mjs';
import {файлСтатьи} from './articles.mjs';

// Назначения записей у плана те же, что у состава: заводить им вторые имена значило бы держать два
// словаря об одном и том же.
export {ВЕРСИЯ, КАРТИНКА, СОСТОЯНИЕ} from './release.mjs';
// Правило годного пути живёт своим файлом — его спрашивает и восстановление после обрыва, — но
// зовущим плана удобнее видеть его здесь, рядом с самим планом.
export {годныйПутьПлана} from './planPath.mjs';

/** Откуда возьмутся байты записи при материализации. Слова человеку — в настройках. */
export const ДИСК = 'диск';
export const СОЗДАНО = 'создано';

/**
 * Запись без байтов вовсе: путь, который на сайте есть, а у человека его больше нет. Без неё
 * публикация умела бы только добавлять — удалённая картинка осталась бы на сайте навсегда, а
 * переименованная лежала бы там дважды. Приёмка Б11 называет удалённые и переименованные наравне
 * с изменёнными.
 */
export const УДАЛЕНО = 'удалено';

/**
 * Режим файла в git. Значение задано не нами — это формат git, и настройкой оно не бывает
 * (SPEC 4.4 про надписи и пороги, а не про чужой формат). Ничего, кроме обычного файла, программа
 * не публикует: символическая ссылка или подмодуль в составе статьи — не наш случай.
 */
export const РЕЖИМ_ФАЙЛА = '100644';

/**
 * Каркас публикации.
 *
 * `открытаяВерсия` — факты ОДНОЙ версии, открытой в окне: путь, локаль, вид, файл состояния,
 * файлы папки, число статей в папке. `наСайте` — живёт ли статья на сайте (песочница не живёт).
 * `языки` — по записи на каждый язык этого рода: `{локаль, путь, опубликован, заглушка}`, где
 * `опубликован` строго логический, а `заглушка` — текст чистой заглушки на этом языке.
 * `наСайтеВПапке` — обычные файлы, лежащие в ЗАКРЕПЛЁННОЙ опубликованной ветке внутри каталога
 * открытой версии; `null` — спросить не удалось, и это отказ, а не «там пусто».
 *
 * Возвращает `{записи, разрывы, отказ}`. Запись: `{путь, назначение, локаль, источник, режим, текст}`;
 * `текст` не пуст только у созданных. `разрыв` — состав доказать нечем; `отказ` — состав известен,
 * но публиковать нельзя. Незнание всегда отказ: угадав, программа либо опубликует лишнее, либо
 * выпустит статью, которой на сайте не будет.
 */
export function каркасПлана({открытаяВерсия, наСайте, языки, наСайтеВПапке}) {
  const своя = открытаяВерсия;
  if (!своя || typeof своя.путь !== 'string' || своя.путь === '') {
    return {записи: [], разрывы: [{причина: 'нетВерсий'}], отказ: null};
  }

  // Открытая версия целиком: её файл, её готовность и картинки её папки. Прежние разрывы —
  // запись вне канона и вторая статья в папке — остаются и по-прежнему запрещают публикацию.
  const состав = составВыпуска({версии: [своя]});
  const свойКаркас = состав.файлы.map(сДиска);
  const свои = new Set(свойКаркас.map((запись) => запись.путь));

  // Повторы причин снимаются здесь, у их единственного источника: вторую статью в папке называют
  // своим разрывом и состав на диске, и уборка на сайте, а человек от повтора решит, что бед две.
  const итог = (записи, отказ = null, ещёРазрывы = []) => ({
    записи: поПутям(записи),
    разрывы: безПовторов([...состав.разрывы, ...ещёРазрывы]),
    отказ,
  });
  const неизвестно = (чего, локали = []) => итог(свойКаркас, {код: 'фактыНеизвестны', локали, чего});

  // **Свои пути проверяются первыми и до всякого возврата.** Они приходят с диска, а не из
  // настроек, и оттого кажутся заведомо верными — но именно они станут именами файлов во временной
  // копии и аргументами записи в git. Путь с `..`, с буквой диска или повторяющийся увёл бы запись
  // за пределы репозитория или положил бы один файл поверх другого, причём у статьи вне сайта это
  // случилось бы совсем без проверок. Записи при такой беде не отдаются вовсе: каркасу, чьи
  // собственные пути недостоверны, верить нечему.
  if (свои.size !== свойКаркас.length || свойКаркас.some((запись) => !годныйПутьПлана(запись.путь))) {
    const локаль = typeof своя.локаль === 'string' && своя.локаль !== '' ? [своя.локаль] : [];
    return {записи: [], разрывы: состав.разрывы, отказ: {код: 'фактыНеизвестны', локали: локаль, чего: 'свойПуть'}};
  }

  // Статья вне сайта (песочница): языковой подмены там не бывает, и заглушек там нет вовсе.
  if (наСайте === false) return итог(свойКаркас);

  // **Отсутствие факта — не «вне сайта».** Пропущенный или испорченный признак прошёл бы этой веткой
  // мимо всей защиты, и статья уехала бы на сайт без заглушек.
  if (наСайте !== true) return неизвестно('место');

  const беда = бедаПеречня(языки, своя, свои);
  if (беда) return неизвестно(беда.чего, беда.локали);

  // Пропавшие с диска собственные файлы: их надо убрать и с сайта. Спросить сайт не удалось —
  // отказ: приняв незнание за «убирать нечего», программа молча оставила бы там удалённое.
  const уборка = убрать(своя, свои, наСайтеВПапке);
  if (уборка === null) return неизвестно('вПапке', [своя.локаль]);
  // Состав в этой части не доказан — и это разрыв, а не тихая публикация без уборки: молча выпустив
  // такую статью, программа оставила бы на сайте старое имя переименованной картинки и промолчала
  // бы о неоднозначности, которую сама же увидела.
  if (уборка.разрыв) return итог(свойКаркас, null, [уборка.разрыв]);

  const созданные = [];

  for (const язык of языки) {
    if (язык.локаль === своя.локаль) continue;
    // Файл этого языка на сайте есть. Его не трогают ничем: там может лежать давно готовый перевод.
    if (язык.опубликован === true) continue;

    // Текста заглушки для языка не задано. Подставить чужой язык значит соврать читателю, а
    // умолчание в коде завело бы второй источник правды рядом с настройкой (SPEC 4.4.1).
    if (typeof язык.заглушка !== 'string' || язык.заглушка === '') {
      return итог(свойКаркас, {код: 'нетШаблонаЗаглушки', локали: [язык.локаль], чего: null});
    }

    // У созданной заглушки уезжает только её собственный файл. Готовность — служебная запись о
    // работе человека, а картинок у страницы, которой ещё нет на сайте, не бывает.
    созданные.push({
      путь: язык.путь,
      назначение: ВЕРСИЯ,
      локаль: язык.локаль,
      источник: СОЗДАНО,
      режим: РЕЖИМ_ФАЙЛА,
      текст: язык.заглушка,
    });
  }

  return итог([...свойКаркас, ...созданные, ...уборка.записи]);
}

/**
 * Что убрать с сайта: пути, которые лежат там внутри каталога открытой версии, а у человека их
 * больше нет. Возвращает `{записи}`, `{разрыв}` либо `null` — «сайт не спрошен».
 *
 * **Граница та же, что у состава, и другой быть не может.** Обычная статья владеет своим каталогом
 * вглубь, страница категории — только верхним уровнем без `_category_.json`, у корневой страницы и
 * записи вне канона собственного каталога нет вовсе. Возьми правило шире — публикация одной
 * страницы унесла бы с сайта дочерние статьи целого раздела.
 *
 * **Файл статьи не убирается никогда, а вторая статья в тех же границах — разрыв.** Чужой файл
 * статьи означает, что каталог на сайте принадлежит не только этой версии: чьи там картинки, по
 * путям не видно. Ровно это же положение на диске состав давно называет разрывом `папкаНеОдна`, и на
 * сайте оно не может значить меньше: промолчи правило — публикация прошла бы успешно, оставив там
 * старое имя переименованной картинки.
 */
function убрать(своя, свои, наСайтеВПапке) {
  const граница = границаСостава(своя.вид);
  if (граница === 'нечего' || граница === 'толькоФайл') return {записи: []};

  const папка = своя.путь.slice(0, своя.путь.lastIndexOf('/'));
  if (папка === '') return {записи: []};
  if (!Array.isArray(наСайтеВПапке)) return null;

  const внутри = наСайтеВПапке.filter((путь) => годныйПутьПлана(путь) && вГранице(путь, папка, граница));
  if (внутри.some((путь) => путь !== своя.путь && файлСтатьи(путь))) {
    return {разрыв: {причина: 'папкаНеОдна', путь: своя.путь, локаль: своя.локаль}};
  }

  return {
    записи: внутри
      .filter((путь) => !файлСтатьи(путь) && !свои.has(путь))
      .map((путь) => ({
        путь,
        назначение: путь === (своя.состояние ?? своя.местоГотовности) ? СОСТОЯНИЕ : КАРТИНКА,
        локаль: своя.локаль,
        источник: УДАЛЕНО,
        режим: null,
        текст: null,
      })),
  };
}

/** Одна беда — одна причина. Сравниваются все поля разрыва: разные пути — разные беды. */
function безПовторов(разрывы) {
  const виденные = new Set();

  return разрывы.filter((разрыв) => {
    const ключ = `${разрыв.причина}|${разрыв.путь ?? ''}|${разрыв.локаль ?? ''}`;
    if (виденные.has(ключ)) return false;
    виденные.add(ключ);

    return true;
  });
}

/** Попадает ли путь сайта в собственные границы версии. Сам каталог своим содержимым не считается. */
export function вГранице(путь, папка, граница) {
  if (!путь.startsWith(`${папка}/`)) return false;

  const хвост = путь.slice(папка.length + 1);
  if (граница !== 'верхнийУровень') return true;

  return !хвост.includes('/') && хвост !== ИМЯ_КАТЕГОРИИ;
}

/** Можно ли публиковать: состав доказан целиком, отказа нет и в каркасе есть языковая версия. */
export function публикацияВозможна(каркас) {
  return каркас.отказ === null
    && каркас.разрывы.length === 0
    && каркас.записи.some((запись) => запись.назначение === ВЕРСИЯ);
}

/** Запись каркаса, чьи байты лежат на диске: их положит материализация, правило их не знает. */
const сДиска = (файл) => ({
  путь: файл.путь,
  назначение: файл.назначение,
  локаль: файл.локаль,
  источник: ДИСК,
  режим: РЕЖИМ_ФАЙЛА,
  текст: null,
});

/**
 * Порядок записей — по кодам знаков, а не по правилам языка.
 *
 * `localeCompare` зависит от языка системы: на разных машинах он даёт разный порядок одних и тех же
 * путей. Отсюда считается отпечаток плана, и порядок обязан быть один и тот же везде, иначе сборка
 * и коммит на соседней машине разошлись бы на пустом месте.
 */
const поПутям = (записи) => [...записи].sort((a, b) => (a.путь < b.путь ? -1 : a.путь > b.путь ? 1 : 0));

/**
 * Что не так с перечнем языков. `null` — всё в порядке.
 *
 * Перечень — единственное, чем правило знает, каких файлов не хватает на сайте, и одновременно
 * единственный источник путей, куда лягут созданные заглушки. Поэтому он проверяется целиком:
 * пустой отменил бы защиту молча, а повтор или чужой путь позволили бы заглушке лечь поверх работы
 * человека или вовсе мимо репозитория.
 */
function бедаПеречня(языки, своя, свои) {
  if (!Array.isArray(языки) || языки.length === 0) return {чего: 'языки', локали: []};

  const локали = new Set();
  const пути = new Set();
  let нашлась = false;

  for (const язык of языки) {
    const локаль = язык?.локаль;
    if (typeof локаль !== 'string' || локаль === '' || локали.has(локаль)) {
      return {чего: 'языки', локали: typeof локаль === 'string' ? [локаль] : []};
    }
    локали.add(локаль);

    if (!годныйПутьПлана(язык?.путь)) return {чего: 'путь', локали: [локаль]};
    // Два языка с одним путём: заглушка одного легла бы поверх другого.
    if (пути.has(язык.путь)) return {чего: 'столкновение', локали: [локаль]};
    пути.add(язык.путь);

    if (локаль === своя.локаль) {
      нашлась = true;
      // Перечень описывает не ту статью, что открыта. Дальше считать нечего: чужие пути увели бы
      // заглушки к посторонней статье.
      if (язык.путь !== своя.путь) return {чего: 'своя', локали: [локаль]};
      continue;
    }

    // Спросить опубликованную ветку не удалось. «Не знаю» — не «нет»: приняв незнание за отсутствие,
    // программа переписала бы заглушкой живой перевод, который на сайте уже стоит.
    if (язык.опубликован !== true && язык.опубликован !== false) {
      return {чего: 'опубликованная', локали: [локаль]};
    }

    // Путь чужого языка совпал с файлом открытой версии — её собственной картинкой или готовностью.
    // Заглушка стёрла бы работу человека прямо в коммите.
    if (свои.has(язык.путь)) return {чего: 'столкновение', локали: [локаль]};
  }

  // Открытого языка в перечне нет: значит перечень не про этот род, и молчание о нём означало бы
  // «соседей не нужно» — то есть отмену защиты целиком.
  return нашлась ? null : {чего: 'языки', локали: [своя.локаль]};
}
