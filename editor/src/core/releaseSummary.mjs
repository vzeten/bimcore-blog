// Что человек увидит перед публикацией: короткий итог вместо перечня файлов.
//
// **Список путей проверкой не является.** Последнюю содержательную проверку человек уже сделал,
// когда читал статью; десятки строк с путями он читать не станет, а прочитав, ничего нового не
// узнает. Поэтому здесь считается другое: какая языковая версия действительно меняется, какая
// остаётся как была, какая ещё заглушка, каких языков нет вовсе и какие картинки действительно
// изменились. Неизменённое не называется уезжающим — оно и не меняется.
//
// Чистое правило: на входе факты, собранные адаптером (состав, что расходится с сайтом, признак
// заглушки), на выходе — итог для окна. Ни git, ни диска здесь нет (SPEC 4.6).

import {ВЕРСИЯ, КАРТИНКА, СОСТОЯНИЕ} from './release.mjs';

/** Что стало с языковой версией. Слова человеку живут в настройках, здесь только признаки. */
export const ИЗМЕНИЛАСЬ = 'изменилась';
export const НЕ_МЕНЯЛАСЬ = 'неМенялась';
export const ЗАГЛУШКА = 'заглушка';
export const НЕТ_ВЕРСИИ = 'нетВерсии';

/**
 * Итог выпуска для человека.
 *
 * `файлы` — состав выпуска; `изменённые` — те его пути, что расходятся с сайтом (остальные там уже
 * лежат ровно такими); `заглушки` — локали, версия которых до сих пор заглушка перевода;
 * `всеЛокали` — все языки сайта по настройке, чтобы молчание о языке не сходило за «всё хорошо».
 *
 * Возвращает `{версии, картинки, естьЧтоПубликовать}`. Версия названа у КАЖДОГО языка сайта:
 * человек обязан понимать состояние всех языков статьи, а не только тех, что изменились.
 */
export function итогВыпуска({файлы, изменённые, заглушки, скрытые, всеЛокали}) {
  const состав = Array.isArray(файлы) ? файлы : [];
  const менялось = new Set(изменённые ?? []);
  const заглушкаУ = new Set(заглушки ?? []);
  const скрытаУ = new Set(скрытые ?? []);

  const версии = (всеЛокали ?? []).map((локаль) => {
    const своя = состав.find((файл) => файл.назначение === ВЕРСИЯ && файл.локаль === локаль);
    if (своя === undefined) return {локаль, состояние: НЕТ_ВЕРСИИ, путь: null, скрыта: false};

    // Файл состояния версии ходит вместе с ней и отдельной строкой человеку не показывается:
    // это служебная запись готовности, а не его работа.
    const свои = состав.filter((файл) => файл.локаль === локаль && файл.назначение !== КАРТИНКА);
    const тронута = свои.some((файл) => менялось.has(файл.путь));
    const скрыта = скрытаУ.has(локаль);
    if (тронута) return {локаль, состояние: ИЗМЕНИЛАСЬ, путь: своя.путь, скрыта};

    return {локаль, состояние: заглушкаУ.has(локаль) ? ЗАГЛУШКА : НЕ_МЕНЯЛАСЬ, путь: своя.путь, скрыта};
  });

  // Картинки называются только изменившиеся. Семьдесят неизменённых файлов в списке — это шум,
  // из-за которого человек перестанет читать список вовсе.
  const картинки = состав
    .filter((файл) => файл.назначение === КАРТИНКА && менялось.has(файл.путь))
    .map((файл) => файл.путь);

  return {
    версии,
    картинки,
    // Публиковать нечего, если ни один файл состава не расходится с сайтом.
    естьЧтоПубликовать: состав.some((файл) => менялось.has(файл.путь)),
    // Сколько служебных записей готовности едет вместе со статьёй — только для технических
    // подробностей, в человеческий итог они не попадают.
    служебных: состав.filter((файл) => файл.назначение === СОСТОЯНИЕ && менялось.has(файл.путь)).length,
  };
}
