// Лишние файлы папки статьи: те, на которые не ссылается НИ ОДНА её языковая версия.
//
// Чистое правило: на входе пути файлов и тексты всех версий, собранные адаптером, на выходе —
// перечень путей. Ни диска, ни git здесь нет (SPEC 4.6).
//
// **Ссылка ищется САМИМ ИМЕНЕМ ФАЙЛА, а не разбором записи.** Разбери правило markdown-картинки,
// JSX-теги, импорты, карточки товара и поля шапки по отдельности — и любая шестая запись, о которой
// никто не вспомнил (`@site/...`, относительный путь из соседней локали, свойство чужого
// компонента), означала бы удаление нужного файла. Имя файла содержат они все одинаково, поэтому
// одного вопроса «встречается ли это имя в текстах статьи» хватает на все виды записи сразу.
// Правило намеренно широкое в сторону сохранения: лишним называется только то, чьё имя не
// встретилось нигде ни разу. Случайное совпадение (`img-1.png` внутри `img-11.png`) оставляет файл
// на месте, и это верная сторона ошибки.
//
// **Тексты приходят СРАЗУ ПО ВСЕМ ЯЗЫКАМ статьи.** У каждой локали своя папка, но ссылаться на
// соседнюю она вправе, и файл, нужный испанской версии, не становится лишним оттого, что русская о
// нём молчит. Собрать тексты не удалось — адаптер не зовёт это правило вовсе, и не убирается ничего.
//
// Регистр не учитывается: на Windows `IMG-01.PNG` и `img-01.png` — один и тот же файл, и ссылка,
// записанная иначе, обязана удержать его от уборки. Тем же правилом живёт замена картинки
// (`imageFormat.файлИспользуется`).

import {служебноеИмя, файлСтатьи} from './articles.mjs';

/**
 * Какие из названных файлов лишние.
 *
 * `пути` — файлы папки версии (пути от корня репозитория); `тексты` — тексты ВСЕХ языковых версий
 * статьи; `имяОбложки` — имя файла обложки без расширения из настроек (`картинки.имяОбложки`).
 *
 * Возвращает пути в том же порядке. Вход не тот, какого ждали, — пустой перечень: незнание здесь
 * значит «не убирать», а не «убрать всё».
 */
export function лишниеФайлы({пути, тексты, имяОбложки}) {
  if (!Array.isArray(пути) || !Array.isArray(тексты)) return [];
  if (тексты.some((текст) => typeof текст !== 'string')) return [];

  // Тексты склеиваются один раз: у статьи их три, а файлов в папке бывает семьдесят.
  const текст = тексты.join('\n').toLowerCase();
  const обложка = String(имяОбложки ?? '').toLowerCase();

  return пути.filter((путь) => лишний(путь, текст, обложка));
}

/** Имя файла без пути: им лишний файл называется человеку — место на диске ему ни о чём не говорит. */
export const имяФайла = (путь) => String(путь ?? '').slice(String(путь ?? '').lastIndexOf('/') + 1);

/**
 * Один файл: лишний ли он.
 *
 * Никогда не лишними считаются служебные файлы версии и её обложка. Служебное имя — то же правило,
 * что и у обхода папок (`служебноеИмя`, SPEC 2.7): `_state.json` и `_category_.json` сайт не
 * собирает, ссылок на них не бывает по их природе, и назвать их лишними значило бы унести
 * готовность и описание раздела. Обложка `cover.*` лежит рядом со статьёй и работает даже тогда,
 * когда в шапке её ещё нет: её ставит отдельный ход публикации.
 *
 * Файл без расширения не трогается вовсе: чем он является, по имени не видно.
 */
function лишний(путь, текст, обложка) {
  const имя = String(путь ?? '');
  if (имя === '') return false;

  const куски = имя.split('/');
  if (куски.some(служебноеИмя)) return false;

  const короткое = куски[куски.length - 1];
  if (файлСтатьи(короткое)) return false;

  const точка = короткое.lastIndexOf('.');
  if (точка <= 0) return false;
  if (короткое.slice(0, точка).toLowerCase() === обложка) return false;

  return !текст.includes(короткое.toLowerCase());
}
