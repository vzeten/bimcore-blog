// Блоки статьи, записанные JSX-тегом: разбор, обратная сборка, смена свойства и вставка.
// Чистые правила без редактора и DOM: на входе текст, на выходе текст.
//
// Программа знает ровно те блоки, что перечислены в настройках (`блоки`). Всё остальное — чужой
// текст: незнакомое имя, незакрытый или многострочный тег, свойство в фигурных скобках JSX или
// в одинарных кавычках здесь не разбираются вовсе и остаются в файле дословно.

import {lineBounds, type Edit, type Selection} from './commands';

/** Свойство тега как оно записано: имя и значение в двойных кавычках. */
export interface Свойство {
  имя: string;
  значение: string;
}

/** Разобранный тег: имя блока и его свойства в том порядке, в каком они стоят в тексте. */
export interface Блок {
  имя: string;
  свойства: Свойство[];
}

/**
 * Смысловое поле блока: что человек выбирает сам. Описание приходит из настроек, поэтому новый
 * блок заводится там же, без правки программы.
 */
export interface ПолеБлока {
  /** Имя свойства в теге статьи. */
  имя: string;
  подпись: string;
  /** Значение — человеческое название. Список закрытый: своего в коде нет. */
  значения: Record<string, string>;
  /** Начальное значение предлагает раздел статьи, но не навязывает. */
  поРазделу?: boolean;
}

/** Блок, который программа знает в лицо: чем показать вместо JSX и что дать выбрать человеку. */
export interface ОписаниеБлока {
  подпись: string;
  поля: ПолеБлока[];
}

/**
 * Самозакрывающийся тег в одну строку с простыми свойствами в двойных кавычках и ничем больше.
 * Многострочный тег сюда намеренно не подходит: собрать его обратно можно только в одну строку,
 * а это переписало бы то, как человек его набрал. Синтаксис чужого формата (MDX), поэтому живёт
 * в коде, а не в настройках (SPEC 4.4).
 */
const ТЕГ = /^<([A-Za-z][A-Za-z0-9]*)((?:[ \t]+[A-Za-z][A-Za-z0-9-]*="[^"<>]*")*)[ \t]*\/>$/;
const СВОЙСТВО = /([A-Za-z][A-Za-z0-9-]*)="([^"<>]*)"/g;

/** Значение, которое нельзя записать в тег, не сломав его. */
const ОПАСНЫЕ_ЗНАКИ = /["<>]/;

/**
 * Разбор тега. `null` — это не простой самозакрывающийся тег, и трогать его нельзя:
 * так неизвестный и неполный JSX остаётся текстом статьи, а не превращается в блок.
 */
export function разборТега(текст: string): Блок | null {
  const найдено = ТЕГ.exec(текст);
  if (найдено === null) return null;

  const свойства: Свойство[] = [];
  for (const [, имя, значение] of найдено[2].matchAll(СВОЙСТВО)) свойства.push({имя, значение});

  return {имя: найдено[1], свойства};
}

/** Обратная сборка тега из имени и свойств. Разбор и сборка — пара: одно правило записи. */
export function сборкаТега(блок: Блок): string {
  const хвост = блок.свойства.map(({имя, значение}) => ` ${имя}="${значение}"`).join('');
  return `<${блок.имя}${хвост} />`;
}

/**
 * Тот же тег с другим значением одного свойства. Незнакомые программе свойства остаются на своих
 * местах и в своём порядке — правится ровно то, что человек выбрал. Свойства не было вовсе —
 * оно дописывается в конец.
 *
 * `null` — тег не разобран или значение сломало бы запись: тогда текст не меняется вообще.
 */
export function сменаСвойства(текст: string, имя: string, значение: string): string | null {
  const блок = разборТега(текст);
  if (блок === null || ОПАСНЫЕ_ЗНАКИ.test(значение)) return null;

  const было = блок.свойства.some((свойство) => свойство.имя === имя);
  const свойства = было
    ? блок.свойства.map((свойство) => (свойство.имя === имя ? {имя, значение} : свойство))
    : [...блок.свойства, {имя, значение}];

  return сборкаТега({имя: блок.имя, свойства});
}

/** Значение свойства тега. `null` — тега нет или свойство в нём не записано. */
export function значениеСвойства(текст: string, имя: string): string | null {
  const блок = разборТега(текст);
  if (блок === null) return null;

  return блок.свойства.find((свойство) => свойство.имя === имя)?.значение ?? null;
}

/**
 * Что предлагает раздел статьи. Раздел ищется по той же цепочке узлов, какой живёт дерево
 * реестра, и побеждает самое глубокое совпадение: `docs/guides/templates` — это шаблон,
 * а не общая инструкция, хотя лежит внутри `docs/guides`.
 *
 * `null` — раздел ничего не предлагает и умолчания в настройках нет: тогда свойство не пишется
 * вовсе, а не подставляется догадкой из кода (SPEC 4.4.1).
 */
export function значениеПоРазделу(
  карта: Record<string, string>,
  раздел: {kind: string; path: string},
): string | null {
  const узел = раздел.path === '' ? раздел.kind : `${раздел.kind}/${раздел.path}`;
  const части = узел.split('/');

  for (let глубина = части.length; глубина > 0; глубина -= 1) {
    const значение = карта[части.slice(0, глубина).join('/')];
    if (значение !== undefined) return значение;
  }

  return карта['умолчание'] ?? null;
}

/**
 * Новый тег блока для вставки. Человек не вводит ничего: свойство, которое умеет предлагать
 * раздел, программа подставляет сама, а поменять его он может в свойствах блока. Поле, которому
 * нечего подставить, в тег не пишется — пустое свойство хуже отсутствующего.
 */
export function новыйТег(
  имя: string,
  описание: ОписаниеБлока,
  предложение: (поле: ПолеБлока) => string | null,
): string {
  const свойства: Свойство[] = [];

  for (const поле of описание.поля) {
    if (поле.поРазделу !== true) continue;
    const значение = предложение(поле);
    if (значение !== null) свойства.push({имя: поле.имя, значение});
  }

  return сборкаТега({имя, свойства});
}

/**
 * Вставка блока отдельной строкой. Тег обязан стоять сам по себе: `<truncate />` внутри абзаца
 * разрежет анонс посреди предложения, а `<CTA />` соседним словом слипнется с текстом.
 * Пустых строк добавляется ровно столько, сколько не хватает, — соседний текст не переписывается.
 */
export function вставкаБлока(текст: string, at: Selection, тег: string): Edit {
  const строка = lineBounds(текст, at);
  const пустая = текст.slice(строка.from, строка.to).trim() === '';
  const место = пустая ? строка.from : строка.to;

  const до = текст.slice(0, место);
  const после = текст.slice(место);
  const отступДо = до === '' ? '' : отступ(своиПереводы(до, 'конец'));
  const отступПосле = после === '' ? '' : отступ(своиПереводы(после, 'начало'));

  const insert = `${отступДо}${тег}${отступПосле}`;
  return {from: место, to: место, insert, caret: отступДо.length + тег.length};
}

/** Сколько переводов строк уже стоит у соседа с нужной стороны: 0, 1 или 2. */
function своиПереводы(сосед: string, край: 'начало' | 'конец'): number {
  const найдено = край === 'конец' ? /\n{1,2}$/.exec(сосед) : /^\n{1,2}/.exec(сосед);
  return найдено === null ? 0 : найдено[0].length;
}

/** Сколько переводов строк дописать, чтобы блок стоял отдельной строкой. */
function отступ(есть: number): string {
  return '\n'.repeat(Math.max(0, 2 - есть));
}
