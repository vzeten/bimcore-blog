import {lineBounds, type Edit, type Selection} from './commands';
import {ОПАСНЫЕ_ЗНАКИ, разборТега as разборТегаЯдра} from './jsxTag.mjs';

export interface Свойство {
  имя: string;
  значение: string;
  /** Значение записано выражением JSX (`image={productPreview}`), а не строкой в кавычках. */
  выражение: boolean;
  /** Границы записи значения в тексте тега: правится ровно этот кусок. */
  от: number;
  до: number;
}

export interface Блок {
  имя: string;
  свойства: Свойство[];
  /** Место перед закрытием тега: сюда дописывается свойство, которого в теге не было. */
  конец: number;
  /** Чем новое свойство отделяется от соседнего: пробелом либо переводом строки с отступом. */
  отступ: string;
}

/**
 * Вид поля решает, чем человек его заполняет. Поле без вида остаётся выбором из словаря
 * `значения`: так устроен призыв к действию, и новые виды его не касаются.
 *
 * Обязательным поле бывает только там, где без него блока не существует (`обязательно`): у всех
 * прочих незаполненное свойство ничего не блокирует, а описание, дату и длительность видео позже
 * заполняет отдельная доработка (`PLAN.md`).
 */
export type ВидПоля = 'выбор' | 'ссылкаВидео' | 'строка' | 'дата' | 'длительность';

export interface ПолеБлока {
  имя: string;
  подпись: string;
  вид?: ВидПоля;
  /**
   * Без этого свойства блока не существует: сайт не показывает карточку товара без названия
   * (`if (!name || !image) return null`). Пустое значение получает отказ, а прежнее остаётся
   * в статье: молча стереть то, на чём держится блок, программа не вправе.
   */
  обязательно?: boolean;
  значения?: Record<string, string>;
  поРазделу?: boolean;
  /**
   * Поле спрашивается уже при вставке блока. Остальные свойства человек правит потом, нажав на
   * готовый блок: перегружать вставку видео пятью полями значит мешать обычному сценарию.
   */
  приВставке?: boolean;
  подсказка?: string;
}

export interface ОписаниеБлока {
  подпись: string;
  поля: ПолеБлока[];
  /** Имя свойства, чьё значение показывается в статье как название блока. */
  названиеПоля?: string;
  /**
   * Свойства, которые новый блок молча берёт у шапки статьи: свойство тега — поле шапки.
   * Человеку они не показываются: у видео это название для доступности, а не то, что он вводит.
   */
  начальные?: Record<string, string>;
}

/** Разбор тега живёт в `jsxTag.mjs`: тем же правилом читает теги подготовка. */
export function разборТега(текст: string): Блок | null {
  return разборТегаЯдра(текст) as Блок | null;
}

/**
 * Сборка нового тега — одна на всю программу, второго сборщика JSX не заводится.
 *
 * Обычный тег пишется одной строкой. Столбиком записаны только карточки товара: так они лежат
 * в статьях сайта, и такой тег программа читает своим же разбором. Значение-выражение JSX
 * (`image={productPreview}`) пишется без кавычек: за именем стоит импорт файла статьи.
 */
export function сборкаТега(
  блок: {имя: string; свойства: {имя: string; значение: string; выражение?: boolean}[]},
  столбиком = false,
): string {
  const запись = ({имя, значение, выражение}: {имя: string; значение: string; выражение?: boolean}): string =>
    `${имя}=${выражение === true ? `{${значение}}` : `"${значение}"`}`;

  if (!столбиком) return `<${блок.имя}${блок.свойства.map((с) => ` ${запись(с)}`).join('')} />`;
  return [`<${блок.имя}`, ...блок.свойства.map((с) => `  ${запись(с)}`), '/>'].join('\n');
}

/**
 * Правка одного свойства. Меняется ровно запись его значения, весь остальной тег остаётся теми же
 * знаками: запись столбиком не схлопывается в строку, а `
` не превращается в `
`. Тег,
 * собранный заново, менял бы файл человека там, где он ничего не менял.
 *
 * Значение-выражение JSX не переписывается вовсе: за именем стоит импорт файла статьи, и обычная
 * строка на его месте оборвала бы связь тега с картинкой.
 */
export function сменаСвойства(текст: string, имя: string, значение: string): string | null {
  const блок = разборТега(текст);
  if (блок === null || ОПАСНЫЕ_ЗНАКИ.test(значение)) return null;

  const было = блок.свойства.find((свойство) => свойство.имя === имя);
  if (было === undefined) {
    return `${текст.slice(0, блок.конец)}${блок.отступ}${имя}="${значение}"${текст.slice(блок.конец)}`;
  }
  if (было.выражение) return null;

  return `${текст.slice(0, было.от)}"${значение}"${текст.slice(было.до)}`;
}

/** Выражение JSX словами человека не показывается: имя переменной он не вводил и править не может. */
export function значениеСвойства(текст: string, имя: string): string | null {
  const блок = разборТега(текст);
  if (блок === null) return null;

  const свойство = блок.свойства.find((найдено) => найдено.имя === имя);
  if (свойство === undefined || свойство.выражение) return null;

  return свойство.значение;
}

export function значениеПоРазделу(
  карта: Record<string, string>,
  раздел: {kind: string; path: string},
): string | null {
  const узел = раздел.path === '' ? раздел.kind : `${раздел.kind}/${раздел.path}`;
  const части = узел.split('/');

  for (let глубина = части.length; глубина > 0; глубина -= 1) {
    const значение = карта[части.slice(0, глубина).join('/')];
    if (значение !== undefined) return значение;
  }

  return карта['умолчание'] ?? null;
}

/**
 * Новый блок для вставки. Значение сразу получают поле раздела (`поРазделу`) и свойства из
 * `начальные`, которые берутся у шапки статьи молча: спрашивать у человека название видео,
 * когда оно уже написано в заголовке статьи, незачем.
 *
 * Значение с кавычкой или угловой скобкой не ставится вовсе: такой тег программа перестала бы
 * разбирать, и блок стал бы для неё обычным текстом статьи.
 */
export function новыйТег(
  имя: string,
  описание: ОписаниеБлока,
  предложение: (что: {поле?: ПолеБлока; изШапки?: string}) => string | null,
): string {
  const свойства: {имя: string; значение: string}[] = [];
  const добавить = (имяСвойства: string, значение: string | null): void => {
    if (значение === null || значение === '' || ОПАСНЫЕ_ЗНАКИ.test(значение)) return;
    свойства.push({имя: имяСвойства, значение});
  };

  for (const поле of описание.поля) {
    if (поле.поРазделу !== true) continue;
    добавить(поле.имя, предложение({поле}));
  }

  for (const [свойство, полеШапки] of Object.entries(описание.начальные ?? {})) {
    добавить(свойство, предложение({изШапки: полеШапки}));
  }

  return сборкаТега({имя, свойства});
}

export function вставкаБлока(текст: string, at: Selection, тег: string): Edit {
  const строка = lineBounds(текст, at);
  const пустая = текст.slice(строка.from, строка.to).trim() === '';
  const место = пустая ? строка.from : строка.to;

  const до = текст.slice(0, место);
  const после = текст.slice(место);
  const отступДо = до === '' ? '' : отступ(своиПереводы(до, 'конец'));
  const отступПосле = после === '' ? '' : отступ(своиПереводы(после, 'начало'));

  const insert = `${отступДо}${тег}${отступПосле}`;
  return {from: место, to: место, insert, caret: отступДо.length + тег.length};
}

function своиПереводы(сосед: string, край: 'начало' | 'конец'): number {
  const найдено = край === 'конец' ? /\n{1,2}$/.exec(сосед) : /^\n{1,2}/.exec(сосед);
  return найдено === null ? 0 : найдено[0].length;
}

function отступ(есть: number): string {
  return '\n'.repeat(Math.max(0, 2 - есть));
}
