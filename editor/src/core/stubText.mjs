// Заглушка перевода: её текст, её признак и её язык. Одно место на всю программу.
//
// Заглушку пишут два правила — создание статьи целиком и начало отдельной языковой версии, — а
// узнают её ещё два: подготовка к выпуску и состав публикации. Разойдись их мерки хоть на слово,
// программа считала бы заглушкой не то, что сама написала, в тот же день, когда владелец поправит
// текст в настройках.
//
// Языка заглушки в коде нет: он приходит ключом настройки «заглушкиПеревода».

/**
 * Текст заглушки для языка: заголовок, тело и описание.
 * Нет строки или она неполная — `null`, и зовущий обязан отказаться, а не выдумывать текст.
 *
 * Неполная считается отсутствующей намеренно: файл без описания остановил бы выпуск своей же
 * статьи, а заглушка без тела ничего не сообщила бы читателю.
 */
export function шаблонЗаглушки(локаль, settings) {
  const шаблон = (settings['заглушкиПеревода'] ?? {})[локаль];
  const полон = ['заголовок', 'тело', 'описание'].every(
    (поле) => String(шаблон?.[поле] ?? '').trim() !== '',
  );

  return полон ? шаблон : null;
}

/**
 * Осталась ли языковая версия заглушкой перевода. Считается по тому же тексту, которым программа
 * заглушку и пишет.
 *
 * Перевели заглушку хотя бы частично — её текст пропал, и версия заглушкой уже не считается.
 * Заглушка написана на языке своей страницы, и какой это язык, отсюда не видно: сравниваем со
 * всеми заведёнными образцами. Спрашивать локаль у зовущего значило бы завести второе место,
 * знающее, где какая заглушка лежит.
 */
export function этоЗаглушка(тело, settings) {
  const текст = String(тело ?? '');

  return Object.values(settings['заглушкиПеревода'] ?? {}).some((шаблон) => {
    const образец = String(шаблон?.['тело'] ?? '').trim();
    return образец !== '' && текст.includes(образец);
  });
}

/**
 * Осталось ли описание версии тем, что вписала заглушка. Сверяется со ВСЕМИ языками сразу —
 * заглушка написана на языке своей страницы, и какой это язык, из описания не видно.
 */
export function шаблонноеОписание(описание, settings) {
  const текст = String(описание ?? '').trim();
  if (текст === '') return false;

  return Object.values(settings['заглушкиПеревода'] ?? {}).some(
    (шаблон) => текст === String(шаблон?.['описание'] ?? '').trim(),
  );
}

/**
 * Название статьи без пометки заглушки.
 *
 * Пометка снимается ТОЛЬКО у настоящей заглушки — той, чьё тело программа сама и написала.
 * По одному заголовку судить нельзя: живая статья, названная «Translation placeholder: …»,
 * потеряла бы начало собственного названия.
 *
 * Живёт здесь, а не у зовущих, потому что зовущих стало двое: начало языковой версии и текст
 * заглушки для публикации. Разойдись их мерки, у одной и той же статьи получилось бы два разных
 * заголовка заглушки — «Заглушка перевода: Translation placeholder: Название».
 */
export function названиеБезПометки(title, исходный, settings) {
  let имя = String(title ?? '').trim();
  if (!этоЗаглушка(исходный, settings)) return имя;

  for (const шаблон of Object.values(settings['заглушкиПеревода'] ?? {})) {
    const пометка = String(шаблон?.['заголовок'] ?? '').trim();
    if (пометка !== '' && имя.startsWith(пометка)) имя = имя.slice(пометка.length).trim();
  }

  return имя;
}
