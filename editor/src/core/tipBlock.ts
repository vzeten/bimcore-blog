// Блок «Совет» статьи — директива `:::tip` Docusaurus. Единственное место, где программа знает
// его границы: по этим же правилам блок показывается цельным и вставляется в текст.
//
// Правило смотрит только на начало строки, как соседние правила разметки (`softBreak.ts`,
// `listIndent.ts`), и в спорном случае молчит: незакрытый блок и чужая директива внутри пары
// остаются обычным текстом статьи. Не узнать блок безопаснее, чем спрятать чужие строки.
import {вставкаБлока} from './jsxBlocks';
import type {Edit, Selection} from './commands';

/** Найденный в тексте совет: где его границы и что написано в его собственном заголовке. */
export interface Совет {
  /** Номер строки-открытия, от нуля. */
  открытие: number;
  /** Номер строки-закрытия, от нуля. */
  закрытие: number;
  /** Собственный заголовок из квадратных скобок. `null` — своего заголовка у блока нет. */
  заголовок: string | null;
}

// Синтаксис директив задал Docusaurus, а не владелец: в настройки он не выносится (SPEC 4.4).
// Отступ до трёх пробелов начало блока не отменяет — как и у прочей разметки markdown.
const ОТКРЫТИЕ = /^ {0,3}:::tip(?:\[([^\][\n]*)\])?[ \t]*$/;
const ЗАКРЫТИЕ = /^ {0,3}:::[ \t]*$/;
/** Любая другая директива: чужое открытие внутри пары делает границы совета неоднозначными. */
const ДИРЕКТИВА = /^ {0,3}:::/;

/**
 * Советы текста: только закрытые пары `:::tip` … `:::`.
 * `вКоде` — какие строки лежат внутри огороженного кода: там `:::tip` не директива, а пример.
 */
export function советы(строки: string[], вКоде: boolean[]): Совет[] {
  const найдены: Совет[] = [];

  for (let номер = 0; номер < строки.length; номер += 1) {
    if (вКоде[номер] === true) continue;

    const открытие = ОТКРЫТИЕ.exec(строки[номер]);
    if (открытие === null) continue;

    const закрытие = ближайшееЗакрытие(строки, вКоде, номер + 1);
    if (закрытие === null) continue;

    найдены.push({открытие: номер, закрытие, заголовок: свойЗаголовок(открытие[1])});
    номер = закрытие;
  }

  return найдены;
}

/**
 * Обычное название совета для языка статьи: им подписан блок без собственного заголовка.
 * Своих слов в коде нет — названия приходят из настроек, а язык статьи из её пути. Языка нет
 * в словаре (песочница, чужая папка) — берётся основной язык сайта, тоже из настроек.
 */
export function названиеСовета(
  названия: Record<string, string>,
  локаль: string | null,
  основной: string,
): string {
  return названия[локаль ?? основной] ?? названия[основной] ?? '';
}

/** Строки-границы всех советов. По ним показ знает, где кончается служебная строка. */
export function границыСоветов(строки: string[], вКоде: boolean[]): Set<number> {
  const границы = new Set<number>();
  for (const совет of советы(строки, вКоде)) {
    границы.add(совет.открытие);
    границы.add(совет.закрытие);
  }
  return границы;
}

/**
 * Вставка совета: открытие с заголовком, пустая строка для текста человека и закрытие.
 * Пустые строки вокруг блока ставит то же правило, что и у блоков JSX, — второго правила
 * отступов в программе не заводится. Курсор встаёт на пустую строку внутри: человек сразу пишет.
 */
export function вставкаСовета(текст: string, at: Selection, заголовок: string): Edit {
  const открытие = годныйЗаголовок(заголовок) ? `:::tip[${заголовок.trim()}]` : ':::tip';
  const правка = вставкаБлока(текст, at, `${открытие}\n\n:::`);

  return {...правка, caret: правка.insert.indexOf(открытие) + открытие.length + 1};
}

function ближайшееЗакрытие(строки: string[], вКоде: boolean[], с: number): number | null {
  for (let номер = с; номер < строки.length; номер += 1) {
    if (вКоде[номер] === true) continue;
    if (ЗАКРЫТИЕ.test(строки[номер])) return номер;
    if (ДИРЕКТИВА.test(строки[номер])) return null;
  }

  return null;
}

/** Пустой заголовок — тот же случай, что и его отсутствие: показывать в блоке нечего. */
function свойЗаголовок(записан: string | undefined): string | null {
  const свой = (записан ?? '').trim();
  return свой === '' ? null : свой;
}

/**
 * Заголовок, который переживёт запись в файл. Квадратная скобка внутри оборвала бы директиву
 * на середине, и блок перестал бы быть блоком — тогда совет пишется без своего заголовка,
 * а название ему даёт показ.
 */
function годныйЗаголовок(заголовок: string): boolean {
  return заголовок.trim() !== '' && !/[[\]\n]/.test(заголовок);
}
