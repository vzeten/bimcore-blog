// Смысловой блок статьи — штатная директива Docusaurus. Единственное место, где программа знает
// его границы: по этим же правилам блок показывается цельным и вставляется в текст.
//
// Правило смотрит только на начало строки, как соседние правила разметки (`softBreak.ts`,
// `listIndent.ts`), и в спорном случае молчит: незакрытый блок и чужая директива внутри пары
// остаются обычным текстом статьи. Не узнать блок безопаснее, чем спрятать чужие строки.
import {lineBounds, type Edit, type Selection} from './commands';

export interface Совет {
  тип: string;
  открытие: number;
  закрытие: number;
  заголовок: string | null;
}

// Синтаксис директив задал Docusaurus, а не владелец: в настройки он не выносится (SPEC 4.4).
// Отступ до трёх пробелов начало блока не отменяет — как и у прочей разметки markdown.
const ОТКРЫТИЕ = /^ {0,3}:::(note|tip|info|warning|danger)(?:\[([^\][\n]*)\])?[ \t]*$/;
const ЗАКРЫТИЕ = /^ {0,3}:::[ \t]*$/;
/** Любая другая директива: чужое открытие внутри пары делает границы совета неоднозначными. */
const ДИРЕКТИВА = /^ {0,3}:::/;

/**
 * `вКоде` — какие строки лежат внутри огороженного кода: там `:::tip` не директива, а пример.
 */
export function советы(строки: string[], вКоде: boolean[]): Совет[] {
  const найдены: Совет[] = [];

  for (let номер = 0; номер < строки.length; номер += 1) {
    if (вКоде[номер] === true) continue;

    const открытие = ОТКРЫТИЕ.exec(строки[номер]);
    if (открытие === null) continue;

    const закрытие = ближайшееЗакрытие(строки, вКоде, номер + 1);
    if (закрытие === null) continue;
    if (!ЗАКРЫТИЕ.test(строки[закрытие])) { номер = закрытие; continue; }

    найдены.push({тип: открытие[1], открытие: номер, закрытие, заголовок: свойЗаголовок(открытие[2])});
    номер = закрытие;
  }

  return найдены;
}

export function названияБлоков(
  названия: Record<string, Record<string, string>>,
  локаль: string | null,
  основной: string,
): Record<string, string> {
  return названия[локаль ?? основной] ?? названия[основной] ?? {};
}

export function границыСоветов(строки: string[], вКоде: boolean[]): Set<number> {
  const границы = new Set<number>();
  for (const совет of советы(строки, вКоде)) {
    границы.add(совет.открытие);
    границы.add(совет.закрытие);
  }
  return границы;
}

/**
 * Примечание как оформление выделенного текста. Выделение внутри примечания того же типа снимает
 * его границы, текст остаётся; другого типа — меняет тип, а заголовок, который дала программа,
 * вместе с ним (свой заголовок человека остаётся). Иначе выделенные строки целиком одеваются в
 * границы, и пустая строка отделяет их от соседей. `названия` — названия типов на языке статьи.
 */
export function оформлениеСовета(текст: string, at: Selection, тип: string, названия: Record<string, string>, найденные: Совет[]): Edit | null {
  const открытиеС = (заголовок: string): string => (годныйЗаголовок(заголовок) ? `:::${тип}[${заголовок.trim()}]` : `:::${тип}`);
  const открытие = открытиеС(названия[тип] ?? '');
  if (!ОТКРЫТИЕ.test(открытие)) return null;

  const строки = текст.split('\n');
  const начала = строки.map((_, i) => строки.slice(0, i).reduce((сумма, с) => сумма + с.length + 1, 0));
  const номер = (место: number): number => начала.filter((начало) => начало <= место).length - 1;
  const свой = найденные.find((совет) => совет.открытие < номер(at.from) && номер(at.to) < совет.закрытие);

  if (свой !== undefined) {
    const открытиеОт = начала[свой.открытие];
    const телоОт = начала[свой.открытие + 1];
    const закрытиеДо = начала[свой.закрытие] + строки[свой.закрытие].length;
    const тело = текст.slice(телоОт, начала[свой.закрытие] - 1);
    if (свой.тип !== тип) {
      // Правка покрывает контейнер целиком — только такую пропускает защита служебных строк.
      const своё = свой.заголовок !== null && свой.заголовок !== названия[свой.тип];
      const новое = своё ? открытиеС(свой.заголовок ?? '') : открытие;
      const сдвиг = новое.length - строки[свой.открытие].length;
      return {from: открытиеОт, to: закрытиеДо, insert: `${новое}\n${тело}\n:::`, select: {from: at.from - открытиеОт + сдвиг, to: at.to - открытиеОт + сдвиг}};
    }
    return {from: открытиеОт, to: закрытиеДо, insert: тело, select: {from: at.from - телоОт, to: at.to - телоОт}};
  }

  const границы = lineBounds(текст, at);
  const выделено = текст.slice(границы.from, границы.to);
  const до = границы.from === 0 || строки[номер(границы.from) - 1].trim() === '' ? '' : '\n';
  const после = границы.to === текст.length || строки[номер(границы.to) + 1].trim() === '' ? '' : '\n';
  const начало = до.length + открытие.length + 1;
  return {from: границы.from, to: границы.to, insert: `${до}${открытие}\n${выделено}\n:::${после}`, select: {from: начало, to: начало + выделено.length}};
}

function ближайшееЗакрытие(строки: string[], вКоде: boolean[], с: number): number | null {
  for (let номер = с; номер < строки.length; номер += 1) {
    if (вКоде[номер] === true) continue;
    if (ДИРЕКТИВА.test(строки[номер])) return номер;
  }

  return null;
}

function свойЗаголовок(записан: string | undefined): string | null {
  const свой = (записан ?? '').trim();
  return свой === '' ? null : свой;
}

/**
 * Заголовок, который переживёт запись в файл. Квадратная скобка внутри оборвала бы директиву
 * на середине, и блок перестал бы быть блоком — тогда совет пишется без своего заголовка,
 * а название ему даёт показ.
 */
function годныйЗаголовок(заголовок: string): boolean {
  return заголовок.trim() !== '' && !/[[\]\n]/.test(заголовок);
}
