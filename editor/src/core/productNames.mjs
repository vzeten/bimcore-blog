// Названия товаров, уже записанные в карточках самих статей. Ими список магазина дополняется там,
// где у товара нет названия на языке открытой статьи.
//
// Зачем: в магазине переведены не все названия, а в русских статьях семейств нужное слово человек
// написал давно и своей рукой. Прочитать его — единственный способ не заставлять писать одно и то
// же дважды и не заводить рядом с каталогом ручную таблицу переводов, которая разошлась бы
// со статьями в первый же день.
//
// Читается ровно одно свойство карточки — название. Описание сюда не собирается намеренно: оно
// остаётся свойством СВОЕЙ карточки в своей статье, и одинакового описания у разных статей быть
// не должно. Статьи это правило не меняет вовсе — только читает.
import {тегиТекста} from './jsxTag.mjs';

/** Имена чужого формата: их задали статьи сайта, а не наши настройки (SPEC 4.4). */
const КАРТОЧКА = 'ProductCard';
const КОД = 'ecwidProductId';
const НАЗВАНИЕ = 'name';

/**
 * Названия из статей: код товара → название по языкам. Статья без локали (песочница, черновик
 * вне корней сайта) не даёт слов ни одному языку: приписать её текст языку было бы догадкой.
 */
export function названияИзСтатей(статьи) {
  const поКоду = new Map();

  for (const {локаль, текст} of статьи) {
    if (локаль === null || локаль === undefined) continue;

    for (const тег of тегиТекста(текст)) {
      if (тег.имя !== КАРТОЧКА) continue;

      const код = свойство(тег, КОД);
      const имя = свойство(тег, НАЗВАНИЕ);
      if (код === '' || имя === '') continue;

      const языки = поКоду.get(код) ?? {};
      // Первая встреченная статья языка и остаётся его словом. Разойдись две статьи в названии
      // одного товара — выбирать между ними человеку, а не программе молча при каждом открытии
      // окна; порядок обхода задаёт тот, кто читает файлы, и он одинаков на любой машине.
      if (языки[локаль] === undefined) языки[локаль] = имя;
      поКоду.set(код, языки);
    }
  }

  return поКоду;
}

/**
 * Товары каталога с дополненными названиями. Магазин главнее: он источник каталога, и его слово
 * из статей не переписывается. Из статей берётся только то, чего в магазине нет вовсе или что там
 * пусто, и каждое слово приписано языку своей статьи — подмены одного языка другим не возникает.
 */
export function сНазваниямиСтатей(товары, поКоду) {
  return товары.map((товар) => {
    const изСтатей = поКоду.get(товар.id);
    if (изСтатей === undefined) return товар;

    const названия = {...изСтатей};
    for (const [язык, имя] of Object.entries(товар.названия ?? {})) {
      if (String(имя).trim() !== '') названия[язык] = имя;
    }

    return {...товар, названия};
  });
}

/** Значение свойства тега строкой. Выражение JSX значением названия быть не может. */
function свойство(тег, имя) {
  const найдено = тег.свойства.find((своё) => своё.имя === имя && !своё.выражение);
  return найдено === undefined ? '' : найдено.значение.trim();
}
