// Поиск Google для окна аналитики (ED-054, операция 2): ряды по дням, неделям и месяцам, охват сайта, языка
// или одной страницы, список страниц с разницей 30 дней. Чистые правила: базы, сети и диска здесь нет.
//
// Строка — `{день: 'YYYY-MM-DD', страница: полный адрес, показы, переходы, позиция, неполный: 0|1}`.
// Последние дни Google досчитывает: они показываются, но в сравнение 30/30 не входят — сравнение кончается
// последним ПОЛНЫМ днём (решение владельца в карточке ED-054).

import {адресСтраницы} from './views.mjs';

/** Путь страницы без хоста: `https://learn.bimcore.one/ru/blog/x/` → `/ru/blog/x`. */
export function путьСтраницы(полный) {
  try {
    return адресСтраницы(new URL(полный).pathname);
  } catch {
    return адресСтраницы(полный);
  }
}

/** Язык страницы по префиксу адреса: `/ru/…` → `ru`; без префикса — обязательный язык. */
export function языкСтраницы(путь, языки, обязательный) {
  const первый = путь.split('/')[1] ?? '';
  return языки.includes(первый) && первый !== обязательный ? первый : обязательный;
}

/** Подходит ли строка охвату: `сайт`, код языка или `{страница: путь}`. */
export function вОхвате(строка, охват, {языки, обязательный}) {
  if (охват === 'сайт') return true;
  const путь = путьСтраницы(строка.страница);
  if (typeof охват === 'object' && охват !== null) return путь === адресСтраницы(охват.страница);
  return языкСтраницы(путь, языки, обязательный) === охват;
}

const день = (д) => new Date(`${д}T00:00:00Z`);
const вДень = (дата) => дата.toISOString().slice(0, 10);
export const сдвиг = (д, дни) => вДень(new Date(день(д).getTime() + дни * 86_400_000));

/** Начало шага, в который попадает день: неделя — с понедельника, месяц — с первого числа. */
export function началоШага(д, шаг) {
  if (шаг === 'месяц') return `${д.slice(0, 7)}-01`;
  if (шаг === 'неделя') return сдвиг(д, -((день(д).getUTCDay() + 6) % 7));
  return д;
}

/** Последний полный день: самый поздний день без пометки «неполный». `null` — данных нет. */
export function последнийПолный(строки) {
  let итог = null;
  for (const с of строки) if (!с.неполный && (итог === null || с.день > итог)) итог = с.день;
  return итог;
}

/**
 * Ряд по шагу за дни `с`…`по` включительно: точки без пропусков (пустой шаг — нули), каждая с показами,
 * переходами, средней позицией по показам, теми же числами по языкам (столбик делится на языки, и части
 * в сумме дают ровно столбик) и пометкой «неполный», если в шаг попал неполный день или шаг кончается
 * позже последнего полного дня.
 */
export function ряд(строки, {охват, шаг, с, по, сайт}) {
  const точки = new Map();
  for (let д = началоШага(с, шаг); д <= по;) {
    точки.set(д, {начало: д, показы: 0, переходы: 0, взвешено: 0, неполный: false, языки: {}});
    д = шаг === 'месяц' ? сдвиг(конецШага(д, 'месяц'), 1) : сдвиг(д, шаг === 'неделя' ? 7 : 1);
  }
  const полный = последнийПолный(строки);
  for (const с_ of строки) {
    if (с_.день < с || с_.день > по || !вОхвате(с_, охват, сайт)) continue;
    const точка = точки.get(началоШага(с_.день, шаг));
    if (!точка) continue;
    точка.показы += с_.показы;
    точка.переходы += с_.переходы;
    точка.взвешено += с_.позиция * с_.показы;
    if (с_.неполный) точка.неполный = true;
    const язык = языкСтраницы(путьСтраницы(с_.страница), сайт.языки, сайт.обязательный);
    const поЯзыку = точка.языки[язык] ?? (точка.языки[язык] = {показы: 0, переходы: 0});
    поЯзыку.показы += с_.показы;
    поЯзыку.переходы += с_.переходы;
  }
  return [...точки.values()].map((т) => ({
    начало: т.начало,
    показы: т.показы,
    переходы: т.переходы,
    позиция: т.показы > 0 ? Math.round((т.взвешено / т.показы) * 10) / 10 : null,
    языки: т.языки,
    неполный: т.неполный || (полный !== null && конецШага(т.начало, шаг) > полный),
  }));
}

function конецШага(начало, шаг) {
  if (шаг === 'день') return начало;
  if (шаг === 'неделя') return сдвиг(начало, 6);
  const д = день(начало);
  return вДень(new Date(Date.UTC(д.getUTCFullYear(), д.getUTCMonth() + 1, 0)));
}

/**
 * Страницы охвата за период и разница с предыдущим таким же — в штуках. По умолчанию — 30 полных дней,
 * кончающихся последним полным днём; выбранный на графике период (`период: {с, по}`, ED-054, слово владельца
 * 2026-09-24) сравнивается с предыдущим отрезком той же длины: неделя с прошлой неделей, день с прошлым днём.
 * Неполные дни не входят ни в числа, ни в сравнение.
 */
export function страницы(строки, {охват, сайт, период = null}) {
  const полный = последнийПолный(строки);
  if (полный === null) return {по: null, страницы: []};
  const по = период && период.по < полный ? период.по : полный;
  const с30 = период ? период.с : сдвиг(по, -29);
  const длина = Math.round((день(по) - день(с30)) / 86_400_000) + 1;
  const с60 = сдвиг(с30, -длина);
  const итог = new Map();
  for (const с_ of строки) {
    if (с_.неполный || с_.день > по || с_.день < с60 || !вОхвате(с_, охват, сайт)) continue;
    const путь = путьСтраницы(с_.страница);
    if (!итог.has(путь)) итог.set(путь, {путь, показы: 0, переходы: 0, взвешено: 0, прежниеПоказы: 0, прежниеПереходы: 0});
    const стр = итог.get(путь);
    if (с_.день >= с30) {
      стр.показы += с_.показы;
      стр.переходы += с_.переходы;
      стр.взвешено += с_.позиция * с_.показы;
    } else {
      стр.прежниеПоказы += с_.показы;
      стр.прежниеПереходы += с_.переходы;
    }
  }
  return {
    с: с30,
    по,
    страницы: [...итог.values()].map((стр) => ({
      путь: стр.путь,
      показы: стр.показы,
      переходы: стр.переходы,
      ctr: стр.показы > 0 ? Math.round((стр.переходы / стр.показы) * 1000) / 10 : null,
      позиция: стр.показы > 0 ? Math.round((стр.взвешено / стр.показы) * 10) / 10 : null,
      разницаПоказов: стр.показы - стр.прежниеПоказы,
      разницаПереходов: стр.переходы - стр.прежниеПереходы,
    })),
  };
}
