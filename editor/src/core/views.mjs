// Просмотры статей: чистый подсчёт по строкам отчёта Google Analytics. Диска, сети и git здесь нет.
//
// Строка отчёта — `[адрес страницы, день YYYYMMDD, просмотры]`. Статья — набор адресов всех её языков,
// нынешних и прежних (`адресаДляПросмотров`). Какой адрес какой статье принадлежит, решается один раз
// для всех: адрес, на который претендуют две статьи, не засчитывается ни одной — лучше честный
// недосчёт, чем чужие просмотры в числе статьи (условие контролёра Codex, 2026-09-23).

import {адресВнутриЯзыка, адресВЯзыке} from './siteRoutes.mjs';
import {articlePlace} from './frontmatterRules.mjs';

/**
 * Все адреса статьи, под которыми сайт показывал её страницы, с языком каждого: `Map<адрес, локаль>`.
 *
 * `версии` — нынешние файлы статьи `{путь, текст}`, `прежние` — её прошлые состояния из опубликованной
 * ветки (тот же вид). Адрес считает та же формула, что у публикации (`адресВнутриЯзыка`), по пути и
 * `slug` ОДНОГО файла вместе. Язык без своего файла сайт показывает текстом обязательного языка под
 * своим префиксом (`siteRoutes.mjs`), поэтому такие адреса тоже его: у `/ru/…` свой язык, `ru`.
 */
export function адресаДляПросмотров(версии, прежние, {roots, префиксБлога, обязательный, локали}) {
  const адреса = new Map();
  const своиЯзыки = new Set((версии ?? []).map((версия) => articlePlace(версия.путь, roots).locale));

  for (const версия of [...(версии ?? []), ...(прежние ?? [])]) {
    const свой = адресВнутриЯзыка(версия.путь, версия.текст, roots, префиксБлога);
    if (свой === '') continue;
    const язык = articlePlace(версия.путь, roots).locale;
    const языки = язык === обязательный ? [язык, ...локали.filter((код) => !своиЯзыки.has(код))] : [язык];
    for (const код of языки) адреса.set(адресВЯзыке(свой, код, обязательный), код);
  }

  return адреса;
}

/**
 * Адрес страницы так, как его сравнивает программа: без `?…` и `#…`, без хвостовой косой, с
 * раскрытыми `%xx`. Сайт отдаёт страницы с косой на конце (`trailingSlash: true`), а свои адреса
 * программа держит без неё (`чистыйАдрес` в `siteRoutes.mjs`).
 */
export function адресСтраницы(сырой) {
  let адрес = String(сырой ?? '').split(/[?#]/)[0];
  try {
    адрес = decodeURI(адрес);
  } catch {
    // Битая последовательность `%` — адрес сравнивается как пришёл: чужим он от этого не станет.
  }
  адрес = `/${адрес}`.replace(/\/{2,}/g, '/').replace(/\/+$/, '');
  return адрес === '' ? '/' : адрес;
}

/**
 * Владелец каждого адреса. Вход — статьи `{key, адреса: Map<адрес, локаль>}`. Выход — `Map<адрес,
 * {key, локаль}>` без спорных адресов: спорный адрес исключается целиком, а не отдаётся первой статье.
 */
export function владельцыАдресов(статьи) {
  const владельцы = new Map();
  const спорные = new Set();

  for (const статья of статьи ?? []) {
    for (const [сырой, локаль] of статья.адреса ?? []) {
      const адрес = адресСтраницы(сырой);
      const прежний = владельцы.get(адрес);
      if (прежний === undefined) владельцы.set(адрес, {key: статья.key, локаль});
      else if (прежний.key !== статья.key) спорные.add(адрес);
    }
  }

  for (const адрес of спорные) владельцы.delete(адрес);
  return владельцы;
}

/** День `YYYYMMDD` плюс `дни` (может быть отрицательным). Счёт по UTC: у дня нет часового пояса. */
export function сдвигДня(день, дни) {
  const д = new Date(Date.UTC(Number(день.slice(0, 4)), Number(день.slice(4, 6)) - 1, Number(день.slice(6, 8)) + дни));
  return `${д.getUTCFullYear()}${String(д.getUTCMonth() + 1).padStart(2, '0')}${String(д.getUTCDate()).padStart(2, '0')}`;
}

/** Первый день месяца за `назад` месяцев до месяца дня `день`. */
export function началоМесяца(день, назад = 0) {
  const д = new Date(Date.UTC(Number(день.slice(0, 4)), Number(день.slice(4, 6)) - 1 - назад, 1));
  return `${д.getUTCFullYear()}${String(д.getUTCMonth() + 1).padStart(2, '0')}01`;
}

/**
 * Отчётный период для запроса к Google: «за всё время» — от дня `сНачала` (с него Google считает
 * просмотры сайта), но не позже, чем нужно году по месяцам (12 полных плюс текущий) и 60 дням
 * сравнения; конец — последний полный день `поДень`.
 */
export function периодОтчёта(поДень, месяцев, сНачала = поДень) {
  const с = [сНачала, началоМесяца(поДень, месяцев), сдвигДня(поДень, -59)].sort()[0];
  return {с, по: поДень};
}

/**
 * Числа всех статей по строкам отчёта: `всего` — за весь отчёт, `за30`/`прежние30` — для разницы,
 * `языки` — те же 30 дней по языкам, `месяцы` — помесячно и по языкам. `поДень` — последний полный
 * день отчёта; `месяцев` — сколько полных месяцев показать перед текущим. Статья без единого
 * засчитанного адреса в ответ не попадает: у неё нет адреса на сайте, и окно ставит прочерк, а не ноль.
 */
export function просмотрыСтатей({строки, статьи, поДень, месяцев, языки}) {
  const владельцы = владельцыАдресов(статьи);
  const с30 = сдвигДня(поДень, -29);
  const с60 = сдвигДня(поДень, -59);
  const месяцы = Array.from({length: месяцев + 1}, (_, номер) => началоМесяца(поДень, месяцев - номер).slice(0, 6));

  const итог = {};
  for (const статья of статьи ?? []) {
    const есть = [...(статья.адреса ?? new Map()).keys()].some((адрес) => владельцы.get(адресСтраницы(адрес))?.key === статья.key);
    if (!есть) continue;
    const поЯзыкам = () => Object.fromEntries(языки.map((код) => [код, 0]));
    итог[статья.key] = {
      всего: 0,
      за30: 0,
      прежние30: 0,
      языки: поЯзыкам(),
      месяцы: месяцы.map((месяц) => ({месяц, просмотры: 0, языки: поЯзыкам()})),
    };
  }

  for (const [сырой, день, число] of строки ?? []) {
    const владелец = владельцы.get(адресСтраницы(сырой));
    const числа = владелец && итог[владелец.key];
    const просмотры = Number(число);
    if (!числа || !Number.isFinite(просмотры) || день > поДень) continue;

    числа.всего += просмотры;
    if (день >= с30) {
      числа.за30 += просмотры;
      if (владелец.локаль in числа.языки) числа.языки[владелец.локаль] += просмотры;
    } else if (день >= с60) {
      числа.прежние30 += просмотры;
    }

    const месяц = числа.месяцы.find((строка) => строка.месяц === день.slice(0, 6));
    if (месяц) {
      месяц.просмотры += просмотры;
      if (владелец.локаль in месяц.языки) месяц.языки[владелец.локаль] += просмотры;
    }
  }

  return итог;
}

/**
 * Изменение 30 дней против предыдущих 30 в процентах, целым числом. `null` — сравнивать не с чем:
 * в прошлом периоде просмотров не было, и «плюс бесконечность процентов» человеку ничего не скажет.
 */
export function изменение(за30, прежние30) {
  if (!(прежние30 > 0)) return null;
  return Math.round(((за30 - прежние30) / прежние30) * 100);
}
