// Куда встаёт новая картинка: чистое правило от текста и позиции курсора.
//
// Место задаёт курсор человека, но картинка обязана лечь отдельным блоком: разметка `![](…)`
// посреди слова, внутри строки таблицы или приклеенная к абзацу — это уже не «картинка здесь»,
// а порча текста и другой вид на сайте. Поэтому вставка идёт на ближайшую границу той
// конструкции, в которой стоит курсор, и вокруг неё обеспечивается пустая строка.
//
// Правило чистое и проверяется тестом без редактора: результат — текст и позиции.

/** Готовая вставка: что дописать, где окажется сам узел и куда поставить курсор. */
export interface ВставкаКартинки {
  /** Куда дописать. Диапазон нулевой: выделенный человеком текст не заменяется и не пропадает. */
  from: number;
  insert: string;
  /** Границы узла картинки в тексте ПОСЛЕ вставки — по ним открывается панель alt-текста. */
  узелОт: number;
  узелДо: number;
  /** Куда встанет курсор: на пустую строку под картинкой, чтобы дальше просто писать текст. */
  курсор: number;
}

/** Вид строки. Разные виды не сливаются в один блок: заголовок с абзацем не одно и то же. */
type Вид = 'пустая' | 'заголовок' | 'таблица' | 'список' | 'цитата' | 'код' | 'текст';

interface Строка {
  от: number;
  /** Конец текста строки — до перевода строки и до хвостового `\r` (файл бывает в windows-виде). */
  до: number;
  текст: string;
  вид: Вид;
  /** Номер конструкции: строки одной конструкции (абзаца, списка, таблицы, ограды) делят его. */
  группа: number;
}

/**
 * Место новой картинки. `курсор` — позиция каретки, `src` — адрес файла, `перевод` — перевод
 * строки этого файла (`\n` или `\r\n`): вставлять свой вид переводов в чужой файл нельзя.
 */
export function местоВставкиКартинки(
  текст: string,
  курсор: number,
  src: string,
  перевод: string,
): ВставкаКартинки {
  const строки = разобрать(текст);
  const место = Math.max(0, Math.min(курсор, текст.length));
  const номер = строкаПозиции(строки, место);
  const узел = `![](${src})`;

  const {первая, последняя} = блок(строки, номер);
  // Курсор ровно в начале блока — человек показал место ПЕРЕД ним; иначе картинка встаёт после
  // блока. Так вставка не уезжает в начало или конец статьи и не рвёт конструкцию посередине.
  const пустая = строки[номер].вид === 'пустая';
  const доБлока = !пустая && место === строки[первая].от;

  const якорь = пустая ? строки[номер].от : доБлока ? строки[первая].от : строки[последняя].до;
  const предыдущая = строки[(пустая ? номер : первая) - 1];
  const следующая = строки[(пустая ? номер : последняя) + 1];
  const соседСверху = предыдущая !== undefined && предыдущая.вид !== 'пустая';
  const соседСнизу = следующая !== undefined && следующая.вид !== 'пустая';

  // Пустая строка нужна с обеих сторон: без неё картинка попадает в тот же абзац, что соседний
  // текст, и на сайте перестаёт быть отдельным блоком.
  // Вставка ПОСЛЕ блока встаёт в конец его последней строки, поэтому первый перевод закрывает
  // эту строку, а второй даёт пустую; вставка ПЕРЕД блоком — наоборот.
  const до = доБлока || пустая ? (соседСверху ? перевод : '') : перевод + перевод;
  const после = доБлока ? перевод + перевод : соседСнизу ? перевод : '';

  // Картинка в самом конце статьи: под ней заводится строка, иначе дописывать текст негде.
  const хвост = якорь === текст.length && после === '' ? перевод : '';
  const insert = `${до}${узел}${после}${хвост}`;
  const узелОт = якорь + до.length;
  const узелДо = узелОт + узел.length;

  return {
    from: якорь,
    insert,
    узелОт,
    узелДо,
    // Курсор уходит на строку под картинкой: на самой строке картинки места для текста нет —
    // курсор туда не встаёт вовсе (правило пустых карманов).
    курсор: узелДо + переводПосле(`${после}${хвост}`, текст.slice(якорь), перевод),
  };
}

/**
 * Длина перевода строки, который окажется сразу за узлом: своего (мы его и дописали) либо уже
 * стоявшего в файле. Считается по факту, а не по виду переводов файла: в чужом файле встречается
 * и одинокий `\r\n` среди `\n`, и курсор не должен оказаться посреди перевода строки.
 */
function переводПосле(свой: string, остаток: string, перевод: string): number {
  if (свой.startsWith(перевод)) return перевод.length;
  if (свой !== '') return 0;
  if (остаток.startsWith('\r\n')) return 2;
  return остаток.startsWith('\n') ? 1 : 0;
}

/**
 * Строки текста: вид каждой и номер конструкции, которой она принадлежит. Номер считается один
 * раз сверху вниз — так строка-продолжение пункта списка попадает в тот же блок, что и сам пункт,
 * с какой бы стороны на неё ни посмотрели.
 */
function разобрать(текст: string): Строка[] {
  const строки: Строка[] = [];
  let от = 0;
  let группа = 0;
  /** Что за конструкция идёт сейчас: с ней сравнивается каждая следующая строка. */
  let конструкция: Вид | null = null;
  /** Открытая ограда: её знак и длина. Закрыть её может только такая же или длиннее. */
  let ограда: {знак: string; длина: number} | null = null;

  for (const кусок of текст.split('\n')) {
    const чистый = кусок.replace(/\r$/, '');
    const до = от + чистый.length;
    const край = /^\s*(`{3,}|~{3,})/.exec(чистый);

    if (ограда !== null) {
      // Внутри ограды всё — код, включая пустые строки. Закрывает её только строка из тех же
      // знаков не короче открывающей: `` ``` `` внутри `~~~~` — это код, а не конец куска.
      строки.push({от, до, текст: чистый, вид: 'код', группа});
      // Закрывает ограду только строка из тех же знаков не короче открывающей и без хвоста:
      // подпись языка (```js) бывает лишь у открывающей, а строка ```js внутри куска — это код.
      if (край !== null && край[1][0] === ограда.знак && край[1].length >= ограда.длина
        && чистый.slice(край[0].length).trim() === '') {
        ограда = null;
        конструкция = null;
      }
    } else if (край !== null) {
      ограда = {знак: край[1][0], длина: край[1].length};
      группа += 1;
      конструкция = 'код';
      строки.push({от, до, текст: чистый, вид: 'код', группа});
    } else {
      const свой = вид(чистый);
      if (!продолжает(свой, конструкция)) {
        группа += 1;
        конструкция = свой;
      }
      строки.push({от, до, текст: чистый, вид: свой, группа});
    }

    от = от + кусок.length + 1;
  }

  return строки;
}

/** Вид строки по её началу — так же, как его читает разметка markdown. */
function вид(строка: string): Вид {
  const начало = строка.trim();
  if (начало === '') return 'пустая';
  if (/^#{1,6}\s/.test(начало)) return 'заголовок';
  if (начало.startsWith('|')) return 'таблица';
  if (/^([-*+]\s|\d+[.)]\s)/.test(начало)) return 'список';
  if (начало.startsWith('>')) return 'цитата';
  return 'текст';
}

/**
 * Номер строки, в которой стоит курсор. Граница строк принадлежит той строке, что выше — включая
 * место между `\r` и `\n` в файле windows-вида: иначе курсор в конце такой строки считался бы
 * стоящим уже в следующей, и картинка уехала бы через блок.
 */
function строкаПозиции(строки: Строка[], место: number): number {
  for (let i = 0; i < строки.length; i += 1) {
    if (место <= строки[i].до) return i;
    if (строки[i + 1] !== undefined && место < строки[i + 1].от) return i;
  }

  return строки.length - 1;
}

/**
 * Границы конструкции, в которой стоит курсор: соседние строки с тем же номером группы.
 * Пустая строка сама себе граница; огороженный код берётся целиком; заголовок — одна строка;
 * таблица, список и цитата тянутся своими строками; абзац — соседними строками обычного текста.
 *
 * Именно вид строки, а не только пустая строка между блоками: в живых статьях заголовок,
 * абзац, список и таблица идут вплотную, и по одним пустым строкам картинка уехала бы
 * далеко от места, которое выбрал человек.
 */
function блок(строки: Строка[], номер: number): {первая: number; последняя: number} {
  const группа = строки[номер].группа;
  let первая = номер;
  let последняя = номер;

  while (первая > 0 && строки[первая - 1].группа === группа) первая -= 1;
  while (последняя < строки.length - 1 && строки[последняя + 1].группа === группа) последняя += 1;

  return {первая, последняя};
}

/**
 * Продолжает ли строка идущую конструкцию. Пустая строка и заголовок не продолжают ничего
 * и ничем не продолжаются. Обычный текст продолжает список и цитату: так записан длинный пункт,
 * перенесённый на вторую строку, — и картинка не должна разрезать его пополам. Сравнение идёт
 * с конструкцией, а не с прошлой строкой: иначе список из пунктов с продолжениями распался бы
 * на куски, и картинка легла бы между его пунктами.
 */
function продолжает(свой: Вид, конструкция: Вид | null): boolean {
  if (конструкция === null || свой === 'пустая' || свой === 'заголовок') return false;
  if (конструкция === 'пустая' || конструкция === 'заголовок' || конструкция === 'код') return false;
  if (свой === конструкция) return true;

  return свой === 'текст' && (конструкция === 'список' || конструкция === 'цитата');
}
