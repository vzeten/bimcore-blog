// Разбор и сборка файла статьи. Единственное место, где это правило записано.
// Главное требование: открыть и сохранить без правок — файл не меняется ни на байт.
// Поэтому шапка хранится ровно тем куском текста, каким была в файле.

// Невидимая метка в начале файла: её оставляют Windows-редакторы. Это байты файла, а не текст статьи,
// поэтому она не настройка, а часть чужого формата. Без неё разбор шапки промахивается,
// и вся шапка уезжает в тело статьи.
const МЕТКА = '\uFEFF';

export function splitArticle(raw) {
  const метка = String(raw).startsWith(МЕТКА) ? МЕТКА : '';
  const text = String(raw).slice(метка.length);
  const match = /^---\r?\n[\s\S]*?\r?\n---\r?\n?/.exec(text);
  if (!match) return {head: '', frontmatterRaw: '', body: raw, eol: dominantEol(raw), метка};

  const inner = /^---\r?\n([\s\S]*?)\r?\n---/.exec(match[0]);

  return {
    head: метка + match[0],
    frontmatterRaw: inner ? inner[1] : '',
    body: text.slice(match[0].length),
    eol: dominantEol(raw),
    метка,
  };
}

export function joinArticle({head, body}) {
  return head + body;
}

/**
 * Собрать шапку обратно в текст файла. Правило живёт здесь, а не в сервере:
 * иначе невидимая метка и вид перевода строки теряются при сохранении.
 */
export function buildHead({frontmatterRaw, eol, метка = ''}) {
  // Хвостовой `\r` здесь НЕ снимается, хотя вместе со следующим переводом строки он даёт `\r\r\n`.
  // Снять его значило бы переписать файл при одном только «открыл и сохранил» (SPEC 5.1).
  // Порча лечится там, где рождается — при правке шапки и при переключении видимости, — а разбор
  // шапки её переживает: строка читается через `headLine`.
  return `${метка}---${eol}${frontmatterRaw}${eol}---${eol}`;
}

/** Какой перевод строки в файле главный. Нужен, чтобы вернуть текст из редактора в том же виде. */
export function dominantEol(raw) {
  const crlf = (raw.match(/\r\n/g) || []).length;
  const lf = (raw.match(/(?<!\r)\n/g) || []).length;
  return crlf > lf ? '\r\n' : '\n';
}

/** Совпадает ли текст с точностью до переводов строк. */
export function sameText(a, b) {
  return a.replace(/\r\n/g, '\n') === b.replace(/\r\n/g, '\n');
}

/**
 * Изменилось ли в статье хоть что-нибудь.
 * Смотреть только на тело нельзя: тогда правка одной шапки молча теряется.
 */
export function nothingChanged(current, next) {
  return sameText(current.body, next.body) && sameText(current.frontmatterRaw, next.frontmatterRaw);
}

/**
 * Шапка построчно, как она лежит в файле. Единственное место, где шапка режется на строки:
 * все разборы обязаны видеть одни и те же строки.
 */
export function headLines(raw) {
  return String(raw ?? '').split(/\r?\n/);
}

/**
 * Строка без одинокого `\r` на конце — так её и надо разбирать.
 *
 * Такой `\r` встречается в файлах, которые правились с windows-переводами строк, и это часть
 * перевода строки, а не значения поля. Без снятия строка `image: ./cover.png\r` перестаёт
 * считаться полем вовсе: поле пропадает из окна вместе с возможностью его изменить.
 *
 * Разбирать очищенную строку, а возвращать в файл исходную — не прихоть: нетронутое поле
 * обязано вернуться дословно, иначе одно только открытие статьи переписывало бы файл (SPEC 5.1).
 */
export function headLine(line) {
  return String(line ?? '').replace(/\r+$/, '');
}

/**
 * Значение без кавычек — то, что прочитал бы сам YAML: у двойных кавычек снимается и
 * экранирование. Единственное место правила: им пользуется и чтение поля по имени, и разбор
 * шапки в человеческий вид. Разойдись они — заголовок с кавычкой показывался бы в свойствах
 * статьи чисто, а в списке статей и в шапке окна с обратными слешами.
 */
export function безКавычек(значение) {
  const текст = String(значение ?? '');
  if (текст.length > 1 && текст.startsWith('"') && текст.endsWith('"')) {
    return текст.slice(1, -1).replace(/\\(["\\])/g, '$1');
  }
  // В одиночных кавычках YAML экранирует апостроф удвоением: `'it''s'` читается как `it's`.
  // Вне кавычек он этого не делает, поэтому и мы не делаем: `it''s` там так и остаётся.
  const одиночные = /^'(.*)'$/s.exec(текст);
  return одиночные ? одиночные[1].replace(/''/g, "'") : текст;
}

export function readField(frontmatterRaw, field) {
  const line = headLines(frontmatterRaw).map(headLine).find((item) => item.startsWith(`${field}:`));
  if (!line) return '';
  return безКавычек(line.slice(field.length + 1).trim());
}
