// Создание статьи: адрес из названия и план записи файлов.
// Чистые правила без диска: что и куда ляжет, решается здесь, а пишет адаптер.
// Ошибка тут роняет сборку всего сайта, поэтому проверки идут ДО записи, а не после.

import {normalizeSlug} from './frontmatterRules.mjs';

/**
 * Кириллица в латиницу. Своя таблица, а не библиотека: готовые средства кириллицы не знают
 * (SPEC 3.7), а адрес после публикации не меняется без переадресации — ошибиться нельзя.
 */
const БУКВЫ = {
  а: 'a', б: 'b', в: 'v', г: 'g', д: 'd', е: 'e', ё: 'e', ж: 'zh', з: 'z', и: 'i', й: 'y',
  к: 'k', л: 'l', м: 'm', н: 'n', о: 'o', п: 'p', р: 'r', с: 's', т: 't', у: 'u', ф: 'f',
  х: 'h', ц: 'c', ч: 'ch', ш: 'sh', щ: 'sch', ъ: '', ы: 'y', ь: '', э: 'e', ю: 'yu', я: 'ya',
};

/**
 * Адрес из названия: только латиница, цифры и дефис.
 * Пусто на выходе — это не повод придумать «new-article»: выдуманный адрес останется в сайте
 * навсегда, поэтому пустая строка возвращается как есть, а спросит человека уже интерфейс.
 */
export function адресИзНазвания(название) {
  return String(название ?? '')
    .toLowerCase()
    .split('')
    .map((знак) => (знак in БУКВЫ ? БУКВЫ[знак] : знак))
    .join('')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

/** Годен ли адрес для сайта: латиница, цифры и дефис, не пустой, не служебное имя. */
export function адресГоден(адрес) {
  return /^[a-z0-9]+(-[a-z0-9]+)*$/.test(String(адрес ?? ''));
}

/**
 * Название внутри кавычек: экранируются слеш и кавычка, переводы строк схлопываются.
 * Иначе название вроде `C:\Revit` или с переносом даёт негодный YAML, и статья перестаёт
 * разбираться вовсе.
 */
function безопасное(title) {
  return String(title).replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\s+/g, ' ').trim();
}

/**
 * Шапка новой статьи. Набор полей — из настроек по роду раздела: у урока он один, у блога другой,
 * и меняться он будет без правки кода (SPEC 4.4).
 *
 * Пустое значение не пишется вовсе: пустой `image` роняет сборку (SPEC 2.1), а пустое описание
 * человеку всё равно заполнять — лишняя строка только мешает.
 */
function шапка({род, title, slug, settings, сегодня}) {
  // Набора для рода нет — это дефект настроек, а не повод молча взять чужой: статья получила бы
  // не те поля, и человек узнал бы об этом на сборке сайта.
  const набор = settings['поляСоздания'][род];
  const строки = [];

  for (const поле of набор['порядок']) {
    const значение = поле === 'title' || поле === 'sidebar_label' ? `"${безопасное(title)}"`
      : поле === 'slug' ? slug
      // Место в меню: первое, дальше человек двигает сам. Считать «следующий свободный номер»
      // здесь нечем — план не читает диск.
      : поле === 'sidebar_position' ? '1'
      : поле === 'date' ? сегодня
      // Статья рождается видимой только по ссылке: файлы попадают в репозиторий сразу,
      // и недописанная статья не должна оказаться в меню.
      : поле === 'unlisted' ? 'true'
      : набор['значения'][поле] ?? '';

    // Пустым остаётся только то, что человек допишет сам. Исключение — картинка: пустое поле
    // роняет сборку (SPEC 2.1), поэтому без значения его нет вовсе.
    if (значение !== '' || поле !== 'image') строки.push(`${поле}: ${значение}`);
  }

  return `---\n${строки.join('\n')}\n---\n`;
}

/**
 * Где лежит статья этой локали: тот же путь внутри своего корня, что и у основной версии.
 * Реестр сшивает языковые версии ПО ПУТИ, а не по адресу: разойдись пути хоть на букву —
 * и программа покажет две статьи вместо одной.
 */
function путьВерсии(корень, внутри) {
  return `${корень['папка']}/${внутри}`;
}

/**
 * План создания статьи: что и куда записать. Ничего не пишет и не читает диск —
 * решение принимается целиком, до первой записи, иначе можно оставить статью-калеку.
 *
 * `раздел` — имя узла дерева: род и папки над статьёй, например `docs/lessons`.
 * `язык` — на каком языке пишется статья. Пусто — основной язык из настроек.
 */
export function планСоздания({раздел, название, адрес, язык, settings}) {
  const roots = settings['контент'];
  // Дата публикации нужна блогу: без неё Docusaurus не соберёт запись.
  const сегодня = местнаяДата();

  // Раздел приходит от клиента тем же именем, каким он назван в дереве. Пути файловой системы
  // окно не знает и знать не должно. Проверка идёт первой: `..` и обратные слеши увели бы
  // запись за пределы своего корня.
  const имяРаздела = String(раздел ?? '').trim();
  const плохоеИмя = имяРаздела === ''
    || имяРаздела.includes('\\')
    || имяРаздела.startsWith('/')
    || /(^|\/)\.\.?(\/|$)/.test(имяРаздела);
  if (плохоеИмя) return {ошибка: 'плохойРаздел'};

  const [род, ...папки] = имяРаздела.split('/');
  if (!settings['поляСоздания'][род]) return {ошибка: 'нетПолейРода'};

  // На каком языке пишем. Песочница живёт вне сайта, и правило обязательного английского
  // её не касается: там создаётся только своя версия.
  const хочу = String(язык ?? '').trim() || settings['основнойЯзык'];
  // Выбранного языка в этом разделе может не быть — например, песочница живёт только на одном.
  // Молча подменить язык нельзя: человек выбрал английский, а получил бы русскую статью
  // и узнал бы об этом только по шапке окна.
  if (!roots.some((root) => root['род'] === род)) return {ошибка: 'плохойРаздел'};
  const свой = roots.find((root) => root['род'] === род && root['локаль'] === хочу);
  if (!свой) return {ошибка: 'нетЯзыкаВРазделе'};

  const имя = String(название ?? '').trim();
  if (имя === '') return {ошибка: 'нетНазвания'};

  const slug = String(адрес ?? '').trim() || адресИзНазвания(имя);
  if (!адресГоден(slug)) return {ошибка: 'нетАдреса'};

  // Папка статьи — её адрес: так статья и её картинки лежат рядом (SPEC 1.3).
  const внутри = [...папки, slug, 'index.mdx'].join('/');

  const основной = свой['локаль'];
  // Английская заглушка обязательна для любой неанглийской статьи: без английской версии
  // статьи на сайте не существует вовсе, молча (SPEC 2.4). Пишем сразу на английском —
  // заглушка не нужна, статья и есть английская.
  const обязательные = свой['наСайте'] === true
    ? roots.filter((root) => root['род'] === род && [основной, settings['обязательныйЯзык']].includes(root['локаль']))
    : [свой];

  const файлы = обязательные.map((корень) => {
    const path = путьВерсии(корень, внутри);
    const свояЛокаль = корень['локаль'] === основной;
    const title = свояЛокаль ? имя : `${settings['заглушкаПеревода']['заголовок']} ${имя}`;

    return {
      path,
      локаль: корень['локаль'],
      заглушка: !свояЛокаль,
      // Адрес общий для всех языков и без локали: её добавляет сам сайт (SPEC 2.5).
      text: шапка({род, title, slug: normalizeSlug(path, slug, roots), settings, сегодня})
        + (свояЛокаль ? '\n' : `\n${settings['заглушкаПеревода']['тело']}\n`),
    };
  });

  // Состояние версии планируется здесь же, а не дописывается адаптером: иначе появится второе
  // место, знающее, из чего состоит новая статья. Без состояния реестр покажет у только что
  // созданной статьи автора «Неизвестный».
  const состояния = файлы.map((файл) => ({
    path: файл.path.replace(/[^/]+$/, settings['хранение']['файлСостояния']),
    text: черновик(settings),
  }));

  return {slug, файлы, состояния, локаль: основной};
}

/**
 * Сегодняшняя дата местного времени. По UTC около полуночи вышел бы вчерашний день,
 * а дата публикации у блога — это день по календарю человека, а не по Гринвичу.
 */
function местнаяДата() {
  const сейчас = new Date();
  const два = (число) => String(число).padStart(2, '0');
  return `${сейчас.getFullYear()}-${два(сейчас.getMonth() + 1)}-${два(сейчас.getDate())}`;
}

/** Состояние новой версии: черновик, ничего не опубликовано, обсуждений нет. */
function черновик(settings) {
  return `${JSON.stringify({готовность: settings['статусы'][0], опубликованныйКоммит: null, нити: []}, null, 2)}\n`;
}
