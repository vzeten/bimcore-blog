// Проверка перечня языков для каркаса публикации (`publishPlan.mjs`). Отдельным файлом: каркас упёрся
// в предел размера (SPEC 4.9), а правило «перечень описывает именно эту статью» — одно целое.

import {годныйПутьПлана} from './planPath.mjs';

/**
 * Что не так с перечнем языков. `null` — всё в порядке.
 *
 * `отмеченные` — версии, которые публикуются этой записью (этап 3: одна или несколько по галочкам
 * окна). `свои` — пути всех их собственных файлов.
 *
 * Перечень — единственное, чем правило знает, каких файлов не хватает на сайте, и одновременно
 * единственный источник путей, куда лягут созданные заглушки. Поэтому он проверяется целиком:
 * пустой отменил бы защиту молча, а повтор или чужой путь позволили бы заглушке лечь поверх работы
 * человека или вовсе мимо репозитория.
 */
export function бедаПеречня(языки, отмеченные, свои) {
  if (!Array.isArray(языки) || языки.length === 0) return {чего: 'языки', локали: []};

  const своиЯзыки = new Map(отмеченные.map((версия) => [версия.локаль, версия.путь]));
  const локали = new Set();
  const пути = new Set();

  for (const язык of языки) {
    const локаль = язык?.локаль;
    if (typeof локаль !== 'string' || локаль === '' || локали.has(локаль)) {
      return {чего: 'языки', локали: typeof локаль === 'string' ? [локаль] : []};
    }
    локали.add(локаль);

    if (!годныйПутьПлана(язык?.путь)) return {чего: 'путь', локали: [локаль]};
    // Два языка с одним путём: заглушка одного легла бы поверх другого.
    if (пути.has(язык.путь)) return {чего: 'столкновение', локали: [локаль]};
    пути.add(язык.путь);

    if (своиЯзыки.has(локаль)) {
      // Перечень описывает не ту статью, что публикуется. Дальше считать нечего: чужие пути увели бы
      // заглушки к посторонней статье.
      if (язык.путь !== своиЯзыки.get(локаль)) return {чего: 'своя', локали: [локаль]};
      continue;
    }

    // Спросить опубликованную ветку не удалось. «Не знаю» — не «нет»: приняв незнание за отсутствие,
    // программа переписала бы заглушкой живой перевод, который на сайте уже стоит.
    if (язык.опубликован !== true && язык.опубликован !== false) {
      return {чего: 'опубликованная', локали: [локаль]};
    }

    // Путь чужого языка совпал с файлом публикуемой версии — её картинкой или готовностью.
    // Заглушка стёрла бы работу человека прямо в коммите.
    if (свои.has(язык.путь)) return {чего: 'столкновение', локали: [локаль]};
  }

  // Публикуемого языка в перечне нет: значит перечень не про этот род, и молчание о нём означало бы
  // «соседей не нужно» — то есть отмену защиты целиком.
  const нет = [...своиЯзыки.keys()].filter((локаль) => !локали.has(локаль));
  return нет.length === 0 ? null : {чего: 'языки', локали: [нет[0]]};
}
