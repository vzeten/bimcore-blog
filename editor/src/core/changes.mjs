// События «Действия» (ED-054): какие изменения первой линии серверной `main` считаются изменениями статей
// сайта и как из вывода git получается запись. Чистые правила: диска, сети и git здесь нет.
//
// Событие — изменение, ДОШЕДШЕЕ до серверной `main`, а не доказанная выкладка на сайт (условие контролёра
// Codex): выкладка может сорваться, а дата коммита не равна времени отправки. Поэтому у записи две даты:
// дата коммита и время, когда программа его увидела.

import {articlePlace} from './frontmatterRules.mjs';
import {файлСтатьи, служебноеИмя} from './articles.mjs';

/** Разделитель полей строки коммита в выводе git. Внутренний договор с git, а не настройка. */
export const РАЗДЕЛИТЕЛЬ = '\u001f';

/**
 * Файл статьи сайта: лежит в корне контента `наСайте`, имя — статья (`.md`/`.mdx`), ни одна часть пути
 * не служебная (`_category_.json`, `_state.json`, `.папка` сайт не собирает). Картинки статьёй не считаются.
 */
export function статьяСайта(путь, roots) {
  const место = articlePlace(String(путь ?? ''), roots);
  if (!место.наСайте) return false;
  const части = место.inside.split('/');
  return файлСтатьи(части[части.length - 1]) && !части.some((часть) => служебноеИмя(часть));
}

/**
 * Номер правил разбора. Смена номера — история разбирается заново с начала (ключ коммит+путь не удваивает
 * записей, описания не затираются). 2 — изображения статей (слово владельца 2026-09-24).
 */
export const ПРАВИЛА_РАЗБОРА = '2';

/**
 * Изображение сайта: лежит в корне контента `наСайте`, картинка по расширению, ни одна часть пути не служебная.
 * Своей статьёй не бывает — к статье его привязывает `changeEvents.mjs` по папке и ссылке в тексте.
 */
export function изображениеСайта(путь, roots) {
  const место = articlePlace(String(путь ?? ''), roots);
  if (!место.наСайте) return false;
  const части = место.inside.split('/');
  return /\.(png|jpe?g|webp|gif|svg|avif)$/i.test(части[части.length - 1]) && !части.some((часть) => служебноеИмя(часть));
}

/**
 * Разница изображений одной статьи для показа: новое — `+имя`, убранное — `-имя`, заменённое — обе строки.
 * Счёт — как у строк текста: добавлено новые и заменённые, убрано убранные и заменённые.
 */
export function разницаИзображений(список) {
  const строки = [];
  let добавлено = 0;
  let убрано = 0;
  for (const {путь, вид} of [...список].sort((а, б) => а.путь.localeCompare(б.путь))) {
    const имя = путь.split('/').pop();
    if (вид !== 'добавлено') {
      строки.push(`-${имя}`);
      убрано += 1;
    }
    if (вид !== 'удалено') {
      строки.push(`+${имя}`);
      добавлено += 1;
    }
  }
  return {дельта: `${строки.join('\n')}\n`, добавлено, убрано};
}

const ВИД = {A: 'добавление', M: 'правка', D: 'удаление', R: 'переименование'};

/**
 * Разбор `git show --diff-merges=first-parent --name-status -M` (или `log` с теми же ключами) с форматом
 * `@%H␟%an␟%cI`: коммиты по порядку вывода и изменения статей в каждом. Переименование — одна запись со
 * старым и новым путём; если статьёй была только одна из сторон, запись остаётся по той, что статья (переезд в служебное — удаление, обратно —
 * добавление). Слияние git с `-m --first-parent` показывает один раз — против первого родителя.
 */
export function разобратьЛог(вывод, roots) {
  const коммиты = [];
  let текущий = null;
  const видели = new Set();

  for (const строка of String(вывод ?? '').split('\n')) {
    if (строка.startsWith('@')) {
      const [коммит, автор, дата] = строка.slice(1).split(РАЗДЕЛИТЕЛЬ);
      текущий = {коммит: коммит.trim(), автор: автор ?? '', дата: (дата ?? '').trim(), изменения: [], изображения: []};
      коммиты.push(текущий);
      continue;
    }
    if (!текущий || строка.trim() === '') continue;

    const [код, первый, второй] = строка.split('\t');
    const буква = код?.[0];
    if (!ВИД[буква] && буква !== 'C') continue;

    // Изображения — отдельным списком: новое, заменённое, убранное; переезд и копия — убрано там (у переезда)
    // и новое здесь.
    if (буква === 'R' || буква === 'C') {
      if (буква === 'R' && изображениеСайта(первый, roots)) текущий.изображения.push({путь: первый, вид: 'удалено'});
      if (изображениеСайта(второй, roots)) текущий.изображения.push({путь: второй, вид: 'добавлено'});
    } else if (изображениеСайта(первый, roots)) {
      текущий.изображения.push({путь: первый, вид: буква === 'A' ? 'добавлено' : буква === 'D' ? 'удалено' : 'заменено'});
    }

    let изменение;
    if (буква === 'R') {
      const было = статьяСайта(первый, roots);
      const стало = статьяСайта(второй, roots);
      if (было && стало) изменение = {вид: ВИД.R, путь: второй, прежнийПуть: первый};
      else if (стало) изменение = {вид: ВИД.A, путь: второй, прежнийПуть: null};
      else if (было) изменение = {вид: ВИД.D, путь: первый, прежнийПуть: null};
    } else {
      const путь = буква === 'C' ? второй : первый;
      if (статьяСайта(путь, roots)) изменение = {вид: буква === 'C' ? ВИД.A : ВИД[буква], путь, прежнийПуть: null};
    }

    // Один коммит — одна запись на путь: слияние с `-m` без `--first-parent` показало бы его дважды.
    const ключ = `${текущий.коммит}|${изменение?.путь}`;
    if (изменение && !видели.has(ключ)) {
      видели.add(ключ);
      текущий.изменения.push(изменение);
    }
  }

  return коммиты;
}

/** Счёт строк разницы: добавленные и убранные, без заголовков `+++`/`---`. */
export function счётСтрок(разница) {
  let добавлено = 0;
  let убрано = 0;
  for (const строка of String(разница ?? '').split('\n')) {
    if (строка.startsWith('+++') || строка.startsWith('---')) continue;
    if (строка.startsWith('+')) добавлено += 1;
    else if (строка.startsWith('-')) убрано += 1;
  }
  return {добавлено, убрано};
}

/** Разница, укороченная до `пределБайт` по границе строки, с пометкой, что хвост отрезан. */
export function короче(разница, пределБайт, пометка) {
  const текст = String(разница ?? '');
  if (Buffer.byteLength(текст, 'utf8') <= пределБайт) return текст;
  let итог = '';
  for (const строка of текст.split('\n')) {
    if (Buffer.byteLength(`${итог}${строка}\n`, 'utf8') > пределБайт) break;
    итог += `${строка}\n`;
  }
  return `${итог}${пометка}\n`;
}
