// Панель экземпляров: чистые правила о том, что показывать и что разрешено делать.
// Ни сети, ни диска, ни процессов здесь нет — живые ответы подаются снаружи (SPEC 4.6, 4.7).
//
// Правило заведено потому, что управление экземплярами до сих пор жило в голове человека и в
// чёрных окнах: какой сервер сейчас поднят, из какого кода и на каких материалах, было видно
// только по строкам запуска, а остановить не тот процесс мешала одна внимательность. Здесь
// собрано ровно два решения: во что превращается живой опрос порта и когда остановка разрешена.
//
// Главное правило безопасности: остановка НИКОГДА не выводится из памяти панели. Запись о том,
// что вчера на порту жил испытательный экземпляр, ничего не говорит о том, кто отвечает сегодня.

import {ПОРТ_ВЛАДЕЛЬЦА, РОЛЬ_ИСПЫТАТЕЛЬНАЯ} from './runtimeIdentity.mjs';

/**
 * Порт самой панели. Пришпилен здесь по тому же доводу, что и `4780` (SPEC 7.1.6): панель
 * открывается ярлыком, и её адрес обязан быть одним и тем же всегда, а не зависеть от файла
 * настроек, который у каждой копии кода свой.
 */
export const ПОРТ_ПАНЕЛИ = 4779;

/** Состояния наблюдаемого порта. Больше видов не бывает: либо наш, либо чужой, либо тихо. */
export const РАБОТАЕТ = 'работает';
export const ОСТАНОВЛЕН = 'остановлен';
export const ЧУЖОЙ = 'чужой';

/** Виды экземпляра для человека. Рабочий отделён от испытательных нарочно: их нельзя спутать. */
export const ВИД_РАБОЧИЙ = 'рабочий';
export const ВИД_КОД = 'испытательныйКод';
export const ВИД_МАТЕРИАЛЫ = 'испытательныйМатериалы';

/** Коды отказов панели. Слова для человека живут в настройках (SPEC 6.10). */
export const НЕТ_ОПОЗНАНИЯ = 'нетОпознания';
export const ЧУЖОЙ_ОТВЕТ = 'чужойОтвет';
export const НЕТ_ВЛАДЕЛЬЦА = 'нетВладельца';
export const НЕ_ТОТ_ПРОЦЕСС = 'неТотПроцесс';
export const СМЕНИЛСЯ_ВЛАДЕЛЕЦ = 'сменилсяВладелец';
export const ВСЁ_ЕЩЁ_ОТВЕЧАЕТ = 'всёЕщёОтвечает';
export const НЕЧЕГО_ЗАПУСКАТЬ = 'нечегоЗапускать';
export const УЖЕ_РАБОТАЕТ = 'ужеРаботает';
export const ПОРТ_ЗАНЯТ = 'портЗанят';
export const НЕ_ПОДНЯЛСЯ = 'неПоднялся';
export const НЕ_НАБЛЮДАЕТСЯ = 'неНаблюдается';

/** Один вид косых, без лишней на конце и без учёта регистра: Windows зовёт папку по-разному. */
const ровно = (путь) => String(путь ?? '').split('\\').join('/').replace(/\/+$/, '').toLowerCase();

/**
 * Ответ порта — это опознание нашего редактора, а не что-нибудь ещё. Проверяются именно те поля,
 * на которых панель потом строит действия: без папки кода нечего сверять с процессом, а без порта
 * нельзя доказать, что сервер отвечает про себя, а не пересказывает соседа.
 */
export function опознаниеЛи(тело) {
  if (!тело || typeof тело !== 'object') return false;
  if (typeof тело['role'] !== 'string' || тело['role'] === '') return false;
  if (typeof тело['code'] !== 'string' || тело['code'] === '') return false;
  if (typeof тело['materials'] !== 'string' || тело['materials'] === '') return false;
  return Number.isInteger(тело['port']) && typeof тело['accepted'] === 'boolean';
}

/**
 * Вид экземпляра глазами владельца. Рабочим считается только принятый код на своём `4780`: одного
 * признака `accepted` мало — принятый код можно поднять и на другом номере, и такое окно рабочим
 * для человека не является. Всё остальное — испытательное, и панель говорит, чем именно.
 */
export function вид(о) {
  if (о['role'] === РОЛЬ_ИСПЫТАТЕЛЬНАЯ) return ВИД_МАТЕРИАЛЫ;
  if (о['accepted'] === true && Number(о['port']) === ПОРТ_ВЛАДЕЛЬЦА) return ВИД_РАБОЧИЙ;
  return ВИД_КОД;
}

/**
 * Одна строка панели по живому ответу порта и памяти о нём.
 *
 * `ответ` — итог опроса: `{опознание}` для нашего сервера, `{чужой: true}` для любого другого
 * ответившего, `null` для молчания. Память участвует ТОЛЬКО когда живого ответа нет: иначе
 * устаревшая запись выдавала бы себя за работающий сервер, а это ровно тот обман, из-за которого
 * правило и заведено. Поэтому у строки есть признак `живое`: всё, что не живое, показывается как
 * последнее известное, а не как нынешнее состояние.
 */
export function строкаПорта({порт, ответ, память = null}) {
  if (ответ && ответ['опознание']) {
    const о = ответ['опознание'];
    return {
      порт, состояние: РАБОТАЕТ, живое: true, вид: вид(о),
      ветка: о['branch'] ?? null, коммит: о['commit'] ?? null, чисто: о['clean'] === true,
      код: о['code'], материалы: о['materials'], адрес: о['url'],
      действия: {открыть: true, запустить: false, остановить: true},
    };
  }

  if (ответ && ответ['чужой']) {
    // Неизвестная программа — препятствие, а не экземпляр: ни одного действия, и память о прежнем
    // жильце порта сюда не подмешивается. Завершать такой процесс панель не умеет вовсе.
    return {
      порт, состояние: ЧУЖОЙ, живое: false, вид: null,
      ветка: null, коммит: null, чисто: false, код: null, материалы: null, адрес: null,
      действия: {открыть: false, запустить: false, остановить: false},
    };
  }

  if (!память) return null;

  return {
    порт, состояние: ОСТАНОВЛЕН, живое: false, вид: память['вид'] ?? null,
    ветка: память['ветка'] ?? null, коммит: память['коммит'] ?? null, чисто: память['чисто'] === true,
    код: память['код'] ?? null, материалы: память['материалы'] ?? null,
    адрес: `http://localhost:${порт}`,
    действия: {открыть: false, запустить: Boolean(память['код']), остановить: false},
  };
}

/**
 * Все наблюдаемые порты одной таблицей. Порт рабочего окна стоит первым и не пропадает, даже когда
 * редактор остановлен: его запуск известен из кода, и владельцу нужна одна привычная строка, а не
 * пустая панель. Какие порты наблюдаются, решает зовущий (`panelRoute.mjs`); перебора здесь нет.
 */
export function строки({порты, ответы, память = {}}) {
  return порты
    .map((порт) => строкаПорта({порт, ответ: ответы[порт] ?? null, память: память[порт] ?? null}))
    .filter((строка) => строка !== null);
}

/**
 * Процесс с этим номером — действительно запуск названного кода. Сравнивается полный путь до
 * `server.mjs` внутри папки кода, которую сервер только что назвал сам: номер процесса, взятый у
 * системы по владельцу порта, без такой сверки доказывает только «кто-то держит порт».
 */
export function принадлежитКоду(командная, код) {
  if (!командная || !код) return false;
  return ровно(командная).includes(`${ровно(код)}/server.mjs`);
}

/** Сервер назвал свой номер процесса. Пустое поле бывает только у кода старше самой панели. */
export function назвалНомер(о) {
  return Number.isInteger(о['pid']) && о['pid'] > 0;
}

/**
 * Можно ли останавливать. Разрешение собирается заново перед самим действием. Обязательны два
 * условия: сервер на этом порту только что назвал себя нашим редактором и система назвала номер
 * процесса, который этот порт держит.
 *
 * Дальше решает ОДИН вопрос: держит ли порт тот же процесс, который ответил.
 *
 * Сервер назвал свой номер — сверяется только он, и путь права голоса не имеет. Несовпадение
 * означает, что порт уже НЕ у ответившего: между опросом и остановкой его занял другой процесс. Из
 * той же папки кода — тем более: путь у обоих одинаков, и по совпадению пути завершился бы чужой
 * новый процесс, а работа человека в нём пропала бы. Такая смена — отказ, и повтор через миг
 * спросит порт заново уже про нового жильца.
 *
 * Номера в ответе нет — тогда спрашивается сама система: пока связь, по которой пришло опознание,
 * ещё открыта, она называет процесс, ОБСЛУЖИВШИЙ этот запрос. Доказательство прямее и слова
 * сервера о себе, и командной строки: тут ничей рассказ не участвует вовсе. Совпасть с владельцем
 * слушающего порта он обязан так же — иначе это опять смена жильца.
 *
 * Довод заведён живой пробой владельца: принятый редактор был поднят как `node .\\server.mjs`, и у
 * него не оказалось НИ ОДНОГО из двух прежних признаков — папки кода в командной строке (путь
 * относительный) и своего номера в опознании (код старше панели). Вполне живое принятое окно
 * оказалось неопознаваемым.
 *
 * Не назвала и система — остаётся последний, самый слабый признак: полный путь до `server.mjs` в
 * командной строке владельца порта. Он же отсекает соседнюю программу.
 *
 * Память панели в этом решении не участвует ни одним полем: вчерашняя запись о порте ничего не
 * говорит о том, кто отвечает сегодня.
 *
 * @returns {{номер: number}|{отказ: string}}
 */
export function решениеОстановки({порт, ответ, владелец}) {
  if (!ответ || ответ['чужой'] || !ответ['опознание']) return {отказ: НЕТ_ОПОЗНАНИЯ};

  const о = ответ['опознание'];
  if (Number(о['port']) !== Number(порт)) return {отказ: ЧУЖОЙ_ОТВЕТ};

  const номер = владелец ? владелец['номер'] : null;
  if (!Number.isInteger(номер) || номер <= 0) return {отказ: НЕТ_ВЛАДЕЛЬЦА};

  if (назвалНомер(о)) {
    return о['pid'] === номер ? {номер} : {отказ: СМЕНИЛСЯ_ВЛАДЕЛЕЦ};
  }

  const ответил = владелец['ответил'];
  if (Number.isInteger(ответил) && ответил > 0) {
    return ответил === номер ? {номер} : {отказ: СМЕНИЛСЯ_ВЛАДЕЛЕЦ};
  }

  if (!принадлежитКоду(владелец['командная'], о['code'])) return {отказ: НЕ_ТОТ_ПРОЦЕСС};

  return {номер};
}

/**
 * Можно ли запускать. Порт обязан молчать: занятый чужой программой сам не освободится, а поднимать
 * второй сервер поверх работающего незачем. Чем именно поднимать, панель берёт из запуска строки —
 * из кода для рабочего окна, из памяти для испытательного.
 *
 * @returns {{код: string, материалы: string}|{отказ: string}}
 */
export function решениеЗапуска({ответ, запуск}) {
  if (ответ && ответ['опознание']) return {отказ: УЖЕ_РАБОТАЕТ};
  if (ответ && ответ['чужой']) return {отказ: ПОРТ_ЗАНЯТ};
  if (!запуск || !запуск['код'] || !запуск['материалы']) return {отказ: НЕЧЕГО_ЗАПУСКАТЬ};

  return {код: запуск['код'], материалы: запуск['материалы']};
}

/**
 * Чем запомнить работающий экземпляр, чтобы после остановки поднять его обратно тем же составом.
 * Запоминается только живое опознание: чужой ответ и молчание память не трогают вовсе.
 */
export function записьПамяти(о) {
  return {
    вид: вид(о), ветка: о['branch'] ?? null, коммит: о['commit'] ?? null,
    чисто: о['clean'] === true, код: о['code'], материалы: о['materials'],
    роль: о['role'], принят: о['accepted'] === true,
  };
}
