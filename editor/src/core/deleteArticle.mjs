// Правила удаления статьи с диска. Чистые: на входе факты о статье, на выходе решение.
// Диска и git здесь нет — их дело собрать факты, а не решать (SPEC 4.6).
//
// Удаление всегда обратимое: любая статья уходит в корзину (решение владельца 2026-09-18). Насовсем
// данные уходят только из самой корзины и только по прямому нажатию человека.
//
// Про сайт это правило не судит: была ли статья на сайте, спрашивается у ЗАКРЕПЛЁННОЙ основы при
// снятии (`adapters/retireFacts.mjs`), и если была — снятие публикуется до корзины тем же нажатием.

/**
 * Что уносить в корзину.
 *
 * `версии` — по одной записи на языковую версию:
 * `path` — файл статьи, `состояние` — свой файл состояния рядом с ней, `папка` — папка статьи,
 * `служебная` — это страница раздела, а не статья,
 * `своя` — папка принадлежит только этой статье: в ней нет других статей и вложенных статей.
 */
export function решениеОбУдалении({версии}) {
  const свои = Array.isArray(версии) ? версии : [];
  if (свои.length === 0) return {ошибка: 'нетСтатьи'};

  // Страница раздела держит под собой другие статьи: удалить её значит уронить раздел целиком.
  if (свои.some((версия) => версия.служебная === true)) return {ошибка: 'страницаРаздела'};

  return {
    режим: 'корзина',
    файлы: свои.flatMap((версия) => [версия.path, версия.состояние].filter(Boolean)),
    // Папка уходит только когда она целиком этой статьи: в общей папке лежат чужие картинки и соседи.
    папки: свои.filter((версия) => версия.своя === true).map((версия) => версия.папка).filter(Boolean),
    пути: свои.map((версия) => версия.path),
    языки: свои.map((версия) => версия.локаль).filter(Boolean),
  };
}
