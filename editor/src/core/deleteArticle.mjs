// Правила удаления статьи. Чистые: на входе факты о статье, на выходе решение.
// Диска и git здесь нет — их дело собрать факты, а не решать (SPEC 4.6).
//
// Удаление необратимо и текст человека не щадит, поэтому граница узкая: стирается только то,
// чего никогда не было на сайте. У опубликованной статьи есть публичный адрес, и убирать его
// без переадресации запрещено смыслом SPEC 2.5 — это отдельное задание (В3-05).

/**
 * Можно ли удалять и что именно стирать.
 *
 * `версии` — по одной записи на языковую версию:
 * `path` — файл статьи, `состояние` — файл состояния рядом с ней, `папка` — папка статьи,
 * `наСайте` — лежит ли версия в корне, который уезжает на сайт,
 * `опубликована` — найдена ли она в опубликованной ветке,
 * `служебная` — это страница раздела, а не статья,
 * `соседи` — сколько статей лежит в той же папке.
 *
 * `веткаИзвестна` — удалось ли вообще заглянуть в опубликованную ветку. Не удалось — отказ:
 * «не знаю» значит «может быть на сайте», и молчаливое разрешение стёрло бы живую статью.
 */
export function решениеОбУдалении({версии, веткаИзвестна}) {
  const свои = Array.isArray(версии) ? версии : [];
  if (свои.length === 0) return {ошибка: 'нетСтатьи'};

  // Песочница живёт вне сайта: её опубликованность доказывать нечем и не нужно.
  const наСайте = свои.filter((версия) => версия.наСайте === true);
  if (наСайте.length > 0 && веткаИзвестна !== true) return {ошибка: 'ветканеизвестна'};

  // Достаточно одной опубликованной версии: статья одна, и половинчатое удаление оставило бы
  // на сайте перевод без исходника — это хуже, чем не удалить вовсе.
  if (наСайте.some((версия) => версия.опубликована === true)) return {ошибка: 'ужеНаСайте'};

  // Страница раздела держит под собой другие статьи: удалить её значит уронить сборку раздела.
  if (свои.some((версия) => версия.служебная === true)) return {ошибка: 'страницаРаздела'};

  // В папке лежит ещё чья-то статья: там общие картинки и общий файл состояния, и понять,
  // что из этого чьё, нельзя. Отказ честнее, чем угадывание.
  if (свои.some((версия) => Number(версия.соседи ?? 1) > 1)) return {ошибка: 'папкаНеОдна'};

  return {
    файлы: свои.flatMap((версия) => [версия.path, версия.состояние].filter(Boolean)),
    папки: свои.map((версия) => версия.папка).filter(Boolean),
    пути: свои.map((версия) => версия.path),
  };
}
