// Правила удаления статьи. Чистые: на входе факты о статье, на выходе решение.
// Диска и git здесь нет — их дело собрать факты, а не решать (SPEC 4.6).
//
// Удаление всегда обратимое: любая статья уходит в корзину, и опубликованная, и никогда не
// публиковавшаяся (решение владельца 2026-09-18, заменило прежние два режима). Насовсем данные
// уходят только из самой корзины и только по прямому нажатию человека.
//
// Причина публикации остаётся в решении — она нужна словами: побывавшая на сайте страница там и
// останется, пока её не снимут отдельно, и человеку об этом говорят прямо.

/**
 * Что делать и что именно уносить.
 *
 * `версии` — по одной записи на языковую версию:
 * `path` — файл статьи, `состояние` — свой файл состояния рядом с ней, `папка` — папка статьи,
 * `наСайте` — лежит ли версия в корне, который уезжает на сайт,
 * `опубликована` — есть ли она в опубликованной ветке сейчас,
 * `былаОпубликована` — была ли когда-либо в истории ветки (`null` — узнать не удалось),
 * `служебная` — это страница раздела, а не статья,
 * `своя` — папка принадлежит только этой статье: в ней нет других статей и вложенных статей.
 *
 * `веткаИзвестна` — удалось ли вообще заглянуть в опубликованную ветку.
 */
export function решениеОбУдалении({версии, веткаИзвестна}) {
  const свои = Array.isArray(версии) ? версии : [];
  if (свои.length === 0) return {ошибка: 'нетСтатьи'};

  // Страница раздела держит под собой другие статьи: удалить её значит уронить раздел целиком.
  if (свои.some((версия) => версия.служебная === true)) return {ошибка: 'страницаРаздела'};

  // Песочница живёт вне сайта: её опубликованность доказывать нечем и не нужно.
  const наСайте = свои.filter((версия) => версия.наСайте === true);
  const опубликована = наСайте.some((версия) => версия.опубликована === true || версия.былаОпубликована === true);
  const неизвестно = наСайте.length > 0
    && (веткаИзвестна !== true || наСайте.some((версия) => версия.былаОпубликована !== true && версия.былаОпубликована !== false));
  const причина = опубликована ? 'опубликована' : неизвестно ? 'неизвестно' : 'неОпубликована';

  return {
    режим: 'корзина',
    причина,
    файлы: свои.flatMap((версия) => [версия.path, версия.состояние].filter(Boolean)),
    // Папка уходит только когда она целиком этой статьи: в общей папке лежат чужие картинки и соседи.
    папки: свои.filter((версия) => версия.своя === true).map((версия) => версия.папка).filter(Boolean),
    пути: свои.map((версия) => версия.path),
    языки: свои.map((версия) => версия.локаль).filter(Boolean),
  };
}
