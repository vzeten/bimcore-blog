// Устройство списка, одно на клавиши и кнопки: пункты с границами по строкам, простота, зазоры,
// соседние списки того же вида и построчные правки уплотнения. Что список, а что пункт, говорит
// дерево разбора markdown окна; где пункт кончается, считается по строкам, потому что дерево
// продолжает последний пункт закрывающей `:::` и не знает границ примечания.
//
// Пункт бывает простой (маркер и текст с переносами, вложенный список без пустых строк) или
// блочный (внутри есть пустая строка: второй абзац, картинка, код). Пустые строки между пунктами
// одного списка — зазор, а не текст: уплотнение убирает его, когда человек действует над списком.
// Пустые строки внутри блочного пункта — текст, они остаются: такой список на сайте разреженный
// по CommonMark, и обещать ему компактность нельзя. Слова и вложения правки здесь не трогают:
// меняются только маркеры, номера, зазоры, отступ продолжений и косая переноса перед ушедшим зазором.

import type {SyntaxNode, Tree} from '@lezer/common';

export type ВидСписка = 'точки' | 'числа';

/** Одна замена в тексте: то же, что ChangeSpec редактора. Правки строятся построчно, чтобы история и цвета слов не задевали нетронутое. */
export interface Замена {
  from: number;
  to: number;
  insert: string;
}

/** Что о тексте знает окно: дерево разбора, строки-границы примечаний и два правила о строке. */
export interface Окружение {
  дерево: Tree;
  границы: ReadonlySet<number>;
  /** Строка абзаца — обычный текст, а не строка таблицы, картинка на своей строке или разметка MDX. */
  обычная: (строка: string) => boolean;
  /** Строка кончается косой жёсткого переноса. */
  косая: (строка: string) => boolean;
  /** Тот же разбор, что в окне: нужен кнопке после первой ступени правки. */
  разбор?: (text: string) => Tree;
}

export interface Текст {
  строки: string[];
  начала: number[];
  номер: (pos: number) => number;
}

export function построчно(text: string): Текст {
  const строки = text.split('\n');
  const начала: number[] = [];
  for (let pos = 0, i = 0; i < строки.length; i += 1) {
    начала.push(pos);
    pos += строки[i].length + 1;
  }
  const номер = (pos: number): number => {
    let i = начала.length - 1;
    while (i > 0 && начала[i] > pos) i -= 1;
    return i;
  };
  return {строки, начала, номер};
}

export interface Маркер {
  отступ: number;
  /** Сам маркер: `-`, `*`, `+` либо номер со знаком `.` или `)`. */
  текст: string;
  /** Знак у точек, разделитель у чисел: по нему CommonMark разделяет списки. */
  знак: string;
  номер: number | null;
  /** Колонка содержимого пункта: от неё считаются продолжения и вложения. */
  колонка: number;
}

const МАРКЕР = /^( *)(?:([-*+])|(\d{1,9})([.)]))( *)/;

/** Маркер по первой строке пункта; табуляция в отступе не разбирается — её ширина в файле неизвестна. */
export function маркерСтроки(строка: string): Маркер | null {
  const м = МАРКЕР.exec(строка);
  if (м === null || (м[5].length === 0 && м[0].length < строка.length)) return null;
  const текст = м[2] ?? `${м[3]}${м[4]}`;
  // Пять и больше пробелов после маркера — отступной код: содержимое начинается через один пробел.
  const пробелы = м[5].length === 0 || м[5].length >= 5 ? 1 : м[5].length;
  return {отступ: м[1].length, текст, знак: м[2] ?? м[4], номер: м[3] === undefined ? null : Number(м[3]), колонка: м[1].length + текст.length + пробелы};
}

export interface Пункт {
  узел: SyntaxNode;
  /** Первая и последняя непустая строка пункта; конец обрезан границей примечания. */
  от: number;
  до: number;
  маркер: Маркер;
}

export interface Список {
  узел: SyntaxNode;
  вид: ВидСписка;
  пункты: Пункт[];
}

export function видУзла(узел: SyntaxNode | null): ВидСписка | null {
  return узел === null ? null : узел.name === 'BulletList' ? 'точки' : узел.name === 'OrderedList' ? 'числа' : null;
}

/**
 * Список по узлу дерева, либо `null`, если у пункта неизвестная форма маркера. Граница примечания
 * между пунктами делит узел: дерево тянет список сквозь `:::`, а сайт закрывает примечание, поэтому
 * берётся тот отрезок, где стоит строка `у` (по умолчанию — первый).
 */
export function список(т: Текст, узел: SyntaxNode, границы: ReadonlySet<number>, у = т.номер(узел.from)): Список | null {
  const вид = видУзла(узел);
  if (вид === null) return null;
  const дети: SyntaxNode[] = [];
  for (let д = узел.firstChild; д !== null; д = д.nextSibling) if (д.name === 'ListItem') дети.push(д);
  const отрезки: Пункт[][] = [[]];
  for (const [i, д] of дети.entries()) {
    const от = т.номер(д.from);
    const маркер = маркерСтроки(т.строки[от]);
    if (маркер === null) return null;
    let до = i + 1 < дети.length ? т.номер(дети[i + 1].from) - 1 : т.номер(д.to);
    let граница = false;
    for (let j = от; j <= до; j += 1) {
      if (границы.has(j)) {
        до = j - 1;
        граница = true;
        break;
      }
    }
    while (до > от && т.строки[до].trim() === '') до -= 1;
    отрезки[отрезки.length - 1].push({узел: д, от, до, маркер});
    if (граница && i + 1 < дети.length) отрезки.push([]);
  }
  const пункты = отрезки.filter((о) => о.length > 0 && о[0].от <= у).pop() ?? отрезки[0];
  return пункты.length === 0 ? null : {узел, вид, пункты};
}

/** Простой список: ни в одном пункте нет пустой строки. Вложенный список без пустых строк пункт блочным не делает. */
export function простой(с: Список, т: Текст): boolean {
  return с.пункты.every((п) => {
    for (let i = п.от; i <= п.до; i += 1) if (т.строки[i].trim() === '') return false;
    return true;
  });
}

/**
 * Список вместе с непосредственными соседями того же вида: между ними только пустые строки, без
 * границы примечания. Соседи берутся среди узлов того же родителя, то есть того же уровня.
 */
export function группа(с: Список, т: Текст, границы: ReadonlySet<number>): Список[] {
  const пусто = (a: number, b: number): boolean => {
    for (let i = a + 1; i < b; i += 1) if (т.строки[i].trim() !== '' || границы.has(i)) return false;
    return true;
  };
  const итог = [с];
  for (let сосед = с.узел.prevSibling, текущий = с; сосед !== null && видУзла(сосед) === с.вид; сосед = сосед.prevSibling) {
    const сп = список(т, сосед, границы, т.номер(сосед.to));
    if (сп === null || !пусто(сп.пункты[сп.пункты.length - 1].до, текущий.пункты[0].от)) break;
    итог.unshift(сп);
    текущий = сп;
  }
  for (let сосед = с.узел.nextSibling, текущий = с; сосед !== null && видУзла(сосед) === с.вид; сосед = сосед.nextSibling) {
    const сп = список(т, сосед, границы);
    if (сп === null || !пусто(текущий.пункты[текущий.пункты.length - 1].до, сп.пункты[0].от)) break;
    итог.push(сп);
    текущий = сп;
  }
  return итог;
}

/**
 * Удаление зазора между строками: уходят пустые строки между ними. Косая переноса в конце верхней
 * строки уходит тоже — вплотную к пункту она стала бы буквой на сайте; заодно правка накрывает
 * скрытый диапазон косой целиком, а не задевает его частью.
 */
export function удалениеЗазора(т: Текст, выше: number, ниже: number, косая: (строка: string) => boolean): Замена {
  const строка = т.строки[выше];
  return {from: т.начала[выше] + строка.length - (косая(строка) ? 1 : 0), to: т.начала[ниже] - 1, insert: ''};
}

/** Продолжения пункта сдвигаются вслед за сменой ширины маркера; ленивые строки левее колонки не трогаются. */
export function сдвигПродолжений(т: Текст, п: Пункт, дельта: number): Замена[] {
  const итог: Замена[] = [];
  for (let i = п.от + 1; i <= п.до; i += 1) {
    const строка = т.строки[i];
    if (строка.trim() === '') continue;
    const пробелы = /^ */.exec(строка)![0].length;
    if (пробелы < п.маркер.колонка) continue;
    итог.push(дельта > 0 ? {from: т.начала[i], to: т.начала[i], insert: ' '.repeat(дельта)} : {from: т.начала[i], to: т.начала[i] - дельта, insert: ''});
  }
  return итог;
}

/**
 * Уплотнение группы: маркеры получают знак `знак` (у чисел — номера подряд от номера первого
 * пункта), зазоры уходят там, где `удалятьЗазор` разрешает. `сдвигПосле` — номер пункта в группе,
 * после которого клавиша вставляет новый пункт: следующие номера сдвигаются на единицу.
 */
export function уплотнение(
  т: Текст,
  группа: Список[],
  знак: string,
  удалятьЗазор: (после: Пункт, до: Пункт) => boolean,
  косая: (строка: string) => boolean,
  сдвигПосле = Infinity,
): Замена[] {
  const пункты = группа.flatMap((с) => с.пункты);
  const числа = группа[0].вид === 'числа';
  const первый = пункты[0].маркер.номер ?? 1;
  const итог: Замена[] = [];
  пункты.forEach((п, i) => {
    const текст = числа ? `${первый + i + (i > сдвигПосле ? 1 : 0)}${знак}` : знак;
    if (текст !== п.маркер.текст) {
      const от = т.начала[п.от] + п.маркер.отступ;
      итог.push({from: от, to: от + п.маркер.текст.length, insert: текст});
      итог.push(...сдвигПродолжений(т, п, текст.length - п.маркер.текст.length));
    }
    if (i > 0 && п.от > пункты[i - 1].до + 1 && удалятьЗазор(пункты[i - 1], п)) итог.push(удалениеЗазора(т, пункты[i - 1].до, п.от, косая));
  });
  return итог;
}

/** Номер, который получит новый пункт, вставленный после пункта `индекс` группы. */
export function номерНового(группа: Список[], индекс: number): number {
  const пункты = группа.flatMap((с) => с.пункты);
  return (пункты[0].маркер.номер ?? 1) + индекс + 1;
}
