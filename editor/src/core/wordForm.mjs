// Слово при числе по правилам русского языка: «в 1 статье», «в 3 статьях», «в 5 статьях», «в 21 статье».
// Чистое правило: сами формы слова живут в настройках (`склонения`), здесь только выбор между ними.

/**
 * Форма слова для числа. `формы` — `{один, несколько, много}`: для 1 и 21, для 2–4 и 22–24, для 5–20
 * и 0. Одиннадцать–четырнадцать всегда «много»: «в 11 статьях», а не «в 11 статье».
 */
export function формаЧисла(число, формы) {
  const n = Math.abs(Math.trunc(Number(число) || 0));
  const последняя = n % 10;
  const две = n % 100;
  if (две >= 11 && две <= 14) return формы['много'];
  if (последняя === 1) return формы['один'];
  if (последняя >= 2 && последняя <= 4) return формы['несколько'];
  return формы['много'];
}
