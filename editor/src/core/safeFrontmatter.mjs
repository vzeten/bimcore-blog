// Защитная правка шапки при сохранении: то, что роняет сборку сайта, до диска не доезжает.
// Отдельно от `frontmatterRules.mjs` потому, что это другая ответственность: там правила значений
// (что YAML прочитает, нужны ли кавычки, каким должен быть адрес), а здесь — единственное место,
// где программа меняет чужую шапку сама, без действия человека.

import {headGroups, безКавычек, значениеГруппы} from './articleFile.mjs';
import {isEmptyImage, адресВШапку, normalizeSlug, читаетсяНеСтрокой} from './frontmatterRules.mjs';

/**
 * Приводит строки шапки в безопасный вид.
 * Возвращает новый текст шапки и список того, что было исправлено.
 *
 * Находка — запись, а не фраза для человека: код правила, поле шапки и, где есть, было и стало.
 * Слова живут в настройках (SPEC 4.4), а подготовка (круг 2) ведёт человека к месту в статье
 * по имени поля. Разбирай она готовую фразу — рядом с правилом появился бы второй его источник.
 */
export function safeFrontmatter(path, raw, roots) {
  const fixed = [];
  const out = [];

  for (const группа of headGroups(raw)) {
    if (группа.ключ === null) {
      out.push(группа);
      continue;
    }

    const key = группа.ключ;
    const value = группа.значение;

    if (key === 'image' && isEmptyImage(value)) {
      fixed.push({код: 'пустаяОбложка', поле: key});
      continue;
    }

    // Убирается только то, что роняет сборку: список ключевых слов без единого годного значения
    // Docusaurus не принимает вовсе — ни скобками `[]`, ни голым ключом, ни списком из пустых строк.
    // Пустой `tags` сборку проходит, и переписывать из-за него чужой файл при каждом сохранении
    // нельзя (SPEC 5.1) — его уберёт правка шапки, когда человек сам очистит поле.
    //
    // Ключевые слова читаются YAML-разбором своего куска, а не строкой: у двенадцати живых статей
    // блога они записаны строками `- слово`, и построчно такой список выглядит пустым, не будучи им.
    // Убери мы его — элементы под ключом осиротели бы, и шапка стала бы нечитаемой.
    if (key === 'keywords' && списокБезЗначений(группа)) {
      fixed.push({код: 'пустыеКлючевыеСлова', поле: key});
      continue;
    }

    if (key === 'slug') {
      // Кавычки снимаются до нормализации: адрес из одних цифр записан в кавычках, и без этого
      // правило приняло бы кавычку за часть адреса и выдало бы `/lessons/"2026"`.
      const запись = String(value).trim();
      const голый = безКавычек(запись);
      const next = normalizeSlug(path, голый, roots);
      // Строка переписывается только по делу: адрес не по правилу раздела, либо запись без
      // кавычек, которую YAML прочитает не строкой (`slug: 2026` станет числом). Кавычки, уже
      // стоящие в файле, сами поводом не являются: одиночные YAML читает строкой не хуже
      // двойных, и менять их значило бы переписывать файл на пустом месте (SPEC 5.1).
      //
      // Две причины — две находки, а не одна. Отчёт подготовки показывает «было → стало»,
      // и у адреса, взятого в кавычки, оба конца одинаковы: сказать человеку «2026 → 2026»
      // значит соврать — менялся не адрес, а его запись.
      const переписан = next !== голый;
      const вКавычки = !переписан && запись === голый && читаетсяНеСтрокой(запись);

      if (переписан || вКавычки) {
        fixed.push(переписан
          ? {код: 'адресПоПравилу', поле: key, было: голый, стало: next}
          : {код: 'адресВКавычки', поле: key, адрес: голый});
        out.push({...группа, строки: [`${key}: ${адресВШапку(next)}`]});
        continue;
      }
    }

    out.push(группа);
  }

  return {frontmatterRaw: out.flatMap((группа) => группа.строки).join('\n'), fixed};
}

/**
 * Список, в котором нет ни одного годного значения: пустые скобки, голый ключ без элементов,
 * список из пустых строк. Любой из этих видов роняет сборку сайта — Docusaurus требует в поле
 * ключевых слов хотя бы одно непустое значение.
 *
 * Прочитать не удалось — не трогаем: стирать то, чего программа не поняла, нельзя.
 */
function списокБезЗначений(группа) {
  const {ok, значение} = значениеГруппы(группа);

  if (!ok) return false;
  if (значение === null || значение === undefined) return true;
  if (!Array.isArray(значение)) return false;

  return значение.every((item) => String(item ?? '').trim() === '');
}
