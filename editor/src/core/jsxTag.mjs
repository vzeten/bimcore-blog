// Разбор самозакрывающегося JSX-тега статьи: одно место на всю программу.
//
// Окно (`jsxBlocks.ts`) и живой показ читают теги статьи одинаково. Разойдись у них правило
// разбора — окно показало бы блок, которого не видит остальная программа, и наоборот.
//
// Понимаются ровно две записи, и обе взяты не из головы, а с диска. Одной строкой —
// `<Имя свойство="значение" />`: так пишет теги сама программа. Столбиком — по свойству на строку
// с одинаковым отступом и закрытием на своей строке: так записаны все карточки товара в статьях
// сайта. Смешанная запись, разные отступы, тег с детьми и пустая строка посреди тега не
// разбираются вовсе: править вслепую то, чего не понял, значит испортить текст человека.

const ИМЯ_ТЕГА = '[A-Za-z][A-Za-z0-9]*';
const ИМЯ_СВОЙСТВА = '[A-Za-z][A-Za-z0-9-]*';
/** Значение: строка в кавычках либо выражение JSX из одного имени. */
const ЗНАЧЕНИЕ = '"[^"<>]*"|\\{[A-Za-z_$][A-Za-z0-9_$]*\\}';

/**
 * Две записи, которые программа знает не по догадке, а потому что видела их на диске. Столбиком
 * записана ровно одна разновидность тега — карточка товара; выражение JSX стоит ровно у её
 * картинки и ровно с этим именем, за которым в статье идёт импорт файла. Это имена чужого
 * формата, которые задали не мы, а не наши настройки (SPEC 4.4).
 *
 * Любая другая запись остаётся текстом статьи. Понять наполовину хуже, чем не понять вовсе:
 * блок пообещал бы человеку правку, которую программа не умеет сделать без потери.
 */
const СТОЛБИКОМ_ТЕГ = 'ProductCard';
export const ВЫРАЖЕНИЕ = {тег: 'ProductCard', свойство: 'image', имя: 'productPreview'};

const ПАРА = `${ИМЯ_СВОЙСТВА}=(?:${ЗНАЧЕНИЕ})`;
/** Тег одной строкой: свойства через пробелы, закрытие в той же строке. */
const СТРОКОЙ = `<(${ИМЯ_ТЕГА})((?:[ \\t]+${ПАРА})*)[ \\t]*\\/>`;
/**
 * Тег столбиком: по свойству на строку, закрытие на своей строке. Одинаковость отступа стережёт
 * уже разбор: выразить её здесь можно только обратной ссылкой, а она в этой записи читается
 * восьмеричным знаком и роняет чтение модуля.
 */
const СТОЛБИКОМ = `<(${ИМЯ_ТЕГА})((?:\\r?\\n[ \\t]+${ПАРА})+)\\r?\\n[ \\t]*\\/>`;
/** Чем свойство отделено от предыдущего у тега столбиком: перевод строки вместе с отступом. */
const РАЗДЕЛИТЕЛЬ = /\r?\n[ \t]+/g;

/** Тег целиком: строка обязана быть тегом от начала до конца. */
export const ТЕГ = new RegExp(`^(?:${СТРОКОЙ}|${СТОЛБИКОМ})$`);

/** Тот же тег, но найденный внутри текста статьи. */
const ТЕГ_В_ТЕКСТЕ = new RegExp(`${СТРОКОЙ}|${СТОЛБИКОМ}`, 'g');

/** Свойства внутри уже найденного тега. */
export const СВОЙСТВО = new RegExp(`(${ИМЯ_СВОЙСТВА})=(${ЗНАЧЕНИЕ})`, 'g');

/** Знаки, которые нельзя записать в значение свойства: тег после них перестанет разбираться. */
export const ОПАСНЫЕ_ЗНАКИ = /["<>]/;

/**
 * Разбор строки, которая целиком является тегом. `null` — текст тегом не является либо написан
 * так, как программа не понимает; тогда он остаётся текстом статьи как есть.
 *
 * У каждого свойства отдаются границы его значения в тексте тега: правка меняет ровно этот кусок
 * и не переписывает тег заново. Иначе запись столбиком схлопнулась бы в строку, а перевод строки
 * `\r\n` стал бы `\n` — файл человека изменился бы там, где он ничего не менял.
 */
export function разборТега(текст) {
  const найдено = ТЕГ.exec(текст);
  if (найдено === null) return null;

  // Какая из двух записей совпала: у тега одной строкой заполнены первые две скобки,
  // у тега столбиком — следующие две.
  const строкой = найдено[1] !== undefined;
  const имя = строкой ? найдено[1] : найдено[3];
  const хвост = строкой ? найдено[2] : найдено[4];

  const разделители = хвост.match(РАЗДЕЛИТЕЛЬ) ?? [];
  // Разные отступы у соседних строк — запись, которой в статьях сайта нет. Показать такой тег
  // блоком значило бы обещать понимание, которого нет.
  if (разделители.some((разделитель) => разделитель !== разделители[0])) return null;

  // Столбиком в статьях сайта записана только карточка товара; так же записанный чужой тег —
  // запись, которой программа не видела.
  if (!строкой && имя !== СТОЛБИКОМ_ТЕГ) return null;

  const свойства = свойстваТега(хвост, 1 + имя.length);
  if (свойства.some((свойство) => свойство.выражение && !этоКартинкаКарточки(имя, свойство))) return null;

  return {
    имя,
    свойства,
    // Место перед закрытием тега и отступ соседей: сюда и так же встаёт свойство, которого
    // в теге не было.
    конец: 1 + имя.length + хвост.length,
    отступ: строкой ? ' ' : разделители[0],
  };
}

/**
 * Все понятные теги внутри текста статьи, по порядку. Границы отдаются вместе с тегом: показ
 * ставит виджет ровно на место тега, а не «где-то в статье».
 */
export function тегиТекста(текст) {
  const найденные = [];

  for (const совпадение of текст.matchAll(ТЕГ_В_ТЕКСТЕ)) {
    const разобран = разборТега(совпадение[0]);
    if (разобран === null) continue;

    найденные.push({...разобран, от: совпадение.index, до: совпадение.index + совпадение[0].length});
  }

  return найденные;
}

/** Номер строки, в которой стоит место `от`. Считается от единицы: человеку показывают её. */
export function строкаМеста(текст, от) {
  return текст.slice(0, от).split('\n').length;
}

/** Свойства тега вместе с границами их значений: правится ровно кусок значения. */
function свойстваТега(хвост, началоХвоста) {
  const свойства = [];

  for (const совпадение of хвост.matchAll(СВОЙСТВО)) {
    const [, имя, значение] = совпадение;
    const местоЗначения = началоХвоста + совпадение.index + имя.length + 1;

    свойства.push({
      имя,
      значение: значение.slice(1, -1),
      // Выражение JSX программа показывает, но не переписывает: за именем стоит импорт файла,
      // и подстановка туда обычной строки оборвала бы связь тега с картинкой статьи.
      выражение: значение.startsWith('{'),
      от: местоЗначения,
      до: местоЗначения + значение.length,
    });
  }

  return свойства;
}

/** Единственное выражение JSX, которое программа понимает: картинка карточки товара. */
function этоКартинкаКарточки(имяТега, свойство) {
  return имяТега === ВЫРАЖЕНИЕ.тег
    && свойство.имя === ВЫРАЖЕНИЕ.свойство
    && свойство.значение === ВЫРАЖЕНИЕ.имя;
}

/**
 * Импорт файла, введённого в статью: `import productPreview from './product.png';`. Картинка
 * карточки товара записана в теге именем переменной, а сам адрес лежит строкой выше по статье —
 * прочитать его можно только здесь, по её тексту целиком. Вместе с адресом отдаются границы самой
 * записи: строка принадлежит MDX и остаётся в файле, но показ прячет её от человека, и знать, где
 * она лежит, обязано то же правило, что её прочитало.
 *
 * Адрес отдаётся ровно так, как записан в статье: что за ним стоит на диске — путь рядом со
 * статьёй, общая папка сайта или её корень (`@site/…`), — решает тот, кто открывает файл.
 *
 * Понимается ровно одна запись импорта — та, какой пользуются статьи сайта. Чего программа не
 * поняла, у того адреса нет: показ обойдётся без картинки, а текст статьи остаётся нетронутым.
 */
export function импортСтатьи(текст, имя) {
  if (!/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(имя)) return null;

  const запись = new RegExp(
    `^[ \t]*import[ \t]+${имя}[ \t]+from[ \t]+['"]([^'"\n]+)['"][ \t]*;?[ \t]*$`,
    'm',
  );
  const найдено = запись.exec(текст);
  if (найдено === null) return null;

  return {адрес: найдено[1], от: найдено.index, до: найдено.index + найдено[0].length};
}
