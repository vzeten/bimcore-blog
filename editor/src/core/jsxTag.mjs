// Разбор самозакрывающегося JSX-тега статьи: одно место на всю программу.
//
// Окно (`jsxBlocks.ts`) и подготовка (`blockRules.mjs`) читают теги статьи одинаково. Разойдись
// у них правило разбора — окно показало бы блок, которого подготовка не видит, и наоборот:
// человек получил бы «всё заполнено» о теге, чьи свойства программа даже не разобрала.
//
// Разбирается ровно тег вида `<Имя свойство="значение" />`. Многострочный тег, тег с детьми и
// значение в фигурных скобках JSX не разбираются вовсе: править вслепую то, чего не понял,
// значит испортить текст человека.

/** Тег целиком: строка обязана быть тегом от начала до конца. */
export const ТЕГ = /^<([A-Za-z][A-Za-z0-9]*)((?:[ \t]+[A-Za-z][A-Za-z0-9-]*="[^"<>]*")*)[ \t]*\/>$/;

/** Тот же тег, но найденный внутри текста статьи. */
const ТЕГ_В_ТЕКСТЕ = /<([A-Za-z][A-Za-z0-9]*)((?:[ \t]+[A-Za-z][A-Za-z0-9-]*="[^"<>]*")*)[ \t]*\/>/g;

/** Свойства внутри уже найденного тега. */
export const СВОЙСТВО = /([A-Za-z][A-Za-z0-9-]*)="([^"<>]*)"/g;

/** Знаки, которые нельзя записать в значение свойства: тег после них перестанет разбираться. */
export const ОПАСНЫЕ_ЗНАКИ = /["<>]/;

/**
 * Разбор строки, которая целиком является тегом. `null` — текст тегом не является либо написан
 * так, как программа не понимает; тогда он остаётся текстом статьи как есть.
 */
export function разборТега(текст) {
  const найдено = ТЕГ.exec(текст);
  if (найдено === null) return null;

  return {имя: найдено[1], свойства: свойстваТега(найдено[2])};
}

/**
 * Все понятные теги внутри текста статьи, по порядку. Границы отдаются вместе с тегом: подготовка
 * называет человеку строку файла, а не «где-то в статье».
 */
export function тегиТекста(текст) {
  const найденные = [];

  for (const совпадение of текст.matchAll(ТЕГ_В_ТЕКСТЕ)) {
    найденные.push({
      имя: совпадение[1],
      свойства: свойстваТега(совпадение[2]),
      от: совпадение.index,
      до: совпадение.index + совпадение[0].length,
    });
  }

  return найденные;
}

/** Номер строки, в которой стоит место `от`. Считается от единицы: человеку показывают её. */
export function строкаМеста(текст, от) {
  return текст.slice(0, от).split('\n').length;
}

function свойстваТега(хвост) {
  const свойства = [];
  for (const [, имя, значение] of хвост.matchAll(СВОЙСТВО)) свойства.push({имя, значение});
  return свойства;
}
