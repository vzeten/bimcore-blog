// Быстрые проверки публикации: правила. Сборки сайта на компьютере больше нет (решение владельца
// 2026-09-18), и её место заняли проверки того, что на деле роняло сборку на GitHub: картинка, которой
// нет рядом со статьёй (июнь 2026, 15 упавших сборок подряд), и ссылка на страницу, которой нет
// (`onBrokenLinks: 'throw'` в конфиге сайта). Разбор MDX зовёт адаптер: разборщик живёт у сайта.
//
// Чистые правила: на входе факты о БУДУЩЕМ сайте — опубликованная основа плюс план, — на выходе
// находки. Диска и git здесь нет (SPEC 4.6).
//
// **Ложный блокер хуже пропуска.** Сайт на GitHub всё равно соберётся или не соберётся сам, и
// живой сайт при неудаче останется прежним; а ложный отказ запирает человека без выхода. Поэтому
// блокером называется только то, что доказано; адрес, о котором правило судить не берётся
// (страница раздела, метки блога, файл из `static`), — предупреждение.

import {readField, splitArticle} from './articleFile.mjs';
import {articlePlace, isUnlisted} from './frontmatterRules.mjs';
import {служебноеИмя} from './articles.mjs';
import {черновикСайта} from './localeSigns.mjs';
import {адресВерсии, адресВЯзыке, адресПоSlug, кудаВедёт, кускиБезКода, ссылкиТекста} from './siteRoutes.mjs';
import {БЛОКЕР, ПРЕДУПРЕЖДЕНИЕ, находка} from './prepareRules.mjs';

/**
 * Служебные адреса блога Docusaurus: метки, страницы ленты, архив, авторы. Чужой формат — так их
 * называет сам движок, — поэтому перечнем в коде, а не настройкой (SPEC 4.4).
 */
const СЛУЖЕБНЫЕ_БЛОГА = ['tags', 'page', 'archive', 'authors'];

/**
 * Страницы будущего сайта по файлам статей. `версии` — `{путь, slug, черновик}` каждого файла статьи
 * в основе плюс плане. Возвращает `{живые, все, файлы}`: адреса, которые сайт выпустит; все адреса,
 * включая черновики (по ним видно устройство разделов); пути файлов, у которых есть страница.
 *
 * Статья без версии обязательного языка не собирается вовсе. Язык без своего файла отдаёт под
 * своим адресом текст обязательного языка. Черновик страницы не даёт; черновик обязательного языка
 * при живом своём файле другого языка страницу этого языка не отнимает — проверено не было, и
 * ложный блокер здесь хуже пропуска.
 */
export function страницыСайта(версии, сайт) {
  const группы = new Map();
  for (const версия of версии ?? []) {
    const место = articlePlace(версия.путь, сайт.roots);
    if (!место.наСайте || (место.kind !== 'docs' && место.kind !== 'blog')) continue;
    // Служебное имя Docusaurus не собирает вовсе (SPEC 2.7): страницы у такого файла нет.
    if (место.inside.split('/').some(служебноеИмя)) continue;
    const ключ = `${место.kind}|${место.inside}`;
    if (!группы.has(ключ)) группы.set(ключ, {род: место.kind, версии: new Map()});
    группы.get(ключ).версии.set(место.locale, версия);
  }

  const живые = new Set();
  const все = new Set();
  const файлы = new Set();
  for (const группа of группы.values()) {
    const главная = группа.версии.get(сайт.обязательный);
    if (!главная) continue;
    const локали = [...new Set(сайт.roots.filter((root) => root['род'] === группа.род && root['наСайте'] === true).map((root) => root['локаль']))];
    for (const локаль of локали) {
      const своя = группа.версии.get(локаль);
      const версия = своя ?? главная;
      const адрес = адресВЯзыке(адресПоSlug(версия.путь, версия.slug, сайт.roots, сайт.префиксБлога), локаль, сайт.обязательный);
      if (адрес === '') continue;
      все.add(адрес);
      if (версия.черновик) continue;
      живые.add(адрес);
      if (своя) файлы.add(своя.путь);
    }
  }

  return {живые, все, файлы};
}

/** Адрес без префикса языка: устройство разделов у всех языков одно. */
function безЯзыка(адрес, локали) {
  const код = локали.find((локаль) => адрес === `/${локаль}` || адрес.startsWith(`/${локаль}/`));
  return код === undefined ? адрес : (адрес.slice(код.length + 1) || '/');
}

/**
 * Берётся ли правило судить об адресе. Нет — если это страница раздела (под ней живут страницы),
 * служебный адрес блога, файл, адрес в один шаг или адрес там, где страниц нет вовсе.
 */
function судимый(адрес, страницы, сайт) {
  const свой = безЯзыка(адрес, сайт.локали);
  const шаги = свой.split('/').filter(Boolean);
  if (шаги.length < 2 || шаги.at(-1).includes('.')) return false;
  if (`/${шаги[0]}` === сайт.префиксБлога && СЛУЖЕБНЫЕ_БЛОГА.includes(шаги[1])) return false;

  const известные = [...страницы.все].map((страница) => безЯзыка(страница, сайт.локали));
  if (известные.some((страница) => страница.startsWith(`${свой}/`))) return false;
  const родитель = `/${шаги.slice(0, -1).join('/')}`;
  return известные.some((страница) => страница.startsWith(`${родитель}/`));
}

/**
 * Ссылки изменённых документов против будущего сайта. `документы` — `{путь, текст}`; `страницы` —
 * ответ `страницыСайта`. Ссылка на страницу, которой не будет, — блокер `ссылкаВНикуда` с местом;
 * адрес, о котором правило не судит, — предупреждение `ссылкаНеПроверена`. Якоря не проверяются.
 */
export function проверитьСсылки(документы, страницы, сайт) {
  const найдено = [];
  for (const документ of документы ?? []) {
    const откуда = {
      путь: документ.путь,
      локаль: articlePlace(документ.путь, сайт.roots).locale,
      адрес: адресВерсии(документ.путь, документ.текст, сайт),
      хост: сайт.хост,
      обязательный: сайт.обязательный,
      локали: сайт.локали,
    };
    for (const ссылка of ссылкиТекста(документ.текст)) {
      if (ссылка.картинка) continue;
      const куда = кудаВедёт(ссылка.цель, откуда);
      if (куда === null) continue;
      const место = {этап: 'ссылки', путь: документ.путь, строка: ссылка.строка, значение: ссылка.цель, текст: ссылка.подпись || ссылка.цель};

      if (куда.файл !== undefined) {
        if (страницы.файлы.has(куда.файл)) continue;
        const нашФайл = articlePlace(куда.файл, сайт.roots).наСайте;
        найдено.push(находка({...место, код: нашФайл ? 'ссылкаВНикуда' : 'ссылкаНеПроверена', уровень: нашФайл ? БЛОКЕР : ПРЕДУПРЕЖДЕНИЕ}));
        continue;
      }
      if (страницы.живые.has(куда.адрес)) continue;
      const доказано = судимый(куда.адрес, страницы, сайт);
      найдено.push(находка({...место, код: доказано ? 'ссылкаВНикуда' : 'ссылкаНеПроверена', уровень: доказано ? БЛОКЕР : ПРЕДУПРЕЖДЕНИЕ}));
    }
  }
  return найдено;
}

/**
 * Путь файла на сайте по ссылке из документа: картинки, обложки и `import`. Внешний адрес, данные
 * и выражение — `null`: судить о них нечем. Абсолютный путь ведёт в `static/`, `@site/` — в корень.
 */
export function путьФайла(цель, откуда) {
  const голая = String(цель ?? '').trim().replace(/^<(.*)>$/s, '$1').split(/[?#]/)[0];
  if (голая === '' || /^[a-z][a-z0-9+.-]*:/i.test(голая) || голая.startsWith('//') || /[{}()]/.test(голая)) return null;
  let раскрыто = голая;
  try {
    раскрыто = decodeURIComponent(голая);
  } catch {
    // Испорченная запись остаётся как есть.
  }
  if (раскрыто.startsWith('@site/')) return раскрыто.slice('@site/'.length);
  if (раскрыто.startsWith('/')) return `static${раскрыто}`;
  if (раскрыто.startsWith('@')) return null;

  // Адрес кодирует не-латинские буквы процентами: путь файла обязан вернуться к своему имени.
  const папка = откуда.slice(0, откуда.lastIndexOf('/') + 1);
  const путь = new URL(раскрыто.replace(/%/g, '%25'), `https://файл/${папка}`).pathname;
  try {
    return decodeURIComponent(путь).slice(1);
  } catch {
    return путь.slice(1);
  }
}

/**
 * Картинки тела и обложка в шапке. `естьФайл(путь)` — лежит ли файл на будущем сайте. Картинки нет —
 * блокер `картинкиНет` с местом (15 упавших сборок июня 2026), обложки нет — блокер `обложкиНет`.
 */
export function проверитьКартинки(документы, естьФайл) {
  const найдено = [];
  for (const документ of документы ?? []) {
    for (const ссылка of ссылкиТекста(документ.текст)) {
      if (!ссылка.картинка) continue;
      const путь = путьФайла(ссылка.цель, документ.путь);
      if (путь !== null && !естьФайл(путь)) {
        найдено.push(находка({код: 'картинкиНет', уровень: БЛОКЕР, этап: 'картинки', путь: документ.путь, строка: ссылка.строка, значение: ссылка.цель}));
      }
    }
    const обложка = readField(splitArticle(документ.текст).frontmatterRaw, 'image').trim();
    const путь = обложка === '' ? null : путьФайла(обложка, документ.путь);
    if (путь !== null && !естьФайл(путь)) {
      найдено.push(находка({код: 'обложкиНет', уровень: БЛОКЕР, этап: 'шапка', путь: документ.путь, поле: 'image', значение: обложка}));
    }
  }
  return найдено;
}

/**
 * Шапка того, что уедет: `draft` и `unlisted` разом Docusaurus отвергает и роняет сборку ВСЕГО
 * сайта (проверено 2026-09-08). Публикация такой пары не пишет, но руками её поставить можно.
 */
export function проверитьШапку(документы) {
  return (документы ?? [])
    .filter((документ) => {
      const шапка = splitArticle(документ.текст).frontmatterRaw;
      return черновикСайта(шапка) && isUnlisted(шапка);
    })
    .map((документ) => находка({код: 'черновикИСкрыта', уровень: БЛОКЕР, этап: 'шапка', путь: документ.путь}));
}

/** `import` вне кода: имена, которые он вводит, и откуда. */
function импорты(текст) {
  const итог = [];
  for (const кусок of кускиБезКода(текст)) {
    if (кусок.код) continue;
    for (const м of кусок.текст.matchAll(/^import\s+([\s\S]+?)\s+from\s+['"]([^'"]+)['"];?[ \t]*$/gm)) {
      const имена = м[1].replace(/[{}]/g, ',').split(',').map((часть) => часть.trim().split(/\s+as\s+/).pop().replace(/^\*\s*/, '').trim()).filter(Boolean);
      итог.push({имена, откуда: м[2], место: м.index});
    }
  }
  return итог;
}

/**
 * JSX-компоненты тела. Имя с большой буквы обязано быть в `известные` (ключи `src/theme/MDXComponents.js`
 * сайта) или прийти `import` в самом документе: иначе страница падает при сборке. Строчные теги —
 * обычный HTML, о них сборка не спорит. `известные === null` — перечень прочитать не удалось:
 * одно предупреждение `компонентыНеПроверены`, а не блокер.
 *
 * `import` относительного файла, которого нет, — блокер `импортНеНайден`; `import` пакета —
 * предупреждение `импортВMdx`: что там лежит, правило не знает.
 */
export function проверитьКомпоненты(документы, известные, естьФайл) {
  const найдено = [];
  if (известные === null && (документы ?? []).length > 0) {
    найдено.push(находка({код: 'компонентыНеПроверены', уровень: ПРЕДУПРЕЖДЕНИЕ, этап: 'mdx'}));
  }
  for (const документ of документы ?? []) {
    const {body} = splitArticle(документ.текст);
    const строкаВ = (место) => body.slice(0, место).split('\n').length;
    const свои = new Set();
    for (const импорт of импорты(body)) {
      импорт.имена.forEach((имя) => свои.add(имя));
      const место = {этап: 'mdx', путь: документ.путь, строка: строкаВ(импорт.место), значение: импорт.откуда};
      if (!импорт.откуда.startsWith('.')) {
        if (!импорт.откуда.startsWith('@site/')) найдено.push(находка({...место, код: 'импортВMdx', уровень: ПРЕДУПРЕЖДЕНИЕ}));
        continue;
      }
      if (!естьФайл(путьФайла(импорт.откуда, документ.путь))) найдено.push(находка({...место, код: 'импортНеНайден', уровень: БЛОКЕР}));
    }
    if (известные === null) continue;

    let смещение = 0;
    const названные = new Set();
    for (const кусок of кускиБезКода(body)) {
      if (!кусок.код) {
        const строчный = [...кусок.текст.matchAll(/(`+)[\s\S]*?\1/g)].map((м) => [м.index, м.index + м[0].length]);
        for (const м of кусок.текст.matchAll(/<([A-Z][\w]*)(?:\.[\w.]+)?(?=[\s/>])/g)) {
          const имя = м[1];
          if (строчный.some(([от, до]) => м.index >= от && м.index < до)) continue;
          if (известные.has(имя) || свои.has(имя) || названные.has(имя)) continue;
          названные.add(имя);
          найдено.push(находка({код: 'компонентНеизвестен', уровень: БЛОКЕР, этап: 'mdx', путь: документ.путь, строка: строкаВ(смещение + м.index), значение: имя}));
        }
      }
      смещение += кусок.текст.length;
    }
  }
  return найдено;
}

/**
 * Имена, которые объявляет файл глобальных компонентов MDX: ключи объекта (`CTA,`, `truncate: …`)
 * и признак распространения чужого перечня (`...MDXComponents`). Файл читается текстом, без
 * исполнения: импорт потянул бы весь сайт (как у `siteConfig.mjs`).
 */
export function ключиКомпонентов(текст) {
  const имена = new Set();
  let распространяет = false;
  const тело = /(?:export\s+default|=)\s*\{([\s\S]*)\}/.exec(String(текст ?? ''))?.[1] ?? '';
  for (const строка of тело.split('\n')) {
    const чистая = строка.replace(/\/\/.*$/, '').trim();
    if (/^\.\.\.\s*[A-Za-z_$]/.test(чистая)) распространяет = true;
    const ключ = /^([A-Za-z_$][\w$]*)\s*[,:(]/.exec(чистая) ?? /^([A-Za-z_$][\w$]*)\s*$/.exec(чистая);
    if (ключ) имена.add(ключ[1]);
  }
  return {имена, распространяет};
}
