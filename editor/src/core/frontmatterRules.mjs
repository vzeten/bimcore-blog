// Защитные правила шапки статьи, спасённые из прежней CMS.
// Единственное место, где они записаны: модуль общий для сервера и проверок.
// Нарушение любого из них роняет сборку всего сайта или ломает связь языков.

import {безКавычек, headLine, headLines} from './articleFile.mjs';

/**
 * Какого рода статья, на каком языке и какой у неё путь внутри своего раздела.
 * Корни приходят из настроек: код не знает, где лежит контент сайта.
 * Совпадений может быть несколько — берётся самое длинное, иначе вложенная папка
 * проиграет своему родителю.
 */
export function articlePlace(path, roots) {
  const clean = path.split('\\').join('/');

  const matched = [...roots]
    .filter((root) => clean.startsWith(`${root['папка']}/`))
    .sort((a, b) => b['папка'].length - a['папка'].length)[0];

  if (!matched) return {kind: 'вне контента', locale: null, inside: clean, наСайте: false};

  return {
    kind: matched['род'],
    locale: matched['локаль'],
    inside: clean.slice(matched['папка'].length + 1),
    наСайте: matched['наСайте'] === true,
  };
}

/**
 * Папки над статьёй внутри её раздела: у `guides/families/chairs/index.mdx` это `guides/families`.
 * Одно правило на два применения — адрес статьи и дерево разделов.
 */
export function folderChain(inside) {
  const parts = inside.split('/').filter(Boolean);
  parts.pop();
  return parts.slice(0, -1);
}

/**
 * Адрес статьи по правилам сайта: у документации абсолютный с префиксом раздела,
 * у блога относительный. Локаль в адрес не попадает — её добавляет сам сайт.
 * Уже абсолютный адрес не переписывается, иначе раздел задвоится.
 */
export function normalizeSlug(path, slug, roots) {
  const value = String(slug ?? '').trim();
  if (value === '') return value;

  const place = articlePlace(path, roots);
  if (place.kind === 'blog') return value.replace(/^\/+/, '');
  if (place.kind !== 'docs') return value;
  if (value.startsWith('/')) return value;

  return `/${[...folderChain(place.inside), value].join('/')}`;
}

/**
 * Видимость статьи живёт в её шапке: `unlisted` — поле Docusaurus, а не наша выдумка,
 * поэтому имя поля в коде. Хранить видимость ещё и в состоянии нельзя: сайт читает только шапку.
 */
export const ПОЛЕ_ВИДИМОСТИ = 'unlisted';

/**
 * Читается ли значение поля `unlisted` как «скрыта». Одно правило на всю программу: им пользуется
 * и чтение шапки целиком, и разбор поля в человеческий вид. Разойдись они — окно показывало бы
 * флажок снятым у статьи, которую сайт прячет.
 */
export function скрытоеЗначение(значение) {
  return /^\s*true\s*$/.test(String(значение ?? ''));
}

export function isUnlisted(frontmatterRaw) {
  const строка = headLines(frontmatterRaw)
    .map(headLine)
    .find((line) => line.startsWith(`${ПОЛЕ_ВИДИМОСТИ}:`));

  return строка === undefined ? false : скрытоеЗначение(строка.slice(ПОЛЕ_ВИДИМОСТИ.length + 1));
}

/**
 * Переключение видимости. Остальные строки шапки не трогаются вовсе.
 * Строка, ставшая последней, теряет одинокий `\r`: следом идёт свой перевод строки, и вдвоём
 * они дают `\r\r\n`, после которого последнее поле шапки перестаёт читаться.
 */
export function setUnlisted(frontmatterRaw, hidden) {
  const lines = headLines(frontmatterRaw);
  const at = lines.findIndex((line) => headLine(line).startsWith(`${ПОЛЕ_ВИДИМОСТИ}:`));

  if (!hidden) {
    const без = lines.filter((line, index) => index !== at);
    if (без.length > 0) без[без.length - 1] = headLine(без[без.length - 1]);
    return без.join('\n');
  }
  if (at >= 0) {
    lines[at] = `${ПОЛЕ_ВИДИМОСТИ}: true`;
    return lines.join('\n');
  }

  const tail = [...lines];
  while (tail.length > 0 && tail[tail.length - 1].trim() === '') tail.pop();
  if (tail.length > 0) tail[tail.length - 1] = headLine(tail[tail.length - 1]);

  return [...tail, `${ПОЛЕ_ВИДИМОСТИ}: true`].join('\n');
}

/** Пустое или пробельное поле обложки роняет сборку всего сайта, поэтому ключ убирается целиком. */
export function isEmptyImage(value) {
  return String(value ?? '').trim() === '';
}

/**
 * Пустой список в шапке: `keywords: []` роняет сборку сайта (Docusaurus требует в этом поле
 * хотя бы одно значение), а `tags: []` хоть и проходит, но пустым полем ничего не сообщает.
 * Найдено репетицией выпуска 2026-08-10: блог-статья, созданная программой, не собиралась.
 */
export function пустойСписок(значение) {
  return /^\[\s*\]$/.test(String(значение ?? '').trim());
}

/**
 * Поля, значение которых Docusaurus обязан прочитать строкой. Пишутся в кавычках всегда:
 * пустое описание без кавычек YAML читает как `null`, и сборка падает на «must be a string»,
 * а заголовок вроде `Ошибка: что делать` без кавычек — вовсе не читается.
 */
const СТРОКОВЫЕ = ['title', 'sidebar_label', 'description'];

/** Обязано ли поле быть строкой. Одно место правила: им пользуется и правка, и создание статьи. */
export const строковоеПоле = (key) => СТРОКОВЫЕ.includes(key);

/**
 * Знаки, с которых YAML начинает не строку: список, ссылку, метку, блок, комментарий.
 * Первый знак значения решает, чем оно окажется, поэтому проверяется отдельно от остального.
 */
const ОПАСНОЕ_НАЧАЛО = '-?:,[]{}#&*!|>\'"%@`';

/**
 * Нужны ли значению кавычки, чтобы YAML прочитал его тем же текстом. Проверка консервативная:
 * без нужды кавычки не ставятся, иначе `sidebar_position: 1` стало бы строкой.
 */
export function нужныКавычки(значение) {
  const текст = String(значение ?? '');
  if (текст === '' || текст !== текст.trim()) return true;
  if (ОПАСНОЕ_НАЧАЛО.includes(текст[0])) return true;
  // Двоеточие с пробелом разбивает строку на пару «ключ — значение», решётка с пробелом
  // отрезает всё, что после неё: и то и другое молча теряет текст человека.
  return /:\s/.test(текст) || текст.endsWith(':') || /\s#/.test(текст);
}

/** Слова, которые YAML читает не словами, а да-нет или пустотой. */
const ЛИТЕРАЛЫ = /^(true|false|null|~|yes|no|on|off)$/i;

/**
 * Прочитает ли YAML это значение не строкой: числом, да-нет, пустотой или датой.
 * Нужно там, где значение обязано остаться текстом: адрес статьи из одних цифр (`slug: 2026`)
 * без кавычек станет числом, а Docusaurus ждёт в этом поле строку.
 */
export function читаетсяНеСтрокой(значение) {
  const текст = String(значение ?? '').trim();
  if (текст === '') return false;
  if (ЛИТЕРАЛЫ.test(текст)) return true;
  if (/^[+-]?(\d+\.?\d*|\.\d+)([eE][+-]?\d+)?$/.test(текст)) return true;
  return /^\d{4}-\d{2}-\d{2}/.test(текст);
}

/**
 * Адрес статьи в том виде, в каком он ляжет в шапку. Одно место правила: им пользуется и правка
 * шапки в окне, и создание статьи, иначе адрес выглядел бы по-разному у одинаковых статей.
 */
export function адресВШапку(адрес) {
  return нужныКавычки(адрес) || читаетсяНеСтрокой(адрес) ? вКавычках(адрес) : адрес;
}

/**
 * Значение в двойных кавычках. Обратный слеш и кавычка экранируются, переводы строк заменяются
 * пробелом: многострочное значение в одной строке шапки — это уже не YAML.
 *
 * Прочие пробелы остаются как есть. Схлопывать их значило бы тихо править текст человека:
 * два пробела подряд он поставил сам, и молча склеивать их программа не вправе.
 */
export function вКавычках(значение) {
  const текст = String(значение ?? '')
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/[\r\n]+/g, ' ');
  return `"${текст}"`;
}

/** Адреса разных языков одной статьи обязаны совпадать, иначе ломается переключатель языка. */
export function sameSlugAcrossLocales(ownSlug, otherSlug) {
  return String(ownSlug ?? '').trim() === String(otherSlug ?? '').trim();
}

/**
 * Приводит строки шапки в безопасный вид.
 * Возвращает новый текст шапки и список того, что было исправлено.
 */
export function safeFrontmatter(path, raw, roots) {
  const fixed = [];
  const lines = headLines(raw);
  const out = [];

  for (const line of lines) {
    const found = /^([A-Za-z_][\w-]*):\s?(.*)$/.exec(headLine(line));
    if (!found) {
      out.push(line);
      continue;
    }

    const [, key, value] = found;

    if (key === 'image' && isEmptyImage(value)) {
      fixed.push('убрано пустое поле обложки: оно роняет сборку сайта');
      continue;
    }

    // Убирается только то, что роняет сборку: пустые `keywords` Docusaurus не принимает вовсе.
    // Пустой `tags` сборку проходит, и переписывать из-за него чужой файл при каждом сохранении
    // нельзя (SPEC 5.1) — его уберёт правка шапки, когда человек сам очистит поле.
    //
    // И только форма со скобками. Список, расписанный строками ниже (`keywords:` и под ним
    // `- слово`), для построчного разбора выглядит так же пусто, но он не пустой: тронь эту
    // строку — и элементы под ней осиротеют.
    if (key === 'keywords' && пустойСписок(value)) {
      fixed.push('убрано пустое поле ключевых слов: оно роняет сборку сайта');
      continue;
    }

    if (key === 'slug') {
      // Кавычки снимаются до нормализации: адрес из одних цифр записан в кавычках, и без этого
      // правило приняло бы кавычку за часть адреса и выдало бы `/lessons/"2026"`.
      const запись = String(value).trim();
      const голый = безКавычек(запись);
      const next = normalizeSlug(path, голый, roots);
      // Строка переписывается только по делу: адрес не по правилу раздела, либо запись без
      // кавычек, которую YAML прочитает не строкой (`slug: 2026` станет числом). Кавычки, уже
      // стоящие в файле, сами поводом не являются: одиночные YAML читает строкой не хуже
      // двойных, и менять их значило бы переписывать файл на пустом месте (SPEC 5.1).
      const надо = next !== голый || (запись === голый && читаетсяНеСтрокой(запись));
      if (надо) {
        fixed.push(`адрес статьи приведён к правилу раздела: ${голый} → ${next}`);
        out.push(`${key}: ${адресВШапку(next)}`);
        continue;
      }
    }

    out.push(line);
  }

  return {frontmatterRaw: out.join('\n'), fixed};
}
