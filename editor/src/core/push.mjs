// Правила отправки статьи на сайт. Отправка в `main` = публикация (SPEC 1.2), поэтому здесь
// заслон, а не помощник: любой невыясненный признак — отказ.
//
// **Уезжает один названный коммит, а не ветка.** Публикационный коммит стоит поверх свежей основы
// сервера и в местные ветки не попадает; текущая ветка и `HEAD` человека правилу не нужны вовсе.
// Тем не менее правило смотрит на каждый коммит диапазона между основой и отправляемым и на каждый
// путь в нём: так оно ловит и переписанную историю, и запись, подложенную мимо программы.
//
// **Второй заслон — против обхода показа.** Согласие человека относится к тому набору, который ему
// показали: и коммит, и сам набор сверяются с показанным. Запрос мимо окна отправки не делает.
//
// Чистые правила: на входе факты, собранные адаптером, на выходе решение. Ни git, ни сети здесь
// нет (SPEC 4.6).

/**
 * Можно ли отправлять и что именно уедет.
 *
 * `коммитSha` — полный SHA коммита, который ждёт отправки; `удалённыйSha` — полный SHA удалённой
 * ветки, только что прочитанный с сервера (`null` — спросить не удалось); `отставание` — на
 * сколько коммитов удалённая ветка впереди отправляемого (`null` — сосчитать не удалось);
 * `коммиты` — что уедет, каждый со своими путями и числом родителей (`null` — прочитать не
 * удалось); `разрешённыеПути` — всё, что вообще принадлежит этой статье, и ничего кроме;
 * `нашиКоммиты` — карта «SHA → пути», записанная самой программой при каждой её записи.
 *
 * Только для самой отправки: `сверятьСогласие` — включает три проверки согласия, `показанныйSha` и
 * `показанныйНабор` — что человеку показали, `наборСейчас` — то же, посчитанное заново.
 *
 * Возвращает `{ошибка}` либо `{коммиты, файлы, уже}`; `уже` — этот коммит на сайте уже есть.
 */
export function решениеОбОтправке({
  коммитSha,
  удалённыйSha,
  отставание,
  коммиты,
  разрешённыеПути,
  нашиКоммиты = null,
  сверятьСогласие = false,
  ожидаемыйSha = null,
  показанныйSha = null,
  показанныйНабор = null,
  наборСейчас = null,
}) {
  // Чей это коммит, доказывает не путь в нём, а запись программы о том, что она его сделала.
  // Пути доказательством быть не могут: ручной коммит в ту же статью по путям выглядит точно так же.
  // Записи нет вовсе — это «не знаю», и отправлять вслепую нельзя.
  const свои = нашиКоммиты instanceof Map ? нашиКоммиты : null;
  if (свои === null) return {ошибка: 'очередьБитая'};

  // Удалённую ветку не прочитали — не знаем, что уедет. Старому ответу веры нет: пока человек
  // читал перечень, на сайт могли толкнуть с другой машины.
  if (непусто(удалённыйSha) === false) return {ошибка: 'удалённыйНеизвестен'};
  if (непусто(коммитSha) === false) return {ошибка: 'нечегоОтправлять'};

  // Отправлять нечего, потому что всё уже там. Это успех, а не отказ: так выглядит повтор после
  // оборванной связи, когда сервер сайта запрос всё-таки принял. Проверяется ДО согласия и до
  // происхождения: когда везти нечего, спрашивать «чей это коммит» не о чем.
  if (удалённыйSha === коммитSha) return {уже: true, коммиты: [], файлы: []};

  if (сверятьСогласие) {
    // Согласие пришло на другой коммит, чем ждёт отправки сейчас. Память о показе одна на сервер,
    // поэтому без этой сверки согласие, данное в одном окне, отправило бы то, что успели
    // подготовить в другом.
    if (ожидаемыйSha !== коммитSha) return {ошибка: 'головаСместилась', голова: коммитSha};
    // Коммит сделан не этой программой: значит он не проходил ни проверок, ни полной сборки на
    // наших глазах, и отправлять его нам нечем доказать.
    if (!свои.has(коммитSha)) return {ошибка: 'неНашКоммит'};
    // Показа не было вовсе — запрос пришёл мимо окна.
    if (непусто(показанныйSha) === false) return {ошибка: 'показаНеБыло'};
    // Показали одно, отправляем другое: между показом и словом человека что-то изменилось.
    if (показанныйSha !== коммитSha || показанныйНабор !== наборСейчас) {
      return {ошибка: 'показУстарел'};
    }
  }

  // Сосчитать отставание не удалось — это «не знаю», а не «ноль».
  if (typeof отставание !== 'number' || Number.isNaN(отставание)) return {ошибка: 'удалённыйНеизвестен'};

  // Удалённая ветка ушла вперёд: основа коммита уже не вершина сайта. Никакого `pull`, `merge` и
  // `rebase` программа не делает — коммит устарел, и статью публикуют заново новым планом.
  if (отставание > 0) return {ошибка: 'основаУстарела', отставание};

  if (!Array.isArray(коммиты)) return {ошибка: 'удалённыйНеизвестен'};
  if (коммиты.length === 0) return {ошибка: 'нечегоОтправлять'};

  // Слияние показывает свои файлы иначе, чем обычный коммит: перечень путей у него пуст, и
  // «чужих файлов нет» означало бы «мы их не посмотрели». Отказ честнее.
  if (коммиты.some((коммит) => Number(коммит.родителей) > 1)) return {ошибка: 'слияниеВпереди'};

  // **Каждый уезжающий коммит обязан быть нашим, и это проверяется по записи, а не по путям.**
  // Ручной коммит, сделанный человеком в ту же статью руками, по путям неотличим от нашего, но
  // проверок и полной сборки он не проходил, и везти его программе нечем доказать.
  const неНаши = коммиты.filter((коммит) => !свои.has(коммит.sha)).map((коммит) => коммит.sha);
  if (неНаши.length > 0) return {ошибка: 'неНашиКоммиты', неНаши};

  // Содержимое коммита обязано совпасть с тем, что программа о нём записала: разошлось — значит
  // историю переписали после нас, и запись больше ничего не доказывает.
  const переписан = коммиты.some((коммит) => разошлись(коммит.файлы ?? [], свои.get(коммит.sha)));
  if (переписан) return {ошибка: 'неНашиКоммиты', неНаши: коммиты.map((коммит) => коммит.sha)};

  const разрешено = new Set(разрешённыеПути ?? []);

  const файлы = [];
  const чужие = [];
  for (const коммит of коммиты) {
    for (const путь of коммит.файлы ?? []) {
      if (!файлы.includes(путь)) файлы.push(путь);
      if (разрешено.has(путь)) continue;
      if (!чужие.includes(путь)) чужие.push(путь);
    }
  }

  // Разрешён ровно состав этой статьи и больше ничего. Публикация статьи трогает статью — работа
  // над самой программой, правила помощникам и настройки сайта уезжать вместе с ней не должны
  // (решение владельца 2026-08-15, отменившее список служебных путей).
  if (чужие.length > 0) return {ошибка: 'чужиеФайлы', чужие};

  return {коммиты: коммиты.map((коммит) => коммит.sha), файлы, уже: false};
}

/**
 * Отпечаток показанного набора: по нему видно, тот ли это набор, который человек читал перед
 * согласием. Считается по коммитам и их путям, а не по одному SHA: коммит мог остаться прежним, а
 * перечень уезжающего измениться — например, ветку на сервере откатили назад.
 */
export function отпечатокНабора(коммиты) {
  return (Array.isArray(коммиты) ? коммиты : [])
    .map((коммит) => [коммит.sha, ...(коммит.файлы ?? [])].join('\n'))
    .join('\n--\n');
}

const непусто = (значение) => typeof значение === 'string' && значение !== '';

/** Разошлись ли перечни путей. Порядок неважен, состав важен. */
function разошлись(фактические, записанные) {
  const было = new Set(записанные ?? []);
  if (было.size !== фактические.length) return true;

  return фактические.some((путь) => !было.has(путь));
}
