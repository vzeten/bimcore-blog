// Поля шапки статьи в человеческом виде: без квадратных скобок у списков, без кавычек у строк,
// короткий адрес вместо полного. Чистые функции, единое место правила.
//
// Железный инвариант: поле, которого человек не касался, при сборке возвращается ДОСЛОВНО.
// Поэтому «изменилось ли поле» решается по показанному значению, а не по обратной сборке:
// нетронутое показанное значение → исходная строка файла как есть.

import {безКавычек, headGroups, headLine, значениеГруппы} from './articleFile.mjs';
import {
  ПОЛЕ_ВИДИМОСТИ, адресВШапку, вКавычках, isEmptyImage, normalizeSlug, нужныКавычки,
  пустоеЗначение, скрытоеЗначение, строковоеПоле,
} from './frontmatterRules.mjs';

// Имена полей задал Docusaurus, не мы, — это чужой формат, а не наша настройка.
// Наружу список отдаётся затем, чтобы окно не заводило рядом свой: два перечня одних и тех же
// полей разошлись бы при первом же изменении, и поле показывалось бы не тем видом, каким пишется.
export const СПИСКИ = ['tags', 'authors', 'keywords'];

// Снятие кавычек — одно правило на всю программу, живёт в `articleFile.mjs`: человек не должен
// видеть YAML-синтаксис ни в свойствах статьи, ни в списке статей, ни в шапке окна.
const снятьКавычки = безКавычек;

/**
 * Поле куска в человеческом виде. Списки идут через YAML-разбор, остальные поля — через разбор
 * строки: у них значение и есть строка, и второй разбор ничего не добавил бы.
 */
export function полеГруппы(группа, path, roots) {
  const {ok, значение} = группа.строки.length > 1 || СПИСКИ.includes(группа.ключ)
    ? значениеГруппы(группа)
    : {ok: false, значение: null};

  // Значение, занявшее в файле не одну строку (перенос YAML или блочный скаляр `|`), в одну строку
  // ввода не поместится без потери переводов строк, поэтому оно только показывается. Показывается
  // при этом прочитанное значение, а не сырые строки файла: YAML-синтаксиса вроде ведущего `|`
  // человек видеть не должен нигде (правило этого модуля).
  if (!СПИСКИ.includes(группа.ключ)) {
    if (группа.строки.length === 1) return parseField(группа.ключ, группа.значение, path, roots);

    return {
      kind: 'заперто',
      причина: 'многострочное',
      display: ok && значение !== null && значение !== undefined && typeof значение !== 'object'
        ? String(значение).replace(/\s*\n\s*/g, ' ').trim()
        : сыроеЗначение(группа),
    };
  }

  // Ключ без значения и без элементов YAML читает пустотой. Человеку это пустое поле, которое
  // он заполнит; в файле пустым оно не останется — строка уйдёт целиком (пустых ключей не бывает).
  if (ok && (значение === null || значение === undefined)) return {kind: 'list', display: ''};
  if (!ok) return {kind: 'заперто', причина: 'неПрочитано', display: сыроеЗначение(группа)};

  // Значение прочиталось, но списком не является: `keywords: розетки` вместо перечня. Сказать здесь
  // «прочитать не смогла» значит соврать человеку, у которого слово стоит прямо перед глазами.
  if (!Array.isArray(значение)) {
    return {kind: 'заперто', причина: 'этоНеСписок', display: String(значение)};
  }

  // Элемент списка сам может быть не словом, а записью с полями: так Docusaurus разрешает писать
  // авторов блога (`- name: … title: …`). Строкой такой элемент показать нечем — вышло бы
  // `[object Object]`, — а правка строки записала бы эту бессмыслицу в файл поверх настоящих
  // значений. Поле показывается куском файла и не правится.
  if (значение.some((item) => item !== null && typeof item === 'object')) {
    return {kind: 'заперто', причина: 'сложныйСписок', display: сыроеЗначение(группа)};
  }

  const элементы = значение.map((item) => String(item ?? ''));

  // Запятая внутри самого элемента. Значение программа прочитала, а вот принять правку обратно
  // не может: в поле элементы разделяются запятыми, и такой элемент вернулся бы двумя. Причина
  // у этого запрета своя, и человеку называется своя — файл-то в порядке.
  if (элементы.some((item) => item.includes(','))) {
    return {kind: 'заперто', причина: 'запятаяВЭлементе', display: элементы.join(', ')};
  }

  return {kind: 'list', display: элементы.join(', ')};
}

/** Значение куска как оно записано в файле — для поля, которое программа прочитать не смогла. */
function сыроеЗначение(группа) {
  const первая = headLine(группа.строки[0]).slice(группа.ключ.length + 1).trim();
  const остальные = группа.строки.slice(1).map((line) => headLine(line).trim());

  return [первая, ...остальные].filter(Boolean).join(' ');
}

/** Какого рода поле и как показать его значение человеку. */
export function parseField(key, raw, path, roots) {
  const value = String(raw ?? '');
  const trimmed = value.trim();

  // Видимость — «да» или «нет», и человек видит её флажком, а не словом `true` в строке ввода.
  // Читается тем же правилом, каким видимость читает сайт: всё, кроме `true`, значит «в меню».
  if (key === ПОЛЕ_ВИДИМОСТИ) return {kind: 'флаг', display: скрытоеЗначение(value) ? 'true' : ''};

  if (key === 'slug' && trimmed !== '') {
    // Человек вводит короткий адрес; префикс раздела добавляет программа при сохранении.
    // Кавычки снимаются первым делом: адрес из одних цифр записан в кавычках, и без этого
    // человек увидел бы в поле адреса YAML-синтаксис, а следующая правка его удвоила бы.
    const голый = снятьКавычки(trimmed);
    return {kind: 'slug', display: голый.split('/').filter(Boolean).pop() ?? голый};
  }

  if ((trimmed.startsWith('"') && trimmed.endsWith('"')) || (trimmed.startsWith("'") && trimmed.endsWith("'"))) {
    return {kind: 'text', display: снятьКавычки(trimmed)};
  }

  return {kind: 'plain', display: value};
}

/**
 * Собрать значение поля обратно в строку YAML из показанного человеку вида.
 *
 * Кавычки решаются по ИМЕНИ поля, а не по тому, как значение записано сейчас: описание живых статей
 * записано без кавычек и разбирается как `plain`, но строкой быть обязано всё равно.
 */
export function formatField(key, kind, display, path, roots) {
  if (kind === 'list') {
    // Элементы берутся в кавычки все до одного. Разбирать, какой из них YAML прочитал бы неверно,
    // здесь незачем: метка, автор и ключевое слово — всегда слова, а без кавычек `true` стало бы
    // да-нет, `2026` числом, а дата — датой. Одно правило вместо списка исключений.
    const items = display.split(',').map((item) => item.trim()).filter(Boolean).map(вКавычках);
    return `[${items.join(', ')}]`;
  }

  if (kind === 'slug') return адресВШапку(normalizeSlug(path, display, roots));
  if (строковоеПоле(key) || kind === 'text') return вКавычках(display);
  return нужныКавычки(display) ? вКавычках(display) : display;
}

/** Разбор шапки в поля с человеческим видом. Многострочные и сложные значения не трогаются. */
export function readFields(raw, path, roots) {
  return разобратьШапку(raw, path, roots)
    .filter(({группа}) => группа.ключ !== null)
    .map(({группа, поле}) => ({key: группа.ключ, raw: группа.значение, ...поле}));
}

/**
 * Шапка кусками вместе с разобранным полем каждого. Одно место разбора на чтение и на сборку:
 * считай их порознь — запрет правки, увиденный окном, не помешал бы сборке переписать поле.
 */
function разобратьШапку(raw, path, roots) {
  const группы = headGroups(raw);
  // Ключ, встретившийся в шапке дважды, — сломанная шапка: YAML берёт последнее значение, окно
  // показало бы два одинаковых поля, а правка верхнего пропадала бы молча. Правится в файле.
  const дважды = группы.map((группа) => группа.ключ)
    .filter((ключ, i, все) => ключ !== null && все.indexOf(ключ) !== i);

  return группы.map((группа) => ({
    группа,
    поле: группа.ключ === null ? null
      : дважды.includes(группа.ключ)
        ? {kind: 'заперто', причина: 'ключДважды', display: сыроеЗначение(группа)}
        : полеГруппы(группа, path, roots),
  }));
}

/**
 * Собрать шапку обратно. Поля, чей показанный вид не менялся, возвращаются исходной строкой.
 * Только по-настоящему изменённое поле переписывается — иначе файл дрожит на ровном месте.
 *
 * `порядок` — принятый порядок полей шапки для этого рода статей (настройка `поляСоздания`).
 * По нему кладётся поле, которого в шапке ещё не было: место строки берётся из общего правила,
 * а не выбирается наугад, иначе одинаковые статьи расходятся видом шапки.
 */
export function writeFields(raw, fields, path, roots, порядок = []) {
  const byKey = new Map(fields.map((field) => [field.key, field]));

  const собранные = разобратьШапку(raw, path, roots)
    .map(({группа, поле: исходное}) => {
      if (группа.ключ === null || !byKey.has(группа.ключ)) return группа;
      // Строку видимости пишет одно правило ядра (`setUnlisted`), и общий сбор полей её не трогает
      // ни здесь, ни при дописывании: два писателя одной строки разошлись бы при первой же
      // правке правила (SPEC 4.3).
      if (группа.ключ === ПОЛЕ_ВИДИМОСТИ) return группа;

      const field = byKey.get(группа.ключ);

      // Поле, которое программа не может записать обратно без потери, не переписывается никогда:
      // непрочитанное значение, список с запятой внутри элемента, многострочное значение,
      // повторяющийся ключ. Причина у каждого своя, поведение одно.
      //
      // Проверка стоит ПЕРВОЙ, раньше даже пустой обложки: у шапки с двумя строками `image`, где
      // вторая пуста, запертой оказывается обложка — и уборка пустой строки, идя раньше, стирала
      // бы её сама, без действия человека. «Открыл и сохранил — ни байта» (SPEC 5.1) на такой
      // шапке переставало держаться, а окно в это же время говорило «правится только в файле».
      if (исходное.kind === 'заперто') return группа;

      // Обложка без значения из шапки убирается целиком: пустое `image` роняет сборку сайта
      // (SPEC 2.1). Прочие поля пустыми жить могут — их заполняет человек.
      if (field.key === 'image' && isEmptyImage(field.display)) return null;
      if (field.display === исходное.display) return группа;

      const значение = formatField(группа.ключ, field.kind, field.display, path, roots);
      // Пустых ключей не бывает: очищенное поле уходит из шапки строкой целиком.
      //
      // Проверка стоит ПОСЛЕ сравнения с исходным значением: нетронутый `tags: []` в чужой статье
      // убирать без действия человека нельзя, иначе одно только открытие и сохранение меняло бы
      // файл (SPEC 5.1).
      if (пустоеЗначение(field.display, значение)) return null;

      // Кусок заменяется одной строкой целиком: у списка, записанного строками `- слово`,
      // его элементы больше не принадлежат прежнему значению.
      return {...группа, строки: [`${группа.ключ}: ${значение}`]};
    })
    .filter((группа) => группа !== null);

  return дописатьНовые(собранные, fields, порядок, path, roots)
    .flatMap((группа) => группа.строки)
    .join('\n');
}

/**
 * Дописать поля, которых в шапке не было. Пустое значение не пишется вовсе: поле, которого
 * человек не заполнял, не должно появляться в файле — тем более пустая обложка (SPEC 2.1).
 */
function дописатьНовые(группы, fields, порядок, path, roots) {
  const итог = [...группы];

  for (const field of fields) {
    if (field.key === ПОЛЕ_ВИДИМОСТИ) continue;

    const ключиКусков = итог.map((группа) => группа.ключ);
    const ключи = ключиКусков.filter((ключ) => ключ !== null);
    if (ключи.includes(field.key)) continue;

    const значение = formatField(field.key, field.kind, field.display, path, roots);
    // Тем же правилом, каким строка убирается: иначе поле, которое человек только что очистил,
    // вернулось бы сюда пустыми скобками — `tags: []`, `authors: []`, `keywords: []`.
    if (пустоеЗначение(field.display, значение)) continue;

    // Поля вне принятого порядка не дописываем: места для них в шапке никто не назначал.
    const среди = местоПоля(ключи, порядок, field.key);
    if (среди < 0) continue;

    // Место считается по кускам, а не по строкам: у списка, записанного строками `- слово`,
    // строк несколько, и по номеру строки новое поле встало бы посреди чужих элементов.
    // Идти в самый конец нельзя по той же причине: в конце шапки может стоять пустая строка,
    // и поле оказалось бы за ней.
    const заПоследним = ключиКусков.lastIndexOf(ключи[ключи.length - 1]) + 1;
    const куда = среди >= ключи.length ? заПоследним : ключиКусков.indexOf(ключи[среди]);

    итог.splice(куда, 0, {ключ: field.key, значение: null, строки: [`${field.key}: ${значение}`]});
  }

  return итог;
}

/**
 * Каким по счёту встанет поле среди уже имеющихся: сразу за последним из тех, кто по принятому
 * порядку идёт раньше. Никого из них нет — перед первым, кто идёт позже; нет и таких — в конец.
 * `-1` — поля нет в принятом порядке, места для него не назначено.
 *
 * Единственное место этого правила. Считай его окно по-своему — поле показывалось бы человеку
 * не там, куда строка ляжет в файле, и после сохранения прыгало бы на другое место.
 */
export function местоПоля(ключи, порядок, ключ) {
  const место = порядок.indexOf(ключ);
  if (место < 0) return -1;

  for (let i = место - 1; i >= 0; i -= 1) {
    const свой = ключи.indexOf(порядок[i]);
    if (свой >= 0) return свой + 1;
  }

  for (let i = место + 1; i < порядок.length; i += 1) {
    const свой = ключи.indexOf(порядок[i]);
    if (свой >= 0) return свой;
  }

  return ключи.length;
}
