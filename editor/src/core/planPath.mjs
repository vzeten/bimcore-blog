// Один вопрос: годится ли путь для плана публикации.
//
// Отдельным файлом потому, что спрашивают его двое и по разным поводам: каркас — про свои пути и
// пути будущих заглушек, восстановление после обрыва — про путь, который собирается дописать на
// диск. Живи правило в одном из них, второй звал бы соседа через всю программу или, что хуже,
// написал бы себе своё — и однажды они разошлись бы.

/**
 * Годен ли путь для плана: записан ровно так, как лежит в репозитории.
 *
 * Это не придирка к виду. Путь плана станет и именем файла во временной копии, и аргументом записи
 * в git: строка с `..` указывает наружу репозитория, а обратная косая и ведущая косая попадут в git
 * не тем путём, под которым файл там записан.
 *
 * Буква диска отсекается отдельно: `C:/чужое.mdx` состоит из обычных кусков и всеми прочими
 * проверками проходит как относительный, оставаясь при этом полным путём мимо репозитория.
 */
export function годныйПутьПлана(путь) {
  if (typeof путь !== 'string' || путь === '' || путь.includes('\\')) return false;
  if (/^[A-Za-z]:/.test(путь)) return false;

  return !путь.split('/').some((кусок) => кусок === '..' || кусок === '.' || кусок === '');
}
