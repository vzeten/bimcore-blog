// Уровень пункта списка: `Tab` вкладывает пункт, `Shift+Tab` возвращает его наружу.
// Чистые правила: на входе текст статьи и выделение, на выходе — правка того же вида, что у
// кнопок панели. Ни редактора, ни синтаксического дерева здесь нет: правило работает построчно,
// поэтому второго разборщика markdown рядом со штатным не заводится.
//
// Число пробелов человек не считает. Вложенный пункт встаёт ровно в колонку содержимого своего
// родителя — это единственное правило CommonMark, по которому список остаётся списком, а не
// превращается в отдельный абзац; у `- ` колонка одна, у `10. ` другая, и обе берутся из
// самого родителя, а не из настройки «сколько пробелов».
//
// Главная опасность здесь — принять за пункт списка строку ПРОГРАММЫ. `- строка` внутри кода
// выглядит как пункт, а сдвиг отступа превратил бы код в список и молча испортил статью.
// Поэтому строки сначала размечаются одним проходом сверху: где идёт код, а где список.

import type {Edit, Selection} from './commands';

/** Пункт списка: отступ, маркер и пробелы после него. Без пробела (или конца строки) это не пункт. */
const ПУНКТ = /^([ \t]*)([-*+]|\d{1,9}[.)])([ \t]+|$)/;

/** Ограда огороженного кода: знак и его длина важны — закрывает только такая же, не короче. */
const ОГРАДА = /^[ \t]*(`{3,}|~{3,})(.*)$/;

/** Отступ, с которого начинается отступной код: четыре колонки от содержимого своего окружения. */
const КОЛОНОК_ДО_КОДА = 4;

interface Пункт {
  отступ: string;
  маркер: string;
  разрыв: string;
  /** Колонка, с которой начинается содержимое пункта: сюда встаёт вложенный в него пункт. */
  колонка: number;
}

interface Строка {
  текст: string;
  от: number;
}

interface Разметка {
  /** Колонка, с которой начинается содержимое строки. */
  отступ: number;
  /** Строка внутри кода — огороженного или отступного. Пунктом списка она быть не может. */
  код: boolean;
  /** Строка является пунктом списка. */
  пункт: Пункт | null;
}

function разобрать(строка: string): Пункт | null {
  const найдено = ПУНКТ.exec(строка);
  if (!найдено) return null;

  const [, отступ, маркер, разрыв] = найдено;
  // Пустой пункт записан как `-` без пробела: содержимое всё равно начинается через один пробел.
  const ширинаРазрыва = Math.max(разрыв.length, 1);
  return {отступ, маркер, разрыв, колонка: отступ.length + маркер.length + ширинаРазрыва};
}

function строки(текст: string): Строка[] {
  const список: Строка[] = [];
  let от = 0;
  for (const строка of текст.split('\n')) {
    список.push({текст: строка, от});
    от += строка.length + 1;
  }
  return список;
}

function номерСтроки(список: Строка[], позиция: number): number {
  for (let i = список.length - 1; i >= 0; i -= 1) {
    if (позиция >= список[i].от) return i;
  }
  return 0;
}

/** Ширина отступа в колонках: табуляция ведёт до ближайшей четвёртой, как её считает markdown. */
function ширинаОтступа(строка: string): number {
  let колонка = 0;
  for (const знак of строка) {
    if (знак === ' ') колонка += 1;
    else if (знак === '\t') колонка += 4 - (колонка % 4);
    else break;
  }
  return колонка;
}

/**
 * Разметка статьи одним проходом сверху: что здесь код, а что пункт списка.
 *
 * Проход обязателен, потому что обе беды видны только сверху. Ограду закрывает лишь ограда того же
 * знака и не короче — вложенная короткая ограда внутри длинной кода не заканчивает. А отступной код
 * начинается не «от четырёх пробелов», а от четырёх колонок относительно содержимого пункта, в
 * котором строка лежит: одна и та же строка с отступом четыре — код в обычном тексте и обычный
 * вложенный пункт внутри списка.
 */
function разметить(список: Строка[]): Разметка[] {
  const итог: Разметка[] = [];
  const открытые: {колонка: number}[] = [];
  let ограда: {знак: string; длина: number} | null = null;

  for (const {текст} of список) {
    const отступ = ширинаОтступа(текст);

    if (ограда) {
      итог.push({отступ, код: true, пункт: null});
      const закрытие = /^[ \t]*(`{3,}|~{3,})[ \t]*$/.exec(текст);
      if (закрытие && закрытие[1][0] === ограда.знак && закрытие[1].length >= ограда.длина) ограда = null;
      continue;
    }

    if (текст.trim() === '') {
      итог.push({отступ, код: false, пункт: null});
      continue;
    }

    while (открытые.length > 0 && отступ < открытые[открытые.length - 1].колонка) открытые.pop();
    const контекст = открытые.length > 0 ? открытые[открытые.length - 1].колонка : 0;

    const начало = ОГРАДА.exec(текст);
    if (начало && отступ - контекст < КОЛОНОК_ДО_КОДА) {
      ограда = {знак: начало[1][0], длина: начало[1].length};
      итог.push({отступ, код: true, пункт: null});
      continue;
    }

    if (отступ - контекст >= КОЛОНОК_ДО_КОДА) {
      итог.push({отступ, код: true, пункт: null});
      continue;
    }

    const пункт = разобрать(текст);
    итог.push({отступ, код: false, пункт});
    if (пункт) открытые.push({колонка: пункт.колонка});
  }

  return итог;
}

/**
 * Ближайший пункт выше, подходящий по отступу. Пустые строки, продолжения пункта и его код список
 * не обрывают, а строка у левого края, которая пунктом не является, обрывает: список кончился.
 */
function пунктВыше(разметка: Разметка[], список: Строка[], индекс: number, годен: (отступ: number) => boolean): number {
  for (let i = индекс - 1; i >= 0; i -= 1) {
    if (список[i].текст.trim() === '') continue;

    const строка = разметка[i];
    if (строка.пункт) {
      if (годен(строка.отступ)) return i;
      continue;
    }

    if (строка.отступ > 0) continue;
    return -1;
  }
  return -1;
}

/**
 * Станет ли пункт первым на своём новом уровне. Нужно только нумерованным, и не ради красоты:
 * вложенный список открывается внутри абзаца родителя, а открыть его в CommonMark может только
 * пункт с номером один. `1. один` + `   2. два` вообще не даёт вложенного списка — второй пункт
 * остаётся простым текстом внутри первого (проверено штатным MDX). Остальные номера при этом не
 * трогаются: их сайт считает сам, и переписывать чужие строки незачем.
 */
function первыйНаУровне(разметка: Разметка[], список: Строка[], индекс: number, уровень: number): boolean {
  for (let i = индекс - 1; i >= 0; i -= 1) {
    if (список[i].текст.trim() === '') continue;

    const строка = разметка[i];
    if (строка.пункт) {
      if (строка.отступ === уровень) return false;
      if (строка.отступ < уровень) return true;
      continue;
    }

    if (строка.отступ > 0) continue;
    return true;
  }
  return true;
}

/** Последняя строка, принадлежащая пункту: его продолжения, его код и вложенные под него пункты. */
function конецПоддерева(разметка: Разметка[], список: Строка[], индекс: number, отступ: number): number {
  let последняя = индекс;
  for (let i = индекс + 1; i < список.length; i += 1) {
    if (список[i].текст.trim() === '') continue;
    if (разметка[i].отступ <= отступ) break;
    последняя = i;
  }
  return последняя;
}

/** Курсор стоит в пункте списка (а не в обычном тексте и не в коде). */
export function вСписке(текст: string, где: Selection): boolean {
  const список = строки(текст);
  return разметить(список)[номерСтроки(список, где.from)].пункт !== null;
}

/**
 * Общая часть обоих движений: считает новую колонку и переписывает пункт вместе с поддеревом.
 * `null` — двигать нечего или некуда; текст в этом случае не трогается вовсе.
 */
function сдвинутьУровень(
  текст: string,
  где: Selection,
  колонка: (разметка: Разметка[], список: Строка[], индекс: number, пункт: Пункт) => number | null,
): Edit | null {
  const список = строки(текст);
  const индекс = номерСтроки(список, где.from);
  if (индекс !== номерСтроки(список, где.to)) return null;

  const разметка = разметить(список);
  const пункт = разметка[индекс].пункт;
  if (!пункт) return null;
  // Отступ табуляциями программа не пересчитывает: ширина табуляции в файле неизвестна, и
  // догадка сдвинула бы пункт не туда. Такую строку правило не трогает.
  if (пункт.отступ.includes('\t') || пункт.разрыв.includes('\t')) return null;

  const новаяКолонка = колонка(разметка, список, индекс, пункт);
  if (новаяКолонка === null || новаяКолонка === пункт.отступ.length) return null;

  const последняя = конецПоддерева(разметка, список, индекс, пункт.отступ.length);
  const сдвиг = новаяКолонка - пункт.отступ.length;

  const хвост: string[] = [];
  for (let i = индекс + 1; i <= последняя; i += 1) {
    const строка = список[i].текст;
    if (строка.trim() === '') {
      хвост.push(строка);
      continue;
    }
    if (/^[ \t]*\t/.test(строка)) return null;
    // Поддерево глубже пункта, поэтому снять с него нужное число пробелов всегда есть откуда.
    хвост.push(сдвиг > 0 ? ' '.repeat(сдвиг) + строка : строка.slice(-сдвиг));
  }

  const цифровой = /^\d/.test(пункт.маркер);
  const маркер = цифровой && первыйНаУровне(разметка, список, индекс, новаяКолонка)
    ? `1${пункт.маркер.slice(-1)}`
    : пункт.маркер;

  const остаток = список[индекс].текст.slice(пункт.отступ.length + пункт.маркер.length + пункт.разрыв.length);
  const голова = `${' '.repeat(новаяКолонка)}${маркер}${пункт.разрыв}${остаток}`;

  const от = список[индекс].от;
  const до = список[последняя].от + список[последняя].текст.length;
  const сдвигКурсора = сдвиг + (маркер.length - пункт.маркер.length);
  const начало = Math.max(0, где.from - от + сдвигКурсора);

  const правка: Edit = {from: от, to: до, insert: [голова, ...хвост].join('\n')};
  if (где.to > где.from) правка.select = {from: начало, to: Math.max(начало, где.to - от + сдвигКурсора)};
  else правка.caret = начало;

  return правка;
}

/**
 * `Tab`: пункт становится вложенным в предыдущий пункт того же уровня.
 * Первый пункт списка вложить не во что — над ним нет старшего пункта, и текст остаётся как был.
 */
export function вложить(текст: string, где: Selection): Edit | null {
  return сдвинутьУровень(текст, где, (разметка, список, индекс, пункт) => {
    const выше = пунктВыше(разметка, список, индекс, (отступ) => отступ <= пункт.отступ.length);
    if (выше === -1) return null;

    const старший = разметка[выше].пункт!;
    // Старший пункт мельче нашего — значит, мы уже его первый ребёнок, и вкладывать глубже некуда.
    if (старший.отступ.length < пункт.отступ.length) return null;
    if (старший.отступ.includes('\t') || старший.разрыв.includes('\t')) return null;

    return старший.колонка;
  });
}

/**
 * `Shift+Tab`: пункт возвращается на уровень своего родителя.
 * Пункт без отступа возвращать некуда, а пункт с отступом, но без старшего пункта над ним,
 * встаёт к левому краю: он и так верхний в своём списке.
 */
export function поднять(текст: string, где: Selection): Edit | null {
  return сдвинутьУровень(текст, где, (разметка, список, индекс, пункт) => {
    if (пункт.отступ.length === 0) return null;

    const родитель = пунктВыше(разметка, список, индекс, (отступ) => отступ < пункт.отступ.length);
    if (родитель === -1) return 0;

    const старший = разметка[родитель].пункт!;
    if (старший.отступ.includes('\t')) return null;

    return старший.отступ.length;
  });
}
