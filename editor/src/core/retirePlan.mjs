// Каркас снятия статьи с сайта: какие пути уходят из опубликованной ветки и какие соседние файлы
// получают правку ссылок. Чистое правило: на входе факты о закреплённой основе, на выходе записи
// того же вида, что у каркаса публикации (`publishPlan.mjs`). Диска и git здесь нет (SPEC 4.6).
//
// **Снимается всё, что сайт знает о статье, во всех языках.** Файл каждой языковой версии, лежащий
// в основе, её файл состояния и файлы её каталога в тех же границах, что у состава публикации:
// обычная статья владеет каталогом вглубь, у записи вне канона и у корневой страницы каталога нет —
// уходят только её файл и состояние. Вторая статья в тех же границах — разрыв `папкаНеОдна`: чьи
// там картинки, по путям не видно, и уносить их нельзя.
//
// **Соседи правятся по СЕРВЕРНОЙ версии.** Правку ссылок приносит адаптер уже готовым текстом —
// его содержимое из основы без ссылок на снятую статью. Неопубликованные правки соседа на диске
// в снятие не попадают.

import {ВЕРСИЯ, КАРТИНКА, СОСТОЯНИЕ, РЕЖИМ_ФАЙЛА, УДАЛЕНО, вГранице} from './publishPlan.mjs';
import {годныйПутьПлана} from './planPath.mjs';
import {границаСостава} from './articleKind.mjs';
import {файлСтатьи} from './articles.mjs';

/** Назначение записи: соседний документ, в котором убраны ссылки на снятую статью. */
export const СОСЕД = 'сосед';

/** Источник байтов: текст соседа из закреплённой основы, уже без ссылок. */
export const ОСНОВА = 'основа';

/**
 * Каркас снятия.
 *
 * `версии` — языковые версии статьи, лежащие в основе: `{путь, локаль, состояние}`, где `состояние` —
 * путь её файла готовности (есть ли он в основе, решает `вОснове`). `вид` — вид открытой версии: у
 * всех языков статьи он один. `вОснове` — множество путей основы, спрошенных точно; `вПапках` —
 * карта «путь версии → обычные файлы её каталога в основе» либо `null` у версии, для которой
 * спросить не удалось. `соседи` — готовые правки ссылок `{путь, локаль, текст}`, `разрывыСоседей` —
 * ссылки, которые разобрать не вышло.
 *
 * Возвращает `{записи, разрывы, отказ}`. Версий в основе нет — записей нет: снимать нечего.
 */
export function каркасСнятия({версии, вид, вОснове, вПапках, соседи = [], разрывыСоседей = []}) {
  const записи = [];
  const разрывы = [...разрывыСоседей];
  const граница = границаСостава(вид);

  for (const версия of версии ?? []) {
    if (!годныйПутьПлана(версия?.путь)) {
      return {записи: [], разрывы, отказ: {код: 'фактыНеизвестны', локали: [версия?.локаль].filter(Boolean), чего: 'свойПуть'}};
    }

    const свои = new Set([версия.путь]);
    if (версия.состояние && вОснове.has(версия.состояние)) свои.add(версия.состояние);

    if (граница === 'каталогРекурсивно' || граница === 'верхнийУровень') {
      const вПапке = вПапках.get(версия.путь);
      if (!Array.isArray(вПапке)) return {записи: [], разрывы, отказ: {код: 'фактыНеизвестны', локали: [версия.локаль], чего: 'вПапке'}};

      const папка = версия.путь.slice(0, версия.путь.lastIndexOf('/'));
      const внутри = вПапке.filter((путь) => годныйПутьПлана(путь) && вГранице(путь, папка, граница));
      if (внутри.some((путь) => путь !== версия.путь && файлСтатьи(путь))) {
        разрывы.push({причина: 'папкаНеОдна', путь: версия.путь, локаль: версия.локаль});
        continue;
      }
      for (const путь of внутри) свои.add(путь);
    }

    for (const путь of свои) {
      записи.push({
        путь,
        назначение: путь === версия.путь ? ВЕРСИЯ : путь === версия.состояние ? СОСТОЯНИЕ : КАРТИНКА,
        локаль: версия.локаль,
        источник: УДАЛЕНО,
        режим: null,
        текст: null,
      });
    }
  }

  const уходят = new Set(записи.map((запись) => запись.путь));
  for (const сосед of соседи) {
    // Сосед, который и сам уходит с сайта, правке не подлежит: его файла там больше не будет.
    if (уходят.has(сосед.путь)) continue;
    if (!годныйПутьПлана(сосед.путь)) {
      return {записи: [], разрывы, отказ: {код: 'фактыНеизвестны', локали: [сосед.локаль].filter(Boolean), чего: 'путь'}};
    }
    записи.push({путь: сосед.путь, назначение: СОСЕД, локаль: сосед.локаль, источник: ОСНОВА, режим: РЕЖИМ_ФАЙЛА, текст: сосед.текст});
  }

  return {записи: поПутям(записи), разрывы, отказ: null};
}

/** Можно ли снимать: разрывов и отказа нет, и с сайта уходит хотя бы одна языковая версия. */
export function снятиеВозможно(каркас) {
  return каркас.отказ === null
    && каркас.разрывы.length === 0
    && каркас.записи.some((запись) => запись.назначение === ВЕРСИЯ && запись.источник === УДАЛЕНО);
}

/** Порядок по кодам знаков — тот же, что у плана публикации: от него зависит отпечаток. */
const поПутям = (записи) => [...записи].sort((a, b) => (a.путь < b.путь ? -1 : a.путь > b.путь ? 1 : 0));
