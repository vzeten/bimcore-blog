// Где лежат материалы владельца: статьи, картинки и всё, что он правит своими руками.
// Чистое правило: диск здесь не спрашивается, наличие папок подаётся снаружи (SPEC 4.6, 4.7).
//
// Правило заведено потому, что корень, выведенный из места самой программы, ехал вместе с кодом:
// запуск копии ветки молча подменял материалы её собственным деревом, и владелец не находил в окне
// своих статей. Место кода и место материалов — разные вещи, и второе называется явно, а не
// угадывается по соседней папке. Умолчания у него нет намеренно (SPEC 4.4.1): не задан — отказ,
// потому что тихая подстановка соседней папки и есть тот дефект, ради которого правило написано.

/** Коды отказов. Тексты для человека живут в настройках (SPEC 6.10). */
export const НЕ_ЗАДАН = 'неЗадан';
export const НЕ_АБСОЛЮТНЫЙ = 'неАбсолютный';
export const НЕТ_ПАПКИ = 'нетПапки';
export const НЕ_МАТЕРИАЛЫ = 'неМатериалы';

/**
 * Абсолютный путь: буква диска или ведущая косая. Синтаксис пути, а не наша настройка (SPEC 4.4).
 * Относительный путь запрещён нарочно: он считался бы от папки запуска, то есть снова от места
 * кода, — ровно то, что правило убирает.
 */
const АБСОЛЮТНЫЙ = /^(?:[A-Za-z]:[\\/]|[\\/])/;

/** Один вид косых и без лишней на конце: путь сравнивается и печатается одинаково. */
function ровно(путь) {
  const один = путь.split('\\').join('/').replace(/\/+$/, '');
  return /^[A-Za-z]:$/.test(один) ? `${один}/` : один;
}

/**
 * Корень материалов по настройкам.
 *
 * `папкаЕсть` — единственный вопрос к внешнему миру, и задаёт его адаптер. Проверяются четыре
 * вещи подряд, потому что каждая следующая без предыдущей бессмысленна: значение задано, оно
 * абсолютно, папка существует и в ней действительно лежат корни контента сайта. Последняя
 * проверка отделяет опечатку в пути от настоящих материалов: папка может быть, а статей в ней нет.
 *
 * @returns {{корень: string}|{отказ: string, значение: string}} корень с косыми одного вида
 *   либо код отказа вместе со значением, на котором отказ случился.
 */
export function выборКорня(settings, папкаЕсть) {
  const заданный = String(settings['материалы']?.['корень'] ?? '').trim();
  if (заданный === '') return {отказ: НЕ_ЗАДАН, значение: заданный};
  if (!АБСОЛЮТНЫЙ.test(заданный)) return {отказ: НЕ_АБСОЛЮТНЫЙ, значение: заданный};

  const корень = ровно(заданный);
  if (!папкаЕсть(корень)) return {отказ: НЕТ_ПАПКИ, значение: корень};

  const сайт = (settings['контент'] ?? []).filter((root) => root['наСайте']);
  const естьХотьОдин = сайт.some((root) => папкаЕсть(`${корень}/${root['папка']}`));

  return естьХотьОдин ? {корень} : {отказ: НЕ_МАТЕРИАЛЫ, значение: корень};
}
