// Где лежат материалы владельца: статьи, картинки и всё, что он правит своими руками.
// Чистое правило: диск здесь не спрашивается, наличие папок подаётся снаружи (SPEC 4.6, 4.7).
//
// Правило заведено потому, что корень, выведенный из места самой программы, ехал вместе с кодом:
// запуск копии ветки молча подменял материалы её собственным деревом, и владелец не находил в окне
// своих статей. Место кода и место материалов — разные вещи.
//
// Обычный корень пришпилен ЗДЕСЬ, а не в настройках, и это сознательное исключение из SPEC 4.4.
// Настройка — то, что владелец меняет по своему усмотрению; папка его материалов такой не является:
// пока корень брался из настроек, любая копия программы со своим `settings.json` могла назначить
// корнем собственное дерево и стать обычным источником чтения, записи и Git. Сменить папку
// материалов теперь можно только переделкой кода — то самое проверочное условие SPEC 4.4.

/** Постоянная папка материалов владельца. Обычное окно работает только с ней. */
export const ПАПКА_ВЛАДЕЛЬЦА = 'C:/My_code/bimcore-blog';

/** Коды отказов. Тексты для человека живут в настройках (SPEC 6.10). */
export const НЕ_АБСОЛЮТНЫЙ = 'неАбсолютный';
export const НЕТ_ПАПКИ = 'нетПапки';
export const НЕ_МАТЕРИАЛЫ = 'неМатериалы';

/**
 * Абсолютный путь: буква диска или ведущая косая. Синтаксис пути, а не наша настройка (SPEC 4.4).
 * Относительный корень запрещён нарочно: он считался бы от папки запуска, то есть снова от места
 * кода, — ровно то, что правило убирает.
 */
const АБСОЛЮТНЫЙ = /^(?:[A-Za-z]:[\\/]|[\\/])/;

/** Один вид косых и без лишней на конце: путь сравнивается и печатается одинаково. */
function ровно(путь) {
  const один = путь.split('\\').join('/').replace(/\/+$/, '');
  return /^[A-Za-z]:$/.test(один) ? `${один}/` : один;
}

/**
 * Корень материалов и признак «это не обычное окно».
 *
 * `испытательный` — заявка на другой корень, поданная явным переключателем запуска. Пусто или не
 * подан — обычное окно, и корень берётся только из `ПАПКА_ВЛАДЕЛЬЦА`: выбора у обычного запуска
 * нет вовсе. Подан — корень испытательный, и он обязан быть назван при запуске: молча притворяться
 * обычным окном экземпляр на чужом дереве не должен.
 *
 * `папкаЕсть` — единственный вопрос к внешнему миру, и задаёт его адаптер. Проверяется, что путь
 * абсолютен, папка существует и в ней действительно лежат корни контента сайта: папка может быть,
 * а статей в ней нет.
 *
 * Сравнение с папкой владельца — без учёта регистра: Windows считает `C:/My_code` и `c:/my_code`
 * одной папкой, и разный регистр не повод объявлять своё же дерево чужим.
 *
 * @returns {{корень: string, испытательный: boolean}|{отказ: string, значение: string}}
 */
export function выборКорня(settings, папкаЕсть, испытательный = null) {
  const заявка = String(испытательный ?? '').trim();
  const заданный = заявка === '' ? ПАПКА_ВЛАДЕЛЬЦА : заявка;
  if (!АБСОЛЮТНЫЙ.test(заданный)) return {отказ: НЕ_АБСОЛЮТНЫЙ, значение: заданный};

  const корень = ровно(заданный);
  if (!папкаЕсть(корень)) return {отказ: НЕТ_ПАПКИ, значение: корень};

  const сайт = (settings['контент'] ?? []).filter((root) => root['наСайте']);
  const естьКонтент = сайт.some((root) => папкаЕсть(`${корень}/${root['папка']}`));
  if (!естьКонтент) return {отказ: НЕ_МАТЕРИАЛЫ, значение: корень};

  return {корень, испытательный: корень.toLowerCase() !== ПАПКА_ВЛАДЕЛЬЦА.toLowerCase()};
}
