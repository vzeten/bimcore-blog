// Имя нового файла картинки: чистые правила подбора свободного номера по шаблону из настроек.
//
// Шаблон живёт в `settings.json` (`картинки.шаблонИмени`), а разбор имён — здесь: раньше номер
// искался регуляркой `img-(\d+)` прямо в ручке вставки, и это был второй источник правды —
// сменив шаблон в настройках, человек получил бы имена по новому образцу и подсчёт по старому.

/** Что разрешено в имени файла картинки (SPEC 2.2): латиница, цифры, дефис. */
const БЕЗОПАСНОЕ_ИМЯ = /^[a-z0-9-]+\.[a-z0-9]+$/i;

/**
 * Имя файла по шаблону, номеру и расширению. Сколько знаков в номере — тоже настройка
 * (`картинки.знаковВНомере`): вид имени выбирает человек, а не переделка программы, и своего
 * умолчания в коде нет (SPEC 4.4.1).
 *
 * `null` — имя построить нельзя: в шаблоне нет ровно одного места под номер, число знаков
 * не годится либо получается небезопасное имя (путь, пробел, кириллица). Такое имя роняет
 * сборку сайта, поэтому программа отказывается, а не пишет как получится.
 */
export function имяКартинки(шаблон, номер, расширение, знаковВНомере) {
  const образец = String(шаблон ?? '');
  if (образец.split('{номер}').length !== 2) return null;
  if (!Number.isInteger(знаковВНомере) || знаковВНомере < 1) return null;

  const имя = `${образец.replace('{номер}', String(номер).padStart(знаковВНомере, '0'))}.${расширение}`;
  return БЕЗОПАСНОЕ_ИМЯ.test(имя) ? имя : null;
}

/**
 * Номер картинки по имени файла. `null` — имя не по шаблону: собственные имена законны
 * (`arcat.jpg`, решение 2026-08-14) и в подсчёте номеров не участвуют.
 *
 * Расширение в счёт не идёт: `img-01.jpg` занимает первый номер и для PNG тоже — иначе рядом
 * легли бы `img-01.jpg` и `img-01.png`, и смена формата одной из них упёрлась бы в занятый адрес.
 * `img-1` и `img-01` — тоже один номер: ведущие нули на число не влияют.
 */
export function номерКартинки(имя, шаблон) {
  const образец = String(шаблон ?? '');
  if (образец.split('{номер}').length !== 2) return null;

  const [до, после] = образец.split('{номер}');
  const правило = new RegExp(`^${экранировать(до)}(\\d+)${экранировать(после)}\\.[a-z0-9]+$`, 'i');
  const найдено = правило.exec(String(имя ?? ''));

  return найдено ? Number(найдено[1]) : null;
}

/**
 * Первый номер, которым ещё никто не назван. Существующие картинки не перенумеровываются
 * (слово владельца): берётся следующий за самым большим занятым, а дыры в середине не
 * заполняются — номер из дыры мог стоять в ссылке уже опубликованной статьи.
 */
export function следующийНомерКартинки(имена, шаблон) {
  let занято = 0;
  for (const имя of имена ?? []) {
    const номер = номерКартинки(имя, шаблон);
    if (номер !== null) занято = Math.max(занято, номер);
  }

  return занято + 1;
}

/** Знаки, которые в регулярном выражении значат не себя, а правило поиска. */
function экранировать(текст) {
  return текст.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}
