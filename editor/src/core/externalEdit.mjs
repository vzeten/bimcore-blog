// Внешняя правка: файл статьи изменили мимо программы — ИИ в соседнем окне, сотрудник, `git pull`.
// Здесь только правила: считать ли это новой версией, какое у неё время и какой автор.
// Диска и git тут нет — их дело адаптера, поэтому правила проверяются без репозитория.

import {sameText} from './articleFile.mjs';

/**
 * Разошёлся ли файл с последним известным состоянием.
 * `известное` — содержимое последнего снимка, а если снимков нет — файла из git;
 * `null` означает, что известного состояния нет вовсе: другой копии этого текста у нас не существует,
 * и первое же увиденное содержимое стоит сохранить.
 *
 * Сравнивается полный текст файла, а не одно тело: иначе внешняя правка шапки
 * (`title`, `slug`, `image`, `unlisted`) не стала бы версией и потерялась бы.
 * Переводы строк из сравнения исключены (SPEC 3.6): переписанный CRLF — не новая версия.
 */
export function естьВнешняяПравка({текстФайла, известное}) {
  if (известное === null || известное === undefined) return true;
  return !sameText(String(известное), String(текстФайла));
}

/**
 * Когда появилась внешняя версия. Обычно это время изменения файла: момент, когда содержимое
 * оказалось на этом диске. Но если время файла не позже последней известной версии
 * (файл восстановлен из копии, сбиты часы), берётся момент обнаружения: иначе снимок встанет
 * в ленте не туда, а уборка лишних снимков — они сортируются временем — удалит его первым.
 */
export function времяВерсии({времяФайла, времяПоследнейВерсии, сейчас}) {
  const файл = Date.parse(времяФайла);
  if (!Number.isFinite(файл)) return сейчас;

  const последняя = Date.parse(времяПоследнейВерсии ?? '');
  if (Number.isFinite(последняя) && файл <= последняя) return сейчас;

  return new Date(файл).toISOString();
}

/**
 * Кто правил файл. Одно правило на всю программу: и для версии внешней правки,
 * и для колонки реестра «Кто менял» (решение владельца, см. `DECISIONS.md`).
 *
 * Закоммиченная правка — автор коммита. Незакоммиченная — имя из `git config user.name`
 * автором НЕ считается: это имя коммиттера по умолчанию, а не доказательство, кто правил текст,
 * и такая подпись приписывала бы владельцу правки ИИ. Единственное честное свидетельство для
 * незакоммиченного файла — наш собственный снимок: если он не старше файла, последним писал
 * редактор, и записанный в снимке автор настоящий. Иначе — «Неизвестный», без догадок.
 */
export function авторПравки({файлГрязный, авторКоммита, снимок, времяФайла, неизвестный}) {
  if (!файлГрязный) return имяИли(авторКоммита, неизвестный);

  const снят = Date.parse(снимок?.когда ?? '');
  const изменён = Date.parse(времяФайла);
  const нашСнимокСвежее = Number.isFinite(снят) && Number.isFinite(изменён) && снят >= изменён;

  return нашСнимокСвежее ? имяИли(снимок.автор, неизвестный) : неизвестный;
}

function имяИли(имя, запасное) {
  return typeof имя === 'string' && имя.trim() !== '' ? имя : запасное;
}
