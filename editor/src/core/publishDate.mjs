// Дата записи блога: чистое правило одной величины — какой `date` обязан стоять у открытой версии.
//
// Дата блога — это день ПЕРВОЙ публикации, а не день, когда человек завёл файл (решение владельца
// 2026-09-16). Поэтому её ставит сама публикация, а не окно: до выпуска дня публикации ещё нет, и
// любое заранее записанное число — догадка, которая разойдётся с лентой сайта.
//
// Здесь только правило: ни диска, ни git. Факты про сайт собирает адаптер, а решение о записи
// принимает ход публикации.

/**
 * Какая дата обязана стоять у открытой версии. Возвращает строку `ГГГГ-ММ-ДД` либо `null` —
 * «программа даты не касается».
 *
 * `род` — род статьи из настройки «контент» (`blog`, `docs`, `проба`); дата живёт только у блога,
 * у документации её не бывает вовсе.
 * `своя` — `{дата}` этой же версии в ОСНОВЕ (то, что стоит на сайте) либо `null`, если её там нет.
 * `соседи` — то же по другим языкам этой записи: `[{дата}]` только для опубликованных.
 * `сегодня` — сегодняшний день по календарю человека.
 *
 * Порядок ответов задан смыслом, а не удобством:
 *
 * 1. **Версия уже на сайте — её дата принадлежит сайту.** Смена даты опубликованной записи двигает
 *    её в ленте и в карте сайта, поэтому программа возвращает ровно то, что там стоит: этим же
 *    ответом чинится и ручная правка даты в файле, и заглушка, которую публикация создала с датой,
 *    а на диске у человека такой строки нет. Даты на сайте нет вовсе — `null`: выдумывать день
 *    выхода уже вышедшей записи программа не вправе.
 * 2. **Опубликован соседний язык — берётся его дата.** Языковые версии одной записи обязаны стоять
 *    в ленте одним днём; сегодняшнее число развело бы перевод и оригинал по разным дням.
 * 3. **Записи на сайте ещё нет — сегодня.** Это и есть день первой публикации.
 */
/**
 * Род, у которого бывает дата. Имя рода задано настройкой «контент» и Docusaurus, а не нами
 * (SPEC 4.4 про слова человеку и пороги, а не про чужие имена разделов).
 */
export const РОД_БЛОГА = 'blog';

export function нужнаяДата({род, своя, соседи, сегодня}) {
  if (род !== РОД_БЛОГА) return null;

  if (своя !== null && своя !== undefined) return датаИлиНичего(своя.дата);

  const сосед = (соседи ?? []).map((версия) => датаИлиНичего(версия?.дата)).find((дата) => дата !== null);
  if (сосед !== undefined && сосед !== null) return сосед;

  return датаИлиНичего(сегодня);
}

/**
 * Дата, записанная в шапке, либо `null`. Пустая строка и не-строка датой не являются: пустым
 * значением поле в файл не пишется вовсе, и обещать им день выхода нельзя.
 */
function датаИлиНичего(значение) {
  const дата = String(значение ?? '').trim();
  return дата === '' ? null : дата;
}

/**
 * Надо ли программе тронуть файл: нужная дата известна и отличается от той, что стоит в шапке.
 * Отдельная функция, а не сравнение на месте: её спрашивают и окно перед публикацией, и заслон
 * внутри записи, и разойдись эти два сравнения — заслон отказывал бы там, где окно уже всё сделало.
 */
export function датаРасходится({нужна, вФайле}) {
  if (нужна === null) return false;
  return String(вФайле ?? '').trim() !== нужна;
}
