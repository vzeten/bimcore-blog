// Правила значений полей шапки: длина описания и «порядок в меню — число».
//
// Отдельным модулем от `prepareRules.mjs` по размеру файла (SPEC 4.9), а не по смыслу: там
// правила о том, ЕСТЬ ли поле, здесь — о том, ГОДИТСЯ ли записанное в нём значение.
//
// Оба правила меряют показанное значение поля, а не сырую строку файла. Кавычки — синтаксис YAML,
// а не текст описания: считай программа их, и описание в кавычках длиной 159 знаков она объявила
// бы длиннее предела в 160.

import {значениеГруппы, значениеКуска} from './articleFile.mjs';
import {ЧИСЛО_YAML} from './frontmatterRules.mjs';
import {БЛОКЕР, ПРЕДУПРЕЖДЕНИЕ, находка, значениеПоля} from './prepareRules.mjs';

// Имя поля задал Docusaurus, а не мы: чужой формат в коде и остаётся (SPEC 4.4).
const ПОРЯДОК_В_МЕНЮ = 'sidebar_position';

/**
 * Годится ли прочитанное значение сайту как число.
 *
 * Спрашивается у YAML, а не у сырой строки файла: комментарий в конце строки сайт отбрасывает, и
 * блокер на таком значении был бы обещанием падения, которого не будет. Строка тоже годится, если
 * читается числом: схема сайта приводит `"2"` к двойке сама.
 *
 * **Экзотические записи чисел это правило не судит и судить не может честно:** программа читает
 * шапку одним YAML, сайт другим, и на `0x10`, `0o17`, `017`, `2_0`, `1:30` они расходятся в обе
 * стороны. Щель названа хвостом в `PLAN.md`. Мерка чисел взята у правил шапки, своей здесь не
 * заводится (SPEC 4.3); живёт рядом с вызовом, потому что в `frontmatterRules.mjs` 300 строк
 * из 300 — места там нет вовсе.
 */
const годноеЧисло = ({ok, значение}) => ok
  && (typeof значение === 'number'
    ? Number.isFinite(значение)
    : typeof значение === 'string' && ЧИСЛО_YAML.test(значение.trim()));

/** Правила значений: по каждой версии оба правила, находки складываются в общий список. */
export function значенияПолей({версии, settings, этап}) {
  return версии.flatMap((версия) => [
    ...длинаОписания(версия, settings, этап),
    ...порядокВМеню(версия, settings, этап),
  ]);
}

/**
 * Описание длиннее предела. Предупреждение, а не блокер (решение владельца 2026-08-13): сборку
 * длинное описание не роняет, поисковик обрезает хвост — статью это не портит, а хвост человек
 * поправит сам.
 *
 * О пустом описании правило молчит: о нём уже сказано блокером «описание не заполнено», и вторая
 * строка отчёта про ту же строку файла человеку ничего не добавляет.
 */
function длинаОписания(версия, settings, этап) {
  const предел = settings['пределОписания'];
  const {вид, текст} = значениеКуска(кусок(версия, 'description'));

  // Описание обязано быть строкой: список, да-нет и запись с полями сайт не примет, и сборка
  // падает («description must be a string»). Меряй мы длину склейки такого значения — программа
  // молчала бы про файл, от которого сайт не соберётся.
  if (вид !== 'строка' && вид !== 'нет') {
    return [находка({
      код: 'описаниеНеСтрока', уровень: БЛОКЕР, этап, путь: версия.путь, поле: 'description',
    })];
  }

  if (текст === '' || текст.length <= предел) return [];

  return [находка({
    код: 'описаниеДлинное',
    уровень: ПРЕДУПРЕЖДЕНИЕ,
    этап,
    путь: версия.путь,
    поле: 'description',
    длина: текст.length,
    предел,
  })];
}

/**
 * Порядок статьи в меню обязан читаться числом: схема Docusaurus ждёт там число, и от слова вместо
 * числа падает сборка всего сайта. Отсюда блокер.
 *
 * Спрашивается только у тех родов, которым это поле назначено настройкой `поляСоздания`. У блога
 * его в перечне нет, и сайт его у блога не читает вовсе — находка повела бы человека править
 * безвредную строку. Признак берётся из настройки, а не из имени рода в коде: умолчание, повторяющее
 * настройку, срабатывает молча, когда настройку изменили (SPEC 4.4.1).
 *
 * Что считается годным, сверено с настоящей схемой сайта: `2`, `"2"`, `0002`, `2.5`, `-1` и `2`
 * с комментарием в конце строки сборку не роняют и находки не дают; `два`, `2a`, `true`, пустое
 * значение и список — роняют и дают. Экзотические записи чисел правило обходит (см. выше).
 */
function порядокВМеню(версия, settings, этап) {
  const назначено = settings['поляСоздания'][версия.род]?.['порядок'] ?? [];
  if (!назначено.includes(ПОРЯДОК_В_МЕНЮ)) return [];

  const группа = кусок(версия, ПОРЯДОК_В_МЕНЮ);
  // Поля в шапке нет вовсе — это не беда: Docusaurus расставит статьи сам, и большинство разделов
  // так и живёт. Правило говорит о записанном значении, а не о его отсутствии.
  if (группа === undefined) return [];
  if (годноеЧисло(значениеГруппы(группа))) return [];

  return [находка({
    код: 'порядокВМенюНеЧисло',
    уровень: БЛОКЕР,
    этап,
    путь: версия.путь,
    поле: ПОРЯДОК_В_МЕНЮ,
    // Человеку показывается то, что он видит в поле: разобранное значение тут не поможет —
    // беда как раз в том, что разобрать его сайту нечем. Правило показанного значения одно
    // на подготовку и живёт в `prepareRules.mjs` (SPEC 4.3).
    значение: значениеПоля(версия, ПОРЯДОК_В_МЕНЮ),
  })];
}

/** Кусок шапки по ключу; значение из него достаёт общее правило `значениеСтрокой`. */
function кусок(версия, ключ) {
  return версия.группы.find((группа) => группа.ключ === ключ);
}
