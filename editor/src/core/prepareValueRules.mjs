// Правила значений полей шапки: длина описания и «порядок в меню — число».
//
// Отдельным модулем от `prepareRules.mjs` по размеру файла (SPEC 4.9), а не по смыслу: там
// правила о том, ЕСТЬ ли поле, здесь — о том, ГОДИТСЯ ли записанное в нём значение.
//
// Оба правила меряют показанное значение поля, а не сырую строку файла. Кавычки — синтаксис YAML,
// а не текст описания: считай программа их, и описание в кавычках длиной 159 знаков она объявила
// бы длиннее предела в 160.

import {значениеГруппы, значениеКуска} from './articleFile.mjs';
import {БЛОКЕР, ПРЕДУПРЕЖДЕНИЕ, находка, значениеПоля} from './prepareRules.mjs';

// Имя поля задал Docusaurus, а не мы: чужой формат в коде и остаётся (SPEC 4.4).
const ПОРЯДОК_В_МЕНЮ = 'sidebar_position';

/**
 * Простая десятичная запись числа — единственная, за которую программа ручается: её одинаково
 * читают и она, и сайт, и её же программа пишет сама.
 *
 * Перечислять «подозрительные» форматы (шестнадцатеричные, восьмеричные, с подчёркиванием,
 * шестидесятеричные, двоичные) пробовали — и каждый круг проверки находил запись, которой в
 * перечне нет. Поэтому вопрос перевёрнут: не «похоже ли это на экзотику», а «ручаемся ли мы».
 * Ведущий ноль сюда не входит намеренно: `017` программа читает семнадцатым, а сайт пятнадцатым.
 */
const ПРОСТОЕ_ЧИСЛО = /^[+-]?(0|[1-9]\d*)(\.\d+)?$/;

/**
 * Знаки, из которых числовая запись состоит хоть в одном разборе: цифры, знак, точка, разделитель
 * разрядов и двоеточие YAML 1.1, буквы шестнадцатеричной, восьмеричной, двоичной записи и
 * показателя степени. Всё, где есть знак вне этого набора, числом не станет ни у нас, ни у сайта.
 */
const ЗНАКИ_ЧИСЛА = /^[-+._:0-9a-fA-FxXoO]+$/;

/**
 * Число, которое сайт примет. Схема отвергает не только слова: целое больше девяти с лишним
 * квадриллионов она называет «не безопасным числом», и сборка падает. Проверять это обязательно —
 * поле «Порядок в меню» в окне обычное текстовое, длинный номер человек наберёт руками.
 */
const безопасноеЧисло = (значение) => Number.isFinite(значение)
  && (!Number.isInteger(значение) || Number.isSafeInteger(значение));

/**
 * Канонический вид простой десятичной записи: ведущий плюс, хвостовые нули дробной части и
 * отрицательный ноль — украшение записи, а не её точность. Ровно так их снимает и схема сайта,
 * прежде чем судить о точности; показатель степени сюда не попадает — простой записью он не
 * считается и до этой мерки не доходит.
 */
const каноническаяЗапись = (текст) => {
  const безПлюса = текст.replace(/^\+/, '');
  const безХвоста = безПлюса.includes('.')
    ? безПлюса.replace(/0+$/, '').replace(/\.$/, '')
    : безПлюса;

  return безХвоста === '-0' ? '0' : безХвоста;
};

/**
 * У записи в кавычках сайт проверяет ещё и точность: если число не воспроизводит запись обратно,
 * схема отвечает тем же «not a safe number». Отсюда вторая половина проверки — для строк.
 *
 * Сравнивается канонический вид, а не сырая строка: иначе выпуск останавливался бы на записи,
 * которую сайт собирает, — и первой такой была бы запись самой программы. Поле «Порядок в меню» в
 * окне обычное текстовое, и набранное человеком `-2.0` программа кладёт в файл в кавычках, потому
 * что значение начинается со знака минус.
 */
const записьБезПотери = (текст) => {
  const число = String(Number(текст));

  // Число мельче одной миллионной печатается показательной формой, и точность такой записи схема
  // сайта не сверяет вовсе: сравнивать ей не с чем. Числа с другого края, огромные, тоже
  // печатаются показательной формой, но их отсекает мерка безопасного числа — как и у сайта.
  if (/e/i.test(число)) return true;

  return число === каноническаяЗапись(текст);
};

/** Правила значений: по каждой версии оба правила, находки складываются в общий список. */
export function значенияПолей({версии, settings, этап}) {
  return версии.flatMap((версия) => [
    ...длинаОписания(версия, settings, этап),
    ...порядокВМеню(версия, settings, этап),
  ]);
}

/**
 * Описание длиннее предела. Предупреждение, а не блокер (решение владельца 2026-08-13): сборку
 * длинное описание не роняет, поисковик обрезает хвост — статью это не портит, а хвост человек
 * поправит сам.
 *
 * О пустом описании правило молчит: о нём уже сказано блокером «описание не заполнено», и вторая
 * строка отчёта про ту же строку файла человеку ничего не добавляет.
 */
function длинаОписания(версия, settings, этап) {
  const предел = settings['пределОписания'];
  const {вид, текст} = значениеКуска(кусок(версия, 'description'));

  // Список, да-нет и запись с полями сайт в описании не примет, и сборка падает («description
  // must be a string»). Число и дату он приводит к строке сам — их правило пропускает и меряет
  // как обычное описание: блокер на них остановил бы выпуск здоровой статьи.
  if (вид === 'чужойВид') {
    return [находка({
      код: 'описаниеНеСтрока', уровень: БЛОКЕР, этап, путь: версия.путь, поле: 'description',
    })];
  }

  if (текст === '' || текст.length <= предел) return [];

  return [находка({
    код: 'описаниеДлинное',
    уровень: ПРЕДУПРЕЖДЕНИЕ,
    этап,
    путь: версия.путь,
    поле: 'description',
    длина: текст.length,
    предел,
  })];
}

/**
 * Порядок статьи в меню обязан читаться числом: схема Docusaurus ждёт там число, и от слова вместо
 * числа падает сборка всего сайта. Отсюда блокер.
 *
 * Спрашивается только у тех родов, которым это поле назначено настройкой `поляСоздания`. У блога
 * его в перечне нет, и сайт его у блога не читает вовсе — находка повела бы человека править
 * безвредную строку. Признак берётся из настройки, а не из имени рода в коде: умолчание, повторяющее
 * настройку, срабатывает молча, когда настройку изменили (SPEC 4.4.1).
 *
 * Три исхода, и делит их не формат записи, а мера уверенности программы.
 * **Блокер** — там, где сайт не соберётся ни при каком чтении: значения нет вовсе, оно да-нет,
 * список или запись с полями, либо это слово без единой цифры (`два`). **Тишина** — простая
 * десятичная запись, за которую программа ручается. **Предупреждение** — всё остальное: запись
 * с цифрами, которую программа числом не прочла или прочла иначе, чем прочтёт сайт. Обещать про
 * такую запись «сборка упадёт» нельзя — `0b1_0` и `1:30` сайт читает числами и собирается.
 */
function порядокВМеню(версия, settings, этап) {
  const назначено = settings['поляСоздания'][версия.род]?.['порядок'] ?? [];
  if (!назначено.includes(ПОРЯДОК_В_МЕНЮ)) return [];

  const группа = кусок(версия, ПОРЯДОК_В_МЕНЮ);
  // Поля в шапке нет вовсе — это не беда: Docusaurus расставит статьи сам, и большинство разделов
  // так и живёт. Правило говорит о записанном значении, а не о его отсутствии.
  if (группа === undefined) return [];

  const {ok, значение} = значениеГруппы(группа);
  const записано = значениеПоля(версия, ПОРЯДОК_В_МЕНЮ).trim();
  const беда = (код, уровень) => [находка({
    код, уровень, этап, путь: версия.путь, поле: ПОРЯДОК_В_МЕНЮ, значение: записано,
  })];

  if (!ok || значение === null || значение === undefined) return беда('порядокВМенюНеЧисло', БЛОКЕР);
  if (typeof значение !== 'number' && typeof значение !== 'string') {
    return беда('порядокВМенюНеЧисло', БЛОКЕР);
  }
  // Слово без единой цифры числом не прочтёт ни один разбор — здесь программа уверена.
  if (typeof значение === 'string' && !/\d/.test(значение)) return беда('порядокВМенюНеЧисло', БЛОКЕР);
  // Знак, которого в числовой записи не бывает ни в одном разборе: запятая вместо точки, пробел
  // между разрядами, буква слова, номер. Значение прочлось строкой, а строку кавычки и пробелы
  // делают строкой в любой версии YAML — значит оба разбора видят здесь одно и то же, и сайт не
  // соберётся ни при каком чтении. Самая частая такая запись — `2,5`: десятичная дробь по-русски.
  if (typeof значение === 'string' && !ЗНАКИ_ЧИСЛА.test(значение.trim())) {
    return беда('порядокВМенюНеЧисло', БЛОКЕР);
  }

  // Значение прочлось числом, но таким, которого сайт не примет ни при каком чтении: бесконечность,
  // не-число, целое за пределом безопасного. Вид записи здесь роли не играет — оба разбора читают
  // `.inf`, `.nan` и `1e21` одинаково, поэтому оговорка про разные YAML к ним не относится, и
  // уровень тот же, что у слова без цифр.
  if (typeof значение === 'number' && !безопасноеЧисло(значение)) {
    return беда('порядокВМенюНеЧисло', БЛОКЕР);
  }

  // За простую десятичную запись программа ручается. У числа она сверяется с первым словом строки:
  // остаток может быть комментарием, который сайт отбросит.
  const первое = записано.split(/\s+/)[0] ?? '';
  const простое = typeof значение === 'number'
    ? ПРОСТОЕ_ЧИСЛО.test(первое) && Number(первое) === значение
    : ПРОСТОЕ_ЧИСЛО.test(значение.trim());

  if (!простое) return беда('порядокВМенюСпорный', ПРЕДУПРЕЖДЕНИЕ);

  // Запись простая, но само число сайту не годится — тут программа уверена так же, как в слове.
  const текст = typeof значение === 'number' ? первое : значение.trim();
  const годно = безопасноеЧисло(Number(текст))
    && (typeof значение === 'number' || записьБезПотери(текст));

  return годно ? [] : беда('порядокВМенюНеЧисло', БЛОКЕР);
}

/** Кусок шапки по ключу; значение из него достаёт общее правило `значениеКуска`. */
function кусок(версия, ключ) {
  return версия.группы.find((группа) => группа.ключ === ключ);
}
