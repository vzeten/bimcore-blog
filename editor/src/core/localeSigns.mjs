// Признаки одной языковой версии — то, что видно возле её обозначения `RU`, `EN`, `ES`.
// Одно правило на реестр и на шапку открытой статьи: окно правил не знает (SPEC 4.8), а второй
// расчёт тех же фактов означал бы, что список и шапка расходятся в показаниях о той же версии.
//
// Общего слова готовности здесь нет намеренно. Одно слово описывает статью целиком, а версий у
// неё три и живут они порознь: при «RU опубликована, EN изменена, ES заглушка» слово
// «Опубликована» прятало правку EN. Решение владельца 2026-09-07, `BUSINESS.md`.
//
// Признаки НЕЗАВИСИМЫ и складываются: версия бывает и заглушкой, и скрытой, и черновиком сразу,
// поэтому здесь не одно значение с приоритетом, а набор. Спорят они только за цвет букв — цвет
// один, и порядок спора задан отдельно (`цветЛокали`).

import {readField} from './articleFile.mjs';
import {файлСтатьи} from './articles.mjs';
import {ПОЛЕ_ЧЕРНОВИКА} from './frontmatterFields.mjs';
import {скрытоеЗначение} from './frontmatterRules.mjs';

/**
 * Стоит ли в шапке версии `draft: true`. Логическое значение читается тем же правилом, что и
 * `unlisted`: вопрос у них один — прочитает ли YAML написанное как `true` (SPEC 4.3). Поэтому
 * `draft: false` и отсутствие поля означают одинаковое «нет», а `True` и `TRUE` — «да».
 */
export function черновикСайта(frontmatterRaw) {
  return скрытоеЗначение(readField(frontmatterRaw, ПОЛЕ_ЧЕРНОВИКА));
}

/** Ни одного признака: так выглядит локаль, файла которой нет. */
const НЕТ_ВЕРСИИ = {
  есть: false, черновик: false, неПубликовалась: false, изменена: false, заглушка: false, поСсылке: false,
};

/**
 * Есть ли у версии неопубликованная работа человека. Мест хранения два и они равноправны: сам
 * файл статьи и подтверждённый сервером черновик автосохранения. Человеку важно одно — работа
 * сохранена программой, а сайт её ещё не видел (решение владельца 2026-09-07, `BUSINESS.md`).
 *
 * Набранное в окне сюда не попадает: до ответа сервера работы у программы нет, и точка обещала бы
 * сайту то, чего не сохранено нигде.
 */
function правкаНеУехала(версия) {
  return версия['отличается'] === true || версия['правкаВЧерновике'] === true;
}

/**
 * Признаки версии по её собственным фактам. `версия` — запись свода либо `null`, когда файла
 * этой локали нет вовсе.
 *
 * `опубликован`: `true` — путь лежит в опубликованной ветке, `false` — не лежит, `null` — ветку
 * прочитать не удалось. `отличается` — тем же порядком про сравнение с веткой, а
 * `правкаВЧерновике` — про работу, которую программа приняла, но в файл ещё не положила.
 *
 * Недоказанное молчит. «Ещё не публиковалась» при недоступном git было бы новым враньём вместо
 * прежнего: неизвестно — это не «нет».
 */
export function признакиЛокали(версия) {
  if (!версия) return {...НЕТ_ВЕРСИИ};

  return {
    есть: true,
    черновик: черновикНаСайте(версия) === true,
    неПубликовалась: версия['опубликован'] === false,
    изменена: версия['опубликован'] === true && правкаНеУехала(версия),
    заглушка: версия['заглушка'] === true,
    поСсылке: скрытаНаСайте(версия) === true,
  };
}

/**
 * Выпущена ли версия НА САЙТ черновиком. Вопрос задан живой странице, а не файлу на диске: красные
 * буквы обещают, что сборка сайта этой страницы не выпускает, а не что человек так задумал.
 *
 * Правило одно в одно с `скрытаНаСайте` и по той же причине: `true` — версия лежит в опубликованной
 * ветке и в шапке ИМЕННО ОПУБЛИКОВАННОЙ версии стоит `draft: true`; `false` — на сайте её нет вовсе
 * либо опубликованная шапка обычная; `null` — спросить не удалось, и выдумывать ответ нельзя.
 *
 * Отсюда обещание владельцу: местная смена доступности до публикации букв не красит и не
 * обесцвечивает. Поставленный локально `draft` цвета не даёт, снятый локально — не убирает его до
 * выпуска; саму неуехавшую работу показывает красная точка.
 */
export function черновикНаСайте(версия) {
  if (версия['опубликован'] !== true) return false;
  if (typeof версия['черновикВВетке'] === 'boolean') return версия['черновикВВетке'];
  // Файл, СОВПАДАЮЩИЙ с веткой, и есть опубликованный: его собственное `draft` — то же значение.
  if (версия['отличается'] === false) return версия['черновикСайта'] === true;

  return null;
}

/**
 * Видна ли версия НА САЙТЕ только по прямой ссылке. Вопрос задан выпущенной странице, а не файлу
 * на диске: значок обещает нынешнее поведение живого сайта, а не будущую настройку.
 *
 * `true` — версия лежит в опубликованной ветке и в шапке ИМЕННО ОПУБЛИКОВАННОЙ версии стоит
 * `unlisted: true`; `false` — на сайте её нет вовсе либо опубликованная шапка обычная;
 * `null` — спросить не удалось, и выдумывать ответ нельзя (значка тогда нет).
 *
 * Отсюда и обещание владельцу: местная смена `unlisted` до публикации значка не создаёт и не
 * убирает. Снятый локально флаг оставляет значок до выпуска, поставленный локально — не заводит
 * его раньше выпуска; саму неуехавшую правку показывает красная точка.
 *
 * `скрытаВВетке` — шапка, прочитанная у самой ветки (`null` — не читали). Читать её приходится не
 * всегда: файл, СОВПАДАЮЩИЙ с веткой, и есть опубликованный, и его собственное `unlisted` — то же
 * самое значение. Кого спрашивать у git, называет `путиЗаОпубликованнойШапкой`.
 */
export function скрытаНаСайте(версия) {
  if (версия['опубликован'] !== true) return false;
  if (typeof версия['скрытаВВетке'] === 'boolean') return версия['скрытаВВетке'];
  if (версия['отличается'] === false) return версия['скрыта'] === true;

  return null;
}

/**
 * Чью опубликованную шапку придётся прочитать у самой ветки — одну на оба признака выпуска, цвет
 * букв и значок ссылки. Спрашиваются только версии, чей файл от ветки ОТЛИЧАЕТСЯ: у совпадающих
 * ответ уже лежит на диске, и лишний вызов git ничего бы не уточнил, зато стоил бы чтения на
 * каждую статью реестра.
 *
 * `расходятся` не перечень (сравнить не удалось) — не спрашивается никто: чинить незнание догадкой
 * хуже, чем промолчать признаком. Картинки и прочее отсеиваются: шапка бывает только у статьи.
 */
export function путиЗаОпубликованнойШапкой(опубликованные, расходятся) {
  if (!(расходятся instanceof Set) || !(опубликованные instanceof Set)) return [];

  return [...расходятся].filter((путь) => файлСтатьи(путь) && опубликованные.has(путь));
}

/**
 * Каким цветом буквы локали. Цвет один на версию, поэтому здесь признаки спорят, и порядок спора
 * назван владельцем: `draft` важнее «ещё не публиковалась».
 *
 * `обычная` — версия опубликована и совпадает с веткой; сюда же попадает случай, когда про
 * публикацию ничего не известно: молчание честнее ложного «ещё не публиковалась».
 * Точки и значок ссылки цветом не заменяются — у них свои места рядом с буквами.
 */
export function цветЛокали(признаки) {
  if (!признаки.есть) return 'нет';
  if (признаки.черновик) return 'черновик';
  if (признаки.неПубликовалась) return 'новая';
  return 'обычная';
}

/**
 * Что сказать про версию словами. Цвет не имеет права быть единственным объяснением, поэтому
 * подсказка перечисляет ВСЕ сложившиеся признаки, а не самый важный из них.
 *
 * `ещё` — слова зовущего про эту же версию (шапка добавляет своё «правился раньше основной»).
 * Своих слов у правила нет: все тексты живут в настройках.
 */
export function подсказкаЛокали(код, признаки, settings, ещё = []) {
  const язык = settings['локали'][код] ?? код;
  const п = settings['подписи'];

  const слова = [
    признаки.есть ? null : п['версииНет'],
    признаки.черновик ? п['локальЧерновик'] : null,
    признаки.неПубликовалась ? п['локальНеПубликовалась'] : null,
    признаки.изменена ? п['локальИзменена'] : null,
    признаки.заглушка ? п['локальЗаглушка'] : null,
    признаки.поСсылке ? settings['видимость']['поСсылке'] : null,
    ...ещё,
  ].filter(Boolean);

  return слова.length === 0 ? язык : `${язык}: ${слова.join(', ')}`;
}
