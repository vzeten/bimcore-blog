// Правила подготовки статьи: сами проверки, их уровни и вид находки.
//
// Отдельно от `prepare.mjs`, где живёт порядок этапов и вердикт: там оркестратор, здесь правила.
// Ни одной проверки, которая уже есть в другом месте, тут не написано заново — шапку разбирают
// куски, защитные правила живут в `safeFrontmatter`, состав статьи в `articles`, пустота значения
// в `frontmatterRules`. Своими стали только «описание заполнено» и «обязательные поля категории».

import {безКавычек} from './articleFile.mjs';
import {normalizeSlug, sameSlugAcrossLocales, пустоеЗначение, списокБезЗначений} from './frontmatterRules.mjs';
import {safeFrontmatter} from './safeFrontmatter.mjs';
import {missingOnSite} from './articles.mjs';
import {бедыНастройки, обязательныеПоля} from './prepareSettings.mjs';

/**
 * Уровни находок. Перечень открытый: круг 4 добавит сюда «исправлено», когда подготовка начнёт
 * править механическое сама, и форма записи от этого не изменится.
 */
export const БЛОКЕР = 'блокер';
export const ПРЕДУПРЕЖДЕНИЕ = 'предупреждение';

/**
 * Этапы подготовки по порядку: дешёвое раньше дорогого. Перечень — данные, а не хвост кода,
 * и порядок вызова берётся отсюда же: два перечня разошлись бы при первом же новом этапе.
 *
 * `внешний` — этап идёт дочерним процессом и живёт в адаптере (блок В). Ядро называет ему место.
 */
export const ЭТАПЫ = [
  {код: 'настройки', внешний: false},
  {код: 'шапка', внешний: false},
  {код: 'составСтатьи', внешний: false},
  {код: 'поляПоиска', внешний: false},
  {код: 'адресаВерсий', внешний: false},
  {код: 'contentCheck', внешний: true},
  {код: 'сборка', внешний: true},
];

/**
 * Какие причины запрета правки поля считаются бедой, а какие нет. «Заперто» означает «программа
 * не может записать значение обратно», а не «не может его прочитать»: у большинства причин
 * значение прочитано и проверкам доступно.
 *
 * Здесь только те, при которых сборка сайта падает или проверить нечем. Список с запятой внутри
 * значения, многострочное значение и список записями с полями — исправный файл, и говорить о нём
 * в отчёте значит шуметь про то, что чинить не нужно.
 *
 * Полноту сторожит машина: причина, заведённая в настройках и забытая здесь, даёт красный тест.
 * Неизвестная причина считается предупреждением, а не тишиной, — молчать о непонятом нельзя.
 */
const УРОВЕНЬ_ЗАПРЕТА = {
  ключДважды: БЛОКЕР,
  этоНеСписок: БЛОКЕР,
  неПрочитано: БЛОКЕР,
  запятаяВЭлементе: null,
  многострочное: null,
  сложныйСписок: null,
  неПравитсяЗдесь: null,
};

/**
 * Уровень каждой правки, которую сделала бы защитная проверка шапки. Перечень явный, а не
 * «всё, кроме одного»: новое правило иначе стало бы блокером молча, без слова человеку и без теста.
 */
const УРОВЕНЬ_ПРАВКИ = {
  пустаяОбложка: БЛОКЕР,
  пустыеКлючевыеСлова: БЛОКЕР,
  // Адрес после публикации не меняется без переадресации, поэтому неверный останавливает выпуск.
  адресПоПравилу: БЛОКЕР,
  // Схема сайта принимает и число: беда только в записи, и лечится она сохранением.
  адресВКавычки: ПРЕДУПРЕЖДЕНИЕ,
};
/**
 * Находка: запись для программы, а не фраза для человека. Слова заводятся в настройках вместе
 * с окном отчёта — разбирай оно готовую фразу, рядом с правилом появился бы второй его источник.
 *
 * `путь` необязателен: у отсутствующей английской версии файла нет вовсе, а красная сборка
 * говорит про весь сайт. `подробности` — чужой текст, который принесут внешние этапы: сообщение
 * проверки качества, хвост лога сборки. Разбирать его в структурные находки мы не будем.
 */
export function находка({код, уровень, этап, путь = null, поле = null, строка = null, ...прочее}) {
  return {код, уровень, этап, путь, поле, строка, ...прочее};
}
/** Беды самой настройки: уровень им назначается здесь, чтобы перечень уровней жил в одном месте. */
export function настройки({settings, этап}) {
  return бедыНастройки(settings).map((беда) => находка({...беда, уровень: БЛОКЕР, этап}));
}

/**
 * Шапка версии: сухой прогон защитных правил плюс поля, которые программа не может записать
 * обратно. Сухой прогон ничего не меняет — он отвечает на вопрос «а поправила бы программа
 * этот файл, если бы его сохранили». У файла, прошедшего через окно, находок не будет вовсе:
 * защитные правила применяются при каждом сохранении. Появятся они у файла, правленного мимо.
 */
export function шапкиВерсий({версии, settings, этап}) {
  return версии.flatMap((версия) => {
    const {fixed} = safeFrontmatter(версия.путь, версия.frontmatterRaw, settings['контент']);

    const защитные = fixed.map((правка) => находка({
      ...правка,
      уровень: УРОВЕНЬ_ПРАВКИ[правка['код']] ?? ПРЕДУПРЕЖДЕНИЕ,
      этап,
      путь: версия.путь,
    }));

    const запертые = версия.поля
      .filter((поле) => поле.kind === 'заперто')
      .map((поле) => ({поле, уровень: уровеньЗапрета(поле.причина)}))
      .filter(({уровень}) => уровень !== null)
      .map(({поле, уровень}) => находка({
        код: `поле:${поле.причина}`, уровень, этап, путь: версия.путь, поле: поле.key,
      }));

    // Задвоенный ключ даёт по находке на каждую свою запись: две одинаковые строки отчёта
    // про одну беду человеку ничего не добавляют.
    return [...защитные, ...безПовторов(запертые)];
  });
}

/** Одинаковые находки об одном поле схлопываются: беда одна, значит и строка отчёта одна. */
function безПовторов(находки) {
  const видели = new Set();

  return находки.filter((найдено) => {
    const ключ = `${найдено.код}|${найдено.путь}|${найдено.поле}`;
    if (видели.has(ключ)) return false;
    видели.add(ключ);
    return true;
  });
}

/** Причина запрета, которой нет в карте, — не повод молчать: программа скажет о ней осторожно. */
function уровеньЗапрета(причина) {
  return причина in УРОВЕНЬ_ЗАПРЕТА ? УРОВЕНЬ_ЗАПРЕТА[причина] : ПРЕДУПРЕЖДЕНИЕ;
}

/**
 * Состав статьи: без английской версии Docusaurus не соберёт статью вовсе и промолчит (SPEC 2.4).
 * Считается по снимку — какие локали в нём есть; существование файлов решает адаптер, не правило.
 */
export function составСтатьи({версии, settings, этап}) {
  const статья = {
    наСайте: версии.some((версия) => версия.наСайте),
    versions: Object.fromEntries(версии.map((версия) => [версия.локаль, версия])),
  };

  if (!missingOnSite(статья, settings)) return [];

  return [находка({
    код: 'нетОбязательнойВерсии', уровень: БЛОКЕР, этап, локаль: settings['обязательныйЯзык'],
  })];
}

/**
 * Поля, без которых статью не найдут в поиске. Требование владельца, а не Docusaurus: движок
 * не требует ни одного поля шапки вовсе.
 *
 * Описание обязательно у КАЖДОЙ версии, видимой и скрытой: слово владельца дословно. Английская
 * заглушка его проходит, потому что описание у неё своё, из настроек. Обязательные поля категории
 * у скрытой версии только предупреждают: странице, которой поиск не видит, их отсутствие сегодня
 * не вредит, а завтра, когда её откроют, навредит — молчать нельзя, останавливать незачем.
 */
export function поляПоиска({версии, категория, settings, найдено, этап}) {
  // Находки копятся в общий список: часть правил говорится один раз на статью, а не на версию,
  // и решить это можно только зная, что уже сказано по соседним версиям.
  const общие = [];

  return версии.flatMap((версия) => {
    const беды = [];
    const описание = значениеПоля(версия, 'description');

    if (пусто(версия, 'description')) {
      беды.push(находка({код: 'описаниеПусто', уровень: БЛОКЕР, этап, путь: версия.путь, поле: 'description'}));
    } else if (описание.trim() === String(settings['заглушкаПеревода']['описание']).trim()) {
      // Человек, доводя заглушку до настоящего перевода, заменит заголовок и тело — они кричат
      // о себе, — а описание спрятано в свойствах и останется прежним: в поиске у переведённой
      // статьи будет «перевод пока не готов». Сравнение идёт с настройкой, поэтому спецслучая
      // про заглушки в коде нет.
      беды.push(находка({код: 'описаниеШаблонное', уровень: ПРЕДУПРЕЖДЕНИЕ, этап, путь: версия.путь, поле: 'description'}));
    }

    for (const поле of обязательныеПоля(категория, settings)) {
      // Поле, которому не назначено место в шапке этого рода, окно не покажет: находка «заполните
      // его» повела бы человека туда, где заполнять нечего. Это беда настройки, а не статьи.
      if (!(settings['поляСоздания'][версия.род]?.['порядок'] ?? []).includes(поле)) {
        // Это беда одной настройки, а не трёх файлов: у трёхъязычной статьи человек получил бы
        // три одинаковых блокера про одно и то же. Говорится один раз, без пути версии.
        const сказано = [...найдено, ...общие].some((было) => было.код === 'полюНегдеСтоять' && было.поле === поле);
        if (!сказано) беды.push(находка({код: 'полюНегдеСтоять', уровень: БЛОКЕР, этап, поле}));
        continue;
      }

      if (!пусто(версия, поле)) continue;
      // Про это поле уже сказано разбором шапки — пустой список ключевых слов виден и там, и тут.
      // Две строки отчёта про одну строку файла человеку ничего не добавляют.
      if (найдено.some((было) => было.путь === версия.путь && было.поле === поле)) continue;

      беды.push(находка({
        код: 'полеКатегорииПусто',
        уровень: версия.скрыта ? ПРЕДУПРЕЖДЕНИЕ : БЛОКЕР,
        этап,
        путь: версия.путь,
        поле,
      }));
    }

    общие.push(...беды);
    return беды;
  });
}

/**
 * Пусто ли поле по существу. У списка это спрашивается тем же правилом, каким защитная проверка
 * решает, убрать ли строку: показанный вид тут врёт — список из пустых строк выглядит строкой
 * с запятыми и кажется заполненным.
 */
function пусто(версия, ключ) {
  const группа = версия.группы.find((кусок) => кусок.ключ === ключ);
  if (группа === undefined) return true;
  if (списокБезЗначений(группа)) return true;

  return пустоеЗначение(значениеПоля(версия, ключ));
}

/** Показанное значение поля: пустая строка и у поля, которого в шапке нет вовсе. */
function значениеПоля(версия, ключ) {
  return версия.поля.find((поле) => поле.key === ключ)?.display ?? '';
}

/**
 * Адреса языковых версий обязаны совпадать, иначе ломается переключатель языка (SPEC 2.5).
 *
 * Сравниваются адреса, приведённые к правилу раздела, а не записанные в файле: адрес не по правилу
 * уже дал находку сухого прогона, и сырое сравнение выдало бы вторую строку отчёта про ту же
 * строку файла. Расходятся приведённые — это отдельная настоящая беда.
 */
export function адресаВерсий({версии, settings, этап}) {
  const беды = [];
  const адреса = версии.map((версия) => {
    const запись = версия.поля.find((поле) => поле.key === 'slug');
    const голый = запись === undefined ? '' : безКавычек(String(запись.raw ?? '').trim());

    // Ключ есть, а значения нет — своя беда, и называть её надо своим именем: YAML читает такой
    // адрес пустотой, и сборка падает на нём, а не на расхождении версий.
    if (запись !== undefined && голый === '') {
      беды.push(находка({код: 'адресПуст', уровень: БЛОКЕР, этап, путь: версия.путь, поле: 'slug'}));
    }

    return {версия, адрес: приведённыйАдрес(версия, голый, settings)};
  });

  if (адреса.length < 2) return беды;

  const образец = адреса.find(({версия}) => версия.локаль === settings['основнойЯзык']) ?? адреса[0];

  return [
    ...беды,
    ...адреса
      .filter((версия) => версия !== образец)
      .filter(({адрес}) => !sameSlugAcrossLocales(образец.адрес, адрес))
      .map(({версия, адрес}) => находка({
        код: 'адресаВерсийРазные',
        уровень: БЛОКЕР,
        этап,
        путь: версия.путь,
        поле: 'slug',
        // Не «было и стало»: там эти слова значат «программа перепишет», а здесь никто ничего
        // переписывать не собирается. Оба адреса приведены к правилу раздела — в файле запись
        // может быть короче или отсутствовать вовсе, а окно обязано говорить про адрес на сайте.
        образец: образец.адрес,
        адрес,
      })),
  ];
}

/**
 * Адрес версии так, как он ляжет на сайт. Записи в шапке может не быть вовсе — тогда адрес даёт
 * путь файла, ровно как это делает сам Docusaurus. Считать такую версию «без адреса» и выбрасывать
 * из сравнения нельзя: адрес, записанный только у одной версии, разошёлся бы с выведенным у
 * соседней, переключатель языка повёл бы в никуда, а подготовка промолчала бы.
 */
function приведённыйАдрес(версия, голый, settings) {
  const свой = голый === '' ? имяПапки(версия.путь) : голый;
  return normalizeSlug(версия.путь, свой, settings['контент']);
}

/** Имя папки статьи: из него Docusaurus и делает адрес, когда своего в шапке нет. */
function имяПапки(путь) {
  const части = String(путь).split('/').filter(Boolean);
  return части.length < 2 ? '' : части[части.length - 2];
}
