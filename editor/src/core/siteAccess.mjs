// Доступность языковой версии на сайте: ОДНО понятие человека поверх двух полей Docusaurus.
//
// Полей два — `draft` и `unlisted`, — но состояний у страницы три, а не четыре: Docusaurus 3.10
// отвергает шапку, где стоят оба, и роняет сборку ВСЕГО сайта («Can't be draft and unlisted at the
// same time», проверено полной сборкой 2026-09-08). Дай человеку два независимых флажка — и он
// собственными руками соберёт запрещённую пару, а узнает об этом только на выпуске.
//
// Поэтому выбор один и с тремя ответами (решение владельца 2026-09-08): «Недоступно» — страницы на
// сайте нет вовсе, «По ссылке» — страница есть, но не в меню, «Доступно всем» — обычная страница.
// Переход всегда пишет одно поле и убирает противоположное, поэтому запрещённая пара не рождается.
//
// Правило живёт здесь, а не в окне (SPEC 4.8), и проверяется результатом: отрисовать окно нечем.

import {ПОЛЕ_ЧЕРНОВИКА} from './frontmatterFields.mjs';
import {ПОЛЕ_ВИДИМОСТИ} from './frontmatterRules.mjs';

/** Страницы на сайте нет вовсе: сборка её не выпускает. */
export const НЕДОСТУПНО = 'недоступно';
/** Страница на сайте есть, но её нет ни в меню, ни в поиске: только по прямой ссылке. */
export const ПО_ССЫЛКЕ = 'поСсылке';
/** Обычная страница сайта. */
export const ДОСТУПНО = 'всем';

/** Порядок ответов — от самого закрытого к самому открытому. Им же идут строки выбора в окне. */
export const РЕЖИМЫ = [НЕДОСТУПНО, ПО_ССЫЛКЕ, ДОСТУПНО];

/**
 * Какая сейчас доступность по полям шапки. `поля` — поля в человеческом виде (`frontmatterFields`),
 * где значение флажка уже приведено к «да»/«нет»: явное `false` там неотличимо от отсутствия
 * строки, как его читает и сам сайт.
 *
 * Спор двух полей решается в пользу `draft`: такую шапку программа не пишет, но её могли написать
 * руками, и страницы на сайте в этом случае нет вовсе — сказать «по ссылке» значило бы соврать.
 */
export function режимДоступности(поля) {
  const стоит = (ключ) => (поля ?? []).find((поле) => поле.key === ключ)?.display === 'true';

  if (стоит(ПОЛЕ_ЧЕРНОВИКА)) return НЕДОСТУПНО;
  if (стоит(ПОЛЕ_ВИДИМОСТИ)) return ПО_ССЫЛКЕ;

  return ДОСТУПНО;
}

/**
 * Какими станут поля после выбора режима. Меняются ровно два поля, остальные возвращаются как есть:
 * выбор доступности не имеет права трогать чужие строки шапки.
 *
 * Противоположное поле не «оставляется как было», а очищается — на этом и держится обещание, что
 * запрещённая пара не появится ни на одном переходе. Пустое значение уберёт строку целиком общим
 * правилом шапки: пустых ключей не бывает.
 */
export function поляРежима(поля, режим) {
  return (поля ?? []).map((поле) => {
    if (поле.key === ПОЛЕ_ЧЕРНОВИКА) return {...поле, display: режим === НЕДОСТУПНО ? 'true' : ''};
    if (поле.key === ПОЛЕ_ВИДИМОСТИ) return {...поле, display: режим === ПО_ССЫЛКЕ ? 'true' : ''};

    return поле;
  });
}
