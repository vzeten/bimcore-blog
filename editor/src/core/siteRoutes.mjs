// Адреса страниц сайта и уборка ссылок на снятую статью. Чистые правила: на входе путь и текст,
// на выходе адрес или новый текст. Диска и git здесь нет (SPEC 4.6).
//
// **Адрес считается так же, как его считает сайт.** Документация живёт от корня (`routeBasePath: '/'`),
// блог — под своим префиксом, обязательный язык идёт без префикса, остальные — под `/<язык>`
// (`plugins/translation-map/map.mjs`, `localeRoute`). Своих правил пути здесь нет: адрес внутри
// раздела даёт `normalizeSlug`/`адресБезSlug` — то же место, где программа считает адрес всегда.
//
// **Снятая статья исчезает во ВСЕХ языках сразу.** Язык без своего файла отдаёт под своим адресом
// текст обязательного языка; снят и он — страницы нет нигде. Поэтому адреса статьи считаются по
// каждому языку сайта, а не только по тем, чьи файлы лежат у человека.

import {splitArticle, readField} from './articleFile.mjs';
import {articlePlace, normalizeSlug, адресБезSlug} from './frontmatterRules.mjs';

/** Адрес без хвостовой косой и без повторов косой; корень остаётся `/`. */
export function чистыйАдрес(адрес) {
  const свой = `/${String(адрес ?? '')}`.replace(/\/{2,}/g, '/').replace(/\/+$/, '');
  return свой === '' ? '/' : свой;
}

/**
 * Адрес версии внутри своего языка: `/lessons/proba`, `/blog/post`. Пустая строка — страницы на
 * сайте у файла нет (песочница, запись вне известных корней).
 */
export function адресВнутриЯзыка(путь, текст, roots, префиксБлога) {
  const место = articlePlace(путь, roots);
  if (!место.наСайте || (место.kind !== 'docs' && место.kind !== 'blog')) return '';

  const slug = readField(splitArticle(String(текст ?? '')).frontmatterRaw, 'slug').trim();
  const свой = slug !== '' ? normalizeSlug(путь, slug, roots) : адресБезSlug(путь, roots);

  return чистыйАдрес(место.kind === 'blog' ? `${префиксБлога}/${свой}` : свой);
}

/** Адрес в языке: обязательный язык без префикса, остальные — под своим. */
export function адресВЯзыке(адрес, локаль, обязательный) {
  if (адрес === '' || локаль === обязательный) return адрес;
  return адрес === '/' ? `/${локаль}` : `/${локаль}${адрес}`;
}

/** Полный адрес версии на сайте — с префиксом её языка. */
export function адресВерсии(путь, текст, {roots, префиксБлога, обязательный}) {
  return адресВЯзыке(адресВнутриЯзыка(путь, текст, roots, префиксБлога), articlePlace(путь, roots).locale, обязательный);
}

/**
 * Все адреса статьи на сайте: адрес каждой версии в каждом языке сайта. Версии — `{путь, текст}`;
 * текст нужен ради `slug` в шапке.
 */
export function адресаСтатьи(версии, {roots, префиксБлога, обязательный, локали}) {
  const адреса = new Set();
  for (const версия of версии ?? []) {
    const свой = адресВнутриЯзыка(версия.путь, версия.текст, roots, префиксБлога);
    if (свой === '') continue;
    for (const локаль of локали) адреса.add(адресВЯзыке(свой, локаль, обязательный));
  }
  return адреса;
}

/**
 * Куда ведёт ссылка из документа: `{адрес}` страницы сайта, `{файл}` соседнего документа по пути
 * репозитория либо `null` — ссылка не на наш сайт (почта, чужой сервер, якорь на той же странице).
 *
 * `откуда` — ссылающийся документ: `{путь, адрес, локаль}` плюс `хост` сайта, `обязательный` язык и
 * `локали` сайта.
 * Абсолютный путь без хоста сайт в языке документа читает как адрес этого языка: у русской
 * страницы `/lessons/x` ведёт на `/ru/lessons/x`. Относительный адрес браузер разрешает от адреса
 * страницы, а у сайта он всегда кончается косой (`trailingSlash: true`).
 */
export function кудаВедёт(цель, откуда) {
  const голая = String(цель ?? '').trim().replace(/^<(.*)>$/s, '$1');
  if (голая === '' || голая.startsWith('#') || голая.startsWith('//')) return null;

  if (/^[a-z][a-z0-9+.-]*:/i.test(голая)) {
    if (!/^https?:/i.test(голая) || !откуда.хост) return null;
    try {
      const адрес = new URL(голая);
      return адрес.host === откуда.хост ? {адрес: чистыйАдрес(раскрыть(адрес.pathname))} : null;
    } catch {
      return null;
    }
  }

  const путь = голая.split(/[?#]/)[0];
  if (путь === '') return null;
  if (путь.startsWith('/')) {
    const свой = чистыйАдрес(путь);
    // Адрес с префиксом любого языка сайта автор написал нарочно: он ведёт в тот язык.
    const {локаль, обязательный, локали = [локаль]} = откуда;
    const сЯзыком = локаль === обязательный || локали.some((код) => свой === `/${код}` || свой.startsWith(`/${код}/`));
    return {адрес: сЯзыком ? свой : адресВЯзыке(свой, локаль, обязательный)};
  }

  // Ссылка на файл документа: Docusaurus сам превращает её в адрес целевой страницы.
  if (/\.mdx?$/i.test(путь)) {
    const папка = откуда.путь.slice(0, откуда.путь.lastIndexOf('/') + 1);
    return {файл: раскрыть(new URL(путь, `https://файл/${папка}`).pathname).slice(1)};
  }

  const страница = откуда.адрес === '/' ? '' : String(откуда.адрес ?? '');
  return {адрес: чистыйАдрес(раскрыть(new URL(путь, `https://сайт${страница}/`).pathname))};
}

/** Раскрыть `%XX` в пути; испорченная запись остаётся как есть — угадывать её незачем. */
function раскрыть(путь) {
  try {
    return decodeURIComponent(путь);
  } catch {
    return путь;
  }
}

/** Markdown-ссылка `[текст](цель "заголовок")`; `!` впереди — картинка, её не трогаем. */
const MD_ССЫЛКА = /(!?)\[((?:[^[\]\\]|\\.|\[(?:[^[\]\\]|\\.)*\])*)\]\(\s*(<[^>\n]*>|[^\s()]*(?:\([^\s()]*\)[^\s()]*)*)(?:\s+(?:"[^"\n]*"|'[^'\n]*'|\([^)\n]*\)))?\s*\)/g;

/** Ссылка разметкой: `<a href="…">текст</a>` и `<Link to="…">текст</Link>`. */
const ТЕГ_ССЫЛКИ = /<(a|Link)\b([^>]*?)\b(?:href|to)\s*=\s*(?:"([^"]*)"|'([^']*)'|\{\s*["'`]([^"'`]*)["'`]\s*\})([^>]*)>([\s\S]*?)<\/\1\s*>/g;

/**
 * Убрать ссылки на снятые страницы: ссылка становится своим текстом, текст вокруг не меняется.
 *
 * `цели` — `{адреса: Set, файлы: Set}`: адреса снятых страниц без хвостовой косой и пути их файлов.
 * `откуда` — ссылающийся документ (см. `кудаВедёт`).
 *
 * Код не трогается: ни блок в тройных кавычках, ни `код` в строке — там ссылка лишь пример.
 * Шапка не трогается тоже. Что после уборки ещё похоже на снятый адрес (ссылка-сноска, голый
 * адрес в тексте, форма, которую правило не знает), уходит в `непонятные`: угадывать чужую
 * разметку нельзя, и зовущий обязан остановиться, а не оставить на сайте битую ссылку.
 *
 * Возвращает `{текст, заменено, непонятные}`.
 */
export function безСсылок(текст, цели, откуда) {
  const {head, body} = splitArticle(String(текст ?? ''));
  const наша = (цель) => {
    const куда = кудаВедёт(цель, откуда);
    return куда !== null && (куда.адрес !== undefined ? цели.адреса.has(куда.адрес) : цели.файлы.has(куда.файл));
  };

  let заменено = 0;
  const непонятные = [];
  const части = кускиБезКода(body).map((кусок) => {
    if (кусок.код) return кусок.текст;
    const строчный = строчныйКод(кусок.текст);
    const вКоде = (место) => строчный.some(([от, до]) => место >= от && место < до);

    let свой = кусок.текст.replace(MD_ССЫЛКА, (всё, знак, подпись, цель, место) => {
      if (знак === '!' || вКоде(место) || !наша(цель)) return всё;
      заменено += 1;
      return подпись;
    });
    const строчныйПосле = строчныйКод(свой);
    свой = свой.replace(ТЕГ_ССЫЛКИ, (всё, _тег, _до, a, b, c, _после, подпись, место) => {
      if (строчныйПосле.some(([от, до]) => место >= от && место < до) || !наша(a ?? b ?? c)) return всё;
      заменено += 1;
      return подпись;
    });
    непонятные.push(...остатки(свой, цели.адреса, откуда));
    return свой;
  });

  return {текст: head + части.join(''), заменено, непонятные: [...new Set(непонятные)]};
}

/**
 * Что в тексте вне кода всё ещё похоже на снятый адрес. Ищется сам адрес и, у страниц своего
 * языка, он же без префикса языка; слева — начало, пробел, скобка, кавычка или хост.
 */
function остатки(текст, адреса, {локаль, обязательный}) {
  const строчный = строчныйКод(текст);
  const найдено = [];
  for (const адрес of адреса) {
    const формы = [адрес];
    if (локаль !== обязательный && адрес.startsWith(`/${локаль}/`)) формы.push(адрес.slice(локаль.length + 1));
    for (const форма of формы) {
      const образец = new RegExp(`(?<=^|[\\s("'<\\[=]|://[^/\\s"'()<>]+)${экранировать(форма)}(?=$|[/#?)"'\\s>\\]])`, 'g');
      for (const совпадение of текст.matchAll(образец)) {
        if (!строчный.some(([от, до]) => совпадение.index >= от && совпадение.index < до)) найдено.push(форма);
      }
    }
  }
  return найдено;
}

const экранировать = (строка) => строка.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/**
 * Текст по кускам: `{код: true}` — блок в тройных кавычках или тильдах вместе с забором, остальное —
 * обычный текст. Незакрытый блок тянется до конца документа, как у самого разборщика markdown.
 */
export function кускиБезКода(текст) {
  const куски = [];
  const строки = текст.split(/(?<=\n)/);
  let обычный = '';
  let блок = null;

  for (const строка of строки) {
    if (блок === null) {
      const забор = /^[ \t]*(`{3,}|~{3,})/.exec(строка);
      if (забор) {
        if (обычный !== '') куски.push({код: false, текст: обычный});
        обычный = '';
        блок = {забор: забор[1], текст: строка};
      } else {
        обычный += строка;
      }
      continue;
    }

    блок.текст += строка;
    const конец = new RegExp(`^[ \\t]*${блок.забор[0] === '`' ? '`' : '~'}{${блок.забор.length},}[ \\t]*\\r?\\n?$`);
    if (конец.test(строка)) {
      куски.push({код: true, текст: блок.текст});
      блок = null;
    }
  }

  if (блок !== null) куски.push({код: true, текст: блок.текст});
  if (обычный !== '') куски.push({код: false, текст: обычный});
  return куски;
}

/** Места строчного кода: `[начало, конец)` каждого куска в обратных кавычках. */
function строчныйКод(текст) {
  const места = [];
  for (const совпадение of текст.matchAll(/(`+)[\s\S]*?\1/g)) {
    места.push([совпадение.index, совпадение.index + совпадение[0].length]);
  }
  return места;
}
