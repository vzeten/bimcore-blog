// Обработчики файлов медиа: «медиаподготовка» и «переименование картинок». Чистые правила: файлы
// приходят байтами в рабочей копии. Преобразование делает инструмент адаптера — единственный
// алгоритм сайта `scripts/image-prep.py`; здесь решается только «какие файлы» и «как обновить ссылки».
// Род файла — по байтам: PNG/JPG/GIF/WebM узнаёт `imageType.mjs`, WebP — сигнатура здесь же,
// потому что в теле и обложке статьи WebP не живёт и общий разбор его намеренно не знает.

import {типКартинки} from './imageType.mjs';
import {имяКартинки} from './imageName.mjs';
import {живыеИмена} from './refineHead.mjs';
import {заменитьАдреса, локальноеИмя, обложкаШапки, ссылкиМедиа} from './refineText.mjs';

/** Технические величины формата сайта — те же, что в `scripts/image-prep.py`. */
const ДЛИННАЯ_СТОРОНА = 1000;
const ФОРМАТ_САЙТА = 'png';
/** Что скрипт преобразует; GIF и WebM он не трогает. */
const НЕПОДВИЖНЫЕ = new Set(['png', 'jpg', 'webp']);
const В_КИЛОБАЙТЕ = 1024;

/** Род по байтам вместе с WebP (`RIFF????WEBP`). */
export function родМедиа(байты) {
  const б = байты ?? new Uint8Array(0);
  const слово = (i, текст) => [...текст].every((з, k) => б[i + k] === з.charCodeAt(0));
  return б.length >= 12 && слово(0, 'RIFF') && слово(8, 'WEBP') ? 'webp' : типКартинки(б);
}

/** Ширина и высота по заголовку: PNG — IHDR, JPEG — первый кадр SOF; иначе `null`. */
export function размерыКартинки(байты, род) {
  const б = байты ?? new Uint8Array(0);
  const u16 = (i) => (б[i] << 8) | б[i + 1];
  const u32 = (i) => ((б[i] << 24) | (б[i + 1] << 16) | (б[i + 2] << 8) | б[i + 3]) >>> 0;
  if (род === 'png' && б.length >= 24) return {ширина: u32(16), высота: u32(20)};
  if (род !== 'jpg') return null;
  for (let i = 2; i + 9 < б.length;) {
    if (б[i] !== 0xff) return null;
    const маркер = б[i + 1];
    if (маркер >= 0xc0 && маркер <= 0xcf && маркер !== 0xc4 && маркер !== 0xc8 && маркер !== 0xcc) {
      return {ширина: u16(i + 7), высота: u16(i + 5)};
    }
    i += 2 + u16(i + 2);
  }
  return null;
}

/** Размер после уменьшения до длинной стороны сайта: меньшее не растёт (правило скрипта). */
export function размерПоСтандарту({ширина, высота}) {
  const доля = Math.min(1, ДЛИННАЯ_СТОРОНА / Math.max(ширина, высота, 1));
  return {ширина: Math.max(1, Math.round(ширина * доля)), высота: Math.max(1, Math.round(высота * доля))};
}

/** Размеры и вес одной строкой отчёта. */
export function описание(байты, род) {
  const размер = размерыКартинки(байты, род);
  const хвост = `${String(род ?? '?').toUpperCase()}, ${Math.round(байты.length / В_КИЛОБАЙТЕ)} КБ`;
  return размер === null ? хвост : `${размер.ширина}×${размер.высота}, ${хвост}`;
}

/** Используемые версией файлы, которые есть в копии: по порядку появления, обложка последней. */
function используемые(копия) {
  const имена = [...ссылкиМедиа(копия.текст).map((с) => с.адрес), обложкаШапки(копия.текст)]
    .map(локальноеИмя).filter((имя) => имя !== null && копия.файлы.get(имя) instanceof Uint8Array);
  return [...new Set(имена)].map((имя) => ({имя, байты: копия.файлы.get(имя), род: родМедиа(копия.файлы.get(имя))}));
}

const расширение = (имя) => имя.slice(имя.lastIndexOf('.') + 1).toLowerCase().replace('jpeg', 'jpg');
const тоЖе = (a, b) => a.toLowerCase() === b.toLowerCase();

/** Обработчик 3: неподвижные картинки всегда проходят скрипт сайта; анимация и видео не читаются. */
export const медиаподготовка = {
  анализ(копия) {
    const список = используемые(копия);
    if (список.length === 0) return null;
    const свои = new Set(список.map((ф) => ф.имя));
    const отчёт = {изменено: [], оставлено: [], человеку: []};
    const цели = [];

    for (const {имя, байты, род} of список) {
      if (!НЕПОДВИЖНЫЕ.has(род)) {
        отчёт.оставлено.push({что: имя, причина: род === null ? 'чужойВид' : 'анимация'});
        continue;
      }
      const новое = `${имя.slice(0, имя.lastIndexOf('.'))}.${ФОРМАТ_САЙТА}`;
      if (!тоЖе(новое, имя) && живыеИмена(копия).some((занято) => тоЖе(занято, новое) && !свои.has(занято))) {
        отчёт.человеку.push({что: имя, причина: 'имяЗанято'});
        continue;
      }
      const размер = размерыКартинки(байты, род);
      const ожидается = размер === null ? '' : `${Object.values(размерПоСтандарту(размер)).join('×')}, `;
      const стало = `${новое}: ${ожидается}${ФОРМАТ_САЙТА.toUpperCase()}`;
      цели.push({имя, новое: тоЖе(новое, имя) ? имя : новое, род, стало});
      отчёт.изменено.push({что: имя, было: описание(байты, род), стало});
    }
    return {цели, отчёт};
  },

  async применить(копия, предложение, инструменты) {
    const готовые = await инструменты.подготовить(предложение.цели.map(({имя, род}) => ({байты: копия.файлы.get(имя), род})));
    const файлы = new Map(копия.файлы);
    const карта = new Map();
    const отчёт = {...предложение.отчёт, изменено: []};
    предложение.цели.forEach(({имя, новое, род, стало}, i) => {
      const {байты, предсказано} = готовые[i];
      файлы.set(новое, байты);
      if (новое !== имя) {
        файлы.set(имя, null);
        карта.set(имя, новое);
      }
      отчёт.изменено.push({что: имя, было: описание(копия.файлы.get(имя), род), стало: предсказано ? стало : `${новое}: ${описание(байты, ФОРМАТ_САЙТА)}`});
    });
    return {копия: {...копия, файлы, текст: заменитьАдреса(копия.текст, карта)}, отчёт};
  },

  проверить(копия, предложение) {
    return предложение.цели.every(({имя, новое}) => копия.файлы.get(новое) instanceof Uint8Array
      && (новое === имя || !ссылкиМедиа(копия.текст).some((с) => локальноеИмя(с.адрес) === имя)));
  },
};

/** Обработчик 4: картинки тела по шаблону имени и порядку в статье; обложка и чужие файлы не трогаются. */
export const переименование = {
  анализ(копия, settings) {
    const {шаблонИмени, знаковВНомере} = settings['картинки'];
    const обложка = локальноеИмя(обложкаШапки(копия.текст));
    const список = используемые(копия).filter(({имя, род}) => имя !== обложка && род !== null && род !== 'webm');
    if (список.length === 0) return null;
    const свои = new Set(список.map((ф) => ф.имя));
    const занятые = живыеИмена(копия).filter((имя) => !свои.has(имя)).map((имя) => имя.toLowerCase());
    const отчёт = {изменено: [], оставлено: [], человеку: []};
    const цели = [];

    список.forEach(({имя}, i) => {
      const папка = имя.includes('/') ? имя.slice(0, имя.lastIndexOf('/') + 1) : '';
      const короткое = имяКартинки(шаблонИмени, i + 1, расширение(имя), знаковВНомере);
      if (короткое === null) return отчёт.человеку.push({что: имя, причина: 'имяНеПодобрано'});
      const новое = `${папка}${короткое}`;
      if (новое === имя) return отчёт.оставлено.push({что: имя, причина: 'тоЖеИмя'});
      if (занятые.includes(новое.toLowerCase())) return отчёт.человеку.push({что: имя, причина: 'имяЗанято'});
      цели.push({имя, новое});
      return отчёт.изменено.push({что: имя, было: имя, стало: новое});
    });
    return {цели, отчёт};
  },

  применить(копия, предложение) {
    const файлы = new Map(копия.файлы);
    // Сначала все источники снимаются, потом ложатся все цели: обмен имён иначе затёр бы одно другим.
    for (const {имя} of предложение.цели) файлы.set(имя, null);
    for (const {имя, новое} of предложение.цели) файлы.set(новое, копия.файлы.get(имя));
    return {копия: {...копия, файлы, текст: заменитьАдреса(копия.текст, new Map(предложение.цели.map(({имя, новое}) => [имя, новое])))}};
  },

  проверить(копия, предложение) {
    const старые = new Set(предложение.цели.map((ц) => ц.имя).filter((имя) => копия.файлы.get(имя) === null));
    return предложение.цели.every(({новое}) => копия.файлы.get(новое) instanceof Uint8Array)
      && !ссылкиМедиа(копия.текст).some((с) => старые.has(локальноеИмя(с.адрес)));
  },
};
