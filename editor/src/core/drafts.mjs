// Автосохранённый черновик: рабочее состояние статьи до кнопки «Сохранить».
// Чистые правила: что считать черновиком, когда его предлагать и когда это конфликт.
// Файлов здесь нет — их читает и пишет адаптер.
//
// Отпечаток файла приходит строкой снаружи: как его считать — дело адаптера (там node:crypto),
// а правило «сравнить отпечатки» должно проверяться без диска.

import {плоскоеИмя} from './history.mjs';
import {nothingChanged} from './articleFile.mjs';

/** Имя файла черновика: путь к статье превращается в плоское имя, как у снимков. */
export function draftName(articlePath) {
  return `${плоскоеИмя(articlePath)}.json`;
}

/**
 * Имя черновика по прежней схеме — без отпечатка пути.
 * Нужно ровно для одного: не потерять незаписанную работу, оставшуюся в черновике старого вида.
 * Читается только как запасной вариант и только при совпадении пути внутри записи.
 */
export function староеИмяЧерновика(articlePath) {
  return `${String(articlePath).split('\\').join('/').replace(/[^\wа-яё-]+/gi, '_')}.json`;
}

/**
 * Черновик как запись: что правил человек, от какой версии файла он отталкивался,
 * когда правка была сделана в окне (`правкаОт`) и когда её приняли на диск (`когда`).
 */
export function newDraft({path, frontmatterRaw, body, отпечатокБазы, когда, правкаОт}) {
  return {path, frontmatterRaw, body, отпечатокБазы, когда, правкаОт: правкаОт ?? когда};
}

/** Запись черновика. Один и тот же вход даёт один и тот же текст. */
export function writeDraft(draft) {
  const ordered = {
    path: draft['path'],
    когда: draft['когда'],
    правкаОт: draft['правкаОт'] ?? draft['когда'],
    отпечатокБазы: draft['отпечатокБазы'],
    frontmatterRaw: draft['frontmatterRaw'],
    body: draft['body'],
  };

  return `${JSON.stringify(ordered, null, 2)}\n`;
}

/**
 * Принимать ли пришедший черновик. Браузер прерывает устаревший запрос, но сервер мог принять его
 * раньше обрыва: тогда поздний ответ старой правки затёр бы или удалил уже записанную свежую.
 * Порядок держится на времени правки в окне, а не на времени прихода запроса.
 * Времени нет ни в запросе, ни на диске — принимаем: старые черновики должны продолжать работать.
 */
export function свежееЧерновика(правкаОт, прежний) {
  const пришло = Date.parse(правкаОт ?? '');
  const было = Date.parse(прежний?.['правкаОт'] ?? '');
  if (!Number.isFinite(пришло) || !Number.isFinite(было)) return true;
  return пришло >= было;
}

/**
 * Позднее из двух времён. Нужно, чтобы порог свежести не сбрасывался, когда черновик убран:
 * настоящее сохранение удаляет черновик, и без памяти о нём задержавшийся старый запрос
 * воскресил бы черновик поверх уже сохранённой работы.
 */
export function позже(a, b) {
  const первое = Date.parse(a ?? '');
  const второе = Date.parse(b ?? '');
  if (!Number.isFinite(первое)) return Number.isFinite(второе) ? b : null;
  if (!Number.isFinite(второе)) return a;
  return первое >= второе ? a : b;
}

/** Разбор черновика. Битый файл — не повод падать: считаем, что черновика нет. */
export function readDraft(raw) {
  if (typeof raw !== 'string' || raw.trim() === '') return null;

  try {
    const parsed = JSON.parse(raw);
    // Проверяются все поля, а не только часть: черновик с недостающим полем дал бы
    // «продолжение работы» с пустой шапкой или сравнение с пустым отпечатком.
    const целый = ['path', 'когда', 'отпечатокБазы', 'frontmatterRaw', 'body']
      .every((поле) => typeof parsed?.[поле] === 'string');

    return целый ? parsed : null;
  } catch {
    return null;
  }
}

/**
 * Что делать с найденным черновиком при открытии статьи.
 * `нет` — предлагать нечего (черновика нет, битый, протух или совпадает с файлом);
 * `черновик` — продолжаем работу с автосохранения, молча;
 * `конфликт` — файл изменился снаружи после автосохранения, выбор делает человек.
 */
export function draftDecision({draft, файл, отпечатокФайла, сейчас, settings}) {
  if (!draft) return 'нет';

  const жизньМс = settings['хранение']['черновикЖивётДней'] * 24 * 60 * 60 * 1000;
  const возраст = Date.parse(сейчас) - Date.parse(draft['когда']);
  if (!Number.isFinite(возраст) || возраст > жизньМс) return 'нет';

  // Совпадение с файлом проверяется ПЕРВЫМ: если продолжать нечего, то и конфликта нет,
  // каким бы ни был отпечаток. Иначе черновик, дописанный гонкой уже после сохранения,
  // спрашивал бы человека о выборе между двумя одинаковыми текстами.
  // Переводы строк в счёт не идут (SPEC 3.6): на диске файл может быть в windows-виде, а в окне
  // текст живёт в unix-виде, и точное сравнение выдавало бы одинаковые тексты за разные —
  // человеку предлагали бы «продолжить работу», которой он не делал.
  if (nothingChanged(файл, {body: draft['body'], frontmatterRaw: draft['frontmatterRaw']})) return 'нет';

  // Файл сменился под черновиком — молча подменять нельзя, спрашиваем человека.
  if (draft['отпечатокБазы'] !== отпечатокФайла) return 'конфликт';

  return 'черновик';
}

/**
 * Какие снимки удалить, чтобы их осталось не больше предела.
 * Имена снимков начинаются со времени, поэтому старые — первые по алфавиту.
 */
export function extraSnapshots(names, максимум) {
  const sorted = [...names].sort();
  return sorted.length <= максимум ? [] : sorted.slice(0, sorted.length - максимум);
}
