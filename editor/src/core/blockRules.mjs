// Блоки в теле статьи глазами подготовки: заполнены ли у них поля, без которых блок бесполезен.
//
// Свойства блока человек правит в окне, а видит их последствия на сайте: видео без номера не
// покажется вовсе, а видео без названия и даты не попадёт в поиск. Молчание подготовки об этом —
// ложный успех: статья выпущена, а блок в ней пустой.
//
// Что именно требуется, решает не код, а реестр блоков в настройках: у поля стоит `обязательное`
// с уровнем находки. Блока нет в реестре — программа его не понимает и потому о нём молчит.

import {строкаМеста, тегиТекста} from './jsxTag.mjs';
import {БЛОКЕР, находка} from './prepareRules.mjs';

/**
 * Пустые обязательные поля известных блоков тела. Возвращается по находке на поле: человеку
 * называется блок, поле и строка файла, а не «где-то в статье что-то не так».
 */
export function пустыеПоляБлоков(тело, блоки) {
  const беды = [];
  if (!блоки) return беды;

  for (const тег of тегиТекста(тело ?? '')) {
    const описание = блоки[тег.имя];
    if (описание === undefined) continue;

    for (const поле of описание.поля ?? []) {
      if (поле.обязательное === undefined) continue;

      const значение = тег.свойства.find((свойство) => свойство.имя === поле.имя)?.значение ?? '';
      if (значение.trim() !== '') continue;

      беды.push({
        блок: тег.имя,
        подписьБлока: описание.подпись,
        поле: поле.имя,
        подписьПоля: поле.подпись,
        уровень: поле.обязательное,
        строка: строкаМеста(тело, тег.от),
      });
    }
  }

  return беды;
}

/**
 * Блоки тела статьи: заполнено ли у них то, без чего блок бесполезен читателю. Что требовать,
 * сказано в реестре блоков настроек, а не здесь: программа спрашивает ровно те поля, которые
 * сама же показывает человеку в свойствах блока.
 *
 * Тег, которого в реестре нет, правило не трогает вовсе — он остаётся текстом статьи (SPEC 4.9).
 */
export function блокиТела({версии, settings, этап}) {
  return версии.flatMap((версия) => пустыеПоляБлоков(версия.тело, settings['блоки']).map((беда) => находка({
    код: `блок:${беда.уровень === БЛОКЕР ? 'пустоОбязательное' : 'пустоЖелательное'}`,
    уровень: беда.уровень,
    этап,
    путь: версия.путь,
    поле: беда.поле,
    строка: беда.строка,
    блок: беда.подписьБлока,
    свойство: беда.подписьПоля,
  })));
}
