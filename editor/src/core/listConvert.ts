// Кнопки списка панели: выделенные абзацы становятся пунктами компактного списка, повторное нажатие
// действующего вида возвращает абзацы, другой вид меняет маркеры. Чистое правило: на входе текст,
// выделение и вид, на выходе — построчные замены либо отказ.
//
// Единица преобразования — абзац или пункт вместе со строками-продолжениями и вложениями, а не
// физическая строка: перенос внутри абзаца остаётся внутри пункта, второй абзац, картинка, код и
// вложенный список остаются внутри пункта. Что абзац, а что пункт, говорит настоящее дерево разбора
// markdown окна (`Окружение.дерево`), а не взгляд на строку: `2. монтаж` посреди абзаца — текст,
// потому что нумерованный список прерывает абзац только единицей. Границы примечаний текстом не
// считаются и обрывают единицу. Выделение целиком внутри вложенного списка правит его пункты.
//
// Правка идёт двумя ступенями одной транзакции. Первая ставит и меняет маркеры задетых единиц.
// Вторая смотрит на результат тем же разбором и уплотняет затронутый список вместе с соседними
// списками того же вида (`listStructure.ts`): знак маркера один, номера подряд, зазоры уходят, если
// каждый пункт простой. Слова и вложения соседей не трогаются — только их маркеры, номера и зазоры;
// список за текстом, заголовком, картинкой или границей примечания соседом не считается.
//
// Отказ (`null`) остаётся там, где без потерь не превратить: заголовок, цитата, код, таблица, картинка,
// разметка MDX или граница примечания в задетом, а также форма, которую окно и сайт читают
// по-разному: строка с номером не единицей сразу под пунктом другого списка без пустой строки.

import type {SyntaxNode} from '@lezer/common';
import type {Selection} from './commands';
import {
  видУзла, группа, построчно, простой, сдвигПродолжений, список, уплотнение,
  type Замена, type Окружение, type Пункт, type Список, type Текст, type ВидСписка,
} from './listStructure';

export type {Окружение, ВидСписка} from './listStructure';

export interface ПравкаСписка {
  /** Первая ступень — в координатах исходного текста. */
  changes: Замена[];
  /** Вторая ступень — в координатах текста после первой; пуста, когда ступень одна. */
  затем: Замена[];
  /** Что выделить после правки, в координатах исходного текста: от начала первой единицы до конца последней. */
  выделение: Selection;
}

interface Единица {
  от: number;
  до: number;
  /** Узел дерева: пункт либо верхнеуровневый абзац. */
  узел: SyntaxNode;
  пункт: Пункт | null;
  список: Список | null;
}

/** Строка с номером не единицей: по CommonMark она не прерывает абзац, но сайт начинает ею список. */
const ЧУЖОЙ_НОМЕР = /^( {0,3})(\d{1,9})([.)])(?:\s|$)/;

function чужойНомер(строка: string): {отступ: number; знак: string} | null {
  const м = ЧУЖОЙ_НОМЕР.exec(строка);
  return м === null || Number(м[2]) === 1 ? null : {отступ: м[1].length, знак: м[3]};
}

/**
 * Пункт, к которому ленивым продолжением прилипла строка с чужим номером: она стоит левее колонки
 * содержимого и не продолжает нумерованный список того же знака. Окно и сайт читают её по-разному.
 */
function пунктНеоднозначен(т: Текст, п: Пункт, вид: ВидСписка): boolean {
  const абзац = п.узел.firstChild?.nextSibling ?? null;
  if (абзац === null || абзац.name !== 'Paragraph') return false;
  const свой = вид === 'числа' ? п.маркер.знак : '';
  const до = Math.min(п.до, т.номер(абзац.to));
  for (let i = п.от + 1; i <= до; i += 1) {
    const н = чужойНомер(т.строки[i]);
    if (н !== null && н.отступ < п.маркер.колонка && н.знак !== свой) return true;
  }
  return false;
}

/** Вложенный список пункта, целиком накрывающий строки `a..b`, либо `null`. */
function вложенныйСписок(т: Текст, с: Список, a: number, b: number, границы: ReadonlySet<number>): Список | null {
  const пункт = с.пункты.find((п) => п.от <= a && b <= п.до);
  for (let д = пункт?.узел.firstChild ?? null; д !== null; д = д.nextSibling) {
    if (видУзла(д) === null) continue;
    const вс = список(т, д, границы, a);
    if (вс !== null && вс.пункты[0].от <= a && b <= вс.пункты[вс.пункты.length - 1].до) return вс;
  }
  return null;
}

/** Единицы, задетые выделением, либо `null`, если среди задетого есть то, что без потерь не превратить. */
function единицы(text: string, at: Selection, о: Окружение): {единицы: Единица[]; т: Текст} | null {
  const т = построчно(text);
  const a = т.номер(at.from);
  // Выделение до начала строки эту строку не задевает.
  const b = т.номер(at.to > at.from && т.начала[т.номер(at.to)] === at.to ? at.to - 1 : at.to);
  for (let i = a; i <= b; i += 1) if (о.границы.has(i)) return null;
  const задет = (от: number, до: number): boolean => от <= b && до >= a;

  const узлы: SyntaxNode[] = [];
  for (let узел = о.дерево.topNode.firstChild; узел !== null; узел = узел.nextSibling) {
    if (!задет(т.номер(узел.from), т.номер(узел.to))) continue;
    if (узел.name !== 'Paragraph' && видУзла(узел) === null) return null;
    узлы.push(узел);
  }

  const итог: Единица[] = [];
  // Куски строк между границами примечаний — абзацы: граница не текст и ни в один кусок не входит.
  const абзацы = (узел: SyntaxNode, от: number, до: number): boolean => {
    for (let i = от, с = от; i <= до + 1; i += 1) {
      if (i <= до && !о.границы.has(i)) continue;
      let конец = i - 1;
      while (конец >= с && т.строки[конец].trim() === '') конец -= 1;
      let начало = с;
      while (начало <= конец && т.строки[начало].trim() === '') начало += 1;
      if (начало <= конец && задет(начало, конец)) {
        for (let j = начало; j <= конец; j += 1) if (!о.обычная(т.строки[j])) return false;
        итог.push({от: начало, до: конец, узел, пункт: null, список: null});
      }
      с = i + 1;
    }
    return true;
  };

  for (const узел of узлы) {
    if (узел.name === 'Paragraph') {
      if (!абзацы(узел, т.номер(узел.from), т.номер(узел.to))) return null;
      continue;
    }
    let с: Список | null = список(т, узел, о.границы, a);
    if (с === null) return null;
    // Выделение целиком внутри одного пункта и его вложенного списка: единицы — вложенные пункты.
    if (узлы.length === 1) {
      for (let вложенный: Список | null = с; вложенный !== null; вложенный = вложенныйСписок(т, с, a, b, о.границы)) с = вложенный;
    }
    for (const п of с.пункты) if (задет(п.от, п.до)) итог.push({от: п.от, до: п.до, узел: п.узел, пункт: п, список: с});
    // Хвост узла за границей примечания дерево приписало последнему пункту, а это уже абзацы.
    const последняя = с.пункты[с.пункты.length - 1].до;
    const конецУзла = т.номер(узел.to);
    for (let i = последняя + 1; i <= конецУзла; i += 1) {
      if (!о.границы.has(i)) continue;
      if (!абзацы(узел, i + 1, конецУзла)) return null;
      break;
    }
  }
  итог.sort((x, y) => x.от - y.от);
  return итог.length === 0 ? null : {единицы: итог, т};
}

/**
 * Соседи задетого по дереву — пункт рядом либо соседний список — с формой, которую окно и сайт
 * читают по-разному: сайт мог бы слить их с результатом правки иначе, чем окно.
 */
function соседиНеоднозначны(т: Текст, ед: Единица[], о: Окружение): boolean {
  const неоднозначен = (узел: SyntaxNode | null): boolean => {
    if (узел === null) return false;
    const списокУзла = узел.name === 'ListItem' ? узел.parent : узел;
    const л = списокУзла === null || видУзла(списокУзла) === null ? null : список(т, списокУзла, о.границы);
    if (л === null) return false;
    return л.пункты.some((п) => (узел.name !== 'ListItem' || п.узел.from === узел.from) && пунктНеоднозначен(т, п, л.вид));
  };
  const первая = ед[0];
  const последняя = ед[ед.length - 1];
  const сверху = первая.узел.prevSibling ?? (первая.пункт === null ? null : первая.узел.parent?.prevSibling ?? null);
  const снизу = последняя.узел.nextSibling ?? (последняя.пункт === null ? null : последняя.узел.parent?.nextSibling ?? null);
  return неоднозначен(сверху) || неоднозначен(снизу);
}

/** Действующий вид списка выделения: все задетые единицы — пункты одного вида; иначе `null`. */
export function видСписка(text: string, at: Selection, о: Окружение): ВидСписка | null {
  const р = единицы(text, at, о);
  if (р === null) return null;
  const первый = р.единицы[0].список?.вид ?? null;
  return первый !== null && р.единицы.every((е) => е.список?.вид === первый) ? первый : null;
}

/** Правка по кнопке: см. шапку файла. */
export function преобразованиеСписка(text: string, at: Selection, вид: ВидСписка, о: Окружение): ПравкаСписка | null {
  const р = единицы(text, at, о);
  if (р === null) return null;
  const {единицы: ед, т} = р;
  for (const е of ед) if (е.пункт !== null && е.список !== null && пунктНеоднозначен(т, е.пункт, е.список.вид)) return null;
  if (соседиНеоднозначны(т, ед, о)) return null;
  const последняя = ед[ед.length - 1];
  const to = т.начала[последняя.до] + т.строки[последняя.до].length;
  if (ед.every((е) => е.список?.вид === вид)) {
    // Выделение начинается с текста первого пункта: маркер уходит, а строка остаётся выделенной целиком.
    const первая = ед[0];
    const from = т.начала[первая.от] + Math.min(первая.пункт!.маркер.колонка, т.строки[первая.от].length);
    return {changes: снятие(т, ед, о), затем: [], выделение: {from, to}};
  }
  return создание(text, т, ед, вид, о, {from: т.начала[ед[0].от], to});
}

/**
 * Снятие: маркер и отступ продолжений уходят, вложения выходят наружу. Абзацы отделяются пустой
 * строкой друг от друга и от текста вплотную — иначе прилипли бы продолжением. Граница
 * примечания — не текст, от неё отделять нечего.
 */
function снятие(т: Текст, ед: Единица[], о: Окружение): Замена[] {
  const итог: Замена[] = [];
  const текстРядом = (i: number): boolean => i >= 0 && i < т.строки.length && т.строки[i].trim() !== '' && !о.границы.has(i);
  ед.forEach((е, k) => {
    const м = е.пункт!.маркер;
    const начало = т.начала[е.от];
    const вплотную = k > 0 ? ед[k - 1].до + 1 === е.от : текстРядом(е.от - 1);
    итог.push({from: начало, to: начало + Math.min(м.колонка, т.строки[е.от].length), insert: `${вплотную ? '\n' : ''}${' '.repeat(м.отступ)}`});
    for (let i = е.от + 1; i <= е.до; i += 1) {
      const строка = т.строки[i];
      if (строка.trim() === '') continue;
      const пробелы = /^ */.exec(строка)![0].length;
      if (пробелы > м.отступ) итог.push({from: т.начала[i] + м.отступ, to: т.начала[i] + Math.min(пробелы, м.колонка), insert: ''});
    }
  });
  const ниже = ед[ед.length - 1].до + 1;
  if (текстРядом(ниже)) итог.push({from: т.начала[ниже], to: т.начала[ниже], insert: '\n'});
  return итог;
}

/** Создание или смена вида: первая ступень ставит маркеры, вторая уплотняет затронутый список с соседями. */
function создание(text: string, т: Текст, ед: Единица[], вид: ВидСписка, о: Окружение, выделение: Selection): ПравкаСписка | null {
  // Правка сама создала бы форму, которую окно и сайт читают по-разному: под новыми пунктами без
  // пустой строки строка с чужим номером, а последний новый пункт не продолжает её список тем же знаком.
  const следующая = т.строки[ед[ед.length - 1].до + 1];
  const н = следующая === undefined ? null : чужойНомер(следующая);
  if (н !== null && !(вид === 'числа' && н.знак === '.')) return null;

  const первая: Замена[] = [];
  ед.forEach((е, k) => {
    const текст = вид === 'точки' ? '-' : `${k + 1}.`;
    const начало = т.начала[е.от];
    if (е.пункт === null) {
      первая.push({from: начало, to: начало, insert: `${текст} `});
      // Отступ продолжения не больше трёх пробелов: четыре построчный разбор счёл бы кодом.
      const колонка = Math.min(3, текст.length + 1);
      for (let i = е.от + 1; i <= е.до; i += 1) {
        const пробелы = /^ */.exec(т.строки[i])![0].length;
        первая.push({from: т.начала[i], to: т.начала[i] + пробелы, insert: ' '.repeat(колонка)});
      }
    } else if (е.список!.вид !== вид) {
      const м = е.пункт.маркер;
      первая.push({from: начало + м.отступ, to: начало + м.отступ + м.текст.length, insert: текст});
      первая.push(...сдвигПродолжений(т, е.пункт, текст.length - м.текст.length));
    }
  });
  if (о.разбор === undefined) return {changes: первая, затем: [], выделение};

  // Вторая ступень: первая переводов строк не добавляет, номера строк прежние.
  const промежуточный = применить(text, первая);
  const т2 = построчно(промежуточный);
  const дерево2 = о.разбор(промежуточный);
  let узел: SyntaxNode | null = дерево2.resolveInner(т2.начала[ед[0].от] + (ед[0].пункт?.маркер.отступ ?? 0), 1);
  while (узел !== null && узел.name !== 'ListItem') узел = узел.parent;
  const с = узел?.parent == null ? null : список(т2, узел.parent, о.границы, ед[0].от);
  if (с === null) return null;
  const гр = группа(с, т2, о.границы);
  for (const л of гр) for (const п of л.пункты) if (пунктНеоднозначен(т2, п, л.вид)) return null;
  const всеПросты = гр.every((л) => простой(л, т2));
  const свои = new Set(ед.map((е) => е.от));
  const затем = уплотнение(т2, гр, вид === 'точки' ? '-' : '.', (после, до) => всеПросты || (свои.has(после.от) && свои.has(до.от)), о.косая);
  return {changes: первая, затем, выделение};
}

export function применить(text: string, changes: Замена[]): string {
  const по = [...changes].sort((x, y) => x.from - y.from || x.to - y.to);
  let итог = '';
  let pos = 0;
  for (const з of по) {
    итог += text.slice(pos, з.from) + з.insert;
    pos = з.to;
  }
  return итог + text.slice(pos);
}
