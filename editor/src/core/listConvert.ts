// Кнопки списка панели: выделенные абзацы становятся пунктами компактного списка, повторное нажатие
// действующего вида возвращает абзацы, другой вид меняет только маркеры. Чистое правило: на входе
// текст, выделение и вид, на выходе — правка того же вида, что у остальных кнопок, либо отказ.
//
// Единица преобразования — абзац или пункт вместе со строками-продолжениями, а не физическая
// строка: перенос внутри абзаца остаётся внутри пункта, а не плодит пункты. Что абзац, а что
// пункт, говорит настоящее дерево разбора markdown редактора, а не взгляд на строку: `2. монтаж`
// посреди абзаца — текст, потому что нумерованный список прерывает абзац только единицей. Границы
// примечания текстом не являются и единицу обрывают. Всё остальное — вложенный список, заголовок,
// цитата, код, блок, граница примечания в выделении — без потерь не превратить: правка не делается.
// Невыделенных соседей правка не меняет: пункт того же списка через пустую строку и соседний список
// того же вида, который слился бы с новыми пунктами, ведут к отказу целиком. Для маркированного
// списка слияния можно избежать без правки соседей: CommonMark начинает новый список со сменой
// знака маркера, поэтому рядом с `-` новый список получает `*` (или `+`), а на экране и на сайте
// точки одинаковые. Нумерованному списку такой лазейки нет: там знак — точка.
// Есть форма, которую окно и сайт читают по-разному: строка с номером не единицей сразу под пунктом
// другого списка без пустой строки (`- a` и под ней `2. b`) — дерево окна продолжает ею пункт, сайт
// начинает ею новый список. Рядом с такой формой правка не делается, и сама она не создаётся.

import type {SyntaxNode, Tree} from '@lezer/common';
import type {Edit, Selection} from './commands';

export type ВидСписка = 'точки' | 'числа';

/**
 * Что о тексте знает окно: дерево разбора, строки-границы примечаний и какие строки абзаца всё же
 * обычный текст (а не строка таблицы, картинка на своей строке или разметка MDX, которых дерево не знает).
 */
export interface Окружение {
  дерево: Tree;
  границы: ReadonlySet<number>;
  обычная: (строка: string) => boolean;
}

/** Единица: строки от `от` до `до` включительно и её узел дерева (пункт либо абзац). */
interface Единица {
  от: number;
  до: number;
  узел: SyntaxNode;
  пункт: {вид: ВидСписка; колонка: number} | null;
}

interface Разбор {
  список: Единица[];
  строки: string[];
  начала: number[];
  номер: (pos: number) => number;
}

/** Строка с номером не единицей: по CommonMark она не прерывает абзац, но сайт начинает ею список. */
const ЧУЖОЙ_НОМЕР = /^( {0,3})(\d{1,9})([.)])(?:\s|$)/;

function чужойНомер(строка: string): {отступ: number; знак: string} | null {
  const м = ЧУЖОЙ_НОМЕР.exec(строка);
  return м === null || Number(м[2]) === 1 ? null : {отступ: м[1].length, знак: м[3]};
}

/**
 * Пункт, к которому ленивым продолжением прилипла строка с чужим номером: она стоит левее колонки
 * содержимого и не продолжает нумерованный список того же знака. Окно и сайт читают её по-разному.
 */
function пунктНеоднозначен(text: string, пункт: SyntaxNode, {строки, начала, номер}: Разбор): boolean {
  const абзац = пункт.firstChild?.nextSibling ?? null;
  if (абзац === null || абзац.name !== 'Paragraph') return false;
  const колонка = абзац.from - начала[номер(абзац.from)];
  const свой = пункт.parent !== null && видСпискаУзла(пункт.parent) === 'числа' ? знакПункта(text, пункт) : '';
  for (let i = номер(пункт.from) + 1; i <= номер(абзац.to); i += 1) {
    const номерВСтроке = чужойНомер(строки[i]);
    if (номерВСтроке !== null && номерВСтроке.отступ < колонка && номерВСтроке.знак !== свой) return true;
  }
  return false;
}

/** Все пункты узла: список даёт своих детей, пункт — себя. */
function пункты(узел: SyntaxNode): SyntaxNode[] {
  if (узел.name === 'ListItem') return [узел];
  const итог: SyntaxNode[] = [];
  for (let п = узел.firstChild; п !== null; п = п.nextSibling) if (п.name === 'ListItem') итог.push(п);
  return итог;
}

/** Знаки маркированного списка по CommonMark, в порядке предпочтения. */
const ЗНАКИ_ТОЧЕК = ['-', '*', '+'];

/**
 * Соседние списки первой и последней единицы через пустую строку: `null`, если с той стороны
 * граница примечания, пункт того же списка (его судит правило соседей) или не список.
 */
function соседниеСписки({список, номер}: Разбор): (SyntaxNode | null)[] {
  return ([[список[0], false], [список[список.length - 1], true]] as [Единица, boolean][]).map(([е, вперёд]) => {
    if (вперёд ? е.до < номер(е.узел.to) : е.от > номер(е.узел.from)) return null;
    let узел = е.узел;
    if (е.пункт !== null) {
      if ((вперёд ? узел.nextSibling : узел.prevSibling) !== null) return null;
      узел = узел.parent!;
    }
    const сосед = вперёд ? узел.nextSibling : узел.prevSibling;
    return сосед !== null && видСпискаУзла(сосед) !== null ? сосед : null;
  });
}

/** Знак нового маркированного списка: первый свободный от соседей — с ним они остаются отдельными списками. */
function знакНовогоСписка(text: string, разбор: Разбор): string {
  const занятые = соседниеСписки(разбор).flatMap((сосед, i) => {
    const крайний = сосед === null ? null : i === 0 ? сосед.lastChild : сосед.firstChild;
    return сосед !== null && видСпискаУзла(сосед) === 'точки' && крайний !== null ? [знакПункта(text, крайний)] : [];
  });
  return ЗНАКИ_ТОЧЕК.find((знак) => !занятые.includes(знак)) ?? '-';
}

/** Колонка продолжения: не больше трёх пробелов, как у `Shift+Enter` в пункте. */
function колонкаМаркера(маркер: string): number {
  return Math.min(3, маркер.length + 1);
}

function видСпискаУзла(узел: SyntaxNode): ВидСписка | null {
  return узел.name === 'BulletList' ? 'точки' : узел.name === 'OrderedList' ? 'числа' : null;
}

/** Последний знак маркера пункта: у точек сам знак, у чисел точка или скобка — по нему списки сливаются. */
function знакПункта(text: string, пункт: SyntaxNode): string {
  const метка = пункт.firstChild;
  return метка === null ? '' : text.charAt(метка.to - 1);
}

/** Единицы, задетые выделением, либо `null`, если среди них есть то, что без потерь не превратить. */
function единицы(text: string, at: Selection, о: Окружение): Разбор | null {
  const строки = text.split('\n');
  const начала: number[] = [];
  for (let pos = 0, i = 0; i < строки.length; i += 1) {
    начала.push(pos);
    pos += строки[i].length + 1;
  }
  const номер = (pos: number): number => {
    let i = начала.length - 1;
    while (i > 0 && начала[i] > pos) i -= 1;
    return i;
  };
  const a = номер(at.from);
  // Выделение до начала строки эту строку не задевает.
  const b = номер(at.to > at.from && начала[номер(at.to)] === at.to ? at.to - 1 : at.to);
  for (let i = a; i <= b; i += 1) if (о.границы.has(i)) return null;
  const задет = (от: number, до: number): boolean => от <= b && до >= a;
  // Куски строк узла между границами примечаний: граница — не текст и ни в один кусок не входит.
  const куски = (от: number, до: number): [number, number][] => {
    const итог: [number, number][] = [];
    for (let i = от, с = от; i <= до + 1; i += 1) {
      if (i > до || о.границы.has(i)) {
        if (с <= i - 1) итог.push([с, i - 1]);
        с = i + 1;
      }
    }
    return итог;
  };
  const обычные = (с: number, по: number, колонка: number): boolean =>
    строки.slice(с, по + 1).every((строка, i) => о.обычная(i === 0 ? строка.slice(колонка) : колонка === 0 ? строка : строка.trimStart()));

  const список: Единица[] = [];
  for (let узел = о.дерево.topNode.firstChild; узел !== null; узел = узел.nextSibling) {
    if (!задет(номер(узел.from), номер(узел.to))) continue;
    const вид = видСпискаУзла(узел);
    if (узел.name !== 'Paragraph' && вид === null) return null;

    for (let часть = вид === null ? узел : узел.firstChild; часть !== null; часть = вид === null ? null : часть.nextSibling) {
      // Пункт — маркер и один абзац, ничего больше: вложенный список или код без потерь не превратить.
      const абзац = вид === null ? часть : часть.firstChild?.nextSibling ?? null;
      if (вид !== null && (часть.firstChild?.name !== 'ListMark' || (абзац !== null && (абзац.name !== 'Paragraph' || абзац.nextSibling !== null)))) return null;
      const от = номер(часть.from);
      const колонка = абзац === null ? строки[от].length : абзац.from - начала[номер(абзац.from)];
      for (const [k, [с, по]] of куски(от, номер((абзац ?? часть).to)).entries()) {
        if (!задет(с, по) || список.some((е) => е.от === с)) continue;
        // Первый кусок пункта — сам пункт; текст после границы примечания в том же узле — уже абзац.
        const свой = k === 0 && вид !== null;
        if (!обычные(с, по, свой ? колонка : 0)) return null;
        список.push({от: с, до: по, узел: свой ? часть : узел, пункт: свой ? {вид: вид!, колонка} : null});
      }
    }
  }
  return список.length === 0 ? null : {список, строки, начала, номер};
}

/** Действующий вид списка выделения: все задетые единицы — пункты одного вида; иначе `null`. */
export function видСписка(text: string, at: Selection, о: Окружение): ВидСписка | null {
  const разбор = единицы(text, at, о);
  if (разбор === null) return null;
  const первый = разбор.список[0].пункт?.вид ?? null;
  return разбор.список.every((е) => е.пункт?.вид === первый) ? первый : null;
}

/**
 * Правка меняла бы невыделенного соседа: пункт того же списка через пустую строку (разреженный
 * список) либо соседний список того же вида и знака, с которым слились бы новые пункты.
 */
function меняетСоседей(text: string, разбор: Разбор, вид: ВидСписка, снять: boolean, знак: string): boolean {
  const {список, номер} = разбор;
  const выбран = (узел: SyntaxNode): boolean => список.some((е) => е.узел.from === узел.from);
  const неоднозначен = (узел: SyntaxNode): boolean => пункты(узел).some((п) => пунктНеоднозначен(text, п, разбор));
  if (список.some((е) => е.пункт !== null && неоднозначен(е.узел))) return true;
  for (const [е, вперёд] of [[список[0], false], [список[список.length - 1], true]] as [Единица, boolean][]) {
    // За краем куска стоит граница примечания — списка там нет.
    if (вперёд ? е.до < номер(е.узел.to) : е.от > номер(е.узел.from)) continue;
    let узел = е.узел;
    if (е.пункт !== null) {
      const рядом = вперёд ? узел.nextSibling : узел.prevSibling;
      if (рядом !== null) {
        if (выбран(рядом)) continue;
        if (неоднозначен(рядом) || (вперёд ? номер(рядом.from) - е.до : е.от - номер(рядом.to)) > 1) return true;
        continue;
      }
      узел = узел.parent!;
    }
    const сосед = вперёд ? узел.nextSibling : узел.prevSibling;
    if (сосед === null || видСпискаУзла(сосед) === null) continue;
    if (неоднозначен(сосед)) return true;
    if (снять || видСпискаУзла(сосед) !== вид) continue;
    const крайний = вперёд ? сосед.firstChild : сосед.lastChild;
    if (крайний !== null && знакПункта(text, крайний) === знак) return true;
  }
  return false;
}

/**
 * Правка сама создала бы ту же форму: под новыми пунктами без пустой строки стоит строка с чужим
 * номером, а последний новый пункт не продолжает её нумерованный список тем же знаком.
 */
function создаётНеоднозначность(строки: string[], последняя: Единица, вид: ВидСписка, снять: boolean): boolean {
  const следующая = строки[последняя.до + 1];
  if (снять || следующая === undefined) return false;
  const номерВСтроке = чужойНомер(следующая);
  return номерВСтроке !== null && !(вид === 'числа' && номерВСтроке.знак === '.');
}

/** Строки единицы без маркера и отступа продолжения: то, что человек написал сам. */
function содержимое(строки: string[], е: Единица): string[] {
  return строки.slice(е.от, е.до + 1).map((строка, i) => {
    if (е.пункт === null) return строка;
    if (i === 0) return строка.slice(Math.min(строка.length, е.пункт.колонка));
    const пробелы = /^ */.exec(строка)![0].length;
    return строка.slice(Math.min(пробелы, е.пункт.колонка));
  });
}

/**
 * Правка по кнопке: абзацы и пункты чужого вида — в пункты этого вида (пустые строки между ними
 * уходят: список компактный); все единицы уже этого вида — обратно в абзацы, разделённые пустой
 * строкой и отделённые ею от соседних пунктов, чтобы не прилипнуть продолжением.
 * `null` — отказ: среди задетого есть то, что без потерь не превратить, или правка задела бы соседей.
 */
export function преобразованиеСписка(text: string, at: Selection, вид: ВидСписка, о: Окружение): Edit | null {
  const разбор = единицы(text, at, о);
  if (разбор === null) return null;
  const {список, строки} = разбор;
  const снять = видСписка(text, at, о) === вид;
  const знакТочек = вид === 'точки' && !снять ? знакНовогоСписка(text, разбор) : '-';
  if (меняетСоседей(text, разбор, вид, снять, вид === 'точки' ? знакТочек : '.') || создаётНеоднозначность(строки, список[список.length - 1], вид, снять)) return null;
  const начало = (i: number): number => строки.slice(0, i).reduce((sum, s) => sum + s.length + 1, 0);
  const первая = список[0];
  const последняя = список[список.length - 1];
  const from = начало(первая.от);
  const to = начало(последняя.до) + строки[последняя.до].length;
  // Абзацы, ставшие из пунктов, отделяются пустой строкой от соседнего текста: иначе прилипли бы
  // продолжением. Граница примечания — не текст, от неё отделять нечего.
  const текстРядом = (i: number): boolean => i >= 0 && i < строки.length && строки[i].trim() !== '' && !о.границы.has(i);
  const выше = снять && текстРядом(первая.от - 1) ? '\n' : '';
  const ниже = снять && текстРядом(последняя.до + 1) ? '\n' : '';

  let insert: string;
  if (снять) {
    insert = `${выше}${список.map((е) => содержимое(строки, е).join('\n')).join('\n\n')}${ниже}`;
  } else {
    insert = список.map((е, n) => {
      const маркер = вид === 'точки' ? знакТочек : `${n + 1}.`;
      const отступ = ' '.repeat(колонкаМаркера(маркер));
      return содержимое(строки, е).map((строка, i) => (i === 0 ? `${маркер} ${строка}` : `${отступ}${строка.trimStart()}`)).join('\n');
    }).join('\n');
  }
  return {from, to, insert, select: {from: выше.length, to: insert.length - ниже.length}};
}
