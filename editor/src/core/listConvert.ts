// Кнопки списка панели: выделенные абзацы становятся пунктами компактного списка, повторное нажатие
// действующего вида возвращает абзацы, другой вид меняет только маркеры. Чистое правило: на входе
// текст, выделение и вид, на выходе — правка того же вида, что у остальных кнопок, либо отказ.
//
// Единица преобразования — абзац или пункт вместе со строками-продолжениями, а не физическая
// строка: перенос внутри абзаца остаётся внутри пункта, а не плодит пункты. Что здесь код, а что
// пункт, решает тот же проход сверху, что и у уровня списка (`listIndent.ts`); что обычная строка
// абзаца — правило переносов, которое передаёт вызывающий. Всё остальное — вложенный список,
// заголовок, цитата, таблица, блок, граница примечания, код — преобразовать без потерь нельзя,
// и тогда правка не делается вовсе: частичной правки у кнопки нет.

import type {Edit, Selection} from './commands';
import {разметкаТекста} from './listIndent';

export type ВидСписка = 'точки' | 'числа';

/** Единица: строки от `от` до `до` включительно; у пункта — маркер и колонка содержимого. */
interface Единица {
  от: number;
  до: number;
  пункт: {вид: ВидСписка; колонка: number} | null;
}

/** Граница примечания — не абзац, хотя правило абзаца её не отличает. */
const ГРАНИЦА_СОВЕТА = /^ {0,3}:::/;

/** Колонка продолжения: не больше трёх пробелов, как у `Shift+Enter` в пункте. */
function колонкаМаркера(маркер: string): number {
  return Math.min(3, маркер.length + 1);
}

/** Единицы, задетые выделением, либо `null`, если среди них есть то, что без потерь не превратить. */
function единицы(text: string, at: Selection, обычная: (строка: string) => boolean): Единица[] | null {
  const {список, разметка} = разметкаТекста(text);
  const пустая = (i: number): boolean => список[i].текст.trim() === '';
  const пункт = (i: number): boolean => разметка[i].пункт !== null && разметка[i].отступ === 0;
  // Строка, которая может быть частью абзаца или пункта: заголовок, блок и граница примечания
  // обрывают единицу, даже стоя вплотную.
  const текстовая = (i: number): boolean => !пустая(i) && !ГРАНИЦА_СОВЕТА.test(список[i].текст)
    && (пункт(i) || разметка[i].отступ > 0 || обычная(список[i].текст));
  const номер = (позиция: number): number => {
    for (let i = список.length - 1; i >= 0; i -= 1) if (позиция >= список[i].от) return i;
    return 0;
  };

  let a = номер(at.from);
  // Выделение до начала строки эту строку не задевает.
  let b = номер(at.to > at.from && список[номер(at.to)].от === at.to ? at.to - 1 : at.to);
  while (a > 0 && !пункт(a) && текстовая(a) && текстовая(a - 1)) a -= 1;
  while (b + 1 < список.length && !пункт(b + 1) && текстовая(b + 1)) b += 1;

  const итог: Единица[] = [];
  for (let i = a; i <= b; i += 1) {
    if (пустая(i)) continue;
    const {код, отступ, пункт: маркер} = разметка[i];
    const текущая = итог[итог.length - 1];
    const продолжение = текущая !== undefined && текущая.до === i - 1 && !пустая(i - 1) && маркер === null;
    if (код || (маркер !== null && отступ > 0) || ГРАНИЦА_СОВЕТА.test(список[i].текст)) return null;
    if (!обычная(продолжение ? список[i].текст.trimStart() : список[i].текст) && маркер === null) return null;

    if (продолжение) {
      текущая.до = i;
      continue;
    }
    const вид: ВидСписка | null = маркер === null ? null : /^\d/.test(маркер.маркер) ? 'числа' : 'точки';
    итог.push({от: i, до: i, пункт: вид === null ? null : {вид, колонка: маркер!.колонка}});
  }
  return итог.length === 0 ? null : итог;
}

/** Действующий вид списка выделения: все задетые единицы — пункты одного вида; иначе `null`. */
export function видСписка(text: string, at: Selection, обычная: (строка: string) => boolean): ВидСписка | null {
  const единицыВыделения = единицы(text, at, обычная);
  if (единицыВыделения === null) return null;
  const первый = единицыВыделения[0].пункт?.вид ?? null;
  return единицыВыделения.every((е) => е.пункт?.вид === первый) ? первый : null;
}

/** Строки единицы без маркера и отступа продолжения: то, что человек написал сам. */
function содержимое(строки: string[], е: Единица): string[] {
  return строки.slice(е.от, е.до + 1).map((строка, i) => {
    if (е.пункт === null) return строка;
    if (i === 0) return строка.slice(Math.min(строка.length, е.пункт.колонка));
    const пробелы = /^ */.exec(строка)![0].length;
    return строка.slice(Math.min(пробелы, е.пункт.колонка));
  });
}

/**
 * Правка по кнопке: абзацы и пункты чужого вида — в пункты этого вида (пустые строки между ними
 * уходят: список компактный); все единицы уже этого вида — обратно в абзацы, разделённые пустой
 * строкой и отделённые ею от соседних пунктов, чтобы не прилипнуть к ним продолжением.
 * `null` — отказ: среди задетого есть то, что без потерь не превратить.
 */
export function преобразованиеСписка(
  text: string,
  at: Selection,
  вид: ВидСписка,
  обычная: (строка: string) => boolean,
): Edit | null {
  const единицыВыделения = единицы(text, at, обычная);
  if (единицыВыделения === null) return null;
  const строки = text.split('\n');
  const начало = (i: number): number => строки.slice(0, i).reduce((sum, s) => sum + s.length + 1, 0);
  const первая = единицыВыделения[0];
  const последняя = единицыВыделения[единицыВыделения.length - 1];
  const from = начало(первая.от);
  const to = начало(последняя.до) + строки[последняя.до].length;
  const снять = видСписка(text, at, обычная) === вид;
  // Абзацы, ставшие из пунктов, отделяются пустой строкой от соседних пунктов: иначе прилипли бы продолжением.
  const выше = снять && первая.от > 0 && строки[первая.от - 1].trim() !== '' ? '\n' : '';
  const ниже = снять && последняя.до + 1 < строки.length && строки[последняя.до + 1].trim() !== '' ? '\n' : '';

  let insert: string;
  if (снять) {
    insert = `${выше}${единицыВыделения.map((е) => содержимое(строки, е).join('\n')).join('\n\n')}${ниже}`;
  } else {
    insert = единицыВыделения.map((е, n) => {
      const маркер = вид === 'точки' ? '-' : `${n + 1}.`;
      const отступ = ' '.repeat(колонкаМаркера(маркер));
      return содержимое(строки, е).map((строка, i) => (i === 0 ? `${маркер} ${строка}` : `${отступ}${строка.trimStart()}`)).join('\n');
    }).join('\n');
  }
  return {from, to, insert, select: {from: выше.length, to: insert.length - ниже.length}};
}
