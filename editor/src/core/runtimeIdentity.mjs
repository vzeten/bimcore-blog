// Кто именно сейчас поднят и какой порт ему разрешён. Чистое правило: ни диск, ни git, ни
// переменные среды здесь не спрашиваются — факты подаются снаружи (SPEC 4.6, 4.7).
//
// Правило заведено потому, что снаружи два экземпляра выглядели одинаково. Копия программы с другой
// ветки кода отвечала на том же `4780`, и ярлык владельца, спросив у неё только «жив ли сервер»,
// открывал её как обычное окно. Дальше человек правит статьи в непроверенной программе, а при
// испытательном корне — ещё и не в своей папке материалов.
//
// Порт пришпилен ЗДЕСЬ, а не в настройках, по тому же доводу, что и папка материалов (SPEC 4.4):
// пока номер брался из `settings.json`, любая копия со своим файлом настроек объявляла себя
// хозяйкой `4780` и снова становилась неотличимой. Сменить порт обычного окна теперь можно только
// переделкой кода — то самое проверочное условие SPEC 4.4.

/** Порт обычного принятого редактора. Занимать его другим экземплярам нельзя. */
export const ПОРТ_ВЛАДЕЛЬЦА = 4780;

/** Ветка принятого кода: только с неё запуск считается обычным редактором владельца. */
export const ВЕТКА_ПРИНЯТОГО = 'editor';

/**
 * Рабочая копия принятого кода. Пришпилена здесь по тому же доводу, что и порт: имя ветки само по
 * себе ничего не доказывает — ту же ветку можно взять в любую копию, а рядом с ней держать свои
 * правки. Папка запущенного кода известна процессу из его собственного места на диске, подделать
 * её настройкой нельзя.
 */
export const ПАПКА_ПРИНЯТОГО = 'C:/My_code/bimcore-blog/editor/.coordination/worktrees/accepted-editor/editor';

/**
 * Роли экземпляра. Это внутренний договор сервера с ярлыком, а не надпись для человека (SPEC 4.4):
 * ярлык — командный файл Windows, и русские буквы в нём зависят от кодовой страницы консоли.
 * Слова для человека берутся по этой роли из настроек (`материалы.запуск`).
 */
export const РОЛЬ_ОБЫЧНАЯ = 'owner';
export const РОЛЬ_ИСПЫТАТЕЛЬНАЯ = 'trial';

/** Коды отказов запуска. Тексты для человека живут в настройках (SPEC 6.10). */
export const НЕТ_ПОРТА = 'нетПорта';
export const ЧУЖОЙ_ПОРТ = 'чужойПорт';
export const НЕВЕРНЫЙ_ПОРТ = 'неверныйПорт';

/** Предел номера порта — величина протокола, а не наша настройка. */
const ПРЕДЕЛ_ПОРТА = 65535;

/** Номер порта записан цифрами и целиком: `4791`, но не `4791abc`, не `0x10` и не пустая строка. */
const ЦИФРАМИ = /^\d+$/;

/** Один вид косых, без лишней на конце и без учёта регистра: Windows зовёт одну папку по-разному. */
const ровно = (путь) => String(путь ?? '').split('\\').join('/').replace(/\/+$/, '').toLowerCase();

/**
 * Принятый экземпляр — совпадение сразу четырёх фактов: материалы владельца, папка принятой рабочей
 * копии, её ветка и чистое дерево кода. Меньшего не хватает, и каждое условие закрывает свой обход:
 * одного корня мало — код с рабочей ветки читает те же статьи, но его никто не принимал; одного
 * имени ветки мало — `editor` берётся в любую копию; чистота обязательна, потому что правка в
 * рабочем дереве меняет поведение, не меняя ни ветки, ни номера коммита.
 *
 * Все четыре факта берутся у мира, а не у чужих слов: папка — из собственного места процесса, ветка
 * и чистота — у git этого же дерева. Версия неизвестна или чистоту спросить не удалось — экземпляр
 * не принят: непроверяемая личность не может владеть портом владельца.
 */
export const принятый = ({испытательный, ветка, чисто, код}) => !испытательный
  && ветка === ВЕТКА_ПРИНЯТОГО
  && чисто === true
  && ровно(код) === ровно(ПАПКА_ПРИНЯТОГО);

/**
 * Порт запуска. Обычному принятому окну номер не нужен — оно получает свой `4780`. Любому другому
 * экземпляру порт называют явно, и `4780` ему не отдаётся ни при какой заявке: два сервера на одном
 * номере не живут, а перепутать их человеку ничего не мешает.
 *
 * @returns {{порт: number}|{отказ: string, значение: string}}
 */
export function выборПорта({принятый: принят, заявка}) {
  const строка = String(заявка ?? '').trim();
  if (строка === '') return принят ? {порт: ПОРТ_ВЛАДЕЛЬЦА} : {отказ: НЕТ_ПОРТА, значение: ''};

  if (!ЦИФРАМИ.test(строка)) return {отказ: НЕВЕРНЫЙ_ПОРТ, значение: строка};
  const порт = Number(строка);
  if (порт < 1 || порт > ПРЕДЕЛ_ПОРТА) return {отказ: НЕВЕРНЫЙ_ПОРТ, значение: строка};
  if (порт === ПОРТ_ВЛАДЕЛЬЦА && !принят) return {отказ: ЧУЖОЙ_ПОРТ, значение: строка};

  return {порт};
}

/**
 * Опознание экземпляра — один источник фактов на всю программу: по нему печатаются строки запуска,
 * им же отвечает ручка `/api/identity`, и его читает ярлык владельца. Второго описания «кто я»
 * в программе быть не должно: разойдись они, окно называло бы себя одним, а ярлыку отвечало другим.
 *
 * Имена полей латинские по той же причине, что и роли: ответ читает командный файл Windows.
 *
 * `accepted` здесь — слово самого сервера, и одного его мало: ответить так может кто угодно. Поэтому
 * ярлык сравнивает `code` и `commit` с тем, что ему сказал git о принятой рабочей копии, а не верит
 * признаку на слово. Поля названы полностью именно для этого.
 */
export function опознание({корень, испытательный, ветка, коммит, чисто, код, порт}) {
  return {
    role: испытательный ? РОЛЬ_ИСПЫТАТЕЛЬНАЯ : РОЛЬ_ОБЫЧНАЯ,
    accepted: принятый({испытательный, ветка, чисто, код}),
    branch: ветка ?? null,
    commit: коммит ?? null,
    clean: чисто === true,
    code: код,
    materials: корень,
    port: порт,
    url: `http://localhost:${порт}`,
  };
}
