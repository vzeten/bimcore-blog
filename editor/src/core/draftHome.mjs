// Дом черновика и истории: где лежит незаписанная работа владельца и что делать со старым
// хранилищем той копии кода, из которой сервер подняли сегодня.
// Чистые правила: диск здесь не спрашивается, ответы про файлы подаются снаружи (SPEC 4.6, 4.7).
//
// Правило заведено потому, что хранилище выводилось из места самой ПРОГРАММЫ: запуск кода из
// другой рабочей копии молча уводил черновик и снимки в её собственную папку, и незавершённый
// текст пропадал из окна вместе со сменой версии кода. Работа принадлежит МАТЕРИАЛАМ, а не коду,
// поэтому и лежит она в папке материалов — там же, где статьи, которые она правит.
//
// Имя папки пришпилено здесь, а не в настройках, по той же причине, что и корень материалов
// (`materialRoot.mjs`, SPEC 4.4): владелец не выбирает, где хранится его незаписанный текст, —
// сменить это можно только переделкой кода.

/** Папка редактора ВНУТРИ материалов: в ней и живут `.drafts` и `.history` владельца. */
export const ПАПКА_РЕДАКТОРА = 'editor';

/** Исходы для одного старого файла при переносе. */
export const КОПИРОВАТЬ = 'копировать';
export const СОВПАЛО = 'совпало';
export const СПОР = 'спор';

/** Один вид косых и без лишней на конце: путь сравнивается одинаково, как ни напиши его запуск. */
function ровно(путь) {
  return String(путь).split('\\').join('/').replace(/\/+$/, '');
}

/**
 * Один и тот же путь или два разных. Регистр не учитывается: Windows считает `C:/My_code` и
 * `c:/my_code` одной папкой, и разный регистр не повод затевать перенос папки в саму себя.
 */
export function одинПуть(a, b) {
  return ровно(a).toLowerCase() === ровно(b).toLowerCase();
}

/**
 * Переносить ли старое хранилище копии кода в общее.
 *
 * Испытательный экземпляр не переносит НИКОГДА: его корень чужой, и перенос стал бы дорогой,
 * по которой работа владельца утекла бы на чужое дерево (или чужая работа — к владельцу).
 * Совпадающие пути — переносить нечего: старое хранилище и есть общее.
 */
export function нуженПеренос({хранилище, наследие, испытательный}) {
  if (испытательный) return false;
  return !одинПуть(хранилище, наследие);
}

/**
 * Что сделать с одним старым файлом. Решают только два факта, и оба — про БАЙТЫ:
 * такие же байты уже лежат в общем хранилище (переносить нечего, и повтор переноса ничего не
 * добавит) или место под именем свободно (можно просто положить).
 *
 * Третий случай — под этим именем лежит ДРУГОЙ текст. Выбирать между ними по времени или по пути
 * запрещено: оба варианта — работа человека, и «свежий» по времени файла ничего не доказывает.
 */
export function исходФайла({такиеЖеБайты, местоСвободно}) {
  if (такиеЖеБайты) return СОВПАЛО;
  return местоСвободно ? КОПИРОВАТЬ : СПОР;
}

/** Имя файла без расширения `.json`: от него растут имена вариантов. */
const основа = (имяЧерновика) => String(имяЧерновика).replace(/\.json$/, '');

/**
 * Имя варианта, который программа не выбрала. В имени — отпечаток самих байтов, поэтому повтор
 * переноса даёт то же имя и второй копии того же текста не появляется.
 */
export function имяСпора(имяЧерновика, отпечаток) {
  return `${основа(имяЧерновика)}__${String(отпечаток).slice(0, 8)}.json`;
}

/** По этому началу имени видно, что вариант принадлежит именно этому черновику. */
export function префиксСпора(имяЧерновика) {
  return `${основа(имяЧерновика)}__`;
}
