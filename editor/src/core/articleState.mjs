// Состояние языковой версии статьи: что хранится рядом со статьёй и переживает публикацию.
// Черновые снимки текста здесь не живут — они лежат отдельно и в git не попадают.

// Видимость здесь не хранится намеренно: сайт читает её из шапки статьи (`unlisted`),
// и второе место для того же факта означало бы, что программа показывает одно, а сайт делает другое.

// Порядок статусов в настройках — это стадии по времени: первый — начальное состояние новой версии,
// последний — опубликованное. Договор, а не случайность; на нём держится `готовностьВерсии`.
const ЧЕРНОВИК = (settings) => settings['статусы'][0];
const ОПУБЛИКОВАНА = (settings) => settings['статусы'][settings['статусы'].length - 1];

/**
 * Готовность версии — единственное место правила SPEC 4.5.2; реестр и шапка открытой статьи
 * получают её через общий свод.
 *
 * `записанное` — текст файла состояния («» — файла нет). `совпадаетСПубликацией` — `true`, когда
 * файл версии лежит в опубликованной ветке и совпадает с диском; `false` — его там нет либо он
 * отличается; `null` — сравнить не удалось.
 *
 * «Опубликована» не хранится никогда: она выводится из доказанного совпадения и перебивает записанную
 * стадию, даже если старый файл состояния помнит «Черновик». Любое местное отличие, отсутствие в
 * ветке и недоступный git возвращают записанную стадию (без файла состояния — «Черновик»): ложная
 * «Опубликована» спрятала бы неуехавшую правку, а одно наличие пути совпадения не доказывает.
 */
export function готовностьВерсии(записанное, совпадаетСПубликацией, settings) {
  if (совпадаетСПубликацией === true) return ОПУБЛИКОВАНА(settings);
  return readState(записанное, settings)['готовность'];
}

/** Пустое состояние новой версии. Значения по умолчанию берутся из настроек. */
export function emptyState(settings) {
  return {
    готовность: ЧЕРНОВИК(settings),
    опубликованныйКоммит: null,
    нити: [],
  };
}

/** Разбор состояния из файла. Битый или пустой файл не должен ронять программу. */
export function readState(raw, settings) {
  if (typeof raw !== 'string' || raw.trim() === '') return emptyState(settings);

  try {
    const parsed = JSON.parse(raw);
    return {...emptyState(settings), ...parsed, нити: Array.isArray(parsed['нити']) ? parsed['нити'] : []};
  } catch {
    return emptyState(settings);
  }
}

/** Запись состояния. Один и тот же вход даёт один и тот же текст — иначе файл дрожит в git. */
export function writeState(state) {
  const ordered = {
    готовность: state['готовность'],
    опубликованныйКоммит: state['опубликованныйКоммит'] ?? null,
    нити: state['нити'] ?? [],
  };

  return `${JSON.stringify(ordered, null, 2)}\n`;
}

/**
 * Имя файла версии, у которого состояние лежит под именем из настройки как есть.
 * Значение задано не нами: `index` — конвенция Docusaurus, настройкой она не бывает (SPEC 4.4).
 *
 * Понятие «индекс папки» у самого Docusaurus шире (`readme` и файл по имени своей папки —
 * `индексПапки` в `frontmatterRules.mjs`), и звать оттуда здесь НЕЛЬЗЯ, хотя выглядит родственным:
 * там отвечают на вопрос «чей адрес даёт папка», а здесь — «где лежит состояние». По широкому
 * понятию `index.mdx` и `readme.mdx` в одной папке получили бы один файл состояния, то есть ровно
 * ту подмену готовности, ради которой правило и заводится.
 */
const ИМЯ_ИНДЕКСА = 'index';

/**
 * Путь файла состояния — от полного пути файла версии, а не от одной его папки.
 * Единственное место, где этот путь вычисляется: реестр, сохранение, создание и удаление зовут его.
 *
 * `index.mdx` рядом со статьёй-файлом обязан остаться при своём `_state.json`, иначе правка стала бы
 * переносом данных; статья-файл получает своё имя, иначе её готовность подменяет готовность
 * страницы раздела.
 *
 * Имя строится из настройки: у индекса — как есть (тогда путь не меняется ни при какой настройке),
 * у остальных — с обязательным ведущим подчёркиванием, потому что файл с подчёркиванием Docusaurus
 * не собирает (SPEC 2.7). Путь возвращается в том же виде, в каком пришёл, — со слэшами: ядро общее
 * для сервера и окна, и `node:path` ему запрещён (SPEC 4.10.1).
 */
export function путьФайлаСостояния(путьВерсии, settings) {
  const изНастройки = settings['хранение']['файлСостояния'];
  const части = String(путьВерсии ?? '').split('/');
  const имяФайла = части[части.length - 1].replace(/\.[^./]+$/, '');

  const имя = имяФайла === ИМЯ_ИНДЕКСА
    ? изНастройки
    : `_${имяФайла}.${изНастройки.replace(/^_+/, '')}`;

  return [...части.slice(0, -1), имя].join('/');
}

/** Правка текста после подготовки возвращает версию в черновик. */
export function afterEdit(state, settings) {
  if (state['готовность'] === ЧЕРНОВИК(settings)) return state;
  return {...state, готовность: ЧЕРНОВИК(settings)};
}

/**
 * Какое состояние отдать окну после сохранения: только то, что действительно легло на диск.
 * Запись состояния — служебный шаг, он мог не пройти при удачно записанном файле статьи.
 *
 * При сбое не отдаётся ничего, и это важнее, чем кажется: «прежнее» состояние тут назвать нечем.
 * У версии без своего файла состояния готовность выводится из факта публикации (SPEC 4.5.2),
 * а прочитанное с диска пустое состояние всегда выглядит черновиком. Отдав его, программа
 * объявила бы опубликованную статью черновиком — ровно тем враньём, ради которого всё и делалось.
 * Ничего не отдав, она оставляет в шапке прежнюю надпись, которая по-прежнему верна.
 */
export function состояниеДляОкна(новое, предупреждения) {
  return (предупреждения ?? []).includes('состояние') ? null : новое;
}
