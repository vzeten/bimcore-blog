// Проверка самой настройки подготовки: та ли это настройка, по которой можно спрашивать поля.
//
// Отдельным модулем, потому что отвечает на другой вопрос. Прочие правила подготовки смотрят на
// статью, а это — на настройку: сломана она, и любой их ответ ничего не стоит.
//
// Проверяется во время работы, а не только тестом. Настройки правит владелец и тестов при этом
// не запускает: переименует категорию — требование полей молча испарится до следующего прогона,
// и статья уедет на сайт без того, о чём её обещали спросить. Сломанная проверка обязана кричать.

/** Какие поля подготовка требует у статьи этой категории. Нет записи — не требует ничего. */
export function обязательныеПоля(категория, settings) {
  return (settings['обязательныеПоля'] ?? {})[категория] ?? [];
}

/** Имена категорий, какие вообще бывают у статей: ими и только ими можно ключевать настройку. */
function известныеКатегории(settings) {
  return new Set([
    ...Object.values(settings['категорииПоПути']),
    ...Object.values(settings['категорииПоРоду']),
    settings['категорияСлужебной'],
  ]);
}

/**
 * Беды самой настройки. Возвращает записи вида `{код, поле}` — уровень им назначает подготовка,
 * чтобы перечень уровней жил в одном месте.
 *
 * Ключа `обязательныеПоля` может не быть вовсе: пояснение к настройке прямо разрешает не
 * перечислять категории, и это законное «ничего не требуем», а не повод падать.
 */
export function бедыНастройки(settings) {
  const известные = известныеКатегории(settings);
  const беды = [];

  for (const [имя, поля] of Object.entries(settings['обязательныеПоля'] ?? {})) {
    if (!известные.has(имя)) беды.push({код: 'настройкаНеЗнаетКатегорию', поле: имя});

    for (const поле of поля) {
      // Описание обязательно у каждой версии, видимой и скрытой (слово владельца), а у полей
      // категории есть поблажка для скрытых. Пусти мы описание сюда — слово владельца молча
      // обошлось бы через настройку.
      if (поле === 'description') беды.push({код: 'описаниеНеПолеКатегории', поле});
    }
  }

  return беды;
}
