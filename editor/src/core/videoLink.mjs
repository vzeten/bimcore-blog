// Ссылка на видео и его длительность человеческими словами.
//
// В статье хранится ровно то, чего ждёт компонент сайта: номер видео и длительность в секундах
// (`src/components/YouTube.jsx`). Человеку ни номер, ни секунды не показываются: он даёт обычную
// ссылку из адресной строки и пишет минуты и секунды, а перевод в договор сайта делает программа.
//
// Обратный перевод намеренно бережный. Старую запись `PT5M30S` модуль читает, чтобы показать её
// человеку минутами и секундами, но сам её не переписывает: молча менять чужую запись значит
// править статью, которую никто не просил править.

/** Номер видео на YouTube: одиннадцать знаков без пробелов. */
const НОМЕР = /^[A-Za-z0-9_-]{11}$/;

/** Хозяева ссылок, которые программа считает ссылками на YouTube. */
const ХОЗЯЕВА = ['youtube.com', 'www.youtube.com', 'm.youtube.com', 'youtu.be', 'www.youtu.be',
  'youtube-nocookie.com', 'www.youtube-nocookie.com'];

/**
 * Номер видео из того, что человек вставил в поле «Ссылка».
 *
 * Возвращается либо `{номер}`, либо `{ошибка}` с кодом причины — слова человеку живут в настройках.
 * Отказ ничего не меняет в статье: человек видит причину и правит ввод, а текст остаётся прежним.
 */
export function номерВидео(ввод) {
  const текст = String(ввод ?? '').trim();
  if (текст === '') return {ошибка: 'пусто'};

  // Голый номер человек получает, открыв уже вставленный блок: показывать ему отказ на то,
  // что программа сама туда и записала, было бы нелепо.
  if (НОМЕР.test(текст)) return {номер: текст};

  const адрес = разобратьАдрес(текст);
  if (адрес === null) return {ошибка: 'неСсылка'};
  if (!ХОЗЯЕВА.includes(адрес.hostname.toLowerCase())) return {ошибка: 'чужаяСсылка'};

  const найден = номерИзАдреса(адрес);
  return найден === null ? {ошибка: 'нетНомера'} : {номер: найден};
}

/** Ссылка, которую человек видит в свойствах блока. Собирается из номера, в статье не хранится. */
export function ссылкаВидео(номер) {
  return номер === '' ? '' : `https://www.youtube.com/watch?v=${номер}`;
}

/** Обложка видео. Мелкий кадр есть у каждого видео, поэтому берётся он, а не HD. */
export function обложкаВидео(номер) {
  return НОМЕР.test(номер) ? `https://i.ytimg.com/vi/${номер}/hqdefault.jpg` : null;
}

/**
 * Длительность из статьи — минутами и секундами. Понимаются обе записи: число секунд, которое
 * пишет программа, и `PT...`, которую мог оставить человек или прежний редактор.
 * `null` — значение непонятно; тогда оно показывается как есть и программой не трогается.
 */
export function разборДлительности(значение) {
  const текст = String(значение ?? '').trim();
  if (текст === '') return {минуты: '', секунды: ''};

  if (/^\d+$/.test(текст)) return вМинуты(Number(текст));

  const iso = /^PT(?:(\d+)H)?(?:(\d+)M)?(?:(\d+)S)?$/.exec(текст.toUpperCase());
  if (iso === null || (iso[1] === undefined && iso[2] === undefined && iso[3] === undefined)) return null;

  return вМинуты(Number(iso[1] ?? 0) * 3600 + Number(iso[2] ?? 0) * 60 + Number(iso[3] ?? 0));
}

/**
 * Минуты и секунды обратно в договор сайта — число секунд строкой. Пустой ввод даёт пустое
 * значение: длительность необязательна, и выдумывать ноль вместо неё нельзя.
 */
export function длительностьВСекундах(минуты, секунды) {
  const м = число(минуты);
  const с = число(секунды);
  if (м === null || с === null) return null;
  if (м === 0 && с === 0 && String(минуты ?? '').trim() === '' && String(секунды ?? '').trim() === '') return '';

  return String(м * 60 + с);
}

function вМинуты(всего) {
  return {минуты: String(Math.floor(всего / 60)), секунды: String(всего % 60)};
}

function число(значение) {
  const текст = String(значение ?? '').trim();
  if (текст === '') return 0;
  if (!/^\d+$/.test(текст)) return null;

  return Number(текст);
}

function разобратьАдрес(текст) {
  // Строка с пробелами и хост без точки ссылкой не считаются: `new URL` проглотит и «совсем не
  // ссылка», сделав хостом первое слово, и человек получил бы «эта ссылка ведёт не на YouTube»
  // о том, что ссылкой вовсе не было.
  if (/\s/.test(текст)) return null;

  try {
    // Человек копирует адрес и без «https://»: отказывать ему из-за приставки было бы придиркой.
    const адрес = new URL(/^[a-z]+:\/\//i.test(текст) ? текст : `https://${текст}`);
    return адрес.hostname.includes('.') ? адрес : null;
  } catch {
    return null;
  }
}

function номерИзАдреса(адрес) {
  const части = адрес.pathname.split('/').filter((часть) => часть !== '');

  // `youtu.be/НОМЕР` — весь путь и есть номер; `youtube.com/embed/НОМЕР` — второй кусок пути.
  const изПути = адрес.hostname.toLowerCase().includes('youtu.be')
    ? части[0]
    : (части[0] === 'embed' ? части[1] : undefined);
  const кандидат = изПути ?? адрес.searchParams.get('v') ?? '';

  return НОМЕР.test(кандидат) ? кандидат : null;
}
