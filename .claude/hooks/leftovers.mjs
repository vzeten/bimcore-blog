// Крючок в конце хода: не осталось ли после работы мусора редактора.
// Тесты не запускает — только смотрит на файлы, поэтому работает мгновенно и не тормозит работу.
//
// Запускается из настроек: node .claude/hooks/leftovers.mjs

//
// Чего крючок НЕ трогает: `editor/.history` и `editor/.drafts`. Это не мусор, а данные программы —
// лента версий и несохранённая работа, в том числе по реальным статьям владельца. Предложить
// «прибрать» их значит подтолкнуть к потере истории. Осиротевшие записи от удалённых статей
// подчищать должна сама программа, а не крючок.

import {execFileSync} from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const корень = process.env.CLAUDE_PROJECT_DIR ?? process.cwd();

// Свежесть, по которой незакоммиченная статья в контенте считается следом текущей работы.
// Техническая величина крючка: старые статьи владельца лежат в дереве неделями, и ругаться на них
// при каждом ходе — значит приучить не читать предупреждения вовсе.
const СВЕЖЕСТЬ_ЧАСОВ = 3;

const находки = [];

/**
 * След проверки, а не работа. Новый модуль или тест — это сделанное дело, и называть его мусором
 * значит приучить пропускать предупреждения мимо глаз. Мусор — то, что остаётся ПОСЛЕ проверок:
 * пробные статьи в песочнице и картинки, которыми проверяли загрузку.
 */
function следПроверки(путь) {
  const вПесочнице = /^editor[\\/]sandbox[\\/]/.test(путь);
  const статьяИлиКартинка = /\.(mdx|md|png|jpe?g|gif|webp|svg)$/i.test(путь);
  return вПесочнице || (путь.startsWith('editor') && статьяИлиКартинка);
}

// Незакоммиченные файлы. Смотрим два места по разным правилам: в программе — следы проверок,
// в контенте сайта — только свежие, чтобы не поднимать шум из-за статей, которые владелец пишет сам.
let строки = [];
try {
  строки = execFileSync('git', ['status', '--porcelain', '--', 'editor', 'docs', 'blog', 'i18n'], {
    cwd: корень,
    encoding: 'utf8',
  }).split('\n').filter(Boolean);
} catch {
  // Не репозиторий или git недоступен — крючок молчит, это не его дело.
}

const порог = Date.now() - СВЕЖЕСТЬ_ЧАСОВ * 3600 * 1000;

for (const строка of строки) {
  if (!строка.startsWith('??')) continue;
  const путь = строка.slice(3).trim().replace(/^"|"$/g, '');
  const вКонтенте = /^(docs|blog|i18n)[\\/]/.test(путь);

  if (вКонтенте) {
    let когда = 0;
    try {
      когда = fs.statSync(path.join(корень, путь)).mtimeMs;
    } catch {
      continue;
    }
    if (когда < порог) continue;
    находки.push(`новое в контенте сайта: ${путь}`);
    continue;
  }

  if (следПроверки(путь)) находки.push(`след проверки: ${путь}`);
}

if (находки.length === 0) process.exit(0);

process.stdout.write(JSON.stringify({
  systemMessage: 'После работы осталось незакоммиченное. Проверьте, ваше ли это, и приберите своё:\n'
    + находки.map((строка) => `  · ${строка}`).join('\n'),
}));
