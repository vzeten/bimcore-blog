// Крючок в конце хода: не осталось ли после работы свежих файлов в контенте сайта.
// Тесты не запускает — только смотрит на файлы, поэтому работает мгновенно и не тормозит работу.
//
// Запускается из настроек: node .claude/hooks/leftovers.mjs

//
// Всю папку editor крючок не трогает. Песочница, черновики и история — данные живой проверки
// владельца, а не мусор Claude. Окончание операции определяет сам исполнитель через run-status;
// событие Stop означает конец одного ответа и срабатывает также во время ожидания фонового агента.

import {execFileSync} from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';

const корень = process.env.CLAUDE_PROJECT_DIR ?? process.cwd();

// Этот hook вызывается в конце хода Claude, а не при закрытии процесса. Поэтому он не имеет права
// менять run-status: следующий ход той же живой сессии ещё может продолжать работу. Конец процесса
// и забытый `running` различает внешний наблюдатель по PID.

// Свежесть, по которой незакоммиченная статья в контенте считается следом текущей работы.
// Техническая величина крючка: старые статьи владельца лежат в дереве неделями, и ругаться на них
// при каждом ходе — значит приучить не читать предупреждения вовсе.
const СВЕЖЕСТЬ_ЧАСОВ = 3;

const находки = [];

// В контенте сайта смотрим только свежие файлы, чтобы не поднимать старую работу владельца.
let строки = [];
try {
  строки = execFileSync('git', ['status', '--porcelain', '--', 'docs', 'blog', 'i18n'], {
    cwd: корень,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'ignore'],
  }).split('\n').filter(Boolean);
} catch {
  // Не репозиторий или git недоступен — крючок молчит, это не его дело.
}

const порог = Date.now() - СВЕЖЕСТЬ_ЧАСОВ * 3600 * 1000;

for (const строка of строки) {
  if (!строка.startsWith('??')) continue;
  const путь = строка.slice(3).trim().replace(/^"|"$/g, '');
  const вКонтенте = /^(docs|blog|i18n)[\\/]/.test(путь);

  if (вКонтенте) {
    let когда = 0;
    try {
      когда = fs.statSync(path.join(корень, путь)).mtimeMs;
    } catch {
      continue;
    }
    if (когда < порог) continue;
    находки.push(`новое в контенте сайта: ${путь}`);
    continue;
  }
}

if (находки.length === 0) process.exit(0);

process.stdout.write(JSON.stringify({
  systemMessage: 'После работы осталось незакоммиченное. Проверьте, ваше ли это, и приберите своё:\n'
    + находки.map((строка) => `  · ${строка}`).join('\n'),
}));
