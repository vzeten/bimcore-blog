// Крючок перед правкой файла: предупреждает, что путь ведёт в контент сайта, а не в редактор.
// Не блокирует — решение за помощником и владельцем; дело крючка сказать вслух, что цена ошибки
// здесь другая: неверная правка в docs/, blog/ или i18n/ роняет сборку всего сайта.
//
// Запускается из настроек: node .claude/hooks/content-warning.mjs
// На вход приходит JSON запроса инструмента, на выход — JSON с сообщением.

let вход = '';

process.stdin.on('data', (кусок) => { вход += кусок; });

process.stdin.on('end', () => {
  let путь = '';
  try {
    путь = JSON.parse(вход)?.tool_input?.file_path ?? '';
  } catch {
    // Разобрать не вышло — молчим: крючок не должен мешать работе из-за собственной поломки.
    return;
  }

  // Папки контента сайта. Совпадение ищется по границе пути, чтобы `editor/docs-notes` не считался
  // контентом, а `i18n/ru/...` считался.
  const внутриКонтента = /(^|[\\/])(docs|blog|i18n)[\\/]/.test(путь);
  if (!внутриКонтента) return;

  const текст = `Файл лежит в контенте сайта, а не в программе-редакторе: ${путь}. `
    + 'Правка здесь идёт на learn.bimcore.one. Проверьте, что это действительно нужно, '
    + 'и что правило шапки статьи не нарушено.';

  process.stdout.write(JSON.stringify({
    systemMessage: текст,
    hookSpecificOutput: {hookEventName: 'PreToolUse', additionalContext: текст},
  }));
});
