// Единственный нормализатор каталога Ecwid. Им живут оба места, где программа спрашивает магазин:
// сборка сайта (плагин рядом, секрет из среды GitHub) и сервер редактора (тот же токен из
// `.env.local`). Второго алгоритма нет намеренно: разойдись они, редактор вставил бы в статью
// адрес или картинку не того товара, который потом покажет сайт.
//
// Токен живёт только в среде процесса. В том, что отсюда выходит, его нет ни в одном поле:
// каталог уезжает и в публичный `product-catalog.json`, и в браузер редактора.

const БАЗА = 'https://app.ecwid.com/api/v3';
/** Магазин один на весь сайт; второе его написание в программе разошлось бы с первым молча. */
export const МАГАЗИН = '86326685';

/** Имя переменной среды с публичным токеном Ecwid: одно на сборку сайта и на сервер редактора. */
export const ПЕРЕМЕННАЯ_ТОКЕНА = 'ECWID_PUBLIC_TOKEN';

/**
 * Спросить магазин и отдать нормализованный каталог вместе с ценами. Три запроса: язык магазина
 * (в нём записаны непереведённые названия), категории и сами товары. Ошибка сети или отказ Ecwid
 * бросаются наружу — что с ними делать, решает зовущий: сборка сайта обходится без цен,
 * а редактор отказывается вставлять товар.
 */
export async function собратьКаталог({storeId = МАГАЗИН, token, запрос = fetch} = {}) {
  const спросить = async (путь, поля) => {
    const адрес = `${БАЗА}/${storeId}/${путь}?token=${encodeURIComponent(token)}`
      + `&limit=100&responseFields=${encodeURIComponent(поля)}`;
    const ответ = await запрос(адрес);
    if (!ответ.ok) throw new Error(`Ecwid ${путь}: ${ответ.status}`);
    return ответ.json();
  };

  const [профиль, категории, товары] = await Promise.all([
    спросить('profile', 'languages(defaultLanguage)'),
    спросить('categories', 'items(id,name,nameTranslated)'),
    спросить(
      'products',
      'items(id,sku,name,nameTranslated,url,imageUrl,thumbnailUrl,defaultCategoryId,'
        + 'price,defaultDisplayedPriceFormatted)',
    ),
  ]);

  return нормализовать({
    язык: профиль?.languages?.defaultLanguage || 'en',
    категории: категории?.items ?? [],
    товары: товары?.items ?? [],
  });
}

/**
 * Ответ Ecwid в понятия программы. Чистое правило без сети: его же проверяет тест.
 *
 * Названия отдаются по языкам, а не одной строкой: подставить читателю чужой язык нельзя, и
 * какого языка не хватило — решает тот, кто открыл статью. Непереведённое название лежит под
 * языком самого магазина, потому что именно на нём оно и написано.
 *
 * Товар без адреса или без картинки в каталог не идёт: карточку без них сайт не показывает вовсе
 * (`if (!name || !image) return null`), и предлагать такой товар человеку значило бы обещать ему
 * блок, которого не будет.
 */
export function нормализовать({язык, категории, товары}) {
  const названияКатегорий = new Map(
    категории.map((к) => [к.id, {[язык]: к.name ?? '', ...(к.nameTranslated ?? {})}]),
  );

  const цены = {};
  const годные = [];

  for (const товар of товары) {
    if (товар.price != null) {
      цены[String(товар.id)] = {
        value: String(товар.price),
        formatted: товар.defaultDisplayedPriceFormatted || '',
      };
    }

    const картинка = товар.imageUrl || товар.thumbnailUrl || '';
    if (!товар.url || !картинка) continue;

    годные.push({
      id: String(товар.id),
      названия: {[язык]: товар.name ?? '', ...(товар.nameTranslated ?? {})},
      адрес: товар.url,
      картинка,
      категория: названияКатегорий.get(товар.defaultCategoryId) ?? {},
      sku: товар.sku ?? '',
    });
  }

  return {язык, товары: годные, цены};
}
