// Ссылки в markdown-копиях страниц для ИИ-агентов: убрать удвоенный префикс локали.
//
// **Зачем.** Плагин llms-txt строит абсолютную ссылку как «адрес сайта + baseUrl + путь из HTML».
// В сборке локали `baseUrl` уже равен `/ru/`, и путь в HTML тоже начинается с `/ru/`, поэтому
// получалось `https://learn.bimcore.one/ru/ru/blog/...` — адрес, которого нет. Найдено проверкой
// 2026-09-16, карточка `#73`.
//
// **Почему шаг стоит на markdown, а не на HTML.** Снять префикс до правила ссылок плагина нельзя:
// он ищет путь в своей карте маршрутов, и ключи там с префиксом — ссылка на markdown-копию потеряла
// бы `.md`. Точка «после» у HTML-шагов тоже не подходит: к ней дерево уже переведено в markdown.
// Поэтому правится готовый адрес в markdown-шаге (`content.remarkPlugins`), штатной точкой самого
// плагина. Поведение `llms.txt` не меняется: там адреса и так верные.
//
// Зависимостей не добавляет: обход дерева здесь свой, вместо `unist-util-visit`.

/**
 * Готовый адрес нашего сайта с удвоенным префиксом локали: `…/ru/ru/blog/…` → `…/ru/blog/…`.
 * Чужие адреса не трогаются, даже если в них случайно есть такой же кусок пути.
 */
export function безДвойнойЛокали(href, локаль, адресСайта = '') {
  const двойной = `/${локаль}/${локаль}`;
  // Свой адрес бывает двух видов: полный и от корня сайта. Пустое начало годится только для
  // пути от корня, иначе под правило попал бы чужой домен с таким же куском пути.
  for (const начало of адресСайта === '' ? [''] : [адресСайта, '']) {
    if (начало === '' && !href.startsWith('/')) continue;
    const с = `${начало}${двойной}`;
    if (href === с) return `${начало}/${локаль}`;
    if (href.startsWith(`${с}/`)) return `${начало}/${локаль}${href.slice(с.length)}`;
  }
  return href;
}

/**
 * Markdown-шаг: у готовых ссылок страницы схлопнуть удвоенный префикс локали.
 *
 * `локаль` — `ru`, `es`; для языка по умолчанию префикса нет и шаг ничего не делает.
 * `адресСайта` — `https://learn.bimcore.one`: правятся только свои ссылки, чужие остаются как есть.
 */
export function собратьСсылкиЛокали(настройки = {}) {
  const локаль = String(настройки.локаль ?? '');
  const адресСайта = String(настройки.адресСайта ?? '');

  return (дерево) => {
    if (локаль === '') return;

    const обойти = (узел) => {
      if (узел.type === 'link' && typeof узел.url === 'string') {
        узел.url = безДвойнойЛокали(узел.url, локаль, адресСайта);
      }
      for (const ребёнок of узел.children ?? []) обойти(ребёнок);
    };

    обойти(дерево);
  };
}
