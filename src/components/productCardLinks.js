// Ссылки карточки товара — без React, чтобы правило проверялось тестом (решение владельца 2026-10-01,
// база marketing/data/learn-funnel-strategy.md, 12.3).
//
// Данные лежат в `src/data/products.json`: какие способы оплаты бывают, в каком магазине каждый, на каких языках
// страницы человеку предлагается выбор, и у каждого товара — адреса в магазинах и его инструкция. Здесь только
// правило, как из этих данных получаются ссылки; ни одного магазина, валюты или языка в этом файле нет.

/** Метка статьи, которую сборка уже поставила на адрес из статьи (`utm_campaign` = язык/статья). */
export function кампанияИз(адрес) {
  try {
    return new URL(адрес).searchParams.get('utm_campaign') ?? '';
  } catch {
    return '';
  }
}

/**
 * Адрес магазина с метками карточки. Прежние параметры ссылки сохраняются; кампания берётся готовая, если её уже
 * поставила сборка (`plugins/shop-utm.mjs`), иначе — переданная.
 */
export function сМеткойКарточки(адрес, {кампания, содержимое, валюта}) {
  let url;
  try {
    url = new URL(адрес);
  } catch {
    return адрес;
  }
  if (валюта) url.searchParams.set('currency', валюта);
  url.searchParams.set('utm_source', 'learn');
  url.searchParams.set('utm_medium', 'productcard');
  if (!url.searchParams.get('utm_campaign') && кампания) url.searchParams.set('utm_campaign', кампания);
  url.searchParams.set('utm_content', содержимое);
  return url.toString();
}

/**
 * Ссылки карточки.
 *
 * Ответ:
 * - `оплата` — способы оплаты в порядке таблицы, `{код, href}`. Пусто, если на этом языке страницы выбора нет
 *   или у товара нашёлся только один магазин: тогда человек идёт сразу по `главная`;
 * - `главная` — адрес главной кнопки без выбора: магазин способа `world` (иначе первый найденный);
 * - `инструкция` — путь инструкции набора без языка (`/guides/families/…/`) или `null`.
 *
 * Адрес из статьи (`buyUrl`) нужен только товару, которого нет в таблице: таблица — главный источник.
 */
export function ссылкиКарточки({данные, код, язык, кампания = '', buyUrl = ''}) {
  const товар = данные.товары[String(код ?? '')] ?? {};
  const метка = кампания || кампанияИз(buyUrl);
  const адресМагазина = (магазин) => товар[магазин] || (магазин === 'bimcore' ? buyUrl : '');

  const все = данные.оплата.варианты
    .map((вариант) => ({вариант, адрес: адресМагазина(вариант.магазин)}))
    .filter(({адрес}) => адрес)
    .map(({вариант, адрес}) => ({
      код: вариант.код,
      href: сМеткойКарточки(адрес, {кампания: метка, содержимое: вариант.код, валюта: вариант.валюта}),
    }));

  const выбор = данные.оплата.языкиСВыбором.includes(язык) && все.length > 1;
  const главная = (все.find((с) => с.код === 'world') ?? все[0])?.href ?? null;

  return {оплата: выбор ? все : [], главная, инструкция: товар.инструкция ?? null};
}
